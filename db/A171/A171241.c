/* Calculation of OEIS A171241
   Sequence of numbers k such that A169611(k) = 3.
   Equivalent to the union of the four arithmetic progressions
   k*m with k ∈ {8,12,18,27} and gcd(m,6)=1 (i.e. m odd and not a multiple of 3).
   The terms are returned in increasing order. No external cache is used; the n‑th term
   is generated by a simple merge of the four sequences, which runs in O(n) time. */

#include <stddef.h>   /* for size_t */
#include "../utils/advance_multiplier.h"

static const idx_t BASE[4] = {8,12,18,27};

/* Public API */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for offset 0, safe fallback */

    idx_t m[4] = {1,1,1,1};        /* current multipliers for each base */
    seq_t val[4];                  /* current values k*m for each base */

    /* initialise first values */
    for (int i = 0; i < 4; ++i) {
        val[i] = (seq_t)BASE[i] * (seq_t)m[i];
    }

    seq_t result = 0;              /* will hold the n-th term */

    for (idx_t step = 0; step < n; ++step) {
        /* find the smallest among the four current values */
        int min_idx = 0;
        for (int i = 1; i < 4; ++i) {
            if (val[i] < val[min_idx])
                min_idx = i;
        }

        result = val[min_idx];      /* candidate for the next term */

        /* advance the sequence that just produced the current minimum */
        advance_multiplier(&m[min_idx]);
        val[min_idx] = (seq_t)BASE[min_idx] * (seq_t)m[min_idx];
    }

    return result;
}
