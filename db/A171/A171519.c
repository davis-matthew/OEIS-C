/*
 * A171519  a(n) = numbers m such that are not the product of k-th
 *          noncomposite number and k for any k >= 1.
 * https://oeis.org/A171519
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 50, u16 n <= 50, u32 n <= 50, u64 n <= 50, u128 n <= 50,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A171519
    The sequence consists of the positive integers m which are not equal
    to k·A008578(k) for any k ≥ 1, where A008578(k) is the k‑th
    non‑composite number (1,2,3,5,7,11,…).  No closed form is known;
    the sequence is generated by enumerating the natural numbers and
    skipping the forbidden products.
*/
#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>

/* Local helpers ----------------------------------------------------- */
static void ensure_primes_upto(size_t idx);
/*  ensure_PrimeIndexes: primes[0..idx] are defined; primes array
    holds the first idx+1 primes (2,3,5,…). */

static uint64_t *primes = NULL;
static size_t prime_cnt = 0, prime_cap = 0;

/*  dynamic array for cache of the sequence -------------------------------- */
static seq_t *cache = NULL;
static size_t cache_len = 0, cache_cap = 0;

/*  storage for the generator state ---------------------------------------- */
static idx_t  gen_k = 1;          /* current k value */
static seq_t  gen_fk = 1;         /* f(k) = k·a_k for current k */
static seq_t  gen_next_m = 2;     /* next integer to test */

/*  generate a(n) ---------------------------------------------------------- */
seq_t a(idx_t n)
{
    /* expand cache until it contains at least n terms                */
    while (cache_len < n)
    {
        /* advance k until f(k) ≥ gen_next_m */
        while (gen_fk < gen_next_m)
        {
            ++gen_k;
            seq_t a_k;
            if (gen_k <= 3)                     /* 1,2,3 are the first three non‑composites */
                a_k = (seq_t)gen_k;
            else                                /* subsequent are primes */
            {
                ensure_primes_upto((size_t)gen_k - 2);
                a_k = (seq_t)primes[(size_t)gen_k - 2];
            }
            gen_fk = a_k * (seq_t)gen_k;
        }

        /* skip forbidden products */
        if (gen_fk == gen_next_m)
        {
            ++gen_next_m;
            continue;
        }

        /* store the valid term */
        if (cache_len == cache_cap)
        {
            size_t new_cap = (cache_cap == 0) ? 64 : cache_cap * 2;
            seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            cache = tmp;
            cache_cap = new_cap;
        }
        cache[cache_len++] = gen_next_m;

        ++gen_next_m;
    }

    return cache[n - 1];
}

/*  primes helper ------------------------------------------------------------ */
static void ensure_primes_upto(size_t idx)
{
    /* make sure primes[0..idx] exist                            */
    while (prime_cnt <= idx)
    {
        uint64_t candidate = 2;
        if (prime_cnt > 0)
            candidate = primes[prime_cnt - 1] + 1;

        for (;; ++candidate)                 /* find next prime candidate */
        {
            bool prime = true;
            for (size_t i = 0; i < prime_cnt; ++i)
            {
                uint64_t p = primes[i];
                if (p * p > candidate) break;
                if (candidate % p == 0)
                {
                    prime = false;
                    break;
                }
            }
            if (prime)
            {
                /* store candidate                                 */
                if (prime_cnt == prime_cap)
                {
                    size_t new_cap = (prime_cap == 0) ? 2 : prime_cap * 2;
                    uint64_t *tmp = (uint64_t *)realloc(primes,
                                                new_cap * sizeof(uint64_t));
                    primes = tmp;
                    prime_cap = new_cap;
                }
                primes[prime_cnt++] = candidate;
                break;
            }
        }
    }
}
