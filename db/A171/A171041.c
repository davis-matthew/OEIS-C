/*
 * A171041  In the sequence of prime numbers, replace all the '8' digits with
 *          '0' and vice versa.
 * https://oeis.org/A171041
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 54, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   _prime_limit_for_idx, build_primes_upto
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Formula: a(n) = the decimal representation of the n-th prime with all
 * digits 8 and 0 exchanged (8→0, 0→8).  The sequence starts at a(1).
 *
 * Implementation uses a static cache of primes generated by the helper
 * functions _prime_limit_for_idx and build_primes_upto, then performs
 * a digit‑wise substitution on the n‑th prime.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/_prime_limit_for_idx.h"
#include "../utils/build_primes_upto.h"

static idx_t *primes_cache = NULL;
static size_t primes_cache_cnt = 0;

seq_t a(idx_t n)
{
    if (n < 1) return 0;                     /* undefined for n=0 */

    /* Ensure we have already generated at least n primes */
    if (primes_cache == NULL || (size_t)n > primes_cache_cnt) {
        idx_t limit = _prime_limit_for_idx(n);
        uint64_t *tmp = NULL;
        size_t tmpcnt = 0;

        build_primes_upto(limit, &tmp, &tmpcnt);
        free(primes_cache);                  /* release old cache */
        primes_cache = (idx_t *)tmp;         /* uint64_t and idx_t have same size */
        primes_cache_cnt = tmpcnt;
    }

    /* nth prime (1‑based) */
    idx_t p = primes_cache[n - 1];

    /* Extract digits of p */
    uint8_t digits[32];
    size_t len = 0;
    idx_t temp = p;
    if (temp == 0) {                         /* unlikely, but be complete */
        digits[len++] = 0;
    }
    while (temp > 0) {
        digits[len++] = (uint8_t)(temp % 10);
        temp /= 10;
    }

    /* Reconstruct number with 8↔0 swapped, processing from most‑significant digit */
    seq_t res = 0;
    for (int i = (int)len - 1; i >= 0; --i) {
        uint8_t d = digits[i];
        if (d == 8) d = 0;
        else if (d == 0) d = 8;
        res = res * 10 + d;                 /* arithmetic in seq_t */
    }
    return res;
}
