/*
 * A171084  A "run" means a maximal string of decreasing numbers; this
 *          sequence has the property that the sequence of run lengths is the
 *          sequence itself and all natural numbers appear exactly once.
 * https://oeis.org/A171084
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 231, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Self‑referential run‑length sequence A171084 (OEIS) */
/* Sequence generated by building maximal decreasing runs whose lengths
   themselves follow the sequence. */
#include <stdlib.h>
#include <stdbool.h>

/* Resize *ptr to hold at least "need" elements (1‑based indexing). */
static void ensure_capacity(size_t need, size_t *cap, seq_t **ptr)
{
    if (need > *cap) {
        size_t newcap = (*cap) * 2;
        if (newcap < need) newcap = need;
        seq_t *tmp = (seq_t *)realloc(*ptr, (newcap + 1) * sizeof(seq_t));
        if (!tmp) abort(); /* memory exhaustion */
        *ptr = tmp;
        *cap = newcap;
    }
}

/* The sequence a(n) for n ≥ 1 */
seq_t a(idx_t n)
{
    if (n < 1) return 0;   /* below the offset */

    static seq_t *seq = NULL;        /* 1‑based array of sequence values */
    static size_t seq_cap = 0;       /* array capacity (without 0‑th dummy) */
    static idx_t seq_len = 0;        /* number of elements stored */
    static idx_t run_index = 2;      /* next run to generate (starts at 2) */
    static seq_t start_prev = 0;     /* start of the previous run */
    static bool initialized = false;

    if (!initialized) {
        seq_cap = 64;
        seq = (seq_t *)malloc((seq_cap + 1) * sizeof(seq_t));
        if (!seq) abort();

        /* Run 1: length 2, decreasing 2, 1 */
        start_prev = (seq_t)2;
        ensure_capacity(2, &seq_cap, &seq);
        seq[1] = (seq_t)2;
        seq[2] = (seq_t)1;
        seq_len   = 2;
        run_index = 2;
        initialized = true;
    }

    while (seq_len < n) {
        /* Length of the next run is a(run_index) */
        seq_t run_len = seq[run_index];                 /* run length */
        seq_t start   = start_prev + run_len;           /* first value of run */

        idx_t new_len = seq_len + (idx_t)run_len;
        ensure_capacity((size_t)new_len, &seq_cap, &seq);

        /* Fill in the decreasing run: start, start‑1, … */
        for (idx_t j = 0; j < (idx_t)run_len; ++j)
            seq[seq_len + 1 + j] = start - (seq_t)j;

        seq_len   = new_len;
        start_prev = start;
        ++run_index;
    }

    return seq[n];
}
