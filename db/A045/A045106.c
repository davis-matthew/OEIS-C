#include "../utils/has_four_ones_one_two.h"
/* Sequence: Numbers whose base‑4 representation contains exactly four 1's and one 2.
   (generated by brute‑force search) */

seq_t a(idx_t n)
{
    if (n == 0)
        return 0;

    idx_t found = 0;
    seq_t v = (seq_t)342;        /* first term: 11112_base4 = 342 */

    for (;; ++v)
    {
        if (has_four_ones_one_two(v))
        {
            if (++found == n)
                return v;
        }
    }
}
