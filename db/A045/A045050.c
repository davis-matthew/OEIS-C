/*
 * A045050  Numbers whose base-4 representation contains exactly two 0's and
 *          three 2's.
 * https://oeis.org/A045050
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 4000, u32 n <= 4000, u64 n <= 4000,
 *            u128 n <= 4000, big any n
 * Helpers:   seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the n‑th number whose base‑4 representation contains exactly
   two 0's and three 2's.  The sequence is generated by increasing
   length, and for each length digits are produced in lexicographic
   (hence numeric) order. */

#include <stddef.h>
#include <stdlib.h>
#include "../utils/seq_realloc.h"

static seq_t *cache      = NULL;
static size_t cache_cap  = 0;
static size_t cache_len  = 0;
static idx_t next_len    = 5;           /* first length to generate */

/* Add a new value to the cache, growing the array when necessary. */
static void cache_push(seq_t val)
{
    if (cache_len == cache_cap) {
        size_t new_cap = cache_cap ? cache_cap << 1 : 8;
        seq_t *tmp = seq_realloc(cache, cache_cap, new_cap);
        if (!tmp) abort();              /* out of memory */
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

/* Recursively build all numbers of a fixed length that satisfy the
   zero/ two constraints.  The digits are generated in increasing
   order, ensuring numeric order of the results. */
static void generate_len_rec(idx_t pos, idx_t len,
                             int zeros_left, int twos_left,
                             seq_t val)
{
    if (pos == len) {                    /* finished a candidate */
        if (zeros_left == 0 && twos_left == 0)
            cache_push(val);
        return;
    }

    int start = (pos == 0) ? 1 : 0;       /* no leading zero */
    for (int d = start; d <= 3; ++d) {
        int nz = zeros_left;
        int nt = twos_left;

        if (d == 0) --nz;
        else if (d == 2) --nt;
        if (nz < 0 || nt < 0) continue;

        int rem = (int)(len - pos - 1);
        if (nz > rem || nt > rem || (nz + nt) > rem) continue;

        generate_len_rec(pos + 1, len, nz, nt,
                         val * 4 + (seq_t)d);
    }
}

/* Generate all valid numbers of a given length. */
static void generate_len(idx_t len)
{
    generate_len_rec(0, len, 2, 3, (seq_t)0);
}

/* Public entry point required by the build. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                /* undefined but safe */

    while (cache_len < (size_t)n) {
        generate_len(next_len++);
    }
    return cache[n - 1];
}
