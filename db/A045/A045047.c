/* Numbers whose base-4 representation contains exactly two 0's and no 2's.
   Generated by combinatorial enumeration. */

static seq_t count_completions(idx_t positions, int zeros_needed)
{
    if (zeros_needed < 0 || zeros_needed > positions) return 0;
    seq_t comb = 1;
    for (int i = 1; i <= zeros_needed; ++i) {
        comb = comb * (positions - zeros_needed + i) / i;
    }
    seq_t pow2 = 1;
    for (int i = 0; i < positions - zeros_needed; ++i) pow2 *= 2;
    return comb * pow2;
}

seq_t a(idx_t n)
{
    if (n < 1) return 0;

    /* find the length L of the n-th number */
    idx_t L = 3;
    seq_t acc = 0;
    while (1) {
        seq_t cnt = (seq_t)(L - 1) * (seq_t)(L - 2);
        seq_t pow2 = 1;
        for (idx_t i = 0; i < L - 3; ++i) pow2 *= 2;
        cnt *= pow2;
        if (n <= acc + cnt) break;
        acc += cnt;
        ++L;
    }

    /* zero‑based index among numbers of length L */
    seq_t offset = (seq_t)n - acc - 1;
    int zeros_needed = 2;
    seq_t result = 0;

    for (idx_t pos = L; pos > 0; --pos) {
        idx_t remaining = pos - 1;
        int digits[3];
        int dsize;

        if (pos == L) {          /* most significant digit */
            digits[0] = 1;
            digits[1] = 3;
            dsize = 2;
        } else {                 /* other positions */
            digits[0] = 0;
            digits[1] = 1;
            digits[2] = 3;
            dsize = 3;
        }

        for (int k = 0; k < dsize; ++k) {
            int d = digits[k];
            int zeros_after = zeros_needed - (d == 0);
            if (zeros_after > remaining || zeros_after < 0) continue;

            seq_t cnt = count_completions(remaining, zeros_after);
            if (offset < cnt) {
                result = result * 4 + d;
                zeros_needed = zeros_after;
                break;
            } else {
                offset -= cnt;
            }
        }
    }

    return result;
}
