/*
 * A045080  Numbers whose base-4 representation contains exactly three 0's and
 *          four 3's.
 * https://oeis.org/A045080
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 30, u32 n <= 30, u64 n <= 30, u128 n <= 30,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: numbers whose base‑4 representation contains exactly
   three 0’s and four 3’s.  Generated by exhaustive enumeration
   over increasing length, keeping the values in ascending order. */

#include <stdlib.h>

/* ---------- helper for powers of 4 (idx_t) ---------- */
static inline idx_t pow4_idx(idx_t e)
{
    idx_t r = 1;
    for (idx_t i = 0; i < e; ++i) r *= 4;
    return r;
}

/* ---------- dynamic cache of already generated terms ---------- */
static seq_t *cache      = NULL;
static size_t cache_len  = 0;
static size_t cache_cap  = 0;

/* push a new term into the cache, enlarging it if necessary */
static void push_cache(seq_t val)
{
    if (cache_len == cache_cap) {
        size_t newcap = cache_cap ? cache_cap * 2 : 64;
        seq_t *tmp = (seq_t *)realloc(cache, newcap * sizeof(seq_t));
        if (!tmp) exit(1);
        cache = tmp;
        cache_cap = newcap;
    }
    cache[cache_len++] = val;
}

/* ---------- state of the incremental generator ---------- */
static idx_t gen_L          = 0;   /* current length being processed */
static idx_t gen_start      = 0;   /* first number of the current length */
static idx_t gen_end        = 0;   /* one past the last number of the current length */
static idx_t gen_x          = 0;   /* current number being tested */

/* extend the cache until it contains at least n terms */
static void generate_until(idx_t n)
{
    /* initialise generator on first use */
    if (gen_L == 0) {
        gen_L     = 7; /* minimum length (3 zeros + 4 threes) */
        gen_start = pow4_idx(gen_L - 1);
        gen_end   = pow4_idx(gen_L);
        gen_x     = gen_start;
    }

    while (cache_len < n) {
        /* enumerate all numbers of the current length */
        while (gen_x < gen_end) {
            idx_t tmp = gen_x;
            int zeros = 0, threes = 0;
            /* quick way to extract base‑4 digits using bit shifts */
            for (idx_t i = 0; i < gen_L; ++i) {
                int d = tmp & 3;          /* tmp % 4 == lowest base‑4 digit */
                if (d == 0) ++zeros;
                else if (d == 3) ++threes;
                tmp >>= 2;                /* tmp /= 4 */
            }
            if (zeros == 3 && threes == 4)
                push_cache((seq_t)gen_x);
            ++gen_x;
        }
        /* move to the next length */
        ++gen_L;
        gen_start = pow4_idx(gen_L - 1);
        gen_end   = pow4_idx(gen_L);
        gen_x     = gen_start;
    }
}

/* ---------- public function required by the specification ---------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;           /* behaviour for n=0 is unspecified */
    generate_until(n);
    return cache[n - 1];            /* return the n‑th term (1‑based) */
}
