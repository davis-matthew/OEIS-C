/*
 * A045033  Numbers whose base-4 representation contains exactly four 0's and
 *          no 1's.
 * https://oeis.org/A045033
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 702, u32 n <= 2000, u64 n <= 2000,
 *            u128 n <= 2000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS: A045033 – numbers whose base‑4 representation contains exactly
   four 0's and no 1's.  
   The sequence is generated by enumerating base‑4 strings of increasing
   length that satisfy the constraints and selecting the n‑th string in
   numeric order. */

#include <stdbool.h>

/* -------------- helpers -------------- */

static idx_t pow2(idx_t e)
{
    idx_t r = 1;
    while (e--) r = r * 2;
    return r;
}

static idx_t comb(idx_t n, idx_t k)
{
    if (k > n) return 0;
    if (k == 0 || k == n) return 1;
    if (k > n - k) k = n - k;
    __int128 res = 1;
    for (idx_t i = 1; i <= k; ++i)
        res = res * (n - k + i) / i;
    return (idx_t)res;
}

/* number of length 'len' strings over {0,2,3} that contain exactly
   'zeros' zeros  (no leading‐zero restriction). */
static idx_t count_completions(idx_t len, idx_t zeros)
{
    if (zeros > len) return 0;
    if (len == 0) return zeros == 0 ? 1 : 0;
    /* each non–zero digit can be 2 or 3 → 2 possibilities */
    __int128 res = (__int128)comb(len, zeros) * pow2(len - zeros);
    return (idx_t)res;
}

/* -------------- sequence function -------------- */

seq_t a(idx_t n)
{
    if (n < 1) return 0;        /* undefined for indices ≤ 0 */

    /* find minimal length L such that cumulative count ≥ n */
    idx_t L = 5;            /* at least 5 digits (4 zeros + 1 non‑zero) */
    idx_t cumulative = 0;
    while (1) {
        /* count for this length: leading digit 2 choices,
           trailing positions choose 4 zero positions and
           remaining digits (2 or 3). */
        idx_t cnt_len = 2 * count_completions(L - 1, 4);
        if (cumulative + cnt_len >= n) break;
        cumulative += cnt_len;
        ++L;
    }

    /* index within strings of length L */
    idx_t k = n - cumulative;          /* 1‑based */

    seq_t result = 0;
    idx_t zeros_needed = 4;

    for (idx_t pos = 0; pos < L; ++pos) {
        idx_t rem = L - pos;           /* including current position */

        if (pos == 0) {   /* leading position: digits 2,3 */
            const idx_t digits[2] = {2, 3};
            for (int d = 0; d < 2; ++d) {
                idx_t use_zero = 0;
                if (zeros_needed < use_zero) continue; /* never true */
                idx_t zeros_left = zeros_needed - use_zero;
                idx_t cnt = count_completions(rem - 1, zeros_left);
                if (k > cnt) { k -= cnt; continue; }
                result = result * 4 + (seq_t)digits[d];
                zeros_needed = zeros_left;
                break;
            }
        } else {          /* other positions: digits 0,2,3 */
            const idx_t digits[3] = {0, 2, 3};
            for (int d = 0; d < 3; ++d) {
                idx_t use_zero = (digits[d] == 0) ? 1 : 0;
                if (zeros_needed < use_zero) continue;
                idx_t zeros_left = zeros_needed - use_zero;
                idx_t cnt = count_completions(rem - 1, zeros_left);
                if (k > cnt) { k -= cnt; continue; }
                result = result * 4 + (seq_t)digits[d];
                zeros_needed = zeros_left;
                break;
            }
        }
    }

    return result;
}
