/*
 * A045034  Numbers whose base-4 representation contains exactly four 0's and
 *          one 1.
 * https://oeis.org/A045034
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 1321, u32 n <= 5000, u64 n <= 5000,
 *            u128 n <= 5000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A045034: numbers whose base‑4 representation contains exactly
   four 0's and one 1.  The sequence is generated by enumerating all
   admissible base–4 digit strings in lexicographic order. */

/* All integer arithmetic is carried out in idx_t (uint64_t) to avoid
   overflow in the counting phase.  The final value is accumulated in
   seq_t, which may be uint8_t, uint16_t, uint32_t, uint64_t or a
   big‑integer type. */

#include <stdbool.h>
#include <stdint.h>

/*--- combinatorial helpers ----------------------------------------*/
static idx_t binom_idx(unsigned int n, unsigned int k)
{
    if (k > n) return 0;
    if (k > n - k) k = n - k;
    idx_t r = 1;
    for (unsigned int i = 1; i <= k; ++i)
        r = r * (n - k + i) / i;
    return r;
}

static idx_t pow2_idx(unsigned int e)
{
    idx_t r = 1;
    for (unsigned int i = 0; i < e; ++i)
        r *= 2;
    return r;
}

/* Count all completions of a partial number with
   remPos remaining positions, remZeros zeros to place, remOnes ones to place. */
static idx_t count_completions(unsigned int remPos,
                               unsigned int remZeros,
                               unsigned int remOnes)
{
    if (remZeros > remPos)          return 0;
    if (remOnes > remPos - remZeros) return 0;
    if (remOnes > 1)                return 0;

    idx_t ways = binom_idx(remPos, remZeros);
    if (remOnes == 1)
        ways *= (remPos - remZeros);
    unsigned int freePos = remPos - remZeros - remOnes;
    if (freePos > 0)
        ways *= pow2_idx(freePos);
    return ways;
}

/* Count admissible numbers of base‑4 length L. */
static idx_t count_len(unsigned int L)
{
    if (L < 5) return 0;
    /* leading digit 1 */
    idx_t term1 = binom_idx(L - 1, 4) * pow2_idx(L - 5);
    /* leading digit 2 or 3 */
    idx_t term2 = 0;
    if (L >= 6)
        term2 = (idx_t)2 * (idx_t)(L - 1) *
                binom_idx(L - 2, 4) * pow2_idx(L - 6);
    return term1 + term2;
}

/*--- main sequence function ---------------------------------------*/
seq_t a(idx_t n)
{
    if (n < (idx_t)1) return (seq_t)0;   /* undefined for 0 */

    /* Find the block (length) containing the nth term. */
    idx_t target = n;
    idx_t cumulative = 0;
    unsigned int L = 5;
    while (true) {
        idx_t cnt = count_len(L);
        if (cumulative + cnt >= target)
            break;
        cumulative += cnt;
        ++L;
    }

    idx_t kth = target - cumulative;  /* 1‑based index inside this block */

    /* Digit construction. */
    static const unsigned int MAX_L = 64;
    uint8_t digits[MAX_L];
    unsigned int pos;
    unsigned int remZeros = 4;
    unsigned int remOnes  = 1;
    unsigned int remPos   = L;

    for (pos = 0; pos < L; ++pos) {
        unsigned int positionsLeft = remPos - 1;

        for (int d = 0; d <= 3; ++d) {
            if (pos == 0 && d == 0)           continue;   /* no leading zero */
            if (d == 1 && remOnes == 0)       continue;   /* one 1 already used */
            if (d == 0 && remZeros == 0)      continue;   /* no zeros left */

            unsigned int nz = remZeros;
            unsigned int no = remOnes;
            if (d == 0) nz--;
            else if (d == 1) no = 0;

            idx_t suffix = count_completions(positionsLeft, nz, no);

            if (kth > suffix) {
                kth -= suffix;
                continue;
            }

            digits[pos] = (uint8_t)d;
            remZeros = nz;
            remOnes  = no;
            remPos   = positionsLeft;
            break;
        }
    }

    /* Convert base‑4 digits to decimal value. */
    seq_t value = 0;
    for (pos = 0; pos < L; ++pos)
        value = value * 4 + (seq_t)digits[pos];
    return value;
}
