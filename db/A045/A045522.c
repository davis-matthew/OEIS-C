/*
 * A045522  Numbers k such that k! has initial digit '3'.
 * https://oeis.org/A045522
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 32, u16 n <= 8269, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   append_candidate
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute the n-th term of OEIS A045522: numbers k whose factorial begins with
   the digit 3.  The sequence is generated by incremental search. */
#include <stddef.h>
#include <math.h>
#include "../utils/append_candidate.h"

seq_t a(idx_t n)
{
    static seq_t *terms = NULL;     /* stored terms, indexed 0..len-1 */
    static size_t len   = 0;        /* number of terms stored   */
    static size_t cap   = 0;        /* current capacity         */
    static idx_t  cur_k = 0;        /* last k processed          */
    static long double log_sum = 0.0L;   /* cumulative log10(k!)    */

    /* Return dummy or error if n is zero - behaviour below offset
       is unspecified, but keep consistent. */
    if (n == 0) return 0;

    /* If we already have the requested term, return it. */
    if (len >= (size_t)n)
        return terms[(size_t)n - 1];

    /* Generate terms until we have at least n terms. */
    while (len < (size_t)n)
    {
        cur_k++;                               /* next k            */
        log_sum += log10l((long double)cur_k); /* log10(k!) update  */

        long double frac  = log_sum - floorl(log_sum);
        long double mant  = powl(10.0L, frac);   /* 10^frac          */
        int leading = (int)(mant + 1e-12L);     /* first digit      */
        if (leading == 10) leading = 9;         /* guarding round‑off */

        if (leading == 3)                       /* store term if needed */
            append_candidate(&terms, &len, &cap, (seq_t)cur_k);
    }

    return terms[(size_t)n - 1];
}
