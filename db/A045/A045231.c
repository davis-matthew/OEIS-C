/*
 * A045231  Numbers whose base-5 representation contains exactly three 1's and
 *          two 2's.
 * https://oeis.org/A045231
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 38, u32 n <= 38, u64 n <= 38, u128 n <= 38,
 *            big any n
 * Helpers:   has_three1_two2
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A045231: a(n) – numbers whose base‑5 representation contains
   exactly three 1's and two 2's.
   Implementation: iterative enumeration.
   The sequence is generated by testing successive integers for the
   required digit pattern.  Results are cached so that subsequent
   calls with any index may be answered without rescanning. */

#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/has_three1_two2.h"

/* Cached list of terms.  20000 is more than enough for n ≤ 10000. */
#define MAX_CACHE 20000
static seq_t cache[MAX_CACHE];
static size_t cache_len = 0;

/* Highest integer checked so far (in decimal).  Ever increasing. */
static idx_t last_checked = 0;

/* Compute a(n) for n ≥ 1.  The cache grows as needed. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;  /* undefined for offset 0 */

    /* Grow the cache until it contains the requested term. */
    while (cache_len < (size_t)n) {
        /* Find the next qualifying number. */
        do {
            ++last_checked;
        } while (!has_three1_two2((seq_t)last_checked));

        /* Store the found term. */
        if (cache_len < MAX_CACHE) {
            cache[cache_len++] = (seq_t)last_checked;
        } else {
            /* Should not happen for the intended limits. */
            abort();
        }
    }

    return cache[(size_t)n - 1];
}
