/*
 * A045166  Numbers whose base-5 representation contains exactly two 0's and
 *          one 1.
 * https://oeis.org/A045166
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 12, u16 n <= 52, u32 n <= 52, u64 n <= 52, u128 n <= 52,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute numbers whose base‑5 representation contains exactly two 0’s and one 1.
   The sequence is generated by recursive enumeration of base‑5 strings of increasing
   length, producing the terms in ascending numeric order. */

#include <stdlib.h>

/* Global cache for generated terms */
static seq_t *cache = NULL;      /* pointer to array of seq_t */
static size_t cache_used = 0;    /* how many terms are stored */
static size_t cache_cap = 0;     /* current capacity of the array */
static int next_len = 3;         /* next length of base‑5 strings to generate */

/* Append a value to the cache, resizing if necessary */
static void push_value(seq_t val) {
    if (cache_used == cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 8;
        seq_t *new_cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        cache = new_cache;
        cache_cap = new_cap;
    }
    cache[cache_used++] = val;
}

/* Recursive generation of all base‑5 numbers of a fixed length L
   that contain exactly two 0's and one 1.  The digits are chosen
   lexicographically, so numbers are produced in ascending order. */
static void rec_gen(int pos, int zeros_left, int ones_left,
                    seq_t value, int L) {
    if (pos == L) {
        if (zeros_left == 0 && ones_left == 0)
            push_value(value);
        return;
    }
    int rem = L - pos - 1;   /* positions remaining after this one */
    seq_t base = value * (seq_t)5;  /* shift left by one base-5 digit */

    for (int d = 0; d <= 4; ++d) {
        if (pos == 0 && d == 0)          /* leading zero not allowed */
            continue;
        int nz = zeros_left - (d == 0);
        int no = ones_left   - (d == 1);
        if (nz < 0 || no < 0)
            continue;
        if (nz > rem || no > rem || nz + no > rem)
            continue;
        rec_gen(pos + 1, nz, no, base + (seq_t)d, L);
    }
}

/* Generate all terms of a given base‑5 length L and append them to the cache */
static void generate_len(int L) {
    rec_gen(0, 2, 1, (seq_t)0, L);   /* start with two zeros and one one to place */
}

/* External function required for OEIS interface */
seq_t a(idx_t n) {
    if (n == 0) return 0;                /* safety: sequence is 1‑based */
    while (cache_used < (size_t)n) {
        generate_len(next_len);
        ++next_len;                      /* move to strings of next length */
    }
    return cache[n - 1];
}
