/*
 * A229955  Triangular array read by rows: 3 dimensional analog of A227997.
 * https://oeis.org/A229955
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabl, walk
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 6, u32 n <= 21, u64 n <= 36, u128 n <= 36,
 *            big any n
 * Helpers:   binom
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A229955 – triangular array read by rows.  
   Let c[n] = binom(2n,n)^3.  
   Define s[0]=0, s[1]=c[1], and for n≥2  
       s[n] = c[n] – Σ_{j=1}^{n-1} c[j] * s[n-j].  
   The triangular array T is generated by  
       T[n][1] = s[n],  
       for k>1:  T[n][k] = Σ_{m=1}^{n-1} s[m] * T[n-m][k-1].  
   The sequence a(n) is obtained by reading the rows of T left‑to‑right. */

#include <stddef.h>
#include <stdlib.h>
#include "../utils/binom.h"

seq_t a(idx_t n)
{
    /* Find the row containing the nth term.  r = ceil((sqrt(8n+1)-1)/2). */
    idx_t r = 0;
    idx_t terms = 0;
    while (terms < n) {
        ++r;
        terms += r;
    }

    /* Allocate arrays c[0..r] and s[0..r] (c[0] unused). */
    seq_t *c = (seq_t *)malloc((r + 1) * sizeof(seq_t));
    seq_t *s = (seq_t *)malloc((r + 1) * sizeof(seq_t));
    if (!c || !s) {
        free(c); free(s);
        return (seq_t)0;
    }

    c[0] = (seq_t)1;   /* dummy */
    for (idx_t i = 1; i <= r; ++i) {
        seq_t b = binom(2 * i, i);   /* binom(2i,i) */
        c[i] = b * b * b;            /* ^3 */
    }

    s[0] = (seq_t)0;
    if (r >= 1) s[1] = c[1];
    for (idx_t i = 2; i <= r; ++i) {
        seq_t sum = (seq_t)0;
        for (idx_t j = 1; j < i; ++j) {
            sum += c[j] * s[i - j];
        }
        s[i] = c[i] - sum;
    }

    /* Build the triangular array row by row. */
    seq_t **T = (seq_t **)malloc((r + 1) * sizeof(seq_t *));
    if (!T) {
        free(c); free(s);
        return (seq_t)0;
    }

    for (idx_t row = 1; row <= r; ++row) {
        T[row] = (seq_t *)calloc(row + 1, sizeof(seq_t));
        if (!T[row]) {
            for (idx_t p = 1; p < row; ++p) free(T[p]);
            free(T); free(c); free(s);
            return (seq_t)0;
        }
        T[row][1] = s[row];
        for (idx_t k = 2; k <= row; ++k) {
            seq_t sum = (seq_t)0;
            for (idx_t m = 1; m < row; ++m) {
                idx_t prev_row = row - m;
                if (k - 1 <= prev_row) {
                    sum += s[m] * T[prev_row][k - 1];
                }
            }
            T[row][k] = sum;
        }
    }

    /* Locate the nth term in the flattened sequence. */
    idx_t cnt = 0;
    seq_t result = (seq_t)0;
    for (idx_t row = 1; row <= r; ++row) {
        for (idx_t k = 1; k <= row; ++k) {
            ++cnt;
            if (cnt == n) {
                result = T[row][k];
                goto cleanup;
            }
        }
    }

cleanup:
    for (idx_t row = 1; row <= r; ++row) free(T[row]);
    free(T); free(c); free(s);
    return result;
}
