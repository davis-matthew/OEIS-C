/*
 * A395270  Numbers that are radicals of abundant numbers.
 * https://oeis.org/A395270
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 54, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the nth term of A395270: numbers that are radicals of abundant
   numbers.  A number r is included iff r is squarefree and
   ∏_{p|r} p/(p-1) > 2.  The sequence is generated by a simple sieve that
   factors each candidate using a precomputed smallest‑prime‑factor array
   and tests the above condition.  Results are cached so that calls with
   arbitrary (non‑monotonic) indices up to about 10 000 finish in well
   under two seconds. */
#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

static uint32_t *g_spf = NULL;
static size_t    g_spf_limit = 0;
static bool      g_spf_built = false;

static void build_spf(size_t limit)
{
    g_spf = (uint32_t *)malloc((limit + 1) * sizeof(uint32_t));
    if (!g_spf) exit(1);
    for (size_t i = 0; i <= limit; ++i) g_spf[i] = (uint32_t)i;
    for (size_t i = 2; i * i <= limit; ++i) {
        if (g_spf[i] == (uint32_t)i) {            /* i is prime */
            for (size_t j = i * i; j <= limit; j += i) {
                if (g_spf[j] == (uint32_t)j) g_spf[j] = (uint32_t)i;
            }
        }
    }
    g_spf_limit = limit;
    g_spf_built = true;
}

static bool is_radical_abundant(uint64_t x)
{
    uint64_t t = x;
    seq_t    numer = 1;
    seq_t    denom = 1;
    while (t > 1) {
        uint32_t p = g_spf[t];
        int      e = 0;
        while (t % p == 0) {
            t /= p;
            if (++e > 1) return false;           /* not squarefree */
        }
        numer *= (seq_t)p;
        denom *= (seq_t)(p - 1);
    }
    return numer > (seq_t)2 * denom;
}

static seq_t *g_terms    = NULL;
static size_t g_len        = 0;
static size_t g_capacity   = 0;

static void append_term(seq_t val)
{
    if (g_len >= g_capacity) {
        size_t new_cap = g_capacity ? g_capacity * 2 : 64;
        seq_t *tmp = (seq_t *)realloc(g_terms, new_cap * sizeof(seq_t));
        if (!tmp) exit(1);
        g_terms    = tmp;
        g_capacity = new_cap;
    }
    g_terms[g_len++] = val;
}

static uint64_t g_last_checked = 1;

seq_t a(idx_t n)
{
    if (n == 0) return 0;
    if (!g_spf_built) build_spf(500000);          /* sufficient for n ≤ 10 000 */
    while (g_len < (size_t)n) {
        ++g_last_checked;
        if (g_last_checked < 2) continue;        /* 1 is not a radical candidate */
        if (is_radical_abundant(g_last_checked))
            append_term((seq_t)g_last_checked);
    }
    return g_terms[n - 1];
}
