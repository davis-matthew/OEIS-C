/*
 * A182736  Sum of parts in all partitions of 2n that do not contain 1 as a
 *          part.
 * https://oeis.org/A182736
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 16, u32 n <= 52, u64 n <= 183, u128 n <= 672,
 *            big any n
 * Helpers:   seq_alloc_array, seq_free_array
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A182736: Sum of parts in all partitions of 2n that do not contain 1 as a part.
   Formula: a(n) = 2*n*(p(2n) - p(2n-1))
   where p(m) is the unrestricted partition number of m.  The partition
   numbers are generated by Euler's pentagonal recurrence and cached
   in a static array so that repeated calls are O(1) after the first
   expansion. */
#include <stdlib.h>
#include <stdint.h>
#include "../utils/seq_alloc_array.h"   /* seq_alloc_array, seq_free_array */
#include "../utils/seq_free_array.h"

static seq_t *p_partitions = NULL;   /* stores p(0)..p(max_n)          */
static idx_t   p_max        = 0;      /* highest index currently known  */

/* Allocate and initialise the partition table to cover indices up to N.
   N must be >= 0. */
static void ensure_partitions(idx_t N)
{
    if (p_partitions != NULL && N <= p_max)
        return;          /* already ready */

    size_t new_size = (size_t)N + 1;

    if (p_partitions == NULL) {
        /* first allocation */
        p_partitions = seq_alloc_array(new_size);
        p_partitions[0] = (seq_t)1;   /* p(0) = 1 */
        p_max = 0;
    } else {
        /* grow existing array */
        seq_t *newp = seq_alloc_array(new_size);
        /* copy old contents */
        for (idx_t i = 0; i <= p_max; ++i)
            newp[i] = p_partitions[i];
        newp[0] = (seq_t)1;   /* copy p(0) */
        seq_free_array(p_partitions);
        p_partitions = newp;
    }

    /* Compute missing partition numbers up to N */
    for (idx_t i = p_max + 1; i <= N; ++i) {
        seq_t pos = 0;   /* sum of terms with + sign */
        seq_t neg = 0;   /* sum of terms with - sign */
        for (idx_t k = 1; ; ++k) {
            idx_t pent1 = k * (3 * k - 1) / 2;
            if (pent1 > i)
                break;
            idx_t idx1 = i - pent1;
            if (k & 1)  /* sign +1 */
                pos += p_partitions[idx1];
            else        /* sign -1 */
                neg += p_partitions[idx1];

            idx_t pent2 = k * (3 * k + 1) / 2;
            if (pent2 > i)
                continue; /* still need next k */
            idx_t idx2 = i - pent2;
            if (k & 1)
                pos += p_partitions[idx2];
            else
                neg += p_partitions[idx2];
        }
        p_partitions[i] = pos - neg;   /* p(i)  */
    }

    p_max = N;
}

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;   /* a(0) = 0 by definition */

    idx_t N = 2 * n;          /* we need p(2n) and p(2n-1)   */
    ensure_partitions(N);     /* guarantees p_partitions[0..N] */

    seq_t part_no1 = p_partitions[N] - p_partitions[N - 1]; /* p(2n)-p(2n-1) */
    seq_t two_n = (seq_t)2 * (seq_t)n;

    return two_n * part_no1;
}
