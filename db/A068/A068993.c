/*
 * A068993  Numbers k such that A062799(k) = 4.
 * https://oeis.org/A068993
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 78, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Finds the n-th term of A068993: numbers k such that
   (1 + 2*v₂(k)) * τ((k/2^v₂(k))²) = 9,
   where v₂(k) is the 2-adic valuation of k and
   τ(m) is the divisor–count function.  The sequence is
   generated by scanning integers and testing the condition. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Static data for incremental generation */
static seq_t *terms = NULL;          /* array of found terms       */
static size_t terms_size = 0;        /* number of terms stored     */
static size_t terms_cap = 0;         /* allocated capacity         */

static uint32_t *spf = NULL;        /* smallest prime factor table */
static size_t spf_limit = 0;        /* maximum number prepared in spf */

/* Current integer being examined (next k to test) */
static uint64_t next_k = 1;

/* Reallocate the term array if necessary */
static void push_term(seq_t val)
{
    if (terms_size == terms_cap) {
        size_t new_cap = (terms_cap == 0) ? 8 : terms_cap << 1;
        seq_t *new_ptr = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
        terms = new_ptr;
        terms_cap = new_cap;
    }
    terms[terms_size++] = val;
}

/* Fill the spf array up to a new limit */
static void build_spf_upto(size_t limit)
{
    uint32_t *new_spf = (uint32_t *)calloc(limit + 1, sizeof(uint32_t));
    if (!new_spf) return;          /* allocation failures are not handled here */

    for (size_t i = 2; i <= limit; ++i) {
        if (!new_spf[i]) {
            new_spf[i] = (uint32_t)i;
            if (i * i <= limit) {
                for (size_t j = i * i; j <= limit; j += i)
                    if (!new_spf[j]) new_spf[j] = (uint32_t)i;
            }
        }
    }

    free(spf);
    spf = new_spf;
    spf_limit = limit;
}

/* Ensure enough terms are generated for a given n */
static void ensure_terms(idx_t n)
{
    while (terms_size < (size_t)n) {
        /* Extend spf table if needed */
        if ((size_t)next_k > spf_limit) {
            size_t new_limit = spf_limit ? (spf_limit << 1) : 1024;
            while (new_limit < (size_t)next_k) new_limit <<= 1;
            build_spf_upto(new_limit);
        }

        uint64_t k = next_k++;
        /* Compute v₂(k) and odd part m */
        uint64_t e = 0;
        uint64_t m = k;
        while ((m & 1ULL) == 0) {
            ++e;
            m >>= 1;  /* divide by 2 */
        }

        /* Compute τ(m²) = ∏ (2*exp_i + 1) */
        uint64_t tau = 1;
        if (m > 1) {
            uint64_t temp = m;
            while (temp > 1) {
                uint32_t p = spf[temp];
                uint64_t cnt = 0;
                while (temp % p == 0) {
                    temp /= p;
                    ++cnt;
                }
                tau *= (2 * cnt + 1);
                if (tau > 9) break;  /* exceed target, no need to continue */
            }
        }

        if ((1 + 2 * e) * tau == 9) {
            push_term((seq_t)k);
        }
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined, return 0 */

    ensure_terms(n);
    return terms[(size_t)n - 1];
}
