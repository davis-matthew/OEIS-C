/*
 * A068363  Primes p such that there exists k such that p = prime(k) +
 *          prime(k+2) + prime(k+4).
 * https://oeis.org/A068363
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 10, u16 n <= 614, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   is_prime_64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A068363: Primes that are the sum of three alternate primes
 *  a(n) = prime(n) + prime(n+2) + prime(n+4) for the first n such sums that
 *  yield a prime number.
 *  Generated by a deterministic sieve of Eratosthenes and an on‑the‑fly
 *  primality test for the resulting sums.
 */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <string.h>
#include "../utils/is_prime_64.h"

/* Main sequence generator */
seq_t a(idx_t n) {
    /* ---------------- Static state ---------------- */
    static bool initialized = false;
    static uint64_t *prime_list = NULL;
    static size_t prime_count = 0;
    static seq_t *terms = NULL;
    static size_t term_len = 0, term_cap = 0;
    static bool *is_comp = NULL;

    /* ---------------- Initialisation ---------------- */
    if (!initialized) {
        /* Sieve limit: 5 000 000 (covers >300 k primes, plenty for n≤10 000) */
        const idx_t LIMIT = 5000000ULL;
        is_comp = (bool *)calloc(LIMIT + 1, sizeof(bool));
        if (!is_comp) return (seq_t)0;   /* allocation failure */

        /* Sieve of Eratosthenes */
        for (idx_t i = 2; i * i <= LIMIT; ++i) if (!is_comp[i]) {
            for (idx_t j = i * i; j <= LIMIT; j += i) is_comp[j] = true;
        }

        /* Count primes up to LIMIT */
        for (idx_t i = 2; i <= LIMIT; ++i) if (!is_comp[i]) ++prime_count;

        prime_list = (uint64_t *)malloc(prime_count * sizeof(uint64_t));
        if (!prime_list) return (seq_t)0; /* allocation failure */

        for (idx_t i = 2, idx = 0; i <= LIMIT; ++i) if (!is_comp[i]) {
            prime_list[idx++] = i;
        }

        /* Reserve space for terms */
        term_cap = prime_count;               /* at most one term per k */
        terms = (seq_t *)malloc(term_cap * sizeof(seq_t));
        if (!terms) return (seq_t)0; /* allocation failure */

        /* Generate sums prime(k) + prime(k+2) + prime(k+4) */
        for (size_t k = 0; k + 4 < prime_count; ++k) {
            seq_t sum = (seq_t)prime_list[k]
                        + (seq_t)prime_list[k + 2]
                        + (seq_t)prime_list[k + 4];
            bool prime = false;
            if (sum <= LIMIT) prime = !is_comp[(idx_t)sum];
            else prime = is_prime_64((uint64_t)sum);
            if (prime) {
                if (term_len == term_cap) {
                    term_cap += prime_count; /* increase capacity */
                    terms = (seq_t *)realloc(terms, term_cap * sizeof(seq_t));
                    if (!terms) return (seq_t)0;
                }
                terms[term_len++] = sum;
            }
        }
        initialized = true;
    }

    /* ---------------- Answer query ---------------- */
    if (n == 0 || n > term_len) return (seq_t)0;
    return terms[n - 1];
}
