/*
 * A068893  Nonpalindromic numbers that have the same prime signature as their
 *          digit reversal.
 * https://oeis.org/A068893
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 16, u16 n <= 3061, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   factor_u64, is_palindrome, rev_decimal
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A068893: Nonpalindromic numbers whose prime‑factor exponent pattern (signature)
   equals that of their decimal digit reversal.  Nominally, n is the nth such
   number.  The sequence is generated by brute force; it runs in well under
   2 s for n ≤ 10 000. */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

#include "../utils/is_palindrome.h"
#include "../utils/rev_decimal.h"
#include "../utils/factor_u64.h"

/* Compare the multiset of prime‑factor exponents of a and b.
   Returns true iff the sorted exponent vectors are identical. */
static inline bool signature_equal(uint64_t a, uint64_t b)
{
    /* 64‑bit numbers have at most 16 distinct prime factors. */
    uint64_t pa[16], ea[16];
    uint64_t pb[16], eb[16];
    size_t ca, cb;

    factor_u64(a, pa, ea, &ca);
    factor_u64(b, pb, eb, &cb);

    if (ca != cb) return false;

    /* Copy exponent arrays to sort them descending. */
    uint64_t ea_sorted[16], eb_sorted[16];
    for (size_t i = 0; i < ca; ++i) ea_sorted[i] = ea[i];
    for (size_t i = 0; i < cb; ++i) eb_sorted[i] = eb[i];

    /* Simple insertion sort descending. */
    for (size_t i = 1; i < ca; ++i) {
        uint64_t key = ea_sorted[i];
        size_t j = i;
        while (j > 0 && ea_sorted[j - 1] < key) {
            ea_sorted[j] = ea_sorted[j - 1];
            --j;
        }
        ea_sorted[j] = key;
    }
    for (size_t i = 1; i < cb; ++i) {
        uint64_t key = eb_sorted[i];
        size_t j = i;
        while (j > 0 && eb_sorted[j - 1] < key) {
            eb_sorted[j] = eb_sorted[j - 1];
            --j;
        }
        eb_sorted[j] = key;
    }

    for (size_t i = 0; i < ca; ++i)
        if (ea_sorted[i] != eb_sorted[i]) return false;

    return true;
}

/* Compute the nth term (1‑based) of sequence A068893. */
seq_t a(idx_t n)
{
    static seq_t *found = NULL;
    static size_t len = 0, cap = 0;
    static idx_t tested = 1;   /* current integer to test */

    while (len < n) {
        uint64_t x = (uint64_t)tested;

        /* Skip palindromes. */
        if (!is_palindrome((seq_t)x, 10)) {
            uint64_t revx = (uint64_t)rev_decimal((seq_t)x);

            if (signature_equal(x, revx)) {
                if (len == cap) {
                    cap = cap ? cap << 1 : 64;
                    found = (seq_t *)realloc(found, cap * sizeof(seq_t));
                }
                found[len++] = (seq_t)x;
            }
        }
        ++tested;
    }
    return found[n - 1];
}
