/*  Numbers having the sum of distinct prime factors not less than 
    the sum of exponents in prime factorization.  
    a(n) is the n-th positive integer x with  
        sum_{p|x} p  ≥  sum_{p|x} (exponent of p in x).  
    The sequence is generated by testing the integers 1,2,3,… in order. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/good_number.h"

/* The types seq_t and idx_t are supplied by the build system. */

/* Main function required by the framework. */
seq_t a(idx_t n)
{
    /* static state: list of valid numbers generated so far */
    static seq_t *valid = NULL;      /* array of numbers satisfying the condition */
    static size_t valid_len = 0;     /* how many numbers stored */
    static size_t cap = 0;           /* allocated capacity of the array */
    static unsigned long long last_checked = 0ULL;  /* last integer that was examined */

    /* initialize the dynamic array lazily */
    if (valid == NULL) {
        cap = 128;  /* arbitrary small start */
        valid = (seq_t *)malloc(cap * sizeof(seq_t));
        if (valid == NULL)
            return (seq_t)0;  /* out‑of‑memory - should not happen */
    }

    /* generate until we have the requested nth term */
    while (valid_len < n) {
        last_checked++;
        if (good_number(last_checked)) {
            /* enlarge storage if necessary */
            if (valid_len >= cap) {
                cap *= 2;
                seq_t *tmp = (seq_t *)realloc(valid, cap * sizeof(seq_t));
                if (tmp == NULL)
                    return (seq_t)0;  /* out‑of‑memory */
                valid = tmp;
            }
            valid[valid_len++] = (seq_t)last_checked;
        }
    }

    return valid[n - 1];  /* a(1) is stored at index 0 */
}
