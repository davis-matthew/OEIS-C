/*
 * A068309  Number of different lucky numbers occurring when 2n is expressed
 *          as p1+q1 = ... = pk+qk where pk,qk are lucky numbers with pk <=
 *          qk.
 * https://oeis.org/A068309
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 78, u16 n <= 78, u32 n <= 78, u64 n <= 78, u128 n <= 78,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Computes A068309: for n≥1, a(n) = |{p : p is lucky and ∃q ≥ p lucky with p+q = 2n}|.
 *  Lucky numbers are generated by the classical sieve starting from the odd integers.
 *  The sieve is recomputed lazily whenever a larger value of 2*n is requested. */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdint.h>

/* ----------  Cache of lucky numbers  ---------- */
struct LuckyCache {
    size_t limit;          /* current upper bound of generated lucky numbers         */
    size_t count;          /* number of lucky numbers in 'values'                     */
    int   *values;         /* sorted lucky numbers                                   */
    unsigned char *is_lucky;   /* bitmap: is_lucky[v]==1 if v is lucky                  */
    int   *index_of;       /* index_of[v]==position in 'values', -1 if not lucky      */
};

static struct LuckyCache cache = {0, 0, NULL, NULL, NULL};

/* Recompute the lucky numbers up to 'new_limit'.
 * The entire list must be regenerated because the sieve depends
 * on all numbers up to the limit. */
static void recompute_lucky(size_t new_limit)
{
    size_t odd_count = (new_limit + 1) / 2;
    int *array = (int *)malloc(odd_count * sizeof(int));
    size_t len = 0;
    for (int v = 1; v <= (int)new_limit; v += 2)
        array[len++] = v;

    /* Sieve: remove every step‑th element where step is the i‑th lucky number */
    for (size_t i = 1; i < len; ++i) {
        int step = array[i];
        if (step > (int)len)
            break;
        size_t dst = 0;
        for (size_t j = 0; j < len; ++j) {
            if ((j + 1) % step != 0)
                array[dst++] = array[j];
        }
        len = dst;
    }

    /* Allocate final structures */
    int *values = (int *)malloc(len * sizeof(int));
    for (size_t i = 0; i < len; ++i)
        values[i] = array[i];
    free(array);

    unsigned char *is_lucky = (unsigned char *)calloc(new_limit + 1, sizeof(unsigned char));
    int *index_of = (int *)malloc((new_limit + 1) * sizeof(int));
    for (size_t i = 0; i <= new_limit; ++i)
        index_of[i] = -1;
    for (size_t i = 0; i < len; ++i) {
        int v = values[i];
        is_lucky[v] = 1;
        index_of[v] = (int)i;
    }

    /* Free old cache and store new data */
    free(cache.values);
    free(cache.is_lucky);
    free(cache.index_of);
    cache.limit    = new_limit;
    cache.count    = len;
    cache.values   = values;
    cache.is_lucky = is_lucky;
    cache.index_of = index_of;
}

/* Ensure that lucky numbers are available up to 'required' (value must be >0). */
static void ensure_limit(size_t required)
{
    if (required <= cache.limit)
        return;
    recompute_lucky(required);
}

/* ----------  Sequence function  ---------- */
seq_t a(idx_t n)
{
    if (n == 0)          /* undefined for n<1; return 0 for safety */
        return 0;

    size_t target = (size_t)n * 2;          /* 2*n for the sum */
    ensure_limit(target);                   /* make sure we have luckies up to target */

    unsigned char *seen = (unsigned char *)calloc(cache.count, sizeof(unsigned char));
    size_t idx;
    for (idx = 0; idx < cache.count; ++idx) {
        int p = cache.values[idx];
        if ((size_t)p > target)
            break;
        int q = (int)target - p;
        if (q < p)                /* keep p ≤ q, avoid double counting pairs */
            continue;
        if (q <= (int)cache.limit && cache.is_lucky[q]) {
            int idx_q = cache.index_of[q];
            if (idx_q >= 0) {
                seen[idx]   = 1;
                seen[idx_q] = 1;
            }
        }
    }

    /* Count distinct lucky numbers that appeared */
    size_t cnt = 0;
    for (idx = 0; idx < cache.count; ++idx)
        if (seen[idx]) ++cnt;

    free(seen);
    return (seq_t)cnt;
}
