/*
 * A068807  Primes whose sum of digits is a power of 2.
 * https://oeis.org/A068807
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 15, u16 n <= 666, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   digit_sum, is_power_of_two, next_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the n‑th prime whose decimal digit
   sum is a power of two.  The sequence is generated by a
   simple search over successive primes and is memoised
   so that any order of calls is supported. */

#include <stdlib.h>        /* malloc, realloc, size_t */
#include <stddef.h>        /* size_t */
#include <stdint.h>        /* uint64_t */
#include <stdbool.h>       /* bool */

#include "../utils/next_prime.h"      /* uint64_t next_prime(uint64_t) */
#include "../utils/digit_sum.h"       /* seq_t digit_sum(seq_t) */
#include "../utils/is_power_of_two.h" /* bool is_power_of_two(seq_t) */

/* Static cache of qualifying primes. */
static seq_t *cache     = NULL;   /* array of primes */
static size_t cache_len = 0;      /* number of cached elements */
static size_t cache_cap = 0;      /* current capacity of cache */

/* Return the n-th term of the sequence (n ≥ 1). */
seq_t a(idx_t n)
{
    /* n is guaranteed to be ≥ 1 in the OEIS tests, but guard
       against n == 0 in case the function is mis‑used. */
    if (n == 0) {
        return 0;
    }

    /* Return from cache if already computed. */
    if (n <= (idx_t)cache_len) {
        return cache[(size_t)(n - 1)];
    }

    /* Start searching from the prime following the last cached one
       (or from 1 if nothing has been cached). */
    uint64_t last_prime = (cache_len > 0) ? (uint64_t)cache[cache_len - 1] + 1
                                          : 1U;

    /* Keep looking until we have found n qualifying primes. */
    while (cache_len < (size_t)n) {
        /* Find next prime ≥ last_prime. */
        last_prime = next_prime(last_prime);

        /* Check whether this prime satisfies the digit‑sum property. */
        seq_t sum = digit_sum((seq_t)last_prime);
        if (is_power_of_two(sum)) {
            /* Grow the cache if necessary. */
            if (cache_len == cache_cap) {
                size_t new_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) {          /* allocation failure */
                    return 0;
                }
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = (seq_t)last_prime;
        }

        /* Move to the next candidate for the next loop iteration. */
        last_prime++;
    }

    /* Now cache_len == n, so return the newly added element. */
    return cache[(size_t)(n - 1)];
}
