/*
 * A283024  Natural numbers n such that the number of primes of the form
 *          d(n)/x is equal to the number of primes of the form sigma(n)/y
 *          where x, y are divisors of n.
 * https://oeis.org/A283024
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   factor_u64, is_prime_big, is_prime_small, pow_uint
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the nth term of OEIS sequence A283024.
   a(1) = 1, a(2) = 2, a(3) = 4, ….
   The sequence is generated by scanning the natural numbers
   and collecting those for which the number of primes among
   the values d(n)/x (x|n) equals the number of primes among
   sigma(n)/y (y|n).  The result is memoised so that repeated
   calls with arbitrary ordering of n are fast.  The code
   uses the helper routines supplied in the utils directory
   (factor_u64, pow_uint, is_prime_small, is_prime_big). */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

#include "../utils/factor_u64.h"   /* factor_u64 */
#include "../utils/pow_uint.h"     /* pow_uint */
#include "../utils/is_prime_small.h" /* is_prime_small */
#include "../utils/is_prime_big.h"   /* is_prime_big */

/* Recursively generate all divisors of a number from its prime
   factorisation.  The array 'out' must have enough space for all
   divisors. */
static void
gen_divisors(uint64_t cur, size_t idx,
             const uint64_t *pr, const uint64_t *ex,
             size_t cnt, uint64_t *out, size_t *pos)
{
    if (idx == cnt) {
        out[*pos] = cur;
        (*pos)++;
        return;
    }
    uint64_t p = pr[idx];
    uint64_t val = cur;
    for (size_t e = 0; e <= ex[idx]; ++e) {
        gen_divisors(val, idx + 1, pr, ex, cnt, out, pos);
        val *= p;
    }
}

/* Storage for the terms of the sequence that have been found so far. */
static seq_t  *seq  = NULL;
static size_t seq_len = 0;
static size_t seq_cap = 0;
static uint64_t     tested_n = 1;  /* Next natural number to test */

/* Ensure that the array 'seq' contains at least 'target' terms. */
static void
ensure_terms(idx_t target)
{
    while (seq_len < target) {
        /* Factorise tested_n */
        uint64_t primes[64];
        uint64_t exps[64];
        size_t   cnt = 0;
        factor_u64(tested_n, primes, exps, &cnt);

        /* Number of divisors d(n) */
        uint64_t dN = 1;
        for (size_t i = 0; i < cnt; ++i)
            dN *= (exps[i] + 1);

        /* Sum of divisors sigma(n) */
        seq_t sigma = 1;
        for (size_t i = 0; i < cnt; ++i) {
            seq_t term = (pow_uint(primes[i], exps[i] + 1) - 1) /
                         (primes[i] - 1);
            sigma *= term;
        }

        /* Generate all divisors of tested_n */
        uint64_t num_divs = 1;
        for (size_t i = 0; i < cnt; ++i)
            num_divs *= (exps[i] + 1);

        uint64_t *divs = (uint64_t *)malloc(num_divs * sizeof(uint64_t));
        if (!divs) abort();
        size_t pos = 0;
        gen_divisors(1, 0, primes, exps, cnt, divs, &pos);

        /* Count primes among d(n)/x */
        size_t count_d = 0;
        for (size_t i = 0; i < num_divs; ++i) {
            uint64_t x = divs[i];
            if (x == 0) continue;
            if (dN % x == 0) {
                uint64_t q = dN / x;
                if (is_prime_small((seq_t)q))
                    ++count_d;
            }
        }

        /* Count primes among sigma(n)/y */
        size_t count_sigma = 0;
        for (size_t i = 0; i < num_divs; ++i) {
            uint64_t y = divs[i];
            if (y == 0) continue;
            if ((sigma % (seq_t)y) == 0) {
                seq_t q = sigma / (seq_t)y;
                if (is_prime_big(q))
                    ++count_sigma;
            }
        }

        free(divs);

        /* If the counts are equal, record tested_n */
        if (count_d == count_sigma) {
            if (seq_len >= seq_cap) {
                size_t new_cap = seq_cap ? seq_cap * 2 : 8;
                seq_t *tmp = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
                if (!tmp) abort();
                seq = tmp;
                seq_cap = new_cap;
            }
            seq[seq_len] = (seq_t)tested_n;
            ++seq_len;
        }

        ++tested_n;
    }
}

/* Public function returning the nth term (1‑based index). */
seq_t a(idx_t n)
{
    if (n < 1)
        return 0;
    ensure_terms(n);
    return seq[n - 1];
}
