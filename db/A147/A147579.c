/* Sequence A147579:
   Numbers with exactly 6 distinct odd prime divisors {3,5,7,11,13,17}.
   The sequence is generated by enumerating all products
   3^a * 5^b * 7^c * 11^d * 13^e * 17^f with a,b,c,d,e,f >= 1
   in ascending order using a multi‑pointer sieve. */
#include <stdlib.h>

seq_t a(idx_t n)
{
    /* static state: sequence cache and pointer indices for each prime */
    static seq_t *seq = NULL;
    static size_t seq_len = 0;
    static size_t seq_cap = 0;
    static size_t idx[6] = {0,0,0,0,0,0};

    /* primes used in the sequence */
    static const seq_t primes[6] = {(seq_t)3,(seq_t)5,(seq_t)7,
                                   (seq_t)11,(seq_t)13,(seq_t)17};

    /* ensure cache capacity */
    if (!seq_cap) {
        seq_cap = 16;
        seq = (seq_t *)malloc(seq_cap * sizeof(seq_t));
    }

    /* base element: product of all six primes (exponents = 1) */
    if (seq_len == 0) {
        seq[0] = (seq_t)3 * 5 * 7 * 11 * 13 * 17;
        seq_len = 1;
    }

    /* target index (zero‑based) */
    size_t target = (size_t)(n - 1);
    if (target >= seq_len) {
        /* grow cache as needed */
        while (seq_len <= target) {
            /* allocate more space if required */
            if (seq_len >= seq_cap) {
                size_t new_cap = seq_cap * 2;
                seq = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
                seq_cap = new_cap;
            }

            /* compute the smallest candidate among all primes */
            seq_t min_candidate = seq[idx[0]] * primes[0];
            for (size_t i = 1; i < 6; ++i) {
                seq_t cand = seq[idx[i]] * primes[i];
                if (cand < min_candidate)
                    min_candidate = cand;
            }

            /* append the new term */
            seq[seq_len++] = min_candidate;

            /* advance all indices that produced this candidate */
            for (size_t i = 0; i < 6; ++i) {
                if (seq[idx[i]] * primes[i] == min_candidate)
                    idx[i]++;
            }
        }
    }

    return seq[target];
}
