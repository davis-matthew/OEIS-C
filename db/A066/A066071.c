#include "../utils/mem.h"

/* -----------------  Generic primality test ------------------------ */
static bool isPrimeGeneric(seq_t n)
{
    /* all seq_t are unsigned; use the smallest type that fits */
    if ((seq_t)(ULLONG_MAX) >= n) {
        return is_prime_u64((uint64_t)n);
    }
#if defined(__SIZEOF_INT128__)
    return is_prime_u128((__uint128_t)n);
#else
    /* fallback: if seq_t > 64‑bit but no 128‑bit support,
       order the test as simple trial division up to sqrt */
    seq_t limit = 0;
    for (seq_t i = 2; i*i <= n; ++i) {
        if (n % i == 0) return false;
    }
    return true;
#endif
}

seq_t a(idx_t n)
{
    /* Static cache of already found valid terms. */
    static seq_t *cache       = NULL;
    static size_t cache_len   = 0;
    static size_t cache_cap   = 0;
    static idx_t  next_candidate = 1;   /* start scanning from 1 */

    /* Largest value representable in seq_t. */
    const seq_t  max_seq_val  = ~((seq_t)0);
    const idx_t  max_idx_val  = (idx_t)max_seq_val;

    /* Ensure we have at least n terms in the cache. */
    while (cache_len < n) {
        /* Stop if we would overflow seq_t on the next candidate. */
        if (next_candidate > max_idx_val) break;

        seq_t x = (seq_t)next_candidate;
        bool ok = false;

        if (next_candidate == 1) {
            /* 1 is included by definition. */
            seq_t phi = totient_seq(x);
            ok = isPrimeGeneric(phi + 1);
        } else if (!is_prime(next_candidate)) {   /* only composites */
            seq_t phi = totient_seq(x);
            ok = isPrimeGeneric(phi + 1);
        }

        if (ok) {
            if (cache_len == cache_cap) {
                /* Grow the cache – start at 16, double each time. */
                cache_cap = cache_cap ? cache_cap << 1 : 16;
                cache = mem_resize(seq_t, cache, cache_cap);
            }
            cache[cache_len++] = x;
        }

        ++next_candidate;
    }

    /* Return the (n-1)-th element (a(1) = first term). */
    return cache[n - 1];
}
