/*
 * A066071  Nonprime numbers k such that phi(k) + 1 is prime.
 * https://oeis.org/A066071
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 104, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   calc_phi, isPrimeGeneric, is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A066071 – Non‑prime numbers k such that φ(k)+1 is prime.
   Generated by scanning integers in order and selecting those that
   (a) are not prime (1 is included), and (b) satisfy isPrimeGeneric(φ(k)+1). */

#include <stdbool.h>
#include <stdlib.h>
#include "../utils/calc_phi.h"
#include "../utils/isPrimeGeneric.h"
#include "../utils/is_prime.h"

seq_t a(idx_t n)
{
    /* Static cache of already found valid terms. */
    static seq_t *cache       = NULL;
    static size_t cache_len   = 0;
    static size_t cache_cap   = 0;
    static idx_t  next_candidate = 1;   /* start scanning from 1 */

    /* Largest value representable in seq_t. */
    const seq_t  max_seq_val  = ~((seq_t)0);
    const idx_t  max_idx_val  = (idx_t)max_seq_val;

    /* Ensure we have at least n terms in the cache. */
    while (cache_len < n) {
        /* Stop if we would overflow seq_t on the next candidate. */
        if (next_candidate > max_idx_val) break;

        seq_t x = (seq_t)next_candidate;
        bool ok = false;

        if (next_candidate == 1) {
            /* 1 is included by definition. */
            seq_t phi = calc_phi(x);
            ok = isPrimeGeneric(phi + 1);
        } else if (!is_prime(next_candidate)) {   /* only composites */
            seq_t phi = calc_phi(x);
            ok = isPrimeGeneric(phi + 1);
        }

        if (ok) {
            if (cache_len == cache_cap) {
                /* Grow the cache – start at 16, double each time. */
                cache_cap = cache_cap ? cache_cap << 1 : 16;
                cache = (seq_t *)realloc(cache, cache_cap * sizeof(*cache));
            }
            cache[cache_len++] = x;
        }

        ++next_candidate;
    }

    /* Return the (n-1)-th element (a(1) = first term). */
    return cache[n - 1];
}
