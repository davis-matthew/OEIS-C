/*
 * A066651  Primes of the form 2*s + 1, where s is a squarefree number
 *          (A005117).
 * https://oeis.org/A066651
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 32, u16 n <= 3686, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   is_prime, is_squarefree
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The A066651 sequence: 
   a(n) = the nth prime p such that (p-1)/2 is squarefree.  
   The sequence is generated by a simple search up to the required
   index; it is memoised so that calls for any n are fast.      */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/is_prime.h"          /* bool is_prime(idx_t)      */
#include "../utils/is_squarefree.h"    /* bool is_squarefree(seq_t) */

static seq_t *cache = NULL;     /* cached sequence values      */
static size_t cache_len = 0;    /* number of cached values     */
static size_t cache_cap = 0;    /* current capacity of cache   */
static uint64_t last_checked_prime = 2; /* last inspected prime  */

/* Grow the cache if needed and append a new value.  */
static void append_cache(seq_t val)
{
    if (cache_len == cache_cap) {
        cache_cap = (cache_cap == 0) ? 16 : (cache_cap << 1);
        cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        if (!cache) exit(EXIT_FAILURE);
    }
    cache[cache_len++] = val;
}

/* Ensure that cache contains at least n elements.          */
static void ensure_cache(idx_t n)
{
    if (cache == NULL) {
        cache_cap = 16;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache) exit(EXIT_FAILURE);
        cache_len = 0;
    }

    while (cache_len < (size_t)n) {
        /* Find next prime after last_checked_prime. */
        uint64_t cand = last_checked_prime + 1;
        if ((cand & 1) == 0)  /* skip even numbers */
            ++cand;

        for (;;) {
            if (is_prime(cand)) {
                /* candidate is prime */
                seq_t s = ((seq_t)(cand - 1)) / 2;
                if (is_squarefree(s))
                    append_cache((seq_t)cand);
                last_checked_prime = cand;
                break;
            } else {
                cand += 2;  /* only odd candidates */
            }
        }
    }
}

/* Public function required by the framework.                */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* offset 1; undefined for n==0 */
    ensure_cache(n);
    return cache[(size_t)n - 1];
}
