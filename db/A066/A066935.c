/* Sequence A066935: numbers k such that
 *    bigomega(k+1) ≡ 0 (mod bigomega(k))
 *
 * The sequence is generated by brute‑force search, caching results
 * so that any previous terms can be returned instantly.
 *
 * Only the function `bigomega(idx_t)` is needed from the utilities.
 */
#include <stddef.h>
#include <stdlib.h>

#include "../utils/bigomega.h"

seq_t a(idx_t n)
{
    /* Cache of already found terms (1‑based indexing). */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;   /* Number of terms stored */
    static size_t cache_cap = 0;   /* Allocated capacity */
    static idx_t next_k = 2;       /* Next candidate to test (k ≥ 2) */

    /* Initialise cache lazily. */
    if (cache_cap == 0) {
        cache_cap = 64;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
    }

    /* Extend cache until we have at least `n` terms. */
    while (cache_len < (size_t)n) {
        /* Search forward for the next valid k. */
        for (;;) {
            seq_t wk = bigomega(next_k);
            /* wk will never be 0 for next_k ≥ 2, but we guard against
             * that to keep the logic safe. */
            if (wk) {
                seq_t wk1 = bigomega(next_k + (idx_t)1);
                if ((wk1 % wk) == 0)
                    break;            /* Valid term found. */
            }
            ++next_k;
        }

        /* Store the found term in the cache. */
        if (cache_len == cache_cap) {
            cache_cap <<= 1;
            cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        }
        cache[cache_len++] = (seq_t)next_k;

        /* Prepare for the next search. */
        ++next_k;
    }

    return cache[n - 1];
}
