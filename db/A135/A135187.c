/*
 * A135187  Numbers n that raised to the powers from 1 to k (with k>=1) are
 *          multiple of the sum of their digits (n raised to k+1 must not be a
 *          multiple). Case k=2.
 * https://oeis.org/A135187
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 2, u32 n <= 49, u64 n <= 49, u128 n <= 49,
 *            big any n
 * Helpers:   digit_sum, pow_seq
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A135187: numbers n such that   n^1 and n^2 are multiples of the sum
   of their digits, but n^3 is not.  The sequence is generated by testing
   successive integers; cached values give O(1) random access. */
#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/digit_sum.h"   /* seq_t digit_sum(seq_t v); */
#include "../utils/pow_seq.h"     /* seq_t pow_seq(seq_t a, int k); */

static seq_t *cache = NULL;          /* stored terms */
static size_t cache_len = 0;          /* number of terms stored */
static size_t cache_cap = 0;          /* allocated capacity */
static idx_t last_checked = 0;        /* largest integer examined so far */

/* Test whether n satisfies the A135187 conditions (k = 2). */
static bool check_candidate(seq_t n)
{
    seq_t s1 = digit_sum(n);
    if (n % s1 != 0) return false;

    seq_t n2 = pow_seq(n, 2);
    seq_t s2 = digit_sum(n2);
    if (n2 % s2 != 0) return false;

    seq_t n3 = pow_seq(n, 3);
    seq_t s3 = digit_sum(n3);
    /* n^3 must NOT be a multiple of its digit sum */
    return (n3 % s3) != 0;
}

/* Ensure the cache has enough capacity. */
static void grow_cache(void)
{
    if (cache_len >= cache_cap) {
        size_t new_cap = cache_cap ? (cache_cap << 1) : 8;
        seq_t *new_arr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!new_arr) abort();   /* out of memory */
        cache = new_arr;
        cache_cap = new_cap;
    }
}

/* Return the n‑th term of the sequence; n ≥ 1.  Random access is
   supported via a static cache: the cache is extended lazily until it
   contains at least n terms. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* out of bounds, return 0 */

    while (cache_len < (size_t)n) {
        ++last_checked;
        seq_t cand = (seq_t)last_checked;
        if (check_candidate(cand)) {
            grow_cache();
            cache[cache_len++] = cand;
        }
    }
    return cache[n - 1];
}
