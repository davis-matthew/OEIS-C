/*  A135877 – Triangle generated by inserting zeros at positions
 *  floor(((m+1)^2)/4) - 1   (m=1..2r+2) for row r
 *  and taking suffix sums from right to left.
 *  a(0) = 1; the sequence is the triangle read row by row.
 */

#include <stddef.h>
#include <stdlib.h>

seq_t a(idx_t n)
{
    /*  State kept between calls  */
    static seq_t *seq = NULL;      /* linearised sequence of terms      */
    static idx_t  seq_cap = 0;     /* allocated size of seq             */
    static idx_t  seq_len = 0;     /* number of elements stored in seq   */

    static seq_t *row = NULL;      /* the current row (last generated)   */
    static idx_t  row_len = 0;     /* length of the current row          */
    static idx_t  row_idx = 0;     /* its index (0‑based)                */

    /*  Initialisation  */
    if (seq == NULL) {
        /* row 0  */
        row_len = 1;
        row = (seq_t *)malloc(sizeof(seq_t) * row_len);
        row[0] = (seq_t)1;

        /* linearisation beginning with row 0  */
        seq_cap = 64;
        seq = (seq_t *)malloc(sizeof(seq_t) * seq_cap);
        seq[0] = row[0];
        seq_len = 1;
    }

    /*  Generate rows until we have enough terms  */
    while (seq_len <= n) {
        /*  Determine number of zeros to insert  */
        idx_t zeros = 2 * row_idx + 2;               /* 2r+2 for row r */
        idx_t new_len = row_len + zeros;             /* length of the next row */

        /*  Allocate array for intermediate values (pre‑sums)  */
        seq_t *mid = (seq_t *)malloc(sizeof(seq_t) * new_len);
        for (idx_t i = 0; i < new_len; ++i) mid[i] = (seq_t)0;

        /*  Mark zero positions  */
        idx_t *is_zero = (idx_t *)calloc((size_t)new_len, sizeof(idx_t));
        for (idx_t m = 1; m <= zeros; ++m) {
            idx_t pos = ((m + 1) * (m + 1)) / 4 - 1;
            if (pos < new_len) is_zero[pos] = 1;
        }

        /*  Fill non‑zero positions with elements of the previous row  */
        idx_t rpos = 0;
        for (idx_t i = 0; i < new_len; ++i) {
            if (is_zero[i]) continue;   /* zero stays 0 */
            mid[i] = row[rpos++];
        }
        free(is_zero);

        /*  Compute suffix sums from right to left  */
        for (idx_t i = new_len - 1; i > 0; --i) {
            mid[i - 1] += mid[i];
        }

        /*  Append the new row to the linearised sequence  */
        if (seq_cap < seq_len + new_len) {
            idx_t new_cap = seq_cap ? seq_cap * 2 : 64;
            while (new_cap < seq_len + new_len) new_cap *= 2;
            seq = (seq_t *)realloc(seq, sizeof(seq_t) * new_cap);
            seq_cap = new_cap;
        }
        for (idx_t i = 0; i < new_len; ++i) {
            seq[seq_len++] = mid[i];
        }

        /*  Prepare for next iteration  */
        free(row);
        row = mid;
        row_len = new_len;
        ++row_idx;
    }

    return seq[n];
}
