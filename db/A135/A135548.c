/*
 * A135548  Numbers in A134651 which are the sum of two terms from A001043 in
 *          a unique way.
 * https://oeis.org/A135548
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 58, u16 n <= 58, u32 n <= 58, u64 n <= 58, u128 n <= 58,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A135548: sum of two terms from A001043 in a unique way.
   The values are generated by counting all sums S[i]+S[j] where
   S[k] = prime[k] + prime[k+1] (sum of consecutive primes).
   a(n) is the nth value for which that sum representation is unique. */
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

static seq_t *seq_cache = NULL;   /* array of unique sums, 0‑based */
static size_t seq_len   = 0;       /* number of values stored */

/* Generate enough terms to satisfy a requested index n. */
static void compute_sequence(idx_t n)
{
    if (seq_len >= (size_t)n) return;          /* already have them */

    /* start with a modest range; if not enough, double it */
    idx_t M = n * 10 > 1000 ? n * 10 : 1000;   /* upper bound for sums */

    while (1) {
        /* 1. Sieve primes up to limitPrime */
        idx_t limitPrime = M / 2 + 10;         /* enough to produce S <= M */
        bool *is_prime = (bool *)malloc((size_t)(limitPrime + 1));
        if (!is_prime) { return; }
        memset(is_prime, 1, (size_t)(limitPrime + 1));
        is_prime[0] = is_prime[1] = 0;
        for (idx_t i = 2; i * i <= limitPrime; ++i)
            if (is_prime[i])
                for (idx_t j = i * i; j <= limitPrime; j += i)
                    is_prime[j] = 0;

        /* collect primes */
        size_t prime_cnt = 0;
        for (idx_t i = 2; i <= limitPrime; ++i)
            if (is_prime[i]) ++prime_cnt;
        uint64_t *primes = (uint64_t *)malloc(prime_cnt * sizeof(uint64_t));
        if (!primes) { free(is_prime); return; }
        size_t pk = 0;
        for (idx_t i = 2; i <= limitPrime; ++i)
            if (is_prime[i]) primes[pk++] = (uint64_t)i;
        free(is_prime);

        /* 2. Build list S of sums of consecutive primes, up to M */
        size_t S_cnt = (pk >= 2) ? pk - 1 : 0;
        uint64_t *S = (uint64_t *)malloc(S_cnt * sizeof(uint64_t));
        if (!S) { free(primes); return; }
        for (size_t i = 0; i < S_cnt; ++i)
            S[i] = primes[i] + primes[i + 1];
        free(primes);
        /* Trim S to values <= M to reduce work */
        size_t S_len = 0;
        for (size_t i = 0; i < S_cnt; ++i)
            if (S[i] <= (uint64_t)M) S[S_len++] = S[i];
        /* now S[0..S_len-1] are relevant */

        /* 3. Count sums S[i]+S[j] <= M (unordered pairs) */
        uint8_t *cnt = (uint8_t *)calloc((size_t)M + 1, sizeof(uint8_t));
        if (!cnt) { free(S); return; }
        for (size_t i = 0; i < S_len; ++i) {
            for (size_t j = i; j < S_len; ++j) {
                uint64_t sum = S[i] + S[j];
                if (sum > (uint64_t)M) break;  /* further j only larger */
                if (cnt[(size_t)sum] < 2) ++cnt[(size_t)sum];
            }
        }
        free(S);

        /* 4. Collect values with exactly one representation */
        size_t new_len = 0;
        for (size_t v = 1; v <= (size_t)M; ++v)
            if (cnt[v] == 1) ++new_len;

        seq_t *new_cache = (seq_t *)malloc(new_len * sizeof(seq_t));
        if (!new_cache) { free(cnt); return; }
        size_t idx = 0;
        for (size_t v = 1; v <= (size_t)M; ++v)
            if (cnt[v] == 1) new_cache[idx++] = (seq_t)v;
        free(cnt);

        /* Replace old cache */
        free(seq_cache);
        seq_cache = new_cache;
        seq_len   = new_len;

        if (seq_len >= (size_t)n) break;           /* enough terms */
        /* Not enough: try again with a larger M */
        M *= 2;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;           /* offset is 1 */
    compute_sequence(n);                   /* ensure cache contains nth */
    if (seq_len < (size_t)n) return (seq_t)0; /* should not happen */
    return seq_cache[(size_t)n - 1];
}
