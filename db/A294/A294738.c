/*  Compute terms of OEIS A294738:
    Numbers that are the sum of five non‑zero squares in exactly four unordered ways.
    The function a(n) returns the n‑th such number (a(1)=62).  The values are
    generated by a dynamic‑programming sieve over squares up to an upper bound
    that safely includes all terms known to exist (≤ 60000).  */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

seq_t a(idx_t n)
{
    static bool ready = false;   /* have we built the table yet? */
    static seq_t *list = NULL;   /* array of found terms */
    static size_t list_len = 0;  /* number of terms stored */

    if (!ready) {
        /* upper limit that contains all known terms – see the OEIS comment */
        const idx_t LIMIT = 60000;
        /* allocate DP tables: dp[k][val] = number of ways to write val as sum of k squares */
        seq_t **dp = (seq_t **)malloc(6 * sizeof(seq_t *));
        for (int k = 0; k <= 5; ++k)
            dp[k] = (seq_t *)calloc((size_t)LIMIT + 1, sizeof(seq_t));

        dp[0][0] = (seq_t)1;

        /* iterate over the possible square values in nondecreasing order – guarantees unordered combinations */
        for (idx_t t = 1; (idx_t)t * (idx_t)t <= LIMIT; ++t) {
            idx_t s = (idx_t)t * (idx_t)t;
            for (idx_t val = s; val <= LIMIT; ++val) {
                /* for each required number of squares k, add contributions from dp[k-1] */
                for (int k = 1; k <= 5; ++k)
                    dp[k][val] += dp[k - 1][val - s];
            }
        }

        /* collect all values that have exactly four representations as a sum of five squares */
        size_t cap = 64;
        list = (seq_t *)malloc(cap * sizeof(seq_t));
        for (idx_t val = 1; val <= LIMIT; ++val) {
            if (dp[5][val] == (seq_t)4) {
                if (list_len == cap) {
                    cap <<= 1;
                    list = (seq_t *)realloc(list, cap * sizeof(seq_t));
                }
                list[list_len++] = (seq_t)val;
            }
        }

        /* free DP tables */
        for (int k = 0; k <= 5; ++k)
            free(dp[k]);
        free(dp);

        ready = true;
    }

    if (n == 0 || (size_t)n > list_len)
        return (seq_t)0;
    return list[(size_t)n - 1];
}
