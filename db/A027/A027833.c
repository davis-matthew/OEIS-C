/*
 * A027833  Distances between successive 2's in sequence A001223 of
 *          differences between consecutive primes.
 * https://oeis.org/A027833
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1000, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A027833: the distances between successive 2's in the prime‑gap sequence
   A001223.  The sequence is generated by scanning consecutive primes,
   recording the positions where the gap equals 2, and storing the
   differences between successive such positions.  The function keeps a
   cache of already‑computed distances so that calls may be in any order. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* static state for on‑demand computation */
static bool          initialized = false;
static uint32_t      prev_prime = 3;     /* last prime found (p_{k}) */
static idx_t         prev_index = 2;     /* index of that prime (k)       */
static idx_t         last_twin_index = 0;/* index of last gap == 2         */
static uint32_t      next_candidate = 5; /* next odd number to test       */

/* distance array: dist_arr[0] = a(1), dist_arr[1] = a(2), ...   */
static seq_t        *dist_arr = NULL;
static size_t        dist_len = 0;    /* how many distances stored         */
static size_t        dist_cap = 0;    /* allocated capacity                 */

/* ---------- Miller–Rabin primality test (deterministic for 32‑bit) ---------- */
static uint64_t modpow(uint64_t base, uint64_t exp, uint64_t mod)
{
    uint64_t result = 1 % mod;
    uint64_t acc    = base % mod;
    while (exp) {
        if (exp & 1) result = (result * acc) % mod;
        acc = (acc * acc) % mod;
        exp >>= 1;
    }
    return result;
}

static bool is_prime32(uint32_t n)
{
    if (n < 2) return false;
    if (n == 2 || n == 3) return true;
    if ((n & 1) == 0) return false;

    uint32_t d = n - 1;
    int s = 0;
    while ((d & 1) == 0) { d >>= 1; ++s; }

    /* bases sufficient for 32‑bit integers */
    const uint32_t bases[] = {2, 7, 61};
    for (size_t i = 0; i < sizeof(bases)/sizeof(bases[0]); ++i) {
        uint32_t a = bases[i];
        if (a >= n) continue;
        uint64_t x = modpow(a, d, n);
        if (x == 1 || x == n - 1) continue;
        bool cont = false;
        for (int r = 1; r < s; ++r) {
            x = (x * x) % n;
            if (x == n - 1) { cont = true; break; }
        }
        if (!cont) return false;
    }
    return true;
}

/* ---------- dynamic array helpers (with explicit cast) ---------- */
static inline void ensure_dist_cap(size_t need)
{
    if (dist_cap >= need) return;
    size_t new_cap = dist_cap ? dist_cap << 1 : 8;
    while (new_cap < need) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(dist_arr, new_cap * sizeof(seq_t));
    if (!tmp) return;               /* keep old pointer on failure */
    dist_arr = tmp;
    dist_cap = new_cap;
}

/* ---------- ensure static state initialized ---------- */
static void init_once(void)
{
    if (initialized) return;
    /* allocate distance array */
    dist_cap = 8;
    dist_arr = (seq_t *)malloc(dist_cap * sizeof(seq_t));
    dist_len = 0;
    /* initial state reflects primes 2 and 3 */
    prev_prime   = 3;
    prev_index   = 2;
    last_twin_index = 0;
    next_candidate   = 5;
    initialized = true;
}

/* ---------- generate primes until dist_len ≥ n ---------- */
static void generate_up_to(idx_t n)
{
    init_once();
    while (dist_len < n) {
        /* find next prime */
        uint32_t cand;
        do {
            cand = next_candidate;
            next_candidate += 2; /* test only odds */
        } while (!is_prime32(cand));

        /* process gap from prev_prime to cand */
        uint32_t gap = cand - prev_prime;
        if (gap == 2) {
            idx_t twin_idx = prev_index;
            if (last_twin_index != 0) {
                ensure_dist_cap(dist_len + 1);
                dist_arr[dist_len++] = (seq_t)(twin_idx - last_twin_index);
            }
            last_twin_index = twin_idx;
        }

        /* advance state */
        prev_prime = cand;
        ++prev_index;
    }
}

/* ---------- public function ---------- */
seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;
    generate_up_to(n);
    return dist_arr[n - 1];
}
