/* Sequence: even n for which 2*n-5 is a prime of the form 4k+3. */
/* The implementation keeps a static cache: each call ensures that at least n terms are
 * generated by testing successive even numbers with a primality test and the
 * congruence condition. */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/is_prime.h"
#include "../utils/mem.h"

/* --- dynamic array helpers ------------------------------------------- */
static void grow_seq(seq_t **arr, size_t *cap, size_t need)
{
    if (*cap < need) {
        size_t new_cap = (*cap == 0) ? 64 : (*cap << 1);
        while (new_cap < need) new_cap <<= 1;
        seq_t *tmp = mem_resize(seq_t, *arr, (new_cap * sizeof(**arr)) / sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);
        *arr = tmp;
        *cap = new_cap;
    }
}

seq_t a(idx_t n)
{
    /* static cache of found terms */
    static seq_t *cache = NULL;
    static size_t cache_cap = 0;
    static size_t cache_len = 0;
    /* next even number to test (first candidate is 4) */
    static idx_t gen_even = 4;

    if (n == 0) {
        /* undefined for n < 1; return 0 to keep type safety */
        return (seq_t)0;
    }

    /* zero‑based target index */
    idx_t target = n - 1;

    /* generate terms until we have enough to answer this request */
    while (cache_len <= target) {
        idx_t cand  = gen_even;                 /* even candidate */
        idx_t prime = 2 * cand - 5;             /* the candidate prime */

        if (is_prime(prime) && ((prime & 3U) == 3U)) {
            /* grow capacity if necessary */
            if (cache_len == cache_cap) {
                grow_seq(&cache, &cache_cap, cache_len + 1);
            }
            /* store candidate */
            cache[cache_len++] = (seq_t)cand;
        }
        gen_even += 2;   /* next even number to test */
    }

    return cache[target];
}
