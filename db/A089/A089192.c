/*
 * A089192  Numbers n such that 2n - 7 is a prime.
 * https://oeis.org/A089192
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 95, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   mod_mul
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A089192
   a(n) = the nth integer m such that 2*m - 7 is a prime number
   The sequence is generated by searching for the next m whose
   (2*m-7) passes a deterministic Miller–Rabin test for 64‑bit values.
*/

#include <stdint.h>
#include <stdlib.h>
#include "../utils/mod_mul.h"

/* deterministic Miller–Rabin for 64‑bit integers */

static uint64_t mod_pow(uint64_t base, uint64_t exp, uint64_t mod)
{
    uint64_t result = 1;
    while (exp) {
        if (exp & 1) result = mod_mul(result, base, mod);
        base = mod_mul(base, base, mod);
        exp >>= 1;
    }
    return result;
}

static int is_prime_uint64(uint64_t n)
{
    if (n < 2) return 0;
    static const uint64_t smalls[] = {2ULL,3ULL,5ULL,7ULL,11ULL,13ULL,17ULL,19ULL,23ULL,29ULL,31ULL,37ULL};
    for (size_t i = 0; i < sizeof(smalls)/sizeof(smalls[0]); ++i) {
        if (n == smalls[i]) return 1;
        if (n % smalls[i] == 0) return 0;
    }

    uint64_t d = n - 1;
    int s = 0;
    while ((d & 1) == 0) { d >>= 1; ++s; }

    static const uint64_t bases[] = {2ULL, 325ULL, 9375ULL,
                                     28178ULL, 450775ULL, 9780504ULL,
                                     1795265022ULL};
    for (size_t ai = 0; ai < sizeof(bases)/sizeof(bases[0]); ++ai) {
        uint64_t a = bases[ai] % n;
        if (a == 0) continue;
        uint64_t x = mod_pow(a, d, n);
        if (x == 1 || x == n-1) continue;
        int cont = 0;
        for (int r = 1; r < s; ++r) {
            x = mod_mul(x, x, n);
            if (x == n-1) { cont = 1; break; }
        }
        if (!cont) return 0;
    }
    return 1;
}

/* cache of already generated sequence terms */
static seq_t *cache = NULL;
static idx_t cache_size  = 0;
static idx_t cache_cap   = 0;

/* ensure the cache can hold at least 'need' elements */
static void ensure_capacity(idx_t need)
{
    if (need <= cache_cap) return;
    idx_t new_cap = cache_cap ? cache_cap * 2 : 16;
    while (new_cap < need) new_cap *= 2;
    seq_t *tmp = (cache ? (seq_t *)realloc(cache, new_cap * sizeof(seq_t))
                        : (seq_t *)malloc(new_cap * sizeof(seq_t)));
    cache = tmp;
    cache_cap = new_cap;
}

/* the main sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;               /* undefined for 0, but safe */
    if (n <= cache_size) return cache[n-1];

    ensure_capacity(n);

    uint64_t candidate = (cache_size == 0) ? 5ULL : (uint64_t)cache[cache_size-1] + 1ULL;

    while (cache_size < n) {
        uint64_t p = 2ULL * candidate - 7ULL;
        if (is_prime_uint64(p))
            cache[cache_size++] = (seq_t)candidate;
        ++candidate;
    }
    return cache[n-1];
}
