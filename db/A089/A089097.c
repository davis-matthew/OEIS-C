/*
 * A089097  Convoluted convolved Fibonacci numbers G_j^(10).
 * https://oeis.org/A089097
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = (1/10) * (coeff of z^{n-1} in (1 - z - z^2)^10 - coeff of
 *            z^{n-1} in (1 - z^2 - z^4)^5 - coeff of z^{n-1} in (1 - z^5 -
 *            z^10)^2 + coeff of z^{n-1} in (1 - z^10 - z^20) )
 * Range:     u8 n <= 3, u16 n <= 8, u32 n <= 19, u64 n <= 27, u128 n <= 27,
 *            big any n
 * Helpers:   mul_small, poly_pow
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The following implementation computes the sequences generated by the four
   denominators by using the linear recurrences satisfied by 1/P(z) where
   P(z) is each denominator polynomial.  The coefficients of the
   polynomials are precalculated once.  For a series S(z)=1/P(z), the
   coefficients S_k satisfy
          S_0 = 1
          S_k = -∑_{i=1..deg} coeff_P[i] * S_{k-i}
   The code computes S_k for k = 0 … n-1, then evaluates the formula
   above.  All calculations are performed with the generic integer type
   seq_t, using only the allowed operators.  The helper function
   mul_small from "../utils/mul_small.h" is used to multiply a seq_t
   by a small signed coefficient.  The implementation is fully
   deterministic and independent of the particular size of seq_t
   (8‑, 16‑, 32‑, 64‑, 128‑bit, or arbitrary‑precision). */

#include <stdlib.h>
#include <stdint.h>
#include "../utils/mul_small.h"
#include "../utils/poly_pow.h"

static void compute_series(seq_t *arr, size_t needed,
                           const int64_t *coeff, int deg)
{
    if (needed == 0) return;
    arr[0] = 1;
    for (size_t k = 1; k < needed; ++k) {
        seq_t add = 0;
        seq_t sub = 0;
        for (int i = 1; i <= deg && (size_t)i <= k; ++i) {
            int64_t c = coeff[i];
            if (c == 0) continue;
            unsigned int m = (c < 0 ? (unsigned int)(-c) : (unsigned int)c);
            seq_t term = mul_small(arr[k - i], m);
            if (c < 0)
                add += term;
            else
                sub += term;
        }
        arr[k] = add - sub;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;

    static int64_t coeffA[21], coeffB[21], coeffC[21], coeffD[21];
    static int degA, degB, degC, degD;
    static int initialized = 0;

    if (!initialized) {
        /* (1 - z - z^2)^10 */
        int64_t baseA[3] = {1, -1, -1};
        poly_pow(baseA, 2, 10, coeffA, &degA);

        /* (1 - z^2 - z^4)^5 */
        int64_t baseB[5] = {1, 0, -1, 0, -1};
        poly_pow(baseB, 4, 5, coeffB, &degB);

        /* (1 - z^5 - z^10)^2 */
        int64_t baseC[11] = {0};
        baseC[0] = 1;
        baseC[5] = -1;
        baseC[10] = -1;
        poly_pow(baseC, 10, 2, coeffC, &degC);

        /* (1 - z^10 - z^20) */
        for (int i = 0; i < 21; ++i) coeffD[i] = 0;
        coeffD[0] = 1;
        coeffD[10] = -1;
        coeffD[20] = -1;
        degD = 20;

        initialized = 1;
    }

    size_t len = (size_t)n;   /* need indices 0 .. n-1 */

    seq_t *A = (seq_t*)malloc(len * sizeof(seq_t));
    seq_t *B = (seq_t*)malloc(len * sizeof(seq_t));
    seq_t *C = (seq_t*)malloc(len * sizeof(seq_t));
    seq_t *D = (seq_t*)malloc(len * sizeof(seq_t));

    compute_series(A, len, coeffA, degA);
    compute_series(B, len, coeffB, degB);
    compute_series(C, len, coeffC, degC);
    compute_series(D, len, coeffD, degD);

    seq_t val = A[len - 1];
    val = val - B[len - 1];
    val = val - C[len - 1];
    val = val + D[len - 1];
    seq_t result = val / 10;

    free(A);
    free(B);
    free(C);
    free(D);

    return result;
}
