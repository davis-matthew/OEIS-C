/*
 * A199825  Number of -1..1 arrays x(0..n+1) of n+2 elements with zero sum and
 *          no two neighbors summing to zero.
 * https://oeis.org/A199825
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 9, u16 n <= 17, u32 n <= 33, u64 n <= 66, u128 n <= 130,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
 * Sequence A199825: Number of arrays x(0..n+1) of length n+2 with entries
 * -1,0,1, total sum zero and no two adjacent entries summing to zero.
 * 
 * The sequence is generated by a dynamic‑programming approach that
 * builds all sequences of increasing length.  For each length `L`
 * (equivalent to `n = L-2`) we keep the number of partial sequences
 * ending in each possible last value (-1, 0, 1) and having each possible
 * partial sum.  The transition rules are only three per state, allowing
 * an O(L^2) algorithm, which runs comfortably within the 2‑second limit
 * for n up to about 10 000.
 */

#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>

#define MAX_N   10000             /* assumed maximum n needed */
#define MAX_LEN (MAX_N + 2)       /* maximum array length L = n+2   */
#define OFFSET  (MAX_LEN + 5)     /* array offset to handle negative sums  */
#define FSIZE   (2 * OFFSET + 1)  /* total size of the DP arrays        */

static seq_t dpPrev[3][FSIZE];      /* DP for the current length L */
static seq_t dpCurr[3][FSIZE];      /* DP for the next length L+1 */

/* Pointers that are swapped instead of copying whole arrays */
static seq_t *dpPrevPtr[3];
static seq_t *dpCurrPtr[3];

/* Cache of sequence values a(n), 1 <= n <= MAX_N */
static seq_t *aCache = NULL;

/* Current length that has been processed so far (dpPrev holds data for this length) */
static idx_t processedL = 0;

/* Transition mapping: from state i to the two allowed next states */
static const int trans[3][2] = {
    {0, 1},   /* from -1 to (-1,0)   */
    {0, 2},   /* from 0  to (-1,1)   */
    {1, 2}    /* from 1  to (0,1)    */
};

/* Value corresponding to each state index */
static const int stepVal[3] = { -1, 0, 1 };

/* One‑time initialization of DP structures and cache */
static void init(void)
{
    if (aCache != NULL)
        return;

    /* Zero all DP arrays */
    for (int s = 0; s < 3; ++s)
        for (idx_t i = 0; i < FSIZE; ++i)
            dpPrev[s][i] = 0;

    /* Begin with length L = 1 */
    dpPrev[0][OFFSET - 1] = 1;  /* entry -1 */
    dpPrev[1][OFFSET]     = 1;  /* entry  0 */
    dpPrev[2][OFFSET + 1] = 1;  /* entry  1 */
    processedL = 1;

    /* Point the pointers to the arrays */
    for (int s = 0; s < 3; ++s) {
        dpPrevPtr[s] = dpPrev[s];
        dpCurrPtr[s] = dpCurr[s];
    }

    /* Allocate cache for a(n) values */
    aCache = (seq_t *)calloc(MAX_N + 1, sizeof(seq_t));
}

/*---------------------------------------------------------------------*/
/*  a(n)  –  OEIS sequence A199825                                    */
/*---------------------------------------------------------------------*/
seq_t a(idx_t n)
{
    /* Ensure structures are ready */
    init();

    /* Guard against requests beyond the pre‑defined maximum */
    if (n > MAX_N) {
        /* For safety this implementation supports only n <= MAX_N.
           If a larger n is requested, the behaviour is undefined
           (the function simply returns 0). */
        return 0;
    }

    /* Desired length L = n + 2    (array length) */
    idx_t targetL = n + 2;

    /* Extend DP to the required length, step by step */
    while (processedL < targetL) {

        /* Current and next lengths */
        idx_t currL  = processedL;     /* length of dpPrev */
        idx_t nextL  = currL + 1;      /* length we are computing */

        /* Zero dpCurr over its new relevant index range */
        idx_t startIdx = OFFSET - nextL;
        idx_t endIdx   = OFFSET + nextL;
        for (int s = 0; s < 3; ++s) {
            for (idx_t i = startIdx; i <= endIdx; ++i)
                dpCurrPtr[s][i] = 0;
        }

        /* Indices that are valid for the current length */
        idx_t currStart = OFFSET - currL;
        idx_t currEnd   = OFFSET + currL;

        /* Transition from all valid states/partial sums */
        for (int prev = 0; prev < 3; ++prev) {
            const seq_t *prevVec = dpPrevPtr[prev];
            for (idx_t idx = currStart; idx <= currEnd; ++idx) {
                seq_t val = prevVec[idx];
                if (!val) continue;          /* skip zero entries */

                /* Two allowed next states for this prev state */
                for (int t = 0; t < 2; ++t) {
                    int next  = trans[prev][t];
                    int step  = stepVal[next];
                    dpCurrPtr[next][idx + step] += val;
                }
            }
        }

        /* Swap pointers: dpCurr becomes the new dpPrev */
        for (int s = 0; s < 3; ++s) {
            seq_t *tmp = dpPrevPtr[s];
            dpPrevPtr[s] = dpCurrPtr[s];
            dpCurrPtr[s] = tmp;
        }

        /* Update processed length */
        processedL = nextL;

        /* Store a(n) for n = processedL - 2 (only when length >= 3) */
        if (processedL >= 3) {
            idx_t nIdx = processedL - 2;            /* corresponding n */
            seq_t sum  = dpPrevPtr[0][OFFSET] + dpPrevPtr[1][OFFSET] + dpPrevPtr[2][OFFSET];
            aCache[nIdx] = sum;
        }
    }

    /* Return the cached value */
    return aCache[n];
}
