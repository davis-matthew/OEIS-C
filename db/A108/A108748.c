/* Sequence: A108748 – numbers of the form 9^i * 13^j, with i, j ≥ 0.
   The first term (i = j = 0) is 1.  The sequence is generated by
   the classic super‑ugly‑number algorithm using two factors 9 and 13.

   Eq. 1:  a(1) = 1
   a(n) = min( 9 * a(i9), 13 * a(i13) ),  with i9 and i13 updated
   as the indices that produced the last chosen candidate.
   Duplicates are removed by advancing both indices when the
   candidates are equal. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

static seq_t *terms = NULL;   /* array of computed terms */
static idx_t  terms_size  = 0;/* number of terms stored     */
static idx_t  terms_cap   = 0;/* allocated array capacity   */
static idx_t  i9   = 0;       /* index for next 9‑multiple    */
static idx_t  i13  = 0;       /* index for next 13‑multiple   */

static void ensure_capacity(void)
{
    if (terms_size < terms_cap)
        return;
    size_t new_cap = terms_cap ? terms_cap * 2 : 16;
    seq_t *tmp = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
    if (!tmp) abort();             /* unlikely OOM */
    terms       = tmp;
    terms_cap   = new_cap;
}

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;           /* undefined for 0, but harmless */

    /* Initialise on first call */
    if (!terms) {
        terms_cap   = 16;
        terms       = (seq_t *)malloc(terms_cap * sizeof(seq_t));
        if (!terms) abort();
        terms[0]    = (seq_t)1;
        terms_size  = 1;
        i9 = i13 = 0;
    }

    /* Generate terms until we have at least n of them */
    while (terms_size < n) {
        seq_t cand9  = terms[i9] * ((seq_t)9);
        seq_t cand13 = terms[i13] * ((seq_t)13);

        seq_t next;
        bool bump_i9 = false, bump_i13 = false;

        if (cand9 <= cand13) {
            next       = cand9;
            bump_i9    = true;
            if (cand9 == cand13)
                bump_i13 = true;   /* avoid duplicate */
        } else {
            next       = cand13;
            bump_i13   = true;
        }

        ensure_capacity();
        terms[terms_size++] = next;

        if (bump_i9) i9++;
        if (bump_i13) i13++;
    }

    return terms[n - 1];
}
