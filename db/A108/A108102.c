/*
 * A108102  Numbers k such that the string 1117k is prime.
 * https://oeis.org/A108102
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 22, u16 n <= 55, u32 n <= 55, u64 n <= 55, u128 n <= 55,
 *            big any n
 * Helpers:   is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Search: a(n) = the nth integer k (1‑based) such that 1117 concatenated
   with k (i.e., the decimal number 1117…k) is prime.  The sequence is
   generated by testing successive k and storing those that yield a prime
   when prefixed by 1117. */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/is_prime.h"

static seq_t *seq     = NULL;   /* cache of found terms */
static size_t seq_sz  = 0;
static size_t seq_cap = 0;

static uint64_t k_next     = 1; /* next k to test */
static uint64_t pow10      = 10; /* 10^(digits(k_next))   */
static uint64_t next_pow10 = 10; /* threshold for digit increase */

/* Ensure the cache has at least min_cap elements. */
static void ensure_capacity(size_t min_cap)
{
    if (seq_cap >= min_cap) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    while (new_cap < min_cap) new_cap *= 2;
    seq_t *new_arr = (seq_t *)malloc(new_cap * sizeof(seq_t));
    if (seq) {
        for (size_t i = 0; i < seq_sz; ++i) new_arr[i] = seq[i];
        free(seq);
    }
    seq = new_arr;
    seq_cap = new_cap;
}

/* Generate sequence terms up to the requested index n. */
static void generate_to(idx_t n)
{
    /* We assume n fits in size_t for the intended use (n ≤ 10000). */
    while (seq_sz < (size_t)n) {
        /* Update the power of ten if we have moved to the next digit length. */
        if (k_next == next_pow10) {
            pow10      = pow10 * 10;
            next_pow10 *= 10;
        }

        /* Construct the candidate number 1117 * 10^d + k_next. */
        uint64_t N = 1117ULL * pow10 + k_next;

        /* Check primality (the function is provided by the build). */
        if (is_prime(N)) {
            ensure_capacity(seq_sz + 1);
            seq[seq_sz++] = (seq_t)k_next;
        }

        ++k_next;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;           /* offset is 1; n=0 is unused */
    generate_to(n);
    return seq[n - 1];
}
