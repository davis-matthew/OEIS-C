/*
 * A225361  Partition numbers of the form 11k.
 * https://oeis.org/A225361
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 21, u32 n <= 37, u64 n <= 37, u128 n <= 37,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: A225361 – partition numbers divisible by 11
   The nth term a(n) is the nth partition number that is a
   multiple of 11.  Partition numbers are generated by Euler’s
   pentagonal recurrence.  We collect the terms that are
   divisible by 11 and store them in a static array.
   The function returns the nth such term (1‑based index). */

#include <stdlib.h>

/* Helper: ensure capacity for a seq_t array. */
static void ensure_seq_cap(seq_t **arr, size_t *cap, size_t needed) {
    if (*cap < needed) {
        size_t new_cap = (*cap > 0) ? (*cap << 1) : 256;
        if (new_cap < needed) new_cap = needed;
        seq_t *tmp = (seq_t *)realloc(*arr, new_cap * sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE); /* out of memory */
        *arr = tmp;
        *cap = new_cap;
    }
}

/* Global static cache */
static seq_t *part = NULL;          /* array of partition numbers p(0), p(1), … */
static size_t part_cap = 0;
static idx_t next_part_idx = 0;      /* next index to compute */

static seq_t *divisible = NULL;     /* array of p(n) that are multiples of 11 */
static size_t divisible_cap = 0;
static size_t divisible_len = 0;

/* Compute partition numbers up to at least the nth divisible term. */
static void ensure_terms(idx_t n) {
    /* One‑time initialisation */
    if (!part) {
        ensure_seq_cap(&part, &part_cap, 256);
        part[0] = 1;                      /* p(0) = 1 */
        next_part_idx = 1;
    }
    if (!divisible) {
        ensure_seq_cap(&divisible, &divisible_cap, 256);
    }

    /* Generate new partition numbers until we have at least n divisible terms */
    while (divisible_len < (size_t)n) {
        idx_t m = next_part_idx;           /* compute p(m) */

        /* Euler's pentagonal recurrence */
        seq_t sum_pos = 0;
        seq_t sum_neg = 0;
        for (idx_t k = 1; ; ++k) {
            idx_t pent1 = k * (3 * k - 1) / 2;
            idx_t pent2 = k * (3 * k + 1) / 2;
            if (pent1 > m && pent2 > m) break;

            if (pent1 <= m) {
                if (k & 1) sum_pos += part[m - pent1];
                else       sum_neg += part[m - pent1];
            }
            if (pent2 <= m) {
                if (k & 1) sum_pos += part[m - pent2];
                else       sum_neg += part[m - pent2];
            }
        }
        seq_t val = sum_pos;
        if (sum_neg != (seq_t)0) val -= sum_neg; /* final p(m) */
        /* Store in partition array */
        ensure_seq_cap(&part, &part_cap, (size_t)(m + 1));
        part[m] = val;
        next_part_idx = m + 1;

        /* Check divisibility by 11 */
        if ((val % (seq_t)11) == (seq_t)0) {
            ensure_seq_cap(&divisible, &divisible_cap, divisible_len + 1);
            divisible[divisible_len++] = val;
        }
    }
}

seq_t a(idx_t n) {
    if (n < 1) return (seq_t)0;
    ensure_terms(n);
    return divisible[n - 1];
}
