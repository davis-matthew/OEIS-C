/*
 * A172015  Numbers of the form 6*k-+1 such that 6*k-1=prime and
 *          6*k+1=nonprime.
 * https://oeis.org/A172015
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 22, u16 n <= 54, u32 n <= 54, u64 n <= 54, u128 n <= 54,
 *            big any n
 * Helpers:   is_prime, seq_alloc_array, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A172015: numbers of the form 6*k-1 and 6*k+1 for which 6*k-1 is prime
   and 6*k+1 is composite. The terms are generated by searching for suitable k
   and cached for fast retrieval. */

#include <stddef.h>
#include "../utils/is_prime.h"
#include "../utils/seq_alloc_array.h"
#include "../utils/seq_realloc.h"

static seq_t *cache = NULL;   /* cached sequence values           */
static size_t cap   = 0;      /* allocated capacity               */
static idx_t  len   = 0;      /* number of cached elements        */
static idx_t  next_k = 1;     /* next k to test for 6*k-1 prime   */

/* Ensure the cache can hold at least 'needed' elements. */
static void grow_cache(size_t needed)
{
    if (cap < needed) {
        size_t new_cap = (cap ? (cap << 1) : 16);
        while (new_cap < needed) new_cap <<= 1;
        cache = seq_realloc(cache, cap, new_cap);
        cap   = new_cap;
    }
}

/* Generate terms until the cache contains at least 'n' elements. */
static void generate_terms_upto(idx_t n)
{
    while (len < n) {
        for (idx_t k = next_k; ; ++k) {
            idx_t cand = 6 * k - 1;            /* 6*k-1 candidate */
            if (is_prime(cand) && !is_prime(cand + 2)) {
                next_k = k + 1;                /* start next search after this k */
                grow_cache(len + 2);           /* reserve space for two values */
                cache[len++] = (seq_t)cand;         /* 6*k-1 (prime)   */
                cache[len++] = (seq_t)(cand + 2);   /* 6*k+1 (composite) */
                break;
            }
        }
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;             /* offset is 1; ignore a(0) */
    if (len < n) generate_terms_upto(n);
    return cache[n-1];
}
