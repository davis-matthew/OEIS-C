/*
 * A328944  Arithmetic numbers (A003601) that are not harmonic (A001599).
 * https://oeis.org/A328944
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 29, u16 n <= 2104, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A328944 – Arithmetic numbers that are not harmonic. */
/* The function computes the terms by testing successive m ≥ 3 and
   records all m such that σ(m)/d(m) is an integer but m·d(m)/σ(m)
   is not.  The implementation is fully memoised and works for any
   seq_t type (built‑in or arbitrary precision). */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

/* -------------------------------------------------------------------------- */
/* Small integer square root: floor(√n) for 0 ≤ n ≤ UINT64_MAX. */
static inline idx_t isqrt_u64(idx_t n) {
    idx_t lo = 0, hi = (idx_t)1 << 32;          /* hi > sqrt(UINT64_MAX) */
    while (lo < hi) {
        idx_t mid = lo + (hi - lo) / 2;
        if ((unsigned __int128)mid * mid <= n) lo = mid + 1;
        else hi = mid;
    }
    return lo - 1;
}

/* -------------------------------------------------------------------------- */
/* Prime sieve – keeps a dynamically growable list of primes up to a
   requested limit.  The function expands the stored list only when a
   larger limit is required. */
static uint32_t *primes = NULL;      /* array of primes (uint32_t) */
static size_t   prime_cnt = 0;       /* number of primes stored   */
static uint32_t prime_limit = 0;     /* maximum value sieved so far */

static void ensure_prime_limit(uint32_t limit) {
    if (limit <= prime_limit) return;                /* already have enough */

    /* Allocate array of flags. */
    size_t sz = (size_t)limit + 1;
    bool *is_prime = (bool *)calloc(sz, sizeof(bool));
    if (!is_prime) return;                           /* allocation error */

    for (size_t i = 0; i < sz; ++i) is_prime[i] = true;
    is_prime[0] = is_prime[1] = false;

    for (uint32_t p = 2; (uint64_t)p * p <= limit; ++p) {
        if (is_prime[p]) {
            for (uint32_t q = p * p; q <= limit; q += p)
                is_prime[q] = false;
        }
    }

    /* Count primes. */
    size_t cnt = 0;
    for (uint32_t p = 2; p <= limit; ++p)
        if (is_prime[p]) ++cnt;

    /* Allocate new array and copy primes. */
    uint32_t *new_pr = (uint32_t *)realloc(primes, cnt * sizeof(uint32_t));
    if (!new_pr) {
        new_pr = (uint32_t *)malloc(cnt * sizeof(uint32_t));
        if (!new_pr) { free(is_prime); return; }     /* panic on OOM   */
    }

    size_t ip = 0;
    for (uint32_t p = 2; p <= limit; ++p)
        if (is_prime[p]) new_pr[ip++] = p;

    free(is_prime);
    primes = new_pr;
    prime_cnt = cnt;
    prime_limit = limit;
}

/* -------------------------------------------------------------------------- */
/* Compute σ(m) (sum of divisors) and d(m) (number of divisors) for a
   single unsigned 64‑bit integer m.  The calculation uses the prime
   list generated by ensure_prime_limit. */
static void sigma_d(uint64_t m, seq_t *sigma_out, seq_t *d_out) {
    seq_t sigma = 1;
    seq_t d = 1;
    uint64_t x = m;
    uint32_t lim = (uint32_t)isqrt_u64(m);
    ensure_prime_limit(lim);

    for (size_t i = 0; i < prime_cnt && (uint64_t)primes[i] * primes[i] <= x; ++i) {
        uint32_t p = primes[i];
        if (x % p == 0) {
            int e = 0;
            seq_t pe = 1;          /* p^e   */
            while (x % p == 0) {
                x /= p;
                ++e;
                pe *= (seq_t)p;
            }
            /* σ(p^e) = (p^(e+1)-1)/(p-1) */
            seq_t numerator = pe * (seq_t)p - 1;
            seq_t sigma_part = numerator / (p - 1);
            sigma *= sigma_part;
            d *= (e + 1);
        }
    }

    if (x > 1) {            /* remaining prime > sqrt(m) */
        seq_t sigma_part = 1 + (seq_t)x;
        sigma *= sigma_part;
        d *= 2;
    }

    *sigma_out = sigma;
    *d_out = d;
}

/* -------------------------------------------------------------------------- */
/* Storage for already computed terms of the sequence. */
static seq_t *terms = NULL;          /* array of terms (seq_t) */
static size_t terms_len = 0;         /* number of terms stored    */
static size_t terms_cap = 0;         /* array capacity            */
static uint64_t next_m = 3;          /* next candidate m (≥3)     */

static void ensure_terms_capacity(size_t need) {
    if (need <= terms_cap) return;
    size_t new_cap = terms_cap ? terms_cap * 2 : 4;
    while (new_cap < need) new_cap <<= 1;
    seq_t *new_terms = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
    if (!new_terms) return;            /* allocation error – stop */
    terms = new_terms;
    terms_cap = new_cap;
}

/* -------------------------------------------------------------------------- */
/* Main sequence function.  It lazily generates terms as needed and keeps
   them in a static array for fast subsequent access. */
seq_t a(idx_t n) {
    if (n == 0) return (seq_t)0;            /* undefined for n < 1 */

    if ((size_t)n <= terms_len)            /* already computed */
        return terms[n - 1];

    ensure_terms_capacity((size_t)n);

    /* Generate terms until we have at least n of them. */
    while (terms_len < (size_t)n) {
        uint64_t m = next_m++;
        seq_t sigma, d;
        sigma_d(m, &sigma, &d);

        /* Arithmetic number: σ(m) divisible by d(m). */
        if (sigma % d == 0) {
            /* Not harmonic: (m*d) not divisible by σ(m). */
            seq_t prod = (seq_t)m * d;
            if (prod % sigma != 0)
                terms[terms_len++] = (seq_t)m;
        }
    }

    return terms[n - 1];
}
