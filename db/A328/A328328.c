/*
 * A328328  Unitary admirable numbers: numbers k such that there is a proper
 *          unitary divisor d of k such that usigma(k) - 2d = 2k, where usigma
 *          is the sum of unitary divisors function (A034448).
 * https://oeis.org/A328328
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 13, u16 n <= 1705, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   gcd_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  
 *  A328328 – unitary admirable numbers  
 *  A number k is unitary admirable if there exists a proper unitary
 *  divisor d of k such that
 *
 *          sigma_u(k) – 2*d = 2*k
 *
 *  where sigma_u is the sum of unitary divisors (OEIS A034448).
 *  This function returns the nth such number (offset 1).  The sequence
 *  is generated by a sieve‑like scan, caching the found values for
 *  arbitrary order of calls.
 */

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/gcd_u64.h"

/* --------------------------------------------------------------------
 *  Prime sieve – used for factorisation.  The limit is large enough
 *  that all numbers encountered for n up to about 10 000 will be
 *  factorised correctly.
 * -------------------------------------------------------------------- */
#define PRIME_SIEVE_LIMIT 10000000ULL

static uint64_t *primes = NULL;
static size_t primes_cnt = 0;
static bool primes_ready = false;

static void init_primes(void)
{
    if (primes_ready) return;

    uint64_t N = PRIME_SIEVE_LIMIT;
    bool *is_prime = (bool *)malloc((N + 1) * sizeof(bool));
    for (uint64_t i = 0; i <= N; ++i) is_prime[i] = true;
    is_prime[0] = is_prime[1] = false;
    for (uint64_t i = 2; i * i <= N; ++i) {
        if (is_prime[i]) {
            for (uint64_t j = i * i; j <= N; j += i) is_prime[j] = false;
        }
    }
    primes_cnt = 0;
    primes = (uint64_t *)malloc((N + 1) * sizeof(uint64_t));
    for (uint64_t i = 2; i <= N; ++i)
        if (is_prime[i]) primes[primes_cnt++] = i;
    free(is_prime);
    primes_ready = true;
}

/* --------------------------------------------------------------------
 *  GCD for 64‑bit values, used when checking unitary divisors.
 * -------------------------------------------------------------------- */

/* --------------------------------------------------------------------
 *  Sum of unitary divisors of *n*.  The result is returned as seq_t,
 *  allowing arbitrary‑precision builds.  Factorisation is done with
 *  the previously computed prime list.
 * -------------------------------------------------------------------- */
static seq_t unitary_sigma(uint64_t n)
{
    init_primes();
    seq_t res = 1;
    uint64_t tmp = n;

    for (size_t i = 0; i < primes_cnt; ++i) {
        uint64_t p = primes[i];
        if (p * p > tmp) break;
        if (tmp % p == 0) {
            seq_t power = 1;
            while (tmp % p == 0) {
                tmp /= p;
                power *= (seq_t)p;
            }
            res *= (1 + power);
        }
    }
    if (tmp > 1) {                 /* remaining prime factor */
        res *= (1 + (seq_t)tmp);
    }
    return res;
}

/* --------------------------------------------------------------------
 *  Cache of discovered sequence values.  The cache is grown as
 *  necessary when a higher index is requested.
 * -------------------------------------------------------------------- */
static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;

/* Append a new element to the cache, extending capacity if needed */
static void cache_append(seq_t val)
{
    if (cache_len == cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 8 : cache_cap * 2;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

/* --------------------------------------------------------------------
 *  Main sequence function.
 * -------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;               /* offset < 1 not required */

    /* Grow cache until we have n elements */
    static uint64_t candidate = 2;       /* next integer to test */
    while (cache_len < (size_t)n) {
        uint64_t k = candidate;
        seq_t sigma = unitary_sigma(k);
        seq_t s = sigma - (seq_t)(2 * k);

        if (s > 0 && (s & 1) == 0) {        /* s = 2*d  */
            seq_t d = s >> 1;                /* candidate divisor */
            if (d < (seq_t)k) {
                uint64_t d_val = (uint64_t)d;
                if (k % d_val == 0) {
                    uint64_t nd = k / d_val;
                    if (gcd_u64(d_val, nd) == 1) {
                        cache_append((seq_t)k);
                    }
                }
            }
        }
        ++candidate;
    }
    return cache[(size_t)n - 1];
}
