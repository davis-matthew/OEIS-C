/*
 * A328603  Numbers whose prime indices have no consecutive divisible parts,
 *          meaning no prime index is a divisor of the next-smallest prime
 *          index, counted with multiplicity.
 * https://oeis.org/A328603
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 60, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A328603: numbers whose prime indices have no consecutive divisible parts.
   Generated by testing integers in increasing order and filtering based on the prime-index condition. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* Global state for the generated sequence */
static seq_t *seq_arr = NULL;       /* storage for sequence values      */
static size_t seq_cap = 0;          /* current capacity of seq_arr      */
static idx_t seq_len = 0;           /* number of values already stored  */
static uint64_t last_candidate = 1; /* next integer to test             */

/* Sieve data structures */
static uint64_t *spf = NULL;        /* smallest prime factor for each n */
static uint32_t *prime_idx = NULL;  /* 1‑based index of each prime      */
static size_t spf_cap = 0;          /* maximum n for which spf is valid */
static size_t prime_len = 0;        /* number of primes found           */

/* --------------------------------------------------------------------- */
/*  Build or rebuild the sieve up to `limit` (inclusive).               */
/* --------------------------------------------------------------------- */
static void build_sieve(uint64_t limit)
{
    if (limit < 2) limit = 2;

    uint64_t *new_spf = (uint64_t *)calloc(limit + 1, sizeof(uint64_t));
    uint32_t *new_prime_idx = (uint32_t *)calloc(limit + 1, sizeof(uint32_t));

    size_t primes_cap = (limit / 10) + 10;
    if (primes_cap < 16) primes_cap = 16;
    uint32_t *primes = (uint32_t *)malloc(primes_cap * sizeof(uint32_t));
    size_t primes_len = 0;

    for (uint64_t i = 2; i <= limit; ++i) {
        if (!new_spf[i]) {
            new_spf[i] = i;
            if (primes_len == primes_cap) {
                primes_cap <<= 1;
                primes = (uint32_t *)realloc(primes, primes_cap * sizeof(uint32_t));
            }
            primes[primes_len++] = (uint32_t)i;
        }

        for (size_t j = 0; j < primes_len &&
                        primes[j] <= new_spf[i] &&
                        i * (uint64_t)primes[j] <= limit; ++j) {
            new_spf[i * primes[j]] = primes[j];
        }
    }

    /* Fill prime index table (1‑based indices) */
    for (size_t k = 0; k < primes_len; ++k) {
        new_prime_idx[primes[k]] = (uint32_t)(k + 1);
    }

    /* Replace old tables */
    free(primes);
    free(spf);
    free(prime_idx);
    spf = new_spf;
    prime_idx = new_prime_idx;
    spf_cap = limit;
    prime_len = primes_len;
}

/* --------------------------------------------------------------------- */
/*  Test whether `candidate` satisfies the prime‑index condition.       */
/* --------------------------------------------------------------------- */
static bool ok_candidate(uint64_t candidate)
{
    if (candidate == 1) return true;  /* empty multiset -> ok */

    /* Collect prime indices in ascending order (factorization order). */
    uint32_t idx_stack[64];
    size_t idx_len = 0;

    uint64_t tmp = candidate;
    while (tmp > 1) {
        uint32_t p = (uint32_t)spf[tmp];
        uint32_t idx = prime_idx[p];
        while (tmp % p == 0) {
            if (idx_len == 64) return false;   /* unlikely overflow */
            idx_stack[idx_len++] = idx;
            tmp /= p;
        }
    }

    /* Check consecutive divisibility. */
    for (size_t i = 0; i + 1 < idx_len; ++i) {
        if (idx_stack[i + 1] % idx_stack[i] == 0)
            return false;
    }
    return true;
}

/* --------------------------------------------------------------------- */
/*  Append a value to the stored sequence.                               */
/* --------------------------------------------------------------------- */
static void store_value(seq_t val)
{
    if (seq_len == seq_cap) {
        size_t new_cap = (seq_cap == 0) ? 16 : seq_cap << 1;
        seq_t *tmp = (seq_t *)realloc(seq_arr, new_cap * sizeof(seq_t));
        if (!tmp) exit(1);
        seq_arr = tmp;
        seq_cap = new_cap;
    }
    seq_arr[seq_len++] = val;
}

/* --------------------------------------------------------------------- */
/*  Main function exposed to the test harness.                           */
/* --------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0; /* undefined for n < 1 */

    /* Ensure sieve is at least as large as the smallest number we
       might need to test next. */
    if (last_candidate > spf_cap)
        build_sieve(last_candidate * 2);

    while (seq_len < n) {
        if (last_candidate > spf_cap)
            build_sieve(last_candidate * 2);

        if (ok_candidate(last_candidate))
            store_value((seq_t)last_candidate);

        ++last_candidate;
    }

    return seq_arr[n - 1];
}
