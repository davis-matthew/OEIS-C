/*
 * A389864  Powers k^m, m > 1, such that k is neither squarefree nor perfect
 *          power.
 * https://oeis.org/A389864
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 none, u64 n <= 10000, u128 n <= 10000,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements: a(n) = n-th smallest integer k^m (m>1) such that
   k is not squarefree and not a perfect power.  The sequence is
   generated by a min‑heap, caching results so that any order of
   calls is supported.  */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

/* ------------------------------------------------------------------ */
/* Simple gcd for small integers                                       */
/* ------------------------------------------------------------------ */
static unsigned int ugcd(unsigned int a, unsigned int b)
{
    while (b) {
        unsigned int t = a % b;
        a = b;
        b = t;
    }
    return a;
}

/* ------------------------------------------------------------------ */
/* Prime sieve up to √KLIMIT                                            */
/* ------------------------------------------------------------------ */
#define KLIMIT 200000

static uint32_t *primes = NULL;
static size_t prime_cnt = 0;

static void build_primes(void)
{
    if (primes != NULL) return;

    /* Compute √KLIMIT without using <cmath> to avoid conflicts with
       arbitrary‑precision sqrt overloads. */
    uint32_t limit = 1;
    while ((uint64_t)limit * limit <= (uint64_t)KLIMIT) ++limit;
    if (limit > 0) --limit;          /* floor(sqrt(KLIMIT)) */

    bool *sieve = (bool *)calloc(limit + 1, sizeof(bool));
    if (!sieve) exit(EXIT_FAILURE);

    primes = (uint32_t *)malloc(10000 * sizeof(uint32_t));
    if (!primes) exit(EXIT_FAILURE);

    for (uint32_t p = 2; p <= limit; ++p) {
        if (!sieve[p]) {
            primes[prime_cnt++] = p;
            for (uint64_t mult = (uint64_t)p * p; mult <= limit; mult += p)
                sieve[(size_t)mult] = true;
        }
    }
    free(sieve);
}

/* ------------------------------------------------------------------ */
/* Test whether a base k is suitable (not squarefree, not perfect power) */
/* ------------------------------------------------------------------ */
static bool is_valid_k(uint64_t k)
{
    uint64_t temp = k;
    bool has_sq = false;
    unsigned int g = 0;

    for (size_t i = 0; i < prime_cnt && (uint64_t)primes[i] * primes[i] <= temp; ++i) {
        uint32_t p = primes[i];
        unsigned int exp = 0;
        while (temp % p == 0) {
            temp /= p;
            ++exp;
        }
        if (exp >= 2) has_sq = true;
        g = (g == 0) ? exp : ugcd(g, exp);
    }
    if (temp > 1) {                     /* remaining prime factor exponent = 1 */
        g = (g == 0) ? 1 : ugcd(g, 1);
    }
    return has_sq && g == 1;
}

/* ------------------------------------------------------------------ */
/* Heap node for generating powers                                     */
/* ------------------------------------------------------------------ */
typedef struct {
    seq_t value;      /* current power value */
    uint64_t k;       /* base */
    uint32_t m;       /* current exponent (>=2) */
} Node;

static Node *heap = NULL;
static size_t heap_cap = 0;
static size_t heap_sz = 0;

static void heap_swap(size_t i, size_t j)
{
    Node tmp = heap[i];
    heap[i] = heap[j];
    heap[j] = tmp;
}

static bool less_node(const Node *a, const Node *b)
{
    return a->value < b->value;
}

static void heap_sift_up(size_t idx)
{
    while (idx > 0) {
        size_t parent = (idx - 1) >> 1;
        if (less_node(&heap[parent], &heap[idx])) break;
        heap_swap(idx, parent);
        idx = parent;
    }
}

static void heap_sift_down(size_t idx)
{
    while (1) {
        size_t left = (idx << 1) + 1;
        size_t right = left + 1;
        size_t smallest = idx;
        if (left < heap_sz && !less_node(&heap[smallest], &heap[left]))
            smallest = left;
        if (right < heap_sz && !less_node(&heap[smallest], &heap[right]))
            smallest = right;
        if (smallest == idx) break;
        heap_swap(idx, smallest);
        idx = smallest;
    }
}

static void heap_push(Node node)
{
    if (heap_sz == heap_cap) {
        size_t new_cap = heap_cap ? heap_cap * 2 : 128;
        Node *tmp = (Node *)realloc(heap, new_cap * sizeof(Node));
        if (!tmp) exit(EXIT_FAILURE);
        heap = tmp;
        heap_cap = new_cap;
    }
    heap[heap_sz++] = node;
    heap_sift_up(heap_sz - 1);
}

static Node heap_pop(void)
{
    Node res = heap[0];
    heap[0] = heap[--heap_sz];
    heap_sift_down(0);
    return res;
}

/* ------------------------------------------------------------------ */
/* Cached sequence values                                               */
/* ------------------------------------------------------------------ */
static seq_t *seq_cache = NULL;
static idx_t seq_len = 0;      /* number of terms stored */
static seq_t last_val;         /* last term emitted */
static bool last_set = false;  /* whether last_val is defined */

/* ------------------------------------------------------------------ */
/* Main function                                                        */
/* ------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* undefined, avoid underflow */

    /* Lazy initialization */
    static bool initialized = false;
    if (!initialized) {
        /* Allocate cache for initial size (adjustable later) */
        seq_cache = (seq_t *)malloc(20000 * sizeof(seq_t));
        if (!seq_cache) exit(EXIT_FAILURE);
        seq_len = 0;

        /* Build prime list */
        build_primes();

        /* Populate heap with all valid bases up to KLIMIT */
        for (uint64_t k = 2; k <= KLIMIT; ++k) {
            if (!is_valid_k(k)) continue;
            seq_t val = (seq_t)k * k;   /* k^2 */
            heap_push((Node){val, k, 2});
        }
        initialized = true;
    }

    /* Generate terms until we have at least n */
    while (seq_len < n) {
        Node top = heap_pop();
        seq_t val = top.value;

        /* Deduplicate consecutive equal values */
        if (!last_set || val != last_val) {
            if (seq_len >= 20000) {    /* grow cache as needed */
                seq_cache = (seq_t *)realloc(seq_cache, (seq_len + 1000) * sizeof(seq_t));
                if (!seq_cache) exit(EXIT_FAILURE);
            }
            seq_cache[seq_len++] = val;
            last_val = val;
            last_set = true;
        }

        /* Push next power for this base if it does not overflow (uint64_t case) */
        if (sizeof(seq_t) <= sizeof(uint64_t)) {
            uint64_t uval = (uint64_t)val;
            if (uval <= UINT64_MAX / top.k) {
                seq_t next_val = (seq_t)(uval * top.k);
                heap_push((Node){next_val, top.k, top.m + 1});
            }
        } else {
            /* For arbitrary‑precision seq_t, overflow is not a problem */
            seq_t next_val = val * (seq_t)top.k;
            heap_push((Node){next_val, top.k, top.m + 1});
        }
    }

    return seq_cache[n - 1];
}
