/*
 * A389597  Standard composition numbers of integer compositions with all
 *          distinct first differences.
 * https://oeis.org/A389597
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 67, u16 n <= 67, u32 n <= 67, u64 n <= 67, u128 n <= 67,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n) – the n‑th integer k whose standard composition
 * (defined in OEIS A066099) has all distinct first differences.
 * The sequence is generated by a linear search over k:
 *   - for each k, form its standard composition by bit positions
 *   - check that the first differences of this composition are unique
 *   - count qualifying k’s until the n‑th one is reached. */
#include <stdbool.h>
#include <stdint.h>

/* Returns true iff the standard composition of k has all distinct
 * first differences. */
static bool qualifies(uint64_t k)
{
    /* a holds the composition in reverse order (see analysis). */
    uint8_t a[64];
    int L = 0;               /* number of parts in a */
    uint8_t prev = 0;        /* previous position, starts at 0 */

    /* Collect positions of 1‑bits (LSB has position 1). */
    for (int i = 0; i < 64; ++i) {
        if (k & ((uint64_t)1 << i)) {
            uint8_t pos = (uint8_t)(i + 1);
            a[L++] = pos - prev;  /* diff from previous position */
            prev = pos;
        }
    }

    /* Compositions of length 0 or 1 automatically satisfy the
     * distinct‑difference property. */
    if (L <= 1) return true;

    /* Check that the differences of the a array are all distinct.
     * The differences are in the range [-63, 63], so a bitset is
     * sufficient. */
    bool seen[127] = {0};
    for (int i = 1; i < L; ++i) {
        int diff = (int)a[i] - (int)a[i-1];
        int idx  = diff + 63;           /* shift to [0,126] */
        if (seen[idx]) return false;
        seen[idx] = true;
    }
    return true;
}

seq_t a(idx_t n)
{
    if (n == 1) return (seq_t)0;   /* a(1) = 0 */

    idx_t count = 0;
    idx_t k = 0;
    while (1) {
        if (qualifies((uint64_t)k)) {
            count++;
            if (count == n) {
                return (seq_t)k;
            }
        }
        ++k;
    }
}
