/*
 * A054047  Numbers which can be read as (possibly different) numbers when
 *          rotated by 180 degrees (final zeros allowed).
 * https://oeis.org/A054047
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 49, u16 n <= 58, u32 n <= 58, u64 n <= 58, u128 n <= 58,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A054047: numbers whose decimal digits belong to {0,1,6,8,9} (rotatable digits).
   The list is in increasing order.  The n‑th term is generated by interpreting
   the index (after removing 0) as a mixed radix representation: first digit
   uses 4 possibilities (1,6,8,9) and each subsequent digit uses 5 possibilities
   (0,1,6,8,9).  This yields an O(log_5 n) algorithm. */

seq_t a(idx_t n)
{
    if (n == 0) {
        return (seq_t)0;
    }

    /* Index among numbers that exclude 0 (zero is handled separately). */
    seq_t m = (seq_t)(n - 1);   /* m = n-1  (0‑based among non‑zero terms) */
    seq_t m1 = m + 1;            /* m1 = m + 1 = n */

    /* Find smallest power of five greater than m1: 5^L > m1. */
    seq_t pow = (seq_t)1;
    while (pow <= m1) {
        pow *= 5;
    }
    /* Now pow = 5^L, pow_prev = 5^(L-1) */
    seq_t pow_prev = pow / 5;

    /* Position within the block of length L. */
    seq_t pos = m - (pow_prev - 1);        /* 0 <= pos < 4*pow_prev */
    int first_idx = (int)(pos / pow_prev); /* index 0..3 for first digit */
    seq_t rem = pos % pow_prev;             /* remaining part for other digits */

    /* Determine number of remaining digits (L-1). */
    int remaining = 0;
    seq_t tmp = 1;
    while (tmp < pow_prev) {                /* pow_prev = 5^(remaining) */
        tmp *= 5;
        remaining++;
    }

    /* Convert remainder to base‑5 with exactly 'remaining' digits. */
    int digit_map[5] = {0, 1, 6, 8, 9};
    int first_map[4] = {1, 6, 8, 9};
    int digits[20];  /* 20 is enough for all practical n; index 0 = most significant. */
    for (int i = remaining - 1; i >= 0; --i) {
        seq_t d = rem % 5;
        digits[i] = (int)d;
        rem /= 5;
    }

    /* Assemble the decimal number. */
    seq_t result = first_map[first_idx];
    for (int i = 0; i < remaining; ++i) {
        result = result * 10 + (seq_t)digit_map[digits[i]];
    }

    return result;
}
