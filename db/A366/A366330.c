/*
 * A366330  Minimal numbers (with respect to division) with no coprime divisor
 *          shift.
 * https://oeis.org/A366330
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 12, u16 n <= 1807, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

/* Sequence A366330: minimal numbers (with respect to division) with no coprime divisor shift
 *
 *  The sequence is generated by testing each integer k (k ≥ 2):
 *      * k must have no coprime divisor shift.
 *      * None of its proper divisors may already belong to the sequence.
 *
 *  A number k has a coprime divisor shift iff for every prime divisor p of k the set
 *      { d mod p | d : d|k, d ≠ 0 mod p } together with 0 does **not**
 *  contain all residues mod p.  Equivalently, k has no shift exactly when for some
 *  prime p dividing k the residues of all divisors modulo p cover every residue
 *  0,1,…,p‑1.  The test uses all divisors of k generated from its prime factorisation.
 *
 *  The implementation pre‑computes a smallest‑prime‑factor (spf) table up to
 *  a fixed limit (2 000 000) which is sufficient for n up to about 10⁴
 *  (the 10 000‑th term is well below this bound).  The sequence itself is
 *  memoised; any subsequent call to a(idx_t n) simply returns the already
 *  computed value.  All operations use integer arithmetic only, and the code
 *  is compliant with the C11 / C++17 standards required by the problem.
 */

#define MAX_LIMIT 2000000  /* enough for n up to at least 10 000 */

/* smallest prime factor table */
static uint32_t spf[MAX_LIMIT + 1];

/* flag array telling whether a number already belongs to the sequence */
static bool in_seq[MAX_LIMIT + 1];

/* dynamic array holding the sequence values */
static seq_t *seq_list = NULL;
static size_t seq_len   = 0;   /* current number of values */
static size_t seq_cap   = 0;   /* current allocated capacity */

/* next integer to test for inclusion in the sequence */
static uint32_t next_candidate = 2;

/* --------------------------------------------------------------------- */
/* type for a prime factor (prime and exponent) */
struct Factor {
    uint32_t p;
    uint8_t  e;
};

/* recursive generator of all divisors from a factor list */
static void gen_divisors(const struct Factor *f, int fcnt, int idx,
                         uint64_t cur, uint32_t *divs, size_t *cnt)
{
    if (idx == fcnt) {
        divs[(*cnt)++] = (uint32_t)cur;
        return;
    }
    uint64_t mult = 1;
    for (int e = 0; e <= f[idx].e; ++e) {
        gen_divisors(f, fcnt, idx + 1, cur * mult, divs, cnt);
        mult *= f[idx].p;
    }
}

/* initialise the spf table once */
static void init_spf(void)
{
    for (uint32_t i = 0; i <= MAX_LIMIT; ++i)
        spf[i] = 0;
    spf[0] = spf[1] = 1;
    for (uint32_t i = 2; i <= MAX_LIMIT; ++i) {
        if (spf[i] == 0) {
            spf[i] = i;
            if ((uint64_t)i * i <= MAX_LIMIT) {
                for (uint32_t j = i * i; j <= MAX_LIMIT; j += i)
                    if (spf[j] == 0) spf[j] = i;
            }
        }
    }
}

/* ensure that seq_list contains at least n elements (indices 0 .. n-1) */
static void ensure_sequence(idx_t n)
{
    if (seq_len >= (size_t)n) return;

    if (seq_cap == 0) {                 /* initial allocation */
        seq_cap = 64;
        seq_list = (seq_t *)malloc(seq_cap * sizeof(seq_t));
    }

    while (seq_len < (size_t)n) {
        uint32_t cand = next_candidate++;
        if (cand > MAX_LIMIT) abort(); /* should not happen with current limits */

        /* prime numbers > 2 always have a shift, so they cannot belong to the sequence */
        if (cand > 2 && spf[cand] == cand) continue;

        /* factorise cand */
        struct Factor f[16];
        int fcnt = 0;
        uint32_t tmp = cand;
        while (tmp > 1) {
            uint32_t p = spf[tmp];
            uint8_t cnt = 0;
            while ((tmp % p) == 0) {
                tmp /= p;
                ++cnt;
            }
            f[fcnt++] = (struct Factor){p, cnt};
        }

        /* generate all divisors of cand */
        uint32_t divisors[256];
        size_t divisors_cnt = 0;
        gen_divisors(f, fcnt, 0, 1, divisors, &divisors_cnt);

        /* Test whether cand has a coprime divisor shift */
        bool no_shift = false;           /* true  →  cand has no shift  */
        for (int i = 0; i < fcnt && !no_shift; ++i) {
            uint32_t p = f[i].p;

            size_t seen_cnt = 1;         /* residue 0 is always present */
            bool seen_mask_small = (p <= 64);
            uint64_t mask = 1ULL;        /* bit 0 set */
            uint32_t residues[256];
            residues[0] = 0;

            for (size_t di = 0; di < divisors_cnt; ++di) {
                uint32_t d = divisors[di];
                if (d % p == 0) continue;           /* residue 0 already counted */
                uint32_t r = d % p;

                bool already = false;
                if (seen_mask_small) {
                    if ((mask >> r) & 1ULL) already = true;
                } else {
                    for (size_t k = 0; k < seen_cnt; ++k)
                        if (residues[k] == r) { already = true; break; }
                }

                if (!already) {
                    if (seen_mask_small) {
                        mask |= ((uint64_t)1 << r);
                    } else {
                        residues[seen_cnt++] = r;
                    }
                    ++seen_cnt;
                    if (seen_cnt == (size_t)p) {     /* all residues present */
                        no_shift = true;
                        break;
                    }
                }
            }
        }
        if (!no_shift) continue;           /* cand has a shift – skip it */

        /* Minimality test: none of the proper divisors may already be in the seq */
        bool minimal = true;
        for (size_t di = 0; di < divisors_cnt; ++di) {
            uint32_t d = divisors[di];
            if (d == cand) continue;            /* skip the number itself */
            if (in_seq[d]) { minimal = false; break; }
        }
        if (!minimal) continue;

        /* Add cand to the sequence */
        if (seq_len == seq_cap) {
            seq_cap *= 2;
            seq_list = (seq_t *)realloc(seq_list, seq_cap * sizeof(seq_t));
        }
        seq_list[seq_len++] = (seq_t)cand;
        in_seq[cand] = true;
    }
}

/* exported sequence function */
seq_t a(idx_t n)
{
    static bool started = false;
    if (!started) { init_spf(); started = true; }
    ensure_sequence(n);
    return seq_list[n - 1];
}
