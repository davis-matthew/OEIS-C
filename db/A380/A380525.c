/*
 * A380525  Squarefree numbers k such that for all factorizations of k as x*y,
 *          the sum (x * y') + (x' * y) is carryless when the addition is done
 *          in the primorial base, A049345. Here n' stands for A003415(n), the
 *          arithmetic derivative of n.
 * https://oeis.org/A380525
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 75, u16 n <= 8864, u32 n <= 9095, u64 n <= 9095,
 *            u128 n <= 9095, big any n
 * Helpers:   derivative_of_div
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute OEIS sequence A380525
   Squarefree integers k whose sums (x*y' + x'*y) are carryless
   in primorial base (radices are successive primes).
   The sequence is generated by testing each integer in order
   and storing those that satisfy the condition. */
#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/derivative_of_div.h"

static uint64_t *primes = NULL;     /* list of primes for factoring and radix */
static size_t primes_cnt = 0;
static uint64_t primes_limit = 0;
static void ensure_primes_up_to(uint64_t limit)
{
    if (limit <= primes_limit) return;
    uint64_t n = limit;
    uint8_t *mark = (uint8_t*)malloc(n + 1);
    if (!mark) abort();
    for (uint64_t i = 0; i <= n; ++i) mark[i] = 1;
    mark[0] = mark[1] = 0;
    for (uint64_t i = 2; i * i <= n; ++i)
        if (mark[i])
            for (uint64_t j = i * i; j <= n; j += i) mark[j] = 0;
    size_t cnt = 0;
    for (uint64_t i = 2; i <= n; ++i) if (mark[i]) ++cnt;
    uint64_t *arr = (uint64_t*)malloc(cnt * sizeof(uint64_t));
    if (!arr) abort();
    size_t pos = 0;
    for (uint64_t i = 2; i <= n; ++i) if (mark[i]) arr[pos++] = i;
    free(mark);
    free(primes);
    primes = arr;
    primes_cnt = cnt;
    primes_limit = n;
}

/* integer square root (floor) */
static uint64_t isqrt(uint64_t x)
{
    uint64_t lo = 0, hi = x, ans = 0;
    while (lo <= hi) {
        uint64_t mid = lo + ((hi - lo) >> 1);
        __uint128_t sq = (__uint128_t)mid * mid;
        if (sq <= x) { ans = mid; lo = mid + 1; }
        else hi = mid - 1;
    }
    return ans;
}

/* test squarefree by trial division */
static bool is_squarefree(uint64_t n)
{
    if (n <= 1) return true;
    for (size_t i = 0; i < primes_cnt && primes[i] * primes[i] <= n; ++i) {
        uint64_t p = primes[i];
        if (n % p == 0) {
            n /= p;
            if (n % p == 0) return false;
            while (n % p == 0) n /= p; /* just in case */
        }
    }
    return true;
}

/* factor a squarefree n into distinct primes */
static void factor_squarefree(uint64_t n, uint64_t *fac, size_t *cnt)
{
    *cnt = 0;
    for (size_t i = 0; i < primes_cnt && primes[i] * primes[i] <= n; ++i) {
        uint64_t p = primes[i];
        if (n % p == 0) {
            fac[(*cnt)++] = p;
            n /= p;
        }
    }
    if (n > 1) fac[(*cnt)++] = n;
}

/* generate all divisors of a squarefree number (subsets of its primes) */
static void generate_divisors(uint64_t *pr, size_t pr_cnt,
                              uint64_t *div, size_t *cnt)
{
    *cnt = 1;
    div[0] = 1;
    for (size_t i = 0; i < pr_cnt; ++i) {
        uint64_t p = pr[i];
        size_t old = *cnt;
        for (size_t j = 0; j < old; ++j)
            div[old + j] = div[j] * p;
        *cnt = old * 2;
    }
}

/* test carryless addition of a and b in primorial mixed radix */
static bool carryless_add(uint64_t a, uint64_t b)
{
    size_t i = 0;
    while (a > 0 || b > 0) {
        uint64_t r = primes[i];
        uint64_t da = a % r; a /= r;
        uint64_t db = b % r; b /= r;
        if (da + db >= r) return false;
        ++i;
        if (i >= primes_cnt) return false; /* out of radices */
    }
    return true;
}

/* dynamic array for sequence values */
static seq_t *seq = NULL;
static idx_t seq_len = 0;
static size_t seq_cap = 0;
static uint64_t next_val = 1;

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined offset handling */
    /* initialise primes for use */
    if (!primes_cnt) ensure_primes_up_to(200000);  /* enough for all parts */

    while (seq_len < n) {
        uint64_t k = next_val;
        ++next_val;

        if (!is_squarefree(k)) continue;

        /* factor k to get its distinct prime factors */
        uint64_t k_facs[32];
        size_t k_cnt;
        factor_squarefree(k, k_facs, &k_cnt);

        /* generate all divisors */
        uint64_t divs[128];
        size_t dcnt;
        generate_divisors(k_facs, k_cnt, divs, &dcnt);

        bool ok = true;
        for (size_t i = 0; i < dcnt && ok; ++i) {
            uint64_t x = divs[i];
            uint64_t y = k / x;
            if (x > y) continue;                /* avoid double work */

            uint64_t x_deriv = derivative_of_div(x, k_facs, k_cnt);
            uint64_t y_deriv = derivative_of_div(y, k_facs, k_cnt);

            uint64_t t1 = x_deriv * y;
            uint64_t t2 = x * y_deriv;

            if (!carryless_add(t1, t2)) ok = false;
        }

        if (ok) {
            if (seq_len == seq_cap) {
                seq_cap = seq_cap ? seq_cap * 2 : 16;
                seq = (seq_t*)realloc(seq, seq_cap * sizeof(seq_t));
                if (!seq) abort();
            }
            seq[seq_len++] = (seq_t)k;
        }
    }
    return seq[n - 1];
}
