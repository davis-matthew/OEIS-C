/*
 * A380693  Numbers k such that the least prime dividing k is larger than or
 *          equal to the maximum exponent in the prime factorization of k;
 *          a(1) = 1 by convention.
 * https://oeis.org/A380693
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 218, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   build_primes_upto, ensure_capacity
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A380693: Numbers k such that the least prime dividing k
   is greater than or equal to the maximum exponent in the prime
   factorization of k.  The sequence is generated by testing integers
   sequentially and using a cached list of primes for factorisation. */

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include <math.h>

/* Utility prototypes */
#include "../utils/build_primes_upto.h"    /* build_primes_upto(idx_t, uint64_t **, size_t *) */
#include "../utils/ensure_capacity.h"     /* ensure_capacity(size_t, size_t *, void **, size_t) */

/* Cached terms of the sequence */
static seq_t  *seq_cache  = NULL;
static size_t  seq_cap    = 0;   /* capacity of seq_cache   */
static size_t  seq_len    = 0;   /* number of terms stored */

/* Cached primes for factorisation */
static uint64_t *prime_list = NULL;
static size_t   prime_cnt   = 0;
static idx_t    prime_limit = 0;   /* upper n for which primes are built */

/* Integer square root using double for the small sizes needed here */
static uint64_t isqrt_u64(uint64_t n)
{
    uint64_t r = (uint64_t) sqrt((double)n);
    while ((r + 1) * (r + 1) <= n) ++r;
    while (r * r > n) --r;
    return r;
}

/* Ensure prime list contains all primes <= sqrt(k) */
static void
ensure_primes(uint64_t k)
{
    uint64_t limit = isqrt_u64(k) + 1;
    if (limit <= prime_limit)
        return;
    free(prime_list);
    build_primes_upto(limit, &prime_list, &prime_cnt);
    prime_limit = limit;
}

/* Check whether k satisfies the condition.
   For k==1 it always returns true. */
static bool
is_term(uint64_t k)
{
    if (k == 1)
        return true;

    ensure_primes(k);

    uint64_t rem = k;
    uint64_t min_prime = 0;
    uint64_t max_exp   = 0;

    for (size_t i = 0; i < prime_cnt && prime_list[i] * prime_list[i] <= rem; ++i)
    {
        uint64_t p = prime_list[i];
        if (rem % p == 0)
        {
            if (min_prime == 0)
                min_prime = p;
            uint64_t e = 0;
            while (rem % p == 0)
            {
                rem /= p;
                ++e;
            }
            if (e > max_exp)
                max_exp = e;
        }
    }
    /* rem > 1 means a remaining prime factor */
    if (rem > 1)
    {
        if (min_prime == 0)
            min_prime = rem;
        if (1 > max_exp)
            max_exp = 1;
    }

    return min_prime >= max_exp;
}

/* Main sequence function.  Builds the cache lazily and returns
   the n-th term (n ≥ 1). */
seq_t a(idx_t n)
{
    static idx_t next_k = 1;   /* next integer to test */

    if (n == 0)
        return 0;              /* undefined, but return 0 */

    while (seq_len < n)
    {
        if (is_term((uint64_t)next_k))
        {
            /* Grow cache if necessary */
            ensure_capacity(seq_len + 1, &seq_cap, (void **)&seq_cache, sizeof(seq_t));
            seq_cache[seq_len++] = (seq_t)next_k;
        }
        ++next_k;
    }
    return seq_cache[n - 1];
}
