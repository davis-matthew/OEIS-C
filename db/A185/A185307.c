/*
 * A185307  Numbers not divisible by the number of their distinct prime
 *          factors.
 * https://oeis.org/A185307
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 73, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 73 terms through n = 9258 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the n‑th member (n ≥ 1) of OEIS sequence A185307,
   which consists of the positive integers that are not divisible by the
   number of their distinct prime factors (omega(n)).  The sequence is
   generated by testing successive integers and selecting those that satisfy
   the condition.  No closed form is known for this sequence, so a simple
   sieve‑like search is performed and the results are cached for repeated
   queries. */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/mem.h"

/* Count distinct prime factors of an unsigned 64-bit integer n.
   The result fits in a signed int for all n that may be passed. */
static int count_distinct_primes(uint64_t n)
{
    if (n <= 1)
        return 0;

    int cnt = 0;
    /* Handle factor 2 separately. */
    if (n % 2 == 0) {
        cnt++;
        while (n % 2 == 0)
            n /= 2;
    }
    /* Test odd divisors up to sqrt(n). */
    for (uint64_t p = 3; p <= n / p; p += 2) {
        if (n % p == 0) {
            cnt++;
            while (n % p == 0)
                n /= p;
        }
    }
    if (n > 1)   /* Remaining prime factor. */
        cnt++;
    return cnt;
}

/* Cache for the sequence values */
static seq_t *seq_cache   = NULL;   /* array of terms */
static size_t   cache_cap = 0;      /* allocated capacity (in seq_t elements) */
static idx_t   cache_len   = 0;      /* number of terms stored */

/* Last integer that has been examined for inclusion */
static idx_t examined = 0;          /* start before the first integer */

/* Ensure the cache can hold at least min_cap terms. */
static void grow_cache(idx_t min_cap)
{
    if (cache_cap >= (size_t)min_cap)
        return;

    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
    while (new_cap < (size_t)min_cap)
        new_cap *= 2;

    seq_t *tmp = mem_resize(seq_t, seq_cache, new_cap);
    if (!tmp)
        abort();   /* out of memory */
    seq_cache = tmp;
    cache_cap = new_cap;
}

/* Main sequence generator */
seq_t a(idx_t n)
{
    if (n == 0)   /* safety: caller may pass n < 1, but behaviour is undefined */
        return 0;

    /* Generate terms until we have at least n of them. */
    while (cache_len < n) {
        /* Examine the next integer. */
        ++examined;

        /* Count distinct prime factors of examined. */
        int omega = count_distinct_primes((uint64_t)examined);

        /* Include if the number is 1 (omega==0) or examined is not divisible
           by omega. */
        if (omega == 0 || (examined % (idx_t)omega) != 0) {
            grow_cache(cache_len + 1);
            seq_cache[cache_len] = (seq_t)examined;
            ++cache_len;
        }
    }

    /* The requested term is now in the cache. */
    return seq_cache[n - 1];
}
