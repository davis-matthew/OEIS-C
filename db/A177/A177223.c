/*
 * A177223  Numbers k that are the products of two distinct primes such that
 *          2*k+1, 4*k+3 and 8*k+7 are also products of two distinct primes.
 * https://oeis.org/A177223
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 227, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A177223: numbers k such that k, 2k+1, 4k+3 and 8k+7 are each
   a product of two distinct primes.  The sequence is generated by a
   straightforward search that tests each candidate k in increasing order. */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>

/* ---------- prime sieve ------------------------------------------------- */
#define PRIME_LIMIT 5000000          /* sufficient for ~10 k terms */

static uint64_t *primes = NULL;
static size_t    prime_cnt = 0;

static void build_primes(void)
{
    if (primes != NULL)
        return;

    bool *comp = (bool *)calloc(PRIME_LIMIT + 1, sizeof(bool));
    if (!comp) return;

    size_t cap  = 400000;                  /* rough upper bound */
    primes     = (uint64_t *)malloc(cap * sizeof(uint64_t));
    if (!primes) {
        free(comp);
        return;
    }

    prime_cnt = 0;
    for (uint64_t i = 2; i <= PRIME_LIMIT; ++i) {
        if (!comp[i]) {
            if (prime_cnt == cap) {
                cap <<= 1;
                uint64_t *tmp = (uint64_t *)realloc(primes, cap * sizeof(uint64_t));
                if (!tmp) {
                    free(comp);
                    return;
                }
                primes = tmp;
            }
            primes[prime_cnt++] = i;
            if (i * i <= PRIME_LIMIT) {
                for (uint64_t j = i * i; j <= PRIME_LIMIT; j += i)
                    comp[j] = true;
            }
        }
    }
    free(comp);
}

/* ---------- test for product of two distinct primes -------------------- */
static bool two_prime_product(seq_t v)
{
    uint64_t val = (uint64_t)v;
    if (val < 6u)                /* smallest product: 2*3 = 6 */
        return false;

    uint64_t rem = val;
    uint64_t f1 = 0ULL, f2 = 0ULL;

    for (size_t i = 0; i < prime_cnt; ++i) {
        uint64_t p = primes[i];
        if (p * p > rem) break;
        if (rem % p == 0ULL) {
            if (f1 == 0ULL) {
                f1 = p;
                rem /= p;
                if (rem % p == 0ULL) return false;          /* repeated factor */
            } else if (f2 == 0ULL) {
                f2 = p;
                rem /= p;
                if (rem % p == 0ULL) return false;
            } else {
                return false;                              /* more than two */
            }
        }
    }

    if (rem != 1ULL) {
        if (f1 == 0ULL) f1 = rem;
        else if (f2 == 0ULL) f2 = rem;
        else return false;
    }

    return (f1 != 0ULL) && (f2 != 0ULL) && (f1 != f2);
}

/* ---------- cached sequence values ------------------------------------- */
static seq_t *terms = NULL;
static size_t terms_len = 0;
static size_t terms_cap = 0;

/* generate at least n terms */
static void generate_terms(idx_t n)
{
    if (terms_len >= (size_t)n)
        return;

    if (!terms) {
        terms_cap = (size_t)n > 10 ? (size_t)n : 10;
        terms = (seq_t *)calloc(terms_cap, sizeof(seq_t));
        if (!terms) return;
    }

    if (!primes)
        build_primes();

    uint64_t start = 6ull;
    if (terms_len > 0)
        start = (uint64_t)terms[terms_len - 1] + 1;

    for (uint64_t num = start; terms_len < (size_t)n; ++num) {
        seq_t k = (seq_t)num;
        if (!two_prime_product(k)) continue;

        seq_t a = 2 * k + 1;
        if (!two_prime_product(a)) continue;

        seq_t b = 4 * k + 3;
        if (!two_prime_product(b)) continue;

        seq_t c = 8 * k + 7;
        if (!two_prime_product(c)) continue;

        if (terms_len == terms_cap) {
            terms_cap = terms_cap + (terms_cap >> 1) + 1;
            seq_t *tmp = (seq_t *)realloc(terms, terms_cap * sizeof(seq_t));
            if (!tmp) return;
            terms = tmp;
        }
        terms[terms_len++] = k;
    }
}

/* ---------- public sequence function ----------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;            /* undefined, return 0 */
    generate_terms(n);
    return terms[(size_t)n - 1];
}
