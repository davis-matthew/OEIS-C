/*
 * A177735  a(0)=1, a(n)=A002445(n)/6 for n>=1.
 * https://oeis.org/A177735
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = product of primes p>3 such that (p-1) divides 2*n
 * Range:     u8 n <= 5, u16 n <= 17, u32 n <= 89, u64 n <= 269,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The function uses a simple sieve to generate all primes up to 2*n+1
   once per maximum n requested.  For each n it multiplies the primes
   p>3 for which (p-1) | 2*n and returns the product as seq_t.  The
   special case n==0 returns 1. */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* static cache of primes generated by ensure_primes */
static uint64_t *prime_list = NULL;
static size_t      prime_cnt  = 0;
static idx_t       primes_limit = 0U;

/* Build or extend the prime list up to 'limit' (inclusive) */
static void ensure_primes(idx_t limit)
{
    if (limit <= primes_limit)
        return;

    /* allocate array for sieve */
    size_t sz = (size_t)limit + 1U;
    bool *is_comp = (bool *)malloc(sz);
    if (!is_comp)
        return;                              /* out of memory: abort silently */
    for (size_t i = 0; i < sz; ++i)
        is_comp[i] = false;

    /* classical Eratosthenes sieve */
    for (idx_t i = 2; i * i <= limit; ++i) {
        if (!is_comp[i]) {
            for (idx_t j = i * i; j <= limit; j += i)
                is_comp[j] = true;
        }
    }

    /* count primes to allocate array */
    size_t cnt = 0;
    for (idx_t i = 2; i <= limit; ++i)
        if (!is_comp[i])
            ++cnt;

    /* allocate new prime array */
    uint64_t *new_primes = (uint64_t *)malloc(cnt * sizeof(uint64_t));
    if (!new_primes) {
        free(is_comp);
        return;                              /* out of memory: abort silently */
    }

    /* fill prime array */
    size_t idx = 0;
    for (idx_t i = 2; i <= limit; ++i)
        if (!is_comp[i])
            new_primes[idx++] = (uint64_t)i;

    free(is_comp);

    /* replace old prime list */
    if (prime_list)
        free(prime_list);
    prime_list   = new_primes;
    prime_cnt    = cnt;
    primes_limit = limit;
}

/* Main sequence function */
seq_t a(idx_t n)
{
    if (n == 0U)
        return 1U;

    /* compute 2*n and the sieve limit */
    idx_t v = n + n;
    idx_t limit = v + 1U;
    ensure_primes(limit);

    seq_t prod = 1U;
    for (size_t i = 0; i < prime_cnt; ++i) {
        seq_t p = prime_list[i];
        if (p <= 3U)
            continue;
        idx_t d = (idx_t)p - 1U;
        if (v % d == 0U)
            prod *= p;
    }
    return prod;
}
