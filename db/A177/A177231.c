/*
 * A177231  Fibonacci numbers whose decimal expansion does not contain any
 *          digit "2".
 * https://oeis.org/A177231
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 10, u16 n <= 19, u32 n <= 27, u64 n <= 32, u128 n <= 32,
 *            big any n
 * Helpers:   no_two
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
 * Sequence A177231: Fibonacci numbers whose decimal expansion does not
 * contain any digit "2".  A(n) is the n-th such Fibonacci number
 * (OEIS offset 1: a(1)=0, a(2)=1, a(3)=3, ...).
 * The sequence is generated by iterating through the Fibonacci sequence
 * and collecting only those terms that contain no digit 2,
 * while discarding duplicate values (e.g. the two occurrences of 1).
 */
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/no_two.h"

seq_t a(idx_t n)
{
    /* Static storage for terms that satisfy the condition */
    static seq_t *cache = NULL;
    static size_t cache_len = 0, cache_cap = 0;
    /* Static state for generating Fibonacci numbers */
    static seq_t f_prev = 0;   /* F(k)   */
    static seq_t f_next = 1;   /* F(k+1) */
    static bool initialized = false;
    /* Keep track of the last value that was added to the cache
       to avoid duplicates (the Fibonacci number 1 occurs twice). */
    static seq_t last_added = 0;
    static bool has_last = false;

    if (!initialized)
    {
        cache_cap = 32;
        cache = (seq_t*)malloc(cache_cap * sizeof(seq_t));
        initialized = true;
    }

    /* Generate Fibonacci numbers until we have at least n terms. */
    while (cache_len < n)
    {
        seq_t curr = f_prev;          /* Current Fibonacci number */
        if (no_two(curr))
        {
            if (!has_last || curr != last_added) /* skip duplicates */
            {
                /* Grow cache if needed */
                if (cache_len == cache_cap)
                {
                    size_t new_cap = cache_cap * 2;
                    seq_t *tmp = (seq_t*)realloc(cache, new_cap * sizeof(seq_t));
                    if (!tmp) return 0; /* Allocation failure: return 0 as fallback */
                    cache = tmp;
                    cache_cap = new_cap;
                }
                cache[cache_len++] = curr;
                last_added = curr;
                has_last = true;
            }
        }
        /* Advance to next Fibonacci number */
        seq_t new_next = f_prev + f_next;
        f_prev = f_next;
        f_next = new_next;
    }

    return cache[n - 1];
}
