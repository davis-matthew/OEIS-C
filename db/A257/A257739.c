/*
 * A257739  Numbers n for which A256999(n) > n; numbers that can be made
 *          larger by rotating (by one or more steps) the non-msb bits of
 *          their binary representation (with A080541 or A080542).
 * https://oeis.org/A257739
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 197, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A257739: numbers n for which rotating the non‑MSB bits of n
   yields a larger number.  The sequence is generated by
   checking each integer in increasing order until the required
   index is reached.  The property test uses only integer operations. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

static inline bool good(seq_t m) {
    /* Compute the length of the binary representation */
    idx_t bitlen = 0;
    seq_t t = m;
    if (t == 0) return false;
    while (t) {
        t >>= 1;
        ++bitlen;
    }
    if (bitlen <= 1) return false;           /* no suffix to rotate */
    idx_t L = bitlen - 1;                    /* length of the suffix */
    seq_t mask = ((seq_t)1 << L) - 1;         /* mask for L lowest bits */
    seq_t suffix = m & mask;                 /* the suffix bits */

    /* Try all non‑trivial rotations of the suffix */
    for (idx_t k = 1; k < L; ++k) {
        seq_t rot = ((suffix << k) | (suffix >> (L - k))) & mask;
        if (rot > suffix) return true;       /* can make n larger */
    }
    return false;
}

seq_t a(idx_t n) {
    static seq_t *seq = NULL;
    static size_t cap = 0, len = 0;
    static idx_t last = 0;  /* last integer tested */

    if (seq == NULL) {
        cap = 16;
        seq = (seq_t *)malloc(cap * sizeof(seq_t));
    }

    while (len < n) {
        ++last;
        if (good((seq_t)last)) {
            if (len == cap) {
                cap <<= 1;
                seq = (seq_t *)realloc(seq, cap * sizeof(seq_t));
            }
            seq[len++] = (seq_t)last;
        }
    }
    return seq[n - 1];
}
