/* A257591:  Odd numbers which are not prime powers but have a proper divisor ≡ 1 (mod 4);
   a(n) is the n‑th such odd integer. The sequence is generated by scanning odd
   integers and selecting those that satisfy the two stated conditions.
   The implementation memoises found terms in a static cache so that
   subsequent calls are fast and order‑independent. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

/* external types as defined by the build system */
extern seq_t a(idx_t n);

/* internal cache for memoisation */
static seq_t *cache          = NULL;   /* array of computed terms          */
static size_t cache_size     = 0;      /* number of terms stored so far    */
static size_t cache_cap      = 0;      /* current capacity of the cache    */
static uint64_t last_checked = 1;      /* last odd integer examined        */

/* --------------------------------------------------------------------- */
/* ensure the cache can hold at least 'needed' elements
   --------------------------------------------------------------------- */
static void ensure_cache(size_t needed)
{
    if (cache_cap < needed)
    {
        size_t new_cap = needed;
        seq_t *new_ptr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        cache        = new_ptr;
        cache_cap    = new_cap;
    }
}

/* --------------------------------------------------------------------- */
/* Check whether an odd integer m satisfies the OEIS A257591 definition.
   m must be >1 and odd. The routine performs trial factorisation up to
   sqrt(m).                                   */
static bool is_candidate(uint64_t m)
{
    /* factorisation storage */
    uint64_t primes[64];
    unsigned  exps[64];
    size_t    pcnt = 0;

    uint64_t tmp = m;

    /* trial division by odd factors */
    for (uint64_t p = 3; p <= tmp / p; p += 2)
    {
        if (tmp % p == 0)
        {
            unsigned exp = 0;
            while (tmp % p == 0)
            {
                tmp /= p;
                exp++;
            }
            primes[pcnt] = p;
            exps[pcnt]   = exp;
            pcnt++;
        }
    }
    /* remaining prime factor, if any */
    if (tmp > 1)
    {
        primes[pcnt] = tmp;
        exps[pcnt]   = 1;
        pcnt++;
    }

    /* at least two distinct prime factors are required */
    if (pcnt < 2)
        return false;

    /* ----------------------------------------------------------------- */
    /* Condition 1: any prime factor ≡ 1 (mod 4) gives a proper divisor
       (the prime itself).                                      */
    for (size_t i = 0; i < pcnt; ++i)
    {
        if (primes[i] % 4 == 1ULL)
            return true;
    }

    /* Condition 2: a prime factor ≡ 3 (mod 4) with exponent ≥ 2 gives
       p² ≡ 1 (mod 4).                                           */
    for (size_t i = 0; i < pcnt; ++i)
    {
        if (primes[i] % 4 == 3ULL && exps[i] >= 2U)
            return true;
    }

    /* Condition 3: product of two distinct primes ≡ 3 (mod 4) is a divisor
       ≡ 1 (mod 4), provided that product is a proper divisor.   */
    size_t cnt3 = 0;
    bool   all_exp1 = true;
    for (size_t i = 0; i < pcnt; ++i)
    {
        if (primes[i] % 4 == 3ULL)
        {
            cnt3++;
            if (exps[i] != 1U)
                all_exp1 = false;
        }
    }
    /* If there are at least two such primes and the number is not exactly
       the product of two distinct 3‑mod‑4 primes, we have a proper divisor. */
    if (cnt3 >= 2U)
    {
        if (!(pcnt == 2U && all_exp1 && (primes[0] % 4 == 3ULL) && (primes[1] % 4 == 3ULL)))
            return true;
    }

    return false;
}

/* --------------------------------------------------------------------- */
/* Main function required by the build system.                           */
seq_t a(idx_t n)
{
    /* Undefined for n < 1 – return zero as a placeholder. */
    if (n < 1)
        return (seq_t)0;

    /* Expand the cache to hold at least 'n' terms. */
    ensure_cache((size_t)n);

    /* Scan odd integers until we have found 'n' valid terms. */
    while (cache_size < (size_t)n)
    {
        /* Move to the next odd integer. */
        do
        {
            last_checked++;
        } while ((last_checked & 1ULL) == 0);

        uint64_t candidate = last_checked;

        if (is_candidate(candidate))
        {
            cache[cache_size++] = (seq_t)candidate;
        }
    }

    return cache[n - 1];
}
