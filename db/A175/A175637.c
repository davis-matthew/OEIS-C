/*
 * A175637  Numbers n such that the decimal digits of n are not present in
 *          k*n, k=2..9.
 * https://oeis.org/A175637
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 11, u32 n <= 28, u64 n <= 31, u128 n <= 31,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements OEIS sequence A175637.
   The sequence consists of the numbers whose decimal digits do not appear
   in k*n for any k=2..9.  It is generated by merging the four infinite
   patterns
      1, 11, 111, ...
      7, 77, 777, ...
      707, 70707, 7070707, ...
      909, 90909, 9090909, ...
   together with the single digits 3 and 9, in ascending order. */

/*  The implementation keeps a small static cache of computed terms.
    It is safe for both C11 and C++17 and works for any seq_t type
    that supports the integral operators used below. */

#include <stdbool.h>

/* Number of terms to cache – sufficient for n up to ~10 000. */
#define MAX_CACHE 20000

static seq_t cache[MAX_CACHE];
static idx_t cache_len = 0;

/* current values of the four patterns and flags for the singleton terms */
static seq_t rep_val;      /* 1, 11, 111, … */
static seq_t seven_val;    /* 7, 77, 777, … */
static seq_t seven0_val;   /* 707, 70707, … */
static seq_t nine0_val;    /* 909, 90909, … */
static bool const3_used = false;
static bool const9_used = false;

/* initialise the pattern generators on first use */
static void init_patterns(void)
{
    rep_val     = 1;
    seven_val   = 7;
    seven0_val  = 707;
    nine0_val   = 909;
    const3_used = false;
    const9_used = false;
}

/* generate the next term in the merged sequence */
static seq_t next_term(void)
{
    seq_t min_val = rep_val;
    int kind = 0;                     /* 0:rep,1:seven,2:seven0,3:nine0,4:3,5:9 */

    if (seven_val < min_val) { min_val = seven_val; kind = 1; }
    if (seven0_val < min_val) { min_val = seven0_val; kind = 2; }
    if (nine0_val < min_val) { min_val = nine0_val; kind = 3; }

    if (!const3_used && (seq_t)3 < min_val) { min_val = (seq_t)3; kind = 4; }
    if (!const9_used && (seq_t)9 < min_val) { min_val = (seq_t)9; kind = 5; }

    /* advance the selected pattern */
    switch (kind) {
        case 0:  rep_val = rep_val * 10 + 1; break;
        case 1:  seven_val = seven_val * 10 + 7; break;
        case 2:  seven0_val = seven0_val * 100 + 7; break;
        case 3:  nine0_val = nine0_val * 100 + 9; break;
        case 4:  const3_used = true; break;
        case 5:  const9_used = true; break;
    }
    return min_val;
}

/* public sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                 /* out of range – not used */

    /* initialise the first time */
    static bool initialized = false;
    if (!initialized) {
        init_patterns();
        initialized = true;
    }

    /* generate terms until we have the requested index */
    while (cache_len < n && cache_len < MAX_CACHE) {
        cache[cache_len++] = next_term();
    }

    /* if n is larger than MAX_CACHE the function cannot provide it,
       but the exercise guarantees n will not exceed this bound. */
    return cache[n - 1];
}
