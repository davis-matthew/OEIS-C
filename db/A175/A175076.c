/*
 * A175076  Composites c which end at 2 under iterations of {r mod (max prime
 *          p < r)} starting at r = c.
 * https://oeis.org/A175076
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 59, u16 n <= 59, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements OEIS A175076: composites that end at 2 under iterations of
   r mod (largest prime < r).  The sequence is generated by testing
   successive composites and collecting those that reach 2. */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"

static seq_t *terms = NULL;          /* stored sequence terms        */
static size_t terms_cap = 0;         /* capacity of terms array       */
static idx_t   terms_cnt = 0;        /* number of terms computed      */

static bool ends_at_2(seq_t r)
{
    while (r != (seq_t)2) {
        /* find largest prime less than r */
        seq_t p = r - (seq_t)1;
        while (!is_prime_big(p)) {
            --p;
        }
        r = r % p;
        if (r < (seq_t)2) {
            return false;
        }
    }
    return true;
}

static void ensure_terms_capacity(idx_t needed)
{
    if (terms_cnt >= needed)
        return;

    for (;;) {
        /* test next candidate */
        seq_t cand = (idx_t)(terms_cnt == 0 ? 4 : (seq_t)(terms[terms_cnt - 1] + (seq_t)1));
        /* advance until we find enough terms */
        while (cand < (seq_t)UINT64_MAX) { /* upper bound safeguard */
            if (!is_prime_big(cand)) {
                if (ends_at_2(cand)) {
                    if (terms_cnt >= terms_cap) {
                        size_t newcap = terms_cap ? terms_cap << 1 : 16;
                        seq_t *np = (seq_t *)realloc(terms, newcap * sizeof(seq_t));
                        terms = np;
                        terms_cap = newcap;
                    }
                    terms[terms_cnt++] = cand;
                    if (terms_cnt >= needed)
                        return;
                }
            }
            cand = cand + (seq_t)1;
        }
        /* If we run out of reasonable bounds, stop */
        return;
    }
}

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;          /* undefined for index 0 */
    ensure_terms_capacity(n);
    return terms[n - (idx_t)1];
}
