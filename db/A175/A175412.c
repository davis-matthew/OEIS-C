/*
 * A175412  Those primes p where p+{the number of divisors of (p+1)} is prime.
 * https://oeis.org/A175412
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 23, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   divisor_count_u64, ensure_capacity, is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
 * Formula: a(n) is the nth prime p such that (p + τ(p+1)) is prime, 
 * where τ(m) is the number of divisors of m. 
 * The sequence is generated by iteratively testing primes and
 * storing qualifying values in a growing cache.
 */

#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>
#include "../utils/is_prime.h"
#include "../utils/divisor_count_u64.h"
#include "../utils/ensure_capacity.h"

seq_t a(idx_t n)
{
    /* Static cache state */
    static seq_t *cache   = NULL;   /* array of found terms */
    static size_t  cnt    = 0;      /* number of terms stored */
    static size_t  cap    = 0;      /* capacity of cache array */
    static uint64_t last  = 2;      /* next integer to test as prime */

    /* On first call, initialise cache and cap */
    if (cap == 0) {
        cap = 64;
        cache = (seq_t *)malloc(cap * sizeof(seq_t));
    }

    /* Generate terms until we have at least n of them */
    while (cnt < n) {
        /* Find next prime candidate */
        while (!is_prime(last))
            ++last;

        uint64_t p = last;
        ++last; /* next search start */

        /* Compute divisor count of (p+1) */
        uint64_t d = divisor_count_u64(p + 1);

        /* Test whether p + d is prime */
        if (is_prime(p + d)) {
            /* Ensure cache capacity */
            ensure_capacity(cnt + 1, &cap, (void **)&cache, sizeof(seq_t));
            cache[cnt++] = (seq_t)p;
        }
    }

    /* Return the requested term (1‑based index) */
    return cache[n - 1];
}
