/* OEIS A175773 – Expansion of 1/(1 - x - x^6 - x^11 + x^12)
 *
 * Recurrence for n ≥ 12:
 *     a(n) = a(n-1) + a(n-6) + a(n-11) − a(n-12)
 * Initial values:
 *     a(0)=1, a(1)=1, a(2)=1, a(3)=1, a(4)=1, a(5)=1,
 *     a(6)=2, a(7)=3, a(8)=4, a(9)=5, a(10)=6, a(11)=8
 *
 * The sequence is generated by memoisation in a static cache.
 * The cache is initialised only once and grows as needed.
 * The function safely handles calls in any order of n.
 */

#include <stddef.h>
#include <stdlib.h>

/* static cache for memoisation */
static seq_t *cache      = NULL;   /* array of terms   */
static size_t cached_size = 0;     /* numbers of terms cached (valid indices 0 .. cached_size-1) */
static size_t cache_cap   = 0;     /* allocated capacity */

/* ensure cache has capacity for indices up to 'n' (inclusive) */
static void ensure_cache_capacity(size_t n)
{
    if (n < cache_cap) return;

    size_t new_cap = cache_cap ? cache_cap * 2 : 64;
    while (new_cap <= n) new_cap <<= 1;

    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    cache = tmp;
    cache_cap = new_cap;
}

/* initialise cache with the first 12 terms */
static void init_cache(void)
{
    if (cached_size > 0) return;

    ensure_cache_capacity(11);           /* indices 0..11 */

    /* initial terms: a(0)..a(11) */
    const seq_t init[12] = {
        (seq_t)1, (seq_t)1, (seq_t)1, (seq_t)1,
        (seq_t)1, (seq_t)1, (seq_t)2, (seq_t)3,
        (seq_t)4, (seq_t)5, (seq_t)6, (seq_t)8
    };
    for (size_t i = 0; i < 12; ++i) {
        cache[i] = init[i];
    }
    cached_size = 12;
}

/* sequence function --------------------------------------------------------*/
seq_t a(idx_t n)
{
    /* ensure cache has been set up */
    if (!cache) init_cache();

    /* if index below cached_size, directly return the value */
    if ((size_t)n < cached_size) {
        return cache[(size_t)n];
    }

    size_t idx = (size_t)n;

    /* extend cache up to idx */
    ensure_cache_capacity(idx);

    /* compute any missing terms using the recurrence */
    for (size_t i = cached_size; i <= idx; ++i) {
        seq_t val = cache[i-1] + cache[i-6] + cache[i-11];
        val = val - cache[i-12];
        cache[i] = val;
    }

    /* only extend cached_size forward */
    if (idx + 1 > cached_size) {
        cached_size = idx + 1;
    }

    return cache[idx];
}
