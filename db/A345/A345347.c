/*
 * A345347  Find the largest k with F(k) <= n, where F(k) is the k-th
 *          Fibonacci number. a(n) = F(k+2) + n.
 * https://oeis.org/A345347
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   a(n) = F(k+2) + n, where k is the largest integer with F(k) ≤ n
 *            (F(k) is the k‑th Fibonacci number, F(0)=0, F(1)=1)
 * Range:     u8 n <= 60, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The following computes the required Fibonacci numbers with a simple
   growing cache.  It works for the full range of idx_t and seq_t types
   that the build supplies. */

#include <stdlib.h>
#include <stddef.h>

static seq_t *fib_cache = NULL;   /* cache of Fibonacci numbers */
static size_t fib_cache_size = 0; /* number of cached values */
static size_t fib_cache_cap  = 0; /* allocated capacity */

/* Ensure that fib_cache contains at least indices 0 … k.  If k+1
   Fibonacci numbers are needed, they will be generated by the
   recurrence F(i)=F(i-1)+F(i-2). */
static void
ensure_fib_up_to(idx_t k)
{
    /* initialisation of the first two Fibonacci numbers */
    if (fib_cache_size == 0) {
        size_t init_cap = 2;
        fib_cache = (seq_t *)realloc(NULL, init_cap * sizeof(seq_t));
        if (!fib_cache) return; /* allocation failed – silence */
        fib_cache_cap = init_cap;
        fib_cache[0] = 0;
        fib_cache[1] = 1;
        fib_cache_size = 2;
    }

    /* extend the cache as needed */
    if (k + 1 > fib_cache_cap) {
        size_t new_cap = fib_cache_cap ? fib_cache_cap * 2 : 8;
        while (new_cap < (size_t)(k + 1))
            new_cap *= 2;
        seq_t *tmp = (seq_t *)realloc(fib_cache, new_cap * sizeof(seq_t));
        if (!tmp) return; /* allocation failed – silence */
        fib_cache = tmp;
        fib_cache_cap = new_cap;
    }

    if (fib_cache_size <= (size_t)k) {
        for (size_t i = fib_cache_size; i <= (size_t)k; ++i) {
            fib_cache[i] = fib_cache[i - 1] + fib_cache[i - 2];
        }
        fib_cache_size = (size_t)k + 1;
    }
}

/* Find the largest index k such that fib_cache[k] ≤ n.
   It assumes fib_cache is already extended so that the last
   value satisfies fib_cache[last] > n. */
static idx_t
find_k(idx_t n)
{
    idx_t low = 0;
    idx_t high = (idx_t)fib_cache_size - 1;
    idx_t ans  = 0; /* guaranteed to be ≤ high */

    while (low <= high) {
        idx_t mid = low + ((high - low) >> 1);
        if (fib_cache[mid] <= (seq_t)n) {
            ans = mid;
            low = mid + 1;
        } else {
            high = mid - 1;
        }
    }
    return ans;
}

seq_t a(idx_t n)
{
    /* Step 1: make sure we have a Fibonacci number larger than n
       so that the binary search knows where to stop. */
    if (fib_cache_size < 2)   /* initialise if needed */
        ensure_fib_up_to(1);
    while (fib_cache[fib_cache_size - 1] <= (seq_t)n) {
        /* extend by one more Fibonacci number */
        ensure_fib_up_to((idx_t)fib_cache_size); /* this will add next index */
    }

    /* Step 2: find k such that F(k) ≤ n < F(k+1) */
    idx_t k = find_k(n);

    /* Step 3: ensure we have F(k+2) */
    ensure_fib_up_to(k + 2);

    /* Step 4: compute a(n) = F(k+2) + n */
    return fib_cache[k + 2] + (seq_t)n;
}
