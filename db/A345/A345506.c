/*
 * A345506  Numbers that are the sum of seven cubes in ten or more ways.
 * https://oeis.org/A345506
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute numbers that are the sum of seven cubes in ten or more ways.
   The sequence is generated by dynamic programming that counts
   the number of unordered 7‑tuples of positive integers whose cubes sum
   to a given value.  Terms are memoised in a static array.
   The algorithm limits the maximum sum to 300000, which is enough
   to generate at least 10 000 terms.  */

#include <stdlib.h>
#include <stdbool.h>

static seq_t *dp[8];          /* DP arrays: dp[k][sum] = #ways with k cubes */
static seq_t *terms_arr = NULL;
static size_t terms_len = 0;
static size_t terms_cap = 0;
static bool initialized = false;

/* initialise the DP tables and build the list of terms */
static void init_sequence(void)
{
    if (initialized)
        return;

    /* upper bound for the sums we generate; sufficient for >=10 000 terms */
    const idx_t MAX_N = 300000;
    const size_t sz = (size_t)MAX_N + 1;

    /* allocate and zero DP tables */
    for (int k = 0; k < 8; ++k) {
        dp[k] = (seq_t *)calloc(sz, sizeof(seq_t));
        if (!dp[k])
            abort();
    }
    dp[0][0] = (seq_t)1;          /* one trivial way to make 0 with 0 cubes */

    /* process each cube value */
    for (unsigned int v = 1;; ++v) {
        unsigned long long cube_ll = (unsigned long long)v * v * v;
        if (cube_ll > MAX_N)
            break;
        seq_t cube = (seq_t)cube_ll;
        idx_t c = (idx_t)cube;
        for (idx_t s = c; s <= MAX_N; ++s) {
            idx_t r = s - c;
            for (int k = 1; k <= 7; ++k) {
                dp[k][s] += dp[k - 1][r];
            }
        }
    }

    /* build the list of sums with at least 10 representations */
    terms_cap = 20000;                     /* initial capacity */
    terms_arr = (seq_t *)malloc(terms_cap * sizeof(seq_t));
    if (!terms_arr)
        abort();
    terms_len = 0;
    for (idx_t s = 0; s <= MAX_N; ++s) {
        if (dp[7][s] >= (seq_t)10) {
            if (terms_len == terms_cap) {
                terms_cap *= 2;
                terms_arr = (seq_t *)realloc(terms_arr,
                                              terms_cap * sizeof(seq_t));
                if (!terms_arr)
                    abort();
            }
            terms_arr[terms_len++] = (seq_t)s;
        }
    }

    /* free DP tables – they are no longer needed after the list is built */
    for (int k = 0; k < 8; ++k) {
        free(dp[k]);
        dp[k] = NULL;
    }

    initialized = true;
}

/* Return the nth term of the sequence (1‑based). */
seq_t a(idx_t n)
{
    init_sequence();
    if (n == 0 || n > terms_len)
        return (seq_t)0;   /* undefined, but avoid out‑of‑bounds */
    return terms_arr[n - 1];
}
