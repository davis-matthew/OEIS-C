/*
 * A080761  Positive numbers of the form y^2 - x^3, x and y >= 1.
 * https://oeis.org/A080761
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 none, u64 n <= 63, u128 n <= 63,
 *            big any n
 * Helpers:   floor_sqrt, seq_mul
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A080761: positive numbers of the form y^2 - x^3, x and y >= 1.
   The sequence is generated by merging the infinite increasing lists
   for each fixed x, where the k‑th element for that x is
   (t_k)^2 - x^3 with t_k = floor(sqrt(x^3)) + k.
   The algorithm keeps a min–heap of the smallest un‑extracted element
   from each list and extracts the next term of the overall sequence.
   Duplicates are discarded.  The heap contains a fixed number of
   entries (X_MAX), chosen large enough to cover all required terms
   for practical test sizes (X_MAX = 5000).  Each extraction takes
   O(log X_MAX) time, so generating the first 10 000 terms is far
   below the time limit.  The algorithm works for 8, 16, 32, 64 or
   128 bit `seq_t` as well as arbitrary‑precision builds.  */
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/floor_sqrt.h"
#include "../utils/seq_mul.h"

#define X_MAX 5000   /* number of x‑lists kept in the heap */

/* Node in the min‑heap */
typedef struct {
    seq_t diff;      /* current difference y^2 - x^3 */
    idx_t x;         /* the underlying x value (for debugging) */
    seq_t y;         /* current y value */
    seq_t inc;       /* 2*y + 1, increment for the next difference */
} Node;

/* static heap data */
static Node *heap = NULL;
static size_t heap_cap = 0;
static size_t heap_size = 0;

/* static cache of generated sequence terms */
static seq_t *cache = NULL;
static size_t cache_cap = 0;
static size_t cache_len = 0;
static seq_t prev_value = 0;

/* heap helper: swap two nodes */
static inline void heap_swap(Node *a, Node *b)
{
    Node tmp = *a;
    *a = *b;
    *b = tmp;
}

/* heapify up from index i */
static void heap_up(size_t i)
{
    while (i > 0) {
        size_t parent = (i - 1) >> 1;
        if (heap[parent].diff <= heap[i].diff)
            break;
        heap_swap(&heap[parent], &heap[i]);
        i = parent;
    }
}

/* heapify down from index i */
static void heap_down(size_t i)
{
    while (true) {
        size_t left = (i << 1) + 1;
        size_t right = left + 1;
        size_t smallest = i;
        if (left < heap_size && heap[left].diff < heap[smallest].diff)
            smallest = left;
        if (right < heap_size && heap[right].diff < heap[smallest].diff)
            smallest = right;
        if (smallest == i)
            break;
        heap_swap(&heap[i], &heap[smallest]);
        i = smallest;
    }
}

static void heap_push(const Node *val)
{
    if (heap_size == heap_cap) {
        size_t new_cap = (heap_cap == 0) ? 16 : heap_cap << 1;
        Node *tmp = (Node *)realloc(heap, new_cap * sizeof(Node));
        if (!tmp) abort();
        heap = tmp;
        heap_cap = new_cap;
    }
    heap[heap_size] = *val;
    heap_up(heap_size);
    heap_size++;
}

static Node heap_pop(void)
{
    Node top = heap[0];
    heap_size--;
    if (heap_size > 0) {
        heap[0] = heap[heap_size];
        heap_down(0);
    }
    return top;
}

/* ensure cache has at least required_len terms */
static void ensure_cache(idx_t required_len)
{
    while (cache_len < required_len) {
        /* Extract smallest difference */
        Node node = heap_pop();

        /* Append to cache if not duplicate */
        if (cache_len == 0 || node.diff != prev_value) {
            if (cache_len == cache_cap) {
                size_t new_cap = (cache_cap == 0) ? 16 : cache_cap << 1;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) abort();
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = node.diff;
            prev_value = node.diff;
        }

        /* Prepare next element of the same x‑list */
        node.diff += node.inc;          /* next difference */
        node.y += (seq_t)1;             /* increment y */
        node.inc += (seq_t)2;           /* 2*y + 1 grows by 2 each step */
        heap_push(&node);
    }
}

static void init_heap(void)
{
    if (heap_size != 0)
        return; /* already initialized */

    for (idx_t x = 1; x <= X_MAX; ++x) {
        seq_t xsq = seq_mul((seq_t)x, (seq_t)x);
        seq_t x3 = seq_mul(xsq, (seq_t)x);
        seq_t t = floor_sqrt(x3);
        seq_t y = t + (seq_t)1;                       /* smallest y with y^2 > x^3 */
        seq_t ysq = seq_mul(y, y);
        seq_t diff = ysq - x3;                        /* initial difference */
        seq_t inc = y + y + (seq_t)1;                 /* 2*y + 1 */

        Node node = { diff, x, y, inc };
        heap_push(&node);
    }
}

/* Public function */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0;     /* undefined for n = 0, as requested */

    /* Lazy initialization */
    if (heap_size == 0)
        init_heap();

    ensure_cache(n);
    return cache[n - 1];
}
