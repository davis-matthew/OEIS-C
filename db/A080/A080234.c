/* A080234 – Triangle whose rows are the differences of consecutive pairs
 * of row elements of A080232.  The flattened sequence a(n) is indexed
 * row‑major with offset 0.  The triangle can be generated by the
 * recurrence
 *     a(r,0)   = 1,
 *     a(r,1)   = r-3   (r ≥ 1),
 *     a(r,r)   = a(r,1),
 *     a(r,k)   = a(r-1,k) + a(r-1,k-1)   (2 ≤ k ≤ r-1).
 * The flattened index n is mapped to row r and column c by
 *   r determined by r(r+1)/2 ≤ n < (r+1)(r+2)/2,  c = n − r(r+1)/2.  */
#include <stddef.h>
#include <stdlib.h>

seq_t a(idx_t n)
{
    /* find r where r(r+1)/2 <= n < (r+1)(r+2)/2   (row containing n) */
    idx_t sum = 0;   /* total elements before row r */
    idx_t r   = 0;
    while (sum + (r + 1) <= n) {
        sum += r + 1;
        ++r;
    }
    /* allocate the first row (r = 0) */
    seq_t *prev = (seq_t *)malloc(sizeof(seq_t));
    if (!prev) return 0;        /* memory allocation failed */
    prev[0] = 1;

    /* build rows 1 .. r using the recurrence */
    for (idx_t i = 1; i <= r; ++i) {
        size_t len = (size_t)(i + 1);
        seq_t *cur = (seq_t *)malloc(len * sizeof(seq_t));
        if (!cur) {
            free(prev);
            return 0;           /* memory allocation failed */
        }

        cur[0] = 1;
        cur[1] = (seq_t)i - 3;  /* a(r,1) */

        if (i >= 2) {
            for (idx_t k = 2; k <= i - 1; ++k) {
                cur[k] = prev[k] + prev[k - 1];
            }
        }
        cur[i] = cur[1];         /* a(r,r) = a(r,1) */

        free(prev);
        prev = cur;
    }

    /* now prev points to the desired row; fetch element at column c */
    size_t col = (size_t)(n - sum);
    seq_t result = prev[col];
    free(prev);
    return result;
}
