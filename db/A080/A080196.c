/*
 * A080196  13-smooth numbers which are not 11-smooth.
 * https://oeis.org/A080196
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 17, u16 n <= 539, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A080196: numbers of the form 2^r 3^s 5^t 7^u 11^v 13^w with w>0.
   a(n) = 13 * b(n), where b(n) is the nth number whose prime factors are
   all <=13.  The array b is generated by the classic “multiple‑pointer”
   algorithm over the primes 2,3,5,7,11,13. */

#include <stdlib.h>
#include <stddef.h>

/* Used primes for 13‑smooth numbers (primes <=13) */
static const seq_t fprimes[6] = {(seq_t)2, (seq_t)3, (seq_t)5,
                                 (seq_t)7, (seq_t)11, (seq_t)13};

/* Cached array of all 13‑smooth numbers generated so far */
static seq_t *smooth = NULL;
static size_t smooth_len = 0;   /* number of elements currently stored  */
static size_t smooth_cap = 0;   /* capacity of the allocated array      */

/* Indices into `smooth` for each prime;
   smooth[idxp[i]] * fprimes[i] is the next candidate for prime i. */
static size_t idxp[6] = {0, 0, 0, 0, 0, 0};

/* Ensure that `smooth` contains at least indices 0 … needed (inclusive).
 * This function expands the array if necessary and generates the missing
 * 13‑smooth numbers using the multiple‑pointer algorithm. */
static void ensure_smooth_len(idx_t needed)   /* needed is zero‑based index */
{
    if (smooth_len > needed) return;

    /* initialise the first element */
    if (smooth_len == 0) {
        smooth_cap = 1;
        smooth = (seq_t *)malloc(smooth_cap * sizeof(seq_t));
        smooth[0] = (seq_t)1;
        smooth_len = 1;
    }

    /* increase capacity if required */
    if (smooth_cap <= (size_t)needed) {
        size_t new_cap = smooth_cap ?: 1;
        while (new_cap <= (size_t)needed) new_cap <<= 1;
        smooth = (seq_t *)realloc(smooth, new_cap * sizeof(seq_t));
        smooth_cap = new_cap;
    }

    /* generate new elements until we have up to 'needed' */
    while (smooth_len <= (size_t)needed) {
        seq_t cand[6];
        size_t i;
        for (i = 0; i < 6; ++i) {
            cand[i] = fprimes[i] * smooth[idxp[i]];
        }

        /* find the minimum candidate */
        seq_t minCand = cand[0];
        for (i = 1; i < 6; ++i)
            if (cand[i] < minCand) minCand = cand[i];

        /* store it */
        smooth[smooth_len++] = minCand;

        /* advance indices that produced it */
        for (i = 0; i < 6; ++i)
            if (cand[i] == minCand) ++idxp[i];
    }
}

seq_t a(idx_t n)   /* n >= 1 */
{
    if (n == 0) return 0;   /* offset < 1 is undefined; return 0 */
    idx_t zero_based = n - 1;
    ensure_smooth_len(zero_based);   /* now smooth[zero_based] exists */
    return smooth[zero_based] * (seq_t)13;
}
