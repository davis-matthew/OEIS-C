/*
 * A080863  Numbers k such that lpf(k)-2 = lpf(k+2), where lpf=A020639 (least
 *          prime factor).
 * https://oeis.org/A080863
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = numbers k such that lpf(k)-2 = lpf(k+2)
 * Range:     u8 n <= 9, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  lpf(n) is the least prime factor of n.  The sequence is
    generated by scanning natural numbers and testing the
    condition with a sieve of least‑prime factors.  The sieve
    is expanded when needed.  The result is memoised so that
    subsequent calls with larger n are efficient. */

#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>

/* storage for the dynamic data */
static struct {
    seq_t  *terms;     /* array of found terms */
    size_t  termsSize; /* number of terms stored          */
    size_t  termsCap;  /* allocated capacity of terms     */
    uint32_t *spf;     /* least prime factor array        */
    size_t  spfLimit;  /* size of spf array               */
    size_t  scanK;     /* next k to examine               */
} data = {NULL, 0, 0, NULL, 0, 0};

/* double the capacity of the terms array */
static void growTerms(void)
{
    if (data.termsSize == data.termsCap) {
        size_t newCap = data.termsCap ? data.termsCap * 2 : 4;
        seq_t *newPtr = (seq_t *)realloc(data.terms, newCap * sizeof(seq_t));
        if (!newPtr) abort();
        data.terms = newPtr;
        data.termsCap = newCap;
    }
}

/* build a linear sieve of least prime factors up to N */
static void buildSPF(size_t N)
{
    uint32_t *newSpf = (uint32_t *)calloc(N + 1, sizeof(uint32_t));
    if (!newSpf) abort();

    /* estimate an upper bound for the number of primes: N/log N + 3  */
    size_t primesCap = N / 10 + 10;
    uint32_t *primes = (uint32_t *)malloc(primesCap * sizeof(uint32_t));
    if (!primes) abort();
    size_t primesCnt = 0;

    newSpf[0] = 0;
    newSpf[1] = 1;

    for (size_t i = 2; i <= N; ++i) {
        if (newSpf[i] == 0) {
            newSpf[i] = (uint32_t)i;
            if (primesCnt < primesCap) primes[primesCnt++] = (uint32_t)i;
        }
        for (size_t j = 0; j < primesCnt; ++j) {
            uint32_t p = primes[j];
            uint64_t v = (uint64_t)p * i;
            if (v > N) break;
            newSpf[v] = p;
            if (p == newSpf[i]) break;
        }
    }

    free(primes);
    free(data.spf);
    data.spf = newSpf;
    data.spfLimit = N;
}

/* ensure that the list of terms contains at least n entries */
static void ensureTerms(idx_t n)
{
    if (data.termsSize >= (size_t)n) return;

    if (data.spfLimit == 0) {
        /* initialise with a reasonable limit */
        size_t initLimit = 1000000;
        buildSPF(initLimit);
        data.scanK = 2;
    }

    while ((size_t)n > data.termsSize) {
        /* extend the sieve if necessary */
        if (data.scanK + 2 > data.spfLimit) {
            size_t newLimit = data.spfLimit * 2;
            while (newLimit < data.scanK + 2) newLimit *= 2;
            buildSPF(newLimit);
        }

        uint32_t p  = data.spf[data.scanK];
        uint32_t r  = data.spf[data.scanK + 2];      /* lpf(k+2) */
        if (p > 2 && r == p - 2) {
            growTerms();
            data.terms[data.termsSize++] = (seq_t)data.scanK;
        }
        ++data.scanK;
    }
}

/* public entry point required by the build */
seq_t a(idx_t n)
{
    ensureTerms(n);
    return data.terms[(size_t)n - 1];
}
