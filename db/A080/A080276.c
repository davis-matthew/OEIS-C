/*
 * A080276  Variation on Connell sequence (A001614). In this one, a(1)=1,
 *          terms a(n) onwards are generated in "blocks" as the next a(n-1)
 *          odd numbers > a(n-1) if the previous block ends with a(n-1) even
 *          and the next a(n-1) even numbers > a(n-1) if the previous block
 *          ends with a(n-1) odd.
 * https://oeis.org/A080276
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 66, u16 n <= 66, u32 n <= 66, u64 n <= 66, u128 n <= 66,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stddef.h>
#include <stdbool.h>

/* This function generates the OEIS sequence A080276, defined by blocks:
   a(1) = 1.  For each subsequent block, its length equals the last value
   of the previous block.  If the previous block ended with an odd number,
   the next block contains the next block‑length even numbers; if it ended
   with an even number, the next block contains the next block‑length odd
   numbers.  The sequence is generated by simulating these blocks. */

seq_t a(idx_t n)
{
    if (n == (idx_t)1)
        return (seq_t)1;

    seq_t val = (seq_t)1;          /* current term a(k) */
    idx_t index = (idx_t)1;        /* current index (1‑based) */

    seq_t block_len = (seq_t)1;    /* size of the block to generate */
    seq_t remaining = (seq_t)1;    /* numbers left to generate in current block */
    bool next_even = true;         /* parity of numbers in the next block
                                     (true → even, false → odd) */

    while (index < n) {
        if (remaining == (seq_t)0) {                    /* start new block */
            block_len = val;                            /* length = last value */
            remaining = block_len;
            next_even = (block_len % (seq_t)2 == (seq_t)0) ? false : true;
        }

        seq_t next;
        if (next_even) {                            /* generate an even number */
            if (val % (seq_t)2 == (seq_t)0)
                next = val + (seq_t)2;
            else
                next = val + (seq_t)1;
        } else { /* generate an odd number */
            if (val % (seq_t)2 == (seq_t)1)
                next = val + (seq_t)2;
            else
                next = val + (seq_t)1;
        }

        val = next;
        remaining -= (seq_t)1;
        ++index;
    }

    return val;
}
