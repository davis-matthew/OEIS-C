/*
 * A080466  Multiples of 11 in which the even positioned digits from left are
 *          even and the odd positioned ones are odd.
 * https://oeis.org/A080466
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn, look
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 250, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This code implements the definition of OEIS A080466:
 * “Multiples of 11 in which the even positioned digits from left are even
 *  and the odd positioned ones are odd.”  
 * The sequence is generated by an incremental search over multiples of 11,
 * keeping the results in a static cache so that non‑monotone: calls to
 * a(idx_t n) return the n‑th term in O(1) after an initial O(n) build. */

#include <stdlib.h>
#include <stdint.h>

seq_t a(idx_t n)
{
    /* static cache for results */
    static seq_t *cache = NULL;      /* array of terms */
    static idx_t  cache_size = 0;    /* number of terms stored */
    static idx_t  cache_cap   = 0;    /* allocated capacity */
    static seq_t  next_mult  = 11;    /* next multiple of 11 to test */

    if (n == 0) return 0; /* 0th term is undefined; return 0 as safe placeholder */

    /* grow cache if necessary */
    while (cache_size < n) {
        /* test whether next_mult satisfies the parity condition */
        seq_t x = next_mult;
        /* compute number of decimal digits */
        seq_t tmp = x;
        int len = 0;
        while (tmp > 0) {
            tmp /= 10;
            len++;
        }

        /* check parity constraints */
        int pos_from_right = 0;      /* 0 for least significant digit */
        seq_t y = x;
        int ok = 1;
        while (y > 0) {
            int digit = (int)(y % 10);
            int left_pos = len - pos_from_right;   /* positions are 1‑based from the left */
            int digit_odd = (digit & 1);

            if ((left_pos & 1) == 1) {         /* odd left position → digit must be odd */
                if (!digit_odd) { ok = 0; break; }
            } else {                           /* even left position → digit must be even */
                if (digit_odd) { ok = 0; break; }
            }
            y /= 10;
            pos_from_right++;
        }

        if (ok) {
            /* store the term */
            if (cache_size == cache_cap) {
                cache_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
                cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
            }
            cache[cache_size++] = x;
        }

        /* advance to next multiple of 11 */
        next_mult += 11;
    }

    return cache[n - 1];
}
