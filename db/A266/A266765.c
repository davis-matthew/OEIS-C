/*
 * A266765  Growth series for affine Coxeter group (or affine Weyl group)
 *          D_10.
 * https://oeis.org/A266765
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 8, u32 n <= 38, u64 n <= 469, u128 n <= 1000,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Formula: a(n) is the coefficient of xⁿ in
 *   G(x) = ∏ᵢ (1−x^{mᵢ+1}) / ((1−x)·∏ᵢ (1−x^{mᵢ}))
 * for D₁₀, mᵢ = [1,3,5,7,9,11,13,15,17,9].
 * The coefficient sequence is generated by the recurrence
 *   a(0) = 1
 *   a(n) = nₙ – ∑_{i=1}^n dᵢ·a(n−i) ,
 * where nₙ and dᵢ are the coefficients of the numerator N(x)
 * and the denominator D(x) = (1−x)¹⁰·∏ᵢ (1−x^{mᵢ}) respectively.
 */

#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>

/* ---------- global tables for the generating function ---------- */
static int32_t D_coeff[205];   /* denominator coefficients   */
static int32_t N_coeff[205];   /* numerator coefficients     */
static size_t   D_deg = 0;     /* highest degree of D */
static size_t   N_deg = 0;     /* highest degree of N */
static int      init_done = 0;

/* ---------- initialise the rational generating function ---------- */
static void init_polynomials(void)
{
    if (init_done) return;
    init_done = 1;

    const int m_list[10] = {1,3,5,7,9,11,13,15,17,9};
    const int k = 10;   /* number of factors in product */

    /* compute D(x) = (1–x)^k * ∏(1–x^{mᵢ})  */
    int32_t cur[205] = {0};
    cur[0] = 1;
    int cur_deg = 0;

    /* multiply by (1–x)^k */
    for (int rep = 0; rep < k; ++rep) {
        int32_t nxt[205] = {0};
        for (int i = 0; i <= cur_deg; ++i) {
            nxt[i]   += cur[i];
            nxt[i+1] -= cur[i];
        }
        ++cur_deg;
        for (int i = 0; i <= cur_deg; ++i) cur[i] = nxt[i];
    }

    /* multiply by each (1–x^{mᵢ}) */
    for (int idx = 0; idx < 10; ++idx) {
        int shift = m_list[idx];
        int32_t nxt[205] = {0};
        for (int i = 0; i <= cur_deg; ++i) {
            nxt[i]       += cur[i];
            nxt[i+shift] -= cur[i];
        }
        cur_deg += shift;
        for (int i = 0; i <= cur_deg; ++i) cur[i] = nxt[i];
    }
    D_deg = (size_t)cur_deg;
    for (size_t i = 0; i <= D_deg; ++i) D_coeff[i] = cur[i];

    /* compute N(x) = ∏(1–x^{mᵢ+1})  */
    int32_t ncur[205] = {0};
    ncur[0] = 1;
    int ncur_deg = 0;

    for (int idx = 0; idx < 10; ++idx) {
        int shift = m_list[idx] + 1;
        int32_t nnext[205] = {0};
        for (int i = 0; i <= ncur_deg; ++i) {
            nnext[i]       += ncur[i];
            nnext[i+shift] -= ncur[i];
        }
        ncur_deg += shift;
        for (int i = 0; i <= ncur_deg; ++i) ncur[i] = nnext[i];
    }
    N_deg = (size_t)ncur_deg;
    for (size_t i = 0; i <= N_deg; ++i) N_coeff[i] = ncur[i];
}

/* ---------- memoised storage for a(n) ---------- */
static seq_t *A_arr = NULL;   /* a(n) values */
static size_t A_cap = 0;      /* capacity of A_arr */
static idx_t  A_max = 0;      /* highest index computed (inclusive) */

static void ensure_cap(size_t needed)
{
    if (needed + 1 <= A_cap) return;
    size_t new_cap = (A_cap == 0) ? 1 : A_cap;
    while (new_cap <= needed) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(A_arr, new_cap * sizeof(seq_t));
    A_arr = tmp;
    A_cap = new_cap;
}

/* ---------- sequence definition ---------- */
seq_t a(idx_t n)
{
    init_polynomials();

    if (n == 0) return 1;            /* a(0) = 1 */

    if (A_max < n) {
        size_t required = (size_t)n;
        ensure_cap(required);

        if (A_max == 0) {           /* initialise a(0) if not yet present */
            A_arr[0] = 1;
            A_max = 0;
        }

        for (idx_t k = A_max + 1; k <= n; ++k) {
            seq_t pos = 0;          /* positive contributions */
            seq_t neg = 0;          /* negative contributions */

            /* handle n_k (numerator coefficient)  */
            if ((size_t)k <= N_deg) {
                int32_t nn = N_coeff[(size_t)k];
                if (nn >= 0) pos += (seq_t)nn;
                else        neg += (seq_t)(-nn);
            }

            /* add contributions from denominator coefficients  */
            size_t max_i = (size_t)k <= D_deg ? (size_t)k : D_deg;
            for (size_t i = 1; i <= max_i; ++i) {
                int32_t di = D_coeff[i];
                if (di < 0)                  /* -di > 0  */
                    pos += (seq_t)(-di) * A_arr[(size_t)k - i];
                else if (di > 0)             /* -di < 0  */
                    neg += (seq_t)di * A_arr[(size_t)k - i];
            }

            A_arr[(size_t)k] = pos - neg;   /* pos >= neg is guaranteed */
        }
        A_max = n;
    }
    return A_arr[(size_t)n];
}
