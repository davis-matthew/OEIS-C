/*
 * A226277  Numbers m of the form u^v where u and v are digits in decimal
 *          representation of m.
 * https://oeis.org/A226277
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, fini, full
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 6, u32 n <= 16, u64 n <= 16, u128 n <= 16,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A226277: numbers m of the form u^v where u and v are single-digit
 * decimal digits that both appear in the decimal representation of m.
 *
 * The sequence is finite; its terms are generated by brute‑force search
 * over all 1 ≤ u,v ≤ 9.  The values are stored in a static cache, which
 * is filled on the first call to a() and reused for subsequent calls.
 *
 * seq_t and idx_t are supplied by the build system.  The function assumes
 * seq_t supports + − * / % and comparison operators, and that it has
 * adequate size to hold the maximum value 9^9 = 387420489.
 *
 * The function returns 0 for n==0 or for n larger than the number of
 * known terms (which is 16 for the current definition). */

#include <stdbool.h>
#include <stddef.h>   /* for size_t */

seq_t a(idx_t n)
{
    /* Static cache for the sorted list of terms. */
    static seq_t cache[100];
    static idx_t  count = 0;
    static bool   ready = false;

    if (!ready) {
        /* Generate all u^v for 1..9 and keep those that contain both digits. */
        for (int u = 1; u <= 9; ++u) {
            for (int v = 1; v <= 9; ++v) {
                /* Compute m = u^v.  All powers fit in seq_t. */
                seq_t m = (seq_t)1;
                for (int k = 0; k < v; ++k)
                    m *= (seq_t)u;

                /* Check whether the base and exponent digits appear
                 * somewhere in the decimal representation of m. */
                bool has_u = false, has_v = false;
                seq_t tmp = m;
                if (tmp == 0) {          /* special case: m==0 never occurs here */
                    has_u = (u == 0);
                    has_v = (v == 0);
                } else {
                    while (tmp > 0) {
                        int d = (int)(tmp % (seq_t)10);
                        if (d == u) has_u = true;
                        if (d == v) has_v = true;
                        tmp /= (seq_t)10;
                    }
                }

                if (has_u && has_v) {
                    /* Avoid duplicates (unlikely but safe). */
                    bool dup = false;
                    for (idx_t i = 0; i < count; ++i)
                        if (cache[i] == m) { dup = true; break; }
                    if (!dup) cache[count++] = m;
                }
            }
        }

        /* Sort the cache in ascending order.  Count is at most 16. */
        for (idx_t i = 1; i < count; ++i) {
            seq_t key = cache[i];
            idx_t j = i;
            while (j > 0 && cache[j - 1] > key) {
                cache[j] = cache[j - 1];
                --j;
            }
            cache[j] = key;
        }

        ready = true;
    }

    /* Return the requested term, or 0 if the index is out of range. */
    if (n == 0 || n > count)
        return (seq_t)0;
    return cache[(size_t)(n - 1)];
}
