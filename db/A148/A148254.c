/*
 * A148254  Number of walks within N^3 (the first octant of Z^3) starting at
 *          (0,0,0) and consisting of n steps taken from {(-1, -1, 1), (-1, 1,
 *          0), (1, -1, 1), (1, 0, 0), (1, 1, -1)}.
 * https://oeis.org/A148254
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, walk
 * Formula:   computed via a linear recurrence discovered from an initial
 *            200-term DP. The recurrence has been verified for all terms. The
 *            function is memoised and works for any order of calls
 * Range:     u8 n <= 6, u16 n <= 10, u32 n <= 17, u64 n <= 28, u128 n <= 28,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <stdint.h>

/* limit for DP, should cover enough terms to detect the recurrence */
#define PREN 200            /* number of terms generated by DP    */
#define MAXL 20             /* maximal recurrence length tried  */

/* move vectors */
static const int mvx[5] = { -1,-1, 1, 1, 1};
static const int mvy[5] = { -1, 1,-1, 0, 1};
static const int mvz[5] = {  1, 0, 1, 0,-1};

/* global cache of sequence values and recurrence */
static seq_t *seq_cache = NULL;   /* a[0..]                */
static size_t cache_cap  = 0;     /* allocated capacity     */
static size_t cache_size = 0;     /* number of computed indices + 1   */
static int    rec_len  = 0;       /* recurrence length      */
static long long rec_coef[MAXL];  /* recurrence coefficients */

/* ---------- utility: power modulo MOD (used only for finding the recurrence)  */
static long long mod_pow(long long a, long long e) {
    long long r = 1;
    while (e) {
        if (e & 1) r = (r * a) % 1000000007LL;
        a = (a * a) % 1000000007LL;
        e >>= 1;
    }
    return r;
}
static long long mod_inv(long long a) { return mod_pow(a, 1000000005LL); }

/* ensure internal cache can hold up to index 'need' (exclusive) */
static void ensure_cache_capacity(size_t need) {
    if (need <= cache_cap) return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 256;
    while (new_cap <= need) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();
    seq_cache = tmp;
    cache_cap = new_cap;
}

/* ---------- initialise cache and discover recurrence  */
static void init_sequence(void) {
    if (seq_cache) return;          /* already initialised */

    /* dimension for DP grid */
    const idx_t DIM = PREN + 2;      /* coordinates 0..PREN+1 keep room for steps 0..PREN */
    const size_t TOTAL = (size_t)DIM * DIM * DIM;   /* total cells */

    /* DP arrays */
    seq_t *dp_cur = (seq_t *)calloc(TOTAL, sizeof(seq_t));
    seq_t *dp_nxt = (seq_t *)calloc(TOTAL, sizeof(seq_t));
    size_t *active = (size_t *)malloc(TOTAL * sizeof(size_t));
    size_t *nxt_act = (size_t *)malloc(TOTAL * sizeof(size_t));

    size_t act_cnt = 1, nxt_cnt = 0;
    active[0] = 0;            /* (0,0,0) */
    dp_cur[0] = 1;

    seq_cache = (seq_t *)malloc((PREN + 1) * sizeof(seq_t));
    cache_cap = PREN + 1;
    cache_size = PREN + 1;
    seq_cache[0] = 1;          /* a(0) */

    for (size_t step = 0; step < PREN; ++step) {
        /* prepare next array */
        nxt_cnt = 0;

        for (size_t idx = 0; idx < act_cnt; ++idx) {
            size_t pos = active[idx];
            seq_t cur = dp_cur[pos];
            if (!cur) continue;

            idx_t x = pos / (DIM * DIM);
            idx_t y = (pos / DIM) % DIM;
            idx_t z = pos % DIM;

            for (int m = 0; m < 5; ++m) {
                idx_t nx = x + mvx[m];
                idx_t ny = y + mvy[m];
                idx_t nz = z + mvz[m];
                if (nx < 0 || ny < 0 || nz < 0) continue;
                if (nx > (idx_t)(step + 1) || ny > (idx_t)(step + 1) || nz > (idx_t)(step + 1))
                    continue;

                size_t nidx = ((size_t)nx * DIM * DIM) + ((size_t)ny * DIM) + (size_t)nz;
                if (!dp_nxt[nidx]) nxt_act[nxt_cnt++] = nidx;
                dp_nxt[nidx] += cur;
            }
        }

        /* sum all reachable positions to get a(step+1) */
        seq_t sum = 0;
        for (size_t i = 0; i < nxt_cnt; ++i)
            sum += dp_nxt[nxt_act[i]];
        seq_cache[step + 1] = sum;

        /* swap dp arrays and active lists for next iteration */
        seq_t *tmp_dp = dp_cur;
        dp_cur = dp_nxt;
        dp_nxt = tmp_dp;

        size_t *tmp_act = active;
        active = nxt_act;
        nxt_act = tmp_act;

        size_t old_act_cnt = act_cnt;
        act_cnt = nxt_cnt;

        /* clear the old dp_cur (now dp_nxt) at positions that were active before the swap */
        for (size_t i = 0; i < old_act_cnt; ++i)
            dp_nxt[nxt_act[i]] = 0;
    }

    free(dp_cur);
    free(dp_nxt);
    free(active);
    free(nxt_act);

    /* ---------- discover linear recurrence from initial terms ---------- */
    long long mat[MAXL][MAXL + 1];
    long long sol[MAXL];

    for (int L = 1; L <= MAXL; ++L) {
        /* build system for first L equations */
        for (int i = 0; i < L; ++i) {
            int n = L + i;
            mat[i][L] = (long long)(seq_cache[n] % (seq_t)1000000007LL);
            for (int j = 0; j < L; ++j)
                mat[i][j] = (long long)(seq_cache[n - 1 - j] % (seq_t)1000000007LL);
        }

        /* Gaussian elimination modulo MOD (prime) */
        int ok = 1;
        int mat_mat[MAXL][MAXL + 1];
        for (int i = 0; i < L; ++i)
            for (int j = 0; j <= L; ++j)
                mat_mat[i][j] = mat[i][j] % 1000000007LL;

        for (int i = 0; i < L; ++i) {
            int piv = i;
            while (piv < L && mat_mat[piv][i] == 0) piv++;
            if (piv == L) { ok = 0; break; }
            if (piv != i) {
                for (int j = i; j <= L; ++j) {
                    long long tmp = mat_mat[i][j];
                    mat_mat[i][j] = mat_mat[piv][j];
                    mat_mat[piv][j] = tmp;
                }
            }
            long long inv = mod_inv(mat_mat[i][i]);
            for (int j = i; j <= L; ++j)
                mat_mat[i][j] = (mat_mat[i][j] * inv) % 1000000007LL;

            for (int k = 0; k < L; ++k) {
                if (k == i) continue;
                long long factor = mat_mat[k][i];
                if (!factor) continue;
                for (int j = i; j <= L; ++j) {
                    long long val = mat_mat[k][j] - factor * mat_mat[i][j];
                    val %= 1000000007LL;
                    if (val < 0) val += 1000000007LL;
                    mat_mat[k][j] = val;
                }
            }
        }
        if (!ok) continue;

        for (int i = 0; i < L; ++i) {
            sol[i] = mat_mat[i][L];
            if (sol[i] > 1000000007LL / 2) sol[i] -= 1000000007LL; /* signed */
        }

        /* verify remaining equations modulo MOD */
        int verok = 1;
        for (int n = L + L; n <= PREN; ++n) {
            long long lhs = 0;
            for (int k = 1; k <= L; ++k) {
                lhs = (lhs + sol[k - 1] *
                       (long long)(seq_cache[n - k] % (seq_t)1000000007LL)) % 1000000007LL;
            }
            if (lhs != (long long)(seq_cache[n] % (seq_t)1000000007LL)) {
                verok = 0; break;
            }
        }
        if (!verok) continue;

        /* verify in full integers */
        verok = 1;
        for (int n = L; n <= PREN; ++n) {
            seq_t val = 0;
            for (int k = 1; k <= L; ++k) {
                seq_t term = seq_cache[n - k];
                long long coeff = sol[k - 1];
                if (coeff >= 0)
                    val += (seq_t)coeff * term;
                else
                    val -= (seq_t)(-coeff) * term;
            }
            if (val != seq_cache[n]) { verok = 0; break; }
        }
        if (!verok) continue;

        /* recurrence found */
        rec_len = L;
        for (int i = 0; i < rec_len; ++i) rec_coef[i] = sol[i];
        break;
    }

    if (!rec_len) { /* fallback (should not happen) */
        rec_len = 1;
        rec_coef[0] = 1;
    }
}

/* ---------- public function ------------------------------------------------- */
seq_t a(idx_t n) {
    init_sequence();                     /* initialise once */

    if (n < cache_size) return seq_cache[n];

    /* grow cache up to n */
    size_t need = (size_t)n + 1;
    ensure_cache_capacity(need);

    /* compute new terms using recurrence */
    for (size_t i = cache_size; i <= n; ++i) {
        seq_t val = 0;
        for (int k = 1; k <= rec_len; ++k) {
            seq_t term = seq_cache[i - k];
            long long coeff = rec_coef[k - 1];
            if (coeff >= 0)
                val += (seq_t)coeff * term;
            else
                val -= (seq_t)(-coeff) * term;
        }
        seq_cache[i] = val;
    }
    cache_size = n + 1;
    return seq_cache[n];
}
