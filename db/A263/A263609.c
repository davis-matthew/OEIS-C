/*
 * A263609  Base-4 numbers whose square is a palindrome in base 4.
 * https://oeis.org/A263609
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 8, u32 n <= 25, u64 n <= 34, u128 n <= 34,
 *            big any n
 * Helpers:   base4_repr, is_palindrome
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute OEIS A263609: base‑4 numbers whose square is a palindrome in base‑4.
   The sequence is generated by scanning natural numbers Y in increasing order
   and selecting those for which Y² expressed in base 4 is a palindrome.
   The returned value is the base‑4 representation of Y written as a decimal
   number (i.e. its base‑4 digits concatenated).  a(1) = 0, a(2) = 1, … */

#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include "../utils/is_palindrome.h"
#include "../utils/base4_repr.h"

static seq_t *cache = NULL;          /* stored terms (decimal representation) */
static size_t cache_len = 0;         /* number of terms already found      */
static size_t cache_cap = 0;         /* allocated capacity                 */

/* The next candidate Y to be tested (in its natural decimal value). */
static seq_t next_candidate = 0;

/* Ensure the cache contains at least `n` terms (1‑based). */
static void fill_cache(idx_t n)
{
    if (cache_len >= n) return;

    if (cache_len == 0) {
        /* initialise the cache with the first term a(1) = 0 */
        cache_cap = 32;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        cache[0] = 0;
        cache_len = 1;
        next_candidate = 1;           /* start scanning from Y = 1 */
    }

    while (cache_len < (size_t)n) {
        seq_t Y = next_candidate;
        seq_t sq = Y * Y;
        if (is_palindrome(sq, 4)) {
            seq_t val = base4_repr(Y);
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = val;
        }
        /* Advance to the next Y, wrapping only in the unlikely event that
           we exhaust the range of seq_t (which never happens for the
           required term counts). */
        ++next_candidate;
    }
}

seq_t a(idx_t n)
{
    if (n < 1) return 0;          /* undefined for indices < 1 */
    fill_cache(n);
    return cache[n - 1];
}
