/* Sequence: numbers with exactly 8 ones in binary expansion.
   Generated by Gosper's hack to get the next integer with the same
   population count, starting from 255 (binary 11111111). */

static seq_t next_same_popcount(seq_t x)
{
    /* Gosper's hack; see http://graphics.stanford.edu/~seander/bithacks.html #3 */
    seq_t u = x & (~x + 1);   /* lowbit: lowest set bit of x */
    seq_t v = x + u;
    seq_t t = ((v ^ x) / u) >> 2;
    return v | t;
}

seq_t a(idx_t n)
{
    if (n == 0)
        return 0;          /* undefined for n < 1, return 0 as safe fallback */

    seq_t val = (seq_t)255;           /* a(1) */
    for (idx_t i = 1; i < n; ++i)
        val = next_same_popcount(val);

    return val;
}
