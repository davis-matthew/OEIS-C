/*
 * A023121  Signature sequence of sqrt(2/3) (arrange the numbers i+j*x (i,j >=
 *          1) in increasing order; the sequence of i's is the signature of
 *          x).
 * https://oeis.org/A023121
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1000, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This code computes sequence A023121 – the signature sequence of sqrt(2/3).
 *
 * The sequence is generated by ordering all pairs (i,j) with i,j >= 1 by the
 * value i + j*sqrt(2/3).  The heap below maintains the minimal still un
 * output pair.  For each output we push the successor in the same row
 * (i,j+1).  This yields the i‑components in the required order.
 *
 * Comparator: Let a = (ia,ja) and b = (ib,jb).
 * We need to decide whether i_a + j_a*x < i_b + j_b*x with
 * x = sqrt(2/3) .
 * Let   diff_i = ia - ib
 *       diff_j = jb - ja      (note the reversal to avoid subtraction of j values)
 * The inequality becomes      diff_i < diff_j * x .
 *
 *   • If diff_j > 0:
 *         if diff_i < 0  → true
 *         else compare   3*diff_i²  <  2*diff_j²
 *
 *   • If diff_j < 0:
 *         if diff_i >= 0 → false
 *         else compare   3*diff_i²  >  2*diff_j²
 *
 *   • If diff_j == 0 :  true iff diff_i < 0
 *
 * The test 3*diff_i² ≶ 2*diff_j² is exact and uses 128‑bit integers
 * to avoid overflow.
 */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>

/* a (node) represents a pair (i , j) with i,j >= 1 */
typedef struct { idx_t i; idx_t j; } node_t;

/* comparison: a < b ? */
static int node_less(const node_t *a, const node_t *b)
{
    /* Use signed 128‑bit arithmetic to avoid overflow. */
    __int128 diff_i = (__int128)a->i - (__int128)b->i;   /* ia – ib   */
    __int128 diff_j = (__int128)b->j - (__int128)a->j;   /* jb – ja   */

    if (diff_j > 0) {                 /* rhs positive   */
        if (diff_i < 0) return 1;     /* a < b  */
        /* compare 3*diff_i² < 2*diff_j²  */
        __int128 lhs = 3 * diff_i * diff_i;
        __int128 rhs = 2 * diff_j * diff_j;
        return lhs < rhs;
    } else if (diff_j < 0) {          /* rhs negative   */
        if (diff_i >= 0) return 0;    /* a >= b  */
        /* compare 3*diff_i² > 2*diff_j²  */
        __int128 lhs = 3 * diff_i * diff_i;
        __int128 rhs = 2 * diff_j * diff_j;
        return lhs > rhs;
    } else {                          /* diff_j == 0    */
        return diff_i < 0;
    }
}

/* swap two nodes in a heap */
static void heap_swap(node_t *a, node_t *b)
{
    node_t tmp = *a; *a = *b; *b = tmp;
}

/* sift up the node at position pos (1‑based) */
static void sift_up(node_t *heap, size_t pos)
{
    while (pos > 1) {
        size_t parent = pos >> 1;
        if (!node_less(&heap[pos], &heap[parent])) break;
        heap_swap(&heap[pos], &heap[parent]);
        pos = parent;
    }
}

/* sift down the node at position pos in a heap of size size (1‑based) */
static void sift_down(node_t *heap, size_t pos, size_t size)
{
    while (1) {
        size_t left = pos << 1, right = left + 1, smallest = pos;
        if (left <= size && node_less(&heap[left], &heap[smallest])) smallest = left;
        if (right <= size && node_less(&heap[right], &heap[smallest])) smallest = right;
        if (smallest == pos) break;
        heap_swap(&heap[pos], &heap[smallest]);
        pos = smallest;
    }
}

/* ------------------------------------------------------------------ */
/* seq_t a(idx_t n) – returns a(n) for n >= 1.  n==0 returns 0. */
/* ------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    if (n == 0) return 0;

    /* Allocate a heap of size at most n+1 (1‑based indexing). */
    size_t heap_size = (size_t)n + 1;
    node_t *heap = (node_t *)malloc(heap_size * sizeof(node_t));
    if (!heap) return 0;   /* allocation failure – return 0 as a fallback */

    /* initial heap: all (i,1) for i = 1..n */
    size_t pos = 0;
    for (idx_t i = 1; i <= n; ++i) {
        heap[++pos] = (node_t){ i, 1 };
        sift_up(heap, pos);
    }

    seq_t result = 0;
    for (idx_t step = 1; step <= n; ++step) {
        /* Extract minimum */
        node_t cur = heap[1];
        result = (seq_t)cur.i;

        /* Replace root with last element, pop, then sift down */
        heap[1] = heap[pos];
        --pos;
        sift_down(heap, 1, pos);

        /* Insert successor (i, j+1) */
        node_t next = { cur.i, cur.j + 1 };
        heap[++pos] = next;
        sift_up(heap, pos);
    }

    free(heap);
    return result;
}
