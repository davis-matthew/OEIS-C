/*
 * A218461  Floor( prime(prime(n))/ prime(n) ).
 * https://oeis.org/A218461
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   a(n) = floor( prime(prime(n)) / prime(n) )
 * Range:     u8 n <= 10000, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* Static storage for generated primes */
static uint64_t *primes = NULL;
static size_t    prime_cnt = 0;
static size_t    prime_cap = 0;

/* Extend the prime list so that it contains at least `needed` primes.
   The primes are generated by incremental trial‑division. */
static void ensure_primes_needed(size_t needed)
{
    if (prime_cnt >= needed)
        return;

    if (!primes)
    {
        prime_cap = 16;
        primes = (uint64_t *)malloc(prime_cap * sizeof(uint64_t));
    }

    uint64_t candidate = (prime_cnt == 0) ? 2 : primes[prime_cnt - 1] + 1;
    while (prime_cnt < needed)
    {
        bool is_prime = true;
        for (size_t i = 0; i < prime_cnt; ++i)
        {
            uint64_t p = primes[i];
            if (p * p > candidate)
                break;
            if (candidate % p == 0)
            {
                is_prime = false;
                break;
            }
        }
        if (is_prime)
        {
            if (prime_cnt == prime_cap)
            {
                prime_cap <<= 1;
                primes = (uint64_t *)realloc(primes, prime_cap * sizeof(uint64_t));
            }
            primes[prime_cnt++] = candidate;
        }
        ++candidate;
    }
}

/* Main function required by the build */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;   /* undefined for n < 1, but return 0 */

    /* Need at least n primes for prime(n) */
    ensure_primes_needed((size_t)n);
    uint64_t pn = primes[n - 1];        /* prime(n), 0‑based index */

    /* Need at least pn primes for prime(prime(n)) */
    ensure_primes_needed((size_t)pn);
    uint64_t ppn = primes[pn - 1];      /* prime(prime(n)) */

    return (seq_t)(ppn / pn);
}
