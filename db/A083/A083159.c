/*
 * A083159  Palindromes n such that the n*m is also a palindrome, where m is
 *          the next palindrome after n.
 * https://oeis.org/A083159
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 10, u32 n <= 21, u64 n <= 36, u128 n <= 36,
 *            big any n
 * Helpers:   get_digits, is_palindrome, seq_from_str, seq_mul
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   This function implements OEIS A083159: a(n) is the n‑th palindrome n such that
   n times the next palindrome after n is also a palindrome.  The sequence is
   generated by enumerating palindromes in increasing order and testing the
   product condition.  Values are cached for future calls.
*/

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

#include "../utils/get_digits.h"
#include "../utils/is_palindrome.h"
#include "../utils/seq_mul.h"
#include "../utils/seq_from_str.h"

/* Return the smallest decimal palindrome strictly greater than x. */
static seq_t next_palindrome(seq_t x)
{
    /* Buffer for digits (most significant first).  2048 is ample. */
    static uint8_t digits[2048];
    size_t len;

    get_digits(x, digits, &len);

    /* Candidate palindrome equal to the mirrored version. */
    static uint8_t cand[2048];
    for (size_t i = 0; i < len; ++i)
        cand[i] = digits[i];

    /* Mirror left half to right half. */
    for (size_t i = 0; i < len / 2; ++i)
        cand[len - 1 - i] = cand[i];

    /* Compare with the original number. */
    int cmp = 0;
    for (size_t i = 0; i < len; ++i) {
        if (cand[i] > digits[i]) { cmp = 1; break; }
        if (cand[i] < digits[i]) { cmp = -1; break; }
    }

    /* If candidate > original, return it. */
    if (cmp > 0) {
        char str[2048];
        for (size_t i = 0; i < len; ++i)
            str[i] = '0' + cand[i];
        str[len] = '\0';
        return seq_from_str(str);
    }

    /* Candidate <= original, need to increment middle part. */
    size_t idx = (len - 1) / 2;          /* left middle (or middle) digit */
    cand[idx] += 1;
    bool overflow = false;

    for (size_t k = idx; ; --k) {
        if (cand[k] < 10) break;
        cand[k] -= 10;
        if (k == 0) {                     /* all 9's case */
            overflow = true;
            break;
        }
        cand[k - 1] += 1;
    }

    if (overflow) {
        /* 10^len + 1 : "1" + (len-1 zeros) + "1" */
        char str[2048];
        str[0] = '1';
        for (size_t i = 1; i < len; ++i)
            str[i] = '0';
        str[len] = '1';
        str[len + 1] = '\0';
        return seq_from_str(str);
    }

    /* Mirror again after increment. */
    for (size_t i = 0; i < len / 2; ++i)
        cand[len - 1 - i] = cand[i];

    char str[2048];
    for (size_t i = 0; i < len; ++i)
        str[i] = '0' + cand[i];
    str[len] = '\0';
    return seq_from_str(str);
}

/* Public sequence function */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0;                       /* undefined for offset 1 */

    /* Static cache of discovered terms */
    static seq_t *cache = NULL;
    static size_t cache_size = 0;
    static size_t cache_cap  = 0;

    /* Last palindrome processed (for incremental generation) */
    static seq_t last_pal;
    static bool first = true;
    if (first) {
        last_pal = seq_from_str("0");
        first = false;
    }

    /* Return cached value if available */
    if (cache_size >= (size_t)n)
        return cache[n - 1];

    /* Generate terms until we have at least n entries */
    while (cache_size < (size_t)n) {
        seq_t p = next_palindrome(last_pal);   /* next palindrome > last_pal */
        seq_t q = next_palindrome(p);          /* palindrome after p          */
        seq_t prod = seq_mul(p, q);

        if (is_palindrome(prod, 10)) {
            /* Grow cache if needed */
            if (cache_size == cache_cap) {
                size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) abort();           /* unrecoverable failure */
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_size++] = p;
        }

        last_pal = p;   /* advance to next candidate */
    }

    return cache[n - 1];
}
