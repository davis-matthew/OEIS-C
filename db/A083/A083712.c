/* Sequence: prime palindromes in base 10 whose digits are in {0,1,3,5,7,9}
   (single‑digit primes 2,3,5,7 are also included).
   Generated by enumerating palindromes in numeric order and testing each
   candidate for primality. */
#include <stdbool.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/is_prime_big.h"

static const int allowed[6] = {0,1,3,5,7,9};

/* Recursive generation of all palindromic prefixes of given length. */
static bool gen_left(int pos, int left_len, bool is_even, seq_t left_value,
                     seq_t left_rev, int *count, idx_t n, seq_t *result,
                     const seq_t pow10[])
{
    if (pos == left_len) {
        if (is_even) {
            seq_t pal = left_value * pow10[left_len] + left_rev;
            if (is_prime_big(pal)) {
                ++(*count);
                if ((idx_t)(*count) == n) {
                    *result = pal;
                    return true;
                }
            }
        } else {
            for (int i = 0; i < 6; ++i) {
                seq_t mid = (seq_t)allowed[i];
                seq_t pal = left_value * pow10[left_len + 1] +
                            mid * pow10[left_len] + left_rev;
                if (is_prime_big(pal)) {
                    ++(*count);
                    if ((idx_t)(*count) == n) {
                        *result = pal;
                        return true;
                    }
                }
            }
        }
        return false;
    } else {
        for (int i = 0; i < 6; ++i) {
            int d = allowed[i];
            if (pos == 0 && d == 0) continue;          /* no leading zero */
            seq_t new_val   = left_value * (seq_t)10 + d;
            seq_t new_rev   = left_rev   + d * pow10[pos];
            if (gen_left(pos + 1, left_len, is_even, new_val, new_rev,
                         count, n, result, pow10))
                return true;
        }
        return false;
    }
}

seq_t a(idx_t n)
{
    seq_t result = 0;
    int   count  = 0;

    /* Pre‑compute 10^k up to 31 digits (64‑bit limit). */
    static bool initialized = false;
    static seq_t pow10[32];
    if (!initialized) {
        pow10[0] = (seq_t)1;
        for (int i = 1; i < 32; ++i)
            pow10[i] = pow10[i - 1] * (seq_t)10;
        initialized = true;
    }

    /* Length 1 palindromes: single‑digit primes. */
    const int first_digits[4] = {2,3,5,7};
    for (int i = 0; i < 4; ++i) {
        seq_t val = (seq_t)first_digits[i];
        if (is_prime_big(val)) {
            ++count;
            if ((idx_t)count == n)
                return val;
        }
    }

    /* Length 2 palindrome: only 11 is a prime. */
    {
        seq_t val = (seq_t)11;
        if (is_prime_big(val)) {
            ++count;
            if ((idx_t)count == n)
                return val;
        }
    }

    /* Longer lengths. */
    for (idx_t len = 3; ; ++len) {
        int left_len = (int)(len / 2);
        bool is_even = (len % 2 == 0);
        if (gen_left(0, left_len, is_even, (seq_t)0, (seq_t)0,
                     &count, n, &result, pow10))
            return result;
    }
}
