/*
 * A083806  Perfect powers using only prime digits and 1.
 * https://oeis.org/A083806
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 1, u32 n <= 25, u64 n <= 37, u128 n <= 37,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Computes the nth term of A083806: the n-th perfect power whose
   decimal digits are all prime digits (2,3,5,7) or 1.
   The sequence is generated by enumerating all perfect powers up to a
   fixed bound, filtering by allowed digits, sorting, deduplicating,
   and then indexing.  The bound (10^13) is chosen so that the first
   10 000 terms are fully included.
*/

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* helper: true if x consists only of digits 1,2,3,5,7 */
static bool allowed_digits(seq_t x) {
    if (x == 0) return false;
    while (x > 0) {
        int d = (int)(x % 10);
        if (d != 1 && d != 2 && d != 3 && d != 5 && d != 7)
            return false;
        x /= 10;
    }
    return true;
}

/* comparison function for qsort */
static int cmp_seq(const void *a, const void *b) {
    const seq_t *aa = (const seq_t *)a;
    const seq_t *bb = (const seq_t *)b;
    if (*aa < *bb) return -1;
    if (*aa > *bb) return 1;
    return 0;
}

/* dynamic array of found terms */
static seq_t *terms = NULL;
static size_t terms_size = 0;
static size_t terms_cap = 0;

/* append value to dynamic array */
static void terms_push(seq_t v) {
    if (terms_cap == 0) {
        terms_cap = 1024;
        terms = (seq_t *)malloc(terms_cap * sizeof(seq_t));
    } else if (terms_size == terms_cap) {
        terms_cap <<= 1;
        terms = (seq_t *)realloc(terms, terms_cap * sizeof(seq_t));
    }
    terms[terms_size++] = v;
}

/* generate all terms up to MAX_BOUND */
static void generate_terms(void) {
    const uint64_t MAX_BOUND = 10000000000000ULL;      /* 1e13 */
    /* include the trivial term 1 */
    terms_push((seq_t)1);

    /* exponent loop: e >= 2 */
    for (int e = 2; ; ++e) {
        /* If even the smallest base (2) raised to e exceeds bound,
           stop further exponents. */
        unsigned __int128 pow2 = 2;
        for (int k = 1; k < e; ++k) pow2 *= 2;
        if (pow2 > MAX_BOUND) break;

        unsigned long long base = 2;
        while (true) {
            unsigned __int128 val = 1;
            for (int i = 0; i < e; ++i) {
                val *= base;
                if (val > MAX_BOUND) break;
            }
            if (val > MAX_BOUND) break;   /* this base too large */
            if (allowed_digits((seq_t)val))
                terms_push((seq_t)val);
            ++base;
        }
    }

    /* sort and deduplicate */
    qsort(terms, terms_size, sizeof(seq_t), cmp_seq);
    size_t unique = 0;
    for (size_t i = 0; i < terms_size; ++i) {
        if (i == 0 || terms[i] != terms[unique - 1]) {
            terms[unique++] = terms[i];
        }
    }
    terms_size = unique;
}

/* public function */
seq_t a(idx_t n) {
    if (terms_size == 0) generate_terms();
    /* n is 1-based */
    return terms[n - 1];
}
