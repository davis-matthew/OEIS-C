/* A083795 – Numbers k such that k and k‑1 have the same number of divisors.
   The sequence is generated by scanning integers in increasing order and
   keeping those k for which τ(k) == τ(k−1).  The function a(idx_t n) supplies
   the nth term (a(1) = 3) and memoises all previously found terms so that
   any call sequence (ordered or random) runs in time proportional to the
   value of n.  No external helper functions are used – divisor counts are
   computed by simple trial division.  --------------------------------------- */

#include <stdint.h>
#include <stdlib.h>

/* -------------------------------------------------------------------------- */
/* Helper: small integer divisor count by trial division.                     */
/* -------------------------------------------------------------------------- */
static uint64_t divisor_count_u64(uint64_t m)
{
    if (m < 2) return 1;          /* τ(1) = 1 */

    uint64_t cnt  = 1;
    uint64_t expo = 0;
    uint64_t x    = m;

    /* handle factor 2 */
    if ((x & 1ULL) == 0) {
        expo = 0;
        while ((x & 1ULL) == 0) {
            x >>= 1;
            ++expo;
        }
        cnt *= (expo + 1);
    }

    /* odd factors */
    for (uint64_t f = 3; f * f <= x; f += 2) {
        if (x % f == 0) {
            expo = 0;
            while (x % f == 0) {
                x /= f;
                ++expo;
            }
            cnt *= (expo + 1);
        }
    }

    /* any remaining prime factor */
    if (x > 1)
        cnt *= 2;

    return cnt;
}

/* -------------------------------------------------------------------------- */
/* Main sequence routine                                                    */
/* -------------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    /* (The sequence is 1‑based; n==0 is undefined – return 0 to avoid UB.) */
    if (n == 0) return 0;

    /* Static state between calls. */
    static seq_t  *seq  = NULL;
    static size_t seq_len = 0;   /* how many terms are stored */
    static size_t seq_cap = 0;   /* current array capacity */
    static uint64_t next_candidate = 2; /* integer to test in the next loop */

    /* Grow stored terms until we have at least n of them. */
    while (seq_len < (size_t)n) {
        /* Advance candidate to the next integer to evaluate. */
        next_candidate++;              /* start with 3 on the first pass */

        uint64_t d_prev = divisor_count_u64(next_candidate - 1);
        uint64_t d_curr = divisor_count_u64(next_candidate);

        if (d_prev == d_curr) {        /* τ(k) == τ(k‑1) → record this k */
            if (seq_cap == 0) {
                seq_cap = 4;
                seq = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));
            } else if (seq_len == seq_cap) {
                seq_cap *= 2;
                seq = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));
            }
            seq[seq_len++] = (seq_t)next_candidate;
        }
    }

    return seq[n - 1];                 /* return the requested term */
}
