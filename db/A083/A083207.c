/*
 * A083207  Zumkeller or integer-perfect numbers: numbers n whose divisors can
 *          be partitioned into two disjoint sets with equal sum.
 * https://oeis.org/A083207
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, nice
 * Formula:   not stated
 * Range:     u8 n <= 52, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 73 terms through n = 9683 (2026-11-03)
 * Helpers:   factor_uint64, mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  A083207: Zumkeller (integer‑perfect) numbers – generated by brute‑force checking.
    Each n is tested for the property that its divisors can be partitioned into two
    disjoint sets of equal sum.  The function a(idx_t n) returns the nth such number
    (offset 1 = 6). */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

/* Prime factorisation helper – available in the harness */
#include "../utils/factor_uint64.h"
#include "../utils/mem.h"

/* ----------  generate all divisors of n  ---------- */
static void gen_divs_helper(int idx,
                            uint64_t cur,
                            const uint64_t *fac,
                            const int *exp,
                            int cnt,
                            uint64_t *arr,
                            size_t *pos)
{
    if (idx == cnt) {
        arr[(*pos)++] = cur;
        return;
    }
    uint64_t val = cur;
    for (int e = 0; e <= exp[idx]; ++e) {
        gen_divs_helper(idx + 1, val, fac, exp, cnt, arr, pos);
        val *= fac[idx];
    }
}

static void generate_divisors(uint64_t n,
                              const uint64_t *fac,
                              const int *exp,
                              int cnt,
                              uint64_t **arr,
                              size_t *size)
{
    int tau = 1;
    for (int i = 0; i < cnt; ++i) tau *= (exp[i] + 1);

    *arr = (uint64_t *)calloc(tau, sizeof(uint64_t));
    if (!*arr) abort();
    *size = 0;
    gen_divs_helper(0, 1ULL, fac, exp, cnt, *arr, size);
}

/* ----------  check whether n is a Zumkeller number  ---------- */
static bool is_zumkeller(uint64_t n)
{
    if (n <= 2) return false;                /* 1 and 2 are not Zumkeller */

    uint64_t fac[20];
    int exp[20];
    int cnt = 0;
    factor_uint64(n, fac, exp, &cnt);
    if (cnt == 0) return false;              /* prime */

    /* compute sigma(n) */
    __int128 sigma = 1;
    for (int i = 0; i < cnt; ++i) {
        uint64_t p = fac[i];
        int e = exp[i];
        __int128 p_pow = 1;
        __int128 sum_p = 1;                  /* 1 + p + ... + p^e */
        for (int j = 0; j < e; ++j) {
            p_pow *= p;
            sum_p += p_pow;
        }
        sigma *= sum_p;
    }
    if ((sigma & 1) != 0) return false;      /* odd sum cannot be split */

    uint64_t target = (uint64_t)(sigma >> 1);

    /* generate all divisors */
    uint64_t *divs = NULL;
    size_t div_cnt = 0;
    generate_divisors(n, fac, exp, cnt, &divs, &div_cnt);

    /* subset‑sum DP using bitset */
    size_t bits_len = (target >> 6) + 1;      /* number of 64‑bit words */
    uint64_t *bits = (uint64_t *)calloc(bits_len, sizeof(uint64_t));
    if (!bits) { free(divs); return false; }
    bits[0] = 1ULL;                          /* sum 0 is reachable */

    for (size_t i = 0; i < div_cnt; ++i) {
        uint64_t d = divs[i];
        if (d > target) continue;
        unsigned word_shift = (unsigned)(d >> 6);
        unsigned bit_shift  = (unsigned)(d & 63ULL);
        if (word_shift >= bits_len) continue;

        for (size_t j = bits_len; j-- > 0; ) {
            uint64_t val = bits[j];
            if (!val) continue;
            size_t k = j + word_shift;
            if (k >= bits_len) continue;
            if (bit_shift == 0) {
                bits[k] |= val;
            } else {
                bits[k] |= val << bit_shift;
                if (k + 1 < bits_len)
                    bits[k + 1] |= val >> (64 - bit_shift);
            }
        }
    }

    bool ok = ((bits[target >> 6] >> (target & 63ULL)) & 1ULL) != 0;

    free(bits);
    free(divs);
    return ok;
}

/* ----------  sequence generation  ---------- */
static seq_t *seq = NULL;          /* array of found Zumkeller numbers */
static size_t seq_len = 0;         /* number of stored terms */
static size_t seq_cap = 0;         /* allocated capacity */
static uint64_t last_checked = 5;  /* start checking from 6 */

/* public interface required by the test harness */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for offset 0 */

    while (seq_len < (size_t)n) {
        ++last_checked;
        if (is_zumkeller(last_checked)) {
            if (seq_len == seq_cap) {
                seq_cap = (seq_cap == 0) ? 16 : seq_cap << 1;
                seq = mem_resize(seq_t, seq, seq_cap);
                if (!seq) abort();
            }
            seq[seq_len++] = (seq_t)last_checked;
        }
    }
    return seq[n - 1];
}
