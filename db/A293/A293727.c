/*
 * A293727  Numbers k such that c(k,0) < c(k,1), where c(k,d) = number of d's
 *          in the first k digits of the base-2 expansion of sqrt(2).
 * https://oeis.org/A293727
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy, base
 * Formula:   not stated
 * Range:     u8 n <= 231, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   big_add_uint32, big_cmp, big_shift_left, big_subtract
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Computes OEIS sequence A293727: numbers k such that the number of 1
 * digits in the first k binary digits of sqrt(2) exceeds the number of
 * 0 digits.
 *
 * The sequence is generated by a classical non‑recurrence algorithm:
 * iterate the binary expansion of sqrt(2) one digit at a time, keep
 * a running count of 1’s, and record the current index when 1’s > 0’s.
 * No hard‑coded values are used.
 */

#include <stdint.h>
#include <stddef.h>
#include <string.h>
#include <stdbool.h>
#include "../utils/big_add_uint32.h"
#include "../utils/big_cmp.h"
#include "../utils/big_shift_left.h"
#include "../utils/big_subtract.h"

#define MAX_BITS    50000                       /* safety margin for n≈10000 */
#define LIMB_MAX   ((MAX_BITS + 31) / 32 + 2)   /* 32‑bit limbs */

/* Big‑integer representation (little‑endian limbs) */
static uint32_t root_l[LIMB_MAX], r_l[LIMB_MAX];
static uint32_t tmp1[LIMB_MAX], tmp2[LIMB_MAX], tmp3[LIMB_MAX];
static size_t root_len = 0, r_len = 0;

/* Cache of sequence values */
static seq_t seq_terms[20000] = {0};
static size_t term_len = 0;

/* Current state of digit generation */
static size_t current_k = 0;          /* number of digits processed */
static uint32_t ones_cnt = 0;         /* number of 1's seen */

/* ------------------------------------------------------------------ */
/* Small big‑integer helpers (32‑bit limbs, little‑endian)             */

/* ------------------------------------------------------------------ */

static void eval_until(idx_t n)
{
    /* Initialise once on first call */
    static bool initialized = false;
    if (!initialized) {
        root_len = 1;
        root_l[0] = 1;                 /* integer part of sqrt(2) */
        r_len = 1;
        r_l[0] = 1;                     /* N - root² = 1 */
        current_k = 1;
        ones_cnt = 1;

        seq_terms[0] = (seq_t)1;
        term_len = 1;
        initialized = true;
    }

    while (term_len < (size_t)n) {
        /* ---- Step 1 : bring down two zeros (r <<= 2) ---- */
        big_shift_left(r_l, r_len, 2, tmp1, &r_len);
        memcpy(r_l, tmp1, r_len * sizeof(uint32_t));

        /* ---- Step 2 : shift root left by 1 (root <<= 1) ---- */
        big_shift_left(root_l, root_len, 1, tmp2, &root_len);
        memcpy(root_l, tmp2, root_len * sizeof(uint32_t));

        /* ---- Step 3 : candidate = (root << 1) | 1 ---- */
        size_t cand_len;
        big_shift_left(root_l, root_len, 1, tmp3, &cand_len);
        big_add_uint32(tmp3, &cand_len, 1);

        /* ---- Step 4 : compare and decide ---- */
        uint32_t bit = 0;
        if (big_cmp(r_l, r_len, tmp3, cand_len) >= 0) {
            /* remainder >= candidate */
            big_subtract(r_l, &r_len, tmp3, cand_len);
            /* set new bit to 1 */
            big_add_uint32(root_l, &root_len, 1);
            bit = 1;
        }

        /* ---- Step 5 : update counters ---- */
        ++current_k;
        if (bit) ++ones_cnt;

        /* ---- Step 6 : record if ones > zeros ---- */
        uint32_t zeros_cnt = (uint32_t)current_k - ones_cnt;
        if (ones_cnt > zeros_cnt) {
            seq_terms[term_len] = (seq_t)current_k;
            ++term_len;
        }
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* outside defined offset */
    eval_until(n);
    return seq_terms[n - 1];
}
