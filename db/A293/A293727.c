/*
 * A293727  Numbers k such that c(k,0) < c(k,1), where c(k,d) = number of d's
 *          in the first k digits of the base-2 expansion of sqrt(2).
 * https://oeis.org/A293727
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy, base
 * Formula:   not stated
 * Range:     u8 n <= 231, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 83 terms through n = 9886 (2026-11-01)
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Computes OEIS sequence A293727: numbers k such that the number of 1
 * digits in the first k binary digits of sqrt(2) exceeds the number of
 * 0 digits.
 *
 * The sequence is generated by a classical non‑recurrence algorithm:
 * iterate the binary expansion of sqrt(2) one digit at a time, keep
 * a running count of 1’s, and record the current index when 1’s > 0’s.
 * No hard‑coded values are used.
 */

#include <stdint.h>
#include <stddef.h>
#include <string.h>
#include <stdbool.h>

static void big_add_uint32(uint32_t *a, size_t *lena, uint32_t val)
{
    uint64_t sum = (uint64_t)a[0] + val;
    a[0] = (uint32_t)sum;
    uint32_t carry = sum >> 32;
    size_t i = 1;
    while (carry && i < *lena) {
        uint64_t s = (uint64_t)a[i] + carry;
        a[i] = (uint32_t)s;
        carry = s >> 32;
        ++i;
    }
    if (carry) {
        a[*lena] = carry;
        ++(*lena);
    }
}

static int big_cmp(const uint32_t *a, size_t lena,
                   const uint32_t *b, size_t lenb)
{
    if (lena != lenb)
        return (lena > lenb) ? 1 : -1;
    for (size_t i = lena; i-- > 0; ) {
        if (a[i] != b[i])
            return (a[i] > b[i]) ? 1 : -1;
    }
    return 0;
}

static void big_shift_left(const uint32_t *src, size_t src_len, int shift,
                           uint32_t *dst, size_t *dst_len)
{
    int sw = shift >> 5;          /* whole‑limb shift */
    int sb = shift & 31;          /* intra‑limb shift */
    size_t i, j;
    uint64_t carry = 0, val;

    for (i = 0; i < src_len; ++i) {
        val = ((uint64_t)src[i] << sb) | carry;
        dst[i + sw] = (uint32_t)val;
        carry = val >> 32;
    }
    if (sb > 0) {
        dst[i + sw] = (uint32_t)carry;
        ++i;
    }
    for (j = 0; j < sw; ++j)
        dst[j] = 0;

    *dst_len = i + sw;
    while (*dst_len > 0 && dst[*dst_len - 1] == 0)
        --(*dst_len);
}

static void big_subtract(uint32_t *a, size_t *lena,
                        const uint32_t *b, size_t lenb)
{
    uint32_t borrow = 0;
    size_t i;
    for (i = 0; i < lenb; ++i) {
        uint32_t bi = b[i];
        if (a[i] < bi + borrow) {
            a[i] = a[i] - bi - borrow;
            borrow = 1;
        } else {
            a[i] = a[i] - bi - borrow;
            borrow = 0;
        }
    }
    for (; borrow && i < *lena; ++i) {
        if (a[i] == 0) {
            a[i] = 0xFFFFFFFF;
            borrow = 1;
        } else {
            a[i]--;
            borrow = 0;
        }
    }
    while (*lena > 0 && a[*lena - 1] == 0)
        --(*lena);
}

#define MAX_BITS    50000                       /* safety margin for n≈10000 */
#define LIMB_MAX   ((MAX_BITS + 31) / 32 + 2)   /* 32‑bit limbs */

/* Big‑integer representation (little‑endian limbs) */
static uint32_t root_l[LIMB_MAX], r_l[LIMB_MAX];
static uint32_t tmp1[LIMB_MAX], tmp2[LIMB_MAX], tmp3[LIMB_MAX];
static size_t root_len = 0, r_len = 0;

/* Cache of sequence values */
static seq_t seq_terms[20000] = {0};
static size_t term_len = 0;

/* Current state of digit generation */
static size_t current_k = 0;          /* number of digits processed */
static uint32_t ones_cnt = 0;         /* number of 1's seen */

