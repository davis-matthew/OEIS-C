/*
 * A347541  Numbers q.r such that q*r divides q.r, when q and r have the same
 *          number of digits, "." means concatenation, and r may not begin
 *          with 0.
 * https://oeis.org/A347541
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 7, u32 n <= 11, u64 n <= 17, u128 n <= 22,
 *            big any n
 * Helpers:   cmp_seq_t_asc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function computes OEIS sequence A347541: the concatenation q·r
   such that q * r divides q·r, where q and r have the same number of
   decimal digits, and r does not start with 0.  The values are
   generated by iterating over the digit length m, solving
   k = (10^m + t) / (t * q) with the admissible constants
   k ∈ {2,3,6,7,11} and t ∈ {1,2,4,5}.  For each admissible pair
   the integer q is obtained from
          q = (10^m + t) / (t * k)
   and used to construct the term v = q * 10^m + r where r = t * q.
   All terms obtained for a fixed m are sorted and appended to the
   output sequence, which therefore appears in increasing order.  */

#include <stdlib.h>
#include "../utils/cmp_seq_t_asc.h"

seq_t a(idx_t n)
{
    /* static cache of the terms computed so far */
    static seq_t *vals = NULL;
    static size_t vals_cap = 0;
    static size_t vals_len = 0;

    /* state for generating new terms */
    static idx_t current_m = 0;
    static seq_t pow10 = 1;      /* 10^current_m, starts at 10^0 = 1 */

    /* admissible k and t values */
    const int ks[5] = {2, 3, 6, 7, 11};
    const int ts[4] = {1, 2, 4, 5};

    /* allocate initial cache if needed */
    if (!vals) {
        vals_cap = 32;
        vals = (seq_t *)malloc(vals_cap * sizeof(seq_t));
    }

    /* generate terms until we have at least n of them */
    while (vals_len < n) {
        /* advance to the next digit length */
        current_m++;
        seq_t pow10_prev = pow10;   /* 10^(current_m-1) */
        pow10 = pow10 * (seq_t)10;  /* pow10 = 10^current_m */

        /* temporary array for solutions at this m */
        seq_t temp[20];
        size_t temp_len = 0;

        /* enumerate all (k,t) pairs */
        for (int ki = 0; ki < 5; ++ki) {
            int k = ks[ki];
            for (int ti = 0; ti < 4; ++ti) {
                int t = ts[ti];

                /* numerator N = 10^m + t */
                seq_t N = pow10 + (seq_t)t;

                /* denominator = t * k */
                seq_t denom = (seq_t)(k * t);

                /* require exact divisibility */
                if (N % denom != 0)
                    continue;

                seq_t q = N / denom;

                /* q must have m digits: 10^(m-1) <= q < 10^m */
                if (q < pow10_prev || q >= pow10)
                    continue;

                /* compute r = t * q and check its digit length */
                seq_t r = q * (seq_t)t;
                if (r < pow10_prev || r >= pow10)
                    continue;

                /* build the concatenated number v = q * 10^m + r */
                seq_t v = q * pow10 + r;

                /* store result */
                if (temp_len < sizeof(temp) / sizeof(temp[0]))
                    temp[temp_len++] = v;
            }
        }

        /* sort solutions for this m before appending */
        if (temp_len > 1)
            qsort(temp, temp_len, sizeof(seq_t), cmp_seq_t_asc);

        /* append sorted values to the global cache */
        for (size_t i = 0; i < temp_len; ++i) {
            if (vals_len >= vals_cap) {
                vals_cap *= 2;
                vals = (seq_t *)realloc(vals, vals_cap * sizeof(seq_t));
            }
            vals[vals_len++] = temp[i];
        }
    }

    return vals[n - 1];
}
