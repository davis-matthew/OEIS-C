/*
 * A347791  Inventory sequence using prime divisors (with multiplicity):
 *          Record the number of terms thus far which are divisible by every
 *          prime, then the number of terms thus far not divisible by any
 *          prime, then the number divisible (once) by a single prime, then 2
 *          (including with multiplicity), then 3 etc u...
 * https://oeis.org/A347791
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 956, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Algorithm: Inventory over categories defined by the number of prime
   divisors with multiplicity.  Category 0 counts zeros (divisible by
   every prime), category 1 counts ones (no prime factors), and for k≥2
   category k counts numbers with exactly k−1 prime factors (with
   multiplicity).  The sequence a(n) is generated by repeatedly outputting
   the current count of the next category, adding that value to the
   sequence, updating the count for the category of the added value,
   and advancing the category pointer (resetting to 0 after a zero). */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

static bool initialized = false;
static seq_t *seq_arr = NULL;
static size_t seq_cap = 0;
static idx_t seq_len = 0;
static size_t cat_index = 0;
static size_t *cnt = NULL;
static size_t cnt_size = 0;

/* Count prime factors with multiplicity. */
static unsigned int omega_uint64(uint64_t n)
{
    unsigned int c = 0;
    if (n < 2) return 0;
    while ((n & 1ULL) == 0) { ++c; n >>= 1; }
    for (uint64_t p = 3; p * p <= n; p += 2) {
        while (n % p == 0) { ++c; n /= p; }
    }
    if (n > 1) ++c;
    return c;
}

static void ensure_seq_cap(size_t needed)
{
    if (needed > seq_cap) {
        size_t new_cap = seq_cap ? seq_cap * 2 : 256;
        if (new_cap < needed) new_cap = needed;
        seq_t *tmp = (seq_t*)realloc(seq_arr, new_cap * sizeof(seq_t));
        if (!tmp) abort();
        seq_arr = tmp;
        seq_cap = new_cap;
    }
}

static void ensure_cnt_cap(size_t needed)
{
    if (needed >= cnt_size) {
        size_t new_sz = cnt_size ? cnt_size * 2 : 8;
        while (new_sz <= needed) new_sz *= 2;
        size_t *tmp = (size_t*)realloc(cnt, new_sz * sizeof(size_t));
        if (!tmp) abort();
        for (size_t i = cnt_size; i < new_sz; ++i) tmp[i] = 0;
        cnt = tmp;
        cnt_size = new_sz;
    }
}

static void init_sequence(void)
{
    seq_cap = 256;
    seq_arr = (seq_t*)malloc(seq_cap * sizeof(seq_t));
    if (!seq_arr) abort();
    seq_len = 0;
    cat_index = 0;
    cnt_size = 8;
    cnt = (size_t*)calloc(cnt_size, sizeof(size_t));
    if (!cnt) abort();
    initialized = true;
}

static void generate_up_to(idx_t n)
{
    while (seq_len <= n) {
        if (cat_index >= cnt_size) ensure_cnt_cap(cat_index);
        size_t current_count = cnt[cat_index];
        seq_t val = (seq_t)current_count;

        ensure_seq_cap(seq_len + 1);
        seq_arr[seq_len++] = val;

        size_t cat;
        if (val == 0) cat = 0;
        else if (val == 1) cat = 1;
        else {
            uint64_t x = (uint64_t)val;
            cat = omega_uint64(x) + 1;
        }

        if (cat >= cnt_size) ensure_cnt_cap(cat);
        ++cnt[cat];

        if (val == 0) cat_index = 0;
        else ++cat_index;
    }
}

seq_t a(idx_t n)
{
    if (!initialized) init_sequence();
    if (seq_len <= n) generate_up_to(n);
    return seq_arr[n];
}
