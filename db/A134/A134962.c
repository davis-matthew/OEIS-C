/*
 * A134962  Numbers n with property that for each single digit d of n, we can
 *          also see the decimal expansion of d^2 as a substring of n. Also n
 *          may not contain any 0 digits.
 * https://oeis.org/A134962
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 5, u32 n <= 9688, u64 n <= 9688,
 *            u128 n <= 9688, big any n
 * Helpers:   state_key
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Computation of OEIS A134962: 
   Numbers n with property that for each digit d of n,
   the decimal representation of d² is a substring of n.
   The sequence is generated by brute‑force search in increasing
   length order, storing the results in a static array.
*/

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/state_key.h"

/* Mapping from a single digit d (1‑9) to the index (1‑based) of the
   digit whose square d² represents. 0 means no corresponding square.
*/
static const uint8_t map_single[10] = {
    0, /* 0 */
    1, /* 1 = 1²  */
    0, /* 2 */
    0, /* 3 */
    2, /* 4 = 2²  */
    0, /* 5 */
    0, /* 6 */
    0, /* 7 */
    0, /* 8 */
    3  /* 9 = 3²  */
};

/* Two‑digit numbers whose decimal representation is a square.
   The value stored is the index (1‑based) of the digit whose square
   equals the two‑digit number.
*/
static uint8_t map_two[100];
static bool map_two_inited = false;

static void init_map_two(void)
{
    if (map_two_inited) return;
    for (int i = 0; i < 100; ++i) map_two[i] = 0;
    map_two[16] = 4; /* 4² = 16 */
    map_two[25] = 5; /* 5² = 25 */
    map_two[36] = 6; /* 6² = 36 */
    map_two[49] = 7; /* 7² = 49 */
    map_two[64] = 8; /* 8² = 64 */
    map_two[81] = 9; /* 9² = 81 */
    map_two_inited = true;
}

/* DP memoisation: memo[remain][state_key]  == -1 unknown, 0 false, 1 true
   state_key packs -> digits_present (9), patterns_found (9), last_digit (4)
*/
#define MAXLEN 12
#define MAX_STATES (1u << 22)          /* 2^22 ≈ 4.19 M states */

static signed char memo[(MAXLEN + 1) * MAX_STATES];
static bool memo_inited = false;

static int can_accept(uint16_t digits, uint16_t patterns, uint8_t last, int remain)
{
    if (remain == 0)
        return (digits != 0 && (digits & ~patterns) == 0) ? 1 : 0;

    int key = state_key(digits, patterns, last);
    signed char *cell = &memo[remain * MAX_STATES + key];
    if (*cell != -1) return *cell;

    for (int d = 1; d <= 9; ++d)
    {
        uint16_t ndigits = digits | (1u << (d - 1));
        uint16_t npatterns = patterns;
        if (map_single[d]) npatterns |= (1u << (map_single[d] - 1));
        if (last != 0)
        {
            int two = last * 10 + d;
            if (map_two[two]) npatterns |= (1u << (map_two[two] - 1));
        }
        if (can_accept(ndigits, npatterns, (uint8_t)d, remain - 1))
        {
            *cell = 1;
            return 1;
        }
    }
    *cell = 0;
    return 0;
}

/* Storage for generated sequence terms.  A maximum of 20000 terms
   is sufficient for the required range (n ≤ 10000). */
#define MAX_TERMS 20000
static seq_t seq_arr[MAX_TERMS];
static size_t seq_cnt = 0;
static int cur_len = 0;

/* Push a new term into the sequence array.  Overflow is ignored. */
static void seq_push(seq_t val)
{
    if (seq_cnt < (size_t)MAX_TERMS)
        seq_arr[seq_cnt++] = val;
}

/* Recursive DFS that generates all valid numbers of a fixed length L. */
static void gen_len(int L,
                    seq_t curr, uint16_t digits, uint16_t patterns, uint8_t last,
                    int pos)
{
    if (pos == L)
    {
        if (digits != 0 && (digits & ~patterns) == 0)
            seq_push(curr);
        return;
    }

    for (int d = 1; d <= 9; ++d)
    {
        uint16_t ndigits = digits | (1u << (d - 1));
        uint16_t npatterns = patterns;
        if (map_single[d]) npatterns |= (1u << (map_single[d] - 1));
        if (last != 0)
        {
            int two = last * 10 + d;
            if (map_two[two]) npatterns |= (1u << (map_two[two] - 1));
        }

        if (can_accept(ndigits, npatterns, (uint8_t)d, L - pos - 1))
            gen_len(L, curr * 10 + (seq_t)d, ndigits, npatterns,
                    (uint8_t)d, pos + 1);
    }
}

/* Ensure that we have generated at least 'need' terms. */
static void ensure_terms(idx_t need)
{
    if (!map_two_inited) init_map_two();
    if (!memo_inited)
    {
        for (size_t i = 0; i < sizeof(memo); ++i) memo[i] = -1;
        memo_inited = true;
    }

    while (seq_cnt < (size_t)need)
    {
        ++cur_len;
        gen_len(cur_len, 0, 0, 0, 0, 0);
    }
}

/* The public function required by the problem statement. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;  /* safeguard */
    ensure_terms(n);
    return seq_arr[n - 1];
}
