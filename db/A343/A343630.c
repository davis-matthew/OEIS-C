/*
 * A343630  Coordinate triples (x(n), y(n), z(n); n >= 0) of the 3D spiral
 *          filling space with shells of increasing radius, using circles at
 *          fixed z-values which alternatingly move up and down as do the
 *          x-values.
 * https://oeis.org/A343630
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  sign
 * Formula:   not stated
 * Range:     i8 n <= 97, i16 n <= 97, i32 n <= 97, i64 n <= 97, i128 n <= 97,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
 * Sequence A343630: Flattened list of coordinate triples (x(n),y(n),z(n))
 * from the 3‑D spiral that fills the integer lattice Z³.
 * The terms are generated by listing lattice points in order of
 * non‑decreasing Euclidean distance R² = x² + y² + z².
 * For each squared radius r:
 *   – If r is even, the points are processed by increasing z.
 *     If r is odd, by decreasing z.
 *   – For a fixed z, the points that lie on the circle of radius
 *     sqrt(r − z²) in the xy‑plane are listed by increasing longitude
 *     atan2(y,x) in the interval [0,2π).
 * The function builds shells incrementally and caches the flattened
 * coordinates, so that any index n can be answered in O(1) after the
 * necessary shells have been generated.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <math.h>

/* auxiliary integer square root (floor) for 64‑bit unsigned input */
static idx_t isqrt_u64(idx_t n)
{
    idx_t lo = 0, hi = (idx_t)0xFFFFFFFFULL;
    while (lo <= hi) {
        idx_t mid = (lo + hi) >> 1;
        unsigned __int128 sq = (unsigned __int128)mid * mid;
        if (sq == n) return mid;
        if (sq < n)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return hi;
}

/* comparison structure for sorting points by angle */
typedef struct {
    int64_t x;
    int64_t y;
    double  ang;          /* angle in [0,2π) */
} Pair;

/* compare two points by angle, then by x, then by y */
static int pair_cmp(const void *a, const void *b)
{
    const Pair *pa = (const Pair *)a;
    const Pair *pb = (const Pair *)b;
    if (pa->ang < pb->ang) return -1;
    if (pa->ang > pb->ang) return  1;
    if (pa->x < pb->x)     return -1;
    if (pa->x > pb->x)     return  1;
    if (pa->y < pb->y)     return -1;
    if (pa->y > pb->y)     return  1;
    return 0;
}

/* cache for flattened coordinates: cache[3*k] = x(k), cache[3*k+1] = y(k), cache[3*k+2] = z(k) */
static seq_t *cache = NULL;            /* pointer to array of seq_t */
static size_t cache_cap = 0;           /* capacity (in seq_t elements) */
static size_t cache_len = 0;           /* current number of elements stored */

/* next shell to generate (r value) */
static idx_t next_shell = 0;

/* ensure cache can hold at least ‘needed’ seq_t elements */
static void ensure_cache_size(size_t needed)
{
    if (needed <= cache_cap) return;
    size_t new_cap = cache_cap ? cache_cap : 64;
    while (new_cap < needed) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();                 /* allocation failure */
    cache = tmp;
    cache_cap = new_cap;
}

/* generate all points with squared radius r and append them to the cache */
static void generate_shell(idx_t r)
{
    const double TWO_PI = 2.0 * acos(-1.0);

    if (r == 0) {
        ensure_cache_size(cache_len + 3);
        cache[cache_len++] = (seq_t)0;
        cache[cache_len++] = (seq_t)0;
        cache[cache_len++] = (seq_t)0;
        return;
    }

    int64_t max_z = (int64_t)isqrt_u64(r);
    int z_inc = (r % 2 == 0) ? 1 : -1;
    int64_t z_start = (z_inc == 1) ? -max_z : max_z;
    int64_t z_end   = (z_inc == 1) ?  max_z : -max_z;

    for (int64_t z = z_start; ; z += z_inc) {
        idx_t z2 = (idx_t)(z * z);
        idx_t d  = r - z2;                  /* squared radius in xy‑plane */

        int64_t max_xy = (int64_t)isqrt_u64(d);

        /* collect points on the circle */
        size_t cap = 8;
        Pair  *pairs = (Pair *)malloc(cap * sizeof(Pair));
        size_t pn = 0;

        for (int64_t x = 0; x <= max_xy; ++x) {
            idx_t xsq = (idx_t)(x * x);
            idx_t y2  = d - xsq;
            int64_t y = (int64_t)isqrt_u64(y2);
            if ((idx_t)(y * y) != y2) continue;      /* not a perfect square */

            /* add distinct sign combinations */
            if (x == 0 && y == 0) {
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){0, 0, 0.0};
            } else if (x == 0) {                 /* only +/-y */
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){0,  y, atan2((double)y, 0.0)};
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){0, -y, atan2(-(double)y, 0.0)};
            } else if (y == 0) {                 /* only +/-x */
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){x, 0, atan2(0.0,  (double)x)};
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){-x, 0, atan2(0.0, -(double)x)};
            } else {                             /* all four quadrants */
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){x,  y, atan2((double)y,  (double)x)};
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){x, -y, atan2(-(double)y,  (double)x)};
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){-x,  y, atan2((double)y, -(double)x)};
                if (pn == cap) { cap <<= 1; pairs = (Pair *)realloc(pairs, cap * sizeof(Pair)); }
                pairs[pn++] = (Pair){-x, -y, atan2(-(double)y, -(double)x)};
            }

            /* normalise angles to [0,2π) for comparison */
            for (size_t p = pn - ( (x==0 && y==0) ? 1 :
                                   (x==0) ? 2 :
                                   (y==0) ? 2 : 4 ); p < pn; ++p) {
                if (pairs[p].ang < 0.0) pairs[p].ang += TWO_PI;
            }
        }

        /* sort by longitude (angle) */
        qsort(pairs, pn, sizeof(Pair), pair_cmp);

        /* append points (x,y,z) to cache */
        ensure_cache_size(cache_len + pn * 3);
        for (size_t i = 0; i < pn; ++i) {
            cache[cache_len++] = (seq_t)pairs[i].x;
            cache[cache_len++] = (seq_t)pairs[i].y;
            cache[cache_len++] = (seq_t)z;
        }

        free(pairs);

        if (z == z_end) break;            /* finished current shell */
    }
}

/* Public function required by the test harness */
seq_t a(idx_t n)
{
    if (cache_len == 0) {
        generate_shell(0);
        next_shell = 1;
    }
    while (cache_len <= n) {
        generate_shell(next_shell);
        ++next_shell;
    }
    return cache[n];
}
