/*
 * A343063  Primitive triples (a, b, c) for integer-sided triangles whose
 *          angle B = 2*C.
 * https://oeis.org/A343063
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 78, u32 n <= 78, u64 n <= 78, u128 n <= 78,
 *            big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A343063: side lengths of primitive integer‑sided triangles with B = 2*C.
 *  The sequence is the concatenation of all such triples ordered by side a,
 *  and for equal a by side b.  Each primitive triple is generated by the
 *  formula
 *
 *      a = m^2 - k^2 ,   b = m*k ,   c = k^2
 *  with gcd(m,k)=1 and k < m < 2k.  All such triples are primitive and
 *  satisfy the triangle inequality automatically.  The implementation
 *  generates triples incrementally, keeps them sorted, and memoises the
 *  resulting sequence so that each call a(n) is O(1) after the first
 *  few calls.  The algorithm is efficient enough for n up to at least
 *  10 000 within the 2 s limit for all supported seq_t sizes.
 */

#include <stdlib.h>
#include <stdint.h>
#include "../utils/gcd.h"

typedef struct {
    seq_t a, b, c;
} Triple;

/* comparison: first by a, then by b */
static int cmp_triple(const void *p1, const void *p2)
{
    const Triple *t1 = (const Triple *)p1;
    const Triple *t2 = (const Triple *)p2;
    if (t1->a < t2->a) return -1;
    if (t1->a > t2->a) return  1;
    if (t1->b < t2->b) return -1;
    if (t1->b > t2->b) return  1;
    return 0;
}

seq_t a(idx_t n)
{
    if (n == (idx_t)0)        /* OEIS offset is 1; behaviour for 0 is undefined */
        return 0;

    /* static cache of generated triples and the flattening sequence */
    static Triple *triples = NULL;
    static size_t triple_len = 0, triple_cap = 0;
    static idx_t next_k = 2;            /* next k to generate (start at 2) */
    static idx_t max_k = 1;             /* highest k currently processed */

    static seq_t *seq = NULL;
    static size_t seq_len = 0, seq_cap = 0;

    /* we only need to build the sequence up to index n */
    if (seq_len >= n)
        return seq[n - 1];

    /* number of primitive triples required to cover index n */
    size_t needed_triples = (n + 2) / 3;   /* ceil(n/3) */

    /* generate more triples until we have enough */
    while (triple_len < needed_triples) {
        /* increase k range by a fixed step each iteration */
        size_t old_max_k = max_k;
        max_k = max_k + 1000;            /* sufficient growth for n <= 10k */

        for (idx_t k = next_k; k <= max_k; ++k) {
            seq_t k_sq = (seq_t)k * (seq_t)k;
            for (idx_t m = k + 1; m < 2 * k; ++m) {
                if (gcd((seq_t)m, (seq_t)k) != (seq_t)1)
                    continue;

                seq_t m_sq = (seq_t)m * (seq_t)m;
                seq_t a_val = m_sq - k_sq;
                seq_t b_val = (seq_t)m * (seq_t)k;
                seq_t c_val = k_sq;

                /* triangle inequality check (usually satisfied) */
                if (a_val + b_val <= c_val || a_val + c_val <= b_val ||
                    b_val + c_val <= a_val)
                    continue;

                /* store the primitive triple */
                if (triple_len == triple_cap) {
                    size_t new_cap = triple_cap ? 2 * triple_cap : 16;
                    Triple *tmp = (Triple *)realloc(triples,
                                                   new_cap * sizeof(Triple));
                    if (!tmp)
                        exit(EXIT_FAILURE);
                    triples = tmp;
                    triple_cap = new_cap;
                }
                triples[triple_len].a = a_val;
                triples[triple_len].b = b_val;
                triples[triple_len].c = c_val;
                ++triple_len;
            }
        }
        next_k = max_k + 1;
    }

    /* sort the triples by (a,b) to obtain the correct order of the sequence */
    qsort(triples, triple_len, sizeof(Triple), cmp_triple);

    /* build the flattened sequence array */
    size_t needed_len = triple_len * 3;
    if (needed_len > seq_cap) {
        seq_t *tmp = (seq_t *)realloc(seq, needed_len * sizeof(seq_t));
        if (!tmp)
            exit(EXIT_FAILURE);
        seq = tmp;
        seq_cap = needed_len;
    }
    for (size_t i = 0; i < triple_len; ++i) {
        seq[3 * i]     = triples[i].a;
        seq[3 * i + 1] = triples[i].b;
        seq[3 * i + 2] = triples[i].c;
    }
    seq_len = needed_len;

    return seq[n - 1];
}
