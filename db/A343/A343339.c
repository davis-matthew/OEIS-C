/*
 * A343339  Numbers with no prime index dividing all the other prime indices,
 *          but with a prime index divisible by all the other prime indices.
 * https://oeis.org/A343339
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 44, u32 n <= 44, u64 n <= 44, u128 n <= 44,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A343339
   Numbers n whose smallest prime index does not divide all other prime indices,
   but whose greatest prime index is divisible by all the other prime indices.
   The sequence is generated by testing successive integers for the stated
   property and caching the results.
   The algorithm uses a linear sieve to obtain the smallest prime factor
   (spf) and a mapping from a prime to its index in the list of primes
   (prime_idx).  Each integer is factored using spf, the prime indices
   of its distinct prime divisors are collected, and the two conditions
   are checked.  The values are stored in a cache so that calls to a()
   are answered in O(1) after the required terms have been generated.  */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

/* ------------------------------------------------------------------ */
/* Global data for the sieve and for the cached values.               */
static uint32_t *spf        = NULL;   /* smallest prime factor   */
static unsigned int *prime_idx = NULL;/* prime → index in primes */
static unsigned int *primes   = NULL;/* list of primes          */
static size_t primes_cnt       = 0;
static size_t primes_cap       = 0;
static size_t sieve_limit      = 0;

static seq_t *seq_cache        = NULL;/* cached A343339 values   */
static size_t seq_cache_size   = 0;
static size_t seq_cache_cap    = 0;
static uint64_t last_checked   = 2;    /* next integer to test    */

/* ------------------------------------------------------------------ */
/* Build a linear sieve up to new_limit (inclusive).  All data structures
   are enlarged as needed.  */
static void init_sieve(size_t new_limit)
{
    if (new_limit <= sieve_limit) return;               /* already enough */

    free(spf);          free(prime_idx); free(primes);

    sieve_limit = new_limit;
    spf        = (uint32_t *)calloc(new_limit + 1, sizeof(uint32_t));
    prime_idx  = (unsigned int *)calloc(new_limit + 1, sizeof(unsigned int));

    /* rough guess for the number of primes up to new_limit                  */
    primes_cap = new_limit / 10 + 20;
    primes = (unsigned int *)malloc(primes_cap * sizeof(unsigned int));
    primes_cnt = 0;

    /* linear sieve ----------------------------------------------------- */
    for (unsigned int i = 2; i <= new_limit; ++i) {
        if (spf[i] == 0) {                      /* i is prime                */
            spf[i] = i;
            if (primes_cnt == primes_cap) {
                primes_cap <<= 1;
                primes = (unsigned int *)realloc(primes,
                                                  primes_cap * sizeof(unsigned int));
            }
            primes[primes_cnt++] = i;
        }
        for (size_t j = 0; j < primes_cnt; ++j) {
            unsigned int p = primes[j];
            if (p > spf[i]) break;
            unsigned long long prod = (unsigned long long)i * p;
            if (prod > new_limit) break;
            spf[(unsigned int)prod] = p;
        }
    }

    /* map every prime to its position (1‑based) ------------------------- */
    for (size_t i = 0; i < primes_cnt; ++i) {
        unsigned int p = primes[i];
        prime_idx[p] = (unsigned int)(i + 1);
    }
}

/* ------------------------------------------------------------------ */
/* Test whether v satisfies the conditions of the sequence.  If v
   exceeds the current sieve limit the sieve will be enlarged before
   calling this function.  */
static bool is_valid_uint64(uint64_t v)
{
    if (v <= 1) return false;

    /* collect the indices of distinct prime divisors of v             */
    unsigned int indices[128];
    int icnt = 0;

    while (v > 1) {
        unsigned int p = spf[(unsigned int)v];
        if (p == 0) return false;  /* v contains a prime > current sieve_limit */
        unsigned int idx = prime_idx[p];
        indices[icnt++] = idx;
        while (v % p == 0) v /= p;
    }

    if (icnt < 2) return false;    /* need at least two distinct indices       */

    /* find minimum and maximum indices                              */
    unsigned int min_idx = indices[0];
    unsigned int max_idx = indices[0];
    for (int i = 1; i < icnt; ++i) {
        if (indices[i] < min_idx) min_idx = indices[i];
        if (indices[i] > max_idx) max_idx = indices[i];
    }

    /* condition: greatest index divisible by all indices            */
    for (int i = 0; i < icnt; ++i) {
        if (max_idx % indices[i] != 0) return false;
    }

    /* condition: not all indices are multiples of the smallest one  */
    for (int i = 0; i < icnt; ++i) {
        if (indices[i] != min_idx && indices[i] % min_idx != 0) {
            return true;
        }
    }
    return false;
}

/* ------------------------------------------------------------------ */
/* Extend the cached sequence until it contains at least target terms.
   The cache grows geometrically.  */
static void extend_sequence(idx_t target)
{
    while (seq_cache_size < (size_t)target) {
        /* enlarge the sieve if the next integer to test is beyond it   */
        if (last_checked > sieve_limit) {
            size_t new_limit = sieve_limit ? sieve_limit * 2 : 2000000ULL;
            if (new_limit < last_checked * 2) new_limit = last_checked * 2;
            init_sieve(new_limit);
        }

        if (is_valid_uint64(last_checked)) {
            if (seq_cache_size >= seq_cache_cap) {
                seq_cache_cap = seq_cache_cap ? seq_cache_cap * 2 : 16;
                seq_cache = (seq_t *)realloc(seq_cache,
                                             seq_cache_cap * sizeof(seq_t));
            }
            seq_cache[seq_cache_size++] = (seq_t)last_checked;
        }
        ++last_checked;
    }
}

/* ------------------------------------------------------------------ */
/* Public function returning the n-th term of the sequence (1‑based).
   Calls to a() are independent of order and memoised.             */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;  /* undefined for n=0 – conventionally 0 */
    extend_sequence(n);
    return seq_cache[(size_t)n - 1];
}
