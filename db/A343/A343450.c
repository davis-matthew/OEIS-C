/*
 * A343450  Integers whose nonincreasing digits are nonzero and at most one
 *          more than their position.
 * https://oeis.org/A343450
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy, base
 * Formula:   not stated
 * Range:     u8 n <= 11, u16 n <= 49, u32 n <= 49, u64 n <= 49, u128 n <= 49,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A343450 – integers whose nonincreasing digits are nonzero and at most one more than their
   position from the right.  The numbers are generated by back‑tracking all legal digit
   sequences, yielding them in increasing numeric order.  The sequence is memoised in a static
   array so that repeated calls are O(1). */

#include <stdlib.h>   /* malloc, realloc, free */
#include <stddef.h>   /* size_t */

/* Types supplied by the build environment */
extern seq_t a(idx_t n);  /* declaration (the definition follows below) */

/* Static cache: holds the sequence terms in order.  The array grows as needed. */
static seq_t *cache      = NULL;   /* pointer to allocated terms */
static size_t cache_cap  = 0;      /* current capacity of the array */
static size_t cache_len  = 0;      /* number of terms stored */

/* Length of the longest number that has already been generated (digit count). */
static idx_t last_len   = 0;

/* Append a value to the cache, resizing the array if necessary. */
static void append_cache(seq_t val)
{
    if (cache_len == cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 4 : cache_cap * 2;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) return; /* allocation failed – keep existing data */
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

/* Recursive backtracking:
   - pos   : number of digits yet to place (including the current one)
   - prev  : maximum allowed digit (from the previous position)
   - curr  : value built so far (digits already chosen)
   The digits are chosen from left to right, ensuring non‑increasing order.
*/
static void generate_rec(idx_t pos, unsigned prev, seq_t curr)
{
    if (pos == 0) {
        append_cache(curr);
        return;
    }
    /* Position count from right: the bound for the current digit is pos + 1. */
    unsigned limit = (prev < pos + 1) ? prev : (unsigned)(pos + 1);
    for (unsigned d = 1; d <= limit; ++d) {
        seq_t next = curr * (seq_t)10 + d;
        generate_rec(pos - 1, d, next);
    }
}

/* Generate all numbers of exactly 'len' digits. */
static void generate_length(idx_t len)
{
    generate_rec(len, 9, (seq_t)0);
}

/* Public function: return the n-th term of A343450 (1‑based index). */
seq_t a(idx_t n)
{
    /* Generate terms until we have at least n of them. */
    while (cache_len < n) {
        ++last_len;
        generate_length(last_len);
    }
    return cache[n - 1];
}
