/* Sequence: A398163
   Numbers k such that neither k nor k+1 has an exponent equal to 2 in their
   prime factorization.
   The sequence is generated by a simple sieve: for each integer k starting
   at 1 check that k and k+1 are both “semi‑2‑free” */
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/is_semi2free.h"

/* ---------  memoised generator  ------------------------------------- */
static seq_t *cache      = NULL;  /* stored terms                          */
static idx_t   cache_sz  = 0;     /* number of terms currently stored      */
static size_t  cache_cap = 0;     /* allocated capacity                     */
static uint64_t next_k   = 1;     /* next k >= 1 to test                    */

/* ensure the cache has at least 'need' slots                         */
static void reserve_cache(size_t need)
{
    if (need <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 4;
    while (new_cap < need)
        new_cap *= 2;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp)
        abort();                  /* out of memory                           */
    cache      = tmp;
    cache_cap  = new_cap;
}

/* Public function required by the build                                    */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;          /* undefined for n == 0                    */
    /* generate terms until we have at least n                           */
    while (cache_sz < n) {
        uint64_t k = next_k;
        next_k = k + 1;

        if (is_semi2free(k) && is_semi2free(k + 1)) {
            reserve_cache((size_t)cache_sz + 1);
            cache[cache_sz] = (seq_t)k;
            ++cache_sz;
        }
    }
    return cache[n - 1];
}
