/*
 * A398389  Even positive numbers m such that m - 2^k is composite for all k >
 *          0 with 2^k < m.
 * https://oeis.org/A398389
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, changed
 * Formula:   not stated
 * Range:     u8 n <= 57, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 83 terms through n = 9966 (2026-11-03)
 * Helpers:   is_prime_u128, is_prime_u64, mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) = the nth even integer m > 2 such that m-2^k is composite for all
   k>0 with 2^k < m.  The sequence is generated by sequentially testing
   each even integer and checking its 2^k‑differences for primality. */
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <limits.h>
#include "../utils/is_prime_u128.h"
#include "../utils/is_prime_u64.h"
#include "../utils/mem.h"

/* -----------------  Generic primality test ------------------------ */
static bool isPrimeGeneric(seq_t n)
{
    /* all seq_t are unsigned; use the smallest type that fits */
    if ((seq_t)(ULLONG_MAX) >= n) {
        return is_prime_u64((uint64_t)n);
    }
#if defined(__SIZEOF_INT128__)
    return is_prime_u128((__uint128_t)n);
#else
    /* fallback: if seq_t > 64‑bit but no 128‑bit support,
       order the test as simple trial division up to sqrt */
    seq_t limit = 0;
    for (seq_t i = 2; i*i <= n; ++i) {
        if (n % i == 0) return false;
    }
    return true;
#endif
}

static seq_t *seq = NULL;          /* stored sequence values */
static idx_t len = 0;              /* number of terms computed so far */
static idx_t cap = 0;              /* current capacity of seq[] */
static seq_t last_even = 6;        /* last even integer that was tested */

/* Ensure seq has room for at least n more elements.  Grow capacity by
 * doubling, starting from 4. */
static void grow_seq(void)
{
    if (len == cap) {
        idx_t new_cap = (cap == 0) ? 4 : cap * 2;
        seq = mem_resize(seq_t, seq, new_cap);
        cap = new_cap;
    }
}

/* Compute a(n).  Calls are safe for any order of n. */
seq_t a(idx_t n)
{
    if (n < 1) return 0;

    /* Generate terms until we have at least n of them. */
    while (len < n) {
        /* Next even integer to test. */
        last_even += 2;
        seq_t m = last_even;
        bool ok = true;

        /* For each power of two less than m, check m - 2^k. */
        seq_t pw = (seq_t)2;
        while (pw < m) {
            seq_t diff = m - pw;
            if (isPrimeGeneric(diff)) {
                ok = false;
                break;
            }
            pw <<= 1;
        }

        if (ok) {
            grow_seq();
            seq[len++] = m;
        }
    }

    return seq[n - 1];
}
