/*
 * A398389  Even positive numbers m such that m - 2^k is composite for all k >
 *          0 with 2^k < m.
 * https://oeis.org/A398389
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, changed
 * Formula:   not stated
 * Range:     u8 n <= 57, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   isPrimeGeneric
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) = the nth even integer m > 2 such that m-2^k is composite for all
   k>0 with 2^k < m.  The sequence is generated by sequentially testing
   each even integer and checking its 2^k‑differences for primality. */
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/isPrimeGeneric.h"

static seq_t *seq = NULL;          /* stored sequence values */
static idx_t len = 0;              /* number of terms computed so far */
static idx_t cap = 0;              /* current capacity of seq[] */
static seq_t last_even = 6;        /* last even integer that was tested */

/* Ensure seq has room for at least n more elements.  Grow capacity by
 * doubling, starting from 4. */
static void grow_seq(void)
{
    if (len == cap) {
        idx_t new_cap = (cap == 0) ? 4 : cap * 2;
        seq = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
        cap = new_cap;
    }
}

/* Compute a(n).  Calls are safe for any order of n. */
seq_t a(idx_t n)
{
    if (n < 1) return 0;

    /* Generate terms until we have at least n of them. */
    while (len < n) {
        /* Next even integer to test. */
        last_even += 2;
        seq_t m = last_even;
        bool ok = true;

        /* For each power of two less than m, check m - 2^k. */
        seq_t pw = (seq_t)2;
        while (pw < m) {
            seq_t diff = m - pw;
            if (isPrimeGeneric(diff)) {
                ok = false;
                break;
            }
            pw <<= 1;
        }

        if (ok) {
            grow_seq();
            seq[len++] = m;
        }
    }

    return seq[n - 1];
}
