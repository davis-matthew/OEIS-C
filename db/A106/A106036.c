/* Trajectory of 1 under the morphism  
   1 → {1,2}
   2 → {1,2,3}
   3 → {1,2,3,3}
   The sequence a(n) is the n-th symbol in the limit word generated by
   repeatedly applying this morphism starting from the single symbol 1. */
#include <stdlib.h>

seq_t a(idx_t n) {
    static seq_t *seq = NULL;
    static idx_t seq_len = 0;

    if (seq == NULL) {
        seq = (seq_t*)malloc(sizeof(seq_t)*1);
        seq[0] = 1;
        seq_len = 1;
    }

    while (seq_len <= n) {
        idx_t i, new_len = 0;
        /* First pass: compute the length of the next word. */
        for (i = 0; i < seq_len; ++i) {
            seq_t s = seq[i];
            if (s == 1) new_len += 2;
            else if (s == 2) new_len += 3;
            else            new_len += 4;   /* s == 3 */
        }

        seq_t *new_seq = (seq_t*)malloc(sizeof(seq_t)*new_len);
        idx_t pos = 0;
        /* Second pass: fill the next word. */
        for (i = 0; i < seq_len; ++i) {
            seq_t s = seq[i];
            if (s == 1) {
                new_seq[pos++] = 1;
                new_seq[pos++] = 2;
            } else if (s == 2) {
                new_seq[pos++] = 1;
                new_seq[pos++] = 2;
                new_seq[pos++] = 3;
            } else { /* s == 3 */
                new_seq[pos++] = 1;
                new_seq[pos++] = 2;
                new_seq[pos++] = 3;
                new_seq[pos++] = 3;
            }
        }

        free(seq);
        seq = new_seq;
        seq_len = new_len;
    }

    return seq[n];
}
