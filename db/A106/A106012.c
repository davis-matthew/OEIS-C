/*
 * A106012  Primes p such that 70*p - 3 and 70*p + 3 are both primes.
 * https://oeis.org/A106012
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 12, u16 n <= 587, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   is_prime, simple_sieve
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A106012:
   primes p such that 70*p - 3 and 70*p + 3 are both primes */
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

#include "../utils/simple_sieve.h"   /* provides simple_sieve */
#include "../utils/is_prime.h"       /* provides is_prime(uint64_t) */

/* Static cache of primes generated by simple_sieve */
static uint32_t *prime_list   = NULL;   /* array of primes */
static size_t    prime_count  = 0;      /* number of primes in the array */
static uint32_t  sieve_limit  = 0;      /* highest number sieved so far */

/* Ensure that all primes up to `limit` are available in prime_list.
   If a larger limit is requested, re-sieve and replace the array. */
static void
prepare_primes(uint32_t limit)
{
    if (sieve_limit >= limit)
        return;          /* already have enough primes */

    /* free previously allocated memory if any */
    if (prime_list != NULL)
        free(prime_list);

    /* generate primes up to the new limit */
    simple_sieve(limit, &prime_list, &prime_count);
    sieve_limit = limit;
}

/* Main sequence generator */
seq_t a(idx_t n)
{
    /* n is at least 1, but we guard against 0 to be safe */
    if (n == 0)
        return 0;

    /* Estimate a safe sieving limit.
       For the n‑th term we need a prime of size ≈ n·(log n)^3.
       A generous upper bound is n * 2000; enforce a modest lower bound. */
    uint64_t est = (uint64_t)n * 2000ULL;
    uint32_t limit = (est > UINT32_MAX) ? UINT32_MAX
                                        : (uint32_t)est;
    if (limit < 1000000U) limit = 1000000U;

    prepare_primes(limit);

    size_t found = 0;
    for (;;)
    {
        /* scan the list of primes we have */
        for (size_t i = 0; i < prime_count; ++i)
        {
            uint32_t p = prime_list[i];

            /* test the twin pair 70p−3, 70p+3 */
            uint64_t a1 = 70ULL * p - 3ULL;
            uint64_t b1 = 70ULL * p + 3ULL;

            if (is_prime(a1) && is_prime(b1))
            {
                ++found;
                if (found == (size_t)n)
                    return (seq_t)p;
            }
        }

        /* not enough found yet – extend the sieve and try again */
        limit = (limit == UINT32_MAX) ? UINT32_MAX
                                      : (uint32_t)((uint64_t)limit * 2);
        prepare_primes(limit);
    }
}
