/* OEIS A379258
   a(n) = number of iterations of Euler’s totient needed to reach 1
   when starting at the n‑th 3‑smooth number (numbers of the form 2ᶦ·3ʲ).
   For n>1,
   a(n) = i + j + 1 + [i==0]  where 2^i·3^j is the n‑th 3‑smooth number.
   The sequence is generated by a two‑pointer merge of the
   2‑ and 3‑multiplication queues.
*/

#include <stdlib.h>
#include <math.h>
#include <stdbool.h>

/* static tables for the exponents of 2 and 3 in the 3‑smooth sequence */
static idx_t *e2 = NULL;   /* exponent of 2 */
static idx_t *e3 = NULL;   /* exponent of 3 */
static idx_t size   = 0;   /* number of generated terms */
static idx_t ptr2   = 0;   /* next candidate produced by multiplying by 2 */
static idx_t ptr3   = 0;   /* next candidate produced by multiplying by 3 */
static idx_t cap    = 0;   /* capacity of the tables */

/* logarithms of the bases, used for comparison without overflow */
static const double LOG2_VAL = log(2.0);
static const double LOG3_VAL = log(3.0);

/* Ensure tables have at least 'need' capacity */
static void
ensure_capacity(idx_t need)
{
    if (cap >= need)
        return;
    idx_t new_cap = cap ? cap << 1 : 1024;
    while (new_cap < need)
        new_cap <<= 1;
    idx_t *tmp_e2 = (idx_t *)realloc(e2, new_cap * sizeof(idx_t));
    idx_t *tmp_e3 = (idx_t *)realloc(e3, new_cap * sizeof(idx_t));
    e2 = tmp_e2;
    e3 = tmp_e3;
    cap = new_cap;
}

/* Initialise the tables on the first call */
static void
init_tables(void)
{
    ptr2 = ptr3 = 0;
    size  = 1;                     /* term 1 is 2^0·3^0 */
    ensure_capacity(2);
    e2[0] = 0;
    e3[0] = 0;
}

/* Generate exponent pairs up to index n (1‑based) */
static void
generate_up_to(idx_t n)
{
    while (size < n) {
        ensure_capacity(size + 1);

        /* candidate from multiplying the element at ptr2 by 2 */
        idx_t i2 = e2[ptr2] + 1;
        idx_t j2 = e3[ptr2];

        /* candidate from multiplying the element at ptr3 by 3 */
        idx_t i3 = e2[ptr3];
        idx_t j3 = e3[ptr3] + 1;

        /* compare 2^(i2)·3^(j2) with 2^(i3)·3^(j3) using logs */
        double log_val2 = i2 * LOG2_VAL + j2 * LOG3_VAL;
        double log_val3 = i3 * LOG2_VAL + j3 * LOG3_VAL;

        if (log_val2 < log_val3) {
            e2[size] = i2;
            e3[size] = j2;
            ++ptr2;
        } else if (log_val3 < log_val2) {
            e2[size] = i3;
            e3[size] = j3;
            ++ptr3;
        } else {   /* equal values; add once and advance both pointers */
            e2[size] = i2;
            e3[size] = j2;
            ++ptr2;
            ++ptr3;
        }
        ++size;
    }
}

/* Public function for the OEIS build */
seq_t a(idx_t n)
{
    if (n == 1)
        return 1;          /* a(1) = 1 by definition */

    if (!e2)
        init_tables();

    generate_up_to(n);          /* ensure we have the n‑th exponent pair */

    idx_t i = e2[n - 1];
    idx_t j = e3[n - 1];

    /* a(n) = i + j + 1 + [i==0]  (for n > 1) */
    seq_t result = (seq_t)i + (seq_t)j + 1 + ((i == 0) ? 1 : 0);
    return result;
}
