/*
 * A379307  Positive integers whose prime indices include no squarefree
 *          numbers.
 * https://oeis.org/A379307
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 55, u32 n <= 55, u64 n <= 55, u128 n <= 55,
 *            big any n
 * Helpers:   floor_sqrt, idx_is_squarefree
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes OEIS A379307: positive integers whose prime indices are all
 * square‑ful (i.e. each prime factor p of n has 1‑based index ≥2 with
 * at least one squared prime factor).
 * The sequence is generated by trial division with a growing list of
 * primes that records whether the index of each prime is square‑free.
 * The algorithm grows a cache of discovered terms and answers any
 * query a(idx_t n) independently of call order. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/floor_sqrt.h"   /* provides floor_sqrt(seq_t) */
#include "../utils/idx_is_squarefree.h"

/* ------------------------------------------------------------------ */
/* Prime list and square‑freedom table (index 0 → prime 2)              */
/* ------------------------------------------------------------------ */
static uint64_t *prime_list   = NULL;   /* primes in ascending order   */
static bool     *prime_sqful  = NULL;   /* true if index is *not* square‑free */
static size_t    prime_cnt    = 0;       /* actual number of primes      */
static size_t    prime_cap    = 0;       /* allocated capacity           */

/* Ensure the prime table contains all primes ≤ maxp.                     */
static void ensure_primes_upto(uint64_t maxp)
{
    /* initialise storage if necessary */
    if (prime_cnt == 0) {
        prime_cap = 8;
        prime_list = (uint64_t*)malloc(prime_cap * sizeof(uint64_t));
        prime_sqful = (bool*)malloc(prime_cap * sizeof(bool));
    }

    /* grow until last prime ≥ maxp */
    while (prime_cnt == 0 || prime_list[prime_cnt - 1] < maxp) {
        /* find the next prime after the current last one */
        uint64_t cand = (prime_cnt == 0 ? 2 : prime_list[prime_cnt - 1] + 1);
        if (cand == 2) {
            /* nothing else needed */
        } else {
            if (cand % 2 == 0) cand++;
            for (;;) {
                bool ispr = true;
                for (size_t i = 0; i < prime_cnt &&
                                    prime_list[i] * prime_list[i] <= cand; ++i) {
                    if (cand % prime_list[i] == 0) { ispr = false; break; }
                }
                if (ispr) break;
                cand += 2;
            }
        }

        /* grow the arrays if required */
        if (prime_cnt == prime_cap) {
            prime_cap = prime_cap ? prime_cap * 2 : 8;
            prime_list = (uint64_t*)realloc(prime_list,
                                            prime_cap * sizeof(uint64_t));
            prime_sqful = (bool*)realloc(prime_sqful,
                                         prime_cap * sizeof(bool));
        }

        /* record the new prime and whether its index is square‑free */
        size_t idx = prime_cnt + 1;              /* 1‑based */
        prime_sqful[prime_cnt] = !idx_is_squarefree(idx);
        prime_list[prime_cnt++] = cand;
    }
}

/* ------------------------------------------------------------------ */
/*   Helper: test whether an integer n satisfies the condition       */
/* ------------------------------------------------------------------ */
static bool is_valid(seq_t n)
{
    if (n == (seq_t)1) return true;    /* 1 is always valid */

    /* Ensure we have primes up to sqrt(n) */
    seq_t sqrt_n = floor_sqrt(n);
    uint64_t limit = (uint64_t)sqrt_n;
    if (limit < 2) limit = 2;
    ensure_primes_upto(limit);

    seq_t temp = n;
    for (size_t i = 0; i < prime_cnt; ++i) {
        seq_t p  = (seq_t)prime_list[i];
        seq_t p2 = p * p;
        if (p2 > temp) break;
        if (temp % p == 0) {
            if (!prime_sqful[i]) return false;   /* index is square‑free */
            while (temp % p == 0) temp /= p;
        }
    }
    if (temp > (seq_t)1) {                 /* temp is a prime > sqrt(original n) */
        uint64_t pval = (uint64_t)temp;    /* Assume it fits in 64 bits           */
        ensure_primes_upto(pval);
        size_t idx = 0;
        for (size_t i = 0; i < prime_cnt; ++i)
            if (prime_list[i] == pval) { idx = i; break; }
        if (idx == 0 && prime_list[0] != pval) return false; /* not found */
        if (!prime_sqful[idx]) return false;   /* index is square‑free */
    }
    return true;
}

/* ------------------------------------------------------------------ */
/*   Memoized sequence function a(idx_t n)                            */
/* ------------------------------------------------------------------ */
static seq_t *seq_cache = NULL;   /* array of a(1), a(2), ...            */
static size_t seq_len  = 0;       /* number of stored terms               */
static size_t seq_cap  = 0;       /* allocated capacity                   */

seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;               /* undefined, but guard */

    size_t target = (size_t)n;                /* fits into size_t for limits    */

    /* initialise cache on first use */
    if (seq_len == 0) {
        seq_cap = 16;
        seq_cache = (seq_t*)calloc(seq_cap, sizeof(seq_t));
        seq_cache[0] = (seq_t)1;              /* a(1) = 1                       */
        seq_len = 1;
    }

    /* expand cache up to the required index */
    while (seq_len < target) {
        /* next candidate is one greater than previous term */
        seq_t candidate = seq_cache[seq_len - 1] + (seq_t)1;
        while (!is_valid(candidate)) candidate += (seq_t)1;

        /* grow the cache if necessary */
        if (seq_len == seq_cap) {
            seq_cap <<= 1;
            seq_cache = (seq_t*)realloc(seq_cache,
                                        seq_cap * sizeof(seq_t));
        }
        seq_cache[seq_len++] = candidate;
    }
    return seq_cache[target - 1];
}
