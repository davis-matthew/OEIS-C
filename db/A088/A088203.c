/*  A088203 – the nth digit returned is the n‑th element of the
 *  concatenation of successive “look‑and‑say’’ rows starting with 2.
 *  The sequence is generated by repeatedly applying the look‑and‑say
 *  rule to the previous row.  No simple closed formula is known; this
 *  implementation uses memoised simulation.  It works for all
 *  (uint8_t) digits 0–9 and returns the result cast to seq_t.  */
#include <stdlib.h>
#include <stdbool.h>

/* external linkage as required */
seq_t a(idx_t n)
{
    /* static buffers for memoisation */
    static unsigned char *digits      = NULL;
    static size_t        digits_len  = 0;
    static size_t        digits_cap  = 0;

    static unsigned char *row        = NULL;
    static size_t        row_len     = 0;
    static size_t        row_cap     = 0;

    static bool initialized = false;

    /* one‑time initialisation */
    if (!initialized) {
        row_cap = 4;
        row = (unsigned char *)malloc(row_cap * sizeof(unsigned char));
        row_len = 1;
        row[0] = 2;                     /* first row “2” */

        digits_cap = 128;
        digits = (unsigned char *)malloc(digits_cap * sizeof(unsigned char));
        digits_len = 1;
        digits[0] = 2;                     /* first digit “2” */

        initialized = true;
    }

    /* target index (1‑based) */
    size_t target = (size_t)n;

    /* generate further rows until we have enough digits */
    while (digits_len < target) {
        /* next row will need at most 2×current length digits */
        size_t next_cap = row_len * 2;
        if (next_cap == 0) next_cap = 4;
        unsigned char *next = (unsigned char *)malloc(next_cap * sizeof(unsigned char));
        size_t next_len = 0;

        /* build next row from current row */
        for (size_t i = 0; i < row_len; ) {
            unsigned char digit = row[i];
            size_t j = i + 1;
            while (j < row_len && row[j] == digit) j++;
            size_t count = j - i;           /* number of identical digits */

            /* encode the count in decimal (most significant digit first) */
            int tmp = (int)count;
            int buf[32];
            int pos = 0;
            if (tmp == 0) {
                buf[pos++] = 0;
            } else {
                while (tmp > 0) {
                    buf[pos++] = tmp % 10;
                    tmp /= 10;
                }
            }
            for (int k = pos - 1; k >= 0; --k) {
                if (next_len >= next_cap) {
                    size_t new_cap = next_cap ? next_cap * 2 : 8;
                    unsigned char *tmp2 = (unsigned char *)realloc(next, new_cap * sizeof(unsigned char));
                    if (!tmp2) abort();
                    next = tmp2;
                    next_cap = new_cap;
                }
                next[next_len++] = (unsigned char)buf[k];
            }

            /* append the digit itself */
            if (next_len >= next_cap) {
                size_t new_cap = next_cap ? next_cap * 2 : 8;
                unsigned char *tmp2 = (unsigned char *)realloc(next, new_cap * sizeof(unsigned char));
                if (!tmp2) abort();
                next = tmp2;
                next_cap = new_cap;
            }
            next[next_len++] = digit;

            i = j;
        }

        /* extend the global digits array if necessary */
        if (digits_len + next_len > digits_cap) {
            size_t new_cap = digits_cap ? digits_cap * 2 : 64;
            while (new_cap < digits_len + next_len) new_cap *= 2;
            unsigned char *tmp = (unsigned char *)realloc(digits, new_cap * sizeof(unsigned char));
            if (!tmp) abort();
            digits = tmp;
            digits_cap = new_cap;
        }
        for (size_t k = 0; k < next_len; ++k) {
            digits[digits_len++] = next[k];
        }

        /* replace current row by the newly generated one */
        free(row);
        row = next;
        row_len = next_len;
        row_cap = next_cap;
    }

    /* return the requested digit, cast to seq_t */
    return (seq_t)digits[target - 1];
}
