/* A088269: palindromic primes p such that 1‖p‖1 is also prime.
   The sequence is generated by enumerating odd‑length decimal
   palindromes, testing primality of p and of 10^(d+1)+p*10+1. */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>

#include "../utils/is_prime_big.h"
#include "../utils/pow10.h"
#include "../utils/mul_small.h"
#include "../utils/digit_len.h"
#include "../utils/seq_realloc.h"
#include "../utils/odd_palindrome.h"

/* Cache of found terms. */
static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;

/* Return the n‑th term of the sequence (n ≥ 1). */
seq_t a(idx_t n)
{
    if (n == (idx_t)0)           /* offset is 1; caller may not ask for 0 */
        return (seq_t)0;

    /* Ensure the cache can hold at least n terms. */
    if (cache_cap < (size_t)n) {
        size_t new_cap = cache_cap ? cache_cap << 1 : 8;
        if (new_cap < (size_t)n)
            new_cap = (size_t)n;
        cache = seq_realloc(cache, cache_cap, new_cap);
        cache_cap = new_cap;
    }

    /* Generate missing terms up to index n. */
    static idx_t next_k = 1;   /* next integer to be turned into a palindrome */
    while (cache_len < (size_t)n) {
        seq_t p = odd_palindrome(next_k);
        next_k++;

        /* Test if base palindrome is prime. */
        if (is_prime_big(p)) {
            int d = digit_len(p);              /* number of decimal digits */
            seq_t ext = pow10((idx_t)(d + 1));  /* 10^(d+1) */
            ext = ext + mul_small(p, 10) + (seq_t)1;  /* 10^(d+1)+p*10+1 */

            if (is_prime_big(ext))
                cache[cache_len++] = p;        /* store the qualifying palindrome */
        }
    }

    return cache[(size_t)n - 1];
}
