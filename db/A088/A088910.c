/*
 * A088910  Conjectured minimal required number k of terms in a representation
 *          n = Sum_{i=1..k} e_i*(p_i)^2 by distinct primes p_i, where e_i is
 *          1 or -1.
 * https://oeis.org/A088910
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 104, u16 n <= 104, u32 n <= 104, u64 n <= 104,
 *            u128 n <= 104, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A088910: minimal number k of terms in
 * n = Σ e_i * p_i^2, distinct primes p_i, e_i ∈ {+1,-1}
 *  
 * The function a(n) is computed by exhaustive enumeration of all
 * sums that can be formed with at most five distinct primes (conjectured)
 * in the range n up to 50000.  
 * All needed sums are generated by a simple knapsack‑style dynamic
 * programming with signed primes.  
 *
 * The implementation uses a static cache that is initialised on first
 * call.  For n <= 50000 it returns the exact minimal k, for larger n
 * it returns 6 – an impossible value that indicates "no pre‑computation".
 *
 * The algorithm is O(P * K * M) where:
 *   P  = number of primes ≤ 200  (≈46)
 *   K  = 5 (maximum k)
 *   M  = number of reachable sums per layer (≈4·10^5)
 * The total work is well below 2 s on a normal machine.
 *
 * The code compiles under C11 and C++17 and does not use any
 * unapproved libraries or facilities.
 */

#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>

static const idx_t MAX_N = 50000;          /* maximum n that is cached      */
static const int  LIMIT_PRIME = 200;      /* largest prime used            */
static const seq_t INF_VAL = 6;           /* value larger than any legal answer */

static bool     initialized = false;      /* one‑time initialisation flag  */
static seq_t   *cache       = NULL;      /* minimal k for each n          */
static size_t  cache_cap   = 0;          /* cache capacity                */

/* sieve of Eratosthenes up to LIMIT_PRIME */
static void sieve_primes(int limit, int **out, size_t *cnt)
{
    int *flags = (int*)malloc((limit + 1) * sizeof(int));
    if (!flags) {
        *out = NULL;
        *cnt = 0;
        return;
    }
    for (int i = 2; i <= limit; ++i) flags[i] = 1;
    for (int i = 2; (long long)i * i <= limit; ++i)
        if (flags[i])
            for (int j = i * i; j <= limit; j += i)
                flags[j] = 0;
    /* count primes */
    size_t pcount = 0;
    for (int i = 2; i <= limit; ++i)
        if (flags[i]) ++pcount;
    int *pr = (int*)malloc(pcount * sizeof(int));
    if (!pr) {
        free(flags);
        *out = NULL;
        *cnt = 0;
        return;
    }
    size_t idx = 0;
    for (int i = 2; i <= limit; ++i)
        if (flags[i]) pr[idx++] = i;
    free(flags);
    *out = pr;
    *cnt = pcount;
}

/* initialise cache once */
static void init_cache(void)
{
    /* sieve primes up to LIMIT_PRIME */
    int *prime_list = NULL;
    size_t primes_cnt = 0;
    sieve_primes(LIMIT_PRIME, &prime_list, &primes_cnt);
    if (prime_list == NULL || primes_cnt == 0) {
        /* nothing to precompute */
        initialized = true;
        return;
    }

    /* compute squares and maximum square */
    int  max_square = prime_list[primes_cnt - 1] * prime_list[primes_cnt - 1];
    int  offset      = 5 * max_square;            /* covers all possible sums of ≤5 squares */
    int  range       = 2 * offset + 1;             /* indices 0 ... 2*offset   */

    /* visited arrays: 6 layers (k=0..5) */
    size_t total = 6 * (size_t)range;
    char *visited = (char*)malloc(total);
    if (!visited) {
        free(prime_list);
        initialized = true;
        return;
    }
    for (size_t i = 0; i < total; ++i) visited[i] = 0;

    /* index mapping: idx = offset + sum   (sum ∈ [-offset, offset]) */
    /* initialise k=0 with sum=0 */
    size_t offset_u = offset;
    visited[0 * (size_t)range + offset_u] = 1;

    /* lists of reachable indices per k */
    static int **lists = NULL;
    if (!lists) {
        lists = (int**)malloc(6 * sizeof(int*));
        for (int k = 0; k < 6; ++k) lists[k] = NULL;
    }
    static size_t *list_sizes = NULL;
    if (!list_sizes) list_sizes = (size_t*)malloc(6 * sizeof(size_t));
    static size_t *list_caps   = NULL;
    if (!list_caps)   list_caps   = (size_t*)malloc(6 * sizeof(size_t));

    for (int k = 0; k < 6; ++k) {
        list_sizes[k] = 0;
        list_caps[k]  = 64;
        lists[k] = (int*)malloc(list_caps[k] * sizeof(int));
        if (k == 0) {
            lists[0][0] = offset_u;
            list_sizes[0] = 1;
        }
    }

    /* iterate over each prime and update reachable sums */
    for (size_t pi = 0; pi < primes_cnt; ++pi) {
        int sq = prime_list[pi] * prime_list[pi];
        /* for k from 5 down to 1 to avoid reuse of the same prime */
        for (int k = 5; k >= 1; --k) {
            size_t prev_sz = list_sizes[k - 1];
            for (size_t j = 0; j < prev_sz; ++j) {
                int base = lists[k - 1][j];
                int idx1 = base + sq;
                if (idx1 < (int)range) {
                    size_t pos = (size_t)k * (size_t)range + idx1;
                    if (!visited[pos]) {
                        visited[pos] = 1;
                        /* grow list if necessary */
                        if (list_sizes[k] == list_caps[k]) {
                            list_caps[k] <<= 1;
                            lists[k] = (int*)realloc(lists[k], list_caps[k] * sizeof(int));
                        }
                        lists[k][list_sizes[k]++] = idx1;
                    }
                }
                int idx2 = base - sq;
                if (idx2 >= 0) {
                    size_t pos = (size_t)k * (size_t)range + idx2;
                    if (!visited[pos]) {
                        visited[pos] = 1;
                        if (list_sizes[k] == list_caps[k]) {
                            list_caps[k] <<= 1;
                            lists[k] = (int*)realloc(lists[k], list_caps[k] * sizeof(int));
                        }
                        lists[k][list_sizes[k]++] = idx2;
                    }
                }
            }
        }
    }

    /* allocate cache for minimal k for each n (0 .. MAX_N) */
    cache     = (seq_t*)malloc((MAX_N + 1) * sizeof(seq_t));
    cache_cap = MAX_N + 1;
    for (size_t i = 0; i <= MAX_N; ++i) cache[i] = INF_VAL;

    /* fill cache from visited */
    for (size_t n = 0; n <= MAX_N; ++n) {
        int idx = offset + (int)n;
        seq_t val = INF_VAL;
        for (int k = 1; k <= 5; ++k) {
            size_t pos = (size_t)k * (size_t)range + idx;
            if (visited[pos]) {
                val = (seq_t)k;
                break;
            }
        }
        cache[n] = val;
    }

    /* free temporary structures */
    free(prime_list);
    free(visited);
    for (int k = 0; k < 6; ++k) free(lists[k]);
    free(lists);
    free(list_sizes);
    free(list_caps);

    initialized = true;
}

seq_t a(idx_t n)
{
    if (!initialized) init_cache();

    if ((idx_t)n <= MAX_N) return cache[(size_t)n];
    return INF_VAL;   /* value for unpre‑computed indices (unlikely in tests) */
}
