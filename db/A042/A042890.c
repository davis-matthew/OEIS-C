#include <stdlib.h>
#include <stdint.h>

static seq_t *cache = NULL;          /* memoised numerators      */
static size_t cache_cap = 0;         /* allocated capacity       */
static size_t max_computed = 0;      /* number of terms computed */

static seq_t prev1 = 0;              /* p_{k-1}  (numerator)   */
static seq_t prev2 = 1;              /* p_{k-2}  (numerator)   */

static idx_t m = 0;                  /* continued fraction state */
static idx_t d = 1;
static idx_t a_term = 0;             /* current a_k in the cf */

/* constants for sqrt(977) */
static const idx_t D = 977;
static const idx_t A0 = 31;

/* compute terms up to n (inclusive) and store in cache */
static void compute_up_to(idx_t n)
{
    if (!cache) {
        /* initial allocation */
        cache_cap = 128;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        /* first term */
        cache[0] = (seq_t)A0;
        prev1 = (seq_t)A0;
        prev2 = (seq_t)1;
        max_computed = 1;
        m = 0;
        d = 1;
        a_term = A0;
    }

    /* resize if necessary */
    if ((size_t)n + 1 > cache_cap) {
        size_t new_cap = cache_cap;
        while ((size_t)n + 1 > new_cap) new_cap *= 2;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) return;          /* allocation failure – silently abort */
        cache = tmp;
        cache_cap = new_cap;
    }

    /* generate terms up to n */
    for (size_t i = max_computed; i <= (size_t)n; ++i) {
        /* next continued‑fraction term a_i */
        idx_t m_next = d * a_term - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (A0 + m_next) / d_next;

        /* update continued‑fraction state */
        m = m_next;
        d = d_next;
        a_term = a_next;

        /* compute next convergent numerator p_i */
        seq_t new_p = (seq_t)a_next * prev1 + prev2;

        cache[i] = new_p;

        /* shift for next iteration */
        prev2 = prev1;
        prev1 = new_p;
    }

    max_computed = (size_t)n + 1;
}

seq_t a(idx_t n)
{
    if (n >= max_computed) compute_up_to(n);
    return cache[n];
}
