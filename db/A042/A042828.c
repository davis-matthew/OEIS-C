/* Numerical companion to OEIS A042828:
   a(n) = numerator of the n-th convergent of sqrt(945).
   The convergents are generated by the standard continued
   fraction algorithm for quadratic irrationals. */

#include <stdint.h>
#include <stdlib.h>

/* Return the n-th term of the sequence.
   n is 0–based: a(0) = 30. */
seq_t a(idx_t n)
{
    /* static state across calls */
    static seq_t *h = NULL;          /* array of numerators */
    static size_t cap = 0;           /* allocated capacity */
    static idx_t max_n = (idx_t)-1;  /* highest index computed */

    /* Continued‑fraction parameters for sqrt(945) */
    static uint64_t m_prev = 0;      /* m_k */
    static uint64_t d_prev = 1;      /* d_k */
    static uint64_t a_prev = 30;     /* a_k, with a_0 = floor(sqrt(945)) = 30 */
    const uint64_t D = 945ULL;
    const uint64_t a0 = 30ULL;       /* floor(sqrt(945)) */

    /* Initialise on first call */
    if (max_n == (idx_t)-1) {
        cap = 1;
        h = (seq_t*)malloc(cap * sizeof(seq_t));
        if (!h) abort();            /* out of memory */
        h[0] = (seq_t)a0;          /* a(0) = 30 */
        max_n = 0;
        /* m_prev, d_prev, a_prev already set for the next step */
    }

    /* If the requested term is already known, return it immediately */
    if (n <= max_n)
        return h[n];

    /* Extend stored sequence up to n */
    for (idx_t i = max_n + 1; i <= n; ++i) {
        /* Compute the next continued‑fraction data */
        uint64_t m_i = d_prev * a_prev - m_prev;
        uint64_t d_i = (D - m_i * m_i) / d_prev;
        uint64_t a_i = (a0 + m_i) / d_i;

        /* Compute the numerator of the i‑th convergent */
        seq_t h_i;
        if (i == 1) {
            /* h(-1) is 1, h(0) is already stored */
            h_i = (seq_t)a_i * h[0] + (seq_t)1;
        } else {
            h_i = (seq_t)a_i * h[i-1] + h[i-2];
        }

        /* Ensure enough capacity in the array */
        if ((size_t)(i + 1) > cap) {
            size_t new_cap = cap ? cap * 2 : 4;
            while (new_cap <= (size_t)i) new_cap <<= 1;
            seq_t *tmp = (seq_t*)realloc(h, new_cap * sizeof(seq_t));
            if (!tmp) abort();      /* out of memory */
            h = tmp;
            cap = new_cap;
        }

        /* Store the computed numerator */
        h[i] = h_i;

        /* Update state for next iteration */
        m_prev = m_i;
        d_prev = d_i;
        a_prev = a_i;

        max_n = i;
    }

    return h[n];
}
