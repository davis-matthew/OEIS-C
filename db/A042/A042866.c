/* OEIS A042866: numerators of the continued‑fraction convergents to sqrt(965)
   The zeroth term a(0) is the integer part of sqrt(965),
   and for n ≥ 1 the recurrence
          a(n) = c(n)·a(n‑1) + a(n‑2)
   where c(n) is the (n‑th) coefficient of the continued fraction
   expansion of sqrt(965).  The coefficients are generated by the
   standard quadratic‑surd algorithm.
   The sequence is cached so that the function is O(n) for any call order. */

#include <stdlib.h>
#include <stdint.h>

/* small helper: floor(sqrt(x)) for 64‑bit unsigned integer x */
static unsigned long long int_sqrt64(unsigned long long x)
{
    unsigned long long r = 0;
    while ((r + 1) * (r + 1) <= x) ++r;
    return r;
}

/* the main function required by the build exercise */
seq_t a(idx_t n)
{
    /* static state for memoisation and continued‑fraction generation */
    static seq_t *cache = NULL;            /* cached numerators */
    static size_t cache_len = 0;           /* number of terms cached */
    static size_t cache_cap = 0;           /* current allocation size */

    /* continued‑fraction state indices */
    static unsigned long long cf_m = 0;    /* m_k value */
    static unsigned long long cf_d = 1;    /* d_k value */
    static unsigned long long cf_a = 0;    /* a_k coefficient */
    static unsigned long long a0 = 0;      /* floor(sqrt(965)) */

    /* recurrence variables */
    static seq_t p_prevprev = 0;           /* p_{k‑2}   */
    static seq_t p_prev     = 1;           /* p_{k‑1}   */

    /* initialise the static variables on first call */
    static int initialized = 0;
    if (!initialized) {
        a0 = int_sqrt64(965ULL);
        cf_a = a0;                         /* a0 = floor(sqrt(965)) */
        cf_m = 0;
        cf_d = 1;
        p_prevprev = 0;   /* corresponds to p_{-2} */
        p_prev     = 1;   /* corresponds to p_{-1} */
        cache_cap = 32;   /* initial allocation size */
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        initialized = 1;
    }

    /* extend the cache up to required index n */
    while (cache_len <= (size_t)n) {
        seq_t coeff = (seq_t)cf_a;          /* current continued‑fraction term */
        seq_t pk = coeff * p_prev + p_prevprev;  /* recurrence for p_k */

        /* store the computed value */
        if (cache_len >= cache_cap) {
            cache_cap *= 2;
            cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        }
        cache[cache_len++] = pk;

        /* update recurrence variables for next iteration */
        p_prevprev = p_prev;
        p_prev     = pk;

        /* compute next coefficient a_{k+1} using the quadratic‑surd algorithm */
        unsigned long long m_next = cf_d * cf_a - cf_m;
        unsigned long long d_next = (965ULL - m_next * m_next) / cf_d;
        unsigned long long a_next = (a0 + m_next) / d_next;

        cf_m = m_next;
        cf_d = d_next;
        cf_a = a_next;
    }

    return cache[(size_t)n];
}
