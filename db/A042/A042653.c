/* 
 * Sequence A042653: Denominators of continued fraction convergents to sqrt(856).
 * Recurrence (valid for n > 51):
 *     a(n) = 1390718379850 * a(n-26) - a(n-52)
 * Initial values a(0)..a(51) are obtained from the continued–fraction
 * expansion of sqrt(856).  The first 24 are given in the problem
 * description; the remaining are generated by the same algorithm.
 *
 * The function below computes any term on demand using an O(n) routine
 * that requires only 52 terms of storage.
 */

#include <stdint.h>   /* for UINT64_C */

seq_t a(idx_t n)
{
    /* constants for sqrt(856) */
    const idx_t D   = 856LL;
    const idx_t a0  = 29LL;                 /* floor(sqrt(856)) */

    /* first 52 terms are generated via the standard continued‑fraction
       algorithm for sqrt(D).  They are stored in a circular buffer.     */
    const idx_t BUF_LEN = 52;
    seq_t buf[BUF_LEN];

    /* continued fraction state */
    idx_t m = 0, d = 1, a_cf = a0;

    /* convergent state: p/q with p_{-1}=1, p_0=a0, q_{-1}=0, q_0=1   */
    seq_t p_prev2 = 1, p_prev1 = (seq_t)a0;
    seq_t q_prev2 = 0, q_prev1 = 1;

    /* term 0 */
    buf[0] = q_prev1;                       /* q0 = 1 */

    idx_t count = 1;                        /* number of terms computed */
    while (count < BUF_LEN) {
        /* next partial quotient */
        m = d * a_cf - m;
        d = (D - m * m) / d;
        a_cf = (a0 + m) / d;

        /* next convergent */
        seq_t p = a_cf * p_prev1 + p_prev2;
        seq_t q = a_cf * q_prev1 + q_prev2;

        buf[count++] = q;                   /* store denominator */

        /* shift for next iteration */
        p_prev2 = p_prev1;  p_prev1 = p;
        q_prev2 = q_prev1;  q_prev1 = q;
    }

    /* If the requested index is within the first 52 terms, return it. */
    if (n < BUF_LEN)
        return buf[(idx_t)n];

    /* recurrence constant */
    const seq_t C = (seq_t)1390718379850ULL;

    /* compute terms from 52 up to n using the recurrence */
    for (idx_t k = BUF_LEN; k <= n; ++k) {
        /* a(k) = C * a(k-26) - a(k-52) */
        idx_t idx1 = (k - 26) % BUF_LEN;
        idx_t idx2 = (k - 52) % BUF_LEN;
        buf[k % BUF_LEN] = C * buf[idx1] - buf[idx2];
    }

    return buf[n % BUF_LEN];
}
