/* Sequence A042407: Denominators of continued‑fraction convergents to sqrt(731)
   a(0) = 1
   The values are obtained from the recurrence
   q_{-1}=0, q_0=1,  q_n = a_n * q_{n-1} + q_{n-2}
   where a_n (n≥1) are the partial quotients of sqrt(731) generated by
   the classic continued‑fraction algorithm. */

#include <stdint.h>

seq_t a(idx_t n)
{
    /* Handle the first term separately */
    if (n == 0) {
        return (seq_t)1;
    }

    const uint64_t D = 731u;         /* the integer under the square root   */
    const uint64_t a0 = 27u;         /* floor(sqrt(D))                       */

    /* CF state variables: m_k, d_k, a_k for the generation of the
       continued‑fraction coefficients.  The recurrence uses a_{k+1}
       computed from the previous values.  We store the previous
       coefficient (a_prev) to generate the next one. */
    uint64_t m = 0u;
    uint64_t d = 1u;
    uint64_t a_prev = a0;

    /* Convergent denominators (q_{-1}=0, q_0=1).  We keep the last two
       values to apply q_n = a_n * q_{n-1} + q_{n-2}. */
    seq_t q_prevprev = (seq_t)0;   /* q_{-1} */
    seq_t q_prev     = (seq_t)1;   /* q_0   */

    for (idx_t i = 1; i <= n; ++i) {
        /* Generate the next coefficient a_i (i ≥ 1). */
        uint64_t m_next = d * a_prev - m;
        uint64_t d_next = (D - m_next * m_next) / d;
        uint64_t a_cur  = (a0 + m_next) / d_next;

        /* Update the denominator using the recurrence. */
        seq_t q_cur = ((seq_t)a_cur) * q_prev + q_prevprev;

        /* Advance the range for the next iteration. */
        q_prevprev = q_prev;
        q_prev = q_cur;

        /* Prepare for the next coefficient. */
        m = m_next;
        d = d_next;
        a_prev = a_cur;
    }

    return q_prev;
}
