/* Denominators of continued fraction convergents to sqrt(890).
   Recurrence:
      q_{-2} = 1, q_{-1} = 0
      q_k   = a_k * q_{k-1} + q_{k-2},   k ≥ 0
   where a_0 = floor(sqrt(890)) = 29 and the remaining
   a_k are generated by the standard continued‑fraction algorithm
   for sqrt(890). */
seq_t a(idx_t n)
{
    /* Parameters of the quadratic surd */
    const unsigned long long D   = 890ULL;
    const unsigned long long a0  = 29ULL;      /* floor(sqrt(D)) */

    /* Continued fraction state for sqrt(D) */
    unsigned long long m     = 0ULL;
    unsigned long long d     = 1ULL;
    unsigned long long coeff = a0;            /* current partial quotient */

    /* Denominator recurrence state */
    seq_t q_nm2 = (seq_t)1;   /* q_{k-2} (initially q_{-2} = 1) */
    seq_t q_nm1 = (seq_t)0;   /* q_{k-1} (initially q_{-1} = 0) */
    seq_t q_k   = (seq_t)0;   /* placeholder */

    idx_t k;

    for (k = 0; k <= n; ++k) {
        if (k > 0) {
            /* Next triple (m, d, a_k) for the continued fraction */
            unsigned long long m_next = d * coeff - m;
            unsigned long long d_next = (D - m_next * m_next) / d;
            unsigned long long coeff_next = (a0 + m_next) / d_next;
            m     = m_next;
            d     = d_next;
            coeff = coeff_next;
        }

        /* Compute denominator q_k = coeff * q_{k-1} + q_{k-2} */
        q_k = (seq_t)coeff * q_nm1 + q_nm2;

        if (k == n) {
            return q_k;
        }

        /* Shift state for next iteration */
        q_nm2 = q_nm1;
        q_nm1 = q_k;
    }

    /* Should never be reached */
    return (seq_t)0;
}
