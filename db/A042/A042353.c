/* Continuants (denominators) of convergents to sqrt(703).
   Uses recurrence: q_{-1}=0, q_0=1;   q_k = a_k q_{k-1} + q_{k-2}.
   The partial quotients a_k are generated by the standard continued
   fraction algorithm for sqrt(703).  */
#include <stdint.h>

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)1;   /* q_0 */

    /* constants for sqrt(703) */
    const idx_t D  = 703;       /* squarefree part of the radicand   */
    const uint32_t a0 = 26;     /* floor(sqrt(703))                   */

    unsigned long long m = 0, d = 1;  /* initial values in the
                                      * continued‑fraction algorithm   */
    uint32_t a_k = a0;                 /* a_0                                                */

    seq_t q_prev_prev = (seq_t)0;  /* q_{-1} */
    seq_t q_prev      = (seq_t)1;  /* q_0    */

    for (idx_t i = 1; i <= n; ++i)
    {
        /* compute next m, d, a_k (a_{i}) */
        unsigned long long m_next = d * a_k - m;
        unsigned long long d_next = (D - m_next * m_next) / d;
        unsigned long long a_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        a_k = (uint32_t)a_next;   /* a_k stays small (≤ 2*a0) */

        /* recurrence for the denominator */
        seq_t q = (seq_t)a_k * q_prev + q_prev_prev;

        q_prev_prev = q_prev;
        q_prev      = q;
    }

    return q_prev;   /* returns q_n  */
}
