/* Algorithm: a(n) is the denominator of the n‑th convergent of the
   continued fraction expansion of √743.  The coefficients of that
   expansion are generated by the standard algorithm for quadratic
   surds, and the denominators are produced by the recurrence
   q_k = a_k q_{k-1} + q_{k-2} (with q_{-2}=1, q_{-1}=0). */

seq_t a(idx_t n)
{
    /* Constants for √743. */
    const idx_t A0 = 27;          /* floor(√743) */
    const idx_t D  = 743;         /* the radicand   */

    /* State for the continued fraction calculation. */
    idx_t m   = 0;
    idx_t d   = 1;
    idx_t a_c = A0;               /* a_0 */

    /* Recurrence state for denominators. */
    seq_t q_prev2 = (seq_t)1;      /* q_{-2} */
    seq_t q_prev1 = (seq_t)0;      /* q_{-1} */

    for (idx_t i = 0; i <= n; ++i) {
        /* Compute q_i. */
        seq_t q_i = (seq_t)a_c * q_prev1 + q_prev2;
        if (i == n) return q_i;

        /* Advance to the next continued‑fraction coefficient a_{i+1}. */
        idx_t m_next = d * a_c - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (A0 + m_next) / d_next;

        /* Shift denominator recurrence state. */
        q_prev2 = q_prev1;
        q_prev1 = q_i;

        m   = m_next;
        d   = d_next;
        a_c = a_next;
    }

    /* Control will never reach here; return 0 as a fallback. */
    return (seq_t)0;
}
