/* OEIS A042155 – Denominators of continued‑fraction convergents to sqrt(602). */
/* Computation: recurrence for convergents of a quadratic irrational:
 *   q_-2 = 1, q_-1 = 0,
 *   q_k   = a_k * q_{k-1} + q_{k-2}  (k ≥ 0)
 * where the a_k are the continued‑fraction coefficients of sqrt(602).
 * The coefficients are generated by the standard algorithm:
 *   m_{k+1} = d_k * a_k - m_k
 *   d_{k+1} = (D - m_{k+1}^2) / d_k
 *   a_{k+1} = floor((a0 + m_{k+1}) / d_{k+1})
 * with D = 602 and a0 = floor(sqrt(602)) = 24. */

#include <stddef.h>
#include <stdlib.h>

static seq_t *den_cache = NULL;      /* cached denominators */
static size_t cache_sz = 0;          /* number of entries currently stored */
static size_t cache_cap = 0;         /* allocated capacity of den_cache */

/* State for generating continued‑fraction coefficients of sqrt(602) */
static idx_t last_k  = 0;            /* highest k that has been computed */
static idx_t m_val   = 0;            /* current m in the CF algorithm */
static idx_t d_val   = 1;            /* current d in the CF algorithm */
static idx_t coeff   = 24;           /* a_k for the current k (a0 = 24) */

/* Ensure that terms 0 .. n are in den_cache; expand cache if needed. */
static void ensure_cache(idx_t n) {
    /* Allocate initial capacity if necessary. */
    if (cache_cap == 0) {
        cache_cap = 16;
        den_cache = (seq_t *)realloc(den_cache, cache_cap * sizeof(seq_t));
        if (!den_cache) return;          /* allocation failed – caller sees garbage */
    }

    /* Initialize the first denomination if this is the first call. */
    if (cache_sz == 0) {
        den_cache[0] = (seq_t)1;        /* q_0 = 1 */
        last_k = 0;
        cache_sz = 1;
    }

    /* Incrementally compute further denominators until we reach n. */
    while (cache_sz <= (size_t)n) {
        /* Expand capacity if we are about to write past the end. */
        if (cache_sz == cache_cap) {
            size_t new_cap = cache_cap ? cache_cap * 2 : 16;
            seq_t *newp = (seq_t *)realloc(den_cache, new_cap * sizeof(seq_t));
            if (!newp) return;          /* allocation failed – caller sees garbage */
            den_cache = newp;
            cache_cap = new_cap;
        }

        /* Compute the next continued‑fraction coefficient a_{last_k+1}. */
        idx_t m_next = d_val * coeff - m_val;
        idx_t d_next = (602 - m_next * m_next) / d_val;
        idx_t a_next = (24 + m_next) / d_next;

        m_val = m_next;
        d_val = d_next;
        coeff = a_next;

        /* Compute q_{last_k+1} = coeff * q_{last_k} + q_{last_k-1}. */
        seq_t q_prev  = den_cache[last_k];
        seq_t q_prev2 = (last_k == 0) ? ((seq_t)0) : den_cache[last_k - 1];
        den_cache[last_k + 1] = coeff * q_prev + q_prev2;

        /* Move to the next index. */
        last_k++;
        cache_sz++;
    }
}

seq_t a(idx_t n) {
    ensure_cache(n);
    return den_cache[n];
}
