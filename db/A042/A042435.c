/* Sequence A042435: denominators of continued‑fraction convergents to √745.
   Recurrence:  q_{-2} = 1,  q_{-1} = 0,
                q_n = a_n * q_{n-1} + q_{n-2},
   where (a_n) are the partial quotients of the continued fraction of √745. */

/* The continued fraction of √745 is periodic.  The first partial quotient a0 is
   floor(√745); subsequent partial quotients are generated by the standard
   formulas using m, d and a.  The function recomputes the required
   convergent denominators from scratch, which is O(n) and works for any n. */

#include <stdint.h>   /* for stdint types if needed */

seq_t a(idx_t n)
{
    /* partial quotients for √745 */
    const seq_t a0 = 27;   /* floor(√745) */
    const seq_t D  = 745;  /* radicand */

    /* current state of the continued fraction */
    seq_t m = 0;   /* m_0 */
    seq_t d = 1;   /* d_0 */
    seq_t a_cur = a0; /* a_i, starting with a_0 */

    /* convergent denominator recurrence */
    seq_t q_prev2 = 1; /* q_{-2} */
    seq_t q_prev1 = 0; /* q_{-1} */
    seq_t q_new   = 0;

    for (idx_t i = 0; i <= n; ++i) {
        /* compute q_i = a_i * q_{i-1} + q_{i-2} */
        q_new = a_cur * q_prev1 + q_prev2;

        /* shift for next iteration */
        q_prev2 = q_prev1;
        q_prev1 = q_new;

        /* compute next partial quotient except after the last required term */
        if (i < n) {
            seq_t m_next = d * a_cur - m;
            seq_t d_next = (D - m_next * m_next) / d;
            seq_t a_next = (a0 + m_next) / d_next;
            m = m_next;
            d = d_next;
            a_cur = a_next;
        }
    }

    return q_new; /* q_n is the denominator of the n‑th convergent */
}
