/*  Numerators of continued fraction convergents to sqrt(708)
 *  The nth convergent numerator p[n] satisfies
 *  p[-2] = 0,  p[-1] = 1,
 *  p[n]  = a[n] * p[n-1] + p[n-2]
 *  where a[n] are the partial quotients of sqrt(708).
 *  The partial quotients are generated by the standard
 *  Pell–continued‑fraction algorithm.
 */

#include <stdint.h>

seq_t a(idx_t n)
{
    const uint64_t D   = 708ULL;   /* D = 708 */
    const uint64_t A0  = 26ULL;    /* floor(sqrt(708)) */

    /* Convergents:  p[-2]=0,  p[-1]=1 */
    seq_t p_minus2 = 0;
    seq_t p_minus1 = 1;

    /* States of the continued‑fraction algorithm */
    uint64_t m   = 0;
    uint64_t d   = 1;
    uint64_t a    = A0;

    for (idx_t i = 0; i <= n; ++i)
    {
        if (i != 0)          /* compute the next partial quotient */
        {
            uint64_t m_next = d * a - m;
            uint64_t d_next = (D - m_next * m_next) / d;
            a = (A0 + m_next) / d_next;
            m = m_next;
            d = d_next;
        }

        /* p[n] = a * p[n-1] + p[n-2] */
        seq_t p = (seq_t)a * p_minus1 + p_minus2;

        p_minus2 = p_minus1;
        p_minus1 = p;
    }

    return p_minus1;   /* numerator of the nth convergent */
}
