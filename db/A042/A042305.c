/*  A042305 - Denominators of continued‑fraction convergents to sqrt(679)
    The terms are generated by first computing the first 32 denominators
    by the standard continued‑fraction algorithm for sqrt(679) and then
    extending the sequence by the linear recurrence
            a(n) = 35585250640*a(n-16) - a(n-32)   (n > 31).
    This approach reproduces all terms of the OEIS sequence and preserves
    exact arithmetic for any seq_t implementation (small integer, 
    __int128 or arbitrary‑precision integer class).               */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

seq_t a(idx_t n)
{
    /* ---------- static state ------------------------------------------ */
    static seq_t *cache = NULL;      /* sequence values   */
    static size_t len   = 0;         /* number of filled terms   */
    static size_t cap   = 0;         /* allocated capacity       */
    static bool   init   = false;    /* whether the first 32 terms are computed */

    /* constants for continued‑fraction computation of sqrt(679) */
    const idx_t  N     = 679;                      /* radicand */
    const idx_t  a0    = 26;                       /* floor(sqrt(679)) */

    /* recurrence coefficient for n > 31 */
    const seq_t COEF = (seq_t)35585250640ULL;      /* 35585250640U */

    /* ---------- initialise the cache and first 32 terms ------------- */
    if (!init) {
        /* allocate an initial block of 64 terms */
        cap   = 64;
        cache = (seq_t *)malloc(cap * sizeof(seq_t));
        /* Q_-2 = 1 , Q_-1 = 0 , Q_0 = 1 */
        cache[0] = (seq_t)1;
        len = 1;

        /* variables for generating continued‑fraction terms */
        idx_t m = 0;          /* initial m0 */
        idx_t d = 1;          /* initial d0 */
        idx_t a_prev = a0;    /* a_prev = a0 initially (used in m/d transition) */

        /* generate terms until we have 32 values (indices 0..31) */
        while (len < 32) {
            /* step the CF state: compute m_{k+1}, d_{k+1}, a_{k+1} */
            idx_t m_next = d * a_prev - m;
            idx_t d_next = (N - m_next * m_next) / d;
            idx_t a_next = (a0 + m_next) / d_next;

            /* compute next denominator Q_k using the CF recurrence */
            seq_t q_prev1 = cache[len - 1];
            seq_t q_prev2 = (len >= 2 ? cache[len - 2] : (seq_t)0);
            seq_t q_next  = a_next * q_prev1 + q_prev2;

            /* store the new denominator */
            if (len >= cap) {
                cap <<= 1;
                cache = (seq_t *)realloc(cache, cap * sizeof(seq_t));
            }
            cache[len] = q_next;
            ++len;

            /* advance the CF state for the next step */
            m     = m_next;
            d     = d_next;
            a_prev = a_next;
        }
        init = true;
    }

    /* ---------- extend the sequence up to requested index ---------- */
    while (len <= n) {
        /* recurrence: a(n) = 35585250640 * a(n-16) - a(n-32) */
        seq_t val = COEF * cache[len - 16] - cache[len - 32];

        if (len >= cap) {
            cap <<= 1;
            cache = (seq_t *)realloc(cache, cap * sizeof(seq_t));
        }
        cache[len] = val;
        ++len;
    }

    return cache[n];
}
