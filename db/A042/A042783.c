/* Denominators of continued‑fraction convergents to sqrt(922)
   Let a_0 = floor(sqrt(922)) = 30 and let the continued–fraction terms
   (a_n) for sqrt(922) be generated by the standard algorithm.
   Define q_{-2}=1, q_{-1}=0 and
   q_n = a_n * q_{n-1} + q_{n-2}   (n ≥ 0).
   Then a(n) = q_n.  The values a(0),a(1),… are 1,2,3,8,11,107,… as
   listed in the OEIS entry. */

#include <stdlib.h>
#include <stdint.h>

/* D = 922 is not a perfect square */
static const idx_t D = 922;
static const idx_t a0 = 30;            /* floor(sqrt(922)) */

/* Cached denominators */
static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;

/* Recurrence state: q_{-2} = 1, q_{-1} = 0 */
static seq_t q_prev2 = 1;              /* q_{-2} */
static seq_t q_prev1 = 0;              /* q_{-1} */

/* Continued fraction state */
static idx_t m = 0;                    /* m_0 */
static idx_t d = 1;                    /* d_0 */
static idx_t a_coeff = a0;             /* a_0 */

/*
 * Compute the nth denominator of the convergents to sqrt(922).
 * Required external linkage: seq_t a(idx_t n)
 */
seq_t a(idx_t n)
{
    /* Grow the cache up to index n */
    while (cache_len <= n) {
        /* New denominator */
        seq_t q_cur = (seq_t)a_coeff * q_prev1 + q_prev2;

        /* Store it */
        if (cache_len == cache_cap) {
            size_t new_cap = cache_cap == 0 ? 16 : cache_cap * 2;
            seq_t *newp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            cache = newp;
            cache_cap = new_cap;
        }
        cache[cache_len] = q_cur;
        cache_len++;

        /* Shift recurrence state */
        q_prev2 = q_prev1;
        q_prev1 = q_cur;

        /* Compute next continued‑fraction term */
        idx_t m_next = d * a_coeff - m;
        idx_t d_next = (D - (m_next * m_next)) / d;
        idx_t a_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        a_coeff = a_next;
    }

    return cache[n];
}
