/*
 * A042245  Denominators of continued fraction convergents to sqrt(648).
 * https://oeis.org/A042245
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, frac, easy
 * Formula:   a(n) = denominator of the n-th convergent to sqrt(648)
 * Range:     u8 n <= 3, u16 n <= 6, u32 n <= 13, u64 n <= 25, u128 n <= 50,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function implements the recurrence for the denominators of the continued
   fraction convergents to sqrt(648).  The continued fraction for sqrt(648) has
   the period generated by the standard algorithm for quadratic irrationals.
   The function lazily computes each term and caches the results to allow
   random-order queries.  It uses standard integer arithmetic for the period
   calculation and carries the accumulated denominators in type seq_t. */

#include <stdlib.h>   /* for malloc */

seq_t a(idx_t n)
{
    /* static cache for computed denominators */
    static seq_t *cache = NULL;
    static size_t cache_cap = 0;
    static size_t cache_len = 0;

    /* parameters for continued fraction of sqrt(648) */
    const unsigned long long D   = 648ULL;
    const unsigned long long a0  = 25ULL;          /* floor(sqrt(648)) */
    static unsigned long long m   = 0ULL;          /* current m in CF algorithm */
    static unsigned long long d   = 1ULL;          /* current d in CF algorithm */
    static unsigned long long a_next = a0;         /* next a in CF algorithm */

    /* previous two convergents: p_{-2}, p_{-1} and q_{-2}, q_{-1} */
    static seq_t p_prevprev = 0, p_prev = 1;
    static seq_t q_prevprev = 1, q_prev = 0;

    /* initialise cache and first term on first call */
    if (cache == NULL) {
        /* initial allocation */
        cache_cap = 16;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));

        /* compute first convergent (index 0) */
        seq_t p0 = (seq_t)a0 * p_prev + p_prevprev; // 25 * 1 + 0
        seq_t q0 = (seq_t)a0 * q_prev + q_prevprev; // 25 * 0 + 1

        cache[0] = q0;
        cache_len = 1;

        /* shift p/q for next iteration */
        p_prevprev = p_prev;
        q_prevprev = q_prev;
        p_prev = p0;
        q_prev = q0;

        /* advance CF state to produce a1 */
        unsigned long long m1 = d * a_next - m;
        unsigned long long d1 = (D - m1 * m1) / d;
        unsigned long long a1 = (a0 + m1) / d1;
        m = m1;
        d = d1;
        a_next = a1;
    }

    /* generate terms up to requested index n */
    while (cache_len <= n) {
        /* compute next convergent using current a_next */
        seq_t p_new = (seq_t)a_next * p_prev + p_prevprev;
        seq_t q_new = (seq_t)a_next * q_prev + q_prevprev;

        /* append new denominator to cache */
        if (cache_len == cache_cap) {
            cache_cap = cache_cap * 2 + 4;
            cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        }
        cache[cache_len] = q_new;
        cache_len++;

        /* shift for next iteration */
        p_prevprev = p_prev;
        q_prevprev = q_prev;
        p_prev = p_new;
        q_prev = q_new;

        /* advance CF state to produce next a_next */
        unsigned long long m1 = d * a_next - m;
        unsigned long long d1 = (D - m1 * m1) / d;
        unsigned long long a1 = (a0 + m1) / d1;
        m = m1;
        d = d1;
        a_next = a1;
    }

    return cache[n];
}
