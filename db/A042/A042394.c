/* OEIS A042394: a(n) = numerator of the nth convergent to sqrt(724) */
/* Computed using the standard recurrence for continued fractions:
 *   p_{-1}=1, p_0=a0, a0=floor(sqrt(724))
 *   p_n = a_n * p_{n-1} + p_{n-2}
 * with coefficients a_n generated by the standard continued fraction
 * algorithm for sqrt(724).  This works for any idx_t and seq_t that
 * support integer arithmetic. */

#include <stdint.h>

/* idx_t and seq_t are provided by the build system. */
extern idx_t _floor_isqrt_u64(idx_t n);

seq_t a(idx_t n)
{
    /* D = 724, a0 = floor(sqrt(724)) = 26 */
    const idx_t D    = 724;
    const idx_t a0   = 26;

    if (n == 0)
        return (seq_t)a0;

    /* Continued fraction state */
    idx_t m = 0;           /* m_0 */
    idx_t d = 1;           /* d_0 */
    idx_t a_prev = a0;     /* a_{k-1}, starts with a0 for k = 1 */

    /* Numerator recurrence state */
    seq_t p_prevprev = (seq_t)1;   /* p_{-1} */
    seq_t p_prev     = (seq_t)a0;  /* p_0 */
    seq_t p_k = 0;

    for (idx_t k = 1; k <= n; ++k) {
        /* Compute next m, d, and coefficient a_k */
        idx_t m_new = d * a_prev - m;
        idx_t d_new = (D - m_new * m_new) / d;
        idx_t a_new = (a0 + m_new) / d_new;   /* floor division */

        /* Update numerator */
        p_k = (seq_t)a_new * p_prev + p_prevprev;

        /* Advance states */
        p_prevprev = p_prev;
        p_prev     = p_k;
        m = m_new;
        d = d_new;
        a_prev = a_new;
    }

    return p_prev;
}
