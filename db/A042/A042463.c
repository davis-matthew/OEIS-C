/* Denominators of continued fraction convergents to sqrt(759).  */
/* The sequence satisfies the recurrence
 *   q_{-2} = 1,  q_{-1} = 0
 *   q_n   = a_n * q_{n-1} + q_{n-2}   for n >= 0,
 * where a_0 = 27 and the subsequent partial quotients a_n
 * are generated by the standard continued‑fraction algorithm
 * for sqrt(759).  The first terms are a(0)=1, a(1)=1, a(2)=2,
 * a(3)=9, a(4)=11, … as given in the OEIS entry.  */
#include <stdint.h>

seq_t a(idx_t n) {
    /* constants for sqrt(759) */
    const uint64_t D   = 759ULL;      /* the radicand */
    const uint64_t a0  = 27ULL;       /* floor(sqrt(759)) */

    /* continued‑fraction state */
    uint64_t m = 0;       /* m_k in the standard algorithm */
    uint64_t d = 1;       /* d_k */
    uint64_t a = a0;      /* a_k, starts with a0 */

    /* previous two denominators: q_{k-1} and q_{k-2} */
    seq_t q_prev2 = 1;    /* q_{-2} */
    seq_t q_prev1 = 0;    /* q_{-1} */

    for (idx_t k = 0; k <= n; ++k) {
        /* compute current denominator */
        seq_t q = ((seq_t)a) * q_prev1 + q_prev2;

        if (k == n) {
            return q;
        }

        /* advance to next partial quotient a_{k+1} */
        uint64_t m_next = d * a - m;
        uint64_t d_next = (D - m_next * m_next) / d;
        uint64_t a_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        a = a_next;

        /* shift q indices for next step */
        q_prev2 = q_prev1;
        q_prev1 = q;
    }

    /* This point should never be reached because the loop returns */
    return 0;
}
