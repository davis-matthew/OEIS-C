/* Numerators of continued‑fraction convergents to sqrt(555)
   a(0) = 23, a(1) = 24, a(2) = 47, …
   Generated by the standard convergent recurrence:
   h_{-2} = 0, h_{-1} = 1, h_i = a_i * h_{i-1} + h_{i-2},
   where a_i are the partial quotients of sqrt(555):
   a_0 = 23, a_{i>0} cycles through {1,1,3,1,3,1,1,46}. */

seq_t a(idx_t n)
{
    /*  The period of the continued fraction for sqrt(555) is 8 */
    static const seq_t period[8] = {1,1,3,1,3,1,1,46};

    /* Initial two numerators h_{-2} = 0, h_{-1} = 1 */
    seq_t h_minus2 = (seq_t)0;
    seq_t h_minus1 = (seq_t)1;
    seq_t h = 0;
    idx_t i;

    for (i = 0; i <= n; ++i) {
        seq_t ai;
        if (i == 0) {
            ai = (seq_t)23;
        } else {
            ai = period[(i - 1) % 8];
        }
        h = ai * h_minus1 + h_minus2;
        if (i == n) {
            return h;
        }
        h_minus2 = h_minus1;
        h_minus1 = h;
    }
    /* Unreachable, but return 0 to satisfy the compiler. */
    return (seq_t)0;
}
