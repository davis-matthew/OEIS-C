/* Denominators of continued‑fraction convergents to sqrt(722).
   Generated by the standard recurrence for convergents:
   q_{-1} = 0, q_0 = 1,
   for k >= 1:  q_k = a_k * q_{k-1} + q_{k-2},
   where a_k are the partial quotients of sqrt(722) obtained by the
   classical continued‑fraction algorithm:
     m_0 = 0,  d_0 = 1,  a_0 = floor(sqrt(722)) = 26,
     m_k = d_{k-1} * a_{k-1} - m_{k-1},
     d_k = (722 - m_k^2) / d_{k-1},
     a_k = floor((a_0 + m_k) / d_k).                         */

#include <stdint.h>

seq_t a(idx_t n)
{
    /* Constants for D = 722. */
    const uint64_t D   = 722ULL;
    const uint64_t a0  = 26ULL;          /* floor(sqrt(722)) */

    if (n == 0)
        return (seq_t)1;                 /* q_0 = 1 */

    /* Initial values of the recurrence: q_{-1}=0, q_0=1. */
    seq_t q_prev  = (seq_t)0;            /* q_{k-2} */
    seq_t q_curr  = (seq_t)1;            /* q_{k-1} */

    /* State for generating partial quotients. */
    uint64_t m = 0;          /* m_0 */
    uint64_t d = 1;          /* d_0 */
    uint64_t a_prev = a0;    /* a_{k-1}, initially a_0 */

    for (idx_t k = 1; k <= n; ++k) {
        /* Next partial quotient a_k. */
        m = d * a_prev - m;
        d = (D - m * m) / d;
        uint64_t a_curr = (a0 + m) / d;   /* floor */

        /* Convergent recurrence: q_k = a_k * q_{k-1} + q_{k-2}. */
        seq_t q_next = ((seq_t)a_curr) * q_curr + q_prev;

        /* Shift for next iteration. */
        q_prev = q_curr;
        q_curr = q_next;

        /* Prepare for next partial quotient. */
        a_prev = a_curr;
    }

    return q_curr;
}
