/* Denominators of continued‑fraction convergents to sqrt(813) (OEIS A042569).
   Recurrence:
        p_k = a_k * p_{k-1} + p_{k-2}
        q_k = a_k * q_{k-1} + q_{k-2}
   with a_0 = ⌊√813⌋ = 28 and subsequent a_k generated by the usual
   continued‑fraction recurrence for √D:  (m_{k+1}, d_{k+1}, a_{k+1})
        m_{k+1} = d_k a_k - m_k
        d_{k+1} = (D - m_{k+1}²) / d_k
        a_{k+1} = ⌊(a_0 + m_{k+1}) / d_{k+1}⌋   */
#include <stdlib.h>
#include <stdint.h>

seq_t a(idx_t n)
{
    /* static mutable state – cache of computed denominators */
    static seq_t *denoms = NULL;    /* array of previously computed q_k   */
    static size_t  cap    = 0;       /* capacity of the cache             */
    static size_t  len    = 0;       /* number of elements stored         */

    /* alternating continued‑fraction parameters */
    static idx_t  m   = 0;           /* current m_k                         */
    static idx_t  d   = 1;           /* current d_k                         */
    static idx_t  a_k = 28;          /* current a_k (a_0 = floor sqrt(813)) */

    /* continued‑fraction convergent accumulators */
    static seq_t p_prev2 = 0;        /* p_{k-2}   */
    static seq_t p_prev1 = 1;        /* p_{k-1}   */
    static seq_t q_prev2 = 1;        /* q_{k-2}   */
    static seq_t q_prev1 = 0;        /* q_{k-1}   */

    /* initialise cache on first call */
    if (len == 0) {
        /* first convergent (k = 0) uses a_0 */
        seq_t p = (seq_t)a_k * p_prev1 + p_prev2;   /* 28*1+0 = 28 */
        seq_t q = (seq_t)a_k * q_prev1 + q_prev2;   /* 28*0+1 = 1 */
        /* store q_0 */
        cap = 16;
        denoms = (seq_t *)realloc(NULL, cap * sizeof(seq_t));
        if (!denoms) abort();
        denoms[0] = q;
        len = 1;
        /* shift accumulators for the next step */
        p_prev2 = p_prev1;  p_prev1 = p;
        q_prev2 = q_prev1;  q_prev1 = q;
        /* compute a_1 */
        idx_t m_next = d * a_k - m;                      /* 28 */
        idx_t d_next = (813ULL - (uint64_t)m_next * (uint64_t)m_next) / d; /* 29 */
        idx_t a_next = (28ULL + m_next) / d_next;        /* 1  */
        m = m_next;  d = d_next;  a_k = a_next;
    }

    /* generate further terms until index n is available */
    while (len <= (size_t)n) {
        /* compute next q_k using current a_k */
        seq_t q = (seq_t)a_k * q_prev1 + q_prev2;
        /* extend cache if needed */
        if (len == cap) {
            size_t new_cap = cap ? 2 * cap : 16;
            seq_t *tmp = (seq_t *)realloc(denoms, new_cap * sizeof(seq_t));
            if (!tmp) abort();
            denoms = tmp;
            cap = new_cap;
        }
        denoms[len] = q;
        len++;

        /* compute corresponding p_k */
        seq_t p = (seq_t)a_k * p_prev1 + p_prev2;
        /* shift accumulators for the next iteration */
        p_prev2 = p_prev1;  p_prev1 = p;
        q_prev2 = q_prev1;  q_prev1 = q;

        /* advance continued‑fraction coefficients */
        idx_t m_next = d * a_k - m;
        idx_t d_next = (813ULL - (uint64_t)m_next * (uint64_t)m_next) / d;
        idx_t a_next = (28ULL + m_next) / d_next;

        m = m_next;
        d = d_next;
        a_k = a_next;
    }

    return denoms[n];
}
