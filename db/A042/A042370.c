/* OEIS A042370
   Numerators of continued fraction convergents to sqrt(712).
   Recurrence: a(n) = 3202*a(n-6) - a(n-12)   (n ≥ 12)
   Initial values:
   a(0)=26, a(1)=27, a(2)=80, a(3)=507, a(4)=1094, a(5)=1601,
   a(6)=84346, a(7)=85947, a(8)=256240, a(9)=1623387,
   a(10)=3503014, a(11)=5126401
   (All further terms are generated by the recurrence) */

#include <stdlib.h>
#include <stdint.h>

/*--------------------  Seed values  --------------------*/
static const seq_t init[12] = {
    26, 27, 80, 507, 1094, 1601,
    84346, 85947, 256240, 1623387,
    3503014, 5126401
};

/*--------------------  Cached sequence values  --------------------*/
static seq_t *cache          = NULL;   /* dynamic array of computed terms      */
static size_t cache_cap      = 0;      /* allocated length of `cache`          */
static idx_t  max_computed   = 0;      /* largest n for which cache[n] is valid */

/* Ensure the cache can hold values up to 'next'. */
static void ensure_capacity(idx_t next)
{
    if ((idx_t)cache_cap > next) return;        /* already enough                    */
    size_t new_cap = cache_cap ? cache_cap : 16;
    while ((idx_t)new_cap <= next) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();                          /* allocation failure                */
    cache      = tmp;
    cache_cap  = new_cap;
}

/*--------------------------------------------------------------------*/
seq_t a(idx_t n)
{
    /* Initialise cache on first call. */
    if (!cache) {
        cache_cap    = 32;                      /* choose a modest initial size     */
        cache        = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache) abort();                    /* allocation failure               */
        for (idx_t i = 0; i < 12; ++i) cache[i] = init[i];
        max_computed = 11;                      /* indices 0…11 are now known       */
    }

    /* Return value if already computed. */
    if (n <= max_computed) return cache[n];

    /* Grow cache so it can store up to n. */
    ensure_capacity(n);

    /* Compute missing terms using the recurrence. */
    for (idx_t i = max_computed + 1; i <= n; ++i) {
        /* The recurrence only applies for i ≥ 12; the loop,
           however, will always start at i = 12 because
           max_computed is 11 after initialisation.  */
        seq_t prod = cache[i - 6] * (seq_t)3202;
        cache[i]   = prod - cache[i - 12];
    }
    max_computed = n;

    return cache[n];
}
