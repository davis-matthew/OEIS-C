/* Denominators of continued fraction convergents to sqrt(811)
   OEIS A042565
   The terms are generated by the standard recurrence for the
   continued‑fraction convergents of √D with D = 811.

   a0 = floor(sqrt(811)) = 28
   m0 = 0, d0 = 1
   For i ≥ 0
     ai   = a0  (for i = 0) or computed from the previous values
     m_{i+1} = d_i * a_i – m_i
     d_{i+1} = (811 – m_{i+1}^2) / d_i
     a_{i+1} = (28 + m_{i+1}) / d_{i+1}

   Denominator recurrence:
     q_{-2} = 1,   q_{-1} = 0
     q_i   = a_i * q_{i-1} + q_{i-2}

   The function returns a(i) = q_i for any i ≥ 0.  The routine can be
   called in arbitrary order; it performs a light O(i) computation each
   time.
*/
#include <stdint.h>

/* sequence element type and index type are supplied by the
   build system (seq_t, idx_t).  No other includes or static
   helpers are required. */
seq_t a(idx_t n)
{
    /* fixed constants for D = 811 */
    const seq_t D   = (seq_t)811;   /* discriminant */
    const seq_t a0  = (seq_t)28;    /* floor(sqrt(D))  */

    /* variables for the continued‑fraction expansion */
    seq_t m = (seq_t)0;   /* m_0 */
    seq_t d = (seq_t)1;   /* d_0 */
    seq_t a_cur = a0;     /* a_0 = a0 */

    /* variables for the convergent denominator recurrence */
    seq_t q_prev2 = (seq_t)1;   /* q_{-2} */
    seq_t q_prev1 = (seq_t)0;   /* q_{-1} */

    for (idx_t i = (idx_t)0; i <= n; ++i)
    {
        /* current partial quotient a_i */
        const seq_t ai = (i == (idx_t)0) ? a0 : a_cur;

        /* compute denominator q_i */
        const seq_t q = ai * q_prev1 + q_prev2;
        q_prev2 = q_prev1;
        q_prev1 = q;

        if (i == n) break;      /* desired term reached */

        /* update m, d, and next a for the next iteration */
        const seq_t m_new = d * ai - m;
        const seq_t numer = D - m_new * m_new;
        const seq_t d_new = numer / d;
        const seq_t a_next = (a0 + m_new) / d_new;

        m = m_new;
        d = d_new;
        a_cur = a_next;
    }

    return q_prev1;   /* a(n) = q_n */
}
