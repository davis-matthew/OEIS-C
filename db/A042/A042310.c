/* Recurrence: a(0)=26; for n>=1, a(n) = c(n)*a(n-1)+a(n-2),
   where c(n) are the continued‑fraction coefficients of sqrt(682).
   The coefficients are generated by the standard sqrt‑continued‑fraction
   algorithm. */

#include <stdint.h>

seq_t a(idx_t n)
{
    if (n == 0) return 26;

    /* terms needed for the continued fraction of sqrt(682) */
    const uint64_t D   = 682ULL;
    const uint64_t a0  = 26ULL;   /* floor(sqrt(682)) */

    /* state for generating the continued‑fraction coefficients */
    uint64_t m = 0, d = 1, a_coeff = a0;

    /* recurrence initial values: p_{-2}=0, p_{-1}=1 */
    seq_t p_prevprev = 0, p_prev = 1, p_curr = 0;

    for (idx_t k = 0; k <= n; ++k) {
        uint64_t a_val = (k == 0) ? a0 : a_coeff;

        /* p_k = a_k * p_{k-1} + p_{k-2} */
        p_curr = ((unsigned __int128)a_val * p_prev) + p_prevprev;
        if (k == n) return p_curr;

        /* shift the recurrence state for the next iteration */
        p_prevprev = p_prev;
        p_prev = p_curr;

        /* compute the next continued‑fraction coefficient */
        uint64_t m_next = d * a_val - m;
        uint64_t d_next = (D - m_next * m_next) / d;
        uint64_t a_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        a_coeff = a_next;
    }

    return 0;  /* should never reach here */
}
