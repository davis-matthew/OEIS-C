/* A042145: denominators of continued‑fraction convergents to sqrt(597)
   Recurrence: k_{-1}=0, k_0=1, k_n = a_n * k_{n‑1} + k_{n‑2}
   where a_0 = ⌊√597⌋ = 24 and the continued fraction of √597
   is generated by the standard recurrence:
       m_{i+1} = d_i*a_i - m_i
       d_{i+1} = (597 - m_{i+1}^2) / d_i
       a_{i+1} = (a_0 + m_{i+1}) / d_{i+1}
   For n = 0,1 the sequence starts 1,2,7,...
*/

#include <stdlib.h>
#include <stdint.h>

seq_t a(idx_t n)
{
    /* static cache of computed denominators */
    static seq_t *denoms = NULL;
    static idx_t cache_len = 0;      /* number of terms stored */
    static size_t cache_cap = 0;     /* capacity of denoms */

    /* Continued‑fraction state, kept static so successive calls can build
       further terms without recomputing from scratch. */
    static unsigned long long m = 0;
    static unsigned long long d = 1;
    static unsigned long long ai = 24;   /* a_0 = ⌊√597⌋ = 24 */
    const unsigned long long D  = 597ULL;
    const unsigned long long a0 = 24ULL;

    /* If requested term already cached, return it. */
    if (n < cache_len)
        return denoms[n];

    /* Ensure the cache has enough space for n+1 terms. */
    size_t needed = (size_t)(n + 1);
    if (needed > cache_cap) {
        size_t new_cap = cache_cap ? (cache_cap << 1) : 16;
        while (new_cap < needed)
            new_cap <<= 1;
        seq_t *tmp = (seq_t *)realloc(denoms, new_cap * sizeof(seq_t));
        if (!tmp)
            abort();                 /* fatal error */
        denoms = tmp;
        cache_cap = new_cap;
    }

    /* For the recurrence k_n = a_n*k_{n-1}+k_{n-2} we keep the last two
       computed denominators.  If the cache is empty we start with
       k_{-1}=0, k_0=1. */
    seq_t k_prevprev, k_prev;
    if (cache_len == 0) {
        k_prevprev = (seq_t)1;
        k_prev    = (seq_t)0;
    } else if (cache_len == 1) {
        k_prevprev = (seq_t)0;
        k_prev    = denoms[0];
    } else {
        k_prevprev = denoms[cache_len - 2];
        k_prev    = denoms[cache_len - 1];
    }

    /* Build terms up to n. */
    for (idx_t i = cache_len; i <= n; ++i) {
        seq_t k_i = (seq_t)ai * k_prev + k_prevprev;
        denoms[i] = k_i;

        /* shift for next iteration */
        seq_t temp = k_prev;
        k_prev    = k_i;
        k_prevprev = temp;

        /* advance continued fraction state for the next partial quotient */
        unsigned long long m_next = d * ai - m;
        unsigned long long d_next = (unsigned long long)
            (((__int128)D - (__int128)m_next * m_next) / d);
        unsigned long long a_next = (a0 + m_next) / d_next;

        m  = m_next;
        d  = d_next;
        ai = a_next;
    }

    cache_len = n + 1;
    return denoms[n];
}
