/* 
 * Sequence A042560: Numerators of continued fraction convergents to sqrt(809).
 *
 * a(0) = 28
 * For n ≥ 1, a(n) = a(n‑1) * a_n + a(n‑2)
 * where a_n is the n‑th term of the continued fraction of √809.
 *
 * The continued fraction coefficients are generated by the standard recurrence:
 *   m_{k+1} = d_k * a_k - m_k
 *   d_{k+1} = (D - m_{k+1}^2) / d_k
 *   a_{k+1} = floor((a0 + m_{k+1}) / d_{k+1})
 * with D = 809 and a0 = floor(√809) = 28.
 */
#include "../utils/floor_sqrt.h"

seq_t a(idx_t n) {
    const idx_t D = 809;                 /* discriminant */
    const idx_t a0_num = 28;             /* floor(sqrt(809)) */

    /* Numerator recurrence variables */
    seq_t p_nm2 = 0;                     /* p_{k-2}  */
    seq_t p_nm1 = 1;                     /* p_{k-1}  */
    seq_t p_k   = 0;                     /* p_k      */

    /* Coefficient recurrence variables */
    idx_t m = 0;
    idx_t d = 1;
    idx_t a_coeff = a0_num;

    for (idx_t k = 0; k <= n; ++k) {
        /* Compute the numerator for this index */
        p_k = (seq_t)a_coeff * p_nm1 + p_nm2;

        /* If we reached the desired index, return the result */
        if (k == n)
            return p_k;

        /* Shift for next iteration */
        p_nm2 = p_nm1;
        p_nm1 = p_k;

        /* Generate next continued‑fraction coefficient */
        idx_t m_next = d * a_coeff - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (a0_num + m_next) / d_next;

        /* Update recurrence state */
        m = m_next;
        d = d_next;
        a_coeff = a_next;
    }

    /* Unreachable, but keep compiler happy */
    return 0;
}
