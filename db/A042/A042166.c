/* Numerators of continued fraction convergents to sqrt(608) */
/* This implements the standard recurrence for convergents:
 * p[-2] = 0, p[-1] = 1
 * p[n] = a[n] * p[n-1] + p[n-2]
 * where a[n] are the partial quotients of sqrt(608),
 * with a[0] = floor(sqrt(608)) = 24.
 * The partial quotients are generated by the book algorithm
 * for continued fractions of square roots. */

#include <stdint.h>   /* for uint64_t; idx_t and seq_t are defined elsewhere */

seq_t a(idx_t n)
{
    /* Constants for sqrt(608) = 4*sqrt(38) */
    const idx_t D   = 608;          /* the radicand */
    const idx_t a0  = 24;           /* floor(sqrt(608)) */

    /* Variables for generating the partial quotients a[n] */
    idx_t m = 0;
    idx_t d = 1;
    idx_t a_q = a0;   /* current a[n] */

    /* Convergent recurrence */
    seq_t p_nm2 = (seq_t)0;   /* p[n-2] */
    seq_t p_nm1 = (seq_t)1;   /* p[n-1] */
    seq_t p_n   = (seq_t)0;   /* p[n] */

    for (idx_t i = 0; i <= n; ++i) {
        if (i == 0) {
            a_q = a0;
        } else {
            /* Next partial quotient via the standard algorithm */
            m = d * a_q - m;
            d = (D - m * m) / d;
            a_q = (a0 + m) / d;
        }
        /* Compute p[n] = a_q * p[n-1] + p[n-2] */
        p_n = (seq_t)a_q * p_nm1 + p_nm2;
        /* Shift for next iteration */
        p_nm2 = p_nm1;
        p_nm1 = p_n;
    }
    return p_n;
}
