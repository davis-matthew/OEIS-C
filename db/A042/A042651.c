/* Denominators of convergents to sqrt(855).
   The sequence a(n) is generated by the standard continued‑fraction
   expansion of √855.  Let a_k be the k‑th partial quotient.
   The recurrence for the denominators q_n of the n‑th convergent is
     q_{-2} = 1,  q_{-1} = 0,
     q_n   = a_n * q_{n-1} + q_{n-2}   (n ≥ 0).
   The partial quotients are obtained by the algorithm for quadratic
   surds with D = 855:
     m_0 = 0,  d_0 = 1,  a_0 = ⌊√D⌋ = 29.
     For k ≥ 0:
         m_{k+1} = d_k * a_k – m_k
         d_{k+1} = (D – m_{k+1}²) / d_k
         a_{k+1} = ⌊(a_0 + m_{k+1}) / d_{k+1}⌋
   The sequence of a_k is periodic; the period is detected when
   a_k equals 2*a_0.  The period length (excluding a_0) is stored in
   period_len; the array cf holds a_0 followed by one full period.
*/

#include <stddef.h>

static int cf[200];          /* a_0 followed by one full period */
static size_t period_len;   /* length of the period (cf[1]..cf[period_len]) */
static int initialized = 0; /* flag for one‑time initialization */

static void init_cf(void)
{
    const int D = 855;
    int a0 = 0;
    while ((a0 + 1) * (a0 + 1) <= D) ++a0;   /* integer √855 */

    int m = 0, d = 1, a = a0;
    cf[0] = a0;
    size_t len = 1;

    while (1) {
        m = d * a - m;
        d = (D - m * m) / d;
        a = (a0 + m) / d;
        cf[len++] = a;
        if (a == 2 * a0) break;            /* end of one period */
    }

    period_len = len - 1;
    initialized = 1;
}

seq_t a(idx_t n)
{
    if (!initialized)
        init_cf();

    seq_t q_prev2 = 1;   /* q_{-2} */
    seq_t q_prev1 = 0;   /* q_{-1} */

    for (idx_t i = 0; i <= n; ++i) {
        int ai;
        if (i == 0)
            ai = cf[0];
        else {
            size_t idx = ((size_t)i - 1) % period_len;
            ai = cf[1 + idx];
        }
        seq_t q = (seq_t)ai * q_prev1 + q_prev2;
        q_prev2 = q_prev1;
        q_prev1 = q;
    }
    return q_prev1;
}
