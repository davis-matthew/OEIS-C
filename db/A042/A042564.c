/* Numerators of continued‑fraction convergents to sqrt(811) */
/* Implements the standard recurrence
 *   p(−2)=0 , p(−1)=1
 *   p(k)=a(k)*p(k−1)+p(k−2)  for k≥0
 * where a(0)=⌊√811⌋ and the remaining partial quotients are
 * generated by the periodic algorithm for quadratic irrationals. */
#include <stdint.h>

static const idx_t D = 811;      /* The continued–fraction discriminant   */
static const idx_t A0 = 28;     /* floor(√811)                            */

seq_t a(idx_t n)
{
    /* --- continued‑fraction state ------------------------------------- */
    idx_t m = 0;                 /* m_0                     */
    idx_t d = 1;                 /* d_0                     */
    idx_t a_coeff = A0;          /* a_0                     */

    /* --- convergent numerators --------------------------------------- */
    seq_t p_prev2 = 0;          /* p(−2)                    */
    seq_t p_prev1 = 1;          /* p(−1)                    */
    seq_t p_curr  = (seq_t)a_coeff * p_prev1 + p_prev2; /* p(0) */

    /* Update previous two numerators for the next step */
    p_prev2 = p_prev1;
    p_prev1 = p_curr;

    /* --- generate further partial quotients and numerators ---------- */
    for (idx_t k = 1; k <= n; ++k)
    {
        /* next data of the algorithm for sqrt(D) */
        m = d * a_coeff - m;                     /* m_{k}  */
        d = (D - m * m) / d;                     /* d_{k}  */
        a_coeff = (A0 + m) / d;                  /* a_{k}  */

        /* compute next numerator */
        p_curr = (seq_t)a_coeff * p_prev1 + p_prev2;

        /* shift for next iteration */
        p_prev2 = p_prev1;
        p_prev1 = p_curr;
    }

    return p_curr;
}
