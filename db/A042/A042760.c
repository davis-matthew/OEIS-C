/* Numerators of continued‑fraction convergents to sqrt(911).
   Recurrence: a(0)=30, a(1)=151; for n≥2
      a(n) = c_n * a(n-1) + a(n-2),
   where c_n are the continued‑fraction coefficients of sqrt(911)
   generated by the standard Pell algorithm.  */

#include <stdlib.h>
#include <stdbool.h>

seq_t a(idx_t n)
{
    /* Static state – persistence across calls. */
    static bool initialized = false;
    static seq_t *cache = NULL;
    static size_t cache_len = 0, cache_cap = 0;
    static seq_t p_prev1, p_prev2;   /* p_{k-1} and p_{k-2} */
    static idx_t m, d, a_coeff;      /* continued‑fraction state */
    static const idx_t a0 = 30;       /* floor(sqrt(911)) */
    static const idx_t D  = 911;

    if (!initialized) {
        /* First convergent (k = 0). */
        p_prev2 = (seq_t)1;          /* p_{-1} = 1 */
        p_prev1 = (seq_t)30;         /* p_0   = 30 */
        cache_cap = 8;               /* arbitrary start size */
        cache    = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        cache[0] = (seq_t)30;
        cache_len = 1;

        /* Initial continued‑fraction state for generation of c_1, c_2, ... */
        m = (idx_t)0;
        d = (idx_t)1;
        a_coeff = a0;                /* a_0 = 30 */

        initialized = true;
    }

    if (n < cache_len)
        return cache[n];

    /* Generate terms up to index n. */
    idx_t i = cache_len;
    while (i <= n) {
        /* Compute next continued‑fraction coefficient. */
        idx_t m_next = d * a_coeff - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (a0 + m_next) / d_next;

        /* Next convergent numerator. */
        seq_t p_next = (seq_t)a_next * p_prev1 + p_prev2;

        /* Expand cache if necessary. */
        if (cache_len >= cache_cap) {
            cache_cap = cache_cap ? cache_cap * 2 : 4;
            cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        }
        cache[cache_len++] = p_next;

        /* Advance state for next iteration. */
        p_prev2 = p_prev1;
        p_prev1 = p_next;
        m = m_next;
        d = d_next;
        a_coeff = a_next;

        ++i;
    }

    return cache[n];
}
