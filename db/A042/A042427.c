/* Sequence A042427: Denominators of continued‑fraction convergents to sqrt(741).  
   Recurrence: a(n) = 14705390*a(n-10) - a(n-20) (n > 19).
   Initial values a(0)…a(19) are generated by the continued‑fraction algorithm. */

#include <stdlib.h>
#include <stdint.h>

/* --------------------------------------------------------------------- */
/*  Cached values (static to allow memoisation across calls).             */
/* --------------------------------------------------------------------- */
static seq_t *cache          = NULL;   /* array of cached terms          */
static idx_t  cache_size     = 0;      /* number of cached terms          */

/* --------------------------------------------------------------------- */
/*  Continued fraction parameters for sqrt(741).                         */
/* --------------------------------------------------------------------- */
static const uint64_t D = 741ull;      /* the number under the sqrt     */
static const uint64_t AFloor = 27ull;  /* floor(sqrt(741))              */

/* --------------------------------------------------------------------- */
/*  Return a(n) for any non‑negative n.  Thread‑safe structure is not    */
/*  required - the benchmark calls are serial.                            */
/* --------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    /* ----------------------------------------------------------------- */
    /*  Initialise the cache on first invocation.  Compute the first    */
    /*  20 terms using the classical continued‑fraction algorithm for   */
    /*  sqrt(741).                                                      */
    /* ----------------------------------------------------------------- */
    if (!cache)
    {
        /* allocate space for indices 0..19 (20 terms) */
        cache = (seq_t *)malloc(20 * sizeof(seq_t));
        if (!cache) return 0;          /* allocation failure */

        uint64_t m   = 0;              /* m_0 */
        uint64_t d   = 1;              /* d_0 */
        uint64_t a_cf = AFloor;       /* a_0 */

        /* q_-1 = 0, q_0 = 1 (convergents of sqrt) */
        seq_t q_prevprev = 0;          /* q_{-1} */
        seq_t q_prev     = 1;          /* q_0   */

        /* 0th convergent: q_0 = 1 */
        cache[0] = q_prev;
        /* Prepare a_1 for the next step */
        uint64_t m_next = d * a_cf - m;
        uint64_t d_next = (D - m_next * m_next) / d;
        a_cf = (AFloor + m_next) / d_next;
        m = m_next; d = d_next;

        /* Compute convergents 1 .. 19 */
        for (idx_t i = 1; i < 20; ++i)
        {
            /* q_i = a_i * q_{i-1} + q_{i-2} */
            seq_t q = (seq_t)a_cf * q_prev + q_prevprev;
            cache[i] = q;

            /* Advance for next iteration */
            q_prevprev = q_prev;
            q_prev     = q;

            /* New partial quotient a_{i+1} */
            m_next = d * a_cf - m;
            d_next = (D - m_next * m_next) / d;
            a_cf = (AFloor + m_next) / d_next;

            m = m_next; d = d_next;
        }

        cache_size = 20;
    }

    /* ----------------------------------------------------------------- */
    /*  If requested index is already cached, return it directly.       */
    /* ----------------------------------------------------------------- */
    if (n < cache_size) return cache[n];

    /* ----------------------------------------------------------------- */
    /*  Extend cache up to index n using the recurrence.                 */
    /* ----------------------------------------------------------------- */
    while (cache_size <= n)
    {
        /* a(k) = 14705390*a(k-10) - a(k-20) */
        seq_t term = (seq_t)14705390 * cache[cache_size - 10]
                              - cache[cache_size - 20];

        /* Grow the array by one slot (realloc may grow in larger steps). */
        seq_t *tmp = (seq_t *)realloc(cache,
                                      (cache_size + 1) * sizeof(seq_t));
        if (!tmp) return 0;          /* allocation failure */

        cache = tmp;
        cache[cache_size++] = term;
    }

    return cache[n];
}
