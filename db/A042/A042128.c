/* Sequence A042128: numerators of continued‑fraction convergents to sqrt(589).
   The terms are obtained from the recurrence
       p_{-2} = 0 ,  p_{-1} = 1
       p_k   = a_k * p_{k-1} + p_{k-2}      (k ≥ 0)
   where a_0 = ⌊√589⌋ = 24 and the subsequent partial quotients a_k are
   generated by the standard continued‑fraction algorithm:
       m_{k+1} = d_k * a_k – m_k
       d_{k+1} = (589 – m_{k+1}²) / d_k
       a_{k+1} = ⌊(a_0 + m_{k+1}) / d_{k+1}⌋
*/

#include <stdlib.h>
#include <stdbool.h>

/* Cache for already computed terms. */
static seq_t *cache   = NULL;
static idx_t  cache_cap  = 0;   /* current allocated size */
static idx_t  cached_size = 0;  /* number of terms stored */

/* Current state of the continued‑fraction generator (static across calls). */
static bool   initialized = false;
static idx_t  m, d, a_cur;
static seq_t  p_prevprev, p_prev;

/* Ensure the cache can hold at least 'need' terms. */
static void ensure_cache(idx_t need)
{
    if (cached_size >= need)
        return;
    if (cache_cap < need) {
        idx_t new_cap = cache_cap ? cache_cap << 1 : 64;
        while (new_cap < need)
            new_cap <<= 1;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        cache = tmp;
        cache_cap = new_cap;
    }
}

seq_t a(idx_t n)
{
    /* One‑time initialization of the generator. */
    if (!initialized) {
        initialized = true;
        cached_size = 0;

        /* Initial partial quotient a_0. */
        m      = 0;
        d      = 1;
        a_cur  = 24;          /* floor(sqrt(589)) */

        /* Initial values for the numerator recurrence. */
        p_prevprev = (seq_t)0;
        p_prev     = (seq_t)1;
    }

    /* Compute terms up to n if we haven't cached them yet. */
    if (n >= cached_size) {
        ensure_cache(n + 1);
        for (idx_t k = cached_size; k <= n; ++k) {
            /* Current numerator p_k. */
            seq_t p = a_cur * p_prev + p_prevprev;
            cache[k] = p;

            /* Shift the recurrence state. */
            p_prevprev = p_prev;
            p_prev     = p;

            /* Generate the next partial quotient a_{k+1}. */
            idx_t m_next = d * a_cur - m;
            idx_t d_next = (589 - m_next * m_next) / d;
            idx_t a_next = (24 + m_next) / d_next;

            m      = m_next;
            d      = d_next;
            a_cur  = a_next;

            cached_size = k + 1;
        }
    }

    return cache[n];
}
