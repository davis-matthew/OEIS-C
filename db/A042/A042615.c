/* Sequence A042615 – Denominators of continued fraction convergents to sqrt(836)
 *
 * The denominators q_n satisfy
 *     q_{-1} = 0,   q_0 = 1,
 *     q_n   = a_n * q_{n-1} + q_{n-2}   (n ≥ 1),
 * where a_n are the simple continued‑fraction coefficients of √836.
 * The coefficients are generated by the standard recurrence
 *
 *     m_{k+1} = d_k a_k - m_k
 *     d_{k+1} = (836 - m_{k+1}²) / d_k
 *     a_{k+1} = (28 + m_{k+1}) / d_{k+1}
 *
 * This implementation memoises the denominators and continues the
 * continued‑fraction generation as needed.
 */

#include <stdlib.h>

#define D         836ULL   /* the square‑free part of the continued fraction */
#define SQRT_D    28ULL    /* floor(sqrt(836)) */

/* Persistent memoisation array for q_n */
static seq_t *q_arr = NULL;      /* array of computed denominators */
static size_t q_cap = 0;        /* allocated capacity of q_arr          */
static idx_t  q_len = 0;        /* number of elements currently stored */

/* State of the continued fraction generator (after having produced a_k) */
static uint64_t cf_m = 0;       /* current m_k                         */
static uint64_t cf_d = 1;       /* current d_k                         */
static int      cf_a = SQRT_D;  /* current a_k (a_0 = 28)              */

/* Helper: compute the next coefficient a_{k+1} and update the state */
static seq_t get_next_a(void)
{
    uint64_t m_next = cf_d * cf_a - cf_m;
    uint64_t d_next = (D - m_next * m_next) / cf_d;
    int      a_next = (int)((SQRT_D + m_next) / d_next);

    cf_m = m_next;
    cf_d = d_next;
    cf_a = a_next;

    return (seq_t)a_next;
}

/* Ensure q_arr contains values q_0 … q_n */
static void ensure(idx_t n)
{
    if (q_len > n)                  /* already available */
        return;

    /* Allocate / grow storage if necessary */
    if ((size_t)(n + 1) > q_cap) {
        size_t new_cap = q_cap ? q_cap * 2 : 16;
        if (new_cap < (size_t)(n + 1))
            new_cap = (size_t)(n + 1);
        q_arr = (seq_t *)realloc(q_arr, new_cap * sizeof(seq_t));
        q_cap = new_cap;
    }

    /* Initialise first term if this is the first use */
    if (q_len == 0) {
        q_arr[0] = (seq_t)1;        /* q_0 = 1 */
        q_len   = 1;                /* now we have q_0 */
    }

    /* Compute missing denominators up to n */
    for (idx_t k = q_len; k <= n; ++k) {
        seq_t ak = get_next_a();           /* the coefficient a_k   */
        seq_t qk;

        if (k == 1)                       /* q_1 = a_1 * q_0 + 0  */
            qk = ak * q_arr[0];
        else                               /* q_k = a_k*q_{k-1}+q_{k-2} */
            qk = ak * q_arr[k - 1] + q_arr[k - 2];

        q_arr[k] = qk;
    }

    q_len = n + 1;
}

/* Public function: return the n‑th term of the sequence (0‑based). */
seq_t a(idx_t n)
{
    ensure(n);
    return q_arr[n];
}
