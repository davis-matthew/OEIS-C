/* OEIS A042597: Denominators of continued fraction convergents to sqrt(827).
   Recurrence: Let a0 = ⌊√827⌋ = 28. The continued fraction coefficients after a0
   are generated by the standard algorithm:
       m_k+1 = d_k * a_k – m_k
       d_k+1 = (827 – m_k+1²) / d_k
       a_k+1 = ⌊(a0 + m_k+1) / d_k+1⌋
   Denominators q_k satisfy:
       q_0 = 1
       q_1 = a_1
       q_k = a_k * q_k-1 + q_k-2   (k ≥ 2)
   The function below computes q_n for any n ≥ 0. */
#include <stdint.h>

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)1;          /* q0 */
    /* constants for sqrt(827) continued fraction */
    const idx_t N = 827;
    const idx_t a0 = 28;                 /* floor(sqrt(827)) */
    /* state for the continued‑fraction algorithm */
    idx_t m = 0;
    idx_t d = 1;
    /* compute first numerator after a0: a1 */
    idx_t m1   = d * a0 - m;                 /* m1 = 28 */
    idx_t d1   = (N - m1 * m1) / d;          /* d1 = 43 */
    idx_t a1   = (a0 + m1) / d1;             /* a1 = 1 */
    /* denominators q0, q1 */
    seq_t q_prev2 = 1;                       /* q0 */
    seq_t q_prev1 = (seq_t)a1;               /* q1 */
    if (n == 1) return q_prev1;              /* q1 */
    /* update state for next iteration */
    m = m1;
    d = d1;
    idx_t a_prev = a1;                       /* a_prev = a_k for current k */
    seq_t q_curr;
    /* iterate for k = 2 .. n */
    for (idx_t k = 2; k <= n; ++k)
    {
        /* generate next coefficient a_k */
        idx_t m_next = d * a_prev - m;
        idx_t d_next = (N - m_next * m_next) / d;
        idx_t a_next = (a0 + m_next) / d_next;
        /* recurrence for denominator */
        q_curr = (seq_t)a_next * q_prev1 + q_prev2;
        /* shift for next step */
        q_prev2 = q_prev1;
        q_prev1 = q_curr;
        /* update continued‑fraction state */
        m = m_next;
        d = d_next;
        a_prev = a_next;
    }
    return q_curr;
}
