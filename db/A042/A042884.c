/* Numerators of continued fraction convergents to sqrt(974).
   The numerators p_k satisfy p_{-2}=0, p_{-1}=1 and
   p_k = a_k * p_{k-1} + p_{k-2},
   where the partial quotients a_k are generated by the classic
   continued‑fraction algorithm for √974. */
#include <stdbool.h>
#include <stdlib.h>

/* multiply a seq_t by a small uint32_t constant without overflow
 * for 64‑bit seq_t we use unsigned __int128 as intermediate,
 * for larger seq_t we rely on the built‑in arithmetic. */
static inline seq_t mul_small(seq_t x, unsigned int m)
{
    if (sizeof(seq_t) <= 8) {
        unsigned __int128 res = (unsigned __int128)x * m;
        return (seq_t)res;
    } else {
        return x * m;
    }
}

seq_t a(idx_t n)
{
    const idx_t N   = 974;     /* the integer under the square root */
    const idx_t a0  = 31;      /* floor(sqrt(974)) = 31 */

    /* Continued‑fraction state variables */
    idx_t m = 0;               /* part of the standard (m,d,a) triple */
    idx_t d = 1;
    idx_t a_k = a0;            /* current partial quotient */

    /* Convergent numerators */
    seq_t p_nm2 = 0;           /* p_{-2} */
    seq_t p_nm1 = 1;           /* p_{-1} */
    seq_t p_n   = 0;           /* current numerator */

    for (idx_t k = 0; k <= n; ++k) {
        /* p_k = a_k * p_{k-1} + p_{k-2} */
        seq_t tmp = mul_small(p_nm1, (unsigned int)a_k);
        p_n = tmp + p_nm2;

        if (k == n)
            break;             /* the desired numerator is ready */

        /* shift for the next step */
        p_nm2 = p_nm1;
        p_nm1 = p_n;

        /* compute next partial quotient (m,d,a) */
        m = d * a_k - m;
        d = (N - m * m) / d;
        a_k = (a0 + m) / d;
    }

    return p_n;
}
