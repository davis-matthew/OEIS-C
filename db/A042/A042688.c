/* 
 * Formula: a(n) = numerator of the n-th convergent of the continued fraction of sqrt(874).
 * It is computed via the standard recurrence for continued fractions:
 *
 *   p_{-2} = 0,  p_{-1} = 1
 *   p_k   = a_k * p_{k-1} + p_{k-2}
 *
 * The partial quotients a_k are generated by the Pell‐equation algorithm.
 * This implementation works for any seq_t that supports integer + - * /.
 */

#include <stdint.h>

seq_t a(idx_t n)
{
    /* 874 has a minimal period of the continued fraction of sqrt(874). */
    const seq_t D   = (seq_t)874;   /* the radicand */
    const seq_t a0  = (seq_t)29;    /* floor(sqrt(874)) */

    /* Continued fraction state variables (all in seq_t). */
    seq_t m = (seq_t)0;      /* m_0 */
    seq_t d = (seq_t)1;      /* d_0 */
    seq_t a_k = a0;          /* a_0 */

    /* Convergent numerator recurrence. */
    seq_t prevprev = (seq_t)0;  /* p_{-2} */
    seq_t prev     = (seq_t)1;  /* p_{-1} */
    seq_t curr     = (seq_t)0;  /* p_k */

    for (idx_t k = 0; k <= n; ++k)
    {
        /* Compute current numerator. */
        curr = a_k * prev + prevprev;
        if (k == n)
            return curr;

        /* Advance continued fraction state to next partial quotient. */
        m = d * a_k - m;
        d = (D - m * m) / d;
        a_k = (a0 + m) / d;

        /* Shift for the next iteration. */
        prevprev = prev;
        prev     = curr;
    }

    /* Unreachable, but keep the compiler happy. */
    return (seq_t)0;
}
