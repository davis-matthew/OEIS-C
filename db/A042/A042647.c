/*
 * A042647  Denominators of continued fraction convergents to sqrt(853).
 * https://oeis.org/A042647
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, frac, easy
 * Formula:   denominators q_n of the continued fraction convergents of
 *            sqrt(853)
 * Range:     u8 n <= 5, u16 n <= 9, u32 n <= 17, u64 n <= 34, u128 n <= 68,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence: q_{-1} = 0, q_0 = 1; q_n = a_n * q_{n-1} + q_{n-2}         */
/* where a_n are the partial quotients after the integer part of sqrt(853).   */
/* Continued‑fraction terms are generated by the standard recurrence for sqrt(D). */

#include <stdint.h>

seq_t a(idx_t n)
{
    /* D = 853, integer part of sqrt(853) */
    const idx_t D = 853;
    const idx_t a0 = 29;        /* floor(sqrt(853)) */

    /* Denominator of the zeroth convergent */
    if (n == 0)
        return (seq_t)1;

    /* Initialize convergent recurrence */
    seq_t q_prevprev = (seq_t)0; /* q_{-1} */
    seq_t q_prev     = (seq_t)1; /* q_0  */

    /* Variables for continued‑fraction generation */
    idx_t m = 0;
    idx_t d = 1;
    idx_t a_term = a0;         /* a_0, the integer part */

    /* Compute a_n and q_n iteratively up to n */
    for (idx_t k = 1; k <= n; ++k) {
        /* Generate next continued‑fraction term a_k */
        idx_t m_next = d * a_term - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        a_term = a_next;       /* now a_term == a_k */

        /* Update convergents: q_k = a_k * q_{k-1} + q_{k-2} */
        seq_t q_curr = (seq_t)a_term * q_prev + q_prevprev;

        /* Shift for next iteration */
        q_prevprev = q_prev;
        q_prev     = q_curr;
    }

    return q_prev; /* this is q_n */
}
