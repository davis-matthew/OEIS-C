/* Recurrence for the numerators of the continued fraction convergents to sqrt(839).
   a(0) = 28 and a(n) = a_n * a(n-1) + a(n-2)
   where a_k are the partial quotients of sqrt(839).  The CF is generated by
   the standard recurrence
       m_{k+1} = d_k * a_k - m_k,
       d_{k+1} = (839 - m_{k+1}^2) / d_k,
       a_{k+1} = ⌊(a0 + m_{k+1}) / d_{k+1}⌋.
*/
seq_t a(idx_t n)
{
    const seq_t D  = 839;          /* D in sqrt(D) */
    const seq_t a0 = 28;           /* floor(sqrt(839)) */

    /* convergents p_{-2}=0, p_{-1}=1 */
    seq_t p_prev2 = 0;
    seq_t p_prev1 = 1;
    seq_t p_curr  = 0;

    /* CF state for a_k generation */
    seq_t m   = 0;
    seq_t d   = 1;
    seq_t a_prev = a0;

    for (idx_t k = 0; k <= n; ++k) {
        seq_t ak;
        if (k == 0) {
            ak = a0;              /* first partial quotient */
        } else {
            /* Generate next partial quotient a_{k} */
            seq_t m_next  = d * a_prev - m;
            seq_t d_next  = (D - m_next * m_next) / d;
            seq_t a_next  = (a0 + m_next) / d_next;

            m = m_next;
            d = d_next;
            a_prev = a_next;
            ak = a_next;
        }

        /* recurrence for convergent numerators */
        p_curr = ak * p_prev1 + p_prev2;
        p_prev2 = p_prev1;
        p_prev1 = p_curr;
    }

    return p_curr;
}
