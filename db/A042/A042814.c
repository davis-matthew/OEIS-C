/* OEIS A042814 – Numerators of continued‑fraction convergents to sqrt(938).
   The sequence is generated by the continuants
        p_{-2} = 0,  p_{-1} = 1,
        p_n   = a_n · p_{n-1} + p_{n-2}   (n ≥ 0),
   where the coefficients a_n come from the continued fraction of sqrt(938)
   (a_0 = ⌊√938⌋ = 30).  The function caches already computed values
   so that any subsequent call is O(1) for indices that have been seen. */

#include <stdlib.h>

/* ----------  dynamic array helpers  ---------- */
static seq_t *p_arr = NULL;   /* cached numerators */
static size_t p_cap = 0;      /* current capacity of p_arr   */
static size_t p_size = 0;     /* number of elements stored   */

/* Grow the cache to hold at least 'need' elements. */
static void ensure_capacity(size_t need)
{
    if (need <= p_cap)
        return;
    size_t new_cap = p_cap ? p_cap * 2 : 4;
    while (new_cap < need)
        new_cap *= 2;
    seq_t *tmp = (seq_t *)realloc(p_arr, new_cap * sizeof(seq_t));
    if (!tmp)
        abort();           /* allocation failure */
    p_arr = tmp;
    p_cap = new_cap;
}

/* ----------  state for the continued fraction  ---------- */
static seq_t cf_m = 0;          /* m_i from the algorithm            */
static seq_t cf_d = 1;          /* d_i                               */
static seq_t cf_a = 30;         /* a_i                               */

/* ----------  recurrence state  ---------- */
static seq_t prev2 = 1;   /* p_{-1} */
static seq_t prev1 = 30;  /* p_0    */

/* ----------  main sequence function  ---------- */
seq_t a(idx_t n)
{
    /* first call – initialise cache with the first numerator. */
    if (p_size == 0) {
        ensure_capacity(1);
        p_arr[0] = prev1;   /* a(0) = 30 */
        p_size = 1;
    }

    /* generate terms until the requested index is available. */
    while ((size_t)n >= p_size) {
        /* next continued‑fraction coefficient a_{k+1} */
        seq_t m_next = cf_d * cf_a - cf_m;
        seq_t d_next = ( (seq_t)938 - m_next * m_next ) / cf_d;
        seq_t a_next = ( (seq_t)30 + m_next ) / d_next;

        /* next numerator with the recurrence. */
        seq_t curr = a_next * prev1 + prev2;

        /* advance recurrence state. */
        prev2 = prev1;
        prev1 = curr;

        /* advance continued‑fraction state. */
        cf_m = m_next;
        cf_d = d_next;
        cf_a = a_next;

        /* store the new term. */
        ensure_capacity(p_size + 1);
        p_arr[p_size++] = curr;
    }

    return p_arr[(size_t)n];
}
