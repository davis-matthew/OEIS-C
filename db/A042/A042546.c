/* Numerators of the convergents to sqrt(802) (OEIS A042546).
   The continued fraction of sqrt(802) has a periodic part;
   the numerator sequence is generated by the recurrence
       p_{-2}=0,  p_{-1}=1,  p_k = a_k p_{k-1} + p_{k-2}
   where a_0 = floor(sqrt(802)) and for k≥1  a_k is the k‑th term of
   the periodic part (repeating).  This function returns p_n for any
   n ≥ 0.                                                 */

#include <stddef.h>           /* size_t for period_len declaration */
#include <stdbool.h>          /* bool, true, false */
#include <stdint.h>
#include "../utils/ipow_i32.h"

/* Floor square root by binary search */
static inline seq_t floor_sqrt(seq_t x)
{
    seq_t lo = 0, hi = 1;
    while (ipow_i32(hi, 2) <= x)
        hi <<= 1;
    while (lo < hi)
    {
        seq_t mid = (lo + hi) >> 1;
        seq_t mid2 = mid * mid;
        if (mid2 <= x)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

#define PERIOD_MAX 256

static seq_t period[PERIOD_MAX];
static size_t period_len = 0;
static bool period_computed = false;

/* Compute the periodic part of the continued fraction of sqrt(802) */
static void compute_period(void)
{
    if (period_computed) return;

    const seq_t D     = (seq_t)802;
    const seq_t a0    = floor_sqrt(D);

    seq_t m = (seq_t)0;
    seq_t d = (seq_t)1;
    seq_t a = a0;

    period_len = 0;
    do
    {
        m = d * a - m;
        d = (D - m * m) / d;
        a = (a0 + m) / d;
        period[period_len++] = a;
    }
    while (a != 2 * a0 && period_len < PERIOD_MAX);

    period_computed = true;
}

/* Return a(n), the nth numerator of the convergents to sqrt(802)   */
seq_t a(idx_t n)
{
    compute_period();

    const seq_t a0 = floor_sqrt((seq_t)802);

    seq_t p_prev2 = (seq_t)0;   /* p_{-2} */
    seq_t p_prev1 = (seq_t)1;   /* p_{-1} */
    seq_t p_curr, ak;

    for (idx_t k = 0; k <= n; ++k)
    {
        if (k == 0)
            ak = a0;
        else
            ak = period[(k - 1) % period_len];

        p_curr = ak * p_prev1 + p_prev2;

        if (k == n)
            return p_curr;

        p_prev2 = p_prev1;
        p_prev1 = p_curr;
    }

    /* Unreachable, but keeps the compiler happy. */
    return (seq_t)0;
}
