/*  The continued fraction of sqrt(975) has a periodic part of length 10 */
/*  Recurrence: q_{-1} = 0, q_{-2} = 1, and q_k = a_k·q_{k-1} + q_{k-2} */
/*  where a_0 = ⌊√975⌋ = 31 and the subsequent a_k are generated by the */
/*  standard continued‑fraction algorithm. */

seq_t a(idx_t n)
{
    /* Handle the trivial case explicitly to avoid unnecessary work. */
    if (n == 0) return (seq_t)1;

    /* Parameters for the continued fraction of sqrt(975). */
    const idx_t D  = 975;
    const idx_t a0 = 31;          /* floor(sqrt(975)) */

    /* State of the continued‑fraction algorithm. */
    idx_t m = 0;
    idx_t d = 1;
    idx_t a = a0;

    /* Two previous convergents: q_{k-2} and q_{k-1}. */
    seq_t q_prevprev = (seq_t)1;   /* q_{-2} */
    seq_t q_prev     = (seq_t)0;   /* q_{-1} */
    seq_t q_curr     = 0;

    /* Generate convergents up to index n. */
    for (idx_t i = 0; i <= n; ++i) {
        if (i == 0) {
            a = a0;                      /* first partial quotient */
        } else {
            /* Next terms of the continued fraction. */
            m = d * a - m;
            d = (D - m * m) / d;
            a = (a0 + m) / d;
        }

        /* Recurrence for the denominator of the convergent. */
        q_curr = (seq_t)a * q_prev + q_prevprev;

        /* Advance the window of two previous terms. */
        q_prevprev = q_prev;
        q_prev     = q_curr;
    }

    return q_curr;
}
