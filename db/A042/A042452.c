/*
 * A042452  Numerators of continued fraction convergents to sqrt(754).
 * https://oeis.org/A042452
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, frac, easy
 * Formula:   Numerators of continued‑fraction convergents to sqrt(754)
 * Range:     u8 n <= 1, u16 n <= 8, u32 n <= 17, u64 n <= 35, u128 n <= 72,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) is the n‑th numerator p_n in the recurrence
 * p_-1 = 1, p_0 = floor(sqrt(754)) = 27,
 * p_k = a_k * p_{k-1} + p_{k-2},
 * where the continued fraction coefficients a_k are generated by
 * the classic algorithm for sqrt(D). */

/* -----------------------------------------------------------------------------
   Opaque types seq_t (unsigned integer, up to 128 bits or arbitrary precision)
   and idx_t (unsigned 64‑bit index) are supplied by the build.  The function
   below assumes those types and standard arithmetic operations only.  No
   floating‑point or <math.h> functions are used.  ---------------------------------------------------------------- */

seq_t a(idx_t n)
{
    const idx_t D = 754;          /* the radicand */
    const idx_t a0 = 27;          /* floor(sqrt(754)) */

    /* Base case p_-1 = 1, p_0 = a0 */
    seq_t p_prev2 = 1;            /* p_{k-2}   */
    seq_t p_prev1 = a0;           /* p_{k-1}   */
    if (n == 0) return p_prev1;

    /* Variables for the CF expansion state;
       start with (m_0, d_0, a_0) = (0, 1, a0) */
    idx_t m = 0;
    idx_t d = 1;
    idx_t a_val = a0;

    for (idx_t k = 1; k <= n; ++k)
    {
        /* Next CF coefficient a_k */
        idx_t m_next = d * a_val - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (a0 + m_next) / d_next;

        /* Convergent numerator p_k = a_k * p_{k-1} + p_{k-2} */
        seq_t p = (seq_t)a_next * p_prev1 + p_prev2;

        /* Shift for next iteration */
        p_prev2 = p_prev1;
        p_prev1 = p;

        m = m_next;
        d = d_next;
        a_val = a_next;
    }

    return p_prev1;
}
