/*
 * A042343  Denominators of continued fraction convergents to sqrt(698).
 * https://oeis.org/A042343
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, frac, easy
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 11, u32 n <= 24, u64 n <= 44, u128 n <= 89,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence: q₋₁ = 0, q₀ = 1, qₙ = aₙ·q_{n‑1} + q_{n‑2}.
   The partial quotients aₙ of √698 are generated by the
   continued‑fraction recurrence:  m₀ = 0, d₀ = 1,
   a₀ = ⌊√698⌋ = 26, and for k ≥ 0
       m_{k+1} = d_k·a_k – m_k,
       d_{k+1} = (698 – m_{k+1}²)/d_k,
       a_{k+1} = (a₀ + m_{k+1})/d_{k+1} (integer division).
   The function below memoises the sequence; it works for any
   seq_t and idx_t supplied by the build. */

#include <stdlib.h>
#include <stdbool.h>

static seq_t *cache      = NULL;   /* cached denominators */
static size_t cache_cap  = 0;      /* allocated capacity    */
static size_t cache_len  = 0;      /* number of cached terms */

static bool   initialized   = false;
static unsigned long long cur_m = 0;  /* m_k of current step   */
static unsigned long long cur_d = 1;  /* d_k of current step   */
static unsigned long long cur_a = 26; /* a_k of current step   */

/* Return the n‑th denominator qₙ (with a(0)=1). */
static void grow_cache(size_t need)
{
    if (cache_cap == 0) {
        cache_cap = 16;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
    }
    while (cache_cap < need) {
        cache_cap <<= 1;
        cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
    }
}

seq_t a(idx_t n)
{
    size_t idx = (size_t)n;

    /* Initialise memoisation storage and first term. */
    if (!initialized) {
        grow_cache(1);
        cache[0] = (seq_t)1;    /* q₋₁ = 0, q₀ = 1 */
        cache_len = 1;
        initialized = true;
    }

    /* Extend the cache up to the requested index. */
    while (cache_len <= idx) {
        /* Compute next m, d, a using the continued‑fraction rules. */
        unsigned long long m_next = cur_d * cur_a - cur_m;
        unsigned long long d_next = (698ULL - m_next * m_next) / cur_d;
        /* a_next uses the constant a₀ = 26, not cur_a. */
        const unsigned long long A0 = 26ULL;
        unsigned long long a_next = (A0 + m_next) / d_next;

        /* Compute the next denominator q. */
        seq_t q_prev1 = cache[cache_len - 1];
        seq_t q_prev2 = (cache_len >= 2) ? cache[cache_len - 2] : (seq_t)0;
        seq_t q = (seq_t)a_next * q_prev1 + q_prev2;

        /* Store the new term. */
        grow_cache(cache_len + 1);
        cache[cache_len] = q;
        cache_len++;

        /* Update the continued‑fraction state for the next step. */
        cur_m = m_next;
        cur_d = d_next;
        cur_a = a_next;
    }

    return cache[idx];
}
