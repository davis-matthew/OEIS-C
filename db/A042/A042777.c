/* Denominator of the nth convergent of the continued fraction of sqrt(919).
   Recurrence:  q(-2)=1, q(-1)=0,  q(n)=a(n)*q(n-1)+q(n-2)
   where a(0)=30, and for n>0 the partial quotients a(n) are generated by
   the standard continued‑fraction algorithm for sqrt(919):

   m0=0, d0=1, a0=30.
   mk+1 = dk * a(k) – mk
   dk+1 = (919 – mk+1²) / dk
   a(k+1) = floor((30 + mk+1)/dk+1)

   The function below returns q(n) for any n≥0.  It is O(n) time and
   uses only integer arithmetic. */

seq_t a(idx_t n)
{
    const seq_t D  = 919;          /* D = 919 (constant for sqrt(D))      */
    const seq_t a0 = 30;           /* a0 = floor(sqrt(919))                */

    /* Continued‑fraction state variables */
    seq_t m = 0;   /* m₀ */
    seq_t d = 1;   /* d₀ */
    seq_t a = a0;  /* a₀ for first iteration */

    /* Convergent recurrence state */
    seq_t prev2 = 1; /* q(-2) */
    seq_t prev1 = 0; /* q(-1) */

    for (idx_t i = 0; ; ++i) {
        /* Current denominator q(i) */
        seq_t q = a * prev1 + prev2;

        if (i == n)
            return q;

        /* Advance continued‑fraction state to the next partial quotient */
        m = d * a - m;
        d = (D - m * m) / d;           /* exact division guaranteed   */
        a = (a0 + m) / d;               /* floor of (a0 + m) / d       */

        /* Advance convergent recurrence state */
        prev2 = prev1;
        prev1 = q;
    }
}
