/*
 * A248500  Numbers m that are not coprime to A059995(m): floor(m/10).
 * https://oeis.org/A248500
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 108, u16 n <= 9442, u32 n <= 9442, u64 n <= 9442,
 *            u128 n <= 9442, big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A248500: numbers m such that gcd(m, floor(m/10)) > 1,
   generated by an incremental search with memoization. */
#include <stdlib.h>
#include "../utils/gcd.h"

seq_t a(idx_t n) {
    /* static cache of already computed terms */
    static seq_t *cache = NULL;
    static size_t  cache_len = 0;   /* number of terms stored */
    static size_t  cache_cap = 0;   /* allocated capacity   */
    static seq_t   next_m   = (seq_t)2; /* next candidate to test */

    if (n == 0) return (seq_t)0; /* undefined for offset 1, but safe */

    /* extend cache until we have n terms */
    while (cache_len < (size_t)n) {
        seq_t m      = next_m;
        seq_t floor_m10 = m / (seq_t)10;
        /* test the condition */
        if (gcd(m, floor_m10) > (seq_t)1) {
            /* grow cache if necessary */
            if (cache_len == cache_cap) {
                size_t new_cap = cache_cap ? cache_cap << 1 : 16;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                /* if realloc fails, we abort.  The test harness
                   will not call the function recursively, so a
                   null pointer is an acceptable failure mode. */
                if (!tmp) return (seq_t)0;
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = m;
        }
        ++next_m;  /* advance candidate for next call */
    }
    return cache[n - 1];
}
