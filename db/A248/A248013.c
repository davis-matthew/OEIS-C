/* Computing the n-th integer m such that m has no adjacent decimal digits
   whose sum is <= 9 (OEIS A248013).  The sequence is generated by a linear
   scan with a simple validity test.  */
#include <stdbool.h>
#include "../utils/has_valid_adjacency.h"

/* Return the n-th term (1‑based) of sequence A248013. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* sequence is defined for n >= 1 */

    seq_t current = (seq_t)0;
    idx_t count = 0;

    while (count < n) {
        if (has_valid_adjacency(current)) {
            ++count;
            if (count == n) return current;
        }
        current = current + (seq_t)1;
    }
    /* This point is never reached. */
    return (seq_t)0;
}
