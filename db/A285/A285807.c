/*
 * A285807  Square array A(m,n) = concatenation of { m, m+1, ..., m+n }, with
 *          m, n >= 1, read by falling antidiagonals.
 * https://oeis.org/A285807
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, tabl
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 10, u32 n <= 36, u64 n <= 44, u128 n <= 44,
 *            big any n
 * Helpers:   digit_len_seq
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include "../utils/digit_len_seq.h"
/* 
 * a(n) = concatenation of the consecutive integers from m to m+k,
 * where t is the smallest integer with t*(t+1)/2 ≥ n,
 *   m = n - (t-1)*t/2,
 *   k = t+1 - m.
 *
 * The sequence is generated by reading the infinite square array
 * A(m,k)=concat(m, m+1, …, m+k) by falling antidiagonals.
 */

static seq_t pow10_idx(idx_t e) {
    seq_t r = 1;
    for (idx_t i = 0; i < e; ++i)
        r *= 10;
    return r;
}

seq_t a(idx_t n) {
    /* find smallest t with t*(t+1)/2 >= n */
    idx_t t = 1;
    while (t * (t + 1) / 2 < n)
        ++t;

    idx_t prev = (t - 1) * t / 2;
    idx_t m = n - prev;              /* m >= 1 */
    idx_t k = t + 1 - m;              /* k >= 1 */

    seq_t res = 0;
    idx_t end = m + k;
    for (idx_t v = m; v <= end; ++v) {
        seq_t vi = (seq_t)v;
        seq_t base = pow10_idx(digit_len_seq(vi));
        res = res * base + vi;
    }
    return res;
}
