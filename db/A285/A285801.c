/* Sequence A285801: numbers having at most one odd prime factor with an odd exponent.
   The sequence is generated by a simple brute‑force search. */

#include <stdbool.h>

/* Test whether x satisfies the condition: at most one odd prime
   appears with an odd exponent in the prime factorisation of x. */
static bool is_valid(seq_t x)
{
    if (x <= (seq_t)2) return true;   /* 1 and 2 are always valid */

    seq_t n = x;
    int odd_count = 0;

    seq_t f = (seq_t)2;
    while ((f * f) <= n) {
        if ((n % f) == (seq_t)0) {
            int exp = 0;
            while ((n % f) == (seq_t)0) {
                n = n / f;
                ++exp;
            }
            if ((f % (seq_t)2) != (seq_t)0 && (exp % 2) != 0) {
                ++odd_count;
                if (odd_count > 1) return false;
            }
        }
        f = (f == (seq_t)2) ? (seq_t)3 : f + (seq_t)2;
    }

    /* Remaining factor, if any, is prime. */
    if (n > (seq_t)1) {
        if ((n % (seq_t)2) != (seq_t)0) {
            ++odd_count;
            if (odd_count > 1) return false;
        }
    }

    return true;
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* undefined for 0, safe guard */

    seq_t candidate = (seq_t)1;
    idx_t count = 0;

    while (1) {
        if (is_valid(candidate)) {
            ++count;
            if (count == n) return candidate;
        }
        candidate = candidate + (seq_t)1;
    }
}
