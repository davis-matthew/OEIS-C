/* Recurrence: a(n) is the nth symbol (1‑based) of the 0‑limiting word
   generated by the morphism 0 → 10, 1 → 0000.
   The function builds the even‑iteration words successively
   until the prefix of length n is stable (even iteration is guaranteed
   to be prefix‑stable). */

#include <stdlib.h>

static idx_t _level = 0;   /* current iteration level (even after each call) */
static seq_t * _w = NULL; /* current word */
static idx_t  _len  = 0;  /* length of _w   */
static idx_t  _zeros = 0;/* number of zeros in _w  */
static idx_t  _ones  = 0;/* number of ones  in _w  */

seq_t a(idx_t n)
{
    /* The sequence is 1‑based; ignore n == 0 */
    if (n == 0)
        return (seq_t)0;

    /* Initialise on first call */
    if (_w == NULL) {
        _w = (seq_t *)malloc(sizeof(seq_t));
        if (_w == NULL) return (seq_t)0; /* allocation failure */
        _w[0]  = (seq_t)0;
        _len   = 1;
        _zeros = 1;
        _ones  = 0;
        _level = 0; /* even */
    }

    /* Expand until the word contains position n
       and is at an even iteration (prefix‑stable). */
    while (_len < n || (_level % 2)) {
        /* Compute length of new word */
        idx_t new_len = _zeros * 2 + _ones * 4;
        seq_t *new_w = (seq_t *)malloc(sizeof(seq_t) * new_len);
        if (new_w == NULL)
            return (seq_t)0; /* allocation failure */

        idx_t pos = 0;          /* write position in new_w */
        idx_t new_zeros = 0;
        idx_t new_ones  = 0;

        /* Expand each symbol of the current word */
        for (idx_t i = 0; i < _len; ++i) {
            if (_w[i] == 0) {          /* 0 → 10 */
                new_w[pos++] = (seq_t)1;
                new_w[pos++] = (seq_t)0;
                ++new_ones;
                ++new_zeros;
            } else {                    /* 1 → 0000 */
                new_w[pos++] = (seq_t)0;
                new_w[pos++] = (seq_t)0;
                new_w[pos++] = (seq_t)0;
                new_w[pos++] = (seq_t)0;
                new_zeros += 4;
            }
        }

        /* Free old word and update state */
        free(_w);
        _w = new_w;
        _len = new_len;
        _zeros = new_zeros;
        _ones  = new_ones;
        ++_level;                      /* next iteration level */
    }

    /* Position n is ready in the stable even word */
    return _w[n - 1];
}
