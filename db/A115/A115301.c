/*
 * A115301  Permutations of decimal digits 1-9 giving three 3-digit primes.
 * https://oeis.org/A115301
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  fini, full, nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 816, u64 n <= 816, u128 n <= 816,
 *            big any n
 * Helpers:   is_prime_small
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements OEIS A115301:
   Permutations of the digits 1-9 such that each consecutive 3‑digit block
   is a prime.  The sequence is generated by enumerating all 1‑9
   permutations in lexicographic order and filtering for the prime
   condition.  The full list of 816 terms is built once on first call
   and cached for subsequent accesses. */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include "../utils/is_prime_small.h"   /* bool is_prime_small(seq_t) */

/* Forward declarations */
static void recurse(int pos);

/* Global cache for the sequence values */
static seq_t *seq_cache   = NULL;
static size_t seq_cap     = 0;    /* capacity of seq_cache */
static size_t seq_used    = 0;    /* number of terms stored */

/* Temporary data used during recursion */
static int  perm_digits[9];
static bool used_digit[10];

/* Recursively generate permutations in lexicographic order and
   store those that satisfy the prime condition. */
static void recurse(int pos)
{
    if (pos == 9) {                          /* full permutation built */
        int g3 = perm_digits[6]*100
              + perm_digits[7]*10
              + perm_digits[8];
        if (!is_prime_small(g3))
            return;                         /* last block not prime */

        /* Build the 9‑digit number */
        seq_t val = 0;
        for (int i = 0; i < 9; ++i)
            val = val*10 + perm_digits[i];

        /* Ensure cache has space and store value */
        if (seq_used == seq_cap) {
            size_t new_cap = seq_cap ? seq_cap * 2 : 16;
            seq_cache = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
            seq_cap = new_cap;
        }
        seq_cache[seq_used++] = val;
        return;
    }

    for (int d = 1; d <= 9; ++d) {            /* try digits in ascending order */
        if (!used_digit[d]) {
            used_digit[d] = true;
            perm_digits[pos] = d;

            /* Early pruning: check the first two 3‑digit blocks
               as soon as they are complete. */
            if (pos == 2) {                  /* first block complete */
                int g1 = perm_digits[0]*100
                       + perm_digits[1]*10
                       + perm_digits[2];
                if (!is_prime_small(g1)) {
                    used_digit[d] = false;
                    continue;
                }
            }
            if (pos == 5) {                  /* second block complete */
                int g2 = perm_digits[3]*100
                       + perm_digits[4]*10
                       + perm_digits[5];
                if (!is_prime_small(g2)) {
                    used_digit[d] = false;
                    continue;
                }
            }

            recurse(pos + 1);
            used_digit[d] = false;
        }
    }
}

/* Build the full sequence the first time it is requested. */
static void build_sequence(void)
{
    /* Reset state */
    for (int i = 1; i <= 9; ++i)
        used_digit[i] = false;
    seq_cache = NULL;
    seq_cap   = 0;
    seq_used  = 0;

    /* Generate all valid permutations */
    recurse(0);
}

seq_t a(idx_t n)
{
    /* Lazy evaluation: build sequence on first call */
    static bool built = false;
    if (!built) {
        build_sequence();
        built = true;
    }

    /* Return the n‑th term (1‑based).  Undefined for n > seq_used. */
    if (n == 0 || n > seq_used)
        return 0;
    return seq_cache[n - 1];
}
