/*
 * A279428  Numbers k such that k^2 has an odd number of digits and the middle
 *          digit is 8.
 * https://oeis.org/A279428
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 18, u32 n <= 2509, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   digit_len, pow10, seq_alloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the nth element (1‑based) of OEIS A279428:
   the numbers k such that k² has an odd number of decimal digits and
   the middle digit of k² is 8.  The sequence is generated by brute‑force
   search; the result is cached so that multiple calls are O(1) after a
   one‑time build.  */

#include <stddef.h>
#include <stdint.h>
#include "../utils/seq_alloc.h"
#include "../utils/pow10.h"
#include "../utils/digit_len.h"

#define MAX_TERMS 20000  /* enough for n up to about 10 000 */

static seq_t *terms   = NULL;   /* cached terms          */
static size_t terms_cnt = 0;    /* number of stored terms*/
static idx_t next_k     = 1;    /* next integer to test  */

seq_t a(idx_t n)
{
    /* Undefined for n < 1 – return 0 for safety. */
    if (n == 0) return (seq_t)0;

    /* Allocate the cache once. */
    if (!terms) {
        terms = seq_alloc(MAX_TERMS);
        if (!terms) return (seq_t)0; /* allocation failed */
    }

    /* Build cache until we have at least n terms. */
    while (terms_cnt < (size_t)n) {
        seq_t k   = (seq_t)next_k;
        seq_t sq  = k * k;
        int len   = digit_len(sq);

        if (len & 1) { /* odd number of digits */
            /* Determine the base 10^((len-1)/2) to isolate the middle digit. */
            idx_t exp  = (idx_t)((len - 1) / 2);
            seq_t base = pow10(exp);
            seq_t div  = sq / base;               /* drop the low (len-1)/2 digits */
            if ((div % (seq_t)10) == (seq_t)8) {  /* middle digit is 8 */
                if (terms_cnt < MAX_TERMS) {
                    terms[terms_cnt++] = k;
                }
            }
        }
        ++next_k;
    }

    return terms[n - 1];
}
