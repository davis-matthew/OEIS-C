/*  A371169:  Positive integers with at least as many prime factors (Ω)
 *  as distinct divisors of prime indices.
 *  The sequence is generated by scanning the integers in order and
 *  selecting those that satisfy the condition. */

/*  Standard headers  */
#include <stdbool.h>
#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>

/*  Limit for prime sieve  */
#define PRIME_LIMIT   2000000      /* enough for all integers we generate */
#define MAX_DIVISOR   200000       /* maximum possible divisor value of an index */

/*  Global storage for primes  */
static uint64_t *prime_list = NULL;
static size_t    prime_cnt   = 0;

/*  Simple sieve of Eratosthenes -- generates all primes <= PRIME_LIMIT  */
static void generate_primes(void)
{
    bool *is_comp = (bool *)calloc(PRIME_LIMIT + 1, sizeof(bool));
    if (!is_comp) exit(1);

    /* approximate number of primes for allocation */
    size_t alloc = PRIME_LIMIT / 10 + 10;
    uint64_t *pr = (uint64_t *)malloc(alloc * sizeof(uint64_t));
    size_t pc = 0;

    for (uint64_t i = 2; i <= PRIME_LIMIT; ++i) {
        if (!is_comp[i]) {
            pr[pc++] = i;
            if (i <= PRIME_LIMIT / i) {
                for (uint64_t j = i * i; j <= PRIME_LIMIT; j += i)
                    is_comp[j] = true;
            }
        }
    }
    pr = (uint64_t *)realloc(pr, pc * sizeof(uint64_t));
    prime_list = pr;
    prime_cnt   = pc;

    free(is_comp);
}

/*  Factorisation of n into prime factors and exponents.
 *  primes[] must contain all primes up to at least sqrt(n).          */
static void factor_u64(uint64_t n,
                       const uint64_t *primes,
                       size_t        primes_cnt,
                       uint64_t      *out_pr,
                       uint64_t      *out_exp,
                       size_t       *out_cnt)
{
    size_t cnt = 0;
    for (size_t i = 0; i < primes_cnt && primes[i] * primes[i] <= n; ++i) {
        if (n % primes[i] == 0) {
            uint64_t e = 0;
            do {
                n /= primes[i];
                ++e;
            } while (n % primes[i] == 0);
            out_pr[cnt]  = primes[i];
            out_exp[cnt] = e;
            ++cnt;
        }
    }
    if (n > 1) {
        out_pr[cnt]  = n;
        out_exp[cnt] = 1;
        ++cnt;
    }
    *out_cnt = cnt;
}

/*  Return 1‑based index of prime p (0 if p not found). */
static uint32_t prime_index(uint64_t p)
{
    size_t lo = 0, hi = prime_cnt;
    while (lo < hi) {
        size_t mid = (lo + hi) >> 1;
        if (prime_list[mid] == p) return (uint32_t)(mid + 1);
        if (prime_list[mid] < p)  lo = mid + 1;
        else                      hi = mid;
    }
    return 0;   /* should never happen for primes in our range */
}

/*  Test whether integer x satisfies the sequence condition. */
static bool satisfies(uint64_t x)
{
    /*  Factorise x once  */
    uint64_t primes_buf[64], exps_buf[64];
    size_t   pf_cnt;
    factor_u64(x, prime_list, prime_cnt, primes_buf, exps_buf, &pf_cnt);

    /*  Compute Omega(x) = sum of exponents  */
    seq_t omega = 0;
    for (size_t i = 0; i < pf_cnt; ++i) omega += exps_buf[i];

    /*  Collect distinct divisors of all prime indices  */
    static unsigned char visited[MAX_DIVISOR + 1];
    static uint32_t visited_list[MAX_DIVISOR + 1];
    size_t visitlen = 0;

    for (size_t i = 0; i < pf_cnt; ++i) {
        uint32_t idx = prime_index(primes_buf[i]);   /* 1‑based index  */
        if (idx == 0) continue;                      /* safety */

        /*  Factorise the index itself  */
        uint64_t idx_pr[32], idx_ex[32];
        size_t   idx_cnt;
        factor_u64(idx, prime_list, prime_cnt, idx_pr, idx_ex, &idx_cnt);

        /*  Generate all divisors of idx  */
        uint32_t divs[512];
        size_t   divc = 1;        /* start with divisor 1 */
        divs[0] = 1;
        for (size_t j = 0; j < idx_cnt; ++j) {
            uint64_t base = idx_pr[j];
            uint64_t pow  = 1;
            size_t   prev = divc;
            for (uint64_t k = 1; k <= idx_ex[j]; ++k) {
                pow *= base;
                for (size_t t = 0; t < prev; ++t)
                    divs[divc++] = divs[t] * (uint32_t)pow;
            }
        }

        /*  Mark each divisor  */
        for (size_t t = 0; t < divc; ++t) {
            uint32_t d = divs[t];
            if (d <= MAX_DIVISOR && !visited[d]) {
                visited[d] = 1;
                visited_list[visitlen++] = d;
            }
        }
    }

    seq_t distinct = (seq_t)visitlen;

    /*  Reset marks for next call  */
    for (size_t i = 0; i < visitlen; ++i) visited[visited_list[i]] = 0;

    return omega >= distinct;
}

/*  Main sequence function  */
seq_t a(idx_t n)
{
    /*  Initialise primes only once  */
    static bool primes_ready = false;
    if (!primes_ready) {
        generate_primes();
        primes_ready = true;
    }

    idx_t count = 0;
    uint64_t x   = 1;

    while (count < n) {
        if (satisfies(x)) ++count;
        ++x;
    }
    return (seq_t)(x - 1);   /* x has been incremented past the nth term */
}
