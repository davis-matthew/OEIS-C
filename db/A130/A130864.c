/* Computes the nth term of A130864 (Numbers x such that x + reverse(x)
   is a non‑palindromic prime).  The sequence is generated by
   brute‑force search with memoization. */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdint.h>
#include "../utils/grow_seq_array.h"
#include "../utils/is_prime_small.h"

/* Reverse the decimal representation of v. */
static seq_t reverse_decimal(seq_t v)
{
    seq_t rev = 0;
    while (v > 0) {
        seq_t d = v % 10;
        rev = rev * 10 + d;
        v   = v / 10;
    }
    return rev;
}

/* Test whether x is a palindrome in base 10. */
static bool is_palindrome(seq_t x)
{
    return x == reverse_decimal(x);
}

/* Return the nth term (0‑based) of the sequence. */
seq_t a(idx_t n)
{
    static seq_t *cache    = NULL;   /* array of found terms   */
    static size_t cache_len = 0;     /* number of cached terms */
    static size_t cache_cap = 0;     /* allocated capacity    */
    static seq_t last_x  = 0;        /* last x that satisfied the property */

    /* If the requested value is already known, return it immediately. */
    if (n < cache_len)
        return cache[n];

    /* Ensure we have enough space to store at least (n+1) elements. */
    if (cache_len > cache_cap) {
        /* This should not happen, but guard against pathological usage. */
        cache_cap = cache_len * 2;
        grow_seq_array(&cache, &cache_cap, cache_len);
    }
    if (cache_cap < (size_t)n + 1) {
        grow_seq_array(&cache, &cache_cap, (size_t)n + 1);
    }

    /* Search starting from the first integer after the last known x. */
    seq_t x = last_x ? last_x + 1 : 1;
    while (cache_len <= (size_t)n) {
        seq_t revx = reverse_decimal(x);
        seq_t sum  = x + revx;
        if (!is_palindrome(sum) && is_prime_small(sum)) {
            /* Add the found number to the cache. */
            cache[cache_len++] = x;
            last_x = x;
        }
        ++x;
    }

    return cache[n];
}
