/*
 * Sequence A091783: Numbers with digits in nondecreasing order such that
 * the sum of the reciprocals of the digits is 1.  The set of solutions is
 * finite; they are generated by a depth‑first search over the multiset
 * {1,2,…,9}, keeping the current sum of 1/di in common denominator 2520.
 * The found numbers are sorted once and then indexed from 1.
 *
 * A(idx_t n) returns the n‑th smallest such number; if n exceeds the
 * cardinality the function returns 0.
 */
#include <stdlib.h>
#include <stdint.h> /* for uint64_t */

/* Coefficients for 2520 = lcm(1..9) stored as 2520 / d. */
static const int w[10] = { 0, 2520, 1260,  840,  630,  504,  420,
                           360, 315, 280 };

/* Dynamic array of found numbers. */
static seq_t *solutions = NULL;   /* array of seq_t values */
static size_t sol_len = 0;        /* current number of solutions */
static size_t sol_cap = 0;        /* allocated capacity */
static int built = 0;             /* flag indicating if the array has been built */

/* Append a new solution, growing the array if necessary. */
static void add_solution(seq_t val)
{
    if (sol_len >= sol_cap) {
        size_t new_cap = sol_cap == 0 ? 16 : sol_cap * 2;
        seq_t *tmp = (seq_t *)realloc(solutions, new_cap * sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);   /* allocation failure */
        solutions = tmp;
        sol_cap = new_cap;
    }
    solutions[sol_len++] = val;
}

/* Depth‑first search over nondecreasing digit sequences. */
static void dfs(int start, int sum, seq_t cur)
{
    for (int d = start; d <= 9; ++d) {
        int new_sum = sum + w[d];
        if (new_sum > 2520) continue;
        seq_t next = cur * 10 + d;
        if (new_sum == 2520) {
            add_solution(next);
        } else {
            dfs(d, new_sum, next);
        }
    }
}

/* Comparison function for qsort. */
static int cmp_seq(const void *a, const void *b)
{
    const seq_t *sa = (const seq_t *)a;
    const seq_t *sb = (const seq_t *)b;
    if (*sa < *sb) return -1;
    if (*sa > *sb) return 1;
    return 0;
}

/* Return the n‑th term of the sequence. */
seq_t a(idx_t n)
{
    if (!built) {
        /* Generate all solutions once. */
        dfs(1, 0, 0);
        qsort(solutions, sol_len, sizeof(seq_t), cmp_seq);
        built = 1;
    }
    if (n == 0) return 0;
    if ((idx_t)n <= sol_len) {
        return solutions[(idx_t)n - 1];
    }
    return 0; /* out of range */
}
