/*
 * A091013  Numbers having more than one divisor d such that for some x also
 *          d-x and d+x are divisors.
 * https://oeis.org/A091013
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 56, u16 n <= 56, u32 n <= 56, u64 n <= 56, u128 n <= 56,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A091013
   Numbers having more than one divisor d such that for some x also
   d-x and d+x are divisors.  The sequence is generated by testing
   integers sequentially and storing those that satisfy the property.
   The function a(idx_t n) returns the nth term (offset 1). */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

/* static cache for computed terms – we will pre‑allocate a
   sufficient number of slots to avoid any dynamic allocation that
   would fail for the big‑integer build */
#define MAX_CACHE 20000          /* enough for n up to ~10 000 */
static seq_t seq_cache[MAX_CACHE];
static size_t cache_len = 0;

/* static buffer for divisors during factorisation – 8 192 is
   comfortably larger than the maximum number of divisors of a 64‑bit
   integer (5040). */
#define MAX_DIVS 8192
static uint64_t divisors[MAX_DIVS];
static size_t div_len;

/* comparison function for qsort/bsearch on uint64_t */
static int cmp_uint64(const void *a, const void *b) {
    uint64_t x = *(const uint64_t *)a;
    uint64_t y = *(const uint64_t *)b;
    return (x > y) - (x < y);
}

/* recursive generation of all divisors from prime factorisation */
static void gen_divs_rec(uint64_t cur, const uint64_t *pr, const uint8_t *ex,
                         size_t pcnt, size_t idx) {
    if (idx == pcnt) {
        divisors[div_len++] = cur;
        return;
    }
    uint64_t p = pr[idx];
    uint64_t power = 1;
    for (uint8_t e = 0; e <= ex[idx]; ++e) {
        gen_divs_rec(cur * power, pr, ex, pcnt, idx + 1);
        power *= p;
    }
}

/* test whether a given 64‑bit integer has the A091013 property */
static bool in_sequence(uint64_t n) {
    /* factorise n */
    uint64_t primes[16];
    uint8_t exps[16];
    size_t pcnt = 0;

    uint64_t tmp = n;
    for (uint64_t p = 2; p * p <= tmp; ++p) {
        if (tmp % p == 0) {
            uint8_t e = 0;
            while (tmp % p == 0) {
                tmp /= p;
                ++e;
            }
            primes[pcnt] = p;
            exps[pcnt]  = e;
            ++pcnt;
        }
    }
    if (tmp > 1) {
        primes[pcnt] = tmp;
        exps[pcnt]  = 1;
        ++pcnt;
    }

    /* generate all divisors */
    div_len = 0;
    gen_divs_rec(1, primes, exps, pcnt, 0);
    qsort(divisors, div_len, sizeof(uint64_t), cmp_uint64);

    /* look for distinct divisors d with a symmetric divisor pair */
    size_t d_seen = 0;
    uint64_t d_list[32];              /* holds at most 32 d's for a 64‑bit n */
    for (size_t i = 0; i < div_len; ++i) {
        for (size_t j = i + 1; j < div_len; ++j) {
            uint64_t sum = divisors[i] + divisors[j];
            if ((sum & 1ULL) == 0) {
                uint64_t d = sum >> 1;
                /* d must divide n – test by binary search */
                if (bsearch(&d, divisors, div_len, sizeof(uint64_t), cmp_uint64)) {
                    /* count each d only once */
                    bool seen = false;
                    for (size_t k = 0; k < d_seen; ++k)
                        if (d_list[k] == d) { seen = true; break; }
                    if (!seen) {
                        d_list[d_seen++] = d;
                        if (d_seen >= 2)   /* enough distinct d's */
                            return true;
                    }
                }
            }
        }
    }
    return false;
}

/* ------------------------------------------------------------------ */
/*  Main sequence function                                           */
/* ------------------------------------------------------------------ */
seq_t a(idx_t n) {
    if (n == 0) return (seq_t)0;        /* offset starts at 1 */

    /* extend the cache until it contains at least n terms */
    while (cache_len < n) {
        /* start searching from the next integer after the last cached */
        uint64_t start = (cache_len == 0) ? 12 :
                         (uint64_t)seq_cache[cache_len - 1] + 1;

        for (uint64_t cand = start; ; ++cand) {
            if (in_sequence(cand)) {
                seq_cache[cache_len++] = (seq_t)cand;
                break;
            }
        }
    }
    return seq_cache[n - 1];
}
