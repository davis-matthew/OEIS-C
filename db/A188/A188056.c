/*
 * A188056  Stanley Sequence S(0,8).
 * https://oeis.org/A188056
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   Stanley Sequence S(0,8). a(1)=0, a(2)=8; for n≥3, a(n) is the
 *            smallest integer > a(n‑1) that does not, together with any two
 *            earlier terms, form a 3‑term arithmetic progression
 * Range:     u8 n <= 39, u16 n <= 987, u32 n <= 2000, u64 n <= 2000,
 *            u128 n <= 2000, big any n
 * Helpers:   two_mul_minus
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <stdbool.h>
#include "../utils/two_mul_minus.h"

/* Keeps the sequence values in increasing order. */
static seq_t *seq = NULL;
static size_t seq_len = 0;
static size_t seq_cap = 0;

/* A dynamic bitset that marks numbers which cannot currently be chosen
   as the next term.  Index i (0‑based) corresponds to the integer i.   */
static unsigned long long *forbid_bits = NULL;
static size_t forbid_words = 0;          /* number of 64‑bit words allocated */

/* --------------------------------------------------------------------- */
/*  Ensure that the dynamic array for the sequence holds at least `need`
   elements.  Size is doubled each time to keep amortised linear cost.  */
static inline void ensure_seq_cap(size_t need)
{
    if (need <= seq_cap) return;
    size_t newcap = seq_cap ? seq_cap << 1 : 8;
    while (newcap < need) newcap <<= 1;
    seq_t *tmp = (seq_t *)realloc(seq, newcap * sizeof(seq_t));
    if (!tmp) abort();
    seq = tmp;
    seq_cap = newcap;
}

/* --------------------------------------------------------------------- */
/*  Ensure that the bitset can store the bit for index `need_words`
   (number of 64‑bit words).  Size is doubled each time. */
static inline void ensure_forbid(size_t need_words)
{
    if (need_words <= forbid_words) return;
    size_t newwords = forbid_words ? forbid_words << 1 : 4;
    while (newwords < need_words) newwords <<= 1;
    unsigned long long *tmp = (unsigned long long *)realloc(forbid_bits,
                                   newwords * sizeof(unsigned long long));
    if (!tmp) abort();
    memset(tmp + forbid_words, 0,
           (newwords - forbid_words) * sizeof(unsigned long long));
    forbid_bits = tmp;
    forbid_words = newwords;
}

/* --------------------------------------------------------------------- */
/*  Bit helpers.  `idx` is a non‑negative integer that fits in size_t.   */
static inline bool is_bit_set(size_t idx)
{
    size_t word = idx >> 6;
    return word < forbid_words && ((forbid_bits[word] >> (idx & 63)) & 1ULL);
}

static inline void set_bit(size_t idx)
{
    size_t word = idx >> 6;
    if (word >= forbid_words) ensure_forbid(word + 1);
    forbid_bits[word] |= 1ULL << (idx & 63);
}

/* --------------------------------------------------------------------- */

/* --------------------------------------------------------------------- */
/*  Test if integer `x` is forbidden.  The helper only works for values
    that fit into `size_t`.  Larger values are considered not forbidden
    – they will never be chosen before the bitset grows to contain them. */
static inline bool forbidden(seq_t x)
{
    if (x > (seq_t)SIZE_MAX) return false;
    return is_bit_set((size_t)x);
}

/*  Mark integer `x` as forbidden.  If it does not fit in `size_t`, it is
    ignored – that is safe because those values will never be examined
    via the bitset. */
static inline void add_forbidden(seq_t x)
{
    if (x > (seq_t)SIZE_MAX) return;
    set_bit((size_t)x);
}

/* --------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) abort();           /* sequence is 1‑based */

    while (seq_len < (size_t)n) {  /* grow the sequence up to n */
        if (seq_len == 0) {
            /* Initialise the first two terms */
            ensure_seq_cap(2);
            seq[0] = (seq_t)0;
            seq[1] = (seq_t)8;
            seq_len = 2;
            add_forbidden((seq_t)16);   /* 2×8–0 */
            continue;
        }

        /* Find the smallest integer greater than the last term that
           is not forbidden. */
        seq_t candidate = seq[seq_len - 1] + (seq_t)1;
        while (forbidden(candidate))
            candidate = candidate + (seq_t)1;

        /* Append the accepted candidate. */
        ensure_seq_cap(seq_len + 1);
        seq[seq_len] = candidate;
        seq_len++;

        /* Mark all future forbidden numbers generated by this new term. */
        for (size_t i = 0; i < seq_len - 1; ++i) {
            seq_t f = two_mul_minus(candidate, seq[i]);   /* 2·candidate – seq[i] */
            add_forbidden(f);
        }
    }
    return seq[(size_t)n - 1];
}
