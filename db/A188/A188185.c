/*
 * A188185  Number of strictly increasing arrangements of 7 numbers in
 *          -(n+5)..(n+5) with sum zero.
 * https://oeis.org/A188185
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = number of strictly increasing 7‑tuples in [-(n+5) ,
 *            (n+5)] with sum 0. The first 22 terms are computed by brute
 *            force DP and thereafter the empirical linear recurrence (order
 *            22) is used
 * Range:     u8 n <= 1, u16 n <= 10, u32 n <= 89, u64 n <= 200, u128 n <= 200,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include <stdlib.h>

/* ---------------------------------------------------------------------- */
/*  Base terms for n = 1 .. 22 are generated by dynamic programming.     */
/*  We keep a sliding DP over the numbers in the interval.                */
/* ---------------------------------------------------------------------- */

#define MAX_N   27                     /* max N needed for the first 22 terms */
#define OFF     (7 * MAX_N)            /* maximum absolute sum for N=27      */
#define SZ      (2 * OFF + 1)          /* DP array size                       */

static seq_t base_tbl[22];             /* a(1) .. a(22)                       */
static int  base_done = 0;

/* add a single integer value to the DP */
static void add_value(seq_t dp[8][SZ], int val)
{
    for (int t = 7; t >= 1; --t) {
        for (int s = 0; s < SZ; ++s) {
            seq_t prev = dp[t-1][s];
            if (!prev) continue;
            int ns = s + val;             /* val ∈ [‑27,27], stays inside bounds */
            if (ns < 0 || ns >= SZ) continue;
            dp[t][ns] += prev;
        }
    }
}

/* Compute the first 22 terms and store in base_tbl */
static void compute_base(void)
{
    seq_t dp[8][SZ] = {0};
    dp[0][OFF] = 1;                      /* empty set has sum 0 */

    /* n = 1  ->  N = 6, numbers ‑6 … 6 */
    for (int val = -6; val <= 6; ++val)
        add_value(dp, val);
    base_tbl[0] = dp[7][OFF];             /* a(1) */

    /* n = 2 .. 22  ->  extend interval by ±(n+5) each step */
    for (int n = 2; n <= 22; ++n) {
        int N = n + 5;
        add_value(dp, -N);
        add_value(dp, +N);
        base_tbl[n-1] = dp[7][OFF];
    }
    base_done = 1;
}

/* ---------------------------------------------------------------------- */
/*  Main sequence function                                               */
/* ---------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (!base_done)
        compute_base();

    if (n <= 22)
        return base_tbl[n-1];

    /* sliding buffer for the last 22 values, buffer[0] = a(i-1) */
    seq_t buf[22];
    for (int j = 0; j < 22; ++j)
        buf[j] = base_tbl[21-j];          /* buffer[0] = a(22) for i=23 */

    for (idx_t i = 23; i <= n; ++i) {
        __int128 term =  2*(__int128)buf[0]
                       -   (__int128)buf[2]
                       -   (__int128)buf[4]
                       +   (__int128)buf[5]
                       - 2*(__int128)buf[6]
                       + 2*(__int128)buf[7]
                       +   (__int128)buf[8]
                       -   (__int128)buf[12]
                       - 2*(__int128)buf[13]
                       + 2*(__int128)buf[14]
                       -   (__int128)buf[15]
                       +   (__int128)buf[16]
                       +   (__int128)buf[18]
                       - 2*(__int128)buf[20]
                       +   (__int128)buf[21];
        seq_t val = (seq_t)term;          /* sequence values are non‑negative */

        /* shift buffer */
        for (int j = 21; j > 0; --j)
            buf[j] = buf[j-1];
        buf[0] = val;
    }

    return buf[0];
}
