/* OEIS A146077:  Numbers k such that gcd(k, 2^k-2) != least prime factor of k.
   The sequence is generated by brute‑force search and memoisation.
*/

#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/gcd.h"
#include "../utils/powmod.h"
#include "../utils/mem.h"

/* --- dynamic array helpers ------------------------------------------- */
static void grow_seq(seq_t **arr, size_t *cap, size_t need)
{
    if (*cap < need) {
        size_t new_cap = (*cap == 0) ? 64 : (*cap << 1);
        while (new_cap < need) new_cap <<= 1;
        seq_t *tmp = mem_resize(seq_t, *arr, (new_cap * sizeof(**arr)) / sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);
        *arr = tmp;
        *cap = new_cap;
    }
}

static uint64_t lpf_uint64(uint64_t n)
{
    if (n <= 3ULL) return n;
    if (n % 2ULL == 0ULL) return 2ULL;
    for (uint64_t p = 3ULL; p <= n / p; p += 2ULL)
        if (n % p == 0ULL) return p;
    return n;
}

static int satisfies(uint64_t k)
{
    if (k < 2ULL) return 0;            /* k=1 cannot satisfy */
    seq_t k_seq = (seq_t)k;

    /* (2^k – 2) mod k */
    seq_t pow_mod = powmod((seq_t)2, k, k_seq);   /* 2^k mod k */
    seq_t diff = (pow_mod >= (seq_t)2) ? pow_mod - (seq_t)2
                                       : pow_mod + k_seq - (seq_t)2;

    seq_t g = gcd(k_seq, diff);
    uint64_t lpf = lpf_uint64(k);
    return g != (seq_t)lpf;
}

/* Memoised generation of the sequence. */
seq_t a(idx_t n)
{
    static seq_t *terms = NULL;
    static size_t size   = 0;
    static size_t cap    = 0;
    static uint64_t next_k = 1ULL;

    while (size < n)
    {
        while (!satisfies(next_k))
            ++next_k;

        if (size >= cap)
            grow_seq(&terms, &cap, size + 1);

        terms[size++] = (seq_t)next_k;
        ++next_k;
    }

    return terms[n - 1];
}
