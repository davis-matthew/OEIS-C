/* Sequence A146166 – odd semiprimes with distinct prime factors
   (the product of two distinct odd primes).
   The sequence is generated by sieving smallest prime factors (SPF)
   and extracting numbers of the form p*q where p<q are odd primes.   */

#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include "../utils/mem.h"

/* Rebuild the smallest prime factor array up to 'limit'.
   The array is indexed from 0..limit, unused entries at index 0. */
static void rebuild_spf(uint32_t **p_spf, size_t *spv_limit, size_t limit)
{
    if (*p_spf) free(*p_spf);
    *p_spf = (uint32_t *)malloc((limit + 1) * sizeof(uint32_t));
    memset(*p_spf, 0, (limit + 1) * sizeof(uint32_t));

    for (size_t i = 2; i <= limit; ++i) {
        if (!(*p_spf)[i]) {
            (*p_spf)[i] = (uint32_t)i;
            if ((uint64_t)i * i <= limit) {
                for (size_t j = i * i; j <= limit; j += i)
                    if (!(*p_spf)[j]) (*p_spf)[j] = (uint32_t)i;
            }
        }
    }
    *spv_limit = limit;
}

/* Helper to grow the cache dynamically */
static void grow_cache(seq_t **p_cache, size_t *cap, size_t needed)
{
    size_t new_cap = *cap ? (*cap) << 1 : 16;
    while (new_cap < needed) new_cap <<= 1;
    seq_t *tmp = mem_resize(seq_t, *p_cache, new_cap);
    *p_cache = tmp;
    *cap = new_cap;
}

/* Global state for memoization and sieving */
static seq_t  *cache      = NULL;   /* cached sequence values   */
static size_t  cache_cap  = 0;
static size_t  cache_size = 0;      /* number of cached terms    */

static uint32_t *spf          = NULL;   /* smallest prime factor array */
static size_t    spf_limit    = 0;      /* current limit of spf array */
static size_t    last_checked = 3;      /* next odd index to test     */

/* Ensure that the cache contains at least 'n' terms (n >= 1). */
static void ensure_terms(idx_t n)
{
    size_t need = (size_t)n;
    while (cache_size < need) {
        /* If spf array is not yet initialized, start with a small size. */
        if (spf_limit == 0) {
            rebuild_spf(&spf, &spf_limit, 100); /* minimal starting limit */
            last_checked = 3;
        }
        /* Scan odd numbers from the last checked position up to spf_limit. */
        for (size_t i = last_checked; i <= spf_limit; i += 2) {
            uint32_t p = spf[i];
            if (p == 0) continue;                 /* i <= 1, not possible here */
            size_t q = i / p;
            if (p != q && spf[q] == (uint32_t)q) { /* two distinct odd primes */
                grow_cache(&cache, &cache_cap, cache_size + 1);
                cache[cache_size++] = (seq_t)i;
                if (cache_size >= need) {
                    last_checked = i + 2;
                    return;
                }
            }
        }
        /* Not enough terms yet – increase the sieve limit and rebuild */
        size_t new_limit = spf_limit ? spf_limit * 2 : 200;
        if (new_limit < spf_limit + 100) new_limit = spf_limit + 100; /* safety */
        rebuild_spf(&spf, &spf_limit, new_limit);
        /* continue scanning from where we left off (last_checked) */
    }
}

/* The required function definition for OEIS sequence A146166 */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* undefined, but safety */
    ensure_terms(n);
    return cache[(size_t)(n - 1)];
}
