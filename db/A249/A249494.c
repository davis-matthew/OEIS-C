/*
 * A249494  Lexicographically earliest permutation of the positive integers
 *          such that the parity of the first digit of a(n+1) equals that of
 *          a(n)'s last digit.
 * https://oeis.org/A249494
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 91, u16 n <= 91, u32 n <= 91, u64 n <= 91, u128 n <= 91,
 *            big any n
 * Helpers:   seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Lexicographically earliest permutation of the positive integers
   such that the parity of the first digit of a(n+1) equals the
   parity of the last digit of a(n).  The sequence is generated by
   starting with a(1)=1 and, for each subsequent term, choosing the
   smallest unused positive integer whose first‑digit parity matches
   the required parity. */

#include <stdlib.h>
#include <string.h>
#include <stdbool.h>
#include "../utils/seq_realloc.h"

seq_t a(idx_t n)
{
    /* Static state retained between calls */
    static idx_t generated   = 0;   /* number of terms already produced   */
    static seq_t *cache      = NULL;/* array of already computed terms     */
    static size_t cache_cap  = 0;   /* capacity of cache array             */

    /* Bitmap of used numbers: used[i] == 1 means integer i has been used */
    static unsigned char *used   = NULL;
    static idx_t used_cap        = 0;   /* array size (valid indices 0..used_cap-1) */

    /* Pointers to the next candidate numbers for each parity of first digit */
    static idx_t odd_ptr   = 1;   /* next integer to test for odd first digit */
    static idx_t even_ptr = 2;   /* next integer to test for even first digit */

    /* Grow cache array as needed (seq_realloc may be a no‑op if reallocation fails) */
    if (generated >= cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 16;
        while (new_cap <= (size_t)generated) new_cap *= 2;
        seq_t *tmp = seq_realloc(cache, cache_cap, new_cap);
        if (!tmp) abort();
        cache     = tmp;
        cache_cap = new_cap;
    }

    /* Generate terms up to position n (1‑based). */
    while (generated < n) {
        /* ---------- First term a(1) = 1 -------------------------------- */
        if (generated == 0) {
            cache[0] = (seq_t)1;
            /* Ensure the bitmap covers value 1 */
            if (used_cap <= 1) {
                size_t new_cap = used_cap ? used_cap * 2 : 1024;
                while (new_cap <= 1) new_cap *= 2;
                unsigned char *tmp = (unsigned char*)realloc(used, new_cap);
                if (!tmp) abort();
                if (used_cap < new_cap)
                    memset(tmp + used_cap, 0, new_cap - used_cap);
                used = tmp;
                used_cap = new_cap;
            }
            used[1] = 1;
            generated = 1;
            continue;
        }

        /* ---------- Determine required parity from previous term ----- */
        seq_t prev = cache[generated - 1];
        /* Parity of last digit of prev */
        bool need_odd = ((prev % (seq_t)10) & 1) != 0;

        /* ---------- Find the smallest unused integer with required first‑digit parity */
        idx_t *ptr = need_odd ? &odd_ptr : &even_ptr;
        while (1) {
            idx_t candidate = *ptr;

            /* Grow bitmap if necessary */
            if (candidate >= used_cap) {
                size_t new_cap = used_cap ? used_cap * 2 : 1024;
                while (new_cap <= (size_t)candidate) new_cap *= 2;
                unsigned char *tmp = (unsigned char*)realloc(used, new_cap);
                if (!tmp) abort();
                if (used_cap < new_cap)
                    memset(tmp + used_cap, 0, new_cap - used_cap);
                used = tmp;
                used_cap = new_cap;
            }

            /* Skip numbers that are already used */
            if (used[(size_t)candidate]) {
                (*ptr)++;   /* advance to next candidate */
                continue;
            }

            /* Determine parity of first digit of candidate */
            idx_t t = candidate;
            while (t >= (idx_t)10) t /= 10;
            bool first_odd = (t % 2) != 0;

            if (first_odd != need_odd) {
                (*ptr)++;
                continue;  /* not allowed – try next candidate */
            }

            /* Candidate found */
            cache[generated] = (seq_t)candidate;
            used[(size_t)candidate] = 1;
            *ptr = candidate + 1;   /* update pointer for next search */
            break;
        }

        generated++;
    }

    return cache[n - 1];
}
