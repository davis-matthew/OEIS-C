/* Sequence A056085: Numbers k such that k^10 ≡ 1 (mod 11^3) */
/* The sequence is generated by precomputing all residue classes r in [1,1330] with r%11≠0 and r^10≡1 (mod1331).  */
/* Every term is of the form r + t·1331 (t ≥ 0).  The nth term is obtained as above. */

#include <stddef.h>
#include <stdbool.h>
#include <stdint.h>

/* Fast modular exponentiation using 64‑bit arithmetic.
   Inputs are small enough (base, exponent, mod ≤ 1331), so 64 bits are safe. */
static uint64_t mod_pow_uint(uint64_t base, uint64_t exp, uint64_t mod)
{
    uint64_t result = 1 % mod;
    base %= mod;
    while (exp > 0) {
        if (exp & 1ULL)
            result = (result * base) % mod;
        base = (base * base) % mod;
        exp >>= 1ULL;
    }
    return result;
}

static seq_t residues[1331];
static size_t residue_count = 0;
static bool initialized = false;

static void init_residues(void)
{
    if (initialized)
        return;
    const uint64_t MOD = 1331ULL;
    for (uint64_t r = 1; r < MOD; ++r) {
        if (r % 11ULL == 0ULL) /* skip non‑units */
            continue;
        if (mod_pow_uint(r, 10ULL, MOD) == 1ULL)
            residues[residue_count++] = (seq_t)r;
    }
    initialized = true;
}

seq_t a(idx_t n)
{
    if (n == 0)
        return 0; /* undefined for index 0 – return 0 as a safe default */
    init_residues();

    idx_t block = (n - 1) / residue_count;          /* how many full blocks of size R */
    idx_t pos   = (n - 1) % residue_count;          /* position within the block */

    /* Perform calculation in 64‑bit to avoid overflow, then cast to seq_t. */
    uint64_t term = (uint64_t)block * 1331ULL + (uint64_t)residues[pos];
    return (seq_t)term;
}
