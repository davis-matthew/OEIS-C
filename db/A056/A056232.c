/*
 * A056232  Form an array with 3 rows: row 1 begins with 1; all rows are
 *          increasing; each entry is sum of 2 entries above it; each number
 *          appears at most once; smallest unused number is appended to first
 *          row if possible. Sequence gives row 2.
 * https://oeis.org/A056232
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, nice, easy
 * Formula:   not stated
 * Range:     u8 n <= 53, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A056232: generated by the construction described in the OEIS entry.
   The array has three rows. Row 1 starts with 1. Every entry is the sum of the
   two entries above it. All numbers are distinct. At each step the smallest
   unused integer is appended to row 1 if that also keeps the corresponding
   sum in row 2 unused. The function returns the n‑th element of row 2
   (1‑based indexing). */
#include <stdlib.h>
#include <stdint.h>
#include <string.h>

/* Use a 64‑bit bitset for numbers that appear in any row.  The
   sequence for the tested range always fits in 64 bits, so this
   approach is safe for all builds. */
static uint64_t *used_bits = NULL;
static size_t used_cap_words = 0;          /* number of 64‑bit words allocated */

/* Ensure the bitset can store a number up to `v`. */
static inline void ensure_used_cap(uint64_t v)
{
    size_t w = v >> 6;
    if (w >= used_cap_words) {
        size_t new_cap = w + 1;
        uint64_t *p = (uint64_t*)realloc(used_bits, new_cap * sizeof(uint64_t));
        if (!p) exit(1);                     /* allocation failure */
        memset(p + used_cap_words, 0,
               (new_cap - used_cap_words) * sizeof(uint64_t));
        used_bits = p;
        used_cap_words = new_cap;
    }
}

/* Mark `v` as used. */
static inline void used_set(uint64_t v)
{
    ensure_used_cap(v);
    used_bits[v >> 6] |= ((uint64_t)1 << (v & 63));
}

/* Test whether `v` has already been used. */
static inline int used_get(uint64_t v)
{
    size_t w = v >> 6;
    if (w >= used_cap_words) return 0;
    return (used_bits[w] >> (v & 63)) & 1;
}

/* Dynamic array helpers for seq_t. */
static inline void ensure_seq_cap(seq_t **arr, size_t *cap, size_t new_cap)
{
    if (*cap < new_cap) {
        seq_t *p = (seq_t*)realloc(*arr, new_cap * sizeof(seq_t));
        if (!p) exit(1);
        *arr = p;
        *cap = new_cap;
    }
}

static inline void push_back(seq_t **arr, size_t *size, size_t *cap, seq_t val)
{
    if (*size + 1 > *cap) {
        size_t new_cap = (*cap == 0) ? 4 : *cap << 1;
        ensure_seq_cap(arr, cap, new_cap);
    }
    (*arr)[*size] = val;
    (*size)++;
}

/* Storage for the three rows.  Row 3 is only needed for the used set. */
static seq_t *row1 = NULL, *row2 = NULL;
static size_t sz1 = 0, cap1 = 0;
static size_t sz2 = 0, cap2 = 0;

static uint64_t next_candidate = 2;          /* smallest unused integer that
                                               has not yet been considered */
static int initialized = 0;

/* Initialisation performed on first call. */
static void init_sequence(void)
{
    /* Row 1 begins with 1. */
    push_back(&row1, &sz1, &cap1, (seq_t)1);
    used_set(1);

    /* Start with empty row 2. */
    sz2 = 0;
    cap2 = 0;

    initialized = 1;
}

/* Public function. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;          /* out of range guard */

    if (!initialized) init_sequence();

    /* Grow rows until we have at least n terms in row 2. */
    while (sz2 < (size_t)n) {
        /* Find the next smallest unused integer that can be appended
           while keeping the resulting sum unused. */
        uint64_t cand = next_candidate;
        for (;;) {
            if (used_get(cand)) { cand++; continue; }

            seq_t sum = row1[sz1 - 1] + (seq_t)cand;
            if (used_get((uint64_t)sum)) { cand++; continue; }

            /* Accept the candidate. */
            push_back(&row1, &sz1, &cap1, (seq_t)cand);
            used_set(cand);

            push_back(&row2, &sz2, &cap2, sum);
            used_set((uint64_t)sum);

            /* If we now have two elements in row 2, consider the sum
               that would appear in row 3.  It must also be unique. */
            if (sz2 >= 2) {
                seq_t sum3 = row2[sz2 - 2] + row2[sz2 - 1];
                if (!used_get((uint64_t)sum3)) {
                    used_set((uint64_t)sum3);
                    /* We do not need to store row 3 itself. */
                }
            }

            next_candidate = cand + 1;
            break;
        }
    }

    return row2[n - 1];
}
