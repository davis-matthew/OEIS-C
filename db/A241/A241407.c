/* Sequence: Numbers n such that n^2 ≡ -1 (mod 73).
   Which are exactly the integers congruent to 27 or 46 modulo 73.
   The sequence can be generated by
       a(1) = 27, a(2) = 46
       a(n) = a(n-2) + 73   (for n > 2)
   or equivalently by the closed form
       a(n) = 73 * floor(n/2) + 27   if n is odd
              73 * floor(n/2) - 27   if n is even
*/

seq_t a(idx_t n)
{
    /* floor(n/2) : shift right by 1 for unsigned integer */
    idx_t half = n >> 1;
    seq_t base = (seq_t)73 * (seq_t)half;

    if (n & 1)          /* odd index */
        return base + (seq_t)27;
    else                /* even index */
        return base - (seq_t)27;
}
