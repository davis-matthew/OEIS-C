/*
 * A194411  Numbers m such that Sum_{k=1..m} (<1/3 + k*r> - <k*r>) < 0, where
 *          r=sqrt(2) and < > denotes fractional part.
 * https://oeis.org/A194411
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = n-th positive integer m such that * 3*#{ k ≤ m :
 *            frac(k*√2) ≤ 2/3 } < 2*m. (Here frac(x)=x‑⌊x⌋.)
 * Range:     u8 n <= 61, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This routine keeps a memoised list of the terms found so far and
 * extends it as needed.  It uses no external helpers beyond the
 * standard C library.  The sequence is generated by scanning k = 1,2,...
 * computing t = ⌊k*√2⌋ by an integer square‑root of 2*k*k and
 * counting how many of these satisfy 18*k² ≤ 9*t² + 12*t + 4.
 * Whenever the inequality 3*count < 2*k holds, k is appended to the
 * list of terms.  The returned value is a(seq_t) which can be any
 * integer type (including arbitrary‑precision). */

#include <stdint.h>
#include <stdlib.h>

/* Integer square‑root of an unsigned 128‑bit value.
 * Returns floor(√x).  */
static uint64_t isqrt_u128(__uint128_t x)
{
    uint64_t low = 0, high = UINT64_MAX, ans = 0;
    while (low <= high) {
        uint64_t mid = low + ((high - low) >> 1);
        __uint128_t sq = (__uint128_t)mid * mid;
        if (sq <= x) {
            ans = mid;
            low = mid + 1;
        } else {
            if (mid == 0) break;
            high = mid - 1;
        }
    }
    return ans;
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* undefined, but harmless */

    /* Static state: memoised sequence, last processed k, and counter */
    static seq_t *terms = NULL;   /* array of found terms (1‑based) */
    static size_t terms_cap = 0;  /* allocated size */
    static size_t terms_len = 0;  /* number of terms currently stored */
    static idx_t last_k = 0;       /* last k that was processed */
    static uint64_t count_small = 0;  /* # of k with frac(k*√2) ≤ 2/3 */

    /* Ensure we have enough terms for the requested index */
    while (terms_len < n) {
        /* Advance to the next m (=k) */
        ++last_k;
        idx_t k = last_k;

        /* t = floor(k*√2) = floor(sqrt(2*k*k)) */
        __uint128_t mult = (__uint128_t)k * (__uint128_t)k * 2;
        uint64_t t = isqrt_u128(mult);

        /* Check whether frac(k*√2) ≤ 2/3  ⇔ 18*k² ≤ 9*t² + 12*t + 4 */
        __uint128_t lhs = (__uint128_t)18 * (__uint128_t)k * (__uint128_t)k;
        __uint128_t rhs = (__uint128_t)9 * (__uint128_t)t * (__uint128_t)t
                         + (__uint128_t)12 * (__uint128_t)t
                         + (__uint128_t)4;
        if (lhs <= rhs) {
            ++count_small;
        }

        /* If the sequence condition holds, record this k as a term */
        if ((__uint128_t)3 * (__uint128_t)count_small
                < (__uint128_t)2 * (__uint128_t)k) {
            /* Grow the array if necessary */
            if (terms_len + 1 > terms_cap) {
                size_t new_cap = terms_cap ? terms_cap * 2 : 16;
                seq_t *p = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
                if (!p) return (seq_t)0;          /* allocation failure */
                terms = p;
                terms_cap = new_cap;
            }
            terms[terms_len++] = (seq_t)k;
        }
    }

    return terms[n - 1];   /* return the n‑th term (1‑based indexing) */
}
