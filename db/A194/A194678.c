/*
 * A194678  Number of k in [1,n] for which <n*e>+<k*e> > 1, where < > =
 *          fractional part; row sums of A164677.
 * https://oeis.org/A194678
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 76, u16 n <= 76, u32 n <= 76, u64 n <= 76, u128 n <= 76,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Formula: a(n) = #{ 1 ≤ k ≤ n : frac(n*e) + frac(k*e) > 1 }
 *
 * Implementation detail:
 *   Let β = e - 2 ≈ 0.718281828459045235.
 *   For any integer m, frac(m*e) = frac(m*β).
 *   The fractional parts are generated by iterating:
 *     f_1 = β                (scaled)
 *     f_{m+1} = f_m + β mod 1
 *   where we store values as 64‑bit integers scaled by 10^12:
 *     SCALE = 10^12
 *     BETA  = floor(β * SCALE) = 718281828459
 *
 *   Then <n*e> > threshold where threshold = 1 - frac(n*e)
 *   is equivalent to f_n + f_k > SCALE.
 *
 *   The function computes all f_k for 1..n and counts how many satisfy
 *   f_k > SCALE - f_n.
 *
 *   Complexity: O(n) time, O(1) extra space.
 */
#include <stdint.h>
#include <stdbool.h>

static const uint64_t SCALE = 1000000000000ULL;   /* 10^12, fits in uint64_t */
static const uint64_t BETA  = 718281828459ULL;    /* floor((e-2)*SCALE) */

/* external linkage */
seq_t a(idx_t n) {
    if (n == 0) return 0;   /* undefined for n=0, but harmless */

    /* compute fractional parts f[1..n] on the fly */
    uint64_t f = BETA;          /* f_1 */
    uint64_t f_n = f;           /* placeholder for f_n until we reach it */
    idx_t i = 1;

    /* first pass: find f_n */
    while (i < n) {
        f += BETA;
        if (f >= SCALE) f -= SCALE;
        ++i;
    }
    f_n = f;   /* f_n now contains frac(n*e) * SCALE */

    /* threshold for comparison: SCALE - f_n */
    uint64_t thresh = SCALE - f_n;

    /* second pass: count k with f_k > thresh */
    uint64_t count = 0;
    f = BETA;          /* reset to f_1 for second pass */
    i = 1;
    while (i <= n) {
        if (f > thresh) ++count;
        f += BETA;
        if (f >= SCALE) f -= SCALE;
        ++i;
    }

    return (seq_t)count;
}
