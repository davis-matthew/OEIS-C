/*
 * A181882  The sums of pairs of adjacent terms are the odd palindromic primes
 *          in ascending order.
 * https://oeis.org/A181882
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy, base
 * Formula:   not stated
 * Range:     u8 n <= 10, u16 n <= 42, u32 n <= 42, u64 n <= 42, u128 n <= 42,
 *            big any n
 * Helpers:   isPrimeGeneric, pow10
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A181882: a(1)=2; a(2)=1; for n≥3, a(n)=p_{n-1}−a(n-1)
 * where p_k is the k‑th odd palindromic prime.
 *
 * The sequence is generated by
 *   a(1)=2 , a(2)=1
 *   a(n)=p_{n-1}−a(n-1)
 *   p_k : successive odd palindromic primes
 */

#include <stdlib.h>
#include <stdbool.h>

#include "../utils/isPrimeGeneric.h"
#include "../utils/pow10.h"

/* Ensure an array can hold at least 'needed' elements */
static void ensure_capacity(size_t needed, size_t *cap, seq_t **arr) {
    if (needed <= *cap) return;
    size_t newcap = (*cap == 0) ? 16 : (*cap << 1);
    while (newcap < needed) newcap <<= 1;
    *arr = (seq_t *)realloc(*arr, newcap * sizeof(seq_t));
    *cap = newcap;
}

/* Build an odd palindrome from its left half (in decimal) and total length */
static seq_t make_pal(idx_t half, int len) {
    seq_t pal = (seq_t)half;
    idx_t x   = half;
    if (len & 1) x /= 10;               /* skip the central digit for odd length */
    while (x > 0) {
        pal = pal * 10 + (x % 10);
        x   /= 10;
    }
    return pal;
}

/* ---------- Odd palindromic primes ------------------------------------- */

static seq_t *p_cache = NULL;   /* array of primes */
static size_t p_cap   = 0;       /* allocated capacity */
static idx_t   p_len   = 0;       /* number of primes stored */

/* Generate the next odd palindromic prime and append it to p_cache */
static void generate_next_pal_prime(void) {
    static int        len        = 1;
    static idx_t      half_start = 0;
    static idx_t      half_end   = 0;
    static idx_t      half       = 0;

    for (;;) {
        if (half == 0) {                                 /* start new length */
            half_start = (idx_t)pow10((len - 1) / 2);
            half_end   = (idx_t)pow10((len + 1) / 2) - 1;
            half       = half_start;
        }
        if (half > half_end) {                           /* finished length */
            len++;
            half = 0;
            continue;
        }
        seq_t pal = make_pal(half, len);
        half++;

        if (pal > 2 && isPrimeGeneric(pal)) {
            ensure_capacity(p_len + 1, &p_cap, &p_cache);
            p_cache[p_len++] = pal;
            return;
        }
    }
}

/* Ensure that at least 'need' primes are available */
static void ensure_pal_primes(idx_t need) {
    while (p_len < need) generate_next_pal_prime();
}

/* ---------- Sequence a(n) ---------------------------------------------- */

static seq_t *a_cache = NULL;   /* array of a(n), 0‑based: a_cache[0] = a(1) */
static size_t a_cap   = 0;       /* allocated capacity */
static idx_t   a_len   = 0;       /* number of a(n) values stored */

/* Compute a(n) and store the values up to n (1‑based) */
static seq_t compute_a_value(idx_t n) {
    if (n == 0) return (seq_t)0;          /* offset is 1; unused for n<1 */

    /* The first two values are known */
    if (a_len == 0) {
        ensure_capacity(2, &a_cap, &a_cache);
        a_cache[0] = (seq_t)2;   /* a(1) */
        a_len      = 1;
    }
    if (a_len == 1) {
        a_cache[1] = (seq_t)1;   /* a(2) */
        a_len      = 2;
    }

    /* We need the first n‑1 odd palindromic primes */
    ensure_pal_primes(n - 1);

    /* Grow a_cache if necessary */
    if (a_len < n) {
        ensure_capacity(n, &a_cap, &a_cache);
        for (idx_t i = a_len; i < n; ++i) {
            /* a(i+1) = p_i − a_i (array indices are 0‑based) */
            a_cache[i] = p_cache[i - 1] - a_cache[i - 1];
        }
        a_len = n;
    }

    return a_cache[n - 1];
}

/* External linkage as required */
seq_t a(idx_t n) {
    return compute_a_value(n);
}
