/*
 * A181803  Triangle read by rows: T(n,k) is the k-th smallest divisor d of n
 *          such that n sets a record for the number of its divisors that are
 *          multiples of d.
 * https://oeis.org/A181803
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 85, u16 n <= 85, u32 n <= 85, u64 n <= 85, u128 n <= 85,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A181803: a(n) is the n‑th element of the flattened triangle
   of record‑setting divisors.  The triangle is generated by
   considering each integer m in order, recording each divisor d of m
   for which the number of divisors of m that are multiples of d
   (which equals τ(m/d)) is a new record among all smaller integers. */

#include <stdlib.h>
#include <stdint.h>
#include <string.h>

static seq_t *cache = NULL;
static size_t cache_cap = 0;
static size_t cache_len = 0;
static idx_t current_m = 0;

static uint32_t *best_tau = NULL;
static size_t best_tau_cap = 0;

static idx_t *temp_divs = NULL;
static size_t temp_cap = 0;
static size_t temp_len = 0;

static int cmp_idx(const void *a, const void *b)
{
    idx_t x = *(const idx_t *)a;
    idx_t y = *(const idx_t *)b;
    return (x < y) ? -1 : (x > y) ? 1 : 0;
}

static void ensure_best_tau(idx_t limit)
{
    if ((size_t)limit < best_tau_cap)
        return;
    size_t new_cap = best_tau_cap ? best_tau_cap << 1 : 8;
    while (new_cap <= (size_t)limit)
        new_cap <<= 1;
    uint32_t *tmp = (uint32_t *)realloc(best_tau, new_cap * sizeof(uint32_t));
    if (!tmp && new_cap > 0)
        abort();
    memset(tmp + best_tau_cap, 0, (new_cap - best_tau_cap) * sizeof(uint32_t));
    best_tau = tmp;
    best_tau_cap = new_cap;
}

static void ensure_temp(size_t len)
{
    if (len <= temp_cap)
        return;
    size_t new_cap = temp_cap ? temp_cap << 1 : 8;
    while (new_cap < len)
        new_cap <<= 1;
    idx_t *tmp = (idx_t *)realloc(temp_divs, new_cap * sizeof(idx_t));
    if (!tmp && new_cap > 0)
        abort();
    temp_divs = tmp;
    temp_cap = new_cap;
}

static void gen_divs_rec(int i, int cnt, idx_t current_d, int current_tau,
                         int *primes, int *exps)
{
    if (i == cnt) {
        idx_t d = current_d;
        uint32_t old = best_tau[(size_t)d];
        if ((uint32_t)current_tau > old) {
            best_tau[(size_t)d] = (uint32_t)current_tau;
            if (temp_len == temp_cap)
                ensure_temp(temp_len + 1);
            temp_divs[temp_len++] = d;
        }
        return;
    }
    int e = exps[i];
    idx_t p_pow = 1;
    for (int f = 0; f <= e; ++f) {
        int factor = e - f + 1;
        idx_t nd = current_d * p_pow;
        int ntau = current_tau * factor;
        gen_divs_rec(i + 1, cnt, nd, ntau, primes, exps);
        p_pow *= (idx_t)primes[i];
    }
}

static void factor_uint64(idx_t n, int *primes, int *exps, int *cnt)
{
    *cnt = 0;
    idx_t t = n;
    if (t % 2 == 0) {
        int e = 0;
        while (t % 2 == 0) {
            t /= 2;
            ++e;
        }
        primes[*cnt] = 2;
        exps[*cnt] = e;
        ++(*cnt);
    }
    for (idx_t p = 3; p * p <= t; p += 2) {
        if (t % p == 0) {
            int e = 0;
            while (t % p == 0) {
                t /= p;
                ++e;
            }
            primes[*cnt] = (int)p;
            exps[*cnt] = e;
            ++(*cnt);
        }
    }
    if (t > 1) {
        primes[*cnt] = (int)t;
        exps[*cnt] = 1;
        ++(*cnt);
    }
}

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0; /* undefined for 0, guard against it */

    while (cache_len < n) {
        ++current_m;
        ensure_best_tau(current_m);

        int primes[16];
        int exps[16];
        int cnt;
        factor_uint64(current_m, primes, exps, &cnt);

        temp_len = 0;
        if (temp_cap == 0) {
            temp_cap = 16;
            temp_divs = (idx_t *)malloc(temp_cap * sizeof(idx_t));
            if (!temp_divs)
                abort();
        }

        gen_divs_rec(0, cnt, (idx_t)1, 1, primes, exps);

        if (temp_len > 1)
            qsort(temp_divs, temp_len, sizeof(idx_t), cmp_idx);

        for (size_t i = 0; i < temp_len; ++i) {
            if (cache_len == cache_cap) {
                size_t new_cap = cache_cap ? cache_cap << 1 : 16;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp && new_cap > 0)
                    abort();
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = (seq_t)temp_divs[i];
        }
    }

    return cache[n - 1];
}
