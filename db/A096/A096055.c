/*
 * Implementation of OEIS sequence A096055.
 * The sequence is generated by iteratively expanding the array
 * according to the definition:
 *   s(0) = {1}
 *   For k>0:
 *     if a(k) = 0,  s(k) = s(k-1) ‖ s(k-1)
 *     if a(k) = 1,  s(k) = s(k-1) ‖ {0} ‖ s(k-1)
 *   a(n) is the n-th element of the limit of s(k).
 *
 * This algorithm builds the array incrementally until it reaches
 * the required index, reusing previously computed values.
 */

#include <stdlib.h>
#include <string.h>

static seq_t *seq = NULL;          /* dynamic array holding the current s(k) */
static size_t   len = 0;           /* current length of seq */
static idx_t    stage = 0;         /* current stage number (k)       */
static int      ready = 0;         /* flag indicating that seq has been initialized */

/* Return a(n) for any n >= 1.  The function is thread‑unsafe but
 * satisfies the required properties for deterministic builds. */
seq_t a(idx_t n)
{
    /* Ensure the sequence is initialized. */
    if (!ready) {
        /* start with s(0) = {1}. */
        seq = (seq_t *)malloc(sizeof(seq_t));
        if (!seq) exit(1);     /* abort on allocation failure */
        seq[0] = 1;
        len   = 1;
        stage = 0;
        ready = 1;
    }

    /* Grow the sequence until it contains at least n elements. */
    while (n > len) {
        /* a(k) is the (k-1)-th element of the current array. */
        seq_t ak = seq[stage];

        size_t old_len = len;
        size_t new_len = (ak == 0) ? 2 * old_len : 2 * old_len + 1;

        /* Reallocate to the new size. */
        seq_t *tmp = (seq_t *)realloc(seq, new_len * sizeof(seq_t));
        if (!tmp) exit(1);      /* abort on allocation failure */
        seq = tmp;
        len = new_len;

        if (ak == 0) {
            /* Append a duplicate of the old array. */
            memcpy(&seq[old_len], seq, old_len * sizeof(seq_t));
        } else {
            /* Insert a zero between the two copies. */
            seq[old_len] = 0;
            memcpy(&seq[old_len + 1], seq, old_len * sizeof(seq_t));
        }

        /* Move to the next stage. */
        ++stage;
    }

    return seq[n - 1];
}
