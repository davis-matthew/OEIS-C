/*
 * A096421  a(1)=1; for n > 1, a(n) = Sum_{1<=j<n, gcd(j,n)=1} a(j)*a(n-j).
 * https://oeis.org/A096421
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 12, u32 n <= 22, u64 n <= 28, u128 n <= 28,
 *            big any n
 * Helpers:   _gcd_idx
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A096421
 *
 * Formula: a(1) = 1;
 *         a(n) = ∑_{1≤j<n, gcd(j,n)=1} a(j)·a(n-j)   for n>1
 *
 * The implementation keeps a static cache of already computed terms.
 * New terms are generated by dynamic programming up to the required index.
 * A simple Euclidean algorithm is used to test coprimality.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/_gcd_idx.h"

/* Static cache for sequence values */
static seq_t *cache = NULL;          /* cache[1] .. cache[computed] */
static size_t cache_size   = 0;      /* allocated size */
static idx_t  computed_up_to = 0;    /* highest index computed */

/* Ensure the cache can hold indices up to 'n' */
static void ensure_cache(idx_t n) {
    if (cache_size <= (size_t)n) {
        size_t newsize = cache_size ? cache_size * 2 : 8;
        while (newsize <= (size_t)n) newsize <<= 1;
        seq_t *tmp = (seq_t *)realloc(cache, newsize * sizeof(seq_t));
        cache = tmp;
        cache_size = newsize;
    }
}

/* Compute all terms up to 'n' inclusive */
static void compute_up_to(idx_t n) {
    if (n <= computed_up_to) return;

    if (cache == NULL) {                /* first time */
        cache = (seq_t *)malloc(8 * sizeof(seq_t));
        cache_size = 8;
        cache[0] = 0;                   /* unused */
        cache[1] = 1;                   /* a(1) = 1 */
        computed_up_to = 1;
    }

    ensure_cache(n);

    for (idx_t i = computed_up_to + 1; i <= n; ++i) {
        seq_t sum = 0;
        for (idx_t j = 1; j <= i / 2; ++j) {
            if (_gcd_idx(j, i) == 1) {
                seq_t prod = cache[j] * cache[i - j];
                if (j < i - j)
                    sum += prod * 2;      /* counts j and i-j separately */
                else
                    sum += prod;          /* j == i-j (only possible when i == 2) */
            }
        }
        cache[i] = sum;
    }
    computed_up_to = n;
}

/* Public entry point required by the framework */
seq_t a(idx_t n) {
    if (n < 1) return 0;               /* undefined for n < 1 */
    compute_up_to(n);
    return cache[n];
}
