/* A096105: Numbers where every digit is a multiple of the digit to its left.
   Generated by enumerating all such numbers in numeric order. */

#include <stdlib.h>

/* Cache of sequence values ----------------------------------------------- */
static seq_t* cache   = NULL;
static size_t cache_size = 0;   /* number of stored values */
static size_t cache_cap   = 0;   /* allocated capacity */
static unsigned next_len   = 0;  /* next length to generate */

/* Append a value to the cache, growing storage if necessary. */
static void cache_append(seq_t val)
{
    if (cache_size == cache_cap) {
        cache_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
        cache = (seq_t*)realloc(cache, cache_cap * sizeof(seq_t));
    }
    cache[cache_size++] = val;
}

/* Recursive generator for numbers of a fixed length. */
static void generate_len_rec(seq_t value, unsigned pos, unsigned len)
{
    if (pos == len) {
        cache_append(value);
        return;
    }

    if (pos == 0) {               /* first digit: 1-9 */
        for (unsigned d = 1; d <= 9; ++d)
            generate_len_rec((seq_t)d, 1, len);
    } else {                      /* subsequent digits */
        unsigned last = (unsigned)(value % 10);
        if (last == 0) {          /* only 0 can follow a 0 */
            generate_len_rec(value * 10, pos + 1, len);
        } else {
            for (unsigned d = 0; d <= 9; ++d)
                if (d % last == 0)
                    generate_len_rec(value * 10 + d, pos + 1, len);
        }
    }
}

/* Generate all numbers of a given length. */
static void generate_length(unsigned len)
{
    generate_len_rec(0, 0, len);
}

/* Ensure the cache holds at least n terms. */
static void ensure_cache(idx_t n)
{
    if (cache == NULL) {
        cache_cap = 16;
        cache = (seq_t*)malloc(cache_cap * sizeof(seq_t));
    }

    while (cache_size < (size_t)n) {
        ++next_len;
        generate_length(next_len);
    }
}

/* Public function -------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;

    ensure_cache(n);
    return cache[(size_t)(n - 1)];
}
