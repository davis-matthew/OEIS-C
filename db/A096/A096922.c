/*
 * A096922  Numbers m for which there is a unique k such that m = k + (product
 *          of nonzero digits of k).
 * https://oeis.org/A096922
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 104, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A096922: numbers m that appear exactly once as k + prod_nonzero(k).
   Generated by a brute‑force count of f(k)=k+∏(nonzero digits of k) for k up
   to a large bound (2 000 000).  The resulting list of unique ms is stored
   once and answered in O(1). */
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* Helper: product of non‑zero decimal digits of n */
static uint64_t prod_nonzero_digits(uint64_t n)
{
    uint64_t prod = 1;
    while (n)
    {
        uint64_t d = n % 10;
        if (d) prod *= d;
        n /= 10;
    }
    return prod;
}

/* Static cache */
static seq_t *cache = NULL;          /* array of unique m’s (as seq_t) */
static size_t cache_len = 0;         /* number of elements stored */

/* Precompute the sequence the first time it is needed. */
static void init_sequence(void)
{
    const idx_t MAX_K = 2000000;         /* upper bound for k */
    const uint64_t MAX_PROD = 531441ULL; /* 9^6, largest product for 7‑digit numbers */
    const idx_t MAX_M = MAX_K + MAX_PROD + 10;  /* safety margin */

    /* Count occurrences of each m = k + prod of non‑zero digits of k */
    int *cnt = (int*)calloc((size_t)MAX_M, sizeof(int));
    if (!cnt) exit(1);   /* allocation failure */

    for (idx_t k = 1; k <= MAX_K; ++k)
    {
        uint64_t prod = prod_nonzero_digits((uint64_t)k);
        uint64_t m = (uint64_t)k + prod;
        if (m < MAX_M) ++cnt[(size_t)m];
    }

    /* Collect unique ms (count == 1) in ascending order */
    cache_len = 0;
    for (idx_t m = 1; m < MAX_M; ++m)
        if (cnt[(size_t)m] == 1) ++cache_len;

    cache = (seq_t*)malloc(cache_len * sizeof(seq_t));
    if (!cache) exit(1);   /* allocation failure */

    size_t pos = 0;
    for (idx_t m = 1; m < MAX_M; ++m)
        if (cnt[(size_t)m] == 1)
            cache[pos++] = (seq_t)m;

    free(cnt);
}

/* Public function required by the build */
seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* sequence is 1-indexed, undefined for n=0 */

    /* Initialize once */
    static int initialized = 0;
    if (!initialized)
    {
        init_sequence();
        initialized = 1;
    }

    if (n > cache_len) return 0;   /* out of bounds – input beyond precomputed range */
    return cache[n - 1];
}
