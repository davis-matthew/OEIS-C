/*
 * A064408  Even numbers not the sum of a pair of the greater of the twin
 *          primes.
 * https://oeis.org/A064408
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 70, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A064408: Even numbers not the sum of a pair of the greater of the twin primes.
   The sequence is generated by scanning even numbers in ascending order and
   determining whether each can be written as a sum of two greater twin primes.
   A Sieve of Eratosthenes is maintained up to at least the largest twin prime
   required for the even numbers examined so far.   */

#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

/* ------------------------------------------------------------------ */
/*  Global static data                                                 */
/* ------------------------------------------------------------------ */
static uint8_t *sieve              = NULL;   /* 0/1 array of primality  */
static uint8_t *twin_exists        = NULL;   /* 0/1 array: true if n is a greater twin prime   */
static idx_t  *twin_primes         = NULL;   /* list of greater twin primes                */
static size_t  twin_count          = 0;      /* number of twin primes currently stored      */
static idx_t   current_limit       = 0;      /* largest number sieved                       */

static seq_t  *cache               = NULL;   /* computed terms of the sequence             */
static size_t  cache_size          = 0;      /* number of terms in cache                   */
static size_t  cache_cap           = 0;      /* capacity of cache array                    */
static seq_t   next_even           = 2;      /* next even number to test                   */

/* ------------------------------------------------------------------ */
/*  Helper: Ensure sieve and twin data are available up to at least
   `needed`.  The data structures are rebuilt from scratch each time.
   ------------------------------------------------------------------ */
static void
ensure_limit(idx_t needed)
{
    if (current_limit >= needed)
        return;

    /* choose a new limit large enough to cover `needed` and at least double the
       previous limit (except when starting).  */
    idx_t new_limit = current_limit ? current_limit * 2 : 10;
    if (new_limit < needed)
        new_limit = needed;

    /* ---------- Allocate new sieve ----------
       The sieve array stores 1 for prime, 0 for composite.  */
    uint8_t *new_sieve = (uint8_t *)malloc((size_t)(new_limit + 1));
    if (!new_sieve) abort();
    memset(new_sieve, 1, (size_t)(new_limit + 1));
    if (new_limit >= 0) new_sieve[0] = 0;
    if (new_limit >= 1) new_sieve[1] = 0;

    /* Classic Eratosthenes sieve */
    for (idx_t p = 2; p * p <= new_limit; ++p) {
        if (new_sieve[p]) {
            for (idx_t q = p * p; q <= new_limit; q += p)
                new_sieve[q] = 0;
        }
    }

    /* ---------- Build array of greater twin primes ----------
       A greater twin prime is the larger of a pair p-2 , p, both primes.  */
    uint8_t *new_twin = (uint8_t *)calloc((size_t)(new_limit + 1), 1);
    if (!new_twin) abort();

    for (idx_t p = 5; p <= new_limit; p += 2) {
        if (new_sieve[p] && new_sieve[p - 2])
            new_twin[p] = 1;
    }

    /* ---------- Build list of greater twin primes ----------
       Store them in ascending order.  */
    size_t new_cap = new_limit / 5 + 2;   /* rough upper bound                */
    idx_t *new_twin_primes = (idx_t *)malloc(new_cap * sizeof(idx_t));
    if (!new_twin_primes) abort();
    size_t new_count = 0;

    for (idx_t p = 5; p <= new_limit; p += 2) {
        if (new_twin[p]) {
            if (new_count == new_cap) {
                new_cap *= 2;
                new_twin_primes = (idx_t *)realloc(new_twin_primes,
                                                   new_cap * sizeof(idx_t));
                if (!new_twin_primes) abort();
            }
            new_twin_primes[new_count++] = p;
        }
    }

    /* ---------- Replace old arrays ---------- */
    free(sieve);
    free(twin_exists);
    free(twin_primes);

    sieve        = new_sieve;
    twin_exists  = new_twin;
    twin_primes  = new_twin_primes;
    twin_count   = new_count;
    current_limit = new_limit;
}

/* ------------------------------------------------------------------ */
/*  Sequence function a(n)                                            */
/* ------------------------------------------------------------------ */
seq_t
a(idx_t n)
{
    if (n == 0)
        return 0;

    /* Generate terms until we have enough in the cache. */
    while (cache_size < n) {
        seq_t val = next_even;

        /* The largest twin prime that might appear in a sum with `val`
           is `val - 5` (the smallest greater twin prime is 5).  */
        idx_t needed = (val >= 5) ? (idx_t)(val - 5) : 5;
        ensure_limit(needed);

        /* Check whether `val` can be expressed as the sum of two greater
           twin primes.  */
        bool representable = false;
        for (size_t i = 0; i < twin_count; ++i) {
            idx_t p = twin_primes[i];
            if (p > val)
                break;
            idx_t r = (idx_t)(val - p);
            if (r <= current_limit && twin_exists[r]) {
                representable = true;
                break;
            }
        }

        if (!representable) {
            /* Append to the cache.  */
            if (cache_size == cache_cap) {
                cache_cap = cache_cap ? cache_cap * 2 : 64;
                cache     = (seq_t *)realloc(cache,
                                              cache_cap * sizeof(seq_t));
                if (!cache) abort();
            }
            cache[cache_size++] = val;
        }

        next_even += 2;
    }

    return cache[n - 1];
}
