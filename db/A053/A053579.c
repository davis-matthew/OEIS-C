/* Composite numbers whose cototient n‑φ(n) is a power of two.
   The sequence is generated by merging the arithmetic progressions
   n = 2^a * m,  a ≥ a_min(m),  m = 1 or a Mersenne prime (q = 2^w – 1).
   For m = 1 the minimal exponent is 2 (n = 4,8,16,…).
   For a Mersenne prime the minimal exponent is 1 (n = 2·q, 4·q, …). */

#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/pow2.h"            /* seq_t pow2(idx_t exp); */
#include "../utils/ensure_capacity.h" /* void ensure_capacity(size_t need, size_t *cap, void **ptr, size_t elem_size); */

#define NUM_M 11                       /* number of odd factors m used */

static const uint32_t m_exps[NUM_M] = {
    0,   /* m = 1  (accounts for pure powers of two) */
    2,   /* 3   = 2^2-1   */
    3,   /* 7   = 2^3-1   */
    5,   /* 31  = 2^5-1   */
    7,   /* 127 = 2^7-1   */
    13,  /* 8191        */
    17,  /* 131071      */
    19,  /* 524287      */
    31,  /* 2147483647  */
    61,  /* 2305843009213693951 */
    89   /* 2^89-1     */
};

/* Per‑prime data */
static seq_t m_val[NUM_M];          /* m = 1 or 2^exp‑1             */
static seq_t cur_val[NUM_M];        /* current smallest candidate   */
static uint64_t a_cur[NUM_M];       /* current exponent of 2 factor */

/* Sequence cache */
static seq_t *cache = NULL;         /* array of computed terms       */
static size_t cache_size = 0;       /* number of terms stored        */
static size_t cache_cap = 0;        /* capacity of cache array       */
static bool initialized = false;

/* Lazily initialise m_val and cur_val */
static void seq_init(void)
{
    for (size_t i = 0; i < NUM_M; ++i) {
        if (m_exps[i] == 0) {                    /* m = 1 */
            m_val[i]   = (seq_t)1;
            cur_val[i] = pow2(2);                /* 2^2 = 4 */
            a_cur[i]   = 2;
        } else {
            m_val[i]   = pow2(m_exps[i]) - 1;     /* 2^exp – 1 */
            cur_val[i] = pow2(1) * m_val[i];     /* 2 * m    */
            a_cur[i]   = 1;
        }
    }
    initialized = true;
}

/* Generate terms until cache_size ≥ n */
static void seq_generate_until(idx_t n)
{
    while (cache_size < (size_t)n) {
        /* find minimal current value */
        size_t idx_min = 0;
        for (size_t i = 1; i < NUM_M; ++i) {
            if (cur_val[i] < cur_val[idx_min])
                idx_min = i;
        }

        /* append the minimal value */
        size_t needed = cache_size + 1;
        ensure_capacity(needed, &cache_cap, (void **)&cache, sizeof(seq_t));
        cache[cache_size++] = cur_val[idx_min];

        /* advance this generator: multiply by two */
        if (sizeof(seq_t) == sizeof(uint64_t)) {
            /* For 64‑bit builds avoid overflow: stop if next value would overflow */
            if (cur_val[idx_min] > (UINT64_MAX >> 1))
                return;       /* All future values exceed 64 bits – stop */
        }
        cur_val[idx_min]  = cur_val[idx_min] * 2;   /* doubles 2‑exponent by one */
        a_cur[idx_min]   += 1;
    }
}

/* Public API required by the exercise */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;                     /* undefined – return 0 */

    if (!initialized)
        seq_init();

    seq_generate_until(n);
    return cache[n-1];                        /* 1‑based indexing */
}
