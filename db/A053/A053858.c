/* Sequence: Squarefree even composite numbers with an odd number of prime factors.
   a(1) = 30, a(2) = 42, a(3) = 66, …
   The sequence is generated by sieving the Möbius function μ(n).
   An integer n is included iff n is even, squarefree (μ(n)≠0) and
   has an odd number of distinct prime factors, i.e. μ(n) = -1.
   This guarantees n is composite (k≥3). */

#include <stdlib.h>
#include <stdbool.h>

/* ensure_mu(limit) builds the Möbius array up to `limit`.  */
static signed char *mu = NULL;
static size_t mu_len = 0;
static void ensure_mu(size_t limit)
{
    if (limit <= mu_len) return;

    /* free old array if any */
    if (mu != NULL) free(mu);

    size_t n = limit + 1;
    mu = (signed char *)malloc(n * sizeof(signed char));
    if (!mu) { /* memory allocation failure: abort */
        exit(1);
    }
    /* initialise μ to 1 (will be updated for primes) */
    for (size_t i = 0; i < n; ++i) mu[i] = 1;
    mu[0] = 0;
    mu[1] = 1;

    /* simple sieve to compute μ */
    unsigned char *isComp = (unsigned char *)calloc(n, sizeof(unsigned char));
    if (!isComp) { free(mu); exit(1); }

    for (size_t i = 2; i <= limit; ++i) {
        if (!isComp[i]) { /* i is prime */
            /* multiply by -1 for each multiple of i */
            for (size_t j = i; j <= limit; j += i)
                mu[j] = -mu[j];

            /* zero out multiples of i^2 (square factors) */
            size_t sq = i * i;
            if (sq <= limit) {
                for (size_t j = sq; j <= limit; j += sq)
                    mu[j] = 0;
            }

            /* mark composites */
            if (i <= limit / 2) {
                for (size_t j = 2 * i; j <= limit; j += i)
                    isComp[j] = 1;
            }
        }
    }
    free(isComp);
    mu_len = limit;
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* offset starts at 1, but guard */

    size_t limit = 20 * (size_t)n + 200;
    if (limit < 1000) limit = 1000;   /* safety for very small n */
    ensure_mu(limit);

    size_t count = 0;
    for (size_t i = 4; i <= limit; i += 2) {
        if (mu[i] == -1) {
            ++count;
            if (count == (size_t)n)
                return (seq_t)i;
        }
    }

    /* In the unlikely event the limit was insufficient,
       double the limit and retry until the term is found.  */
    size_t new_limit = limit * 2;
    while (1) {
        ensure_mu(new_limit);
        count = 0;
        for (size_t i = 4; i <= new_limit; i += 2) {
            if (mu[i] == -1) {
                ++count;
                if (count == (size_t)n)
                    return (seq_t)i;
            }
        }
        new_limit *= 2;
    }
}
