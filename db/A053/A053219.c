/*  OEIS A053219 – Reverse of triangle A053218, read by rows.
    The triangle A053218 is generated by
        row[0] = row index (1‑based)
        row[j] = row[j‑1] + previous_row[j‑1]   (j > 0)
    The sequence is obtained by reversing each row of this triangle
    and then flattening the rows in order.
    This implementation builds rows incrementally and caches them,
    so subsequent calls are fast and order‑independent.  */
#include <stdlib.h>

static seq_t **triangle = NULL;   /* 1‑based: triangle[r] is row r */
static idx_t triangle_rows = 0;   /* number of rows currently cached */
static size_t triangle_cap = 0;   /* capacity of the triangle array */

/* Ensure that rows 1 … upto are built and cached. */
static void ensure_rows(idx_t upto)
{
    if (triangle_rows >= upto) return;

    /* Resize the triangle pointer array if needed. */
    size_t new_cap = triangle_cap > 0 ? triangle_cap : 1;
    while (new_cap <= (size_t)upto) new_cap <<= 1;
    triangle = (seq_t **)realloc(triangle, new_cap * sizeof(seq_t *));
    for (size_t i = triangle_cap; i < new_cap; ++i) triangle[i] = NULL;
    triangle_cap = new_cap;

    /* Build missing rows. */
    for (idx_t r = triangle_rows + 1; r <= upto; ++r)
    {
        seq_t *row = (seq_t *)malloc(sizeof(seq_t) * r);
        row[0] = (seq_t)r;
        for (idx_t j = 1; j < r; ++j)
            row[j] = row[j - 1] + triangle[r - 1][j - 1];
        triangle[r] = row;
    }
    triangle_rows = upto;
}

/* Return the n-th term of A053219, 1‑based. */
seq_t a(idx_t n)
{
    if (n < 1) return 0;   /* undefined below the offset */

    /* Find the row r such that r*(r+1)/2 >= n.  */
    idx_t r = 1;
    while (((__int128)r * (r + 1) / 2) < n) ++r;

    ensure_rows(r);

    /* Position of the term within its row (0‑based from the left). */
    idx_t prev_sum = r * (r - 1) / 2;       /* sum of lengths of previous rows */
    idx_t offset   = n - prev_sum - 1;     /* index in the original row */

    /* In the reversed row this corresponds to: */
    idx_t rev_index = (r - 1) - offset;     /* index in the original row */

    return triangle[r][rev_index];
}
