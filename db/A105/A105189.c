/*
 * A105189  Numbers n such that the string k100000000001 is prime.
 * https://oeis.org/A105189
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 21, u16 n <= 55, u32 n <= 55, u64 n <= 55, u128 n <= 55,
 *            big any n
 * Helpers:   seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes OEIS A105189: k such that k*10^12+100000000001 is prime.
   The sequence is generated by searching k incrementally and testing
   the number with a deterministic Miller–Rabin primality test. */

#include <stdbool.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/seq_realloc.h"

#define TEN12  ((uint64_t)1000000000000ULL)
#define SUFFIX ((uint64_t)100000000001ULL)

/* ------- Miller–Rabin primality test for 64‑bit values ------- */

static uint64_t mod_mul(uint64_t a, uint64_t b, uint64_t mod)
{
    return (unsigned __int128)a * b % mod;
}

static uint64_t mod_pow(uint64_t base, uint64_t exp, uint64_t mod)
{
    uint64_t result = 1;
    while (exp) {
        if (exp & 1ULL)
            result = mod_mul(result, base, mod);
        base = mod_mul(base, base, mod);
        exp >>= 1;
    }
    return result;
}

static bool isPrime64(uint64_t n)
{
    if (n < 2) return false;

    /* Small primes trial division */
    static const uint64_t small[] =
        {2ULL,3ULL,5ULL,7ULL,11ULL,13ULL,17ULL,19ULL,
         23ULL,29ULL,31ULL,37ULL};
    for (size_t i = 0; i < sizeof(small)/sizeof(small[0]); ++i) {
        if (n == small[i]) return true;
        if (n % small[i] == 0) return false;
    }

    /* Write n-1 = d * 2^s with d odd */
    uint64_t d = n - 1;
    int s = 0;
    while ((d & 1ULL) == 0) { d >>= 1; ++s; }

    /* Deterministic bases for 64‑bit integers */
    static const uint64_t bases[]
        = {2ULL, 325ULL, 9375ULL, 28178ULL,
           450775ULL, 9780504ULL, 1795265022ULL};

    for (size_t i = 0; i < sizeof(bases)/sizeof(bases[0]); ++i) {
        uint64_t a = bases[i] % n;
        if (a == 0) continue;
        uint64_t x = mod_pow(a, d, n);
        if (x == 1 || x == n - 1) continue;
        bool composite = true;
        for (int r = 1; r < s; ++r) {
            x = mod_mul(x, x, n);
            if (x == n - 1) { composite = false; break; }
        }
        if (composite) return false;
    }
    return true;
}

/* ------- Cache management ------- */

static seq_t *cache     = NULL;   /* cached terms */
static idx_t  cache_len = 0;     /* elements currently stored */
static idx_t  cache_cap = 0;     /* allocated capacity */
static uint64_t next_k  = 1;     /* next candidate k to test */

/* Grow the cache so that it contains at least target+1 terms (0‑based). */
static void grow_cache(idx_t target)
{
    if (target < cache_len) return;

    while (cache_len <= target) {
        uint64_t candidate = next_k * TEN12 + SUFFIX;
        if (isPrime64(candidate)) {
            if (cache_len == cache_cap) {
                cache_cap = cache_cap ? cache_cap * 2 : 64;
                cache = seq_realloc(cache, cache_cap);
            }
            cache[cache_len++] = (seq_t)next_k;
        }
        ++next_k;
    }
}

/* ------- Public function (OEIS entry) ------- */

/* Return the n-th term of the sequence (1‑based). */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;
    grow_cache(n - 1);
    return cache[n - 1];
}
