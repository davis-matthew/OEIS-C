/*
 * A369662  Numbers k whose arithmetic derivative k' is of the form 4m+2, and
 *          k' has an odd number of prime factors.
 * https://oeis.org/A369662
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 9, u16 n <= 3964, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A369662: numbers k whose arithmetic derivative k′ is
 * congruent to 2 (mod 4) and k′ has an odd number of prime factors.
 * The sequence is generated by brute–force searching for k satisfying
 * these conditions; found values are cached so repeated calls are fast. */

#include <stdbool.h>
#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>

/* -------------------------------------------------------------------- */
/* Auxiliary: trial division factorisation of a uint64_t.  The arrays
 * must be large enough to hold all factors (here 64 is sufficient).   */
static size_t factor_uint64(uint64_t n, uint64_t *pr, uint64_t *ex)
{
    size_t cnt = 0;
    if (n <= 1) return 0;
    if (n % 2 == 0) {
        pr[cnt] = 2; ex[cnt] = 0;
        while (n % 2 == 0) { n /= 2; ++ex[cnt]; }
        ++cnt;
    }
    for (uint64_t p = 3; p * p <= n; p += 2) {
        if (n % p == 0) {
            pr[cnt] = p; ex[cnt] = 0;
            while (n % p == 0) { n /= p; ++ex[cnt]; }
            ++cnt;
        }
    }
    if (n > 1) { pr[cnt] = n; ex[cnt] = 1; ++cnt; }
    return cnt;
}

/* -------------------------------------------------------------------- */
/* Test whether a given k satisfies the two conditions of the
 * sequence definition.  Factorisation is performed twice, once for k
 * and once for the derivative d.  All arithmetic is done in 64‑bit
 * integers; the final value is cast back to seq_t. */
static bool matches(uint64_t k)
{
    uint64_t primes_k[64], exps_k[64];
    size_t nf = factor_uint64(k, primes_k, exps_k);

    uint64_t d = 0;
    for (size_t i = 0; i < nf; ++i) {
        uint64_t p = primes_k[i];
        uint64_t e = exps_k[i];
        d += (k / p) * e;
    }

    /* Condition 1: d ≡ 2 (mod 4) */
    if ((d & 3) != 2) return false;

    uint64_t primes_d[64], exps_d[64];
    size_t nd = factor_uint64(d, primes_d, exps_d);
    uint64_t omega = 0;
    for (size_t i = 0; i < nd; ++i) omega += exps_d[i];

    /* Condition 2: Ω(d) is odd */
    return (omega & 1U) != 0;
}

/* -------------------------------------------------------------------- */
/* Cache storage for sequence values, grown on demand. */
static seq_t *cache      = NULL;
static size_t cache_len  = 0;
static size_t cache_cap  = 0;
static uint64_t next_k   = 2;   /* integer candidate to test */

/* Resize the cache when it becomes full. */
static void grow_cache(void)
{
    size_t new_cap = (cache_cap == 0) ? 16 : cache_cap << 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();
    cache = tmp;
    cache_cap = new_cap;
}

/* -------------------------------------------------------------------- */
/* Main sequence function with memoisation. */
seq_t a(idx_t n)
{
    /* Ensure the cache contains at least n terms. */
    while (cache_len < (size_t)n) {
        if (cache_len == cache_cap) grow_cache();

        /* Find the next k that matches the definition. */
        while (!matches(next_k)) ++next_k;

        /* Store the found term. */
        cache[cache_len++] = (seq_t)next_k;
        ++next_k;
    }
    return cache[n - 1];
}
