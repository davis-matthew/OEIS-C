/*
 * A369007  Numbers k for which k' / gcd(k,k') is a multiple of 27, where k'
 *          stands for the arithmetic derivative of k, A003415(k).
 * https://oeis.org/A369007
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 1626, u32 n <= 9648, u64 n <= 9648,
 *            u128 n <= 9648, big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A369007: numbers k such that k' / gcd(k,k') is a multiple of 27.
   k' is the arithmetic derivative of k.  The sequence is generated by
   checking each integer in ascending order until the requested index is
   reached.  The arithmetic derivative is computed via prime factorisation
   using trial division.  GCD is obtained from the provided utils/gcd.h. */

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/gcd.h"

/* integer square‑root, floor */
static uint64_t isqrt_uint64(uint64_t n)
{
    uint64_t low = 0, high = 4294967295ULL;          /* sqrt(2^64–1) < 2^32 */
    while (low <= high) {
        uint64_t mid = (low + high) >> 1;
        unsigned __int128 sq = (unsigned __int128)mid * mid;
        if (sq == n) return mid;
        if (sq < n)
            low = mid + 1;
        else
            high = mid - 1;
    }
    return high;
}

/* smallest prime factor of n (trial division).  Used only for n >= 1. */
static uint64_t smallest_prime_factor(uint64_t n)
{
    if (n % 2ULL == 0ULL) return 2ULL;
    uint64_t lim = isqrt_uint64(n);
    for (uint64_t d = 3; d <= lim; d += 2) {
        if (n % d == 0ULL) return d;
    }
    return n;          /* prime */
}

/* arithmetic derivative of k, computed as sum_e e * k/p.  Works for k >= 1. */
static seq_t deriv(uint64_t k)
{
    seq_t der = 0;
    uint64_t t   = k;
    while (t > 1) {
        uint64_t p  = smallest_prime_factor(t);
        unsigned exp = 0;
        while (t % p == 0ULL) {
            t   /= p;
            exp++;
        }
        der += (seq_t)exp * (seq_t)(k / p);
    }
    return der;          /* der == 0 when k == 1 */
}

/* test whether k satisfies the definition */
static bool qualifies(uint64_t k)
{
    seq_t d = deriv(k);
    seq_t g = gcd((seq_t)k, d);
    seq_t q = d / g;
    return (q % 27) == 0;
}

/* --- main entry function --- */
seq_t a(idx_t n)
{
    /* persistent storage of found terms */
    static seq_t *arr      = NULL;
    static size_t  len     = 0;
    static size_t  cap     = 0;
    static uint64_t next_val = 1;   /* next integer to test */

    /* grow until we have at least n terms */
    while (len < (size_t)n) {
        if (qualifies(next_val)) {
            if (len == cap) {
                size_t newcap = (cap == 0) ? 16 : cap << 1;
                seq_t *tmp = (seq_t *)realloc(arr, newcap * sizeof(seq_t));
                if (!tmp) abort();          /* allocation failure */
                arr = tmp;
                cap = newcap;
            }
            arr[len++] = (seq_t)next_val;
        }
        ++next_val;
    }
    return arr[n - 1];
}
