/*
 * A369604  T is a "boomerang sequence": adding 9 to the 1st digit of T, 10 to
 *          the 2nd digit of T, 11 to the 3rd digit of T, 12 to the 4th digit
 *          of T, 13 to the 5th digit of T, 14 to the 6th digit of T, etc.,
 *          and following each result with a comma leaves T unchanged.
 * https://oeis.org/A369604
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 79, u16 n <= 79, u32 n <= 79, u64 n <= 79, u128 n <= 79,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Boomerang sequence:
   a(n) = digit(n) + ( n + 8 )
   where digit(n) is the nth decimal digit of the concatenated
   sequence a(1),a(2),…,a(n) with commas omitted.
   The sequence is generated by iteratively appending each a(k). */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <assert.h>

/* static storage for the sequence and its digit stream */
static seq_t *seq_cache = NULL;
static size_t seq_len = 0, seq_cap = 0;

static uint8_t *digits = NULL;
static size_t dig_len = 0, dig_cap = 0;

/* initialise with a(1)=10 and its digits "10" */
static void init(void)
{
    if (seq_cache != NULL)
        return;

    /* allocate for first term */
    seq_cap = 16;
    seq_cache = (seq_t *)malloc(sizeof(seq_t) * seq_cap);
    seq_cache[0] = (seq_t)10;
    seq_len = 1;

    /* allocate digits stream */
    dig_cap = 32;
    digits = (uint8_t *)malloc(dig_cap * sizeof(uint8_t));
    digits[0] = 1;
    digits[1] = 0;
    dig_len = 2;
}

/* return the nth term, 1‑based */
seq_t a(idx_t n)
{
    init();

    if (n == 0)
        return (seq_t)0;   /* undefined, but safe for callers */

    /* extend the cache until it contains the requested term */
    while (seq_len < (size_t)n)
    {
        size_t pos = seq_len;          /* zero‑based index of new term */
        assert(dig_len > pos);         /* its leading digit must already exist */

        uint8_t d = digits[pos];       /* digit(n) */
        seq_t val = (seq_t)d + ((seq_t)(pos + 1) + (seq_t)8);

        /* append the new term to the cache */
        if (seq_len == seq_cap)
        {
            seq_cap = seq_cap ? seq_cap * 2 : 8;
            seq_cache = (seq_t *)realloc(seq_cache, seq_cap * sizeof(seq_t));
        }
        seq_cache[seq_len++] = val;

        /* push decimal digits of val into the digit stream */
        if (val == 0)
        {
            if (dig_len == dig_cap)
            {
                dig_cap = dig_cap ? dig_cap * 2 : 16;
                digits = (uint8_t *)realloc(digits, dig_cap);
            }
            digits[dig_len++] = 0;
            continue;
        }

        /* temporary buffer for reversed digits */
        uint8_t rev[32];
        int revlen = 0;
        seq_t tmp = val;
        while (tmp > (seq_t)0)
        {
            rev[revlen++] = (uint8_t)(tmp % (seq_t)10);
            tmp /= (seq_t)10;
        }

        /* append in correct order */
        for (int i = revlen - 1; i >= 0; --i)
        {
            if (dig_len == dig_cap)
            {
                dig_cap = dig_cap ? dig_cap * 2 : 16;
                digits = (uint8_t *)realloc(digits, dig_cap);
            }
            digits[dig_len++] = rev[i];
        }
    }

    return seq_cache[n - 1];
}
