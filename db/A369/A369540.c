/*
 * A369540  Numbers k neither squarefree nor prime powers such that A119288(k)
 *          <= k/A007947(k) < A053669(k) and A007947(k) is a primorial P(i) =
 *          A002110(i) for some i.
 * https://oeis.org/A369540
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 24, u32 n <= 91, u64 n <= 312,
 *            u128 n <= 1084, big any n
 * Helpers:   ensure_capacity_idx, get_prime, seq_mul
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A369540
 *
 *   a(n) = m * P(r),   where  n ≥ 1,
 *         P(r) is the r‑th primorial (product of the first r primes),
 *         3 ≤ m < prime(r+1),
 *   r is chosen so that the cumulative number of terms up to row r-1 is
 *   less than n and the cumulative number up to row r is at least n.
 *   Within each row r (r ≥ 2) the values are ordered by increasing m.
 *
 * The sequence is generated by computing primorials and cumulative row
 * counts on demand.  No hard‑coded table is used. */

#include <stddef.h>
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

#include "../utils/get_prime.h"   /* get_prime(n): returns the n‑th prime */
#include "../utils/seq_mul.h"     /* seq_mul(a,b): multiplies seq_t values */
#include "../utils/ensure_capacity_idx.h"

/* ------------------------------------------------------------------ */
/* dynamic array helpers                                              */
/* ------------------------------------------------------------------ */
static void ensure_capacity_seq(seq_t **arr, size_t *cap, size_t needed)
{
    if (*cap >= needed) return;
    size_t new_cap = (*cap == 0) ? 16 : (*cap * 2);
    while (new_cap < needed) new_cap <<= 1;
    seq_t *tmp = (seq_t *)malloc(new_cap * sizeof(seq_t));
    if (*arr) {
        memcpy(tmp, *arr, (*cap) * sizeof(seq_t));
        free(*arr);
    }
    *arr = tmp;
    *cap = new_cap;
}

/* ------------------------------------------------------------------ */
/* storage for primorials and cumulative row counts                   */
/* ------------------------------------------------------------------ */
static seq_t *prim      = NULL;   /* prim[n] = nth primorial, prim[0] unused */
static size_t prim_cap  = 0;
static idx_t  prim_len  = 0;      /* highest n with computed primorial */

static idx_t *cum       = NULL;   /* cum[n] = number of terms up to row n   */
static size_t cum_cap   = 0;
static idx_t  cum_len   = 0;      /* highest n with computed cumulative */

/* ------------------------------------------------------------------ */
/* expand tables so that cum[n] ≥ target                              */
/* ------------------------------------------------------------------ */
static void ensure_upto(idx_t target)
{
    if (cum_len >= 2 && cum[cum_len] >= target) return;

    /* initialise if empty */
    if (cum_len == 0) {
        ensure_capacity_idx(&cum, &cum_cap, 3);   /* indices 0..2 at least */
        cum[0] = 0;          /* unused */
        cum[1] = 0;          /* row 1 contributes 0 terms */
        cum_len = 1;
    }
    if (prim_len == 0) {
        ensure_capacity_seq(&prim, &prim_cap, 3);  /* indices 0..2 at least */
        prim[0] = 0;          /* unused */
        prim[1] = (seq_t)2;   /* P(1) = 2 */
        prim_len = 1;
    }

    /* grow tables until we reach the desired target */
    while (cum_len < 2 || cum[cum_len] < target) {
        idx_t n = cum_len + 1;          /* next row to compute */

        /* allocate space for new entry */
        ensure_capacity_idx(&cum, &cum_cap, n + 1);
        ensure_capacity_seq(&prim, &prim_cap, n + 1);

        ++cum_len;
        ++prim_len;

        /* compute P(n) = P(n-1) * prime(n) */
        prim[n] = seq_mul(prim[n - 1], (seq_t)get_prime(n));

        /* terms in this row: prime(n+1) - 3  (m = 3 … prime(n+1)-1) */
        idx_t count = get_prime(n + 1) - 3;
        cum[n] = cum[n - 1] + count;
    }
}

/* ------------------------------------------------------------------ */
/* main sequence function                                             */
/* ------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    if (n < 1) return 0;          /* undefined for n = 0, but safe fallback */

    /* make sure tables are up to date */
    ensure_upto(n);

    /* find the row containing the n-th term */
    size_t row = 2;
    while (row <= cum_len && cum[row] < n) ++row;

    /* offset of this term within the row (0‑based) */
    idx_t previous = cum[row - 1];
    idx_t offset   = n - previous - 1;      /* 0‑based offset within row */

    /* m = 3 + offset */
    seq_t m = (seq_t)(3 + offset);

    /* return k = m * P(row) */
    return seq_mul(prim[row], m);
}
