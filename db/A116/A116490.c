/*
 * A116490  Numbers that can be written as a product of evil numbers (A001969)
 *          and of odious numbers (A000069).
 * https://oeis.org/A116490
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 26, u16 n <= 8695, u32 n <= 8695, u64 n <= 8695,
 *            u128 n <= 8695, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A116490: Numbers that can be written as a product of evil numbers
   (numbers with an even number of 1-bits) and odious numbers
   (numbers with an odd number of 1-bits).  The implementation
   checks for membership in both multiplicative semigroups
   generated by each class.  Each term is found by a simple
   incremental scan. */

#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

/* ---------- helper macros ---------- */

/* popcount parity helpers ------------------------------------------- */
static inline bool is_evil(idx_t n)
{
    return ((__builtin_popcountll((unsigned long long)n)) & 1) == 0;
}

static inline bool is_odious(idx_t n)
{
    return ((__builtin_popcountll((unsigned long long)n)) & 1) == 1;
}

/* integer square root for 64‑bit values ---------------------------- */
static inline idx_t floor_sqrt_u64(idx_t n)
{
    idx_t low = 0, high = (idx_t)1 << 32;   /* high^2 fits in 128 bits */
    while (low < high) {
        idx_t mid = (low + high + 1) >> 1;
        __uint128_t sq = (__uint128_t)mid * mid;
        if (sq <= n)
            low = mid;
        else
            high = mid - 1;
    }
    return low;
}

/* ---------- memoised semigroup membership ------------------------ */
static signed char *evil_mem   = NULL;
static signed char *odious_mem = NULL;
static size_t mem_cap = 0;

static void ensure_mem(idx_t n)
{
    size_t need = (size_t)n + 1;
    if (need <= mem_cap) return;
    size_t new_cap = mem_cap ? mem_cap << 1 : 1;
    while (new_cap < need) new_cap <<= 1;

    signed char *tmp = (signed char*)realloc(evil_mem, new_cap);
    if (!tmp) exit(1);
    for (size_t i = mem_cap; i < new_cap; ++i) tmp[i] = -1;
    evil_mem = tmp;

    tmp = (signed char*)realloc(odious_mem, new_cap);
    if (!tmp) exit(1);
    for (size_t i = mem_cap; i < new_cap; ++i) tmp[i] = -1;
    odious_mem = tmp;

    mem_cap = new_cap;
}

static inline bool in_evil_semigroup(idx_t n)
{
    if (n == 1) return true;
    ensure_mem(n);
    signed char *s = &evil_mem[n];
    if (*s != -1) return *s;

    bool res = false;
    if (is_evil(n))
        res = true;
    else {
        idx_t lim = floor_sqrt_u64(n);
        for (idx_t d = 2; d <= lim; ++d) {
            if (n % d != 0) continue;
            idx_t q = n / d;
            if ( (is_evil(d) || in_evil_semigroup(d))
              && (is_evil(q) || in_evil_semigroup(q)) ) {
                res = true;
                break;
            }
        }
    }
    *s = res;
    return res;
}

static inline bool in_odious_semigroup(idx_t n)
{
    if (n == 1) return true;
    ensure_mem(n);
    signed char *s = &odious_mem[n];
    if (*s != -1) return *s;

    bool res = false;
    if (is_odious(n))
        res = true;
    else {
        idx_t lim = floor_sqrt_u64(n);
        for (idx_t d = 2; d <= lim; ++d) {
            if (n % d != 0) continue;
            idx_t q = n / d;
            if ( (is_odious(d) || in_odious_semigroup(d))
              && (is_odious(q) || in_odious_semigroup(q)) ) {
                res = true;
                break;
            }
        }
    }
    *s = res;
    return res;
}

/* ---------- sequence generator ----------------------------------- */
static seq_t *a_terms = NULL;
static size_t a_len = 0;
static size_t a_cap = 0;
static idx_t a_next_candidate = 1;

static void ensure_terms_cap(size_t needed)
{
    if (a_cap >= needed) return;
    size_t new_cap = a_cap ? a_cap << 1 : 1;
    while (new_cap < needed) new_cap <<= 1;
    seq_t *tmp = (seq_t*)realloc(a_terms, new_cap * sizeof(seq_t));
    if (!tmp) exit(1);
    a_terms = tmp;
    a_cap = new_cap;
}

static inline bool qualifies(idx_t n)
{
    if (n == 1) return true;
    return in_evil_semigroup(n) && in_odious_semigroup(n);
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;          /* offset handling */

    while (a_len < n) {
        idx_t cand = a_next_candidate;
        if (qualifies(cand)) {
            ensure_terms_cap(a_len + 1);
            a_terms[a_len++] = (seq_t)cand;
        }
        ++a_next_candidate;
    }
    return a_terms[n - 1];
}
