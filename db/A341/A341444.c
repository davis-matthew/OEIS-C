/*
 * A341444  Dirichlet inverse of A083399, where A083399(n) = 1 + omega(n).
 * https://oeis.org/A341444
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  sign
 * Formula:   a(1) = 1; for n > 1, a(n) = -∑_{d|n, d<n} (1+ω(n/d))·a(d)
 * Range:     i8 n <= 359, i16 n <= 8957, i32 n <= 8957, i64 n <= 8957,
 *            i128 n <= 8957, big any n
 * Helpers:   count_distinct_primes
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* where ω(m) = number of distinct prime divisors of m. */
/* This implementation memoizes results in a static array and recomputes
   values on demand using the recurrence.  Divisors are generated by a
   simple O(√n) loop. */
#include <stdlib.h>
#include <stdint.h>
#include "../utils/count_distinct_primes.h"

seq_t a(idx_t n)
{
    /* static cache for previously computed values */
    static seq_t *cache = NULL;          /* allocated for indices 1..max_cached */
    static idx_t cache_size = 0;         /* current maximum index cached     */

    /* allocate or grow cache to hold up to n */
    if (n > cache_size) {
        seq_t *new_cache = NULL;
        if (cache == NULL) {
            /* first allocation; also reserve index 0 unused */
            new_cache = (seq_t *)malloc((n + 1) * sizeof(seq_t));
        } else {
            new_cache = (seq_t *)realloc(cache, (n + 1) * sizeof(seq_t));
        }
        cache = new_cache;

        /* initialise the first value */
        if (cache_size == 0) {
            cache[1] = 1;
        }

        /* compute all values from cache_size+1 up to n */
        for (idx_t m = cache_size + 1; m <= n; ++m) {
            if (m == 1) {
                /* already set */
                continue;
            }
            seq_t sum = 0;
            for (idx_t d = 1; d * d <= m; ++d) {
                if (m % d == 0) {
                    /* d is a divisor of m */
                    if (d < m) {
                        idx_t q = m / d;                /* n/d  */
                        seq_t f = 1 + (seq_t)count_distinct_primes((uint64_t)q);
                        sum += f * cache[d];
                    }
                    idx_t d2 = m / d;
                    if (d2 != d && d2 < m) {
                        idx_t q2 = m / d2;
                        seq_t f2 = 1 + (seq_t)count_distinct_primes((uint64_t)q2);
                        sum += f2 * cache[d2];
                    }
                }
            }
            cache[m] = -sum;
        }
        cache_size = n;
    }
    return cache[n];
}
