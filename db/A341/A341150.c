/*
 * A341150  Triangle read by rows, lower triangle of the all-zeros matrix
 *          modified step by step with T(0,0) = 1, then at each step, if
 *          T(n,k) has changed in previous step, increase T(n+k,k) and
 *          T(3n+1-2k,2n+1-k) by 1.
 * https://oeis.org/A341150
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, tabl
 * Formula:   not stated
 * Range:     u8 n <= 90, u16 n <= 90, u32 n <= 90, u64 n <= 90, u128 n <= 90,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
 * Figure out the triangle T(n,k) generated by the rules:
 *  T(0,0) = 1, all other entries start at 0.
 *  Whenever T(n,k) has been increased (i.e., its value is >0 at the time
 *  it is processed), increase by 1
 *     * T(n+k,k)  if k > 0      (the self‑target for k = 0 is ignored)
 *     * T(3n+1-2k, 2n+1-k).
 *  The process is acyclic because all target indices satisfy 
 *  i > n whenever k > 0, and for k = 0 the target is the same cell
 *  (which is omitted).  The value added to each entry is the total
 *  number of distinct paths from the root to that entry.
 *
 *  The sequence a(n) is obtained by reading the triangle row by row:
 *  a(0) = T(0,0), a(1) = T(1,0), a(2) = T(1,1), a(3) = T(2,0), …
 *
 *  The following implementation computes the required value by a dynamic
 *  programming fill of the triangle up to the row containing index n.
 *  It works for any integer type seq_t and idx_t supplied by the build
 *  (sequences of arbitrary length are handled via the type seq_t).
 *
 *  Complexity:  O(r^2) where r ≈ sqrt(2 n).
 */

#include <stdlib.h>

/* ------------------------------------------------------------------ */
/* Helper: convert triangle coordinates (n,k) to a linear array index */
/* The number of elements in rows 0..(n-1) is n*(n+1)/2 */
static inline size_t tri_index(idx_t n, idx_t k)
{
    return (size_t)(n * (n + 1) / 2 + k);
}

/* ------------------------------------------------------------------ */
/* Main function required by the test harness */
seq_t a(idx_t n)
{
    /* Determine the minimum row r so that the total number of elements
       up to that row exceeds the requested index n. */
    idx_t r = 0;
    while ((r + 1) * (r + 2) / 2 <= n) {
        ++r;
    }
    /* Total number of elements up to row r */
    idx_t total = (r + 1) * (r + 2) / 2;
    /* Allocate the array that will hold all values of the triangle */
    seq_t *tri = (seq_t*)calloc((size_t)total, sizeof(seq_t));
    if (tri == NULL) {
        /* Out of memory; return 0 as a fallback (should not happen). */
        return (seq_t)0;
    }

    /* Initialize the root */
    tri[tri_index(0, 0)] = (seq_t)1;

    /* Fill the triangle row by row. */
    for (idx_t i = 0; i <= r; ++i) {
        for (idx_t j = 0; j <= i; ++j) {
            seq_t val = tri[tri_index(i, j)];
            if (val == (seq_t)0) {
                continue;  /* nothing to propagate */
            }

            /* First target: (i+j, j) – only if j > 0 to avoid the
               self‑target at column 0. */
            if (j != (idx_t)0) {
                idx_t ni = i + j;
                if (ni <= r) {
                    tri[tri_index(ni, j)] += val;
                }
            }

            /* Second target: (3i+1-2j, 2i+1-j) */
            idx_t ni2 = 3 * i + (idx_t)1 - (idx_t)2 * j;
            idx_t nj2 = 2 * i + (idx_t)1 - j;
            if (ni2 <= r) {
                tri[tri_index(ni2, nj2)] += val;
            }
        }
    }

    seq_t result = tri[(size_t)n];
    free(tri);
    return result;
}
