/*
 * A255357  Natural numbers n, other than multiples of 10, such that n, n^2
 *          and n^3 lack the digit 1 in their decimal expansion.
 * https://oeis.org/A255357
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, look
 * Formula:   not stated
 * Range:     u8 n <= 21, u16 n <= 1483, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 78 terms through n = 9922 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A255357: numbers n (not multiples of 10) such that n, n² and n³
   have no digit 1 in their decimal representation.  The terms are
   generated by a brute‑force search. */

#include <stdbool.h>
#include <stddef.h>   /* size_t */
#include <stdlib.h>
#include "../utils/mem.h"

/* Append a value to the cached array, expanding it if necessary.  `p` is a
   pointer to the array pointer. */
static void append_candidate(seq_t **p, size_t *len, size_t *cap, seq_t val)
{
    if (*len == *cap) {
        size_t newcap = (*cap == 0) ? 16 : (*cap << 1);
        seq_t *tmp = mem_resize(seq_t, *p, newcap);
        if (!tmp) {
            exit(EXIT_FAILURE);
        }
        *p = tmp;
        *cap = newcap;
    }
    (*p)[*len] = val;
    (*len)++;
}

/* Helper: test whether a 64‑bit integer contains digit 1. */
static inline bool no_digit_one_uint64(uint64_t x)
{
    while (x) {
        if ((x % 10U) == 1U) return false;
        x /= 10U;
    }
    return true;
}

/* Cache of found terms.  Memory is managed by append_candidate. */
static seq_t *cache = NULL;
static size_t cached = 0;    /* number of terms stored */
static size_t cap = 0;       /* capacity of cache buffer */
/* Next integer to examine (always >= 2). */
static idx_t candidate = 2;

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* guard against zero, though offset is 1 */

    /* Grow the cache until it holds at least n terms. */
    while (cached < n)
    {
        /* Skip numbers divisible by 10. */
        while ((candidate % 10U) == 0U) ++candidate;

        bool ok = true;

        /* Test candidate itself. */
        if (!no_digit_one_uint64(candidate)) ok = false;

        /* Test candidate². */
        if (ok) {
            uint64_t sq = candidate * candidate;
            if (!no_digit_one_uint64(sq)) ok = false;
        }

        /* Test candidate³. */
        if (ok) {
            uint64_t sq = candidate * candidate;
            uint64_t cube = sq * candidate;
            if (!no_digit_one_uint64(cube)) ok = false;
        }

        if (ok) {
            /* Store the term as seq_t.  If seq_t is an arbitrary‑precision
               type the cast is harmless; for small types the value is assumed
               to fit in the tested range. */
            append_candidate(&cache, &cached, &cap, (seq_t)candidate);
        }

        ++candidate;
    }

    return cache[n - 1];
}
