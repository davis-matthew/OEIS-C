/*  a(n) is the symmetric sum a_k for k such that
 *  n lies in the k‑th antidiagonal of the triangle
 *  a(m,k) = elementary symmetric sum of order k
 *  of the set {1,2,5,6,…,m+2} (no 3,4).
 *  For m = 0,1,2 we use the hard‑coded rows.
 *  For m ≥ 3 the row is generated by the recurrence
 *  e_k += e_{k-1}*x for every element x of the set.
 */
#include <stdlib.h>
#include "../utils/mem.h"

/* ---- helper: compute a single row of the triangle ---- */
static seq_t *row_for_m(idx_t m)
{
    if (m == 0) {
        seq_t *r = mem_new(seq_t, 1);
        r[0] = 1;
        return r;
    }
    if (m == 1) {
        seq_t *r = mem_new(seq_t, 2);
        r[0] = 1; r[1] = 1;
        return r;
    }
    if (m == 2) {
        seq_t *r = mem_new(seq_t, 3);
        r[0] = 1; r[1] = 3; r[2] = 2;
        return r;
    }

    /* m >= 3: build the row by adding each element of the set */
    seq_t *row = mem_new(seq_t, (size_t)(m + 1));
    row[0] = 1;
    /* iterate through all numbers from 1 to m+2, skipping 3 and 4 */
    for (idx_t num = 1; num <= m + 2; ++num) {
        if (num == 3 || num == 4) continue;
        for (idx_t i = m; i >= 1; --i) {
            row[i] = row[i] + row[i - 1] * (seq_t)num;
        }
    }
    return row;
}

/* ---- helper: largest m with m*(m+1)/2 <= n ---- */
static idx_t triangular_inverse(idx_t n)
{
    /* binary search on m */
    idx_t low = 0, high = 1;
    while ((high * (high + 1) / 2) <= n)
        high <<= 1;            /* double until too large */
    while (low <= high) {
        idx_t mid = low + ((high - low) >> 1);
        idx_t t = mid * (mid + 1) / 2;
        if (t <= n)
            low = mid + 1;
        else
            high = mid - 1;
    }
    return high;     /* largest m with T_m <= n */
}

/* ---------------------------------------------------- */
seq_t a(idx_t n)
{
    idx_t m = triangular_inverse(n);
    idx_t k = n - m * (m + 1) / 2;   /* k = n - T_m  */
    seq_t *row = row_for_m(m);       /* row of length m+1  */
    seq_t ans  = row[k];
    mem_free(row);
    return ans;
}
