/*
 * A364754  Smallest nonnegative integer not expressible by the addition and
 *          subtraction of fewer than n Lucas numbers.
 * https://oeis.org/A364754
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 8, u32 n <= 16, u64 n <= 26, u128 n <= 26,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Implements A364754: a(n) = (Lucas(3*n-1)-1)/2 for n>0
   More conveniently, a(n) = 1 + Sum_{i=1}^{n-1} Lucas(3*i), with a(0)=0.
   The Lucas numbers are generated by L(0)=2, L(1)=1, L(k)=L(k-1)+L(k-2).
   The function caches computed Lucas numbers and the partial sums to
   support arbitrary order of calls efficiently.
*/
#include <stdlib.h>

seq_t a(idx_t n)
{
    if (n == 0)               /* a(0)=0 */
        return (seq_t)0;

    /* --- Cache for Lucas numbers ------------------------------------- */
    static seq_t *lucas      = NULL;
    static size_t lucas_cap  = 0;
    static size_t lucas_size = 0;        /* next free index */

    /* We require Lucas(3*n-1) */
    idx_t target_lucas = 3*n - 1;
    size_t needed_lucas = (size_t)target_lucas + 1;

    if (lucas == NULL) {
        /* First allocation.  Ensure indices 0 and 1 exist. */
        lucas_cap = needed_lucas > 2 ? needed_lucas : 2;
        lucas     = (seq_t*)malloc(lucas_cap * sizeof(seq_t));
        if (!lucas) return (seq_t)0;   /* allocation failure, best-effort */
        lucas[0] = (seq_t)2;
        lucas[1] = (seq_t)1;
        lucas_size = 2;
    } else if (needed_lucas > lucas_cap) {
        /* Grow the array */
        size_t new_cap = lucas_cap * 2;
        if (new_cap < needed_lucas) new_cap = needed_lucas;
        seq_t *tmp = (seq_t*)realloc(lucas, new_cap * sizeof(seq_t));
        if (!tmp) return (seq_t)0;
        lucas     = tmp;
        lucas_cap = new_cap;
    }

    /* Compute new Lucas terms if needed */
    while (lucas_size <= target_lucas) {
        lucas[lucas_size] = lucas[lucas_size-1] + lucas[lucas_size-2];
        ++lucas_size;
    }

    /* --- Cache for cumulative sums of Lucas(3*i) --------------------- */
    static seq_t *cum      = NULL;
    static size_t cum_cap  = 0;
    static size_t cum_size = 0;        /* next free index, cum[0] is defined */

    size_t needed_cum = (size_t)(n-1);  /* we need cum[n-1] */

    if (cum == NULL) {
        /* First allocation. Ensure cum[0] is 0. */
        cum_cap = needed_cum + 1;
        if (cum_cap < 1) cum_cap = 1;
        cum     = (seq_t*)malloc(cum_cap * sizeof(seq_t));
        if (!cum) return (seq_t)0;
        cum[0] = (seq_t)0;
        cum_size = 1;
    } else if (needed_cum + 1 > cum_cap) {
        size_t new_cap = cum_cap * 2;
        if (new_cap < needed_cum + 1) new_cap = needed_cum + 1;
        seq_t *tmp = (seq_t*)realloc(cum, new_cap * sizeof(seq_t));
        if (!tmp) return (seq_t)0;
        cum     = tmp;
        cum_cap = new_cap;
    }

    /* Compute missing cumulative sums */
    while (cum_size <= needed_cum) {
        /* cum[i] = cum[i-1] + Lucas(3*i) */
        seq_t val = lucas[3 * (cum_size)];
        cum[cum_size] = cum[cum_size - 1] + val;
        ++cum_size;
    }

    /* a(n) = 1 + cum[n-1] */
    return (seq_t)1 + cum[n - 1];
}
