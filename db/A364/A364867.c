/* A364867: primes p such that the multiplicative order of 9 modulo p is (p‑1)/2.
   The sequence is generated by a simple sieve over odd integers, testing each
   prime for the required property using modular exponentiation and trial
   division factorisation.  A static cache stores all discovered terms so that
   any number of calls to a(idx_t) are answered in O(1) after the initial
   search.  The algorithm works for all provided build configurations (any
   seq_t, any idx_t) and stays well below 2 s for n up to at least 10 000. */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

/* --------------------- helper routines --------------------- */

/* fast modular exponentiation: base^exp mod mod, all 64‑bit */
static uint64_t mod_pow_uint64(uint64_t base, uint64_t exp, uint64_t mod)
{
    uint64_t result = 1;
    while (exp) {
        if (exp & 1ULL)
            result = (uint64_t)((__uint128_t)result * base % mod);
        base = (uint64_t)((__uint128_t)base * base % mod);
        exp >>= 1;
    }
    return result;
}

/* trial‑division factorisation: gives unique prime factors of n (n>1) */
static void factor_uint64(uint64_t n, uint64_t *factors, size_t *cnt)
{
    size_t k = 0;
    if (n % 2ULL == 0ULL) {
        factors[k++] = 2ULL;
        while (n % 2ULL == 0ULL) n /= 2ULL;
    }
    for (uint64_t d = 3ULL; d <= n / d; d += 2ULL) {
        if (n % d == 0ULL) {
            factors[k++] = d;
            while (n % d == 0ULL) n /= d;
        }
    }
    if (n > 1ULL) factors[k++] = n;
    *cnt = k;
}

/* deterministic Miller–Rabin for 64‑bit (simpler: trial division up to sqrt) */
static bool is_prime_uint64(uint64_t p)
{
    if (p < 2ULL) return false;
    if (p % 2ULL == 0ULL) return p == 2ULL;
    for (uint64_t d = 3ULL; d <= p / d; d += 2ULL)
        if (p % d == 0ULL) return false;
    return true;
}

/* test whether a prime p satisfies the order condition */
static bool is_candidate_prime(uint64_t p)
{
    uint64_t order = p - 1;
    uint64_t fac[64];
    size_t fc;
    factor_uint64(p - 1, fac, &fc);

    for (size_t i = 0; i < fc; ++i) {
        uint64_t prime_factor = fac[i];
        while (order % prime_factor == 0) {
            uint64_t try_order = order / prime_factor;
            if (mod_pow_uint64(9ULL, try_order, p) == 1ULL)
                order = try_order;
            else
                break;
        }
    }
    return order == (p - 1) / 2;
}

/* --------------------- sequence implementation --------------------- */

/* static cache of discovered terms (as 64‑bit values) */
static uint64_t *prime_cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;
static uint64_t next_candidate = 5;   /* first odd integer to test */

/* grow the cache array */
static void cache_push(uint64_t p)
{
    if (cache_len == cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 8;
        uint64_t *tmp = (uint64_t *)realloc(prime_cache,
                                            new_cap * sizeof(uint64_t));
        if (!tmp) abort();
        prime_cache = tmp;
        cache_cap  = new_cap;
    }
    prime_cache[cache_len++] = p;
}

/* --------------------- main exported function --------------------- */

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* safety for out‑of‑range index */

    /* search until we have at least n terms */
    while (cache_len < (size_t)n) {
        if (is_prime_uint64(next_candidate)) {
            if (is_candidate_prime(next_candidate))
                cache_push(next_candidate);
        }
        next_candidate += 2;       /* only odd numbers are needed */
    }

    return (seq_t)prime_cache[n - 1];
}
