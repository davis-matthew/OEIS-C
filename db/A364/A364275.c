/*
 * A364275  Lexicographically earliest sequence of distinct positive terms
 *          such that the cumulative sum Q(n) of the first n terms of the
 *          sequence has at least one duplicated digit.
 * https://oeis.org/A364275
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 20, u16 n <= 2745, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   digit_counts
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A364275:
 *  Lexicographically earliest set of distinct positive integers a(n) such that
 *  the cumulative sum Q(n)=∑_{i=1}^n a(i) contains at least one duplicated
 *  decimal digit.
 *
 *  The sequence is generated by a greedy search: at each step choose the
 *  smallest unused integer that makes the new cumulative sum have a
 *  duplicated digit.
 */

#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>
#include "../utils/digit_counts.h"   /* digit_counts(x, cnt[10]) */

/* Ensure a bool array can be indexed at least up to 'req' (inclusive). */
static void ensure_used_capacity(size_t req, bool **used, size_t *cap)
{
    if (req < *cap) return;
    size_t new_cap = *cap;
    if (new_cap == 0) new_cap = 1;
    while (new_cap <= req) new_cap <<= 1;
    bool *tmp = (bool *)realloc(*used, new_cap);
    if (!tmp) abort();           /* should not happen */
    for (size_t i = *cap; i < new_cap; ++i) tmp[i] = false;
    *used = tmp;
    *cap = new_cap;
}

/* Return true iff x has at least one repeated decimal digit. */
static bool has_duplicate_digit(seq_t x)
{
    unsigned char cnt[10] = {0};
    digit_counts(x, cnt);
    for (int d = 0; d < 10; ++d) {
        if (cnt[d] >= 2u) return true;
    }
    return false;
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;  /* undefined, return 0 */

    /* Static state shared across calls. */
    static seq_t *seq  = NULL;      /* array of terms */
    static size_t     seq_cap = 0;  /* capacity of seq[]   */
    static idx_t      seq_len = 0;  /* number of terms stored */
    static seq_t      cumulative_sum = 0; /* sum of stored terms */

    static bool *used = NULL;        /* used[i]==true means i already chosen */
    static size_t used_cap = 0;      /* capacity of 'used' array */

    static idx_t min_unused = 1;     /* smallest unused positive integer */

    /* Build terms up to requested n. */
    while (seq_len < n) {
        /* Find the lexicographically earliest candidate. */
        seq_t cand = min_unused;
        for (;;) {
            /* Ensure we can index used[cand]. */
            if ((size_t)cand >= used_cap)
                ensure_used_capacity((size_t)cand, &used, &used_cap);

            if (!used[(size_t)cand]) {
                seq_t test_sum = cumulative_sum + cand;
                if (has_duplicate_digit(test_sum))
                    break;           /* candidate found */
            }
            ++cand;
        }

        /* Record the chosen term. */
        if (seq_len >= seq_cap) {
            size_t new_cap = seq_cap ? seq_cap << 1 : 4;
            seq_t *tmp = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
            if (!tmp) abort();    /* should not happen */
            seq = tmp;
            seq_cap = new_cap;
        }
        seq[seq_len++] = cand;
        cumulative_sum += cand;

        /* Mark the term as used. */
        if ((size_t)cand >= used_cap)
            ensure_used_capacity((size_t)cand, &used, &used_cap);
        used[(size_t)cand] = true;

        /* Update min_unused to the next smallest unused integer. */
        while (min_unused < used_cap && used[(size_t)min_unused])
            ++min_unused;
        /* Ensure capacity in case we just reached used_cap. */
        if (min_unused >= used_cap)
            ensure_used_capacity(min_unused, &used, &used_cap);
    }

    return seq[n - 1];
}
