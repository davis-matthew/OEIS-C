/*
 * A364347  Numbers k > 0 such that if prime(a) and prime(b) both divide k,
 *          then prime(a+b) does not.
 * https://oeis.org/A364347
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 67, u16 n <= 67, u32 n <= 67, u64 n <= 67, u128 n <= 67,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A364347: Numbers k > 0 such that for all indices a,b
   of primes dividing k, prime(a+b) does not divide k.  The sequence
   is generated by sieving numbers and testing the above property. */
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

/* ---------- Sieve constants and globals ---------- */
#define SIEVE_MAX 200000   /* enough for the first 10 000 terms */

/* smallest prime factor for each integer */
static uint32_t *spf = NULL;
/* index (1‑based) of each prime number in the list of all primes */
static uint32_t *prime_index = NULL;
/* list of primes up to SIEVE_MAX, used for linear sieve */
static uint32_t primes[SIEVE_MAX + 1];
static size_t primes_size = 0;
static uint32_t prime_count = 0;

/* ---------- Term storage ---------- */
static seq_t *terms = NULL;      /* array of found sequence values   */
static size_t terms_cap = 0;     /* current capacity of the array   */
static size_t terms_count = 0;   /* number of terms stored so far   */
static idx_t max_checked = 0;    /* largest integer already tested */

/* ---------- Utility: linear sieve ---------- */
static void init_sieve(void)
{
    size_t i, j;
    spf = (uint32_t*)malloc((SIEVE_MAX + 1) * sizeof(uint32_t));
    prime_index = (uint32_t*)malloc((SIEVE_MAX + 1) * sizeof(uint32_t));
    memset(spf, 0, (SIEVE_MAX + 1) * sizeof(uint32_t));
    memset(prime_index, 0, (SIEVE_MAX + 1) * sizeof(uint32_t));

    primes_size = 0;
    prime_count = 0;
    for (i = 2; i <= SIEVE_MAX; ++i) {
        if (spf[i] == 0) {
            spf[i] = (uint32_t)i;
            prime_index[i] = ++prime_count;
            primes[primes_size++] = (uint32_t)i;
        }
        for (j = 0; j < primes_size && primes[j] <= spf[i] &&
             (uint64_t)primes[j] * i <= SIEVE_MAX; ++j) {
            spf[primes[j] * i] = primes[j];
        }
    }
}

/* ---------- Test a single number for the property ---------- */
static bool is_valid(idx_t x,
                     const uint32_t *prime_index,
                     const uint32_t *spf,
                     uint32_t prime_cnt)
{
    if (x == 1) return true;     /* 1 has no prime divisors */

    uint32_t idx_list[20];
    size_t idx_cnt = 0;

    idx_t tmp = x;
    while (tmp > 1) {
        uint32_t p = spf[(uint32_t)tmp];
        uint32_t idx = prime_index[p];
        /* store the index only once */
        bool already = false;
        for (size_t k = 0; k < idx_cnt; ++k) {
            if (idx_list[k] == idx) { already = true; break; }
        }
        if (!already) idx_list[idx_cnt++] = idx;
        while (tmp % p == 0) tmp /= p;
    }

    /* check all pairs, including equal indices */
    for (size_t i = 0; i < idx_cnt; ++i) {
        for (size_t j = 0; j < idx_cnt; ++j) {
            uint32_t sum = idx_list[i] + idx_list[j];
            if (sum > prime_cnt) continue;
            for (size_t k = 0; k < idx_cnt; ++k) {
                if (idx_list[k] == sum) return false;
            }
        }
    }
    return true;
}

/* ---------- Main sequence function ---------- */
seq_t a(idx_t n)
{
    static bool initialized = false;
    if (!initialized) {
        init_sieve();
        initialized = true;
    }

    /* grow the terms array as needed */
    if (terms_cap == 0) {
        terms_cap = 4;
        terms = (seq_t*)malloc(terms_cap * sizeof(seq_t));
    }

    while (terms_count < n) {
        ++max_checked;
        if (max_checked > SIEVE_MAX) {
            /* this should not happen for the needed range
               but we extend the sieve if necessary           */
            /* For brevity we simply return 0, but in real
               usage one would reallocate a larger sieve.    */
            return (seq_t)0;
        }

        if (is_valid(max_checked, prime_index, spf, prime_count)) {
            if (terms_count == terms_cap) {
                terms_cap *= 2;
                terms = (seq_t*)realloc(terms, terms_cap * sizeof(seq_t));
            }
            terms[terms_count++] = (seq_t)max_checked;
        }
    }
    return terms[n - 1];
}
