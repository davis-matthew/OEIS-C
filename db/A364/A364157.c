/* A364157: nth integer whose rounded‑down (floor) mean of prime factors
   (with multiplicity) is 2.  The sequence is generated by testing
   successive integers and selecting those whose mean of prime factors
   satisfies floor(mean) == 2.  The routine caches results so that
   repeated calls with arbitrary indices are efficient. */
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include <stddef.h>
#include "../utils/smallest_prime_factor.h"
#include "../utils/mem.h"

/* Append a value to the cached array, expanding it if necessary.  `p` is a
   pointer to the array pointer. */
static void append_candidate(seq_t **p, size_t *len, size_t *cap, seq_t val)
{
    if (*len == *cap) {
        size_t newcap = (*cap == 0) ? 16 : (*cap << 1);
        seq_t *tmp = mem_resize(seq_t, *p, newcap);
        if (!tmp) {
            exit(EXIT_FAILURE);
        }
        *p = tmp;
        *cap = newcap;
    }
    (*p)[*len] = val;
    (*len)++;
}

/* Return true if the integer m has floor(mean of prime factors) == 2. */
static bool _is_good (uint64_t m)
{
    uint64_t sum = 0;
    uint64_t total = 0;
    uint64_t x = m;

    while (x > 1U) {
        uint64_t p = smallest_prime_factor (x);
        sum += p;
        ++total;
        x /= p;
    }
    return (sum / total) == 2U;
}

/* Public API ----------------------------------------------------------- */
seq_t a (idx_t n)
{
    if (n < 1U) return 0;   /* safety for indices below the offset */

    static seq_t *cache = NULL;    /* cached values   */
    static size_t cache_len = 0;   /* number of cached terms */
    static size_t cache_cap = 0;   /* capacity of cache     */
    static idx_t last_checked = 1U;/* last integer examined */

    /* Ensure cache contains at least n terms */
    while (cache_len < (size_t)n) {
        ++last_checked;
        if (_is_good ((uint64_t)last_checked)) {
            append_candidate (&cache, &cache_len, &cache_cap,
                              (seq_t)last_checked);
        }
    }
    return cache[(size_t)n - 1U];
}
