/*  OEIS A144711
    numbers n such that the average of squares of the distinct prime divisors of n
    is a perfect square integer.  That is, if p1,…,pr are the distinct primes of n,
    then (p1²+…+pr²)/r = c² for some integer c.  All prime powers satisfy
    this, and the remaining terms are exactly the numbers in A255580.
    The sequence can be generated by a simple incremental sieve and trial
    factorisation.  */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

#include <stddef.h>
#include <math.h>
#include "../utils/build_spf.h"
#include "../utils/ipow_i32.h"
#include "../utils/mem.h"

/* Floor square root by binary search */
static inline seq_t floor_sqrt(seq_t x)
{
    seq_t lo = 0, hi = 1;
    while (ipow_i32(hi, 2) <= x)
        hi <<= 1;
    while (lo < hi)
    {
        seq_t mid = (lo + hi) >> 1;
        seq_t mid2 = mid * mid;
        if (mid2 <= x)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

/* allocate an array of seq_t of given length (may be 0) */
static seq_t *seq_alloc_array(size_t n)
{
    return mem_new(seq_t, n);
}

static void seq_free_array(seq_t* p)          { mem_free(p); }

/* ----------  Helper: integer square test ---------- */
static inline bool is_square(seq_t x)
{
    seq_t r = floor_sqrt(x);
    return r * r == x;
}

/* ----------  SPF table management ---------- */
static idx_t *spf = NULL;          /* smallest prime factor array */
static idx_t spf_limit = 0;        /* size of spf (inclusive) */

static void ensure_spf(idx_t limit)
{
    if (limit <= spf_limit) return;
    if (spf) free(spf);
    build_spf(limit, &spf);
    spf_limit = limit;
}

/* ----------  Cache of sequence terms ---------- */
static seq_t *cache = NULL;
static size_t cache_cap = 0;      /* allocated length of cache */
static size_t term_count = 0;     /* number of terms stored */

static void grow_cache(size_t new_cap)
{
    seq_t *new_cache = seq_alloc_array(new_cap);
    if (cache) {
        mem_copy(new_cache, cache, term_count * sizeof(seq_t));
        seq_free_array(cache);
    }
    cache = new_cache;
    cache_cap = new_cap;
}

/* ----------  Main sequence function ---------- */
seq_t a(idx_t n)
{
    /* Initialise static data on first call */
    static bool first = true;
    static idx_t next_val = 2;        /* next integer to test */

    if (first) {
        cache_cap = 64;
        cache = seq_alloc_array(cache_cap);
        /* Choose a sieve limit that comfortably covers the required range.
           For n ≤ 10000 the 10 000th term is below 200 000, so 500 000 is safe. */
        ensure_spf(500000);
        first = false;
    }

    /* Generate terms until we have at least n of them */
    while (term_count < (size_t)n) {

        idx_t val = next_val;
        idx_t tmp = val;
        idx_t prev = 0;
        seq_t sum_squares = 0;
        idx_t prime_cnt = 0;

        /* Factorise val using the SPF table */
        while (tmp > 1) {
            idx_t p = spf[tmp];
            if (p != prev) {
                prime_cnt++;
                sum_squares += (seq_t)p * (seq_t)p;
                prev = p;
            }
            tmp /= p;
        }

        bool ok = (prime_cnt == 1);                 /* prime powers always qualify */
        if (!ok && prime_cnt > 1) {
            if (sum_squares % (seq_t)prime_cnt == 0) {
                seq_t avg = sum_squares / (seq_t)prime_cnt;
                ok = is_square(avg);
            }
        }

        if (ok) {
            if (term_count >= cache_cap)
                grow_cache(cache_cap * 2);
            cache[term_count++] = (seq_t)val;
        }

        next_val++;
    }

    return cache[(size_t)n - 1];
}
