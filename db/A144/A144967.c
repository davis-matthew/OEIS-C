/*
 * A144967  Semiprimes n such that n + 1 is divisible by the sum of decimal
 *          digits of n.
 * https://oeis.org/A144967
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 46, u32 n <= 46, u64 n <= 46, u128 n <= 46,
 *            big any n
 * Helpers:   alloc_seq_array, free_seq_array
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: semiprimes n such that n+1 is divisible by the sum of decimal
   digits of n.  No simple formula; the sequence is generated by a search
   over the integers. */
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <stddef.h>
#include "../utils/alloc_seq_array.h"
#include "../utils/free_seq_array.h"

/* Smallest prime factor (trial division). */
static uint64_t _smallest_prime_factor(uint64_t n)
{
    if (n < 2) return n;
    if (n % 2 == 0) return 2;
    if (n % 3 == 0) return 3;
    for (uint64_t d = 5; d * d <= n; d += 6) {
        if (n % d == 0)     return d;
        if (n % (d + 2) == 0) return d + 2;
    }
    return n;
}

/* Primality test (trial division). */
static bool is_prime_uint64(uint64_t n)
{
    if (n < 2) return false;
    if (n % 2 == 0) return n == 2;
    if (n % 3 == 0) return n == 3;
    for (uint64_t d = 5; d * d <= n; d += 6) {
        if (n % d == 0)     return false;
        if (n % (d + 2) == 0) return false;
    }
    return true;
}

/* Check whether n is a semiprime (product of exactly two primes). */
static bool is_semiprime_uint64(uint64_t n)
{
    if (n < 4) return false;
    uint64_t p = _smallest_prime_factor(n);
    if (p == n) return false;           /* n is prime */
    uint64_t q = n / p;
    if (q <= 1) return false;
    if (p == q) return true;            /* square of a prime */
    return is_prime_uint64(q);
}

/* Sum of decimal digits of n. */
static uint64_t digit_sum_uint64(uint64_t n)
{
    uint64_t sum = 0;
    while (n > 0) {
        sum += n % 10;
        n /= 10;
    }
    return sum;
}

/* Dynamic cache of found sequence values. */
static seq_t *seq_cache = NULL;   /* array of found terms */
static size_t  seq_cap   = 0;     /* allocated capacity of seq_cache */
static size_t  seq_len   = 0;     /* number of terms currently cached */
static uint64_t last_checked = 0; /* last candidate n checked */

/* Grow the cache array to at least 'need' elements. */
static void ensure_cap(size_t need)
{
    if (seq_cap >= need) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    if (new_cap < need) new_cap = need;
    seq_t *new_arr = alloc_seq_array(new_cap);
    for (size_t i = 0; i < seq_len; ++i)
        new_arr[i] = seq_cache[i];
    if (seq_cache)
        free_seq_array(seq_cache);
    seq_cache = new_arr;
    seq_cap = new_cap;
}

/* Append a new term to the cache. */
static void add_cache(seq_t val)
{
    ensure_cap(seq_len + 1);
    seq_cache[seq_len++] = val;
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;           /* offset is 1, guard for n=0 */

    while (seq_len < (size_t)n)
    {
        last_checked++;              /* start from 1 upwards */
        uint64_t cand = last_checked;

        if (!is_semiprime_uint64(cand)) continue;

        uint64_t s = digit_sum_uint64(cand);
        if (s == 0) continue;        /* safety */

        if ((cand + 1) % s == 0)
            add_cache((seq_t)cand);
    }

    return seq_cache[n - 1];
}
