/*
 * A144777  Integers having decimal digital mean equal to zero.
 * https://oeis.org/A144777
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 9, u16 n <= 624, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes integers having decimal digital mean equal to zero.
   Property: 2*digit_sum(n) == 9*digit_count(n).  Only integers with an even
   number of digits are possible. */
#include <stdbool.h>
#include <stdlib.h>

/* Recursive helper that traverses all numbers of length d whose digit sum is
   sum_left.  The numbers are generated in ascending numeric order.  When the
   count reaches target, the result is stored and early termination occurs. */
static bool dfs(idx_t pos, seq_t prefix, idx_t sum_left, idx_t d,
                idx_t *count, idx_t target, seq_t *result)
{
    if (pos == d) {
        if (sum_left == 0) {
            (*count)++;
            if (*count == target) {
                *result = prefix;
                return true;  /* found */
            }
        }
        return false;  /* not found */
    }

    int start = (pos == 0) ? 1 : 0;
    for (int dig = start; dig <= 9; ++dig) {
        idx_t d_val = (idx_t)dig;
        if (d_val > sum_left)
            break;

        /* Prune: remaining sum cannot be achieved with remaining digits. */
        if (sum_left - d_val > 9ULL * (d - pos - 1))
            continue;

        seq_t next = prefix * 10 + (seq_t)dig;
        if (dfs(pos + 1, next, sum_left - d_val, d, count, target, result))
            return true;  /* propagate found */
    }
    return false;  /* not found in this branch */
}

/* Main sequence function.  It generates terms on demand and returns the nth
   term.  The sequence is generated by increasing even digit lengths, and
   numbers within the same length are produced in ascending order. */
seq_t a(idx_t n)
{
    idx_t count = 0;     /* number of terms generated so far */
    seq_t result = 0;

    for (idx_t d = 2; ; d += 2) {             /* even digit lengths only */
        idx_t target_sum = 9ULL * d / 2;       /* required digit sum */

        if (dfs(0, 0, target_sum, d, &count, n, &result))
            return result;   /* found the nth term */
    }
}
