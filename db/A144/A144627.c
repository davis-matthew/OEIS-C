/* Sequence: A144627 – Initial members of triples listed in A144625.
   The terms are generated by concatenating blocks of the form
   (k, k-1, …, 1) for k = 1, 2, 3, …,
   each block followed by a zero padding:
     • for k = 1 the padding consists of two zeros,
     • for k ≥ 2 the padding consists of a single zero.
   The very first element (index 0) is defined to be 0. */

