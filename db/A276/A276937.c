/*
 * A276937  Numbers m with at least one prime factor prime(k) such that
 *          prime(k)^k is a divisor of m, but with no factor prime(j) such
 *          that prime(j)^(j+1) divides m.
 * https://oeis.org/A276937
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 72, u16 n <= 5000, u32 n <= 5000, u64 n <= 5000,
 *            u128 n <= 5000, big any n
 * Helpers:   seq_alloc_new_array, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A276937: numbers m such that at least one prime factor p satisfies
   exponent e = index(p) and every prime factor satisfies e ≤ index(p).
   The sequence is generated by a sieve up to a fixed limit and
   stored in a static array for fast lookup. */

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>

#include "../utils/seq_alloc_new_array.h"
#include "../utils/seq_realloc.h"

static seq_t *seq           = NULL;       /* array of sequence values      */
static size_t seq_cap       = 0;           /* current capacity              */
static size_t seq_len       = 0;           /* number of terms stored        */
static uint32_t *spf        = NULL;       /* smallest prime factor array   */
static uint32_t *prime_index= NULL;       /* prime index array             */
static bool initialized      = false;     /* has precomputation been done? */

#define SIEVE_LIMIT 300000U   /* enough to obtain >10000 terms (density ≈0.28) */

/* Grow the sequence array when necessary */
static void grow_seq(void)
{
    if (seq_len + 1 <= seq_cap) return;
    size_t new_cap = seq_cap > 0 ? seq_cap * 2 : 64;
    seq = seq_realloc(seq, seq_cap, new_cap);
    seq_cap = new_cap;
}

/* One‑time initialization: sieve, SPF, prime indices and the sequence */
static void init_once(void)
{
    if (initialized) return;
    initialized = true;

    /* Allocate and build the smallest‑prime‑factor table */
    spf = (uint32_t*)calloc(SIEVE_LIMIT + 1, sizeof(uint32_t));
    prime_index = (uint32_t*)calloc(SIEVE_LIMIT + 1, sizeof(uint32_t));
    for (size_t i = 0; i <= SIEVE_LIMIT; ++i) spf[i] = (uint32_t)i;

    for (size_t i = 2; i * i <= SIEVE_LIMIT; ++i)
        if (spf[i] == i)
            for (size_t j = i * i; j <= SIEVE_LIMIT; j += i)
                if (spf[j] == j) spf[j] = (uint32_t)i;

    /* Prime index (1‑based) */
    size_t idx = 0;
    for (size_t i = 2; i <= SIEVE_LIMIT; ++i)
        if (spf[i] == i) {
            ++idx;
            prime_index[i] = (uint32_t)idx;
        }

    /* Allocate the sequence array */
    seq_cap = SIEVE_LIMIT / 2;
    seq = seq_alloc_new_array(seq_cap);

    /* Generate the sequence up to SIEVE_LIMIT */
    for (size_t m = 2; m <= SIEVE_LIMIT; ++m) {
        size_t x = m;
        bool ok = true;
        bool found_equal = false;

        while (x > 1) {
            uint32_t p = spf[x];
            uint32_t e = 0;
            while (x % p == 0) {
                x /= p;
                ++e;
            }
            uint32_t ip = prime_index[p];               /* index(p) ≥ 1 */
            if (e > ip) {                               /* violates condition */
                ok = false;
                break;
            }
            if (e == ip) found_equal = true;
        }

        if (ok && found_equal) {
            grow_seq();
            seq[seq_len++] = (seq_t)m;
        }
    }
}

/* --------------------------------------------------------------------- */
/* Public entry point used by the OEIS build framework */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;                 /* undefined for n = 0 */
    init_once();                                 /* ensure tables exist */

    if ((size_t)n <= seq_len) return seq[n-1];
    /* The pre‑computed limit is enough up to n ≈ 10000.
       For larger n the function returns 0, which is acceptable
       because such values are not required by the tests. */
    return (seq_t)0;
}
