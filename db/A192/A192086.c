/*
 * A192086  Numbers n such that the binary weight (A000120) of n^3 is less
 *          than the binary weight of n^2.
 * https://oeis.org/A192086
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 29, u64 n <= 2500, u128 n <= 2500,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A192086: numbers n such that the binary weight of n³ is
   less than the binary weight of n². The function a(n) returns the
   n‑th term (offset 1).  The sequence is generated by brute‑force
   search and cached statically. */

#include <stddef.h>   /* size_t, NULL */
#include <stdlib.h>   /* malloc, realloc */

/* Count 1‑bits in a seq_t value.  Works for unsigned integer
   types and any type satisfying the required operators. */
static unsigned popcount_seq(seq_t x)
{
    unsigned cnt = 0;
    while (x) {
        x &= (x - 1);
        ++cnt;
    }
    return cnt;
}

seq_t a(idx_t n)
{
    static seq_t *terms = NULL;       /* cached terms */
    static size_t  cap   = 0;         /* allocated capacity */
    static size_t  len   = 0;         /* number of terms stored */
    static idx_t   searched = 0;      /* largest integer checked */

    /* Build the cache until it contains at least n terms. */
    while (len < n) {
        ++searched;
        seq_t m    = (seq_t)searched;
        seq_t sq   = m * m;
        seq_t cube = sq * m;
        unsigned pc_sq   = popcount_seq(sq);
        unsigned pc_cube = popcount_seq(cube);
        if (pc_cube < pc_sq) {
            if (len == cap) {
                size_t new_cap = (cap == 0) ? 64 : cap * 2;
                seq_t *tmp = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
                terms = tmp;
                cap   = new_cap;
            }
            terms[len++] = m;
        }
    }
    return terms[n - 1];
}
