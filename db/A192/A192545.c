/*
 * A192545  Numbers such that all numbers are composite when replacing exactly
 *          one digit with another, except the leading digit with zero.
 * https://oeis.org/A192545
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 1721, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: A192545 – numbers for which every one‑digit replacement
   (except replacing the leftmost digit by 0) produces a composite
   number.  The value is generated by testing increasing integers. */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>

/* -----------------------------------------------------------------------
   Helper: extract decimal digits into an array.
   dig[0] is the most significant digit.  len is set to the number of
   digits.  buf must have enough space (at least 128 is plenty for all
   reasonable seq_t sizes used here).

   ----------------------------------------------------------------------- */
static void get_digits(seq_t x, uint8_t *buf, size_t *len)
{
    if (x == 0) {
        *len = 1;
        buf[0] = 0;
        return;
    }
    seq_t tmp = x;
    size_t pos = 0;
    while (tmp > 0) {
        buf[pos++] = (uint8_t)(tmp % 10);
        tmp /= 10;
    }
    *len = pos;
    /* reverse to get most‑significant first */
    for (size_t i = 0; i < pos / 2; ++i) {
        uint8_t t = buf[i];
        buf[i] = buf[pos - 1 - i];
        buf[pos - 1 - i] = t;
    }
}

/* -----------------------------------------------------------------------
   Helper: primality test for seq_t values that fit in the native
   integer range (this is enough for all terms up to n≈10000).
   ----------------------------------------------------------------------- */
static bool is_prime(seq_t n)
{
    if (n < 2) return false;
    if (n % 2 == 0) return n == 2;
    for (seq_t i = 3; i <= n / i; i += 2) {
        if (n % i == 0) return false;
    }
    return true;
}

/* -----------------------------------------------------------------------
   Helper: test whether a given number satisfies the sequence property.
   ----------------------------------------------------------------------- */
static bool good_number(seq_t x)
{
    uint8_t dig[128];
    size_t len, i, j;

    get_digits(x, dig, &len);

    for (i = 0; i < len; ++i) {
        uint8_t orig = dig[i];
        for (j = 0; j <= 9; ++j) {
            if (j == orig) continue;
            /* Skip replacing the leading digit by 0 */
            if (i == 0 && j == 0) continue;

            seq_t y = 0;
            for (size_t k = 0; k < len; ++k) {
                y = y * 10 + (k == i ? j : dig[k]);
            }
            if (is_prime(y)) return false;
        }
    }
    return true;
}

/* -----------------------------------------------------------------------
   Memoised enumeration of the sequence.
   ----------------------------------------------------------------------- */
static seq_t *cache = NULL;
static size_t cache_size = 0;
static size_t cache_cap   = 0;
static seq_t last_val = 199;          /* first candidate is 200 */

/* Append a value to the cache, grow if necessary */
static void cache_append(seq_t val)
{
    if (cache_size == cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 64 : cache_cap * 2;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) abort();          /* out of memory */
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_size++] = val;
}

/* External interface for the OEIS function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;            /* undefined; offset starts at 1 */
    /* If we already have enough terms cached, return immediately */
    if ((idx_t)cache_size >= n) return cache[n - 1];

    /* Generate terms until we have the requested number */
    while ((idx_t)cache_size < n) {
        ++last_val;
        if (good_number(last_val)) cache_append(last_val);
    }
    return cache[n - 1];
}
