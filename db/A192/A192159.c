/*
 * A192159  Monotonic ordering of nonnegative differences 3^i-10^j, for 40>=
 *          i>=0, j>=0.
 * https://oeis.org/A192159
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 10, u16 n <= 31, u32 n <= 42, u64 n <= 42, u128 n <= 42,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation of OEIS sequence A192159:
   Monotonic ordering of all non‑negative differences 3^i – 10^j
   for 0 ≤ i ≤ 40 and j ≥ 0.  The sequence is generated by
   enumerating all such differences, removing duplicates, sorting
   ascending and then answering the n‑th term on demand. */
#include <stdlib.h>
#include <stdint.h>

static int cmp_seq_t(const void *a, const void *b)
{
    const seq_t *x = (const seq_t *)a;
    const seq_t *y = (const seq_t *)b;
    if (*x < *y) return -1;
    if (*x > *y) return 1;
    return 0;
}

seq_t a(idx_t n)
{
    /* Static cache of the generated terms.  41 × 20 = 820 backing
       capacity is more than enough for all 3^i – 10^j with i ≤ 40. */
    static seq_t stored[900];
    static size_t term_count = 0;
    static int initialized = 0;

    if (!initialized) {
        size_t count = 0;
        uint64_t max_val = 0;
        if (sizeof(seq_t) <= 8) {
            /* maximum representable value for the small types */
            switch (sizeof(seq_t)) {
                case 1: max_val = 0xFFULL;       break;
                case 2: max_val = 0xFFFFULL;     break;
                case 4: max_val = 0xFFFFFFFFULL; break;
                case 8: max_val = 0xFFFFFFFFFFFFFFFFULL; break;
            }
        }

        uint64_t pow3 = 1ULL;               /* 3^i */
        for (int i = 0; i <= 40; ++i) {
            uint64_t pow10 = 1ULL;          /* 10^j */
            while (pow10 <= pow3) {
                uint64_t diff = pow3 - pow10;
                if (sizeof(seq_t) <= 8) {
                    if (diff <= max_val)
                        stored[count++] = (seq_t)diff;
                } else {
                    stored[count++] = (seq_t)diff;
                }
                if (pow10 > pow3 / 10) break; /* avoid overflow of pow10 */
                pow10 *= 10;
            }
            if (i < 40) {                 /* prepare next power of 3   */
                pow3 *= 3;
            }
        }

        /* sort and deduplicate the collected values */
        qsort(stored, count, sizeof(seq_t), cmp_seq_t);

        size_t uniq = 0;
        for (size_t i = 0; i < count; ++i) {
            if (uniq == 0 || stored[i] != stored[uniq - 1]) {
                stored[uniq++] = stored[i];
            }
        }
        term_count = uniq;
        initialized = 1;
    }

    if (n == 0 || n > term_count) return 0;
    return stored[(size_t)(n - 1)];
}
