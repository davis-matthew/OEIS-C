/*
 * A307213  Divide the natural numbers into sets of successive sizes
 *          3,4,5,6,7,...,, starting with {1,2,3}. Cycle through each set
 *          until you reach a prime; if the prime was the n-th element in its
 *          set, jump to the n-th element of the next set.
 * https://oeis.org/A307213
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 72, u16 n <= 2543, u32 n <= 4165, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   is_prime_big, seq_realloc, set_start
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence: a(1)=1; thereafter each term is generated by
   traversing successive sets of lengths 3,4,5,…, looking for a prime.
   The position of the found prime in its set is used for the next set,
   and the sequence continues until the requested index is reached. */

#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/is_prime_big.h"
#include "../utils/seq_realloc.h"   /* for seq_realloc */
#include "../utils/set_start.h"

static seq_t *cache = NULL;
static size_t cache_cap = 0;
static size_t cache_len = 0;

/* Current traversal state after the last cached term. */
static idx_t  traversal_j   = 1;      /* set index (j)                */
static idx_t  traversal_pos = 1;      /* position within current set  */
static seq_t  traversal_start;        /* start of current set         */
static seq_t  traversal_val;          /* value to be cached next      */

/* Ensure the cache can store at least 'need' elements. */
static void ensure_capacity(size_t need)
{
    if (need <= cache_cap) return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
    while (new_cap < need) new_cap <<= 1;
    cache = seq_realloc(cache, cache_cap, new_cap);
    cache_cap = new_cap;
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;          /* undefined for n=0, safety */

    idx_t target = n - (idx_t)1;          /* zero‑based index needed */

    /* Initialise traversal state on first use. */
    if (cache_len == 0) {
        traversal_j   = 1;
        traversal_pos = 1;
        traversal_start = set_start(traversal_j);
        traversal_val   = traversal_start + traversal_pos - (seq_t)1;
    }

    /* Generate terms until we have the requested index cached. */
    while (cache_len <= target) {
        ensure_capacity(cache_len + 1);
        cache[cache_len++] = traversal_val;

        /* Decide next traversal state. */
        if (is_prime_big(traversal_val)) {
            /* Move to next set, same relative position. */
            ++traversal_j;
            traversal_start = set_start(traversal_j);
            /* traversal_pos unchanged */
        } else {
            /* Advance within current set. */
            ++traversal_pos;
            if (traversal_pos > traversal_j + (idx_t)2)
                traversal_pos = (idx_t)1;      /* cycle to start of set */
        }
        /* Compute the value for the next term. */
        traversal_val = traversal_start + traversal_pos - (seq_t)1;
    }

    return cache[target];
}
