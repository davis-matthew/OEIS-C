/* Algorithm: Compute a(n) as the first coordinate of the nth point
   in a counter‑clockwise hexagonal spiral.
   The spiral is generated by rings: ring 0 contains the origin,
   ring r has 6 r cells.  For a point in ring r at position k
   (0 ≤ k < 6r) the first coordinate q is
   0: q = r
   1: q = r – 1 – pos
   2: q = –1 – pos
   3: q = –r
   4: q = –r + 1 + pos
   5: q = 1 + pos
   where side = k / r and pos = k % r. */

#include <stdint.h>

seq_t a(idx_t n) {
    if (n == 0) return (seq_t)0;

    /* Find the ring r (r ≥ 1) such that 3*r*(r+1) ≥ n. */
    idx_t r = 1;
    for (;;) {
        unsigned __int128 tmp = (unsigned __int128)3 * r * (r + 1);
        if (tmp >= n) break;
        ++r;
    }

    /* Starting index of ring r (1‑based for ring r>0). */
    unsigned __int128 start = (unsigned __int128)1
                             + (unsigned __int128)3 * (r - 1) * r;
    idx_t offset = n - (idx_t)start;          /* 0 … 6r-1 */
    idx_t side   = offset / r;                /* 0 … 5 */
    idx_t pos    = offset % r;                /* 0 … r-1 */

    seq_t val;
    switch (side) {
        case 0:
            val = (seq_t)r;
            break;
        case 1:
            val = (seq_t)(r - 1 - pos);
            break;
        case 2:
            val = (seq_t)(-(int64_t)1 - (int64_t)pos);
            break;
        case 3:
            val = (seq_t)(-(int64_t)r);
            break;
        case 4:
            val = (seq_t)(-(int64_t)r + 1 + (int64_t)pos);
            break;
        default: /* side 5 */
            val = (seq_t)(1 + (int64_t)pos);
            break;
    }
    return val;
}
