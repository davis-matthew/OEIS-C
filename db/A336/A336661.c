/*
 * A336661  Numbers that have decimal expansion c(1)c(2)...c(n) with distinct
 *          digits that satisfy c(1) <> 0, c(1) is the largest digit, and for
 *          each i in 1..n there is j in 0..2 such that c(i) == 3*c(i-1) + j
 *          (mod 10) (with c(0): = c(n)).
 * https://oeis.org/A336661
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, fini
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 15, u32 n <= 127, u64 n <= 141,
 *            u128 n <= 141, big any n
 * Helpers:   cmp_vals
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A336661: numbers with distinct decimal digits c(1)…c(k) (k ≥ 1) that
   form a directed cycle under the map d → 3·d + j (mod 10) for some j∈{0,1,2},
   with the first digit the largest in the cycle.  The function returns the nth
   term (1‑based).  The sequence is generated by enumerating all such cycles,
   converting each to an integer, sorting them, and indexing the sorted list.
*/

#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/cmp_vals.h"

/* successor table: succ[d][k] = (3*d + k) mod 10, k=0..2 */
static const int succ[10][3] = {
    {0,1,2},   /* 0 -> 0,1,2   */
    {3,4,5},   /* 1 -> 3,4,5   */
    {6,7,8},   /* 2 -> 6,7,8   */
    {9,0,1},   /* 3 -> 9,0,1   */
    {2,3,4},   /* 4 -> 2,3,4   */
    {5,6,7},   /* 5 -> 5,6,7   */
    {8,9,0},   /* 6 -> 8,9,0   */
    {1,2,3},   /* 7 -> 1,2,3   */
    {4,5,6},   /* 8 -> 4,5,6   */
    {7,8,9}    /* 9 -> 7,8,9   */
};

/* dynamic array for all sequence values */
static seq_t *values = NULL;
static size_t values_len = 0, values_cap = 0;

/* push a new value into the array, reallocating if needed */
static void push_value(seq_t v)
{
    if (values_len == values_cap) {
        size_t new_cap = (values_cap == 0) ? 16 : values_cap * 2;
        seq_t *tmp = (seq_t *)realloc(values, new_cap * sizeof(seq_t));
        if (tmp == NULL) abort();    /* memory failure */
        values = tmp;
        values_cap = new_cap;
    }
    values[values_len++] = v;
}

/* depth‑first search for cycles starting and ending at 'start'.
   'current'   – current vertex
   'mask'      – bitmask of visited vertices
   'number'    – integer built from the path so far
   'len'       – number of vertices in the current path (including start)
   The start vertex is guaranteed to be the largest in the cycle.
   Each time a cycle is closed (next == start and len > 1), the number is
   stored.  Only vertices smaller than start are visited (ensuring the start
   remains the maximum). */
static void dfs_cycles(int start, int current, uint16_t mask,
                       seq_t number, int len)
{
    for (int k = 0; k < 3; ++k) {
        int next = succ[current][k];
        if (next == start) {
            if (len > 1)
                push_value(number);
            continue;   /* do not extend further */
        }
        if (mask & (1u << next)) continue;   /* already used */
        if (next > start) continue;          /* would violate start=maximum */
        dfs_cycles(start, next, mask | (1u << next),
                   number * (seq_t)10 + (seq_t)next, len + 1);
    }
}

/* generate all values of the sequence once, then sort them */
static void generate_all(void)
{
    for (int d = 0; d < 10; ++d) {
        /* cycle of length 1 if d is a fixed point of the relation */
        for (int k = 0; k < 3; ++k) {
            if (succ[d][k] == d) {
                push_value((seq_t)d);
                break;
            }
        }
        /* cycles of length ≥2 starting from d (d is maximum) */
        dfs_cycles(d, d, 1u << d, (seq_t)d, 1);
    }
    qsort(values, values_len, sizeof(seq_t), cmp_vals);
}

/* public function returning the nth term.  n is 1‑based. */
seq_t a(idx_t n)
{
    static bool built = false;
    if (!built) {
        generate_all();
        built = true;
    }
    if (n == 0 || n > values_len) return 0;
    return values[(size_t)n - 1];
}
