/*
 * A336506  Lambda-practical numbers: numbers that are p-practical for every
 *          rational prime p.
 * https://oeis.org/A336506
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 61, u16 n <= 6586, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Lambda‑practical numbers (OEIS A336506).  
 *  The value a(n) is the n‑th integer m such that every k ≤ m can be
 *  expressed as Σ_{d|m} λ(d)·n_d with 0 ≤ n_d ≤ φ(d)/λ(d).  The sequence
 *  is generated by testing successive integers using a sieve of smallest
 *  prime factors, computing all divisor Carmichael lambdas, and then
 *  applying the greedy representability check.  The first term is a(1)=1.
 */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>

/* --------------------------------------------------------------------- */
/*  Helper for division gcd                                          */
/* --------------------------------------------------------------------- */
static inline uint64_t gcd_u64(uint64_t a, uint64_t b)
{
    while (b != 0) {
        uint64_t t = a % b;
        a = b;
        b = t;
    }
    return a;
}

/* --------------------------------------------------------------------- */
/*  Sieve for smallest prime factor                                    */
/* --------------------------------------------------------------------- */
static uint64_t *spf = NULL;            /* smallest prime factor array   */
static size_t   spf_limit = 0;          /* current size of the sieve     */

static void init_sieve(void)
{
    if (spf != NULL) return;           /* already initialized           */
    /* Choose a sieve limit that comfortably covers the 10 000th
     * lambda‑practical number (roughly < 2·10⁵).  Use 1 000 000 for safety. */
    const size_t limit = 1000000;
    spf_limit = limit;
    spf = (uint64_t *)calloc(limit + 1, sizeof(uint64_t));
    if (!spf) abort();                 /* out of memory                 */
    spf[0] = 0;
    spf[1] = 1;
    for (size_t i = 2; i <= limit; ++i) {
        if (spf[i] == 0) {             /* i is prime                    */
            spf[i] = i;
            if (i * i <= limit) {
                for (size_t j = i * i; j <= limit; j += i)
                    if (spf[j] == 0) spf[j] = i;
            }
        }
    }
}

/* --------------------------------------------------------------------- */
/*  Container for a divisor’s lambda and φ/λ counts                    */
/* --------------------------------------------------------------------- */
typedef struct { uint64_t l; uint64_t lim; } DivPair;

/* --------------------------------------------------------------------- */
/*  Comparator for sorting DivPair by l                                 */
/* --------------------------------------------------------------------- */
static int cmp_pair(const void *a, const void *b)
{
    const DivPair *x = (const DivPair *)a;
    const DivPair *y = (const DivPair *)b;
    return (x->l < y->l) ? -1 : (x->l > y->l);
}

/* --------------------------------------------------------------------- */
/*  Recursive enumeration of all divisors with Lambdas                  */
/* --------------------------------------------------------------------- */
static void dfs_division(size_t idx, size_t pcnt,
                         const uint64_t pf[16], const int pe[16],
                         uint64_t curr_lcm, uint64_t curr_phi,
                         DivPair *pairs, size_t *cnt)
{
    if (idx == pcnt) {
        pairs[*cnt].l   = curr_lcm;
        pairs[*cnt].lim = curr_phi / curr_lcm;
        (*cnt)++;
        return;
    }
    uint64_t p      = pf[idx];
    int      e_tot  = pe[idx];
    uint64_t lambda_part[17];
    uint64_t phi_part[17];
    lambda_part[0] = 1;
    phi_part[0]    = 1;
    for (int e = 1; e <= e_tot; ++e) {
        if (p == 2) {
            if (e == 1)          lambda_part[e] = 1;
            else if (e == 2)     lambda_part[e] = 2;
            else                 lambda_part[e] = 1ULL << (e - 2);
        } else {
            uint64_t pow = 1;
            for (int k = 0; k < e - 1; ++k) pow *= p;
            lambda_part[e] = pow * (p - 1);
        }
        if (p == 2) {
            phi_part[e] = 1ULL << (e - 1);
        } else {
            uint64_t pow = 1;
            for (int k = 0; k < e - 1; ++k) pow *= p;
            phi_part[e] = pow * (p - 1);
        }
    }
    for (int e = 0; e <= e_tot; ++e) {
        uint64_t new_lcm = curr_lcm;
        if (lambda_part[e] > 1) {
            uint64_t g = gcd_u64(curr_lcm, lambda_part[e]);
            new_lcm = (curr_lcm / g) * lambda_part[e];
        }
        uint64_t new_phi = curr_phi * phi_part[e];
        dfs_division(idx + 1, pcnt, pf, pe, new_lcm, new_phi,
                     pairs, cnt);
    }
}

/* --------------------------------------------------------------------- */
/*  Test whether m is lambda‑practical                                  */
/* --------------------------------------------------------------------- */
static bool is_lambda_practical(uint64_t m)
{
    /* Factor m using the sieve (m ≤ spf_limit).                                 */
    uint64_t pf[16];
    int      pe[16];
    size_t   pcnt = 0;
    uint64_t x = m;
    while (x > 1) {
        uint64_t p = spf[x];
        int e = 0;
        while (x % p == 0) { x /= p; e++; }
        pf[pcnt] = p;
        pe[pcnt] = e;
        pcnt++;
    }

    /* Enumerate all divisors and collect (λ, φ/λ).                                 */
    DivPair all[2048];                        /* large enough for all cases */
    size_t all_cnt = 0;
    dfs_division(0, pcnt, pf, pe, 1, 1, all, &all_cnt);

    /* Sort by λ to merge identical λ values.                                    */
    qsort(all, all_cnt, sizeof(DivPair), cmp_pair);

    /* Merge duplicates.                                                              */
    size_t uniq_cnt = 0;
    for (size_t i = 0; i < all_cnt; ++i) {
        if (uniq_cnt == 0 || all[i].l != all[uniq_cnt - 1].l) {
            all[uniq_cnt++] = all[i];
        } else {
            all[uniq_cnt - 1].lim += all[i].lim;
        }
    }

    /* Greedy test of representability up to m.                                    */
    uint64_t reachable = 0;
    for (size_t i = 0; i < uniq_cnt; ++i) {
        uint64_t val = all[i].l;
        uint64_t cnt = all[i].lim;
        if (val > reachable + 1) return false;
        reachable += val * cnt;
        if (reachable >= m) return true;
    }
    return false;
}

/* --------------------------------------------------------------------- */
/*  Cache for computed terms                                              */
/* --------------------------------------------------------------------- */
static seq_t  *lambda_cache = NULL;   /* array of found lambda‑practical numbers */
static size_t  cache_cap   = 0;
static size_t  cache_len   = 0;
static uint64_t last_checked = 0;

/* --------------------------------------------------------------------- */
/*  Public sequence function                                             */
/* --------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;        /* undefined for index 0 */

    if (spf == NULL) init_sieve();      /* ensure sieve ready */

    /* Generate terms until we have n of them.                                 */
    while (cache_len < (size_t)n) {
        last_checked += 1;
        if (is_lambda_practical(last_checked)) {
            if (cache_len == cache_cap) {   /* enlarge cache               */
                cache_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
                lambda_cache = (seq_t *)realloc(lambda_cache,
                                                 cache_cap * sizeof(seq_t));
                if (!lambda_cache) abort();
            }
            lambda_cache[cache_len++] = (seq_t)last_checked;
        }
    }
    return lambda_cache[n - 1];
}
