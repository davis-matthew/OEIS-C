/*
 * A336900  a(n) is the first element of the lexicographically earliest Heron
 *          square root triple with area n > 0, or 0, if no such triple
 *          exists.
 * https://oeis.org/A336900
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   build_primes, maybe_update
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A336900 implementation
 *
 * Formula: a(n) is the smallest first element 'a' of the
 * lexicographically earliest Heron square‑root triple [a,b,c]
 * with area n.  A triple satisfies
 *
 *      a ≥ b ≥ c > 0
 *      4·b·c – (a – b – c)² = 16·n²
 *
 * and the sides √a, √b, √c form a non‑degenerate triangle.
 *
 * The sequence is generated by enumerating all decompositions of
 * P = m² + 4·n² into b·c (with b ≥ c) and all corresponding
 * values a = b + c ± 2·m.  The lexicographically earliest triple
 * (smallest a, if tied smallest b, then c) is recorded.
 * This algorithm runs in O(n·d) where d is the average number of
 * divisors of the P’s, well below the 2‑second limit for n ≤ 10⁴.
 */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

/* utility functions provided by the AOEIS build */
#include "../utils/build_primes.h"   /* void build_primes(idx_t limit, idx_t **out, size_t *cnt) */
#include "../utils/maybe_update.h"

static idx_t *prime_list = NULL;
static size_t prime_cnt   = 0;
static idx_t  prime_limit = 0;

static void ensure_primes(idx_t lim)
{
    if (prime_limit >= lim) return;
    if (prime_list != NULL) free((void *)prime_list);
    build_primes(lim, &prime_list, &prime_cnt);
    prime_limit = lim;
}

/* generate all divisors of a number given its prime powers\n
 *   factors[0..cnt-1]   – distinct prime factors\n
 *   exps[0..cnt-1]      – corresponding exponents\n
 *   divs[0] already 1\n
 *   div_cnt is updated with the number of divisors written.
 */
static void generate_divisors(const seq_t *factors, const int *exps,
                              size_t cnt, seq_t *divs, size_t *div_cnt)
{
    size_t cur_cnt = 1;
    divs[0] = 1;
    for (size_t i = 0; i < cnt; ++i)
    {
        seq_t p  = factors[i];
        int   e  = exps[i];
        size_t base_cnt = cur_cnt;
        seq_t p_pow = 1;
        for (int k = 0; k < e; ++k)
        {
            p_pow *= p;
            for (size_t j = 0; j < base_cnt; ++j)
                divs[cur_cnt++] = divs[j] * p_pow;
        }
    }
    *div_cnt = cur_cnt;
}

/* main sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for n=0 */

    /* Prepare a generous list of primes up to √(4n² + (2n)²) ≈ 4n */
    idx_t prime_lim = 5 * n + 10;
    if (prime_lim < 2) prime_lim = 2;
    ensure_primes(prime_lim);

    seq_t seq_n = (seq_t)n;
    seq_t base  = (seq_t)4 * seq_n * seq_n;   /* 4n² */

    bool found = false;
    seq_t best_a = 0, best_b = 0, best_c = 0;

    /* We enumerate m = k = |a-b-c|/2, for m from 0 up to 2n */
    idx_t m_max = 2 * n;
    for (idx_t m = 0; m <= m_max; ++m)
    {
        seq_t m_sq = (seq_t)m * (seq_t)m;
        seq_t P = base + m_sq;      /* P = m² + 4n² = b·c */

        /* factorise P */
        seq_t tmp = P;
        size_t fact_cnt = 0;
        seq_t factor_list[64];
        int   exp_list[64];

        for (size_t i = 0; i < prime_cnt &&
             (seq_t)prime_list[i] * (seq_t)prime_list[i] <= tmp; ++i)
        {
            seq_t p = (seq_t)prime_list[i];
            if (tmp % p == 0)
            {
                int e = 0;
                while (tmp % p == 0) { tmp /= p; ++e; }
                factor_list[fact_cnt] = p;
                exp_list[fact_cnt]   = e;
                ++fact_cnt;
            }
        }
        if (tmp > 1)
        {
            factor_list[fact_cnt] = tmp;
            exp_list[fact_cnt]   = 1;
            ++fact_cnt;
        }

        /* generate all divisors of P */
        seq_t divs[512];
        size_t div_cnt;
        generate_divisors(factor_list, exp_list, fact_cnt,
                          divs, &div_cnt);

        seq_t s = (seq_t)2 * (seq_t)m;   /* 2m = |a-b-c| */

        for (size_t i = 0; i < div_cnt; ++i)
        {
            seq_t c_div = divs[i];
            seq_t b_div = P / c_div;
            if (b_div < c_div) continue;          /* enforce b≥c */

            /* candidate a = b + c + 2m */
            seq_t a1 = b_div + c_div + s;
            maybe_update(a1, b_div, c_div, &best_a, &best_b, &best_c, &found);

            /* candidate a = b + c - 2m, allowed only if a≥b */
            if (s <= c_div)
            {
                seq_t a2 = b_div + c_div - s;
                if (a2 >= b_div)
                    maybe_update(a2, b_div, c_div, &best_a, &best_b, &best_c, &found);
            }
        }
    }

    return found ? best_a : 0;
}
