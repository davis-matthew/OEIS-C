/*
 * A336256  The cardinalities of the sets A(n), where A(0) is the empty set
 *          and A(n+1) is the union of A(n) and the Collatz orbit of the
 *          smallest natural number missing in A(n).
 * https://oeis.org/A336256
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 13, u16 n <= 55, u32 n <= 55, u64 n <= 55, u128 n <= 55,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
   Sequence A336256:
   a(0) = 0.
   A(0) = ∅.
   For n ≥ 0, let m be the smallest non‑negative integer not in A(n).
   A(n+1) = A(n) ∪ CollatzOrbit(m),
   where the Collatz orbit of m is generated by n → n/2 if even,
               n → 3n+1 if odd,
   until a number already in the global set is reached.
   a(n) is |A(n)|.
   This implementation builds the sequence lazily and memoises results.
*/

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* --------------------- static state --------------------- */
static seq_t *a_vals = NULL;     /* cached a(n) values          */
static idx_t  a_cap  = 0;        /* allocated entries in a_vals*/
static idx_t  cur_max = 0;       /* largest n computed          */

/* Bitset holding membership of visited numbers (one byte per 8 numbers) */
static uint8_t *bitset   = NULL; /* bit array                   */
static idx_t    bits_cap = 0;    /* number of bytes allocated  */

/* Ensure space for at least n+1 entries in a_vals ----------------------- */
static void ensure_a_vals(idx_t n)
{
    if (n + 1 <= a_cap) return;
    idx_t new_cap = a_cap ? a_cap * 2 : 32;
    while (new_cap <= n) new_cap <<= 1;
    a_vals = (seq_t *)realloc(a_vals, new_cap * sizeof(seq_t));
    a_cap  = new_cap;
}

/* Ensure bitset can store indices up to idx (inclusive) ---------------- */
static void ensure_bitset(idx_t idx)
{
    if (idx <= (bits_cap << 3) - 1) return;      /* already covered */
    idx_t new_cap = bits_cap ? bits_cap << 1 : 1024; /* start at 1024 bytes */
    while (new_cap <= (idx >> 3) + 1) new_cap <<= 1;
    bitset = (uint8_t *)realloc(bitset, new_cap);
    /* clear new bytes */
    for (idx_t i = bits_cap; i < new_cap; ++i) bitset[i] = 0;
    bits_cap = new_cap;
}

/* Test whether number i is in the set --------------------------------- */
static inline bool bit_get(idx_t i)
{
    return bitset[i >> 3] & (1U << (i & 7));
}

/* Mark number i as present ---------------------------------------------- */
static inline void bit_set(idx_t i)
{
    bitset[i >> 3] |= (1U << (i & 7));
}

/* Add the Collatz orbit of start to the set; return number of new elems */
static size_t add_collatz_orbit(seq_t start)
{
    size_t added = 0;
    seq_t  x = start;

    for (;;) {
        idx_t ix = (idx_t)x;
        ensure_bitset(ix);
        if (bit_get(ix))          /* number already present: stop orbit */
            break;
        bit_set(ix);
        ++added;

        /* next Collatz step */
        if ((x & (seq_t)1) == 0)          /* even */
            x = x >> 1;
        else                               /* odd */
            x = (seq_t)(x * (seq_t)3 + (seq_t)1);
    }
    return added;
}

/* ------------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    /* initialise on first call ------------------------------------------- */
    if (a_vals == NULL) {
        a_vals = (seq_t *)calloc(1, sizeof(seq_t));   /* a(0)=0          */
        a_cap  = 1;
        cur_max = 0;

        bitset = (uint8_t *)calloc(1024, 1);          /* 1024 bytes      */
        bits_cap = 1024;
    }

    if (n == 0) return (seq_t)0;
    if (n <= cur_max) return a_vals[n];                /* cached value    */

    /* compute from cur_max+1 up to n ----------------------------------- */
    for (idx_t i = cur_max + 1; i <= n; ++i) {
        /* find smallest missing number, starting from 0 */
        idx_t m = 0;
        while (true) {
            ensure_bitset(m);
            if (!bit_get(m)) break;
            ++m;
        }

        /* add its Collatz orbit */
        size_t new_cnt = add_collatz_orbit((seq_t)m);

        /* update current set size */
        seq_t new_size = a_vals[cur_max] + (seq_t)new_cnt;

        /* store a(i) */
        ensure_a_vals(i);
        a_vals[i] = new_size;

        cur_max = i;
    }

    return a_vals[n];
}
