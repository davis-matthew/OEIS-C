/* Sequence A354775
   Indices where A354169 is the sum of two consecutive powers of 2.
   The differences d(n) = a(n) – a(n‑1) follow:
     d(2)=4, d(3)=16, d(4)=12, d(5)=12,
     d(6)=18, d(7)=6, d(8)=18, d(9)=6,
     for n≥10   d(n)=48·2^⌊(n‑10)/2⌋
   a(1)=5.  The sequence is generated by a(n)=a(n‑1)+d(n).
*/

#include "../utils/pow2.h"

seq_t a(idx_t n)
{
    if (n == 0)            /* offset is 1; n==0 not defined, return 0 */
        return 0;
    seq_t val = 5;          /* a(1) */
    if (n == 1)
        return val;

    for (idx_t i = 2; i <= n; ++i)
    {
        seq_t d;
        if (i <= 5)
        {
            /* d(2)=4, d(3)=16, d(4)=12, d(5)=12 */
            if (i == 2)
                d = 4;
            else if (i == 3)
                d = 16;
            else
                d = 12;  /* i==4 or 5 */
        }
        else if (i <= 9)
        {
            /* d(6)=18, d(7)=6, d(8)=18, d(9)=6 */
            d = (i & 1ULL) ? 6 : 18;
        }
        else
        {
            /* for i>=10: d(i)=48*2^floor((i-10)/2) */
            idx_t e = (i - 10) >> 1;          /* floor division by 2 */
            d = 48 * pow2(e);
        }
        val += d;
    }
    return val;
}
