/* 
   A354570 – ordered odd leg lengths k of primitive Pythagorean triples
   with all prime factors of k congruent to 3 (mod 4).
   The sequence is generated by enumerating odd integers k whose prime
   factors all lie in the residue class 3 (mod 4).  If k = ∏ p_i^e_i
   with r distinct primes, then k appears 2^(r‑1) times in the
   sequence (multiplicity comes from the two possible parity assignments
   for the coprime pair (m,n) giving the primitive triple).
   The function caches generated terms so that a(idx_t n) is O(1)
   after an initial O(n) precomputation.
*/

#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/*--- cache for generated terms ------------------------------------*/
static seq_t *cache = NULL;   /* array of terms stored so far     */
static size_t cache_size = 0; /* number of terms in cache         */
static size_t cache_cap   = 0; /* allocated capacity (elements)    */
static uint64_t next_odd  = 3; /* next odd integer to test         */

/* Append `mult` copies of value `k` to the cache, expanding it if needed. */
static void add_to_cache(uint64_t k, size_t mult)
{
    size_t needed = cache_size + mult;
    if (needed > cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 64;
        while (new_cap < needed) new_cap *= 2;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        /* realloc failure is ignored – build will abort on OOM            */
        cache = tmp;
        cache_cap = new_cap;
    }
    for (size_t i = 0; i < mult; ++i)
        cache[cache_size++] = (seq_t)k;
}

/* Ensure that cache contains at least n terms. */
static void ensure_cache(idx_t n)
{
    if (cache_size >= (size_t)n) return;

    while (cache_size < (size_t)n) {
        uint64_t k = next_odd;
        next_odd += 2; /* next odd integer */

        uint64_t tmp   = k;
        size_t   distinct = 0;
        bool     ok = true;

        /* trial‑division for odd primes only */
        for (uint64_t p = 3; p <= tmp / p; p += 2) {
            if (tmp % p == 0) {
                if (p % 4 != 3) { /* forbidden prime factor */
                    ok = false;
                    break;
                }
                ++distinct;
                while (tmp % p == 0) tmp /= p;
            }
        }
        if (!ok) continue;

        if (tmp > 1) {          /* remaining prime factor (odd) */
            if (tmp % 4 != 3) continue;
            ++distinct;
        }

        /* multiplicity = 2^(distinct‑1)  (distinct ≥ 1 for k ≥ 3) */
        size_t mult = 1ULL << (distinct - 1);
        add_to_cache(k, mult);
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0; /* undefined below offset, keep 0 for safety */
    ensure_cache(n);
    return cache[(size_t)n - 1];
}
