/*
 * A208860  Number of nX4 0..3 arrays with new values 0..3 introduced in row
 *          major order and no element equal to more than one of its immediate
 *          leftward or upward or left-upward diagonal neighbors.
 * https://oeis.org/A208860
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 2, u32 n <= 4, u64 n <= 9, u128 n <= 17,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Sequence A208860: Number of n×4 0..3 arrays with
 *  new values introduced in row‑major order and no element equal to
 *  more than one of its immediate leftward, upward or left‑upward
 *  diagonal neighbors.
 *
 *  The values are generated by dynamic programming over rows.
 */
#include <stdint.h>
#include <stdbool.h>

/* external linkage */
seq_t a(idx_t n)
{
    /* n must be ≥ 1; for n < 1 return 0 (not used by the test harness) */
    if (n < 1) return (seq_t)0;

    /* ------------------------------------------------------------------
     *  Pre‑compute transitions for every state:
     *
     *  State = (max_value_used << 8) | previous_row_pattern
     *  max_value_used : 0..3  (2 bits)
     *  previous_row_pattern : 0..255 (8 bits)
     *
     *  For each state we store the list of successor states
     *  that can appear in the next row.
     * ------------------------------------------------------------------ */
    static bool trans_ready = false;
    static uint16_t trans_len[1 << 10];      /* number of successors per state */
    static int16_t  trans_array[(1 << 10) * (1 << 8)];  /* flattened list of dest states */

    if (!trans_ready) {
        for (int s = 0; s < (1 << 10); ++s) {
            int maxv = s >> 8;          /* high 2 bits */
            int prow = s & 0xFF;        /* low 8 bits : previous row pattern */

            /* decode previous row into an array for quick access */
            int prev[4];
            for (int j = 0; j < 4; ++j)
                prev[j] = (prow >> (2 * j)) & 3;

            int pos = 0; /* destination list position for this state */
            for (int nrow = 0; nrow < (1 << 8); ++nrow) {
                int nk = maxv;
                bool ok = true;
                for (int j = 0; j < 4 && ok; ++j) {
                    int v = (nrow >> (2 * j)) & 3;

                    /* count equal neighbours <= 1 */
                    int matches = 0;
                    if (j > 0) {
                        int left = (nrow >> (2 * (j - 1))) & 3;
                        if (left == v) ++matches;
                    }
                    if (prev[j] == v) ++matches;
                    if (j > 0 && prev[j - 1] == v) ++matches;
                    if (matches > 1) { ok = false; break; }

                    /* new‑value rule: at most one new value in increasing order */
                    if (v > nk) {
                        if (v != nk + 1) { ok = false; break; }
                        nk = v;
                    }
                }
                if (ok) {
                    int dest = (nk << 8) | nrow;
                    trans_array[s * (1 << 8) + pos++] = (int16_t)dest;
                }
            }
            trans_len[s] = (uint16_t)pos;
        }
        trans_ready = true;
    }

    /* ------------------------------------------------------------------
     *  Initialise DP after the first row.
     *
     *  For the first row no upper neighbours exist, only local left
     *  neighbour checks and the new‑value rule.
     * ------------------------------------------------------------------ */
    static seq_t dp[1 << 10];
    for (int i = 0; i < (1 << 10); ++i) dp[i] = (seq_t)0;

    for (int row = 0; row < (1 << 8); ++row) {
        int nk = -1;
        bool ok = true;
        for (int j = 0; j < 4 && ok; ++j) {
            int v = (row >> (2 * j)) & 3;

            /* left neighbour check (at most one match) */
            if (j > 0) {
                int left = (row >> (2 * (j - 1))) & 3;
                if (left == v) {
                    /* one match allowed; nothing to do */
                }
            }

            /* new‑value rule */
            if (v > nk) {
                if (nk == -1) {
                    if (v != 0) { ok = false; break; }
                    nk = 0;
                } else if (v != nk + 1) {
                    ok = false; break;
                }
                nk = v;
            }
        }
        if (ok) {
            int state = (nk << 8) | row;
            dp[state] += (seq_t)1;
        }
    }

    /* ------------------------------------------------------------------
     *  Process the remaining rows using the pre‑computed transitions.
     * ------------------------------------------------------------------ */
    static seq_t ndp[1 << 10];
    for (idx_t r = 2; r <= n; ++r) {
        for (int i = 0; i < (1 << 10); ++i) ndp[i] = (seq_t)0;

        for (int s = 0; s < (1 << 10); ++s) {
            if (dp[s] == (seq_t)0) continue;
            uint16_t len = trans_len[s];
            int base = s * (1 << 8);
            for (int t = 0; t < len; ++t) {
                int dst = trans_array[base + t];
                ndp[dst] += dp[s];
            }
        }
        /* swap dp and ndp */
        for (int i = 0; i < (1 << 10); ++i) dp[i] = ndp[i];
    }

    /* ------------------------------------------------------------------
     *  Sum over all final states to obtain the total number of arrays.
     * ------------------------------------------------------------------ */
    seq_t total = (seq_t)0;
    for (int s = 0; s < (1 << 10); ++s)
        total += dp[s];
    return total;
}
