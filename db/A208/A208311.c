/* A208311: number of n×5 0/1 arrays with first cell 0, filled row‑major,
 * where no element equals both of its immediate leftward and upward
 * neighbors.  Generated by a simple dynamic programming over 5‑bit rows.
 *
 * The recurrence of depth 8 in the OEIS entry follows from this DP,
 * but we compute directly to avoid large intermediate integers.
 */

#include <stdint.h>
#include <stdbool.h>

static bool trans[32][32];

static void build_trans(void) {
    for (int p = 0; p < 32; ++p) {
        for (int c = 0; c < 32; ++c) {
            bool ok = true;
            for (int j = 0; j < 5; ++j) {
                int up = (p >> j) & 1;
                int val = (c >> j) & 1;
                if (j > 0) {
                    int left = (c >> (j - 1)) & 1;
                    if (up == left && val == up) {
                        ok = false;
                        break;
                    }
                }
            }
            trans[p][c] = ok;
        }
    }
}

seq_t a(idx_t n) {
    if (n == 0) return 0;   /* outside offset, return 0 */

    static bool built = false;
    if (!built) {
        build_trans();
        built = true;
    }

    seq_t cur[32] = {0};
    seq_t nxt[32] = {0};

    /* first row: first cell (bit 0) must be 0 */
    for (int p = 0; p < 32; ++p) {
        if ((p & 1) == 0) cur[p] = 1;
    }

    if (n == 1) {
        seq_t sum = 0;
        for (int p = 0; p < 32; ++p) sum += cur[p];
        return sum;
    }

    for (idx_t step = 1; step < n; ++step) {
        for (int i = 0; i < 32; ++i) nxt[i] = 0;
        for (int p = 0; p < 32; ++p) if (cur[p]) {
            for (int c = 0; c < 32; ++c) if (trans[p][c]) {
                nxt[c] += cur[p];
            }
        }
        /* copy back */
        for (int i = 0; i < 32; ++i) cur[i] = nxt[i];
    }

    seq_t result = 0;
    for (int p = 0; p < 32; ++p) result += cur[p];
    return result;
}
