/*
 * Computes OEIS sequence A208272: primes containing digit 2.
 * For each requested n (>=1), this function returns the n-th prime
 * whose decimal representation contains at least one digit '2'.
 * The sequence is generated by iteratively testing successive
 * integers for primality and digit membership, caching the found
 * terms to allow out-of-order queries and repeated calls.
 */

#include <stdbool.h>
#include <stdlib.h>
#include <stddef.h>

/* use provided utilities */
#include "../utils/is_prime_big.h"
#include "../utils/get_digits.h"

seq_t a(idx_t n) {
    /* static cache of already found terms */
    static seq_t *cache = NULL;
    static size_t cache_size = 0;
    static size_t cache_cap = 0;

    /* initialise cache with first term (prime 2) */
    if (cache == NULL) {
        cache_cap = 64;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache) return 0;          /* allocation failed */
        cache[0] = 2;
        cache_size = 1;
    }

    /* If we already have the answer, return immediately */
    if (n <= cache_size) {
        return cache[n - 1];
    }

    /* Start searching for further terms */
    seq_t current = cache[cache_size - 1] + 1;

    while (cache_size < n) {
        /* find next prime */
        while (!is_prime_big(current)) {
            current++;
        }

        /* check if prime contains digit 2 */
        uint8_t digits[32];
        size_t len = 0;
        get_digits(current, digits, &len);
        bool has_two = false;
        for (size_t i = 0; i < len; ++i) {
            if (digits[i] == 2) {
                has_two = true;
                break;
            }
        }

        if (has_two) {
            /* grow cache if necessary */
            if (cache_size == cache_cap) {
                cache_cap *= 2;
                seq_t *new_cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
                if (!new_cache) return 0;  /* allocation failed */
                cache = new_cache;
            }
            cache[cache_size++] = current;
        }
        current++;
    }

    return cache[n - 1];
}
