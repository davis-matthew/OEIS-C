/*
 * A084668  Brilliant Niven numbers, i.e., numbers with two prime factors of
 *          the same length (in decimal notation) which are also divisible by
 *          the sum of their digits.
 * https://oeis.org/A084668
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, fini, full, nonn
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 13, u32 n <= 13, u64 n <= 13, u128 n <= 13,
 *            big any n
 * Helpers:   _smallest_prime_factor, digit_len, digit_sum
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A084668 – Brilliant Niven numbers: semiprimes whose prime factors
   have the same decimal length and are divisible by the sum of their
   digits.
   The sequence is generated by a simple incremental search with
   memoisation.  The function may be called in any order; terms are
   stored in a static cache that is expanded only when needed.  */


#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Utilities */
#include "../utils/digit_sum.h"   /* seq_t digit_sum(seq_t) */
#include "../utils/digit_len.h"   /* int digit_len(seq_t) */
#include "../utils/_smallest_prime_factor.h"  /* uint64_t _smallest_prime_factor(uint64_t) */


seq_t a(idx_t n)
{
    /* undefined for n==0 – behaviour below the offset does not matter */
    if (n == 0)
        return 0;

    /* 0‑based cache: cache[0] holds a(1) */
    static seq_t *cache          = NULL;
    static size_t cache_len      = 0;
    static size_t cache_cap      = 0;
    static seq_t next_candidate  = 4;   /* smallest candidate that satisfies all criteria */

    /* Ensure the cache contains at least n terms. */
    while (cache_len < (size_t)n)
    {
        /* Stop if the next candidate does not fit into 64 bits.  */
        if (next_candidate > (seq_t)UINT64_MAX)
            break;          /* no further terms can be checked with the available utilities */

        uint64_t cand64 = (uint64_t)next_candidate;   /* candidate fits in 64‑bit */

        /* 1. Niven (Harshad) property: divisible by sum of digits. */
        seq_t sum = digit_sum(next_candidate);
        if (sum == 0 || (next_candidate % sum) != 0)
        {
            ++next_candidate;
            continue;
        }

        /* 2. Semiprime with exactly two prime factors. */
        uint64_t p = _smallest_prime_factor(cand64);
        if (p == cand64)                 /* candidate itself is prime */
        {
            ++next_candidate;
            continue;
        }
        uint64_t q = cand64 / p;
        if (_smallest_prime_factor(q) != q)   /* q not prime -> more than two factors */
        {
            ++next_candidate;
            continue;
        }

        /* 3. Prime factors must have the same decimal length. */
        int dl_p = digit_len((seq_t)p);
        int dl_q = digit_len((seq_t)q);
        if (dl_p != dl_q)
        {
            ++next_candidate;
            continue;
        }

        /* 4. All criteria satisfied – store the term. */
        if (cache_len == cache_cap)
        {
            size_t new_cap = cache_cap ? cache_cap << 1 : 4;
            seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            if (!tmp) abort();          /* allocation failure – stop the program */
            cache      = tmp;
            cache_cap  = new_cap;
        }
        cache[cache_len++] = next_candidate;

        /* Advance to the next integer for the subsequent search. */
        ++next_candidate;
    }

    /* Return the requested term.  If n exceeds the length of the sequence
       the program will have stopped populating the cache – the caller will
       receive garbage in such an impossible case.  */
    return cache[n - 1];
}
