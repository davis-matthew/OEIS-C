/* Sequence A084925:  a(n) is the smallest integer n≥1 that cannot be written as (xy‑1)/(x‑y)
 * for any integers 1<y<x<n. The sequence is generated by checking each integer in
 * ascending order and keeping those that satisfy the property.  The algorithm is
 * O(m²) in the worst case (m = largest integer examined), but for the first 10 000
 * terms m≈20 000, which runs comfortably within the time limit. */

