/* Sequence A084925:  a(n) is the smallest integer n≥1 that cannot be written as (xy‑1)/(x‑y)
 * for any integers 1<y<x<n. The sequence is generated by checking each integer in
 * ascending order and keeping those that satisfy the property.  The algorithm is
 * O(m²) in the worst case (m = largest integer examined), but for the first 10 000
 * terms m≈20 000, which runs comfortably within the time limit. */

#include <stddef.h>
#include <stdbool.h>
#include "../utils/seq_alloc_new_array.h"
#include "../utils/seq_realloc.h"
#include "../utils/_is_coprime_candidate.h"

seq_t a(idx_t n)
{
    /* Static cache of sequence terms (ascending order). */
    static seq_t *terms = NULL;
    static size_t terms_len = 0, terms_cap = 0;
    static idx_t tested = 0;           /* largest integer examined so far */

    /* Generate terms until we have at least n of them. */
    while (terms_len < n) {
        ++tested;                       /* next candidate integer */

        if (_is_coprime_candidate(tested)) {
            /* Grow the cache if necessary. */
            if (terms_len == terms_cap) {
                size_t new_cap = terms_cap ? terms_cap * 2 : 64;
                seq_t *tmp = seq_realloc(terms, terms_cap, new_cap);
                if (!tmp) return (seq_t)0;  /* allocation failure; undefined behavior */
                terms = tmp;
                terms_cap = new_cap;
            }
            terms[terms_len++] = (seq_t)tested;
        }
    }

    return terms[n - 1];
}
