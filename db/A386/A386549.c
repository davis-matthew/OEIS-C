/*
 * A386549  Indices of hexagonal numbers that are one-sixth of another
 *          hexagonal number.
 * https://oeis.org/A386549
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 4, u32 n <= 6, u64 n <= 11, u128 n <= 17,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   a(1) = 0.  
   For n ≥ 2 the indices are generated by the linear recurrence  

       z_{k+1} = 49*z_k + 120*t_k  
       t_{k+1} = 20*z_k + 49*t_k  

   with initial values z₀ = 7 , t₀ = 3.  
   The k‑th index (k = n‑2) is  
           i_k = (t_k + 1) / 4.  

   This produces 1, 72, 7031, … matching the OEIS sequence A386549. 
*/
#include <stddef.h>

seq_t a(idx_t n)
{
    /* a(1) = 0 (by convention) */
    if (n <= (idx_t)1)
        return (seq_t)0;

    /* initial Pell solution (k = 0) */
    seq_t z = (seq_t)7;
    seq_t t = (seq_t)3;

    /* number of recurrence steps: k = n‑2 (k=0 gives a(2)=1) */
    size_t steps = (size_t)(n - (idx_t)2);
    for (size_t i = 0; i < steps; ++i) {
        seq_t new_z = (seq_t)49 * z + (seq_t)120 * t;
        seq_t new_t = (seq_t)20 * z + (seq_t)49 * t;
        z = new_z;
        t = new_t;
    }

    /* compute the index from the final t */
    seq_t idx = (t + (seq_t)1) / (seq_t)4;
    return idx;
}
