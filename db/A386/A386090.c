/*
 * A386090  Primes having only {1, 2, 3, 9} as digits.
 * https://oeis.org/A386090
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 19, u16 n <= 233, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Prime numbers whose decimal digits are only from the set {1,2,3,9}.
   The sequence is generated by enumerating all such numbers in
   increasing order and selecting the primes.  This implementation
   maintains all state between calls and uses a simple base‑4 odometer
   to produce the next candidate.  Primality is tested with a small
   sieve (up to 200 000). */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* allowed decimal digits */
static const uint8_t ALLOWED_DIGITS[4] = { 1, 2, 3, 9 };

/* ---------- sieve for primality testing ----------------- */
static bool sieve_done = false;
static uint32_t *prime_list = NULL;
static size_t prime_count  = 0;

static void init_prime_sieve(void)
{
    if (sieve_done) return;

    /* Choose a limit comfortably larger than any prime we will test
       (the 10 000th prime of this set is below 10^9). */
    const size_t LIMIT = 200000;
    bool *mark = (bool *)calloc(LIMIT + 1, sizeof(bool));
    for (size_t i = 2; i * i <= LIMIT; ++i)
        if (!mark[i])
            for (size_t j = i * i; j <= LIMIT; j += i)
                mark[j] = true;

    prime_list = (uint32_t *)malloc((LIMIT + 1) * sizeof(uint32_t));
    prime_count = 0;
    for (size_t i = 2; i <= LIMIT; ++i)
        if (!mark[i]) prime_list[prime_count++] = (uint32_t)i;

    free(mark);
    sieve_done = true;
}

/* test whether n<2^64 is prime using the small sieve */
static bool is_prime_uint64(uint64_t n)
{
    if (n < 2) return false;
    for (size_t i = 0; i < prime_count; ++i) {
        uint32_t p = prime_list[i];
        uint64_t sq = (uint64_t)p * (uint64_t)p;
        if (sq > n) break;
        if (n % p == 0) return n == p;
    }
    return true;
}

/* ---------- cache for the sequence --------------------- */
static seq_t *seq_cache = NULL;
static size_t seq_len  = 0;
static size_t seq_cap  = 0;

static void grow_cache(size_t needed)
{
    if (seq_cap >= needed) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 64;
    if (new_cap < needed) new_cap = needed;
    seq_cache = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    seq_cap = new_cap;
}

/* ---------- state of the incremental generator ---------- */
#define MAX_DIGITS 20
static uint8_t odometer[MAX_DIGITS];
static uint64_t odometer_len = 1;   /* current number of digits */

/* initialise the odometer to all zeros for the current length */
static void odometer_reset(void)
{
    for (size_t i = 0; i < odometer_len; ++i) odometer[i] = 0;
}

/* increment the odometer.  If all digits overflow, increase the
   number of digits and reset. */
static void odometer_inc(void)
{
    size_t i = odometer_len;
    if (i == 0) return;          /* should never happen */

    --i;                         /* start from least significant */
    while (true) {
        if (odometer[i] < 3) {
            odometer[i]++;        /* simple increment */
            break;
        } else {
            odometer[i] = 0;      /* carry over */
            if (i == 0) {         /* overflow all digits */
                odometer_len++;
                if (odometer_len > MAX_DIGITS) {
                    /* safety: this should never happen for 10 000 terms */
                    odometer_len = MAX_DIGITS;
                }
                odometer_reset();
                break;
            }
            --i;
        }
    }
}

/* generate the next candidate number (not yet tested for primality) */
static seq_t next_candidate(void)
{
    seq_t value = 0;
    for (size_t i = 0; i < odometer_len; ++i)
        value = value * 10 + (seq_t)ALLOWED_DIGITS[odometer[i]];
    return value;
}

/* ---------- the required sequence function -------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* off‑by‑zero is not used by tests */

    init_prime_sieve();

    if ((size_t)n <= seq_len)        /* already computed */
        return seq_cache[(size_t)n - 1];

    grow_cache((size_t)n);

    /* generate primes until we have n of them */
    while (seq_len < (size_t)n) {
        seq_t val = next_candidate();

        odometer_inc();  /* prepare for the next candidate */

        if (is_prime_uint64((uint64_t)val))
            seq_cache[seq_len++] = val;
    }

    return seq_cache[(size_t)n - 1];
}
