/*
 * A386196  Primes having only {5, 6, 7, 8} as digits.
 * https://oeis.org/A386196
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 26, u32 n <= 40, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   ensure_capacity, is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A386196: primes composed only of the digits 5,6,7,8
   computed by brute‑force generation and primality testing. */

#include <stddef.h>
#include <stdbool.h>

#include "../utils/is_prime_big.h"
#include "../utils/ensure_capacity.h"

/* Static cache of primes found so far.  cache_len holds the current count.   */
static seq_t  *cache      = NULL;
static size_t  cache_cap  = 0;
static size_t  cache_len  = 0;

/* Current length of numbers being generated by the search loops.              */
static size_t current_len = 1;

/* Recursive generator for all numbers of a given length whose digits are
   {5,6,7,8}.  Each produced number is tested for primality and stored
   into the cache if it is prime.  The recursion builds the digits from
   most‑significant to least‑significant.                                        */
static void rec_generate(size_t pos, size_t len, seq_t val)
{
    if (pos == len) {
        if (is_prime_big(val)) {
            if (cache_len + 1 > cache_cap)
                ensure_capacity(cache_len + 1, &cache_cap,
                                (void **)&cache, sizeof(seq_t));
            cache[cache_len++] = val;
        }
        return;
    }

    /* Generate digits in ascending order to keep numbers sorted.            */
    for (int d = 5; d <= 8; ++d) {
        rec_generate(pos + 1, len, val * 10 + d);
    }
}

/* Generate all numbers of the specified length.  This function calls
   the recursive generator.                                                   */
static void generate_length(size_t len)
{
    rec_generate(0, len, 0);
}

/* Expand the cache until it contains at least n primes.  This is called
   lazily when a() requests a term beyond the current cache.                 */
static void ensure_n_primes(idx_t n)
{
    while (cache_len < (size_t)n) {
        generate_length(current_len);
        ++current_len;
    }
}

/* Return the nth prime composed only of the digits 5,6,7,8.  Off‑set is 1. */
seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;          /* undefined for n<1, but safe */

    ensure_n_primes(n);
    return cache[(size_t)n - 1];
}
