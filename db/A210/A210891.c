/*
 * A210891  Number of days after Mar 01 00 such that the date written in the
 *          format D.M.YY is palindromic.
 * https://oeis.org/A210891
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 214, u32 n <= 214, u64 n <= 214, u128 n <= 214,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A210891 – days after Mar 01 00 to the nth palindromic D.M.YY date.
   Sequence is generated by searching all dates between 2000‑01‑01 and
   2099‑12‑31 and selecting those whose string representation
   "D.M.YY" is a palindrome, counting days from 2000‑03‑01 (0). */

#include <stddef.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>   /* for snprintf */

static seq_t pal_offsets[300] = {0};   /* 214 entries */
static size_t pal_n = 0;
static bool pal_built = false;

static void build_pal_offsets(void) {
    if (pal_built) return;
    pal_built = true;

    /* cumulative days before each year 2000‑00 to 2099‑00 */
    int days_before_year[101];
    days_before_year[0] = 0;
    for (int y = 1; y <= 100; ++y) { /* y corresponds to year 2000+(y-1) */
        int prev = y - 1;
        bool leap = (prev % 4 == 0);
        int days_in_year = 365 + (leap ? 1 : 0);
        days_before_year[y] = days_before_year[y - 1] + days_in_year;
    }

    const int YEAR_LIMIT = 100;  /* 2000‑00 … 2099‑99 */
    const int REFERENCE_ABS_DAY = 60; /* days before 2000‑03‑01 */

    for (int y = 0; y < YEAR_LIMIT; ++y) {          /* year offset from 2000 */
        bool leap = (y % 4 == 0);
        /* month cumulative days */
        int month_cum[13];
        month_cum[0] = 0;
        for (int m = 1; m <= 12; ++m) {
            int mdays = 31;
            if (m == 2) mdays = leap ? 29 : 28;
            else if (m == 4 || m == 6 || m == 9 || m == 11) mdays = 30;
            month_cum[m] = month_cum[m - 1] + mdays;
        }

        for (int m = 1; m <= 12; ++m) {          /* month 1‑12 */
            int mdays = month_cum[m] - month_cum[m - 1];
            for (int d = 1; d <= mdays; ++d) {    /* day 1‑mdays */
                char buf[20];
                int len = snprintf(buf, sizeof(buf), "%d.%d.%02d", d, m, y);
                /* palindrome test (include dots) */
                bool pal = true;
                for (int i = 0, j = len - 1; i < j; ++i, --j) {
                    if (buf[i] != buf[j]) { pal = false; break; }
                }
                if (!pal) continue;

                int abs_day = days_before_year[y] + month_cum[m - 1] + (d - 1);
                int offset = abs_day - REFERENCE_ABS_DAY;
                if (offset < 0) continue;   /* before 2000‑03‑01, ignore */

                pal_offsets[pal_n++] = (seq_t)offset;
            }
        }
    }
}

seq_t a(idx_t n) {
    if (n == 0) return 0;   /* undefined for 0, but keep defined */
    build_pal_offsets();
    if (n - 1 < pal_n) return pal_offsets[n - 1];
    return 0;   /* n beyond known terms */
}
