/*
 * A210999  Composite numbers that are in the gap between an odd-indexed prime
 *          and an even-indexed prime.
 * https://oeis.org/A210999
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 86, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A210999: composite numbers that lie strictly between an odd‑indexed prime
   and the next even‑indexed prime.  The sequence is generated by sieving all
   primes up to a fixed limit and collecting the composites in each corresponding gap. */
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

seq_t a(idx_t n)
{
    /* Static state ------------------------------------------------------------*/
    static bool initialized = false;
    static const uint64_t LIMIT = 400000;          /* enough for n up to several 10⁴              */
    static uint8_t *is_prime = NULL;
    static uint64_t *primes = NULL;               /* prime list (uint64_t)                       */
    static size_t primes_cnt = 0, primes_cap = 0;
    static seq_t *terms = NULL;                    /* composite list (seq_t)                      */
    static size_t terms_cnt = 0, terms_cap = 0;

    /* One‑time sieve & list construction -------------------------------------*/
    if (!initialized) {
        /* Allocate and run simple sieve --------------------------------------*/
        is_prime = (uint8_t*)malloc(LIMIT + 1);
        memset(is_prime, 1, LIMIT + 1);
        if (is_prime) is_prime[0] = is_prime[1] = 0;
        for (uint64_t i = 2; i * i <= LIMIT; ++i) {
            if (is_prime[i]) {
                for (uint64_t j = i * i; j <= LIMIT; j += i)
                    is_prime[j] = 0;
            }
        }

        /* Build prime list -----------------------------------------------*/
        primes_cap = LIMIT / 10 + 10;
        primes = (uint64_t*)malloc(primes_cap * sizeof(uint64_t));
        for (uint64_t i = 2; i <= LIMIT; ++i) {
            if (is_prime[i]) {
                if (primes_cnt == primes_cap) {
                    primes_cap *= 2;
                    primes = (uint64_t*)realloc(primes, primes_cap * sizeof(uint64_t));
                }
                primes[primes_cnt++] = i;
            }
        }

        /* Collect composites between odd‑even prime pairs ------------------*/
        terms_cap = LIMIT / 5 + 10;
        terms = (seq_t*)malloc(terms_cap * sizeof(seq_t));
        for (size_t idx = 0; idx + 1 < primes_cnt; idx += 2) {
            uint64_t p1 = primes[idx];
            uint64_t p2 = primes[idx + 1];
            for (uint64_t v = p1 + 1; v < p2; ++v) {
                if (!is_prime[v]) {                     /* v is composite */
                    if (terms_cnt == terms_cap) {
                        terms_cap *= 2;
                        terms = (seq_t*)realloc(terms, terms_cap * sizeof(seq_t));
                    }
                    terms[terms_cnt++] = (seq_t)v;
                }
            }
        }
        initialized = true;
    }

    /* Bounds check -----------------------------------------------------------*/
    if (n == 0 || (size_t)n > terms_cnt)
        return (seq_t)0;        /* undefined for requested n (should not occur) */

    return terms[n - 1];
}
