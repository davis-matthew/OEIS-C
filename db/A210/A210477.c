/*
 * A210477  Product of adjacent primes with a gap of 6.
 * https://oeis.org/A210477
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 14, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A210477: product of two consecutive primes whose difference is 6
   a(n) = p * (p + 6) where p is the nth prime such that the next
   consecutive prime equals p + 6.  The sequence is generated by
   scanning the primes in order and recording a product whenever two
   adjacent primes differ by 6.  The implementation uses a static
   cache so that calls to a(idx_t n) in any order are handled
   efficiently. */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime.h"

/* Static state between calls */
static seq_t   *seq_cache = NULL;   /* cached values of a(n)      */
static size_t  seq_len   = 0;        /* number of terms cached     */
static size_t  seq_cap   = 0;        /* capacity of seq_cache      */
static uint64_t prev_prime = 0;      /* last prime processed       */

/* Ensure seq_cache can hold at least 'needed' terms. */
static void ensure_cache_capacity(size_t needed)
{
    if (seq_cap < needed) {
        size_t new_cap = (seq_cap == 0) ? 8 : (seq_cap << 1);
        if (new_cap < needed) new_cap = needed;
        seq_cache = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
        seq_cap = new_cap;
    }
}

/* Return the first prime strictly greater than 'start'. */
static uint64_t next_prime(uint64_t start)
{
    uint64_t candidate = start + 1;

    /* Handle the special case of 2. */
    if (candidate <= 2) return 2;
    /* Skip even numbers after 2. */
    if ((candidate & 1ULL) == 0) ++candidate;

    for (;;) {
        if (is_prime(candidate)) return candidate;
        candidate += 2;   /* next odd candidate */
    }
}

/* Generate terms until at least 'target' terms have been cached. */
static void generate_terms_to(size_t target)
{
    /* Initialise on first call. */
    if (prev_prime == 0) prev_prime = 2;

    while (seq_len < target) {
        uint64_t curr = next_prime(prev_prime);

        if (curr - prev_prime == 6) {
            ensure_cache_capacity(seq_len + 1);
            seq_cache[seq_len++] = (seq_t)prev_prime * (seq_t)curr;
        }
        prev_prime = curr;
    }
}

/* Public function: returns the nth term (1‑based). */
seq_t a(idx_t n)
{
    if (n == 0) return 0;               /* below offset, value irrelevant */

    generate_terms_to((size_t)n);        /* extend cache if necessary */
    return seq_cache[(size_t)n - 1];
}
