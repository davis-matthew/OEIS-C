/*
 * A011733  A binary m-sequence: expansion of reciprocal of x^20 + x^3 + 1
 *          (mod 2, shifted by 19 initial 0's).
 * https://oeis.org/A011733
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 80, u16 n <= 80, u32 n <= 80, u64 n <= 80, u128 n <= 80,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A011733: a binary m‑sequence from 1/(1 + x^3 + x^20) over GF(2),
   shifted by 19 zeros.  For n < 19, a(n) = 0.  For n ≥ 19, let k = n‑19.
   Then a(n) = a(k), where the sequence a(k) satisfies the linear recurrence
   a(k) = a(k‑3) + a(k‑20) (mod 2) with initial value a(0) = 1.  The period
   of the periodic part is 2^20‑1 = 1048575.  This implementation pre‑computes
   the period on first call and thereafter returns values in O(1).  */
#include <stdlib.h>     /* malloc, free */
#include <stdbool.h>    /* bool */

static seq_t *period = NULL;
static bool initialized = false;
#define PERIOD_LEN 1048575ULL

static void init_period(void) {
    period = (seq_t *)malloc(PERIOD_LEN * sizeof(seq_t));
    if (!period) abort();           /* OOM – let the program crash explicitly */
    /* a(0) = 1, others generated by recurrence */
    period[0] = 1;
    for (idx_t i = 1; i < PERIOD_LEN; ++i) {
        seq_t val = 0;
        if (i >= 3)   val ^= period[i - 3];
        if (i >= 20)  val ^= period[i - 20];
        period[i] = val;
    }
    initialized = true;
}

seq_t a(idx_t n) {
    if (!initialized) init_period();
    if (n < 19) return 0;          /* shift by 19 zeros */
    idx_t k = (n - 19) % PERIOD_LEN;
    return period[k];
}
