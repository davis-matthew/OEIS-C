/*
 * A195093  Numbers k such that (number of prime factors of k counted with
 *          multiplicity) less (number of distinct prime factors of k) = 9.
 * https://oeis.org/A195093
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 47, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   alloc_uint32, alloc_uint8
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A195093:  numbers k such that Ω(k) - ω(k) = 9.
   Generated by a sieve up to a fixed limit and collecting all
   k whose prime‑factor multiset has exactly nine more prime
   factors (counted with multiplicity) than distinct prime factors. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/alloc_uint32.h"
#include "../utils/alloc_uint8.h"

/* local constants ------------------------------------------------------- */
static const size_t LIMIT = 20000000;   /* adjust if more terms are needed  */
static const size_t INIT_CAP = 16384;   /* initial capacity for answer array */

/* --------------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    /* static storage for the sequence cache --------------------------------- */
    static bool initialized = false;
    static seq_t *seq = NULL;          /* array of a(i) for i>=1          */
    static idx_t seq_len = 0;          /* number of stored terms           */

    if (!initialized) {
        /* ---------- build spf table ---------------------------------------- */
        uint32_t *spf = alloc_uint32(LIMIT);
        if (!spf) return 0;  /* out of memory */

        for (size_t i = 2; i <= LIMIT; ++i) {
            if (!spf[i]) {
                spf[i] = (uint32_t)i;            /* i is prime                */
                if (i > LIMIT / i) continue;    /* i*i would overflow        */
                for (size_t j = i * i; j <= LIMIT; j += i) {
                    if (!spf[j]) spf[j] = (uint32_t)i;
                }
            }
        }

        /* ---------- build diff array and collect terms --------------------- */
        uint8_t *diff = alloc_uint8(LIMIT);
        if (!diff) { free(spf); return 0; }

        diff[1] = 0;
        seq = (seq_t *)malloc(INIT_CAP * sizeof(seq_t));
        if (!seq) { free(spf); free(diff); return 0; }

        seq_len = 0;
        size_t seq_cap = INIT_CAP;

        for (size_t x = 2; x <= LIMIT; ++x) {
            uint32_t p = spf[x];
            size_t m = x / p;
            uint8_t d = diff[m];
            /*  if p divides m, Ω increases by 1 but ω does not.  */
            if (m % p == 0) {
                d = d + 1;
            }   /* else d unchanged (ω increases by 1, Ω also adds 1) */
            diff[x] = d;

            if (d == 9) {
                if (seq_len == seq_cap) {
                    seq_cap <<= 1;
                    seq = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));
                }
                seq[seq_len++] = (seq_t)x;
            }
        }

        /* free temporary arrays -------------------------------------------- */
        free(spf);
        free(diff);

        initialized = true;
    }

    /* ---------- answer request ------------------------------------------- */
    if (n < 1 || n > (idx_t)seq_len) {
        return 0;   /* out of bounds – caller should not request these */
    }
    return seq[n - 1];
}
