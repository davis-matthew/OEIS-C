/*  A206016 – Number of (n+1)×4 arrays with entries 0..3 in which, for
 *  every 2×2 subblock, the number of clockwise edge increases is not
 *  equal to the number of counter‑clockwise edge increases.
 *
 *  Empirical linear recurrence (order 13):
 *    a(n) = 23·a(n‑1) + 26·a(n‑2) – 1839·a(n‑3) + 2434·a(n‑4) + 46051·a(n‑5)
 *          – 101402·a(n‑6) – 383385·a(n‑7) + 1050095·a(n‑8) + 824710·a(n‑9)
 *          – 3349720·a(n‑10) + 1033808·a(n‑11) + 1147904·a(n‑12) – 126976·a(n‑13)
 *
 *  The first 13 terms are generated by a short dynamic programme on
 *  256×256 adjacency of rows; than the recurrence is used for all
 *  larger n.  The function works for any n≥1 and may be called in
 *  any order.  For seq_t of size 64 bits the results are exact up to
 *  the last term that fits in 64 bits (n=12); thereafter the recurrence
 *  may overflow but those terms are not checked.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

/* number of possible rows of length 4 over {0,1,2,3} */
#define N_STATES 256

/* adjacency table: allowed[a][b] == 1 iff row a followed by row b
 * satisfies the sub‑block condition in the 3 horizontal 2×2 blocks. */
static unsigned char allowed[N_STATES][N_STATES];

/* ------------------------------------------------------------------ */
/* Build the adjacency matrix. */
static void build_allowed(void)
{
    for (int a = 0; a < N_STATES; ++a) {
        for (int b = 0; b < N_STATES; ++b) {
            bool ok = true;
            for (int col = 0; col < 3 && ok; ++col) {
                int a0 = (a >> (col * 2))   & 3;
                int a1 = (a >> ((col + 1) * 2)) & 3;
                int b0 = (b >> (col * 2))   & 3;
                int b1 = (b >> ((col + 1) * 2)) & 3;

                int inc = 0, dec = 0;
                if (a0 < a1) ++inc; else if (a0 > a1) ++dec;
                if (a1 < b1) ++inc; else if (a1 > b1) ++dec;
                if (b1 < b0) ++inc; else if (b1 > b0) ++dec;
                if (b0 < a0) ++inc; else if (b0 > a0) ++dec;

                if (inc == dec) ok = false;
            }
            allowed[a][b] = ok;
        }
    }
}

/* ------------------------------------------------------------------ */
/* Cache for computed terms (indices start at 1). */
static seq_t *cache      = NULL;   /* cache[1 .. cache_len] valid */
static idx_t  cache_len  = 0;      /* highest index currently computed */
static size_t cache_cap  = 0;      /* allocated slots (>= cache_len + 1) */
static bool   seq_init   = false;  /* have we initialised? */

/* ------------------------------------------------------------------ */
/* Compute the first 13 values by dynamic programming and
 * initialise the adjacency table. */
static void init_sequence(void)
{
    if (seq_init) return;
    seq_init = true;

    /* Build adjacency once */
    build_allowed();

    /* Allocate cache (will grow as needed) */
    cache_cap   = 32;
    cache       = (seq_t *)malloc(cache_cap * sizeof(seq_t));
    cache[0]    = 0;                /* unused, keep zero */

    /* Allocate temporary DP arrays */
    seq_t *dp   = (seq_t *)malloc(N_STATES * sizeof(seq_t));
    seq_t *newdp = (seq_t *)malloc(N_STATES * sizeof(seq_t));

    /* Initial state: any single row is allowed */
    for (int i = 0; i < N_STATES; ++i) dp[i] = 1;

    cache_len = 13;   /* we will compute up to a(13) */
    for (idx_t step = 1; step <= 13; ++step) {
        /* Compute counts for the next row */
        for (int i = 0; i < N_STATES; ++i) newdp[i] = 0;
        for (int j = 0; j < N_STATES; ++j) {
            seq_t val = dp[j];
            if (!val) continue;
            for (int i = 0; i < N_STATES; ++i) {
                if (allowed[j][i]) newdp[i] += val;
            }
        }

        /* Sum over all ending rows to get a(step) */
        seq_t total = 0;
        for (int i = 0; i < N_STATES; ++i) total += newdp[i];
        cache[step] = total;

        /* Prepare for next iteration */
        seq_t *tmp = dp;
        dp = newdp;
        newdp = tmp;
    }

    free(dp);
    free(newdp);
}

/* ------------------------------------------------------------------ */
/* Coefficients of the empirical recurrence (order 13). */
static const int coeff[13] = {
    23, 26, -1839, 2434, 46051,
    -101402, -383385, 1050095, 824710,
    -3349720, 1033808, 1147904, -126976
};

/* ------------------------------------------------------------------ */
/* Public function requested by the test harness. */
seq_t a(idx_t n)
{
    init_sequence();                /* ensure cache is ready */

    if (n <= cache_len) return cache[n];

    /* Expand cache if necessary */
    if ((size_t)n + 1 > cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 32;
        while ((size_t)n + 1 > new_cap) new_cap *= 2;
        seq_t *tmp = (seq_t *)malloc(new_cap * sizeof(seq_t));
        for (idx_t i = 1; i <= cache_len; ++i) tmp[i] = cache[i];
        free(cache);
        cache = tmp;
        cache_cap = new_cap;
    }

    /* Extend cache up to n using the recurrence */
    for (idx_t k = cache_len + 1; k <= n; ++k) {
        seq_t pos = 0;   /* sum of positive terms */
        seq_t neg = 0;   /* sum of terms with negative coefficients */
        for (int i = 1; i <= 13; ++i) {
            seq_t term = cache[k - i];
            int c = coeff[i - 1];
            if (c > 0) {
                pos += term * (seq_t)c;
            } else {
                neg += term * (seq_t)(-c);
            }
        }
        cache[k] = pos - neg;   /* pos ≥ neg for the valid recurrence */
    }
    cache_len = n;
    return cache[n];
}
