/*
 * A319406  Write n-th prime in binary, then increase each run of 0's by one
 *          0, and increase each run of 1's by one 1. a(n) is the decimal
 *          equivalent of the result.
 * https://oeis.org/A319406
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 11, u16 n <= 101, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Algorithm: For the n‑th prime p, write p in binary,
   extend every maximal run of identical bits by one,
   then interpret the resulting binary string as a decimal number. */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* Find the n‑th prime (1‑based).  The array holds primes
   up to at least 20 000, which is sufficient for n ≈ 10 000
   (the 10 000th prime is 104 729).  Subsequent primes are
   generated by simple trial division against the primes
   already found.  The function is memoised across calls. */
static uint32_t nth_prime(idx_t n)
{
    /* Storage for up to 20 000 primes – far more than needed. */
    static uint32_t primes[20000];
    static size_t prime_count = 0;

    if (prime_count == 0) {
        primes[0] = 2U;
        prime_count = 1;
    }

    while (prime_count < (size_t)n) {
        uint32_t cand = primes[prime_count - 1] + 1U;
        for (;;) {
            bool is_p = true;
            for (size_t i = 0; i < prime_count && (uint64_t)primes[i] * primes[i] <= cand; ++i) {
                if (cand % primes[i] == 0) {
                    is_p = false;
                    break;
                }
            }
            if (is_p) {
                if (prime_count < sizeof(primes) / sizeof(primes[0])) {
                    primes[prime_count++] = cand;
                }
                break;
            }
            ++cand;
        }
    }
    return primes[n - 1];
}

seq_t a(idx_t n)
{
    /* 1. Fetch the n‑th prime. */
    uint32_t p = nth_prime(n);

    /* 2. Determine the binary length of the prime. */
    unsigned bitlen = 0;
    uint32_t tmp = p;
    while (tmp) {
        ++bitlen;
        tmp >>= 1;
    }
    if (bitlen == 0) bitlen = 1;          /* never happens for primes */

    /* 3. Scan bits from most significant to least significant,
       building the run‑extended result as we go. */
    seq_t result = 0;
    uint32_t cur_bit = (p >> (bitlen - 1)) & 1U;
    unsigned run_len = 1U;

    for (int i = (int)bitlen - 2; i >= 0; --i) {
        uint32_t bit = (p >> i) & 1U;
        if (bit == cur_bit) {
            ++run_len;
        } else {
            /* Append the extended run of cur_bit. */
            result <<= (run_len + 1);
            if (cur_bit) {
                seq_t mask = ((seq_t)1 << (run_len + 1)) - 1;
                result |= mask;
            }
            cur_bit = bit;
            run_len = 1U;
        }
    }

    /* 4. Append the final run. */
    result <<= (run_len + 1);
    if (cur_bit) {
        seq_t mask = ((seq_t)1 << (run_len + 1)) - 1;
        result |= mask;
    }

    return result;
}
