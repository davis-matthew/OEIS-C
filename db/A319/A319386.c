/*
 * A319386  Semiprimes k = pq with primes p < q such that p-1 does not divide
 *          q-1.
 * https://oeis.org/A319386
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 17, u16 n <= 7600, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   factor_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute the OEIS sequence A319386:
   ant-Carmichael semiprimes k = p*q (p < q primes) such that
   p-1 does not divide q-1.
   The sequence is generated by scanning odd numbers not
   divisible by 3, testing for semiprimality and the
   divisibility condition.  Results are memoised.  */
#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/factor_u64.h"

seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* offset is 1 */

    /* static cache */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;

    /* last candidate checked (odd, not divisible by 3) */
    static uint64_t last_checked = 35;   /* first valid odd > 3 */

    size_t need = (size_t)n;

    /* generate terms until we have at least n of them */
    while (cache_len < need)
    {
        /* skip multiples of 3 (they are already odd) */
        if ((last_checked % 3) == 0)
        {
            last_checked += 2;
            continue;
        }

        /* factor the current candidate */
        uint64_t pr[8], ex[8];
        size_t cnt = 0;
        factor_u64(last_checked, pr, ex, &cnt);

        /* check for a semiprime with two distinct primes */
        if (cnt == 2 && ex[0] == 1 && ex[1] == 1)
        {
            uint64_t p = pr[0], q = pr[1];
            if (p > q) { uint64_t t = p; p = q; q = t; }

            if (p < q && ((q - 1) % (p - 1)) != 0)
            {
                /* ensure capacity */
                if (cache_len + 1 > cache_cap)
                {
                    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                    if (!tmp) return 0;      /* out of memory */
                    cache = tmp;
                    cache_cap = new_cap;
                }
                cache[cache_len++] = (seq_t)last_checked;
            }
        }

        last_checked += 2;   /* next odd number */
    }

    return cache[need - 1];
}
