/* A353578: Numbers in the smallest subset of N containing 3 and closed
   under the mappings k → 2k+1, k → 8k+3, and k → 16k+3.
   The sequence is generated incrementally in sorted order with
   three advance pointers; no heap or hash table is required.  This
   algorithm runs in O(n) time and uses O(n) memory. */

#include <stdlib.h>
#include "../utils/min_three.h"

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;  /* undefined for 0, safe fallback */

    /* Allocate an array large enough for the first n terms. */
    seq_t *seq = (seq_t *)malloc((size_t)n * sizeof(seq_t));
    if (!seq)
        return (seq_t)0;  /* allocation failure */

    /* First term is 3.  Indices of the next candidate generated by each
       mapping start at 0, pointing to the element that is currently
       being processed. */
    seq[0] = (seq_t)3;
    idx_t p2  = 0, p8  = 0, p16 = 0;

    for (idx_t i = 1; i < n; ++i)
    {
        seq_t cand2, cand8, cand16, next;

        /* Repeatedly compute the smallest candidate that is strictly
           greater than the previous term (duplicates are skipped). */
        while (1)
        {
            cand2  = seq[p2] * (seq_t)2 + (seq_t)1;
            cand8  = seq[p8] * (seq_t)8 + (seq_t)3;
            cand16 = seq[p16] * (seq_t)16 + (seq_t)3;
            next   = min_three(cand2, cand8, cand16);

            if (i > 0 && next == seq[i - 1])
            {
                /* Duplicate found – advance all pointers that produced it
                   and try again. */
                if (cand2 == next)  p2++;
                if (cand8 == next)  p8++;
                if (cand16 == next) p16++;
                continue;
            }
            break;
        }

        seq[i] = next;

        /* Advance the pointers whose candidate produced the term. */
        if (cand2 == next)  p2++;
        if (cand8 == next)  p8++;
        if (cand16 == next) p16++;
    }

    seq_t result = seq[n - 1];
    free(seq);
    return result;
}
