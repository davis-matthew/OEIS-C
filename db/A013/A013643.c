/*
 * A013643  Numbers k such that the continued fraction for sqrt(k) has period
 *          3.
 * https://oeis.org/A013643
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, changed
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 76, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   compute_dn
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A013643: numbers k such that the continued fraction for sqrt(k)
   has period 3.  They are generated by the formula
   d(m,n) = a^2 + 4mn + 1,
   where a = ((4m^2 + 1)n + m)   and m,n are positive integers. */

#include <stdlib.h>
#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/compute_dn.h"

struct Node {
    seq_t val;      /* value d(m,n) */
    uint64_t m;     /* current m */
    uint64_t n;     /* current n */
};

/* ----------  cache of the sequence  ---------- */
static seq_t *cache      = NULL;
static size_t cache_len  = 0;
static size_t cache_cap  = 0;

/* ----------  min–heap of candidate values  ---------- */
static struct Node *heap     = NULL;
static size_t heap_size       = 0;
static size_t heap_cap        = 0;
static uint64_t next_m_to_add = 2;      /* next m to be inserted */

/* ----------  push node into min‑heap  ---------- */
static void push_node(struct Node node)
{
    if (heap_cap == 0) {
        heap_cap = 64;
        heap = (struct Node *)malloc(heap_cap * sizeof(struct Node));
    } else if (heap_size == heap_cap) {
        heap_cap <<= 1;
        heap = (struct Node *)realloc(heap, heap_cap * sizeof(struct Node));
    }

    size_t i = heap_size++;
    heap[i] = node;

    /* sift up */
    while (i > 0) {
        size_t p = (i - 1) >> 1;
        if (heap[p].val <= heap[i].val) break;
        struct Node tmp = heap[p];
        heap[p] = heap[i];
        heap[i] = tmp;
        i = p;
    }
}

/* ----------  pop smallest node  ---------- */
static struct Node pop_node(void)
{
    struct Node top = heap[0];
    heap[0] = heap[--heap_size];

    size_t i = 0;
    while (1) {
        size_t left = (i << 1) + 1;
        if (left >= heap_size) break;
        size_t right = left + 1;
        size_t child = left;
        if (right < heap_size && heap[right].val < heap[left].val)
            child = right;
        if (heap[i].val <= heap[child].val) break;
        struct Node tmp = heap[i];
        heap[i] = heap[child];
        heap[child] = tmp;
        i = child;
    }
    return top;
}

/* ----------  public interface  ---------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;

    /* Initialise heap with m = 1 */
    if (heap == NULL) {
        heap_cap = 64;
        heap = (struct Node *)malloc(heap_cap * sizeof(struct Node));
        seq_t val = compute_dn(1, 1);
        heap[0].val = val;
        heap[0].m   = 1;
        heap[0].n   = 1;
        heap_size   = 1;
        next_m_to_add = 2;
    }

    /* Generate elements until we have n of them */
    while (cache_len < (size_t)n) {
        if (heap_size == 0) break;   /* should not happen */

        struct Node top = pop_node();

        /* store to cache if not a duplicate */
        if (cache_len == 0 || top.val != cache[cache_len - 1]) {
            if (cache_len == cache_cap) {
                if (cache_cap == 0) {
                    cache_cap = 64;
                    cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
                } else {
                    cache_cap <<= 1;
                    cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
                }
            }
            cache[cache_len++] = top.val;
        }

        /* push next n for the same m */
        struct Node next_node;
        next_node.m = top.m;
        next_node.n = top.n + 1;
        next_node.val = compute_dn(top.m, next_node.n);
        push_node(next_node);

        /* insert new m values while their minimal d <= current minimum */
        while (next_m_to_add > 0) {   /* loop will break via condition */
            seq_t d_min = compute_dn(next_m_to_add, 1);
            if (heap_size == 0 || d_min <= heap[0].val) {
                struct Node init_node;
                init_node.m   = next_m_to_add;
                init_node.n   = 1;
                init_node.val = d_min;
                push_node(init_node);
                next_m_to_add++;
            } else {
                break;
            }
        }
    }

    return cache[n - 1];
}
