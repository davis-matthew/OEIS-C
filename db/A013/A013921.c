/*
 * A013921  Composite numbers that are equal to the sum of the first k
 *          composites for some k.
 * https://oeis.org/A013921
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 14, u16 n <= 279, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 66 terms through n = 9852 (2026-11-03)
 * Helpers:   is_prime_u128, is_prime_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: a(n) are composite numbers equal to the sum of the first k
 * composite numbers for some k.  The sequence is generated by iterating
 * over composite integers, maintaining a running sum, and recording the
 * sums that themselves are composite. */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <limits.h>
#include "../utils/is_prime_u128.h"
#include "../utils/is_prime_u64.h"

/* -----------------  Generic primality test ------------------------ */
static bool isPrimeGeneric(seq_t n)
{
    /* all seq_t are unsigned; use the smallest type that fits */
    if ((seq_t)(ULLONG_MAX) >= n) {
        return is_prime_u64((uint64_t)n);
    }
#if defined(__SIZEOF_INT128__)
    return is_prime_u128((__uint128_t)n);
#else
    /* fallback: if seq_t > 64‑bit but no 128‑bit support,
       order the test as simple trial division up to sqrt */
    seq_t limit = 0;
    for (seq_t i = 2; i*i <= n; ++i) {
        if (n % i == 0) return false;
    }
    return true;
#endif
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for n < 1, harmless  */

    idx_t  found   = 0;            /* how many terms we already found   */
    idx_t  candidate = 4;          /* next integer to test for compositeness */
    seq_t sum = 0;                 /* cumulative sum of composites       */

    while (found < n) {
        /* test the next integer for being composite */
        if (!isPrimeGeneric((seq_t)candidate)) {
            sum += (seq_t)candidate;                     /* add composite */

            /* if the resulting sum is composite, record it */
            if (!isPrimeGeneric(sum)) {
                ++found;
                if (found == n) return sum;
            }
        }
        ++candidate;               /* advance to next integer            */
    }

    return sum;  /* not reached, but keeps the compiler happy */
}
