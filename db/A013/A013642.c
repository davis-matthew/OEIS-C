/*
 * A013642  Numbers k such that the continued fraction for sqrt(k) has period
 *          2.
 * https://oeis.org/A013642
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, changed
 * Formula:   not stated
 * Range:     u8 n <= 59, u16 n <= 2022, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   OEIS A013642: numbers k such that the continued fraction for sqrt(k)
   has period 2.  Each term is k = a² + b where a ≥ 1 and b | (2a), b > 1.
   The sequence is generated by enumerating these pairs, collecting the
   resulting k, sorting, deduplicating, and storing the values in ascending
   order.
*/

#include <stdlib.h>
#include <stdbool.h>

/* Helper comparison for qsort */
static int cmp_seq_t(const void *p1, const void *p2)
{
    const seq_t *a = (const seq_t *)p1;
    const seq_t *b = (const seq_t *)p2;
    if (*a < *b) return -1;
    if (*a > *b) return  1;
    return 0;
}

/* Cached sequence values and bookkeeping */
static seq_t *cache = NULL;        /* sorted, unique values */
static size_t cache_len = 0;       /* how many cached values */
static idx_t   current_a = 0;      /* largest ‘a’ processed in the cache */

/* Build the cache for all a ≤ limit.  The function stops early if a²
   overflows the seq_t type (preventing incorrect results on very small
   seq_t sizes). */
static void rebuild_cache(idx_t limit)
{
    /* Rough estimate for the number of generated values; 12 per a is ample. */
    size_t est = (size_t)(limit * 12);
    seq_t *tmp = (seq_t *)malloc(est * sizeof(seq_t));
    if (!tmp) abort();

    size_t n = 0;              /* number of generated values */
    for (idx_t a = 1; a <= limit; ++a) {
        /* Detect overflow of a² when seq_t is small.  If it overflows,
           skip all larger a since a² will only increase. */
        seq_t a_sq = (seq_t)a * (seq_t)a;
        if (a_sq < (seq_t)a) break;   /* overflow detected */

        idx_t d = 2 * a;          /* all admissible b divide d */
        for (idx_t i = 1; i * i <= d; ++i) {
            if (d % i == 0) {
                idx_t b1 = i;
                if (b1 > 1) {
                    seq_t k = a_sq + (seq_t)b1;
                    if (n == est) {          /* grow the buffer */
                        est <<= 1;
                        seq_t *t = (seq_t *)realloc(tmp, est * sizeof(seq_t));
                        if (!t) abort();
                        tmp = t;
                    }
                    tmp[n++] = k;
                }
                idx_t b2 = d / i;
                if (b2 > 1 && b2 != b1) {
                    seq_t k = a_sq + (seq_t)b2;
                    if (n == est) {
                        est <<= 1;
                        seq_t *t = (seq_t *)realloc(tmp, est * sizeof(seq_t));
                        if (!t) abort();
                        tmp = t;
                    }
                    tmp[n++] = k;
                }
            }
        }
    }

    /* Sort and remove duplicates */
    qsort(tmp, n, sizeof(seq_t), cmp_seq_t);
    size_t uniq = 0;
    for (size_t i = 0; i < n; ++i) {
        if (i == 0 || cmp_seq_t(&tmp[i], &tmp[uniq-1]) != 0)
            tmp[uniq++] = tmp[i];
    }

    /* Resize the cache to the exact size */
    seq_t *new_cache = (seq_t *)realloc(cache, uniq * sizeof(seq_t));
    if (!new_cache && uniq > 0) abort();
    if (new_cache) memcpy(new_cache, tmp, uniq * sizeof(seq_t));
    free(tmp);

    cache = new_cache;
    cache_len = uniq;
    current_a = limit;
}

/* Ensure the cache contains at least n terms.  The function doubles the
   limit until enough terms are available.  It terminates when further
   increases produce no new values (happens when a² overflows the type). */
static void ensure_terms(idx_t n)
{
    if (cache_len >= n) return;
    idx_t limit = current_a > 1 ? current_a : 64;   /* start reasonably */
    while (cache_len < n) {
        limit <<= 1;
        rebuild_cache(limit);
        /* If rebuilding with a larger limit doesn't add values,
           breaking to avoid infinite loop. */
        if (limit == current_a) break;
    }
}

/* Public sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for 0; acceptable placeholder */
    ensure_terms(n);
    return cache[n-1];             /* cache is 0‑based; a(1) = cache[0] */
}
