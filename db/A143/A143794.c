/*
 * A143794  Primes p, with index k, such that p-k and p+k are both prime.
 * https://oeis.org/A143794
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 76, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Validated: standard, pass, 55 terms through n = 891 (2026-11-03)
 * Helpers:   is_prime_u128, is_prime_u64, mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Formula: a(n) is the n-th prime p for which p-k and p+k are also prime,
 * where k is the 1‑based index of p in the prime list.
 * The sequence values are generated by scanning successive primes and testing
 * the required condition.  The array of found terms is memoized so that
 * repeated calls to a(n) are efficient.
 */

#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>
#include <limits.h>
#include "../utils/is_prime_u128.h"
#include "../utils/is_prime_u64.h"
#include "../utils/mem.h"

/* -----------------  Generic primality test ------------------------ */
static bool isPrimeGeneric(seq_t n)
{
    /* all seq_t are unsigned; use the smallest type that fits */
    if ((seq_t)(ULLONG_MAX) >= n) {
        return is_prime_u64((uint64_t)n);
    }
#if defined(__SIZEOF_INT128__)
    return is_prime_u128((__uint128_t)n);
#else
    /* fallback: if seq_t > 64‑bit but no 128‑bit support,
       order the test as simple trial division up to sqrt */
    seq_t limit = 0;
    for (seq_t i = 2; i*i <= n; ++i) {
        if (n % i == 0) return false;
    }
    return true;
#endif
}

static seq_t *seq = NULL;        /* array of sequence terms */
static size_t seq_cap = 0;       /* current capacity of seq */
static size_t seq_len = 0;       /* number of terms stored */

static uint64_t next_candidate = 2; /* next integer to test for primality */
static idx_t prime_index = 0;       /* 1‑based index of the last prime seen */

/* Grow the seq array to accommodate at least `needed` elements. */
static void ensure_seq_cap(size_t needed)
{
    if (needed <= seq_cap) return;
    size_t new_cap = seq_cap ? seq_cap << 1 : 8;
    while (new_cap < needed) new_cap <<= 1;
    seq_t *tmp = mem_resize(seq_t, seq, new_cap);
    if (!tmp) abort();                /* allocation failure */
    seq = tmp;
    seq_cap = new_cap;
}

/* Generate terms until we have at least `target` terms. */
static void generate_terms(idx_t target)
{
    if (target <= seq_len) return;

    while (seq_len < target)
    {
        bool is_prime = false;
        uint64_t cand = next_candidate;

        /* Test whether cand is prime using the generic routine. */
        if (cand == 2) {
            is_prime = true;
        } else if ((cand & 1ULL) && isPrimeGeneric((seq_t)cand)) {
            is_prime = true;
        }

        if (is_prime)
        {
            /* cand is the next prime, so increment the prime index. */
            ++prime_index;
            seq_t p        = (seq_t)cand;
            seq_t k        = (seq_t)prime_index;

            /* Check the defining condition of the sequence. */
            if (isPrimeGeneric(p - k) && isPrimeGeneric(p + k))
            {
                ensure_seq_cap(seq_len + 1);
                seq[seq_len++] = p;
            }
        }

        /* Advance to the next candidate. */
        next_candidate = (cand == 2) ? 3U : cand + 2U;
    }
}

/* Public API: return the n-th term of the sequence (1‑based). */
seq_t a(idx_t n)
{
    if (n == 0) return 0;            /* offset does not matter below 1 */

    if (n > seq_len) generate_terms(n);
    return seq[n - 1];
}
