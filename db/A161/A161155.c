/*
 * A161155  Positive integers n such that {the number of (non-leading) 0's in
 *          the binary representation of n} is coprime to n, {the number of
 *          1's in the binary representation of n} is coprime to n and {the
 *          number of digits in the binary representation of n} is coprime to
 *          n.
 * https://oeis.org/A161155
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   a(n) = n-th positive integer n such that gcd(number of 0's in
 *            binary repr., n) = 1, gcd(number of 1's in binary repr., n) = 1,
 *            gcd(number of binary digits, n) = 1 The sequence is generated by
 *            searching integers sequentially
 * Range:     u8 n <= 85, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/gcd.h"

static size_t seq_size = 0;          /* number of terms stored */
static size_t seq_cap  = 0;          /* capacity of the array */
static seq_t *seq_arr  = NULL;       /* cached terms */
static uint64_t next_val = 1;        /* next candidate integer to test */

/* Helper: test whether a candidate value satisfies the three coprime conditions. */
static inline bool valid_candidate(uint64_t v)
{
    /* length of binary representation */
    uint64_t len = 64 - __builtin_clzll(v);
    /* number of 1 bits */
    uint64_t ones = __builtin_popcountll(v);
    /* number of 0 bits (non‑leading) */
    uint64_t zeros = len - ones;

    seq_t sv = (seq_t)v;
    return (gcd((seq_t)zeros, sv) == 1) &&
           (gcd((seq_t)ones,  sv) == 1) &&
           (gcd((seq_t)len,   sv) == 1);
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    /* Ensure the cached array has enough space for new terms. */
    if (seq_arr == NULL) {
        seq_cap = 8;
        seq_arr = (seq_t *)malloc(seq_cap * sizeof(seq_t));
    }

    /* Generate terms until we have at least n of them. */
    while (seq_size < n) {
        /* Find the next valid integer. */
        while (!valid_candidate(next_val)) {
            next_val++;
        }

        /* Store the new term. */
        if (seq_size == seq_cap) {
            seq_cap *= 2;
            seq_arr = (seq_t *)realloc(seq_arr, seq_cap * sizeof(seq_t));
        }
        seq_arr[seq_size++] = (seq_t)next_val;
        next_val++; /* next candidate to test */
    }

    return seq_arr[n - 1];
}
