/* Sequence: A061345 – odd prime powers (1 and the powers of odd primes).
   Computation: iterate over odd integers and test whether the integer has
   exactly one prime divisor.  The test uses trial division with a cached
   list of primes generated by a simple sieve.  The implementation
   supports any seq_t (unsigned) type and any idx_t (unsigned). */
#include <stdint.h>
#include <stdlib.h>

/* --------------------------------------------------------------------
   Prime sieve and cache
   -------------------------------------------------------------------- */
static uint64_t *prime_table = NULL;   /* array of primes (including 2)   */
static size_t    prime_cnt   = 0;     /* number of primes stored  */
static size_t    prime_cap   = 0;     /* allocated capacity of prime_table */

/* Expand the prime table to include all primes <= limit.
   The function is idempotent; a larger limit will extend the table. */
static void ensure_primes(size_t limit)
{
    if (limit <= prime_cap) return;               /* already sufficient */

    /* Allocate or enlarge the prime array */
    uint64_t *new_table = (uint64_t*)realloc(prime_table, (limit + 1) * sizeof(uint64_t));
    if (!new_table && limit) abort();             /* allocation failure */
    prime_table = new_table;
    prime_cap   = limit;

    /* Sieve up to limit */
    unsigned char *sieve = (unsigned char*)calloc(limit + 1, 1);   /* 0 .. limit */
    if (!sieve) abort();

    for (size_t i = 2; i * i <= limit; ++i)
        if (!sieve[i])
            for (size_t j = i * i; j <= limit; j += i)
                sieve[j] = 1;

    prime_cnt = 0;
    for (size_t i = 2; i <= limit; ++i)
        if (!sieve[i]) prime_table[prime_cnt++] = i;

    free(sieve);
}

/* --------------------------------------------------------------------
   Test whether a 64‑bit unsigned integer is a power of a single odd prime.
   -------------------------------------------------------------------- */
static int is_odd_prime_power_u64(uint64_t n)
{
    if (n < 3 || (n & 1ULL) == 0ULL) return 0;    /* 0,1,2 and even numbers are invalid */

    uint64_t tmp = n;
    uint64_t base = 0;        /* current prime divisor */
    int distinct = 0;          /* number of distinct prime factors */

    /* Ensure primes up to sqrt(tmp).  For the expected range a fixed limit
       (here 200 000) suffices for all n <= 10 000. */
    ensure_primes(200000);

    for (size_t i = 0; i < prime_cnt; ++i) {
        uint64_t p = prime_table[i];
        if (p * p > tmp) break;
        if (tmp % p == 0) {
            if (distinct == 1 && p != base) return 0;   /* more than one distinct prime */
            base = p;  distinct = 1;
            while (tmp % p == 0) tmp /= p;
        }
    }
    if (tmp > 1) {                         /* remaining prime factor > sqrt(tmp) */
        if (distinct == 1 && tmp == base) return 1;   /* only one prime factor */
        if (distinct == 0) {              /* n itself is prime */
            base = tmp; distinct = 1;
        } else {                          /* added a second distinct prime */
            return 0;
        }
    }

    /* At this point distinct == 1 and base is odd (n is odd)           */
    return 1;
}

/* --------------------------------------------------------------------
   Main sequence function
   -------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)1;          /* a(0) = 1 by definition */

    /* Enumerate odd integers until the n‑th odd prime power is found. */
    idx_t  found = 0;               /* how many odd prime powers have been seen */
    uint64_t cand = 3;              /* first odd candidate > 1 */

    while (1) {
        if (is_odd_prime_power_u64(cand)) {
            if (found == n - 1) return (seq_t)cand;
            ++found;
        }
        cand += 2;                  /* next odd integer */
    }
}
