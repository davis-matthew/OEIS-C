/*
 * A061511  a(0) = 0; a(n) is obtained by incrementing each digit of a(n-1) by
 *          1.
 * https://oeis.org/A061511
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 19, u16 n <= 28, u32 n <= 37, u64 n <= 46, u128 n <= 56,
 *            big any n
 * Helpers:   inc_digits
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence: a(0) = 0;
   a(n)   = f( a(n-1) )
   f(x)   = increment each decimal digit of x by 1;
   if a digit d == 9, it becomes the two-digit string "10". */

/* The sequence is generated by iterating the increment transform.
   To support arbitrary calls, a memoised cache is maintained
   and extended on demand. */

#include <stdlib.h>
#include <stdint.h>
#include "../utils/inc_digits.h"

static seq_t *seq_cache = NULL;   /* cache of computed terms */
static size_t cache_size = 0;     /* number of entries stored */

/* public entry point */
seq_t a(idx_t n)
{
    /* Ensure cache exists and has space for index n */
    if (seq_cache == NULL) {
        cache_size  = 64;
        seq_cache   = (seq_t *)malloc(cache_size * sizeof(seq_t));
        seq_cache[0] = (seq_t)0;   /* a(0) = 0 */
    }
    if (n >= (idx_t)cache_size) {
        /* grow cache to accommodate n */
        size_t new_size = cache_size;
        while (n >= (idx_t)new_size) new_size <<= 1;
        seq_cache = (seq_t *)realloc(seq_cache, new_size * sizeof(seq_t));
        cache_size = new_size;
    }

    /* Compute terms up to n if necessary */
    for (size_t i = 1; i <= (size_t)n; ++i) {
        if (seq_cache[i] != (seq_t)0) continue;  /* already computed */
        seq_cache[i] = inc_digits(seq_cache[i - 1]);
    }

    return seq_cache[n];
}
