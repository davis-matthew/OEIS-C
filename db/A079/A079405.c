/*
 * A079405  Number of dots in primes in Braille.
 * https://oeis.org/A079405
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 103, u16 n <= 103, u32 n <= 103, u64 n <= 103,
 *            u128 n <= 103, big any n
 * Helpers:   _prime_limit_for_idx, build_primes_upto
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Braille dot counts of digits of the n‑th prime (0‑indexed). */

#include <stddef.h>
#include <stdlib.h>
#include <stdint.h>
#include "../utils/_prime_limit_for_idx.h"
#include "../utils/build_primes_upto.h"

/* Braille dot count for decimal digits 0‑9. */
static const seq_t dot_map[10] = {3, 1, 2, 2, 3, 2, 3, 4, 3, 2};

/* Cached list of primes generated by build_primes_upto. */
static uint64_t *prime_cache = NULL;      /* 0‑indexed array of primes. */
static size_t   prime_cnt   = 0;          /* Number of primes stored. */
static idx_t    prime_limit = 0;          /* Upper bound used for building primes. */

seq_t a(idx_t n)
{
    /* Ensure the cache contains at least the (n‑th) prime (0‑indexed). */
    if ((size_t)n >= prime_cnt) {
        /* Ask for an upper bound that is guaranteed to contain the n‑th prime. */
        idx_t needed_limit = _prime_limit_for_idx(n);

        /* Rebuild the cache if it is insufficient. */
        while ((size_t)n >= prime_cnt) {
            /* If the requested limit is too small, double it. */
            if (needed_limit <= prime_limit)
                needed_limit = prime_limit * 2 + 1;

            free(prime_cache);                     /* Free old storage. */
            build_primes_upto(needed_limit, &prime_cache, &prime_cnt);
            prime_limit = needed_limit;
        }
    }

    /* Sum the Braille dot counts of the decimal digits of the prime. */
    uint64_t p = prime_cache[(size_t)n];
    seq_t sum = 0;
    while (p > 0) {
        uint8_t digit = (uint8_t)(p % 10U);
        sum += dot_map[digit];
        p /= 10U;
    }
    return sum;
}
