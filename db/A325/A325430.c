/* Complement of A325429.
   Sequence generated by iterating i = 1,2,3,…,
   marking 3*i and floor(3*i/2) whenever i is not in the set.
   The numbers marked are the terms a(n) in ascending order. */

#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* Array of a(n) values. */
static seq_t *seq = NULL;
static idx_t seq_len = 0;
static idx_t seq_cap = 0;

/* Boolean array indicating whether a number has been marked as a term. */
static uint8_t *marked = NULL;
static idx_t marked_cap = 0;

/* Next integer i to process. */
static idx_t next_i = 1;

/* Ensure ``marked'' has space for index ``idx''. */
static void ensure_marked_cap(idx_t idx)
{
    if (idx < marked_cap) return;
    idx_t new_cap = marked_cap ? marked_cap << 1 : 128;
    while (new_cap <= idx) new_cap <<= 1;
    uint8_t *tmp = (uint8_t *)realloc(marked, new_cap * sizeof(uint8_t));
    if (!tmp) exit(1);
    /* initialise new entries to 0 */
    memset(tmp + marked_cap, 0, (new_cap - marked_cap) * sizeof(uint8_t));
    marked = tmp;
    marked_cap = new_cap;
}

/* Ensure ``seq'' has space for another term. */
static void ensure_seq_cap(void)
{
    if (seq_len < seq_cap) return;
    idx_t new_cap = seq_cap ? seq_cap << 1 : 128;
    seq_t *tmp = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
    if (!tmp) exit(1);
    seq = tmp;
    seq_cap = new_cap;
}

seq_t a(idx_t n)
{
    /* Construct sequence terms until we have at least n of them. */
    while (seq_len < n) {
        /* Mark the current integer if not already. */
        ensure_marked_cap(next_i);
        if (marked[next_i]) {
            /* next_i is a term of the sequence. */
            ensure_seq_cap();
            seq[seq_len++] = (seq_t)next_i;
        } else {
            /* next_i belongs to the complement set. Generate images if i>1. */
            if (next_i > 1) {
                seq_t m1 = (seq_t)next_i * 3;
                seq_t m2 = ((seq_t)next_i * 3) / 2;   /* floor division */

                idx_t idx1 = (idx_t)m1;
                idx_t idx2 = (idx_t)m2;

                ensure_marked_cap(idx1);
                if (!marked[idx1]) marked[idx1] = 1;

                ensure_marked_cap(idx2);
                if (!marked[idx2]) marked[idx2] = 1;
            }
        }
        ++next_i;
    }
    return seq[n - 1];
}
