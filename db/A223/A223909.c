/*
 * A223909  Numbers for which the maximal run of 1's in their binary
 *          representation contains odd number of 1's.
 * https://oeis.org/A223909
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 127, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 80 terms through n = 9734 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute A223909: numbers where the maximal run of consecutive 1 bits in
   the binary representation is of odd length.  The sequence is
   generated by scanning all positive integers and collecting those with
   that property. */
#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>
#include "../utils/mem.h"

/* Return true iff the largest run of consecutive 1 bits in v has odd length. */
static bool maxrun_odd(seq_t v)
{
    seq_t curr = 0, maxrun = 0;
    while (v)
    {
        if (v & (seq_t)1)          /* current bit is 1   */
        {
            curr++;
            if (curr > maxrun) maxrun = curr;
        }
        else
            curr = 0;              /* bit is 0, reset run */
        v >>= 1;
    }
    return (maxrun & (seq_t)1) != 0;
}

static seq_t *cache = NULL;
static size_t cache_cap = 0;   /* allocated capacity of cache */
static size_t cache_len = 0;   /* number of terms stored in cache   */
static idx_t next_candidate = 1; /* next integer to test          */

/* Ensure the cache can hold at least 'needed' elements.  */
static void grow_cache(size_t needed)
{
    if (needed <= cache_cap) return;
    size_t newcap = cache_cap ? cache_cap * 2 : 16;
    while (newcap < needed) newcap *= 2;
    seq_t *tmp = mem_resize(seq_t, cache, newcap);
    if (!tmp) abort();          /* out of memory */
    cache = tmp;
    cache_cap = newcap;
}

seq_t a(idx_t n)
{
    if (n < 1) abort();         /* sequence is defined for n >= 1  */

    /* Generate terms until we have at least n of them. */
    while (cache_len < (size_t)n)
    {
        seq_t val = (seq_t)next_candidate;
        if (maxrun_odd(val))
        {
            grow_cache(cache_len + 1);
            cache[cache_len++] = val;
        }
        ++next_candidate;
    }

    return cache[(size_t)(n - 1)];
}
