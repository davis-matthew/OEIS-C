/*
 * A179955  Numbers whose sum of digits is 10 and which contain no 0 digits.
 * https://oeis.org/A179955
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, fini, full, nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 3, u32 n <= 511, u64 n <= 511, u128 n <= 511,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A179955: numbers whose digit sum is 10 and which contain no 0 digits.
   The sequence has 511 terms.  All terms are generated by recursively
   constructing compositions of 10 with parts 1–9, building the corresponding
   decimal number and storing it.  After generation the array is sorted
   numerically.  Subsequent calls use the precomputed table. */

#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>

/* Forward declaration of the comparator used by qsort. */
static int cmp_seq_t(const void *a, const void *b);

/* Static storage for the pre‑computed sequence */
#define SEQ_CAP 512
static seq_t seq[SEQ_CAP];
static unsigned seq_len = 0;
static bool seq_ready = false;

/* Recursive generator: builds all numbers whose digits sum to 'rem' and
   so far form 'val'.  When rem == 0, a full number has been constructed. */
static void gen(int rem, seq_t val)
{
    if (rem == 0) {
        if (seq_len < SEQ_CAP) {
            seq[seq_len++] = val;
        }
        return;
    }
    for (int d = 1; d <= 9; ++d) {
        if (d > rem) break;         /* too large digit */
        seq_t next = val * (seq_t)10 + (seq_t)d;
        gen(rem - d, next);
    }
}

/* Prepare the sequence once.  This is thread‑unsafe if needed but the
   SEQ_OFFSET is used in a controlled environment. */
static void prepare_sequence(void)
{
    if (!seq_ready) {
        seq_len = 0;
        gen(10, (seq_t)0);           /* start with sum 10 and value 0 */
        /* After generation seq_len should be 511 */
        if (seq_len < SEQ_CAP) {
            qsort(seq, seq_len, sizeof(seq_t), cmp_seq_t);
        }
        seq_ready = true;
    }
}

/* Comparator for qsort (works for integer and arbitrary‑precision types). */
static int cmp_seq_t(const void *a, const void *b)
{
    const seq_t *aa = (const seq_t *)a;
    const seq_t *bb = (const seq_t *)b;
    return (*aa < *bb) ? -1 : (*aa > *bb) ? 1 : 0;
}

/* Public API required by the build system. */
seq_t a(idx_t n)
{
    prepare_sequence();
    if (n == 0 || n > seq_len) {
        return (seq_t)0;              /* out of bounds: return 0 */
    }
    return seq[n - 1];
}
