/*
 * A273157  Numbers which have nonpositive entries in the difference table of
 *          their divisors (complement of A273130).
 * https://oeis.org/A273157
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 62, u16 n <= 62, u32 n <= 62, u64 n <= 62, u128 n <= 62,
 *            big any n
 * Helpers:   seq_cmp_func
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A273157: numbers that have nonpositive entries in the difference
   table of their divisors (the complement of A273130).  The sequence is
   generated by testing each integer for this property and caching found
   values for fast repeated queries. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/seq_cmp_func.h"

/* Test whether x has a nonpositive entry in its divisor-difference table. */
static bool has_nonpositive_entry(seq_t x)
{
    /* build list of divisors */
    static seq_t *divs = NULL;
    static size_t div_cap = 0;
    size_t div_len = 0;

    /* allocate space for divisors */
    if (divs == NULL || div_cap < 64) {
        div_cap = 64;
        divs = (seq_t *)realloc(divs, div_cap * sizeof(seq_t));
        if (!divs) exit(1);
    }

    for (seq_t d = 1; d <= x / d; ++d) {
        if (x % d == 0) {
            if (div_len == div_cap) {
                div_cap <<= 1;
                divs = (seq_t *)realloc(divs, div_cap * sizeof(seq_t));
                if (!divs) exit(1);
            }
            divs[div_len++] = d;
            if (d != x / d) {
                if (div_len == div_cap) {
                    div_cap <<= 1;
                    divs = (seq_t *)realloc(divs, div_cap * sizeof(seq_t));
                    if (!divs) exit(1);
                }
                divs[div_len++] = x / d;
            }
        }
    }

    /* sort divisors ascending */
    qsort(divs, div_len, sizeof(seq_t), seq_cmp_func);

    /* iterate over successive difference tables */
    seq_t *cur = divs;
    size_t cur_len = div_len;
    while (cur_len > 1) {
        /* check for nonpositive entry */
        for (size_t i = 0; i + 1 < cur_len; ++i) {
            if (cur[i] >= cur[i + 1]) {
                if (cur != divs) free(cur);
                return true;
            }
        }

        /* build next level of differences */
        seq_t *next = (seq_t *)malloc((cur_len - 1) * sizeof(seq_t));
        if (!next) exit(1);
        for (size_t i = 0; i + 1 < cur_len; ++i) {
            next[i] = cur[i + 1] - cur[i];
        }

        /* advance to next row */
        if (cur != divs) free(cur);
        cur = next;
        cur_len -= 1;
    }

    if (cur != divs) free(cur);
    return false;
}

/* Main sequence function.  Uses cache to handle arbitrary call order. */
seq_t a(idx_t n)
{
    /* static cache of discovered terms */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;

    /* static pointer to next candidate to test */
    static idx_t next_candidate = 1;

    /* extend cache until it contains the nth term */
    while (cache_len < n) {
        seq_t val = (seq_t)next_candidate;
        if (has_nonpositive_entry(val)) {
            if (cache_len == cache_cap) {
                cache_cap = (cache_cap == 0) ? 16 : cache_cap << 1;
                cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
                if (!cache) exit(1);
            }
            cache[cache_len++] = val;
        }
        ++next_candidate;
    }

    return cache[n - 1];
}
