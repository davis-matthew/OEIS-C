/* Continuant transform of Catalan numbers
   a(n) = K(C1, C2, …, Cn)   (K is the continuant)
   Recurrence:   a0 = 1
                 a1 = C1 = 1
                 for n ≥ 2:     a_n = C_n * a_{n-1} + a_{n-2}
   Catalan numbers C_k are generated by
                C_0 = 1
                C_k = C_{k-1} * 2*(2k-1) / (k+1)   for k ≥ 1   */
seq_t a(idx_t n)
{
    if (n == (idx_t)0) return 0;                  /* offset starts at 1 */

    seq_t a_prev2 = 1;            /* a_0 */
    seq_t a_prev1 = 0;            /* will hold a_{k-1} during the loop */
    seq_t catalan = 1;            /* C_1 = 1 */

    for (idx_t k = (idx_t)1; k <= n; ++k) {
        /* compute C_k for k ≥ 2 */
        if (k > (idx_t)1) {
            /* numerator: 2 * (2k - 1) */
            seq_t num = ((seq_t)2) * (((seq_t)2) * k - ((seq_t)1));
            catalan = catalan * num / ((seq_t)(k + (idx_t)1));
        }

        if (k == (idx_t)1) {                   /* a_1 = C_1 */
            a_prev1 = catalan;
        } else {
            seq_t cur = catalan * a_prev1 + a_prev2;
            a_prev2 = a_prev1;
            a_prev1 = cur;
        }
    }
    return a_prev1;
}
