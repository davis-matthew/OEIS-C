/*
 * A071365  Numbers k such that A071364(k) <> A046523(k).
 * https://oeis.org/A071365
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 16, u16 n <= 5076, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A071365: numbers k that have at least two distinct prime
   factors and whose exponents in the ordered factorization
   (primes in increasing order) are not non‑increasing; i.e. there is
   at least one strict increase from left to right.  The sequence
   is generated by scanning integers and collecting those that satisfy
   the condition.  */
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>

/* limit for precomputed smallest prime factor table */
#define SIEVE_LIMIT 500000

/* static tables for sieve */
static uint32_t spf[SIEVE_LIMIT + 1];
static uint32_t primes[SIEVE_LIMIT];
static size_t primes_cnt = 0;

/* cache for sequence terms */
static seq_t *seq_cache = NULL;
static size_t cache_cap = 0;
static size_t seq_count = 0;
static idx_t next_k = 2;  /* next integer to test */

/* build the sieve once */
static void init_sieve(void) {
    for (idx_t i = 2; i <= (idx_t)SIEVE_LIMIT; ++i) {
        if (spf[(uint32_t)i] == 0) {
            spf[(uint32_t)i] = (uint32_t)i;
            primes[primes_cnt++] = (uint32_t)i;
        }
        for (size_t j = 0; j < primes_cnt; ++j) {
            uint32_t p = primes[j];
            idx_t prod = i * (idx_t)p;
            if (p > spf[(uint32_t)i] || prod > (idx_t)SIEVE_LIMIT)
                break;
            spf[(uint32_t)prod] = p;
        }
    }
}

/* append a value to the cache, extending capacity if necessary */
static void cache_append(seq_t val) {
    if (seq_count == cache_cap) {
        size_t new_cap = cache_cap == 0 ? 20000 : cache_cap * 2;
        seq_t *tmp = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
        seq_cache = tmp;
        cache_cap = new_cap;
    }
    seq_cache[seq_count++] = val;
}

/* check if a given integer k satisfies the sequence condition */
static bool qualifies(idx_t k) {
    idx_t x = k;
    int last_exp = 0;
    int distinct = 0;
    bool increased = false;
    bool first = true;

    while (x > 1) {
        uint32_t p = spf[(uint32_t)x];
        int exp = 0;
        while (x % p == 0) {
            exp++;
            x /= p;
        }
        if (first) {
            first = false;
            last_exp = exp;
            distinct = 1;
        } else {
            if (exp > last_exp)
                increased = true;
            last_exp = exp;
            distinct++;
        }
    }
    return distinct >= 2 && increased;
}

/* public function required by the build */
seq_t a(idx_t n) {
    /* lazy initialization */
    if (seq_cache == NULL) {
        init_sieve();
        seq_cache = NULL;
        cache_cap = 0;
        seq_count = 0;
        next_k = 2;
    }

    while (seq_count < n) {
        if (next_k > (idx_t)SIEVE_LIMIT) {
            /* should never happen for n up to 10000 with current limit */
            return 0;
        }
        if (qualifies(next_k)) {
            cache_append((seq_t)next_k);
        }
        ++next_k;
    }

    return seq_cache[n - 1];
}
