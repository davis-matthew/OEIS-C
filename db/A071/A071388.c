/*
 * A071388  Numbers k such that the cardinality of the set of solutions to
 *          phi(x) = k is a prime.
 * https://oeis.org/A071388
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 56, u16 n <= 8830, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A071388: numbers k such that the number of integer solutions
   of φ(x) = k is a prime.  The sequence is generated by sieving the
   totient function up to a fixed bound and collecting those k whose
   count of preimages is prime.  The list of values is cached after the
   first call to a(idx_t).  */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>

/* Forward declaration of the public function. */
seq_t a(idx_t n);

/* ------------------------------------------------------------------ */
/*  Simple primality test for 32‑bit integers.  The values we test
    (the frequencies) are small, so a trial division is adequate. */
static bool is_prime_uint32(uint32_t x)
{
    if (x < 2) return false;
    if (x % 2 == 0) return x == 2;
    for (uint32_t d = 3; (uint64_t)d * d <= x; d += 2)
        if (x % d == 0) return false;
    return true;
}

/* ------------------------------------------------------------------ */
/*  Cached data.  They are initialised once, on the first call to a(). */
static seq_t *a_terms   = NULL;   /* array of terms of the sequence */
static size_t a_terms_len = 0;     /* number of valid terms */

/* ------------------------------------------------------------------ */
/*  Build the list of terms.  The totient sieve is performed once,
    up to a bound that is sufficiently large to supply more than
    10 000 terms of the sequence. */
static void init_sequence(void)
{
    static bool initialized = false;
    if (initialized) return;

    /* Bound for the totient sieve.  10 000 000 comfortably
       yields several hundred thousand terms, enough for the
       required test suite. */
    const uint32_t N = 10000000U;

    /* Allocate arrays for φ and for the frequencies. */
    uint32_t *phi  = (uint32_t *)malloc((N + 1) * sizeof(uint32_t));
    uint32_t *freq = (uint32_t *)calloc((N + 1), sizeof(uint32_t));

    /* Initialise φ[n] = n and compute the totient by a simple
       multiplicative sieve.  The sieve is O(N log log N). */
    for (uint32_t i = 0; i <= N; ++i) phi[i] = i;
    for (uint32_t p = 2; p <= N; ++p)
        if (phi[p] == p)          /* p is prime */
            for (uint32_t j = p; j <= N; j += p)
                phi[j] -= phi[j] / p;

    /* Count how many x map to each totient value k. */
    for (uint32_t x = 1; x <= N; ++x)
        ++freq[phi[x]];

    /* Collect the k whose frequency is a prime.  Grow the list
       dynamically as required. */
    size_t cap = 100000;                     /* initial capacity */
    a_terms = (seq_t *)malloc(cap * sizeof(seq_t));
    a_terms_len = 0;
    for (uint32_t k = 1; k <= N; ++k)
    {
        if (is_prime_uint32(freq[k]))
        {
            if (a_terms_len == cap)             /* grow if needed */
            {
                cap <<= 1;
                a_terms = (seq_t *)realloc(a_terms, cap * sizeof(seq_t));
            }
            a_terms[a_terms_len++] = (seq_t)k;
        }
    }

    /* Clean up temporary arrays. */
    free(phi);
    free(freq);

    initialized = true;
}

/* ------------------------------------------------------------------ */
/*  Return the n‑th term of the sequence (1‑based).  If n is out of
    range, 0 is returned. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;           /* undefined, guard against overflow */
    init_sequence();                /* ensure the list is ready */
    if ((size_t)n <= a_terms_len)
        return a_terms[n - 1];
    return 0;                       /* n too large for the pre‑computed list */
}
