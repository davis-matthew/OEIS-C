/*
 * A071250  Palindromes with successive increasing difference: a(k)-a(k-1) >
 *          a(k+1)- a(k).
 * https://oeis.org/A071250
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 11, u16 n <= 45, u32 n <= 45, u64 n <= 45, u128 n <= 45,
 *            big any n
 * Helpers:   build_pal
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A071250: Palindromes with successive increasing difference
   (differences strictly increasing).  The sequence is generated by
   iterating over all palindromes in increasing order and selecting
   those where the difference to the previous selected palindrome
   strictly increases. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/build_pal.h"

/* Helper to compute 10^e as a seq_t. */
static seq_t pow10(int e)
{
    seq_t r = 1;
    for (int i = 0; i < e; ++i) r *= 10;
    return r;
}

/* Main sequence function.  Uses static state to memoise computed terms
   and to continue palindrome generation across calls. */
seq_t a(idx_t n)
{
    /* Input is 1‑based; return 0 for n==0 just for safety. */
    if (n == 0) return 0;

    /* Static state initialised on first invocation. */
    static bool initialized = false;
    static size_t capacity = 16;          /* initial array size */
    static seq_t *seq = NULL;            /* array of terms */
    static size_t seq_len = 0;           /* number of terms stored */

    /* Generation state for producing palindromes in order. */
    static int gen_len = 1;                 /* current palindrome length   */
    static seq_t gen_half_start = 1;        /* first half value of current len  */
    static seq_t gen_half_end   = 9;        /* last  half value of current len  */
    static seq_t gen_half       = 1;        /* next half to use                 */

    /* Track the last accepted palindrome and difference. */
    static seq_t last_pal   = 0;
    static seq_t last_diff  = 0;
    static bool has_last_pat = false;      /* true after first accepted term  */

    /* Initialise storage and generation state on first call. */
    if (!initialized) {
        seq = (seq_t *)malloc(capacity * sizeof(seq_t));
        if (!seq) exit(1);   /* malloc failed */
        initialized = true;
    }

    /* Generate terms until we have at least n. */
    while (seq_len < n) {
        seq_t pal = build_pal(gen_half, gen_len);

        /* Advance generator to next palindrome. */
        ++gen_half;
        if (gen_half > gen_half_end) {
            /* Move to next length. */
            ++gen_len;
            int half_len = (gen_len + 1) / 2;
            gen_half_start = pow10(half_len - 1);
            gen_half_end   = pow10(half_len) - 1;
            gen_half       = gen_half_start;
        }

        /* Accept or reject this palindrome. */
        if (!has_last_pat) {
            /* First term – always accept. */
            seq[seq_len++] = pal;
            last_pal = pal;
            last_diff = 0;      /* diff for second term will be > 0 */
            has_last_pat = true;
        } else {
            seq_t diff = pal - last_pal;
            if (diff > last_diff) {
                /* Increasing difference – accept. */
                /* Ensure enough capacity. */
                if (seq_len >= capacity) {
                    capacity *= 2;
                    seq_t *tmp = (seq_t *)realloc(seq, capacity * sizeof(seq_t));
                    if (!tmp) exit(1);
                    seq = tmp;
                }
                seq[seq_len++] = pal;
                last_pal = pal;
                last_diff = diff;
            }
        }
    }

    return seq[n - 1];
}
