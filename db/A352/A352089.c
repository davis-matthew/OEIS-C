/*
 * A352089  Tribonacci-Niven numbers: numbers that are divisible by the number
 *          of terms in their minimal (or greedy) representation in terms of
 *          the tribonacci numbers (A278038).
 * https://oeis.org/A352089
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 55, u16 n <= 6748, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Computation: Tribonacci‑Niven numbers are generated by
   scanning integer k >= 1, computing the greedy Tribonacci
   representation, counting the number of terms, and
   keeping k if k is divisible by that count.  The function
   memoises the list so that any call to a(n) returns the
   n‑th term (1‑based indexing) in O(1) after the list has
   been computed up to that index.
*/

#include <stdlib.h>
#include <stdbool.h>

/* Static storage for Tribonacci numbers (first few: 1,1,2,4,7,13,…) */
static seq_t *trib = NULL;
static size_t trib_len = 0;      /* number of elements stored */
static size_t trib_cap = 0;      /* current allocation */

/* Static storage for found Tribonacci‑Niven numbers */
static seq_t *terms = NULL;
static size_t terms_len = 0;
static size_t terms_cap = 0;

/* Ensure that the Tribonacci array contains numbers up to at least `limit`. */
static void
ensure_trib(seq_t limit)
{
    if (trib_len == 0) {
        /* initialise with 1,1,2 */
        tril: ;
        if (trib_cap < 3) {
            trib_cap = 3;
            trib = (seq_t *)realloc(trib, trib_cap * sizeof(seq_t));
        }
        trib[0] = (seq_t)1;
        trib[1] = (seq_t)1;
        trib[2] = (seq_t)2;
        trib_len = 3;
    }

    while (trib[trib_len-1] < limit) {
        seq_t next;
        if (trib_len >= 3) {
            next = trib[trib_len-1] + trib[trib_len-2] + trib[trib_len-3];
        } else {
            /* this block will not be reached because trib_len >=3 after init */
            next = (seq_t)0;
        }

        if (trib_len == trib_cap) {
            trib_cap = trib_cap ? trib_cap * 2 : 4;
            trib = (seq_t *)realloc(trib, trib_cap * sizeof(seq_t));
        }
        trib[trib_len++] = next;
    }
}

/* Count the number of terms in the greedy Tribonacci representation of `k`. */
static idx_t
count_terms(seq_t k)
{
    seq_t rem = k;
    idx_t count = 0;
    /* Start from the largest Tribonacci number <= k */
    size_t i = trib_len;
    while (rem > 0) {
        while (i > 0 && trib[i-1] > rem) --i;
        if (i == 0) break;     /* should not happen for k >= 1 */
        rem -= trib[i-1];
        ++count;
    }
    return count;
}

/* Ensure the terms array can hold at least `needed` elements. */
static void
ensure_terms(size_t needed)
{
    if (terms_cap == 0) {
        terms_cap = 4;
        terms = (seq_t *)realloc(terms, terms_cap * sizeof(seq_t));
    }
    while (terms_cap < needed) {
        terms_cap = terms_cap * 2;
        terms = (seq_t *)realloc(terms, terms_cap * sizeof(seq_t));
    }
}

seq_t a(idx_t n)
{
    if (n == (idx_t)0) {
        return (seq_t)0;  /* undefined for offset 1, but safe for callers */
    }

    /* Initialise tribonacci array on first call */
    if (trib_len == 0) {
        trib_cap = 3;
        trib = (seq_t *)realloc(trib, trib_cap * sizeof(seq_t));
        trib[0] = (seq_t)1;
        trib[1] = (seq_t)1;
        trib[2] = (seq_t)2;
        trib_len = 3;
    }

    /* Generate terms until we have at least n of them */
    while (terms_len < (size_t)n) {
        seq_t candidate = (terms_len == 0) ? (seq_t)1 : terms[terms_len-1] + (seq_t)1;
        for (;;) {
            /* Make sure we have Tribonacci numbers up to candidate */
            ensure_trib(candidate);
            idx_t cnt = count_terms(candidate);
            if (cnt != (idx_t)0 && candidate % cnt == (seq_t)0) {
                /* Store candidate */
                ensure_terms(terms_len + 1);
                terms[terms_len++] = candidate;
                break;
            }
            ++candidate;
        }
    }
    return terms[n-1];
}
