/*
 * A352830  Numbers whose weakly increasing prime indices y have no fixed
 *          points y(i) = i.
 * https://oeis.org/A352830
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 61, u16 n <= 61, u32 n <= 61, u64 n <= 61, u128 n <= 61,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: a(n) = n-th smallest positive integer whose multiset of prime indices
   has no fixed points y(i)=i.  The values are generated by sieving primes up
   to a fixed limit and testing each integer in order. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

#define MAX_LIMIT 2000000  /* sufficient for n up to about 10 000 */

/* Prime sieve data */
static uint32_t *spf = NULL;           /* smallest prime factor for each number */
static uint32_t *prime_index = NULL;   /* prime index for each prime number */
static uint32_t *primes = NULL;        /* list of primes */
static size_t prime_count = 0;

/* Sequence cache */
static seq_t *seq_cache = NULL;   /* cached terms of A352830 */
static size_t seq_cap = 0;         /* allocated capacity of seq_cache */
static size_t seq_len = 0;         /* number of cached terms */

/* Next number to test (global, persists across calls) */
static idx_t current_number = 1;

/* ---------- sieve initialization ------------------------------------- */
static void init_sieve(void)
{
    if (spf != NULL) return;   /* already initialized */

    spf = (uint32_t*)malloc((MAX_LIMIT + 1) * sizeof(uint32_t));
    prime_index = (uint32_t*)malloc((MAX_LIMIT + 1) * sizeof(uint32_t));
    /* A rough upper bound on the number of primes below MAX_LIMIT */
    size_t prime_est = MAX_LIMIT / 10 + 1000;
    primes = (uint32_t*)malloc(prime_est * sizeof(uint32_t));

    for (size_t i = 0; i <= MAX_LIMIT; ++i) spf[i] = 0;

    size_t pc = 0;
    for (size_t i = 2; i <= MAX_LIMIT; ++i) {
        if (spf[i] == 0) {
            spf[i] = (uint32_t)i;
            prime_index[i] = (uint32_t)(pc + 1);   /* prime indices start at 1 */
            primes[pc++] = (uint32_t)i;
        }
        for (size_t j = 0; j < pc; ++j) {
            uint64_t v = (uint64_t)primes[j] * i;
            if (v > MAX_LIMIT) break;
            spf[(size_t)v] = primes[j];
            if (i % primes[j] == 0) break;
        }
    }
    prime_count = pc;
}

/* ---------- helper: check whether a number satisfies the condition ----- */
static bool is_good(uint32_t n)
{
    if (n <= 1) return true;    /* 1 has an empty multiset of indices */

    uint32_t x = n;
    uint32_t pos = 1;           /* current position in the sorted multiset */

    while (x > 1) {
        uint32_t p = spf[x];
        uint32_t idx = prime_index[p];
        uint32_t exp = 0;
        do {
            x /= p;
            ++exp;
        } while (x % p == 0);
        for (uint32_t i = 0; i < exp; ++i) {
            if (idx == pos) return false;   /* fixed point found */
            ++pos;
        }
    }
    return true;
}

/* ---------- helper: grow cache if needed -------------------------------- */
static void ensure_capacity(size_t needed)
{
    if (seq_cap >= needed) return;
    size_t new_cap = seq_cap > 0 ? seq_cap : 32;
    while (new_cap < needed) new_cap <<= 1;            /* double until big enough */
    seq_t *tmp = (seq_t*)realloc(seq_cache, new_cap * sizeof(seq_t));
    seq_cache = tmp;
    seq_cap = new_cap;
}

/* ---------- main sequence function ------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* outside the offset – undefined */

    init_sieve();

    /* Generate terms until we have at least n of them */
    while (seq_len < (size_t)n) {
        if (is_good((uint32_t)current_number)) {
            ensure_capacity(seq_len + 1);
            seq_cache[seq_len++] = (seq_t)current_number;
        }
        ++current_number;
        if (current_number > MAX_LIMIT) {
            /* For n > ~10 000 this simplistic implementation would need a larger
               sieve.  The intended use guarantees enough coverage, so we return
               0 in the unlikely event of overflow. */
            return (seq_t)0;
        }
    }
    return seq_cache[n - 1];
}
