/*
 * A352836  Lexicographically earliest sequence of positive integers such that
 *          the binary expansions of two consecutive terms have a 1 at the
 *          same position and for any distinct m and n, {a(m), a(m+1)} <>
 *          {a(n), a(n+1)}.
 * https://oeis.org/A352836
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, look, base
 * Formula:   not stated
 * Range:     u8 n <= 9999, u16 n <= 9999, u32 n <= 9999, u64 n <= 9999,
 *            u128 n <= 9999, big any n
 * Helpers:   pair_key
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A352836: lexicographically earliest sequence of positive
 * integers such that consecutive terms share a common set bit and every
 * unordered pair of consecutive terms is distinct.  The sequence is
 * generated by a greedy algorithm that, at each step, chooses the
 * smallest integer that shares a bit with the previous term and
 * whose unordered pair with the previous term has not appeared
 * before. */
#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/pair_key.h"

/* ----------  internal data structures ---------- */

static seq_t *seq          = NULL;  /* the sequence itself   */
static size_t seq_len      = 0;
static size_t seq_cap      = 0;

static seq_t *val_array    = NULL;  /* distinct values seen  */
static seq_t *next_cand    = NULL;  /* next candidate per id */
static size_t val_len      = 0;
static size_t val_cap      = 0;

#define EDGE_HASH_BITS 16
#define EDGE_HASH_SIZE (1U << EDGE_HASH_BITS)
#define EDGE_MASK     (EDGE_HASH_SIZE - 1)
static uint64_t edge_keys[EDGE_HASH_SIZE];
static const uint64_t EMPTY_KEY = 0xFFFFFFFFFFFFFFFFULL;

static bool initialized = false;

/* ----------  helper functions ---------- */

/* initialise all data structures (called once) */
static void init(void)
{
    if (initialized) return;
    initialized = true;

    seq_cap   = 128;
    seq       = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));

    val_cap   = 128;
    val_array = (seq_t *)realloc(val_array, val_cap * sizeof(seq_t));
    next_cand = (seq_t *)realloc(next_cand, val_cap * sizeof(seq_t));

    for (size_t i = 0; i < EDGE_HASH_SIZE; ++i)
        edge_keys[i] = EMPTY_KEY;
}

/* ensure sequence array can hold 'needed' elements */
static void ensure_seq_cap(size_t needed)
{
    if (needed <= seq_cap) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 128;
    if (new_cap < needed) new_cap = needed;
    seq = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
    seq_cap = new_cap;
}

/* ensure value arrays can hold 'needed' distinct values */
static void ensure_val_cap(size_t needed)
{
    if (needed <= val_cap) return;
    size_t new_cap = val_cap ? val_cap * 2 : 128;
    if (new_cap < needed) new_cap = needed;
    val_array = (seq_t *)realloc(val_array, new_cap * sizeof(seq_t));
    next_cand = (seq_t *)realloc(next_cand, new_cap * sizeof(seq_t));
    val_cap = new_cap;
}

/* intern a value: return an id, adding the value if not already seen */
static uint32_t intern(seq_t val)
{
    for (uint32_t i = 0; i < (uint32_t)val_len; ++i) {
        if (val_array[i] == val)
            return i;
    }
    ensure_val_cap(val_len + 1);
    val_array[val_len] = val;
    next_cand[val_len] = (seq_t)1;   /* start searching from 1 */
    return val_len++;
}

/* probe index for a given key */
static inline size_t probe_index(uint64_t key)
{
    return (size_t)((key * 2654435761ULL) >> (64 - EDGE_HASH_BITS));
}

/* check whether an unordered pair has already been used */
static bool pair_used(uint32_t a, uint32_t b)
{
    uint64_t key = pair_key(a, b);
    size_t i = probe_index(key);
    while (edge_keys[i] != EMPTY_KEY) {
        if (edge_keys[i] == key) return true;
        i = (i + 1) & EDGE_MASK;
    }
    return false;
}

/* record a new unordered pair */
static void add_pair(uint32_t a, uint32_t b)
{
    uint64_t key = pair_key(a, b);
    size_t i = probe_index(key);
    while (edge_keys[i] != EMPTY_KEY) {
        if (edge_keys[i] == key) return;   /* already recorded */
        i = (i + 1) & EDGE_MASK;
    }
    edge_keys[i] = key;
}

/* build the sequence up to index n (1‑based) */
static void build_up_to(idx_t n)
{
    if (n == 0) return;
    init();
    if (seq_len == 0) {              /* first term */
        seq[0] = (seq_t)1;
        seq_len = 1;
        intern(seq[0]);              /* register value 1 */
    }
    while ((size_t)seq_len < (size_t)n) {
        seq_t prev_val = seq[seq_len - 1];
        uint32_t prev_id = intern(prev_val);

        seq_t cand = next_cand[prev_id];
        uint32_t cand_id;
        while (1) {
            if ((prev_val & cand) == 0) {   /* no common bit */
                cand++;
                continue;
            }
            cand_id = intern(cand);
            if (pair_used(prev_id, cand_id)) {   /* pair already used */
                cand++;
                continue;
            }
            break;   /* found suitable candidate */
        }

        /* append new term */
        ensure_seq_cap(seq_len + 1);
        seq[seq_len] = cand;
        seq_len++;

        /* record the unordered pair and update the next candidate for prev */
        add_pair(prev_id, cand_id);
        next_cand[prev_id] = cand + 1;
    }
}

/* ----------  public function ---------- */

/*  a(n) returns the n'th term (1‑based) of A352836. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;
    build_up_to(n);
    return seq[n - 1];
}
