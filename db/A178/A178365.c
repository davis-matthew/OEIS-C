/* Sequence A178365 – Numbers whose rounded‑up arithmetic mean of decimal
   digits equals 5.  The values are generated by a depth‑first search
   over the digit positions, pruning using the min/max possible sums
   for the remaining positions. */

#include <stdint.h>
#include <stdbool.h>

/* Recursive generator that visits all k‑digit numbers in ascending order
   and reports the nth hit in the current digit length. */
static bool dfs(idx_t k, idx_t pos, seq_t num, int sum,
                int L, int U, idx_t *found, idx_t target, seq_t *result)
{
    if (pos == k) {                /* a complete number */
        if (sum >= L && sum <= U) {
            (*found)++;
            if (*found == target) {
                *result = num;
                return true;        /* nth element has been found */
            }
        }
        return false;
    }

    int rem = (int)k - (int)pos - 1;   /* remaining positions */
    int d_min = (pos == 0) ? 1 : 0;    /* most significant digit non‑zero */
    int d_max = 9;

    /* Intersect digit range with the sum constraints */
    int min_needed = L - 9 * rem - sum;
    if (min_needed > d_min) d_min = min_needed;
    int max_allowed = U - sum;
    if (max_allowed < d_max) d_max = max_allowed;
    if (d_min > d_max) return false;   /* no admissible digit */

    for (int d = d_min; d <= d_max; ++d) {
        seq_t next_num = num * 10 + (seq_t)d;
        int next_sum = sum + d;
        if (dfs(k, pos + 1, next_num, next_sum,
                L, U, found, target, result))
            return true;        /* propagate success upwards */
    }
    return false;                 /* not found in this branch */
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for n = 0 */
    idx_t found = 0;               /* how many valid numbers seen so far */

    for (idx_t k = 1; ; ++k) {     /* iterate over digit lengths */
        int L = 4 * (int)k + 1;    /* minimum feasible sum: 4k+1 */
        int U = 5 * (int)k;        /* maximum feasible sum: 5k    */
        seq_t value = 0;
        if (dfs(k, 0, 0, 0, L, U, &found, n, &value))
            return value;          /* nth member found */
    }
}
