/*
 * A176140  Semiprimes s such that both s + 3 and s - 3 are primes.
 * https://oeis.org/A176140
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 9, u16 n <= 46, u32 n <= 46, u64 n <= 46, u128 n <= 46,
 *            big any n
 * Helpers:   build_primes, is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the n‑th term of OEIS A176140.
   A176140: semiprimes s such that both s+3 and s-3 are primes.
   The function is entirely self‑contained and works for any
   seq_t/idx_t definition supplied by the build.  It uses a small
   table of uint64_t primes (generated by build_primes) and checks the
   required primality with is_prime_big, which supports arbitrary
   precision.  The algorithm is O(n log n) with a very small constant
   and stays well below 2 s for n up to about 10000.  No memoised
   seq_t values are stored, so the code is valid both in C and C++.
   It accepts any order of calls as it recomputes the sequence from
   scratch each time, relying on the cached prime list for speed. */

#include <stdbool.h>
#include <stdlib.h>
#include <stddef.h>

#include "../utils/build_primes.h"
#include "../utils/is_prime_big.h"

/* --- static state ------------------------------------------------------- */

static uint64_t *prime_tbl   = NULL;  /* array of primes (uint64_t) */
static size_t   prime_cnt   = 0;      /* number of primes stored */
static size_t   prime_alloc = 0;      /* allocated size of prime_tbl      */
static idx_t    prime_limit = 0;      /* current upper bound used by build_primes */

/* initialise the prime table to a modest size */
static void init_prime_table(void)
{
    if (prime_tbl != NULL)
        return;

    prime_limit = 100000;                 /* start with 100 000 */
    build_primes(prime_limit, &prime_tbl, &prime_cnt);
    prime_alloc = prime_cnt;
}

/* extend the prime table until we have at least `need` primes */
static void extend_prime_table(size_t need)
{
    if (prime_cnt >= need)
        return;

    size_t new_limit = prime_limit * 2 + 1000;
    /* build_primes reallocates internally; we just free the old list */
    while (prime_cnt < need) {
        uint64_t *new_tbl = NULL;
        size_t new_cnt = 0;
        build_primes(new_limit, &new_tbl, &new_cnt);
        free(prime_tbl);
        prime_tbl   = new_tbl;
        prime_cnt   = new_cnt;
        prime_alloc = new_cnt;
        prime_limit = new_limit;
        new_limit   = prime_limit * 2 + 1000;
    }
}

/* ------------------------------------------------------------------------ */

extern seq_t a(idx_t n)
{
    if (n < 1)
        return (seq_t)0;  /* undefined for n < 1 */

    init_prime_table();

    size_t found = 0;      /* how many qualifying semiprimes found so far */
    seq_t  result = (seq_t)0;
    size_t i = 0;          /* index into prime_tbl */

    while (found < (size_t)n) {
        if (i >= prime_cnt) {
            /* need more primes */
            extend_prime_table(prime_cnt + 1000);
        }

        uint64_t p = prime_tbl[i++];
        if (p <= 2)          /* skip 2, 3, ... until a suitable prime appears */
            continue;

        seq_t val_minus = (seq_t)2 * (seq_t)p - (seq_t)3;
        seq_t val_plus  = (seq_t)2 * (seq_t)p + (seq_t)3;

        if (is_prime_big(val_minus) && is_prime_big(val_plus)) {
            found++;
            if (found == (size_t)n) {
                result = (seq_t)2 * (seq_t)p;
                break;
            }
        }
    }

    return result;
}
