/*
 * A176870  Prime numbers p such that p-LargestCube is prime, (LargestCube <=
 *          p).
 * https://oeis.org/A176870
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 16, u16 n <= 957, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Validated: standard, pass, 66 terms through n = 876 (2026-11-03)
 * Helpers:   is_prime, mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A176870: the n‑th prime p such that p – ⌊∛p⌋³ is also prime.
   The sequence is generated by iterating over primes and testing the
   required property.  A small, memoised cache is kept so that calls
   to a(idx_t n) in any order are fast (≈O(n) work for n terms). */

#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>
#include <limits.h>
#include <string.h>
#include <stddef.h>
#include <math.h>
#include "../utils/is_prime.h"
#include "../utils/mem.h"

/* integer cube root: largest k with k³ ≤ x */
static idx_t int_cube_root(idx_t x)
{
    idx_t lo = 0, hi = x;
    while (lo < hi) {
        idx_t mid = lo + (hi - lo + 1) / 2;
        __int128 cube = (__int128)mid * mid * mid;
        if (cube <= x)
            lo = mid;
        else
            hi = mid - 1;
    }
    return lo;
}

/* allocate an array of seq_t of given length (may be 0) */
static seq_t *seq_alloc_array(size_t n)
{
    return mem_new(seq_t, n);
}

static void seq_free_array(seq_t* p)          { mem_free(p); }

/* cache of found terms */
static seq_t *cache          = NULL;
static size_t cache_len      = 0;
static size_t cache_cap      = 0;
/* the smallest integer that has not yet been examined */
static idx_t next_candidate  = 2;

/* enlarge the cache so that it can hold at least 'need' terms */
static void grow_cache(size_t need)
{
    if (need <= cache_cap) return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 64;
    while (new_cap < need) new_cap *= 2;
    seq_t *new_cache = seq_alloc_array(new_cap);
    for (size_t i = 0; i < cache_len; ++i) new_cache[i] = cache[i];
    if (cache) seq_free_array(cache);
    cache        = new_cache;
    cache_cap    = new_cap;
}

/* Return the n-th term of the sequence, with a(1) = 3. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                     /* offset 1 */

    grow_cache((size_t)n);                    /* ensure sufficient space */

    while (cache_len < n) {
        /* Find the next prime ≥ next_candidate. */
        idx_t p = next_candidate;
        while (!is_prime(p)) ++p;

        /* Test the defining condition. */
        idx_t r     = int_cube_root(p);       /* floor(cuberoot(p)) */
        idx_t cube  = r * r * r;              /* r³ fits in idx_t */
        idx_t diff  = p - cube;              /* p – r³   ,  diff ≥ 2 */

        if (is_prime(diff))                  /* both p and diff prime */
            cache[cache_len++] = (seq_t)p;

        /* Advance the search start to the next integer. */
        next_candidate = p + 1;
    }
    return cache[n - 1];
}
