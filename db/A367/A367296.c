/* Sequence A367296: k such that 8 is the first decimal digit of 2^k
   The sequence is generated by testing the fractional part of
   k·log10(2).  A term is kept when fractional part ∈ [log10(8), log10(9)). */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Precise constants using long double
   log10(2) ≈ 0.3010299956639811952137388947244930
   log10(8) = 3·log10(2)
   log10(9) ≈ 0.9542425094393248854278945690020040  */
static const long double LOG10_2 = 0.3010299956639811952137388947244930L;
static const long double LOG10_8 = 3.0L * LOG10_2;          /* ≈ 0.9030899869919436 */
static const long double LOG10_9 = 0.9542425094393248854278945690020040L;

static seq_t *seq_cache   = NULL;  /* array of k values found so far   */
static size_t seq_cap     = 0;      /* current capacity                */
static size_t seq_len     = 0;      /* number of cached elements       */
static idx_t  next_k      = 1;      /* exponent to test next           */

static void ensure_capacity(size_t needed)
{
    if (needed <= seq_cap) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    if (new_cap < needed) new_cap = needed;
    seq_cache = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    seq_cap = new_cap;
}

static void fill_until(idx_t n)
{
    while (seq_len < n) {
        /* test current exponent next_k (already incremented when looped) */
        long double prod  = (long double)next_k * LOG10_2;
        long double frac  = prod - (idx_t)prod;          /* fractional part */
        if (frac >= LOG10_8 && frac < LOG10_9) {
            ensure_capacity(seq_len + 1);
            seq_cache[seq_len++] = (seq_t)next_k;
        }
        ++next_k;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;          /* undefined for n==0 */
    fill_until(n);
    return seq_cache[n - 1];
}
