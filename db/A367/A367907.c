/*
 * A367907  Numbers n such that it is not possible to choose a different
 *          binary index of each binary index of n.
 * https://oeis.org/A367907
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 134, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A367907 – Numbers n such that no system of distinct representatives
 * exists for the binary‑index set‑system of n.
 *
 * The sequence is generated by iteratively testing each integer n
 * (starting from 1) to see whether the bipartite graph formed by
 * the binary indices of n has a perfect matching.  If not, n is
 * added to the cache.  The function a(idx_t n) returns the n‑th
 * term of the sequence.  The implementation uses only integer
 * operations and a simple depth‑first search for augmenting paths.
 */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>

/* Helper: depth‑first search to find an augmenting path in the bipartite
 * graph.  left vertices are 0..m-1, right vertices are 1..maxRight.
 */
static bool dfs_match(int u, bool visited[], int matchR[],
                      const int adj_len[], const int adj[][8])
{
    for (int k = 0; k < adj_len[u]; ++k) {
        int v = adj[u][k];
        if (!visited[v]) {
            visited[v] = true;
            if (matchR[v] == 0 || dfs_match(matchR[v] - 1, visited, matchR,
                                            adj_len, adj)) {
                matchR[v] = u + 1;   /* store index+1 to avoid zero */
                return true;
            }
        }
    }
    return false;
}

/* Test whether the set‑system associated with integer n has no
 * system of distinct representatives.  Returns true iff n belongs
 * to A367907.
 */
static bool has_no_sdr(uint64_t n)
{
    /* Collect indices of 1‑bits in n. */
    uint64_t indices[64];
    int m = 0;
    for (uint64_t t = n, pos = 1; t; ++pos, t >>= 1) {
        if (t & 1ULL) {
            indices[m++] = pos;
        }
    }
    if (m == 0) return false;  /* n = 0 never occurs, but guard */

    /* Build adjacency lists: for each index i we list the positions
     * of 1‑bits in i itself.  Left side has m vertices.
     */
    int adj[64][8];
    int adj_len[64];
    int maxRight = 0;
    for (int u = 0; u < m; ++u) {
        uint64_t val = indices[u];
        int len = 0;
        for (uint64_t t = val, pos = 1; t; ++pos, t >>= 1) {
            if (t & 1ULL) {
                if (len < 8) adj[u][len] = (int)pos;
                ++len;
                if (pos > (uint64_t)maxRight) maxRight = (int)pos;
            }
        }
        adj_len[u] = len;
    }

    /* Matching arrays.  right vertices are 1..maxRight.
     * matchR[v] == 0 means v is free; otherwise it stores left index+1.
     */
    int matchR[128] = {0};
    bool visited[128];

    /* Try to match each left vertex. */
    for (int u = 0; u < m; ++u) {
        for (int i = 0; i <= maxRight; ++i) visited[i] = false;
        if (!dfs_match(u, visited, matchR, adj_len, adj))
            return true;   /* no perfect matching found */
    }
    return false;          /* perfect matching exists */
}

/* Static cache of computed terms. */
static seq_t *cache = NULL;
static idx_t cache_len = 0;
static idx_t cache_cap = 0;
static uint64_t next_candidate = 1;

/*
 * Returns the nth term (1‑based) of A367907.
 * The function computes terms lazily and memoizes them
 * in a dynamic array so that calls in arbitrary order
 * stay efficient.
 */
extern seq_t a(idx_t n)
{
    while (cache_len < n) {
        if (has_no_sdr(next_candidate)) {
            if (cache_len == cache_cap) {
                size_t new_cap = cache_cap == 0 ? 64 : cache_cap * 2;
                seq_t *tmp = (seq_t *)realloc(cache,
                                                new_cap * sizeof(seq_t));
                if (!tmp) {
                    /* allocation failure – abort */
                    return 0;
                }
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = (seq_t)next_candidate;
        }
        ++next_candidate;
    }
    return cache[n - 1];
}
