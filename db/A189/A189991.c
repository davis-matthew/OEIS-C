/*
 * A189991  Numbers with prime factorization p^4*q^4.
 * https://oeis.org/A189991
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = (p*q)^4 with p<q primes, sorted by the value (p*q)^4
 * Range:     u8 none, u16 none, u32 n <= 76, u64 n <= 1000, u128 n <= 1000,
 *            big any n
 * Helpers:   build_primes_upto
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence consists of the fourth powers of the products of two
   distinct primes.  It can be generated by maintaining a min‑heap of
   all pairs (p_i, p_j) with i<j.  When the smallest product is
   extracted we push the next product involving the same p_i.  The
   heap always contains at most (number of primes – 1) elements.  The
   values are cached so that repeated calls to a() are O(1).  */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/build_primes_upto.h"

typedef struct {
    seq_t val;   /* current product p_i * p_j */
    idx_t i;     /* index of p_i in the primes array */
    idx_t j;     /* index of p_j in the primes array */
} HeapNode;

static void heap_swap(HeapNode *a, HeapNode *b)
{
    HeapNode t = *a;
    *a = *b;
    *b = t;
}

static void sift_up(HeapNode *heap, size_t pos)
{
    while (pos > 0) {
        size_t parent = (pos - 1) >> 1;
        if (heap[pos].val < heap[parent].val) {
            heap_swap(&heap[pos], &heap[parent]);
            pos = parent;
        } else {
            break;
        }
    }
}

static void sift_down(HeapNode *heap, size_t pos, size_t size)
{
    while (true) {
        size_t left = (pos << 1) + 1;
        if (left >= size)
            break;
        size_t right = left + 1;
        size_t smallest = left;
        if (right < size && heap[right].val < heap[left].val)
            smallest = right;
        if (heap[smallest].val < heap[pos].val) {
            heap_swap(&heap[pos], &heap[smallest]);
            pos = smallest;
        } else {
            break;
        }
    }
}

static void heap_push(HeapNode *heap, size_t *size, idx_t i, idx_t j,
                      const uint64_t *primes, size_t primes_cnt)
{
    HeapNode *node = &heap[*size];
    node->i = i;
    node->j = j;
    node->val = (seq_t)primes[i] * (seq_t)primes[j];
    (*size)++;
    sift_up(heap, *size - 1);
}

static HeapNode heap_pop(HeapNode *heap, size_t *size, const uint64_t *primes,
                         size_t primes_cnt)
{
    HeapNode min = heap[0];
    heap[0] = heap[*size - 1];
    (*size)--;
    sift_down(heap, 0, *size);
    if (min.j + 1 < primes_cnt) {
        heap_push(heap, size, min.i, min.j + 1, primes, primes_cnt);
    }
    return min;
}

seq_t a(idx_t n)
{
    /* ---------- static shared state ---------- */
    static bool initialized = false;
    static uint64_t *primes = NULL;
    static size_t primes_cnt = 0;
    static HeapNode *heap = NULL;
    static size_t heap_size = 0;
    static size_t heap_cap = 0;
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;

    if (!initialized) {
        /* Determine a limit that guarantees enough pairs for n up to ~10000.
           200000 primes give ~18k primes, which is far more than needed. */
        build_primes_upto(200000, &primes, &primes_cnt);

        heap_cap = (primes_cnt > 0) ? primes_cnt - 1 : 0;
        heap = (HeapNode *)malloc(heap_cap * sizeof(HeapNode));
        for (size_t i = 0; i < primes_cnt - 1; ++i) {
            heap_push(heap, &heap_size, (idx_t)i, (idx_t)(i + 1), primes,
                      primes_cnt);
        }

        cache_cap = 16;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        cache_len = 0;

        initialized = true;
    }

    /* ---------- generate terms until we have n ---------- */
    while (cache_len < n) {
        HeapNode node = heap_pop(heap, &heap_size, primes, primes_cnt);
        seq_t n_val = (seq_t)primes[node.i] * (seq_t)primes[node.j];
        /* nth term = n_val^4 */
        seq_t val = n_val;
        val = val * val;       /* n_val^2 */
        val = val * val;       /* n_val^4 */

        if (cache_len == cache_cap) {
            cache_cap *= 2;
            cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        }
        cache[cache_len++] = val;
    }

    return cache[n - 1];
}
