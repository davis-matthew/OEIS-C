/*
 * A026481  a(n) = least positive integer > a(n-1) and not a(i)*a(j)*a(k) for
 *          1<=i<j<k<n.
 * https://oeis.org/A026481
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 65, u16 n <= 65, u32 n <= 65, u64 n <= 65, u128 n <= 65,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A026481: sequence of integers that are not the product of
   three earlier distinct terms.  The first term is 1 and 2 is omitted
   by definition.  Subsequent terms are generated by taking the
   smallest integer greater than the previous term that cannot be
   written as a(i)*a(j)*a(k) with 1 ≤ i < j < k < n.  This function
   memoises the sequence statically so that calls in any order are
   efficient.  The implementation works for any seq_t/idx_t
   combination supported by the build. */

#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* Static storage for the sequence */
static seq_t *seq_arr = NULL;
static size_t seq_len = 0;
static size_t seq_cap = 0;

/* Resize the static array to have at least 'need' capacity. */
static void ensure_capacity(size_t need)
{
    if (seq_cap >= need)
        return;
    size_t new_cap = seq_cap ? seq_cap << 1 : 16;
    if (new_cap < need)
        new_cap = need;
    seq_arr = (seq_t *)realloc(seq_arr, new_cap * sizeof(seq_t));
    seq_cap = new_cap;
}

/* Binary search for 'val' in the sorted array 'arr' of length 'len'. */
static bool contains(const seq_t *arr, size_t len, seq_t val)
{
    size_t lo = 0, hi = len;
    while (lo < hi) {
        size_t mid = (lo + hi) >> 1;
        if (arr[mid] == val)
            return true;
        if (arr[mid] < val)
            lo = mid + 1;
        else
            hi = mid;
    }
    return false;
}

/* Check whether 'candidate' equals a product of any three distinct earlier terms. */
static bool is_product(seq_t candidate)
{
    /* Need at least three earlier terms. */
    if (seq_len < 3)
        return false;

    for (size_t i = 0; i + 2 < seq_len; ++i) {
        seq_t ai = seq_arr[i];

        /* If ai^3 > candidate, further ai will only be larger - break. */
        if (ai != 0 && ai > candidate / (ai * ai))
            break;

        for (size_t j = i + 1; j + 1 < seq_len; ++j) {
            seq_t aj = seq_arr[j];
            /* If ai*aj > candidate, further j will only be larger - break. */
            if (aj > candidate / ai)
                break;

            seq_t prod = ai * aj;
            if (candidate % prod != 0)
                continue;

            seq_t rem = candidate / prod;
            if (rem == ai || rem == aj) /* indices must be distinct */
                continue;

            /* rem must be an earlier term; binary search. */
            if (contains(seq_arr, seq_len, rem))
                return true;
        }
    }
    return false;
}

/* Public function required by the problem. */
seq_t a(idx_t n)
{
    if (n == 0)      /* undefined offset 1, return 0 for safety */
        return 0;

    /* Ensure the sequence is built up to the required index. */
    while (seq_len < (size_t)n) {
        seq_t candidate;
        if (seq_len == 0) {
            /* First term is explicitly 1. */
            candidate = 1;
        } else if (seq_len == 1 && seq_arr[0] == 1) {
            /* By definition, 2 is omitted; start with 3. */
            candidate = 3;
        } else {
            candidate = seq_arr[seq_len - 1] + 1;
        }

        /* Find the first candidate that is not a product of three distinct
           earlier terms. */
        while (is_product(candidate))
            ++candidate;

        /* Store the new term. */
        ensure_capacity(seq_len + 1);
        seq_arr[seq_len++] = candidate;
    }

    return seq_arr[n - 1];
}
