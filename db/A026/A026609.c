/*
 * A026609  a(n) = number of 3's between n-th 1 and (n+1)st 1 in A026600.
 * https://oeis.org/A026609
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 90, u16 n <= 90, u32 n <= 90, u64 n <= 90, u128 n <= 90,
 *            big any n
 * Helpers:   build_word
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes sequence A026609: number of 3's between the n‑th and (n+1)‑st 1
   in the infinite word generated by the morphism
        mu: 1 -> 123 , 2 -> 231 , 3 -> 312 .
   The word is built by iteratively applying mu to the starting symbol 1.
   For each new 1 encountered, the count of 3's seen since the previous 1
   is stored as a(n). */
#include <stdlib.h>
#include <stddef.h>
#include "../utils/build_word.h"

/* Cache of already computed values a(1)..a(cache_len) */
static seq_t *cache = NULL;
static idx_t  cache_len = 0;

/* Public function: a(n) */
seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* offset starts at 1; never called for n==0 */

    /* If we already have enough values cached, just return the stored one. */
    if (n <= cache_len)
        return cache[(size_t)(n - 1)];

    /* Allocate a new cache big enough to hold a(1)..a(n) */
    seq_t *new_cache = (seq_t*)malloc(sizeof(seq_t) * (size_t)n);

    /* Build a word containing at least (n+1) occurrences of the symbol 1. */
    size_t word_len;
    unsigned char *word = build_word(n, &word_len);

    /* Scan the word, counting 3's between consecutive 1's. */
    idx_t ones_seen = 1;          /* the first 1 is at position 0 */
    seq_t ct3       = 0;          /* number of 3's since the last 1 */
    size_t idx = 1;               /* start scanning after the first 1 */
    idx_t n_plus_1 = n + 1;

    while (ones_seen <= n_plus_1 && idx < word_len) {
        unsigned char sym = word[idx++];
        if (sym == 3)
            ct3 += (seq_t)1;
        else if (sym == 1) {      /* reached next 1 */
            ones_seen++;
            if (ones_seen <= n + 1) {
                new_cache[(size_t)(ones_seen - 2)] = ct3;
            }
            ct3 = 0;
        }
    }

    free(word);

    /* Replace the old cache with the newly computed one. */
    free(cache);
    cache     = new_cache;
    cache_len = n;

    return cache[(size_t)(n - 1)];
}
