/*
 * A372850  Numbers whose distinct prime indices are the binary indices of
 *          some prime number.
 * https://oeis.org/A372850
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 15, u16 n <= 34, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Helpers:   build_primes_upto, is_prime_big, pow2
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function implements the OEIS definition:
   Numbers k such that the sum of 2^(i-1) over the distinct prime indices
   of k is a prime.  The n-th term a(n) is the n‑th such k
   (a(1)=3).  The sequence is generated by scanning k=1,2,3,… and
   collecting terms that satisfy the condition; the results are memoised
   in a static array so that any order of calls is supported. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

#include "../utils/pow2.h"           /* seq_t pow2(idx_t exp); */
#include "../utils/is_prime_big.h"   /* bool is_prime_big(seq_t n); */
#include "../utils/build_primes_upto.h" /* void build_primes_upto(idx_t limit, uint64_t **out, size_t *cnt); */

/* Sieve limit: sufficient to cover prime factors of all k that occur in
   the first 10 000 terms of the sequence.  2 000 000 gives > 170 000
   primes, which is more than enough. */
static const idx_t SIEVE_LIMIT = 2000000u;

/* Global data */
static uint64_t *g_primes = NULL;        /* list of primes up to SIEVE_LIMIT */
static size_t    g_prime_cnt = 0;
static int32_t  *g_prime_index = NULL;    /* index (1‑based) of each prime <= SIEVE_LIMIT */

/* Memoised sequence values */
static seq_t *g_seq = NULL;      /* array of sequence terms */
static size_t g_seq_cap = 0;
static size_t g_seq_len = 0;

/* Last integer examined */
static uint64_t g_last_k = 0;

/* --------------------------------------------------------------------- */
/* Initialise the prime sieve and index table.  This runs once per program. */
static void init_primes(void)
{
    if (g_primes) return;   /* already initialised */

    /* Build the prime list up to SIEVE_LIMIT. */
    build_primes_upto(SIEVE_LIMIT, &g_primes, &g_prime_cnt);

    /* Build the prime index table for constant‑time lookup. */
    g_prime_index = (int32_t*)calloc((size_t)(SIEVE_LIMIT + 1), sizeof(int32_t));
    for (size_t i = 0; i < g_prime_cnt; ++i) {
        uint64_t p = g_primes[i];
        if (p <= SIEVE_LIMIT) {
            g_prime_index[(size_t)p] = (int32_t)(i + 1);   /* 1‑based index */
        }
    }
}

/* --------------------------------------------------------------------- */
/* Compute the n-th term of the sequence.  Only idx_t ≥ 1 is used. */
seq_t a(idx_t n)
{
    /* Ensure static structures are ready. */
    init_primes();
    if (!g_seq) {
        g_seq_cap = 16;
        g_seq = (seq_t*)malloc(g_seq_cap * sizeof(seq_t));
    }

    /* Generate terms until we have at least n of them. */
    while (g_seq_len < (size_t)n) {
        ++g_last_k;
        uint64_t k = g_last_k;

        /* Collect distinct prime indices of k.  We store them in a small
           fixed‑size array because k has few distinct prime factors. */
        int32_t indices[64];
        size_t idx_cnt = 0;

        uint64_t tmp = k;
        for (size_t j = 0; j < g_prime_cnt && g_primes[j] * g_primes[j] <= tmp; ++j) {
            uint64_t p = g_primes[j];
            if (tmp % p == 0) {
                /* Record the index once. */
                indices[idx_cnt++] = g_prime_index[(size_t)p];
                while (tmp % p == 0) tmp /= p;
            }
        }
        if (tmp > 1) { /* remaining prime factor > sqrt(k) */
            /* tmp is itself prime and <= SIEVE_LIMIT in all cases that
               occur for the first 10 000 sequence terms. */
            indices[idx_cnt++] = g_prime_index[(size_t)tmp];
        }

        /* Compute the sum of 2^(index-1) for these distinct indices. */
        seq_t sum = 0;
        for (size_t j = 0; j < idx_cnt; ++j) {
            sum += pow2((idx_t)(indices[j] - 1));
        }

        /* If the sum is prime, k is part of the sequence. */
        if (is_prime_big(sum)) {
            if (g_seq_len == g_seq_cap) {
                g_seq_cap *= 2;
                g_seq = (seq_t*)realloc(g_seq, g_seq_cap * sizeof(seq_t));
            }
            g_seq[g_seq_len++] = (seq_t)k;
        }
    }

    return g_seq[(size_t)n - 1];
}
