/*
 * A073328  Numbers n such that S(n) is a palindromic prime, where S(n) is the
 *          Kempner function A002034.
 * https://oeis.org/A073328
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 51, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   _smallest_prime_factor, is_palindrome, is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Numbers n such that S(n) is a palindromic prime, where S(n) is the
 * Kempner function (A002034).  This function enumerates the
 * sequence A073328.  The sequence is generated by testing integers
 * in order and keeping the ones whose Kempner value is a prime that
 * is also a palindrome.  Results are memoised in a static cache so
 * that subsequent calls to a() with any index are fast.  The
 * implementation uses the build‑time supplied helper routines
 * _smallest_prime_factor, is_prime_big and is_palindrome. */
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

/* Helpers provided by the build environment */
#include "../utils/_smallest_prime_factor.h"
#include "../utils/is_prime_big.h"
#include "../utils/is_palindrome.h"

/* ------------------------------------------------------------------
 *  Compute the Kempner function S(n).  It is defined as the smallest
 *  integer m such that n divides m!.  For each prime power p^e
 *  occurring in the factorisation of n we compute the minimal m
 *  such that the exponent of p in m! is at least e.
 * ------------------------------------------------------------------ */
static seq_t min_m_for_prime_power(uint32_t p, uint32_t e)
{
    seq_t m = 0;
    while (1) {
        ++m;
        seq_t v = 0;
        seq_t pp = p;
        while (pp <= m) {
            v += m / pp;
            /* Avoid overflow of pp *= p */
            if (pp > m / p) break;
            pp *= p;
        }
        if (v >= e) return m;
    }
}

/* ------------------------------------------------------------------ */
static seq_t kempner(seq_t n)
{
    if (n <= 1) return (seq_t)1;          /* S(1) = 1 */

    seq_t result = 0;
    uint64_t tmp = (uint64_t)n;           /* assume n fits in 64 bits */

    while (tmp > 1) {
        uint32_t p = (uint32_t)_smallest_prime_factor(tmp);
        uint32_t exp = 0;
        while (tmp % p == 0) {
            tmp /= p;
            ++exp;
        }
        seq_t m_min = min_m_for_prime_power(p, exp);
        if (m_min > result) result = m_min;
    }
    return result;
}

/* ------------------------------------------------------------------ */
/*  Test whether a candidate integer n satisfies the required
 *  property: its Kempner function is a palindromic prime. */
static bool has_property(seq_t n)
{
    seq_t s = kempner(n);
    if (!is_prime_big(s)) return false;
    return is_palindrome(s, (idx_t)10);
}

/* ------------------------------------------------------------------ */
/*  Dynamic cache of the sequence values.  The cache is expanded
 *  incrementally until it contains at least n terms. */
static seq_t *cache = NULL;
static size_t cache_size  = 0;
static size_t cache_cap   = 0;
static idx_t last_checked = 1;   /* last integer examined */

/* ------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;         /* undefined for offset 0 */

    /* Allocate cache on first call */
    if (cache == NULL) {
        cache_cap = 16;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache) abort();
    }

    /* Expand cache until we have at least n terms. */
    while (cache_size < (size_t)n) {
        ++last_checked;
        if (has_property((seq_t)last_checked)) {
            if (cache_size >= cache_cap) {
                cache_cap *= 2;
                cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
                if (!cache) abort();
            }
            cache[cache_size++] = (seq_t)last_checked;
        }
    }

    return cache[(size_t)(n - 1)];
}
