/* OEIS A073033: 4‑cycle of the k → σ(k)−k process.
   The cycle is generated by starting with the first term 18656380
   and repeatedly applying σ(k)−k.  This function computes the
   cycle once and returns the n‑th term modulo the cycle length. */

#include <stdbool.h>
#include "../utils/sigma_seq_t.h"

static seq_t cycle[4];
static bool cycle_initialized = false;

seq_t a(idx_t n)
{
    if (!cycle_initialized) {
        seq_t cur = 18656380;
        for (int i = 0; i < 4; ++i) {
            cycle[i] = cur;
            seq_t sigma = sigma_seq_t(cur);
            cur = sigma - cur;
        }
        cycle_initialized = true;
    }
    return cycle[(int)((n - 1) % 4)];
}
