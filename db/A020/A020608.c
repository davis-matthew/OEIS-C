/*
 * A020608  Smallest nonempty set S containing prime divisors of 7k+3 for each
 *          k in S.
 * https://oeis.org/A020608
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, fini, full
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 6, u32 n <= 6, u64 n <= 6, u128 n <= 6,
 *            big any n
 * Helpers:   factor_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS: A020608
   The set S is generated by starting with the smallest prime (2) and
   repeatedly adding all prime divisors of 7k+3 for every element k in S.
   The sequence a(n) lists the primes in S in ascending order.  */

/* The set is finite: {2,5,17,19,43,61}.  */
#include <stdbool.h>
#include "../utils/factor_u64.h"

static seq_t  S[32];      /* workspace: primes in the closure set */
static size_t S_size;     /* number of elements currently in S      */
static size_t proc_idx;   /* next element to process                */
static bool   initialized;/* have we built the set yet?             */

/* Insert a prime into S while maintaining ascending order.
   Duplicate entries are ignored. */
static void insert_sorted(seq_t val)
{
    size_t i;
    for (i = 0; i < S_size; ++i) {
        if (S[i] == val) return;    /* already present          */
        if (S[i] > val) break;      /* found insertion point   */
    }
    for (size_t j = S_size; j > i; --j) S[j] = S[j-1];
    S[i] = val;
    ++S_size;
}

/* Public entry point. */
seq_t a(idx_t n)
{
    if (!initialized) {
        S_size = 0;
        insert_sorted((seq_t)2);   /* start with the smallest prime */

        proc_idx = 0;
        while (proc_idx < S_size) {
            uint64_t k = (uint64_t)S[proc_idx];
            uint64_t m = 7ull * k + 3ull;   /* compute 7k + 3           */

            /* factor m into its prime distinct factors */
            size_t cnt = 0;
            uint64_t primes[64];
            uint64_t exps[64];
            factor_u64(m, primes, exps, &cnt);

            for (size_t j = 0; j < cnt; ++j)
                insert_sorted((seq_t)primes[j]);

            ++proc_idx;
        }
        initialized = true;
    }

    /* a(n) defined only for 1 ≤ n ≤ |S|; return 0 otherwise */
    if (n == 0 || (idx_t)n > (idx_t)S_size) return (seq_t)0;
    return S[(size_t)n - 1];
}
