/*
 * A020690  Numbers of form 7 x^2 + 8 y^2.
 * https://oeis.org/A020690
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 31, u16 n <= 58, u32 n <= 58, u64 n <= 58, u128 n <= 58,
 *            big any n
 * Validated: partial, pass, 58 terms through n = 58 (2026-11-03)
 * Helpers:   ipow_i32, mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the OEIS sequence A020690: numbers of the form
   7*x^2 + 8*y^2.  The values are generated by a brute–force
   search, memoizing results so that any n ≥ 1 can be returned.
   The sequence is 1-indexed; a(1) = 0, a(2) = 7, a(3) = 8, ... */
#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include "../utils/ipow_i32.h"
#include "../utils/mem.h"

/* Floor square root by binary search */
static inline seq_t floor_sqrt(seq_t x)
{
    seq_t lo = 0, hi = 1;
    while (ipow_i32(hi, 2) <= x)
        hi <<= 1;
    while (lo < hi)
    {
        seq_t mid = (lo + hi) >> 1;
        seq_t mid2 = mid * mid;
        if (mid2 <= x)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

static bool is_representable(seq_t m)
{
    /* Search over x: 7*x^2 ≤ m */
    for (idx_t x = 0; ; ++x) {
        seq_t xsq = (seq_t)x * (seq_t)x;
        seq_t part = (seq_t)7 * xsq;
        if (part > m) break;

        seq_t rem = m - part;
        /* rem must be divisible by 8 */
        if ((rem & (seq_t)7) != 0) continue;

        seq_t k = rem / (seq_t)8;
        seq_t y = floor_sqrt(k);
        if (y * y == k) return true;
    }
    return false;
}

/* Cached sequence values */
static seq_t *cache      = NULL;
static size_t cache_cap  = 0;
static size_t cache_len  = 0;
static seq_t next_candidate = 0;

seq_t a(idx_t n)
{
    if (n == (idx_t)0) return 0;   /* Undefined for n=0; safe fallback */

    /* Ensure we have computed up to the requested index */
    while (cache_len < n) {
        if (is_representable(next_candidate)) {
            /* Grow cache if necessary */
            if (cache_len >= cache_cap) {
                size_t new_cap = (cache_cap == 0) ? 64 : cache_cap * 2;
                seq_t *tmp = mem_new(seq_t, new_cap);
                if (!tmp) {
                    /* Allocation failure – exit safely */
                    exit(1);
                }
                if (cache) {
                    mem_copy(tmp, cache, cache_len * sizeof(seq_t));
                    mem_free(cache);
                }
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = next_candidate;
        }
        ++next_candidate;
    }

    return cache[n - 1];
}
