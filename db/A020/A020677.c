/*
 * A020677  Numbers of form 3*x^2 + 4*y^2.
 * https://oeis.org/A020677
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 30, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Numbers of the form 3*x^2 + 4*y^2
    a(1) = 0, a(2) = 3, a(3) = 4, a(4) = 7, ...
    The sequence is generated by enumerating all x,y ≥ 0 such that
    3*x² + 4*y² ≤ limit, sorting the results, removing duplicates and
    keeping the first n values requested.
    The routine grows the limit until a(n) is available. */

#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

/* Comparator for qsort on seq_t values. */
static int cmp_seq(const void *a, const void *b)
{
    seq_t av = *(const seq_t *)a;
    seq_t bv = *(const seq_t *)b;
    return (av < bv) ? -1 : (av > bv);
}

/* Global cache of computed sequence values. */
static seq_t *cache = NULL;
static size_t cachelen = 0;   /* number of stored terms   */
static idx_t  cache_limit = 0;/* last limit used to build cache */

/* Build or rebuild the cache from scratch for all values ≤ limit. */
static void build_upto(idx_t limit)
{
    /* Free any previous cache. */
    if (cache != NULL) {
        free(cache);
        cache = NULL;
        cachelen = 0;
    }

    /* Temporary storage for raw candidates. */
    size_t cap = 1024;
    seq_t *cand = (seq_t *)malloc(cap * sizeof(seq_t));
    size_t cand_cnt = 0;

    /* Enumerate all x,y pairs with 3x²+4y² ≤ limit. */
    for (idx_t x = 0; ; ++x) {
        seq_t part_x = (seq_t)3 * (seq_t)x * (seq_t)x;
        if (part_x > (seq_t)limit) break;

        for (idx_t y = 0; ; ++y) {
            seq_t part_y = (seq_t)4 * (seq_t)y * (seq_t)y;
            seq_t val = part_x + part_y;
            if (val > (seq_t)limit) break;

            if (cand_cnt == cap) {
                cap <<= 1;
                cand = (seq_t *)realloc(cand, cap * sizeof(seq_t));
            }
            cand[cand_cnt++] = val;
        }
    }

    /* Sort and deduplicate. */
    if (cand_cnt == 0) {
        free(cand);
        return;
    }

    qsort(cand, cand_cnt, sizeof(seq_t), cmp_seq);

    seq_t *uniq = (seq_t *)malloc(cand_cnt * sizeof(seq_t));
    size_t uniq_cnt = 0;
    for (size_t i = 0; i < cand_cnt; ++i) {
        if (uniq_cnt == 0 || cand[i] != uniq[uniq_cnt - 1]) {
            uniq[uniq_cnt++] = cand[i];
        }
    }

    free(cand);
    cache = uniq;
    cachelen = uniq_cnt;
    cache_limit = limit;
}

/* Public entry point required by the framework. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;  /* offset is 1; value for n=0 is irrelevant */

    /* Ensure the cache contains at least n terms. */
    if (cachelen < n) {
        idx_t limit = (cache_limit == 0) ? 1 : cache_limit * 2 + 1;
        while (cachelen < n) {
            build_upto(limit);
            if (cachelen >= n) break;
            limit *= 2; /* double the limit until enough terms are found */
        }
    }

    return cache[n - 1];
}
