/*
 * A020885  Ordered areas (divided by 6) of primitive Pythagorean triangles
 *          (with multiple entries).
 * https://oeis.org/A020885
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 1, u32 n <= 23, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implementation: a(n) = area/6 of primitive Pythagorean triangles
   (duplicates allowed), sorted in nondecreasing order.  The sequence
   is generated by Euclid's formula, coefficients are stored in a
   static array, sorted once, and indexed directly.  The code uses
   only C11 facilities and the supplied gcd() helper. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/gcd.h"

/* Estimate maximum number of entries required for the tests.  The
   chosen limit is comfortably larger than the number of primitive
   triples produced by m <= 2000.  Each m contributes roughly
   φ(m)/2 triples.  The total is about 600 000 for m<=2000.  */
#define MAX_CAPACITY  600000
/* Sufficiently large generation bound for m to reach MAX_CAPACITY. */
#define M_MAX          2000

static seq_t *values = NULL;      /* array of area/6 values   */
static size_t count   = 0;        /* number of stored values  */
static bool initialized = false; /* flag to run init once      */

/* Comparator for qsort (ascending order). */
static int cmp_seq_t(const void *p1, const void *p2)
{
    const seq_t *a = (const seq_t *)p1;
    const seq_t *b = (const seq_t *)p2;
    return (*a < *b) ? -1 : (*a > *b) ? 1 : 0;
}

/* Main function required by the interface. */
seq_t a(idx_t n)
{
    /* Lazy initialization: generate and sort once. */
    if (!initialized) {
        size_t cap = MAX_CAPACITY;
        values = (seq_t *)calloc(cap, sizeof(seq_t));
        if (!values) return 0;  /* allocation failed – should not happen */

        count = 0;

        for (idx_t m = 2; m <= M_MAX && count < cap; ++m) {
            for (idx_t k = 1; k < m && count < cap; ++k) {
                /* (m - k) must be odd and m,k coprime for a primitive triple. */
                if (((m - k) & 1) == 0) continue;
                if (gcd((seq_t)m, (seq_t)k) != 1) continue;

                /* Compute value = m * k * (m*m - k*k) / 6   */
                uint64_t mm = (uint64_t)m;
                uint64_t kk = (uint64_t)k;
                uint64_t a_val = mm*mm - kk*kk;          /* m^2 - k^2  */
                uint64_t area   = mm * kk * a_val;      /* mn(m^2-n^2) */
                uint64_t val64  = area / 6;             /* area/6      */

                values[count++] = (seq_t)val64;
            }
        }

        /* Any remaining capacity is unused; no need to shrink. */
        qsort(values, count, sizeof(seq_t), cmp_seq_t);

        initialized = true;
    }

    /* Safe access: tests assume n >= 1 and that the list is long enough. */
    return values[n - 1];
}
