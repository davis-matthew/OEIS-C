/*
 * A256878  Numbers divisible by prime(d) for each digit d in their base-8
 *          representation, none of which may be zero.
 * https://oeis.org/A256878
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 50, u32 n <= 50, u64 n <= 50, u128 n <= 50,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: A256878
   Formula: numbers x such that for every non‑zero base‑8 digit d of x,
   x is divisible by prime(d).  The sequence is generated by a
   brute‑force search of the natural numbers in ascending order. */

#include <stdlib.h>
#include <stdbool.h>

/* Prime numbers keyed by the base‑8 digit value:
   primes[1] = 2, primes[2] = 3, ..., primes[7] = 17. */
static const seq_t primes[8] = {
    (seq_t)0, (seq_t)2, (seq_t)3, (seq_t)5, (seq_t)7,
    (seq_t)11, (seq_t)13, (seq_t)17
};

/* Cache for already generated terms.  cache[0] == a(1), cache[1] == a(2), … */
static seq_t *cache      = NULL;   /* pointer to allocated array */
static size_t cache_cap  = 0;       /* number of elements allocated */
static size_t cache_cnt  = 0;       /* number of terms stored so far */
static seq_t last_candidate = 0;    /* last integer examined */

/* Ensure the cache has room for at least 'needed' elements. */
static void ensure_cache_capacity(size_t needed)
{
    if (needed <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 8;
    while (new_cap < needed)
        new_cap *= 2;
    seq_t *ptr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!ptr)
        exit(EXIT_FAILURE);
    cache = ptr;
    cache_cap = new_cap;
}

/* Test whether number n satisfies the sequence condition. */
static bool is_valid(seq_t n)
{
    seq_t tmp = n;
    while (tmp != (seq_t)0) {
        unsigned digit = (unsigned)(tmp % (seq_t)8);
        if (digit == 0)
            return false;
        if ((n % primes[digit]) != (seq_t)0)
            return false;
        tmp /= (seq_t)8;
    }
    return true;
}

/* Compute the nth term (n >= 1). */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;          /* offset undefined for n==0 */

    idx_t target = n;
    while ((idx_t)cache_cnt < target) {
        ++last_candidate;
        if (is_valid(last_candidate)) {
            ensure_cache_capacity(cache_cnt + 1);
            cache[cache_cnt++] = last_candidate;
        }
    }
    return cache[(size_t)(n - 1)];
}
