/* Computation: sequence of integers n such that the base‑7
   representation of n contains the substring "01" but that of
   n+1 does not.  Generated by linear search with memoization. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Return true if the base‑7 representation of x contains the substring "01". */
static inline bool has01(seq_t x)
{
    /* For x == 0 the string is "0", so no "01". */
    if (x == 0) return false;

    seq_t last = x % 7;     /* least significant digit */
    x /= 7;
    while (x > 0) {
        seq_t cur = x % 7;
        if (cur == 0 && last == 1) return true;
        last = cur;
        x /= 7;
    }
    return false;
}

/* Return the nth term of the sequence (a(1) is the first term). */
seq_t a(idx_t n)
{
    if (n < 1) return 0;          /* undefined for indices < 1 */

    /* Static cache of already-found terms. */
    static seq_t *cache   = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;

    /* Keeps track of the next integer to test. */
    static seq_t next_candidate = 0;

    /* Grow the cache until it holds the nth term. */
    while (cache_len < (size_t)n) {
        /* Ensure enough space for the next element. */
        if (cache_len == cache_cap) {
            cache_cap = cache_cap ? cache_cap * 2 : 64;
            seq_t *tmp = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
            if (!tmp) exit(EXIT_FAILURE);
            cache = tmp;
        }

        /* Test the current candidate. */
        if (has01(next_candidate) && !has01(next_candidate + 1)) {
            cache[cache_len++] = next_candidate;
        }
        ++next_candidate;
    }

    return cache[(size_t)n - 1];
}
