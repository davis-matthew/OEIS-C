/* A044175: numbers n such that the base‑7 representation of n contains the
   substring "52" while the base‑7 representation of n-1 does not.
   The sequence is generated by scanning the natural numbers for this
   property.  The first term (offset = 1) is 37. */
#include <stdlib.h>
#include <stdbool.h>

/* Cached values of the sequence */
static seq_t *cache   = NULL;
static size_t cache_len = 0;  /* number of elements currently stored */
static size_t cache_cap = 0;  /* allocated capacity */
static idx_t last_checked = 0;  /* largest number examined so far */

/* Test whether a base‑7 representation of x contains the digit pair
   52 (with 5 as the higher digit).  Digits are examined from
   least‑significant to most‑significant. */
static bool has52(seq_t x)
{
    if (x == 0)
        return false;
    int prev = -1;  /* previous (lower) digit */
    while (x > 0) {
        int d = (int)(x % 7);
        if (d == 5 && prev == 2)
            return true;
        prev = d;
        x /= 7;
    }
    return false;
}

/* Return the n‑th term of the sequence (n ≥ 1).  All calls are
   independent; the function keeps a static cache so that any order
   of calls works. */
seq_t a(idx_t n)
{
    if (n == 0)               /* undefined, but defined for safety */
        return 0;

    /* Grow the cache until it contains at least n elements */
    while (cache_len < n) {
        idx_t cur = last_checked + 1;
        for (;;) {
            seq_t cur_val  = (seq_t)cur;
            seq_t prev_val = (seq_t)(cur - 1);
            if (has52(cur_val) && !has52(prev_val)) {
                /* Ensure enough space */
                if (cache_len + 1 > cache_cap) {
                    size_t new_cap = cache_cap ? cache_cap * 2 : 32;
                    seq_t *tmp = (seq_t *)realloc(cache,
                                                  new_cap * sizeof(seq_t));
                    if (!tmp) abort();          /* allocation failure */
                    cache = tmp;
                    cache_cap = new_cap;
                }
                cache[cache_len++] = cur_val;
                last_checked = cur;
                break;   /* found the next term, continue with cache size */
            }
            ++cur;
        }
    }
    return cache[n - 1];
}
