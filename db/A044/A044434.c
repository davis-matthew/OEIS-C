/*
 * A044434  Numbers n such that string 0,1 occurs in the base 3 representation
 *          of n but not of n+1.
 * https://oeis.org/A044434
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 36, u16 n <= 49, u32 n <= 49, u64 n <= 49, u128 n <= 49,
 *            big any n
 * Helpers:   has01
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A044434: numbers n such that base‑3 representation of n contains
   the substring "01" but n+1 does not. The terms are generated by a
   simple brute‑force search and cached across calls.  */
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/has01.h"

/* Cache for already‑computed sequence values.  */
static seq_t* cache = NULL;
static size_t cache_len = 0;     /* number of values currently stored */
static size_t cache_cap = 0;     /* allocated capacity */

/* Grow the cache when needed.  */
static void grow_cache(void)
{
    if (cache_cap == 0) {
        cache_cap = 64;
        cache = (seq_t*)malloc(cache_cap * sizeof(seq_t));
    } else if (cache_len == cache_cap) {
        cache_cap *= 2;
        cache = (seq_t*)realloc(cache, cache_cap * sizeof(seq_t));
    }
}

/* Next integer to be examined in the brute‑force search. */
static idx_t next_candidate = 0;

/* Main sequence generator.  */
seq_t a(idx_t n)
{
    /* Iterate until we have at least n terms cached. */
    while (cache_len < n) {
        seq_t cand = (seq_t)next_candidate;
        if (has01(cand) && !has01(cand + 1u)) {
            grow_cache();
            cache[cache_len++] = cand;
        }
        ++next_candidate;
    }
    return cache[n - 1];
}
