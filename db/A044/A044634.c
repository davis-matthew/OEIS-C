/*
 * A044634  Numbers n such that string 0,2 occurs in the base 9 representation
 *          of n but not of n+1.
 * https://oeis.org/A044634
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 39, u32 n <= 39, u64 n <= 39, u128 n <= 39,
 *            big any n
 * Helpers:   no02_in_base9
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Sequence A044634:
 *   Numbers n such that the base‑9 representation of n contains the
 *   substring “02” but the base‑9 representation of n+1 does not.
 *   The sequence can be generated by
 *      n = (81*z + 2)               for k = 0
 *      n = 9*(prev+1) - 1           for k ≥ 1 (next = 9*prev + 8)
 *   where z is a positive integer whose base‑9 representation has
 *   no “02” substring.
 *
 *   The first terms are: 83, 164, 245, 326, 407, 488, ...
 */

#include <stdbool.h>
#include <stdlib.h>
#include "../utils/no02_in_base9.h"

/* Simple binary heap of nodes ordered by node.val (seq_t). */
typedef struct {
    seq_t   val;           /* term value */
    idx_t   z;             /* base part whose recurrence produces the term */
} node_t;

static void heap_swap(node_t *a, node_t *b)
{
    node_t tmp = *a;
    *a = *b;
    *b = tmp;
}

static void heap_push(node_t *heap, size_t *len, size_t cap, node_t v)
{
    if (*len >= cap) { /* grow heap if needed */
        cap = cap ? cap * 2 : 16;
        heap = (node_t *)realloc(heap, cap * sizeof(node_t));
    }
    size_t i = (*len)++;
    while (i > 0) {
        size_t parent = (i - 1) >> 1;
        if (heap[parent].val <= v.val) break;
        heap[i] = heap[parent];
        i = parent;
    }
    heap[i] = v;
}

static node_t heap_pop(node_t *heap, size_t *len)
{
    node_t top = heap[0];
    if (--(*len) == 0)
        return top;
    node_t last = heap[*len];
    size_t i = 0;
    while (true) {
        size_t left = i * 2 + 1;
        if (left >= *len) break;
        size_t right = left + 1;
        size_t child = (right < *len && heap[right].val < heap[left].val) ? right : left;
        if (last.val <= heap[child].val) break;
        heap[i] = heap[child];
        i = child;
    }
    heap[i] = last;
    return top;
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0; /* index starts at 1 */

    /* Choose how many z values to generate.
       n * 10 + 100 is more than enough for the requested index. */
    idx_t zmax = n * 10 + 100;

    /* Collect all positive z that avoid “02”. */
    idx_t *goodz = (idx_t *)malloc(zmax * sizeof(idx_t));
    idx_t goodcnt = 0;
    for (idx_t z = 1; z <= zmax; ++z) {
        if (no02_in_base9(z))
            goodz[goodcnt++] = z;
    }

    /* Build a heap with the first term (k = 0) for each good z. */
    node_t *heap = (node_t *)malloc(goodcnt * sizeof(node_t));
    size_t heaplen = 0;
    for (idx_t i = 0; i < goodcnt; ++i) {
        node_t node;
        node.val = (seq_t)81 * (seq_t)goodz[i] + 2; /* 81*z + 2 */
        node.z   = goodz[i];
        heap_push(heap, &heaplen, goodcnt, node);
    }

    seq_t result = 0;
    for (idx_t step = 1; step <= n; ++step) {
        node_t cur = heap_pop(heap, &heaplen);
        result = cur.val;

        /* Generate the next term for the same z:
           next = 9 * prev + 8   (for k >= 1). */
        seq_t next_val = cur.val * 9 + 8;

        node_t next_node;
        next_node.val = next_val;
        next_node.z   = cur.z;
        heap_push(heap, &heaplen, goodcnt, next_node);
    }

    /* Clean up */
    free(goodz);
    free(heap);
    return result;
}
