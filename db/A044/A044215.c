/*
 * A044215  Numbers k such that string 3,4 occurs in the base 8 representation
 *          of k but not of k-1.
 * https://oeis.org/A044215
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 1136, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   This function returns the nth term of OEIS A044215.
   It finds numbers k such that the base‑8 representation of k
   contains the substring "34" while that of k−1 does not.
   The sequence is generated by a linear scan of integers, testing
   each value and caching results; the algorithm runs in O(n·d),
   where d ≈ log₈k is the number of base‑8 digits.  For n≤10⁴ the
   running time is far below two seconds.
*/

#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

/* Test whether base‑8 representation of x contains the substring "34". */
static bool has34(seq_t x)
{
    if (x == 0)
        return false;

    unsigned char digits[64];
    size_t len = 0;
    seq_t temp = x;

    /* Extract digits least‑significant first. */
    while (temp != 0) {
        digits[len++] = (unsigned char)(temp % (seq_t)8);
        temp /= (seq_t)8;
    }

    /* Scan from most‑significant digit. */
    for (size_t i = len; i > 1; --i) {
        if (digits[i - 1] == 3 && digits[i - 2] == 4)
            return true;
    }
    return false;
}

/* Return the nth term (1‑based).  Static storage ensures that
   calls in any order are handled correctly. */
seq_t a(idx_t n)
{
    static seq_t *terms = NULL;
    static size_t terms_size = 0;
    static size_t terms_cap = 0;

    /* Current integer to test, and flag for whether (current-1) has "34". */
    static idx_t current_k = 1;
    static bool prev_has34 = false;  /* has34(0) == false */

    while (terms_size < (size_t)n) {
        bool has = has34((seq_t)current_k);

        if (has && !prev_has34) {
            /* Store the term. */
            if (terms_size == terms_cap) {
                size_t new_cap = terms_cap ? (terms_cap << 1) : 16;
                seq_t *new_terms = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
                if (!new_terms) /* out of memory */
                    abort();
                terms = new_terms;
                terms_cap = new_cap;
            }
            terms[terms_size++] = (seq_t)current_k;
        }

        prev_has34 = has;
        ++current_k;
    }

    return terms[n - 1];
}
