/*
 * A044806  Numbers k such that the digit string 9,3 occurs in the base-10
 *          representation of k but not of k+1.
 * https://oeis.org/A044806
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 39, u32 n <= 39, u64 n <= 39, u128 n <= 39,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Computes a(n) for OEIS A044806
   Numbers k such that the decimal string of k contains the substring "93" 
   but the decimal string of k+1 does not. This sequence is generated by
   scanning natural numbers and keeping those that satisfy the condition.
*/
#include <stdbool.h>
#ifdef __cplusplus
#include <cstddef>
#include <cstdlib>
#include <new>
#define ALLOC_SEQ(n) (new seq_t[(n)])
#define FREE_SEQ(p)  delete [] (p)
#else
#include <stddef.h>
#include <stdlib.h>
#define ALLOC_SEQ(n) ((seq_t*)malloc(sizeof(seq_t)*(n)))
#define FREE_SEQ(p)  ((void)free((p)))
#endif

/* Test whether decimal representation of n contains substring "93". */
static bool has_93(seq_t n) {
    if (n < (seq_t)10) return false;          /* at least two digits needed */
    seq_t prev = n % (seq_t)10;                /* least significant digit */
    n /= (seq_t)10;
    while (n != (seq_t)0) {
        seq_t curr = n % (seq_t)10;
        if (curr == (seq_t)9 && prev == (seq_t)3)
            return true;
        prev = curr;
        n /= (seq_t)10;
    }
    return false;
}

/* Dynamically grow the cache that holds found sequence terms. */
static void grow_cache(size_t new_cap, seq_t **cache, size_t *cap, size_t len) {
    seq_t *new_cache = ALLOC_SEQ(new_cap);
    for (size_t i = 0; i < len; ++i)
        new_cache[i] = (*cache)[i];
    FREE_SEQ(*cache);
    *cache = new_cache;
    *cap   = new_cap;
}

/* External function required by the build system. */
seq_t a(idx_t n) {
    if (n == (idx_t)0)
        return (seq_t)0;                       /* behavior below offset is irrelevant */

    /* Static cache for efficiency across multiple calls. */
    static seq_t *cache = NULL;
    static size_t cache_cap = 0;
    static size_t cache_len = 0;
    static seq_t last_checked = (seq_t)0;

    if (cache_cap == 0) {                      /* first call: allocate initial storage */
        cache_cap = 64;
        cache     = ALLOC_SEQ(cache_cap);
    }

    /* Generate terms until we have at least n of them. */
    while (cache_len < (size_t)n) {
        seq_t k = last_checked + (seq_t)1;
        ++last_checked;                         /* move forward for next iteration */

        if (has_93(k) && !has_93(k + (seq_t)1)) {
            if (cache_len == cache_cap)
                grow_cache(cache_cap * 2, &cache, &cache_cap, cache_len);
            cache[cache_len++] = k;
        }
    }

    return cache[(size_t)n - 1];
}
