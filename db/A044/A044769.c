/* Sequence: A044769
   Numbers n such that the decimal representation of n contains the
   substring "56" but the decimal representation of n+1 does NOT. */

/* The function is generated by a simple brute‑force search.
   It keeps an internal cache of already found terms.  For each
   candidate number it checks the decimal digits by repeated division
   by 10 (exactly the operations allowed on seq_t) and looks for the
   pattern 5 followed by 6. */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include "../utils/mem.h"

/* --------------------------------------------------------------------- */
static bool has56(seq_t x)
{
    if (x == 0)
        return false;

    /* initial capacity sufficient for most numbers; grows as needed */
    size_t      cap = 64;
    unsigned char *digits = (unsigned char *)malloc(cap);
    if (!digits)
        return false;                      /* allocation failure → false */

    size_t len = 0;
    seq_t   temp = x;

    /* extract decimal digits (least significant first) */
    while (temp != 0) {
        unsigned digit = (unsigned)(temp % 10);
        if (len == cap) {
            cap <<= 1;
            unsigned char *newdigits = (unsigned char *)realloc(digits, cap);
            if (!newdigits) {
                free(digits);
                return false;               /* allocation failure */
            }
            digits = newdigits;
        }
        digits[len++] = (unsigned char)digit;
        temp /= 10;
    }

    /* scan from most significant to least – reverse the order */
    for (size_t i = len; i > 1; --i) {
        if (digits[i - 1] == 5 && digits[i - 2] == 6) {
            free(digits);
            return true;
        }
    }

    free(digits);
    return false;
}

/* --------------------------------------------------------------------- */
/*  Helper to test whether a decimal representation of x contains     */
/*  the consecutive digits 5 and 6.  The function is generic for any   */
/*  seq_t: it repeatedly divides by 10 and stores the remainders.      */

/* --------------------------------------------------------------------- */
/*  Cache of already generated terms (zero‑based).  The cache is grown    */
/*  as needed so that a(n) can be answered for any n in any order.       */
/* --------------------------------------------------------------------- */
static seq_t *cache     = NULL;   /* array of terms */
static size_t cache_cap = 0;      /* allocated capacity      */
static size_t cache_len = 0;      /* number of terms stored  */

/* Ensure that the cache contains at least n terms (n >= 1). */
static void ensure_terms(idx_t n)
{
    if ((size_t)n <= cache_len)
        return;                       /* already have enough terms */

    /* initial allocation if necessary */
    if (cache_cap == 0) {
        cache_cap = 16;
        cache = mem_new(seq_t, cache_cap);
        if (!cache)
            exit(EXIT_FAILURE);
    }

    /* start searching from the next integer after the last cached value */
    seq_t cur = 1;
    if (cache_len > 0)
        cur = cache[cache_len - 1] + 1;

    /* generate terms until we reach the requested count */
    while (cache_len < (size_t)n) {
        if (has56(cur) && !has56(cur + 1)) {
            if (cache_len == cache_cap) {            /* grow cache */
                cache_cap <<= 1;
                seq_t *newcache = mem_resize(seq_t, cache, cache_cap);
                if (!newcache)
                    exit(EXIT_FAILURE);
                cache = newcache;
            }
            cache[cache_len++] = cur;
        }
        cur++;
    }
}

/* --------------------------------------------------------------------- */
/*  Public function required by the problem statement.                  */
/* --------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    /* OEIS offset is 1 – undefined for n <= 0, but return 0 safely. */
    if (n <= 0)
        return 0;

    ensure_terms(n);
    return cache[(size_t)n - 1];
}
