/* Sequence A044664: Numbers n such that the base‑9 representation of n
   contains the substring “35” but the base‑9 representation of n+1 does
   not.  The function `a(idx_t n)` returns the nth term (offset 1). */

#include <stdbool.h>

/* Return true iff base‑9 representation of x contains the substring 35. */
static bool has35(seq_t x)
{
    if (x == 0)
        return false;
    seq_t prev = 9;                      /* sentinel ≠ 0..8 */
    while (x > 0) {
        seq_t d = x % 9;
        if (prev == 5 && d == 3)     /* more significant digit 3, next 5 */
            return true;
        prev = d;
        x = x / 9;
    }
    return false;
}

/* Public function required by the kernel. */
seq_t a(idx_t n)
{
    /* The sequence is generated by scanning positive integers until
       the nth number satisfying the conditions is found.  For n ≤ 10 000
       this takes far less than 2 s on typical hardware. */
    if (n == 0)
        return 0;                      /* undefined, but keep safe */

    idx_t found = 0;
    seq_t cand  = 0;

    while (found < n) {
        if (has35(cand) && !has35(cand + 1)) {
            ++found;
            if (found == n)
                return cand;
        }
        ++cand;
    }
    return 0;   /* unreachable */
}
