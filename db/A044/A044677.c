/*
 * A044677  Numbers n such that string 5,0 occurs in the base 9 representation
 *          of n but not of n+1.
 * https://oeis.org/A044677
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 39, u32 n <= 39, u64 n <= 39, u128 n <= 39,
 *            big any n
 * Helpers:   has50
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: numbers whose base‑9 representation contains the adjacent digits
   5 followed by 0, while the next integer does not.  
   Generated by a simple brute‑force search with memoisation. */
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/has50.h"

static seq_t *cached_values = NULL;     /* array of found terms            */
static idx_t  cached_len   = 0;          /* number of values stored         */
static idx_t  cached_cap   = 0;          /* current capacity of the array   */
static seq_t  next_candidate = 0;        /* next integer to test           */

/* Ensure capacity for at least `need` elements. */
static void ensure_capacity(idx_t need)
{
    if (need <= cached_cap)
        return;
    idx_t new_cap = cached_cap ? cached_cap * 2 : 128;
    while (new_cap < need)
        new_cap *= 2;
    seq_t *new_vals = (seq_t *)realloc(cached_values,
                                       new_cap * sizeof(seq_t));
    cached_values = new_vals;
    cached_cap     = new_cap;
}

seq_t a(idx_t n)
{
    if (n == 0)
        return 0;                        /* undefined for n<1, but harmless */

    /* Grow the list until we have at least n entries. */
    while (cached_len < n) {
        seq_t cand = next_candidate;
        while (1) {
            if (has50(cand)) {
                seq_t cand_plus1 = cand + 1;
                if (!has50(cand_plus1)) {
                    /* Found a valid term. */
                    ensure_capacity(cached_len + 1);
                    cached_values[cached_len++] = cand;
                    next_candidate = cand + 1;
                    break;
                }
            }
            cand++;
        }
    }

    return cached_values[(size_t)(n - 1)];
}
