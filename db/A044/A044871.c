/*
 * A044871  Positive integers having the same number of base-15 runs of odd
 *          length as even.
 * https://oeis.org/A044871
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 15, u16 n <= 438, u32 n <= 9018, u64 n <= 9018,
 *            u128 n <= 9018, big any n
 * Helpers:   has_equal_runs, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A044871: Positive integers having the same number of base‑15 runs
 * of odd length as even. The function returns the nth such integer
 * (1‑based indexing). The sequence is generated by scanning the positive
 * integers and testing the required property. */
 
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/seq_realloc.h"   /* provides seq_realloc   */
#include "../utils/has_equal_runs.h"

static seq_t *cache = NULL;  /* dynamically expanded array of sequence terms   */
static size_t cache_size = 0;/* number of terms stored in cache                 */
static size_t cache_cap  = 0;/* capacity of cache                              */
static seq_t last_checked = 224; /* last integer examined (will start from 225)   */

/* Resize the cache to accommodate at least new_cap elements. */
static void ensure_cache_capacity(size_t new_cap)
{
    if (cache_cap >= new_cap)
        return;
    size_t old_cap = cache_cap;
    cache_cap = cache_cap ? cache_cap * 2 : 2;
    if (cache_cap < new_cap)
        cache_cap = new_cap;
    cache = seq_realloc(cache, old_cap, cache_cap);
}

/* ------------------------------------------------------------ */
seq_t a(idx_t n)
{
    if (n < 1)  /* the sequence is defined for n ≥ 1 */
        return 0;

    /* Generate terms until we have at least n of them. */
    while (cache_size < (size_t)n) {
        last_checked++;                     /* next integer to test   */
        if (has_equal_runs(last_checked)) {
            /* store the term */
            ensure_cache_capacity(cache_size + 1);
            cache[cache_size++] = last_checked;
        }
    }
    return cache[n - 1];
}
