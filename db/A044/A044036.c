/*
 * A044036  Numbers k such that 6 and 8 occur juxtaposed in the base-10
 *          representation of k but not of k+1.
 * https://oeis.org/A044036
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   numbers k such that the decimal representation of k contains the
 *            substring "68" or "86" but the representation of k+1 does not
 * Range:     u8 n <= 4, u16 n <= 41, u32 n <= 41, u64 n <= 41, u128 n <= 41,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdbool.h>

static bool has_adjacent(seq_t x) {
    if (x < 10) return false;
    seq_t t = x;
    while (t >= 10) {
        seq_t last2 = t % 100;                 /* last two digits */
        if (last2 == (seq_t)68 || last2 == (seq_t)86)
            return true;
        t /= 10;
    }
    return false;
}

seq_t a(idx_t n) {
    /* n ≥ 1 because OEIS offset is 1.  The sequence is generated by
       scanning natural numbers and selecting those that satisfy the
       condition described above.  The algorithm runs in O(k) time,
       where k is the searched value; for n ≈ 10 000 the maximum k is
       well below 5 × 10⁵, which is easily fast enough. */
    idx_t count = 0;
    for (idx_t k = 1; ; ++k) {
        seq_t sk = (seq_t)k;
        if (has_adjacent(sk) && !has_adjacent(sk + 1)) {
            ++count;
            if (count == n)
                return sk;
        }
    }
}
