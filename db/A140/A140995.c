/*
 * A140995  Triangle G(n, k) read by rows, for 0 <= k <= n, where G(n, n) =
 *          G(n+1, 0) = 1, G(n+2, 1) = 2, G(n+3, 2) = 4, G(n+4, 3) = 8, and
 *          G(n+5, m) = G(n+1, m-3) + G(n+1, m-4) + G(n+2, m-3) + G(n+3, m-2)
 *          + G(n+4, m-1) for n >= 0 and m = 4..(n+4).
 * https://oeis.org/A140995
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, tabl
 * Formula:   not stated
 * Range:     u8 n <= 62, u16 n <= 90, u32 n <= 90, u64 n <= 90, u128 n <= 90,
 *            big any n
 * Helpers:   allocate_seq_array
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A140995:  G(n,k) triangle flattened by rows.
 *  The G(n,k) values are generated by the recurrence given in the OEIS
 *  description.  The a(n) function returns the n‑th element of the flattened
 *  triangle, where n starts at 0.  The implementation builds rows on demand
 *  and keeps all previously computed rows so that calls can be made in any
 *  order.  The static state uses signed indices for safe comparison.
 */

#include <stdlib.h>
#include <stddef.h>
#include "../utils/allocate_seq_array.h"   /* allocate_seq_array(len) */

static seq_t **triangle = NULL;   /* array of pointers to rows */
static long long max_row = -1;    /* largest row already built, -1 = none */

/* Build rows up to ‘r’ if they have not been built yet.  */
static void
ensure_rows(idx_t r)
{
    if ((long long)r <= max_row)
        return;   /* nothing to do */

    /* Expand the outer array of pointers if needed. */
    size_t new_size = (size_t)(r + 1);
    if (triangle == NULL)
    {
        triangle = (seq_t **)malloc(new_size * sizeof(seq_t *));
    }
    else
    {
        triangle = (seq_t **)realloc(triangle, new_size * sizeof(seq_t *));
    }

    /* Build each new row. */
    for (idx_t row = (idx_t)(max_row + 1); row <= r; ++row)
    {
        /* Allocate the row array.  */
        size_t len = (size_t)(row + 1);
        seq_t *row_ptr = allocate_seq_array(len);
        triangle[(size_t)row] = row_ptr;

        /* Base values for all positions.  */
        row_ptr[0] = (seq_t)1;
        row_ptr[row] = (seq_t)1;
        if (row >= 2)
            row_ptr[1] = (seq_t)2;
        if (row >= 3)
            row_ptr[2] = (seq_t)4;
        if (row >= 4)
            row_ptr[3] = (seq_t)8;

        /* Recurrence for interior positions (row ≥ 5).  */
        if (row >= 5)
        {
            for (idx_t k = 4; k < row; ++k)  /* skip last element */
            {
                row_ptr[k] =
                    triangle[(size_t)(row-4)][k-3] +
                    triangle[(size_t)(row-4)][k-4] +
                    triangle[(size_t)(row-3)][k-3] +
                    triangle[(size_t)(row-2)][k-2] +
                    triangle[(size_t)(row-1)][k-1];
            }
        }
    }
    max_row = (long long)r;
}

/*  Public routine – returns a(n), the n‑th element of the flattened triangle.
 *  It works for any n ≥ 0, in any call order. */
seq_t a(idx_t n)
{
    /* Find the row that contains the n‑th element.  */
    idx_t r = 0;
    while (((r + 1) * (r + 2)) / 2 <= n)
        ++r;

    /* Build the necessary rows.  */
    ensure_rows(r);

    /* Number of elements preceding row r.  */
    idx_t prev = r * (r + 1) / 2;
    idx_t pos  = n - prev;   /* position inside row r */

    return triangle[(size_t)r][pos];
}
