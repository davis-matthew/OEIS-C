/*
 * A387271  Positive integers whose ternary expansion has equal run-length
 *          multisets for digits 1 and 2.
 * https://oeis.org/A387271
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 40, u16 n <= 4718, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: numbers whose base‑3 expansions have equal run‑length
   multisets for digits 1 and 2.  The sequence is generated by
   brute‑force enumeration of positive integers satisfying the
   run‑length property. */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

static seq_t *seq_buf = NULL;
static size_t seq_len = 0;
static size_t seq_cap = 0;
static idx_t next_val = 1;

/* Decide whether x satisfies the run‑length multiset equality. */
static bool is_valid(idx_t x)
{
    /* run lengths are at most 64 for all 64‑bit integers */
    int cnt[64] = {0};
    int cur_digit = -1;
    int run_len   = 0;

    while (x > 0) {
        int d = (int)(x % 3);
        x /= 3;
        if (d == 0) {
            if (run_len > 0) {
                cnt[run_len] += (cur_digit == 1) ? 1 : -1;
                run_len = 0;
            }
            continue;
        }
        if (cur_digit == -1) {
            cur_digit = d;
            run_len   = 1;
        } else if (d == cur_digit) {
            run_len++;
        } else {
            cnt[run_len] += (cur_digit == 1) ? 1 : -1;
            cur_digit = d;
            run_len   = 1;
        }
    }
    /* record final run if any */
    if (run_len > 0)
        cnt[run_len] += (cur_digit == 1) ? 1 : -1;

    for (int i = 1; i < 64; ++i)
        if (cnt[i] != 0)
            return false;
    return true;
}

/* Append a new term into the cached sequence. */
static void add_term(seq_t val)
{
    if (seq_len == seq_cap) {
        size_t new_cap = seq_cap ? seq_cap * 2 : 16;
        seq_t *tmp = (seq_t *)realloc(seq_buf, new_cap * sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);
        seq_buf = tmp;
        seq_cap = new_cap;
    }
    seq_buf[seq_len++] = val;
}

seq_t a(idx_t n)
{
    if (n == 0) return 0; /* undefined, but guard against underflow */

    while (seq_len < n) {
        if (is_valid(next_val))
            add_term((seq_t)next_val);
        ++next_val;
    }
    return seq_buf[n - 1];
}
