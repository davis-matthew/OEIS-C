/*
 * A391117  Powers of 7 that do not contain the digit 7 (in base 10).
 * https://oeis.org/A391117
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 4, u32 n <= 5, u64 n <= 7, u128 n <= 9,
 *            big any n
 * Helpers:   digit_counts
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute the nth element of sequence A391117
   (powers of 7 that do not contain the digit 7).
   The sequence is generated by iterating over exponents k,
   computing 7^k and keeping the term when its decimal
   representation has no '7' digit.  Results are cached
   for fast random access.  */
#include <stdlib.h>
#include "../utils/digit_counts.h"

static seq_t *cache = NULL;   /* cached valid terms */
static size_t cache_len = 0;  /* number of cached terms */
static size_t cache_cap = 0;  /* current capacity of cache */

static seq_t power = 1;        /* current 7^k value */
static idx_t current_k = 0;    /* exponent of current power */

static void add_value(seq_t val) {
    if (cache_len + 1 > cache_cap) {
        size_t new_cap = cache_cap ? cache_cap << 1 : 8;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) abort();          /* safe guard */
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

seq_t a(idx_t n) {
    if (n == 0) return 0;  /* undefined for offset 1, safe return */

    /* Generate terms until we have at least n of them */
    while (cache_len < n) {
        if (current_k != 0) {
            power *= 7;           /* 7^(k) from previous k-1 */
        }
        unsigned char cnt[10];
        digit_counts(power, cnt);
        if (cnt[7] == 0) {
            add_value(power);
        }
        current_k++;
    }
    return cache[n - 1];
}
