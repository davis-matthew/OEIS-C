/*
 * A214365  Digit-wise Fibonacci: Start with 0,1; then the next term is always
 *          the sum of the earliest two consecutive digits not yet summed so
 *          far.
 * https://oeis.org/A214365
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 10000, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Digit‑wise Fibonacci
   a(0) = 0, a(1) = 1
   For n >= 2 the sequence is generated by repeatedly taking the
   earliest pair of consecutive decimal digits of all terms that have
   appeared so far, adding the two digits, appending the decimal
   representation of the result to the term list, and moving one
   position forward.  This algorithm exactly reproduces the
   terms of A214365. */

#include <stdint.h>
#include <stdlib.h>

seq_t a(idx_t n)
{
    /* Return the first two terms immediately. */
    if (n == 0) return (seq_t)0;
    if (n == 1) return (seq_t)1;

    /* Digit stream: store decimal digits of the terms. */
    size_t cap = 16;                     /* initial capacity */
    uint8_t *digits = (uint8_t *)malloc(cap * sizeof(uint8_t));
    if (!digits) return (seq_t)0;        /* allocation failed – return 0 */

    digits[0] = 0;                       /* a(0) */
    digits[1] = 1;                       /* a(1) */
    size_t dsize = 2;                    /* current number of digits in cache */

    size_t p = 0;                        /* window start position */

    seq_t val = 0;                       /* placeholder for the result */

    for (idx_t i = 2; i <= n; ++i) {
        /* Compute the next term as the sum of the two earliest unused
           consecutive digits (i.e., digits[p] and digits[p+1]). */
        uint8_t sum = digits[p] + digits[p + 1];
        val = (seq_t)sum;                /* store as seq_t for the answer */

        if (i == n) break;               /* result ready – skip appending */

        /* Append the decimal digits of 'sum' to the digit stream. */
        if (sum < 10) {
            if (dsize + 1 > cap) {
                cap = cap * 2;
                digits = (uint8_t *)realloc(digits, cap * sizeof(uint8_t));
            }
            digits[dsize++] = sum;
        } else {
            if (dsize + 2 > cap) {
                cap = cap * 2;
                digits = (uint8_t *)realloc(digits, cap * sizeof(uint8_t));
            }
            digits[dsize++] = sum / 10;
            digits[dsize++] = sum % 10;
        }

        ++p;    /* advance to the next pair */
    }

    free(digits);
    return val;
}
