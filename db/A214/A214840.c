/*
 * A214840  Averages y of twin prime pairs that satisfy y = x^2 + x - 2.
 * https://oeis.org/A214840
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 16, u32 n <= 967, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   isPrimeGeneric
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A214840: a(n) is the average y = x² + x – 2 of twin‑prime pairs
   (p, p+2) where p = x² + x – 3 and p+2 = x² + x – 1 are both prime.
   The terms are generated by scanning integer x ≥ 2 in increasing order
   and testing the two potential primes for primality.  Results are
   cached so that any n ≥ 1 can be answered in any call order. */

#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/isPrimeGeneric.h"

seq_t a(idx_t n)
{
    /* static cache of results */
    static seq_t *cache   = NULL;   /* array of y values */
    static size_t cache_cap = 0;    /* allocated capacity */
    static size_t count      = 0;    /* number of terms stored */
    static idx_t  next_x     = 2;    /* next x to test */

    /* OEIS offset is 1; n == 0 is undefined but we return 0 safely */
    if (n == 0)
        return (seq_t)0;

    /* generate terms until the cache contains at least n entries */
    while (count < n) {
        idx_t      x      = next_x++;
        seq_t      xs     = (seq_t)x;
        seq_t      p1     = xs * xs + xs - (seq_t)3;   /* x² + x – 3  */
        seq_t      p2     = xs * xs + xs - (seq_t)1;   /* x² + x – 1  */

        if (isPrimeGeneric(p1) && isPrimeGeneric(p2)) {
            seq_t y = xs * xs + xs - (seq_t)2;          /* x² + x – 2 */

            /* grow cache if necessary */
            if (count >= cache_cap) {
                size_t new_cap = cache_cap ? cache_cap * 2 : 4;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                /* In C++ realloc with a class type requires a cast and
                   assumes trivial copyability; the build uses a type that
                   is safe for this usage. */
                cache = tmp;
                cache_cap = new_cap;
            }

            cache[count++] = y;
        }
    }

    return cache[n - 1];
}
