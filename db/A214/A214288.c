/*
 * A214288  Primes of the form phi(n)+1 sorted by increasing n, where phi is
 *          the Euler totient function.
 * https://oeis.org/A214288
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 158, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   is_prime_big, phi
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: primes of the form φ(n)+1 sorted by increasing n.
   The sequence is generated by scanning consecutive integers m =
   1,2,3,…, computing φ(m)+1 for each m and keeping the values that
   are prime.  a(n) returns the n‑th such prime (1‑based index). */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/phi.h"        /* static seq_t phi(idx_t m) */
#include "../utils/is_prime_big.h" /* bool is_prime_big(seq_t n) */

/* State that persists across calls.  The prime list is sorted in the
   order of increasing m. */
static seq_t  *prime_list   = NULL;   /* array of primes φ(m)+1             */
static size_t prime_cap    = 0;       /* malloced capacity                 */
static size_t prime_len    = 0;       /* number of primes stored           */
static idx_t  last_m       = 0;       /* last m processed (1‑based)        */

/* Ensure that prime_list can hold at least <need> elements. */
static void ensure_prime_cap(size_t need)
{
    if (need <= prime_cap)
        return;
    size_t new_cap = prime_cap ? prime_cap << 1 : 4;
    while (new_cap < need)
        new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(prime_list, new_cap * sizeof(seq_t));
    if (!tmp)
        abort();                     /* out of memory */
    prime_list = tmp;
    prime_cap  = new_cap;
}

/* Return the n-th prime of the form φ(m)+1, with 1‑based index n. */
seq_t a(idx_t n)
{
    /* Undefined for n==0, but return 0 rather than crashing. */
    if (n == 0)
        return (seq_t)0;

    /* Generate primes until we have enough. */
    while (prime_len < (size_t)n) {
        ++last_m;                           /* m = 1,2,3,… */
        seq_t phi_val = phi(last_m);        /* compute φ(m) */
        seq_t cand     = phi_val + (seq_t)1; /* φ(m)+1    */
        if (is_prime_big(cand)) {
            ensure_prime_cap(prime_len + 1);
            prime_list[prime_len++] = cand;
        }
    }
    return prime_list[n - 1];
}
