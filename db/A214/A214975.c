/*
 * A214975  Numbers k for which A116543(k) < A007895(k); i.e., the Lucas
 *          representation of k is shorter than the Zeckendorf representation.
 * https://oeis.org/A214975
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 59, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A214975
 *  a(n) = the nth integer k for which the number of terms in the
 *  greedy Lucas representation of k is less than the number of terms
 *  in its Zeckendorf representation.
 *
 *  The sequence is generated by examining integers k in increasing
 *  order and counting the digits used by the two greedy algorithms.
 *  Results up to the requested n are cached so subsequent calls
 *  are fast.  The implementation works for any build where
 *  seq_t and idx_t are unsigned integer types, including arbitrary
 *  precision integers treated as a single type.
 */

#include <stdlib.h>

/* --------- static data and helpers --------- */

static seq_t *fib      = NULL;  /* Fibonacci used for Zeckendorf (1,2,3,5,...)   */
static size_t fib_len = 0, fib_cap = 0;
static seq_t *lucas    = NULL;  /* All Lucas in index order (2,1,3,4,7,...)      */
static size_t lucas_len = 0, lucas_cap = 0;
static seq_t *asc_l    = NULL;  /* Lucas numbers sorted increasingly (1,2,3,4,7,...) */
static size_t asc_len = 0, asc_cap = 0;
static seq_t *terms    = NULL;  /* results of the sequence                     */
static size_t terms_len = 0, terms_cap = 0;
static idx_t last_k = 0;        /* last k checked                              */

/* Make sure an array has at least 'need' capacity */
static void grow_array(void **p, size_t *cap, size_t need)
{
    if (need <= *cap) return;
    size_t new_cap = (*cap > 0 ? *cap * 2 : 16);
    if (new_cap < need) new_cap = need;
    void *tmp = realloc(*p, new_cap * sizeof(seq_t));
    if (!tmp) abort();  /* out of memory */
    *p = tmp;
    *cap = new_cap;
}

/* Initialise all tables on first use */
static void init_tables(void)
{
    if (fib) return;           /* already initialised */

    /* Fibonacci for Zeckendorf: 1, 2 */
    fib_cap = 2;
    fib = (seq_t*)malloc(fib_cap * sizeof(seq_t));
    fib[0] = (seq_t)1;
    fib[1] = (seq_t)2;
    fib_len = 2;

    /* Lucas in index order: L(0)=2, L(1)=1 */
    lucas_cap = 2;
    lucas = (seq_t*)malloc(lucas_cap * sizeof(seq_t));
    lucas[0] = (seq_t)2;
    lucas[1] = (seq_t)1;
    lucas_len = 2;

    /* Ascending Lucas list: start with 1, 2 */
    asc_cap = 2;
    asc_l   = (seq_t*)malloc(asc_cap * sizeof(seq_t));
    asc_l[0] = (seq_t)1;   /* L(1) */
    asc_l[1] = (seq_t)2;   /* L(0) */
    asc_len = 2;

    /* Term cache */
    terms_cap = 16;
    terms = (seq_t*)malloc(terms_cap * sizeof(seq_t));
    terms_len = 0;
}

/* Extend Fibonacci table to cover values up to at least n */
static void extend_fib(idx_t n)
{
    while (fib_len > 0 && fib[fib_len-1] <= (seq_t)n) {
        grow_array((void**)&fib, &fib_cap, fib_len + 1);
        fib[fib_len] = fib[fib_len-1] + fib[fib_len-2];
        fib_len++;
    }
}

/* Extend Lucas tables to cover values up to at least n.
 * For each new Lucas number we also append it to ascending list.
 */
static void extend_lucas(idx_t n)
{
    while (lucas_len > 0 && lucas[lucas_len-1] <= (seq_t)n) {
        grow_array((void**)&lucas, &lucas_cap, lucas_len + 1);
        lucas[lucas_len] = lucas[lucas_len-1] + lucas[lucas_len-2];
        lucas_len++;

        /* Since all new Lucas numbers after L(1) are increasing,
           we can safely append to asc_l. */
        grow_array((void**)&asc_l, &asc_cap, asc_len + 1);
        asc_l[asc_len] = lucas[lucas_len-1];
        asc_len++;
    }
}

/* Count digits used by greedy Lucas representation (skip next lower term). */
static int lucas_digit_count(idx_t k)
{
    int cnt = 0;
    seq_t rem = (seq_t)k;
    for (size_t i = asc_len; i > 0; ) {
        seq_t val = asc_l[i-1];
        if (val <= rem) {
            cnt++;
            rem -= val;
            if (i >= 2) i -= 2;
            else i = 0;
        } else {
            i--;
        }
    }
    return cnt;
}

/* Count digits used by Zeckendorf representation. */
static int zeckendorf_digit_count(idx_t k)
{
    int cnt = 0;
    seq_t rem = (seq_t)k;
    for (size_t i = fib_len; i > 0; ) {
        seq_t val = fib[i-1];
        if (val <= rem) {
            cnt++;
            rem -= val;
            i--;          /* skip to next smaller Fibonacci */
        } else {
            i--;
        }
    }
    return cnt;
}

/* Grow the terms cache until we have at least n terms. */
static void ensure_terms_up_to(idx_t n)
{
    while (terms_len < (size_t)n) {
        last_k++;

        extend_fib(last_k);
        extend_lucas(last_k);

        if (lucas_digit_count(last_k) < zeckendorf_digit_count(last_k)) {
            grow_array((void**)&terms, &terms_cap, terms_len + 1);
            terms[terms_len] = (seq_t)last_k;
            terms_len++;
        }
    }
}

/* --------- public function --------- */

seq_t a(idx_t n)
{
    init_tables();
    if (n == 0) return (seq_t)0;          /* safety: offset is 1 */
    ensure_terms_up_to(n);
    return terms[n-1];
}
