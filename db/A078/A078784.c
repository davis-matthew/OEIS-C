/*
 * A078784  Primes on axis of Ulam square spiral (with rows ... / 7 8 9 / 6 1
 *          2 / 5 4 3 / ... ) with origin at (1).
 * https://oeis.org/A078784
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 11, u16 n <= 52, u32 n <= 52, u64 n <= 52, u128 n <= 52,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) = nth prime that appears on any axis of the Ulam square spiral.
   The axis numbers are generated by four quadratic formulas.
   For each layer n (starting at 0) we check the numbers in the
   order East, South, West, North:

       East   : 4n^2 + 5n + 2
       South  : 4n^2 - n + 1
       West   : 4n^2 + n + 1
       North  : 4n^2 + 3n + 1

   Every time a prime number is found we increment a counter; the
   function returns the value when the counter reaches the requested
   index n.  */

#include <stdbool.h>
#include "../utils/is_prime_big.h"

seq_t a(idx_t n)
{
    if (n == 0) {
        /* offset is 1, but we never called with n==0 in tests */
        return 0;
    }

    idx_t needed = n;
    idx_t count  = 0;
    idx_t layer  = 0;

    while (count < needed) {
        seq_t ns = (seq_t)layer;

        /* East */
        seq_t east = 4 * ns * ns + 5 * ns + 2;
        if (is_prime_big(east)) {
            ++count;
            if (count == needed) return east;
        }

        /* South */
        seq_t south = 4 * ns * ns - ns + 1;
        if (is_prime_big(south)) {
            ++count;
            if (count == needed) return south;
        }

        /* West */
        seq_t west = 4 * ns * ns + ns + 1;
        if (is_prime_big(west)) {
            ++count;
            if (count == needed) return west;
        }

        /* North */
        seq_t north = 4 * ns * ns + 3 * ns + 1;
        if (is_prime_big(north)) {
            ++count;
            if (count == needed) return north;
        }

        ++layer;
    }

    /* This point should never be reached, but return 0 for safety. */
    return 0;
}
