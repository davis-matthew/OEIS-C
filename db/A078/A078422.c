/*
 * A078422  a(n) = prime(n+1)^prime(n).
 * https://oeis.org/A078422
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = prime(n+1)^prime(n)
 * Range:     u8 n <= 2, u16 n <= 3, u32 n <= 4, u64 n <= 6, u128 n <= 9,
 *            big any n
 * Helpers:   pow_seq_t
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The pow_seq_t function performs exponentiation on the build’s
   arbitrary‑precision type 'seq_t'.  It is declared in the utility
   header pow_seq_t.h. */
#include "../utils/pow_seq_t.h"

#define MAX_PRIME_COUNT 20000   /* enough for n ≤ 10000 (prime(10001)=104743) */

/* Store primes in a static array.  The array is grown only when more
   primes are required. */
static uint32_t _prime_list[MAX_PRIME_COUNT];
static int      _prime_cnt = 0;

/* Ensure that _prime_list contains at least 'needed' primes (1‑based
   rank).  If more primes are needed, they are generated by simple
   trial division. */
static void _ensure_primes(idx_t needed)
{
    while ((idx_t)_prime_cnt < needed) {
        uint32_t candidate;
        if (_prime_cnt == 0)
            candidate = 2;
        else
            candidate = _prime_list[_prime_cnt - 1] + 1;

        /* Find the next prime ≥ candidate. */
        for (;;) {
            if (candidate == 2 || candidate == 3) {
                _prime_list[_prime_cnt++] = candidate;
                break;
            }
            if ((candidate & 1) == 0) {   /* skip even numbers */
                ++candidate;
                continue;
            }

            int is_prime = 1;
            for (int i = 0; i < _prime_cnt; ++i) {
                uint32_t p = _prime_list[i];
                if ((uint64_t)p * p > candidate)
                    break;
                if (candidate % p == 0) {
                    is_prime = 0;
                    break;
                }
            }
            if (is_prime) {
                _prime_list[_prime_cnt++] = candidate;
                break;
            }
            ++candidate;
        }
    }
}

/* Return the k‑th prime (k ≥ 1). */
static uint32_t _get_prime(idx_t k)
{
    _ensure_primes(k);
    return _prime_list[k - 1];
}

/* a(n) = prime(n+1)^prime(n)  (n ≥ 1) */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;   /* undefined; return 0 for safety */

    uint32_t p_n  = _get_prime(n);     /* prime(n)   */
    uint32_t p_n1 = _get_prime(n + 1); /* prime(n+1) */

    /* Compute prime(n+1) ^ prime(n).  pow_seq_t handles arbitrary
       precision built‐ins. */
    return pow_seq_t((seq_t)p_n1, (idx_t)p_n);
}
