/*
 * A357985  Counterclockwise square spiral constructed using the integers so
 *          that a(n) plus all other numbers currently visible from the
 *          current number equals n; start with a(0) = 0.
 * https://oeis.org/A357985
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  sign
 * Formula:   not stated
 * Range:     i8 n <= 24, i16 n <= 45, i32 n <= 54, i64 n <= 54, i128 n <= 54,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes sequence A357985 by definition.
   a(0) = 0; for n > 0,
   a(n) = n - Σ a(j) over all j < n for which the vector
   (x_j - x_n, y_j - y_n) is primitive (gcd(|dx|,|dy|)=1).
   Coordinates are generated by a counter‑clockwise square spiral. */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

/* static arrays for values and coordinates */
static seq_t *values = NULL;   /* a(n) values */
static int   *xs     = NULL;   /* x‑coordinates */
static int   *ys     = NULL;   /* y‑coordinates */

/* array sizes and capacities */
static size_t values_len   = 0;  /* number of stored terms        */
static size_t values_cap   = 0;  /* capacity of values array       */
static size_t xs_cap       = 0;  /* capacity of xs array           */
static size_t ys_cap       = 0;  /* capacity of ys array           */

/* spiral state */
static int curx   = 0;   /* current x coordinate */
static int cury   = 0;   /* current y coordinate */
static int dir    = 0;   /* 0=right,1=up,2=left,3=down */
static int step   = 1;   /* length of current leg  */
static int remain = 1;   /* steps left in current leg */

/* Ensure array has capacity at least `needed`. */
static void grow_array(void **arr, size_t *cap, size_t needed, size_t elem_size) {
    if (*cap >= needed) return;
    size_t newcap = (*cap == 0) ? 64 : (*cap << 1);
    while (newcap < needed) newcap <<= 1;
    *arr = realloc(*arr, newcap * elem_size);
    *cap = newcap;
}

/* Ensure all terms up to `n` have been computed. */
static void ensure_up_to(idx_t n) {
    if (values_len > n) return;   /* already have it */

    /* First initialisation */
    if (values_len == 0) {
        grow_array((void **)&values, &values_cap, 1, sizeof(seq_t));
        grow_array((void **)&xs,     &xs_cap,     1, sizeof(int));
        grow_array((void **)&ys,     &ys_cap,     1, sizeof(int));

        values[0] = 0;
        xs[0]     = 0;
        ys[0]     = 0;
        values_len = 1;

        curx = 0; cury = 0;
        dir  = 0;
        step = 1;
        remain = 1;
    }

    while (values_len <= (size_t)n) {
        /* Move one step in current direction */
        switch (dir) {
            case 0: curx++; break;          /* right  */
            case 1: cury++; break;          /* up     */
            case 2: curx--; break;          /* left   */
            case 3: cury--; break;          /* down   */
        }
        remain--;

        /* Prepare space for the new term */
        size_t i = values_len;          /* index of new term */
        grow_array((void **)&values, &values_cap, i + 1, sizeof(seq_t));
        grow_array((void **)&xs,     &xs_cap,     i + 1, sizeof(int));
        grow_array((void **)&ys,     &ys_cap,     i + 1, sizeof(int));

        xs[i] = curx;
        ys[i] = cury;

        /* Compute sum of visible previous numbers */
        seq_t sum = 0;
        for (size_t j = 0; j < i; ++j) {
            int dx = xs[j] - curx;
            int dy = ys[j] - cury;

            unsigned int ux = dx < 0 ? (unsigned int)(-dx) : (unsigned int)dx;
            unsigned int uy = dy < 0 ? (unsigned int)(-dy) : (unsigned int)dy;

            unsigned int g;
            if (ux == 0) {
                g = uy;
            } else if (uy == 0) {
                g = ux;
            } else {
                unsigned int a = ux, b = uy;
                while (b != 0) {
                    unsigned int t = a % b;
                    a = b;
                    b = t;
                }
                g = a;
            }

            if (g == 1) sum += values[j];
        }

        /* Compute a(i) */
        values[i] = (seq_t)i - sum;
        values_len = i + 1;

        /* Update spiral state */
        if (remain == 0) {
            int old_dir = dir;
            if (old_dir == 1 || old_dir == 3) step++;
            dir = (dir + 1) & 3;
            remain = step;
        }
    }
}

seq_t a(idx_t n) {      /* external linkage required */
    ensure_up_to(n);
    return values[(size_t)n];
}
