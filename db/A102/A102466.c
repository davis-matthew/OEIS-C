/*
 * A102466  Numbers such that the number of divisors is the sum of numbers of
 *          prime factors with and without repetitions.
 * https://oeis.org/A102466
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 145, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A102466
 *  a(n) = nth smallest integer ≥2 such that τ(n)=Ω(n)+ω(n).
 *  Equivalently, n is a prime power or a product of two primes.
 *  The sequence is generated by sieving for prime factors and
 *  collecting all numbers that satisfy the condition.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

static seq_t *res   = NULL;   /* array of computed sequence terms */
static idx_t res_len = 0;     /* number of terms stored */
static idx_t res_cap = 0;     /* capacity of the array */

static idx_t *spf   = NULL;   /* smallest prime factor array */
static idx_t spf_lim = 0;     /* current maximum index for spf */
static idx_t last_limit = 0;  /* last number processed in generation */

/* Extend the spf array to at least 'new_lim' */
static void expand_spf(idx_t new_lim)
{
    if (new_lim <= spf_lim) return;

    idx_t *new_spf = (idx_t *)malloc((new_lim + 1) * sizeof(idx_t));
    if (!new_spf) return;               /* out of memory – unlikely in this scope */

    for (idx_t i = 0; i <= new_lim; ++i) new_spf[i] = 0;

    for (idx_t i = 2; i <= new_lim; ++i) {
        if (new_spf[i] == 0) {          /* i is prime */
            new_spf[i] = i;
            if (i <= new_lim / i) {     /* prevent overflow of i*i */
                for (idx_t j = i * i; j <= new_lim; j += i)
                    if (new_spf[j] == 0) new_spf[j] = i;
            }
        }
    }

    free(spf);
    spf = new_spf;
    spf_lim = new_lim;
}

/* Check if a number satisfies τ(n)=Ω(n)+ω(n) */
static bool qualifies(idx_t n)
{
    if (n < 2) return false;
    idx_t m = n;
    int distinct = 0, total = 0;

    while (m > 1) {
        idx_t p = spf[m];
        if (p == 0) p = m;          /* fallback, should not occur */

        int cnt = 0;
        do {
            m /= p;
            ++cnt;
        } while (m % p == 0);
        ++distinct;
        total += cnt;
    }
    return (distinct == 1) || (total == 2);
}

/* Generate sequence terms up to 'limit', appending to res */
static void generate_terms(idx_t limit)
{
    if (limit <= last_limit) return;
    for (idx_t n = last_limit + 1; n <= limit; ++n) {
        if (qualifies(n)) {
            if (res_len == res_cap) {
                idx_t new_cap = res_cap ? res_cap * 2 : 64;
                seq_t *new_res = (seq_t *)realloc(res, new_cap * sizeof(seq_t));
                if (!new_res) return;  /* memory failure */
                res = new_res;
                res_cap = new_cap;
            }
            res[res_len++] = (seq_t)n;
        }
    }
    last_limit = limit;
}

/* Public function as required */
seq_t a(idx_t n)
{
    if (n == 0) return 0;  /* undefined, but keep safe */

    /* Ensure we have computed at least n terms. */
    while (res_len < n) {
        /* Pick an initial bound that grows with n. */
        idx_t bound = last_limit == 0 ? (n * 2 + 100) : (last_limit * 2);
        expand_spf(bound);
        generate_terms(bound);
    }
    return res[n - 1];
}
