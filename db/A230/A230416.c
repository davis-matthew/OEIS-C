/* Sequence: A230416 – The infinite trunk of factorial beanstalk with reversed subsections
   The sequence is generated by iterating over rows m = 2,3,4,...
   Row m starts at s = m! – 1 and contains successive values
   cur = cur – sum_of_factorial_digits(cur) until the value equals (m–1)! – 1,
   which is the first element of the previous row.  The flattened rows form a(0)=0,
   a(1)=1, a(2)=5, a(3)=2, …  */

/* Requires the utility to ensure dynamic array capacity */
#include <stdlib.h>
#include "../utils/ensure_capacity.h"
#include "../utils/fact_digit_sum.h"

/* Sequence value function */
seq_t a(idx_t n)
{
    /* Static cache of computed values */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;   /* number of terms currently stored */
    static size_t cap = 0;         /* allocated capacity */
    static idx_t next_m = 2;        /* next row index (m) to generate */
    static seq_t prev_fact = 1;     /* factorial of (next_m - 1) */

    /* Initialize cache with a(0) */
    if (cache_len == 0) {
        ensure_capacity(1, &cap, (void **)&cache, sizeof(seq_t));
        cache[0] = 0;
        cache_len = 1;
    }

    /* Grow the cache until it contains term n */
    while (cache_len <= (size_t)n) {

        /* Start of the next row */
        seq_t curr_fact = prev_fact * (seq_t)next_m;   /* m! = (m-1)! * m */
        seq_t start_val = curr_fact - 1;              /* first element of row m */

        /* Append start value */
        ensure_capacity(cache_len + 1, &cap, (void **)&cache, sizeof(seq_t));
        cache[cache_len++] = start_val;

        seq_t cur = start_val;
        seq_t repeat_val = prev_fact - 1;   /* (m-1)! – 1, the value that signals the end of the row */

        /* Generate remaining elements of the row */
        while (1) {
            seq_t sum_dig = fact_digit_sum(cur);
            seq_t nxt = cur - sum_dig;
            if (nxt == repeat_val) break;            /* reached the previous row's start */
            ensure_capacity(cache_len + 1, &cap, (void **)&cache, sizeof(seq_t));
            cache[cache_len++] = nxt;
            cur = nxt;
        }

        /* Prepare for the next row */
        prev_fact = curr_fact;
        ++next_m;
    }

    return cache[(size_t)n];
}
