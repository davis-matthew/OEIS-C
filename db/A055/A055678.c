/*
 * A055678  Integers not congruent to 0 (mod 6) that are divisible by the
 *          number of their divisors.
 * https://oeis.org/A055678
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 16, u16 n <= 1495, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   my_malloc, my_realloc, tau_large
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Implements OEIS sequence A055678:
 *  a(n) = the n‑th positive integer m such that
 *  (m mod 6 ≠ 0) and m is divisible by τ(m) (the number of divisors of m).
 *  The sequence is generated by a simple search and a sieve for τ(n) up to a
 *  pre‑chosen limit.  This suffices for n up to at least 10000 in far
 *  under two seconds. */

#include <stdint.h>
#include <stdlib.h>
#include <stddef.h>
#include "../utils/my_malloc.h"
#include "../utils/my_realloc.h"
#include "../utils/tau_large.h"

/*  The build supplies the types  seq_t  (unsigned integer or big class)
 *  and idx_t  (unsigned, e.g. uint64_t).  We do not define them here. */

static const idx_t MAX_TAU_LIMIT = 2000000U;          /* sieve limit      */
static uint32_t *tau_table = NULL;                   /* τ(1)…τ(limit)  */
static seq_t   *seq_values = NULL;                   /* collected terms */
static size_t  seq_len   = 0;                        /* number of terms  */
static size_t  seq_cap   = 0;                        /* array capacity   */
static idx_t   next_candidate = 0;                   /* next integer to test */

/*-------------------------------------------------------*/

/*-------------------------------------------------------*/

/*-------------------------------------------------------*/
/* Initialise the sieve table for τ(n) and the sequence  */
static void init(void)
{
    if (seq_values != NULL) return;   /* already initialized */

    /* Allocate and compute τ(n) up to the sieve limit. */
    tau_table = (uint32_t*)calloc(MAX_TAU_LIMIT + 1U, sizeof(uint32_t));
    if (!tau_table) exit(1);

    for (idx_t i = 1U; i <= MAX_TAU_LIMIT; ++i)
        for (idx_t j = i; j <= MAX_TAU_LIMIT; j += i)
            ++tau_table[j];

    /* Allocate initial space for sequence values. */
    seq_cap = 16384U;
    seq_values = (seq_t*)my_malloc(seq_cap * sizeof(seq_t));
    if (!seq_values) exit(1);

    /* Generate the sequence up to the sieve limit. */
    for (idx_t x = 1U; x <= MAX_TAU_LIMIT; ++x)
    {
        if (x % 6U == 0U) continue;
        uint32_t tau = tau_table[x];
        if (x % (idx_t)tau == 0U)
        {
            if (seq_len == seq_cap)
            {
                seq_cap <<= 1U;
                seq_values = (seq_t*)my_realloc(seq_values,
                                                seq_cap * sizeof(seq_t));
                if (!seq_values) exit(1);
            }
            seq_values[seq_len++] = (seq_t)x;
        }
    }

    next_candidate = MAX_TAU_LIMIT + 1U;
}

/*-------------------------------------------------------*/
/* Extend the sequence until it contains at least `n` terms */
static void extend_to(idx_t n)
{
    if (n <= seq_len) return;

    idx_t cand = next_candidate;
    while (seq_len < n)
    {
        if (cand % 6U != 0U)
        {
            uint32_t tau = (cand <= MAX_TAU_LIMIT) ?
                           tau_table[cand] : tau_large(cand);
            if (cand % (idx_t)tau == 0U)
            {
                if (seq_len == seq_cap)
                {
                    seq_cap <<= 1U;
                    seq_values = (seq_t*)my_realloc(seq_values,
                                                    seq_cap * sizeof(seq_t));
                    if (!seq_values) exit(1);
                }
                seq_values[seq_len++] = (seq_t)cand;
            }
        }
        ++cand;
    }
    next_candidate = cand;
}

/*-------------------------------------------------------*/
/* Public function required by the build system.          */
seq_t a(idx_t n)
{
    if (n == 0U) return (seq_t)0U;   /* undefined for index 0 – return 0 */
    init();                          /* ensure tables exist */
    extend_to(n);                    /* ensure at least n terms */
    return seq_values[n - 1U];       /* 1‑based indexing per OEIS */
}
