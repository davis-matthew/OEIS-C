/*  Sequence A055872
    a(n) = square of the n-th integer x such that floor(x^2/8) is a square.
    The x's are generated by the two Pell equations
        x^2 – 8y^2 = 1   (start x=1)
        x^2 – 8y^2 = 4   (start x=2)
    The two sequences are merged in ascending order, with a(1)=0 fixed.
*/
#include <stdint.h>

seq_t a(idx_t n)
{
    if (n == 1)               /* a(1) = 0 */
        return (seq_t)0;

    /* state for the x^2 – 8y^2 = 1 sequence (x=1, y=0) */
    seq_t x1 = (seq_t)1;
    seq_t y1 = (seq_t)0;

    /* state for the x^2 – 8y^2 = 4 sequence (x=2, y=0) */
    seq_t x4 = (seq_t)2;
    seq_t y4 = (seq_t)0;

    seq_t result = 0;
    idx_t  count  = 1;        /* already counted the zero term */

    while (count < n)
    {
        seq_t next_x;

        if (x1 <= x4) {            /* pick the smaller x */
            next_x = x1;

            /* advance the (x^2-8y^2=1) Pell sequence */
            seq_t nx = (seq_t)3 * x1 + (seq_t)8 * y1;
            seq_t ny = x1 + (seq_t)3 * y1;
            x1 = nx;
            y1 = ny;
        } else {
            next_x = x4;

            /* advance the (x^2-8y^2=4) Pell sequence */
            seq_t nx = (seq_t)3 * x4 + (seq_t)8 * y4;
            seq_t ny = x4 + (seq_t)3 * y4;
            x4 = nx;
            y4 = ny;
        }

        result = next_x * next_x;   /* x^2 is the desired value */
        ++count;
    }

    return result;
}
