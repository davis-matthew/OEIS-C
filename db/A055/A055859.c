/*
 * A055859  a(n) and floor(a(n)/7) are both squares; i.e., squares which
 *          remain squares when written in base 7 and last digit is removed.
 * https://oeis.org/A055859
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 9, u32 n <= 15, u64 n <= 24, u128 n <= 24,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  A055859 – squares k² such that floor(k²/7) is a perfect square.
    The sequence is generated by merging three Pell‑type recurrences
    corresponding to the congruence classes d = 1, 2 and 4:
          k² – 7 t² = d,     d ∈ {1,2,4}
    The minimal solutions are:
          d=1 : (k,t) = (1,0)
          d=2 : (k,t) = (3,1)
          d=4 : (k,t) = (2,0)
    Successive solutions (k,t) are obtained by multiplying by
          8 + 3√7  →  (k₁, t₁) = (8k + 21t, 3k + 8t)
    The roots k are merged in increasing order; the sequence term a(n)
    is k².  The value 0 is the fixed point for d=0 (k=0).
    The function is memoised for out‑of‑order requests.                                                */

#include <stddef.h>   /* size_t */
#include <stdlib.h>   /* malloc, realloc */

static seq_t        *cache      = NULL;  /* cached a(n) values   */
static size_t        cache_len  = 0;      /* number of cached terms */
static size_t        cache_cap  = 0;      /* allocated slots      */

typedef struct { seq_t k; seq_t t; } sol_t;   /* current (k,t) of a class */

static sol_t sol[3];   /* 0→d=1, 1→d=2, 2→d=4 */

/* initialise the first terms and the three classes */
static void init_series(void)
{
    if (cache_len > 0) return;         /* already initialised */

    /* store the first term a(1) = 0 */
    cache_len = 1;
    cache_cap = 64;
    cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
    cache[0] = (seq_t)0;

    /* initial solutions of the three Pell families */
    sol[0].k = (seq_t)1; sol[0].t = (seq_t)0;   /* d = 1 */
    sol[1].k = (seq_t)3; sol[1].t = (seq_t)1;   /* d = 2 */
    sol[2].k = (seq_t)2; sol[2].t = (seq_t)0;   /* d = 4 */
}

/* advance a class to its next solution */
static void next_sol(int i)
{
    seq_t k = sol[i].k;
    seq_t t = sol[i].t;
    /* k' = 8k + 21t  ;  t' = 3k + 8t  */
    sol[i].k = k * (seq_t)8 + t * (seq_t)21;
    sol[i].t = k * (seq_t)3 + t * (seq_t)8;
}

/* duplicate current solutions if necessary (hash to avoid missing a term) */
static void push_next(void)
{
    /* find the smallest k among the three classes */
    seq_t min_k = sol[0].k;
    for (int i = 1; i < 3; ++i)
        if (sol[i].k < min_k) min_k = sol[i].k;

    /* append its square to the cache */
    if (cache_len >= cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 64;
        if (new_cap < cache_len + 1) new_cap = cache_len + 1;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        cache   = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = min_k * min_k;

    /* advance all classes that produced this min_k (to avoid duplicates) */
    for (int i = 0; i < 3; ++i)
        if (sol[i].k == min_k)
            next_sol(i);
}

/* --------------------------------------------------------------- */
/*  External function expected by the build system                 */
/* --------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;          /* out of range: just return 0 */

    init_series();                         /* ensure first terms are in cache */

    while (cache_len < n)                  /* generate terms up to n            */
        push_next();

    return cache[n - 1];                   /* offsets are 1‑based                */
}
