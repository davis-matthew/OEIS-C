/* OEIS A355547: Numbers k such that the quadratic x^2 – s*x + p
 * has non‑integer roots, where s = sum of digits of k and
 * p = product of digits of k.
 * The sequence is generated by scanning the natural numbers
 * and selecting those that do not yield integer roots.
 */

#include <stdbool.h>
#include <stdint.h>
#include "../utils/append_candidate.h"
#include "../utils/floor_sqrt.h"

seq_t a(idx_t n)
{
    /* static cache of found terms */
    static seq_t *cache = NULL;
    static size_t cache_len = 0, cache_cap = 0;
    static seq_t next_k = 1;   /* next number to test */

    /* compute terms until we have the requested index */
    while (cache_len < (size_t)n) {
        seq_t k = next_k++;

        /* compute sum s and product p of decimal digits of k */
        seq_t s = 0, p = 1;
        seq_t t = k;
        if (k == 0) {               /* handled just in case */
            s = 0;
            p = 0;
        } else {
            while (t != 0) {
                seq_t d = t % 10;
                s += d;
                p *= d;
                t /= 10;
            }
        }

        /* discriminant D = s^2 - 4p
         * if p > s^2 / 4, D would be negative -> non‑integer roots */
        seq_t ss = s * s;
        if (p > ss / 4) {
            /* D < 0, guaranteed non‑integer roots */
            append_candidate(&cache, &cache_len, &cache_cap, k);
            continue;
        }

        seq_t D = ss - (p << 2);          /* D >= 0 */
        seq_t sq = floor_sqrt(D);         /* floor(sqrt(D)) */

        /* check if D is a perfect square and parity matches */
        if (sq * sq == D && ((s ^ sq) & 1) == 0) {
            /* integer roots: skip this k */
            continue;
        }

        /* non‑integer roots: keep this term */
        append_candidate(&cache, &cache_len, &cache_cap, k);
    }

    return cache[n - 1];
}
