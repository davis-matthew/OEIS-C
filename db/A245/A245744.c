/*  A245744
 *  Sequence: primes p such that p + d is also prime, where d is the
 *  smallest non‑zero decimal digit of p.
 *  The sequence starts: 29, 67, 89, 227, …
 *
 *  This implementation keeps a static cache of all found terms.
 *  Subsequent calls (in any order) retrieve the value directly from
 *  the cache, enlarging it only when a larger index is requested.
 *  Candidates are generated by repeatedly calling next_prime(uint64_t),
 *  which is much faster than testing every integer.
 */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>
#include "../utils/is_prime_big.h"
#include "../utils/get_digits.h"
#include "../utils/next_prime.h"

/* --------------------------------------------------------------- */
seq_t a(idx_t n)
{
    /* persistent state -------------------------------------------------- */
    static seq_t *cache = NULL;   /* array of found terms          */
    static size_t cap   = 0;      /* allocated capacity           */
    static size_t len   = 0;      /* number of terms stored       */

    static uint64_t cur_prime = 2; /* next prime to examine        */

    /* initialise cache on first call ------------------------------------ */
    if (!cache) {
        cap   = 64;
        cache = (seq_t *)malloc(cap * sizeof(seq_t));
        len   = 0;
    }

    /* generate terms until we have at least n of them ------------------- */
    while (len < n) {
        /* 1. current prime candidate ----------------------------------- */
        seq_t p = (seq_t)cur_prime;

        /* 2. find the smallest non‑zero decimal digit of p ---------- */
        uint8_t dig[32];
        size_t dl = 0;
        get_digits(p, dig, &dl);

        int d = 10;                 /* sentinel for min non‑zero digit */
        for (size_t i = 0; i < dl; ++i) {
            uint8_t val = dig[i];
            if (val != 0 && val < d) d = val;
        }
        if (d == 10) d = 0;          /* safety: should never happen    */

        /* 3. test if p + d is also prime ------------------------------- */
        seq_t q = p + (seq_t)d;
        if (is_prime_big(q)) {
            /* store p in cache ---------------------------------------- */
            if (len >= cap) {
                cap *= 2;
                cache = (seq_t *)realloc(cache, cap * sizeof(seq_t));
            }
            cache[len++] = p;
        }

        /* 4. advance to the next prime candidate ----------------------- */
        cur_prime = next_prime(cur_prime + 1);
    }

    /* return the requested term ---------------------------------------- */
    return cache[n - 1];
}
