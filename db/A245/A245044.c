/*
 * A245044  Semiprimes with digits in descending order that differ exactly by
 *          2.
 * https://oeis.org/A245044
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy, fini, full
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 7, u32 n <= 8, u64 n <= 8, u128 n <= 8,
 *            big any n
 * Helpers:   _smallest_prime_factor_uint64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A245044:  semiprimes whose decimal digits form a decreasing
   arithmetic progression with common difference 2.  The values are
   generated by enumerating all such candidates (there are only 29 for
   base‑10 numbers) and keeping those that are the product of exactly
   two primes (counted with multiplicity).  The array of results is
   built lazily on the first call and reused for all subsequent calls. */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/_smallest_prime_factor_uint64.h"

/* semiprime test for 64‑bit numbers */
static bool is_semiprime_uint64(uint64_t n)
{
    if (n < 4) return false;                 /* need at least 2*2 */
    uint64_t p = _smallest_prime_factor_uint64(n);
    if (p == n) return false;                /* prime */
    uint64_t q = n / p;
    if (q == 1) return false;
    return _smallest_prime_factor_uint64(q) == q;
}

/* The main sequence function. */
seq_t a(idx_t n)
{
    /* static cache of candidates and semiprimes */
    static bool built = false;
    static seq_t candidates[29];
    static seq_t semiprimes[29];
    static size_t semip_count = 0;

    if (!built) {
        /* 1. generate all decimal digits decreasing by 2 from 1..9 */
        size_t k = 0;
        for (int d = 1; d <= 9; ++d) {
            seq_t val = 0;
            for (int len = 1; ; ++len) {
                int digit = d - 2 * (len - 1);
                if (digit < 0) break;
                val = val * 10 + (seq_t)digit;
                candidates[k++] = val;
            }
        }

        /* 2. sort candidates ascending (simple bubble sort, data size is tiny) */
        for (size_t i = 0; i < k; ++i) {
            for (size_t j = i + 1; j < k; ++j) {
                if (candidates[i] > candidates[j]) {
                    seq_t tmp = candidates[i];
                    candidates[i] = candidates[j];
                    candidates[j] = tmp;
                }
            }
        }

        /* 3. keep only semiprimes, result is already sorted */
        size_t cnt = 0;
        for (size_t i = 0; i < k; ++i) {
            uint64_t v = (uint64_t)candidates[i];
            if (is_semiprime_uint64(v)) {
                semiprimes[cnt++] = candidates[i];
            }
        }
        semip_count = cnt;
        built = true;
    }

    if (n == 0) return (seq_t)0;                /* offset is 1, safety */
    if ((size_t)n > semip_count) return (seq_t)0;
    return semiprimes[(size_t)n - 1];
}
