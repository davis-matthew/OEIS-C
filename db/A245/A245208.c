/*
 * A245208  Nonprimes such that it takes exactly 3 iterations of
 *          reverse-and-add digits to generate a prime.
 * https://oeis.org/A245208
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) = nonprime number such that it takes exactly three
 *            reverse‑and‑add steps to reach a prime
 * Range:     u8 none, u16 n <= 1, u32 n <= 1, u64 n <= 36, u128 n <= 36,
 *            big any n
 * Helpers:   grow_seq, is_prime_big, reverse_decimal
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence is generated by a lazy scan of integers, storing only the
 * values that satisfy the required property.  The function is memoised, so
 * repeated calls for arbitrary indices do not recompute previous terms.
 */

#include <stdbool.h>
#include <stddef.h>
#include "../utils/reverse_decimal.h"
#include "../utils/is_prime_big.h"
#include "../utils/grow_seq.h"

/* Helper: test if a nonprime number becomes prime exactly after
 * three reverse‑and‑add iterations. */
static inline bool good_nonprime(seq_t x)
{
    if (is_prime_big(x))
        return false;

    seq_t cur = x;
    for (int i = 1; i <= 3; ++i) {
        seq_t rev = reverse_decimal(cur);
        seq_t nxt = cur + rev;

        if (is_prime_big(nxt))
            return i == 3;   /* prime reached exactly on third step */

        cur = nxt;
    }
    return false;   /* did not reach a prime in three steps */
}

/* Returns the n‑th term of the sequence (0‑based).  The function
 * memoises previously computed terms so that repeated calls are
 * fast, irrespective of call order. */
seq_t a(idx_t n)
{
    /* static state for memoisation */
    static seq_t *cache = NULL;           /* array of found terms     */
    static size_t  cap   = 0;             /* allocated capacity       */
    static size_t  size  = 0;             /* number of stored terms   */
    static idx_t   cand  = 2;             /* current integer to test  */

    /* Grow and initialise the cache on first use. */
    if (cache == NULL)
        grow_seq(&cache, &cap, 16);

    /* Extend the cache until we have at least n+1 terms. */
    while (size <= (size_t)n) {
        /* Find the next integer that satisfies the property. */
        while (!good_nonprime((seq_t)cand))
            ++cand;

        /* Store the found term. */
        grow_seq(&cache, &cap, size + 1);
        cache[size++] = (seq_t)cand;
        ++cand;
    }

    return cache[(size_t)n];
}
