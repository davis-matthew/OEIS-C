/*
 * A392111  Numbers k such that 5*k - (greatest prime < 5*k) = (least prime >
 *          5*k) - 5*k.
 * https://oeis.org/A392111
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 58, u16 n <= 58, u32 n <= 58, u64 n <= 58, u128 n <= 58,
 *            big any n
 * Helpers:   next_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A392111: Numbers k such that  
   5*k - (greatest prime < 5*k) = (least prime > 5*k) - 5*k.
   The terms are generated by iterating over primes and
   collecting k = (p+q)/10 whenever p and q are either
   consecutive primes or are separated by exactly one prime
   that is the midpoint 5*k. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/next_prime.h"

static seq_t cache[20050];          /* store sequence terms */
static idx_t cache_size = 0;        /* number of cached terms */

static uint64_t prev_prime = 0;     /* previous prime in scan */
static uint64_t curr_prime = 0;     /* current prime in scan */
static bool prime_state_initialized = false;

/* add a term to the cache (no overflow expected for test limits) */
static void add_term(seq_t val) {
    if (cache_size < 20050) {
        cache[cache_size++] = val;
    } else {
        abort(); /* should not happen for n <= 10000 */
    }
}

/* initialise prime scanning variables */
static void init_prime_state(void) {
    prev_prime = 2;
    curr_prime = next_prime(prev_prime);   /* next prime after 2 : 3 */
    prime_state_initialized = true;
}

seq_t a(idx_t n) {
    if (n == 0) return 0;   /* undefined for n < 1, but never called */

    /* if we already have enough terms, just return */
    if (n <= cache_size) return cache[n - 1];

    /* initialise scanning state if required */
    if (!prime_state_initialized) init_prime_state();

    /* generate terms until we reach the required index */
    while (cache_size < n) {
        /* case 1: consecutive primes (prev, curr) */
        if (((__uint128_t)prev_prime + curr_prime) % 10 == 0) {
            add_term((seq_t)((prev_prime + curr_prime) / 10));
        }

        /* compute next prime */
        uint64_t next = next_prime(curr_prime);

        /* case 2: primes separated by exactly one prime (prev, next) */
        __uint128_t sum_skipped = (__uint128_t)prev_prime + next;
        if (sum_skipped % 10 == 0 && curr_prime * 2 == (uint64_t)sum_skipped) {
            add_term((seq_t)((uint64_t)sum_skipped / 10));
        }

        /* advance scanning window */
        prev_prime = curr_prime;
        curr_prime = next;
    }

    return cache[n - 1];
}
