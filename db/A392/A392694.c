/*
 * A392694  Numbers whose weakly increasing prime indices are the 0-prepended
 *          first sums of some reversed integer partition.
 * https://oeis.org/A392694
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, changed
 * Formula:   not stated
 * Range:     u8 n <= 148, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  A sequence of numbers whose prime indices satisfy a partition rule.
    The numbers are generated by testing each integer in ascending order
    and keeping those for which the multiset of prime indices
    (indices of the primes dividing the number) can be written as
    0-prepended first sums of a weakly increasing integer partition.
    See the description in OEIS A392694.
*/

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>

/* ---------- Pre‑computation of primes and smallest prime factor ---------- */
#define SIEVE_LIMIT 2000000      /* enough to generate >10 000 terms */

/* global storage for the sieve; initialised once */
static uint32_t *g_spf = NULL;         /* smallest prime factor of i */
static uint32_t *g_prime_index = NULL; /* prime(p) -> 1‑based index */
static size_t   g_limit = 0;

/* initialise sieve data once */
static void init_sieve(void)
{
    static bool inited = false;
    if (inited) return;
    g_limit = SIEVE_LIMIT;

    g_spf = (uint32_t*)malloc((g_limit + 1) * sizeof(uint32_t));
    g_prime_index = (uint32_t*)calloc(g_limit + 1, sizeof(uint32_t));

    /* linear sieve with list of primes */
    size_t primes_needed = g_limit / 10;           /* >#primes up to limit */
    uint32_t *primes = (uint32_t*)malloc(primes_needed * sizeof(uint32_t));
    size_t primes_cnt = 0;

    for (size_t i = 2; i <= g_limit; ++i) {
        if (g_spf[i] == 0) {          /* i is prime */
            g_spf[i] = (uint32_t)i;
            primes[primes_cnt] = (uint32_t)i;
            g_prime_index[i] = (uint32_t)(primes_cnt + 1); /* 1‑based */
            ++primes_cnt;
        }
        for (size_t j = 0; j < primes_cnt; ++j) {
            uint32_t p = primes[j];
            if (p > g_spf[i]) break;
            size_t ip = i * p;
            if (ip > g_limit) break;
            if (g_spf[ip] == 0) g_spf[ip] = p;
        }
    }
    free(primes);
    inited = true;
}

/* ---------- Sequence storage ---------- */
static seq_t *g_seq = NULL;       /* array of terms */
static size_t g_seq_sz = 0;      /* number of stored terms */
static size_t g_seq_cap = 0;     /* allocated capacity */
static uint32_t g_last_checked = 1; /* last integer processed */

/* push a new term into the array, enlarging if necessary */
static void push_term(seq_t val)
{
    if (g_seq_sz == g_seq_cap) {
        size_t new_cap = (g_seq_cap == 0) ? 64 : g_seq_cap * 2;
        seq_t *tmp = (seq_t*)realloc(g_seq, new_cap * sizeof(seq_t));
        g_seq = tmp;
        g_seq_cap = new_cap;
    }
    g_seq[g_seq_sz++] = val;
}

/* ---------- Test if an integer satisfies the property ---------- */
static bool valid_number(uint32_t v)
{
    if (v == 1u) return true;          /* 1 has empty prime index multiset */

    uint32_t m = v;
    uint32_t prev_pi = 0;
    bool first = true;

    while (m > 1u) {
        uint32_t p = g_spf[m];
        uint32_t idx = g_prime_index[p];       /* 1‑based prime index */

        if (first) {
            prev_pi = idx;          /* p1 = idx */
            first = false;
        } else {
            uint32_t pi = idx - prev_pi;       /* pi = current - previous pi */
            if (pi < prev_pi || pi < 1u) return false;
            prev_pi = pi;
        }
        m /= p;
    }
    return true;
}

/* ---------- Main function required by the platform ---------- */
seq_t a(idx_t n)
{
    init_sieve();                 /* ensure sieve ready */

    /* initialise sequence with 1 if needed */
    if (g_seq_sz == 0) {
        push_term((seq_t)1);
        g_last_checked = 1;
    }

    /* generate terms until we reach the requested index */
    while (g_seq_sz < (size_t)n) {
        ++g_last_checked;
        if (valid_number((uint32_t)g_last_checked)) {
            push_term((seq_t)g_last_checked);
        }
    }
    return g_seq[(size_t)n - 1];
}
