/*  Sequence A169263 – number of reduced words of length n in the Coxeter group
 *  on 10 generators with relations S_i^2=I and (S_i S_j)^29=I.
 *
 *  The growth series is rational with denominator
 *
 *      Q(t) = 1 - 8t - 8t^2 - ... - 8t^28 + 36 t^29
 *
 *  Hence, for n ≥ 30 the coefficients satisfy the linear recurrence
 *
 *      a(n) = 8 ∑_{k=1}^{28} a(n-k) - 36 a(n-29)
 *
 *  The first 30 values (a(0)…a(29)) are available explicitly; they are used
 *  as initial conditions.  Subsequent terms are generated by the recurrence
 *  above.  The routine keeps a cache of all computed terms so subsequent
 *  calls are O(1).
 */

#include <stddef.h>
#include <stdlib.h>
#include "../utils/grow_seq.h"
#include "../utils/seq_from_str.h"

static seq_t *cache   = NULL;     /* array of computed a(n) */
static size_t cache_cap = 0;      /* current capacity of cache   */
static idx_t  cache_max = 0;      /* largest n for which a(n) is stored */

/* Initialise the cache with the first 30 values of the sequence */
static void init_cache(void)
{
    /* Ensure space for at least 30 elements */
    grow_seq(&cache, &cache_cap, 30);
    cache_max = 29;

    cache[0] = (seq_t)1;          /* a(0) */
    cache[1] = (seq_t)10;         /* a(1) */

    /* a(k) = 10 · 9^(k-1) for 2 ≤ k ≤ 28 */
    for (idx_t k = 2; k <= 28; ++k)
        cache[k] = cache[k-1] * (seq_t)9;

    /* a(29) – value taken from the OEIS entry */
    cache[29] = seq_from_str("5233476330273605372135115165");
}

/* Return a(n) for arbitrary non‑negative n */
seq_t a(idx_t n)
{
    if (!cache)
        init_cache();

    /* Return already computed value */
    if (n <= cache_max)
        return cache[(size_t)n];

    /* Compute new values up to n */
    for (idx_t m = cache_max + 1; m <= n; ++m)
    {
        /* Compute 8 * (a(m-1)+…+a(m-28)) - 36 * a(m-29) */
        seq_t sum = cache[(size_t)(m-28)];
        for (idx_t k = m-27; k <= m-1; ++k)
            sum += cache[(size_t)k];

        seq_t term1 = (seq_t)8 * sum;
        seq_t term2 = (seq_t)36 * cache[(size_t)(m-29)];
        seq_t new_val = term1 - term2;

        /* Ensure the array can hold the new element */
        grow_seq(&cache, &cache_cap, (size_t)(m + 1));
        cache[(size_t)m] = new_val;
    }

    cache_max = n;
    return cache[(size_t)n];
}
