/*
 * A169516  Number of reduced words of length n in Coxeter group on 23
 *          generators S_i with relations (S_i)^2 = (S_i S_j)^34 = I.
 * https://oeis.org/A169516
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 3, u32 n <= 7, u64 n <= 14, u128 n <= 15,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A169516 recurrence:
   a(0) = 1
   For n ≥ 1:
       a(n) = 21 * Σ_{k=1}^{33} a(n-k)     // sum of previous 33 terms
             – 231 * a(n-34)               // a(n-34) exists only for n ≥ 34
             + p(n)
   where the numerator coefficient p(n) is
       p(n) = 1   if n = 0 or n = 34
       p(n) = 2   if 1 ≤ n ≤ 33
       p(n) = 0   otherwise
   The sequence is generated by the rational function
   (t^34 + 2t^33 + … + 2t + 1)/(1 – 21t – 21t^2 – … – 21t^33 + 231t^34).
*/

#include <stdlib.h>    /* malloc, realloc, abort */

seq_t a(idx_t n)
{
    /* static cache of already-computed terms */
    static seq_t *cache   = NULL;
    static size_t cap     = 0;   /* allocated capacity (terms) */
    static size_t len     = 0;   /* number of terms stored: indices 0 .. len-1 */

    /* resize cache if necessary to hold up to n (inclusive) */
    if (n + 1 > (idx_t)cap) {
        size_t newcap = cap ? cap * 2 : (size_t)(n + 1);
        if (newcap < (size_t)(n + 1))
            newcap = (size_t)(n + 1);

        seq_t *tmp = (seq_t *)realloc(cache, newcap * sizeof(seq_t));
        if (!tmp) abort();      /* allocation failure */
        cache = tmp;
        cap   = newcap;
    }

    /* compute all missing terms from index 'len' up to 'n' */
    for (idx_t i = (idx_t)len; i <= n; ++i) {
        seq_t sum = 0;

        /* 21 * Σ_{k=1}^{33} a(i-k)  */
        for (idx_t k = 1; k <= 33 && i >= k; ++k) {
            sum += cache[i - k];
        }
        sum = sum * (seq_t)21;

        /* subtract 231 * a(i-34) if i ≥ 34 */
        if (i >= 34) {
            sum -= cache[i - 34] * (seq_t)231;
        }

        /* add numerator coefficient p(i) */
        seq_t pi;
        if (i == 0 || i == 34) {
            pi = (seq_t)1;
        } else if (i <= 33) {          /* 1 ≤ i ≤ 33 */
            pi = (seq_t)2;
        } else {
            pi = (seq_t)0;
        }

        cache[i] = sum + pi;
    }

    len = (size_t)(n + 1);
    return cache[n];
}
