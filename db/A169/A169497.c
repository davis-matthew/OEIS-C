/*
 * A169497  Number of reduced words of length n in Coxeter group on 4
 *          generators S_i with relations (S_i)^2 = (S_i S_j)^34 = I.
 * https://oeis.org/A169497
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 9, u32 n <= 19, u64 n <= 25, u128 n <= 25,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A169497 – number of reduced words of length n in
   the Coxeter group on 4 generators with relations (S_i)^2 = (S_i S_j)^34 = I.
   The sequence is generated by dynamic programming over the last two
   generators and the length of the current alternating segment.  The value
   a(0) = 1, a(1) = 4, a(2) = 12, … */

#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

/* maximum n for which the cache is kept; the sequence is required only
   up to about 10000 in the test harness.  The static array is large
   enough for that range without dynamic allocation of seq_t objects. */
#define MAX_N 10000

/* length of alternating run that is allowed: run length 34 would
   create the forbidden relation (S_i S_j)^34 = I, therefore forbidden.
   The longest allowed run is 33. */
#define MAX_RUN 33
/* dimension of dp tables: 4 generators × 4 generators × 34 run-lengths
   (index 0 is unused). */
#define DP_DIM (4 * 4 * 34)

/* helper macro to compute the linear index into the 3‑D dp arrays */
#define IDX(prev, last, run) (((prev) * 4 + (last)) * 34 + (run))

/* -------------------------------------------------------------- */
/* public function required by the build system */
/* -------------------------------------------------------------- */
seq_t a(idx_t n)
{
    /* ======================================================== */
    /*  Static storage: cache and DP tables.                     */
    /* ======================================================== */
    static seq_t cache[MAX_N + 1] = {0};
    static size_t cache_len = 0;          /* number of values stored in cache */
    static bool initialized = false;      /* one‑time initialisation flag */

    /* DP states for current and next length */
    static seq_t cur1[4]        = {0};          /* words ending with single letter */
    static seq_t cur2[DP_DIM]   = {0};          /* words ending with two distinct letters
                                                 and an alternating run of length
                                                 'run' (1 … MAX_RUN)                */
    static seq_t next1[4]       = {0};
    static seq_t next2[DP_DIM]  = {0};

    /* ======================================================== */
    /*  Initialise on first call or when cache is empty.       */
    /* ======================================================== */
    if (!initialized) {
        /* a(0) = 1 */
        cache[0] = 1;
        cache_len = 1;
        initialized = true;
    }

    /* ======================================================== */
    /*  Grow the cache up to requested n.                       */
    /* ======================================================== */
    while (cache_len <= n) {

        /* ------------------------------------------------------------------ */
        /*  Clear next arrays. If we are extending from length 0, we need to
           initialise the first step specially.                               */
        /* ------------------------------------------------------------------ */
        memset(next1, 0, sizeof(next1));
        memset(next2, 0, sizeof(next2));

        size_t cur_len = cache_len - 1;   /* length represented by cur* arrays */

        if (cur_len == 0) {
            /* starting from the empty word */
            for (int c = 0; c < 4; ++c)
                next1[c] = 1;          /* one word of length 1 ending with generator c */
        } else {
            /* ------------------------------------------------------------ */
            /*  Transition from words of length 1 (cur1) to length 2.         */
            /* ------------------------------------------------------------ */
            for (int last = 0; last < 4; ++last) {
                seq_t val = cur1[last];
                if (!val) continue;
                for (int c = 0; c < 4; ++c) {
                    if (c == last) continue;          /* no consecutive equal letters */
                    /* new word has two distinct letters (prev=last, last=c) */
                    next2[ IDX(last, c, 1) ] += val;
                }
            }

            /* ------------------------------------------------------------ */
            /*  Transition from words of length >=2 (cur2).                    */
            /* ------------------------------------------------------------ */
            for (int prev = 0; prev < 4; ++prev) {
                for (int last = 0; last < 4; ++last) {
                    if (prev == last) continue;      /* end states always have prev!=last */
                    for (int run = 1; run <= MAX_RUN; ++run) {
                        seq_t val = cur2[ IDX(prev, last, run) ];
                        if (!val) continue;
                        for (int c = 0; c < 4; ++c) {
                            if (c == last) continue;  /* no consecutive equal letters */
                            if (c == prev) {
                                /* extend the alternating run */
                                int new_run = run + 1;
                                if (new_run > MAX_RUN) continue;  /* would give length 34 */
                                next2[ IDX(prev, last, new_run) ] += val;
                            } else {
                                /* start a new run of length 1 with generator c */
                                next1[c] += val;
                            }
                        }
                    }
                }
            }
        }

        /* ------------------------------------------------------------ */
        /*  Sum all next states to get a(cur_len+1).                     */
        /* ------------------------------------------------------------ */
        seq_t a_next = 0;
        for (int i = 0; i < 4; ++i) a_next += next1[i];
        for (int i = 0; i < DP_DIM; ++i) a_next += next2[i];

        /* Store the result */
        if (cache_len <= MAX_N) {
            cache[cache_len] = a_next;
        }

        /* ------------------------------------------------------------ */
        /*  Prepare for the next iteration: swap cur and next arrays.   */
        /* ------------------------------------------------------------ */
        /* swap cur1 and next1 */
        for (int i = 0; i < 4; ++i) cur1[i] = next1[i];
        /* swap cur2 and next2 */
        for (int i = 0; i < DP_DIM; ++i) cur2[i] = next2[i];

        ++cache_len;
    }

    return cache[n];
}
