/*
 * A169413  Number of reduced words of length n in Coxeter group on 16
 *          generators S_i with relations (S_i)^2 = (S_i S_j)^32 = I.
 * https://oeis.org/A169413
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 4, u32 n <= 8, u64 n <= 16, u128 n <= 16,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A169413
 *  a(n) satisfies the recurrence
 *    a(n) = c(n) + 14*∑_{k=1}^{31} a(n-k) – 105*a(n-32)
 *  where c(0)=1, c(1..31)=2, c(32)=1, c(n)=0 otherwise,
 *  and a(0)=1.
 *  Sequence is generated by memoised dynamic programming. */

#include <stddef.h>
#include <stdlib.h>

/* coefficient of the numerator generating function */
static inline seq_t coeff(idx_t n)
{
    if (n == 0)          return (seq_t)1;
    if (n == 32)         return (seq_t)1;
    if (n >= 1 && n <= 31) return (seq_t)2;
    return (seq_t)0;
}

/* cache for computed terms */
static seq_t *cache = NULL;
static idx_t cache_len = 0;
static idx_t computed_up_to = (idx_t)-1;

/* ensure the cache can hold indices up to n */
static void ensure_cache(idx_t n)
{
    if (cache_len > n) return;
    idx_t new_len = cache_len ? cache_len : 1;
    while (new_len <= n) new_len <<= 1;
    seq_t *new_cache = (seq_t*)malloc(new_len * sizeof(seq_t));
    if (!new_cache) return;                      /* allocation failed – leave cache unchanged */
    if (cache) {
        for (idx_t i = 0; i < cache_len; ++i) new_cache[i] = cache[i];
        free(cache);
    }
    cache = new_cache;
    cache_len = new_len;
}

/* compute all terms up to and including n */
static void compute_upto(idx_t n)
{
    if (computed_up_to != (idx_t)-1 && computed_up_to >= n) return;
    idx_t start = (computed_up_to == (idx_t)-1) ? 0 : computed_up_to + 1;
    for (idx_t i = start; i <= n; ++i) {
        seq_t c = coeff(i);
        seq_t sum31 = 0;
        for (int k = 1; k <= 31; ++k) {
            if (i >= (idx_t)k) sum31 += cache[i - k];
        }
        seq_t term = c + sum31 * (seq_t)14;
        if (i >= 32) term -= cache[i - 32] * (seq_t)105;
        cache[i] = term;
    }
    computed_up_to = n;
}

/* public sequence accessor */
seq_t a(idx_t n)
{
    ensure_cache(n);
    compute_upto(n);
    return cache[n];
}
