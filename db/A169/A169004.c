/*
 * A169004  Number of reduced words of length n in Coxeter group on 39
 *          generators S_i with relations (S_i)^2 = (S_i S_j)^23 = I.
 * https://oeis.org/A169004
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 3, u32 n <= 6, u64 n <= 12, u128 n <= 14,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence for OEIS A169004:
   a(0) = 1
   a(1) = 39
   a(2) = 1482
   ...
   a(n) = 37*(a(n-1)+...+a(n-22)) - 703*a(n-23)   for n >= 23
   (The first 23 terms are generated by the same linear relation with
    the additional constant term from the numerator of the generating function.) */

#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

seq_t a(idx_t n)
{
    /* Static cache for computed values */
    static seq_t *cache = NULL;
    static size_t cache_cap = 0;    /* allocated size of cache   */
    static idx_t cache_size = 0;    /* number of values already stored (cache_size = k implies cache[0..k-1] exist) */

    /* Running sums for the recurrence */
    static seq_t totalSum = 0;      /* sum of all computed terms (used while i < 23) */
    static seq_t sum_last22 = 0;    /* sum of the last 22 terms (used for i >= 23) */

    /* Ensure the cache is large enough for index n */
    if (n + 1 > cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 256;
        while (new_cap <= n + 1) new_cap *= 2;
        seq_t *new_cache = (seq_t *)malloc(new_cap * sizeof(seq_t));
        if (!new_cache) return 0;            /* allocation failed – unlikely */
        if (cache) {
            memcpy(new_cache, cache, cache_size * sizeof(seq_t));
            free(cache);
        }
        cache = new_cache;
        cache_cap = new_cap;
    }

    /* Compute terms up to n, if they are not already cached */
    for (idx_t i = cache_size; i <= n; ++i) {
        seq_t val;
        if (i == 0) {
            val = 1;
            totalSum = 1;                     /* a(0) contributes to totalSum */
        }
        else if (i < 23) {
            /* For the first 22 positive indices use the special
               formula coming from the numerator of the generating function */
            val = 2 + 37 * totalSum;          /* coefficient is 2 for i >= 1 */
            totalSum += val;
            if (i == 22) {
                /* After a(22) we prepare the sum of a(1)..a(22) */
                sum_last22 = totalSum - cache[0];
            }
        }
        else {
            /* Recurrence for n >= 23 */
            val = 37 * sum_last22 - 703 * cache[i - 23];
            /* Update the rolling sum for the next term (remove a_{i-22}, add a_i) */
            sum_last22 += val - cache[i - 22];
        }
        cache[i] = val;
    }
    cache_size = n + 1;

    return cache[n];
}
