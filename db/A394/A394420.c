/*    
    A394420 – Primes not on any previously drawn infinite lines in A394415.
    The sequence is generated by enumerating primes p₁, p₂, … in order.
    For a prime pᵢ (i ≥ 1) we consider all infinite lines that have
    been drawn before pᵢ is added; these lines are the ones through
    successive points (j , pⱼ) and (j+1 , pⱼ₊₁) for 1 ≤ j ≤ i–2.
    If pᵢ lies on any of those lines (i.e. it is collinear with one)
    it is excluded from the sequence, otherwise it is included.
    Regular primes 2 is never part of the output, but it is used
    to form the earlier lines.
*/

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* grow a dynamic array to at least 'needed' elements */
static void grow_array(void **ptr, size_t *cap, size_t elem_size, size_t needed)
{
    if (*cap >= needed) return;
    size_t new_cap = (*cap == 0) ? 16 : *cap * 2;
    while (new_cap < needed) new_cap <<= 1;
    *ptr = realloc(*ptr, new_cap * elem_size);
    *cap = new_cap;
}

/* return the n-th term of A394420 (1‑based index) */
seq_t a(idx_t n)
{
    if (n == 0) return 0;  /* undefined, but defensive */

    /* static state */
    static uint64_t *primes  = NULL;   /* all primes found (including 2) */
    static size_t   primes_cap = 0, primes_cnt = 0;
    static seq_t   *inc      = NULL;   /* primes that belong to the sequence */
    static size_t   inc_cap   = 0, inc_cnt  = 0;

    /* initialise once */
    if (primes == NULL) {
        grow_array((void **)&primes, &primes_cap, sizeof(uint64_t), 16);
        grow_array((void **)&inc,    &inc_cap,    sizeof(seq_t),    16);
        primes[0] = 2;
        primes_cnt = 1;
    }

    /* generate additional primes and test eligibility until we have n terms */
    while (inc_cnt < (size_t)n) {
        /* --------- find next prime ------------------------------------ */
        uint64_t cand;
        if (primes_cnt == 1) cand = 3;                 /* second prime */
        else                 cand = primes[primes_cnt-1] + 2; /* odd numbers only */

        while (true) {
            bool composite = false;
            for (size_t i = 0; i < primes_cnt; ++i) {
                uint64_t p = primes[i];
                if (p * p > cand) break;
                if (cand % p == 0) { composite = true; break; }
            }
            if (!composite) break;
            cand += 2;
        }

        /* store the new prime */
        grow_array((void **)&primes, &primes_cap, sizeof(uint64_t), primes_cnt + 1);
        primes[primes_cnt++] = cand;
        size_t curIdx = primes_cnt;   /* 1‑based index of this prime */

        /* --------- test if this prime is excluded -------------------- */
        bool excluded = false;
        if (cand == 2) {                /* 2 is never output */
            excluded = true;
        } else if (curIdx >= 4) {       /* need at least 2 earlier lines */
            for (size_t j = 0; j + 1 < curIdx - 1; ++j) {
                /* line through points j and j+1 (0‑based indexing) */
                uint64_t delta = primes[j + 1] - primes[j];
                uint64_t diff  = cand - primes[j];
                uint64_t mult  = delta * (curIdx - (j + 1));
                if (diff == mult) { excluded = true; break; }
            }
        }

        /* --------- store if not excluded ----------------------------- */
        if (!excluded) {
            grow_array((void **)&inc, &inc_cap, sizeof(seq_t), inc_cnt + 1);
            inc[inc_cnt++] = (seq_t)cand;
        }
    }

    return inc[n - 1];
}
