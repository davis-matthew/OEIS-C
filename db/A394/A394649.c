/*
 * A394649  Rectangular array, read by descending antidiagonals: the offset
 *          sum array of the infinite Fibonacci word, A003849; see Comments.
 * https://oeis.org/A394649
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, tabl
 * Formula:   a(n) = s(offset) + s(diag) where s is the Fibonacci word A003849
 *            and (offset, diag) are determined by the descending‑antidiagonal
 *            enumeration of the offset‑sum array
 * Range:     u8 n <= 77, u16 n <= 77, u32 n <= 77, u64 n <= 77, u128 n <= 77,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>

static seq_t *fib_word = NULL;
static size_t fib_len = 0;

/* Ensure fib_word contains the Fibonacci word up to (but not including)
   index len.  The Fibonacci word is generated by the morphism
   0 → 01, 1 → 0. */
static void ensure_fib_len(idx_t len)
{
    if ((idx_t)fib_len >= len)
        return;

    /* First word is just "0". */
    if (fib_len == 0) {
        fib_len = 1;
        fib_word = (seq_t *)malloc(fib_len * sizeof(seq_t));
        fib_word[0] = 0;
    }

    /* Grow until we reach the requested length. */
    while ((idx_t)fib_len < len) {
        size_t new_len = 0;
        for (size_t i = 0; i < fib_len; ++i)
            new_len += (fib_word[i] == 0) ? 2 : 1;

        seq_t *tmp = (seq_t *)malloc(new_len * sizeof(seq_t));
        size_t pos = 0;
        for (size_t i = 0; i < fib_len; ++i) {
            if (fib_word[i] == 0) {
                tmp[pos++] = 0;
                tmp[pos++] = 1;
            } else {
                tmp[pos++] = 0;
            }
        }

        free(fib_word);
        fib_word = tmp;
        fib_len = new_len;
    }
}

seq_t a(idx_t n)
{
    /* Find the diagonal d containing the nth term and its offset within it. */
    idx_t d = 0;
    idx_t cumulative = 0;
    while (1) {
        cumulative += d + 1;
        if (cumulative > n)
            break;
        ++d;
    }

    /* Total terms in all previous diagonals: d*(d+1)/2. */
    idx_t prev_total = d * (d + 1) / 2;
    idx_t offset = n - prev_total;   /* 0 <= offset <= d */

    /* Values up to index d are needed. */
    ensure_fib_len((idx_t)d + 1);

    seq_t val = fib_word[offset] + fib_word[d];
    return val;
}
