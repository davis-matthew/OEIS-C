/*
 * A128389  Emirps with only composite digits (i.e., 4, 6, 8, 9).
 * https://oeis.org/A128389
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, less, base
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 none, u64 n <= 26, u128 n <= 26,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A128389: Emirps consisting only of the composite digits 4,6,8,9.
   The sequence is generated by enumerating all numbers of increasing
   length that start and end with 9 and contain only 4/6/8/9 in the
   remaining positions, checking each for primality and that its reverse
   is a distinct prime. No simple closed formula is known. */

/* === Includes ================================================================= */
#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

/* === Utility that knows how to test primality for arbitrary seq_t ======== */
#include "../utils/is_prime_big.h"

/* === Type aliases provided by the build ------------------------------------ */
/* seq_t and idx_t are defined externally by the build system. They are not
   defined here to keep the code portable. */

/* === Forward declarations of helper functions ============================== */
static seq_t reverse_num(seq_t n);
static void ensure_cache_cap(size_t need);
static void cache_append(seq_t val);
static void generate_length(idx_t len);
static void ensure_cache_for(idx_t n);

/* === Static state for memoisation ========================================= */
static seq_t *cache = NULL;   /* array of already found emirps */
static size_t cache_len = 0;  /* number of items currently stored */
static size_t cache_cap = 0;  /* allocated capacity of cache array   */
static idx_t next_len = 2;    /* next number of digits to generate   */

/* === Reverse a seq_t by decimal digits ===================================== */
static seq_t reverse_num(seq_t n)
{
    seq_t rev = 0;
    while (n > 0) {
        rev = rev * 10 + (n % 10);
        n = n / 10;
    }
    return rev;
}

/* === Ensure cache has capacity for at least 'need' elements ================= */
static void ensure_cache_cap(size_t need)
{
    if (cache_cap >= need)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
    while (new_cap < need)
        new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp)
        exit(EXIT_FAILURE);
    cache = tmp;
    cache_cap = new_cap;
}

/* === Append a single emirp to the cache ===================================== */
static void cache_append(seq_t val)
{
    ensure_cache_cap(cache_len + 1);
    cache[cache_len++] = val;
}

/* === Generate all emirps of a given decimal length ========================== */
static void generate_length(idx_t len)
{
    if (len < 2)
        return;

    const int map[4] = {4, 6, 8, 9};
    idx_t inner = len - 2;            /* number of middle digits */
    size_t total   = 1;              /* 4^(inner) combinations   */
    for (idx_t i = 0; i < inner; ++i)
        total *= 4;

    for (size_t idx = 0; idx < total; ++idx) {
        /* Decode idx into base‑4 digits for the middle part. */
        size_t tmp = idx;
        unsigned char mid[32];  /* len-2 <= 30 for all needed n */
        for (idx_t i = 0; i < inner; ++i) {
            mid[i] = tmp & 3;
            tmp >>= 2;
        }

        /* Build the full value: 9 + middle digits + 9. */
        seq_t val = 9;
        for (idx_t i = inner; i > 0; --i) {
            val = val * 10 + map[mid[i - 1]];
        }
        val = val * 10 + 9;

        /* Test primality and emirp property. */
        if (is_prime_big(val)) {
            seq_t rev = reverse_num(val);
            if (rev != val && is_prime_big(rev))
                cache_append(val);
        }
    }
}

/* === Ensure we have at least 'n' emirps pre‑computed ======================== */
static void ensure_cache_for(idx_t n)
{
    if (cache_len >= n)
        return;
    for ( ; cache_len < n; ++next_len )
        generate_length(next_len);
}

/* === Main sequence function to be used by the test harness ---------------- */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0;                          /* undefined for index 0 */
    ensure_cache_for(n);
    return cache[n - 1];
}
