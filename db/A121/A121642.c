/*
 * A121642  Numbers with composite sum of digits and prime sum of cubes of
 *          digits.
 * https://oeis.org/A121642
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 43, u32 n <= 43, u64 n <= 43, u128 n <= 43,
 *            big any n
 * Helpers:   get_digits, is_prime_big, is_prime_small, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Numbers with composite sum of digits and prime sum of cubes of digits.
   The sequence is generated by searching natural numbers in increasing
   order; the k‑th term is returned.  */
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/get_digits.h"
#include "../utils/is_prime_small.h"
#include "../utils/is_prime_big.h"
#include "../utils/seq_realloc.h"

seq_t a(idx_t n)
{
    static seq_t *cache   = NULL;   /* cached sequence values            */
    static size_t cache_len = 0;    /* number of cached values          */
    static size_t cache_cap = 0;    /* allocated capacity               */
    static seq_t next_candidate = (seq_t)1;  /* next number to test    */

    size_t target = (size_t)n;            /* ensure we use a machine size_t   */

    /* Compute terms until we have at least "target" values. */
    while (cache_len < target) {
        /* Find the next number satisfying the property. */
        while (1) {
            uint8_t digits[64];
            size_t dlen;
            get_digits(next_candidate, digits, &dlen);

            int sum_digits = 0;
            int sum_cubes  = 0;
            for (size_t i = 0; i < dlen; ++i) {
                int d = digits[i];
                sum_digits += d;
                sum_cubes  += d * d * d;
            }

            if (sum_digits >= 4 &&
                !is_prime_small((seq_t)sum_digits) &&
                is_prime_big((seq_t)sum_cubes)) {
                break;   /* a valid candidate was found */
            }
            ++next_candidate;
        }

        /* Grow the cache if necessary. */
        if (cache_len == cache_cap) {
            size_t new_cap = cache_cap ? cache_cap * 2 : 4;
            seq_t *p = seq_realloc(cache, cache_cap, new_cap);
            if (!p) abort();         /* out‑of‑memory */
            cache     = p;
            cache_cap = new_cap;
        }

        /* Store the candidate and advance to the next number. */
        cache[cache_len++] = next_candidate;
        ++next_candidate;
    }

    return cache[target - 1];   /* a(1) corresponds to cache[0] */
}
