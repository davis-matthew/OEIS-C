/*
 * A191838  Ordered sums f+2*g, where f and g are positive Fibonacci numbers
 *          (A000045).
 * https://oeis.org/A191838
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 24, u16 n <= 64, u32 n <= 64, u64 n <= 64, u128 n <= 64,
 *            big any n
 * Helpers:   cmp_seq_t, seq_alloc_array, seq_free_array
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A191838:
   Ordered sums f + 2*g where f and g are positive Fibonacci numbers.
   The function returns the n-th term (offset 1).  The sequence is
   generated by computing all sums of the form fib[i] + 2*fib[j]
   for 1 ≤ i, j, collecting distinct values in sorted order. */

#include <stdlib.h>
#include <stdbool.h>
#include <limits.h>

/* utility functions that are part of the framework */
#include "../utils/seq_alloc_array.h"
#include "../utils/seq_free_array.h"
#include "../utils/cmp_seq_t.h"

/* maximum number of Fibonacci indices to precompute.
   It must be large enough to cover all terms that fit into
   seq_t and at least enough to generate 10000 distinct values
   for big‑int builds. */
#define MAX_FIB_LIMIT 500

seq_t a(idx_t n)
{
    static bool initialized = false;
    static seq_t *fib = NULL;
    static idx_t fib_count = 0;
    static seq_t *unique_terms = NULL;
    static size_t unique_count = 0;

    if (!initialized) {
        /* ---- build Fibonacci array ---------------------------------- */
        fib = seq_alloc_array(MAX_FIB_LIMIT + 1);   /* index 0 unused */
        fib[1] = 1;
        fib[2] = 1;
        fib_count = 2;
        for (idx_t i = 3; i <= MAX_FIB_LIMIT; ++i) {
            seq_t next = fib[i-1] + fib[i-2];
            /* stop if overflow occurred (only relevant for 64‑bit build) */
            if (next < fib[i-1]) {                /* overflow detected   */
                fib_count = i-1;
                break;
            }
            fib[i] = next;
            fib_count = i;
        }

        /* ---- generate all sums f + 2*g ----------------------------- */
        size_t total_pairs = (size_t)fib_count * (size_t)fib_count;
        seq_t *candidates = seq_alloc_array(total_pairs);
        size_t idx = 0;
        for (idx_t i = 1; i <= fib_count; ++i) {
            seq_t fi = fib[i];
            for (idx_t j = 1; j <= fib_count; ++j) {
                seq_t two_g = fib[j] << 1;      /* 2 * fib[j]          */
                candidates[idx++] = fi + two_g;
            }
        }

        /* ---- sort the sums ---------------------------------------- */
        qsort(candidates, total_pairs, sizeof(seq_t), cmp_seq_t);

        /* ---- deduplicate ------------------------------------------- */
        unique_terms = seq_alloc_array(total_pairs);
        unique_count = 0;
        for (size_t k = 0; k < total_pairs; ++k) {
            if (k == 0 || candidates[k] != candidates[k-1]) {
                unique_terms[unique_count++] = candidates[k];
            }
        }
        seq_free_array(candidates);

        initialized = true;
    }

    /* bounds check – the sequence is defined only for n >= 1
       and for which the value fits into seq_t. */
    if (n == 0 || (size_t)n > unique_count)
        return 0;   /* undefined, but not likely to be called */

    return unique_terms[n-1];
}
