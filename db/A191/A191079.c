/* Sequence A191079: primes that are not squares modulo 71.
   For each index n ≥ 1, a(n) is the nth prime p such that the Legendre
   symbol (p|71) = –1 (i.e., p is a quadratic nonresidue modulo 71).
   The sequence is generated by enumerating primes and testing each
   with Euler's criterion p^((71–1)/2) ≡ –1 (mod 71). */

#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <string.h>

#include "../utils/is_prime.h"
#include "../utils/mod_pow.h"

seq_t a(idx_t n)
{
    static seq_t *cache = NULL;   /* cached terms of the sequence            */
    static size_t cap   = 0;        /* current capacity of cache               */
    static size_t count = 0;        /* number of terms stored                 */
    static uint64_t cur  = 2;       /* current integer to test as prime       */

    if (n == 0) return 0;          /* undefined for n < 1                    */

    if ((size_t)n > count) {
        /* enlarge cache if necessary */
        if ((size_t)n > cap) {
            size_t new_cap = cap ? cap * 2 : 16;
            if (new_cap < (size_t)n) new_cap = n;
            seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            if (tmp == NULL) return 0;  /* allocation failure – return 0 */
            cache = tmp;
            cap = new_cap;
        }

        /* constants used in the Legendre test */
        const seq_t mod      = (seq_t)71;            /* modulus 71          */
        const seq_t nonres   = mod - 1;             /* 70 ≡ –1 (mod 71)    */
        const uint64_t exp   = 35;                   /* (71‑1)/2             */

        /* generate new terms until we have at least n of them */
        while (count < n) {
            /* find next prime */
            while (!is_prime(cur))
                cur++;

            /* skip the prime 71 itself (0 (mod 71)) */
            if (cur == 71ULL) {
                cur++;
                continue;
            }

            /* Euler's criterion: p^35 mod 71 */
            seq_t leg = mod_pow((seq_t)cur, exp, mod);
            if (leg == nonres) {
                cache[count++] = (seq_t)cur;  /* record quadratic nonresidue */
            }
            cur++;  /* advance to next candidate integer */
        }
    }

    return cache[n - 1];
}
