/* Sequence A191021: primes p such that (p|23)=1, i.e. p is a quadratic
   residue modulo 23 (excluding 23 itself).  Computed by sieving up to an
   automatically‑determined bound and counting qualifying primes. */

#include <stdlib.h>
#include <stdint.h>
#include <math.h>

/* For every residue r mod 23, residues23[r] is 1 iff r is a quadratic
   residue modulo 23.  The table was generated by testing x² mod 23. */
static const unsigned char residues23[23] = {
    0, /* 0  */
    1, /* 1  = 1²      */
    1, /* 2  = 5²      */
    1, /* 3  = 7²      */
    1, /* 4  = 2²      */
    0, /* 5  */
    1, /* 6  = 11²     */
    0, /* 7  */
    1, /* 8  = 10²     */
    1, /* 9  = 3²      */
    0, /*10  */
    0, /*11  */
    1, /*12  = 9²      */
    1, /*13  = 6²      */
    0, /*14  */
    0, /*15  */
    1, /*16  = 4²      */
    0, /*17  */
    1, /*18  = 8²      */
    0, /*19  */
    0, /*20  */
    0, /*21  */
    0  /*22  */
};

seq_t a(idx_t n)
{
    /* n < 1 is undefined; return 0 for safety. */
    if (n == 0) return 0;

    /* Estimate an upper bound for the nth required prime.  For n >= 6
       the known bound for the nth prime is n*(log n + log log n).
       We double it and add a small constant to be safe. */
    idx_t limit;
    if (n < 6) {
        limit = 100;
    } else {
        double dn    = (double)n;
        double logn  = log(dn);
        double logln = log(logn);
        double ub    = dn * (logn + logln) * 2.0 + 100.0;
        limit = (idx_t)ub;
    }

    for (;;) {
        /* Allocate the sieve array.  calloc gives zeroes, meaning "prime". */
        uint8_t *is_composite = (uint8_t *)calloc((size_t)limit + 1, 1);
        if (!is_composite) return 0;  /* memory failure */

        /* Classic Eratosthenes sieve. */
        for (idx_t i = 2; i * i <= limit; ++i) {
            if (!is_composite[i]) {
                for (idx_t j = i * i; j <= limit; j += i)
                    is_composite[j] = 1;
            }
        }

        /* Scan primes and count those that are quadratic residues mod 23. */
        idx_t count = 0;
        for (idx_t p = 2; p <= limit; ++p) {
            if (!is_composite[p]) {
                if (residues23[(int)(p % 23)]) {
                    ++count;
                    if (count == n) {
                        free(is_composite);
                        return (seq_t)p;
                    }
                }
            }
        }

        free(is_composite);
        /* If not enough primes were found, double the bound and try again. */
        limit <<= 1;
    }
}
