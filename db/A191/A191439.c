/*
 * A191439  Dispersion of ([n*sqrt(2)+n+1/2]), where [ ]=floor, by
 *          antidiagonals.
 * https://oeis.org/A191439
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabl
 * Formula:   a(n) = dispersion of floor(n*sqrt(2)+n+1/2) by antidiagonals
 * Range:     u8 n <= 7, u16 n <= 22, u32 n <= 58, u64 n <= 58, u128 n <= 58,
 *            big any n
 * Helpers:   floor_sqrt
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This implements the sequence A191439: a(n) = D[i, j] where D is the
   array generated by
        D[r][1] = t(r)       (t is the complement of s)
        D[r][k+1] = s(D[r][k]),
   and (i, j) are the antidiagonal coordinates of n.                         */

#include "../utils/floor_sqrt.h"   /* floor_sqrt(seq_t) for integer square root */

static seq_t round_sqrt2(seq_t val)
/*  returns round(val*sqrt(2)) using integer arithmetic only.             */
{
    /* compute floor(val*sqrt(2)) */
    unsigned __int128 val128 = (unsigned __int128)val;
    unsigned __int128 two_val_sq = val128 * val128 * 2;
    seq_t r_floor = floor_sqrt((seq_t)two_val_sq);

    /* decide whether to add 1 or not:
        val*sqrt(2) < r_floor + 0.5    -> r = r_floor
        otherwise                        r = r_floor + 1          */
    unsigned __int128 lhs = 8 * val128 * val128;          /* 8*val^2   */
    unsigned __int128 rhs = (unsigned __int128)(2 * r_floor + 1);
    rhs = rhs * rhs;                                     /* (2r+1)^2  */

    return (lhs < rhs) ? r_floor : r_floor + 1;
}

static seq_t s_of_value(seq_t val)
/*  returns s(val) = floor(val*sqrt(2)+val+1/2) = val + round(val*sqrt(2)). */
{
    seq_t r = round_sqrt2(val);
    return val + r;
}

static seq_t t_of_index(idx_t idx)
/*  returns the idx‑th element of the complement of s.                      */
{
    idx_t cur = 1;          /* natural number being examined       */
    idx_t s_idx = 1;        /* current index in the sequence s     */
    seq_t s_val = s_of_value((seq_t)s_idx);   /* s(1) */

    while (idx > 0) {
        if ((seq_t)cur == s_val) {  /* cur is in s, skip it */
            ++cur;
            ++s_idx;
            s_val = s_of_value((seq_t)s_idx);
        } else {                    /* cur is in t, count it    */
            --idx;
            if (idx == 0)
                return (seq_t)cur;
            ++cur;
        }
    }
    return (seq_t)cur;      /* unreachable, for the compiler */
}

seq_t a(idx_t n)
/*  main routine:  returns the n‑th term of A191439.                         */
{
    /* --- locate antidiagonal coordinates (i, j) for position n --- */
    idx_t d = 1;
    idx_t sum = 1;
    while (sum < n) {
        ++d;
        sum += d;
    }
    unsigned __int128 sb128 = (unsigned __int128)(d - 1) * d / 2;
    idx_t sum_before = (idx_t)sb128;
    idx_t offset = n - sum_before - 1;          /* 0‑based offset on diagonal */
    idx_t i = offset + 1;                       /* row index (t-index)       */
    idx_t j = d - offset;                       /* column index in the row   */

    /* --- start from t(i) and apply s j‑1 times --- */
    seq_t val = t_of_index(i);
    for (idx_t k = 1; k < j; ++k)
        val = s_of_value(val);

    return val;
}
