/*
 * A191907  Square array read by antidiagonals up: T(n,k) = -(n-1) if n
 *          divides k, else 1.
 * https://oeis.org/A191907
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  sign, tabl
 * Formula:   not stated
 * Range:     i8 n <= 136, i16 n <= 136, i32 n <= 136, i64 n <= 136,
 *            i128 n <= 136, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes sequence A191907.
   The sequence is generated by reading the array T(n,k) along
   antidiagonals in a bottom‑to‑top order, where
          T(n,k) = -(n-1) if n divides k, otherwise 1.
   The mapping from index n to coordinates (row, col) is:
          D = minimal integer with D*(D-1)/2 >= n
          s = n - (D-1)*(D-2)/2   (1 <= s < D)
          row = D - s             (1 <= row < D)
          col = s
   Then a(n) = T(row, col) */

/* Header includes */
#include <stdint.h>

/* -- Helper: compute minimal D such that D*(D-1)/2 >= n */
static idx_t find_diagonal(idx_t n)
{
    idx_t low = 1;
    /* High can be set to 2*n; safe for n>=1 */
    idx_t high = n > 1 ? 2 * n : 2;
    while (low < high) {
        idx_t mid = low + (high - low) / 2;
        /* Compute mid*(mid-1)/2 using 128-bit to avoid overflow */
        __int128 t = (__int128)mid * (mid - 1) / 2;
        if (t >= n)
            high = mid;
        else
            low = mid + 1;
    }
    return low;
}

/* Main sequence function */
seq_t a(idx_t n)
{
    if (n == 0) /* Not part of the sequence (offset 1), but keep defined */
        return 0;

    /* 1. Find diagonal D */
    idx_t D = find_diagonal(n);

    /* 2. Compute position within that diagonal */
    __int128 prev_count = (__int128)(D - 1) * (D - 2) / 2;
    idx_t s = (idx_t)(n - prev_count);          /* 1 <= s < D */

    /* 3. Coordinates (row, col) */
    idx_t row = D - s; /* 1 <= row < D */
    idx_t col = s;     /* 1 <= col < D */

    /* 4. Determine the value at T(row, col) */
    seq_t result;
    if (col % row == 0) /* row divides col */
        result = -(seq_t)(row - 1);
    else
        result = 1;

    return result;
}
