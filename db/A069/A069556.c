/*
 * A069556  Primes in which the k-th digit (counting from the right) is either
 *          a nonzero multiple of k or a divisor of k; furthermore the digit 1
 *          is allowed only when k has no other divisors < 10.
 * https://oeis.org/A069556
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 13, u16 n <= 50, u32 n <= 50, u64 n <= 50, u128 n <= 50,
 *            big any n
 * Helpers:   seq_alloc, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation of sequence A069556
   A(n) = the n-th prime p such that for every digit position k
   counted from the right (k = 1 for the units digit)
   the decimal digit d satisfies: d ≠ 0 and
   (d % k == 0)  or  (k % d == 0,  with the extra rule that d == 1 is
   permitted only if k has no other divisor < 10).
   The sequence is generated by an incremental prime search that
   stores qualifying primes in a static array. */

#include <stddef.h>
#include <stdbool.h>
#include <stdint.h>

#include "../utils/seq_alloc.h"
#include "../utils/seq_realloc.h"

/* Static storage for all primes encountered and for qualifying primes.  */
static seq_t *primes          = NULL;  /* all primes found so far   */
static size_t prime_count     = 0;
static size_t prime_cap       = 0;

static seq_t *qual_primes     = NULL;  /* primes that satisfy the rule */
static size_t qual_count      = 0;
static size_t qual_cap        = 0;

/* Last integer that was tested for primality (may be any integer >= 0). */
static uint64_t last_checked  = 0;

/* Append a value to a dynamic seq_t array, growing it if necessary. */
static void append_array(seq_t **arr, size_t *cnt, size_t *cap, seq_t val)
{
    if (*cnt >= *cap) {
        size_t new_cap = (*cap > 0) ? (*cap << 1) : 4;
        if (*arr == NULL) {
            *arr = seq_alloc(new_cap);
        } else {
            *arr = seq_realloc(*arr, *cap, new_cap);
        }
        *cap = new_cap;
    }
    (*arr)[*cnt] = val;
    ++(*cnt);
}

/* Test whether a prime satisfies the digit rule. */
static bool qualifies(seq_t p)
{
    seq_t num = p;
    seq_t k   = 1;   /* position from the right, 1‑based */

    while (num > 0) {
        seq_t d = num % 10;

        if (d == 0) return false;  /* zero digit never allowed */

        bool ok = false;

        if (d % k == 0) {
            /* non‑zero multiple of k – OK */
            ok = true;
        } else if (k % d == 0) {
            /* d divides k – OK except for special rule on d == 1 */
            if (d == 1) {
                /* digit 1 allowed only if k has no divisor < 10 other
                   than 1 itself.  */
                for (seq_t div = 2; div <= 9; ++div) {
                    if (k % div == 0) return false;
                }
            }
            ok = true;
        }

        if (!ok) return false;

        num = num / 10;
        ++k;
    }
    return true;
}

/* Deterministic trial division primality test using primes we have already
   found.  Works for any seq_t that supports the usual arithmetic. */
static bool is_prime_seq(seq_t n)
{
    if (n < 2) return false;

    for (size_t i = 0; i < prime_count; ++i) {
        seq_t p = primes[i];
        if (p > n / p) break;          /* p*p > n  */
        if (n % p == 0) return false;
    }
    return true;
}

/* Grow the list of qualifying primes until it contains at least `need`
   terms.  New primes are found by simple incremental search. */
static void ensure_terms(idx_t need)
{
    while (qual_count < (size_t)need) {
        /* Candidate integer to test next. */
        uint64_t cand = last_checked + 1;
        if (cand < 2) cand = 2;
        if (cand > 2 && (cand & 1U) == 0) ++cand;  /* skip even numbers */

        /* Check primality and update arrays. */
        if (is_prime_seq(cand)) {
            append_array(&primes, &prime_count, &prime_cap, cand);

            if (qualifies(cand)) {
                append_array(&qual_primes, &qual_count, &qual_cap, cand);
            }
        }

        last_checked = cand;
    }
}

/* Public sequence function.  Returns the n‑th qualifying prime. */
seq_t a(idx_t n)
{
    if (n <= 0) return 0;          /* Outside the offset, value irrelevant. */
    ensure_terms(n);
    return qual_primes[n - 1];
}
