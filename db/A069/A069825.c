/*
 * A069825  Numbers k such that there is no x < k such that sigma(x) = phi(k).
 * https://oeis.org/A069825
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 63, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 74 terms through n = 9617 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A069825: Numbers k such that there is no x < k with sigma(x)=phi(k) */
/* The sequence is generated by a search using divisor sum and Euler's totient. */

#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include "../utils/mem.h"

/* Simple sieve to compute primes up to 'n' (used for totient) */
static void compute_primes(size_t n, int **primes_out, size_t *cnt_out)
{
    size_t i, j;
    int *isPrime = (int*)malloc((n + 1) * sizeof(int));
    memset(isPrime, 1, (n + 1) * sizeof(int));
    isPrime[0] = isPrime[1] = 0;
    for (i = 2; i * i <= n; ++i)
        if (isPrime[i])
            for (j = i * i; j <= n; j += i)
                isPrime[j] = 0;
    *cnt_out = 0;
    for (i = 2; i <= n; ++i)
        if (isPrime[i])
            (*cnt_out)++;
    *primes_out = (int*)malloc((*cnt_out) * sizeof(int));
    size_t k = 0;
    for (i = 2; i <= n; ++i)
        if (isPrime[i])
            (*primes_out)[k++] = (int)i;
    free(isPrime);
}

/* Set bit at index 'idx' */
static inline void set_bit(uint64_t *bits, size_t idx)
{
    bits[idx >> 6] |= (1ULL << (idx & 63));
}

/* Test if bit at index 'idx' is set */
static inline int test_bit(const uint64_t *bits, size_t idx)
{
    return (bits[idx >> 6] >> (idx & 63)) & 1ULL;
}

typedef uint64_t idx_t;   /* assumed by the build for indices */
/* seq_t is defined by the build (8, 16, 32, 64 or 128 bits). */

static uint64_t *phi = NULL;          /* totient values */
static uint64_t *sigma = NULL;        /* sum of divisors */
static uint64_t *seenBits = NULL;     /* bitset of seen sigma values */
static size_t seenBitsSize = 0;       /* number of uint64_t words in seenBits */
static size_t seq_capacity = 0;       /* allocated size for seq array */
static seq_t *seq = NULL;             /* generated sequence values */
static size_t seq_count = 0;          /* number of elements stored */
static size_t currentLimit = 0;       /* current maximum bound */

/* Compute totient values up to limit */
static void compute_phi(size_t limit)
{
    size_t i;
    for (i = 0; i <= limit; ++i)
        phi[i] = i;
    int *primes = NULL;
    size_t pcount = 0;
    compute_primes(limit, &primes, &pcount);
    for (i = 0; i < pcount; ++i) {
        int p = primes[i];
        for (size_t j = p; j <= limit; j += p)
            phi[j] = (phi[j] / (uintptr_t)p) * ((uintptr_t)p - 1);
    }
    free(primes);
}

/* Compute sum of divisors up to limit */
static void compute_sigma(size_t limit)
{
    size_t i, j;
    for (i = 0; i <= limit; ++i)
        sigma[i] = 0;
    for (i = 1; i <= limit; ++i)
        for (j = i; j <= limit; j += i)
            sigma[j] += i;
}

/* Rebuild everything up to 'limit' */
static void rebuild(size_t limit)
{
    /* Free previous data */
    if (phi) free(phi);
    if (sigma) free(sigma);
    if (seenBits) free(seenBits);
    if (seq) mem_free(seq);
    phi = NULL;
    sigma = NULL;
    seenBits = NULL;
    seq = NULL;
    seq_count = 0;
    seq_capacity = 0;
    currentLimit = limit;

    phi = (uint64_t*)malloc((limit + 1) * sizeof(uint64_t));
    sigma = (uint64_t*)malloc((limit + 1) * sizeof(uint64_t));

    compute_phi(limit);
    compute_sigma(limit);

    /* Find maximum sigma value to size the bitset */
    uint64_t maxSigma = 0;
    for (size_t i = 1; i <= limit; ++i)
        if (sigma[i] > maxSigma)
            maxSigma = sigma[i];

    seenBitsSize = (maxSigma >> 6) + 1;
    seenBits = (uint64_t*)calloc(seenBitsSize, sizeof(uint64_t));

    seq_capacity = limit; /* at most 'limit' sequence values */
    seq = mem_new(seq_t, seq_capacity);

    for (size_t k = 1; k <= limit; ++k) {
        uint64_t phiVal = phi[k];
        if (!test_bit(seenBits, (size_t)phiVal))
            seq[seq_count++] = (seq_t)k;
        set_bit(seenBits, (size_t)sigma[k]);
    }
}

/* Ensure enough terms have been computed for index 'n' */
static void ensure(idx_t n)
{
    if (seq_count >= (size_t)n)
        return;
    /* Increase limit geometrically until we have enough terms */
    size_t limit = currentLimit ? currentLimit : 8192;
    while (seq_count < (size_t)n) {
        if (limit < (n * 10))
            limit = n * 10;
        limit <<= 1; /* double the limit */
        rebuild(limit);
    }
}

/* Public function */
seq_t a(idx_t n)
{
    if (n < 1) return 0; /* undefined for n < 1 */
    ensure(n);
    return seq[n - 1];
}
