/* Non-squares modulo 98: a(n) is the nth positive integer that is not
   a quadratic residue modulo 98.  The sequence is generated by a simple
   sieve of the 98 residue classes. */

#include <stdbool.h>

seq_t a(idx_t n)
{
    /* First compute the set of quadratic residues modulo 98.
       We do this only once per program execution. */
    static bool residue[98];
    static bool initialized = false;
    if (!initialized) {
        /* mark all residues as false */
        for (idx_t i = 0; i < 98; ++i)
            residue[i] = false;
        /* compute residues of x^2 mod 98 for x in [0,97] */
        for (idx_t x = 0; x < 98; ++x) {
            idx_t r = (x * x) % 98;
            residue[r] = true;
        }
        initialized = true;
    }

    idx_t count = 0;
    idx_t x     = 1;
    while (1) {
        idx_t r = x % 98;
        if (!residue[r]) {
            ++count;
            if (count == n)
                return (seq_t)x;
        }
        ++x;
    }
}
