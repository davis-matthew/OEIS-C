/* Sequence A227062: numbers whose base‑5 digit sum equals 5
   Generated by recursive enumeration of base‑5 digits with sum 5
   and ascending numeric value. */
#include <stddef.h>
#include <stdbool.h>
#include "../utils/alloc_seq.h"
#include "../utils/grow_seq.h"

/* Static storage for the generated sequence */
static seq_t *seq_arr = NULL;
static size_t seq_cap = 0;
static size_t seq_len = 0;
static int next_len = 2;   /* next base‑5 length to generate */

/* Recursive helper that generates all base‑5 numbers of a given length
   whose digits sum to 'sum_left'.  'pos' counts the position already set
   (0 = most significant).  'val' holds the decimal value of digits
   processed so far.  The function appends new values to 'seq_arr'. */
static void generate_len_rec(int pos, int len, int sum_left, seq_t val)
{
    /* prune impossible branches */
    if (sum_left < 0 || sum_left > (len - pos) * 4)
        return;

    if (pos == len) {
        if (sum_left == 0) {
            if (seq_len >= seq_cap)
                grow_seq(&seq_arr, &seq_cap, seq_len + 1);
            seq_arr[seq_len++] = val;
        }
        return;
    }

    int d_min = (pos == 0) ? 1 : 0;
    for (int d = d_min; d <= 4 && d <= sum_left; ++d) {
        generate_len_rec(pos + 1, len, sum_left - d, val * 5 + d);
    }
}

/* Main function required by the build system */
seq_t a(idx_t n)
{
    if (seq_arr == NULL) {   /* one-time allocation */
        seq_cap = 32;
        seq_arr = alloc_seq(seq_cap);
    }

    /* Generate further terms until we have at least 'n' of them */
    while (seq_len < n) {
        generate_len_rec(0, next_len, 5, 0);
        next_len++;   /* move to longer numbers next time */
    }

    return seq_arr[n - 1];
}
