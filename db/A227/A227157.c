/*
 * A227157  Numbers k whose factorial base representation A007623(k) does not
 *          contain any nonleading zeros.
 * https://oeis.org/A227157
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 57, u16 n <= 8793, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implementation: a(n) = the n-th positive integer whose factorial‑base
 * representation contains no non‑leading zero digits.  The sequence is
 * generated by enumerating, for each factorial‑base length m, all
 * combinations of digits 1…m (most significant digit first).  The
 * minimal m such that Σ_{k=1}^{m} k! ≥ n is used; all values for smaller
 * lengths are already ≺ any value of length m, so the full list up to n can
 * be built incrementally.  The resulting array is sorted by construction,
 * so a(n) is simply the (n‑1)‑th element. */

#include <stdlib.h>
#include <stdint.h>

/* factorial array: fac[i] = i!  (as seq_t) */
static seq_t fac[25];
static int fac_initialized = 0;

/* storage for generated sequence */
static seq_t *seq = NULL;
static size_t seq_cap = 0;     /* allocated capacity */
static size_t seq_len = 0;     /* number of stored elements */
static idx_t max_len_generated = 0;   /* longest factorial–length generated */

/* ---------- helpers ---------- */

/* ensure we have enough capacity for 'need' elements */
static void ensure_capacity(size_t need)
{
    if (need <= seq_cap) return;
    /* double size until we reach needed capacity */
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    while (new_cap < need) new_cap <<= 1;
    seq = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
    seq_cap = new_cap;
}

/* recursive enumeration of all numbers with factorial‑base length 'len'.
 * 'pos' counts down from 'len' to 0; 'val' accumulates the value so far.
 */
static void gen_recursive(idx_t pos, seq_t val)
{
    if (pos == 0) {
        ensure_capacity(seq_len + 1);
        seq[seq_len++] = val;
        return;
    }
    for (idx_t d = 1; d <= pos; ++d) {
        /* add contribution of digit d at factorial position 'pos' */
        seq_t add = (seq_t)d * fac[pos];
        gen_recursive(pos - 1, val + add);
    }
}

/* generate all numbers for factorial‑base length 'len' */
static void generate_length(idx_t len)
{
    gen_recursive(len, 0);
}

/* ---------- main function ---------- */

seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined behavior for n<1, return 0 */

    /* initialize factorial table once (enough up to length 20) */
    if (!fac_initialized) {
        fac[0] = 1;
        for (int i = 1; i < 21; ++i) fac[i] = fac[i - 1] * (seq_t)i;
        fac_initialized = 1;
    }

    /* generate until we have at least n elements */
    while (seq_len < (size_t)n) {
        ++max_len_generated;
        generate_length(max_len_generated);
    }

    return seq[n - 1];
}
