/* Sequence A118458: lengths of partitions into distinct parts in Abramowitz and Stegun order.
   The sequence is generated by enumerating all partitions of each integer n ≥ 0 into distinct
   parts, sorted in decreasing lexicographic order, and outputting the length of each partition.
   The values are stored in a cache so that calls to a(idx_t) with arbitrary n are answered
   in constant time after the necessary partitions have been generated. */
#include <stdlib.h>

static seq_t *cache = NULL;          /* cache of sequence values */
static size_t cache_cap = 0;         /* current allocated capacity */
static size_t cache_len = 0;         /* number of values stored */
static idx_t next_n = 0;             /* next integer for which partitions are generated */

/* Append a value to the cache, growing its capacity if necessary */
static void append_len(seq_t val) {
    if (cache_len == cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 16;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) abort();          /* allocation failed */
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

/* Recursive generation of distinct partitions of 'remaining' with parts strictly less than 'max_part'.
   For each complete partition, its length (cur_len) is appended to the cache. */
static void generate_rec(idx_t remaining, idx_t max_part, idx_t cur_len) {
    if (remaining == 0) {
        append_len((seq_t)cur_len);
        return;
    }
    idx_t limit = (remaining < max_part ? remaining : max_part);
    for (idx_t part = limit; part >= 1; part--) {
        generate_rec(remaining - part, part - 1, cur_len + 1);
    }
}

/* Generate partitions for the current value of next_n and prepare for the next integer. */
static void generate_next_n(void) {
    generate_rec(next_n, next_n, 0);
    next_n++;
}

/* Main sequence function required by the OEIS test harness. */
seq_t a(idx_t n) {
    if (n < cache_len)
        return cache[n];

    while (cache_len <= (size_t)n) {
        generate_next_n();
    }
    return cache[n];
}
