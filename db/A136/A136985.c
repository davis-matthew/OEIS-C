/*
 * A136985  Numbers k such that k and k^2 use only the digits 1, 2, 3 and 9.
 * https://oeis.org/A136985
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn, more
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 5, u32 n <= 5, u64 n <= 5, u128 n <= 5,
 *            big any n
 * Helpers:   seq_alloc_new_array, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: a(n) = numbers k such that the base‑10 digits of k and k^2
   are all in the set {1,2,3,9}.  The values are generated by brute‑force
   search over all numbers built from these digits, tested in increasing
   numeric order.  The implementation keeps a memoised cache so calls
   return in O(1) after the required terms have been enumerated. */

#include <stdbool.h>
#include <stddef.h>

/* Utility functions to allocate and resize arrays of seq_t objects.
   They are supplied by the build system. */
#include "../utils/seq_alloc_new_array.h"
#include "../utils/seq_realloc.h"

static const int DIGITS[4] = {1, 2, 3, 9};

/* Cache of already found terms */
static seq_t *cache    = NULL;
static idx_t  cache_len   = 0;
static idx_t  cache_cap   = 0;
static idx_t  max_len_gen = 0;   /* length of numbers that have been generated */

/* Check whether all decimal digits of x are in {1,2,3,9}.  The caller
   guarantees that x>0. */
static bool allowed_digits(seq_t x)
{
    /* Only used to test the square of a candidate. */
    seq_t sq = x * x;
    while (sq != 0) {
        int d = (int)(sq % 10);
        if (d != 1 && d != 2 && d != 3 && d != 9)
            return false;
        sq /= 10;
    }
    return true;
}

/* Ensure that the cache has space for at least 'need' elements. */
static void ensure_capacity(idx_t need)
{
    if (cache_cap >= need)
        return;
    idx_t new_cap = cache_cap ? cache_cap * 2 : 64;
    while (new_cap < need)
        new_cap *= 2;
    if (cache_cap == 0)
        cache = seq_alloc_new_array((size_t)new_cap);
    else
        cache = seq_realloc(cache, cache_cap, new_cap);
    cache_cap = new_cap;
}

/* Recursive generator of all numbers with 'len' decimal digits composed
   only of the allowed digits.  Whenever a candidate's square passes the
   digit test, it is stored in the cache. */
static void generate_len(idx_t len, idx_t pos, seq_t value)
{
    if (pos == len) {
        if (allowed_digits(value)) {
            ensure_capacity(cache_len + 1);
            cache[cache_len++] = value;
        }
        return;
    }
    for (int i = 0; i < 4; ++i) {
        generate_len(len, pos + 1, value * 10 + DIGITS[i]);
    }
}

/* Ensure that we have at least 'n' terms in the cache. */
static void make_terms(idx_t n)
{
    while (cache_len < n) {
        /* Generate numbers of the next increasing length.  The sequence is
           strictly increasing in numeric order for each fixed length,
           and longer lengths are always larger. */
        max_len_gen++;
        generate_len(max_len_gen, 0, 0);
    }
}

/* Main sequence function required by the test harness. */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0;          /* undefined offset; harmless */
    make_terms(n);
    return cache[n - 1];
}
