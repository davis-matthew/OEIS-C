/*
 * A136009  Primes p for which the least pentagonal number q=n(3n+/-1)/2 which
 *          makes p+q prime satisfies 2q > p.
 * https://oeis.org/A136009
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  more, nonn
 * Formula:   not stated
 * Range:     u8 n <= 9, u16 n <= 12, u32 n <= 12, u64 n <= 12, u128 n <= 12,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
 * A136009: primes p such that the least generalized pentagonal number 
 * q = n(3n±1)/2 for which p+q is prime satisfies 2q > p.
 * The function a(n) returns the n-th such prime (offset 1).
 * The sequence is generated by searching primes sequentially and
 * keeping a cache of the primes that satisfy the condition.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"

static seq_t     *cache = NULL;   /* cached terms */
static size_t    cache_len = 0;    /* number of cached terms   */
static size_t    cache_cap = 0;    /* allocated capacity       */
static uint64_t  last_checked = 1;/* last integer examined    */

/* Ensure the cache has room for at least 'need' elements. */
static void
ensure_cache_cap(size_t need)
{
    if (need <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap : 4;
    while (new_cap < need)
        new_cap <<= 1;
    seq_t *new_arr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!new_arr)
        abort();                      /* allocation failed */
    cache = new_arr;
    cache_cap = new_cap;
}

/* Find the least generalized pentagonal number q such that p+q is prime.
 * Returns true and stores the q in *q_val.  Assumes p > 0. */
static bool
find_min_q(seq_t p, seq_t *q_val)
{
    for (idx_t m = 1; ; ++m)
    {
        seq_t m_seq = (seq_t)m;

        /* q1 = m(3m-1)/2  (n = m) */
        seq_t g1 = m_seq * ((seq_t)3 * m_seq - (seq_t)1);
        g1 /= (seq_t)2;
        if (is_prime_big(p + g1))
        {
            *q_val = g1;
            return true;
        }

        /* q2 = m(3m+1)/2  (n = -m) */
        seq_t g2 = m_seq * ((seq_t)3 * m_seq + (seq_t)1);
        g2 /= (seq_t)2;
        if (is_prime_big(p + g2))
        {
            *q_val = g2;
            return true;
        }
    }
    /* Unreachable, but keeps the compiler happy. */
    return false;
}

/* Generate primes and fill the cache up to 'target_len' terms. */
static void
prepare_up_to(size_t target_len)
{
    if (cache_len >= target_len)
        return;

    /* Start searching from the integer after the last examined number. */
    uint64_t cand = last_checked + 1;
    if (cand < 2)
        cand = 2;
    if (cand == 2)
        cand = 3;                 /* next candidate after 2 is 3 */
    else if ((cand & 1) == 0)     /* ensure odd if >2 */
        cand++;

    while (cache_len < target_len)
    {
        /* Only odd numbers are tested; 2 was handled above. */
        if (is_prime_big((seq_t)cand))
        {
            seq_t q;
            if (find_min_q((seq_t)cand, &q))
            {
                /* 2*q > p  ->  q + q > cand   */
                if (q + q > (seq_t)cand)
                {
                    ensure_cache_cap(cache_len + 1);
                    cache[cache_len++] = (seq_t)cand;
                }
            }
        }

        last_checked = cand;          /* record what we just examined */
        cand += 2;                    /* next odd candidate            */
    }
}

/* Public function implementing the OEIS sequence. */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;              /* undefined below offset */

    prepare_up_to((size_t)n);
    return cache[n - 1];
}
