/*
 * A271981  Primes p such that p + 40 is also prime.
 * https://oeis.org/A271981
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 21, u16 n <= 1168, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   build_primes, is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: primes p such that p + 40 is also prime. */
/* This implementation builds a sieve up to a limit, collects all qualifying
   primes, and expands that limit until the requested index n is available
   (memoised across calls). */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

/* Utility functions (provided by the test harness). */
#include "../utils/build_primes.h"  /* void build_primes(idx_t limit, idx_t **out, size_t *cnt); */
#include "../utils/is_prime.h"      /* bool is_prime(idx_t n); */

/* Static storage for the qualified primes (as idx_t). */
static idx_t *qual_primes   = NULL;
static size_t qual_len      = 0;
static size_t qual_cap      = 0;

/* Current sieve limit (all primes ≤ limit are known). */
static idx_t sieve_limit = 0;

/* Temporary storage for the list of primes generated by build_primes. */
static idx_t *prime_list = NULL;
static size_t prime_cnt  = 0;

/* Dynamically append a qualifying prime. */
static void add_qual(idx_t p)
{
    if (qual_len == qual_cap) {
        size_t new_cap = qual_cap ? qual_cap * 2 : 16;
        idx_t *tmp = (idx_t *)realloc(qual_primes, new_cap * sizeof(idx_t));
        if (!tmp) abort();
        qual_primes = tmp;
        qual_cap    = new_cap;
    }
    qual_primes[qual_len++] = p;
}

/* Rebuild the sieve up to 'lim' (inclusive) and recompute all qualifying primes. */
static void rebuild_sieve(idx_t lim)
{
    /* Free previous data. */
    free(prime_list);
    prime_list = NULL;
    prime_cnt  = 0;

    /* Build all primes up to lim + 40 so we can test p + 40. */
    build_primes(lim + 40, &prime_list, &prime_cnt);

    /* Reset the list of qualifying primes. */
    free(qual_primes);
    qual_primes = NULL;
    qual_len    = 0;
    qual_cap    = 0;

    /* Scan the prime list and collect qualifying primes. */
    for (size_t i = 0; i < prime_cnt; ++i) {
        idx_t p = prime_list[i];
        if (p > lim - 40) break;            /* primes are sorted */
        if (is_prime(p + 40)) add_qual(p);
    }
    sieve_limit = lim;
}

/* Ensure that at least n qualifying primes are available. */
static void ensure_n_terms(idx_t n)
{
    if (qual_len >= n) return;

    /* Start with a modest initial limit if none set. */
    if (sieve_limit == 0) rebuild_sieve(2000);

    idx_t lim = sieve_limit;
    while (qual_len < n) {
        lim *= 2;
        rebuild_sieve(lim);
    }
}

/* Main sequence function.  Undefined for n==0, but returns 0 politely. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;
    ensure_n_terms(n);
    return (seq_t)qual_primes[n - 1];
}
