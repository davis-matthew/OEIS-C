/*
 * A242550  Prime numbers that will become composite after removing any group
 *          of initial digits.
 * https://oeis.org/A242550
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 10, u16 n <= 326, u32 n <= 367, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   digit_len, is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A242550
   Formula: a(n) = n-th prime p with the property: for every proper suffix s of the decimal
   representation of p, s is composite (i.e. s > 1 and not prime).
   The sequence is generated by testing primes in increasing order and keeping those
   that satisfy the suffix‑composite condition. */

#include <stdlib.h>
#include <stdbool.h>
/* utilities */
#include "../utils/is_prime_big.h"   /* bool is_prime_big(seq_t n) */
#include "../utils/digit_len.h"      /* int digit_len(seq_t x) */

/* static cache for previously computed terms */
static seq_t *terms = NULL;   /* dynamically grown array of terms               */
static idx_t   terms_cnt = 0; /* number of terms stored                         */
static idx_t   last_cand = 10;/* next integer to test (last tested +1)         */
static idx_t   cap = 0;       /* current capacity of terms                      */

/* ensure terms_cnt >= n, computing as required */
static void ensure_terms(idx_t n)
{
    while (terms_cnt < n)
    {
        seq_t p = (seq_t)last_cand;

        /* test primality of candidate */
        if (is_prime_big(p))
        {
            int d = digit_len(p);
            if (d >= 2)   /* ignore 1‑digit primes */
            {
                seq_t pow10k = (seq_t)10;  /* 10^1 */
                bool ok = true;

                for (int k = 1; k < d && ok; ++k)
                {
                    seq_t suffix = p % pow10k;
                    if (suffix <= (seq_t)1 || is_prime_big(suffix))
                    {
                        ok = false;
                        break;
                    }
                    pow10k *= (seq_t)10;
                }

                if (ok)
                {
                    /* enlarge storage if needed */
                    if (terms_cnt == cap)
                    {
                        idx_t new_cap = cap ? cap * 2 : 16;
                        seq_t *tmp = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
                        if (!tmp) abort();          /* memory allocation failure */
                        terms = tmp;
                        cap   = new_cap;
                    }
                    terms[terms_cnt++] = p;
                }
            }
        }

        ++last_cand;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* offset is 1, but callers may ask for 0 */
    ensure_terms(n);
    return terms[n - 1];
}
