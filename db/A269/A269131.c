/*
 * A269131  Composite numbers whose largest prime factor is less than its
 *          second-largest prime factor's square, counting with multiplicity
 *          so that the factors of 18 are 2, 3, 3.
 * https://oeis.org/A269131
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 95, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   build_primes_upto
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements OEIS sequence A269131.
   The function a(n) returns the n‑th composite integer
   whose largest prime factor p satisfies p  <  q²,
   where q is the second‑largest prime factor (counted with
   multiplicity).  The sequence is generated by testing the integers
   in increasing order and caching the ones that meet the condition.  */

/* Standard headers */
#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>

/* Build a list of primes up to ‘limit’.  The returned array must be
   freed with free() when no longer needed.  */
#include "../utils/build_primes_upto.h"

/* ------------------------------------------------------------------ */
/* Local helper: integer square‑root, floor.  Works for uint64_t.       */
static inline uint64_t isqrt_u64(uint64_t n)
{
    uint64_t lo = 0, hi = n, mid, sqrt;
    while (lo <= hi) {
        mid = lo + ((hi - lo) >> 1);
        if (mid > 0 && mid > n / mid) {   /* mid*mid > n */
            hi = mid - 1;
        } else {
            lo = mid + 1;
            sqrt = mid;
        }
    }
    return sqrt;
}

/* ------------------------------------------------------------------ */
/* Static state for caching the sequence and primes.                */
static seq_t *cache        = NULL;
static size_t cache_len    = 0;
static size_t cache_cap    = 0;

static uint64_t cur_val    = 2;          /* last integer tested   */
static uint64_t *primes    = NULL;      /* primes up to sqrt(cur)*/
static size_t primes_cnt   = 0;          /* number of primes      */

/* ------------------------------------------------------------------ */
/* Test whether x satisfies the A269131 condition.  */
static bool good_candidate(uint64_t x)
{
    if (x < 4) return false;            /* not composite */

    uint64_t tmp = x;
    uint64_t largest = 0, second = 0;
    size_t factor_cnt = 0;

    /* Ensure we have primes up to sqrt(x).  */
    uint64_t limit = isqrt_u64(x);
    if (primes_cnt == 0 || primes[primes_cnt - 1] < limit) {
        /* Build a new prime list.  Free the old one if any.  */
        if (primes) free(primes);
        build_primes_upto(limit, &primes, &primes_cnt);
    }

    for (size_t i = 0; i < primes_cnt; ++i) {
        uint64_t p = primes[i];
        if (p > limit) break;
        if (tmp % p != 0) continue;
        /* Factor out all occurrences of p.  */
        while (tmp % p == 0) {
            tmp /= p;
            ++factor_cnt;
            if (p > largest) {
                second = largest;
                largest = p;
            } else if (p > second) {
                second = p;
            }
        }
        limit = isqrt_u64(tmp);          /* update limit after division */
    }

    if (tmp > 1) {                       /* remaining prime factor */
        ++factor_cnt;
        uint64_t p = tmp;
        if (p > largest) {
            second = largest;
            largest = p;
        } else if (p > second) {
            second = p;
        }
    }

    if (factor_cnt < 2) return false;    /* prime */
    /* Condition: largest < second² .  Use uint64_t to avoid overflow. */
    return largest < second * second;
}

/* ------------------------------------------------------------------ */
/* Expand the cache until it contains at least n elements.           */
static void ensure_cache(idx_t n)
{
    if ((idx_t)cache_len >= n) return;

    if (!cache) {
        cache_cap = 1024;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache) abort();
    }
    if (cache_len < (size_t)n && cache_cap < (size_t)n) {
        size_t new_cap = cache_cap;
        while (new_cap < (size_t)n) new_cap <<= 1;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) { free(cache); abort(); }
        cache = tmp;
        cache_cap = new_cap;
    }

    while (cache_len < (size_t)n) {
        do { ++cur_val; } while (!good_candidate(cur_val));
        cache[cache_len++] = (seq_t)cur_val;
    }
}

/* ------------------------------------------------------------------ */
/* Public function for the OEIS sequence.                             */
seq_t a(idx_t n)
{
    ensure_cache(n);
    return cache[(size_t)n - 1];
}
