/*
 * A302696  Numbers whose prime indices (with repetition) are pairwise
 *          coprime. Nonprime Heinz numbers of integer partitions with
 *          pairwise coprime parts.
 * https://oeis.org/A302696
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 123, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Sequence A302696: Numbers whose prime indices (with repetition) are pairwise coprime.
    The sequence is generated by testing every integer in ascending order, keeping a
    small cache of already computed terms.  For each candidate integer we factorize it
    using a dynamic SPF (smallest prime factor) sieve.  The prime indices are
    retrieved from a precomputed map.  A number qualifies if

      • it contains at most one prime factor > 2 with exponent > 1  (a power of 2 only),
      • the set of prime indices > 1 is pairwise coprime,
      • a single prime factor > 2 without a factor 2 is excluded.

    All operations are performed with type seq_t, seq_t can be 8, 16, 32, 64 or 128
    bit, or arbitrary‑precision.  The implementation is simple, memory‑efficient
    and runs well under 2 s for n≈10 000.                                                      */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>
#include "../utils/gcd.h"

static idx_t sieve_limit = 0;            /* current size of SPF array   */
static uint32_t *spf = NULL;             /* smallest prime factor       */
static uint32_t *prime_index = NULL;     /* index of each prime (1‑based) */
static uint32_t prime_cnt = 0;           /* total number of primes seen */

/* Extend the SPF sieve to at least new_limit.  The sieve is rebuilt entirely
   each time to keep the code simple (the limit stays below a few millions). */
static void ensure_sieve_limit(idx_t new_limit) {
    if (sieve_limit >= new_limit) return;

    /* choose a new size slightly larger than new_limit */
    idx_t lim = new_limit * 2 + 10;
    if (lim < 2) lim = 2;

    free(spf);
    free(prime_index);

    spf = (uint32_t*) calloc((size_t)lim + 1, sizeof(uint32_t));
    prime_index = (uint32_t*) calloc((size_t)lim + 1, sizeof(uint32_t));

    prime_cnt = 0;
    for (idx_t i = 2; i <= lim; ++i) {
        if (!spf[(size_t)i]) {                 /* i is prime */
            spf[(size_t)i] = (uint32_t)i;
            prime_index[(size_t)i] = ++prime_cnt;
            if (i <= lim / i) {
                for (idx_t j = i * i; j <= lim; j += i) {
                    if (!spf[(size_t)j]) spf[(size_t)j] = (uint32_t)i;
                }
            }
        }
    }
    sieve_limit = lim;
}

/* Test whether a candidate integer satisfies the defining property.  The
   candidate is a 64‑bit unsigned integer. */
static bool check_candidate(uint64_t num) {
    uint64_t x = num;
    bool has_two = false;
    uint32_t indices[64];
    int idx_cnt = 0;

    while (x > 1) {
        uint32_t p = spf[(size_t)x];
        if (p == 0) p = (uint32_t)x;   /* x is prime larger than the sieve limit */

        int e = 0;
        while (x % p == 0) {
            x /= p;
            ++e;
        }

        if (p == 2) {
            has_two = true;
            continue;
        }
        if (e > 1) return false;          /* exponent >1 not allowed for primes > 2 */

        uint32_t k = prime_index[(size_t)p];
        if (k == 0) return false;          /* safety check */
        indices[idx_cnt++] = k;
    }

    int cnt = idx_cnt;
    if (cnt == 0) return true;            /* power of 2 or 1 */

    if (cnt == 1) {
        if (!has_two) return false;       /* single prime >2 without 2 factor */
        return true;
    }

    for (int i = 0; i < cnt; ++i) {
        for (int j = i + 1; j < cnt; ++j) {
            if (gcd((seq_t)indices[i], (seq_t)indices[j]) != (seq_t)1)
                return false;
        }
    }
    return true;
}

/* Dynamic cache of computed terms */
static seq_t *seq_cache = NULL;
static size_t seq_len = 0;          /* number of terms stored */
static size_t seq_cap = 0;          /* allocated capacity */
static idx_t candidate = 1;         /* next integer to test */

/* Append a term to the cache */
static void append_term(seq_t val) {
    if (seq_len == seq_cap) {
        size_t new_cap = seq_cap * 2 + 16;
        seq_t *tmp = (seq_t*) realloc(seq_cache, new_cap * sizeof(seq_t));
        seq_cache = tmp;
        seq_cap = new_cap;
    }
    seq_cache[seq_len++] = val;
}

/* Public function required by the judging harness */
seq_t a(idx_t n) {
    if (n == 0) return 0;          /* undefined, but safe fallback */

    while (seq_len < n) {
        ensure_sieve_limit(candidate);
        if (check_candidate((uint64_t)candidate)) {
            append_term((seq_t)candidate);
        }
        ++candidate;
    }
    return seq_cache[n - 1];
}
