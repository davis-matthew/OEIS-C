/*
 * A335816  Squares visited by a chess king moving on a square-spiral numbered
 *          board where the king moves to the adjacent unvisited square
 *          containing the spiral number with the fewest divisors. In case of
 *          a tie it chooses the square with the lowest spiral number.
 * https://oeis.org/A335816
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, walk, fini, full
 * Formula:   not stated
 * Range:     u8 n <= 48, u16 n <= 412, u32 n <= 412, u64 n <= 412,
 *            u128 n <= 412, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  This function computes the OEIS sequence A335816.
    The sequence is generated by simulating a chess king's walk on a
    square‑spiral numbered board.  The algorithm:
      1. Build a mapping from integer coordinates (x,y) to the
         square‑spiral number using the standard Ulam spiral.
      2. Pre‑compute divisor counts for numbers up to the maximum
         spiral number encountered (≤ 1681 for a 30×30 grid).
      3. Starting at the centre (number 1), at each step examine the
         eight adjacent squares.  Among the unvisited neighbours pick the
         one with the fewest divisors; if several have the same minimal
         count, choose the smallest number.
      4. Record each visited number; the walk terminates when no
         adjacent unvisited square remains (after 411 steps).
      5. The resulting 411‑term sequence is stored in a static array.
    In all other cases (n > 411 or n = 0) the function returns 0. */

#include <stdint.h>
#include <stdbool.h>
#include <limits.h>

#define MAX_LAYER 30                    /* radius sufficient for all visited squares */
#define GRID_SIZE (2 * MAX_LAYER + 1)
#define MAX_NUM (GRID_SIZE * GRID_SIZE) /* maximal spiral number in the grid */

static bool seq_initialized = false;
static seq_t seq_values[500];
static idx_t seq_len = 0;

/* mapping from coordinates to spiral numbers */
static seq_t grid[GRID_SIZE][GRID_SIZE];
/* divisor counts for numbers up to MAX_NUM */
static int divcnt[MAX_NUM + 1];
/* visited flag for each number */
static unsigned char visited_flag[MAX_NUM + 1];

static void init_grid_and_counts(void)
{
    /* 1. Build the spiral mapping */
    const int OFFSET = MAX_LAYER;
    int num = 1;
    grid[OFFSET][OFFSET] = (seq_t)num;    /* centre (0,0) */
    for (int layer = 1; layer <= MAX_LAYER; ++layer) {
        /* start number of this ring */
        num = (2 * (layer - 1) + 1);
        num = num * num + 1;
        int x = layer;
        int y = -layer + 1;
        grid[OFFSET + x][OFFSET + y] = (seq_t)num++;            /* start cell */

        /* up: 2*layer-1 steps */
        for (int s = 0; s < 2 * layer - 1; ++s) {
            ++y;
            grid[OFFSET + x][OFFSET + y] = (seq_t)num++;
        }
        /* left: 2*layer steps */
        for (int s = 0; s < 2 * layer; ++s) {
            --x;
            grid[OFFSET + x][OFFSET + y] = (seq_t)num++;
        }
        /* down: 2*layer steps */
        for (int s = 0; s < 2 * layer; ++s) {
            --y;
            grid[OFFSET + x][OFFSET + y] = (seq_t)num++;
        }
        /* right: 2*layer steps */
        for (int s = 0; s < 2 * layer; ++s) {
            ++x;
            grid[OFFSET + x][OFFSET + y] = (seq_t)num++;
        }
    }

    /* 2. Compute divisor counts */
    for (int i = 1; i <= MAX_NUM; ++i)
        divcnt[i] = 0;
    for (int d = 1; d <= MAX_NUM; ++d) {
        for (int m = d; m <= MAX_NUM; m += d)
            ++divcnt[m];
    }

    /* 3. Simulate the king's walk */
    memset(visited_flag, 0, sizeof(visited_flag));
    int cx = 0, cy = 0;          /* current coordinates */
    seq_values[0] = (seq_t)1;    /* start at number 1 */
    visited_flag[1] = 1;
    seq_len = 1;

    while (true) {
        int best_num = -1;
        int best_div = INT_MAX;
        int best_x = 0, best_y = 0;
        bool found = false;

        for (int dx = -1; dx <= 1; ++dx) {
            for (int dy = -1; dy <= 1; ++dy) {
                if (dx == 0 && dy == 0) continue;
                int nx = cx + dx;
                int ny = cy + dy;
                if (nx < -MAX_LAYER || nx > MAX_LAYER ||
                    ny < -MAX_LAYER || ny > MAX_LAYER)
                    continue;
                seq_t val = grid[OFFSET + nx][OFFSET + ny];
                int v = (int)val;                 /* v ≤ MAX_NUM */
                if (visited_flag[v]) continue;
                int d = divcnt[v];
                if (!found || d < best_div || (d == best_div && val < (seq_t)best_num)) {
                    best_num = v;
                    best_div = d;
                    best_x = nx;
                    best_y = ny;
                    found = true;
                }
            }
        }

        if (!found) break;      /* no unvisited neighbours – walk ends */

        visited_flag[best_num] = 1;
        seq_values[seq_len++] = (seq_t)best_num;
        cx = best_x;
        cy = best_y;
    }
}

seq_t a(idx_t n)
{
    if (!seq_initialized) {
        init_grid_and_counts();
        seq_initialized = true;
    }
    if (n == 0) return (seq_t)0;                 /* offset = 1 */
    if (n > seq_len) return (seq_t)0;             /* sequence is finite (411 terms) */
    return seq_values[n - 1];
}
