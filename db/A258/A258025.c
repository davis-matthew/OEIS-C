/*
 * A258025  Numbers k such that prime(k+2) - 2*prime(k+1) + prime(k) > 0.
 * https://oeis.org/A258025
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 125, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A258025: numbers k such that prime(k+2) - 2*prime(k+1) + prime(k) > 0
   (computes the nth such k, offset 1).
   The sequence is generated by incremental prime testing and stored for
   memoised access. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* static state shared by all calls to a */
static uint32_t *primes      = NULL;  /* primes[], 1‑indexed in OEIS sense */
static size_t   primes_size  = 0;     /* number of primes stored    */
static size_t   primes_cap   = 0;     /* allocated capacity         */
static uint32_t next_candidate = 2;   /* next integer to test       */

static seq_t *seq          = NULL;    /* values of the sequence     */
static size_t seq_size     = 0;       /* number of terms stored     */
static size_t seq_cap      = 0;       /* allocated capacity         */
static idx_t  next_k       = 1;       /* next k to examine          */

seq_t a(idx_t n)
{
    /* build terms until we have at least n of them */
    while (seq_size < n) {
        /* ensure we have primes up to k+1 (OEIS indices) */
        while (primes_size <= (size_t)next_k + 1) {
            uint32_t cand = next_candidate;
            bool cand_is_prime = true;
            for (size_t i = 0; i < primes_size; ++i) {
                uint32_t p = primes[i];
                uint64_t pp = (uint64_t)p * p;
                if (pp > cand)
                    break;
                if (cand % p == 0) {
                    cand_is_prime = false;
                    break;
                }
            }
            if (cand_is_prime) {
                if (primes_size >= primes_cap) {
                    size_t new_cap = primes_cap ? primes_cap * 2 : 64;
                    uint32_t *tmp = (uint32_t *)realloc(primes,
                                                         new_cap * sizeof(uint32_t));
                    primes = tmp;
                    primes_cap = new_cap;
                }
                primes[primes_size++] = cand;
            }
            ++next_candidate;
        }

        /* compute the finite difference for current k */
        int64_t diff =
            (int64_t)primes[(size_t)next_k + 1] -
            2LL * (int64_t)primes[(size_t)next_k] +
            (int64_t)primes[(size_t)next_k - 1];

        if (diff > 0) {
            if (seq_size >= seq_cap) {
                size_t new_cap = seq_cap ? seq_cap * 2 : 64;
                seq_t *tmp = (seq_t *)realloc(seq,
                                               new_cap * sizeof(seq_t));
                seq = tmp;
                seq_cap = new_cap;
            }
            seq[seq_size++] = (seq_t)next_k;
        }
        ++next_k;
    }

    return seq[n - 1];
}
