/*
 * A396323  Numbers that are neither cubefree nor powerful with at least 3
 *          distinct prime factors.
 * https://oeis.org/A396323
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 7575, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the nth number that is neither cubefree nor powerful
   and has at least 3 distinct prime factors.  The sequence
   a(1)=120, a(2)=168, a(3)=240, ...  (OEIS A396323).  It is
   generated by a simple sieve‑based trial division and
   cached for fast repeated access. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* -------------------------------------------------------------- */
/*  Prime sieve – needed for factorisation of candidates.        */
/* -------------------------------------------------------------- */
static uint32_t *prime_list = NULL;
static size_t prime_count = 0;
static bool primes_initialised = false;

static void init_primes(void)
{
    if (primes_initialised) return;

    /*  Sieve up to 2 000 000 – ample for the range we need.  */
    const uint32_t LIMIT = 2000000;
    bool *is_composite = (bool*)malloc((LIMIT + 1) * sizeof(bool));
    prime_list = (uint32_t*)malloc(LIMIT * sizeof(uint32_t));
    if (!is_composite || !prime_list) abort();

    for (uint32_t i = 0; i <= LIMIT; ++i) is_composite[i] = false;

    for (uint32_t p = 2; p <= LIMIT; ++p) {
        if (!is_composite[p]) {
            prime_list[prime_count++] = p;
            if ((uint64_t)p * p <= LIMIT) {
                for (uint64_t j = (uint64_t)p * p; j <= LIMIT; j += p)
                    is_composite[(size_t)j] = true;
            }
        }
    }
    free(is_composite);
    primes_initialised = true;
}

/* -------------------------------------------------------------- */
/*  Test whether a candidate satisfies the definition.           */
/* -------------------------------------------------------------- */
static bool good_candidate(uint64_t m)
{
    uint64_t tmp = m;
    size_t distinct = 0;
    bool has_cube  = false;   /* at least one exponent ≥ 3  */
    bool has_linear = false;  /* at least one exponent = 1  */

    for (size_t i = 0; i < prime_count; ++i) {
        uint32_t p = prime_list[i];
        if ((uint64_t)p * p > tmp) break;
        if (tmp % p == 0) {
            int exp = 0;
            while (tmp % p == 0) {
                tmp /= p;
                ++exp;
            }
            ++distinct;
            if (exp >= 3) has_cube = true;
            if (exp == 1) has_linear = true;
        }
    }

    if (tmp > 1) {              /* remaining prime factor, exponent 1 */
        ++distinct;
        has_linear = true;
    }

    return (distinct >= 3) && has_cube && has_linear;
}

/* -------------------------------------------------------------- */
/*  Cache for generated terms.                                   */
/* -------------------------------------------------------------- */
static seq_t *cache = NULL;
static size_t cache_size = 0;
static size_t cache_cap  = 0;

static void ensure_cache_capacity(size_t need)
{
    if (need <= cache_cap) return;
    size_t new_cap = (cache_cap > 0) ? cache_cap * 2 : 4;
    while (new_cap < need) new_cap *= 2;
    seq_t *new_ptr = (seq_t*)realloc(cache, new_cap * sizeof(seq_t));
    if (!new_ptr) abort();
    cache = new_ptr;
    cache_cap = new_cap;
}

/* -------------------------------------------------------------- */
/*  Generate terms until we have at least n entries in the cache. */
/* -------------------------------------------------------------- */
static void generate_terms(idx_t n)
{
    static uint64_t next_candidate = 2;   /* next integer to test   */

    init_primes();

    while (cache_size < (size_t)n) {
        if (good_candidate(next_candidate)) {
            ensure_cache_capacity(cache_size + 1);
            /* cast the integer to the arbitrary‑precision type */
            cache[cache_size++] = (seq_t)next_candidate;
        }
        ++next_candidate;
    }
}

/* -------------------------------------------------------------- */
/*  Public function – required by the build.                      */
/* -------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;           /* undefined, but harmless           */
    generate_terms(n);              /* guarantees that cache[n-1] exists */
    return cache[(size_t)n - 1];
}
