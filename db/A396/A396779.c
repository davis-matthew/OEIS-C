/*
 * A396779  Numbers k such that there are no pairs (x,y) whose product is k
 *          with x + y or |x - y| a square.
 * https://oeis.org/A396779
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 22, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   floor_sqrt
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A396779:
   numbers k such that for every pair of positive integers (x,y)
   with x*y = k, neither x+y nor |x-y| is a perfect square.
   The sequence is generated by checking each integer k in increasing
   order until the required index is reached. */

/* Needed utilities and headers */
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/floor_sqrt.h"   /* floor_sqrt(seq_t) */

/* Helper: check if a seq_t value is a perfect square */
static bool is_square_seq(seq_t v)
{
    seq_t s = floor_sqrt(v);
    return s * s == v;
}

/* Main function */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* offset is 1; invalid indices return 0 */

    /* Static cache of found terms */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;  /* number of terms already stored */
    static size_t cache_cap = 0;  /* allocated capacity */
    static idx_t last_k = 1;      /* next integer to test */

    /* Grow cache until we have at least n terms */
    while (cache_len < n)
    {
        idx_t k = last_k;                 /* candidate number */
        bool ok = true;
        idx_t sqrt_k = (idx_t)floor_sqrt((seq_t)k);

        for (idx_t d = 1; d <= sqrt_k; ++d)
        {
            if (k % d == 0)
            {
                idx_t e = k / d;
                seq_t sum  = (seq_t)d + (seq_t)e;
                seq_t diff = (e > d) ? (seq_t)(e - d) : (seq_t)(d - e);
                if (is_square_seq(sum) || is_square_seq(diff))
                {
                    ok = false;
                    break;
                }
            }
        }

        if (ok)
        {
            /* Ensure sufficient capacity */
            if (cache_len == cache_cap)
            {
                size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) abort();  /* out of memory */
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = (seq_t)k;
        }

        ++last_k;  /* next integer */
    }

    return cache[n - 1];
}
