/*
 * A396186  Consider the square spiral with its cells numbered starting at 0,
 *          as in A308884 and A274641. Two players, Black and Red, take turns.
 *          When it is Black's turn, he places a knight at the first cell in
 *          the spiral that is beyond the last Red knight and is not attacked
 *          by any Red knight, and when it is...
 * https://oeis.org/A396186
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 57, u16 n <= 9551, u32 n <= 9551, u64 n <= 9551,
 *            u128 n <= 9551, big any n
 * Helpers:   coord_from_index, pack_coord
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A396186 – squares occupied by Red knights in the alternating
 * knight‑placement square spiral.  The sequence is generated by simulation
 * using hash tables that keep track of squares attacked by each player.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <math.h>
#include <string.h>
#include "../utils/coord_from_index.h"
#include "../utils/pack_coord.h"

/* --------------------------------------------------------------------- */
/* Hash set for 64‑bit keys (attacked squares)                           */
/* --------------------------------------------------------------------- */

#define HASHSET_EMPTY 0xFFFFFFFFFFFFFFFFULL

typedef struct {
    uint64_t *table;
    size_t capacity;   /* power of two */
    size_t size;
} HashSet;

static void hashset_init(HashSet *hs, size_t init_cap) {
    hs->capacity = init_cap;
    hs->size = 0;
    hs->table = (uint64_t *)calloc(hs->capacity, sizeof(uint64_t));
    if (!hs->table) { abort(); }
    /* initialise all entries to empty marker */
    memset(hs->table, 0xFF, hs->capacity * sizeof(uint64_t));
}

static void hashset_rehash(HashSet *hs) {
    size_t newcap = hs->capacity * 2;
    uint64_t *newtab = (uint64_t *)calloc(newcap, sizeof(uint64_t));
    if (!newtab) { abort(); }
    memset(newtab, 0xFF, newcap * sizeof(uint64_t));

    size_t mask = newcap - 1;
    for (size_t i = 0; i < hs->capacity; ++i) {
        uint64_t key = hs->table[i];
        if (key != HASHSET_EMPTY) {
            size_t idx = key & mask;
            while (newtab[idx] != HASHSET_EMPTY)
                idx = (idx + 1) & mask;
            newtab[idx] = key;
        }
    }

    free(hs->table);
    hs->table = newtab;
    hs->capacity = newcap;
}

static void hashset_insert(HashSet *hs, uint64_t key) {
    if (hs->size * 4 >= hs->capacity * 3) {
        hashset_rehash(hs);
    }

    size_t mask = hs->capacity - 1;
    size_t idx = key & mask;
    while (true) {
        if (hs->table[idx] == HASHSET_EMPTY) {
            hs->table[idx] = key;
            ++hs->size;
            return;
        }
        if (hs->table[idx] == key) return;
        idx = (idx + 1) & mask;
    }
}

static bool hashset_contains(const HashSet *hs, uint64_t key) {
    size_t mask = hs->capacity - 1;
    size_t idx = key & mask;
    while (true) {
        if (hs->table[idx] == HASHSET_EMPTY) return false;
        if (hs->table[idx] == key) return true;
        idx = (idx + 1) & mask;
    }
}

/* --------------------------------------------------------------------- */
/* Utilities                                                       */
/* --------------------------------------------------------------------- */

/* All eight knight moves */
static const int knight_moves[8][2] = {
    {  1,  2}, {  1, -2}, {-1,  2}, {-1, -2},
    {  2,  1}, {  2, -1}, {-2,  1}, {-2, -1}
};

static void add_attacks(int x, int y, HashSet *hs) {
    for (int i = 0; i < 8; ++i) {
        int nx = x + knight_moves[i][0];
        int ny = y + knight_moves[i][1];
        hashset_insert(hs, pack_coord(nx, ny));
    }
}

/* Dynamic array to store Red knight indices */
typedef struct {
    idx_t *data;
    size_t size;
    size_t cap;
} RedSeq;

static void redseq_init(RedSeq *s) {
    s->data = NULL;
    s->size = 0;
    s->cap  = 0;
}

static void redseq_push(RedSeq *s, idx_t val) {
    if (s->cap == 0) {
        s->cap = 16;
        s->data = (idx_t *)malloc(s->cap * sizeof(idx_t));
        if (!s->data) { abort(); }
    } else if (s->size == s->cap) {
        s->cap *= 2;
        idx_t *tmp = (idx_t *)realloc(s->data, s->cap * sizeof(idx_t));
        if (!tmp) { abort(); }
        s->data = tmp;
    }
    s->data[s->size++] = val;
}

/* --------------------------------------------------------------------- */
/* Main function                                                       */
/* --------------------------------------------------------------------- */

seq_t a(idx_t n) {
    /* static state to memoise sequence up to the largest requested n */
    static bool initialized = false;
    static HashSet black_attack, red_attack;
    static idx_t last_black_index = 0;
    static idx_t last_red_index   = (idx_t)-1;
    static RedSeq red_seq;

    if (!initialized) {
        hashset_init(&black_attack, 64);
        hashset_init(&red_attack,   64);

        /* Initial Black knight at spiral index 0 */
        add_attacks(0, 0, &black_attack);
        last_black_index = 0;

        redseq_init(&red_seq);
        initialized = true;
    }

    /* Generate sequence until we have at least (n+1) Red knights */
    while (red_seq.size <= n) {
        /* ---- Red's turn ---- */
        idx_t candidate = last_black_index + 1;
        int cx, cy;
        uint64_t key;
        for (;;) {
            coord_from_index(candidate, &cx, &cy);
            key = pack_coord(cx, cy);
            if (!hashset_contains(&black_attack, key)) break;
            ++candidate;
        }
        redseq_push(&red_seq, candidate);
        last_red_index = candidate;
        add_attacks(cx, cy, &red_attack);

        /* ---- Black's turn ---- */
        candidate = last_red_index + 1;
        for (;;) {
            coord_from_index(candidate, &cx, &cy);
            key = pack_coord(cx, cy);
            if (!hashset_contains(&red_attack, key)) break;
            ++candidate;
        }
        last_black_index = candidate;
        add_attacks(cx, cy, &black_attack);
    }

    return (seq_t)red_seq.data[n];
}
