/*
 * A396647  Numbers k = p_1^e_1 * ... * p_i^e_i such that the area of the
 *          convex hull of the planar coordinates [p_i, e_i] is not an
 *          integer, but >= 1/2.
 * https://oeis.org/A396647
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 50, u32 n <= 50, u64 n <= 50, u128 n <= 50,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Sequence A396647: Numbers k whose convex hull of the points (p_i , e_i)
 * invented from the prime factorization k = Π p_i^e_i has a non‑integer area
 * (area * 2 is odd) but is ≥ 1/2.  The sequence is generated by brute force
 * search using a sieve for smallest prime factors.
 *
 * The function a() returns the n‑th term (1‑based), memoising all terms
 * found so far.  It works for any integer type supplied for seq_t and
 * idx_t, and is above C11 and C++17, making no use of floating‑point
 * arithmetic.
 */

#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/*--- Types provided by the build ---------------------------------------*/
typedef int  seq_cmp_t;          /* placeholder for compare function result */

/*--- Helper structures -----------------------------------------------*/
typedef struct { uint32_t x; uint32_t y; } point_t;

/*--- Static global state ----------------------------------------------*/
static uint32_t *spf     = NULL;          /* smallest prime factor array     */
static size_t    spf_lim = 0;             /* current limit of spf array      */
static seq_t   *terms   = NULL;          /* memoised terms                 */
static size_t   terms_cap = 0;            /* allocated capacity of terms     */
static size_t   terms_len = 0;            /* number of terms stored          */
static uint32_t next_k   = 2;             /* next integer to test            */

/*--- Smallest prime factor sieve -------------------------------------*/
static void build_spf(size_t limit)
{
    if (spf) { free(spf); spf = NULL; }
    spf_lim = limit;
    spf = (uint32_t*)malloc((limit + 1) * sizeof(uint32_t));
    if (!spf) exit(EXIT_FAILURE);
    memset(spf, 0, (limit + 1) * sizeof(uint32_t));
    spf[0] = 0; spf[1] = 1;

    for (size_t i = 2; i * i <= limit; ++i)
        if (spf[i] == 0)
            for (size_t j = i * i; j <= limit; j += i)
                if (spf[j] == 0)
                    spf[j] = (uint32_t)i;

    for (size_t i = 2; i <= limit; ++i)
        if (spf[i] == 0)
            spf[i] = (uint32_t)i;
}

static void ensure_spf_limit(uint32_t needed)
{
    if (needed <= spf_lim) return;
    size_t new_lim = spf_lim ? spf_lim * 2 : 1;
    while (new_lim < (size_t)needed) new_lim *= 2;
    build_spf(new_lim);
}

/*--- Primitive helpers ------------------------------------------------*/
static inline int compare_points(const void *a, const void *b)
{
    const point_t *p = (const point_t*)a;
    const point_t *q = (const point_t*)b;
    if (p->x < q->x) return -1;
    if (p->x > q->x) return  1;
    if (p->y < q->y) return -1;
    if (p->y > q->y) return  1;
    return 0;
}

static inline int64_t cross(const point_t *A, const point_t *B, const point_t *C)
{
    int64_t BAx = (int64_t)B->x - A->x;
    int64_t BAy = (int64_t)B->y - A->y;
    int64_t CAx = (int64_t)C->x - A->x;
    int64_t CAy = (int64_t)C->y - A->y;
    return BAx * CAy - BAy * CAx;
}

/*--- Test whether k satisfies the sequence property -------------------*/
static int good_k(uint32_t k)
{
    /* factorise k using spf */
    point_t pts[16];      /* max distinct primes for k < 2^32 is < 16 */
    size_t   m = 0;
    uint32_t tmp = k;
    while (tmp > 1) {
        uint32_t p = spf[tmp];
        uint32_t e = 0;
        while (tmp % p == 0) {
            tmp /= p;
            ++e;
        }
        pts[m].x = p;
        pts[m].y = e;
        ++m;
    }
    if (m < 3) return 0;                 /* need at least 3 points */

    /* sort points by (x,y) */
    qsort(pts, m, sizeof(point_t), compare_points);

    /* build convex hull (Andrew's monotone chain) */
    point_t hull[32];
    size_t hsz = 0;

    /* lower hull */
    for (size_t i = 0; i < m; ++i) {
        while (hsz >= 2 && cross(&hull[hsz-2], &hull[hsz-1], &pts[i]) <= 0)
            --hsz;
        hull[hsz++] = pts[i];
    }
    /* upper hull */
    size_t t = hsz + 1;
    for (size_t i = m; i > 0; --i) {
        while (hsz >= t && cross(&hull[hsz-2], &hull[hsz-1], &pts[i-1]) <= 0)
            --hsz;
        hull[hsz++] = pts[i-1];
    }
    if (hsz < 3) return 0;                /* collinear or only two points */

    /* shoelace formula: twice the signed area */
    int64_t area2 = 0;
    for (size_t i = 0; i < hsz; ++i) {
        size_t j = (i + 1) % hsz;
        area2 += (int64_t)hull[i].x * hull[j].y
               - (int64_t)hull[j].x * hull[i].y;
    }
    if (area2 < 0) area2 = -area2;
    if (area2 == 0) return 0;             /* degenerate polygon */
    return (area2 & 1);                   /* odd => non‑integer area */
}

/*--- Main sequence function -------------------------------------------*/
seq_t a(idx_t n)
{
    /* initialise on first call */
    static int initialized = 0;
    if (!initialized) {
        build_spf( (size_t)1000000 );    /* start with a reasonable limit */
        terms       = NULL;
        terms_cap   = 0;
        terms_len   = 0;
        next_k      = 2;
        initialized = 1;
    }

    /* generate terms until we have at least n of them */
    while (terms_len < (size_t)n) {
        if ((uint32_t)next_k > spf_lim)
            ensure_spf_limit((uint32_t)next_k + 1);   /* grow sieve if needed */

        if (good_k(next_k)) {
            if (terms_len >= terms_cap) {
                size_t new_cap = terms_cap ? terms_cap * 2 : 256;
                seq_t *tmp = (seq_t*)realloc(terms, new_cap * sizeof(seq_t));
                if (!tmp) exit(EXIT_FAILURE);
                terms      = tmp;
                terms_cap  = new_cap;
            }
            terms[terms_len++] = (seq_t)next_k;
        }
        ++next_k;
    }
    return terms[n - 1];
}
