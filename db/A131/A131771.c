/* 
   OEIS A131771 – Partial sums of the sequence A131771 with zeros
   inserted at triangular indices.  The recurrence is:
      Let z(n) = number of indices k < n that are zero indices.
      Zeros occur at positions 1,4,8,13,19,... (generated by
      z_0 = 1, next = z + 3, then step++ each time).
      a(0) = 1.
      If n is a zero index:  a(n) = a(n-1).
      Otherwise                 a(n) = a(n-1) + a(n - z(n)).
   This produces the sequence:
      1,1,2,4,4,8,12,20,20,32,52,72,104,104,156,228,332,436,592,...
*/

#include <stdlib.h>
#include <stddef.h>

seq_t a(idx_t n)
{
    /* static state between calls */
    static seq_t *cache = NULL;
    static size_t cap   = 0;     /* allocated size of cache */
    static size_t len   = 0;     /* next index to compute (size of valid data) */
    static idx_t  zeros_count = 0; /* number of zero indices encountered so far */
    static idx_t  next_zero   = 1; /* next index that will be a zero */
    static idx_t  step        = 3; /* step size between consecutive zeros */

    /* grow cache if necessary */
    if (n + 1 > cap) {
        size_t newcap = cap ? cap << 1 : 64;
        while (newcap < (size_t)(n + 1)) newcap <<= 1;
        seq_t *tmp = (seq_t *)realloc(cache, newcap * sizeof(seq_t));
        if (!tmp) abort();
        cache = tmp;
        cap = newcap;
    }

    /* initialise first term if needed */
    if (len == 0) {
        cache[0] = (seq_t)1; /* a(0) */
        len = 1;
    }

    /* compute terms up to n */
    for (size_t i = len; i <= (size_t)n; ++i) {
        if ((idx_t)i == next_zero) {            /* zero index */
            cache[i] = cache[i - 1];
            ++zeros_count;                      /* zero at i counted for future indices */
            next_zero += step;                  /* next zero position */
            ++step;
        } else {                                /* ordinary index */
            cache[i] = cache[i - 1] + cache[i - zeros_count];
        }
    }

    len = n + 1; /* update next index to compute */
    return cache[n];
}
