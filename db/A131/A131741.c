/*
 * A131741  a(n) is least prime (not already in list) such that no 3-term
 *          subset forms an arithmetic progression.
 * https://oeis.org/A131741
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 22, u16 n <= 539, u32 n <= 540, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A131741: sequence of primes with no 3‑term arithmetic progression.
   a(n) is the smallest prime not already in the list such that
   for all i<j<k,  a(j)-a(i) != a(k)-a(j).  */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/is_prime_big.h"   /* is_prime_big(seq_t) */

/* ---------- Bitset helpers ---------- */
static uint64_t *forb_bits = NULL;   /* array of 64‑bit words */
static size_t   forb_bits_len = 0;    /* number of bits currently usable */

/* Ensure bitset can store bit 'pos' (0‑based).  Expands by doubling. */
static void ensure_forbidden_bits(idx_t pos)
{
    if ((size_t)pos < forb_bits_len)
        return;

    size_t needed_words = ((pos + (idx_t)1) + 63ULL) >> 6U;

    /* if we already have enough words, nothing to do */
    if (needed_words <= (forb_bits_len >> 6))
        return;

    /* Allocate new word array */
    size_t cur_words = forb_bits_len >> 6;
    uint64_t *new_bits = (uint64_t *)realloc(forb_bits,
                                             needed_words * sizeof(uint64_t));
    if (!new_bits)
        abort();                  /* allocation failure */
    /* Zero the newly added part */
    for (size_t i = cur_words; i < needed_words; ++i)
        new_bits[i] = 0ULL;
    forb_bits = new_bits;
    forb_bits_len = needed_words << 6;        /* bits count = words*64 */
}

/* Set bit 'pos' */
static void set_forbidden(idx_t pos)
{
    ensure_forbidden_bits(pos);
    forb_bits[pos >> 6] |= (1ULL << (pos & 63ULL));
}

/* Test if bit 'pos' is set */
static bool is_forbidden(idx_t pos)
{
    if ((size_t)pos >= forb_bits_len)
        return false;
    return (forb_bits[pos >> 6] >> (pos & 63ULL)) & 1ULL;
}

/* ---------- Sequence helpers ---------- */
static seq_t *seq_cache   = NULL;   /* dynamic array of seq_t values */
static size_t  seq_cap    = 0;      /* allocated capacity */
static size_t  seq_len    = 0;      /* current number of terms */

/* Grow the sequence array as needed */
static void ensure_seq_capacity(size_t needed_len)
{
    if (needed_len <= seq_cap)
        return;
    while (seq_cap < needed_len)
        seq_cap = seq_cap ? seq_cap << 1 : 16;
    seq_t *new_arr = (seq_t *)realloc(seq_cache,
                                      seq_cap * sizeof(seq_t));
    if (!new_arr)
        abort();                  /* allocation failure */
    seq_cache = new_arr;
}

/* ---------- Prime generation ---------- */
static idx_t next_prime_candidate = 3;   /* next odd number to test */

/* Find the next prime >= start (start > 2).  Updates next_prime_candidate. */
static seq_t next_prime()
{
    for (;;) {
        idx_t p = next_prime_candidate;
        next_prime_candidate += 2;   /* skip even numbers */

        if (is_prime_big(p))
            return p;
    }
}

/* ---------- Main function ---------- */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;   /* undefined for n=0, but return 0 gracefully */

    /* Initialise on first call */
    if (seq_len == 0) {
        ensure_seq_capacity(16);
        seq_cache[0] = (seq_t)2;
        seq_len = 1;
    }

    /* Grow sequence until it contains term n */
    while (seq_len < (size_t)n) {
        seq_t cand = next_prime();            /* candidate prime */

        if (is_forbidden((idx_t)cand))
            continue;                         /* would create an AP */

        /* Accept cand and record it */
        ensure_seq_capacity(seq_len + 1);
        seq_cache[seq_len] = cand;
        seq_len++;

        /* Add forbidden values generated by pairs (q, cand) */
        for (size_t i = 0; i < seq_len - 1; ++i) {
            seq_t q = seq_cache[i];
            seq_t f = cand + cand - q;        /* 2*cand - q */
            set_forbidden((idx_t)f);
        }
    }

    /* a(n) corresponds to seq_cache[n-1] (offset 1) */
    return seq_cache[(size_t)n - 1];
}
