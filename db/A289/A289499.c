/*
 * A289499  Number of primes in the interval [8n, 9n].
 * https://oeis.org/A289499
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 2459, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   sieve_primes
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: Number of primes in the interval [8n, 9n]
   Formula: a(n) = #{ p prime : 8n ≤ p ≤ 9n }  (n ≥ 1)
   Implementation uses a cached sieve of primes up to the current
   highest 9n needed.  The sieve is rebuilt only when n grows beyond
   the previous limit.  For each call the function performs two
   binary searches on the prime array to count the primes in the
   requested interval.
*/

#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/sieve_primes.h"   /* provides sieve_primes() */

/* Static cache of primes generated by sieve_primes */
static idx_t *prime_cache      = NULL;   /* array of primes */
static size_t prime_cache_cnt  = 0;       /* number of primes in cache */
static idx_t  sieve_limit      = 0;       /* largest 9*n for which sieve is built */

/* Binary search: first index with arr[idx] >= val */
static size_t lower_bound(const idx_t *arr, size_t n, idx_t val)
{
    size_t l = 0, r = n;
    while (l < r) {
        size_t m = (l + r) >> 1;
        if (arr[m] >= val) {
            r = m;
        } else {
            l = m + 1;
        }
    }
    return l;
}

/* Binary search: first index with arr[idx] > val */
static size_t upper_bound(const idx_t *arr, size_t n, idx_t val)
{
    size_t l = 0, r = n;
    while (l < r) {
        size_t m = (l + r) >> 1;
        if (arr[m] > val) {
            r = m;
        } else {
            l = m + 1;
        }
    }
    return l;
}

seq_t a(idx_t n)
{
    /* OEIS offset: first term corresponds to n = 1 */
    if (n == 0) return (seq_t)0;

    /* 9*n needed for upper bound of the interval */
    idx_t limit = n * ((idx_t)9ULL);
    /* rebuild the sieve only when a larger limit is required */
    if (limit > sieve_limit) {
        /* free previous cache */
        free(prime_cache);
        prime_cache = NULL;
        prime_cache_cnt = 0;
        /* generate new prime list up to limit (inclusive) */
        sieve_primes(limit, &prime_cache, &prime_cache_cnt);
        sieve_limit = limit;
    }

    /* Define the inclusive interval [8n, 9n] */
    idx_t low  = n * ((idx_t)8ULL);
    idx_t high = n * ((idx_t)9ULL);

    /* Locate the first and last primes within the interval */
    size_t first = lower_bound(prime_cache, prime_cache_cnt, low);
    size_t after = upper_bound(prime_cache, prime_cache_cnt, high);

    /* Count of primes in [low, high] */
    seq_t count = (seq_t)(after > first ? after - first : 0);
    return count;
}
