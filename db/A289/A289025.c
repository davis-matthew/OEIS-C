/* Sequence A289025
   Fixed point of the mapping
   00 → 0010 , 01 → 010 , 10 → 001   starting with 00
   (OEIS: A289025)
   The sequence is generated by repeatedly replacing disjoint 2‑bit blocks
   using the above rule until the first n bits stop changing. */

/* Include required headers */
#include <stdlib.h>
#include <stdbool.h>

/* The required function */
seq_t a(idx_t n)
{
    static seq_t *cur    = NULL; /* current iterate */
    static seq_t *prev   = NULL; /* previous iterate (for comparison) */
    static idx_t cur_len = 0;    /* length of cur */
    static idx_t prev_len= 0;    /* length of prev */
    static idx_t iter    = 0;    /* iteration counter */

    if (n == 0)              /* offset 1, but guard in case of 0 */
        return 0;

    /* Initialise */
    if (cur == NULL) {
        cur = (seq_t *)malloc((size_t)(2) * sizeof(seq_t));
        cur[0] = 0;
        cur[1] = 0;
        cur_len = 2;
    }

    /* Repeat until the first n bits agree with the previous iterate */
    while (true) {
        if (prev != NULL && cur_len >= n) {
            /* compare the first n bits of prev and cur */
            bool same = true;
            for (idx_t i = 0; i < n; ++i) {
                if (prev[i] != cur[i]) { same = false; break; }
            }
            if (same) break;             /* stable, we can return */
        }

        /* Build next iterate */
        idx_t new_len = 0;
        /* At most twice as long as cur (worst case) */
        seq_t *next = (seq_t *)malloc((size_t)(cur_len * 2 + 2) * sizeof(seq_t));

        for (idx_t i = 0; i + 1 < cur_len; i += 2) {
            seq_t a = cur[i];
            seq_t b = cur[i+1];
            if (a == 0 && b == 0) {            /* 00 → 0010 */
                next[new_len++] = 0;
                next[new_len++] = 0;
                next[new_len++] = 1;
                next[new_len++] = 0;
            } else if (a == 0 && b == 1) {     /* 01 → 010 */
                next[new_len++] = 0;
                next[new_len++] = 1;
                next[new_len++] = 0;
            } else if (a == 1 && b == 0) {     /* 10 → 001 */
                next[new_len++] = 0;
                next[new_len++] = 0;
                next[new_len++] = 1;
            } else {                           /* 11 never appears, keep it */
                next[new_len++] = a;
                next[new_len++] = b;
            }
        }
        if (cur_len & 1)                       /* odd length: keep last bit */
            next[new_len++] = cur[cur_len - 1];

        /* Rotate buffers */
        if (prev) free(prev);
        prev     = cur;
        prev_len = cur_len;
        cur      = next;
        cur_len  = new_len;
        ++iter;

        /* Safety guard */
        if (iter > 200) break;
    }

    return cur[n - 1];
}
