/*
 * A289484  Semigroup of numbers under multiplication, distinct from mutinous
 *          sequence.
 * https://oeis.org/A289484
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 52, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 75 terms through n = 9771 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A289484:  
   numbers n whose prime factorization contains an initial product of
   prime‑powers that exceeds a subsequent prime.
   The sequence is generated by brute‑force testing of each integer
   starting from 12 until the requested index is found.  The result is
   stored in a static cache for later calls.  The algorithm works for
   any seq_t that can hold the required terms and any idx_t that can
   index them. */
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/mem.h"

/* Helper: test whether a given 64‑bit integer belongs to the set S. */
static bool is_S(uint64_t n)
{
    if (n < 12)            /* the very first S number is 12 */
        return false;

    /* factorisation: store prime factors and exponents */
    uint64_t primes[64];
    int       exps [64];
    int       cnt   = 0;
    uint64_t tmp = n;

    for (uint64_t d = 2; d <= tmp / d; ++d)
    {
        if (tmp % d == 0)
        {
            int e = 0;
            while (tmp % d == 0)
            {
                tmp /= d;
                ++e;
            }
            primes[cnt] = d;
            exps[cnt]   = e;
            ++cnt;
            if (cnt == 64)
                break;   /* safety; should never happen for our range */
        }
    }
    if (tmp > 1)          /* remaining prime factor */
    {
        primes[cnt] = tmp;
        exps[cnt]   = 1;
        ++cnt;
    }

    if (cnt < 2)          /* primes, prime powers, and products of two primes */
        return false;

    /* check the defining property */
    uint64_t pref = 1;
    for (int i = 0; i < cnt - 1; ++i)
    {
        uint64_t powv = 1;
        for (int j = 0; j < exps[i]; ++j)
            powv *= primes[i];
        pref *= powv;
        if (pref > primes[i + 1])
            return true;
    }
    return false;
}

/* Cache of previously found terms */
static seq_t *cache   = NULL;
static size_t cache_sz = 0;   /* number of terms currently stored */
static size_t cache_cap = 0;  /* capacity of the cache */

/* Ensure the cache can hold at least 'need' terms. */
static void ensure_cache(size_t need)
{
    if (need <= cache_cap)
        return;
    size_t new_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
    if (new_cap < need)
        new_cap = need;
    seq_t *tmp = mem_resize(seq_t, cache, new_cap);
    cache = tmp;
    cache_cap = new_cap;
}

/* Main sequence routine */
seq_t a(idx_t n)
{
    if (n == 0)           /* offset is 1; behaviour for n < 1 is irrelevant */
        return 0;

    /* generate terms until we have at least n of them */
    if (cache_sz < (size_t)n)
    {
        /* start searching from the next integer after the last stored term */
        uint64_t candidate = (cache_sz == 0) ? 12 : (uint64_t)cache[cache_sz - 1] + 1;

        while (cache_sz < (size_t)n)
        {
            if (is_S(candidate))
            {
                ensure_cache(cache_sz + 1);
                cache[cache_sz++] = (seq_t)candidate;
            }
            ++candidate;
        }
    }

    return cache[n - 1];
}
