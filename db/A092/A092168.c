/* Sequence: primes congruent to 3 (mod 19)
   Generated by a dynamic sieve of Eratosthenes, filtered for the
   required congruence class.  All arithmetic is integer only. */

#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/push_uint32.h"

/* ------------------------------------------------------------------
   Global state for the sieve and prime lists
   ------------------------------------------------------------------ */
static uint8_t *sieve = NULL;
static uint64_t sieve_limit = 0;

static uint32_t *all_primes = NULL;
static size_t all_cnt = 0, all_cap = 0;

static uint32_t *congr_primes = NULL;
static size_t cong_cnt = 0, cong_cap = 0;

/* ------------------------------------------------------------------
   Rebuilds the sieve up to 'limit' (inclusive) and gathers all
   primes and those ≡ 3 (mod 19).
   ------------------------------------------------------------------ */
static void rebuild_sieve(uint64_t limit)
{
    if (sieve) free(sieve);
    sieve = (uint8_t *)calloc(limit + 1, 1);
    if (!sieve) abort();

    all_cnt = cong_cnt = 0;

    for (uint64_t i = 2; i <= limit; ++i) {
        if (!sieve[i]) {
            uint32_t p = (uint32_t)i;
            push_uint32(&all_primes, &all_cnt, &all_cap, p);
            if ((p % 19u) == 3u)
                push_uint32(&congr_primes, &cong_cnt, &cong_cap, p);

            if (i * i <= limit) {
                for (uint64_t j = i * i; j <= limit; j += i)
                    sieve[j] = 1;
            }
        }
    }
    sieve_limit = limit;
}

/* ------------------------------------------------------------------
   Ensures that at least 'n' primes ≡ 3 (mod 19) are available.
   ------------------------------------------------------------------ */
static void ensure_primes(idx_t n)
{
    if ((size_t)n <= cong_cnt) return;

    uint64_t limit = sieve_limit ? sieve_limit : 200u;  /* starting guess */

    /* Keep doubling until we have enough primes */
    while ((size_t)n > cong_cnt) {
        limit <<= 1;
        rebuild_sieve(limit);
    }
}

/* ------------------------------------------------------------------
   Return a(n): the n-th prime that is ≡ 3 (mod 19), with a(1) = 3.
   ------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for zero, guard */
    ensure_primes(n);
    return (seq_t)congr_primes[n - 1];
}
