/*  Sequence A092320:  word‑factorable numbers.
 *
 *  A(n) is the n-th integer k such that k is divisible by the number of
 *  letters in the American English word(s) of k (spaces and hyphens
 *  are ignored).  The sequence is generated by searching numbers
 *  starting from 1 until enough terms have been found.
 */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>

/* Lengths of the number words used in the conversion.
 * 0 means “no word”.
 */
static const unsigned char ones_len[20] = {
    0, /* 0 (unused)   */
    3, /* one          */
    3, /* two          */
    5, /* three        */
    4, /* four         */
    4, /* five         */
    3, /* six          */
    5, /* seven        */
    5, /* eight        */
    4, /* nine         */
    3, /* ten          */
    6, /* eleven       */
    6, /* twelve       */
    8, /* thirteen     */
    8, /* fourteen     */
    7, /* fifteen      */
    7, /* sixteen      */
    9, /* seventeen    */
    8, /* eighteen     */
    8  /* nineteen     */
};

static const unsigned char tens_len[10] = {
    0, /* 0 */
    0, /* 1 (unused) */
    6, /* twenty */
    6, /* thirty */
    5, /* forty */
    5, /* fifty */
    5, /* sixty */
    7, /* seventy */
    6, /* eighty */
    6  /* ninety */
};

static const unsigned char scales_len[7] = {
    0,  /* ""          */
    8,  /* thousand    */
    7,  /* million     */
    7,  /* billion     */
    8,  /* trillion    */
    10, /* quadrillion */
    10  /* quintillion */
};

/* Compute the number of letters in the American English name of n
   (spaces and hyphens are ignored). */
static unsigned long word_len_uint64(uint64_t n)
{
    unsigned long len = 0;
    unsigned int scale = 0;

    if (n == 0)
        return 0;  /* not used for our purposes */

    while (n > 0) {
        uint64_t sub = n % 1000;   /* process group of three digits */
        if (sub > 0) {
            unsigned long sublen = 0;

            /* hundreds */
            if (sub >= 100) {
                unsigned int hd = sub / 100;
                sublen += ones_len[hd] + 7; /* "hundred" is 7 letters */
                sub %= 100;
            }
            /* tens and ones */
            if (sub >= 20) {
                unsigned int td = sub / 10;
                sublen += tens_len[td];
                sub %= 10;
            }
            if (sub > 0 && sub < 20) {
                sublen += ones_len[(unsigned int)sub];
            }

            len += sublen;
            if (scale > 0 && scale < sizeof(scales_len))
                len += scales_len[scale];
        }

        n /= 1000;
        ++scale;
    }
    return len;
}

/* Return the n-th term of the sequence (offset 1). */
seq_t a(idx_t n)
{
    static seq_t *terms = NULL;   /* array of found terms */
    static size_t capacity = 0;   /* allocated capacity */
    static size_t count = 0;      /* number of terms stored */
    static uint64_t current = 1;  /* next number to test */

    if (n == 0)
        return 0;  /* undefined, but guard against bad input */

    /* Generate terms until we have at least n of them */
    while (count < n) {
        unsigned long len = word_len_uint64(current);
        if (len > 0 && (current % len) == 0) {
            /* store the term */
            if (count >= capacity) {
                size_t newcap = capacity == 0 ? 64 : capacity * 2;
                seq_t *tmp = (seq_t*)realloc(terms, newcap * sizeof(seq_t));
                if (!tmp) abort(); /* out of memory */
                terms = tmp;
                capacity = newcap;
            }
            terms[count++] = (seq_t)current;
        }
        ++current;
    }

    return terms[n - 1];
}
