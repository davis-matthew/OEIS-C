/* Sequence: the n-th composite number whose decimal digits are all
   in {2,3,5,7}.  The sequence is generated by enumerating all
   numbers composed of the four allowed digits, testing composite
   with is_prime_big, and collecting in ascending numeric order.  */

#include <stdbool.h>
#include "../utils/is_prime_big.h"
#include "../utils/ensure_capacity.h"

static seq_t *s_cache      = NULL;
static size_t s_cache_cap  = 0;
static idx_t  s_cache_len  = 0;
static idx_t  s_next_len   = 2;                         /* start with 2‑digit numbers */
static const seq_t s_digits[4] = {2, 3, 5, 7};

/* Recursive enumeration of all numbers with a given length */
static void gen_len_rec(idx_t len, idx_t pos, seq_t curr) {
    if (pos == len) {
        /* Add only composite numbers (exclude primes and 1) */
        if (!is_prime_big(curr)) {
            if (s_cache_len == s_cache_cap)
                ensure_capacity(s_cache_len + 1, &s_cache_cap,
                                (void **)&s_cache, sizeof(seq_t));
            s_cache[s_cache_len++] = curr;
        }
        return;
    }
    for (int i = 0; i < 4; ++i)
        gen_len_rec(len, pos + 1, curr * 10 + s_digits[i]);
}

/* Public function requested by the build system */
seq_t a(idx_t n) {
    if (n < 1)
        return 0;   /* offset is 1; behaviour below offset is unspecified */

    while (s_cache_len < n) {
        gen_len_rec(s_next_len, 0, 0);
        ++s_next_len;
    }
    return s_cache[n - 1];
}
