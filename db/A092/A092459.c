/*
 * A092459  Numbers that are not Catalan numbers (A000108).
 * https://oeis.org/A092459
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 75, u16 n <= 75, u32 n <= 75, u64 n <= 75, u128 n <= 75,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the complement of the Catalan numbers (A092459).
   The sequence is generated by scanning the natural numbers and
   skipping those that are equal to a Catalan number.
   A small table of Catalan numbers is maintained and extended
   as needed.  This is correct for any n >= 1. */

#include <stdbool.h>

/* Static table of Catalan numbers (unique values). */
static seq_t cat[2000];
static idx_t cat_len = 0;        /* number of stored Catalan numbers   */
static idx_t cat_k   = 0;        /* latest index used in recurrence    */
static seq_t cat_prev = 1;       /* Catalan(k-1) value                 */

/* Initialise the Catalan table with C(0)=1. */
static void init_cat(void)
{
    cat[0] = 1;
    cat_len = 1;
    cat_k = 0;   /* next index to generate is 0 (C(0)) */
    cat_prev = 1;
}

/* Extend the Catalan table until the last value is >= v. */
static void ensure_cat_up_to(seq_t v)
{
    if (cat_len == 0) init_cat();

    while (cat[cat_len - 1] < v) {
        /* Compute the next Catalan number C(k+1) from C(k). */
        seq_t next = cat_prev *
                     ((seq_t)2 * ((seq_t)2 * cat_k + 1)) /
                     ((seq_t)(cat_k + 2));

        cat_k++;
        cat_prev = next;

        /* Store only unique values. */
        if (next != cat[cat_len - 1]) {
            if (cat_len < 2000) {
                cat[cat_len++] = next;
            } else {
                /* overflow protection – unlikely for the intended limits */
            }
        }
    }
}

/* Membership test: is x a Catalan number? */
static bool is_catalan(seq_t x)
{
    ensure_cat_up_to(x);
    for (idx_t i = 0; i < cat_len; ++i) {
        seq_t c = cat[i];
        if (c == x) return true;
        if (c > x) break;
    }
    return false;
}

/* Return the n-th number that is NOT a Catalan number (offset 1). */
seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined for offset 0, return 0 */

    idx_t found = 0;
    seq_t val = 0;

    while (true) {
        if (!is_catalan(val)) {
            found++;
            if (found == n) return val;
        }
        val++;
    }
}
