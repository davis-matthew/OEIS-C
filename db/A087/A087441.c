/* A087441: Numbers k such that for every prime divisor p of k,
   p-1 divides k-1.  The sequence is generated by an incremental
   sieve that tests each integer in ascending order. */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

/* Checks whether a candidate k satisfies the defining property. */
static bool satisfies(uint64_t k)
{
    if (k <= 1)          /* 1 has no prime divisors */
        return true;

    uint64_t kk = k - 1;
    uint64_t tmp = k;

    /* Trial division – try 2 and then odd numbers. */
    if (tmp % 2 == 0) {
        if (kk % (2 - 1) != 0)  /* 2-1 = 1, always passes */
            return false;
        while ((tmp % 2) == 0)
            tmp /= 2;
    }

    for (uint64_t p = 3; p * p <= tmp; p += 2) {
        if (tmp % p == 0) {
            if (kk % (p - 1) != 0)
                return false;
            while ((tmp % p) == 0)
                tmp /= p;
        }
    }

    /* If a prime factor remains. */
    if (tmp > 1) {
        if (kk % (tmp - 1) != 0)
            return false;
    }

    return true;
}

/* Dynamic cache for already generated terms. */
static seq_t *cache = NULL;     /* array of seq_t values */
static size_t cache_size = 0;   /* number of elements stored */
static size_t cache_cap   = 0;   /* allocated capacity */

/* Last tested integer across calls. */
static uint64_t last_k_checked = 0;

/* Grow the cache array when it becomes full. */
static void grow_cache(void)
{
    size_t new_cap = (cache_cap == 0) ? 128 : cache_cap * 2;
    seq_t *new_cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    cache = new_cache;
    cache_cap = new_cap;
}

/* Helper to add a value to the cache. */
static void cache_add(seq_t val)
{
    if (cache_size == cache_cap)
        grow_cache();
    cache[cache_size++] = val;
}

/* Main sequence constructor. */
seq_t a(idx_t n)
{
    /* The OEIS offset is 1 – ignore n == 0. */
    if (n == 0)
        return 0;

    /* Generate terms until we have at least n of them. */
    while (cache_size < (size_t)n) {
        ++last_k_checked;
        if (satisfies(last_k_checked))
            cache_add((seq_t)last_k_checked);
    }

    return cache[ (size_t)(n - 1) ];
}
