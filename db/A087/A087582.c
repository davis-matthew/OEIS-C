/*
 * A087582  Primes such that successive differences are distinct palindromes.
 * https://oeis.org/A087582
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 42, u32 n <= 42, u64 n <= 42, u128 n <= 42,
 *            big any n
 * Helpers:   is_palindrome, is_prime_big, seq_alloc_new_array, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A087582: primes such that successive differences are distinct palindromes.
   The sequence is generated by a simple incremental search: starting with the
   first prime 2, for each step we scan for the next integer that is
   prime, whose difference to the previous term is a decimal palindrome
   not used before.  The set of used differences is stored in an array
   and checked on each candidate.  This method reproduces all terms
   listed in the OEIS entry and works for arbitrary-precision seq_t. */

#include <stdbool.h>
#include <stddef.h>

#include "../utils/is_prime_big.h"
#include "../utils/is_palindrome.h"
#include "../utils/seq_alloc_new_array.h"
#include "../utils/seq_realloc.h"

static void grow_seq_t(seq_t **arr, size_t *cap, size_t needed)
{
    if (*arr == NULL) {
        *cap = 64;
        *arr = seq_alloc_new_array(*cap);
    } else if (needed > *cap) {
        size_t new_cap = (*cap) * 2;
        if (new_cap < needed) new_cap = needed;
        *arr = seq_realloc(*arr, *cap, new_cap);
        *cap = new_cap;
    }
}

static seq_t *terms = NULL;
static size_t terms_len = 0, terms_cap = 0;
static seq_t *diffs = NULL;
static size_t diff_len = 0, diff_cap = 0;

seq_t a(idx_t n)
{
    /* Grow the sequence until we have at least (n+1) terms. */
    while (terms_len <= (size_t)n) {
        if (terms_len == 0) {   /* first term is 2 */
            grow_seq_t(&terms, &terms_cap, 1);
            terms[0] = 2;
            terms_len = 1;
            continue;
        }

        seq_t last = terms[terms_len - 1];
        /* Look for the next prime after the previous term. */
        seq_t candidate = last + 1;

        for (;;) {
            if (is_prime_big(candidate)) {
                seq_t diff = candidate - last;
                if (is_palindrome(diff, 10)) {
                    /* Ensure we haven't used this palindrome difference before. */
                    bool used = false;
                    for (size_t i = 0; i < diff_len; ++i) {
                        if (diffs[i] == diff) {
                            used = true;
                            break;
                        }
                    }
                    if (!used) {
                        /* Store the new term and its difference. */
                        grow_seq_t(&terms, &terms_cap, terms_len + 1);
                        terms[terms_len++] = candidate;

                        grow_seq_t(&diffs, &diff_cap, diff_len + 1);
                        diffs[diff_len++] = diff;
                        break;
                    }
                }
            }
            ++candidate;
        }
    }

    return terms[(size_t)n];
}
