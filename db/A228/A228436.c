/*
 * A228436  Odd n such that n*d are both odious (A000069) or both evil
 *          (A001969) for every divisor d of n.
 * https://oeis.org/A228436
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 38, u32 n <= 4999, u64 n <= 5000,
 *            u128 n <= 5000, big any n
 * Helpers:   check_divs, pop_parity
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A228436 – odd n such that n*d has equal odious/evil parity for all divisors d.
 * The routine builds the sequence by checking each odd integer and caching
 * successful candidates.  It works for any seq_t/idx_t that supports the
 * required arithmetic and bitwise operations.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <math.h>
#include "../utils/check_divs.h"
#include "../utils/pop_parity.h"

/* --------------------------------------------------------------------- */
/*  Simple dynamic prime list (≤ 2^32).  Generated by trial division.     */
static uint32_t *prime_list = NULL;
static size_t prime_cap  = 0;
static size_t prime_cnt  = 0;
static uint32_t last_candidate = 3;

static void ensure_primes_upto(uint32_t limit)
{
    if (prime_cnt == 0) {
        /* first prime 2 */
        prime_cap = 16;
        prime_list = (uint32_t *)malloc(prime_cap * sizeof(uint32_t));
        prime_list[prime_cnt++] = 2;
    }

    /* extend the list until last_candidate > limit */
    while (last_candidate <= limit) {
        bool is_prime = true;
        for (size_t i = 0; i < prime_cnt; ++i) {
            uint32_t p = prime_list[i];
            if ((uint64_t)p * (uint64_t)p > last_candidate) break;
            if (last_candidate % p == 0) { is_prime = false; break; }
        }
        if (is_prime) {
            if (prime_cnt == prime_cap) {
                prime_cap <<= 1;
                prime_list =
                    (uint32_t *)realloc(prime_list,
                                        prime_cap * sizeof(uint32_t));
            }
            prime_list[prime_cnt++] = last_candidate;
        }
        last_candidate += 2;   /* only odd candidates needed */
    }
}

/* --------------------------------------------------------------------- */

static bool is_good(uint64_t n)
{
    if ((n & 1ULL) == 0)  /* only odd numbers are allowed */
        return false;

    uint32_t factors[32];
    unsigned exps[32];
    size_t fc = 0;

    uint64_t t = n;
    /* ensure primes up to sqrt(t) */
    uint32_t limit = (uint32_t) (sqrt((double) t) + 1.0);
    ensure_primes_upto(limit);

    for (size_t i = 0; i < prime_cnt; ++i) {
        uint32_t p = prime_list[i];
        if ((uint64_t)p * (uint64_t)p > t) break;
        if (t % p == 0) {
            unsigned e = 0;
            while (t % p == 0) {
                t /= p;
                ++e;
            }
            factors[fc]   = p;
            exps[fc++]    = e;
        }
    }
    if (t > 1) {          /* remaining prime factor */
        factors[fc] = (uint32_t)t;
        exps[fc]    = 1;
        ++fc;
    }

    bool first = true;
    unsigned target = 0;
    return check_divs(factors, exps, fc, 0, 1, n, &first, &target);
}

/* --------------------------------------------------------------------- */
/*  Cache of found terms.  The array grows as needed. */
static seq_t *cache = NULL;
static size_t cache_size = 0;
static size_t cache_cap  = 0;
static uint64_t next_candidate = 1;   /* start from 1 */

static void grow_cache(idx_t target)
{
    while (cache_size < (size_t)target) {
        if (is_good(next_candidate)) {
            if (cache_size == cache_cap) {
                cache_cap = cache_cap == 0 ? 16 : cache_cap * 2;
                cache = (seq_t *)realloc(cache,
                                         cache_cap * sizeof(seq_t));
            }
            cache[cache_size++] = (seq_t)next_candidate;
        }
        next_candidate += 2;     /* keep only odd numbers */
    }
}

/* --------------------------------------------------------------------- */
/*  Public entry point */
extern seq_t a(idx_t n)
{
    if (n == 0) return 0;
    grow_cache(n);
    return cache[n - 1];
}
