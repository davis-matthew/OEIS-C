/* Sequence A228119: a(n) is the n‑th positive integer m such that
   m * product_of_digits(m) + 1 is prime.
   Sequence values are generated by a simple search over natural numbers. */
#include <stddef.h>
#include <stdbool.h>
#include "../utils/digit_product.h"
#include "../utils/is_prime_big.h"
#include "../utils/ensure_capacity.h"
#include "../utils/alloc_seq_array.h"

seq_t a(idx_t n)
{
    static seq_t *cache      = NULL;
    static size_t cache_cap  = 0;
    static size_t cache_len  = 0;
    static idx_t  next       = 1;   /* next candidate to test */

    if (n == 0) return 0;  /* undefined for n<=0, return 0 */

    /* Ensure cache can hold at least n elements. */
    if (cache == NULL) {
        cache_cap = 32;
        cache = alloc_seq_array(cache_cap);
    }

    if (n > cache_len) {
        /* Grow cache to accommodate requested index. */
        ensure_capacity((size_t)n, &cache_cap, (void **)&cache, sizeof(seq_t));

        /* Generate terms until we have at least n. */
        while (cache_len < n) {
            seq_t prod = digit_product((seq_t)next);
            seq_t val  = next * prod + 1;
            if (is_prime_big(val))
                cache[cache_len++] = next;
            next++;
        }
    }

    return cache[n - 1];
}
