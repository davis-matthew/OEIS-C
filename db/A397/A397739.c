/*
 * A397739  Squarefree composite numbers k whose second smallest distinct
 *          prime factor is smaller than the square of the least prime factor.
 * https://oeis.org/A397739
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 39, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   factor_u64, is_squarefree
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A397739: squarefree composite numbers k whose second smallest distinct prime factor
   is smaller than the square of the least prime factor.  The sequence is generated by
   scanning integers starting from 6, testing the conditions, and storing the qualifying
   numbers in an expanding cache. */

/* Helper prototypes provided by the build framework */
#include "../utils/is_squarefree.h"
#include "../utils/factor_u64.h"

/* Standard headers */
#include <stddef.h>
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Helper: expand a dynamic array when needed */
static void ensure_capacity(size_t needed, size_t *cap, void **ptr, size_t elem_size)
{
    if (needed <= *cap) return;
    size_t newcap = (*cap == 0) ? 8 : (*cap << 1);
    while (newcap < needed) newcap <<= 1;
    *ptr = realloc(*ptr, newcap * elem_size);
    *cap = newcap;
}

/* Cache of computed terms */
static seq_t *cache = NULL;        /* array of terms */
static size_t cache_len = 0;       /* number of terms stored */
static size_t cache_cap = 0;       /* allocated capacity of cache */
static uint64_t next_candidate = 6;/* next integer to test */

/* Generate terms until the cache holds at least n terms */
static void generate_terms(idx_t n)
{
    if (cache_len >= (size_t)n) return;

    uint64_t primes[64];
    uint64_t exps[64];
    size_t pf_cnt;

    while (cache_len < (size_t)n)
    {
        /* skip numbers too small to be a composite with at least two distinct primes */
        if (next_candidate < 6) { next_candidate = 6; }

        /* Use the framework helper to test square‑freeness */
        if (!is_squarefree((seq_t)next_candidate))
        {
            ++next_candidate;
            continue;
        }

        /* Factorize and count distinct primes */
        pf_cnt = 0;
        factor_u64(next_candidate, primes, exps, &pf_cnt);
        if (pf_cnt < 2)   /* not composite or not enough distinct primes */
        {
            ++next_candidate;
            continue;
        }

        /* Least and second least distinct prime factors */
        uint64_t lpf  = primes[0];
        uint64_t slpf = primes[1];

        /* Check the defining inequality:  slpf < lpf^2 */
        if (slpf < lpf * lpf)
        {
            ensure_capacity(cache_len + 1, &cache_cap, (void **)&cache, sizeof(seq_t));
            cache[cache_len++] = (seq_t)next_candidate;
        }

        ++next_candidate;
    }
}

/* Public entry point for the sequence */
seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;  /* undefined for n == 0, return 0 */
    generate_terms(n);
    return cache[n - 1];
}
