/*
 * A180259  Squares which are the sum of consecutive squares starting with
 *          25^2.
 * https://oeis.org/A180259
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, fini, full
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 6, u64 n <= 8, u128 n <= 8,
 *            big any n
 * Validated: full, pass, 8 terms through n = 8 (2026-11-02)
 * Helpers:   ipow_i32
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes terms of OEIS sequence A180259 – squares which are the sum of
 * consecutive squares starting with 25^2.
 *
 * The sequence is finite. The first eight terms are generated by
 * searching m = 25,26,… until the sum S(m) = ∑_{i=25}^m i^2 is a perfect
 * square.  The found values are cached for subsequent calls.
 * For n > 8 the function returns 0, since no further terms are known. */

#include <stdbool.h>
#include <stdint.h>
#include "../utils/ipow_i32.h"

/* Floor square root by binary search */
static inline seq_t floor_sqrt(seq_t x)
{
    seq_t lo = 0, hi = 1;
    while (ipow_i32(hi, 2) <= x)
        hi <<= 1;
    while (lo < hi)
    {
        seq_t mid = (lo + hi) >> 1;
        seq_t mid2 = mid * mid;
        if (mid2 <= x)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

static bool _seq_initialized = false;
static seq_t _seq_cache[8];
static idx_t _seq_size = 0;

static void _seq_init(void)
{
    _seq_initialized = true;
    _seq_size = 0;
    seq_t m = 25;
    while (_seq_size < 8) {
        /* compute sum_{i=25}^m i^2 = (m-24)*(2*m^2+51*m+1225)/6 */
        seq_t term = (m - 24) * ( (2 * m * m) + 51 * m + 1225 ) / 6;
        seq_t sqrt_term = floor_sqrt(term);
        if (sqrt_term * sqrt_term == term) {
            _seq_cache[_seq_size++] = term;
        }
        ++m;
    }
}

seq_t a(idx_t n)
{
    if (!_seq_initialized) {
        _seq_init();
    }
    if (n == 0 || n > _seq_size) {
        return (seq_t)0;   /* no term defined */
    }
    return _seq_cache[n - 1];
}
