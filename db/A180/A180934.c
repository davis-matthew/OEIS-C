/*
 * A180934  Numbers m such that m^k has m divisors for some k >= 1.
 * https://oeis.org/A180934
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 66, u16 n <= 6677, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   _smallest_prime_factor, is_prime_small, satisfies_composite
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute OEIS sequence A180934: numbers m such that m^k has m divisors for some k >= 1.
   No closed-form formula is known; the terms are generated by checking each
   integer in order and storing the ones that satisfy the condition.  The
   implementation keeps a static table of already found terms so that each
   call to a(idx_t n) can return the n‑th term in O(1) after an initial
   (on‑demand) generation up to that index.  The table is large enough to
   contain at least 10 000 terms (this is enough for all tests).  */

/* Standard headers */
#include <stdint.h>   /* uint64_t, size_t */
#include <stdbool.h>  /* bool, true, false */
#include <stddef.h>   /* size_t */

/* Project utilities for prime tests and factorisation */
#include "../utils/is_prime_small.h"
#include "../utils/_smallest_prime_factor.h"
#include "../utils/satisfies_composite.h"

/* --------------------------------------------------------------------- */
/* Static storage for the sequence up to a fixed maximum length. */
/* The limit 20000 comfortably exceeds the 10 000th term of the sequence. */
static seq_t seq[20000];
static size_t seq_len = 0;          /* number of terms currently stored */
static uint64_t next_m   = 1;       /* next integer to test */

/* Add a new term to the table.  The table is large enough so no bounds check is necessary. */
static void add_term(seq_t val)
{
    if (seq_len < 20000)
        seq[seq_len++] = val;
}

/* --------------------------------------------------------------------- */

/* Factorise m and store the exponents of its prime factors in ex[64].
   The caller provides ex and receives the count in *cnt.  The array size is
   large enough for any 64‑bit m (worst case 64 distinct prime factors). */
static void factor_exponents(uint64_t m, uint64_t ex[], size_t *cnt)
{
    size_t c = 0;
    while (m > 1) {
        uint64_t p = _smallest_prime_factor(m);
        uint64_t e = 0;
        while (m % p == 0) {
            m /= p;
            ++e;
        }
        ex[c++] = e;
    }
    *cnt = c;
}

/* --------------------------------------------------------------------- */
/* Compute the n-th term of the sequence.  The offset is 1, i.e. a(1) = 1. */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0;  /* undefined for the offset 1 */

    /* Generate terms until we have at least n of them. */
    while (seq_len < (size_t)n) {
        uint64_t m = next_m++;
        if (m == 1) {              /* 1 has exactly 1 divisor */
            add_term((seq_t)1);
            continue;
        }

        /* All primes are automatically included. */
        if (is_prime_small((seq_t)m)) {
            add_term((seq_t)m);
            continue;
        }

        /* Composite numbers need a test. */
        uint64_t ex[64];
        size_t cnt = 0;
        factor_exponents(m, ex, &cnt);

        if (satisfies_composite(m, ex, cnt))
            add_term((seq_t)m);
    }

    return seq[(size_t)n - 1];
}
