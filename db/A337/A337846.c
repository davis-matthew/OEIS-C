/*
 * A337846  Odd integers k such that 2^((k-1)/2) == 1 (mod k*(k-2)).
 * https://oeis.org/A337846
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 2, u32 n <= 11, u64 n <= 34, u128 n <= 34,
 *            big any n
 * Helpers:   mod_pow
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function computes terms of OEIS A337846:
   odd integers k such that 2^((k-1)/2) ≡ 1 (mod k*(k-2)).
   The sequence is generated by brute‑force searching over odd
   numbers of the form 8m+1 and testing the congruence with mod_pow. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/mod_pow.h"       /* provides seq_t mod_pow(seq_t, uint64_t, seq_t) */

seq_t a(idx_t n)
{
    /* static cache of found sequence elements */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;
    /* next candidate of the form 8*m+1 to test, starting after 1 */
    static idx_t next_candidate = 9;

    /* the sequence is defined for n ≥ 1; return 0 otherwise for safety */
    if (n == 0) return (seq_t)0;

    /* ensure we have at least n terms in cache */
    while (cache_len < (size_t)n)
    {
        /* grow cache if needed */
        if (cache_len == cache_cap)
        {
            size_t new_cap = (cache_cap == 0) ? 4 : cache_cap * 2;
            seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            if (!tmp) abort();       /* allocation failure */
            cache = tmp;
            cache_cap = new_cap;
        }

        /* candidate k of the form 8*m+1 */
        idx_t k = next_candidate;
        next_candidate += 8;          /* advance to the next 8m+1 */

        /* compute modulus m = k*(k-2) as a seq_t (wrapping on overflow) */
        seq_t kk = (seq_t)k;
        seq_t m = kk * (kk - 2);
        if (m == 0) continue;        /* skip if modulus wrapped to zero */

        /* exponent e = (k-1)/2 */
        uint64_t e = ((uint64_t)k - 1) >> 1;

        /* compute 2^e mod m */
        seq_t val = mod_pow((seq_t)2, e, m);

        /* check the congruence */
        if (val == (seq_t)1)
        {
            cache[cache_len++] = kk;   /* store found term */
        }
    }

    return cache[(size_t)n - 1];
}
