/*
 * A337103  Numbers k with a divisor pair (d,k/d) whose harmonic mean is an
 *          integer.
 * https://oeis.org/A337103
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 27, u16 n <= 61, u32 n <= 61, u64 n <= 61, u128 n <= 61,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function computes the OEIS sequence A337103
   (Numbers k with a divisor pair (d,k/d) whose harmonic mean
   is an integer).  The sequence is generated by testing each
   integer k starting from 1 and storing those that satisfy the
   harmonic‑mean condition.  The result a(n) for 1‑based index n
   is returned.  The implementation uses only integer arithmetic,
   works for any seq_t (including arbitrary‑precision types), and
   memoises computed terms for efficient repeated calls. */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

/* Integer square root for uint64_t (used by the divisor loop). */
static inline uint64_t uint64_isqrt(uint64_t n)
{
    uint64_t x = 0;
    uint64_t y = ((uint64_t)1 << 32); /* 2^32 > sqrt(UINT64_MAX) */
    while (y > 0) {
        if (x + y <= n / (x + y))
            x += y;
        y >>= 1;
    }
    return x;
}

/* Return true iff the integer k has a divisor pair (d, k/d)
   with integer harmonic mean 2*d*(k/d)/(d + k/d). */
static inline bool has_integer_harmonic_mean(uint64_t k)
{
    uint64_t limit = uint64_isqrt(k);
    for (uint64_t d = 1; d <= limit; ++d) {
        if (k % d != 0)
            continue;
        uint64_t e   = k / d;           /* k/d                */
        uint64_t sum = d + e;           /* d + e              */

        /* test if 2*k is divisible by sum without overflow */
        uint64_t rem = k % sum;
        if ((rem * 2ULL) % sum == 0ULL)
            return true;
    }
    return false;
}

/* Main OEIS function: a(idx_t n) returns the n‑th term (1‑based). */
seq_t a(idx_t n)
{
    /* --- memoisation state ------------------------------------------- */
    static seq_t *cache   = NULL;   /* array of found terms          */
    static size_t    cap   = 0;     /* allocated capacity            */
    static size_t    len   = 0;     /* number of stored terms        */
    static uint64_t  next  = 1;     /* next integer to test          */

    if (n == 0)        /* the sequence is 1‑based */
        return (seq_t)0;

    /* Generate terms until we have at least n of them */
    while (len < (size_t)n) {
        uint64_t k = next++;
        if (!has_integer_harmonic_mean(k))
            continue;                      /* skip non‑members */

        /* Grow cache if necessary */
        if (len == cap) {
            size_t new_cap = cap ? cap * 2 : 256;
            seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            if (!tmp) exit(1);              /* allocation failure */
            cache = tmp;
            cap   = new_cap;
        }

        /* Store the term (truncated if it does not fit in seq_t) */
        cache[len++] = (seq_t)k;
    }

    /* a(1) is cache[0], a(2) is cache[1], ... */
    return cache[n - 1];
}
