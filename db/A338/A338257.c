/*
 * A338257  Positive integers k with digits in nondecreasing order for which
 *          the digital sum contains the same distinct digits as the digital
 *          product.
 * https://oeis.org/A338257
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) = n-th integer whose decimal digits are in non‑decreasing
 *            order and for which the set of distinct digits of its digital
 *            sum equals the set of distinct digits of its digital product
 * Range:     u8 n <= 12, u16 n <= 20, u32 n <= 38, u64 n <= 38, u128 n <= 38,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence is generated on demand with a static cache.  Numbers are
   produced in numeric order by increasing length, and only the first
   n terms are computed, so the function works in O(n) time for each
   call and behaves correctly regardless of call order. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Forward declarations for seq_t operations are assumed to be provided
   by the build (integer types have the usual operators, arbitrary
   precision types have the appropriate overloads). */

/* --------------------------------------------------------------------
   Global cache of found terms.  The array is kept sorted in increasing
   order because numbers are generated by length and by
   non‑decreasing digits. */
static seq_t *terms      = NULL;   /* array of found terms          */
static size_t terms_len  = 0;      /* number of terms stored        */
static size_t terms_cap  = 0;      /* current array capacity        */
static int    processed_len = 0;   /* longest length generated so far */

/* --------------------------------------------------------------------
   Compute a 10‑bit mask of the distinct decimal digits of x.
   Bits 0–9 correspond to digits 0–9.  */
static inline uint16_t
digit_mask(seq_t x)
{
    if (x == 0)                     /* digit 0 only */
        return 1u;                  /* bit 0 set              */
    uint16_t mask = 0;
    while (x != 0)
    {
        int d = (int)(x % 10);      /* digit, works for seq_t  */
        mask |= (uint16_t)(1u << d);
        x /= 10;
    }
    return mask;
}

/* --------------------------------------------------------------------
   Append a term to the global array, growing it if necessary. */
static void
push_term(seq_t val)
{
    if (terms_len == terms_cap)
    {
        size_t new_cap = (terms_cap > 0 ? terms_cap * 2 : 64);
        /* Cast the void* returned by realloc so that the code compiles
           in both C and C++.  In C the cast is unused but harmless.   */
        seq_t *newp = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
        if (newp == NULL)
            abort();                /* unrecoverable allocation failure */
        terms      = newp;
        terms_cap  = new_cap;
    }
    terms[terms_len++] = val;
}

/* --------------------------------------------------------------------
   Recursively generate all non‑decreasing‑digit numbers of a given
   length L.  Parameters:
   - pos   : current position (0‑based)
   - last  : smallest digit allowed at this position (ensures non‑decreasing)
   - val   : numeric value built so far
   - sum   : sum of digits built so far (int)
   - prod  : product of digits built so far (seq_t)   */
static void
generate_rec(int L, int pos, int last, seq_t val, int sum, seq_t prod)
{
    if (pos == L)
    {
        if (digit_mask((seq_t)sum) == digit_mask(prod))
            push_term(val);
        return;
    }

    for (int d = last; d <= 9; ++d)
    {
        seq_t new_val  = val * 10 + d;
        int   new_sum  = sum + d;
        seq_t new_prod = prod * (seq_t)d;
        generate_rec(L, pos + 1, d, new_val, new_sum, new_prod);
    }
}

/* Generate all numbers of length L.  The first digit is at least 1,
   so leading zeros are never produced. */
static void
generate_len(int L)
{
    generate_rec(L, 0, 1, (seq_t)0, 0, (seq_t)1);
}

/* --------------------------------------------------------------------
   Public sequence function.  Calls are independent; a static cache
   of previously generated terms is reused to avoid repeat work. */
seq_t
a(idx_t n)
{
    if (n == 0)                /* sequence defined for n >= 1; guard */
        return (seq_t)0;

    /* generate terms until we have at least n of them */
    while (terms_len < (size_t)n)
    {
        ++processed_len;        /* move to the next length */
        generate_len(processed_len);
    }

    return terms[n - 1];
}
