/* OEIS A338679
   Formula: a(n) = Sum_{k=0..n} p(n,k) * 10^(n-k),
   where p(n,k) is the number of partitions of n into k parts.
   The sequence is generated by the product ∏_{k≥1} 1/(1‑10^(k‑1) x^k).
   Implementation uses a standard partition‑type DP that multiplies each
   partial sum by the corresponding weight 10^(k‑1).  The DP runs in
   O(n²) time and uses O(n) extra space. */

#include <stdlib.h>

/* External linkage as required */
seq_t a(idx_t n)
{
    /* Allocate array for dynamic programming */
    seq_t *dp = (seq_t *)malloc((size_t)(n + 1) * sizeof(seq_t));
    if (!dp)
        return 0;               /* allocation failure – unlikely for n≤10000 */

    dp[0] = 1;                  /* empty partition */
    for (idx_t i = 1; i <= n; ++i)
        dp[i] = 0;

    /* factor = 10^(k-1) for the current part size k */
    seq_t factor = 1;

    for (idx_t k = 1; k <= n; ++k) {
        for (idx_t i = k; i <= n; ++i) {
            /* dp[i] += dp[i-k] * factor  */
            dp[i] = dp[i] + (dp[i - k] * factor);
        }
        /* Prepare factor for next k: factor *= 10 */
        factor = factor * 10;
    }

    seq_t result = dp[n];
    free(dp);
    return result;
}
