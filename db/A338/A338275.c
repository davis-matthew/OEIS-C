/*
 * A338275  Array of triples read by antidiagonals of triples, giving analogs
 *          of Pythagorean triples [a,b,c] being [odd,even,odd] consistent
 *          with the functions U(i;n,k) described in A327263.
 * https://oeis.org/A338275
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 63, u16 n <= 63, u32 n <= 63, u64 n <= 63, u128 n <= 63,
 *            big any n
 * Helpers:   triple_a, triple_b, triple_c
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Implementation of OEIS sequence A338275.
 * The sequence is generated by reading the array of triples
 * (a,b,c) defined by the parameters m (odd >=3), n (even >=2, n<m),
 * and i (positive integer).  For each pair (m,n) an infinite
 * sequence of triples is produced:
 *
 *      a = i * ((m-1)^2 - n^2)/2 + (2*m-1)
 *      b = n * ( i*(m-1) + 2 )
 *      c = a + i*n^2
 *
 * The 2‑D table of triples is indexed by row r = index of (m,n)
 * (rows sorted by m then n) and column i (starting from 1).
 * The sequence is obtained by reading the table along antidiagonals:
 * for each diagonal sum s = r + (i-1) we visit in order
 *   r = 0..s   with i = s-r+1.
 *
 *  The generation below constructs only the necessary rows on demand,
 *  then walks the antidiagonals until the requested index is reached.
 */

#include <stdint.h>
#include <stdlib.h>
#include "../utils/triple_a.h"
#include "../utils/triple_b.h"
#include "../utils/triple_c.h"

/* ---------- main sequence function ---------- */
seq_t a(idx_t n)
{
    /* n is 1‑based; target zero‑based index */
    if (n == 0) return 0;                /* offset is 1, but guard */

    /* Determine how many diagonals we need to process to cover position n
       The total number of values through diagonal s is
           T(s) = 3 * (s+1)(s+2)/2
       We find smallest s with T(s) >= n. */
    size_t s = 0;
    uint64_t terms = 0;
    while (terms < (uint64_t)n) {
        terms += 3 * (s + 1);
        ++s;
    }
    size_t max_s = s - 1;                 /* last diagonal processed */
    size_t pair_cnt = max_s + 1;          /* rows needed = largest r index + 1 */

    /* Generate all (m,n) pairs up to pair_cnt.
       rows are sorted by m then n (n even). */
    uint64_t *m_arr = (uint64_t *)malloc(sizeof(uint64_t) * pair_cnt);
    uint64_t *n_arr = (uint64_t *)malloc(sizeof(uint64_t) * pair_cnt);
    if (!m_arr || !n_arr) { return 0; }  /* safety */

    size_t idx = 0;
    for (uint64_t m = 3; idx < pair_cnt; m += 2) {
        for (uint64_t p = 2; p <= m - 1; p += 2) {
            if (idx >= pair_cnt) break;
            m_arr[idx] = m;
            n_arr[idx] = p;
            ++idx;
        }
    }

    /* Walk antidiagonals until we reach the desired term */
    uint64_t target = (uint64_t)n - 1;     /* zero‑based target */
    uint64_t pos = 0;                     /* current position in sequence */

    for (size_t sum = 0; ; ++sum) {
        for (size_t r = 0; r <= sum; ++r) {
            if (r >= pair_cnt) continue;           /* safety check */
            uint64_t j = sum - r;                  /* i-1 */
            seq_t i = (seq_t)(j + 1);              /* i starts at 1 */

            seq_t m = (seq_t)m_arr[r];
            seq_t nn = (seq_t)n_arr[r];

            seq_t A = triple_a(i, m, nn);
            if (pos == target) { free(m_arr); free(n_arr); return A; }
            ++pos;

            seq_t B = triple_b(i, m, nn);
            if (pos == target) { free(m_arr); free(n_arr); return B; }
            ++pos;

            seq_t C = triple_c(A, i, nn);
            if (pos == target) { free(m_arr); free(n_arr); return C; }
            ++pos;
        }
    }

    /* Unreachable, but keep compiler happy */
    free(m_arr); free(n_arr);
    return 0;
}
