/* OEIS A036920: Composite numbers n such that digit sum of n equals
   digit sum of the sum of its prime factors (counted with multiplicity).
   The sequence is generated by searching the integers in ascending
   order and storing the qualifying composites. */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* Utility to factor a 64‑bit integer and return primes, exponents and count. */
#include "../utils/factor_u64.h"

/* Compute digit sum of a 64‑bit integer.  Result fits in any seq_t. */
static seq_t digit_sum_uint64(uint64_t x)
{
    seq_t s = 0;
    while (x) {
        s += (seq_t)(x % 10);
        x /= 10;
    }
    return s;                     /* digit sum of 0 is 0 */
}

/* Compute digit sum of an unsigned 128‑bit integer.  Result fits in any seq_t. */
#if defined(__SIZEOF_INT128__)
static seq_t digit_sum_uint128(unsigned __int128 x)
{
    seq_t s = 0;
    while (x) {
        s += (seq_t)(x % 10);
        x /= 10;
    }
    return s;
}
#else
/* Fallback: use 64‑bit repetition (won't be needed for 64‑bit builds). */
static seq_t digit_sum_uint128(unsigned __int128 x)
{
    /* Break the 128‑bit number into two 64‑bit parts. */
    uint64_t hi = (uint64_t)(x >> 64);
    uint64_t lo = (uint64_t)x;
    return digit_sum_uint64(hi) + digit_sum_uint64(lo);
}
#endif

seq_t a(idx_t n)
{
    /* Static cache of found terms. */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;
    static uint64_t next_candidate = 4;      /* start search from 4 */

    /* Allocate initial cache space. */
    if (cache == NULL) {
        cache_cap = 1024;
        cache = (seq_t*)malloc(cache_cap * sizeof(seq_t));
        cache_len = 0;
    }

    /* Search until we have at least n terms. */
    while (cache_len < n) {
        uint64_t cand = next_candidate++;

        /* Factor the candidate. */
        uint64_t primes[64];
        uint64_t exps[64];
        size_t cnt = 0;
        factor_u64(cand, primes, exps, &cnt);

        /* Determine if candidate is composite: more than one prime factor
           or a prime factor repeated. */
        bool is_composite = (cnt > 1) || (cnt == 1 && exps[0] > 1);
        if (!is_composite) {
            continue;    /* skip primes */
        }

        /* Digit sum of the candidate. */
        seq_t dsum_cand = digit_sum_uint64(cand);

        /* Compute sum of prime factors (with multiplicity) using 128‑bit
           arithmetic to avoid overflow. */
        unsigned __int128 sum_pf = 0;
        for (size_t i = 0; i < cnt; ++i) {
            sum_pf += (unsigned __int128)primes[i] * (unsigned __int128)exps[i];
        }

        /* Digit sum of the sum of prime factors. */
        seq_t dsum_pf = digit_sum_uint128(sum_pf);

        if (dsum_cand == dsum_pf) {
            /* Store the term in the cache. */
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t*)realloc(cache, cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = (seq_t)cand;
        }
    }

    return cache[n - 1];
}
