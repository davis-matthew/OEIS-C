/*
 * A162317  A positive integer k is included if |d(k+1) - d(k)| is a prime,
 *          where d(k) is the number of divisors of k.
 * https://oeis.org/A162317
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 65, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   divisor_count_u64, is_prime_small, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A162317: a(n) is the nth integer k such that |d(k+1)−d(k)| is prime. */
/* The sequence is generated by a linear scan with memoisation. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/divisor_count_u64.h"
#include "../utils/is_prime_small.h"
#include "../utils/seq_realloc.h"

static seq_t *terms = NULL;          /* stored terms (k-values)          */
static size_t terms_cap = 0;         /* capacity of terms array          */
static idx_t   terms_cnt = 0;        /* number of terms already stored   */
static uint64_t next_k   = 1;        /* next k to test                   */

/* Grow the terms array so that it can hold at least one more element. */
static void ensure_capacity(void)
{
    if (terms_cnt < terms_cap)
        return;
    size_t new_cap = terms_cap ? terms_cap << 1 : 16;
    seq_t *tmp = seq_realloc(terms, terms_cap, new_cap);
    if (!tmp)
        abort();               /* allocation failed – terminate   */
    terms = tmp;
    terms_cap = new_cap;
}

/* Append a new found term. */
static void add_term(seq_t k)
{
    ensure_capacity();
    terms[terms_cnt++] = k;
}

/* Return the nth term (1‑based). */
seq_t a(idx_t n)
{
    while (terms_cnt < n) {
        uint64_t d_k  = divisor_count_u64(next_k);
        uint64_t d_k1 = divisor_count_u64(next_k + 1);
        uint64_t diff = d_k1 > d_k ? d_k1 - d_k : d_k - d_k1;
        if (diff > 1 && is_prime_small((seq_t)diff))
            add_term((seq_t)next_k);
        next_k++;
    }
    return terms[n - 1];
}
