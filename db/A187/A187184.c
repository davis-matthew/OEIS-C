/*
 * A187184  Parse the infinite string 0123450123450123450... into distinct
 *          phrases 0, 1, 2, 3, 4, 5, 01, 23, 45, 012, 34, ...; a(n) = length
 *          of n-th phrase.
 * https://oeis.org/A187184
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 1000, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A187184 – parse the infinite string 012345012345… into distinct phrases.
   Recurrence for n > 42:
     a(n) = a(n-1) + a(n-36) - a(n-37)
   Initial values for 1 <= n <= 42 are generated by brute force. */
#include <stddef.h>
#include <stdlib.h>
#include <string.h>

/* static cache for previously computed terms */
static seq_t *a_cache   = NULL;   /* 1‑based indexing in cache[0..len-1] */
static size_t cache_cap = 0;      /* allocated capacity */
static size_t cache_len = 0;      /* number of terms stored (0 if none) */

/* guarantee that the cache can hold at least 'need' terms (1‑based) */
static void grow_cache(size_t need)
{
    if (need <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 64;
    while (new_cap < need)
        new_cap *= 2;
    a_cache = (seq_t *)realloc(a_cache, new_cap * sizeof(seq_t));
    cache_cap = new_cap;
}

/* generate the first 42 terms by the definition (brute force). */
static void generate_initial_terms(void)
{
    const size_t INIT_N = 42;
    /* store used phrases; 0‑based positions; phrase length up to 50 is safe */
    static int used_phrase[42][50];
    static size_t used_len[42];
    size_t used_cnt = 0;
    idx_t pos = 1;          /* 1‑based position in the infinite string */

    for (size_t idx = 0; idx < INIT_N; ++idx) {
        size_t cand_len = 1;
        /* search for the shortest unused phrase */
        while (1) {
            int cand[50];
            for (size_t i = 0; i < cand_len; ++i)
                cand[i] = (int)((pos + i - 1) % 6);   /* digits 0..5 */

            int found = 0;
            for (size_t k = 0; k < used_cnt; ++k) {
                if (used_len[k] == cand_len) {
                    int ok = 1;
                    for (size_t j = 0; j < cand_len; ++j) {
                        if (used_phrase[k][j] != cand[j]) { ok = 0; break; }
                    }
                    if (ok) { found = 1; break; }
                }
            }
            if (!found)
                break;                     /* candidate accepted */
            ++cand_len;                     /* try longer phrase */
        }

        /* store length of the chosen phrase */
        a_cache[idx] = (seq_t)cand_len;

        /* remember this phrase for future checks */
        for (size_t j = 0; j < cand_len; ++j)
            used_phrase[used_cnt][j] = (int)((pos + j - 1) % 6);
        used_len[used_cnt] = cand_len;
        ++used_cnt;

        pos += cand_len;   /* advance position in the infinite string */
    }
    cache_len = INIT_N;
}

/* public function required by the build */
seq_t a(idx_t n)
{
    if (n < 1)
        return 0;             /* undefined indices are treated as 0 */

    size_t nsize = (size_t)n;
    grow_cache(nsize);

    /* first generate the small initial block if necessary */
    if (cache_len == 0)
        generate_initial_terms();

    if (nsize <= cache_len)
        return a_cache[nsize - 1];

    /* extend the cache using the recurrence a(n) = a(n-1)+a(n-36)-a(n-37) */
    for (size_t i = cache_len; i < nsize; ++i) {
        /* i is 0‑based index of a(i+1) */
        seq_t prev   = a_cache[i - 1];
        seq_t term36 = a_cache[i - 36];
        seq_t term37 = a_cache[i - 37];
        a_cache[i] = prev + term36 - term37;
    }
    cache_len = nsize;
    return a_cache[nsize - 1];
}
