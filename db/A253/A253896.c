#include <stdlib.h> /* malloc, realloc, abort */

/* Sequence generated by the rational function
   G(x) = -x^4*(2*x^10-4*x^9+2*x^8-2*x^7+2*x^5+2*x^4+2*x^3+2*x^2+x+1)
          /((x-1)^3*(x+1)*(x^2+1)).
   It satisfies the linear recurrence
        a(n) = 2*a(n-1) - a(n-2) + a(n-4) - 2*a(n-5) + a(n-6)   for n ≥ 16
   with initial values (1‑indexed)
        a(1)=0, a(2)=0, a(3)=0, a(4)=1, a(5)=3, a(6)=7,
        a(7)=13, a(8)=22, a(9)=34, a(10)=48, a(11)=62,
        a(12)=81, a(13)=99, a(14)=121, a(15)=143. */

seq_t a(idx_t n)
{
    /* fast return for the first 15 terms */
    static const seq_t init[15] = {
        0, 0, 0, 1, 3, 7, 13, 22, 34, 48, 62, 81, 99, 121, 143
    };
    if (n <= 15)
        return init[(idx_t)n - 1];

    /* memoisation cache (1‑based) */
    static seq_t *cache = NULL;   /* will hold values a(1)..a(max) */
    static idx_t cache_cap = 0;   /* allocated size (≥ n+1) */
    static idx_t cache_last = 0;  /* highest index already computed */

    /* grow the cache if needed */
    if (n + 1 > cache_cap) {
        idx_t new_cap = cache_cap ? cache_cap * 2 : 16;
        while (new_cap <= n)
            new_cap <<= 1;
        seq_t *tmp = (seq_t *)realloc(cache, sizeof(seq_t) * new_cap);
        if (!tmp) abort();   /* allocation failed */
        cache = tmp;
        cache_cap = new_cap;
    }

    /* compute missing terms */
    for (idx_t i = cache_last + 1; i <= n; ++i) {
        if (i <= 15) {
            /* store the known initial values for consistency */
            cache[i] = init[(idx_t)i - 1];
        } else {
            /* recurrence using only + and - to stay valid in C and C++ */
            cache[i] = cache[i - 1] + cache[i - 1]
                       - cache[i - 2]
                       + cache[i - 4]
                       - cache[i - 5]
                       - cache[i - 5]
                       + cache[i - 6];
        }
    }
    cache_last = n;
    return cache[n];
}
