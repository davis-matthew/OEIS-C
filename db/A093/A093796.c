/*
 * Sequence A093796: digit values after concatenating the natural numbers
 * < 4000 in Roman numeral representation.
 *
 * For each n (1‑based), return the i‑th digit value:
 *   I → 1, V → 5, X → 10, L → 50, C → 100, D → 500, M → 1000
 *
 * The sequence is generated by converting all numbers 1 … 3999 to Roman
 * numerals, concatenating those numerals, and replacing each character by
 * its numeric value.  The implementation precomputes the entire sequence
 * on the first call and then serves elements in constant time.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/mem.h"

/* Convert an integer (1 .. 3999) to Roman numeral string.
 * The caller supplies a buffer large enough (20 bytes is safe).
 * The string is null terminated.
 */
static void int_to_roman(unsigned int n, char *buf)
{
    static const int    val[]  = {1000, 900, 500, 400,
                                 100,   90,  50,  40,
                                  10,    9,   5,   4, 1};
    static const char *sym[]  = {"M","CM","D","CD",
                                 "C","XC","L","XL",
                                 "X","IX","V","IV","I"};
    int i = 0;
    char *p = buf;
    for (; i < 13 && n > 0; ++i) {
        while (n >= val[i]) {
            *p++ = sym[i][0];
            if (sym[i][1]) *p++ = sym[i][1];   /* e.g. 'C','M' for CM */
            n -= val[i];
        }
    }
    *p = '\0';
}

static seq_t roman_char_value(char c)
{
    /* Map Roman symbols to their numeric values */
    switch (c) {
        case 'I': return (seq_t)1;
        case 'V': return (seq_t)5;
        case 'X': return (seq_t)10;
        case 'L': return (seq_t)50;
        case 'C': return (seq_t)100;
        case 'D': return (seq_t)500;
        case 'M': return (seq_t)1000;
        default : return (seq_t)0;   /* safety: should not happen */
    }
}

seq_t a(idx_t n)
{
    static int       initialized = 0;
    static seq_t    *values      = NULL;
    static size_t    len         = 0;
    static size_t    capacity    = 0;

    if (!initialized) {
        /* Precompute the entire sequence (up to 3999). */
        capacity = 32768;                 /* large enough initial cap */
        values   = mem_new(seq_t, capacity);
        len      = 0;

        char roman[32];
        for (unsigned int num = 1; num <= 3999; ++num) {
            int_to_roman(num, roman);
            for (char *p = roman; *p; ++p) {
                seq_t v = roman_char_value(*p);
                if (len == capacity) {
                    capacity *= 2;
                    values = mem_resize(seq_t, values, capacity);
                }
                values[len++] = v;
            }
        }
        initialized = 1;
    }

    /* n is 1‑based; guard against overflow/invalid index */
    if (n == 0 || n > (idx_t)len) {
        /* Handle out-of-range gracefully: return zero */
        return (seq_t)0;
    }
    return values[(size_t)(n - 1)];
}
