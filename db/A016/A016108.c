/* Compute terms of A016108:
   a(n) = k where k = 3*m + 1 and 2^m ≡ 1 (mod k).
   The sequence is generated by brute‑forcing m and testing the condition. */
#include "../utils/mod_pow.h"

seq_t a(idx_t n)
{
    /* The first term of the sequence is 1 (2^0 ≡ 1 (mod 1)). */
    if (n == 1)
        return 1;

    /* Find the (n‑1)th non‑trivial term (excluding the initial 1). */
    idx_t found = 0;
    for (idx_t m = 1; ; ++m)
    {
        seq_t m_val = m;
        seq_t k = 3 * m_val + 1;
        /* Test 2^m ≡ 1 (mod k) using the provided modular exponentiation. */
        if (mod_pow(2, m, k) == 1)
        {
            ++found;
            if (found == n - 1)
                return k;
        }
    }
}
