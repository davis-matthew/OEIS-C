/*
 * A365278  In the binary expansion of n replace each run of k consecutive 1's
 *          by the decimal digits of A007931(k) to get the ternary expansion
 *          of a(n).
 * https://oeis.org/A365278
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 39, u16 n <= 1279, u32 n <= 8192, u64 n <= 8192,
 *            u128 n <= 8192, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A365278
 *  Definition:
 *  a(n) is obtained by taking the binary expansion of n.
 *  For each block of consecutive 1’s of length k, replace the block by
 *  the digits of A007931(k) (the k‑th positive integer whose ternary
 *  representation contains only 1’s and 2’s).
 *  Each 0 in the binary expansion remains a 0 digit in the ternary
 *  result.  The resulting ternary string is interpreted as a base‑3
 *  integer, which is a(n).
 *  Recurrence: a(2 n) = 3 a(n).
 *
 *  Implementation note:
 *  The sequence of A007931(k) for k ≤ 64 (the maximal run‑length in a
 *  64‑bit integer) can be generated by a simple breadth–first walk in
 *  ternary digits.  For each k we store its ternary digits (1 and 2)
 *  from most significant to least.  While scanning the bits of n we
 *  build a(n) by multiplying by 3 and adding the required digits.
 *
 *  All operations use seq_t and idx_t as defined by the build system.
 *  The code is valid in C11 and C++17.  No external libraries are used
 *  except <stdbool.h> for the bool type.
 */

#include <stdbool.h>

#define MAX_RUN 64          /* maximal run of 1’s in a 64‑bit unsigned */
#define MAX_DIGITS 6        /* maximal length of A007931(k) in base‑3 */

static bool init_done = false;

/*  Pre–compute A007931(k) for 1 ≤ k ≤ MAX_RUN and store their digits.  */
static seq_t g_k[MAX_RUN + 1];                     /* g_k[k] = A007931(k)          */
static unsigned char g_len[MAX_RUN + 1];           /* number of ternary digits      */
static unsigned char g_digit[MAX_RUN + 1][MAX_DIGITS]; /* digits, MSB first          */

/*  Append the ternary digits of a run of length len to *res.             */
static inline void append_digits(seq_t *res, unsigned int len) {
    for (unsigned int i = 0; i < g_len[len]; ++i) {
        *res = (*res) * 3 + g_digit[len][i];
    }
}

/*  One–time initialisation of g_k and digit tables.                       */
static void initialise(void) {
    /*  Generate the sequence A007931(k) by breadth‑first expansion.       */
    g_k[1] = 1;
    g_k[2] = 2;
    int count = 2;                               /* elements filled so far */
    for (int i = 1; i <= count && count < MAX_RUN; ++i) {
        g_k[++count] = g_k[i] * 3 + 1;
        if (count >= MAX_RUN) break;
        g_k[++count] = g_k[i] * 3 + 2;
    }

    /*  Convert each value to its ternary digits (most significant first). */
    for (int k = 1; k <= MAX_RUN; ++k) {
        seq_t val = g_k[k];
        unsigned char tmp[MAX_DIGITS];
        int pos = 0;
        do {
            tmp[pos++] = (unsigned char)(val % 3);
            val /= 3;
        } while (val > 0);
        g_len[k] = pos;
        /*  Store digits MSB first. */
        for (int j = 0; j < pos; ++j) {
            g_digit[k][j] = tmp[pos - 1 - j];
        }
    }

    init_done = true;
}

/*  Main function computing a(n).                                          */
seq_t a(idx_t n) {
    if (!init_done) initialise();

    if (n == 0) return 0;

    /*  Find index of the most significant set bit.  */
    int msb = 0;
    for (idx_t tmp = n >> 1; tmp != 0; tmp >>= 1) ++msb;

    seq_t result = 0;
    unsigned int run_len = 0;

    for (int i = msb; i >= 0; --i) {
        bool bit = ((n >> i) & 1ULL) != 0;
        if (bit) {
            ++run_len;
        } else {
            if (run_len > 0) {
                append_digits(&result, run_len);
                run_len = 0;
            }
            /*  Append zero digit.  */
            result = result * 3;
        }
    }

    /*  Handle a trailing run of 1’s.  */
    if (run_len > 0) {
        append_digits(&result, run_len);
    }

    return result;
}
