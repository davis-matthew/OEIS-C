/*
 * A365257  The five digits of a(n) and their four successive absolute first
 *          differences are all distinct.
 * https://oeis.org/A365257
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn, fini, full
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 96, u64 n <= 96, u128 n <= 96,
 *            big any n
 * Helpers:   generate_seq
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A365257: 5‑digit numbers whose five digits and the four
   successive absolute differences are all distinct and together
   comprise the digits 1–9.  The terms are generated by a small
   back‑tracking search and stored in a static cache.  The array is
   sorted in ascending value. */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/generate_seq.h"

/* Helper: comparator for qsort */
static int seq_cmp(const void *a, const void *b)
{
    const seq_t *x = (const seq_t *)a;
    const seq_t *y = (const seq_t *)b;
    if (*x < *y) return -1;
    if (*x > *y) return 1;
    return 0;
}

/* Main sequence function */
seq_t a(idx_t n)
{
    if (n < 1) return 0;          /* undefined for n < 1 */

    /* static cache for the 96 admissible numbers */
    static seq_t cache[96];
    static size_t cache_cnt = 0;

    if (cache_cnt == 0) {         /* build on first call */
        seq_t temp[15120];
        size_t temp_cnt = 0;
        int digits[5];
        generate_seq(0, 0, digits, temp, &temp_cnt);

        /* sort the collected numbers */
        qsort(temp, temp_cnt, sizeof(seq_t), seq_cmp);

        /* copy to static cache */
        cache_cnt = temp_cnt;
        for (size_t i = 0; i < temp_cnt; ++i) {
            cache[i] = temp[i];
        }
    }

    size_t idx = (size_t)(n - 1);
    if (idx < cache_cnt) return cache[idx];
    return 0;                     /* n larger than defined sequence */
}
