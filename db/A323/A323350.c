/* Sequence: A323350 - Nonprime numbers > 1 whose number of prime factors counted with multiplicity is a perfect square */
/* Each term is generated by scanning integers, testing compositeness via is_prime_big,
   counting prime factors with bigomega, and checking if that count is a perfect square using floor_sqrt. */

#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"
#include "../utils/bigomega.h"
#include "../utils/floor_sqrt.h"

static seq_t* cache = NULL;         /* dynamic array holding computed terms          */
static size_t cache_len = 0;        /* number of terms currently stored             */
static size_t cache_cap = 0;        /* current capacity of the cache                */
static seq_t next_candidate = 2;    /* next integer to test                         */

static void ensure_cache_capacity(void) {
    if (cache_len == cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
        seq_t* new_cache = NULL;
        if (cache == NULL) {
            new_cache = (seq_t*)malloc(new_cap * sizeof(seq_t));
        } else {
            new_cache = (seq_t*)realloc(cache, new_cap * sizeof(seq_t));
        }
        if (new_cache == NULL) {
            /* In a real build we might handle out‑of‑memory differently. */
            abort();
        }
        cache = new_cache;
        cache_cap = new_cap;
    }
}

seq_t a(idx_t n) {
    /* Ensure we have at least n terms in the cache. */
    while (cache_len < n) {
        /* Skip primes and 1. */
        if (next_candidate > 1 && !is_prime_big(next_candidate)) {
            seq_t omega = bigomega((idx_t)next_candidate);
            seq_t s = floor_sqrt(omega);
            if (s * s == omega) {
                ensure_cache_capacity();
                cache[cache_len++] = next_candidate;
            }
        }
        /* Advance to next integer.  Using seq_t ensures we never overflow
           for the anticipated range of n (<= 10000). */
        ++next_candidate;
    }
    return cache[n - 1];
}
