/*
 * A323456  Irregular triangle read by rows: row n lists the numbers that can
 *          be obtained from the binary expansion of n by either deleting a
 *          single 0, or inserting a single 0 after any 1.
 * https://oeis.org/A323456
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf, base
 * Formula:   not stated
 * Range:     u8 n <= 640, u16 n <= 7208, u32 n <= 7208, u64 n <= 7208,
 *            u128 n <= 7208, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A323456:  a(n) is the n-th term of the triangle
 * obtained by reading row by row the numbers reachable from the
 * binary expansion of the row index by either:
 * 1. deleting a single 0 bit,
 * 2. inserting a single 0 immediately after any 1 bit.
 *
 * Row n is sorted increasingly, duplicates are removed.  The
 * sequence is generated by iterating rows until the desired
 * index is reached.
 */

#include <stddef.h>

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;        /* offset 1; undefined below */

    idx_t cumulative = 0;
    for (idx_t row = 1;; ++row) {
        /* maximum possible row size is the number of bits in the row,
           which is <= 64, so a small static buffer suffices. */
        static const size_t MAX_V = 128;
        seq_t values[MAX_V];
        size_t count = 0;

        /* Determine bit length of the row number */
        idx_t tmp = row;
        size_t bitlen = 0;
        while (tmp) { ++bitlen; tmp >>= 1; }

        /* Process every bit position */
        for (size_t p = 0; p < bitlen; ++p) {
            idx_t bit = (row >> p) & 1ULL;

            /* Deletion of a zero bit */
            if (bit == 0) {
                idx_t high = (p + 1 >= 64) ? 0 : (row >> (p + 1));
                seq_t low  = (seq_t)row & ((seq_t)((1ULL << p) - 1ULL));
                seq_t res  = ((seq_t)high << p) | low;
                values[count++] = res;
            }
            /* Insertion of a zero after a one bit */
            else {
                idx_t high = (p + 1 >= 64) ? 0 : (row >> (p + 1));
                seq_t low  = (seq_t)row & ((seq_t)((1ULL << p) - 1ULL));
                seq_t res  = ((seq_t)high << (p + 2))
                            | ((seq_t)1 << (p + 1))
                            | low;
                values[count++] = res;
            }
        }

        /* Sort the values (small size, insertion sort is fine) */
        for (size_t i = 1; i < count; ++i) {
            seq_t key = values[i];
            size_t j = i;
            while (j > 0 && values[j - 1] > key) {
                values[j] = values[j - 1];
                --j;
            }
            values[j] = key;
        }

        /* Remove duplicates */
        size_t uniq = 0;
        for (size_t i = 0; i < count; ++i) {
            if (i == 0 || values[i] != values[i - 1]) {
                values[uniq++] = values[i];
            }
        }
        count = uniq;

        /* Check if the desired index lies within this row */
        idx_t next_cum = cumulative + count;
        if (n <= next_cum) {
            size_t idx = (size_t)(n - cumulative - 1); /* 0‑based in the row */
            return values[idx];
        }
        cumulative = next_cum;
    }
}
