/*
 * A323762  Numbers m such that Product_{d|m} (pod(d)/tau(d)) is an integer h
 *          where pod(k) = the product of the divisors of k (A007955) and
 *          tau(k) = the number of the divisors of k (A000005).
 * https://oeis.org/A323762
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 26, u16 n <= 6625, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   add_exp
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes OEIS A323762.  For each integer m, tests whether
 *   ∏_{d|m} pod(d)/tau(d)  is an integer.
 * The test is performed by factoring m, enumerating all its divisors,
 * accumulating prime exponents in the numerator (pod) and denominator
 * (tau), and checking that every denominator exponent is
 * ≤ its numerator counterpart.  The sequence is generated by
 * searching in increasing order; results are memoised. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/add_exp.h"

/* recursive divisor enumeration */
static void dfs_rec(size_t idx, uint64_t tau_cur, uint64_t *curr_exp,
                    size_t k,
                    uint64_t *primes, uint64_t *exp_lim,
                    uint64_t *prime_list, uint64_t *num_exp,
                    uint64_t *den_exp, size_t *pcount)
{
    if (idx == k) {
        /* numerator contribution from this divisor */
        for (size_t i = 0; i < k; ++i) {
            if (curr_exp[i]) {
                uint64_t inc = (curr_exp[i] * tau_cur) / 2;
                add_exp(primes[i], inc, prime_list, num_exp,
                        den_exp, pcount, true);
            }
        }
        /* denominator: factorise tau_cur */
        uint64_t tmp = tau_cur;
        for (uint64_t d = 2; d <= tmp / d; ++d) {
            if (tmp % d == 0) {
                uint64_t cnt = 0;
                while (tmp % d == 0) {
                    tmp /= d;
                    ++cnt;
                }
                add_exp(d, cnt, prime_list, num_exp,
                        den_exp, pcount, false);
            }
        }
        if (tmp > 1) {
            add_exp(tmp, 1, prime_list, num_exp,
                    den_exp, pcount, false);
        }
        return;
    }
    for (uint64_t fi = 0; fi <= exp_lim[idx]; ++fi) {
        curr_exp[idx] = fi;
        dfs_rec(idx + 1, tau_cur * (fi + 1), curr_exp,
                k, primes, exp_lim, prime_list,
                num_exp, den_exp, pcount);
    }
}

/* factorise n into primes and exponents (max 16 distinct primes) */
static size_t factor_n(uint64_t n, uint64_t *primes, uint64_t *exps)
{
    size_t k = 0;
    for (uint64_t p = 2; p <= n / p; ++p) {
        if (n % p == 0) {
            uint64_t c = 0;
            while (n % p == 0) {
                n /= p;
                ++c;
            }
            primes[k] = p;
            exps[k] = c;
            ++k;
        }
    }
    if (n > 1) {
        primes[k] = n;
        exps[k] = 1;
        ++k;
    }
    return k;
}

/* check whether m satisfies the integer-product property */
static bool valid_m(uint64_t m)
{
    if (m == 1) return true;

    /* factorise m */
    uint64_t primes[16], exps[16];
    size_t k = factor_n(m, primes, exps);

    /* prime-exponent tables for the overall fraction */
    uint64_t prime_list[512] = {0};
    uint64_t num_exp[512]   = {0};
    uint64_t den_exp[512]   = {0};
    size_t pcount = 0;

    /* current exponent vector for a divisor */
    uint64_t curr_exp[16] = {0};

    dfs_rec(0, 1, curr_exp, k, primes, exps,
            prime_list, num_exp, den_exp, &pcount);

    /* compare numerator and denominator exponents */
    for (size_t i = 0; i < pcount; ++i) {
        if (num_exp[i] < den_exp[i]) return false;
    }
    return true;
}

/* main sequence function */
seq_t a(idx_t n)
{
    static seq_t *seq = NULL;
    static size_t seq_cap = 0;
    static idx_t seq_len = 0;
    static idx_t last_checked = 0;

    while (seq_len < n) {
        ++last_checked;
        if (valid_m((uint64_t)last_checked)) {
            if (seq == NULL) {
                seq_cap = 64;
                seq = (seq_t *)malloc(sizeof(seq_t) * seq_cap);
            } else if ((size_t)seq_len >= seq_cap) {
                seq_cap *= 2;
                seq = (seq_t *)realloc(seq, sizeof(seq_t) * seq_cap);
            }
            seq[seq_len++] = (seq_t)last_checked;
        }
    }
    return seq[n - 1];
}
