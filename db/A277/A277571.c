/* Sequence A277571: numbers k such that k/6^m ≡ 5 (mod 6), where m is
   the greatest power of 6 dividing k.  The sequence is generated by
   testing successive integers until the required condition is met.
   This method runs in O(n) time and caches the results for subsequent
   calls. */

#include <stdlib.h>

seq_t a(idx_t n) {
    static seq_t *cache = NULL;     /* cached sequence values   */
    static idx_t cache_len = 0;     /* number of cached values  */
    static idx_t cache_cap = 0;     /* capacity of cache array  */
    static idx_t next_candidate = 1;/* next integer to test     */

    if (n == 0) return 0; /* offset starts at 1; unused case */

    /* Generate terms until we have at least n cached values */
    while (cache_len < n) {
        /* Find the next integer that satisfies the condition */
        while (1) {
            seq_t q = (seq_t)next_candidate;
            while (q % 6 == 0) {
                q /= 6;
            }
            if (q % 6 == 5) {
                break; /* candidate found */
            }
            next_candidate++;
        }

        /* Grow the cache if necessary */
        if (cache_len == cache_cap) {
            idx_t new_cap = (cache_cap == 0) ? 64 : cache_cap * 2;
            seq_t *new_cache = (seq_t *)realloc(cache,
                                                 new_cap * sizeof(seq_t));
            if (!new_cache) {
                /* Allocation failed; return zero as an error sentinel */
                return 0;
            }
            cache = new_cache;
            cache_cap = new_cap;
        }

        /* Store the found value and prepare for the next candidate */
        cache[cache_len++] = (seq_t)next_candidate;
        next_candidate++;
    }

    return cache[n - 1];
}
