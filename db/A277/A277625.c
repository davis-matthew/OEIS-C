/*
 * A277625  Nontrivial values of Fibonacci polynomials.
 * https://oeis.org/A277625
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 3696, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Nontrivial Fibonacci polynomial values:
   a(n) = smallest values of FibonacciPolynomial(x,y) for x>=3, y>=1,
   sorted ascending with duplicates removed (the only duplicate is 5).  
   Sequence is generated by merging the infinite monotone sequences
   (one for each y) with a min‑heap. */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>

/* Maximum y sufficient to reach many thousands of terms (≈10000). */
#define Y_MAX 20001

/* Heap node holding the current value of a fixed y. */
typedef struct {
    seq_t val;   /* current FibonacciPolynomial value */
    idx_t y;     /* fixed y for this sequence */
} HeapNode;

/* Global static arrays for the sequences and the heap. */
static seq_t *cur_val;       /* F(x) for current x */
static seq_t *prev_val;      /* F(x-1) */
static seq_t *prevprev_val;  /* F(x-2) */
static HeapNode heap[Y_MAX];

static size_t heap_size = Y_MAX;      /* constant = Y_MAX */
static bool heap_initialized = false;

/* Cache for the sequence a(n). */
static seq_t *cache = NULL;
static size_t cache_len = 0; /* number of values cached */
static size_t cache_cap = 0; /* allocated capacity */

/* Forward declarations. */
static void heapify();
static void sift_down(size_t i);
static void grow_cache();
static void init_heap_and_sequences();

/* ------------------------------------------------------------------ */
/* Heap operations.  The heap always contains Y_MAX nodes.             */
static void sift_down(size_t i)
{
    while (1) {
        size_t l = 2*i + 1;
        size_t r = l + 1;
        size_t smallest = i;

        if (l < heap_size && heap[l].val < heap[smallest].val)
            smallest = l;
        if (r < heap_size && heap[r].val < heap[smallest].val)
            smallest = r;

        if (smallest == i)
            break;

        HeapNode tmp = heap[i];
        heap[i] = heap[smallest];
        heap[smallest] = tmp;
        i = smallest;
    }
}

static void heapify(void)
{
    for (size_t i = heap_size / 2; i > 0; --i)
        sift_down(i - 1);
}

/* ------------------------------------------------------------------ */
/* Initialize the sequences for all y and build the heap.              */
static void init_heap_and_sequences(void)
{
    /* Allocate per‑y arrays. */
    cur_val      = (seq_t *)malloc((Y_MAX + 1) * sizeof(seq_t));
    prev_val     = (seq_t *)malloc((Y_MAX + 1) * sizeof(seq_t));
    prevprev_val = (seq_t *)malloc((Y_MAX + 1) * sizeof(seq_t));

    /* Initialize each sequence at x = 3. */
    for (idx_t y = 1; y <= Y_MAX; ++y) {
        seq_t yseq = (seq_t)y;
        cur_val[y]      = yseq * yseq + 1;   /* F(3,y) = y^2 + 1 */
        prev_val[y]     = yseq;              /* F(2,y) = y     */
        prevprev_val[y] = 1;                 /* F(1,y) = 1     */
        heap[y - 1].val = cur_val[y];
        heap[y - 1].y   = y;
    }

    heapify();
    heap_initialized = true;
}

/* ------------------------------------------------------------------ */
/* Grow the cache array to at least the required capacity.           */
static void grow_cache(void)
{
    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
    seq_t *new_cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (new_cache) {
        cache = new_cache;
        cache_cap = new_cap;
    } else {
        /* Allocation failed; abort to keep build simple. */
        abort();
    }
}

/* ------------------------------------------------------------------ */
/* Ensure that the cache contains at least n terms.                   */
static void ensure_cache(idx_t n)
{
    if (cache_len >= (size_t)n)
        return;

    if (!heap_initialized)
        init_heap_and_sequences();

    /* Generate terms until we have at least n. */
    while (cache_len < (size_t)n) {
        /* Current smallest node. */
        HeapNode node = heap[0];
        seq_t v = node.val;
        idx_t y = node.y;

        /* Store unique values only. */
        if (cache_len == 0 || v != cache[cache_len - 1]) {
            if (cache_len == cache_cap)
                grow_cache();
            cache[cache_len++] = v;
        }

        /* Advance the sequence for this y. */
        seq_t next = (seq_t)y * cur_val[y] + prev_val[y];
        prevprev_val[y] = prev_val[y];
        prev_val[y]     = cur_val[y];
        cur_val[y]      = next;

        /* Update heap root and restore min‑heap property. */
        heap[0].val = next;
        sift_down(0);
    }
}

/* ------------------------------------------------------------------ */
/* Public function required by the specification.                    */
seq_t a(idx_t n)
{
    ensure_cache(n);
    return cache[n - 1];
}
