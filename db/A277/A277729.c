/*
 * A277729  Irregular triangle read by rows: T(n,k) = number of times a gap of
 *          k occurs between the first n successive primes.
 * https://oeis.org/A277729
 *
 * Offset:    2    (a(2) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 9977, u16 n <= 9977, u32 n <= 9977, u64 n <= 9977,
 *            u128 n <= 9977, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Computation of OEIS A277729:
 *  Irregular triangle read by rows: T(n,k) = number of times a gap of k occurs
 *  between the first n successive primes.  The sequence a(n) is obtained by
 *  reading the rows of T(n,k) in order, starting with a(2)=T(2,1).  No
 *  closed‑form formula is known, so the values are generated by building the
 *  triangle incrementally and caching the results.
 */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>

/* ---------- prime generation (trial division) ---------- */
static uint64_t *primes      = NULL;   /* array of primes */
static size_t   prime_cnt   = 0;        /* number of primes stored    */
static size_t   prime_cap   = 0;        /* allocated capacity         */
static uint64_t next_candidate = 2;     /* next integer to test       */

static void ensure_primes(size_t needed)
{
    if (prime_cnt >= needed) return;

    /* grow the array capacity if needed */
    if (prime_cap < needed) {
        size_t new_cap = prime_cap ? prime_cap << 1 : 16;
        while (new_cap < needed) new_cap <<= 1;
        uint64_t *tmp = (uint64_t *)realloc(primes, new_cap * sizeof(uint64_t));
        if (!tmp) abort();
        primes = tmp;
        prime_cap = new_cap;
    }

    /* generate further primes */
    while (prime_cnt < needed) {
        bool is_prime = true;
        for (size_t i = 0; i < prime_cnt; ++i) {
            uint64_t p = primes[i];
            if (p * p > next_candidate) break;
            if (next_candidate % p == 0) {
                is_prime = false;
                break;
            }
        }
        if (is_prime) primes[prime_cnt++] = next_candidate;
        ++next_candidate;
    }
}

/* ---------- sequence cache ---------- */
static seq_t *seq_cache = NULL;   /* flattened triangle values (a(2) at index 0) */
static size_t seq_len   = 0;      /* number of terms stored            */
static size_t seq_cap   = 0;      /* allocated capacity                */
static size_t next_row  = 2;      /* current row to generate (n)       */

static void ensure_seq_cap(size_t needed)
{
    if (seq_cap >= needed) return;
    size_t new_cap = seq_cap ? seq_cap << 1 : 16;
    while (new_cap < needed) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();
    seq_cache = tmp;
    seq_cap = new_cap;
}

/* maximum gap that can be expected for n <= 10000 (primes < 10^6) */
#define MAX_GAP 1000
static seq_t gap_counts[MAX_GAP + 1];

/* ---------- main sequence function ---------- */
seq_t a(idx_t n)
{
    /* defined only for n >= 2 */
    if (n < 2) return 0;

    size_t target = (size_t)(n - 2);           /* zero‑based index in seq_cache */
    /* generate rows until we have the requested index */
    while (seq_len <= target) {
        ensure_primes(next_row);                /* need at least next_row primes */

        /* compute maximum gap among first next_row primes */
        uint64_t maxgap = 0;
        for (size_t i = 1; i < next_row; ++i) {
            uint64_t gap = primes[i] - primes[i-1];
            if (gap > maxgap) maxgap = gap;
        }
        if (maxgap > MAX_GAP) abort();          /* safety check */

        /* zero the counts array up to maxgap */
        for (size_t i = 1; i <= maxgap; ++i) gap_counts[i] = 0;

        /* count occurrences of each gap */
        for (size_t i = 1; i < next_row; ++i) {
            uint64_t gap = primes[i] - primes[i-1];
            ++gap_counts[gap];
        }

        /* append the row to the flattened cache */
        ensure_seq_cap(seq_len + maxgap);
        for (size_t k = 1; k <= maxgap; ++k) {
            seq_cache[seq_len++] = gap_counts[k];
        }

        ++next_row;
    }

    return seq_cache[target];
}
