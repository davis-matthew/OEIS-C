/*
 * A137825  Least number having the highest abundancy among numbers with
 *          exactly n prime factors (counted with multiplicity).
 * https://oeis.org/A137825
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 7, u32 n <= 12, u64 n <= 20, u128 n <= 32,
 *            big any n
 * Helpers:   benefit_of
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A137825: least number having the highest abundancy among numbers
   with exactly n prime factors (counted with multiplicity).  The
   sequence is generated by maintaining a heap of primes sorted by
   the marginal benefit of adding another copy of the prime to the
   product, and successively multiplying by the prime with the
   greatest benefit.  This produces the product of the first n terms
   of a greedy sequence that maximizes abundancy.  The algorithm
   runs in O(n log p) time, where p is the number of primes kept. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/benefit_of.h"

/* ---------- Global state ---------- */
static uint64_t *primes = NULL;      /* array of primes up to LIMIT */
static size_t   prime_cnt = 0;        /* number of primes            */

typedef struct {
    uint64_t  prime;      /* prime */
    unsigned  exp;        /* current exponent of this prime */
    long double benef;    /* marginal benefit of adding one more factor of this prime */
} Node;

static Node  *heap = NULL;          /* max‑heap of nodes */
static size_t heap_size = 0;
static size_t heap_cap = 0;

static seq_t *cache    = NULL;      /* cached sequence values a(0..len-1) */
static idx_t  cache_len = 0;        /* number of cached entries */
static idx_t  cache_cap = 0;        /* allocated cache capacity */

static seq_t current_prod = 0;      /* product of primes chosen so far */

static bool initialized = false;

/* ---------- Helper functions ---------- */

/* Comparison function for max‑heap on benefit (with tie‑breaker by smaller prime). */
static int node_cmp(const Node *a, const Node *b)
{
    if (a->benef > b->benef + 1e-18L) return 1;
    if (a->benef < b->benef - 1e-18L) return -1;
    if (a->prime < b->prime) return 1;
    if (a->prime > b->prime) return -1;
    return 0;
}

static void heap_swap(Node *x, Node *y)
{
    Node tmp = *x;
    *x = *y;
    *y = tmp;
}

static void heap_push(Node *h, size_t *sz, Node node)
{
    h[*sz] = node;
    size_t i = *sz;
    (*sz)++;
    while (i > 0) {
        size_t p = (i - 1) >> 1;
        if (node_cmp(&h[i], &h[p]) <= 0) break;
        heap_swap(&h[i], &h[p]);
        i = p;
    }
}

static Node heap_pop(Node *h, size_t *sz)
{
    Node top = h[0];
    (*sz)--;
    h[0] = h[*sz];
    size_t i = 0;
    while (true) {
        size_t left  = (i << 1) + 1;
        size_t right = left + 1;
        size_t best  = i;
        if (left < *sz && node_cmp(&h[left], &h[best]) > 0) best = left;
        if (right < *sz && node_cmp(&h[right], &h[best]) > 0) best = right;
        if (best == i) break;
        heap_swap(&h[i], &h[best]);
        i = best;
    }
    return top;
}

/* Allocate or grow cache to hold at least indices 0..n. */
static void ensure_cache(idx_t n)
{
    if (n + 1 < cache_cap) return;
    idx_t new_cap = cache_cap ? cache_cap << 1 : 16;
    while (new_cap <= n) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp) exit(EXIT_FAILURE);
    cache = tmp;
    cache_cap = new_cap;
}

/* Generate a list of primes up to LIMIT. */
static void generate_primes(void)
{
    const size_t LIMIT = 2000000u;
    uint8_t *is_comp = (uint8_t *)calloc(LIMIT + 1, 1);
    if (!is_comp) exit(EXIT_FAILURE);

    for (size_t i = 2; i * i <= LIMIT; ++i) {
        if (!is_comp[i]) {
            for (size_t j = i * i; j <= LIMIT; j += i) is_comp[j] = 1;
        }
    }

    size_t cnt = 0;
    for (size_t i = 2; i <= LIMIT; ++i) if (!is_comp[i]) ++cnt;

    primes = (uint64_t *)malloc(sizeof(uint64_t) * cnt);
    if (!primes) exit(EXIT_FAILURE);

    size_t pos = 0;
    for (size_t i = 2; i <= LIMIT; ++i)
        if (!is_comp[i]) primes[pos++] = (uint64_t)i;

    prime_cnt = cnt;
    free(is_comp);
}

/* One‑time initialization of primes, heap, cache and product. */
static void initialize(void)
{
    if (initialized) return;
    generate_primes();

    heap_cap   = prime_cnt;
    heap       = (Node *)malloc(sizeof(Node) * heap_cap);
    if (!heap) exit(EXIT_FAILURE);
    heap_size = 0;
    for (size_t i = 0; i < prime_cnt; ++i) {
        Node n = { primes[i], 0, benefit_of(primes[i], 0) };
        heap_push(heap, &heap_size, n);
    }

    cache = (seq_t *)malloc(16 * sizeof(seq_t));
    if (!cache) exit(EXIT_FAILURE);
    cache_cap = 16;
    cache_len = 1;
    cache[0] = (seq_t)1;
    current_prod = (seq_t)1;

    initialized = true;
}

/* ---------- The required function -------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)1;
    initialize();

    if (n >= cache_len) {
        ensure_cache(n);
        while (cache_len <= n) {
            Node node = heap_pop(heap, &heap_size);

            current_prod = current_prod * (seq_t)node.prime;
            cache[cache_len++] = current_prod;

            node.exp++;
            node.benef = benefit_of(node.prime, node.exp);
            heap_push(heap, &heap_size, node);
        }
    }
    return cache[n];
}
