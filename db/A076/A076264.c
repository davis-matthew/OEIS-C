/*
 * A076264  Number of ternary (0,1,2) sequences without a consecutive '012'.
 * https://oeis.org/A076264
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   a(n) = 3*a(n-1) - a(n-3) (n > 2) Initial values: a(0)=1, a(1)=3,
 *            a(2)=9
 * Range:     u8 n <= 5, u16 n <= 10, u32 n <= 20, u64 n <= 41, u128 n <= 83,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute the N-th term of A076264 in a memoised way.
   The sequence can be generated by the linear recurrence
   a(n) = 3*a(n-1) - a(n-3), so we only need the three
   preceding values.  A dynamic array stores the
   already-computed terms so calls in arbitrary order
   take time proportional to the largest n requested.  */
#include <stdlib.h>

seq_t a(idx_t n)
{
    /* static storage for computed values */
    static seq_t *cache = NULL;
    static idx_t cache_cap = 0;     /* allocated capacity          */
    static idx_t next_computed = 0; /* first index not yet filled */

    /* initialise with the first three terms */
    if (cache == NULL) {
        cache_cap = 3;
        cache = (seq_t*)malloc(cache_cap * sizeof(seq_t));
        if (!cache) return (seq_t)0; /* out of memory – unlikely in tests */
        cache[0] = (seq_t)1;
        cache[1] = (seq_t)3;
        cache[2] = (seq_t)9;
        next_computed = 3;
    }

    /* if the requested term is already in cache, return it */
    if ((seq_t)n < (seq_t)next_computed) {
        return cache[n];
    }

    /* enlarge the cache if necessary */
    if ((idx_t)(n + 1) > cache_cap) {
        size_t new_cap = cache_cap;
        while (new_cap < (size_t)(n + 1)) new_cap *= 2;
        seq_t *tmp = (seq_t*)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) return (seq_t)0;            /* out of memory, should not happen */
        cache = tmp;
        cache_cap = new_cap;
    }

    /* compute missing terms up to n */
    for (idx_t i = next_computed; i <= n; ++i) {
        seq_t val = (seq_t)3 * cache[i - 1] - cache[i - 3];
        cache[i] = val;
    }
    next_computed = n + 1;
    return cache[n];
}
