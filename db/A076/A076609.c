/*
 * A076609  Palindromic numbers with prime middle digit.
 * https://oeis.org/A076609
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 11, u16 n <= 262, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   reverse_last
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: palindromic numbers whose middle digit is prime (2,3,5,7).
   The sequence is generated by listing all odd‑length decimal palindromes
   with a prime middle digit in increasing order.  See OEIS A076609. */

#include <stddef.h>   /* for size_t, not used directly */
#include "../utils/reverse_last.h"

static const int prime_mid[4] = {2,3,5,7};

/* Compute 10^exp as a seq_t.  exp is small (<=4). */
static seq_t pow10(idx_t exp)
{
    seq_t r = 1;
    for (idx_t i = 0; i < exp; ++i)
        r *= 10;
    return r;
}

seq_t a(idx_t n)
{
    /* first four terms are single digit primes */
    if (n <= 4) {
        static const seq_t first[4] = {2,3,5,7};
        return first[n-1];
    }

    /* offset after the first four terms */
    idx_t remain = n - 5;          /* 0‑based index among longer palindromes */

    /* Determine the length.  L = 2*k+1, with k >= 1. */
    idx_t k = 1;
    for (;;) {
        idx_t suffixCount = 1;            /* 10^(k-1) */
        for (idx_t i = 0; i < k-1; ++i)
            suffixCount *= 10;

        idx_t perLen = 9 * suffixCount * 4;   /* count of palindromes of this length */

        if (remain < perLen) break;
        remain -= perLen;
        ++k;
    }

    /* Now k is the index of the length (k=1 -> length 3). */
    idx_t suffixCount = 1;
    for (idx_t i = 0; i < k-1; ++i)
        suffixCount *= 10;

    idx_t perFD = suffixCount * 4;          /* per first digit */

    /* First digit (1..9) */
    idx_t d0 = remain / perFD + 1;
    idx_t rem2 = remain % perFD;

    /* Suffix integer (k-1 digits, may have leading zeros) */
    idx_t suffixIdx = rem2 / 4;

    /* Middle digit index (0..3) */
    idx_t midIdx = rem2 % 4;
    seq_t midDigit = prime_mid[midIdx];

    seq_t p10 = pow10(k);              /* 10^k */

    /* Build prefix: d0 * 10^k + suffix * 10 + middle */
    seq_t prefix = d0 * p10 + suffixIdx * 10 + midDigit;

    /* Reverse the prefix without the middle digit (k digits). */
    seq_t half = prefix / 10;
    seq_t rev = reverse_last(k, half);

    /* Assemble full palindrome */
    seq_t pal = prefix * p10 + rev;
    return pal;
}
