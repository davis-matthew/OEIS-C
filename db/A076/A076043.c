/*
 * A076043  a(1)=2; for n>1, a(n) is smallest squarefree number (greater than
 *          1) not occurring earlier such that a(n) + a(n-1) is a square.
 * https://oeis.org/A076043
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 65, u16 n <= 65, u32 n <= 65, u64 n <= 65, u128 n <= 65,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A076043: a(0) = 2; for n>0, a(n) is the smallest square‑free integer (>1)
   not occurring earlier such that a(n) + a(n – 1) is a perfect square.
   This implementation generates terms on demand by searching the
   successive squares s² for the smallest suitable candidate
   and memoises the sequence. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* --------------------------------------------------------------------- */
/* Integer square root (floor) for seq_t values.                           */
static seq_t floor_sqrt_seq(seq_t x)
{
    seq_t low = 0;
    seq_t high = x;
    while (low <= high) {
        seq_t mid = low + ((high - low) >> 1);
        if (mid == 0) {          /* handle x == 0 case */
            high = 0;
            break;
        }
        if (mid > x / mid) {     /* mid² > x  →  go lower */
            high = mid - 1;
        } else {                 /* mid² ≤ x  →  go higher */
            low = mid + 1;
        }
    }
    return high;
}

/* --------------------------------------------------------------------- */
/* Prime sieve (stored as int) – sufficient for all needed primes.        */
static int  *prime_tbl   = NULL;
static size_t prime_cnt  = 0;
static size_t prime_cap  = 0;

static void init_primes(void)
{
    if (prime_tbl != NULL) return;
    prime_cap = 128;
    prime_tbl = (int *)malloc(prime_cap * sizeof(int));
    if (!prime_tbl) exit(EXIT_FAILURE);
    /* seed with first prime */
    prime_tbl[prime_cnt++] = 2;
}

static void ensure_primes_up_to(seq_t limit)
{
    if (prime_tbl == NULL) init_primes();
    /* extend until last stored prime ≥ limit */
    while ((seq_t)prime_tbl[prime_cnt - 1] < limit) {
        /* find next prime after the last one */
        int candidate = prime_tbl[prime_cnt - 1] + 1;
        bool ok;
        do {
            ok = true;
            for (size_t i = 0; i < prime_cnt; ++i) {
                int p = prime_tbl[i];
                if ((seq_t)p * (seq_t)p > candidate) break;
                if (candidate % p == 0) {
                    ok = false;
                    break;
                }
            }
            if (!ok) ++candidate;
        } while (!ok);
        if (prime_cnt >= prime_cap) {
            prime_cap *= 2;
            int *newptr = (int *)realloc(prime_tbl, prime_cap * sizeof(int));
            if (!newptr) exit(EXIT_FAILURE);
            prime_tbl = newptr;
        }
        prime_tbl[prime_cnt++] = candidate;
    }
}

/* --------------------------------------------------------------------- */
/* Check whether a number is square‑free.
   Uses the prime list generated by ensure_primes_up_to.                  */
static bool is_squarefree(seq_t v)
{
    if (v <= (seq_t)1) return false;
    seq_t lim = floor_sqrt_seq(v);
    ensure_primes_up_to(lim);
    for (size_t j = 0; j < prime_cnt; ++j) {
        int p = prime_tbl[j];
        seq_t p_sq = (seq_t)p * (seq_t)p;
        if (p_sq > v) break;
        if ((v % p_sq) == (seq_t)0) return false;
    }
    return true;
}

/* --------------------------------------------------------------------- */
/* Dynamic array for cached terms.                                        */
static seq_t *seq_cache = NULL;
static size_t seq_cap   = 0;
static size_t seq_len   = 0;

static void extend_seq(size_t need)
{
    if (need <= seq_cap) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    if (new_cap < need) new_cap = need;
    seq_t *new_arr = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    if (!new_arr) exit(EXIT_FAILURE);
    seq_cache = new_arr;
    seq_cap   = new_cap;
}

/* --------------------------------------------------------------------- */
/* Main sequence function.                                               */
seq_t a(idx_t n)
{
    static bool initialized = false;
    if (!initialized) {
        /* initial cache value */
        seq_cache = NULL;
        seq_cap = 0;
        extend_seq(1);
        seq_cache[0] = (seq_t)2;
        seq_len = 1;

        /* initialise primes */
        init_primes();
        initialized = true;
    }

    /* Generate terms up to index n if not already done. */
    while (seq_len <= (size_t)n) {
        seq_t prev = seq_cache[seq_len - 1];

        seq_t start_s = floor_sqrt_seq(prev + (seq_t)1) + (seq_t)1;
        seq_t s = start_s;

        seq_t candidate = 0;
        while (true) {
            seq_t ss = s * s;
            candidate = ss - prev;
            if (candidate <= (seq_t)1) { ++s; continue; }

            /* already used? */
            bool used = false;
            for (size_t i = 0; i < seq_len; ++i)
                if (seq_cache[i] == candidate) { used = true; break; }
            if (used) { ++s; continue; }

            /* square‑free? */
            if (!is_squarefree(candidate)) { ++s; continue; }

            /* candidate found */
            break;
        }

        /* append to cache */
        extend_seq(seq_len + 1);
        seq_cache[seq_len] = candidate;
        ++seq_len;
    }

    return seq_cache[(size_t)n];
}
