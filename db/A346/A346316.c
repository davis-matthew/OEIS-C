/*
 * A346316  Composite numbers with primitive root 6.
 * https://oeis.org/A346316
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 3, u32 n <= 39, u64 n <= 39, u128 n <= 39,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A346316: composite numbers with primitive root 6.
   The sequence consists of all prime powers p^e (e ≥ 2) such that
   6 is a primitive root modulo p and also lifts to p².
   Terms are generated on demand and memoised.
   The implementation uses only integer arithmetic, no floating point,
   and relies on a simple sieve for prime generation.
*/
#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

/* ----------------------------------------------------------------------
   Basic integer utilities (64‑bit arithmetic)
   ----------------------------------------------------------------------*/
static uint64_t mod_mul64(uint64_t a, uint64_t b, uint64_t mod)
{
    return (uint64_t)((__uint128_t)a * b % mod);
}

static uint64_t mod_pow64(uint64_t base, uint64_t exp, uint64_t mod)
{
    uint64_t result = 1 % mod;
    uint64_t cur     = base % mod;
    while (exp)
    {
        if (exp & 1ULL)
            result = mod_mul64(result, cur, mod);
        cur = mod_mul64(cur, cur, mod);
        exp >>= 1ULL;
    }
    return result;
}

/* ----------------------------------------------------------------------
   Sieve of Eratosthenes – generates all primes ≤ limit.
   ----------------------------------------------------------------------*/
static void build_primes_upto(idx_t limit, uint64_t **out, size_t *cnt_out)
{
    if (limit < 2)
    {
        *out = NULL;
        *cnt_out = 0;
        return;
    }

    uint8_t *is_prime = (uint8_t *)malloc((size_t)(limit + 1));
    if (!is_prime) exit(1);
    memset(is_prime, 1, (size_t)(limit + 1));
    is_prime[0] = is_prime[1] = 0;

    for (uint64_t i = 2; i * i <= limit; ++i)
        if (is_prime[i])
            for (uint64_t j = i * i; j <= limit; j += i)
                is_prime[j] = 0;

    size_t cnt = 0;
    for (uint64_t i = 2; i <= limit; ++i)
        if (is_prime[i]) ++cnt;

    uint64_t *pr = (uint64_t *)malloc(cnt * sizeof(uint64_t));
    if (!pr) exit(1);
    size_t idx = 0;
    for (uint64_t i = 2; i <= limit; ++i)
        if (is_prime[i]) pr[idx++] = i;

    free(is_prime);
    *out = pr;
    *cnt_out = cnt;
}

/* ----------------------------------------------------------------------
   Factorisation of n using the prime list generated by the sieve.
   The returned array contains the distinct prime factors of n.
   ----------------------------------------------------------------------*/
static void factor_distinct_primes(uint64_t n, const uint64_t *primes, size_t primes_cnt,
                                   uint64_t **factors_out, size_t *cnt_out)
{
    uint64_t *fac = (uint64_t *)malloc(sizeof(uint64_t) * primes_cnt);
    if (!fac) exit(1);
    size_t fcnt = 0;
    uint64_t tmp = n;
    for (size_t i = 0; i < primes_cnt && primes[i] * primes[i] <= tmp; ++i)
    {
        if (tmp % primes[i] == 0)
        {
            fac[fcnt++] = primes[i];
            while (tmp % primes[i] == 0)
                tmp /= primes[i];
        }
    }
    if (tmp > 1)
        fac[fcnt++] = tmp;

    *factors_out = fac;
    *cnt_out = fcnt;
}

/* ----------------------------------------------------------------------
   Test whether 6 is a primitive root mod p and lifts to p².
   ----------------------------------------------------------------------*/
static bool is_primitive_root6_prime(uint64_t p, const uint64_t *primes, size_t primes_cnt)
{
    if (p == 2 || p == 3) return false;            /* 6 not coprime to p */

    /* 1. check order modulo p */
    uint64_t *factors = NULL;
    size_t fcnt = 0;
    factor_distinct_primes(p - 1, primes, primes_cnt, &factors, &fcnt);

    bool ok = true;
    for (size_t i = 0; i < fcnt && ok; ++i)
    {
        uint64_t q = factors[i];
        if (mod_pow64(6, (p - 1) / q, p) == 1ULL)
            ok = false;
    }
    free(factors);
    if (!ok) return false;

    /* 2. check lifting to p² */
    __uint128_t mod = (__uint128_t)p * (__uint128_t)p;
    __uint128_t base = 6 % mod;
    __uint128_t res  = 1;
    uint64_t exp = p - 1;
    while (exp)
    {
        if (exp & 1ULL)
            res = (res * base) % mod;
        base = (base * base) % mod;
        exp >>= 1ULL;
    }
    return res != 1;
}

/* ----------------------------------------------------------------------
   Min‑heap for the current smallest candidate powers.
   ----------------------------------------------------------------------*/
typedef struct {
    seq_t value;          /* current power p^e */
    uint64_t prime;       /* base prime   */
    uint32_t exp;         /* current exponent e */
} node_t;

static node_t *g_heap      = NULL;
static size_t g_heap_size  = 0;
static size_t g_heap_cap   = 0;

static void heap_push(seq_t val, uint64_t prime, uint32_t exp)
{
    if (g_heap_size + 1 > g_heap_cap)
    {
        size_t new_cap = g_heap_cap ? g_heap_cap * 2 : 64;
        node_t *tmp = (node_t *)realloc(g_heap, new_cap * sizeof(node_t));
        if (!tmp) exit(1);
        g_heap = tmp;
        g_heap_cap = new_cap;
    }
    node_t nd = { val, prime, exp };
    size_t i = g_heap_size++;
    while (i)
    {
        size_t parent = (i - 1) >> 1;
        if (g_heap[parent].value <= nd.value) break;
        g_heap[i] = g_heap[parent];
        i = parent;
    }
    g_heap[i] = nd;
}

static node_t heap_pop(void)
{
    node_t top = g_heap[0];
    g_heap[0] = g_heap[--g_heap_size];
    size_t i = 0;
    while (1)
    {
        size_t left  = i * 2 + 1;
        size_t right = left + 1;
        size_t smallest = i;
        if (left < g_heap_size && g_heap[left].value < g_heap[smallest].value)
            smallest = left;
        if (right < g_heap_size && g_heap[right].value < g_heap[smallest].value)
            smallest = right;
        if (smallest == i) break;
        node_t tmp = g_heap[smallest];
        g_heap[smallest] = g_heap[i];
        g_heap[i] = tmp;
        i = smallest;
    }
    return top;
}

/* ----------------------------------------------------------------------
   Memoised sequence storage.
   ----------------------------------------------------------------------*/
static seq_t *g_terms      = NULL;
static size_t g_terms_size = 0;
static size_t g_terms_cap  = 0;

/* ----------------------------------------------------------------------
   Prime list state for incremental generation.
   ----------------------------------------------------------------------*/
static uint64_t *g_prime_arr    = NULL;
static size_t    g_prime_cnt    = 0;
static size_t    g_prime_index  = 0;
static idx_t     g_prime_limit  = 0;

/* ----------------------------------------------------------------------
   Generate more primes and insert qualifying primes into the heap.
   ----------------------------------------------------------------------*/
static void process_more_primes(void)
{
    idx_t new_limit = (g_prime_limit == 0) ? 1000ULL : g_prime_limit * 2ULL;
    uint64_t *new_arr = NULL;
    size_t new_cnt = 0;
    build_primes_upto(new_limit, &new_arr, &new_cnt);

    /* free old prime array if any */
    if (g_prime_arr) free(g_prime_arr);
    g_prime_arr = new_arr;
    g_prime_cnt = new_cnt;
    g_prime_limit = new_limit;

    /* scan new primes from the stored index onwards */
    for (size_t i = g_prime_index; i < g_prime_cnt; ++i)
    {
        uint64_t p = g_prime_arr[i];
        if (is_primitive_root6_prime(p, g_prime_arr, g_prime_cnt))
        {
            seq_t pseq = (seq_t)p;
            seq_t val  = pseq * pseq;    /* start with p² */
            heap_push(val, p, 2);
        }
    }
    g_prime_index = g_prime_cnt;
}

/* ----------------------------------------------------------------------
   Generate terms up to the required count.
   ----------------------------------------------------------------------*/
static void generate_terms(idx_t target)
{
    while (g_terms_size < target)
    {
        if (g_heap_size == 0)
        {
            process_more_primes();
            if (g_heap_size == 0) break;   /* no more candidates */
        }
        node_t node = heap_pop();

        /* store the term */
        if (g_terms_size + 1 > g_terms_cap)
        {
            size_t new_cap = g_terms_cap ? g_terms_cap * 2 : 128;
            seq_t *tmp = (seq_t *)realloc(g_terms, new_cap * sizeof(seq_t));
            if (!tmp) exit(1);
            g_terms = tmp;
            g_terms_cap = new_cap;
        }
        g_terms[g_terms_size++] = node.value;

        /* push next higher power of the same prime */
        seq_t next_val = node.value * (seq_t)(node.prime);
        heap_push(next_val, node.prime, node.exp + 1);
    }
}

/* ----------------------------------------------------------------------
   Public sequence handler.
   ----------------------------------------------------------------------*/
seq_t a(idx_t n)
{
    if (n == 0) return 0;
    if (g_terms_size < n)
        generate_terms(n);
    return g_terms[n - 1];
}
