/* OEIS A082207 – palindromic integers whose digit‑product is a positive palindrome.
   The sequence is generated by enumerating decimal palindromes in ascending
   order and testing each for the condition that the product of its digits
   (with any zero digit causing immediate rejection) is itself a non‑zero
   palindrome.  No closed form or recurrence is known.  This deterministic
   search is fast enough for n up to about 10 000. */

#include <stdint.h>
#include <stdbool.h>

/* Determine whether a value is a decimal palindrome. */
static bool is_pal(seq_t x)
{
    seq_t rev = 0;
    seq_t t = x;
    while (t > 0) {
        rev = rev * 10 + (t % 10);
        t /= 10;
    }
    return rev == x;
}

/* Product of the non‑zero digits of v; return true if the product is a
   positive palindrome.  Any zero digit leads to rejection. */
static bool product_pal_valid(seq_t v)
{
    if (v == 0) return false;
    seq_t prod = 1;
    seq_t t = v;
    while (t > 0) {
        seq_t d = t % 10;
        if (d == 0) return false;   /* product would be zero, not positive */
        prod = prod * d;
        t /= 10;
    }
    return is_pal(prod);
}

/* Build the palindrome of total length 'len' from the integer 'half'.
   'half' is the left half (including the middle digit if len is odd). */
static seq_t build_pal(idx_t half, int len)
{
    seq_t pal = (seq_t)half;
    idx_t x = half;
    if (len & 1)      /* odd length – skip the middle digit when mirroring */
        x /= 10;
    while (x > 0) {
        pal = pal * 10 + (x % 10);
        x /= 10;
    }
    return pal;
}

/* Return the n-th term of sequence A082207.  Sequence is indexed from 1. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* n=0 is undefined – return 0 as sentinel */

    /* Pre‑computed powers of ten, up to 10^18 (enough for the first 10000 terms). */
    static const uint64_t pow10[20] = {
        1ULL, 10ULL, 100ULL, 1000ULL, 10000ULL, 100000ULL,
        1000000ULL, 10000000ULL, 100000000ULL, 1000000000ULL,
        10000000000ULL, 100000000000ULL, 1000000000000ULL,
        10000000000000ULL, 100000000000000ULL, 1000000000000000ULL,
        10000000000000000ULL, 100000000000000000ULL, 1000000000000000000ULL,
        10000000000000000000ULL
    };

    idx_t count = 0;       /* how many valid palindromes found so far */
    for (int len = 1; ; ++len) {
        int k = (len + 1) / 2;                 /* digits in the left half */
        idx_t start = pow10[k - 1];
        idx_t end   = pow10[k] - 1;
        for (idx_t h = start; h <= end; ++h) {
            seq_t cand = build_pal(h, len);
            if (product_pal_valid(cand)) {
                ++count;
                if (count == n) return cand;
            }
        }
    }
}
