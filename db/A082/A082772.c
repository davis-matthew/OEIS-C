/*
 * A082772  Integers n such that there exists at least one divisor d of n, 1 <
 *          d < n, such that d divides n and d+1 divides n+1.
 * https://oeis.org/A082772
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 90, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A082772: integers n with a divisor d (1<d<n) such that
   d|n and (d+1)|(n+1).  The sequence is generated by a simple
   divisor search. */
#include <stdlib.h>
#include <stddef.h>

static seq_t *terms = NULL;          /* dynamic array of found terms */
static size_t term_cap = 0;          /* current capacity of 'terms' */
static size_t term_len = 0;          /* number of terms stored */
static idx_t next_candidate = 8;     /* next integer to test   */

/* Append a new term to the dynamic array; grow it as necessary. */
static void add_term(seq_t val)
{
    if (term_len >= term_cap) {
        size_t new_cap = term_cap ? term_cap << 1 : 64;
        seq_t *tmp = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
        if (!tmp) abort();          /* allocation failed */
        terms = tmp;
        term_cap = new_cap;
    }
    terms[term_len++] = val;
}

/* Test whether an integer m satisfies the definition. */
static int has_property(idx_t m)
{
    idx_t i;
    for (i = 2; i <= m / i; ++i) {           /* iterate over divisors i and m/i */
        if (m % i == 0) {
            idx_t d1 = i, d2 = m / i;
            if ((m + 1) % (d1 + 1) == 0) return 1;
            if (d2 != d1 && (m + 1) % (d2 + 1) == 0) return 1;
        }
    }
    return 0;
}

/* Compute the nth term (n ≥ 1). Subsequent calls may arrive in any order. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                   /* undefined for n=0 */

    /* Generate terms until we have at least n of them. */
    while (term_len < n) {
        if (has_property(next_candidate))
            add_term((seq_t)next_candidate);
        ++next_candidate;
    }
    return terms[n - 1];
}
