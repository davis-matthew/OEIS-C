/*
 * A082422  Numbers n such that P(n) > P(n+2) > P(n+1), where P(n) = largest
 *          prime factor of n (A006530).
 * https://oeis.org/A082422
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 37, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  Sequence A082422:
    a(n) = the n‑th integer m such that P(m) > P(m+2) > P(m+1),
    where P(x) is the largest prime factor of x.
    The sequence is generated by successive sieve‑based search.   */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>
#include <string.h>

/* --------------  Internal static data  ---------------- */

/* Cache of computed sequence values (internal type uint64_t to avoid overflow). */
static uint64_t *seq_cache   = NULL;
static size_t   seq_len     = 0;   /* number of elements in seq_cache          */
static size_t   seq_cap     = 0;   /* allocated capacity of seq_cache           */

/* Cache of largest prime factor (LPF) for all numbers up to lpf_size. */
static uint32_t *lpf_cache   = NULL;
static size_t   lpf_size     = 0;   /* maximum index up to which lpf_cache is valid */

/* Last integer that was examined during the search. */
static uint64_t last_checked = 0;

/* --------------  Helper functions  ---------------- */

/* Allocate/resize lpf_cache and compute the largest prime factor for
   all integers up to 'limit'. */
static void recompute_lpf(size_t limit)
{
    free(lpf_cache);
    lpf_cache = (uint32_t *)malloc((limit + 1) * sizeof(uint32_t));
    if (!lpf_cache) { lpf_size = 0; return; }
    memset(lpf_cache, 0, (limit + 1) * sizeof(uint32_t));

    for (size_t i = 2; i <= limit; ++i) {
        if (lpf_cache[i] == 0) {          /* i is prime */
            for (size_t j = i; j <= limit; j += i)
                lpf_cache[j] = (uint32_t)i;   /* later primes overwrite smaller ones */
        }
    }
    lpf_size = limit;
}

/* Ensure that lpf_cache covers at least up to 'need'.  Grow if necessary. */
static void ensure_lpf(size_t need)
{
    if (need <= lpf_size) return;
    size_t new_lim = lpf_size ? lpf_size : 1000;
    while (new_lim < need) new_lim <<= 1;   /* double until large enough */
    recompute_lpf(new_lim);
}

/* --------------  Sequence generation  ---------------- */

/* Grow seq_cache to hold at least 'required' elements. */
static void grow_seq_cache(size_t required)
{
    if (required <= seq_cap) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 4;
    while (new_cap < required) new_cap <<= 1;
    uint64_t *tmp = (uint64_t *)realloc(seq_cache, new_cap * sizeof(uint64_t));
    if (!tmp) return;  /* allocation failed – keep old buffer */
    seq_cache = tmp;
    seq_cap   = new_cap;
}

/* Extend the sequence cache until it contains at least 'target' terms. */
static void extend_sequence(idx_t target)
{
    while (seq_len < target) {
        uint64_t cand = last_checked + 1;        /* candidate n  */
        ensure_lpf((size_t)(cand + 2));

        uint32_t Pn  = lpf_cache[(size_t)cand];
        uint32_t Pn1 = lpf_cache[(size_t)(cand + 1)];
        uint32_t Pn2 = lpf_cache[(size_t)(cand + 2)];

        if (Pn > Pn2 && Pn2 > Pn1) {
            grow_seq_cache(seq_len + 1);
            seq_cache[seq_len++] = cand;
        }
        last_checked = cand;
    }
}

/* --------------------------------------------------------- */

/*  Public sequence function. */
seq_t a(idx_t n)
{
    if (n < 1) return 0;           /* undefined for n = 0 */
    extend_sequence(n);
    return (seq_t)seq_cache[n - 1];   /* convert internal uint64_t to seq_t */
}
