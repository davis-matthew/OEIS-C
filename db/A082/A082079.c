/*
 * A082079  Balanced primes of order four.
 * https://oeis.org/A082079
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 75, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   _is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The function computes the n‑th balanced prime of order 4.
   A prime p is counted when it is the centre of a block
   of nine consecutive primes (p₁,…,p₉) such that
   p = (p₁+…+p₉)/9.  The sequence is generated by
   scanning all primes in order and keeping a sliding
   window of the last nine primes.  */
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/_is_prime.h"

seq_t a(idx_t n)
{
    /* static arrays store results across calls                 */
    static seq_t *balanced = NULL;    /* discovered balanced primes   */
    static idx_t bal_cnt  = 0;        /* how many have been stored    */
    static idx_t bal_cap  = 0;        /* current capacity of array    */

    /* circular buffer for the last nine primes                */
    static seq_t window[9];
    static idx_t win_start = 0;    /* position of oldest prime      */
    static idx_t win_cnt   = 0;    /* primes currently in window    */
    static seq_t win_sum   = 0;    /* sum of primes in current window */

    static idx_t candidate = 2;    /* current integer to test          */

    /* initialise storage for balanced primes on first use     */
    if (balanced == NULL) {
        bal_cap   = 16;
        balanced  = (seq_t *)malloc(bal_cap * sizeof(seq_t));
    }

    /* fast return if we already have enough terms            */
    if (n <= bal_cnt)
        return balanced[n-1];

    /* generate primes until we have at least the n‑th balanced one */
    while (bal_cnt < n) {
        /* find the next prime                                        */
        while (!_is_prime(candidate))
            candidate += (candidate == 2) ? 1 : 2;   /* 2,3,5,7,… */

        seq_t prime = candidate;

        /* insert the new prime into the sliding window              */
        if (win_cnt < 9) {                         /* still filling   */
            /* place at the end of the current buffer */
            window[(win_start + win_cnt) % 9] = prime;
            win_sum += prime;
            ++win_cnt;

            /* check only when the window became full                  */
            if (win_cnt == 9) {
                seq_t center = window[(win_start + 4) % 9];
                seq_t rhs    = 9 * center;
                if (rhs == win_sum) {
                    if (bal_cnt == bal_cap) {          /* grow array */
                        bal_cap <<= 1;
                        balanced = (seq_t *)realloc(balanced,
                                                    bal_cap * sizeof(seq_t));
                    }
                    balanced[bal_cnt++] = center;
                }
            }
        } else {                                    /* window full   */
            /* remove old oldest prime and add the new one           */
            seq_t old = window[win_start];
            win_sum -= old;
            window[win_start] = prime;
            win_sum += prime;
            win_start = (win_start + 1) % 9;          /* advance oldest */

            seq_t center = window[(win_start + 4) % 9];
            seq_t rhs    = 9 * center;
            if (rhs == win_sum) {
                if (bal_cnt == bal_cap) {              /* grow array */
                    bal_cap <<= 1;
                    balanced = (seq_t *)realloc(balanced,
                                                bal_cap * sizeof(seq_t));
                }
                balanced[bal_cnt++] = center;
            }
        }

        /* advance to the next candidate number                      */
        candidate += (candidate == 2) ? 1 : 2;
    }

    return balanced[n-1];
}
