/*
 * A077479  Number of distinct prime factors of numbers m with BigOmega(m) ==
 *          0 modulo omega(m).
 * https://oeis.org/A077479
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1000, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   bigomega, count_distinct_primes
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A077479: Number of distinct prime factors of integers m
   such that BigOmega(m) ≡ 0 (mod omega(m)).
   a(n) equals ω(m_n) where m_n is the n‑th integer with that property.
   The sequence is generated by a linear scan of the integers m
   and caching the values. */

#include <stdlib.h>
#include "../utils/bigomega.h"
#include "../utils/count_distinct_primes.h"

/* Static cache for computed terms */
static seq_t      *cache      = NULL;   /* array of a(k) */
static size_t      cache_len  = 0;      /* number of cached terms */
static size_t      cache_cap  = 0;      /* capacity of cache array */
static idx_t       next_m     = 2;      /* next integer m to test */
static idx_t       found_cnt  = 0;      /* number of valid m found so far */

/* Ensure the cache can hold at least 'need' entries. */
static void
ensure_cache_capacity(size_t need)
{
    if (cache_cap >= need)
        return;
    size_t new_cap = (cache_cap == 0) ? 256 : cache_cap;
    while (new_cap < need)
        new_cap <<= 1;                     /* double until large enough */
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp)
        abort();                           /* memory exhausted */
    cache = tmp;
    cache_cap = new_cap;
}

/* Grow the cache until it contains at least 'target' terms. */
static void
grow_cache_to(idx_t target)
{
    while (found_cnt < target) {
        uint64_t m = (uint64_t)next_m;  /* current integer to test   */
        ++next_m;

        int omega_int = count_distinct_primes(m); /* ω(m) */
        if (omega_int == 0)                  /* skip m = 1  */
            continue;

        seq_t big = bigomega((idx_t)m);           /* Ω(m) */
        if ((big % (seq_t)omega_int) == 0) {      /* Ω ≡ 0 (mod ω) */
            ensure_cache_capacity(cache_len + 1);
            cache[cache_len++] = (seq_t)omega_int;
            ++found_cnt;
        }
    }
}

/* Public entry point required by the build system. */
seq_t a(idx_t n)
{
    if (n == 0)                 /* undefined for offset 0, return 0 */
        return 0;

    if (cache_len < (size_t)n)  /* need more terms */
        grow_cache_to(n);

    return cache[n - 1];
}
