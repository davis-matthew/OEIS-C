/*
 * A077303  Partition the concatenation 235711131719232931...of prime numbers
 *          into successive strings such that the n-th string is a multiple of
 *          n and >n.
 * https://oeis.org/A077303
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 1, u32 n <= 1, u64 n <= 7, u128 n <= 7,
 *            big any n
 * Helpers:   sieve_primes
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes OEIS A077303:
   Partition the concatenation of primes 2357111317… into successive
   strings such that the n‑th string is a multiple of n and > n. */

/* The sequence is generated by scanning the prime digits in order
   and attaching digits to the current segment until it satisfies the
   divisibility and size condition. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/sieve_primes.h"

static seq_t *cache        = NULL;
static size_t cache_len    = 0;
static size_t cache_cap    = 0;

static idx_t  *prime_arr   = NULL;      /* array of primes (type idx_t) */
static size_t prime_cnt     = 0;
static size_t prime_cap     = 0;        /* unused, kept for compatibility */
static idx_t   next_prime_idx = 0;
static idx_t   prime_limit   = 0;      /* current numeric upper bound of primes */

/* Digits of the current prime, most‑significant first */
static uint8_t  digit_buf[20];
static int      digit_len   = 0;
static int      digit_pos   = 0;

/* Ensure that primes are available up to at least 'new_limit'.
   The 'sieve_primes' function in the utilities creates the list
   and assigns the array pointer and count. */
static void ensure_primes(idx_t new_limit)
{
    if (new_limit <= prime_limit) return;

    idx_t lim = prime_limit;
    if (lim == 0) lim = 100;
    while (lim < new_limit) lim <<= 1;          /* grow exponentially */

    free(prime_arr);                            /* discard old array */
    sieve_primes(lim, (idx_t **)&prime_arr, &prime_cnt);
    prime_limit = lim;
    /* prime_arr now holds primes up to 'lim', prime_cnt is the count   */
}

/* Load the next prime number's decimal digits into digit_buf. */
static void load_next_prime(void)
{
    if ((size_t)next_prime_idx >= prime_cnt)
        ensure_primes(prime_limit * 2 + 1);     /* double the bound if needed */

    idx_t p = prime_arr[next_prime_idx++];
    /* decompose p into digits, most‑significant first */
    uint8_t tmp_digits[20];
    int pos = 0;
    idx_t tmp = p;
    while (tmp > 0) {
        tmp_digits[pos++] = (uint8_t)(tmp % 10);
        tmp /= 10;
    }
    for (int i = 0; i < pos; ++i)
        digit_buf[i] = tmp_digits[pos - 1 - i];
    digit_len = pos;
    digit_pos = 0;
}

/* Initialise static state on first call. */
static void init_state(void)
{
    if (cache != NULL) return;

    cache_cap = 8;
    cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
    cache_len = 0;

    prime_limit = 100;
    prime_cnt = 0;
    prime_arr = NULL;
    next_prime_idx = 0;

    ensure_primes(prime_limit);
}

/* Main function requested by the build system. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* offset is 1, value for n=0 unused */

    init_state();

    /* Generate terms up to n */
    while (cache_len < n) {
        idx_t part = cache_len + 1;       /* current segment number   */
        seq_t cur_val = 0;                /* value of current segment */
        seq_t cur_rem = 0;                /* remainder modulo part    */
        bool found = false;

        /* Build the current segment until criteria met */
        while (!found) {
            uint8_t digit;
            if (digit_pos < digit_len) {
                digit = digit_buf[digit_pos++];
            } else {
                load_next_prime();
                digit = digit_buf[digit_pos++];
            }
            cur_val = cur_val * 10 + (seq_t)digit;
            cur_rem = (cur_rem * 10 + (seq_t)digit) % (seq_t)part;
            if (cur_val > (seq_t)part && cur_rem == 0)
                found = true;
        }

        /* Store the completed segment in cache */
        if (cache_len == cache_cap) {
            cache_cap *= 2;
            cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        }
        cache[cache_len++] = cur_val;
    }
    return cache[n - 1];
}
