/*  OEIS A322170 – area of the primitive Pythagorean triangle at
    index n in the Berggren tree (row‑major order).
    The triple is generated by successive Berggren matrices:
        M1 = [[ 1, -2,  2],
              [ 2, -1,  2],
              [ 2, -2,  3]]   (digit 0)
        M2 = [[ 1,  2,  2],
              [ 2,  1,  2],
              [ 2,  2,  3]]   (digit 1)
        M3 = [[-1,  2,  2],
              [-2,  1,  2],
              [-2,  2,  3]]   (digit 2)
    The area is a*b/2, where a and b are the two legs.  */

#include <stdint.h>

/* helpers for small integer multiplications */
static inline seq_t mul2(seq_t x) { return x + x; }
static inline seq_t mul3(seq_t x) { return x + x + x; }

seq_t a(idx_t n)
{
    /* locate the row (depth) and position within that row */
    idx_t row = 1;
    idx_t rows_before = 0;
    idx_t row_size   = 1;              /* 3^(row-1) */
    while (rows_before + row_size < n) {
        rows_before += row_size;
        ++row;
        if (row_size > (idx_t)(-1) / 3) break;  /* protect against overflow */
        row_size *= 3;
    }
    idx_t pos = n - rows_before;      /* 1‑based within the row */

    idx_t depth = row - 1;             /* number of transformations */

    /* decode pos‑1 in base‑3: digits[0] is most significant */
    idx_t digits[32] = {0};            /* depth ≤ 20 for n≤1e5 */
    idx_t idx = pos - 1;
    for (int d = depth - 1; d >= 0; --d) {
        digits[d] = idx % 3;
        idx /= 3;
    }

    /* start from the root primitive triple (3,4,5) */
    seq_t a_leg = 3, b_leg = 4, c_leg = 5;
    seq_t new_a, new_b, new_c;

    for (int d = 0; d < depth; ++d) {
        switch (digits[d]) {
        case 0:   /* M1 */
            /* a' = a + 2c – 2b */
            new_a = a_leg + mul2(c_leg) - mul2(b_leg);
            /* b' = 2a + 2c – b */
            new_b = mul2(a_leg) + mul2(c_leg) - b_leg;
            /* c' = 2a + 3c – 2b */
            new_c = mul2(a_leg) + mul3(c_leg) - mul2(b_leg);
            break;

        case 1:   /* M2 */
            /* a' = a + 2b + 2c */
            new_a = a_leg + mul2(b_leg) + mul2(c_leg);
            /* b' = 2a + b + 2c */
            new_b = mul2(a_leg) + b_leg + mul2(c_leg);
            /* c' = 2a + 2b + 3c */
            new_c = mul2(a_leg) + mul2(b_leg) + mul3(c_leg);
            break;

        case 2:   /* M3 */
            /* a' = 2b + 2c – a */
            new_a = mul2(b_leg) + mul2(c_leg) - a_leg;
            /* b' = b + 2c – 2a */
            new_b = b_leg + mul2(c_leg) - mul2(a_leg);
            /* c' = 2b + 3c – 2a */
            new_c = mul2(b_leg) + mul3(c_leg) - mul2(a_leg);
            break;
        }

        a_leg = new_a;
        b_leg = new_b;
        c_leg = new_c;
    }

    return (a_leg * b_leg) / 2;   /* area of the primitive triangle */
}
