/*
 * A034214  Number of ternary codes of length 2 with n words.
 * https://oeis.org/A034214
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 83, u16 n <= 83, u32 n <= 83, u64 n <= 83, u128 n <= 83,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdbool.h>

/*  a(n) = number of orbits of n‑element subsets of {0,…,8}
    under the group generated by
       – swapping the two coordinates,
       – independently permuting the symbols {0,1,2} on each coordinate.
    The group has 6·6·2 = 72 elements; for n>9 the value is 0. */

seq_t a(idx_t n)
{
    static seq_t freq[10] = {0};
    static bool init = false;

    if (!init) {
        /* All 6 permutations of {0,1,2} */
        const unsigned char perm[6][3] = {
            {0,1,2},{0,2,1},{1,0,2},
            {1,2,0},{2,0,1},{2,1,0}
        };

        /* Build 72 group elements: (p0,p1,swap) */
        unsigned char maps[72][9];
        int g = 0;
        for (int p0 = 0; p0 < 6; ++p0)
            for (int p1 = 0; p1 < 6; ++p1)
                for (int swap = 0; swap < 2; ++swap) {
                    for (int w = 0; w < 9; ++w) {
                        int a = w / 3;
                        int b = w % 3;
                        if (swap) { int t = a; a = b; b = t; }
                        int na = perm[p0][a];
                        int nb = perm[p1][b];
                        maps[g][w] = (unsigned char)(na * 3 + nb);
                    }
                    ++g;
                }

        /* Enumerate all subsets of the 9-element set */
        for (int mask = 0; mask < 512; ++mask) {
            int canon = 512;
            for (int h = 0; h < 72; ++h) {
                int nmask = 0;
                for (int w = 0; w < 9; ++w)
                    if (mask & (1 << w))
                        nmask |= 1 << maps[h][w];
                if (nmask < canon) canon = nmask;
            }
            if (canon == mask) {
                int bits = 0;
                for (int w = 0; w < 9; ++w)
                    if (mask & (1 << w))
                        ++bits;
                freq[bits] += 1;
            }
        }
        init = true;
    }

    if (n > 9) return 0;
    return freq[(idx_t)n];
}
