/* Sequence A034045: imprimitive but not primitive representations
   by x² + y² + z².  A term a(n) is the n‑th multiple of 4 that is
   representable by the sum of three squares (i.e., not of the
   form 4^k·(8m+7)).  The sequence is generated by testing
   Legendre's three‑square theorem on multiples of 4. */
#include <stdbool.h>

/* Return true iff n can be expressed as x² + y² + z². */
static inline bool _rep3sq(seq_t n)
{
    if (n == 0u) return true;          /* 0 = 0²+0²+0² */
    seq_t m = n;
    while ((m & 3u) == 0u) {           /* strip factors of 4 */
        m >>= 2;
    }
    return (m & 7u) != 7u;             /* not of the form 8k+7 */
}

/* a(n): n ≥ 1 */
seq_t a(idx_t n)
{
    seq_t cand = 0u;           /* 0 is the first term */
    idx_t  cnt = 0u;

    while (1) {
        if (_rep3sq(cand)) {
            ++cnt;
            if (cnt == n) return cand;
        }
        cand += 4u;            /* next multiple of 4 */
    }
}
