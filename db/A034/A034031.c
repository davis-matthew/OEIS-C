/*
 * A034031  Numbers that are primitively but not imprimitively represented by
 *          x^2+2y^2.
 * https://oeis.org/A034031
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 51, u16 n <= 51, u32 n <= 51, u64 n <= 51, u128 n <= 51,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Algorithm: a(n) = n-th square‑free integer whose prime factors are
   either 2 or primes congruent to 1 or 3 modulo 8.  The sequence
   is generated by testing consecutive integers for this property. */
/* The function works for any build that supplies the types seq_t
   and idx_t.  It keeps a cache of already computed terms so that
   any order of calls is supported. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* ---- Smallest prime factor sieve ------------------------------------- */
static uint32_t *spf = NULL;      /* spf[i] = smallest prime factor of i (i>=2)          */
static size_t   spf_limit = 0;    /* current maximum index for which spf is defined     */

/* Ensure spf is defined for all numbers up to 'limit'.  A new allocation
   recomputes the full sieve; this is fast enough for the sizes encountered
   in the test suite. */
static void build_spf(size_t limit) {
    if (limit <= spf_limit) return;
    size_t new_lim = limit;
    uint32_t *tmp = (uint32_t *)realloc(spf, (new_lim + 1) * sizeof(uint32_t));
    if (!tmp) { abort(); }
    spf = tmp;
    for (size_t i = 0; i <= new_lim; ++i) spf[i] = 0;
    for (size_t i = 2; i * i <= new_lim; ++i) {
        if (spf[i] == 0) {
            for (size_t j = i * i; j <= new_lim; j += i) {
                if (spf[j] == 0) spf[j] = (uint32_t)i;
            }
        }
    }
    for (size_t i = 2; i <= new_lim; ++i) {
        if (spf[i] == 0) spf[i] = (uint32_t)i;   /* prime */
    }
    spf_limit = new_lim;
}

/* ---- Test whether a number satisfies the condition ------------------- */
static bool is_good(uint64_t n) {
    if (n == 1) return true;
    build_spf((size_t)n);              /* spf is now defined up to n */
    uint64_t t = n;
    while (t > 1) {
        uint32_t p = spf[t];
        int exp = 0;
        while (t % p == 0) {
            t /= p;
            ++exp;
            if (exp > 1) return false;  /* not square‑free */
        }
        if (p != 2 && (p % 8 == 5 || p % 8 == 7)) return false;  /* forbidden prime */
    }
    return true;
}

/* ---- Cache of generated sequence terms ------------------------------ */
static seq_t *seq_cache = NULL;       /* array of computed terms, type seq_t */
static size_t cache_size = 0;          /* number of terms stored          */
static size_t cache_cap   = 0;          /* current allocation capacity     */
static uint64_t next_candidate = 1;     /* next integer to test           */

/* Append a new term to the cache */
static void cache_append(seq_t value) {
    if (cache_size == cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 32;
        seq_t *tmp = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
        if (!tmp) { abort(); }
        seq_cache = tmp;
        cache_cap = new_cap;
    }
    seq_cache[cache_size++] = value;
}

/* ---- Public function ------------------------------------------------- */
seq_t a(idx_t n) {
    if (n == 0) return (seq_t)0;        /* behaviour for n<1 is irrelevant */

    while (cache_size < (size_t)n) {
        if (is_good(next_candidate)) {
            cache_append((seq_t)next_candidate);
        }
        ++next_candidate;
    }
    return seq_cache[(size_t)n - 1];
}
