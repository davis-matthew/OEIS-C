/*
 * A034840  Concatenation of 3 or more numbers in arithmetic progression.
 * https://oeis.org/A034840
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) is the nth integer obtained by concatenating three or more
 *            terms of an integer arithmetic progression (allowing zero and
 *            negative common differences)
 * Range:     u8 none, u16 none, u32 n <= 49, u64 n <= 49, u128 n <= 49,
 *            big any n
 * Helpers:   digit_len, pow10
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence is generated by exploring all progressions with
   starting term 1 ≤ a ≤ AMAX, common difference d in [-(a‑1), DMAX],
   and extending each to longer lengths as needed.  The results are
   kept in a min‑heap; the first n elements are produced on the fly
   and cached for future queries. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

#include "../utils/pow10.h"
#include "../utils/digit_len.h"

/* ------------------------------------------------------------------------- */
/* Data structures */

typedef struct {
    seq_t val;      /* concatenated value */
    int64_t a;      /* first term (signed for safety) */
    int64_t d;      /* common difference */
    uint32_t k;     /* current length of the progression */
} Cand;

static Cand *heap = NULL;            /* min‑heap of candidates */
static size_t heap_size = 0;
static size_t heap_cap = 0;

static seq_t *output = NULL;         /* cached output sequence */
static size_t output_size = 0;
static size_t output_cap = 0;

static bool cache_initialized = false;
#define AMAX 500
#define DMAX 500

/* ------------------------------------------------------------------------- */
/* Heap helpers */

static void grow_heap(size_t need)
{
    if (need <= heap_cap) return;
    size_t new_cap = heap_cap ? heap_cap * 2 : 128;
    while (new_cap < need) new_cap *= 2;
    Cand *tmp = (Cand *)realloc(heap, new_cap * sizeof(Cand));
    if (!tmp) abort();
    heap = tmp;
    heap_cap = new_cap;
}

static void push_heap(Cand c)
{
    grow_heap(heap_size + 1);
    size_t i = heap_size++;
    heap[i] = c;
    while (i > 0) {
        size_t p = (i - 1) >> 1;
        if (heap[p].val <= heap[i].val) break;
        Cand tmp = heap[p]; heap[p] = heap[i]; heap[i] = tmp;
        i = p;
    }
}

static Cand pop_heap(void)
{
    Cand root = heap[0];
    heap[0] = heap[--heap_size];
    size_t i = 0;
    while (1) {
        size_t l = (i << 1) + 1;
        size_t r = l + 1;
        size_t smallest = i;
        if (l < heap_size && heap[l].val < heap[smallest].val) smallest = l;
        if (r < heap_size && heap[r].val < heap[smallest].val) smallest = r;
        if (smallest == i) break;
        Cand tmp = heap[i]; heap[i] = heap[smallest]; heap[smallest] = tmp;
        i = smallest;
    }
    return root;
}

/* ------------------------------------------------------------------------- */
/* Output buffer helpers */

static void grow_output(size_t need)
{
    if (need <= output_cap) return;
    size_t new_cap = output_cap ? output_cap * 2 : 128;
    while (new_cap < need) new_cap *= 2;
    seq_t *tmp = (seq_t *)realloc(output, new_cap * sizeof(seq_t));
    if (!tmp) abort();
    output = tmp;
    output_cap = new_cap;
}

/* ------------------------------------------------------------------------- */
/* Progression helpers */

static void extend_candidate(Cand c)
{
    /* Compute next term: a + k*d  (current k terms already used) */
    __int128 next_term128 = (__int128)c.a + (__int128)c.k * c.d;
    if (next_term128 < 0) return;            /* would be negative – stop */
    seq_t next_term = (seq_t)next_term128;

    /* Compute new concatenated value = previous * 10^len(next_term) + next_term */
    seq_t new_val = c.val * pow10((idx_t)digit_len(next_term)) + next_term;
    Cand nxt = { new_val, c.a, c.d, c.k + 1 };
    push_heap(nxt);
}

/* ------------------------------------------------------------------------- */
/* Initial candidate generation */

static void init_candidates(void)
{
    for (uint64_t a = 1; a <= AMAX; ++a) {
        int64_t d_min = -(int64_t)(a - 1);
        for (int64_t d = d_min; d <= DMAX; ++d) {
            int64_t third = (int64_t)a + 2 * d;
            if (third < 0) continue;          /* all terms must be non‑negative */

            /* Build initial concatenation of three terms */
            seq_t term1 = (seq_t)a;
            seq_t term2 = (seq_t)((int64_t)a + d);
            seq_t term3 = (seq_t)third;

            seq_t val = term1 * pow10((idx_t)digit_len(term2)) + term2;
            val = val * pow10((idx_t)digit_len(term3)) + term3;

            Cand c = { val, (int64_t)a, d, 3 };
            push_heap(c);
        }
    }
}

/* ------------------------------------------------------------------------- */
/* Cache generation */

static void ensure_cache(idx_t n)
{
    if (!cache_initialized) {
        cache_initialized = true;
        init_candidates();
    }

    /* Produce outputs until we have at least n + 1 terms cached */
    grow_output(n + 1);
    while (output_size <= n) {
        Cand c = pop_heap();

        /* Store the value into the output sequence */
        output[output_size++] = c.val;

        /* Extend this progression for the next term */
        extend_candidate(c);
    }
}

/* ------------------------------------------------------------------------- */
/* Sequence entry point */

seq_t a(idx_t n)
{
    ensure_cache(n);
    return output[n];
}
