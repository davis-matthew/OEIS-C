/* Compute the n-th integer a such that the fractional part of sqrt(a) is
   in the interval [0.2,0.3), i.e., the fractional part starts with the
   digit 2.  The sequence begins: 5, 18, 28, 39, 52, 53, 68, 85, 86, … */

/* Note: The sequence can be generated by iterating over integer k = floor(sqrt(a)).
   For each k, integer m must satisfy
          ceil(0.4k+0.04) ≤ m ≤ floor(0.6k+0.09).
   Then a = k² + m.  The algorithm below produces terms in increasing order. */

#include <stdint.h>

seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* offset is 1; return 0 for safety */

    idx_t count = 0;               /* number of terms found so far */

    for (idx_t k = 1; ; ++k)       /* k = floor(sqrt(a)) */
    {
        /* lower = ceil(2k/5 + 1/25)  → (10k + 25)/25   */
        idx_t lower = (10 * k + 25) / 25;
        /* upper = floor(3k/5 + 9/100)  → (60k + 9)/100  */
        idx_t upper = (60 * k + 9) / 100;

        if (lower <= upper)
        {
            seq_t sq = (seq_t)k * k;          /* k² in seq_t */

            for (idx_t m = lower; m <= upper; ++m)
            {
                ++count;
                if (count == n)
                    return sq + (seq_t)m;     /* a = k² + m */
            }
        }
    }
}
