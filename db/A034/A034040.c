/*  Imprimitively but not primitively represented by
    (x^2+xy+2y^2, x>=0, y>=0)
    The sequence consists of values that have at least one
    representation with gcd(x,y)>1 but have no representation
    with gcd(x,y)=1.  Values are generated by enumerating all
    (x,y) with 0<=y and 0<=x and collecting the flags for each
    value.  The sequence is built lazily: whenever a(n) is
    requested we increase the search limit until we have found
    n+1 terms.  This implementation works for any integer
    type seq_t and idx_t defined by the build.  The algorithm
    runs in O(limit) time with memory O(limit), where limit
    grows roughly linearly with the number of terms requested. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <string.h>

/* gcd for 64‑bit unsigned integers */
static inline uint64_t gcd_u64(uint64_t a, uint64_t b)
{
    while (b != 0) {
        uint64_t t = a % b;
        a = b;
        b = t;
    }
    return a;
}

/* Dynamically sized array holding flags for each value:
   bit 0 = has primitive representation,
   bit 1 = has imprimitive representation.
*/
static uint8_t *flag = NULL;
static idx_t flag_size = 0;

/* Array of found sequence terms, stored in order */
static seq_t *found = NULL;
static size_t found_len = 0;
static size_t found_cap = 0;

/* Highest value that has already been examined when generating terms */
static idx_t scanned_to = 8;   /* we start scanning from 9 */

/* Current upper limit for enumeration */
static idx_t current_limit = 0;
static bool initialized = false;

/* Rebuild the flag array for all representations up to new_limit. */
static void rebuild_flags(idx_t new_limit)
{
    if (flag) {
        free(flag);
        flag = NULL;
    }
    flag_size = new_limit + (idx_t)1;
    flag = (uint8_t*)calloc((size_t)flag_size, sizeof(uint8_t));
    if (!flag) return;   /* allocation failure – caller will handle it */

    /* Enumerate all (x,y) with 0 <= y and 0 <= x such that
       value = x*x + x*y + 2*y*y <= new_limit. */
    for (idx_t y = 0; (uint64_t)2 * y * y <= new_limit; ++y) {
        for (idx_t x = 0; ; ++x) {
            uint64_t val = (uint64_t)x * x + (uint64_t)x * y + (uint64_t)2 * y * y;
            if (val > new_limit) break;
            if (x == 0 && y == 0) continue;        /* skip (0,0) */
            uint64_t g = gcd_u64((uint64_t)x, (uint64_t)y);
            if (g == 1)
                flag[(size_t)val] |= 1;            /* primitive */
            else
                flag[(size_t)val] |= 2;            /* imprimitive */
        }
    }
}

/* Append a new term to the found array */
static void add_term(seq_t v)
{
    if (found_len >= found_cap) {
        found_cap = found_cap ? found_cap * 2 : 64;
        found = (seq_t*)realloc(found, found_cap * sizeof(seq_t));
    }
    found[found_len++] = v;
}

/* Scan values in (scanned_to, new_limit] for terms to add. */
static void scan_new_range(idx_t new_limit)
{
    for (idx_t v = scanned_to + (idx_t)1; v <= new_limit; ++v) {
        if (v <= (idx_t)8) continue;                /* skip small values */
        uint8_t f = flag[(size_t)v];
        if ((f & 2) && !(f & 1))                   /* imprimitive, not primitive */
            add_term((seq_t)v);
    }
    scanned_to = new_limit;
}

/* Main sequence function */
seq_t a(idx_t n)
{
    /* Lazy initialization */
    if (!initialized) {
        initialized = true;
        current_limit = 128;           /* initial search limit */
        rebuild_flags(current_limit);
        scan_new_range(current_limit);
    }

    /* Grow the limit until we have at least n+1 terms */
    while (found_len <= n) {
        current_limit *= 2;            /* double the search range */
        rebuild_flags(current_limit);
        scan_new_range(current_limit);
    }

    return found[n];
}
