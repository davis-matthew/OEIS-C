/*
 * Formula: a(n) is the nth integer a such that the fractional part of
 * the cube root of a begins with the digit 4, i.e.
 *   0.4 ≤ cube_root(a) – ⌊cube_root(a)⌋ < 0.5
 * The sequence can be generated by iterating over the integer part t
 * of the cube root and collecting all a satisfying
 *   (t + 0.4)³ ≤ a < (t + 0.5)³ .
 * This is equivalent to the inequalities
 *   ceil(((10t+4)³)/1000) ≤ a ≤ floor(((10t+5)³-1)/1000)
 * for each t ≥ 1.  The algorithm walks through t until the n‑th
 * value is found.
 */

seq_t a(idx_t n)
{
    seq_t count   = (seq_t)0;      /* number of values seen so far   */
    seq_t result  = (seq_t)0;      /* the n‑th value returnable      */

    const seq_t MILL = (seq_t)1000;   /* denominator used in bounds     */

    for (idx_t t = 1; ; ++t)
    {
        seq_t t_seq = (seq_t)t;

        /* (10t + 4)³ and (10t + 5)³ computed using seq_t arithmetic */
        seq_t low_base  = t_seq * ((seq_t)10) + (seq_t)4;
        seq_t high_base = t_seq * ((seq_t)10) + (seq_t)5;

        seq_t low_num  = low_base * low_base * low_base;   /* (10t+4)³   */
        seq_t high_num = high_base * high_base * high_base; /* (10t+5)³   */

        /* lower bound: ceil(low_num / 1000)      */
        seq_t low  = (low_num + MILL - (seq_t)1) / MILL;

        /* upper bound: floor((high_num-1) / 1000) */
        seq_t high = (high_num - (seq_t)1) / MILL;

        if (high < low)
            continue;          /* no values for this t */

        seq_t len = high - low + (seq_t)1;   /* how many a for this t */

        if (count + len >= n)
        {
            /* the desired value lies within this block */
            result = low + (n - count - (seq_t)1);
            break;
        }

        count += len;   /* skip this block entirely */
    }

    return result;
}
