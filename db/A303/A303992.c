/*
 * A303992  Triangular array T(n,k) giving coefficients in expansion of
 *          Product_{j=1..n} (1-x^j)^3.
 * https://oeis.org/A303992
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  sign, tabf
 * Formula:   not stated
 * Range:     i8 n <= 209, i16 n <= 2248, i32 n <= 9854, i64 n <= 9854,
 *            i128 n <= 9854, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A303992: a(n) is the coefficient of x^k in the expansion of
   ∏_{j=1}^{r} (1 – x^j)^3, where r and k are chosen such that
   the n‑th element is read row‑by‑row (row 0 first).
   The sequence is generated by successively multiplying the
   previous polynomial by (1 – x^r)^3.  */
/* -------------------------------------------------------------------- */

#include <stdlib.h>

static seq_t *coeff_table = NULL;          /* flattened sequence a(n) */
static size_t coeff_cap   = 0;             /* current capacity of coeff_table */
static size_t coeff_len   = 0;             /* number of elements stored */

static seq_t *poly = NULL;                 /* current row polynomial */
static size_t poly_size = 0;               /* size of current polynomial */
static idx_t next_row = 1;                 /* next row to generate (j) */

/* ensure coeff_table has capacity for at least +need elements */
static void ensure_coeff_capacity(size_t need)
{
    if (coeff_len + need <= coeff_cap) return;
    size_t new_cap = coeff_cap ? coeff_cap : 16;
    while (coeff_len + need > new_cap) new_cap <<= 1;
    coeff_table = (seq_t *)realloc(coeff_table, new_cap * sizeof(seq_t));
    coeff_cap = new_cap;
}

/* generate the next row of the product and append its coefficients
   to the flattened sequence */
static void generate_next_row(void)
{
    size_t j = (size_t)next_row;          /* current row index (1‑based) */
    size_t new_size = poly_size + 3 * j;  /* new polynomial size */

    /* allocate new polynomial and initialise to zero */
    seq_t *new_poly = (seq_t *)calloc(new_size, sizeof(seq_t));

    /* convolution with (1 - 3x^j + 3x^{2j} - x^{3j}) */
    for (size_t e = 0; e < poly_size; ++e) {
        seq_t val = poly[e];
        new_poly[e]          += val;                  /* +1   */
        new_poly[e +  j]     += val * (seq_t)(-3);    /* -3   */
        new_poly[e + 2*j]    += val * (seq_t)3;       /* +3   */
        new_poly[e + 3*j]    += val * (seq_t)(-1);    /* -1   */
    }

    free(poly);                       /* discard previous row polynomial */
    poly       = new_poly;
    poly_size  = new_size;
    ++next_row;                       /* increment to next row index (j) */

    /* append new row to the flattened sequence */
    ensure_coeff_capacity(poly_size);
    for (size_t i = 0; i < poly_size; ++i) {
        coeff_table[coeff_len++] = poly[i];
    }
}

/* public function for the sequence */
seq_t a(idx_t n)
{
    /* one‑time initialisation: row 0 */
    static int initialized = 0;
    if (!initialized) {
        initialized = 1;
        /* initialize row 0 (empty product) */
        poly_size = 1;
        poly = (seq_t *)malloc(sizeof(seq_t));
        poly[0] = (seq_t)1;

        coeff_cap = 16;
        coeff_table = (seq_t *)malloc(coeff_cap * sizeof(seq_t));
        coeff_table[coeff_len++] = poly[0];  /* a(0) = 1 */

        next_row = 1;          /* next row to generate */
    }

    /* generate rows until we have computed up to index n */
    while (coeff_len <= (size_t)n) {
        generate_next_row();
    }

    return coeff_table[(size_t)n];
}
