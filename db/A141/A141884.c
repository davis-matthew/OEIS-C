/* Sequence: primes congruent to 11 (mod 20) */

/* The function implements the OEIS sequence A141884.
///   a(1) = 11
///   a(2) = 31
///   a(3) = 71
///   …
*
* It uses a dynamic cache of found primes. The first stored prime is 11,
* and subsequent candidates are generated by adding 20. Whenever a
* candidate is prime (checked with the supplied helper is_prime), it is
* appended to the cache. The routine runs in O(n) time for the first n
* terms and answers any subsequent query in O(1).
*/

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime.h"

seq_t a(idx_t n)
{
    /* static cache of primes ≡ 11 (mod 20) */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;   /* number of primes stored */
    static size_t cache_cap = 0;   /* allocated capacity in slots */
    static idx_t last_candidate = 0;   /* last checked candidate */
    static bool initialized = false;

    /* Lazy initialization: store the first prime 11 */
    if (!initialized) {
        cache_cap = 8;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache)
            return (seq_t)0;      /* allocation failure – unlikely in tests */
        cache[0] = (seq_t)11;
        cache_len = 1;
        last_candidate = 11;
        initialized = true;
    }

    /* If the requested index is already cached, return it directly */
    if (n <= cache_len)
        return cache[n - 1];

    /* Generate more terms until we reach the desired index */
    while (cache_len < n) {
        /* Advance to the next number ≡ 11 (mod 20) */
        last_candidate += 20;
        if (is_prime(last_candidate)) {
            /* Grow cache if necessary */
            if (cache_len >= cache_cap) {
                cache_cap *= 2;
                seq_t *tmp = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
                if (!tmp) {
                    free(cache);
                    cache = NULL;
                    cache_len = 0;
                    cache_cap = 0;
                    return (seq_t)0;   /* allocation failure */
                }
                cache = tmp;
            }
            cache[cache_len++] = (seq_t)last_candidate;
        }
    }

    return cache[n - 1];
}
