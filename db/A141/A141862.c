/*
 * A141862  Primes of the form k/(p(k-1)-p(k-2)), where p(k)=k-th prime.
 * https://oeis.org/A141862
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 22, u16 n <= 63, u32 n <= 63, u64 n <= 63, u128 n <= 63,
 *            big any n
 * Helpers:   is_prime_small
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A141862: prime values of k/(p(k-1)-p(k-2)), where p(m) is the m‑th prime.
   The function generates terms on demand and memoises them. */

#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include "../utils/is_prime_small.h"

/* Static state */
static idx_t       cur_k   = 3;                 /* next k to test               */
static uint64_t   *primes  = NULL;              /* primes generated by sieve    */
static size_t      primes_cnt = 0;             /* number of primes stored      */
static bool        primes_inited = false;      /* sieve initialised flag       */
static seq_t      *seq      = NULL;             /* memoised sequence values     */
static size_t      seq_len  = 0;                /* number of terms stored       */
static size_t      seq_cap  = 0;                /* capacity of seq array        */

#define SIEVE_LIMIT 5000000   /* enough primes for k up to ~10 000 */

/* Simple sieve that fills the primes array. */
static void init_primes(void)
{
    if (primes_inited) return;
    primes_inited = true;

    /* Allocate composite bitmap. */
    char *is_comp = (char *)malloc(SIEVE_LIMIT + 1);
    if (!is_comp) exit(1);
    memset(is_comp, 0, SIEVE_LIMIT + 1);

    for (idx_t i = 2; i * i <= SIEVE_LIMIT; ++i) {
        if (!is_comp[i]) {
            for (idx_t j = i * i; j <= SIEVE_LIMIT; j += i)
                is_comp[j] = 1;
        }
    }

    /* Count primes. */
    primes_cnt = 0;
    for (idx_t i = 2; i <= SIEVE_LIMIT; ++i)
        if (!is_comp[i]) primes_cnt++;

    /* Store primes. */
    primes = (uint64_t *)malloc(primes_cnt * sizeof(*primes));
    if (!primes) exit(1);
    size_t p = 0;
    for (idx_t i = 2; i <= SIEVE_LIMIT; ++i)
        if (!is_comp[i]) primes[p++] = i;

    free(is_comp);
}

/* Append a prime to the stored sequence, expanding storage if required. */
static void append_prime(seq_t val)
{
    if (seq_len == seq_cap) {
        seq_cap = seq_cap ? seq_cap * 2 : 128;
        seq = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));
        if (!seq) exit(1);
    }
    seq[seq_len++] = val;
}

/* Generate sequence terms until the nth term is available. */
static void ensure_n_terms(idx_t n)
{
    init_primes();
    while (seq_len < n) {
        /* gap = p(k-1) - p(k-2) */
        size_t idx1 = cur_k - 2;          /* index of p(k-1)   */
        size_t idx2 = cur_k - 3;          /* index of p(k-2)   */
        uint64_t gap = primes[idx1] - primes[idx2];

        if (gap != 0 && cur_k % gap == 0) {   /* integer quotient */
            seq_t q = ((seq_t)cur_k) / ((seq_t)gap);
            if (is_prime_small((uint64_t)q))
                append_prime(q);
        }
        cur_k++;
    }
}

/* Public sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;      /* out of bounds – not required for OEIS */
    ensure_n_terms(n);
    return seq[n - 1];
}
