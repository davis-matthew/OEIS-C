/* Sequence A330086
   Implements:  a(2n)   = 2^v2(n)   (the largest power of two dividing n)
               a(2n+1) = tau(letter(n))
   where   letter(n)  is generated by the uniform morphism
           0 → 01,  1 → 23,  2 → 04,  3 → 23,  4 → 24
   and the coding τ maps 0→2, 1→4, 2→1, 3→3, 4→1.
   The function works for any idx_t and seq_t defined by the build system.
   Complexity: O(log n) time and O(1) memory. */

#include <stdint.h>

/* Mapping arrays for the morphism and the coding τ. */
static const unsigned char expansion[5][2] = {
    {0, 1}, /* 0 → 01 */
    {2, 3}, /* 1 → 23 */
    {0, 4}, /* 2 → 04 */
    {2, 3}, /* 3 → 23 */
    {2, 4}  /* 4 → 24 */
};

static const unsigned char tau[5] = {2, 4, 1, 3, 1};

/* Recursive helper that returns the symbol (0‑4) at position n
   in the infinite word generated by the morphism. */
static unsigned char get_letter(idx_t n)
{
    if (n == 0)               /* base word starts with '0' */
        return 0;
    unsigned char parent = get_letter(n >> 1);  /* ancestor letter */
    unsigned char child  = n & 1;              /* 0 for even, 1 for odd */
    return expansion[parent][child];
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    if (n == 0)                /* out‑of‑range, not used for OEIS offset 1 */
        return 0;

    if ((n & 1) == 0) {        /* even index: a(2m) */
        idx_t m   = n >> 1;
        seq_t res = 1;
        while ((m & 1) == 0) { /* find v2(m) */
            m >>= 1;
            res <<= 1;        /* 2^v2(m) */
        }
        return res;
    }

    /* odd index: a(2m+1) = τ(letter(m)) */
    idx_t m          = n >> 1;
    unsigned char l  = get_letter(m);
    return tau[l];
}
