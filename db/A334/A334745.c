/*
 * A334745  Starting with a(1) = a(2) = 1, proceed in a square spiral,
 *          computing each term as the sum of diagonally adjacent prior terms.
 * https://oeis.org/A334745
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 427, u16 n <= 1347, u32 n <= 4725, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A334745: Square‑spiral sum of diagonally adjacent prior terms.
   The sequence is generated by starting with a(1)=a(2)=1 and then
   visiting grid cells in a square spiral (right, up, left, left,
   down, down, right, right, right, …).  For each visited cell
   its value is the sum of the values of the four diagonally adjacent
   cells that have already been visited.  Unvisited diagonal neighbors
   contribute zero. */

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

/* Size of the pre‑allocated grid.  For n ≤ 10000 the spiral radius
   never exceeds 71, therefore an offset of 200 is more than
   sufficient. */
#define GRID_RADIUS   200
#define OFFSET        GRID_RADIUS
#define GRID_SIZE    ((GRID_RADIUS*2)+1)
#define COORD_TO_IDX(x,y) ((size_t)((y+OFFSET)*GRID_SIZE + (x+OFFSET)))
#define CACHE_LIMIT  (200001)   /* enough for all requested n */

/* Static state shared by all calls to a() */
static seq_t grid[GRID_SIZE * GRID_SIZE];
static seq_t cache[CACHE_LIMIT];
static idx_t computed_max = 0;      /* number of terms computed so far */
static bool initialized = false;    /* lazy initialisation flag */

/* Spiral motion variables */
static int32_t cur_x = 0;           /* current x coordinate            */
static int32_t cur_y = 0;           /* current y coordinate            */
static int   dir_index = 0;         /* 0:right, 1:up, 2:left, 3:down  */
static int   side_len = 1;          /* length of current side segment  */
static int   step_in_dir = 0;       /* steps taken in current direction */

/* Sums the diagonal neighbours of (x,y) that have already been visited */
static inline seq_t value_at(int32_t x, int32_t y)
{
    static const int dx[4] = { -1, -1,  1,  1 };
    static const int dy[4] = { -1,  1, -1,  1 };
    size_t base = COORD_TO_IDX(x,y);
    seq_t sum = 0;
    for (int i = 0; i < 4; ++i) {
        int32_t nx = x + dx[i];
        int32_t ny = y + dy[i];
        sum += grid[COORD_TO_IDX(nx,ny)];
    }
    return sum;
}

/* Initialise the static state on the first invocation of a() */
static void init_state(void)
{
    /* Central cell (0,0) */
    grid[COORD_TO_IDX(0,0)] = 1ULL;
    cache[0] = 1ULL;
    /* The second cell (1,0) */
    grid[COORD_TO_IDX(1,0)] = 1ULL;
    cache[1] = 1ULL;

    computed_max = 2;        /* a(1) and a(2) have been computed */

    /* Position state after the second cell.  Next move will go up. */
    cur_x = 1; cur_y = 0;
    dir_index = 1;      /* up */
    side_len = 1;
    step_in_dir = 0;

    initialized = true;
}

/* Main API function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined; safety */

    if (!initialized) init_state();

    /* If the requested term is already cached, return it. */
    if (n <= computed_max) return cache[n-1];

    /* Generate new terms until the requested index is reached. */
    while (computed_max < n)
    {
        /* Move one step in the current direction. */
        switch (dir_index) {
            case 0: ++cur_x; break;   /* right */
            case 1: ++cur_y; break;   /* up    */
            case 2: --cur_x; break;   /* left  */
            case 3: --cur_y; break;   /* down  */
        }

        /* Compute value of the new cell. */
        seq_t val = value_at(cur_x, cur_y);

        /* Store the new term in cache and in the grid. */
        ++computed_max;
        cache[computed_max-1] = val;
        grid[COORD_TO_IDX(cur_x,cur_y)] = val;

        /* Advance stepping state. */
        ++step_in_dir;
        if (step_in_dir == side_len) {
            step_in_dir = 0;
            dir_index = (dir_index + 1) & 3;
            if (dir_index == 2 || dir_index == 0) {
                /* After completing left or right sides, increase step count. */
                side_len++;
            }
        }
    }

    return cache[n-1];
}
