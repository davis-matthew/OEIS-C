/*
 * A334081  If the terms of this sequence are divided into groups, the lengths
 *          of which are the terms of this sequence, the k-th term in a group
 *          is one greater than the k-th term in the previous group with at
 *          least k terms or 1 if no such group exists.
 * https://oeis.org/A334081
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, look, tabf
 * Formula:   not stated
 * Range:     u8 n <= 3784, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * A334081 – Group‑based construction.
 *
 * The sequence is generated by repeatedly forming groups.  Each group
 * has a length equal to the value of the first term of the group.
 * For the k‑th term of a group we take the (k‑th) term of the most
 * recent previous group that has at least k terms and add 1; if no
 * such previous group exists the term is 1.
 *
 * The implementation keeps a static memoised array `seq` containing
 * the sequence values and a dynamic array `last` where
 * last[k] holds the most recent k‑th term of a group with length ≥ k.
 * The algorithm runs O(n) time and stays well under the 2.0 s
 * limit for n up to about 10 000.
 */

#include <stddef.h>

static void ensure_seq_cap(seq_t **arr, size_t *cap, size_t need)
{
    if (*cap < need) {
        size_t new_cap = (*cap == 0) ? 16 : (*cap << 1);
        while (new_cap < need) new_cap <<= 1;
        *arr = (seq_t*)realloc(*arr, new_cap * sizeof(seq_t));
        *cap = new_cap;
    }
}

static void ensure_last_cap(seq_t **arr, size_t *cap, size_t need)
{
    /* we need indices up to `need`; indices start at 1, so allocate `need+1` */
    if (*cap < need + 1) {
        size_t new_cap = (*cap == 0) ? 16 : (*cap << 1);
        while (new_cap < need + 1) new_cap <<= 1;
        *arr = (seq_t*)realloc(*arr, new_cap * sizeof(seq_t));
        /* initialise the new slots; index 0 stays unused */
        for (size_t i = *cap; i < new_cap; ++i) (*arr)[i] = 0;
        *cap = new_cap;
    }
}

seq_t a(idx_t n)
{
    if (n == (idx_t)0) return 0;         /* offset is 1 – lower indices undefined */

    static seq_t *seq  = NULL;           /* 1‑based array of terms */
    static size_t seq_cap = 0;
    static size_t seq_len = 0;           /* highest index computed */

    static seq_t *last = NULL;           /* last[k] = most recent k‑th term of a group
                                            with length ≥ k (1‑based) */
    static size_t last_cap = 0;

    static idx_t group = 1;              /* number of the group being processed */
    static idx_t pos   = 1;              /* start index of that group in `seq` */

    /* initialise storage for first element and for `last` array */
    ensure_last_cap(&last, &last_cap, 1);
    ensure_seq_cap(&seq, &seq_cap, 2);   /* we need to hold at least index 1 */

    while (seq_len < (size_t)n) {
        /* ensure capacity for writing the first element of the group */
        ensure_seq_cap(&seq, &seq_cap, (size_t)pos + 1);

        /* first element of the group */
        seq_t first = last[1] ? last[1] + 1 : 1;
        seq[pos] = first;
        last[1] = first;

        /* length of the current group */
        size_t L;
        if (pos == group) {
            L = (size_t)first;                 /* group of length equal to its first term */
        } else {
            L = (size_t)seq[(size_t)group];    /* the term at index 'group' */
        }

        /* ensure capacity for the entire group */
        ensure_seq_cap(&seq, &seq_cap, (size_t)pos + L);
        ensure_last_cap(&last, &last_cap, L);

        /* generate remaining elements of the group (if any) */
        for (size_t k = 2; k <= L; ++k) {
            seq_t v = last[k] ? last[k] + 1 : 1;
            seq[pos + k - 1] = v;
            last[k] = v;
        }

        /* bookkeeping for next group */
        seq_len = (size_t)pos + L - 1;   /* last index written */
        pos += (idx_t)L;                 /* start of next group */
        ++group;                         /* next group number */
    }

    return seq[(size_t)n];
}
