/*
 * A334067  a(n) is taken to be the smallest positive integer greater than
 *          a(n-1) which is consistent with the condition "n is a term of the
 *          sequence if and only if a(n) is prime" where indices start from 0.
 * https://oeis.org/A334067
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 62, u16 n <= 62, u32 n <= 62, u64 n <= 62, u128 n <= 62,
 *            big any n
 * Helpers:   grow_seq, is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence satisfies: a(0)=1 and for every n ≥ 0,
   a(n) is prime iff n occurs as a term of the sequence.
   It is generated by the smallest possible increasing sequence
   that obeys this rule. */

/* Sequence generator for OEIS A334067 */
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/grow_seq.h"
#include "../utils/is_prime_big.h"

static seq_t *seq = NULL;      /* storage for the sequence values      */
static size_t seq_cap = 0;     /* allocated capacity of seq array      */
static size_t seq_len = 0;     /* number of values computed so far    */

/* Binary search: return true iff value v already appeared in seq[0..seq_len-1] */
static bool value_exists(seq_t v)
{
    size_t lo = 0, hi = seq_len;
    while (lo < hi) {
        size_t mid = (lo + hi) >> 1;
        if (seq[mid] == v) return true;
        if (seq[mid] < v) lo = mid + 1;
        else hi = mid;
    }
    return false;
}

seq_t a(idx_t n)
{
    /* Compute sequence up to n if needed */
    while (seq_len <= (size_t)n) {
        /* Determine if the current index must be a prime position */
        bool prime_required = value_exists((seq_t)n);

        /* Previous value (0 for n=0) */
        seq_t prev = 0;
        if (seq_len > 0) prev = seq[seq_len - 1];

        /* Find the next composite or prime > prev */
        seq_t cand = prev + 1;
        if (prime_required) {
            /* Need a prime */
            while (!is_prime_big(cand)) ++cand;
        } else {
            /* Need a composite (non‑prime) */
            while (is_prime_big(cand)) ++cand;
        }

        /* Grow array if required */
        if (seq_cap <= seq_len) {
            grow_seq(&seq, &seq_cap, seq_len + 1);
        }

        /* Store the new term */
        seq[seq_len++] = cand;
    }
    return seq[(size_t)n];
}
