/*
 * A215693  English flagpole sequence (see comments).
 * https://oeis.org/A215693
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, word
 * Formula:   not stated
 * Range:     u8 n <= 113, u16 n <= 113, u32 n <= 113, u64 n <= 113,
 *            u128 n <= 113, big any n
 * Helpers:   copy_and_mask, fp_append
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Compute the English flagpole sequence (OEIS A215693).
   The term a(n) is generated by repeatedly appending the
   English word of the smallest unused integer whose word
   contains the next character of the concatenated flagpole
   string.  This implementation builds the sequence lazily,
   memoising past terms and the growing flagpole string.  */
   
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>
#include <stdint.h>
#include "../utils/copy_and_mask.h"
#include "../utils/fp_append.h"

/* English word fragments (all lower‑case). */
static const char *const units[] = {
    "one","two","three","four","five","six","seven","eight","nine",
    "ten","eleven","twelve","thirteen","fourteen","fifteen",
    "sixteen","seventeen","eighteen","nineteen"
};
static const char *const tens[] = {
    "twenty","thirty","forty","fifty","sixty","seventy","eighty","ninety"
};
static const char *const scales[] = {
    "thousand","million","billion","trillion","quadrillion",
    "quintillion","sextillion","septillion","octillion",
    "nonillion","decillion"
};

/* Dynamic tables for used numbers and their letter masks. */
static uint8_t *used = NULL;          /* 0 = unused, 1 = used */
static uint32_t *mask_arr = NULL;     /* 26‑bit mask of letters in the number word */
static idx_t used_cap = 0;

/* Ensure tables can hold number n. */
static void ensure_used_cap(idx_t n) {
    if (n < used_cap) return;
    idx_t new_cap = used_cap ? used_cap << 1 : 1;
    while (n >= new_cap) new_cap <<= 1;
    uint8_t *nu = (uint8_t*)realloc(used, new_cap * sizeof *used);
    uint32_t *nm = (uint32_t*)realloc(mask_arr, new_cap * sizeof *mask_arr);
    if (!nu || !nm) abort();
    /* Zero‑initialize the new slots. */
    memset(nu + used_cap, 0, (new_cap - used_cap) * sizeof *nu);
    memset(nm + used_cap, 0, (new_cap - used_cap) * sizeof *nm);
    used = nu; mask_arr = nm; used_cap = new_cap;
}

/* Generate the English word of n (no spaces or hyphens) and its letter mask. */
static void number_to_word_core(idx_t n, char *buf, size_t *len, uint32_t *mask) {
    size_t pos = 0;
    uint32_t m = 0;
    if (n == 0) { /* not used, only for completeness */
        buf[pos++] = 'z';
        buf[pos] = '\0';
        *len = pos; *mask = m; return;
    }

    /* Break into groups of three digits. */
    idx_t tmp = n;
    idx_t groups[20];
    int gcnt = 0;
    while (tmp > 0) {
        groups[gcnt++] = tmp % 1000;
        tmp /= 1000;
    }

    /* Process from the highest group down. */
    for (int i = gcnt - 1; i >= 0; --i) {
        int g = (int)groups[i];
        if (g == 0) continue;

        if (g >= 100) {
            int u = g / 100;
            const char *s = units[u - 1];
            size_t sl = strlen(s);
            copy_and_mask(s, sl, buf, &pos, &m);

            const char *h = "hundred";
            sl = strlen(h);
            copy_and_mask(h, sl, buf, &pos, &m);

            int rem = g % 100;
            if (rem > 0) {
                if (rem < 20) {
                    const char *s2 = units[rem - 1];
                    sl = strlen(s2);
                    copy_and_mask(s2, sl, buf, &pos, &m);
                } else {
                    int t = rem / 10;
                    int u2 = rem % 10;
                    const char *ts = tens[t - 2];
                    sl = strlen(ts);
                    copy_and_mask(ts, sl, buf, &pos, &m);
                    if (u2 > 0) {
                        const char *s2 = units[u2 - 1];
                        sl = strlen(s2);
                        copy_and_mask(s2, sl, buf, &pos, &m);
                    }
                }
            }
        } else if (g < 20) {          /* 1 to 19 */
            const char *s = units[g - 1];
            size_t sl = strlen(s);
            copy_and_mask(s, sl, buf, &pos, &m);
        } else {                      /* 20 to 99 */
            int t = g / 10;
            int u = g % 10;
            const char *ts = tens[t - 2];
            size_t sl = strlen(ts);
            copy_and_mask(ts, sl, buf, &pos, &m);
            if (u > 0) {
                const char *s2 = units[u - 1];
                sl = strlen(s2);
                copy_and_mask(s2, sl, buf, &pos, &m);
            }
        }

        /* Attach scale name (thousand, million, …) if not the lowest group. */
        if (i > 0) {
            const char *scale = scales[i - 1];
            size_t sl = strlen(scale);
            copy_and_mask(scale, sl, buf, &pos, &m);
        }
    }

    buf[pos] = '\0';
    *len = pos;
    *mask = m;
}

/* Public function that computes the sequence term. */
seq_t a(idx_t n) {
    if (n == 0) return (seq_t)0;   /* undefined, safety */

    /* Static tables for the sequence and the flagpole string. */
    static seq_t *seq = NULL;       /* sequence values */
    static size_t seq_cap = 0, seq_len = 0;
    static char *fp = NULL; static size_t fp_cap = 0, fp_len = 0;

    /* Initialise only on first call. */
    if (!seq) {
        seq = NULL; seq_cap = 0; seq_len = 0;
        fp = NULL; fp_cap = 0; fp_len = 0;
        used = NULL; mask_arr = NULL; used_cap = 0;
    }

    /* Generate terms until we reach the requested index. */
    while (seq_len < (size_t)n) {
        seq_t val;
        if (seq_len == 0) {                  /* a(1) = 1 */
            val = (seq_t)1;
            ensure_used_cap(1);
            used[1] = 1;
            /* Compute mask for 1 if not already done. */
            if (mask_arr[1] == 0) {
                char tmp[8192];
                size_t tl;
                uint32_t tm;
                number_to_word_core(1, tmp, &tl, &tm);
                mask_arr[1] = tm;
            }
            /* Append "one" to the flagpole. */
            {
                char tmp[8192];
                size_t tl;
                uint32_t dummy;
                number_to_word_core(1, tmp, &tl, &dummy);
                fp_append(&fp, &fp_len, &fp_cap, tmp, tl);
            }
        } else {
            char tgt = fp[seq_len];          /* next steering letter */
            idx_t cand = 1;
            for (;;) {
                ensure_used_cap(cand);
                if (!used[cand]) {
                    if (mask_arr[cand] == 0) {
                        char tmp[8192];
                        size_t tl;
                        uint32_t tm;
                        number_to_word_core(cand, tmp, &tl, &tm);
                        mask_arr[cand] = tm;
                    }
                    if (mask_arr[cand] & (1u << (tgt - 'a'))) {
                        val = (seq_t)cand;
                        used[cand] = 1;
                        /* Append its word to the flagpole. */
                        char tmp[8192];
                        size_t tl;
                        uint32_t dummy;
                        number_to_word_core(cand, tmp, &tl, &dummy);
                        fp_append(&fp, &fp_len, &fp_cap, tmp, tl);
                        break;
                    }
                }
                ++cand;
            }
        }

        /* Store the computed term. */
        if (seq_len + 1 > seq_cap) {
            size_t new_cap = seq_cap ? seq_cap << 1 : 1;
            while (seq_len + 1 > new_cap) new_cap <<= 1;
            seq_t *newp = (seq_t*)realloc(seq, new_cap * sizeof *newp);
            if (!newp) abort();
            seq = newp; seq_cap = new_cap;
        }
        seq[seq_len] = val;
        ++seq_len;
    }

    return seq[n - 1];   /* a(n) is stored at index n‑1 */
}
