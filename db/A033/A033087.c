/*
 * A033087  Numbers in which all pairs of consecutive base-9 digits differ by
 *          2.
 * https://oeis.org/A033087
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 13, u16 n <= 55, u32 n <= 55, u64 n <= 55, u128 n <= 55,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A033087: numbers whose base‑9 digits differ by exactly 2 in each adjacent pair.
   The sequence is generated by a breadth‑first traversal of a rooted tree
   whose nodes are the valid numbers.  Each node x has at most two children:
   the numbers obtained by appending a digit d' such that |d'-d|=2,
   where d = x modulo 9 is the last base‑9 digit of x.
   The traversal is performed with a min‑heap so that the terms appear
   in increasing order.  The implementation keeps static arrays large
   enough for the required 10 000 terms.  The code is fully compliant
   with C11 and C++17. */

#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* maximum number of terms we need to generate (safe for n ≤ 10000) */
#define MAX_TERMS 40000
#define MAX_HEAP  80000

/* static storage used between calls */
static seq_t seq_cache[MAX_TERMS];
static size_t cache_len = 0;
static size_t cache_cap = MAX_TERMS;

static seq_t heap[MAX_HEAP];
static size_t heap_sz = 0;
static bool heap_inited = false;

/* swap two heap elements */
static inline void heap_swap(size_t i, size_t j)
{
    seq_t tmp = heap[i];
    heap[i] = heap[j];
    heap[j] = tmp;
}

/* push value onto min‑heap */
static void heap_push_seq(seq_t val)
{
    size_t i = heap_sz++;
    heap[i] = val;
    while (i > 0) {
        size_t parent = (i - 1) >> 1;
        if (heap[parent] <= heap[i]) break;
        heap_swap(parent, i);
        i = parent;
    }
}

/* pop minimum from min‑heap */
static seq_t heap_pop_min_seq(void)
{
    seq_t min = heap[0];
    heap_sz--;
    if (heap_sz > 0) {
        heap[0] = heap[heap_sz];
        size_t i = 0;
        while (1) {
            size_t left  = i * 2 + 1;
            if (left >= heap_sz) break;
            size_t right = left + 1;
            size_t child = (right < heap_sz && heap[right] < heap[left]) ? right : left;
            if (heap[i] <= heap[child]) break;
            heap_swap(i, child);
            i = child;
        }
    }
    return min;
}

/* main function requested by the assignment */
seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* offset handling – not used */

    /* initialise heap once with one‑digit numbers 1…8 */
    if (!heap_inited) {
        heap_inited = true;
        for (seq_t v = 1; v <= 8; ++v)
            heap_push_seq(v);
    }

    /* generate terms until we have at least n of them */
    while (cache_len < n) {
        seq_t cur = heap_pop_min_seq();

        /* store the term */
        seq_cache[cache_len++] = cur;

        /* generate successors by appending a new base‑9 digit */
        unsigned digit = (unsigned)(cur % 9);
        if (digit >= 2)
            heap_push_seq(cur * 9 + (seq_t)(digit - 2));
        if (digit <= 6)
            heap_push_seq(cur * 9 + (seq_t)(digit + 2));
    }

    return seq_cache[n - 1];
}
