/*
 * A033170  Positive numbers having the same set of digits in base 6 and base
 *          7.
 * https://oeis.org/A033170
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 830, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A033170 – numbers whose base‑6 and base‑7 representations use exactly the same set of digits.
   Terms are generated by brute‑force search of successive integers, computing digit sets in base 6 and
   base 7 and storing each integer that satisfies the condition.  The cache allows random‑order
   access to the sequence up to any previously computed index. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <limits.h>

/* Find the maximum value that can be represented by seq_t.
   Values larger than this are ignored, because they cannot be stored in the cache. */
static bool _max_seq_val_init = false;
static uint64_t _max_seq_val = 0;

static void
_init_max_seq_val(void)
{
    if (_max_seq_val_init) return;
    switch (sizeof(seq_t)) {
        case 1:  _max_seq_val = UCHAR_MAX;   break;
        case 2:  _max_seq_val = USHRT_MAX;   break;
        case 4:  _max_seq_val = UINT_MAX;    break;
        case 8:  _max_seq_val = UINT64_MAX; break;
        default: _max_seq_val = UINT64_MAX; /* arbitrary‑precision or 128‑bit – no practical limit for search */
    }
    _max_seq_val_init = true;
}

/* Cache used to store already‑found terms. */
static seq_t * _cache   = NULL;   /* pointer to the array of terms */
static size_t  _cache_cap = 0;    /* allocated capacity of the array */
static size_t  _cache_sz  = 0;    /* number of terms currently stored */

/* The last integer that was examined during generation. */
static uint64_t _last_checked = 0;

static void
_grow_cache(size_t needed)
{
    if (_cache_cap >= needed) return;
    size_t new_cap = _cache_cap ? (_cache_cap * 2) : 16;
    while (new_cap < needed) new_cap *= 2;
    seq_t *tmp = (seq_t *)realloc(_cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();           /* out of memory */
    _cache = tmp;
    _cache_cap = new_cap;
}

/* Return the nth term of the sequence, 1‑based indexing. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined below offset; harmless */

    _init_max_seq_val();

    /* Generate terms until we have at least n of them. */
    while (_cache_sz < (size_t)n) {
        _last_checked++;                      /* candidate integer */

        /* Compute digit set in base 6. */
        uint8_t mask6 = 0;
        uint64_t temp = _last_checked;
        if (temp == 0) { mask6 = 1; }           /* 0 has digit 0 */
        while (temp > 0) {
            uint8_t d = (uint8_t)(temp % 6);
            mask6 |= (1U << d);
            temp /= 6;
        }

        /* Compute digit set in base 7, rejecting any candidate that uses digit 6. */
        uint8_t mask7 = 0;
        bool bad = false;
        temp = _last_checked;
        if (temp == 0) { mask7 = 1; }
        while (temp > 0) {
            uint8_t d = (uint8_t)(temp % 7);
            if (d == 6) { bad = true; break; }
            mask7 |= (1U << d);
            temp /= 7;
        }

        if (!bad && mask6 == mask7) {
            /* Candidate fits in seq_t?  Store only if it can be represented. */
            if (_last_checked <= _max_seq_val) {
                _grow_cache(_cache_sz + 1);
                _cache[_cache_sz++] = (seq_t)_last_checked;
            }
            /* If it doesn't fit, we simply skip it; it cannot be returned
               because seq_t cannot hold its value. */
        }
    }

    /* Return the requested term.  Indexing is 1‑based, array is 0‑based. */
    return _cache[n - 1];
}
