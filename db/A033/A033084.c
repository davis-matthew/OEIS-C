/* Algorithm: a(n) is the n‑th positive integer whose base‑6 digits
   satisfy |d_i−d_{i+1}| = 2 for all consecutive digit pairs.
   The sequence is generated by breadth‑first expansion of all base‑6
   numbers that obey this property, storing the resulting decimal
   values in increasing order. */

#include <stdlib.h>

seq_t a(idx_t n)
{
    /* static cache of the sequence values */
    static seq_t *cache = NULL;          /* array of computed terms   */
    static size_t cache_len = 0;          /* number of terms stored   */
    static size_t cache_cap = 0;          /* allocated capacity       */
    static idx_t q_start = 0;             /* index of next number to
                                             expand in BFS queue       */

    /* initialise on first call */
    if (cache_len == 0) {
        /* initial capacity – grows as needed */
        cache_cap = 16;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        /* first five single‑digit numbers (1 … 5) */
        for (int d = 1; d <= 5; ++d) {
            cache[cache_len++] = (seq_t)d;
        }
        q_start = 0;
    }

    /* extend the cache until it contains at least n terms */
    while (cache_len < n) {
        seq_t cur = cache[(size_t)q_start++];   /* pop from queue */
        int last = (int)(cur % (seq_t)6);       /* last base‑6 digit */

        /* helper: ensure there's room for at least one more element */
        if (cache_len == cache_cap) {
            cache_cap <<= 1;                     /* double the size    */
            cache = (seq_t *)realloc(cache,
                                      cache_cap * sizeof(seq_t));
        }

        /* generate children according to the allowed next digits */
        switch (last) {
        case 0: { /* only digit 2 */
            seq_t child = cur * (seq_t)6 + (seq_t)2;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child;
            break;
        }
        case 1: { /* only digit 3 */
            seq_t child = cur * (seq_t)6 + (seq_t)3;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child;
            break;
        }
        case 2: { /* digits 0 and 4 – in ascending order */
            seq_t base = cur * (seq_t)6;
            seq_t child0 = base + (seq_t)0;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child0;
            seq_t child4 = base + (seq_t)4;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child4;
            break;
        }
        case 3: { /* digits 1 and 5 – in ascending order */
            seq_t base = cur * (seq_t)6;
            seq_t child1 = base + (seq_t)1;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child1;
            seq_t child5 = base + (seq_t)5;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child5;
            break;
        }
        case 4: { /* only digit 2 */
            seq_t child = cur * (seq_t)6 + (seq_t)2;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child;
            break;
        }
        case 5: { /* only digit 3 */
            seq_t child = cur * (seq_t)6 + (seq_t)3;
            if (cache_len == cache_cap) {
                cache_cap <<= 1;
                cache = (seq_t *)realloc(cache,
                                          cache_cap * sizeof(seq_t));
            }
            cache[cache_len++] = child;
            break;
        }
        }
    }

    return cache[(size_t)(n - 1)];
}
