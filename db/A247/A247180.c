/*
 * A247180  Numbers with nonrepeating smallest prime factor.
 * https://oeis.org/A247180
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 171, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Search: a(n) is the nth integer whose smallest prime factor
   occurs only once (i.e. the integer is not divisible by the square
   of its smallest prime factor). */
#include <stdlib.h>
#include <stdbool.h>

/* The sequence a(n) is generated by testing consecutive integers
   and storing those for which the smallest prime factor occurs
   exactly once.  A simple trial division using a growing list of
   primes is used. The function is memoised with static storage so
   that random access to any n works efficiently. */
seq_t a(idx_t n)
{
    /* static cache of already generated terms */
    static seq_t *cache    = NULL;
    static size_t cache_len   = 0;   /* number of cached terms      */
    static size_t cache_cap   = 0;   /* allocated capacity         */

    /* static prime list for trial division */
    static uint64_t *prime_list = NULL;
    static size_t prime_len  = 0;   /* number of stored primes    */
    static size_t prime_cap  = 0;   /* allocated capacity         */

    /* next integer to test (starts at 1, first candidate will be 2) */
    static idx_t next_start = 1;

    /* initialise prime list with 2 if it has not yet been set up */
    if (prime_len == 0) {
        prime_cap = 4;
        prime_list = (uint64_t *)malloc(prime_cap * sizeof(uint64_t));
        if (!prime_list) abort();
        prime_list[0] = 2;
        prime_len = 1;
    }

    /* grow the cache until it contains at least n terms */
    while (cache_len < n) {
        ++next_start;
        uint64_t cand = (uint64_t)next_start;   /* candidate value */

        bool include = false;
        bool found   = false;

        /* try to find the smallest prime factor of cand */
        for (size_t i = 0; i < prime_len; ++i) {
            uint64_t p     = prime_list[i];
            uint64_t p_sq  = p * p;
            if (p_sq > cand) break;                 /* p > sqrt(cand) */
            if (cand % p == 0) {                     /* p is smallest factor */
                found   = true;
                include = (cand % p_sq != 0);        /* include only if exponent == 1 */
                break;
            }
        }

        /* if no factor was found, cand itself is prime */
        if (!found) {
            include = true;
            /* add this new prime to the list, grow if necessary */
            if (prime_len == prime_cap) {
                prime_cap = prime_cap ? prime_cap * 2 : 8;
                uint64_t *tmp = (uint64_t *)realloc(prime_list,
                                                    prime_cap * sizeof(uint64_t));
                if (!tmp) abort();
                prime_list = tmp;
            }
            prime_list[prime_len++] = cand;
        }

        /* store the candidate if it satisfies the property */
        if (include) {
            if (cache_len == cache_cap) {
                cache_cap = cache_cap ? cache_cap * 2 : 8;
                seq_t *tmp = (seq_t *)realloc(cache,
                                              cache_cap * sizeof(seq_t));
                if (!tmp) abort();
                cache = tmp;
            }
            cache[cache_len++] = (seq_t)cand;
        }
    }

    return cache[n - 1];
}
