/*
 * A247356  Numbers k such that d(r,k) = 1 and d(s,k) = 1, where d(x,k) = k-th
 *          binary digit of x, r = {sqrt(2)}, s = {sqrt(3)}, and { } =
 *          fractional part.
 * https://oeis.org/A247356
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy, base
 * Formula:   not stated
 * Range:     u8 n <= 63, u16 n <= 1116, u32 n <= 1116, u64 n <= 1116,
 *            u128 n <= 1116, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A247356:
   a(n) is the n-th positive integer k such that the k-th binary digit
   of the fractional part of √2 and of the fractional part of √3 are both 1.
   The digits are generated by a recurrence that keeps the integer part
   and the remainder of 2^{2k}·A, where A is 2 or 3.  The first digit
   is obtained from the comparison R > P, then P and R are updated.
*/

#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

typedef struct { size_t size, cap; uint32_t *v; } BigInt;

/* initialise a BigInt with an unsigned 64‑bit value */
static void bi_init(BigInt *a, uint64_t v)
{
    a->size = a->cap = 0;
    a->v = NULL;
    if (v == 0) {
        a->size = 1;
        a->cap  = 1;
        a->v    = (uint32_t*)malloc(sizeof(uint32_t));
        a->v[0] = 0;
        return;
    }
    while (v) {
        uint32_t lo = (uint32_t)(v & 0xFFFFFFFFU);
        if (a->size == a->cap) {
            a->cap = a->cap ? a->cap * 2 : 4;
            a->v   = (uint32_t*)realloc(a->v, a->cap * sizeof(uint32_t));
        }
        a->v[a->size++] = lo;
        v >>= 32;
    }
    if (a->size == 0) {
        a->size = 1;
        a->cap  = 1;
        a->v    = (uint32_t*)malloc(sizeof(uint32_t));
        a->v[0] = 0;
    }
}

/* copy one BigInt into another (dest gets same size as src) */
static void bi_copy(BigInt *dest, const BigInt *src)
{
    if (dest->cap < src->size)
    {
        dest->cap = src->size;
        dest->v   = (uint32_t*)realloc(dest->v, dest->cap * sizeof(uint32_t));
    }
    memcpy(dest->v, src->v, src->size * sizeof(uint32_t));
    dest->size = src->size;
}

/* compare a > b */
static int bi_gt(const BigInt *a, const BigInt *b)
{
    if (a->size != b->size) return a->size > b->size;
    for (size_t i = a->size; i > 0; --i)
        if (a->v[i-1] != b->v[i-1]) return a->v[i-1] > b->v[i-1];
    return 0;               /* equal */
}

/* left shift by one bit */
static void bi_shl1(BigInt *a)
{
    uint64_t carry = 0;
    for (size_t i = 0; i < a->size; ++i) {
        uint64_t cur = ((uint64_t)a->v[i] << 1) | carry;
        a->v[i] = (uint32_t)(cur & 0xFFFFFFFFU);
        carry   = cur >> 32;
    }
    if (carry) {
        if (a->size == a->cap) {
            a->cap = a->cap ? a->cap * 2 : 4;
            a->v   = (uint32_t*)realloc(a->v, a->cap * sizeof(uint32_t));
        }
        a->v[a->size++] = (uint32_t)carry;
    }
}

/* left shift by two bits (<<2) */
static void bi_shl2(BigInt *a) { bi_shl1(a); bi_shl1(a); }

/* add one to a */
static void bi_add1(BigInt *a)
{
    uint64_t carry = 1;
    for (size_t i = 0; i < a->size; ++i) {
        uint64_t cur = (uint64_t)a->v[i] + carry;
        a->v[i] = (uint32_t)(cur & 0xFFFFFFFFU);
        carry   = cur >> 32;
        if (!carry) break;
    }
    if (carry) {
        if (a->size == a->cap) {
            a->cap = a->cap ? a->cap * 2 : 4;
            a->v   = (uint32_t*)realloc(a->v, a->cap * sizeof(uint32_t));
        }
        a->v[a->size++] = (uint32_t)carry;
    }
}

/* subtract b from a,  a >= b is assumed */
static void bi_sub(BigInt *a, const BigInt *b)
{
    int64_t borrow = 0;
    for (size_t i = 0; i < a->size; ++i) {
        int64_t av = a->v[i];
        int64_t bv = (i < b->size) ? b->v[i] : 0;
        int64_t diff = av - bv - borrow;
        if (diff < 0) {
            diff += (int64_t)1 << 32;
            borrow = 1;
        } else
            borrow = 0;
        a->v[i] = (uint32_t)diff;
    }
    while (a->size > 1 && a->v[a->size-1] == 0) --a->size;
}

/* subtract one from a (a > 0) */
static void bi_sub1(BigInt *a)
{
    size_t i = 0;
    while (i < a->size) {
        if (a->v[i] > 0) { a->v[i]--; break; }
        a->v[i] = 0xFFFFFFFFU;
        ++i;
    }
    while (a->size > 1 && a->v[a->size-1] == 0) --a->size;
}

/* ------------------------------------------------------------ */
/*  Sequence generation  */
static seq_t *cache = NULL;        /* store found indices */
static idx_t  cache_cap = 0;       /* capacity of cache */
static idx_t  cache_size = 0;      /* number of stored terms */

static BigInt   P_r, R_r;          /* state for sqrt(2) */
static BigInt   P_s, R_s;          /* state for sqrt(3) */
static BigInt   tmp, tmp2;        /* temporary copies */
static idx_t    current_k = 0;     /* current digit index (0‑based) */
static int      initialized = 0;

static void init_state(void)
{
    bi_init(&P_r, 1);      /* floor(sqrt(2)) = 1 */
    bi_init(&R_r, 1);      /* 2 - 1^2 = 1 */
    bi_init(&P_s, 1);      /* floor(sqrt(3)) = 1 */
    bi_init(&R_s, 2);      /* 3 - 1^2 = 2 */
    bi_init(&tmp, 0);
    bi_init(&tmp2, 0);
    cache = NULL;
    cache_cap = 0;
    cache_size = 0;
    current_k = 0;
    initialized = 1;
}

seq_t a(idx_t n)
{
    if (!initialized) init_state();

    while (cache_size < n) {
        /* ----  compute bit for sqrt(2)  ---- */
        int bit_r = bi_gt(&R_r, &P_r);

        /* store old P_r before modification */
        bi_copy(&tmp, &P_r);

        /* update P_r and R_r */
        bi_shl1(&P_r);
        if (bit_r) bi_add1(&P_r);
        if (bit_r) {
            bi_shl2(&R_r);      /* R_r *= 4 */
            bi_shl2(&tmp);      /* tmp = old P_r << 2 */
            bi_sub(&R_r, &tmp); /* R_r -= 4*oldP */
            bi_sub1(&R_r);      /* R_r -= 1 */
        } else {
            bi_shl2(&R_r);      /* R_r *= 4 */
        }

        /* ----  compute bit for sqrt(3)  ---- */
        int bit_s = bi_gt(&R_s, &P_s);

        bi_copy(&tmp2, &P_s);
        bi_shl1(&P_s);
        if (bit_s) bi_add1(&P_s);
        if (bit_s) {
            bi_shl2(&R_s);
            bi_shl2(&tmp2);
            bi_sub(&R_s, &tmp2);
            bi_sub1(&R_s);
        } else {
            bi_shl2(&R_s);
        }

        /* if both digits are 1, record the position */
        if (bit_r && bit_s) {
            if (cache_cap <= cache_size) {
                size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                cache = (seq_t*)realloc(cache, new_cap * sizeof(seq_t));
                cache_cap = new_cap;
            }
            cache[cache_size++] = (seq_t)(current_k + 1);
        }

        ++current_k;   /* move to next digit position */
    }

    return cache[n - 1];
}
