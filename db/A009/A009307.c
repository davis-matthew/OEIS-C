/*
 * A009307  If a, b in sequence, so is ab+6.
 * https://oeis.org/A009307
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 292, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A009307 (OEIS):  Start with 2; whenever a and b are in the set,
   also a*b+6 is in the set.  The sequence is the sorted list of the
   numbers generated by this rule.  The implementation keeps a priority
   queue of candidates a[i]*a[j]+6 for each i, advancing j as numbers
   are extracted; duplicated values are ignored.  All state is memoised
   so repeated calls are O(1). */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* binary search: true if value v exists in sorted array seq[0..len-1] */
static bool seq_exists(const seq_t *seq, size_t len, seq_t v)
{
    size_t lo = 0, hi = len;
    while (lo < hi) {
        size_t mid = (lo + hi) >> 1;
        if (seq[mid] < v)
            lo = mid + 1;
        else if (seq[mid] > v)
            hi = mid;
        else
            return true;
    }
    return false;
}

typedef struct {
    seq_t val;   /* candidate value a[i]*a[j] + 6 */
    size_t idx;  /* i whose pointer will now advance */
} Node;

/* push into min‑heap */
static void heap_push(Node **heap, size_t *hsize, size_t *hcap, Node n)
{
    if (*hsize == *hcap) {
        *hcap = (*hcap == 0) ? 4 : (*hcap << 1);
        *heap = (Node *)realloc(*heap, *hcap * sizeof(Node));
    }
    size_t i = (*hsize)++;
    while (i > 0) {
        size_t p = (i - 1) >> 1;
        if ((*heap)[p].val <= n.val)
            break;
        (*heap)[i] = (*heap)[p];
        i = p;
    }
    (*heap)[i] = n;
}

/* pop smallest element from heap */
static Node heap_pop(Node *heap, size_t *hsize)
{
    Node root = heap[0];
    Node last = heap[--(*hsize)];
    size_t i = 0;
    while (1) {
        size_t l = (i << 1) + 1;
        size_t r = l + 1;
        if (l >= *hsize)
            break;
        size_t child = (r < *hsize && heap[r].val < heap[l].val) ? r : l;
        if (last.val <= heap[child].val)
            break;
        heap[i] = heap[child];
        i = child;
    }
    heap[i] = last;
    return root;
}

/* externally visible function as required */
seq_t a(idx_t n)
{
    /* static state shared between calls */
    static seq_t *seq = NULL;
    static size_t *ptr = NULL;          /* j pointers for each a[i] */
    static Node *heap = NULL;
    static size_t seq_len = 0, seq_cap = 0;
    static size_t ptr_len = 0, ptr_cap = 0;
    static size_t hsize = 0, hcap = 0;

    /* initialise */
    if (seq == NULL) {
        seq_cap = 16;
        seq = (seq_t *)malloc(seq_cap * sizeof(seq_t));
        seq[0] = (seq_t)2;
        seq_len = 1;

        ptr_cap = 16;
        ptr = (size_t *)malloc(ptr_cap * sizeof(size_t));
        ptr[0] = 0;   /* start with j = 0 */

        hcap = 4;
        heap = (Node *)malloc(hcap * sizeof(Node));
        heap_push(&heap, &hsize, &hcap, (Node){seq[0] * seq[0] + (seq_t)6, 0});
    }

    size_t target = (size_t)n;   /* n >= 1 */

    while (seq_len < target) {
        /* get smallest candidate */
        Node cur = heap_pop(heap, &hsize);
        seq_t val = cur.val;
        size_t i = cur.idx;

        /* advance the generator for this i */
        ptr[i]++;
        if (ptr[i] < seq_len) {
            seq_t cand = seq[i] * seq[ptr[i]] + (seq_t)6;
            heap_push(&heap, &hsize, &hcap, (Node){cand, i});
        }

        /* if new, add to sequence */
        if (!seq_exists(seq, seq_len, val)) {
            if (seq_len == seq_cap) {
                seq_cap <<= 1;
                seq = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));
            }
            seq[seq_len++] = val;

            if (ptr_len == ptr_cap) {
                ptr_cap <<= 1;
                ptr = (size_t *)realloc(ptr, ptr_cap * sizeof(size_t));
            }
            ptr[ptr_len++] = 0;   /* j = 0 for the new element */

            /* push first candidate for the new element */
            seq_t cand = seq[seq_len - 1] * seq[0] + (seq_t)6;
            heap_push(&heap, &hsize, &hcap, (Node){cand, seq_len - 1});
        }
    }

    return seq[n - 1];
}
