/*
 * A259394  Primes of the form (sum of the digits of k to consecutive powers
 *          starting at 1) + k, ordered by k (duplicates allowed).
 * https://oeis.org/A259394
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 28, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Validated: partial, pass, 60 terms through n = 60 (2026-11-03)
 * Helpers:   is_prime_u128, is_prime_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence a(n) is generated by iterating k = 1,2,3,… and computing
   S(k) = Σ_{j=0}^{d-1} digit_j^(j+1) where digit_0 is the most
   significant decimal digit of k.  The value v(k) = S(k) + k is a
   term iff v(k) is prime.  The n‑th term a(n) is the n‑th such value. */
#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <limits.h>
#include "../utils/is_prime_u128.h"
#include "../utils/is_prime_u64.h"

/* -----------------  Generic primality test ------------------------ */
static bool isPrimeGeneric(seq_t n)
{
    /* all seq_t are unsigned; use the smallest type that fits */
    if ((seq_t)(ULLONG_MAX) >= n) {
        return is_prime_u64((uint64_t)n);
    }
#if defined(__SIZEOF_INT128__)
    return is_prime_u128((__uint128_t)n);
#else
    /* fallback: if seq_t > 64‑bit but no 128‑bit support,
       order the test as simple trial division up to sqrt */
    seq_t limit = 0;
    for (seq_t i = 2; i*i <= n; ++i) {
        if (n % i == 0) return false;
    }
    return true;
#endif
}

seq_t a(idx_t n) {
    idx_t count = 0;
    for (idx_t k = 1;; ++k) {
        /* extract decimal digits of k (least–significant first) */
        uint8_t digits[20];
        size_t len = 0;
        idx_t tmp = k;
        if (tmp == 0) {
            digits[0] = 0;
            len = 1;
        } else {
            while (tmp > 0) {
                digits[len++] = tmp % 10;
                tmp /= 10;
            }
        }

        /* compute sum of digits to increasing powers, starting at 1
           from the most significant digit */
        seq_t sum = 0;
        seq_t exp = 1;
        for (size_t i = 0; i < len; ++i) {
            uint8_t d = digits[len - 1 - i];      /* most significant first */
            seq_t t = 1;
            for (seq_t e = 0; e < exp; ++e) {
                t *= (seq_t)d;
            }
            sum += t;
            ++exp;
        }

        seq_t val = sum + (seq_t)k;
        if (isPrimeGeneric(val)) {
            ++count;
            if (count == n) {
                return val;
            }
        }
    }
}
