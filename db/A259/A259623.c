/*
 * A259623  Strictly increasing list of F and F + 1, where F = A000045, the
 *          Fibonacci numbers.
 * https://oeis.org/A259623
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   a(n) is the nth element of the strictly increasing list of
 *            Fibonacci numbers and Fibonacci+1. Each Fibonacci number F_k and
 *            each F_k+1 are considered in order, duplicates are removed
 * Range:     u8 n <= 22, u16 n <= 44, u32 n <= 90, u64 n <= 182,
 *            u128 n <= 368, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n) for n ≥ 1.
   The value is generated by iterating through Fibonacci numbers until the
   sequence contains at least n terms.  No memoization or
   table lookup is required; the algorithm is O(n) in the index.  */

seq_t a(idx_t n)
{
    if (n == 0)                  /* out of range: not used by callers */
        return (seq_t)0;

    seq_t fib0 = (seq_t)1,        /* F_1 */
          fib1 = (seq_t)1;        /* F_2 */
    seq_t prev = (seq_t)0;        /* last value stored in the list */
    idx_t  count = 0;             /* number of elements emitted so far */

    while (1) {
        /* Emit F_k (fib0).  */
        if (fib0 > prev) {
            prev = fib0;
            if (++count == n)
                return prev;
        }

        /* Emit F_k + 1.  */
        seq_t plus = fib0 + (seq_t)1;
        if (plus > prev) {
            prev = plus;
            if (++count == n)
                return prev;
        }

        /* Prepare next Fibonacci pair, checking for overflow.  */
        seq_t next = fib0 + fib1;

        /* Detect unsigned overflow: in that case fib0 + fib1 wraps around to a
           value smaller than fib0.  For arbitrary‐precision seq_t the test
           always fails, which is correct because no overflow can occur.  */
        if ((sizeof(seq_t) <= sizeof(unsigned long long)) && (next < fib0)) {
            /* Final pair of values that belong after fib0 but before the
               overflow.  We must still consider fib1 (= F_{k+1}) and its
               successor.  */
            if (fib1 > prev) {
                prev = fib1;
                if (++count == n)
                    return prev;
            }
            seq_t plus1 = fib1 + (seq_t)1;
            if (plus1 > prev) {
                prev = plus1;
                if (++count == n)
                    return prev;
            }
            break;                      /* sequence exhausted for fixed width type */
        }

        /* Advance to the next Fibonacci index.  */
        fib0 = fib1;
        fib1 = next;
    }

    /* For finite‑width builds the function can only produce values up
       to the point of overflow (e.g. 12200160415121876739 for uint64_t).
       If a request beyond that is made, return the last computable
       value.  For arbitrary‐precision builds this code never reaches
       this line.  */
    return prev;
}
