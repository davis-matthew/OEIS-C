/* A081466: denominator of the nth term of the sequence generated by
   f(a/b) = (a^2 + b^2)/(a^2 - b^2) starting from 2/1.
   The first few values are: a(1)=1, a(2)=3, a(3)=8, a(4)=225, ... */

seq_t a(idx_t n)
{
    /* the sequence is defined only for n >= 1; return 0 for n == 0 */
    if (n == 0)
        return (seq_t)0;

    seq_t p = (seq_t)2;   /* numerator */
    seq_t q = (seq_t)1;   /* denominator */

    /* iterate the mapping n-1 times to reach the nth fraction */
    for (idx_t i = 1; i < n; ++i)
    {
        seq_t p2 = p * p;
        seq_t q2 = q * q;

        seq_t new_p = p2 + q2;
        seq_t new_q = p2 - q2;

        /* reduce the fraction by 2 when both p and q are odd */
        if ((p & (seq_t)1) && (q & (seq_t)1))
        {
            new_p = new_p / (seq_t)2;
            new_q = new_q / (seq_t)2;
        }

        p = new_p;
        q = new_q;
    }

    return q;   /* denominator of the nth term */
}
