/*  OEIS A075122.
    Formula: a(n) = least positive integer > a(n-1) not equal to a(i)+2*a(j)
              for any 1 ≤ i < j < n.  (a(1)=1) */

/*  The sequence is generated by storing all previously computed terms
    in a dynamic table.  Whenever a new term a(k) is added we mark all
    sums a(i)+2*a(k) for i<k in a dynamic “forbidden” bit array.
    The next term is found by scanning forward from a(k-1)+1 until a
    value not present in the forbidden table is reached.

    The procedure is O(N^2) total because every pair (i,k) with i<k
    is considered once.  For N≈10 000 this is well below the time limit.

    All tables are grown using realloc, so the code is valid in both
    C11 and C++17.  No C++-specific features are used.  The code
    works for any seq_t type that fits in a 64‑bit machine word for
    the test cases. */

#include <stdlib.h>
#include <stdint.h>

static seq_t *seq_arr = NULL;            /* sequence values (0‑based)       */
static size_t seq_len = 0;               /* number of terms stored          */
static size_t seq_cap = 0;               /* allocated capacity               */

static unsigned char *forb_arr = NULL;   /* forbidden values bit array      */
static size_t forb_cap = 0;              /* allocated byte capacity         */

static idx_t generated = 0;              /* number of terms completely built */

/* Ensure that for values up to needed (inclusive) we have a space
   in forb_arr.  The array holds one byte per value.            */
static void ensure_forbidden(size_t needed)
{
    if (needed < forb_cap) return;

    size_t new_cap = forb_cap ? forb_cap : 1;
    while (new_cap <= needed) new_cap <<= 1;
    unsigned char *tmp = (unsigned char *)realloc(forb_arr, new_cap);
    if (!tmp) abort();                  /* memory exhausted          */
    forg:;  /* placeholder to avoid unused label error */
    /* initialise newly added bytes to zero */
    if (needed >= new_cap) needed = new_cap - 1;
    for (size_t i = forb_cap; i <= needed; ++i) tmp[i] = 0;
    forb_arr = tmp;
    forb_cap = new_cap;
}

/* Append a new term to seq_arr.  Grow the array if needed.       */
static void append_seq(seq_t val)
{
    if (seq_len == seq_cap) {
        size_t new_cap = seq_cap ? seq_cap : 1;
        new_cap <<= 1;
        seq_t *tmp = (seq_t *)realloc(seq_arr, new_cap * sizeof(seq_t));
        if (!tmp) abort();              /* memory exhausted          */
        seq_arr = tmp;
        seq_cap = new_cap;
    }
    seq_arr[seq_len++] = val;
}

/* Main sequence function.  Builds terms up to n if necessary.   */
seq_t a(idx_t n)
{
    if (n == 0) return 0;               /* undefined for n=0; return 0 */

    /* Build up to requested n.                                */
    while (generated < n) {
        idx_t new_idx = generated + 1;   /* 1‑based index of new term   */
        seq_t next_val;

        if (new_idx == 1) {
            next_val = (seq_t)1;
        } else {
            /* Find smallest integer > previous term that is not forbidden. */
            seq_t cand = seq_arr[generated - 1] + (seq_t)1;
            for (;;) {
                /* Ensure forbidden table can index cand.            */
                if ((size_t)cand >= forb_cap) ensure_forbidden((size_t)cand);
                if (!forb_arr[(size_t)cand]) break;  /* acceptable value */
                ++cand;
            }
            next_val = cand;
        }

        append_seq(next_val);            /* store the new term          */

        /* Mark all new forbidden sums a(i)+2*a(new_idx) for i<new_idx. */
        for (idx_t i = 0; i < new_idx - 1; ++i) {
            seq_t sum = seq_arr[i] + ((seq_t)2 * next_val);
            /* Convert to size_t for indexing; we assume sum fits in size_t. */
            if ((size_t)sum >= forb_cap) ensure_forbidden((size_t)sum);
            forb_arr[(size_t)sum] = 1;
        }

        ++generated;
    }

    return seq_arr[n - 1];
}
