/*
 * A075589  Primes p such that the number of distinct prime divisors of all
 *          composite numbers between p and the next prime is 9.
 * https://oeis.org/A075589
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 236, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   is_prime_uint64, next_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n): nth prime p such that the set of distinct prime divisors of
 * all composite numbers between p and the next prime has exactly 9 elements.
 * The sequence is generated by a simple search using a sieve of Eratosthenes
 * up to a fixed limit and trial‑division factorisation. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

#include "../utils/next_prime.h"
#include "../utils/is_prime_uint64.h"

/* ----- Prime sieve up to a fixed limit ----- */
#define SIEVE_MAX 10000000UL  /* enough for factorisation up to 10^14          */
static uint32_t *prime_list = NULL;
static size_t    prime_count = 0;
static uint32_t  sieve_limit = 0;

/* initialise sieve only once */
static void init_sieve(void)
{
    if (sieve_limit)
        return;

    sieve_limit = SIEVE_MAX;
    bool *is_composite = (bool*)calloc(sieve_limit + 1, sizeof(bool));
    if (!is_composite) abort();

    for (uint32_t i = 2; i * i <= sieve_limit; ++i) {
        if (!is_composite[i]) {
            for (uint32_t j = i * i; j <= sieve_limit; j += i)
                is_composite[j] = true;
        }
    }

    /* count primes */
    prime_count = 0;
    for (uint32_t i = 2; i <= sieve_limit; ++i)
        if (!is_composite[i]) ++prime_count;

    prime_list = (uint32_t*)malloc(prime_count * sizeof(uint32_t));
    if (!prime_list) abort();

    size_t idx = 0;
    for (uint32_t i = 2; i <= sieve_limit; ++i)
        if (!is_composite[i]) prime_list[idx++] = i;

    free(is_composite);
}

/* ----- Check whether a prime p satisfies the definition ----- */
static bool satisfies(uint64_t p)
{
    uint64_t q = next_prime(p);
    if (q <= p + 1)   /* no composites in between */
        return false;

    /* Array of distinct prime factors collected over all composites.
     * We need at most 9 + 1 to early detect impossibility.          */
    uint64_t seen[10];
    size_t seen_cnt = 0;

    for (uint64_t n = p + 1; n < q; ++n) {
        if (is_prime_uint64(n))
            continue;   /* skip primes */

        uint64_t m = n;
        /* trial division by pre‑computed primes up to sqrt(m) */
        for (size_t i = 0; i < prime_count &&
                          (uint64_t)prime_list[i] * (uint64_t)prime_list[i] <= m;
             ++i) {
            uint32_t pr = prime_list[i];
            if (m % pr == 0) {
                /* record prime if new */
                bool found = false;
                for (size_t j = 0; j < seen_cnt; ++j)
                    if (seen[j] == pr) { found = true; break; }
                if (!found) {
                    if (seen_cnt == 10)   /* safety protection */
                        return false;
                    seen[seen_cnt++] = pr;
                    if (seen_cnt > 9)
                        return false;
                }
                while (m % pr == 0) m /= pr;
            }
        }
        /* remaining factor > 1 is prime */
        if (m > 1) {
            uint64_t pr = m;
            bool found = false;
            for (size_t j = 0; j < seen_cnt; ++j)
                if (seen[j] == pr) { found = true; break; }
            if (!found) {
                if (seen_cnt == 10)
                    return false;
                seen[seen_cnt++] = pr;
                if (seen_cnt > 9)
                    return false;
            }
        }

        if (seen_cnt > 9)   /* early exit if too many primes */
            return false;
    }
    return seen_cnt == 9;
}

/* ----- Cache of computed terms ----- */
static struct {
    seq_t *data;
    size_t len;
    size_t cap;
} cache = {NULL, 0, 0};

static void cache_append(seq_t val)
{
    if (cache.cap == 0) {
        cache.cap = 16;
        cache.data = (seq_t*)malloc(cache.cap * sizeof(seq_t));
    } else if (cache.len == cache.cap) {
        cache.cap <<= 1;
        cache.data = (seq_t*)realloc(cache.data, cache.cap * sizeof(seq_t));
    }
    cache.data[cache.len++] = val;
}

/* ----- Main sequence function ----- */
seq_t a(idx_t n)
{
    /* initialise global resources once */
    init_sieve();

    static uint64_t last_checked = 2;
    static bool first_call = true;
    if (first_call) {
        first_call = false;
        /* Ensure the cache is empty at program start */
        cache.len = 0;
    }

    while (cache.len < n) {
        uint64_t p = next_prime(last_checked);
        if (satisfies(p))
            cache_append((seq_t)p);
        last_checked = p;   /* continue searching after this prime */
    }

    return cache.data[n - 1];
}
