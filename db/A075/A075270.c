/*
 * A075270  Sum of Lucas numbers and inverted Lucas numbers: a(n) =
 *          A000032(n)*A075193(n).
 * https://oeis.org/A075270
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  easy, sign
 * Formula:   a(n) = 3*a(n-2) - a(n-4); a(0) = 3, a(1) = -2, a(2) = 7, a(3) =
 *            -3
 * Range:     i8 n <= 9, i16 n <= 19, i32 n <= 39, i64 n <= 39, i128 n <= 39,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>

seq_t a(idx_t n)
{
    /* Static cache of already computed values */
    static seq_t *cache        = NULL;   /* array holding a(0) … a(current) */
    static size_t  cache_len   = 0;      /* number of computed elements   */
    static size_t  cache_cap   = 0;      /* allocated array capacity      */

    /* Initialise the cache with the first four terms. */
    if (cache == NULL) {
        cache_cap = 4;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (cache == NULL) return (seq_t)0;          /* allocation failed */
        cache[0] = (seq_t)3;
        cache[1] = (seq_t)-2;
        cache[2] = (seq_t)7;
        cache[3] = (seq_t)-3;
        cache_len = 4;                               /* values 0..3 are ready */
    }

    /* Grow the cache if the requested index is beyond the current capacity. */
    size_t target = (size_t)n;
    if (target + 1 > cache_cap) {
        size_t new_cap = cache_cap * 2;
        if (new_cap < target + 1) new_cap = target + 1;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (tmp == NULL) return (seq_t)0;          /* allocation failed */
        cache = tmp;
        cache_cap = new_cap;
    }

    /* Compute missing terms up to the requested index. */
    if (target >= cache_len) {
        for (size_t i = cache_len; i <= target; ++i) {
            /* i >= 4 for all indices generated by this loop */
            cache[i] = (seq_t)3 * cache[i-2] - cache[i-4];
        }
        cache_len = target + 1;
    }

    return cache[target];
}
