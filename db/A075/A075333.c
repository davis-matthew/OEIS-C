/*
 * A075333  Pair up the natural numbers as (r, s) (say) so that all natural
 *          numbers are obtained only once as r, s, s+r, s-r or r*s: (2, 3),
 *          (4, 11), (8, 17), (10, 22), (13, 27), (16, 34), ... Sequence gives
 *          first member of each pair.
 * https://oeis.org/A075333
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 30, u16 n <= 151, u32 n <= 151, u64 n <= 151,
 *            u128 n <= 151, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  The sequence A075333 cannot be expressed by a simple closed formula; it
    is generated by a greedy pairing algorithm.  The first member of each
    pair (r, s) is a(n).  Each natural number must appear exactly once
    as an r, an s, as s+r, as s−r, or as r·s.  The algorithm keeps a
    list of all numbers already used and, for each new term, finds the
    smallest r that is unused, then the smallest s>r that together with r
    satisfies the distinctness and unused conditions.  The function
    a(idx_t n) returns the n‑th term (1‑based). */
#include <stdlib.h>
#include <stdbool.h>

/* Forward declaration from prelude (do not change): */
seq_t a(idx_t n);

/* ---------------------------------------------------------------------- */
/*  Data structures used by the algorithm                                */
/* ---------------------------------------------------------------------- */

static seq_t *seq    = NULL;   /* 1‑based array of generated terms, seq[0] unused */
static size_t seq_cap   = 0;
static size_t seq_len   = 1;   /* seq[1] will be filled on first generation */

static uint64_t *used  = NULL; /* list of all numbers that have been used */
static size_t used_cap  = 0;
static size_t used_len  = 0;

/* ---------------------------------------------------------------------- */
/*  Utility helpers                                                     */
/* ---------------------------------------------------------------------- */

static void ensure_seq_cap(size_t needed)
{
    if (needed > seq_cap) {
        size_t new_cap = seq_cap ? seq_cap * 2 : 64;
        while (new_cap < needed) new_cap <<= 1;
        seq = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
        seq_cap = new_cap;
    }
}

static void ensure_used_cap(size_t needed)
{
    if (needed > used_cap) {
        size_t new_cap = used_cap ? used_cap * 2 : 64;
        while (new_cap < needed) new_cap <<= 1;
        used = (uint64_t *)realloc(used, new_cap * sizeof(uint64_t));
        used_cap = new_cap;
    }
}

/* Test whether a 64‑bit value has already been used. */
static bool value_used(uint64_t val)
{
    for (size_t i = 0; i < used_len; ++i)
        if (used[i] == val) return true;
    return false;
}

/* ---------------------------------------------------------------------- */
/*  Public function                                                       */
/* ---------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    static seq_t next_r = 2;  /* next candidate r (unused integer) */

    /* Generate terms until we have at least n terms. */
    while (seq_len <= (size_t)n) {
        seq_t r = next_r;
        seq_t s = r + 1;

        /* Find the smallest s > r that produces five distinct unused numbers. */
        for (;;) {
            seq_t sum = r + s;
            seq_t diff = s - r;
            uint64_t prod = (uint64_t)r * (uint64_t)s;

            /* Check pairwise distinctness among the five values. */
            if (r == s || r == sum || r == diff || r == prod ||
                s == sum || s == diff || s == prod ||
                sum == diff || sum == prod || diff == prod)
            {
                ++s;
                continue;
            }

            /* Check that none of the five values is already used. */
            if (value_used((uint64_t)r) ||
                value_used((uint64_t)s) ||
                value_used((uint64_t)sum) ||
                value_used((uint64_t)diff) ||
                value_used(prod))
            {
                ++s;
                continue;
            }

            break;   /* suitable s found */
        }

        /* Record the five numbers as used. */
        ensure_used_cap(used_len + 5);
        used[used_len++] = (uint64_t)r;
        used[used_len++] = (uint64_t)s;
        used[used_len++] = (uint64_t)(r + s);
        used[used_len++] = (uint64_t)(s - r);
        used[used_len++] = (uint64_t)r * (uint64_t)s;

        /* Store the first pair member. */
        ensure_seq_cap(seq_len + 1);
        seq[seq_len++] = r;

        /* Find the next unused integer greater than r to serve as the next r. */
        uint64_t cand = (uint64_t)r + 1;
        for (;;) {
            if (!value_used(cand)) {
                next_r = (seq_t)cand;
                break;
            }
            ++cand;
        }
    }

    return seq[(size_t)n];
}
