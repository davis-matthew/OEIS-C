/*
 * A075760  Nontrivial binomial coefficients which are perfect powers
 *          (A001597).
 * https://oeis.org/A075760
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, more
 * Formula:   a(1) = 36 = C(9,2); a(2) = 1225 = C(50,2); a(3) = 19600 =
 *            C(50,3). For n ≥ 4, a(n) = (r_{n-1})², where r₀ = 1, r₁ = 6 and
 *            r_{k+1} = 6 r_k – r_{k-1} (the Pell sequence that generates
 *            triangular‑square numbers)
 * Range:     u8 n <= 1, u16 n <= 4, u32 n <= 7, u64 n <= 12, u128 n <= 12,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the nth term of OEIS sequence A075760 (nontrivial binomial coefficients
   that are perfect powers).  */
seq_t a(idx_t n)
{
    /* Undefined for n=0; return 0 to avoid undefined behaviour. */
    if (n == 0) return (seq_t)0;

    /* First three terms are special (the 19600 term cannot be generated by the
       Pell recurrence).  */
    if (n == 1) return (seq_t)36;          /* C(9,2)  = 36  = 6²          */
    if (n == 2) return (seq_t)1225;        /* C(50,2) = 1225 = 35²        */
    if (n == 3) return (seq_t)19600;       /* C(50,3) = 19600 = 140²      */

    /* For n ≥ 4 compute r_{n-1} from the Pell recurrence and return its square. */
    seq_t r_prev = (seq_t)1;  /* r₀ */
    seq_t r_curr = (seq_t)6;  /* r₁ */

    /* target = n-1: the index of the required Pell term (r₁ corresponds to a(1)). */
    idx_t target = n - 1;

    /* Run the recurrence from k = 2 up to k = target. */
    for (idx_t k = 2; k <= target; ++k) {
        seq_t r_next = 6 * r_curr - r_prev;
        r_prev = r_curr;
        r_curr = r_next;
    }

    /* r_curr now holds r_{n-1}.  Return its square. */
    return r_curr * r_curr;
}
