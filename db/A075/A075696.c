/*
 * A075696  Sum-of-digits of k appears somewhere in prime(k).
 * https://oeis.org/A075696
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 35, u16 n <= 4057, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   digit_sum, get_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation: a(n) is the n‑th integer k such that the decimal digit
   sum of k occurs as a contiguous substring of the decimal representation
   of the k‑th prime.  The sequence is generated by testing k = 1, 2,
   3, … until n qualifying numbers are found.  */

#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <stdbool.h>

#include "../utils/get_prime.h"
#include "../utils/digit_sum.h"

seq_t a(idx_t n)
{
    idx_t k = 1;          /* candidate integer */
    idx_t count = 0;      /* how many qualifying numbers have been found */

    while (1) {
        /* Digit sum of k.  digit_sum accepts a seq_t; cast is safe
           because the sum is always small. */
        seq_t dsum = digit_sum((seq_t)k);

        /* k‑th prime as a uint32_t. */
        uint32_t pk = get_prime(k);

        /* Convert pk and dsum to decimal strings. */
        char pkbuf[32];
        char dsumbuf[8];
        snprintf(pkbuf, sizeof pkbuf, "%u", pk);
        /* dsum is small (at most 9×number_of_digits(k)), so cast to unsigned. */
        snprintf(dsumbuf, sizeof dsumbuf, "%u", (unsigned)dsum);

        /* Check if dsumbuf appears somewhere in pkbuf. */
        if (strstr(pkbuf, dsumbuf) != NULL) {
            ++count;
            if (count == n)
                return (seq_t)k;  /* n‑th term found */
        }
        ++k;
    }
}
