/*
 * A075994  Irregular triangle T(n,k) = floor(n/k) for k = 1, 2, ...,
 *          floor(n/2) for n>=2 and T(1,1)=1.
 * https://oeis.org/A075994
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 97, u16 n <= 97, u32 n <= 97, u64 n <= 97, u128 n <= 97,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) is the nth element of the triangle
   T(r,k) = floor(r/k) for k = 1, …, floor(r/2)  (r ≥ 2) and T(1,1)=1,
   flattened row‑wise with all 1’s deleted except the first one.  */
/* The sequence is generated by finding the row r such that
   cum[r-1] < n ≤ cum[r]  (cum[i] = total terms up to row i),
   then k = n - cum[r-1]  and a(n) = floor(r / k). */

#include <stdlib.h>

seq_t a(idx_t n)
{
    /* static cache of cumulative counts: cum[i] = total terms up to row i */
    static idx_t *cum = NULL;          /* dynamic array of cumulative sums   */
    static size_t cum_size = 0;         /* number of elements stored (lastRow+1) */
    static size_t cum_cap  = 0;         /* capacity of the array               */

    /* initialise cache with rows 0..1 */
    if (cum == NULL) {
        cum_cap  = 64;
        cum      = (idx_t *)malloc(cum_cap * sizeof(idx_t));
        cum_size = 2;                    /* indices 0 and 1 are present */
        cum[0]   = 0;                    /* no rows, zero terms            */
        cum[1]   = 1;                    /* row 1 contains a single 1       */
    }

    /* extend the cache until it covers the requested index n */
    while (cum[cum_size - 1] < n) {
        /* next row to add */
        idx_t next_row = (idx_t)(cum_size);              /* indices start at 1 */
        idx_t row_size = (next_row == 1 ? 1 : next_row / 2);

        idx_t next_cum = cum[cum_size - 1] + row_size;

        /* enlarge storage if necessary */
        if (cum_size >= cum_cap) {
            cum_cap *= 2;
            cum = (idx_t *)realloc(cum, cum_cap * sizeof(idx_t));
        }

        cum[cum_size++] = next_cum;
    }

    /* locate the row r such that cum[r-1] < n ≤ cum[r] */
    idx_t r = 1;
    while (cum[r] < n) ++r;

    /* position within the row (k) */
    idx_t k = n - cum[r - 1];   /* 1 ≤ k ≤ floor(r/2) */

    /* value from the triangle */
    return (seq_t)(r / k);
}
