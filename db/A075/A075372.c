/*
 * A075372  Smallest squarefree number not occurring earlier such that the
 *          every partial sum is squarefree.
 * https://oeis.org/A075372
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 17, u16 n <= 69, u32 n <= 69, u64 n <= 69, u128 n <= 69,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A075372
 *
 *  Formula: a(n) is the smallest square‑free integer that has not yet
 *  appeared in the sequence and such that the new partial sum
 *  S(n)=S(n‑1)+a(n) is also square‑free.  The sequence starts at
 *  a(1)=1 and is generated by the greedy algorithm described above.
 */

#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* ----------  static data structures  ---------- */
static uint32_t *primes = NULL;      /* list of primes up to sieve_limit               */
static size_t   prime_cnt = 0;       /* number of primes stored                       */
static uint8_t  *used   = NULL;      /* bitmap for numbers that have already been used */
static size_t   used_max = 0;        /* current allocation size for used bitmap        */
static seq_t   *cache  = NULL;       /* cached sequence terms                          */
static size_t   cache_cap = 0, cache_len = 0;  /* cache allocation and length      */
static seq_t    sum = 0;             /* current partial sum                            */

/* ----------  helpers  ---------- */

/* sieve of Eratosthenes up to SIEVE_LIMIT, returns primes in primes[]   */
static void build_primes(void)
{
    if (prime_cnt != 0) return;                /* already built */

    const uint32_t SIEVE_LIMIT = 1000000u;     /* enough for n ≤ 10000 */
    uint8_t *sieve = (uint8_t *)calloc(SIEVE_LIMIT + 1, 1);
    if (!sieve) abort();

    sieve[0] = sieve[1] = 1;
    for (uint32_t i = 2; (uint64_t)i * i <= SIEVE_LIMIT; ++i) {
        if (!sieve[i]) {
            for (uint64_t j = (uint64_t)i * i; j <= SIEVE_LIMIT; j += i)
                sieve[(size_t)j] = 1;
        }
    }

    prime_cnt = 0;
    for (uint32_t i = 2; i <= SIEVE_LIMIT; ++i)
        if (!sieve[i]) ++prime_cnt;

    primes = (uint32_t *)malloc(sizeof(uint32_t) * prime_cnt);
    if (!primes) abort();

    size_t idx = 0;
    for (uint32_t i = 2; i <= SIEVE_LIMIT; ++i)
        if (!sieve[i]) primes[idx++] = i;

    free(sieve);
}

/* ensure 'used' array covers at least up_to (inclusive)                */
static void ensure_used_capacity(uint64_t up_to)
{
    if (up_to <= used_max) return;
    size_t new_max = up_to;
    if (used_max > 0) {
        new_max = used_max * 2;
        if (new_max < up_to) new_max = up_to;
    }
    uint8_t *new_used = (uint8_t *)realloc(used, new_max + 1);
    if (!new_used) abort();
    /* initialize new part to 0 */
    if (used_max < new_max)
        memset(new_used + used_max + 1, 0, new_max - used_max);
    used = new_used;
    used_max = new_max;
}

/* square‑free test for 64‑bit value (used when 'cand' fits 64‑bit)       */
static int is_squarefree_u64(uint64_t v)
{
    if (v <= 1) return 1;
    for (size_t i = 0; i < prime_cnt; ++i) {
        uint64_t p = primes[i];
        uint64_t pp = p * p;
        if (pp > v) break;
        if (v % pp == 0) return 0;
    }
    return 1;
}

/* square‑free test for generic seq_t value, safe as long as result
 * fits in 64‑bits (the test set for n ≤ 10000 does)                  */
static int is_squarefree_seq(seq_t v)
{
    if (v <= (seq_t)1) return 1;
    for (size_t i = 0; i < prime_cnt; ++i) {
        seq_t p  = (seq_t)primes[i];
        seq_t pp = p * p;
        if (pp > v) break;
        if (v % pp == 0) return 0;
    }
    return 1;
}

/* generate terms up to index n (1‑based)                               */
static void ensure_terms(idx_t n)
{
    if (cache_len >= (size_t)n) return;
    build_primes();

    while (cache_len < (size_t)n) {
        /* candidate selection – linear scan from 1 onwards              */
        uint64_t cand = 1;
        for (;; ++cand) {
            /* enlarge used bitmap if necessary                        */
            ensure_used_capacity(cand);

            if (used[(size_t)cand]) continue;              /* already used */

            /* check candidate itself is square‑free                  */
            if (!is_squarefree_u64(cand)) continue;

            /* new partial sum must be square‑free                    */
            seq_t new_sum = sum + (seq_t)cand;
            if (!is_squarefree_seq(new_sum)) continue;

            /* accept candidate                                       */
            seq_t term = (seq_t)cand;
            if (cache_len >= cache_cap) {
                size_t new_cap = cache_cap ? cache_cap * 2 : 32;
                seq_t *new_cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!new_cache) abort();
                cache = new_cache;
                cache_cap = new_cap;
            }
            cache[cache_len++] = term;
            used[(size_t)cand] = 1;
            sum += term;
            break;
        }
    }
}

/* ----------  required function  ---------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;           /* undefined, but harmless             */
    ensure_terms(n);
    return cache[(size_t)n - 1];
}
