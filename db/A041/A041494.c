/* A041494: Numerators of continued‑fraction convergents to sqrt(264).
 * Recurrence: p_{-2}=0, p_{-1}=1,
 *              p_n = a_n * p_{n-1} + p_{n-2}
 * where a_0 = 16 and for n≥1 the coefficients a_n are generated by
 * the standard continued‑fraction algorithm for √264.  The function
 * accepts an index n≥0 and returns the n‑th numerator in seq_t.  No
 * lookup table is used.  The algorithm runs in O(n) time and uses only
 * the built‑in operators + - * / (truncating) on seq_t together with
 * 64‑bit integer arithmetic for the continued‑fraction data.  */
#include <stdint.h>

seq_t a(idx_t n)
{
    /* Constants for sqrt(264) */
    const uint64_t D   = 264ULL;
    const uint64_t a0  = 16ULL;   /* floor(sqrt(264)) */

    if (n == 0)            /* first term a(0) = 16 */
        return (seq_t)a0;

    /* Continued‑fraction state variables (all fit in 64 bits). */
    uint64_t m      = 0ULL;            /* m_k */
    uint64_t d      = 1ULL;            /* d_k */
    uint64_t a_coeff = a0;             /* a_k for current step */

    /* Recursion: numerators of the convergents. */
    seq_t p_prev2 = 0;                 /* p_{k-2} */
    seq_t p_prev1 = 1;                 /* p_{k-1} */
    seq_t p_curr  = 0;                 /* p_k */

    for (idx_t i = 0; i <= n; ++i) {
        /* p_k = a_k * p_{k-1} + p_{k-2} */
        seq_t a_cur = (seq_t)a_coeff;
        p_curr = a_cur * p_prev1 + p_prev2;

        if (i == n)                   /* answer ready */
            return p_curr;

        /* Advance to the next continued‑fraction coefficient. */
        uint64_t m_next = d * a_coeff - m;
        uint64_t d_next = (D - m_next * m_next) / d;
        m = m_next;
        d = d_next;
        a_coeff = (a0 + m) / d;

        /* shift the recurrence window for the next iteration */
        p_prev2 = p_prev1;
        p_prev1 = p_curr;
    }

    /* Unreachable, but satisfies the compiler. */
    return p_curr;
}
