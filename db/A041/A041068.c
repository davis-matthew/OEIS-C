/* Recurrence: let p(-2)=0, p(-1)=1.  
   For k≥0 let a_k be the k‑th partial quotient of sqrt(41)  
   (a_0=6, the rest are generated by the standard Pell algorithm).  
   Then a(k)=p_k where p_k = a_k * p_{k-1} + p_{k-2}.  
   This function returns a(n). */

seq_t a(idx_t n)
{
    /* The constant √41 has integer part 6 */
    const idx_t D   = 41;
    const idx_t a0  = 6;          /* a_0   = floor(sqrt(41)) */

    /* State of the continued‑fraction algorithm */
    idx_t m = 0;        /* m_k   */
    idx_t d = 1;        /* d_k   */
    idx_t a = a0;       /* a_k   */

    /* Current and previous numerator terms */
    seq_t p_nm2 = 0;    /* p_{k-1} */
    seq_t p_nm1 = 1;    /* p_{k-2} */
    seq_t p_n   = 0;    /* p_k    */

    for (idx_t k = 0; k <= n; ++k)
    {
        /* p_k = a_k * p_{k-1} + p_{k-2} */
        p_n = p_nm1 * (seq_t)a + p_nm2;

        if (k == n)
            return p_n;

        /* Prepare next partial quotient a_{k+1} */
        idx_t m_next = d * a - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (a0 + m_next) / d_next;

        /* Shift numerator terms for next iteration */
        p_nm2 = p_nm1;
        p_nm1 = p_n;

        /* Update continued‑fraction state */
        m = m_next;
        d = d_next;
        a = a_next;
    }

    /* Unreachable, but keeps the compiler happy */
    return 0;
}
