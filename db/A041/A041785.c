#include <stddef.h>
#include <stdbool.h>

/* Sequence: denominators of continued‑fraction convergents to sqrt(413)
   Formula (for n > 15):
        a(n) = 226798 * a(n-8) - a(n-16)
   Base values a(0) … a(15) are the first 16 convergent denominators and
   are generated by the continued‑fraction algorithm below. */
seq_t a(idx_t n)
{
    /* --- precompute the first 16 values once --------------------------------- */
    static seq_t init[16];
    static bool init_done = false;
    if (!init_done) {
        /* continued‑fraction data for sqrt(413) */
        const idx_t D      = 413;      /* the radicand          */
        const idx_t a0     = 20;       /* floor(sqrt(413))      */
        idx_t m            = 0;
        idx_t d            = 1;
        idx_t a            = a0;

        seq_t q_prev_prev  = 0;        /* Q_{-1}                */
        seq_t q_prev       = 1;        /* Q_0                   */
        init[0]            = 1;        /* a(0) = Q_0            */

        for (int k = 1; k < 16; ++k) {
            idx_t m_next = d * a - m;
            idx_t d_next = (D - m_next * m_next) / d;
            idx_t a_next = (a0 + m_next) / d_next;

            m = m_next;
            d = d_next;
            a = a_next;

            seq_t q_curr = (seq_t)a_next * q_prev + q_prev_prev;
            init[k] = q_curr;

            q_prev_prev = q_prev;
            q_prev      = q_curr;
        }
        init_done = true;
    }

    /* --- answer trivial indices -------------------------------------------- */
    if (n < 16) {
        return init[(size_t)n];
    }

    /* --- compute a(n) using the 8‑step recurrence with a 16‑slot circular
            buffer (only the last 16 values are kept) ------------------------ */
    seq_t buf[16];
    for (int k = 0; k < 16; ++k)
        buf[k] = init[k];

    for (size_t i = 16; i <= n; ++i) {
        seq_t val = (seq_t)226798 * buf[(i - 8) % 16] - buf[(i - 16) % 16];
        buf[i % 16] = val;
    }

    return buf[n % 16];
}
