/* Numerators of continued fraction convergents to sqrt(384).
   The nth term a(n) is the numerator p_n of the nth convergent of
   the regular continued fraction expansion of sqrt(384).  Using the
   classical recurrences:
        p_{-2}=0, p_{-1}=1
        p_k = a_k * p_{k-1} + p_{k-2}
   where the partial quotients a_k are generated by the standard
   sqrt‐expansion algorithm. */

#include <stdint.h>

seq_t a(idx_t n)
{
    /* constants for sqrt(384) */
    const idx_t N   = 384;     /* the radicand */
    const idx_t a0  = 19;      /* floor(sqrt(384)) */

    /* state variables for the continued fraction algorithm */
    idx_t m = 0;          /* m_{k}   */
    idx_t d = 1;          /* d_{k}   */
    idx_t a_k = a0;       /* a_{k} in the loop */

    /* recurrence for convergent numerators */
    seq_t p_prev_prev = 0; /* p_{k-2} */
    seq_t p_prev      = 1; /* p_{k-1} */

    for (idx_t k = 0; k <= n; ++k)
    {
        /* compute p_k = a_k * p_{k-1} + p_{k-2} */
        seq_t p = (seq_t)a_k * p_prev + p_prev_prev;
        p_prev_prev = p_prev;
        p_prev = p;

        /* if we are done, return the result */
        if (k == n)
            return p_prev;

        /* generate next partial quotient a_{k+1} */
        m = d * a_k - m;
        idx_t new_d = (N - m * m) / d;
        d = new_d;
        a_k = (a0 + m) / d;
    }

    /* control should never reach here */
    return 0;
}
