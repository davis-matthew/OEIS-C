/* OEIS A041216
   Numerators of continued fraction convergents to sqrt(119).

   The convergents are generated by the recurrence
   p_{-2} = 0,  p_{-1} = 1
   p_n   = a_n * p_{n-1} + p_{n-2}

   where the partial quotients a_n are
     a_0 = 10,
     a_n = {1, 9, 1, 20} repeated for n ≥ 1.
   Thus a(0)=10, a(1)=1, a(2)=9, a(3)=1, a(4)=20, a(5)=1, ...
   The first few numerators are 10, 11, 109, 120, 2509, ...

   This function computes a(n) for any n ≥ 0 according to the above
   recurrence.  It uses only integer arithmetic on type seq_t.
*/

#include <stddef.h>  // for size_t

static const seq_t cycle[4] = {
    (seq_t)1, (seq_t)9, (seq_t)1, (seq_t)20
};

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)10;

    seq_t p_minus2 = (seq_t)0;  // p_{-2}
    seq_t p_minus1 = (seq_t)1;  // p_{-1}

    for (idx_t k = 0; k <= n; ++k) {
        seq_t coeff;
        if (k == 0) {
            coeff = (seq_t)10;
        } else {
            coeff = cycle[(k - 1) & 3];  // modulo 4 cycle
        }
        seq_t p_k = coeff * p_minus1 + p_minus2;
        if (k == n) return p_k;
        p_minus2 = p_minus1;
        p_minus1 = p_k;
    }
    /* unreachable but keeps the compiler happy */
    return (seq_t)0;
}
