/* a(n) = denominator of the n‑th convergent of √491.
   Let a0 = ⌊√491⌋ = 22.  The continued‑fraction quotients a_k for k ≥ 1
   are generated by the standard quadratic‑surd recurrence:
         m_k   = d_{k-1}·a_{k-1} – m_{k-1}
         d_k   = (491 – m_k²)/d_{k-1}
         a_k   = (a0 + m_k)/d_k
   The denominators satisfy
         q_{-1} = 0,  q_0 = 1
         q_k   = a_k·q_{k-1} + q_{k-2}   (k ≥ 1) */

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)1;   /* q_0 = 1 */

    const uint64_t D   = 491;
    const uint64_t a0  = 22;   /* floor(sqrt(D)) */

    uint64_t m     = 0;
    uint64_t d     = 1;
    uint64_t a_val = a0;

    seq_t q_prev2 = 0;   /* q_{k-2} */
    seq_t q_prev  = 1;   /* q_{k-1} */
    seq_t q_curr  = 0;   /* q_k */

    for (idx_t i = 1; i <= n; ++i) {
        /* generate next quotient a_i */
        uint64_t m_next = d * a_val - m;
        uint64_t d_next = (D - m_next * m_next) / d;
        uint64_t a_next = (a0 + m_next) / d_next;

        /* compute next denominator */
        q_curr = (seq_t)a_next * q_prev + q_prev2;

        /* shift for next iteration */
        q_prev2 = q_prev;
        q_prev  = q_curr;
        m = m_next;
        d = d_next;
        a_val = a_next;
    }

    return q_curr;
}
