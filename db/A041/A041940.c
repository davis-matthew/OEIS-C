/* Sequence A041940:  Numerators of continued‑fraction convergents to sqrt(493).
   The sequence is generated by the standard continued‑fraction algorithm:
   let a0 = ⌊√493⌋ = 22.
   Initialize p_{-2}=0, p_{-1}=1.
   For k≥0   p_k = a_k·p_{k-1} + p_{k-2}  (numerator of the k‑th convergent).
   The partial quotients a_k are produced by
        m_{k+1} = d_k·a_k – m_k
        d_{k+1} = (493 – m_{k+1}²)/d_k
        a_{k+1} = ⌊(a0 + m_{k+1})/d_{k+1}⌋
   with m_0=0, d_0=1.  This yields the exact sequence of numerators. */
#include <stdint.h>

seq_t a(idx_t n)
{
    /* integer part of √493 */
    const uint64_t a0 = 22U;

    /* base convergents: p_{-2}=0, p_{-1}=1, p_0=a0 */
    seq_t p_prev2 = 0;                      /* p_{-2} */
    seq_t p_prev1 = 1;                      /* p_{-1} */
    seq_t p_curr  = (seq_t)a0 * p_prev1;    /* p_0 = a0 */

    /* 0‑based index: a(0)=p_0 */
    if (n == 0)
        return p_curr;

    /* continued‑fraction state for √493: m_k, d_k, a_k */
    uint64_t m = 0;          /* m_0 */
    uint64_t d = 1;          /* d_0 */
    uint64_t a_k = a0;       /* a_0 */

    /* compute convergents up to index n */
    idx_t k;
    for (k = 1; k <= n; ++k) {
        /* compute next partial quotient a_{k} */
        uint64_t m_next = d * a_k - m;
        uint64_t d_next = (493ULL - m_next * m_next) / d;
        uint64_t a_next = (a0 + m_next) / d_next;

        /* shift previous numerators: p_{k-1} becomes p_{k-2},
           p_k becomes p_{k-1} */
        p_prev2 = p_prev1;
        p_prev1 = p_curr;

        /* new numerator p_k = a_next * p_{k-1} + p_{k-2} */
        p_curr = (seq_t)a_next * p_prev1 + p_prev2;

        /* update continued‑fraction state for next iteration */
        m = m_next;
        d = d_next;
        a_k = a_next;
    }

    return p_curr;
}
