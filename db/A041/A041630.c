/*
 * A041630  Numerators of continued fraction convergents to sqrt(334).
 * https://oeis.org/A041630
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, cofr, frac, easy
 * Formula:   a(n) = nth numerator of the continued‑fraction convergents of
 *            sqrt(334)
 * Range:     u8 n <= 1, u16 n <= 9, u32 n <= 17, u64 n <= 37, u128 n <= 73,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence: p[-2]=0, p[-1]=1; a0 = floor(sqrt(334));
   p_n = a_n * p_{n-1} + p_{n-2}    (for n>=0) */
/* The partial quotients a_n are generated by the standard Pell algorithm. */

#include <stdlib.h>

seq_t a(idx_t n)
{
    /* persistent cache */
    static seq_t *p_cache = NULL;
    static size_t cache_cap = 0;
    static size_t cache_len = 0;

    /* state for generating partial quotients */
    static seq_t m_cur = 0;          /* m_k   */
    static seq_t d_cur = 1;          /* d_k   */
    static seq_t a_cur = 0;          /* a_k   */

    const seq_t N = (seq_t)334;     /* the quadratic irrational */
    const seq_t a0 = (seq_t)18;     /* floor(sqrt(334)) */

    /* allocate first block if needed */
    if (cache_len == 0)
    {
        cache_cap = 16;
        p_cache    = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        /* a0 */
        p_cache[0] = a0;
        cache_len  = 1;
        /* initialise state for next quotient a1 */
        m_cur = 0;
        d_cur = 1;
        a_cur = a0;
    }

    /* extend cache up to n */
    if ((idx_t)cache_len <= n)
    {
        for (size_t k = cache_len; k <= (size_t)n; ++k)
        {
            /* step 1: compute next partial quotient a_k (k>=1) */
            seq_t m_next = d_cur * a_cur - m_cur;
            seq_t d_next = (N - m_next * m_next) / d_cur;
            seq_t a_next = (a0 + m_next) / d_next;   /* floor division */

            /* step 2: compute numerator p_k */
            seq_t prev1 = p_cache[k - 1];
            seq_t prev2 = (k > 1) ? p_cache[k - 2] : (seq_t)1;
            seq_t p_k   = a_next * prev1 + prev2;

            /* store result */
            if (cache_len >= cache_cap)
            {
                cache_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
                seq_t *tmp = (seq_t *)realloc(p_cache, cache_cap * sizeof(seq_t));
                p_cache = tmp;
            }
            p_cache[cache_len++] = p_k;

            /* step 3: update state for next iteration */
            m_cur = m_next;
            d_cur = d_next;
            a_cur = a_next;
        }
    }

    return p_cache[(size_t)n];
}
