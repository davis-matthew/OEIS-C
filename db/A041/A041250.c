/* OEIS A041250: Numerators of continued‑fraction convergents to sqrt(137).
   Recurrence:
     p_{-1} = 1 ,  p_0 = 11
     p_n   = a_n * p_{n-1} + p_{n-2}   for n ≥ 1
   The partial quotients a_n are generated by the standard expansion of
   √137:
     m_0 = 0 ,  d_0 = 1 ,  a_0 = 11
     m_k = d_{k-1} * a_{k-1} – m_{k-1}
     d_k = (137 – m_k^2) / d_{k-1}
     a_k = (11 + m_k) / d_k
*/

#include <stdlib.h>

/* ---------- static state ---------- */
static seq_t *cache   = NULL;      /* memory for cached numerators   */
static size_t cache_cap = 0;       /* current capacity of cache     */
static idx_t  last_n   = (idx_t)-1;/* last index for which we know   */

static const idx_t A0 = 11;        /* floor(sqrt(137)) */
static const idx_t D  = 137;       /* the square root argument */

static idx_t m = 0;                /* current m in the CF iteration */
static idx_t d = 1;                /* current d in the CF iteration */
static idx_t a_k = 0;              /* current partial quotient (for next term) */

static seq_t prev2 = 0;            /* p_{n-2} */
static seq_t prev1 = 0;            /* p_{n-1} */

/* ensure that cache has room for indices up to n */
static void ensure_cache(idx_t n)
{
    if ((size_t)n < cache_cap) return;
    size_t new_cap = (size_t)n + 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(*cache));
    if (!tmp) abort();            /* out of memory */
    cache = tmp;
    cache_cap = new_cap;
}

/* initialise the very first terms and the continued‑fraction state */
static void init_first_terms(void)
{
    /* base numerators */
    prev2 = (seq_t)1;          /* p_{-1} */
    prev1 = (seq_t)A0;         /* p_0  = 11  */
    ensure_cache(0);
    cache[0] = (seq_t)A0;      /* store a(0) */

    /* compute the first partial quotient a_1 */
    idx_t m1 = d * A0 - m;                     /* m_1   */
    idx_t d1 = (D - m1 * m1) / d;              /* d_1   */
    a_k  = (A0 + m1) / d1;                     /* a_1   */

    /* set state for the next iteration */
    m = m1;
    d = d1;

    last_n = 0; /* we have cached a(0) */
}

/* computation of the nth numerator */
seq_t a(idx_t n)
{
    ensure_cache(n);

    /* initialise if this is the first call */
    if (last_n == (idx_t)-1)
        init_first_terms();

    /* if requested index already cached, return it immediately */
    if (n <= last_n)
        return cache[n];

    /* compute terms from last_n+1 up to n */
    for (idx_t i = last_n + 1; i <= n; ++i)
    {
        /* p_i = a_i * p_{i-1} + p_{i-2} */
        seq_t pk = ((seq_t)a_k) * prev1 + prev2;
        cache[i] = pk;

        /* advance the continued‑fraction state to obtain next a_{i+1} */
        idx_t m_next = d * a_k - m;
        idx_t d_next = (D - m_next * m_next) / d;
        a_k = (A0 + m_next) / d_next;

        /* update state for next iteration */
        m = m_next;
        d = d_next;
        prev2 = prev1;
        prev1 = pk;
    }

    last_n = n;
    return cache[n];
}
