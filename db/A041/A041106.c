/* 
   a(n) = numerator of the n-th convergent of sqrt(61).
   Recurrence:
     Let a0 = ⌊√61⌋ = 7.
     p_{-2} = 0, p_{-1} = 1.
     For n ≥ 0:
       p_n = a_n * p_{n-1} + p_{n-2},
     where a_0 = a0 and for n ≥ 1, a_n are generated by the
     standard continued‑fraction algorithm for √61.
*/
#include <stdint.h>

seq_t a(idx_t n)
{
    const uint64_t D  = 61;    /* the radicand */
    const uint64_t a0 = 7;     /* floor(sqrt(61)) */

    seq_t p_nm2 = 0;           /* p_{-2} */
    seq_t p_nm1 = 1;           /* p_{-1} */

    uint64_t m = 0;
    uint64_t d = 1;
    uint64_t a_coeff = a0;     /* a_n */

    for (idx_t i = 0; i <= n; ++i) {
        seq_t p_n = a_coeff * p_nm1 + p_nm2;
        if (i == n) return p_n;

        /* generate next continued‑fraction coefficient */
        m = d * a_coeff - m;
        d = (D - m * m) / d;
        a_coeff = (a0 + m) / d;

        p_nm2 = p_nm1;
        p_nm1 = p_n;
    }
    /* unreachable, but keep compiler happy */
    return 0;
}
