/* Computes the numerators of the convergents of sqrt(202).
   The sequence is generated by the standard continued‑fraction
   algorithm.  For n = 0 the first numerator a0 equals floor(sqrt(202))
   = 14, for n = 1 the second numerator is 57, etc.  This method
   works for any n ≥ 0 and produces the exact value as long as it
   fits in seq_t (arbitrary‑precision builds will handle larger
   values automatically).  */
seq_t a(idx_t n)
{
    const idx_t D = 202;          /* discriminant */
    const idx_t a0 = 14;          /* floor(sqrt(202)) */

    /* p_-2 = 0, p_-1 = 1 (numerators of convergents) */
    seq_t p_nm2 = 0;
    seq_t p_nm1 = 1;

    /* parameters for the continued‑fraction expansion */
    idx_t m      = 0;             /* m_0   */
    idx_t d      = 1;             /* d_0   */
    idx_t anum   = a0;            /* a_0   */

    /* iterate n+1 times to reach the nth convergent */
    for (idx_t k = 0; k <= n; ++k)
    {
        /* current numerator   */
        seq_t p_cur = (seq_t)anum * p_nm1 + p_nm2;

        /* update previous numerators for next step */
        p_nm2 = p_nm1;
        p_nm1 = p_cur;

        /* if we've reached the desired index, return */
        if (k == n)
            return p_cur;

        /* compute next partial quotient a_{k+1} */
        idx_t m_next = d * (idx_t)anum - m;
        idx_t d_next = (D - m_next * m_next) / d;
        anum = (a0 + m_next) / d_next;

        /* advance (m,d) for next iteration */
        m = m_next;
        d = d_next;
    }

    /* the loop always returns before reaching here */
    return 0;
}
