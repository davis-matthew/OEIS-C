/* A041652 – Numerators of continued‑fraction convergents to √345.
   The continued‑fraction coefficients are generated by the standard
   recurrence for quadratic surds.  The numerators pₙ satisfy
     p₋₂ = 0,  p₋₁ = 1,
     pₙ   = aₙ·pₙ₋₁ + pₙ₋₂
   where aₙ are the integer continued‑fraction coefficients of √345.
   The algorithm works for any integer type seq_t (including arbitrary‑
   precision) and uses only integer arithmetic. */
seq_t a(idx_t n)
{
    /* Square‑free integer D = 345 */
    const seq_t D   = 345ULL;
    /* floor(√345) = 18 */
    const seq_t a0  = 18ULL;

    /* Continued‑fraction state: m, d, a_coeff all as seq_t        */
    seq_t m       = 0;     /* m₀ */
    seq_t d       = 1;     /* d₀ */
    seq_t a_coeff = a0;    /* a₀ */

    /* Numerator continuants: p₋₂ = 0, p₋₁ = 1                 */
    seq_t p_nm2 = 0;       /* p[n‑2]  */
    seq_t p_nm1 = 1;       /* p[n‑1]  */
    seq_t p      = 0;      /* current p[n] */

    for (idx_t i = 0; i <= n; ++i) {
        /* Compute current numerator */
        p = a_coeff * p_nm1 + p_nm2;

        /* If we reached the requested index, return it */
        if (i == n) {
            return p;
        }

        /* Shift for next iteration */
        p_nm2 = p_nm1;
        p_nm1 = p;

        /* Compute next continued‑fraction coefficient */
        seq_t m_next  = d * a_coeff - m;
        seq_t d_next  = (D - m_next * m_next) / d;
        seq_t a_next  = (a0 + m_next) / d_next;

        /* Update state */
        m        = m_next;
        d        = d_next;
        a_coeff  = a_next;
    }

    /* Unreachable: safeguard for compiler */
    return 0;
}
