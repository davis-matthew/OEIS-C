/* Numerators of continued fraction convergents to sqrt(491).
   a(0) = 22.
   For k ≥ 1:
       Let a_k be the k‑th partial quotient of the continued fraction of sqrt(491).
       Then a(k) = a_k * a(k-1) + a(k-2),
       where a(−1) = 1 and a(0) = 22.
   The partial quotients are generated by the standard algorithm for quadratic
   surds.  This function computes a(n) exactly when it fits in seq_t. */

#include <stdint.h>

seq_t a(idx_t n)
{
    /* Constants for D = 491 */
    const uint64_t D   = 491;
    const uint64_t a0  = 22;            /* floor(sqrt(491)) */

    /* Partial quotient iteration state */
    uint64_t m = 0;
    uint64_t d = 1;
    uint64_t a = a0;                    /* current partial quotient (a_k) */

    /* Convergent numerators:  p_{-1} = 1,  p_0 = a0 */
    seq_t p_minus1 = (seq_t)1;
    seq_t p = (seq_t)a0;

    if (n == 0)
        return p;

    for (idx_t k = 1; k <= n; ++k)
    {
        /* Generate next partial quotient a_{k} */
        uint64_t m_next  = d * a - m;                     /* m_{k+1} */
        uint64_t d_next  = (D - m_next * m_next) / d;     /* d_{k+1} */
        uint64_t a_next  = (a0 + m_next) / d_next;        /* a_{k+1} */

        /* Compute next numerator p_k = a_{k} * p_{k-1} + p_{k-2} */
        seq_t p_next = (seq_t)a_next * p + p_minus1;

        /* Advance state for next iteration */
        p_minus1 = p;
        p        = p_next;
        m = m_next;
        d = d_next;
        a = a_next;
    }

    return p;   /* p now holds a(n) */
}
