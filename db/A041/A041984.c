/* Numerators of continued‑fraction convergents to sqrt(515).
   Recurrence:
      p_{-1} = 1,   p_0 = 22
      p_k   = a_k * p_{k-1} + p_{k-2}   (k ≥ 1)
   where the partial quotients a_k are generated by the usual
   continued‑fraction algorithm for sqrt(515). */

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)22;

    /* p_{-1} and p_0 */
    seq_t p_prev2 = (seq_t)1;
    seq_t p_prev1 = (seq_t)22;

    /* CF variables (all fit in idx_t, because all values stay < 1000) */
    idx_t m     = 0;          /* m_0   */
    idx_t d     = 1;          /* d_0   */
    idx_t a_k   = 22;         /* a_0   */

    for (idx_t k = 1; k <= n; ++k)
    {
        /* next CF terms */
        idx_t m_next = d * a_k - m;
        idx_t d_next = (515 - m_next * m_next) / d;
        idx_t a_next = (22 + m_next) / d_next;

        /* recurrence for the numerator */
        seq_t pk = p_prev1 * (seq_t)a_next + p_prev2;

        /* finished! */
        if (k == n) return pk;

        /* shift for next step */
        p_prev2 = p_prev1;
        p_prev1 = pk;
        m       = m_next;
        d       = d_next;
        a_k     = a_next;
    }

    /* unreachable */
    return 0;
}
