/* A041468: numerators of the continued‑fraction convergents to sqrt(250)
   recurrence:   h_{-1}=1,  h_0=15;
                  h_n = a_n*h_{n-1} + h_{n-2},
   where the partial quotients a_n are generated by the standard
   continued‑fraction algorithm for sqrt(250). */

#include <stdlib.h>    /* malloc, realloc, free */
#include <stddef.h>    /* size_t */

seq_t a(idx_t n)
{
    /* static cache of already computed terms */
    static seq_t *cache      = NULL;
    static size_t cache_size = 0;   /* next free index in cache */
    static size_t cache_cap  = 0;   /* allocated capacity */

    /* recurrence state variables – correspond to the latest cached entry */
    static seq_t h_prev_prev = 1;   /* h_{-1} */
    static seq_t h_prev      = 15;  /* h_0   */
    static seq_t m           = 0;   /* m_0   */
    static seq_t d           = 1;   /* d_0   */
    static seq_t a_curr      = 15;  /* a_0   */

    /* constant parameters for sqrt(250) */
    static const seq_t a0 = 15;
    static const seq_t D  = 250;

    /* allocate the cache on the first call */
    if (cache == NULL)
    {
        cache_cap  = 1;
        cache_size = 1;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (cache == NULL)
            return 0;                 /* allocation failure */
        cache[0] = a0;                /* a(0) */
    }

    /* return cached value if already available */
    if (n < cache_size)
        return cache[n];

    /* ensure the cache is large enough and compute new terms */
    while (cache_size <= n)
    {
        /* compute the next partial quotient a_{k+1} */
        seq_t m_next = d * a_curr - m;
        seq_t d_next = (D - m_next * m_next) / d;
        seq_t a_next = (a0 + m_next) / d_next;   /* floor division */

        /* compute next numerator h_{k+1} */
        seq_t h_next = a_next * h_prev + h_prev_prev;

        /* grow cache if needed */
        if (cache_cap == cache_size)
        {
            size_t new_cap = cache_cap * 2;
            if (new_cap < (size_t)(cache_size + 1))
                new_cap = cache_size + 1;

            seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            if (tmp == NULL)
            {
                free(cache);
                return 0;               /* allocation failure */
            }
            cache = tmp;
            cache_cap = new_cap;
        }

        /* store the computed term */
        cache[cache_size] = h_next;
        cache_size++;

        /* advance recurrence state */
        h_prev_prev = h_prev;
        h_prev      = h_next;
        m           = m_next;
        d           = d_next;
        a_curr      = a_next;
    }

    return cache[n];
}
