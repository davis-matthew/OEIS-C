/*
 * A041882  Numerators of continued fraction convergents to sqrt(463).
 * https://oeis.org/A041882
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, cofr, frac, easy, less
 * Formula:   a(n) = numerator of the n-th convergent of the continued
 *            fraction for sqrt(463)
 * Range:     u8 n <= 2, u16 n <= 9, u32 n <= 18, u64 n <= 40, u128 n <= 82,
 *            big any n
 * Helpers:   int_sqrt
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The numerator sequence satisfies the recurrence p_k = a_k * p_{k-1} + p_{k-2} */
/* with initial values p_{-2} = 0, p_{-1} = 1 and a_0 = floor(sqrt(463)).  */
/* The continued fraction coefficients a_k are generated by the standard algorithm for sqrt(D). */

#include <stdint.h>
#include "../utils/int_sqrt.h"

seq_t a(idx_t n)
{
    /* D = 463, floor(sqrt(D)) = 21 */
    const idx_t D = 463;
    const idx_t a0 = int_sqrt(D);

    /* variables for the continued fraction algorithm */
    idx_t m = 0;
    idx_t d = 1;
    idx_t a_coef = a0;

    /* variables for the convergent numerator recurrence */
    seq_t p_minus2 = 0;      /* p_{-2} */
    seq_t p_minus1 = 1;      /* p_{-1} */
    seq_t p_k = 0;           /* current numerator */

    for (idx_t i = 0; i <= n; ++i) {
        /* compute p_k = a_coef * p_{k-1} + p_{k-2} */
        p_k = (seq_t)a_coef * p_minus1 + p_minus2;

        /* prepare for next step */
        p_minus2 = p_minus1;
        p_minus1 = p_k;

        if (i == n)
            break;   /* we have computed the needed term */

        /* generate next continued fraction coefficient: a_{k+1} */
        idx_t m_next = d * a_coef - m;                     /* m_{k+1} */
        idx_t d_next = (D - m_next * m_next) / d;          /* d_{k+1} */
        idx_t a_next = (a0 + m_next) / d_next;             /* a_{k+1} */

        /* update state for next iteration */
        m = m_next;
        d = d_next;
        a_coef = a_next;
    }

    return p_k;
}
