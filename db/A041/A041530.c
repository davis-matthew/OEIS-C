/* OEIS A041530: Numerators of continued fraction convergents to sqrt(282).
   Recurrence: p(-2)=0, p(-1)=1, p(k)=a(k)*p(k-1)+p(k-2).
   Continued fraction terms a(k) are generated by the standard sqrt algorithm. */
#include <stdint.h>
#include <stddef.h>

seq_t a(idx_t n)
{
    /* Parameters for sqrt(282) */
    const idx_t  D   = 282;     /* The radicand */
    const idx_t  a0  = 16;      /* floor(sqrt(282)) */

    if (n == 0) return (seq_t)a0;

    /* Continued fraction state */
    idx_t m     = 0;           /* m_k */
    idx_t d     = 1;           /* d_k */
    idx_t a_cur = a0;          /* a(k), starts as a0 */

    /* Convergent numerators */
    seq_t p_nm2 = 0;           /* p(k-2) */
    seq_t p_nm1 = 1;           /* p(k-1) */
    seq_t p = 0;

    for (idx_t i = 0; i <= n; ++i) {
        /* p(k) = a_cur * p(k-1) + p(k-2) */
        p = ((seq_t)a_cur) * p_nm1 + p_nm2;
        if (i == n) return p;

        /* Advance one step in the continued fraction */
        p_nm2 = p_nm1;
        p_nm1 = p;

        /* Next period term of sqrt(282) continued fraction */
        m = d * a_cur - m;
        d = (D - m * m) / d;
        a_cur = (a0 + m) / d;
    }
    return 0; /* unreachable */
}
