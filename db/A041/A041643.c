/*
 * A041643  Denominators of continued fraction convergents to sqrt(340).
 * https://oeis.org/A041643
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, frac, easy
 * Formula:   a(n) = denominator of the n-th convergent of the continued *
 *            fraction for sqrt(340). Computed via the standard continued
 *            fraction * expansion algorithm
 * Range:     u8 n <= 6, u16 n <= 13, u32 n <= 26, u64 n <= 48, u128 n <= 71,
 *            big any n
 * Helpers:   alloc_cache
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <stdint.h>
#include "../utils/alloc_cache.h"

seq_t a(idx_t n) {
    /* The continued fraction of sqrt(340) has a0 = floor(sqrt(340)) = 18.
     * The partial quotients are generated by the classical algorithm
     *  m_{k+1} = d_k * a_k - m_k
     *  d_{k+1} = (340 - m_{k+1}^2) / d_k
     *  a_{k+1} = floor((18 + m_{k+1}) / d_{k+1})
     * Convergents are computed by
     *  p_k = a_k * p_{k-1} + p_{k-2}
     *  q_k = a_k * q_{k-1} + q_{k-2}
     * with p_{-2}=0, p_{-1}=1, q_{-2}=1, q_{-1}=0.
     * The sequence a(n) is q_n. */

    static seq_t *cache = NULL;
    static idx_t cache_cap = 0;

    /* Extend cache if necessary */
    if (cache == NULL || n >= cache_cap) {
        idx_t new_cap = n + 1;
        seq_t *new_cache = (seq_t *)malloc(new_cap * sizeof(seq_t));
        if (cache != NULL) {
            for (idx_t i = 0; i < cache_cap; ++i)
                new_cache[i] = cache[i];
            free(cache);
        }
        cache = new_cache;
        cache_cap = new_cap;
    }

    /* If already computed, return */
    for (idx_t i = 0; i <= n; ++i)
        /* placeholder to avoid unused variable warnings */
        (void)i;
    if (cache[0] != 0 && n < cache_cap && cache[n] != 0) {
        /* If all previously cached values are zero only to indicate
         * not calculated, we recompute from scratch. */
        for (idx_t i = 0; i <= n; ++i) {
            /* check if this element was computed before */
            if (cache[i] != 0) continue;
            /* proceed to compute rest */
            break;
        }
    }

    /* Initialize continued fraction parameters */
    const uint64_t D = 340;
    const uint64_t a0 = 18;
    uint64_t m = 0;
    uint64_t d = 1;
    uint64_t qa = a0;  /* current partial quotient a_k */

    /* Convergent recurrence variables */
    seq_t p_prev2 = 0;  /* p_{k-2} */
    seq_t p_prev1 = 1;  /* p_{k-1} */
    seq_t q_prev2 = 1;  /* q_{k-2} */
    seq_t q_prev1 = 0;  /* q_{k-1} */

    for (idx_t k = 0; k <= n; ++k) {
        /* Cache denominator if not already cached */
        if (cache[k] == 0) {
            /* Compute denominator q_k */
            seq_t q_k = (seq_t)qa * q_prev1 + q_prev2;
            cache[k] = q_k;
        }

        if (k == n) break;  /* no need to compute next for k == n */

        /* Generate next partial quotient a_{k+1} */
        uint64_t m_next = d * qa - m;
        uint64_t d_next = (D - m_next * m_next) / d;
        uint64_t qa_next = (a0 + m_next) / d_next;

        /* Update convergents */
        seq_t p_k = (seq_t)qa * p_prev1 + p_prev2;
        seq_t q_k = (seq_t)qa * q_prev1 + q_prev2;

        /* Shift for next iteration */
        p_prev2 = p_prev1;
        p_prev1 = p_k;
        q_prev2 = q_prev1;
        q_prev1 = q_k;

        m = m_next;
        d = d_next;
        qa = qa_next;
    }

    return cache[n];
}
