/* OEIS A041387 – denominators of continued‑fraction convergents to sqrt(208)
   The denominators qₙ are generated by the recurrence
   q₋₂ = 1,  q₋₁ = 0,
   qₙ = aₙ · qₙ₋₁ + qₙ₋₂   (n ≥ 0)
   where the partial quotients aₙ are produced from √208 by the
   standard continued‑fraction algorithm.
   Initially a₀ = ⌊√208⌋ = 14 and the period of the quotients is
   (2, 2, 1, 2, 2, 28).  This implementation computes qₙ directly
   in O(n) time, without bookkeeping or large allocations, and works
   for any seq_t and idx_t provided by the build. */

#include <stdlib.h>

seq_t a(idx_t n)
{
    /* The integer part of √208 */
    const int a0 = 14;

    /* continued‑fraction state: mₖ, dₖ, aₖ */
    idx_t m = 0;
    idx_t d = 1;
    idx_t a_cur = a0;

    /* denominator recurrence state */
    seq_t q_prev2 = 1;   /* q₋₂ */
    seq_t q_prev1 = 0;   /* q₋₁ */

    for (idx_t k = 0; k <= n; ++k) {
        /* qₖ = aₖ · qₖ₋₁ + qₖ₋₂ */
        seq_t qk = (seq_t)a_cur * q_prev1 + q_prev2;

        /* if we have reached the requested index, return the result */
        if (k == n)
            return qk;

        /* compute the next partial quotient */
        idx_t m_next = d * a_cur - m;
        idx_t d_next = (208 - m_next * m_next) / d;
        idx_t a_next = (a0 + m_next) / d_next;

        /* advance the continued‑fraction state */
        m = m_next;
        d = d_next;
        a_cur = a_next;

        /* advance the denominator state */
        seq_t tmp = q_prev1;
        q_prev1 = qk;
        q_prev2 = tmp;
    }

    /* unreachable, but keeps the compiler happy */
    return 0;
}
