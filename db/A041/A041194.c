/*
 * A041194  Numerators of continued fraction convergents to sqrt(108).
 * https://oeis.org/A041194
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, cofr, frac, easy
 * Formula:   a(n) is the numerator of the n‑th convergent of sqrt(108). The
 *            numerators satisfy the recurrence a(0) = 10, a(1) = 21, a(n) =
 *            c(n) * a(n‑1) + a(n‑2) (n ≥ 2) where c(n) are the coefficients
 *            of the continued fraction of sqrt(108)
 * Range:     u8 n <= 4, u16 n <= 9, u32 n <= 22, u64 n <= 43, u128 n <= 87,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

seq_t a(idx_t n)
{
    /* The continued fraction coefficients are generated by the
       standard algorithm for quadratic irrationals. */
    const idx_t D   = 108;   /* 108 = 6² * 3, a nonsquare integer */
    const idx_t a0  = 10;    /* floor(sqrt(108)) */

    /* Variables for the continued fraction computation */
    idx_t m = 0;
    idx_t d = 1;
    idx_t cr = a0;          /* current coefficient  c(n) */

    /* Recurrence for convergents: p_{-2}=0, p_{-1}=1 */
    seq_t p_prev2 = 0;      /* p_{-2} */
    seq_t p_prev1 = 1;      /* p_{-1} */
    seq_t p_cur   = 0;      /* p_n (the desired numerator) */

    for (idx_t i = 0; i <= n; ++i)
    {
        /* Compute p_i */
        seq_t coeff = (seq_t)cr;
        p_cur = coeff * p_prev1 + p_prev2;

        /* Shift for next step */
        p_prev2 = p_prev1;
        p_prev1 = p_cur;
        if (i == n)
            break;

        /* Generate the next coefficient using the CF recurrence */
        idx_t m_next = d * cr - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t cr_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        cr = cr_next;
    }

    return p_cur;
}
