/* Numerators of continued fraction convergents to sqrt(351) (OEIS A041664).
   Recurrence: let p_{-1}=1, p_0=18. For n≥1
   p_n = a_n * p_{n-1} + p_{n-2}, where a_n is the nth coefficient in the
   regular continued fraction expansion of sqrt(351) (generated by the
   standard recursive algorithm). */

seq_t a(idx_t n)
{
    /* Special case for the first term. */
    if (n == (idx_t)0) return (seq_t)18;

    /* Constants for sqrt(351). */
    const idx_t D       = (idx_t)351;   /* D = 351 */
    const idx_t a0_int  = (idx_t)18;    /* floor(sqrt(351)) */

    /* Variables for the continued fraction algorithm. */
    idx_t m      = (idx_t)0;   /* m_0 */
    idx_t d      = (idx_t)1;   /* d_0 */
    idx_t a_prev = a0_int;     /* a_0 */

    /* Numerator recurrence. */
    seq_t prev2 = (seq_t)1;           /* p_{-1} */
    seq_t prev1 = (seq_t)a0_int;      /* p_0 */

    for (idx_t i = (idx_t)1; i <= n; ++i) {
        /* Generate next continued fraction coefficient a_i. */
        idx_t m_new = d * a_prev - m;
        idx_t d_new = (D - m_new * m_new) / d;
        idx_t a_curr = (a0_int + m_new) / d_new;

        /* Compute the numerator p_i. */
        seq_t p_curr = (seq_t)a_curr * prev1 + prev2;

        /* Shift for next iteration. */
        prev2 = prev1;
        prev1 = p_curr;

        /* Prepare for next step of the continued fraction. */
        a_prev = a_curr;
        m      = m_new;
        d      = d_new;
    }

    return prev1;   /* p_n = a(n) */
}
