/* Computes a(n) directly from the continued fraction of sqrt(206).
   No pre‑tabulated constants are used; the sequence is generated by
   the standard recurrence for convergents. */

#include <stdint.h>

seq_t a(idx_t n)
{
    /* Constants for sqrt(206) */
    const uint64_t S   = 206;      /* D in sqrt(D) */
    const uint64_t a0  = 14;       /* floor(sqrt(206)) */

    /* State for the continued fraction algorithm */
    uint64_t m = 0;                /* m_k */
    uint64_t d = 1;                /* d_k */
    uint64_t a_coef = a0;          /* a_k */

    /* Storage for the two previous denominators q_{k-2} and q_{k-1} */
    seq_t q_prev2 = (seq_t)1;      /* q_{-2} */
    seq_t q_prev1 = (seq_t)0;      /* q_{-1} */
    seq_t q = 0;                   /* current denominator q_k */

    for (idx_t i = 0; i <= n; ++i) {
        if (i > 0) {               /* advance the continued fraction */
            m      = d * a_coef - m;
            d      = (S - m * m) / d;
            a_coef = (a0 + m) / d;
        }
        /* Compute q_k = a_k * q_{k-1} + q_{k-2} */
        q = (seq_t)a_coef * q_prev1 + q_prev2;

        /* Shift the two previous values for the next step */
        q_prev2 = q_prev1;
        q_prev1 = q;
    }

    return q;                      /* a(n) is q_n */
}
