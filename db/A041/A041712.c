/* Numerators of continued fraction convergents to sqrt(376)
   (OEIS A041712)
   Computation is done by the standard recurrence:
       h[−1] = 1, h[0] = floor(sqrt(376)) = 19
       h[k] = a[k] * h[k−1] + h[k−2]
   where a[k] are the continued‑fraction coefficients of sqrt(376),
   generated by the usual recurrence
       m[0] = 0, d[0] = 1, a[0] = floor(sqrt(376))
       m[n+1] = d[n] * a[n] – m[n]
       d[n+1] = (376 – m[n+1]²) / d[n]
       a[n+1] = floor((a[0] + m[n+1]) / d[n+1])   */
/* This algorithm needs no hard‑coded terms beyond the initial
   coefficient a[0] and works for any n ≥ 0. */

#include <stdlib.h>

seq_t a(idx_t n) {
    /* static state for memoisation */
    static seq_t *cache = NULL;          /* array of computed numerators   */
    static size_t cache_len = 0;         /* current allocated capacity    */
    static idx_t computed_upto = 0;      /* highest n for which cache is set */

    /* continued‑fraction state (for generating next a[n]) */
    static seq_t m = 0, d = 1, a_coeff = 0;
    static seq_t prevprev = 1, prev = 0;   /* h[-1] = 1, h[0] = a0 will be set on first init */
    static int initialized = 0;           /* 0 → not yet initialised      */
    const seq_t D = (seq_t)376;
    const seq_t a0 = (seq_t)19;           /* floor(sqrt(376))           */

    if (!initialized) {
        /* initialise with the first term (k = 0) */
        prev = a0;                 /* h[0]                         */
        cache_len = (n < 32) ? 32 : (size_t)(n + 1);
        cache = (seq_t*)malloc(cache_len * sizeof(seq_t));
        cache[0] = a0;
        computed_upto = 0;
        /* set continued‑fraction state after term 0 */
        m = 0;
        d = 1;
        a_coeff = a0;                /* a[0] for the first iteration */
        initialized = 1;
    }

    /* Extend cache if needed */
    if (n > computed_upto) {
        /* Grow cache to accommodate n+1 entries */
        size_t new_len = cache_len;
        while (new_len <= (size_t)n) new_len <<= 1;
        cache = (seq_t*)realloc(cache, new_len * sizeof(seq_t));
        cache_len = new_len;

        /* Compute terms from computed_upto+1 up to n */
        for (idx_t i = computed_upto + 1; i <= n; ++i) {
            /* Generate next continued‑fraction coefficient a[i] */
            seq_t m_next = d * a_coeff - m;
            seq_t d_next = (D - (m_next * m_next)) / d;
            seq_t a_next = (a0 + m_next) / d_next;

            /* Compute next convergent numerator h[i] */
            seq_t h = a_next * prev + prevprev;

            /* Store and advance state */
            cache[i] = h;
            prevprev = prev;
            prev = h;
            m = m_next;
            d = d_next;
            a_coeff = a_next;
        }
        computed_upto = n;
    }

    return cache[n];
}
