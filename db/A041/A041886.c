/* Sequence A041886: Numerators of continued‑fraction convergents to sqrt(465)
   a(n) = numerator of the nth convergent of sqrt(465).
   The partial quotients a_k of sqrt(465) are generated by the standard
   continued‑fraction algorithm, and the numerators p_k satisfy
   p_{-2}=0, p_{-1}=1 and
   p_k = a_k·p_{k-1} + p_{k-2}. */
seq_t a(idx_t n)
{
    const idx_t D   = (idx_t)465;   /* D = 465 */
    const idx_t a0  = (idx_t)21;    /* floor(sqrt(465)) */

    idx_t a         = a0;  /* current partial quotient */
    idx_t m         = 0;   /* m_k in the CF algorithm */
    idx_t d         = 1;   /* d_k in the CF algorithm */

    seq_t p_nm2 = (seq_t)0;   /* p_{k-2}   */
    seq_t p_nm1 = (seq_t)1;   /* p_{k-1}   */
    seq_t p     = 0;

    for (idx_t i = 0; ; ++i)
    {
        seq_t ak = (seq_t)a;           /* current partial quotient a_k   */
        p = ak * p_nm1 + p_nm2;        /* compute p_k                    */

        if (i == n)
            return p;                 /* desired term found              */

        /* shift the recurrence window */
        p_nm2 = p_nm1;
        p_nm1 = p;

        /* generate next partial quotient a_{k+1} */
        idx_t m_next = d * a - m;
        idx_t d_next = (idx_t)((D - m_next * m_next) / d);
        idx_t a_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        a = a_next;
    }
}
