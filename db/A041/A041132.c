/* Numerators of continued‑fraction convergents to sqrt(75)
   (generated by the standard recurrence for quadratic surds):
   let p_{-2}=0, p_{-1}=1, a_0=8.
   For k≥1 compute the continued‑fraction coefficient a_k of sqrt(75)
   by the usual m,d recurrence, then
      p_k = a_k · p_{k-1} + p_{k-2}.
   The function returns p_n for index n. */
seq_t a(idx_t n)
{
    /* Base case: the first numerator is a0 = 8. */
    if (n == (idx_t)0)
        return (seq_t)8;

    /* Constants for sqrt(75). */
    const idx_t D   = 75;
    const idx_t a0  = 8;

    /* Continued‑fraction state: m, d and the previous coefficient a_{k-1}. */
    idx_t m      = 0;
    idx_t d      = 1;
    idx_t a_prev = a0;   /* a_{k-1} */

    /* Numerator recurrence state: p_{k-2} and p_{k-1}. */
    seq_t p_prevprev = (seq_t)1; /* p_{-1} */
    seq_t p_prev     = (seq_t)a0;  /* p_0 */

    for (idx_t k = (idx_t)1; k <= n; ++k)
    {
        /* Next continued‑fraction coefficient a_k. */
        m = d * a_prev - m;
        d = (D - m * m) / d;
        idx_t a_k = (a0 + m) / d;

        /* Numerator recurrence: p_k = a_k * p_{k-1} + p_{k-2}. */
        seq_t new_p = (seq_t)a_k * p_prev + p_prevprev;

        /* Shift counters for next iteration. */
        p_prevprev = p_prev;
        p_prev     = new_p;
        a_prev     = a_k;
    }
    return p_prev;
}
