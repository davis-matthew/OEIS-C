/*
 * A340916  Integers m that have at least one divisor d such that d+m/d is a
 *          substring of m.
 * https://oeis.org/A340916
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 48, u32 n <= 48, u64 n <= 48, u128 n <= 48,
 *            big any n
 * Helpers:   append_candidate, floor_sqrt, seq_to_str
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements OEIS A340916: numbers m that have a divisor d with
   d + m/d appearing as a decimal substring of m.
   The sequence is generated by brute‑force enumeration; terms are cached
   for subsequent calls.  For each m, all divisor pairs are checked. */

#include <stdbool.h>
#include <string.h>
#include "../utils/append_candidate.h"
#include "../utils/floor_sqrt.h"
#include "../utils/seq_to_str.h"

static seq_t *seq_cache = NULL;     /* cached terms */
static size_t cache_len = 0;        /* number of cached terms */
static size_t cache_cap = 0;        /* allocated capacity */
static seq_t next_m = (seq_t)4;     /* next integer to test */

/* check whether m satisfies the required property */
static bool has_divisor_condition(seq_t m)
{
    char mstr[128];
    size_t mlen;
    seq_to_str(m, mstr, &mlen);
    mstr[mlen] = '\0';

    seq_t sq_seq = floor_sqrt(m);
    idx_t sq = (idx_t)sq_seq;                 /* assume fits in idx_t */
    for (idx_t d = 1; d <= sq; ++d) {
        seq_t dseq = (seq_t)d;
        if (m % dseq == 0) {
            seq_t comp = m / dseq;
            seq_t sum  = dseq + comp;

            char sumstr[32];
            size_t sumlen;
            seq_to_str(sum, sumstr, &sumlen);
            sumstr[sumlen] = '\0';

            if (strstr(mstr, sumstr) != NULL)
                return true;
        }
    }
    return false;
}

/* public function required by the framework */
seq_t a(idx_t n)
{
    if (n == 0) return 0;               /* undefined for offset 1 */

    while (cache_len < n) {
        if (has_divisor_condition(next_m))
            append_candidate(&seq_cache, &cache_len, &cache_cap, next_m);
        next_m = (seq_t)(next_m + 1);
    }
    return seq_cache[n - 1];
}
