/*
 * A340916  Integers m that have at least one divisor d such that d+m/d is a
 *          substring of m.
 * https://oeis.org/A340916
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 48, u32 n <= 48, u64 n <= 48, u128 n <= 48,
 *            big any n
 * Validated: partial, pass, 48 terms through n = 48 (2026-11-03)
 * Helpers:   ipow_i32, mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements OEIS A340916: numbers m that have a divisor d with
   d + m/d appearing as a decimal substring of m.
   The sequence is generated by brute‑force enumeration; terms are cached
   for subsequent calls.  For each m, all divisor pairs are checked. */

#include <stdbool.h>
#include <string.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/ipow_i32.h"
#include "../utils/mem.h"

/* Append a value to the cached array, expanding it if necessary.  `p` is a
   pointer to the array pointer. */
static void append_candidate(seq_t **p, size_t *len, size_t *cap, seq_t val)
{
    if (*len == *cap) {
        size_t newcap = (*cap == 0) ? 16 : (*cap << 1);
        seq_t *tmp = mem_resize(seq_t, *p, newcap);
        if (!tmp) {
            exit(EXIT_FAILURE);
        }
        *p = tmp;
        *cap = newcap;
    }
    (*p)[*len] = val;
    (*len)++;
}

/* Floor square root by binary search */
static inline seq_t floor_sqrt(seq_t x)
{
    seq_t lo = 0, hi = 1;
    while (ipow_i32(hi, 2) <= x)
        hi <<= 1;
    while (lo < hi)
    {
        seq_t mid = (lo + hi) >> 1;
        seq_t mid2 = mid * mid;
        if (mid2 <= x)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

/* convert a seq_t value to a decimal string */
static void seq_to_str(seq_t v, char *buf, size_t *len)
{
    if (v == 0) {
        buf[0] = '0';
        *len = 1;
        return;
    }
    char tmp[64];
    int pos = 0;
    seq_t ten = (seq_t)10;
    while (v != 0) {
        tmp[pos++] = '0' + (int)(v % ten);
        v /= ten;
    }
    for (int i = 0; i < pos; ++i)
        buf[i] = tmp[pos - 1 - i];
    *len = pos;
}

static seq_t *seq_cache = NULL;     /* cached terms */
static size_t cache_len = 0;        /* number of cached terms */
static size_t cache_cap = 0;        /* allocated capacity */
static seq_t next_m = (seq_t)4;     /* next integer to test */

/* check whether m satisfies the required property */
static bool has_divisor_condition(seq_t m)
{
    char mstr[128];
    size_t mlen;
    seq_to_str(m, mstr, &mlen);
    mstr[mlen] = '\0';

    seq_t sq_seq = floor_sqrt(m);
    idx_t sq = (idx_t)sq_seq;                 /* assume fits in idx_t */
    for (idx_t d = 1; d <= sq; ++d) {
        seq_t dseq = (seq_t)d;
        if (m % dseq == 0) {
            seq_t comp = m / dseq;
            seq_t sum  = dseq + comp;

            char sumstr[32];
            size_t sumlen;
            seq_to_str(sum, sumstr, &sumlen);
            sumstr[sumlen] = '\0';

            if (strstr(mstr, sumstr) != NULL)
                return true;
        }
    }
    return false;
}

/* public function required by the framework */
seq_t a(idx_t n)
{
    if (n == 0) return 0;               /* undefined for offset 1 */

    while (cache_len < n) {
        if (has_divisor_condition(next_m))
            append_candidate(&seq_cache, &cache_len, &cache_cap, next_m);
        next_m = (seq_t)(next_m + 1);
    }
    return seq_cache[n - 1];
}
