/*
 * A340057  Irregular triangle read by rows T(n,k) in which row n lists n
 *          blocks, where the block m consists of the divisors of m multiplied
 *          by A000041(n-m), with 1 <= m <= n.
 * https://oeis.org/A340057
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 316, u16 n <= 2690, u32 n <= 9885, u64 n <= 9885,
 *            u128 n <= 9885, big any n
 * Helpers:   kth_divisor
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A340057 – Irregular triangle read by rows.
   The triangle is defined by the rule that row n contains 
   the blocks m=1..n; block m consists of the divisors of m 
   multiplied by the partition number p(n‑m).  This implementation
   computes the sequence by locating the appropriate row, block
   and divisor using pre‑computed cumulative counts.  Partitions
   are generated by the pentagonal recurrence using modulo
   arithmetic on the target integer type seq_t so that only
   values that genuinely fit in seq_t are required to be exact. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/kth_divisor.h"

#define MAX_ROWS 2000   /* sufficient for n ≈ few 10⁵ – 10⁶ */

static bool initialized = false;
static idx_t *div_count = NULL;   /* d[m] */
static idx_t *row_cum    = NULL;   /* cumulative divisors up to m in a row */
static idx_t *total_cum  = NULL;   /* cumulative terms up to row r */
static seq_t *partitions = NULL;   /* partition numbers  p(k) for k<MAX_ROWS */

/* --------------------------------------------------------------------- */
/* Compute partition numbers p(0)...p(MAX_ROWS-1) using pentagonal
   recurrence with modulo arithmetic on seq_t. */
static void compute_partitions(void) {
    partitions = (seq_t *)malloc(sizeof(seq_t) * (MAX_ROWS + 1));
    partitions[0] = (seq_t)1;        /* p(0) = 1 */
    for (idx_t n = 1; n < MAX_ROWS; ++n) {
        seq_t sum = 0;
        for (idx_t k = 1; ; ++k) {
            idx_t pent1 = (k * (3 * k - 1)) / 2;
            if (pent1 > n) break;
            if (k & 1) sum += partitions[n - pent1];
            else       sum -= partitions[n - pent1];

            idx_t pent2 = (k * (3 * k + 1)) / 2;
            if (pent2 <= n) {
                if (k & 1) sum += partitions[n - pent2];
                else       sum -= partitions[n - pent2];
            }
        }
        partitions[n] = sum;
    }
}

/* --------------------------------------------------------------------- */
/* Pre‑compute divisor counts, row cumulative sums, and total cumulative
   number of sequence terms. */
static void compute_divisors_and_cums(void) {
    div_count = (idx_t *)malloc(sizeof(idx_t) * (MAX_ROWS + 1));
    row_cum   = (idx_t *)malloc(sizeof(idx_t) * (MAX_ROWS + 1));
    total_cum = (idx_t *)malloc(sizeof(idx_t) * (MAX_ROWS + 1));

    div_count[0] = 0;
    for (idx_t i = 1; i <= MAX_ROWS; ++i) div_count[i] = 0;
    for (idx_t i = 1; i <= MAX_ROWS; ++i)
        for (idx_t j = i; j <= MAX_ROWS; j += i)
            ++div_count[j];

    row_cum[0]   = 0;
    total_cum[0] = 0;
    for (idx_t i = 1; i <= MAX_ROWS; ++i) {
        row_cum[i]   = row_cum[i - 1] + div_count[i];
        total_cum[i] = total_cum[i - 1] + row_cum[i];
    }
}

/* --------------------------------------------------------------------- */
/* Initialize static data once. */
static void init(void) {
    if (initialized) return;
    compute_divisors_and_cums();
    compute_partitions();
    initialized = true;
}

/* --------------------------------------------------------------------- */

/* --------------------------------------------------------------------- */
/* Main function required by the build system. */
seq_t a(idx_t n) {
    init();                          /* ensure tables are ready */

    /* Find the row r such that total_cum[r-1] < n <= total_cum[r]. */
    idx_t low = 1, high = MAX_ROWS;
    while (low < high) {
        idx_t mid = (low + high) >> 1;
        if (total_cum[mid] >= n)
            high = mid;
        else
            low = mid + 1;
    }
    idx_t row = low;
    idx_t prev_total = (row > 1) ? total_cum[row - 1] : 0;
    idx_t pos_in_row = n - prev_total; /* 1‑based position within the row */

    /* Locate the block m within the row. */
    low = 1; high = row;
    while (low < high) {
        idx_t mid = (low + high) >> 1;
        if (row_cum[mid] >= pos_in_row)
            high = mid;
        else
            low = mid + 1;
    }
    idx_t block = low;
    idx_t prev_row_cum = (block > 1) ? row_cum[block - 1] : 0;
    idx_t offset = pos_in_row - prev_row_cum - 1; /* 0‑based inside block */

    idx_t divisor = kth_divisor(block, offset);
    idx_t part_index = row - block;              /* p(row‑block) */

    seq_t result = (seq_t)divisor * partitions[part_index];
    return result;
}
