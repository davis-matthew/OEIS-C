/* A340077: odd numbers k for which (k-1) is a multiple of the odd part of φ(k) */
/* The sequence is generated by searching odd numbers and testing the condition.
   The function caches found terms so that calls in arbitrary order are efficient. */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/odd_part.h"
#include "../utils/totient.h"
#include "../utils/mem.h"

/* --- dynamic array helpers ------------------------------------------- */
static void grow_seq(seq_t **arr, size_t *cap, size_t need)
{
    if (*cap < need) {
        size_t new_cap = (*cap == 0) ? 64 : (*cap << 1);
        while (new_cap < need) new_cap <<= 1;
        seq_t *tmp = mem_resize(seq_t, *arr, (new_cap * sizeof(**arr)) / sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);
        *arr = tmp;
        *cap = new_cap;
    }
}

seq_t a(idx_t n) {
    /* static cache of found terms */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;
    static idx_t last_checked = 1;   /* last odd number examined (1 initially) */

    /* initialise cache with the first term */
    if (cache_len == 0) {
        grow_seq(&cache, &cache_cap, 1);
        cache[0] = (seq_t)1;
        cache_len = 1;
    }

    /* generate terms until we have at least n of them */
    while (cache_len < n) {
        /* next odd candidate */
        idx_t cand = last_checked + 2;

        /* compute phi(cand) and its odd part */
        seq_t phi_val      = totient(cand);          /* phi of the candidate (may be large) */
        seq_t odd_part_val = odd_part(phi_val);  /* odd part of phi(cand) */

        idx_t diff         = cand - (idx_t)1;    /* cand-1, as idx_t for modulo */
        idx_t odd_part_idx = (idx_t)odd_part_val;/* cast to idx_t for modulo */

        /* check the divisibility condition */
        if (odd_part_idx != 0 && (diff % odd_part_idx) == 0) {
            /* ensure enough capacity */
            if (cache_len == cache_cap) {
                grow_seq(&cache, &cache_cap, cache_len + 1);
            }
            cache[cache_len++] = (seq_t)cand;
        }

        last_checked = cand;
    }

    return cache[n - 1];
}
