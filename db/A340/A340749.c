/* A340749:  Fermat weak pseudoprimes k.
   A number k is included if there exists a proper divisor d (1 < d < k)
   with d^k ≡ d (mod k).  The function returns the n‑th such k
   (a(1) = 6).  The sequence is generated by testing every integer
   ≥ 6 until the desired index is reached; a simple trial division
   factorisation is used to enumerate all proper divisors. */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

#include "../utils/mod_pow.h"     /* seq_t mod_pow(seq_t base, uint64_t exp, seq_t mod); */
#include "../utils/is_prime.h"    /* bool is_prime(idx_t n); */
#include "../utils/seq_alloc.h"   /* seq_t *seq_alloc(size_t cap); */
#include "../utils/seq_realloc.h" /* seq_t *seq_realloc(seq_t *old, size_t old_cap, size_t new_cap); */

/* Factorise a 64‑bit integer into primes and exponents.  The arrays
   must be large enough to hold the factors.  The number of distinct
   prime factors is returned in *cnt. */
static void factor_uint64(uint64_t n, uint64_t *primes, int *exps, int *cnt)
{
    int c = 0;
    uint64_t d = 2;
    while (d * d <= n) {
        if (n % d == 0) {
            int e = 0;
            while (n % d == 0) {
                n /= d;
                ++e;
            }
            primes[c] = d;
            exps[c] = e;
            ++c;
        }
        ++d;
    }
    if (n > 1) {
        primes[c] = n;
        exps[c] = 1;
        ++c;
    }
    *cnt = c;
}

/* Recursively test all proper divisors of k by generating them
   from the prime factorisation.  If any divisor d satisfies
   d^(k-1) ≡ 1 (mod k/d) the function returns true. */
static bool has_valid_divisor(uint64_t k,
                              const uint64_t *pr,
                              const int *ex,
                              int fc,
                              int idx,
                              uint64_t cur)
{
    if (idx == fc) {
        if (cur <= 1 || cur >= k)           /* proper divisor only */
            return false;
        uint64_t m = k / cur;
        seq_t r = mod_pow((seq_t)cur, (uint64_t)(k - 1), (seq_t)m);
        return r == (seq_t)1;
    }
    uint64_t val = cur;
    for (int e = 0; e <= ex[idx]; ++e) {
        if (has_valid_divisor(k, pr, ex, fc, idx + 1, val))
            return true;
        val *= pr[idx];
    }
    return false;
}

/* Return the n‑th term of A340749 (n ≥ 1). */
seq_t a(idx_t n)
{
    static seq_t *cache     = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;
    static uint64_t next_k   = 6;   /* first candidate number */

    if (cache == NULL) {
        cache_cap = 128;
        cache = seq_alloc(cache_cap);
    }

    /* Extend cache until it contains at least n terms. */
    while (cache_len < (size_t)n) {
        /* Skip primes – no proper divisor other than 1 and the number itself. */
        while (is_prime((idx_t)next_k))
            ++next_k;

        uint64_t primes[16];
        int      exps  [16];
        int      fc;
        factor_uint64(next_k, primes, exps, &fc);

        if (has_valid_divisor(next_k, primes, exps, fc, 0, 1)) {
            if (cache_len >= cache_cap) {
                size_t new_cap = cache_cap * 2;
                seq_t *tmp = seq_realloc(cache, cache_cap, new_cap);
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = (seq_t)next_k;
        }
        ++next_k;
    }

    return cache[n - 1];
}
