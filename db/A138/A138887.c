/*
 * A138887  Numbers that are not Sophie Germain primes.
 * https://oeis.org/A138887
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 67, u16 n <= 67, u32 n <= 67, u64 n <= 67, u128 n <= 67,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A138887: numbers that are not Sophie Germain primes.
   a(0) = 0; a(1) = 1; a(n) = the nth nonnegative integer that is not a
   Sophie Germain prime.  The sequence is generated by testing each
   integer, starting from 0, for the Sophie Germain property
   (prime p and 2p+1 prime).  Integers that are not SG primes are
   stored and returned.  Results are memoised so that any call order
   requires at most a single linear scan up to the largest index
   requested. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"

static seq_t *cache = NULL;   /* stored non‑SG primes */
static size_t cache_len = 0;  /* number of stored values      */
static size_t cache_cap = 0;  /* allocated capacity           */
static seq_t current = 0;     /* next integer to test         */

/* Ensure the cache holds at least 'needed' elements. */
static void ensure_cache_capacity(size_t needed)
{
    if (cache_cap >= needed)
        return;
    size_t new_cap = cache_cap ? cache_cap << 1 : 16;
    while (new_cap < needed)
        new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp)
        exit(1);            /* out of memory */
    cache = tmp;
    cache_cap = new_cap;
}

/* Test whether a given non‑negative integer p is a Sophie Germain prime.
   This requires checking primality of p and of 2p+1.  The helper function
   is_prime_big works for both builtin and arbitrary‑precision types. */
static bool is_sophie_germain(const seq_t *p)
{
    if (!is_prime_big(*p))
        return false;
    seq_t q = (seq_t)2 * (*p) + 1;
    return is_prime_big(q);
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    /* Grow the cache until it contains at least n+1 values. */
    while (cache_len <= n)
    {
        /* Test the current integer. */
        if (!is_sophie_germain(&current))
        {
            /* Store if not a Sophie Germain prime. */
            ensure_cache_capacity(cache_len + 1);
            cache[cache_len++] = current;
        }
        /* Advance to the next integer. */
        current++;
    }
    return cache[(size_t)n];
}
