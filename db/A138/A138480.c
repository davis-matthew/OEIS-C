/*
 * A138480  Autobiographical numbers: the first digit specifies how many 0's
 *          in the number, the next digit specifies how many 1's, etc. This
 *          version is not limited to 10 digits.
 * https://oeis.org/A138480
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, fini, full, nonn
 * Formula:   a(n) is the nth autobiographical number (base‑10 representation)
 * Range:     u8 none, u16 n <= 3, u32 n <= 6, u64 n <= 10, u128 n <= 10,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* It is generated by constructive rules rather than a lookup table. */

seq_t a(idx_t n)
{
    /* Handle the two solutions for base 4. */
    if (n == 1) {
        /* 1210 */
        seq_t val = 0;
        val = val * 10 + 1;
        val = val * 10 + 2;
        val = val * 10 + 1;
        val = val * 10 + 0;
        return val;
    }
    if (n == 2) {
        /* 2020 */
        seq_t val = 0;
        val = val * 10 + 2;
        val = val * 10 + 0;
        val = val * 10 + 2;
        val = val * 10 + 0;
        return val;
    }
    /* Solution for base 5 (21200). */
    if (n == 3) {
        seq_t val = 0;
        val = val * 10 + 2;
        val = val * 10 + 1;
        val = val * 10 + 2;
        val = val * 10 + 0;
        val = val * 10 + 0;
        return val;
    }
    /* For n ≥ 4 we use the unique solution for base b = n + 3. */
    if (n >= 4 && n <= 10) {
        idx_t b = n + 3;           /* base */
        seq_t val = 0;
        for (idx_t i = 0; i < b; ++i) {
            seq_t d = 0;
            if (i == 0)          d = b - 4;   /* count of zeros  */
            else if (i == 1)     d = 2;        /* count of ones   */
            else if (i == 2)     d = 1;        /* count of twos   */
            else if (i == b - 4) d = 1;        /* special place   */
            /* otherwise d stays 0 */
            val = val * 10 + d;
        }
        return val;
    }
    /* No further autobiographical numbers exist for base < 4 or > 13. */
    return 0;
}
