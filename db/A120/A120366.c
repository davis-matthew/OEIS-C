/*
 * A120366  Primes p such that p-1 is not a multiple of 3, 4 or 5.
 * https://oeis.org/A120366
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 11, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A120366: primes p such that p-1 is not a multiple of 3, 4 or 5.
   The sequence is generated by a simple incremental prime test and
   caching of the qualifying primes.  This implementation works for
   both fixed‑width unsigned integer seq_t and for arbitrary‑precision
   seq_t builds. */
#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

/*----- helpers for dynamic uint64_t arrays -----*/
static void
ensure_uint64_cap(uint64_t **arr, size_t *cap, size_t needed)
{
    if (needed > *cap) {
        size_t new_cap = *cap ? *cap << 1 : 1;
        while (new_cap < needed)
            new_cap <<= 1;
        uint64_t *tmp = (uint64_t *)realloc(*arr, new_cap * sizeof(uint64_t));
        *arr = tmp;
        *cap = new_cap;
    }
}

/*----- small prime list: all primes discovered so far -----*/
static uint64_t *prime_list = NULL;
static size_t prime_cnt   = 0;
static size_t prime_cap   = 0;

/*----- list of filtered primes satisfying the OEIS condition -----*/
static uint64_t *filtered = NULL;
static size_t filtered_cnt = 0;
static size_t filtered_cap = 0;

/*----- next candidate to test for primality -----*/
static uint64_t next_candidate = 2;

/*----- primality test using trial division by stored primes -----*/
static bool
is_prime_uint64(uint64_t n)
{
    if (n < 2) return false;
    for (size_t i = 0; i < prime_cnt; ++i) {
        uint64_t p = prime_list[i];
        if (p > n / p)        /* p*p > n → stop */
            break;
        if (n % p == 0)
            return false;
    }
    /* n is prime – store it */
    ensure_uint64_cap(&prime_list, &prime_cap, prime_cnt + 1);
    prime_list[prime_cnt++] = n;
    return true;
}

/*----- main sequence function -----*/
seq_t a(idx_t n)
{
    /* Offset 1: ignore n == 0 */
    if (n == 0)
        return 0;

    size_t target = (size_t)n;

    /* Expand the filtered list until we have `target` elements */
    while (filtered_cnt < target) {
        uint64_t cand = next_candidate;

        /* Advance for the next iteration */
        if (cand == 2)
            next_candidate = 3;
        else
            next_candidate = cand + 2;        /* skip evens after 2 */

        /* Test primality */
        if (is_prime_uint64(cand)) {
            /* Apply the OEIS filter: (p-1) must not be divisible by 3,4,5 */
            if ((cand - 1) % 3 && (cand - 1) % 4 && (cand - 1) % 5) {
                ensure_uint64_cap(&filtered, &filtered_cap, filtered_cnt + 1);
                filtered[filtered_cnt++] = cand;
            }
        }
    }

    /* Convert to seq_t – this works for both integer and arbitrary‑precision seq_t */
    return (seq_t)filtered[target - 1];
}
