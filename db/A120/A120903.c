/*
 * A120903  Triangle T, read by rows, that satisfies matrix equation: T +
 *          (T-I)^2 = C, where C is Pascal's triangle.
 * https://oeis.org/A120903
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  sign, tabl
 * Formula:   not stated
 * Range:     i8 n <= 14, i16 n <= 27, i32 n <= 54, i64 n <= 56, i128 n <= 56,
 *            big any n
 * Helpers:   binom
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS Sequence A120903
   Formula: Let T(n,k) be the triangle entry at row n, column k (0‑based).
   Let h_d be defined by
      h_0 = 1
      h_d = 1 - Σ_{k=1}^{d-1} C(d,k) * h_k * h_{d-k}   (d ≥ 1)
   Then
      T(n,k) = C(n,k) * h_{n-k}
   The sequence a(n) is the triangle read by rows, i.e.
      a(n) = T(r,c)  where r is the row containing the nth element.
   For example: a(0)=1, a(1)=1, a(2)=1, a(3)=-1, a(4)=2, a(5)=1, …
   (All other terms are generated by the same rule.)
   The implementation below uses the provided binom utility function
   and caches the h_d values for efficiency.  The code is pure C11
   and also compiles as C++17.  No floating point operations are used. */

#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/binom.h"   /* seq_t binom(idx_t a, idx_t b) */

/* Return the row r (0‑based) such that r*(r+1)/2 ≤ n < (r+1)*(r+2)/2. */
static idx_t row_of(idx_t n) {
    idx_t r = 0;
    while (((r + 1) * (r + 2)) / 2 <= n)
        ++r;
    return r;
}

/* Cache for the h_d values. */
static seq_t *h_cache = NULL;
static idx_t h_cache_size = 0;

/* Ensure that h_cache holds values up to max_d. */
static void ensure_h_cache(idx_t max_d) {
    if (max_d < h_cache_size)
        return;

    idx_t new_size = max_d + 1;
    seq_t *new_cache = (seq_t *)realloc(h_cache, new_size * sizeof(seq_t));
    if (!new_cache)
        abort();    /* allocation failure */
    h_cache = new_cache;

    /* Initialize entries. */
    idx_t start = h_cache_size == 0 ? 1 : h_cache_size;
    if (h_cache_size == 0)
        h_cache[0] = 1;   /* h_0 = 1 */

    for (idx_t d = start; d <= max_d; ++d) {
        seq_t sum = 0;
        for (idx_t k = 1; k < d; ++k) {
            seq_t term = binom(d, k);
            term *= h_cache[k];
            term *= h_cache[d - k];
            sum += term;
        }
        h_cache[d] = 1 - sum;   /* h_d = 1 - Σ C(d,k)h_kh_{d-k} */
    }
    h_cache_size = new_size;
}

/* Public sequence function. */
seq_t a(idx_t n) {
    /* Find (row,column) coordinates for linear index n. */
    idx_t r = row_of(n);
    idx_t start_index = r * (r + 1) / 2;
    idx_t c = n - start_index;
    idx_t d = r - c;            /* difference n-k */

    ensure_h_cache(d);
    seq_t bin = binom(r, c);
    seq_t result = bin * h_cache[d];
    return result;
}
