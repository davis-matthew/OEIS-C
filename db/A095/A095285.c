/*
 * A095285  Primes in whose binary expansion the number of 1 bits is <= 5 +
 *          number of 0 bits.
 * https://oeis.org/A095285
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 49, u16 n <= 56, u32 n <= 56, u64 n <= 56, u128 n <= 56,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) is the nth prime whose binary expansion contains at most
   5 plus the number of 0‑bits.
   The sequence is generated by trial‑division search;  a(1)=2, a(2)=3, … */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* Test whether a 64‑bit integer is prime (trial division). */
static bool isPrimeUint64(uint64_t n)
{
    if (n < 2)            return false;
    if (n % 2 == 0)       return n == 2;
    for (uint64_t d = 3; d * d <= n; d += 2)
        if (n % d == 0)   return false;
    return true;
}

/* Check the OEIS condition for a prime p. */
static bool qualifies(uint64_t p)
{
    /* number of 1‑bits */
    unsigned int ones  = __builtin_popcountll(p);
    /* total number of bits in the binary representation */
    unsigned int len   = 64 - __builtin_clzll(p);
    /* number of 0‑bits (len includes the leading 1) */
    unsigned int zeros = len - ones;
    return ones <= 5 + zeros;
}

/* Return the nth qualifying prime (1‑based). */
seq_t a(idx_t n)
{
    if (n < 1) return 0;   /* undefined for n == 0, but harmless */

    uint64_t count = 0;
    uint64_t candidate = 2;   /* start at the first prime */

    while (true)
    {
        if (isPrimeUint64(candidate) && qualifies(candidate))
        {
            ++count;
            if (count == (uint64_t)n)
            {
                return (seq_t)candidate;
            }
        }

        /* advance to next candidate: 2 → 3, then skip evens */
        if (candidate == 2) candidate = 3;
        else                ++candidate;   /* only odd numbers are tested */
    }
}
