/*
 * A095786  Values of n for which A095777(n) is 17 (those terms which are
 *          expressible in decimal digits for bases 2 through 18, but not for
 *          base 19).
 * https://oeis.org/A095786
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn, more
 * Formula:   a(n) = the nth integer n for which, for every base b = 10 … 18,
 *            the representation of n in base b uses only decimal digits
 *            (0–9), and the representation in base 19 contains at least one
 *            digit ≥ 10
 * Range:     u8 n <= 1, u16 n <= 5, u32 n <= 5, u64 n <= 5, u128 n <= 5,
 *            big any n
 * Helpers:   decimal_digits_only, not_all_decimal_in_base19
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The values are generated by a simple exhaustive search with memoisation. */
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/decimal_digits_only.h"
#include "../utils/not_all_decimal_in_base19.h"

/* Static cache of already found terms */
static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;
static seq_t next_candidate = 1;

static void ensure_cache(size_t needed)
{
    if (needed <= cache_cap) return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
    while (new_cap < needed) new_cap *= 2;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp) { abort(); }
    cache = tmp;
    cache_cap = new_cap;
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;                       /* undefined for offset 0 */
    /* Generate terms until we have at least n of them */
    while (cache_len < (size_t)n) {
        seq_t val = next_candidate;
        bool ok = true;

        /* Check bases 10 through 18 */
        for (int b = 10; b <= 18; ++b) {
            if (!decimal_digits_only(val, b)) {
                ok = false;
                break;
            }
        }

        /* If ok so far, ensure base 19 fails (has a non‑decimal digit) */
        if (ok && not_all_decimal_in_base19(val)) {
            ensure_cache(cache_len + 1);
            cache[cache_len++] = val;
        }

        next_candidate++;
    }
    return cache[n - 1];
}
