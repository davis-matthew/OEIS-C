/*
 * A297570  Number of nonisomorphic proper colorings of partition star graph
 *          using six colors.
 * https://oeis.org/A297570
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 23, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A297570:
   Number of nonisomorphic proper colorings of a partition star graph 
   using six colors.  Each term corresponds to one integer partition.
   The partitions are listed by summing their parts in non‑decreasing 
   order of the first part (i.e. smaller first part first), which
   is the left‑to‑right traversal of each antichain in Young’s lattice.
   For a partition λ = (p_1^v1, p_2^v2, ...) the value is

      a(λ) = 6 * Π_{p^v in λ} C(5^p + v − 1, v)

   where C(n, k) is the binomial coefficient.  The sequence
   is generated by enumerating all integer partitions in the above
   order and computing the value for each partition. */

#include <stddef.h>
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Constants */
#define MAX_PARTS 100   /* sufficient for sums needed up to n≈10000 */

/* --- Utility: 5^p ---------------------------------------------- */
static seq_t pow5(idx_t p)
{
    seq_t r = (seq_t)1;
    while (p) {
        r *= (seq_t)5;
        --p;
    }
    return r;
}

/* --- Binomial C(a, v) computed multiplicatively ------------------ */
static seq_t binom_seq(seq_t a, idx_t v)
{
    if (v == (idx_t)0) return (seq_t)1;
    seq_t res = (seq_t)1;
    for (idx_t i = (idx_t)1; i <= v; ++i) {
        seq_t num = a - (seq_t)(v - i);
        res = (res * num) / (seq_t)i;
    }
    return res;
}

/* --- Partition enumeration --------------------------------------- */
static idx_t  parts[MAX_PARTS];   /* current partition being built           */
static seq_t *cache   = NULL;     /* cached values up to current index      */
static size_t cache_size = 0;     /* number of stored terms                 */
static size_t cache_cap  = 0;     /* allocated capacity                     */
static idx_t  next_sum_to_generate = 0;  /* next integer sum to process */

/* Ensure the cache can hold at least `needed` terms. */
static void ensure_cache_capacity(size_t needed)
{
    if (needed <= cache_cap) return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 8;
    while (new_cap < needed) new_cap *= 2;
    seq_t *tmp = (seq_t*)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();
    cache = tmp;
    cache_cap = new_cap;
}

/* Recursive generation of partitions of `rem` with parts <= `max_part`. */
static void rec_partitions(idx_t rem, idx_t max_part, idx_t depth)
{
    if (rem == (idx_t)0) {
        /* compute value for this partition */
        seq_t prod = (seq_t)6;          /* the factor k = 6          */
        idx_t i = 0;
        while (i < depth) {
            idx_t p = parts[i];
            idx_t v = 1;
            ++i;
            while (i < depth && parts[i] == p) { ++v; ++i; }
            seq_t power = pow5(p);                     /* 5^p                     */
            seq_t a = power + (seq_t)(v - 1);          /* (k-1)^p + v − 1         */
            seq_t bin = binom_seq(a, v);               /* C(a, v)                  */
            prod *= bin;
        }
        ensure_cache_capacity(cache_size + 1);
        cache[cache_size++] = prod;
        return;
    }

    idx_t limit = rem < max_part ? rem : max_part;
    for (idx_t p = (idx_t)1; p <= limit; ++p) {
        parts[depth] = p;
        rec_partitions(rem - p, p, depth + 1);
    }
}

/* Generate all partitions of the integer `sum`. */
static void generate_partitions_of_sum(idx_t sum)
{
    if (sum == (idx_t)0) {
        /* The empty partition (sum 0) yields value 6. */
        ensure_cache_capacity(cache_size + 1);
        cache[cache_size++] = (seq_t)6;
    } else {
        rec_partitions(sum, sum, 0);
    }
}

/* Fill the cache until it contains the term at index `n`. */
static void fill_to(idx_t n)
{
    while (cache_size <= n) {
        generate_partitions_of_sum(next_sum_to_generate++);
    }
}

/* --------------------------------------------------------------- */
/* Public function required by the framework. */
seq_t a(idx_t n)
{
    fill_to(n);
    return cache[n];
}
