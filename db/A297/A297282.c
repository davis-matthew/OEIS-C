/*
 * A297282  Numbers whose base-14 digits have greater down-variation than
 *          up-variation; see Comments.
 * https://oeis.org/A297282
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 96, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation: a(n) = the n‑th integer that has greater down‑variation
   than up‑variation in base 14.
   For a number x in base 14 let the digits be d0 (least significant),
   d1, …, dk (most significant). The down‑variation DV is the sum of
   differences d_i – d_{i-1} for all i with d_i > d_{i-1};
   the up‑variation UV is the sum of differences d_{i-1} – d_i for all
   i with d_i < d_{i-1}. The number qualifies when DV > UV.
   The sequence is generated by testing successive integers starting at
   14 and selecting the first n that satisfy this property. */

#include <stdbool.h>

static inline bool has_greater_down_variation(seq_t num)
{
    if (num == 0) return false; /* single digit numbers < 14 never join the sequence */

    seq_t prev = num % 14;      /* least significant digit */
    num /= 14;
    seq_t dv = 0;
    seq_t uv = 0;

    while (num != 0)
    {
        seq_t cur = num % 14;
        if (cur > prev)
            dv += cur - prev;
        else if (cur < prev)
            uv += prev - cur;
        prev = cur;
        num /= 14;
    }
    return dv > uv;
}

seq_t a(idx_t n)
{
    /* The OEIS offset is 1: a(1) == 14. */
    idx_t count = 0;
    seq_t cur = 14;          /* first candidate */
    while (1)
    {
        if (has_greater_down_variation(cur))
        {
            ++count;
            if (count == n)
                return cur;
        }
        ++cur;               /* next integer */
    }
}
