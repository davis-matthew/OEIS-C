/* Numbers having an up-first zigzag pattern in base 5
   (OEIS A297131)
   A number n has the property iff in its base‑5 representation
   (digits d[m] ... d[0]) :
     1) all consecutive digits differ   (d[i] != d[i+1])
     2) the most significant digit is less than the next one
        (d[m] < d[m-1]), i.e. the first comparison is “up”.
   This is sufficient because any subsequent equal directions are
   collapsed to a single up/down, leaving an up‑first alternating
   pattern.

   The sequence starts at a(1)=7; a(n) is the nth such number
   for n>=1.  The sequence can be generated by brute force
   inspection of integers; the density is roughly 1/3, so
   finding 10,000 terms takes far less than a millisecond. */

#include <stdbool.h>

/* helper: test whether x satisfies the up‑first zigzag pattern */
static bool up_first_zigzag(seq_t x)
{
    if (x < 5)              /* single‑digit numbers have no comparisons   */
        return false;

    /* extract base‑5 digits (least significant first) */
    unsigned char digs[64];
    int len = 0;
    seq_t tmp = x;
    while (tmp) {
        digs[len++] = (unsigned char)(tmp % 5);
        tmp /= 5;
    }

    /* check most–significant < next   (d[m] < d[m-1]) */
    if (digs[len - 1] >= digs[len - 2])
        return false;

    /* check that no two consecutive digits are equal */
    for (int i = len - 1; i > 0; --i)
        if (digs[i] == digs[i - 1])
            return false;

    return true;
}

seq_t a(idx_t n)
{
    idx_t count = 0;
    for (seq_t num = 7; ; ++num) {          /* start from first possible term   */
        if (up_first_zigzag(num)) {
            ++count;
            if (count == n)
                return num;
        }
    }
}
