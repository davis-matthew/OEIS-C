/*
 * A297837  Solution of the complementary equation a(n) = a(1)*b(n-1) -
 *          a(0)*b(n-2) + 4*n, where a(0) = 1, a(1) = 2, b(0) = 3, b(1) = 4,
 *          and (b(n)) is the increasing sequence of positive integers not in
 *          (a(n)). See Comments.
 * https://oeis.org/A297837
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 48, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   ensure_buf
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Complementary sequences a(n) and b(n) generated by
   a(0)=1, a(1)=2, b(0)=3, b(1)=4 and
   a(n) = 2*b(n-1) - b(n-2) + 4*n   (n ≥ 2).
   The sequence a(n) is returned by the function a(idx_t n).  */

/* dependencies: external types seq_t and idx_t, arbitrary‑precision or
   unsigned integer types.  All computations are performed with the
   arithmetic operators allowed for seq_t. */
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>
#include "../utils/ensure_buf.h"

/* ---------- static storage ---------- */
static seq_t *a_buf = NULL;
static size_t a_cap = 0;
static idx_t  a_len = 0;

static seq_t *b_buf = NULL;
static size_t b_cap = 0;
static idx_t  b_len = 0;

static bool *present = NULL;
static idx_t present_cap = 0;
static idx_t cand = 1;   /* next candidate for b(n) */

/* ---------- helper functions ---------- */

/* Ensure that 'present' can index the value 'val'. */
static void ensure_present(idx_t val)
{
    if (val < present_cap)
        return;
    idx_t new_cap = present_cap ? present_cap << 1 : 2;
    while (new_cap <= val)
        new_cap <<= 1;
    bool *tmp = (bool *)realloc(present, new_cap * sizeof(bool));
    if (!tmp)
        exit(1);
    memset(tmp + present_cap, 0, (new_cap - present_cap) * sizeof(bool));
    present = tmp;
    present_cap = new_cap;
}

/* One‑time initialization of the static data structures. */
static void init_global(void)
{
    if (a_buf != NULL) /* already initialised */
        return;

    a_buf = (seq_t *)calloc(4, sizeof(seq_t));
    b_buf = (seq_t *)calloc(4, sizeof(seq_t));
    present = (bool *)calloc(10, sizeof(bool));
    if (!a_buf || !b_buf || !present)
        exit(1);

    a_cap = b_cap = 4;
    present_cap = 10;

    /* initial values a(0), a(1), b(0), b(1) */
    a_buf[0] = (seq_t)1;   present[1] = true;   a_len = 1;
    a_buf[1] = (seq_t)2;   present[2] = true;   a_len = 2;

    b_buf[0] = (seq_t)3;   present[3] = true;   b_len = 1;
    b_buf[1] = (seq_t)4;   present[4] = true;   b_len = 2;

    /* next candidate for b(n) */
    cand = 5;
}

/* ---------- public interface ---------- */
seq_t a(idx_t n)
{
    init_global();

    if (n >= a_cap)
        ensure_buf(n + 1, &a_buf, &a_cap, &a_len);
    if (n >= b_cap)
        ensure_buf(n + 1, &b_buf, &b_cap, &b_len);

    for (idx_t i = a_len; i <= n; ++i) {
        /* compute a(i) from the recurrence */
        seq_t val_a = (seq_t)2 * b_buf[i - 1] - b_buf[i - 2] + (seq_t)4 * (seq_t)i;
        a_buf[i] = val_a;
        ++a_len;

        /* mark this value as present */
        if ((idx_t)(val_a) >= present_cap)
            ensure_present((idx_t)(val_a));
        present[(idx_t)(val_a)] = true;

        /* find next unused integer for b(i) */
        while (true) {
            if (cand >= present_cap)
                ensure_present(cand);
            if (!present[cand])
                break;
            ++cand;
        }
        seq_t val_b = (seq_t)cand;
        b_buf[i] = val_b;
        ++b_len;
        present[(idx_t)(val_b)] = true;
        ++cand;
    }

    return a_buf[n];
}
