/*
 * A363057  Run lengths of the Fibonacci word (A003849).
 * https://oeis.org/A363057
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 9896, u16 n <= 9896, u32 n <= 9896, u64 n <= 9896,
 *            u128 n <= 9896, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Run‐lengths of the infinite Fibonacci word.
   The word is generated by substitution 0→01, 1→0.
   This function produces the n‑th run length. */

#include <stdlib.h>

/* Assume seq_t and idx_t are defined by the build. */
static seq_t *run_buf = NULL;          /* stored run lengths */
static size_t  run_cap = 0;            /* capacity of run_buf         */
static size_t  run_cnt = 0;            /* number of runs computed     */

static char  *fib  = NULL;            /* current Fibonacci word      */
static size_t fib_len  = 0;            /* length of fib               */
static size_t fib_pos  = 0;            /* next bit to read from fib   */

static int run_started = 0;            /* flag if a run has begun      */
static char last_bit  = 0;             /* last bit seen                */
static size_t current_run_len = 0;      /* length of current run        */

/* Allocate/extend the run length buffer. */
static void ensure_run_capacity(void)
{
    if (run_cnt >= run_cap) {
        size_t new_cap = run_cap == 0 ? 256 : run_cap * 2;
        seq_t *tmp = (seq_t *)realloc(run_buf, new_cap * sizeof(seq_t));
        if (!tmp) abort(); /* memory error – terminate */
        run_buf = tmp;
        run_cap = new_cap;
    }
}

/* Extend the Fibonacci word until it has at least 'min_len' bits. */
static void extend_fib(void)
{
    /* avoid constant reallocation by doubling each time */
    while (fib_len <= fib_pos) {
        /* compute new string by substitution 0->01, 1->0 */
        size_t new_cap = fib_len * 3 + 10;
        char *new_fib = (char *)malloc(new_cap);
        if (!new_fib) abort(); /* memory error */
        size_t pos = 0;
        for (size_t i = 0; i < fib_len; ++i) {
            if (fib[i] == '0') {
                new_fib[pos++] = '0';
                new_fib[pos++] = '1';
            } else { /* fib[i] == '1' */
                new_fib[pos++] = '0';
            }
        }
        free(fib);
        fib = new_fib;
        fib_len = pos;
    }
}

/* Initialize the static state. */
static void init_state(void)
{
    fib = (char *)malloc(2);   /* at least one char + nul */
    if (!fib) abort();
    fib[0] = '0';
    fib[1] = '\0';
    fib_len = 1;
    fib_pos = 0;
    run_started = 0;
    run_cnt = 0;
    run_cap = 0;
    current_run_len = 0;
}

/* Main function requested by the harness. */
seq_t a(idx_t n)
{
    if (n == 0) return 0; /* 0 is undefined; return 0 as safe fallback */

    if (fib == NULL) init_state();

    size_t target = (size_t)n;

    while (run_cnt < target) {
        /* Ensure we have more bits to read. */
        if (fib_pos >= fib_len) extend_fib();

        /* Process bits until we finish at least one more run or reach the target. */
        for (;; ++fib_pos) {
            if (fib_pos >= fib_len) break;        /* need more bits */
            if (run_cnt >= target) break;          /* already enough runs */
            char bit = fib[fib_pos];
            if (!run_started) {                    /* first bit overall */
                last_bit = bit;
                current_run_len = 1;
                run_started = 1;
                continue;
            }
            if (bit == last_bit) {
                ++current_run_len;
            } else {
                /* finish current run */
                ensure_run_capacity();
                run_buf[run_cnt++] = (seq_t)current_run_len;
                last_bit = bit;
                current_run_len = 1;
            }
        }
    }

    /* Return the requested run length. */
    return run_buf[target - 1];
}
