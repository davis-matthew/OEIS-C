/* Sequence A363584:  lexicographically least sequence of distinct
   positive integers with the following restriction:
   If 1 <= k <= a(m) then either a(m+k) < a(m) or a(m+k) > 2*a(m). */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <limits.h>

/* Helper functions that may be available in the build environment. */
#if !defined (UINT64_MAX)
#define UINT64_MAX 0xffffffffffffffffULL
#endif

/* Interval of forbidden values generated by a(m) = L-1.
   Values in [L,R] cannot appear in the next (R-L+1) positions
   after the interval was created.  `expire` is the last position
   where the interval is still active. */
struct Interval {
    seq_t L;
    seq_t R;
    idx_t expire;
    bool active;
};

static idx_t   computed_n   = 0;      /* number of values already stored */
static seq_t * memo          = NULL;   /* a(1) .. a(computed_n)      */
static size_t memo_cap      = 0;       /* allocated size of memo      */
static seq_t * used          = NULL;   /* used values so far          */
static size_t used_cap      = 0;       /* capacity of used array      */
static struct Interval *intervals = NULL;
static size_t interval_count = 0;     /* number of intervals          */
static size_t intervals_cap = 0;      /* allocated size of intervals */

/* Ensure the memo array holds at least `need` elements. */
static void ensure_memo_cap(idx_t need)
{
    if (memo_cap < (size_t)need) {
        size_t new_cap = memo_cap ? memo_cap * 2 : need;
        if (new_cap < (size_t)need) new_cap = need;
        memo = (seq_t *)realloc(memo, new_cap * sizeof(seq_t));
        used = (seq_t *)realloc(used, new_cap * sizeof(seq_t));
        memo_cap = new_cap;
        used_cap = new_cap;
    }
}

/* Ensure the intervals array holds at least `need` elements. */
static void ensure_intervals_cap(size_t need)
{
    if (intervals_cap < need) {
        size_t new_cap = intervals_cap ? intervals_cap * 2 : 16;
        if (new_cap < need) new_cap = need;
        intervals = (struct Interval *)realloc(intervals,
                                               new_cap * sizeof(struct Interval));
        intervals_cap = new_cap;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;                /* undefined for n < 1 */

    /* Generate values up to n if needed. */
    if (computed_n < n) {
        ensure_memo_cap(n);

        for (idx_t pos = computed_n + 1; pos <= n; ++pos) {
            /* deactivate intervals that have expired. */
            for (size_t i = 0; i < interval_count; ++i) {
                if (intervals[i].active && intervals[i].expire < pos)
                    intervals[i].active = false;
            }

            /* find the smallest unused value not blocked by any active interval. */
            seq_t candidate = (seq_t)1;
            for (;;) {
                bool used_flag = false;
                for (idx_t i = 0; i < computed_n; ++i) {
                    if (used[i] == candidate) {  /* already used */
                        used_flag = true;
                        break;
                    }
                }
                if (used_flag) {
                    candidate = candidate + 1;
                    continue;
                }

                bool blocked = false;
                for (size_t i = 0; i < interval_count; ++i) {
                    if (!intervals[i].active) continue;
                    if (candidate >= intervals[i].L && candidate <= intervals[i].R) {
                        candidate = intervals[i].R + 1;
                        blocked = true;
                        break;
                    }
                }
                if (blocked) continue;
                break;          /* candidate is acceptable */
            }

            /* store the value */
            memo[computed_n] = candidate;
            used[computed_n] = candidate;
            ++computed_n;

            /* create the forbidden interval for this value */
            seq_t L = candidate + 1;
            seq_t R = candidate * 2;          /* works for ulong/128/ bigint types */
            idx_t expire;
            /* compute expire = pos + candidate, but guard against overflow into
               idx_t (which is uint64_t). */
            seq_t cand_for_idx = candidate;
            if (cand_for_idx > (seq_t)((~((idx_t)0)) / pos)) {
                /* candidate too large to fit into idx_t addition: keep it
                   effectively infinite so the interval never expires within
                   computed positions. */
                expire = UINT64_MAX;
            } else {
                expire = pos + (idx_t)candidate;
            }

            ensure_intervals_cap(interval_count + 1);
            intervals[interval_count].L = L;
            intervals[interval_count].R = R;
            intervals[interval_count].expire = expire;
            intervals[interval_count].active = true;
            ++interval_count;
        }
    }

    return memo[n - 1];
}
