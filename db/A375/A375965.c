/*
 * A375965  Primes which can be turned into a different prime by exchanging
 *          two consecutive digits.
 * https://oeis.org/A375965
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 17, u16 n <= 1617, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 6425, big any n
 * Helpers:   is_prime_small, next_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the n‑th term of OEIS A375965: primes that can be
 * turned into a different prime by exchanging two consecutive decimal digits.
 * The sequence is generated by scanning primes sequentially and applying the
 * digit‑swap test.  The results are memoised so that the function works for
 * arbitrary call order. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/next_prime.h"
#include "../utils/is_prime_small.h"

/* Helper: extract decimal digits of x into buf[0..len-1] (most significant first) */
static void get_digits_seq(seq_t x, uint8_t *buf, size_t *len)
{
    seq_t t = x;
    uint8_t rev[64];
    size_t pos = 0;

    if (t == 0) {
        rev[pos++] = 0;
    } else {
        while (t != 0) {
            rev[pos++] = (uint8_t)(t % 10);
            t /= 10;
        }
    }
    *len = pos;
    /* reverse into buf */
    for (size_t i = 0; i < pos; ++i)
        buf[i] = rev[pos - 1 - i];
}

seq_t a(idx_t n)
{
    /* static state: cached terms, current prime pointer */
    static seq_t *terms   = NULL;
    static size_t terms_cap = 0;
    static size_t terms_len = 0;
    static uint64_t curr_prime = 1; /* start from 2 */

    /* Ensure we have at least n terms computed */
    if ((size_t)n > terms_len) {
        /* resize array if necessary */
        if (terms_len == terms_cap) {
            size_t new_cap = terms_cap ? terms_cap << 1 : 32;
            seq_t *tmp = (seq_t *)realloc((void *)terms, new_cap * sizeof(seq_t));
            if (tmp == NULL) {
                /* Allocation failed – abort */
                return 0;
            }
            terms      = tmp;
            terms_cap  = new_cap;
        }

        while (terms_len < (size_t)n) {
            /* get next prime */
            curr_prime = next_prime(curr_prime + 1);

            /* skip 1‑digit primes and 11 */
            if (curr_prime < 10 || curr_prime == 11)
                continue;

            /* get decimal digits of the prime */
            uint8_t digits[64];
            size_t dlen;
            get_digits_seq((seq_t)curr_prime, digits, &dlen);

            bool ok = false;
            for (size_t i = 0; i + 1 < dlen && !ok; ++i) {
                if (digits[i] == digits[i + 1])  /* identical digits give same number */
                    continue;

                /* construct swapped number */
                seq_t swapped = 0;
                for (size_t j = 0; j < dlen; ++j) {
                    uint8_t d = digits[j];
                    if (j == i)
                        d = digits[i + 1];
                    else if (j == i + 1)
                        d = digits[i];
                    swapped = swapped * 10 + d;
                }

                if (swapped != (seq_t)curr_prime && is_prime_small(swapped))
                    ok = true;
            }

            if (ok) {
                terms[terms_len++] = (seq_t)curr_prime;
            }
        }
    }

    return terms[n - 1];
}
