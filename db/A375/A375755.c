/*
 * A375755  Lexicographically earliest sequence of distinct positive integers
 *          such that two consecutive terms have different initial digits.
 * https://oeis.org/A375755
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 221, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A375755: lexicographically earliest permutation of
 * positive integers whose consecutive terms have different
 * initial digits.  The sequence is generated by a greedy
 * algorithm: at each step choose the smallest unused integer
 * that does not start with the same digit as the previous term. */

#include <stdlib.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdint.h>

/* --------------------------------------------------------------------- */
/*  INTERNAL STATE                                                       */
/* --------------------------------------------------------------------- */

static uint8_t *used = NULL;      /* used[i]==1 → number i already used */
static size_t used_len = 0;       /* capacity of 'used' array */

static seq_t *seq = NULL;         /* array of computed a(k) */
static size_t seq_len = 0;        /* number of terms stored so far */
static size_t seq_cap = 0;        /* allocated capacity for seq */

static idx_t ptr_digit[10];       /* next candidate number for leading digit d (1..9) */
static idx_t prev_digit = 0;      /* leading digit of the last term chosen */

static bool initialized = false;

/* --------------------------------------------------------------------- */
/*  UTILITY FUNCTIONS                                                    */
/* --------------------------------------------------------------------- */

/* Return the leading decimal digit of n (0 if n==0). */
static inline idx_t leading_digit(idx_t n)
{
    while (n >= 10) n /= 10;
    return n;
}

/* Expand 'used' array to accommodate indices up to at least 'needed'. */
static void ensure_used(size_t needed)
{
    if (needed < used_len) return;
    size_t new_len = used_len ? used_len * 2 : 64;
    while (new_len <= needed) new_len <<= 1;
    uint8_t *tmp = (uint8_t*)realloc(used, new_len);
    if (!tmp) exit(1);            /* allocation failure – abort */
    /* zero the new part */
    for (size_t i = used_len; i < new_len; ++i) tmp[i] = 0;
    used = tmp;
    used_len = new_len;
}

/* Expand 'seq' array to have capacity for at least 'needed' elements. */
static void ensure_seq(size_t needed)
{
    if (needed <= seq_cap) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    while (new_cap < needed) new_cap <<= 1;
    seq_t *tmp = (seq_t*)realloc(seq, new_cap * sizeof(seq_t));
    if (!tmp) exit(1);            /* allocation failure – abort */
    seq = tmp;
    seq_cap = new_cap;
}

/* One‑time initialization of static state. */
static void init_state(void)
{
    if (initialized) return;
    ensure_used(64);    /* start with a modest size */
    ensure_seq(16);
    for (int d = 1; d <= 9; ++d) ptr_digit[d] = (idx_t)d;
    prev_digit = 0;
    seq_len   = 0;
    seq_cap   = 16;
    initialized = true;
}

/* --------------------------------------------------------------------- */
/*  PUBLIC FUNCTION                                                      */
/* --------------------------------------------------------------------- */

seq_t a(idx_t n)
{
    init_state();

    if (n == 0) return 0;  /* undefined for offset 1; return 0 */

    /* Return previously computed value if available. */
    if (n <= seq_len) return seq[n - 1];

    /* Generate terms until we have at least n terms. */
    while (seq_len < n) {
        /* Select the smallest unused candidate whose leading digit
           differs from the previous digit. */
        idx_t chosen = (idx_t)-1;
        int chosen_d = 0;
        for (int d = 1; d <= 9; ++d) {
            if (d == prev_digit) continue;
            idx_t cand = ptr_digit[d];
            if (cand < chosen) {
                chosen = cand;
                chosen_d = d;
            }
        }

        /* Record the chosen term. */
        ensure_seq(seq_len + 1);
        seq[seq_len] = (seq_t)chosen;
        seq_len++;

        /* Mark as used. */
        ensure_used((size_t)chosen);
        used[(size_t)chosen] = 1;

        /* Update for next step. */
        prev_digit = chosen_d;

        /* Advance ptr_digit[chosen_d] to the next number with the
           same leading digit. */
        idx_t next = chosen + 1;
        while (leading_digit(next) != (idx_t)chosen_d) ++next;
        ptr_digit[chosen_d] = next;
    }

    return seq[n - 1];
}
