/*
 * A074197  Let b(1) = n, b(k+1) = b(k)/2 + k if b(k) is even, b(k+1) = b(k)-k
 *          otherwise; sequence gives values of b(1) = n such that b(k) = 2k-4
 *          for k large enough.
 * https://oeis.org/A074197
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = the n-th positive integer that eventually reaches b(k) =
 *            2*k - 4 under the recurrence b(1) = n b(k+1) = b(k)/2 + k if
 *            b(k) is even b(k+1) = b(k) - k if b(k) is odd
 * Range:     u8 n <= 21, u16 n <= 2514, u32 n <= 5000, u64 n <= 5000,
 *            u128 n <= 5000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  The sequence is generated by testing successive candidates and
    keeping those that satisfy the condition.  Each candidate n is
    verified by iterating the recurrence until either the linear
    relation b(k)=2*k-4 is met or a fail condition is detected. */

#include <stdlib.h>

/* Forward declaration of the main function.  seq_t and idx_t are
   provided by the build environment. */
seq_t a(idx_t n);

/* ------------------------------------------------------------------ */
/* Helper: test whether a candidate n belongs to the sequence.        */
static int candidate_ok(seq_t n)
{
    seq_t val = n;
    idx_t k = 1;
    /* limit to avoid infinite loops for non‑members */
    const idx_t MAX_STEPS = 20000;

    for (;;) {
        /* Check for the linear pattern b(k) = 2*k - 4.  The value is
           only defined for k >= 3 because 2*k-4 is negative otherwise. */
        if (k >= 3) {
            seq_t target = (seq_t)2 * k - (seq_t)4;
            if (val == target)
                return 1;          /* found the required condition */
        }

        if (val & (seq_t)1) {          /* odd */
            /* If val < k the subtraction would underflow (negative
               intermediate), which means the sequence cannot hit the
               linear pattern. */
            if (val < (seq_t)k)
                return 0;
            val = val - (seq_t)k;
        } else {                       /* even */
            val = val / (seq_t)2 + (seq_t)k;
        }

        if (++k > MAX_STEPS)
            return 0;                  /* exceeded reasonable length */
    }
}

/* ------------------------------------------------------------------ */
/* Main sequence function.  Uses lazy static allocation to store the
   sequence values once computed.  Subsequent calls reuse the cached
   result. */
seq_t a(idx_t n)
{
    /* Static cache structures */
    static seq_t *cache = NULL;      /* array of computed a(i) values */
    static idx_t cache_len = 0;      /* number of elements currently stored */
    static idx_t cache_cap = 0;      /* allocated capacity */

    static idx_t next_candidate = 1; /* next integer to test */

    /* Grow the cache if needed */
    if (cache_len < cache_cap && next_candidate < n) {
        /* nothing to do: already have enough */
    } else {
        /* Ensure capacity for new elements */
        while (cache_len < n) {
            /* Test the next integer */
            if (candidate_ok((seq_t)next_candidate)) {
                /* Ensure enough capacity */
                if (cache_len == cache_cap) {
                    idx_t new_cap = cache_cap ? cache_cap << 1 : 16;
                    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                    if (!tmp) /* allocation failure */
                        abort();
                    cache = tmp;
                    cache_cap = new_cap;
                }
                cache[cache_len++] = (seq_t)next_candidate;
            }
            next_candidate++;
        }
    }

    return cache[n - 1];
}
