/*
 * A360585  The integers of the sequence appear exactly twice. Between the two
 *          copies of k there are k even integers. The sequence is always
 *          extended with the smallest integer not leading to a contradiction.
 * https://oeis.org/A360585
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 70, u16 n <= 70, u32 n <= 70, u64 n <= 70, u128 n <= 70,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A360585
    The sequence is generated by a greedy rule:
    choose the smallest positive integer k that
    does not violate the requirement:
      • each integer appears exactly twice,
      • between the two copies of k there are exactly k even
        integers.
    The algorithm stores the sequence in a static array and expands
    it on demand.  It is O(n) and works for any seq_t size.  */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

/* Static storage for the sequence and its auxiliary data */
static seq_t *seq          = NULL;      /* a(1) .. a(seq_len)   */
static idx_t  seq_len      = 0;         /* number of terms stored so far */
static idx_t  seq_cap      = 0;         /* allocated capacity of seq array */

static idx_t *prefix_even  = NULL;      /* prefix_even[i] = #even among a(1..i) */
static idx_t  prefix_cap    = 0;

static uint8_t *occ       = NULL;       /* occ[k] = 0,1,2 occurrences of k */
static idx_t   *first_pos = NULL;       /* first_pos[k] = position of first k */
static idx_t    occ_cap    = 0;

/* Ensure that seq and prefix_even have room for at least len_needed terms. */
static void ensure_seq_capacity(idx_t len_needed)
{
    if (len_needed <= seq_cap)
        return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 64;
    while (len_needed > new_cap)
        new_cap <<= 1;

    seq          = (seq_t*)realloc(seq,          (new_cap + 1) * sizeof(seq_t));
    prefix_even  = (idx_t*)realloc(prefix_even,  (new_cap + 1) * sizeof(idx_t));
    if (!seq || !prefix_even) abort();

    if (seq_len == 0)      /* first allocation – initialise index 0 */
        prefix_even[0] = 0;
    seq_cap = new_cap;
}

/* Ensure that occ and first_pos have room for indices up to k. */
static void ensure_k_capacity(idx_t k)
{
    if (k <= occ_cap)
        return;
    size_t new_cap = occ_cap ? occ_cap * 2 : 64;
    while (k > new_cap)
        new_cap <<= 1;

    occ       = (uint8_t*)realloc(occ,          (new_cap + 1) * sizeof(uint8_t));
    first_pos = (idx_t*)realloc(first_pos,      (new_cap + 1) * sizeof(idx_t));
    if (!occ || !first_pos) abort();

    /* initialise new entries to 0 */
    memset(occ + occ_cap, 0, (new_cap - occ_cap) * sizeof(uint8_t));
    /* first_pos entries for new k need not be initialised until used */

    occ_cap = new_cap;
}

/* Append a new term value `val` at the end of the sequence. */
static void append_term(idx_t val)
{
    ensure_seq_capacity(seq_len + 1);
    ++seq_len;
    seq[seq_len] = (seq_t)val;

    idx_t evens_here = ((seq_t)val & 1) == 0 ? 1 : 0;
    prefix_even[seq_len] = prefix_even[seq_len - 1] + evens_here;
}

/* Main function requested by the build. */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;           /* undefined, but harmless */

    /* Expand the sequence up to term n if needed. */
    if (n > seq_len) {
        static idx_t next_candidate = 1;   /* smallest integer to test next */

        for (idx_t pos = seq_len + 1; pos <= n; ++pos) {
            idx_t candidate = next_candidate;

            for (;;) {
                ensure_k_capacity(candidate);
                uint8_t occ_val = occ[(size_t)candidate];

                if (occ_val == 2) {              /* already completed */
                    ++candidate;
                    continue;
                }

                if (occ_val == 1) {              /* second occurrence */
                    idx_t fp = first_pos[(size_t)candidate];
                    /* count even integers strictly between the two copies */
                    idx_t evens_between = prefix_even[seq_len] - prefix_even[fp];
                    if (evens_between != candidate) {
                        ++candidate;
                        continue;
                    }
                }
                /* candidate is admissible */
                break;
            }

            /* Record the chosen candidate. */
            append_term(candidate);

            /* Update occurrence information. */
            if (occ[(size_t)candidate] == 0) {
                occ[(size_t)candidate] = 1;
                first_pos[(size_t)candidate] = seq_len;
            } else {          /* this must be the second occurrence */
                occ[(size_t)candidate] = 2;
            }

            /* next_candidate can stay the same; the inner loop skips
               already rejected values automatically. */
        }
    }

    return seq[n];
}
