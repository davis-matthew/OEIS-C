/*
 * A360680  Numbers for which the prime signature has the same mean as the
 *          first differences of 0-prepended prime indices.
 * https://oeis.org/A360680
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 44, u32 n <= 44, u64 n <= 44, u128 n <= 44,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A360680
    Numbers for which the prime signature has the same mean as the
    first differences of 0‑prepended prime indices.
    Implementation: for n>=1 return the nth such number.
    The sequence is generated by testing integers in ascending order
    and keeping those that satisfy the condition.

    Condition:
        Let n = ∏ p_i^e_i  (p_i distinct primes, e_i >= 1)
        Let Ω(n) = Σ e_i   (total number of prime factors counted with multiplicity)
        Let ω(n) = number of distinct prime factors (size of the signature)
        Let K   = the index of the largest prime factor (index of prime in the
                  sequence 2,3,5,7,11,13,… – 2 has index 1).

        The number n satisfies the condition iff
                (Ω(n))^2  ==  K * ω(n)

    The code below pre‑computes a prime sieve up to a fixed limit
    (8 000 000) and factors numbers using the smallest‑prime‑factor array.
    It memoises the sequence so that successive calls with arbitrary n
    are served in O(1) time after the first expansion.
*/

#include <stdint.h>
#include <stdlib.h>
#include <math.h>

/* ------------------------------------------------------------ */
/*  Prime sieve – smallest prime factor and prime index table  */
static uint32_t *spf = NULL;          /* smallest prime factor         */
static uint32_t *prime_idx = NULL;    /* index of prime in the prime list (1‑based) */
static uint32_t *primes = NULL;       /* list of primes up to the limit */
static size_t   prime_cnt = 0;        /* number of primes */
static const uint32_t SIEVE_LIMIT = 8000000;   /* fixed upper bound */

/* initialize the sieve (linear sieve) */
static void init_sieve(void)
{
    if (spf != NULL) return;           /* already initialised */

    spf = (uint32_t*)calloc(SIEVE_LIMIT + 1, sizeof(uint32_t));
    prime_idx = (uint32_t*)calloc(SIEVE_LIMIT + 1, sizeof(uint32_t));

    /* upper bound for number of primes: n / log(n) + 10 */
    size_t prime_cap = (size_t)(SIEVE_LIMIT / 12.0) + 100;
    primes = (uint32_t*)malloc(prime_cap * sizeof(uint32_t));

    size_t pc = 0;
    for (uint32_t i = 2; i <= SIEVE_LIMIT; ++i) {
        if (spf[i] == 0) {
            spf[i] = i;
            prime_idx[i] = ++pc;
            if (pc == prime_cap) {                /* reallocate if needed */
                prime_cap <<= 1;
                primes = (uint32_t*)realloc(primes,
                                            prime_cap * sizeof(uint32_t));
            }
            primes[pc - 1] = i;
        }
        for (size_t j = 0; j < pc; ++j) {
            uint32_t p = primes[j];
            uint64_t m = (uint64_t)i * p;
            if (m > SIEVE_LIMIT) break;
            spf[(uint32_t)m] = p;
            if (p == spf[i]) break;
        }
    }
    prime_cnt = pc;
}

/* ------------------------------------------------------------ */
/*  Test whether an integer n satisfies the sequence condition  */
static int satisfies(uint32_t n)
{
    if (n == 1) return 1;                 /* 1 is a special case */

    uint32_t tmp = n;
    int sumExp = 0;                       /* Ω(n) */
    int distinct = 0;                     /* ω(n) */
    int maxIdx = 0;                       /* K */

    while (tmp > 1) {
        uint32_t p = spf[tmp];
        uint32_t idx = prime_idx[p];      /* index of prime p */
        int exp = 0;
        do {
            tmp /= p;
            ++exp;
        } while (tmp % p == 0);

        sumExp += exp;
        ++distinct;
        if (idx > maxIdx) maxIdx = (int)idx;
    }

    return ((int64_t)sumExp * sumExp) == ((int64_t)maxIdx * distinct);
}

/* ------------------------------------------------------------ */
/*  Memoised sequence storage                                     */
static seq_t *seq_cache = NULL;   /* the generated sequence */
static idx_t seq_len = 0;         /* number of elements stored  */
static idx_t seq_cap = 0;         /* capacity of seq_cache      */
static uint32_t next_candidate = 1;   /* next integer to test   */

/* ------------------------------------------------------------ */
seq_t a(idx_t n)
{
    /* initialise sieve lazily */
    init_sieve();

    /* grow cache until it contains a(n) */
    while (seq_len < n) {
        /* scan until the next qualifying number */
        while (!satisfies(next_candidate))
            ++next_candidate;

        /* store it */
        if (seq_len == seq_cap) {                /* grow cache */
            size_t new_cap = seq_cap == 0 ? 16 : seq_cap << 1;
            seq_cache = (seq_t*)realloc(seq_cache,
                                        new_cap * sizeof(seq_t));
            seq_cap = new_cap;
        }
        seq_cache[seq_len++] = (seq_t)next_candidate;
        ++next_candidate;
    }

    return seq_cache[n - 1];
}
