/*
 * A360019  Lexicographically earliest increasing sequence of positive numbers
 *          in which no nonempty subsequence of consecutive terms sums to a
 *          triangular number.
 * https://oeis.org/A360019
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 40, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   floor_sqrt
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A360019: lexicographically earliest increasing sequence of positive numbers
 * in which no nonempty subsequence of consecutive terms sums to a triangular number.
 * The sequence is generated by a greedy search: at each step, the smallest
 * integer larger than the last term is chosen that preserves the property.
 *
 * Initial values (for reference):
 *   a(0) = 2,  a(1) = 5,  a(2) = 7,  a(3) = 11,  a(4) = 12,  ...
 */
#include <stdbool.h>
#include <stdlib.h>
#include "../utils/floor_sqrt.h"

/* Check whether S is a triangular number.
 * Triangular numbers are T_m = m (m+1) / 2.
 * S is triangular iff 1 + 8 S is a perfect square. */
static bool is_triangular(seq_t S)
{
    seq_t D = S * 8 + 1;          /* D = 1 + 8S */
    seq_t s = floor_sqrt(D);      /* floor(sqrt(D)) */
    return s * s == D;           /* perfect square check */
}

/* Expanding sequence storage */
static seq_t *seq      = NULL;   /* generated sequence */
static seq_t *prefix   = NULL;   /* prefix sums: prefix[i] = sum of seq[0..i-1] */
static idx_t  size     = 0;      /* number of elements currently in seq */
static idx_t  capacity = 0;      /* allocated capacity for seq (prefix is capacity+1) */

/* Return a(n).  Builds the sequence lazily up to index n. */
seq_t a(idx_t n)
{
    /* lazy allocation on first use */
    if (seq == NULL) {
        capacity = 16;
        seq      = (seq_t *)malloc(capacity * sizeof(seq_t));
        prefix   = (seq_t *)malloc((capacity + 1) * sizeof(seq_t));
        if (!seq || !prefix) exit(1);
        size = 0;
        prefix[0] = 0;  /* prefix sum of zero terms */
    }

    /* Build sequence up to n */
    while (size <= n) {
        /* Ensure we have enough room to add a new element */
        if (size + 1 > capacity) {
            capacity *= 2;
            seq    = (seq_t *)realloc(seq,    capacity * sizeof(seq_t));
            prefix = (seq_t *)realloc(prefix, (capacity + 1) * sizeof(seq_t));
            if (!seq || !prefix) exit(1);
        }

        seq_t total      = prefix[size];                    /* sum of current sequence */
        seq_t candidate  = (size == 0) ? 2 : seq[size-1] + 1; /* smallest possible next value */

        for (;;) {
            /* Single-term subsequence must not be triangular */
            if (!is_triangular(candidate)) {
                bool ok = true;
                seq_t new_total = total + candidate;

                /* Check all suffix sums ending at the new element */
                for (idx_t k = 1; k <= size + 1; ++k) {
                    seq_t sum_k = new_total - prefix[size + 1 - k];
                    if (is_triangular(sum_k)) { ok = false; break; }
                }

                if (ok) {
                    /* Accept the candidate */
                    seq[size]      = candidate;
                    prefix[size+1] = new_total;
                    ++size;
                    break;
                }
            }
            ++candidate; /* try next integer */
        }
    }

    return seq[n];
}
