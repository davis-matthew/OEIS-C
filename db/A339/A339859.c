/*
 * A339859  Largest side of integer-sided primitive triangles whose sides a <
 *          b < c form a geometric progression.
 * https://oeis.org/A339859
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 19, u16 n <= 56, u32 n <= 56, u64 n <= 56, u128 n <= 56,
 *            big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include "../utils/gcd.h"

/* 
 * a(n) is the c value of the n-th primitive triangle with integer sides
 * a < b < c that form a geometric progression (b^2 = a*c).  
 * The triangles are generated by enumerating coprime pairs (x, y) with
 * x < y and x^2 + x*y > y^2, which guarantees a primitive triangle.  
 * For each pair, the sides are (a, b, c) = (x^2, x*y, y^2).  
 * The triples are sorted lexicographically by (a, b, c) by increasing x then y,
 * so the sequence is simply the list of y^2 in that order.
 */
seq_t a(idx_t n)
{
    if (n == 0) return 0;
    idx_t count = 0;
    for (idx_t x = 1; ; ++x) {
        seq_t xsq = (seq_t)x * (seq_t)x;
        for (idx_t y = x + 1; ; ++y) {
            seq_t ysq = (seq_t)y * (seq_t)y;
            /* Triangle inequality: x^2 + x*y > y^2 */
            if (xsq + (seq_t)x * (seq_t)y <= ysq) break;
            /* Primitive test: gcd(x, y) == 1 */
            if (gcd((seq_t)x, (seq_t)y) == 1) {
                ++count;
                if (count == n) return ysq;   /* c = y^2 */
            }
        }
    }
    return 0; /* never reached */
}
