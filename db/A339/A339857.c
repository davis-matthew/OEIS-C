/* OEIS A339857: smallest side a of a primitive integer‑sided triangle
   whose sides a<b<c are in geometric progression.
   The sequence is generated by enumerating coprime pairs (q,p) with
   q ≥ 2, q < p < q·φ (φ = (1+√5)/2), and checking the triangle
   inequality q² + q·p > p².  For each valid pair the triple (q²,
   q·p, p²) is a lexicographically ordered primitive triangle; the
   returned value is the first side q². */

#include <stdbool.h>
#include "../utils/gcd.h"

seq_t a(idx_t n) {
    idx_t count = 0;          /* how many terms produced so far */
    seq_t qsq;                /* current a = q² */

    for (idx_t q = 2; ; ++q) {
        qsq = (seq_t)q * q;                /* a = q² */

        /* p runs from q+1 upward; the triangle inequality fails
           once left <= right, after which it will remain false.  */
        for (idx_t p = q + 1; ; ++p) {
            seq_t left  = qsq + (seq_t)q * p;   /* q² + q·p */
            seq_t right = (seq_t)p * p;         /* p² */

            if (left <= right) break;   /* no further admissible p */

            /* primitive condition: gcd(q,p) = 1 */
            if (gcd((seq_t)q, (seq_t)p) == (seq_t)1) {
                ++count;                 /* one more primitive triangle */
                if (count == n) return qsq;
            }
        }
    }
}
