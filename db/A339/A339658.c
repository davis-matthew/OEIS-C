/*
 * A339658  Heinz numbers of loop-graphical partitions (of even numbers).
 * https://oeis.org/A339658
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 41, u16 n <= 58, u32 n <= 58, u64 n <= 58, u128 n <= 58,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n) – the n‑th Heinz number of a loop‑graphical partition of an
   even number.
   The sequence is generated by enumerating the integers 1,2,3,… and
   checking whether their prime‑index factorisation yields a loop‑graphical
   partition (sum of parts even and number of parts ≥ largest part – 1). */

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>

/* -----------------  global arrays  ----------------- */
static seq_t *cache      = NULL;   /* stored sequence values     */
static size_t cache_len  = 0;      /* number of stored values    */
static size_t cache_cap  = 0;      /* cache capacity             */

static idx_t *spf        = NULL;   /* smallest prime factor[ ]  */
static uint32_t *prime_idx_of  = NULL; /* prime index (1‑based), 0 if composite */
static idx_t spf_limit   = 0;      /* current maximum index of spf  */

static idx_t s_num       = 2;      /* next integer to test       */

/* -----------------  helper functions  ----------------- */

/* Extend spf and prime_idx_of up to at least 'limit' (inclusive).  */
static void extend_spf(idx_t limit)
{
    if (limit <= spf_limit)
        return;

    /* resize arrays */
    spf = (idx_t *)realloc(spf, (limit + 1) * sizeof(idx_t));
    prime_idx_of = (uint32_t *)realloc(prime_idx_of, (limit + 1) * sizeof(uint32_t));

    /* initialise spf values */
    for (idx_t i = spf_limit == 0 ? 2 : spf_limit + 1; i <= limit; ++i)
        spf[i] = i;

    /* sieve for smallest prime factor */
    for (idx_t i = 2; i * i <= limit; ++i)
    {
        if (spf[i] == i)
        {
            for (idx_t j = i * i; j <= limit; j += i)
                if (spf[j] == j)
                    spf[j] = i;
        }
    }

    /* build prime index table */
    uint32_t idx = 0;
    for (idx_t i = 2; i <= limit; ++i)
    {
        if (spf[i] == i)
        {
            prime_idx_of[i] = ++idx;  /* 1‑based index */
        }
        else
        {
            prime_idx_of[i] = 0;
        }
    }
    spf_limit = limit;
}

/* Ensure spf is built up to at least 'required'.  */
static void ensure_limit(idx_t required)
{
    if (required <= spf_limit)
        return;
    idx_t lim = spf_limit;
    if (lim < 2)
        lim = 2;
    while (lim < required)
        lim <<= 1;
    extend_spf(lim);
}

/* Initialise cache with first term 1.  */
static void initialise_cache(void)
{
    if (cache != NULL)
        return;

    cache_cap = 16;
    cache = (seq_t *)calloc(cache_cap, sizeof(seq_t));
    if (cache == NULL)
    {
        /* on failure just return 0 as fallback (unlikely in tests) */
        return;
    }
    cache[0] = (seq_t)1;   /* a(1) = 1 */
    cache_len = 1;
}

/* Append a value to the cache, expanding if necessary.  */
static void cache_append(seq_t val)
{
    if (cache_len >= cache_cap)
    {
        size_t new_cap = cache_cap * 2;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (tmp == NULL)
            return; /* fallback */
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

/* Generate terms until at least 'n' are stored.  */
static void grow_to_n(idx_t n)
{
    initialise_cache();

    while (cache_len < n)
    {
        ensure_limit(s_num);

        /* special case: 1 is always present (handled before loop) */
        if (s_num == 1)
        {
            cache_append((seq_t)1);
            ++s_num;
            continue;
        }

        /* factorise s_num */
        idx_t tmp = s_num;
        idx_t parts_count = 0;
        idx_t max_index = 0;
        bool parity = true;                /* true ⇒ even sum of parts   */

        while (tmp > 1)
        {
            idx_t p = spf[tmp];
            uint32_t idx = prime_idx_of[p];
            int exp = 0;
            while (tmp % p == 0)
            {
                tmp /= p;
                ++exp;
                ++parts_count;
                if (idx > max_index)
                    max_index = idx;
            }
            /* toggle parity if both index and exponent are odd */
            if ((idx & 1) && (exp & 1))
                parity = !parity;
        }

        /* test loop‑graphical condition */
        if (parity && parts_count >= max_index - 1)
        {
            cache_append((seq_t)s_num);
        }

        ++s_num;
    }
}

/* --------------  public function   -------------- */
extern seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;    /* undefined for n = 0 */

    if (n == 1)
        return (seq_t)1;    /* a(1) = 1 */

    grow_to_n(n);
    return cache[n - 1];
}
