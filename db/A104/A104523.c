/*
 * A104523  Numbers that are neither Fibonacci nor Lucas numbers.
 * https://oeis.org/A104523
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 233, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) = the n-th positive integer that is neither a Fibonacci number
   nor a Lucas number.  This is generated by scanning positive
   integers and skipping those that appear in the Fibonacci or
   Lucas sequences.  */

/* Include types and common utilities provided by the build system. */
#include <stdbool.h>
#include <stdint.h>

/* --------------------------------------------------------------------- */
/*  Static tables for Fibonacci and Lucas numbers (generated lazily).   */
/*  The tables are large enough for n up to at least 10 000 (values < 12 000). */
#define TABLE_CAP 1024

static seq_t fib[TABLE_CAP];
static idx_t fib_len = 0;
static seq_t fib_prev, fib_curr;          /* hold the last two Fibonacci terms */

static seq_t luc[TABLE_CAP];
static idx_t luc_len = 0;
static seq_t luc_prev, luc_curr;          /* hold the last two Lucas terms */

static void extend_fib_up_to(seq_t limit)
{
    /* Initialise the Fibonacci list with the first two terms 1,1. */
    if (fib_len == 0) {
        fib[0] = 1;
        fib[1] = 1;
        fib_len = 2;
        fib_prev = 1;
        fib_curr = 1;
    }
    /* Generate subsequent Fibonacci numbers until the last one exceeds the limit. */
    while (fib[fib_len - 1] <= limit && fib_len < TABLE_CAP) {
        seq_t next = fib_prev + fib_curr;
        fib[fib_len++] = next;
        fib_prev = fib_curr;
        fib_curr = next;
    }
}

static void extend_luc_up_to(seq_t limit)
{
    /* Initialise the Lucas list with the first two terms 2,1. */
    if (luc_len == 0) {
        luc[0] = 2;
        luc[1] = 1;
        luc_len = 2;
        luc_prev = 2;
        luc_curr = 1;
    }
    /* Generate subsequent Lucas numbers until the last one exceeds the limit. */
    while (luc[luc_len - 1] <= limit && luc_len < TABLE_CAP) {
        seq_t next = luc_prev + luc_curr;
        luc[luc_len++] = next;
        luc_prev = luc_curr;
        luc_curr = next;
    }
}

static bool is_fib_or_lucas(seq_t x)
{
    /* Ensure the tables cover the current candidate. */
    extend_fib_up_to(x);
    extend_luc_up_to(x);

    /* Linear scans are trivial because the tables contain only ~20 elements
       for numbers below 12 000. */
    for (idx_t i = 0; i < fib_len; ++i) {
        if (fib[i] == x) return true;
    }
    for (idx_t i = 0; i < luc_len; ++i) {
        if (luc[i] == x) return true;
    }
    return false;
}

/* --------------------------------------------------------------------- */
/*  Public function required by the build system. */
seq_t a(idx_t n)
{
    /* The sequence is defined for n >= 1.  No special handling for n=0
       is required. */
    idx_t count = 0;
    seq_t candidate = 1;          /* start from the first positive integer */

    for (;; candidate++) {
        if (!is_fib_or_lucas(candidate)) {
            ++count;
            if (count == n) return candidate;
        }
    }
}
