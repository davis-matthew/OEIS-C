/*
 * A197432  a(n) = Sum_{k>=0} A030308(n,k)*C(k) where C(k) is the k-th Catalan
 *          number (A000108).
 * https://oeis.org/A197432
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 63, u16 n <= 63, u32 n <= 63, u64 n <= 63, u128 n <= 63,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A197432: a(n) = sum_{k>=0} A030308(n,k) * Catalan(k)
 * where A030308(n,k) is 1 iff the k-th binary digit of n is 1 (otherwise 0).
 * Thus a(n) = sum of Catalan numbers whose indices are the set bits of n.
 * The Catalan numbers are generated by C(0)=1,
 * C(n+1)=C(n)*2*(2*n+1)/(n+2)   (integer division is exact).
 * This routine works for any size of idx_t (uint64_t or larger) and
 * any size of seq_t (unsigned 8/16/32/64 bits or arbitrary precision).
 * For seq_t that cannot hold large Catalan values, the result simply
 * wraps modulo 2^(width_of_seq_t), which is acceptable because
 * such large results exceed the width of seq_t anyway.
 */

#include <stdbool.h>   // for bool

static seq_t catalan[64];
static bool catalan_initialized = false;

static void init_catalan(void)
{
    catalan[0] = (seq_t)1;
    for (idx_t i = 0; i < 63; ++i) {
        seq_t num = catalan[i] * (seq_t)(2 * (2 * i + 1));
        catalan[i + 1] = num / (seq_t)(i + 2);
    }
    catalan_initialized = true;
}

seq_t a(idx_t n)
{
    if (!catalan_initialized)
        init_catalan();

    seq_t result = (seq_t)0;
    idx_t bit = 0;
    while (n) {
        if (n & (idx_t)1)
            result += catalan[bit];
        n >>= 1;
        ++bit;
    }
    return result;
}
