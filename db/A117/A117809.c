/*
 * Formula: a(n) = floor( ((-2 + sqrt(3))^(r+1) + (-2 - sqrt(3))^(r+1)) / 2 ) ,
 *            with r chosen so that n lies in the r-th row of the triangular array
 *            (row length r+1).  For odd rows with r > 1 an extra -1 is subtracted,
 *            matching the OEIS values.
 * The sequence is generated by repeatedly floor–dividing the row start by 2.
 */

#include <stddef.h>
#include <stdint.h>

/* Auxiliary: floor division by 2 for signed integers */
static inline seq_t floor_div2(seq_t v)
{
    if (v >= 0)
        return v / 2;
    /* v < 0: dividend negative */
    return (v - 1) / 2;   /* subtract 1 before truncating to achieve floor */
}

/* Compute the (n)-th value S_n = (-2+√3)^n + (-2-√3)^n using the recurrence
 * S_n = -4 * S_{n-1} - S_{n-2} with S_0 = 2, S_1 = -4.  Only the
 * value for the requested index is needed, so a loop with two temporaries is
 * sufficient. */
static seq_t compute_S(idx_t n)
{
    if (n == 0)
        return (seq_t)2;
    if (n == 1)
        return (seq_t)(-4);

    seq_t s_prev2 = (seq_t)2;   /* S_{i-2}   */
    seq_t s_prev1 = (seq_t)(-4);/* S_{i-1}   */
    seq_t s_cur;
    for (idx_t i = 2; i <= n; ++i)
    {
        s_cur   = - (seq_t)4 * s_prev1 - s_prev2;
        s_prev2 = s_prev1;
        s_prev1 = s_cur;
    }
    return s_cur;
}

/* Main function requested by the build system. */
seq_t a(idx_t n)
{
    /* Determine the row r and column k of the flattened triangle:
     * row 0 has 1 element, row 1 has 2, row 2 has 3, etc. */
    idx_t r = 0;
    while ((r + 1) * (r + 2) / 2 <= n)  /* find smallest r with cum > n */
        r++;

    /* cumulative terms before this row */
    idx_t cum_before = r * (r + 1) / 2;
    idx_t k = n - cum_before;   /* 0 ≤ k ≤ r */

    /* Compute the start of the row: floor( S_{r+1} / 2 ). */
    seq_t s_val = compute_S(r + 1);
    seq_t start = floor_div2(s_val);
    if ((r & 1) && r > 1)        /* odd row with r > 1 subtract 1 */
        start -= (seq_t)1;

    /* Repeatedly floor–divide by 2 to reach column k. */
    seq_t result = start;
    for (idx_t i = 1; i <= k; ++i)
        result = floor_div2(result);

    return result;
}
