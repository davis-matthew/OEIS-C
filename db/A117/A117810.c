/*
 * A117810  Numbers m such that m is k*(the sum of decimal digits squared of
 *          m), k=153 case.
 * https://oeis.org/A117810
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, fini, full, nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 7, u32 n <= 7, u64 n <= 7, u128 n <= 7,
 *            big any n
 * Helpers:   digit_square_sum_seq
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes OEIS A117810: numbers m such that m = 153 · (sum of squares of decimal digits of m).
   The sequence is generated by searching over s = sum of squares using m = 153·s, storing the m values 
   in increasing order.  a(1) = 0, a(2) = 4131, a(3) = 12546, …  */
/* Index 1 is the first term; a(1) = 0.  The function works for any
   build where seq_t may be an arbitrary‑precision integer class or a C
   unsigned integer type, and idx_t is uint64_t. */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/digit_square_sum_seq.h"

/* Static cache to store the found sequence values.  The array grows
   by repetition of the build‑up loop, so it remains sorted. */
static seq_t *cached = NULL;   /* dynamic array of seq_t values */
static size_t cache_sz = 0;    /* number of stored values      */
static size_t cache_cap = 0;   /* allocated capacity           */
static idx_t   next_s  = 0;    /* next s to test                */

static void ensure_cache_capacity(void)
{
    if (cache_sz >= cache_cap) {
        size_t new_cap = cache_cap == 0 ? 8 : cache_cap * 2;
        seq_t *newp = (seq_t *)realloc(cached, new_cap * sizeof(seq_t));
        if (!newp) exit(EXIT_FAILURE);   /* out of memory */
        cached = newp;
        cache_cap = new_cap;
    }
}

/* Return the n-th term of the sequence (n >= 1). */
seq_t a(idx_t n)
{
    if (n == 0)   /* safety guard – index 0 is outside the offset */
        return (seq_t)0;

    /* Grow the cache until it contains at least n elements. */
    while (cache_sz < (size_t)n) {
        seq_t m   = (seq_t)153 * (seq_t)next_s;      /* candidate m = 153·s */
        seq_t s_  = digit_square_sum_seq(m);
        if (s_ == (seq_t)next_s) {                  /* satisfies condition */
            ensure_cache_capacity();
            cached[cache_sz++] = m;
        }
        next_s++;
    }
    return cached[n - 1];
}
