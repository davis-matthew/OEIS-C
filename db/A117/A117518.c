static inline seq_t d2_val(idx_t i)
{
    if (i == 0) return (seq_t)3;
    if (i == 1) return (seq_t)1;
    if (i == 2) return (seq_t)5;
    if (i == 3) return (seq_t)3;
    if ((i & (idx_t)1) == 0) return (seq_t)3;            /* even k ≥ 4 */
    idx_t k = (i - (idx_t)5) / (idx_t)2;                 /* odd k ≥ 5 */
    return (seq_t)4 * (seq_t)k + (seq_t)10;
}
/* Sequence A117518: Low point in segment n of A079051.
   The sequence can be generated by the following recurrence:
   a(0)=0, a(1)=1.
   Define d1_i = a(i+1)-a(i).  The second differences d2_i = d1_{i+1}-d1_i
   are given by:
       d2_0 = 3,   d2_1 = 1,   d2_2 = 5,   d2_3 = 3,
       d2_k = 3          for even k ≥ 4,
       d2_k = 4*((k-5)/2)+10   for odd k ≥ 5.
   With these d2 values the sequence agrees with OEIS A117518. */

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;
    seq_t cur  = (seq_t)0;   /* a(0)   */
    seq_t diff = (seq_t)1;   /* d1_0   */

    for (idx_t i = 1; i <= n; ++i) {
        cur += diff;                   /* cur becomes a(i)   */
        if (i == n) break;
        diff += d2_val(i - 1);          /* update to d1_{i}    */
    }
    return cur;
}
