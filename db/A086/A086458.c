/*
 * A086458  Both n and n^3 have the same initial digit and also n and n^3 have
 *          the same final digit when expressed in base 10.
 * https://oeis.org/A086458
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 5, u32 n <= 347, u64 n <= 2000,
 *            u128 n <= 2000, big any n
 * Helpers:   digit_len, pow10, seq_pow
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A086458: numbers whose first and last digits are unchanged by cubing.
 * The sequence is generated by a simple brute‑force search: starting from
 * 0 we test each integer n until we have found the required number of
 * terms.  Memoisation is used so repeated calls to a(idx_t n) are
 * efficient and order‑independent.  The implementation uses only C11
 * compatible features and the helper functions defined in the utils
 * library that are mentioned in the problem statement. */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

#include "../utils/seq_pow.h"      /* seq_pow(base, exp) */
#include "../utils/pow10.h"        /* pow10(exp) */
#include "../utils/digit_len.h"    /* digit_len(x) */

/* ------------------------------------------------------------ */
/* Helper: test whether a last digit satisfies d³ ≡ d (mod 10). */
static const uint8_t allowed_last_digits[] = {0, 1, 4, 5, 6, 9};
static const size_t ALLOWED_CNT =
    sizeof(allowed_last_digits) / sizeof(allowed_last_digits[0]);

static inline bool digit_allowed(uint8_t d)
{
    for (size_t i = 0; i < ALLOWED_CNT; ++i)
        if (d == allowed_last_digits[i])
            return true;
    return false;
}

/* ------------------------------------------------------------ */
/* Static cache of computed sequence values.  The cache is
 * automatically initialised on first use. */
static seq_t *seq_cache = NULL;
static size_t seq_cap   = 0;   /* allocated capacity (in seq_t elements) */
static size_t seq_len   = 0;   /* number of terms stored */

/* Grow the cache to hold at least 'need' elements.  CALLER must
 * ensure 'need' > seq_cap. */
static void ensure_cache_cap(size_t need)
{
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    if (new_cap < need)
        new_cap = need;
    seq_t *tmp = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    if (!tmp) /* malloc failure – abort */
        abort();
    seq_cache = tmp;
    seq_cap   = new_cap;
}

/* ------------------------------------------------------------ */
/* Main function. */
seq_t a(idx_t n)
{
    /* Initialise cache on first call. */
    if (!seq_cache) {
        seq_cap   = 16;
        seq_cache = (seq_t *)malloc(seq_cap * sizeof(seq_t));
        if (!seq_cache)
            abort();
        seq_cache[0] = (seq_t)0; /* a(0) = 0 */
        seq_len      = 1;
    }

    /* Return previously cached value if already computed. */
    if ((size_t)n < seq_len)
        return seq_cache[n];

    /* Generate terms until we reach the requested index. */
    seq_t cand = seq_cache[seq_len - 1] + 1;

    while (seq_len <= (size_t)n) {
        /* Quick filter: last digit must satisfy d³ ≡ d (mod 10). */
        uint8_t last = (uint8_t)(cand % 10);
        if (!digit_allowed(last)) {
            ++cand;
            continue;
        }

        /* Compute cube of the candidate. */
        seq_t cube = seq_pow(cand, 3);

        /* First digit of candidate. */
        int dlen_cand = digit_len(cand);
        seq_t pow10_cand = pow10((idx_t)(dlen_cand - 1));
        seq_t first_cand = cand / pow10_cand;

        /* First digit of cube. */
        int dlen_cube = digit_len(cube);
        seq_t pow10_cube = pow10((idx_t)(dlen_cube - 1));
        seq_t first_cube = cube / pow10_cube;

        /* Check both first‑digit and last‑digit equality. */
        if (first_cand == first_cube && (cube % 10) == last) {
            /* Grow cache if necessary. */
            if (seq_len == seq_cap)
                ensure_cache_cap(seq_len + 1);
            seq_cache[seq_len++] = cand;
            /* Stop when we have enough terms. */
            if (seq_len > (size_t)n)
                break;
        }

        ++cand;
    }

    return seq_cache[n];
}
