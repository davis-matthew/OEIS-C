/*
 * A086290  Minimal exponent in prime factorization of 7-smooth numbers.
 * https://oeis.org/A086290
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = minimal positive exponent in the prime factorization * of
 *            the n-th 7‑smooth number (with a(1)=0 for the number 1)
 * Range:     u8 n <= 76, u16 n <= 806, u32 n <= 9465, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stddef.h>

static size_t cache_capacity = 0;          /* capacity of the arrays (1‑based) */
static seq_t *a_cache = NULL;              /* a(n) values, 1‑based */

/* Arrays holding the 7‑smooth numbers and their exponent vectors. */
static seq_t *smooth_vals  = NULL;          /* smooth value at index i */
static uint16_t *exp2 = NULL;               /* exponent of 2 at index i */
static uint16_t *exp3 = NULL;               /* exponent of 3 at index i */
static uint16_t *exp5 = NULL;               /* exponent of 5 at index i */
static uint16_t *exp7 = NULL;               /* exponent of 7 at index i */
static size_t smooth_len = 0;                /* number of values generated */

/* Pointers used in the classic four‑pointer merge method. */
static idx_t ptr2 = 1, ptr3 = 1, ptr5 = 1, ptr7 = 1;

/* ------------------------------------------------------------------ */
/* Ensure that all tables have room for at least `needed` entries
   (indices are 1‑based). */
static void ensure_capacity(size_t needed)
{
    if (cache_capacity >= needed)
        return;

    size_t new_cap = cache_capacity ? cache_capacity * 2 : 16;
    while (new_cap < needed)
        new_cap <<= 1;

    a_cache     = (seq_t *)realloc(a_cache,     new_cap * sizeof(seq_t));
    smooth_vals = (seq_t *)realloc(smooth_vals, new_cap * sizeof(seq_t));
    exp2        = (uint16_t *)realloc(exp2,        new_cap * sizeof(uint16_t));
    exp3        = (uint16_t *)realloc(exp3,        new_cap * sizeof(uint16_t));
    exp5        = (uint16_t *)realloc(exp5,        new_cap * sizeof(uint16_t));
    exp7        = (uint16_t *)realloc(exp7,        new_cap * sizeof(uint16_t));

    cache_capacity = new_cap;
}

/* ------------------------------------------------------------------ */
/* Generate the sequence up to at least index `n`.  After the call
   smooth_vals[1..smooth_len] and a_cache[1..smooth_len] are fully
   defined. */
static void generate_up_to(idx_t n)
{
    if (n < 1)
        return;

    ensure_capacity((size_t)(n + 1));

    /* First element (the number 1) is never generated by the merge
       process; initialise it here if this is the very first call. */
    if (smooth_len == 0) {
        smooth_len = 1;
        smooth_vals[1] = (seq_t)1;
        exp2[1] = exp3[1] = exp5[1] = exp7[1] = 0;
        a_cache[1] = (seq_t)0;          /* a(1) = 0 */
        ptr2 = ptr3 = ptr5 = ptr7 = 1;
    }

    /* Main generation loop.  By the time it terminates we have
       smooth_len >= n. */
    while (smooth_len < (size_t)n) {
        /* Compute the four candidates.  Multiplication is safe in
           seq_t: either a plain integer type or an arbitrary‑precision
           type that supports operator*. */
        seq_t cand2 = smooth_vals[ptr2] * (seq_t)2;
        seq_t cand3 = smooth_vals[ptr3] * (seq_t)3;
        seq_t cand5 = smooth_vals[ptr5] * (seq_t)5;
        seq_t cand7 = smooth_vals[ptr7] * (seq_t)7;

        /* Determine the smallest candidate. */
        seq_t next = cand2;
        if (cand3 < next) next = cand3;
        if (cand5 < next) next = cand5;
        if (cand7 < next) next = cand7;

        /* Pick one of the candidates that produced `next` and copy
           its exponents.  All matching candidates will have identical
           exponent vectors because 7‑smooth factorisations are unique. */
        uint16_t n2, n3, n5, n7;
        if (next == cand2) {
            n2 = exp2[ptr2] + 1;
            n3 = exp3[ptr2];
            n5 = exp5[ptr2];
            n7 = exp7[ptr2];
        } else if (next == cand3) {
            n2 = exp2[ptr3];
            n3 = exp3[ptr3] + 1;
            n5 = exp5[ptr3];
            n7 = exp7[ptr3];
        } else if (next == cand5) {
            n2 = exp2[ptr5];
            n3 = exp3[ptr5];
            n5 = exp5[ptr5] + 1;
            n7 = exp7[ptr5];
        } else {   /* next == cand7 */
            n2 = exp2[ptr7];
            n3 = exp3[ptr7];
            n5 = exp5[ptr7];
            n7 = exp7[ptr7] + 1;
        }

        /* Advance all pointers that contributed to `next`. */
        if (next == cand2) ++ptr2;
        if (next == cand3) ++ptr3;
        if (next == cand5) ++ptr5;
        if (next == cand7) ++ptr7;

        /* Store the new number and its exponents. */
        size_t idx = smooth_len + 1;
        smooth_vals[idx] = next;
        exp2[idx] = n2;
        exp3[idx] = n3;
        exp5[idx] = n5;
        exp7[idx] = n7;

        /* Compute the minimal positive exponent for this number. */
        seq_t m = (seq_t)-1;          /* sentinel for "none yet" */
        if (n2 && n2 < (uint16_t)m) m = n2;
        if (n3 && n3 < (uint16_t)m) m = n3;
        if (n5 && n5 < (uint16_t)m) m = n5;
        if (n7 && n7 < (uint16_t)m) m = n7;
        if (m == (seq_t)-1)          /* should never happen for n>=2 */
            m = 0;
        a_cache[idx] = m;

        ++smooth_len;
    }
}

/* ------------------------------------------------------------------ */
/* Public interface required by the test harness. */
seq_t a(idx_t n)
{
    if (n < 1)
        return (seq_t)0;          /* Undefined for n==0, but harmless. */
    generate_up_to(n);
    return a_cache[n];
}
