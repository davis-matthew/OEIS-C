/*
 * A086060  Concatenation of the larger members of first n pairs of twin
 *          primes.
 * https://oeis.org/A086060
 *
 * Offset:    3    (a(3) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) = concatenate of the larger members of the first n-2 twin
 *            prime pairs (offset 3 → a(3) = the first larger member)
 * Range:     u8 n <= 4, u16 n <= 5, u32 n <= 7, u64 n <= 11, u128 n <= 15,
 *            big any n
 * Helpers:   build_primes_upto, digit_count, pow10
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

#include "../utils/build_primes_upto.h"   /* build_primes_upto(limit, &primes, &cnt) */
#include "../utils/digit_count.h"        /* digit_count(uint64_t) -> uint64_t */
#include "../utils/pow10.h"              /* pow10(idx_t) -> seq_t */

static uint64_t *prime_list = NULL;      /* array of primes generated by build_primes_upto */
static size_t prime_count = 0;

static uint64_t *twin_larger = NULL;     /* array of larger twin primes */
static size_t twin_count = 0;

/* Initial sieve limit; doubled until enough twin pairs are found. */
static idx_t sieve_limit = 2000000;
static bool primes_built = false;

/* Ensure that at least 'needed' larger twin primes are available. */
static void _ensure_twin_pairs(size_t needed)
{
    if (primes_built && twin_count >= needed)
        return;

    /* Try to find enough pairs by repeatedly increasing the sieve limit. */
    while (twin_count < needed) {
        /* Rebuild prime list at the current limit. */
        if (prime_list) {
            free(prime_list);
            prime_list = NULL;
        }
        build_primes_upto(sieve_limit, &prime_list, &prime_count);

        /* Enumerate twin pairs from the prime list. */
        twin_larger = (uint64_t *)realloc(twin_larger, prime_count * sizeof(uint64_t));
        twin_count = 0;
        for (size_t i = 0; i + 1 < prime_count; ++i) {
            if (prime_list[i + 1] == prime_list[i] + 2) {
                twin_larger[twin_count++] = prime_list[i + 1];
                if (twin_count >= needed)
                    break;
            }
        }

        if (twin_count < needed) {
            /* Not enough pairs yet – double the limit and retry. */
            sieve_limit <<= 1;
            /* Release the incomplete data so the next iteration starts fresh. */
            free(twin_larger);
            twin_larger = NULL;
            twin_count = 0;
        } else {
            primes_built = true;
        }
    }
}

seq_t a(idx_t n)
{
    if (n < 3)
        return 0;                 /* behaviour below the offset is unspecified */

    size_t pairs_needed = (size_t)(n - 2);
    _ensure_twin_pairs(pairs_needed);

    seq_t result = 0;
    for (size_t i = 0; i < pairs_needed; ++i) {
        seq_t prime = (seq_t)twin_larger[i];
        /* Number of decimal digits of the prime. */
        uint64_t d = digit_count((uint64_t)twin_larger[i]);
        seq_t mult = pow10((idx_t)d);
        result = result * mult + prime;
    }
    return result;
}
