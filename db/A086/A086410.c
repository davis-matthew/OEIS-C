/* Smallest prime factor of the nth 3‑smooth number
   Formula: a(1)=1; for n>1, a(n)=2 if the nth 3‑smooth number is even,
           otherwise a(n)=3.
   The nth 3‑smooth number is generated by merging the sequences
   2·H(i) and 3·H(j) where H(k) is the k‑th 3‑smooth number. */
#include <stdlib.h>

seq_t a(idx_t n)
{
    static seq_t *h = NULL;       /* array of 3‑smooth numbers, 1‑based */
    static idx_t h_capacity = 0;
    static idx_t h_size    = 0;    /* current number of stored terms */
    static idx_t i2 = 1;          /* next index for multiple of 2 */
    static idx_t i3 = 1;          /* next index for multiple of 3 */

    if (n == 0) {
        return (seq_t)0;          /* undefined for n=0, but avoid UB */
    }

    /* Initialise on first call */
    if (h == NULL) {
        h_capacity = 64;
        h = (seq_t *)malloc((h_capacity + 1) * sizeof(seq_t)); /* +1 for 1‑based */
        if (!h) return (seq_t)0; /* allocation failed */
        h[1] = (seq_t)1;
        h_size = 1;
        i2 = i3 = 1;
    }

    /* Grow the array if necessary */
    if (n > h_capacity) {
        idx_t new_cap = h_capacity * 2;
        while (new_cap < n) new_cap *= 2;
        seq_t *new_h = (seq_t *)realloc(h, (new_cap + 1) * sizeof(seq_t));
        if (!new_h) return (seq_t)0; /* allocation failed */
        h = new_h;
        h_capacity = new_cap;
    }

    /* Compute missing terms up to n */
    while (h_size < n) {
        seq_t v2 = h[i2] * (seq_t)2;
        seq_t v3 = h[i3] * (seq_t)3;
        seq_t next = (v2 <= v3) ? v2 : v3;
        ++h_size;
        h[h_size] = next;

        if (v2 == next) ++i2;
        if (v3 == next) ++i3;
    }

    if (n == 1) return (seq_t)1;
    /* Smallest prime factor is 2 if the number is even, else 3 */
    return (h[n] & (seq_t)1) ? (seq_t)3 : (seq_t)2;
}
