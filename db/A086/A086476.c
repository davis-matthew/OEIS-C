/*
 * A086476  Primes p such that 32p+1 and (p-1)/32 are both prime.
 * https://oeis.org/A086476
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 6, u32 n <= 31, u64 n <= 31, u128 n <= 31,
 *            big any n
 * Helpers:   is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A086476: primes p such that (p-1)/32 and 32p+1 are prime.
   The sequence is generated by an incremental search using the
   library routine is_prime(idx_t). */

#include <stdlib.h>
#include <stdbool.h>

/* The build provides an implementation of this function. */
#include "../utils/is_prime.h"

/* Storage for terms already found. */
static seq_t *terms   = NULL;     /* array of found primes p */
static idx_t term_count = 0;      /* number of stored terms */
static size_t term_cap   = 0;     /* current capacity */

/* The last value of (p-1)/32 that has been examined. */
static idx_t last_q = 0;

/* Ensure that at least n terms have been computed. */
static void
ensure_terms(idx_t n)
{
    /* Allocate initial storage if needed. */
    if (terms == NULL) {
        term_cap = 8;
        terms = (seq_t *)malloc(term_cap * sizeof(seq_t));
        if (terms == NULL) exit(1);
    }

    /* Generate terms until we have n of them. */
    while (term_count < n) {
        /* Find the next qualifying prime. */
        for (;;) {
            /* Stop if we run out of 64‑bit range (won't happen for n ≤ 10000). */
            if (last_q > UINT64_MAX / (idx_t)32) exit(1);

            if (!is_prime(last_q)) {
                ++last_q;
                continue;
            }

            /* Candidate prime p = 32*q + 1. */
            idx_t p = last_q * (idx_t)32 + (idx_t)1;
            if (!is_prime(p)) {
                ++last_q;
                continue;
            }

            /* Check 32*p + 1. */
            idx_t r = p * (idx_t)32 + (idx_t)1;
            if (!is_prime(r)) {
                ++last_q;
                continue;
            }

            /* Store the found prime. */
            if (term_count == term_cap) {
                term_cap *= 2;
                seq_t *tmp = (seq_t *)realloc(terms, term_cap * sizeof(seq_t));
                if (tmp == NULL) exit(1);
                terms = tmp;
            }
            terms[term_count++] = (seq_t)p;
            ++last_q;
            break;
        }
    }
}

seq_t a(idx_t n)
{
    if (n < (idx_t)1) return (seq_t)0; /* undefined for n <= 0 */
    ensure_terms(n);
    return terms[n - 1];
}
