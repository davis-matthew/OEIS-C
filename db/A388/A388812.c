/*
 * A388812  Decimal expansion of 3/5+1 / sqrt(5).
 * https://oeis.org/A388812
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, cons
 * Formula:   a(n) = decimal digit of (3+√5)/5, with a(1)=1, a(2)=0
 * Range:     u8 n <= 87, u16 n <= 87, u32 n <= 87, u64 n <= 87, u128 n <= 87,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   The sequence digits are generated by the digit‐by‐digit square‑root
   algorithm applied to the integer 20·10^(2k).  The recurrence is:

     S_k = floor(10^k·(3+√5)/5)
          = 6·10^(k-1) + floor(2·10^(k-1)·√5)

   From this we obtain a(n) (n≥3) as the (n‑2)-th decimal digit of √20.
   The implementation keeps the needed digits in a static table and
   extends it on demand.
*/

#include <stdint.h>
#include <stddef.h>
#include <string.h>

/* -----------------  Big integer helpers  ----------------- */
#define MAXLIMBS   1200          /* enough for ~10k decimal digits   */
#define BASE      1000000000U    /* 1e9 base                         */

typedef struct {
    size_t len;                  /* number of used limbs             */
    uint32_t d[MAXLIMBS];        /* little‑endian limbs (base BASE) */
} bi_t;

static void bi_zero(bi_t *x)                { x->len = 0; }

static void bi_set_small(bi_t *x, uint32_t v) {
    if (v == 0) { bi_zero(x); return; }
    x->len = 1; x->d[0] = v;
}

static void bi_copy(const bi_t *s, bi_t *t) {
    t->len = s->len;
    memcpy(t->d, s->d, s->len * sizeof(uint32_t));
}

static int bi_cmp(const bi_t *a, const bi_t *b) {
    if (a->len != b->len) return (a->len > b->len) ? 1 : -1;
    for (size_t i = a->len; i-- > 0; ) {
        if (a->d[i] != b->d[i]) return (a->d[i] > b->d[i]) ? 1 : -1;
    }
    return 0;
}

static void bi_add_small(const bi_t *a, uint32_t b, bi_t *r) {
    uint64_t carry = b;
    size_t i;
    for (i = 0; i < a->len; i++) {
        uint64_t s = (uint64_t)a->d[i] + carry;
        r->d[i] = (uint32_t)(s % BASE);
        carry   = s / BASE;
    }
    for (; carry; i++) {
        r->d[i] = (uint32_t)(carry % BASE);
        carry   = carry / BASE;
    }
    r->len = i;
}

static void bi_mul_small(const bi_t *a, uint32_t m, bi_t *r) {
    if (m == 0 || a->len == 0) { bi_zero(r); return; }
    uint64_t carry = 0;
    size_t i;
    for (i = 0; i < a->len; i++) {
        uint64_t p = (uint64_t)a->d[i] * m + carry;
        r->d[i] = (uint32_t)(p % BASE);
        carry   = p / BASE;
    }
    for (; carry; i++) {
        r->d[i] = (uint32_t)(carry % BASE);
        carry   = carry / BASE;
    }
    r->len = i;
}

static void bi_sub(const bi_t *a, const bi_t *b, bi_t *r) /* a>=b */
{
    int64_t borrow = 0;
    size_t i;
    for (i = 0; i < a->len; i++) {
        int64_t d = (int64_t)a->d[i] - (i < b->len ? b->d[i] : 0) - borrow;
        if (d < 0) { d += BASE; borrow = 1; } else borrow = 0;
        r->d[i] = (uint32_t)d;
    }
    while (i > 0 && r->d[i-1] == 0) i--;
    r->len = i;
}

/* -----------------  Digit generation (√20)  ----------------- */
#define MAX_DIGITS 20000      /* enough for n up to ~20000      */

static bi_t remainder, current;
static size_t group_index = 0;           /* processed groups (0 initially) */
static size_t digits_len  = 0;           /* generated decimal digits of √20 */
static uint8_t  digits[MAX_DIGITS] = {0};

/* generate one more decimal digit of √20 */
static void gen_next_digit(void)
{
    static bi_t tmp, P, tmp2, cand, tmp2a, tmp2b;

    /*  remainder = remainder * 100 + G
       G = 20 for group_index==0, else 0                       */
    bi_mul_small(&remainder, 100u, &tmp);
    bi_add_small(&tmp, (group_index == 0 ? 20u : 0u), &remainder);

    /*  P = 20 * current                                       */
    bi_mul_small(&current, 20u, &P);

    int best = 0;
    for (best = 9; best >= 0; best--) {
        bi_add_small(&P, (uint32_t)best, &tmp2);          /* P + d   */
        bi_mul_small(&tmp2, (uint32_t)best, &cand);      /* (P+d)*d */
        if (bi_cmp(&cand, &remainder) <= 0) break;
    }

    /*  remainder -= cand                                      */
    bi_sub(&remainder, &cand, &remainder);

    /*  current = current*10 + best                            */
    bi_mul_small(&current, 10u, &tmp2a);
    bi_add_small(&tmp2a, (uint32_t)best, &current);

    /* store decimal digit if it's after the integer part      */
    if (group_index > 0) {
        if (digits_len < MAX_DIGITS) digits[digits_len++] = (uint8_t)best;
    }

    group_index++;
}

/* ensure at least k decimal digits of √20 are known            */
static void ensure_digits(size_t k)
{
    while (digits_len < k) gen_next_digit();
}

/* -----------------  Sequence function  ----------------- */
seq_t a(idx_t n)
{
    if (n == 1) return 1;

    if (n == 2) {
        ensure_digits(1);                     /* first decimal digit */
        return (seq_t)((6u + digits[0]) % 10u);
    }

    size_t k = (size_t)(n - 2);                 /* needed decimal digits */
    ensure_digits(k);
    return (seq_t)(digits[k - 1] % 10u);
}
