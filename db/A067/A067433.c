/*
 * A067433  Triangle in which row n gives trajectory of n under the map k ->
 *          k/3 if k is divisible by 3, otherwise k -> next multiple of 3,
 *          stopping when reaching 1 (the initial term n is not included).
 * https://oeis.org/A067433
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, tabf, nonn
 * Formula:   not stated
 * Range:     u8 n <= 84, u16 n <= 84, u32 n <= 84, u64 n <= 84, u128 n <= 84,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n) as the nth entry (1‑based) in the flattened triangle of
 * trajectories generated by:
 *   if k % 3 == 0    -> k = k / 3
 *   otherwise       -> k = k + (3 - k % 3)
 *  The initial term n is not included; each row ends at 1.
 * This implements OEIS sequence A067433.
 */
seq_t a(idx_t n)
{
    idx_t pos = 0;          /* current position in the flattened triangle */
    for (idx_t s = 1; ; ++s) {
        if (s == 1) {       /* row for starting value 1 contains only 1 */
            ++pos;
            if (pos == n) return (seq_t)1;
            continue;
        }

        seq_t k = (seq_t)s;
        do {
            seq_t rem = k % (seq_t)3;
            if (rem == (seq_t)0)
                k = k / (seq_t)3;
            else
                k = k + (seq_t)(3 - rem);

            ++pos;
            if (pos == n) return k;
        } while (k != (seq_t)1);
    }
}
