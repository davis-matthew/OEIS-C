/*
 * A067484  Powers of 6 with initial digit 6.
 * https://oeis.org/A067484
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 1, u32 n <= 2, u64 n <= 3, u128 n <= 6,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Search: a(n) is the n-th power of 6 whose first decimal digit is 6. */
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>
#include <math.h>

/*
 * Compute the n-th term of OEIS A067484 – powers of 6 having leading
 * decimal digit 6.  The implementation stores a growing list of found
 * terms; each new power 6^k is generated by multiplying the previous
 * power by 6.  The leading digit is tested by tracking the fractional
 * part of k*log10(6) using long double arithmetic.
 */
seq_t a(idx_t n)
{
    /* static cache of terms already found */
    static seq_t *terms = NULL;
    static size_t terms_cnt = 0;
    static size_t terms_cap = 0;

    /* state for generating powers of 6 in order */
    static bool initialized = false;
    static idx_t cur_k;          /* current exponent k  (k >= 1)   */
    static seq_t cur_val;        /* current value 6^k              */
    static long double frac;     /* fractional part of k*log10(6)  */

    /* constants */
    const long double log10_6 =
        0.7781512503836436325029362301626901628535784059145L; /* log10(6) */

    /* initialise on first call */
    if (!initialized) {
        terms_cap = 16;
        terms = (seq_t *)malloc(sizeof(seq_t) * terms_cap);

        cur_k   = 1;
        cur_val = (seq_t)6;          /* 6^1 */
        terms[0] = cur_val;
        terms_cnt = 1;

        frac = log10_6;              /* fractional part for k=1 */

        initialized = true;
    }

    /* generate further terms until we have requested amount */
    while (terms_cnt < (size_t)n) {
        /* advance to next exponent */
        cur_k++;

        /* update fractional part of k*log10(6) */
        frac += log10_6;
        if (frac >= 1.0L)
            frac -= 1.0L;

        /* compute next power of 6 */
        cur_val = (seq_t)(cur_val * (seq_t)6);

        /* determine leading decimal digit */
        long double first_digit = powl(10.0L, frac);
        int        leading      = (int)(first_digit + 1e-12L);   /* 0 < first_digit < 10 */

        if (leading == 6) {
            /* store the term */
            if (terms_cnt == terms_cap) {
                terms_cap <<= 1;
                terms = (seq_t *)realloc(terms, sizeof(seq_t) * terms_cap);
            }
            terms[terms_cnt++] = cur_val;
        }
    }

    return terms[n - 1];
}
