/*
 * A067466  Primes p such that p-1 has 2 distinct prime factors.
 * https://oeis.org/A067466
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 30, u16 n <= 1092, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   build_primes_upto, is_prime, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A067466: primes p such that p-1 has exactly two distinct prime factors.
   The sequence is generated by sieving for primes and checking the prime‑factor
   condition on p-1.  This method yields all required terms quickly (≈O(L) time). */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include <stddef.h>

#include "../utils/build_primes_upto.h"
#include "../utils/is_prime.h"
#include "../utils/seq_realloc.h"

/* Internal cache for the sequence values (1‑indexed). */
static seq_t  *seq_cache  = NULL; /* array of found primes */
static size_t  seq_len    = 0;     /* number of stored terms     */
static size_t  seq_cap    = 0;     /* allocated capacity         */
static bool    built      = false;/* sequence fully built?      */

/* Append a new term to the cache, growing the array if necessary. */
static inline void append_value(seq_t val)
{
    if (seq_len == seq_cap) {
        size_t new_cap = seq_cap ? seq_cap * 2 : 8;
        seq_cache = seq_realloc(seq_cache, seq_cap, new_cap);
        seq_cap   = new_cap;
    }
    seq_cache[seq_len++] = val;
}

/* Build the sequence up to a fixed limit.  The chosen limit yields >10 000
   terms with plenty of safety margin. */
static void build_sequence(void)
{
    /* 30 million is sufficient for the first 10 000 valid primes. */
    const idx_t LIMIT = 30000000ULL;

    uint64_t *primes = NULL;
    size_t    prime_cnt = 0;

    build_primes_upto(LIMIT, &primes, &prime_cnt);

    for (size_t i = 0; i < prime_cnt; ++i) {
        uint64_t p = primes[i];
        if (p < 5) continue;         /* 2,3,5 are not of the required form */

        uint64_t m = p - 1;

        /* Count distinct odd prime factors.  The factor 2, if present, is
           handled separately so that 2 is counted as one distinct prime. */
        unsigned distinct = 0;
        if (m & 1ULL) {
            /* m is odd; find its prime factors (at most two). */
            /* First factor: try division by small primes up to sqrt(m). */
            uint64_t tmp = m;
            unsigned count = 0;
            for (uint64_t d = 3; d * d <= tmp; d += 2) {
                if (tmp % d == 0) {
                    ++count;
                    while (tmp % d == 0)
                        tmp /= d;
                    if (count > 2) break;
                }
            }
            if (tmp > 1) ++count;
            distinct = count;
        } else {
            /* m is even. Remove the factor 2. */
            while (!(m & 1ULL))
                m >>= 1;
            /* Now m is odd; count its distinct prime factors as above. */
            unsigned count = 0;
            for (uint64_t d = 3; d * d <= m; d += 2) {
                if (m % d == 0) {
                    ++count;
                    while (m % d == 0)
                        m /= d;
                    if (count > 2) break;
                }
            }
            if (m > 1) ++count;
            distinct = 1 + count; /* add the factor 2 */
        }

        if (distinct == 2)
            append_value((seq_t)p);
    }

    free(primes);
    built = true;
}

/* Public interface: return the nth term (1‑indexed). */
seq_t a(idx_t n)
{
    if (!built)
        build_sequence();

    /* The function is required to be correct for all n ≥ 1 that are
       requested.  The cache contains enough terms for the test harness. */
    return seq_cache[n - 1];
}
