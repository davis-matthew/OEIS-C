/*
 * A170436  Number of reduced words of length n in Coxeter group on 43
 *          generators S_i with relations (S_i)^2 = (S_i S_j)^44 = I.
 * https://oeis.org/A170436
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 2, u32 n <= 5, u64 n <= 11, u128 n <= 14,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A170436
   Recurrence:
     a(0) = 1
     a(n) = 43 * 42^(n-1)          for 1 ≤ n ≤ 43
     a(n) = 41 * Σ_{i=1}^{43} a(n-i) - 861 * a(n-44)   for n ≥ 44
   The first 44 terms are generated by the explicit formula above. */

#include <stddef.h>  /* for size_t */

seq_t a(idx_t n)
{
    /* -------------------------------------------------------------------------
       Handle the trivial cases manually.
       ------------------------------------------------------------------------- */
    if (n == 0) {
        return (seq_t)1;
    }
    if (n <= 43u) {
        seq_t res = (seq_t)43;
        /* res = 43 * 42^(n-1)  (iteratively avoid overflow when seq_t is small) */
        for (idx_t i = 2u; i <= n; ++i) {
            res = res * (seq_t)42;
        }
        return res;
    }

    /* -------------------------------------------------------------------------
       Prepare the first 44 values once; they are needed for the recurrence.
       ------------------------------------------------------------------------- */
    static seq_t init[44];
    static int init_done = 0;
    if (!init_done) {
        init[0] = (seq_t)1;            /* a(0) */
        init[1] = (seq_t)43;           /* a(1) = 43 * 42^0 */
        for (idx_t i = 2u; i <= 43u; ++i) {
            init[i] = init[i - 1] * (seq_t)42;   /* a(i) = 42 * a(i-1) for 2 ≤ i ≤ 43 */
        }
        init_done = 1;
    }

    /* -------------------------------------------------------------------------
       Use a circular buffer of length 44 to store the last 44 terms.
       ------------------------------------------------------------------------- */
    static seq_t buf[44];
    /* Copy the initial 44 terms into the buffer. */
    for (idx_t i = 0u; i < 44u; ++i) {
        buf[i] = init[i];
    }

    /* Sum of the last 43 terms (a[1] … a[43]) needed for the first recurrence step. */
    seq_t sum_last43 = (seq_t)0;
    for (idx_t i = 1u; i <= 43u; ++i) {
        sum_last43 += buf[i];
    }

    seq_t an = (seq_t)0;  /* Value of a(n) to be returned. */

    /* -------------------------------------------------------------------------
       Compute terms from 44 up to n using the recurrence.
       ------------------------------------------------------------------------- */
    for (idx_t k = 44u; k <= n; ++k) {
        /* a(k) = 41 * sum_last43 - 861 * a(k-44)   (indices modulo 44) */
        an = (seq_t)41 * sum_last43 - (seq_t)861 * buf[(k - 44u) % 44u];

        /* Place the new value into the buffer at position k % 44 */
        size_t idx_store = k % 44u;
        /* a(k-43) will leave the sliding window in the next step.
           Its index is (k-43) % 44. */
        seq_t leaving = buf[(k - 43u) % 44u];

        buf[idx_store] = an;                /* update buffer with a(k) */

        /* Update the sum of the last 43 terms for the next iteration */
        sum_last43 = sum_last43 - leaving + an;
    }

    return an;
}
