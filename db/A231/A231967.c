/*
 * A231967  Squarefree numbers (A005117) of the form p*q*r with prime factors
 *          p, q, r with q = 2*p + 1 and r = 2*q + 1.
 * https://oeis.org/A231967
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 3, u32 n <= 9, u64 n <= 1000, u128 n <= 1000,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A231967: squarefree numbers of the form p*q*r
   where p, q = 2p+1, r = 4p+3 are primes.  The function returns
   the n-th such number (1‑based).  The terms are generated by
   enumerating primes p and testing the two derived primes.  The
   implementation builds a simple sieve of Eratosthenes up to a
   dynamically expanding limit and counts qualifying primes.  It
   recomputes the sieve from scratch each time the limit is increased
   (the sieve size never exceeds a few million for the required
   n=10 000).  Results fit in seq_t exactly whenever the value
   itself fits in the chosen integer size.  */

#include <stdlib.h>
#include <stdint.h>
#include <string.h>

/* Helper: add a prime to the dynamic array */
static void add_prime(uint64_t p, uint64_t **primes, size_t *cnt, size_t *cap)
{
    if (*cnt == *cap) {
        size_t new_cap = (*cap == 0) ? 64 : *cap << 1;
        uint64_t *tmp = (uint64_t *)realloc(*primes, new_cap * sizeof(uint64_t));
        if (!tmp) abort();
        *primes = tmp;
        *cap   = new_cap;
    }
    (*primes)[(*cnt)++] = p;
}

/* Build a prime sieve up to `limit` and return prime list.
   The caller must free the returned array.  */
static void build_sieve(uint64_t limit,
                        uint8_t **sieve_out,
                        uint64_t **primes_out,
                        size_t *cnt_out)
{
    /* Allocate and clear sieve array */
    uint8_t *sieve = (uint8_t *)calloc((size_t)(limit + 1), 1);
    if (!sieve) abort();

    /* Eratosthenes */
    for (uint64_t i = 2; i * i <= limit; ++i) {
        if (!sieve[i]) {
            for (uint64_t j = i * i; j <= limit; j += i)
                sieve[j] = 1;
        }
    }

    /* Count primes and collect them */
    size_t cnt = 0, cap = 64;
    uint64_t *primes = (uint64_t *)malloc(cap * sizeof(uint64_t));
    if (!primes) abort();
    for (uint64_t i = 2; i <= limit; ++i) {
        if (!sieve[i]) {
            if (cnt == cap) {
                cap <<= 1;
                uint64_t *tmp = (uint64_t *)realloc(primes, cap * sizeof(uint64_t));
                if (!tmp) abort();
                primes = tmp;
            }
            primes[cnt++] = i;
        }
    }

    *sieve_out   = sieve;
    *primes_out  = primes;
    *cnt_out     = cnt;
}

/* Main sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;        /* undefined below offset */

    uint64_t limit = 1000;              /* starting upper bound for sieve */

    while (1) {
        uint8_t *sieve = NULL;
        uint64_t *primes = NULL;
        size_t primes_cnt = 0;

        /* Build sieve up to current limit */
        build_sieve(limit, &sieve, &primes, &primes_cnt);

        /* Count qualifying primes up to this limit */
        size_t count = 0;
        for (size_t i = 0; i < primes_cnt; ++i) {
            uint64_t p = primes[i];
            uint64_t q = 2 * p + 1;
            uint64_t r = 4 * p + 3;

            if (r > limit)
                break;                  /* need larger limit for further primes */

            if (!sieve[q] && !sieve[r]) {
                ++count;
                if (count == (size_t)n) {
                    seq_t val = (seq_t)p * (seq_t)q * (seq_t)r;
                    free(sieve);
                    free(primes);
                    return val;
                }
            }
        }

        /* Not enough terms yet: extend limit and try again */
        free(sieve);
        free(primes);
        if (limit > UINT64_MAX / 2)
            limit = UINT64_MAX - 1;   /* safeguard against overflow */
        else
            limit = limit * 2 + 1;
    }
}
