/*
 * A315733  Coordination sequence Gal.6.642.6 where Gal.u.t.v denotes the
 *          coordination sequence for a vertex of type v in tiling number t in
 *          the Galebach list of u-uniform tilings.
 * https://oeis.org/A315733
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 45, u16 n <= 49, u32 n <= 49, u64 n <= 49, u128 n <= 49,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence:
 * a(0) = 1, a(1) = 6.
 * For n ≥ 2,
 *   a(n) = a(n-1) + d(n),
 *   where d(n) = 4 if n is a “special” index,
 *                6 otherwise.
 *
 * The set of special indices is
 *   S = {4, 8, 15, 19, 26, 30, 37, 41, 48, 52, …},
 *   generated by s0 = 4 and
 *   s_{k+1} = s_k + 4  if k is even,
 *            = s_k + 7  if k is odd.           */

#include <stdlib.h>
#include <stddef.h>
#include <stdbool.h>

/* ---------- Special index storage ---------- */
static idx_t *specials = NULL;
static size_t spec_len = 0;
static size_t spec_cap = 0;
static idx_t next_special = 4;
static bool step4 = true;

/* Generate special indices up to the given limit. */
static void generate_specials_up_to(idx_t limit)
{
    if (!specials) {
        spec_cap = 16;
        specials = (idx_t *)malloc(spec_cap * sizeof(idx_t));
    }
    while (next_special <= limit) {
        if (spec_len == spec_cap) {
            spec_cap *= 2;
            specials = (idx_t *)realloc(specials, spec_cap * sizeof(idx_t));
        }
        specials[spec_len++] = next_special;
        next_special += step4 ? 4 : 7;
        step4 = !step4;
    }
}

/* Check whether n is a special index. */
static bool is_special(idx_t n)
{
    if (n < 4) return false;
    generate_specials_up_to(n);
    /* Binary search over the sorted special list. */
    size_t lo = 0, hi = spec_len;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (specials[mid] == n) return true;
        if (specials[mid] < n)
            lo = mid + 1;
        else
            hi = mid;
    }
    return false;
}

/* ---------- Sequence cache storage ---------- */
static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;

/* Extend cache to include index n. */
static void ensure_cache(idx_t n)
{
    if (!cache) {
        cache_cap = n + 1 > 64 ? n + 1 : 64;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        cache[0] = (seq_t)1;
        cache[1] = (seq_t)6;
        cache_len = 2;
    }
    if (n >= cache_cap) {
        cache_cap = n + 1;
        cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
    }
    for (idx_t i = cache_len; i <= n; ++i) {
        seq_t diff = is_special(i) ? (seq_t)4 : (seq_t)6;
        cache[i] = cache[i - 1] + diff;
    }
    cache_len = n + 1;
}

/* Required public function. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)1;        /* quick answer for the offset */
    if (n == 1) return (seq_t)6;
    ensure_cache(n);
    return cache[n];
}
