/* 
   OEIS: A315823 
   Coordination sequence Gal.6.507.3
   Recurrence:  a(n) = 2*a(n-6) - a(n-12)  for n > 12
   Initial values (0 ≤ n ≤ 12):
   1, 6, 6, 18, 24, 18, 36, 30, 36, 54, 54, 42, 72
*/
seq_t a(idx_t n)
{
    /* Base values.  All other terms are generated by the recurrence. */
    static const seq_t init[13] = {
        (seq_t)1,  (seq_t)6,  (seq_t)6,  (seq_t)18,
        (seq_t)24, (seq_t)18, (seq_t)36, (seq_t)30,
        (seq_t)36, (seq_t)54, (seq_t)54, (seq_t)42,
        (seq_t)72
    };

    if (n < 13)
        return init[n];

    /* Circular buffer of the last 13 terms */
    seq_t buf[13];
    for (int i = 0; i < 13; ++i)
        buf[i] = init[i];

    for (idx_t idx = 13; idx <= n; ++idx) {
        /* recurrence: a(idx) = 2*a(idx-6) - a(idx-12) */
        seq_t val = (seq_t)2 * buf[(idx - 6) % 13] - buf[(idx - 12) % 13];
        buf[idx % 13] = val;
    }
    return buf[n % 13];
}
