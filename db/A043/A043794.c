/* Sequence A043794: Numbers whose number of runs in base 3 is congruent to 3 (mod 7).
   Generated by brute‑force enumeration of integers, counting runs in base 3
   and selecting those with run count ≡ 3 (mod 7). */
#include <stdbool.h>
#include <stdlib.h>

/* Helper: test whether a number's base‑3 run count ≡ 3 (mod 7). */
static inline bool is_target(seq_t x)
{
    idx_t runs = 0;
    int prev_digit = -1;
    seq_t v = x;
    while (v > 0) {
        int d = (int)(v % 3);
        if (d != prev_digit) {
            runs++;
            prev_digit = d;
        }
        v /= 3;
    }
    return (runs % 7) == 3;
}

/* Static cache for generated terms. */
static seq_t *cache      = NULL;   /* pointer to array of terms */
static size_t  cache_cap = 0;     /* current allocated capacity */
static size_t  cache_len = 0;     /* number of cached terms */
static idx_t   next_candidate = 1;/* next integer to test */

/* Ensure that the cache holds at least n terms. */
static void ensure_cache(idx_t n)
{
    /* Expand the cache until we have at least n elements. */
    while (cache_len < n) {
        /* Find next integer that satisfies the condition. */
        while (!is_target((seq_t)next_candidate)) {
            next_candidate++;
        }

        /* Grow the array if needed. */
        if (cache_len >= cache_cap) {
            size_t new_cap = cache_cap ? cache_cap * 2 : 16;
            seq_t *new_cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            if (!new_cache) abort();           /* memory exhausted */
            cache = new_cache;
            cache_cap = new_cap;
        }

        /* Store the term and advance. */
        cache[cache_len++] = (seq_t)next_candidate;
        next_candidate++;
    }
}

/* External symbol required by the build system. */
seq_t a(idx_t n)
{
    if (n < 1)
        return 0;                 /* undefined for n=0, return 0 as fallback */

    ensure_cache(n);              /* generate terms up to position n */

    return cache[n - 1];          /* a(1) corresponds to index 0 */
}
