/*
 * A043258  Numbers k such that 7 and 8 occur juxtaposed in the base-10
 *          representation of k but not of k-1.
 * https://oeis.org/A043258
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 41, u32 n <= 41, u64 n <= 41, u128 n <= 41,
 *            big any n
 * Helpers:   has78or87
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) is the n-th integer k such that the decimal representation of k contains
   the adjacent digits "78" or "87" while the decimal representation of k-1 does
   not. The sequence is generated by scanning successive integers and testing
   the pattern. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/has78or87.h"

/* Forward declaration of pattern test. */
static bool has78or87(seq_t x);

/* Compute the n-th term of A043258. */
seq_t a(idx_t n)
{
    /* Static cache to memoise the sequence. */
    static seq_t *cache = NULL;
    static idx_t cache_len = 0, cache_cap = 0;

    /* Current integer being inspected. */
    static seq_t next_num = (seq_t)1;
    /* Whether the previous integer (next_num-1) has the pattern. */
    static bool prev_has = false;

    while (cache_len < n) {
        bool cur_has = has78or87(next_num);

        /* Record the number if it is a new occurrence of the pattern. */
        if (cur_has && !prev_has) {
            if (cache_len >= cache_cap) {
                size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) abort();       /* allocation failure */
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = next_num;
        }

        prev_has = cur_has;
        next_num = next_num + (seq_t)1;
    }

    return cache[(size_t)(n - 1)];
}
