/* A043850: Numbers k such that the number of runs in the base‑4
   representation of k is congruent to 0 mod 8.
   The sequence is generated by brute‑force search over integers,
   counting runs in base 4 for each candidate.  It is efficient for
   n up to about 10 000 (≈80 000 tested numbers). */
#include <stdlib.h>
#include <stdbool.h>

seq_t a(idx_t n) {
    /* static state: cache of found terms, current length and last tested number */
    static seq_t *cache = NULL;
    static size_t cap = 0;
    static size_t length = 0;   /* number of terms stored in cache */
    static seq_t last_k = 0;    /* last integer tested (largest k processed) */

    if (n == 0) return 0; /* undefined for this sequence, but avoid UB */

    /* grow cache if we need more terms */
    if (length < (size_t)n) {
        /* initial allocation */
        if (!cache) {
            cap = 1024;
            cache = (seq_t *)malloc(cap * sizeof(seq_t));
            if (!cache) return 0; /* allocation failure, unlikely */
        }

        seq_t k = last_k + 1;            /* start from next integer */
        while (length < (size_t)n) {
            seq_t temp = k;
            int runs = 0;
            int prev_digit = -1;

            /* count runs in base‑4 representation of k */
            while (temp > 0) {
                int digit = (int)(temp % 4);
                if (runs == 0 || digit != prev_digit) {
                    runs++;
                    prev_digit = digit;
                }
                temp /= 4;
            }

            /* if k has 0 runs (k == 0) it would have runs==0,
               but we never test k==0 */
            if (runs % 8 == 0) {
                if (length >= cap) {
                    cap *= 2;
                    cache = (seq_t *)realloc(cache, cap * sizeof(seq_t));
                    if (!cache) return 0; /* allocation failure */
                }
                cache[length++] = k;
            }

            k++;
        }
        last_k = k - 1;
    }

    return cache[n - 1];
}
