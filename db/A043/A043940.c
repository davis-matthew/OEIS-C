/*
 * A043940  Numbers k such that 1 and 3 occur juxtaposed in the base-8
 *          representation of k but not of k+1.
 * https://oeis.org/A043940
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 1849, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 65 terms through n = 9774 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Search: a(n) is the n-th integer k such that k has the digits 1 and 3
   adjacent (in either order) in its base‑8 representation while k+1 does
   not.  The sequence is generated by brute force with memoisation. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/mem.h"

static bool has_adjacent_13(seq_t x) {
    /* Return true if base‑8 digits of x contain adjacent 1 and 3
       (in either order). */
    if (x == (seq_t)0) return false;
    int prev = -1;
    seq_t cur = x;
    while (cur > (seq_t)0) {
        int d = (int)(cur % (seq_t)8U);            /* current least‑significant digit */
        if (prev != -1) {
            if ((prev == 1 && d == 3) || (prev == 3 && d == 1))
                return true;
        }
        prev = d;
        cur /= (seq_t)8U;
    }
    return false;
}

static seq_t *cache = NULL;       /* cached terms */
static size_t cache_cap = 0;      /* allocated size of cache */
static size_t cache_len = 0;      /* number of cached terms */
static idx_t last_checked = 0;    /* last integer examined */

/* Grow the cache to accommodate at least new_cap elements. */
static void grow_cache(size_t new_cap) {
    if (new_cap <= cache_cap) return;
    seq_t *tmp = mem_resize(seq_t, cache, new_cap);
    cache = tmp;
    cache_cap = new_cap;
}

/* Ensure that the cache contains at least required terms. */
static void ensure_cache(idx_t required) {
    while (cache_len < (size_t)required) {
        idx_t k = last_checked + 1;              /* next integer to test */
        seq_t val = (seq_t)k;

        if (has_adjacent_13(val) && !has_adjacent_13(val + (seq_t)1))
            /* store it in the cache */
            if (cache_len == cache_cap)
                grow_cache(cache_cap ? cache_cap * 2 : 16);
        if (cache_len == cache_cap ? cache_len : cache_cap) {
            /* we only increment cache_len if we stored a value */
        }
        if (has_adjacent_13(val) && !has_adjacent_13(val + (seq_t)1))
            cache[cache_len++] = val;

        last_checked = k;
    }
}

seq_t a(idx_t n) {
    if (n == 0) return (seq_t)0;                 /* undefined for n=0, safe return */
    ensure_cache(n);
    return cache[n - 1];
}
