/*
 * A043761  Number of runs in the base 2 representation of n is congruent to 7
 *          mod 9.
 * https://oeis.org/A043761
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 46, u32 n <= 46, u64 n <= 46, u128 n <= 46,
 *            big any n
 * Helpers:   runs_mod9
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: a(n) = the n‑th positive integer whose binary representation
 * contains a number of runs (consecutive equal bits) that is congruent
 * to 7 modulo 9. The values are generated by a simple search.
 */

#include <stdlib.h>
#include "../utils/runs_mod9.h"

static seq_t *cache = NULL;      /* stored terms */
static size_t  cache_cap = 0;    /* allocated capacity */
static idx_t   cache_size = 0;   /* number of terms stored */
static idx_t   last_checked = 0; /* last integer examined */

/* Ensure that the cache can hold at least 'needed' elements. */
static void ensure_cache_cap(size_t needed)
{
    if (needed <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
    while (new_cap < needed)
        new_cap *= 2;
    seq_t *newp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!newp) {
        /* Allocation failed – terminate as per simple error handling policy. */
        exit(1);
    }
    cache = newp;
    cache_cap = new_cap;
}

/* External linkage as required. */
seq_t a(idx_t n)
{
    if (n == 0)   /* offset is 1: a(1) is first term */
        return (seq_t)0;

    /* Generate terms until we have at least n stored. */
    while (cache_size < n) {
        ++last_checked;                     /* next integer to test */
        seq_t cand = (seq_t)last_checked;   /* cast idx_t to seq_t safely */

        if (runs_mod9(cand) == 7) {         /* satisfies the property */
            ensure_cache_cap(cache_size + 1);
            cache[cache_size++] = cand;
        }
    }

    return cache[n - 1];
}
