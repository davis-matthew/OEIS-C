/*  Find numbers k where 5 and 6 occur juxtaposed in the base‑8
 *  representation of k but not of k+1.
 *  The function a(idx_t n) returns the n‑th such number
 *  (a(1) = 46, a(2) = 53, …).  The sequence is generated by a
 *  simple search and cached for fast subsequent queries. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/has56or65_oct.h"

/* number found for index n; static cache for memoisation */
static seq_t *cache      = NULL;   /* array of found terms          */
static idx_t  capacity   = 0;      /* allocated capacity of cache   */
static idx_t  count      = 0;      /* number of terms stored        */
static seq_t  start_next = (seq_t)1;/* next integer to examine      */

/*--- build the cache up to at least n terms ---------------------*/
static void build_up_to(idx_t n)
{
    if (count >= n) return;          /* already enough terms */

    /* enlarge capacity to a power of two ≥ n */
    if (capacity == 0) capacity = 4;
    while (capacity < n) capacity <<= 1;

    /* reallocate the cache array */
    if (cache == NULL) {
        cache = (seq_t *)malloc(capacity * sizeof(seq_t));
        if (cache == NULL) abort();  /* allocation failed */
    } else {
        seq_t *tmp = (seq_t *)realloc(cache, capacity * sizeof(seq_t));
        if (tmp == NULL) abort();    /* allocation failed */
        cache = tmp;
    }

    /* search successive integers, collecting qualifying terms */
    seq_t cur = start_next;
    while (count < n) {
        if (has56or65_oct(cur) && !has56or65_oct(cur + (seq_t)1))
            cache[count++] = cur;
        cur++;
    }
    start_next = cur;      /* next number to test in future calls   */
}

/*--- public sequence function ------------------------------------*/
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0; /* undefined for n<1, safe fallback */
    build_up_to(n);
    return cache[n - 1];
}
