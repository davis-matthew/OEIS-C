/*
 * A043527  Numbers having three 9's in base 10.
 * https://oeis.org/A043527
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 221, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 53 terms through n = 9408 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/mem.h"

static bool has_three_nines(seq_t x)
{
    unsigned int cnt = 0;
    while (x > (seq_t)0) {
        if ((x % (seq_t)10) == (seq_t)9) {
            ++cnt;
            if (cnt > 3)
                return false;
        }
        x /= (seq_t)10;
    }
    return cnt == 3;
}

/* Computes the n-th number that contains exactly three digit-9 in decimal. */
/* The sequence is generated by incrementally scanning integers on demand and */
/* memoising all found terms.  The algorithm runs in O(total terms generated). */

static seq_t *cache = NULL;        /* array of found terms in ascending order */
static idx_t  cache_size = 0;      /* number of terms currently stored      */
static size_t cache_cap   = 0;      /* allocated capacity                    */
static seq_t  next_candidate = (seq_t)1000; /* next integer to test */
static idx_t  found_terms   = 1;    /* number of terms already generated (99..9) */

/* Ensure cache has capacity for at least new_size elements */
static void ensure_cache_capacity(size_t new_size)
{
    if (new_size <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 4;
    if (new_cap < new_size)
        new_cap = new_size;
    seq_t *p = mem_resize(seq_t, cache, new_cap);
    if (!p)
        abort(); /* memory allocation failed */
    cache = p;
    cache_cap = new_cap;
}

seq_t a(idx_t n)
{
    if (n == (idx_t)0)
        return (seq_t)0; /* undefined for offset 0, but return 0 for safety */

    /* initialise cache on first call */
    if (!cache) {
        cache_cap = 4;
        cache = mem_new(seq_t, cache_cap);
        if (!cache)
            abort();
        cache[0] = (seq_t)999;      /* a(1) */
        cache_size = 1;
        found_terms = 1;
        next_candidate = (seq_t)1000;
    }

    /* generate terms until we have at least n terms stored */
    while (found_terms < n) {
        if (has_three_nines(next_candidate)) {
            /* store the new term */
            ensure_cache_capacity(cache_size + 1);
            cache[cache_size] = next_candidate;
            ++cache_size;
            ++found_terms;
        }
        ++next_candidate;
    }

    return cache[n - 1];
}
