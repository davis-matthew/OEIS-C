/* Sequence: numbers whose base‑6 representation has exactly 8 runs.
   Generated by a recursive search over digit patterns. */

#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

/* --- Cache for memoised terms --------------------------------------- */
static seq_t *cache      = NULL;
static size_t cache_cap  = 0;
static size_t cache_size = 0;

/* Append a new term, expanding the array if needed. */
static void add_value(seq_t val)
{
    if (cache_size == cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 128 : cache_cap * 2;
        seq_t *tmp = (seq_t *)malloc(new_cap * sizeof(seq_t));
        if (!tmp) abort(); /* allocation failure */
        if (cache)
            memcpy(tmp, cache, cache_size * sizeof(seq_t));
        free(cache);
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_size++] = val;
}

/* Recursive generator of all base‑6 numbers of length L that have
   exactly 8 runs.  The digits are generated in increasing order,
   so the numbers are added to 'cache' in ascending order as well. */
static void gen_len(int L, int pos, int last_digit, int run_count, seq_t cur)
{
    if (pos == L) {
        if (run_count == 8)
            add_value(cur);
        return;
    }
    int start = (pos == 0) ? 1 : 0;          /* leading digit cannot be 0 */
    for (int d = start; d < 6; ++d) {
        int new_run = run_count;
        if (pos == 0)
            new_run = 1;
        else if (d != last_digit)
            new_run++;

        int remaining = L - pos - 1;
        if (new_run > 8)         continue;   /* too many runs already */
        if (remaining + new_run < 8) continue;/* impossible to reach 8 runs */

        seq_t nxt = cur * (seq_t)6 + (seq_t)d;
        gen_len(L, pos + 1, d, new_run, nxt);
    }
}

/* Main entry point.  The function ensures that the cache contains
   at least 'n' terms and returns the n‑th term (1‑based index). */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;  /* undefined for n = 0, harmless */

    /* Generate further terms until we have 'n' of them. */
    static int current_length = 8;          /* start with 8‑digit numbers */
    while (cache_size < (size_t)n) {
        gen_len(current_length, 0, -1, 0, (seq_t)0);
        current_length++;                   /* next number length */
    }

    return cache[(size_t)(n - 1)];
}
