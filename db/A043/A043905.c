/* Sequence A043905: numbers k such that 2 and 3 occur juxtaposed in the
   base‑6 representation of k but not in the base‑6 representation of k+1.
   The sequence is generated by a simple brute‑force search. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/has_adjacent_23.h"

/* External‑linkage sequence function. */
seq_t a(idx_t n)
{
    static seq_t *cache = NULL;      /* cached terms */
    static idx_t cache_len = 0;      /* number of terms stored */
    static idx_t cache_cap = 0;      /* allocated capacity */
    static seq_t next_k = (seq_t)0;  /* next candidate to test */

    /* Ensure we have at least n terms cached. */
    while (cache_len < n) {
        /* Test the next candidate. */
        next_k = next_k + (seq_t)1;
        if (has_adjacent_23(next_k) && !has_adjacent_23(next_k + (seq_t)1)) {
            /* Grow the cache if needed. */
            if (cache_len == cache_cap) {
                idx_t new_cap = cache_cap ? cache_cap * 2 : 128;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) exit(1);          /* allocation failure */
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = next_k;
        }
    }

    return cache[n - 1];
}
