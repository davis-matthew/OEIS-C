/* OEIS A043823: Numbers k such that the number of runs in the base‑3
   representation of k is congruent to 8 (mod 10).  The sequence is
   generated by brute‑forcing k, counting runs in base 3, and storing the
   qualifying values.  The function is memoised so that any sequence of
   calls runs in O(n) time overall. */
#include <stdlib.h>

/* Count runs in the base‑3 expansion of x. */
static inline int runs_in_base3(seq_t x)
{
    /* Base‑3 representation of 0 is “0”, which is a single run. */
    if (x == 0)
        return 1;

    seq_t prev = (seq_t)-1;  /* impossible digit (not 0,1,2) */
    int count = 0;

    while (x != 0)
    {
        seq_t digit = x % 3;
        if (digit != prev)
        {
            ++count;
            prev = digit;
        }
        x = x / 3;
    }
    return count;
}

/* Cache of discovered terms.  All variables are static so that the cache
   is shared between calls. */
static seq_t *cache   = NULL;
static idx_t cache_size = 0;   /* how many terms are stored */
static idx_t cache_cap  = 0;   /* allocated capacity of cache   */
static seq_t next_k = 0;       /* next integer to test */

/* Append a value to the cache, growing the array if necessary. */
static void cache_push(seq_t val)
{
    if (cache_size == cache_cap)
    {
        idx_t new_cap = (cache_cap == 0) ? 16 : (cache_cap << 1);
        /* The cast is required for C++. */
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_size++] = val;
}

/* Public sequence function.  n is a 1‑based index. */
seq_t a(idx_t n)
{
    /* 0 is undefined for this sequence – return 0 for safety. */
    if (n == 0)
        return 0;

    /* Extend the cache until it contains at least n terms. */
    while (cache_size < n)
    {
        ++next_k;
        if (runs_in_base3(next_k) % 10 == 8)
            cache_push(next_k);
    }

    /* Return the requested term. */
    return cache[n - 1];
}
