/* Sequence A043736: numbers whose number of runs in binary representation
   is congruent to 3 (mod 6).  The sequence is generated by brute‑force search
   for the required number of runs.  */
#include <stdint.h>

seq_t a(idx_t n)
{
    if (n == 0)                     /* offset is 1; behaviour below it is arbitrary */
        return (seq_t)0;

    idx_t count = 0;
    for (idx_t x = 1; ; ++x)         /* search successive integers */
    {
        /* Count runs in binary representation of x */
        int runs = 1;
        idx_t prev = x & 1;
        idx_t y = x >> 1;
        while (y) {
            idx_t bit = y & 1;
            if (bit != prev) {
                ++runs;
                prev = bit;
            }
            y >>= 1;
        }

        if ((runs % 6) == 3) {       /* runs ≡ 3 (mod 6) */
            ++count;
            if (count == n)
                return (seq_t)x;     /* found the n-th term */
        }
    }
}
