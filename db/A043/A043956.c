/*
 * A043956  Numbers k such that 4 and 7 occur juxtaposed in the base-8
 *          representation of k but not of k+1.
 * https://oeis.org/A043956
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 43, u32 n <= 43, u64 n <= 43, u128 n <= 43,
 *            big any n
 * Validated: partial, pass, 43 terms through n = 43 (2026-11-03)
 * Helpers:   mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A043956: returns the n-th integer k such that the base‑8 representation
   of k contains the adjacent digits 4 and 7 (in either order), but the base‑8
   representation of k+1 does not.  The sequence is generated by brute‑force
   search and memoised. */

#include <stdbool.h>
#include <stdlib.h>
#include "../utils/mem.h"

/* Helper that tests whether x (in base 8) contains 4 next to 7 in either order. */
static inline bool has_adjacent_47(seq_t x)
{
    if (x == 0)
        return false;            /* zero has no adjacent digits */

    unsigned char digits[256];  /* enough for 128‑bit numbers */
    size_t len = 0;

    while (x > 0) {
        digits[len++] = (unsigned char)(x % 8);
        x /= 8;
    }

    for (size_t i = len; i > 1; --i) {
        unsigned char d1 = digits[i - 1];      /* more significant digit */
        unsigned char d2 = digits[i - 2];      /* less significant digit */
        if ((d1 == 4 && d2 == 7) || (d1 == 7 && d2 == 4))
            return true;
    }
    return false;
}

/* Memoised cache of terms already computed. */
static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;
static seq_t last_checked = 0;

static void ensure_cache_capacity(void)
{
    if (cache_len == cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 64;
        seq_t *new_cache = mem_resize(seq_t, cache, new_cap);
        if (!new_cache) {
            /* In the unlikely event of allocation failure, terminate. */
            abort();
        }
        cache = new_cache;
        cache_cap = new_cap;
    }
}

/* Public function required by the build system. */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0;                    /* index < 1 is undefined; return 0 */

    /* Generate terms until we have at least n terms cached. */
    while (cache_len < (size_t)n) {
        last_checked += 1;
        if (has_adjacent_47(last_checked) &&
            !has_adjacent_47(last_checked + 1))
        {
            ensure_cache_capacity();
            cache[cache_len++] = last_checked;
        }
    }
    return cache[n - 1];              /* a(1) is the first term */
}
