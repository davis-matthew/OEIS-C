/* A382750: numbers k whose 9‑adic valuation is even
   (equivalently, exponent of 3 modulo 4 is 0 or 1).  The sequence
   is generated by scanning the positive integers and picking those
   that satisfy (v3(k) mod 4 < 2).  The nth term (1‑based) is returned. */

#include <stdlib.h>   /* for types and malloc (required for C) */

seq_t a(idx_t n)
{
    idx_t count = 0;          /* how many qualifying numbers we have seen */

    for (idx_t x = 1; /* infinite */; ++x) {
        idx_t t   = x;
        unsigned e3 = 0;            /* exponent of 3 in t */

        /* Count factors of 3 – fast when 3 does not divide t. */
        while (t % 3 == 0) {
            t   /= 3;
            e3++;                    /* e3 will be small (≤ 60 for uint64_t) */
        }

        /* Include the number if e3 ≡ 0 or 1 (mod 4). */
        if ((e3 & 3u) < 2u) {
            ++count;
            if (count == n)
                return (seq_t)x;      /* cast to seq_t; works for integer or big‑int types */
        }
    }
}
