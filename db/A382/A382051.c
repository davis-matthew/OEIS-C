/*
 * A382051  Primes prime(k) such that k*log(k)/prime(k) <
 *          (k-1)*log(k-1)/prime(k-1).
 * https://oeis.org/A382051
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 23, u16 n <= 56, u32 n <= 56, u64 n <= 56, u128 n <= 56,
 *            big any n
 * Helpers:   is_prime_small
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A382051
    a(n) is the prime prime(k) such that   k*log(k)/prime(k)  <  (k-1)*log(k-1)/prime(k-1),
    where k is the (1‑based) prime index.  The first term is 11.  The sequence is
    generated by a lazy, memoised scan of primes together with the above
    inequality.                                                      */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <math.h>
#include "../utils/is_prime_small.h"   /* provides bool is_prime_small(uint64_t n); */

/* -------------------------------------------------------------------- */
/* static state                                                  */

static seq_t *term_cache = NULL;          /* cached terms              */
static size_t term_cache_cap = 0;
static idx_t  term_cache_len  = 0;        /* number of cached terms    */

static uint64_t *prime_arr  = NULL;       /* array of primes (uint64_t)*/
static size_t   prime_cap    = 0;
static idx_t    prime_cnt    = 0;          /* number of stored primes   */

static uint64_t last_checked_prime = 2;   /* last prime generated     */
static idx_t    current_k           = 2;   /* next k to be processed   */
static long double prev_f          = 0.0L; /* f(k-1) for last processed k */

/* -------------------------------------------------------------------- */
/* helpers to grow the dynamic arrays                               */

static void grow_term_cache(void)
{
    size_t new_cap = term_cache_cap ? term_cache_cap * 2 : 64;
    seq_t *new_ptr = (seq_t *)realloc(term_cache, new_cap * sizeof(seq_t));
    if (!new_ptr) abort();
    term_cache = new_ptr;
    term_cache_cap = new_cap;
}

static void grow_prime_arr(void)
{
    size_t new_cap = prime_cap ? prime_cap * 2 : 32;
    uint64_t *new_ptr = (uint64_t *)realloc(prime_arr, new_cap * sizeof(uint64_t));
    if (!new_ptr) abort();
    prime_arr = new_ptr;
    prime_cap = new_cap;
}

/* -------------------------------------------------------------------- */
/* Ensure that at least k_needed primes are stored in prime_arr.  This
   uses a simple trial‑division routine via the supplied is_prime_small
   helper.  The function is O(k_needed^2) in the worst case but is
   adequate for the required limits (n <= 10000).                     */

static void ensure_primes_of_index(idx_t k_needed)
{
    while (prime_cnt < k_needed)
    {
        uint64_t candidate = last_checked_prime + 1;
        while (!is_prime_small(candidate))
            ++candidate;

        if (prime_cnt == prime_cap) grow_prime_arr();
        prime_arr[prime_cnt++] = candidate;
        last_checked_prime = candidate;
    }
}

/* -------------------------------------------------------------------- */
/* Generate terms up to at least the requested index n.               */

static void ensure_terms(idx_t n)
{
    /* initialise static structures on first call */
    if (!term_cache)
    {
        term_cache_cap = 64;
        term_cache = (seq_t *)calloc(term_cache_cap, sizeof(seq_t));
        if (!term_cache) abort();
    }
    if (!prime_arr)
    {
        prime_cap = 32;
        prime_arr = (uint64_t *)calloc(prime_cap, sizeof(uint64_t));
        if (!prime_arr) abort();
        /* prime(1) = 2 */
        prime_arr[prime_cnt++] = 2;
        last_checked_prime = 2;
    }

    /* prev_f corresponds to f(k-1); initialise to f(1)=0.0 */
    if (current_k == 2 && term_cache_len == 0)
        prev_f = 0.0L;

    /* generate more terms as necessary */
    while (term_cache_len < n)
    {
        /* make sure prime at index current_k exists */
        ensure_primes_of_index(current_k);

        uint64_t pk   = prime_arr[current_k - 1];                     /* prime(k)   */
        long double f = ((long double)current_k * log((long double)current_k))
                        / (long double)pk;

        if (f < prev_f)
        {
            if (term_cache_len == term_cache_cap) grow_term_cache();
            term_cache[term_cache_len++] = (seq_t)pk;
        }

        prev_f = f;
        ++current_k;
    }
}

/* -------------------------------------------------------------------- */
/* public sequence function                                           */

seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;   /* undefined for n < 1; return 0 to keep well‑formed   */
    ensure_terms(n);
    return term_cache[n - 1];     /* a(1) is stored at index 0                            */
}
