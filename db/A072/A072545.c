/*
 * A072545  a(0) = 1, a(n) for n > 0 is the smallest number > a(n-1) such that
 *          a(n)-a(k) is nonprime for 0 <= k < n.
 * https://oeis.org/A072545
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 26, u16 n <= 9671, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   isPrimeGeneric
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A072545 – a(0)=1;  for n>0, a(n) is the smallest integer >a(n‑1)
 * such that for all k<n, a(n)-a(k) is non‑prime.
 * For n≤33 the sequence is generated by brute force.
 * For n>33 all terms are even and only differences with the odd
 * terms 1,11,35,101,311 can be prime; the rest are automatically
 * non‑prime.  Hence we test only those five differences and skip
 * odd candidates.
 */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include "../utils/isPrimeGeneric.h"   /* for isPrimeGeneric(seq_t) */

static seq_t *seq_cache = NULL;   /* a(0) … a(max_n) */
static size_t cache_cap = 0;
static size_t cache_len = 0;

/* Ensure seq_cache has room for indices up to n (inclusive). */
static void ensure_cache_capacity(idx_t n)
{
    size_t needed = (size_t)(n + 1);
    if (needed <= cache_cap)
        return;
    size_t new_cap = cache_cap == 0 ? 16 : cache_cap + cache_cap / 2;
    if (new_cap < needed)
        new_cap = needed;
    seq_t *tmp = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    if (!tmp)
        abort();   /* OOM – terminate */
    seq_cache = tmp;
    cache_cap = new_cap;
}

/* The fixed set of odd terms that occur before index 34. */
static const seq_t odd_terms[] = { (seq_t)1,  (seq_t)11,
                                   (seq_t)35, (seq_t)101,
                                   (seq_t)311 };
static const size_t odd_count = sizeof(odd_terms)/sizeof(odd_terms[0]);

seq_t a(idx_t n)
{
    /* initialise first term when the cache is empty */
    if (cache_len == 0) {
        ensure_cache_capacity(0);
        seq_cache[0] = (seq_t)1;
        cache_len = 1;
    }

    /* generate missing terms up to index n */
    for (idx_t i = (idx_t)cache_len; i <= n; ++i) {
        ensure_cache_capacity(i);

        if (i <= 33) {
            /* brute force for the early part of the sequence */
            seq_t cand = seq_cache[i-1] + (seq_t)1;
            for (;;) {
                bool ok = true;
                for (idx_t k = 0; k < i; ++k) {
                    seq_t diff = cand - seq_cache[k];
                    if (diff > (seq_t)1 && isPrimeGeneric(diff)) {
                        ok = false;
                        break;
                    }
                }
                if (ok) {
                    seq_cache[i] = cand;
                    break;
                }
                ++cand;
            }
        } else {
            /* optimization after index 33 – all terms are even */
            seq_t cand = seq_cache[i-1] + (seq_t)4;
            /* ensure cand is even */
            if ((cand & (seq_t)1) != 0)
                ++cand;
            for (;;) {
                bool ok = true;
                for (size_t j = 0; j < odd_count; ++j) {
                    seq_t diff = cand - odd_terms[j];
                    if (isPrimeGeneric(diff)) {
                        ok = false;
                        break;
                    }
                }
                if (ok) {
                    seq_cache[i] = cand;
                    break;
                }
                cand += (seq_t)2;   /* stay even */
            }
        }
        cache_len = (size_t)(i + 1);
    }

    return seq_cache[(size_t)n];
}
