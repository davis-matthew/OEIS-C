/*  A072587: Numbers having at least one prime factor with an even exponent.
    The sequence is generated by testing each integer >1 for an exponent
    that is even and at least 2 in its prime factorisation.
    a(n) is the n-th such integer (1‑based). */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/has_even_exp.h"

seq_t a(idx_t n)
{
    static seq_t *terms = NULL;
    static size_t len   = 0;
    static size_t cap   = 0;
    static seq_t next   = 2;   /* start checking from 2 */

    if (n == 0) return 0;  /* out of bounds, should not happen */

    while (len < (size_t)n) {
        seq_t cand = next;
        if (cand > 1 && has_even_exp((uint64_t)cand))
            terms[ len++ ] = cand;

        if (len == 0 || len < (size_t)n) {
            /* grow array when needed */
            if (cap < len+1) {
                size_t new_cap = cap ? cap << 1 : 16;
                if (new_cap < len+1) new_cap = len+1;
                seq_t *tmp = (seq_t*)realloc(terms, new_cap * sizeof(seq_t));
                if (!tmp) abort();
                terms = tmp;
                cap = new_cap;
            }
        }
        ++next;
    }
    return terms[n-1];
}
