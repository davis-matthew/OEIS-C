/*
 * A072697  Squarefree numbers such that the sum of the prime factors is a
 *          multiple of the number of prime factors.
 * https://oeis.org/A072697
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 111, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   factor_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: A072697 – square‑free integers n for which the sum of the
   distinct prime factors of n is a multiple of the number of such
   prime factors. The sequence is generated by a simple search, caching
   each found term in a static array. */

#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include "../utils/factor_u64.h"  /* factor_u64(uint64_t n, uint64_t *pr, uint64_t *ex, size_t *cnt) */

static bool satisfies(uint64_t x)
{
    uint64_t primes[32];
    uint64_t exps[32];
    size_t   cnt;

    /* Factor x.  primes[] holds the distinct primes, exps[] their exponents,
       and cnt the number of distinct primes. */
    factor_u64(x, primes, exps, &cnt);
    if (cnt == 0) return false;          /* x == 1 has no prime factors */

    /* Must be square‑free: all exponents equal 1. */
    for (size_t i = 0; i < cnt; ++i) {
        if (exps[i] != 1) return false;
    }

    /* Sum of the (distinct) prime factors. */
    uint64_t sum = 0;
    for (size_t i = 0; i < cnt; ++i) {
        sum += primes[i];
    }

    return (sum % cnt) == 0;
}

seq_t a(idx_t n)
{
    /* Lazy memoised generation: cache holds the terms found so far. */
    static seq_t   *cache = NULL;   /* dynamic array of cached terms   */
    static size_t   cap   = 0;     /* allocated capacity of cache      */
    static size_t   len   = 0;     /* number of terms stored           */
    static uint64_t next  = 2;     /* next integer to test             */

    if (n == 0) return 0;          /* offset is 1; undefined for n==0 */

    /* If the requested index is already cached, return it. */
    if (len >= (size_t)n) {
        return cache[(size_t)n - 1];
    }

    /* Extend the cache until we have at least n terms. */
    while (len < (size_t)n) {
        uint64_t value = next++;

        if (satisfies(value)) {
            /* Grow the cache if necessary. */
            if (len >= cap) {
                size_t new_cap = (cap == 0) ? 8 : cap * 2;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) abort();     /* allocation failed */
                cache = tmp;
                cap   = new_cap;
            }
            cache[len++] = (seq_t)value;
        }
    }

    return cache[(size_t)n - 1];
}
