/*
 * A046387  Products of exactly 5 distinct primes.
 * https://oeis.org/A046387
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 497, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Implements OEIS A046387:  Products of exactly 5 distinct primes.
   The sequence is generated by iterating over all 5‑prime combinations
   in ascending order of the product using a min‑heap and a visited
   table to avoid duplicates.
*/
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Prime sieve limit – large enough to cover all primes needed for n up to 10000 */
static const uint32_t PRIME_LIMIT = 5000;

/* Static data structures */
static uint32_t *PRIMES = NULL;   /* array of primes */
static size_t  PRIME_COUNT = 0;   /* number of primes stored */

/* Cache of computed sequence values */
static seq_t *CACHE   = NULL;
static size_t CACHE_LEN = 0;
static size_t CACHE_CAP = 0;

/* Each heap node contains the product and the indices of the five primes used */
struct Node {
    seq_t prod;
    uint16_t idx[5];
};

/* Min‑heap of nodes */
static struct Node *HEAP = NULL;
static size_t HEAP_SIZE = 0;
static size_t HEAP_CAP = 0;

/* Hash table for visited index combinations */
static uint64_t *VISITED = NULL;
static size_t  VISITED_SIZE = 0;
static size_t  VISITED_USED = 0;

/* --------------------------------------------------------------------- */
/* Sieve of Eratosthenes – fills PRIMES and PRIME_COUNT */
static void init_primes(void)
{
    bool *is_prime = (bool*)calloc(PRIME_LIMIT + 1, sizeof(bool));
    for (size_t i = 2; i <= PRIME_LIMIT; ++i) is_prime[i] = true;
    for (uint32_t i = 2; i * i <= PRIME_LIMIT; ++i) {
        if (is_prime[i]) {
            for (uint32_t j = i * i; j <= PRIME_LIMIT; j += i)
                is_prime[j] = false;
        }
    }
    /* Count primes */
    for (size_t i = 2; i <= PRIME_LIMIT; ++i)
        if (is_prime[i]) PRIME_COUNT++;
    PRIMES = (uint32_t*)malloc(PRIME_COUNT * sizeof(uint32_t));
    size_t pos = 0;
    for (size_t i = 2; i <= PRIME_LIMIT; ++i)
        if (is_prime[i]) PRIMES[pos++] = (uint32_t)i;
    free(is_prime);
}

/* --------------------------------------------------------------------- */
/* Cache helpers */
static void init_cache(void)
{
    CACHE_CAP = 1024;
    CACHE = (seq_t*)malloc(CACHE_CAP * sizeof(seq_t));
    CACHE_LEN = 0;
}

static void grow_cache(void)
{
    CACHE_CAP *= 2;
    CACHE = (seq_t*)realloc(CACHE, CACHE_CAP * sizeof(seq_t));
}

/* --------------------------------------------------------------------- */
/* Heap helpers */
static void init_heap(void)
{
    HEAP_CAP = 1024;
    HEAP = (struct Node*)malloc(HEAP_CAP * sizeof(struct Node));
    HEAP_SIZE = 0;
}

static void grow_heap(void)
{
    HEAP_CAP *= 2;
    HEAP = (struct Node*)realloc(HEAP, HEAP_CAP * sizeof(struct Node));
}

static void heap_percolate_up(size_t pos)
{
    struct Node node = HEAP[pos];
    while (pos > 0) {
        size_t parent = (pos - 1) >> 1;
        if (HEAP[parent].prod <= node.prod) break;
        HEAP[pos] = HEAP[parent];
        pos = parent;
    }
    HEAP[pos] = node;
}

static void heap_percolate_down(size_t pos)
{
    struct Node node = HEAP[pos];
    while (true) {
        size_t left = (pos << 1) + 1;
        if (left >= HEAP_SIZE) break;
        size_t right = left + 1;
        size_t child = left;
        if (right < HEAP_SIZE && HEAP[right].prod < HEAP[left].prod)
            child = right;
        if (HEAP[child].prod >= node.prod) break;
        HEAP[pos] = HEAP[child];
        pos = child;
    }
    HEAP[pos] = node;
}

static void heap_push(seq_t prod, const uint16_t idx[5])
{
    if (HEAP_SIZE == HEAP_CAP) grow_heap();
    struct Node n = { prod, { idx[0], idx[1], idx[2], idx[3], idx[4] } };
    HEAP[HEAP_SIZE++] = n;
    heap_percolate_up(HEAP_SIZE - 1);
}

static struct Node heap_pop_min(void)
{
    struct Node ret = HEAP[0];
    HEAP[0] = HEAP[--HEAP_SIZE];
    if (HEAP_SIZE) heap_percolate_down(0);
    return ret;
}

/* --------------------------------------------------------------------- */
/* Visited set helpers – stores packed 64‑bit keys derived from indices */
static uint64_t pack_key(const uint16_t idx[5])
{
    return ((uint64_t)(idx[0] + 1) << 48) |
           ((uint64_t)(idx[1] + 1) << 36) |
           ((uint64_t)(idx[2] + 1) << 24) |
           ((uint64_t)(idx[3] + 1) << 12) |
           (uint64_t)(idx[4] + 1);
}

static void init_visited(size_t expected)
{
    VISITED_SIZE = 1;
    while (VISITED_SIZE < expected * 2) VISITED_SIZE <<= 1;
    VISITED = (uint64_t*)calloc(VISITED_SIZE, sizeof(uint64_t));
    VISITED_USED = 0;
}

static bool visited_contains(uint64_t key)
{
    size_t idx = (key ^ (key >> 33)) & (VISITED_SIZE - 1);
    while (VISITED[idx]) {
        if (VISITED[idx] == key) return true;
        idx = (idx + 1) & (VISITED_SIZE - 1);
    }
    return false;
}

static void visited_insert(uint64_t key)
{
    if (VISITED_USED + 1 > VISITED_SIZE * 3 / 4) {
        /* Resize */
        size_t new_size = VISITED_SIZE << 1;
        uint64_t *new_vis = (uint64_t*)calloc(new_size, sizeof(uint64_t));
        for (size_t i = 0; i < VISITED_SIZE; ++i) {
            uint64_t v = VISITED[i];
            if (!v) continue;
            size_t idx = (v ^ (v >> 33)) & (new_size - 1);
            while (new_vis[idx]) idx = (idx + 1) & (new_size - 1);
            new_vis[idx] = v;
        }
        free(VISITED);
        VISITED = new_vis;
        VISITED_SIZE = new_size;
    }
    size_t idx = (key ^ (key >> 33)) & (VISITED_SIZE - 1);
    while (VISITED[idx]) idx = (idx + 1) & (VISITED_SIZE - 1);
    VISITED[idx] = key;
    VISITED_USED++;
}

/* --------------------------------------------------------------------- */
/* Build the sequence up to index n (1‑based) */
static void ensure_built(idx_t n)
{
    static bool initialized = false;
    if (!initialized) {
        init_primes();
        init_cache();
        init_heap();
        init_visited(16384);
        uint16_t first[5] = {0, 1, 2, 3, 4};
        seq_t prod = 1;
        for (int k = 0; k < 5; ++k) prod *= PRIMES[first[k]];
        heap_push(prod, first);
        visited_insert(pack_key(first));
        initialized = true;
    }
    while (CACHE_LEN < n) {
        struct Node cur = heap_pop_min();
        if (CACHE_LEN == CACHE_CAP) grow_cache();
        CACHE[CACHE_LEN++] = cur.prod;
        /* generate children */
        for (int i = 0; i < 5; ++i) {
            uint16_t new_idx = cur.idx[i] + 1;
            if (new_idx + (4 - i) >= PRIME_COUNT) continue;
            uint16_t child[5];
            for (int t = 0; t < 5; ++t) child[t] = cur.idx[t];
            child[i] = new_idx;
            for (int t = i + 1; t < 5; ++t) child[t] = new_idx + (t - i);
            uint64_t key = pack_key(child);
            if (visited_contains(key)) continue;
            visited_insert(key);
            seq_t new_prod = 1;
            for (int k = 0; k < 5; ++k) new_prod *= PRIMES[child[k]];
            heap_push(new_prod, child);
        }
    }
}

/* --------------------------------------------------------------------- */
/* Public interface – returns a(n) for n >= 1 */
seq_t a(idx_t n)
{
    if (n == 0) return 0;
    ensure_built(n);
    return CACHE[n - 1];
}
