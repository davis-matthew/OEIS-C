/*
 * A046309  Numbers that are divisible by at least 8 primes (counted with
 *          multiplicity).
 * https://oeis.org/A046309
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   bigomega
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A046309: a(n) = the n‑th integer whose total number of
   prime factors counted with multiplicity is at least 8.
   (generated by scanning integers and testing bigomega). */

#include <stdlib.h>
#include "../utils/bigomega.h"

seq_t a(idx_t n)
{
    /* static cache of found terms */
    static seq_t *terms = NULL;
    static size_t terms_cap = 0;   /* capacity of the cache       */
    static size_t terms_used = 0;  /* number of terms currently stored */

    /* last integer that was examined in the sieve */
    static idx_t last_checked = 1; /* begin after 1, since 1 cannot satisfy the condition */

    /* sequence is defined for n >= 1; nothing is required below the offset. */
    if (n == 0)
        return (seq_t)0;

    /* If we do not yet have enough terms, extend the cache. */
    if (terms_used < (size_t)n) {
        /* enlarge the allocation if necessary */
        if (terms_cap < terms_used + (size_t)n) {
            size_t new_cap = terms_cap ? terms_cap : 4;
            while (new_cap < terms_used + (size_t)n)
                new_cap <<= 1;
            seq_t *tmp = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
            terms = tmp;
            terms_cap = new_cap;
        }

        /* continue scanning integers until we collect the required number of terms */
        idx_t num = last_checked + 1;
        while (terms_used < (size_t)n) {
            if (bigomega(num) >= 8)
                terms[terms_used++] = (seq_t)num;
            ++num;
        }
        last_checked = num - 1;  /* last processed integer           */
    }

    return terms[(size_t)(n - 1)];
}
