/* Sequence A046576:
   First denominator and then numerator of the elements to the right of the
   central elements of the 1/4‑Pascal triangle.
   The triangle is generated by the recurrence
     a(r,1) = a(r,r) = 1            (stored as 4/4)
     a(r,k) = a(r-1,k-1) + a(r-1,k)   for 1 < k < r
   The entries are kept as numerators over a common denominator 4,
   so a value stored as n means n/4.  The generated fractions are
   reduced when they are output.  The function `a(n)` returns the
   n‑th integer in the sequence (denominator then numerator).  */

#include <stdlib.h>
#include "../utils/seq_gcd.h"

static seq_t **triangle_cache = NULL;   /* 1‑indexed rows of the triangle */
static size_t cached_rows   = 0;        /* number of rows currently cached */

/* Ensure that the triangle is built up to `up_to` rows */
static void
ensure_rows(size_t up_to)
{
    if (cached_rows >= up_to) return;

    size_t old = cached_rows;
    size_t new_cap = up_to + 1;      /* 1‑based indexing */

    seq_t **tmp = (seq_t **)realloc(triangle_cache,
                                    new_cap * sizeof(seq_t *));
    triangle_cache = tmp;            /* May be NULL if up_to == 0 */

    for (size_t r = old + 1; r <= up_to; ++r) {
        seq_t *row = (seq_t *)malloc(r * sizeof(seq_t));
        if (!row) {
            /* Unable to allocate the required memory */
            exit(EXIT_FAILURE);
        }

        if (r == 1) {
            row[0] = (seq_t)4;                     /* 1 = 4/4 */
        } else if (r == 2) {
            row[0] = row[1] = (seq_t)4;             /* 1 1 */
        } else if (r == 3) {
            row[0] = row[2] = (seq_t)4;             /* 1 1/4 1 */
            row[1] = (seq_t)1;                      /* 1/4 stored as 1/4 */
        } else {
            seq_t *prev = triangle_cache[r - 1];
            row[0]                     = (seq_t)4;   /* left edge */
            row[r - 1]                 = (seq_t)4;   /* right edge */

            for (size_t j = 1; j < r - 1; ++j) {
                row[j] = prev[j - 1] + prev[j];     /* recurrence */
            }
        }

        triangle_cache[r] = row;
    }

    cached_rows = up_to;
}

/* Return the n‑th term of the sequence (n >= 1) */
seq_t a(idx_t n)
{
    if (n == 0) return 0;

    /* Find the row containing the n‑th term */
    idx_t cum = 0;          /* cumulative terms processed so far */
    size_t r = 1;
    while (1) {
        idx_t row_terms = (r % 2 == 0) ? r : r - 1;   /* 2*floor(r/2) */
        if (cum + row_terms >= n) break;
        cum += row_terms;
        ++r;
    }

    /* Index within the row (0‑based) */
    idx_t idx_in_row = n - cum - 1;

    /* Determine which fraction and which part (denominator or numerator) */
    idx_t fraction_index = idx_in_row / 2;
    idx_t part_index     = idx_in_row % 2;           /* 0 -> denom, 1 -> numer */

    /* Position of the fraction in the row (1‑based) */
    idx_t ceil_half = (r + 1) / 2;                    /* ceil(r/2) */
    idx_t pos = ceil_half + 1 + fraction_index;      /* positions to the right */

    /* Build the triangle up to the required row if necessary */
    ensure_rows(r);

    /* Retrieve the stored numerator over 4 */
    seq_t val = triangle_cache[r][pos - 1];           /* index is 0‑based */

    /* Reduce the fraction val/4 */
    seq_t g   = seq_gcd(val, (seq_t)4);
    seq_t num = val / g;    /* numerator of the reduced fraction */
    seq_t den = (seq_t)4 / g; /* denominator of the reduced fraction */

    return (part_index == 0) ? den : num;
}
