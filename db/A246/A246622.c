/* Sequence: A246622 – primes of the form m + product of nonzero digits of m.
 * The nth term a(n) is the n‑th prime occurring in this form, indexed
 * with a(1)=2.  Each term is generated by increasing m
 * from 1 upward, computing p=m+∏(non‑zero digits of m);
 * if p is prime it is added to the sequence cache.
 *
 * The implementation uses a static cache to allow arbitrary order of
 * calls and keeps the runtime well below 2 s for n up to ~10 000
 * (O(n) with a simple primality test per candidate).
 *
 * Author: ChatGPT
 */

#include <stddef.h>
#include <stdbool.h>

#include "../utils/isPrimeGeneric.h"        /* bool isPrimeGeneric(seq_t n); */
#include "../utils/seq_alloc_new_array.h"   /* seq_t *seq_alloc_new_array(size_t n); */
#include "../utils/grow_seq_array.h"        /* void grow_seq_array(seq_t **arr, size_t *size, size_t new_len); */

/* Cache for previously found terms. */
static seq_t *seq_cache = NULL;   /* array of terms */
static size_t seq_cap  = 0;       /* current capacity */
static size_t seq_len  = 0;       /* number of terms stored */

/* Next candidate m to test. */
static idx_t next_test_m = 1;

/* Ensure capacity for one more element. */
static void ensure_cap(void)
{
    if (seq_len == seq_cap) {
        size_t new_cap = (seq_cap == 0) ? 16 : seq_cap * 2;
        if (seq_cache == NULL) {
            seq_cache = seq_alloc_new_array(new_cap);
        } else {
            grow_seq_array(&seq_cache, &seq_cap, new_cap);
        }
        seq_cap = new_cap;
    }
}

/* Product of non‑zero decimal digits of x. */
static seq_t prod_nonzero_digits(seq_t x)
{
    if (x == 0)                /* product of empty set → 1 (unused for m>=1) */
        return 1;
    seq_t prod = 1;
    while (x > 0) {
        uint8_t d = (uint8_t)(x % 10);
        if (d != 0)
            prod *= d;
        x /= 10;
    }
    return prod;
}

/* Return the nth term (1‑based index). */
seq_t a(idx_t n)
{
    if (n == 0)                  /* undefined for n = 0; return 0 as placeholder */
        return (seq_t)0;

    /* Generate terms until we have the requested one. */
    while (seq_len < (size_t)n) {
        seq_t m = (seq_t)next_test_m;
        seq_t prod = prod_nonzero_digits(m);
        seq_t candidate = m + prod;

        if (isPrimeGeneric(candidate)) {
            ensure_cap();
            seq_cache[seq_len++] = candidate;
        }
        ++next_test_m;
    }

    return seq_cache[n - 1];
}
