/* -----------------  Generic primality test ------------------------ */
static bool isPrimeGeneric(seq_t n)
{
    /* all seq_t are unsigned; use the smallest type that fits */
    if ((seq_t)(ULLONG_MAX) >= n) {
        return is_prime_u64((uint64_t)n);
    }
#if defined(__SIZEOF_INT128__)
    return is_prime_u128((__uint128_t)n);
#else
    /* fallback: if seq_t > 64‑bit but no 128‑bit support,
       order the test as simple trial division up to sqrt */
    seq_t limit = 0;
    for (seq_t i = 2; i*i <= n; ++i) {
        if (n % i == 0) return false;
    }
    return true;
#endif
}

/* C allocation helpers */
static seq_t* seq_alloc_new_array(size_t n)   { return mem_new(seq_t, n); }

/* Helper to grow a sequence array of type seq_t. */
static void grow_seq_array(seq_t **arr, size_t *size, size_t new_len)
{
    if (*size >= new_len) return;
    size_t new_cap = (*size > 0) ? (*size << 1) : 16;
    while (new_cap < new_len) new_cap <<= 1;
    seq_t *tmp = mem_resize(seq_t, *arr, new_cap);
    if (!tmp) abort();
    *arr = tmp;
    *size = new_cap;
}

/* Cache for previously found terms. */
static seq_t *seq_cache = NULL;   /* array of terms */
static size_t seq_cap  = 0;       /* current capacity */
static size_t seq_len  = 0;       /* number of terms stored */

/* Next candidate m to test. */
static idx_t next_test_m = 1;

/* Ensure capacity for one more element. */
static void ensure_cap(void)
{
    if (seq_len == seq_cap) {
        size_t new_cap = (seq_cap == 0) ? 16 : seq_cap * 2;
        if (seq_cache == NULL) {
            seq_cache = seq_alloc_new_array(new_cap);
        } else {
            grow_seq_array(&seq_cache, &seq_cap, new_cap);
        }
        seq_cap = new_cap;
    }
}

/* Product of non‑zero decimal digits of x. */
static seq_t prod_nonzero_digits(seq_t x)
{
    if (x == 0)                /* product of empty set → 1 (unused for m>=1) */
        return 1;
    seq_t prod = 1;
    while (x > 0) {
        uint8_t d = (uint8_t)(x % 10);
        if (d != 0)
            prod *= d;
        x /= 10;
    }
    return prod;
}

/* Return the nth term (1‑based index). */
seq_t a(idx_t n)
{
    if (n == 0)                  /* undefined for n = 0; return 0 as placeholder */
        return (seq_t)0;

    /* Generate terms until we have the requested one. */
    while (seq_len < (size_t)n) {
        seq_t m = (seq_t)next_test_m;
        seq_t prod = prod_nonzero_digits(m);
        seq_t candidate = m + prod;

        if (isPrimeGeneric(candidate)) {
            ensure_cap();
            seq_cache[seq_len++] = candidate;
        }
        ++next_test_m;
    }

    return seq_cache[n - 1];
}
