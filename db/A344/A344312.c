/*
 * A344312  Number k such that k and k+1 have the same number of exponential
 *          divisors (A049419).
 * https://oeis.org/A344312
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   successive integers are tested until their exponential divisor
 *            counts are equal. The algorithm uses a linear sieve to obtain
 *            smallest prime factors for all numbers encountered, then
 *            computes the exponential divisor count via the exponents in the
 *            prime factorisation. The sequence values are cached...
 * Range:     u8 n <= 106, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* --- global cached data --------------------------------------------------- */
static seq_t *seq_arr   = NULL;   /* stored terms                                    */
static size_t seq_len   = 0;      /* number of terms stored                          */
static size_t seq_cap   = 0;      /* allocated capacity                              */

static uint32_t *primes = NULL;   /* primes generated by the sieve                  */
static size_t primes_len = 0, primes_cap = 0;

static uint32_t *spf     = NULL; /* spf[n] = smallest prime factor of n (n>=1)       */
static uint64_t  spf_limit = 0;   /* maximum n for which spf is defined                */

/* -----------------------------------------------------
   dynamic array helpers
----------------------------------------------------- */
static void seq_append(seq_t v)
{
    if (seq_len == seq_cap) {
        seq_cap = (seq_cap == 0 ? 128 : seq_cap * 2);
        seq_arr = (seq_t *)realloc(seq_arr, seq_cap * sizeof(seq_t));
    }
    seq_arr[seq_len++] = v;
}

static void primes_append(uint32_t p)
{
    if (primes_len == primes_cap) {
        primes_cap = (primes_cap == 0 ? 64 : primes_cap * 2);
        primes = (uint32_t *)realloc(primes, primes_cap * sizeof(uint32_t));
    }
    primes[primes_len++] = p;
}

/* -----------------------------------------------------
   linear sieve – ensure spf up to n (inclusive)
----------------------------------------------------- */
static void ensure_sieve(uint64_t n)
{
    if (n <= spf_limit) return;

    uint64_t old = spf_limit;
    spf_limit = n;

    spf = (uint32_t *)realloc(spf, (spf_limit + 1) * sizeof(uint32_t));
    for (uint64_t i = old + 1; i <= spf_limit; ++i) spf[i] = 0;

    /* start from 2 – 0 and 1 are already handled                 */
    for (uint64_t i = 2; i <= spf_limit; ++i) {
        if (spf[i] == 0) {                    /* i is prime */
            spf[i] = (uint32_t)i;
            primes_append((uint32_t)i);
        }
        for (size_t pi = 0; pi < primes_len; ++pi) {
            uint32_t p = primes[pi];
            if ((uint64_t)p > spf[i]) break;
            uint64_t v = i * (uint64_t)p;
            if (v > spf_limit) break;
            spf[v] = p;
            if (p == spf[i]) break;            /* linear sieve rule */
        }
    }
}

/* -----------------------------------------------------
   divisor count of an unsigned 32‑bit integer
----------------------------------------------------- */
static unsigned int divisor_count_uint32(uint32_t e)
{
    unsigned int c = 0;
    for (uint32_t i = 1; i * i <= e; ++i) {
        if (e % i == 0) {
            ++c;
            if (i != e / i) ++c;
        }
    }
    return c;
}

/* -----------------------------------------------------
   exponential divisor count of n
----------------------------------------------------- */
static seq_t exp_divisor_count(uint64_t n)
{
    if (n == 1) return (seq_t)1;

    seq_t res = (seq_t)1;
    uint64_t t = n;
    while (t > 1) {
        uint32_t p = spf[t];
        uint32_t e = 0;
        while (t % p == 0) { t /= p; ++e; }
        unsigned int d_e = divisor_count_uint32(e);
        res *= (seq_t)d_e;
    }
    return res;
}

/* -----------------------------------------------------
   generate terms until the sequence contains at least n terms
----------------------------------------------------- */
static uint64_t next_to_test = 1;        /* next integer to check   */

static void generate_for(idx_t needed)
{
    while (seq_len < needed) {
        uint64_t a = next_to_test;
        uint64_t b = a + 1;
        ensure_sieve(b);                 /* spf for a & b available */

        seq_t da = exp_divisor_count(a);
        seq_t db = exp_divisor_count(b);
        if (da == db) seq_append((seq_t)a);
        ++next_to_test;
    }
}

/* -----------------------------------------------------
   public function required by the build
----------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;          /* offset is 1 */
    generate_for(n);
    return seq_arr[n - 1];
}
