/*
 * A344809  Numbers that are the sum of six squares in five or more ways.
 * https://oeis.org/A344809
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 194, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A344809: Numbers that are sums of six positive squares in five
   or more unordered ways.  The sequence is generated by dynamic programming
   counting partitions of an integer into exactly six squares.  A value
   has at least five representations iff the number of partitions equals
   or exceeds five.  The DP is rebuilt on demand to contain enough terms
   for any requested index, and results are cached for subsequent calls. */
 
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
 
/* Integer square root, floor of sqrt(n).  n fits into idx_t. */
static int int_sqrt_idx(idx_t n)
{
    idx_t r = 0;
    while ((r + 1) * (r + 1) <= n) {
        ++r;
    }
    return (int)r;
}
 
/* Build the sequence up to 'need' terms, up to maximum number *maxN*.
   The built sequence is returned in *seq* with length *len*.  The array
   *maxN* is updated to the value that was actually used.  The DP table
   counts unordered partitions into exactly six squares; counts are
   capped at five because we only need to know whether the number is
   at least five. */
static void build_sequence(size_t need, idx_t *maxN, seq_t **seq, size_t *len)
{
    idx_t limit = *maxN;
    size_t cap   = 0;
    seq_t *out_seq = NULL;
    size_t out_len = 0;
 
    /* Allocate DP tables for 0..6 squares.  Each entry holds 0..5. */
    uint8_t **dp = (uint8_t **)malloc(7 * sizeof(uint8_t *));
    for (int k = 0; k <= 6; ++k) {
        dp[k] = (uint8_t *)calloc((size_t)limit + 1, sizeof(uint8_t));
    }
    dp[0][0] = 1;
 
    int smax = int_sqrt_idx(limit);
    for (int s = 1; s <= smax; ++s) {
        int ss = s * s;
        for (int x = ss; x <= limit; ++x) {
            for (int k = 1; k <= 6; ++k) {
                uint8_t prev = dp[k - 1][x - ss];
                if (!prev) continue;
                uint8_t val  = dp[k][x] + prev;
                if (val > 5) val = 5;
                dp[k][x] = val;
            }
        }
    }
 
    for (int n = 1; n <= limit; ++n) {
        if (dp[6][n] >= 5) {
            if (out_len == cap) {
                cap = cap ? cap * 2 : 256;
                out_seq = (seq_t *)realloc(out_seq, cap * sizeof(seq_t));
            }
            out_seq[out_len++] = (seq_t)n;
            if (out_len >= need) break;   /* enough terms collected */
        }
    }
 
    for (int k = 0; k <= 6; ++k) free(dp[k]);
    free(dp);
 
    *seq = out_seq;
    *len = out_len;
    *maxN = limit;
}
 
/* Public function required by build system.  Returns the n‑th term
   of A344809 (1‑based index).  The function builds or extends an
   internal cache of terms on each call, so later calls are fast. */
seq_t a(idx_t n)
{
    static seq_t *sequence   = NULL;
    static size_t seq_len    = 0;
    static idx_t  max_limit  = 2000;      /* initial search limit */
 
    while (seq_len < (size_t)n) {
        /* Need additional terms – extend the search range. */
        size_t needed = seq_len ? seq_len * 2 : 1000;
        seq_t *new_seq = NULL;
        size_t new_len = 0;
        build_sequence(needed, &max_limit, &new_seq, &new_len);
        if (sequence) free(sequence);
        sequence = new_seq;
        seq_len = new_len;
        /* Increase the limit for the next iteration to avoid frequent
           rebuilds.  Doubling keeps the number of rebuilds small. */
        max_limit *= 2;
    }
    return sequence[n - 1];
}
