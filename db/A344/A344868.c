/* OEIS A344868:
 * Sequence of primes p that satisfy
 *     p = (prime(k) + 2*prime(k+1) + 3*prime(k+2)) / 2
 * for some integer k (k ≥ 2).  The sequence is generated by brute‑force
 * search; results are memoized, so any call order is supported. */

#include <stddef.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include <math.h>              /* for sqrt, used only in small helper */
#include "../utils/build_primes_upto.h"
#include "../utils/is_prime_big.h"

/* ----------------------------------------------------------------------
 * Prime list: primes[] contains the ascending list of primes
 * (primes[0] = 2, primes[1] = 3, ...);  primes_cnt is the number of
 * primes stored.  The list is built once up to a fixed large limit.
 * ---------------------------------------------------------------------- */
#define PRIME_LIMIT ((idx_t)2000000)   /* enough for n ≤ 10000 */

static uint64_t *primes = NULL;   /* dynamic array of primes */
static size_t   primes_cnt = 0;   /* number of primes stored */
static bool     primes_inited = false;

static void init_primes(void)
{
    if (primes_inited) return;
    unsigned long long lcnt = 0;
    build_primes_upto(PRIME_LIMIT, &primes, &primes_cnt);  /* primes are uint64_t */
    primes_inited = true;
}

/* ----------------------------------------------------------------------
 * Cache of sequence terms: term_cache[n‑1] = a(n) (0‑based index).
 * The cache is grown as needed; k_to_process is the next k to evaluate.
 * ---------------------------------------------------------------------- */
static seq_t *term_cache = NULL;   /* dynamic array of terms      */
static size_t term_cnt  = 0;       /* number of stored terms      */
static size_t term_cap  = 0;       /* current capacity of cache   */
static idx_t   k_to_process = 2;   /* next k to evaluate (start at 2) */

/* Grow cache capacity as needed */
static void grow_term_cap(void)
{
    size_t newcap = term_cap ? term_cap * 2 : 16;
    seq_t *tmp = (seq_t *)realloc(term_cache, newcap * sizeof(seq_t));
    if (!tmp) abort();
    term_cache = tmp;
    term_cap  = newcap;
}

static void append_term(seq_t v)
{
    if (term_cnt == term_cap) grow_term_cap();
    term_cache[term_cnt++] = v;
}

/* ----------------------------------------------------------------------
 * Main routine: returns the nth term, 1‑based.
 * ---------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;          /* undefined for n < 1 */

    init_primes();                       /* ensure prime list ready */

    /* compute more terms until we have at least n terms */
    while (term_cnt < (size_t)n) {
        /* ensure that primes up to k+2 are available */
        if ((size_t)(k_to_process + 2) > primes_cnt) {
            /* Should never happen for n ≤ 10000 with PRIME_LIMIT=2e6 */
            abort();
        }

        /* grab the primes needed for this k */
        seq_t pk   = (seq_t)primes[k_to_process - 1];
        seq_t pk1  = (seq_t)primes[k_to_process];
        seq_t pk2  = (seq_t)primes[k_to_process + 1];

        /* compute numerator = pk + 2*pk1 + 3*pk2 */
        seq_t numer = pk + 2u * pk1 + 3u * pk2;

        /* check that the result is integer (numer odd => skip) */
        if ((numer & 1u) == 0u) {
            seq_t p = numer >> 1;               /* integer division by 2 */
            if (is_prime_big(p))                /* test primality */
                append_term(p);
        }
        ++k_to_process;                         /* next potential k   */
    }

    return term_cache[(size_t)(n - 1)];          /* 0‑based index     */
}
