/* This sequence equals 2 iff the nth symbol of the tribonacci word
   (generated by the morphism 1→12, 2→13, 3→1) is 2; otherwise it equals 1.
   The function builds the tribonacci word lazily and caches it between
   calls.                                                */

#include <stdint.h>
#include <stdlib.h>

seq_t a(idx_t n)
{
    /* cache for the tribonacci word */
    static uint8_t *cache = NULL;
    static size_t len   = 0;

    if (n == 0)                  /* undefined; return 0 for safety */
        return (seq_t)0;

    /* initialise the cache with the first symbol “1” */
    if (len == 0) {
        cache = (uint8_t *)malloc(sizeof(uint8_t));
        if (!cache) return (seq_t)0;   /* allocation failure */
        cache[0] = 1;
        len = 1;
    }

    /* expand the cache until it contains the requested position */
    while (len < (size_t)n) {
        /* determine length of the next stage */
        size_t new_len = 0;
        for (size_t i = 0; i < len; ++i) {
            uint8_t sym = cache[i];
            if (sym == 1 || sym == 2) new_len += 2;
            else /* sym == 3 */ new_len += 1;
        }

        /* allocate new buffer and fill it */
        uint8_t *new_cache = (uint8_t *)malloc(new_len * sizeof(uint8_t));
        if (!new_cache) return (seq_t)0;   /* allocation failure */

        size_t pos = 0;
        for (size_t i = 0; i < len; ++i) {
            uint8_t sym = cache[i];
            if (sym == 1) {          /* 1 → 1 2 */
                new_cache[pos++] = 1;
                new_cache[pos++] = 2;
            } else if (sym == 2) {   /* 2 → 1 3 */
                new_cache[pos++] = 1;
                new_cache[pos++] = 3;
            } else {                 /* 3 → 1 */
                new_cache[pos++] = 1;
            }
        }

        /* replace old cache */
        free(cache);
        cache = new_cache;
        len   = new_len;
    }

    /* obtain the n‑th symbol (1‑based index) */
    uint8_t sym = cache[n - 1];
    return (seq_t)(sym == 2 ? 2 : 1);
}
