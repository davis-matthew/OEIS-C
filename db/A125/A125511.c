/*
 * A125511  Octagonal numbers of the form C*(3C - 2) with 3C - 2 = k^2 and C a
 *          composite number.
 * https://oeis.org/A125511
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 9, u32 n <= 186, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Sequence A125511: Octagonal numbers C*(3C-2) where 3C-2 is a perfect square k²
   and C is composite.  The terms are generated by iterating over k such that
   (k²+2) is divisible by 3; for each such k compute C = (k²+2)/3 and
   include the term C*k² only if C is composite (C>1 and not prime).
   The sequence is monotone increasing, so the nth term is produced by
   generating terms until the nth has been found (memoised).
*/

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime.h"   /* bool is_prime(idx_t x) */

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* offset is 1 */

    static idx_t   next_k = 1;      /* next k to test  */
    static size_t  cap    = 0;      /* capacity of cache    */
    static size_t  len    = 0;      /* number of terms stored */
    static seq_t * cache  = NULL;   /* cache of computed terms */

    /* Allocate cache if this is the first call */
    if (cap == 0) {
        cap = 16;
        cache = (seq_t *)malloc(cap * sizeof(seq_t));
    }

    /* Generate terms until we have at least n of them */
    while (len < n) {
        /* Skip k that are multiples of 3, because k²+2 is not divisible by 3 then */
        if (next_k % 3 == 0) {
            ++next_k;
            continue;
        }

        seq_t k2 = (seq_t)next_k * (seq_t)next_k;       /* k²  */
        idx_t C  = ((idx_t)k2 + 2) / 3;                 /* C = (k²+2)/3 */

        /* Check that C is composite (C > 1 and not prime) */
        if (C > 1 && !is_prime(C)) {
            seq_t val = (seq_t)C * k2;                 /* Octagonal number C*k² */

            /* Reallocate cache if needed */
            if (len == cap) {
                cap *= 2;
                cache = (seq_t *)realloc(cache, cap * sizeof(seq_t));
            }
            cache[len++] = val;
        }
        ++next_k;
    }

    return cache[n-1];
}
