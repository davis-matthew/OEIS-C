/* Continued fraction for sqrt(184). Sequence consists of the partial
   quotients in the expansion of sqrt(184).  The terms are periodic,
   generated by the classical algorithm for quadratic surds. */

#include <stdbool.h>
#include <stdlib.h>
#include <stddef.h>
#include "../utils/floor_sqrt.h"

seq_t a(idx_t n)
{
    /* Constant D = 184, whose square‑root expansion we encode */
    const seq_t D = 184;

    /* Static cache for the computed period */
    static bool initialized = false;
    static seq_t a0;           /* a0 = floor(sqrt(D)) */
    static seq_t *period = NULL;  /* array of periodic partial quotients */
    static size_t period_len = 0;

    if (!initialized) {
        a0 = floor_sqrt(D);
        initialized = true;

        /* Generate the period [1,1,3,2,1,2,1,2,3,1,1,26] for sqrt(184) */
        seq_t m = 0, d = 1, a_prev = a0;
        size_t cap = 16;
        period = (seq_t *)malloc(cap * sizeof(seq_t));
        if (!period) return 0; /* unlikely, but defensive */
        size_t idx = 0;
        while (1) {
            seq_t m_next = d * a_prev - m;
            seq_t d_next = (D - m_next * m_next) / d;
            seq_t a_next = (a0 + m_next) / d_next;

            if (idx >= cap) {
                cap <<= 1; /* double capacity */
                period = (seq_t *)realloc(period, cap * sizeof(seq_t));
                if (!period) return 0;
            }
            period[idx++] = a_next;

            if (a_next == a0 * 2) { /* period terminates when a_k = 2*a0 */
                break;
            }

            m = m_next;
            d = d_next;
            a_prev = a_next;
        }
        period_len = idx; /* final period length */
    }

    if (n == 0) {
        return a0;
    }

    /* Index into the periodic part: a(1) corresponds to period[0] */
    size_t pos = (size_t)(n - 1) % period_len;
    return period[pos];
}
