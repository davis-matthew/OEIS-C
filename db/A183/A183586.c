/* OEIS A183586
   Formula: a(n) = 8*a(n-1) + 12*a(n-2)  (n ≥ 3)
   Initial values: a(1) = 6,  a(2) = 56
   Indexing starts at 1 (a(1) is the first term).  The sequence
   is generated by the above linear recurrence.  The routine
   memoises intermediate results in a growable static array so
   that repeated calls with arbitrary n are fast.  All arithmetic
   is performed using the opaque type seq_t, so the code works
   for the standard 8/16/32/64/128‑bit unsigned types and also
   for the arbitrary‑precision class used in the C++ build. */

#include <stdlib.h>   /* calloc, realloc, exit */
#include <string.h>   /* memset */

/* Cache array: cache[0] is unused (zero), cache[1] = a(1), etc. */
static seq_t *cache = NULL;      /* pointer to cache array */
static idx_t cache_cap = 0;      /* maximum allocated index (size-1) */
static idx_t cache_used = 0;     /* largest index with known value */

/* Ensure the cache can hold indices up to 'need' (inclusive). */
static void grow_cache(idx_t need)
{
    if (cache_cap >= need) return;   /* already sufficient */

    /* Double capacity until it can store 'need' */
    idx_t new_cap = cache_cap ? cache_cap << 1 : 4;
    while (new_cap < need) new_cap <<= 1;

    seq_t *tmp;
    if (cache == NULL) {
        /* Allocate and zero-initialize the whole block */
        tmp = (seq_t *)calloc(new_cap + 1, sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);
    } else {
        /* Reallocate and zero the newly added part */
        tmp = (seq_t *)realloc(cache, (new_cap + 1) * sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);
        memset(tmp + cache_cap + 1, 0,
               (new_cap - cache_cap) * sizeof(seq_t));
    }

    cache = tmp;
    cache_cap = new_cap;
}

/* OEIS A183586 */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                  /* safety for n < 1 */

    /* Ensure cache covers at least indices 1 .. n. */
    grow_cache(n);

    /* Initialise the first two terms if they are not yet set. */
    if (cache_used < 2) {
        cache[1] = (seq_t)6;
        cache[2] = (seq_t)56;
        cache_used = 2;
    }

    /* If the requested term is already cached, return it. */
    if (n <= cache_used) return cache[n];

    /* Compute successive terms using the recurrence. */
    for (idx_t i = cache_used + 1; i <= n; ++i) {
        cache[i] = (seq_t)8 * cache[i - 1] + (seq_t)12 * cache[i - 2];
    }
    cache_used = n;
    return cache[n];
}
