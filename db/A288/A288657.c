/*
 * A288657  Numbers whose squares have an odd number of digits.
 * https://oeis.org/A288657
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 26, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 74 terms through n = 9575 (2026-11-01)
 * Helpers:   ipow_i32
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Search: numbers whose squares have an odd number of decimal digits.
   The sequence is generated by iterating over the decimal digit lengths:
   for each m ≥ 0, all numbers n with 10^m ≤ n ≤ floor(sqrt(10)*10^m)
   are included in increasing order.  The 0 term is the first term. */

#include <stdint.h>
#include "../utils/ipow_i32.h"

/* Floor square root by binary search */
static inline seq_t floor_sqrt(seq_t x)
{
    seq_t lo = 0, hi = 1;
    while (ipow_i32(hi, 2) <= x)
        hi <<= 1;
    while (lo < hi)
    {
        seq_t mid = (lo + hi) >> 1;
        seq_t mid2 = mid * mid;
        if (mid2 <= x)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

static seq_t pow10[64];     /* precomputed powers of 10 */
static idx_t pow10_len = 0; /* number of entries currently stored (>=1) */

seq_t a(idx_t n)
{
    /* a(1) = 0 (the only 0‑digit number) */
    if (n == 1) return (seq_t)0;

    /* offset from the first positive term */
    idx_t r = n - 2;          /* 0‑based index for positive terms */

    /* initialise power of 10 table if not already done */
    if (pow10_len == 0) {
        pow10[0] = (seq_t)1;
        pow10_len = 1;
    }

    idx_t total = 0; /* how many positive terms have been counted so far */

    for (idx_t m = 0; ; ++m) {
        /* Ensure pow10 has entries up to exponent 2*m+1 */
        while (pow10_len <= (idx_t)(2*m + 1)) {
            pow10[pow10_len] = pow10[pow10_len - 1] * (seq_t)10;
            ++pow10_len;
        }

        seq_t start  = pow10[m];                     /* 10^m */
        seq_t limit  = floor_sqrt(pow10[2*m + 1]);   /* floor(sqrt(10^(2m+1))) */

        if (limit < start) continue;                /* empty decade (should not happen) */

        idx_t count = (idx_t)(limit - start + 1);
        if (total + count > r) {
            idx_t offset = r - total;
            return start + (seq_t)offset;
        }
        total += count;
    }
}
