/*  Sequence A288106 – Fixed point of the mapping
 *  00 -> 0010, 1 -> 00, starting with 00.
 *  The sequence consists of the successive symbols of the infinite
 *  word generated by that rewriting rule.  a(1) is the first symbol
 *  of the word, a(2) the second, and so on. */

/*  []  */
#include <stdlib.h>

static seq_t *a_buf = NULL;      /* cache of generated symbols   */
static idx_t  a_len = 0;         /* current length of a_buf       */

static void
ensure_generated(idx_t n)
{
    /* initialise the cache with the starting word "00" */
    if (a_len == 0) {
        a_buf = (seq_t *)malloc(2 * sizeof(seq_t));
        if (!a_buf) abort();          /* out‑of‑memory abort */
        a_buf[0] = 0;
        a_buf[1] = 0;
        a_len  = 2;
    }

    /* expand the word until we have at least n symbols   */
    while (a_len < n) {
        /* estimate an upper bound for the next length.
           Each input symbol expands to at most 2 output symbols,
           so a len * 3 is safely large.                 */
        size_t new_cap = (size_t)a_len * 3 + 10;
        seq_t *new_buf = (seq_t *)malloc(new_cap * sizeof(seq_t));
        if (!new_buf) abort();

        size_t new_len = 0;
        idx_t  i = 0;

        while (i < a_len) {
            if (a_buf[i] == 0) {
                /* 0 followed by 0 → 0010 */
                if ((i + 1 < a_len) && a_buf[i + 1] == 0) {
                    new_buf[new_len++] = 0;
                    new_buf[new_len++] = 0;
                    new_buf[new_len++] = 1;
                    new_buf[new_len++] = 0;
                    i += 2;
                } else { /* isolated 0 stays 0 */
                    new_buf[new_len++] = 0;
                    i += 1;
                }
            } else { /* a_buf[i] == 1 → 00 */
                new_buf[new_len++] = 0;
                new_buf[new_len++] = 0;
                i += 1;
            }
        }

        free(a_buf);
        a_buf = new_buf;
        a_len = new_len;
    }
}

seq_t
a(idx_t n)
{
    if (n == 0) return 0;          /* undefined but harmless */

    ensure_generated(n);
    return a_buf[n - 1];
}
