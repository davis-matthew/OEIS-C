/*
 * A235723  Squares which have one or more occurrences of exactly eight
 *          different digits.
 * https://oeis.org/A235723
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) = A054036(n)^2
 * Range:     u8 none, u16 none, u32 n <= 1000, u64 n <= 1000, u128 n <= 1000,
 *            big any n
 * Helpers:   digit_counts
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A(n) is the n-th square that contains exactly eight distinct decimal digits.
   The sequence is generated by scanning successive integers, squaring them,
   and testing the digit set of the square. */

#include <stdbool.h>
#include <stddef.h>
#include "../utils/digit_counts.h"

/* Return true if val has exactly eight distinct decimal digits. */
static bool has_eight_distinct_digits(seq_t val)
{
    unsigned char cnt[10] = {0};
    digit_counts(val, cnt);
    int distinct = 0;
    for (int d = 0; d < 10; ++d)
        if (cnt[d] != 0)
            ++distinct;
    return distinct == 8;
}

seq_t a(idx_t n)
{
    /* Undefined for n = 0; return 0 for safety. */
    if (n == 0)
        return (seq_t)0;

    idx_t found = 0;
    idx_t k = 1;
    seq_t result = 0;

    while (found < n) {
        seq_t sq = ((seq_t)k) * ((seq_t)k);
        if (has_eight_distinct_digits(sq)) {
            ++found;
            if (found == n)
                result = sq;
        }
        ++k;
    }

    return result;
}
