/*
 * A235114  Irregular triangle read by rows: T(n,k) = number of independent
 *          vertex subsets of size k of the graph g_n obtained by attaching
 *          two pendant edges to each vertex of the star graph S_n (having n
 *          vertices).
 * https://oeis.org/A235114
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, tabf
 * Formula:   not stated
 * Range:     u8 n <= 27, u16 n <= 63, u32 n <= 63, u64 n <= 63, u128 n <= 63,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Formula:  a(n) is the n‑th term of the flattened irregular triangle whose
 * rows are generated by
 *
 *     P_r(x) = x·(1+x)^{2r-2} + (1+x)^2 · (1+3x+x^2)^{r-1}   for r ≥ 1
 *     P_0(x) = 1                                            (row 0)
 *
 * With r = ⌊√n⌋ (row index) and k = n − r² (column index, 0 ≤ k ≤ 2r),
 *   a(n) = binom(2r-2, k-1)        (if k ≥ 1)  +
 *          Q(r-1, k)   + 2·Q(r-1, k-1) + Q(r-1, k-2),
 * where Q(m, t) is the coefficient of x^t in (1+3x+x^2)^m.
 *
 * This code implements the computation for any index n ≥ 0 using only
 * integer arithmetic on the supplied typedefs seq_t and idx_t.
 */

#include <stdlib.h>
#include <stdint.h>

/* ---------- Helper: integer sqrt (floor) for 64‑bit unsigned ---------- */
static idx_t isqrt_u64(idx_t x)
{
    idx_t r = 0;
    /* highest bit set for squared values ≤ 2⁶⁴‑1 is 1 << 62 */
    for (idx_t bit = (idx_t)1ULL << 62; bit != 0; bit >>= 1)
    {
        idx_t trial = r | bit;
        /* use 128‑bit to avoid overflow when testing trial² ≤ x */
        if ((__uint128_t)trial * trial <= x)
            r = trial;
    }
    return r;
}

/* ---------- Helper: binomial coefficient (multiplicative) ---------- */
static seq_t binom_idx(idx_t n, idx_t k)
{
    if (k > n)
        return (seq_t)0;
    if (k > n - k)
        k = n - k;
    seq_t res = (seq_t)1;
    for (idx_t i = 1; i <= k; ++i)
    {
        res = res * (seq_t)(n - k + i) / (seq_t)i;
    }
    return res;
}

/* ---------- Main function ------------------------------------------- */
seq_t a(idx_t n)
{
    /* row 0 */
    if (n == 0)
        return (seq_t)1;

    /* locate row r and column k */
    idx_t r = isqrt_u64(n);          /* floor √n  */
    /* ensure r² ≤ n < (r+1)² */
    if (r + 1 > 0 && (r + 1) * (r + 1) <= n)
    {
        /* should not happen, but guard for overflow */
        while ((r + 1) * (r + 1) <= n) ++r;
    }
    else
    {
        while (r * r > n) --r;
    }
    idx_t k = n - r * r;             /* 0 ≤ k ≤ 2r */

    /* ---------- compute Q(r-1, ·) recursively ---------- */
    idx_t m = r - 1;                  /* exponent of (1+3x+x²)      */
    idx_t qsize = (m == 0) ? 1 : 2 * m + 1;
    seq_t *q = (seq_t *)calloc((size_t)qsize, sizeof(seq_t));
    if (!q)
        return (seq_t)0;             /* allocation failure guard   */

    q[0] = (seq_t)1;                 /* (1+3x+x²)^0 */
    for (idx_t t = 1; t <= m; ++t)
    {
        idx_t oldlen = 2 * (t - 1) + 1;
        idx_t newlen = 2 * t + 1;
        seq_t *nxt = (seq_t *)calloc((size_t)newlen, sizeof(seq_t));
        if (!nxt)
        {
            free(q);
            return (seq_t)0;
        }
        for (idx_t j = 0; j < oldlen; ++j)
        {
            seq_t val = q[j];
            nxt[j] += val;          /* coefficient 1 */
            nxt[j + 1] += val * 3;  /* coefficient 3 */
            nxt[j + 2] += val;      /* coefficient 1 */
        }
        free(q);
        q = nxt;
        qsize = newlen;
    }

    /* retrieve needed Q coefficients, guard indices */
    seq_t Qk  = (k <= 2 * m) ? q[k] : (seq_t)0;
    seq_t Qk1 = (k >= 1 && k - 1 <= 2 * m) ? q[k - 1] : (seq_t)0;
    seq_t Qk2 = (k >= 2 && k - 2 <= 2 * m) ? q[k - 2] : (seq_t)0;

    free(q);

    /* binomial part: binom(2r-2, k-1) for k≥1 */
    seq_t bin = (k >= 1) ? binom_idx(2 * r - 2, k - 1) : (seq_t)0;

    /* total T(r,k) */
    seq_t result = bin + Qk + (seq_t)2 * Qk1 + Qk2;
    return result;
}
