/* A235632: Primes whose base‑5 representation is also the base‑8 representation of a prime.
   Generated by searching primes and testing the base‑5 to base‑8 conversion for primality. */

#include <stdlib.h>
#include <stdbool.h>

#include "../utils/is_prime_big.h"
#include "../utils/interpret_base5_as_base8.h"

/* Dynamic array grow helper. */
static void grow_seq(void **ptr, size_t *cap, size_t need, size_t elem_size)
{
    if (*cap >= need)
        return;
    *cap = (*cap == 0) ? 16 : (*cap << 1);
    *ptr = (void *)realloc(*ptr, *cap * elem_size);
}

/* Cached primes and terms. */
static seq_t *primes   = NULL;
static size_t primes_cnt = 0;
static size_t primes_cap = 0;

static seq_t *cache   = NULL;
static size_t cache_sz = 0;
static size_t cache_cap = 0;

static seq_t cur = 2;  /* next integer to test for primality */

/* Ensure we have at least n terms in the cache. */
static void ensure_cache(idx_t n)
{
    while (cache_sz < n) {
        /* primality test for cur using trial division by known primes. */
        bool isprime = true;
        for (size_t i = 0; i < primes_cnt; ++i) {
            seq_t p = primes[i];
            if (p > cur / p)          /* avoid overflow */
                break;
            if (cur % p == 0) {
                isprime = false;
                break;
            }
        }

        if (isprime) {
            /* store cur in primes list. */
            grow_seq((void **)&primes, &primes_cap, primes_cnt + 1, sizeof(seq_t));
            primes[primes_cnt++] = cur;

            /* check the base‑5/base‑8 condition. */
            seq_t q = interpret_base5_as_base8(cur);
            if (is_prime_big(q)) {
                grow_seq((void **)&cache, &cache_cap, cache_sz + 1, sizeof(seq_t));
                cache[cache_sz++] = cur;
            }
        }

        /* advance to the next candidate: skip even numbers. */
        if (cur == 2)
            cur = 3;
        else
            cur += 2;
    }
}

seq_t a(idx_t n)
{
    if (n == 0)
        return 0;                /* undefined for offset 0 */
    ensure_cache(n);
    return cache[n - 1];
}
