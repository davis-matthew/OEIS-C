/*
 * A383080  Numbers k such that sopf(k) does not divide evenly sopfr(k).
 * https://oeis.org/A383080
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 59, u16 n <= 59, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Helpers:   _isqrt_uint64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A383080: numbers k such that sopf(k) (sum of distinct prime
   factors) does not divide sopfr(k) (sum of prime factors with
   multiplicity).  The sequence is generated by searching integers
   in increasing order and caching the results. */

#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/_isqrt_uint64.h"

/* ---------- prime list, built incrementally ---------- */
static uint64_t *primes = NULL;
static size_t primes_len = 0;
static size_t primes_cap = 0;
static uint64_t prime_next_check = 2;

static void _ensure_primes_upto(uint64_t max) {
    while (prime_next_check <= max) {
        bool is_prime = true;
        uint64_t limit = _isqrt_uint64(prime_next_check);
        for (size_t i = 0; i < primes_len && primes[i] <= limit; ++i) {
            if (prime_next_check % primes[i] == 0) {
                is_prime = false;
                break;
            }
        }
        if (is_prime) {
            if (primes_len == primes_cap) {
                size_t new_cap = primes_cap ? (primes_cap << 1) : 16;
                uint64_t *tmp = (uint64_t *)realloc(primes, new_cap * sizeof(uint64_t));
                if (!tmp) exit(EXIT_FAILURE);
                primes = tmp;
                primes_cap = new_cap;
            }
            primes[primes_len++] = prime_next_check;
        }
        ++prime_next_check;
    }
}

/* ---------- sum of distinct and with multiplicity ---------- */
static void _factor_sums(uint64_t k, uint64_t *sopf, uint64_t *sopfr) {
    if (k <= 1) {
        *sopf = 0;
        *sopfr = 0;
        return;
    }
    uint64_t n = k;
    uint64_t sopfr_sum = 0;
    uint64_t sopf_sum = 0;

    uint64_t sqrt_k = _isqrt_uint64(k);
    _ensure_primes_upto(sqrt_k);

    for (size_t i = 0; i < primes_len && primes[i] <= sqrt_k; ++i) {
        uint64_t p = primes[i];
        if (n % p == 0) {
            uint64_t cnt = 0;
            while (n % p == 0) {
                sopfr_sum += p;
                ++cnt;
                n /= p;
            }
            sopf_sum += p;          /* distinct prime counted once */
            sqrt_k = _isqrt_uint64(n);   /* update while loop upper bound */
        }
    }
    if (n > 1) {                     /* remaining prime factor > sqrt(k) */
        sopfr_sum += n;
        sopf_sum += n;
    }
    *sopf = sopf_sum;
    *sopfr = sopfr_sum;
}

/* ---------- caching of computed terms ---------- */
static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;
static uint64_t next_k = 2;   /* smallest integer to test */

static void _append_cache(seq_t val) {
    if (cache_len >= cache_cap) {
        size_t new_cap = cache_cap ? (cache_cap << 1) : 16;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp)
            exit(EXIT_FAILURE);
        cache = tmp;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

/* ---------- required public function ---------- */
seq_t a(idx_t n) {
    if (n == 0)
        return 0;  /* undefined for 0, just guard */
    while (cache_len < (size_t)n) {
        uint64_t sopf = 0, sopfr = 0;
        _factor_sums(next_k, &sopf, &sopfr);
        if (sopf != 0 && (sopfr % sopf) != 0ULL) {
            _append_cache((seq_t)next_k);
        }
        ++next_k;
    }
    return cache[(size_t)n - 1];
}
