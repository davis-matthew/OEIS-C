/*  OEIS A374109 – numbers k such that A113177(k) and A328845(k) are not both even.
    The sequence is generated by enumerating integers in ascending order and selecting
    those whose parity condition holds.
    For a number n factorised as ∏p^e:
      A113177(n) parity = (∑_{p≠3} e) mod 2
      A328845(n) parity = 0 if n is even and (e₂ even or n%4==0),
                           1 otherwise for odd n or n=2*odd.
    The number is included whenever (∑_{p≠3}e) is odd or A328845(n) is odd.
    The routine uses a growing smallest‑prime‑factor sieve and memoises the result
    so that multiple calls are fast. */

#include <stdlib.h>
#include <stdbool.h>

seq_t a(idx_t n)
{
    static seq_t *seq = NULL;          /* memoised sequence values                     */
    static size_t seq_cap = 0;         /* capacity of seq array                        */
    static idx_t  seq_len = 0;         /* number of elements already stored            */
    static idx_t  last_checked = 1;    /* largest n already processed                  */
    static size_t sieve_limit = 0;     /* current size of the SPF sieve                */
    static uint32_t *spf = NULL;       /* smallest prime factor array                   */

    if (n <= seq_len)
        return seq[n - 1];

    /* Ensure we build the sieve in powers of two and grow the sequence as needed */
    size_t target_limit = sieve_limit;
    if (target_limit == 0) target_limit = 2;

    while (seq_len < n) {
        /* Double the sieve size each time we need more numbers */
        if (target_limit == 0) target_limit = 2;
        else target_limit <<= 1;

        /* Rebuild the SPF sieve up to target_limit */
        if (spf == NULL || sieve_limit < target_limit) {
            uint32_t *new_spf = (uint32_t*)realloc(spf, (target_limit + 1) * sizeof(uint32_t));
            if (!new_spf) abort();
            spf = new_spf;
            for (size_t i = 0; i <= target_limit; ++i) spf[i] = 0;
            for (size_t i = 2; i <= target_limit; ++i) {
                if (spf[i] == 0) {
                    spf[i] = (uint32_t)i;
                    if ((uint64_t)i * i <= target_limit)
                        for (size_t j = i * i; j <= target_limit; j += i)
                            if (spf[j] == 0) spf[j] = (uint32_t)i;
                }
            }
            sieve_limit = target_limit;
        }

        /* Scan all numbers from last_checked+1 up to the new limit and add those
           that satisfy the parity condition to the memoised sequence. */
        for (idx_t num = last_checked + 1; num <= target_limit; ++num) {
            idx_t x = num;
            int sum_parity = 0;   /* parity of ∑_{p≠3} e_p          */
            int e2_parity = 0;    /* parity of exponent of 2        */

            while (x > 1) {
                uint32_t p = spf[x];
                int e_parity = 0;          /* parity of exponent of p     */
                while (x % p == 0) {
                    x /= p;
                    e_parity ^= 1;
                }
                if (p != 3) sum_parity ^= e_parity;
                if (p == 2) e2_parity ^= e_parity;
            }

            int deriv_parity;
            if (num & 1ULL) { /* n is odd */
                deriv_parity = sum_parity;
            } else {          /* n is even */
                deriv_parity = (e2_parity == 1 && (num & 3ULL) == 2) ? 1 : 0;
            }

            /* Include n iff it is **not** excluded by the condition sum_parity==0
               and deriv_parity==0. */
            if (!(sum_parity == 0 && deriv_parity == 0)) {
                if (seq_len >= seq_cap) {
                    size_t new_cap = seq_cap ? seq_cap * 2 : 64;
                    seq_t *tmp = (seq_t*)realloc(seq, new_cap * sizeof(seq_t));
                    if (!tmp) abort();
                    seq = tmp;
                    seq_cap = new_cap;
                }
                seq[seq_len++] = (seq_t)num;
            }
        }

        last_checked = target_limit;
    }

    return seq[n - 1];
}
