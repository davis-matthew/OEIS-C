/*
 * A393161  A sequence constructed by greedily sampling the Hermite
 *          distribution, with both parameters as 1, to minimize ratio
 *          discrepancy. The distribution indexing is adjusted to be strictly
 *          decreasing and support all positive integers.
 * https://oeis.org/A393161
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 10000, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A393161 computation.
    The sequence is generated by greedily picking, at each step, the integer k ≥ 1
    that minimizes (c(k)+1) / p(k), where c(k) is the current count of k
    and p(k) is the probability of k under the conditioned Hermite distribution
    with parameters 1,1.  If two values give the same ratio, the smaller k
    is chosen.
    The probability is:
          p(k) = S(k) / (e^2-2)
    with
          S(k) = Σ_{i=0..⌈k/2⌉} 1 / [ i! · (k+1-2i)! ].
    Because e^2-2 is a constant, the comparison reduces to comparing
          (c(k)+1) / S(k) = (c(k)+1)·(k+1)! / T(k)
    where T(k) = (k+1)!·S(k) is an integer.  The values are evaluated with
    long double precision; the comparison is done in that precision, which
    is sufficient for the required ranges (n up to about 10,000).
*/

#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

/* Maximum k that will be considered.  300 is far larger than needed for n≈10000 */
#define MAX_K 300

/* Constant e^2 - 2, evaluated with long double precision */
static const long double E2_MINUS_2_LD = 5.3890560989306502137545923551397881L;

/* Cached sequence values and counts, computed lazily. */
static seq_t *seq_cache = NULL;        /* array of values a(n) */
static size_t cache_len = 0;           /* number of elements currently cached */
static size_t cache_cap = 0;           /* allocated capacity of seq_cache */

static idx_t count_k[MAX_K + 1];      /* counts c(k) for 1 ≤ k ≤ MAX_K */
static long double p_val[MAX_K + 1];  /* p(k) values for 1 ≤ k ≤ MAX_K */

static bool initialized = false;

/* Helper: compute p(k) for 1 ≤ k ≤ MAX_K using a recurrence for the sum S(k). */
static void init_probabilities(void)
{
    for (int k = 1; k <= MAX_K; ++k)
    {
        /* Compute S(k) = Σ 1/(i!·(k+1-2i)!) using the recurrence:
             term_i = term_{i-1} * [(k+3-2i)·(k+2-2i)] / i
           where term_0 = 1/(k+1)!.
         */
        long double fact = 1.0L;
        for (int i = 1; i <= k + 1; ++i)
            fact *= (long double)i;      /* fact = (k+1)! */

        long double term = 1.0L / fact;  /* term_0 */
        long double sum  = term;         /* sum_0 */

        int maxi = (k + 1) / 2;          /* ceil(k/2) */
        for (int i = 1; i <= maxi; ++i)
        {
            term *= ((long double)(k + 3 - 2 * i)) *
                    ((long double)(k + 2 - 2 * i))
                    / (long double)i;
            sum += term;
        }

        p_val[k] = sum / E2_MINUS_2_LD; /* p(k) */
    }

    /* Initialize counts and cache */
    memset(count_k, 0, sizeof(count_k));

    cache_cap = 128;
    seq_cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
    cache_len = 0;
}

/* Grow the cache if necessary. */
static void ensure_cache_capacity(size_t needed)
{
    if (needed <= cache_cap)
        return;
    /* double capacity until we have enough */
    while (cache_cap < needed) {
        size_t newcap = cache_cap * 2;
        seq_t *tmp = (seq_t *)realloc(seq_cache, newcap * sizeof(seq_t));
        if (!tmp) {
            /* allocation failure; abort */
            abort();
        }
        seq_cache = tmp;
        cache_cap = newcap;
    }
}

/* Main function required by the evaluation harness. */
seq_t a(idx_t n)
{
    if (!initialized) {
        init_probabilities();
        initialized = true;
    }

    /* Generate sequence up to n if not yet cached */
    while (cache_len < n) {
        /* Find k minimizing (c(k)+1)/p(k) */
        int best_k = 1;
        long double best_ratio = ((long double)(count_k[1] + 1)) / p_val[1];

        for (int k = 2; k <= MAX_K; ++k) {
            long double ratio = ((long double)(count_k[k] + 1)) / p_val[k];
            if (ratio < best_ratio) {
                best_ratio = ratio;
                best_k = k;
            }
        }

        /* Record the chosen value */
        count_k[best_k] += 1;

        ensure_cache_capacity(cache_len + 1);
        seq_cache[cache_len++] = (seq_t)best_k;
    }

    return seq_cache[n - 1];
}
