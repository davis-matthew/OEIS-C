/*
 * A306528  Numbers k such that gcd(k, phi(k)) = gcd(k, psi(k)).
 * https://oeis.org/A306528
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 71, u16 n <= 71, u32 n <= 71, u64 n <= 71, u128 n <= 71,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n) for OEIS A306528.  The value a(n) is the n‑th
   positive integer k for which gcd(k,phi(k)) = gcd(k,psi(k)).
   The sequence is generated by testing successive integers for
   the condition.  */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

static idx_t *spf = NULL;          /* smallest prime factor table */
static idx_t  spf_limit = 0;       /* current sieve limit */

static void init_sieve(idx_t limit)
{
    if (spf) free(spf);
    spf = (idx_t*) malloc((limit + 1) * sizeof(idx_t));
    for (idx_t i = 0; i <= limit; ++i) spf[i] = 0;
    for (idx_t i = 2; i <= limit; ++i) {
        if (spf[i] == 0) {
            spf[i] = i;
            if (i <= limit / i) {
                for (idx_t j = i * i; j <= limit; j += i)
                    if (spf[j] == 0) spf[j] = i;
            }
        }
    }
    spf_limit = limit;
}

static bool candidate(idx_t n)
{
    if (n == 1) return true;

    idx_t primes[16];
    size_t pcnt = 0;
    idx_t x = n;
    while (x > 1) {
        idx_t p = spf[x];
        primes[pcnt++] = p;
        while (x % p == 0) x /= p;
    }

    for (size_t i = 0; i < pcnt; ++i) {
        idx_t p = primes[i];
        bool has_minus = false, has_plus = false;
        for (size_t j = 0; j < pcnt; ++j) {
            if (i == j) continue;
            idx_t q = primes[j];
            if ((q - 1) % p == 0) has_minus = true;
            if ((q + 1) % p == 0) has_plus = true;
        }
        if (!((has_minus && has_plus) || (!has_minus && !has_plus)))
            return false;
    }
    return true;
}

static seq_t *terms = NULL;        /* array of found terms */
static idx_t  term_cnt = 0;        /* number of terms stored */
static idx_t  term_cap = 0;        /* allocated capacity */
static idx_t  next_checked = 1;    /* next integer to check */

static void grow_terms(idx_t min_cap)
{
    if (term_cap < min_cap) {
        idx_t new_cap = term_cap == 0 ? 16 : term_cap;
        while (new_cap < min_cap) new_cap <<= 1;
        seq_t *new_arr = (seq_t*) realloc(terms, new_cap * sizeof(seq_t));
        terms = new_arr;
        term_cap = new_cap;
    }
}

seq_t a(idx_t n)
{
    /* initialize once */
    static bool init = false;
    if (!init) {
        init_sieve(300000);         /* initial sieve size */
        init = true;
    }

    /* extend table until we have at least n terms */
    while (term_cnt < n) {
        if (next_checked > spf_limit) {
            /* enlarge sieve and continue */
            idx_t new_limit = spf_limit * 2;
            init_sieve(new_limit);
        }
        if (candidate(next_checked)) {
            grow_terms(term_cnt + 1);
            terms[term_cnt++] = (seq_t)next_checked;
        }
        ++next_checked;
    }
    return terms[n - 1];
}
