/*
 * A306561  Square numbers that are also central polygonal numbers (i.e.,
 *          square numbers found in the Lazy Caterer's sequence).
 * https://oeis.org/A306561
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 7, u32 n <= 13, u64 n <= 26, u128 n <= 51,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* a(n) = the n-th square that appears in the Lazy Caterer sequence.
 * The numbers k_n satisfy  k_n^2 = m_n(m_n+1)/2 + 1.
 * They are generated by the Pell recurrence:
 *   x_{t+1} = 3*x_t + 8*y_t
 *   y_{t+1} = x_t + 3*y_t
 * with two base solutions (x,y) = (1,1) and (5,2).
 * a(n) = k_n^2 where k_n = y_t of the appropriate branch. */

seq_t a(idx_t n) {
    /* Safety: the sequence is defined for n >= 1. */
    if (n == 0) return 0;

    /* Static state for the two interleaved Pell sequences. */
    static seq_t odd_x = (seq_t)1;     /* (1,1)  -> t=1 gives a(1)=1^2 */
    static seq_t odd_y = (seq_t)1;
    static idx_t  odd_idx = 1;         /* current t value for odd branch   */

    static seq_t even_x = (seq_t)5;    /* (5,2)  -> t=1 gives a(2)=2^2 */
    static seq_t even_y = (seq_t)2;
    static idx_t  even_idx = 1;        /* current t value for even branch  */

    /* Determine which branch and target index t. */
    if (n & 1ULL) { /* odd n  -> odd branch */
        idx_t t = (n + 1ULL) >> 1;     /* t = (n+1)/2,  t >= 1 */
        while (odd_idx < t) {
            seq_t nx = odd_x * ((seq_t)3) + odd_y * ((seq_t)8);
            seq_t ny = odd_x + odd_y * ((seq_t)3);
            odd_x = nx;
            odd_y = ny;
            ++odd_idx;
        }
        return odd_y * odd_y;          /* a(n) = k^2 */
    } else { /* even n -> even branch */
        idx_t t = n >> 1;              /* t = n/2,  t >= 1 */
        while (even_idx < t) {
            seq_t nx = even_x * ((seq_t)3) + even_y * ((seq_t)8);
            seq_t ny = even_x + even_y * ((seq_t)3);
            even_x = nx;
            even_y = ny;
            ++even_idx;
        }
        return even_y * even_y;        /* a(n) = k^2 */
    }
}
