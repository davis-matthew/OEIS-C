/*
 * A133929  Positive integers that cannot be expressed using four pentagonal
 *          numbers.
 * https://oeis.org/A133929
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, fini
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 6, u32 n <= 6, u64 n <= 6, u128 n <= 6,
 *            big any n
 * Helpers:   or_shift
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A133929: positive integers that cannot be expressed as the sum of
   four or fewer pentagonal numbers (P(k) = k(3k-1)/2, k >= 1).
   The sequence is generated by computing all sums of up to four
   pentagonal numbers up to an increasing bound until enough
   non‑representable integers have been found. */

#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/or_shift.h"

/* Helper macros for bit manipulations -----------------------------------*/
static inline void set_bit(uint64_t *bits, idx_t pos)
{
    bits[pos >> 6] |= 1ULL << (pos & 63);
}
static inline bool test_bit(const uint64_t *bits, idx_t pos)
{
    return (bits[pos >> 6] >> (pos & 63)) & 1ULL;
}

/* OR the bitset src shifted left by shift into dst.                           */
/* words   : number of 64‑bit words in each bitset                          */

/* Global state for memoisation -------------------------------------------*/
static uint64_t *reach1 = NULL, *reach2 = NULL, *reach3 = NULL, *reach4 = NULL;
static seq_t *terms = NULL;
static size_t term_cap = 0, term_count = 0;
static idx_t cur_limit = 0;
static size_t cur_words = 0;

/* Compute all sums of up to four pentagonal numbers up to new_limit.       */
static void recompute_representation(idx_t new_limit)
{
    if (new_limit <= cur_limit) return;          /* already computed */

    /* Allocate bitsets for the new limit. */
    size_t words = (new_limit + 64) >> 6;          /* ceil division */
    uint64_t *new_r1 = (uint64_t *)calloc(words, sizeof(uint64_t));
    uint64_t *new_r2 = (uint64_t *)calloc(words, sizeof(uint64_t));
    uint64_t *new_r3 = (uint64_t *)calloc(words, sizeof(uint64_t));
    uint64_t *new_r4 = (uint64_t *)calloc(words, sizeof(uint64_t));

    /* Generate pentagonal numbers <= new_limit. */
    idx_t p = 1;
    idx_t pent;
    while (true) {
        pent = p * (3 * p - 1) / 2;
        if (pent > new_limit) break;
        /* set the bit for one pentagonal number */
        set_bit(new_r1, pent);

        /* update sums with 2,3,4 pentagonal numbers */
        or_shift(new_r2, new_r1, pent, words, new_limit);
        or_shift(new_r3, new_r2, pent, words, new_limit);
        or_shift(new_r4, new_r3, pent, words, new_limit);

        ++p;
    }

    /* Free old bitsets. */
    free(reach1);
    free(reach2);
    free(reach3);
    free(reach4);

    reach1 = new_r1;
    reach2 = new_r2;
    reach3 = new_r3;
    reach4 = new_r4;
    cur_words = words;
    cur_limit = new_limit;

    /* Rebuild the list of non‑representable integers up to new_limit.    */
    /* Allocate enough space for a few thousand terms (will grow if needed). */
    if (term_cap < new_limit) {                     /* crude heuristic */
        size_t need = new_limit / 2;                /* arbitrary buffer */
        if (need > term_cap) {
            seq_t *tmp = (seq_t *)realloc(terms, need * sizeof(seq_t));
            if (!tmp && need) { /* allocation failed, abort gracefully */ }
            terms = tmp;
            term_cap = need;
        }
    }
    term_count = 0;

    for (idx_t val = 1; val <= new_limit; ++val) {
        if (!test_bit(reach1, val) &&
            !test_bit(reach2, val) &&
            !test_bit(reach3, val) &&
            !test_bit(reach4, val)) {
            if (term_count >= term_cap) {
                size_t new_cap = term_cap ? term_cap << 1 : 128;
                seq_t *tmp = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
                if (!tmp && new_cap) return; /* allocation failed */
                terms = tmp;
                term_cap = new_cap;
            }
            terms[term_count++] = (seq_t)val;
        }
    }
}

/* ----------------------------------------------------------- */
/* public API demanded by the platform                        */
/* ----------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                    /* offset 1 */
    /* Ensure we have at least n terms. */
    if (term_count < n) {
        /* Start with a reasonable bound and grow as needed. */
        idx_t limit = 200000;                 /* initial guess */
        while (term_count < n) {
            if (limit < cur_limit) limit = cur_limit;
            recompute_representation(limit);
            if (term_count >= n) break;
            /* double the limit for the next trial */
            if (limit >= 10000000) {
                /* safety: if still not enough, increase slowly */
                limit += 1000000;
            } else {
                limit <<= 1;
            }
        }
    }
    if (n <= term_count) return terms[n - 1];
    /* If sequence stops (finite), return 0 for indices beyond found terms. */
    return 0;
}
