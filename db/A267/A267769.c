/*  A267769 – numbers whose base‑9 representation is a perfect
    square when read in base 10.
    The sequence is generated by iterating the squares
    k² (k ≥ 0).  If the decimal digits of k² are all ≤ 8,
    the same digits interpreted as a base‑9 number give a term of
    the sequence.  This mapping preserves order, so the list
    produced in increasing k² is already sorted. */
#include <stdlib.h>
#include <stdbool.h>

seq_t a(idx_t n)
{
    /* static state for memoisation */
    static seq_t *seq = NULL;      /* array of sequence values   */
    static size_t seq_len = 0;     /* number of stored terms      */
    static size_t seq_cap = 0;     /* current capacity            */
    static idx_t last_k = 0;       /* next k to examine          */

    if (n == 0) { /* undefined, but return 0 for safety */
        return (seq_t)0;
    }

    /* generate terms until we have at least n */
    for (;; ++last_k) {
        seq_t sq = (seq_t)last_k * (seq_t)last_k;
        seq_t tmp = sq;
        seq_t a_val = (seq_t)0;
        seq_t pow9 = (seq_t)1;
        bool ok = true;

        /* examine decimal digits of the square */
        if (tmp == 0) {               /* special case k = 0 */
            a_val = (seq_t)0;
        } else {
            while (tmp > 0) {
                int d = (int)(tmp % (seq_t)10);
                if (d > 8) {          /* digit out of range → not a term */
                    ok = false;
                    break;
                }
                a_val += (seq_t)d * pow9;
                pow9   *= (seq_t)9;
                tmp   /= (seq_t)10;
            }
        }

        if (ok) {
            /* store the term */
            if (seq_len == seq_cap) {
                seq_cap = seq_cap ? seq_cap * 2 : 16;
                seq = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));
            }
            seq[seq_len++] = a_val;

            if (seq_len >= n) {
                /* we have enough terms */
                last_k++; /* prepare for next search */
                return seq[n - 1];
            }
        }
    }
}
