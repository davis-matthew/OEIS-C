/* Sequence A331626:
 *  Lexicographically earliest sequence of distinct positive terms
 *  such that for each n, a(n), a(n+1) and a(n)+a(n+1) have no digit in common.
 *  The sequence is generated by an incremental search, not by a closed form. */

#include <stdbool.h>
#include <stdlib.h>
#include <stddef.h>

/* Memoised cache of the sequence */
static seq_t *seq_cache = NULL;
static size_t seq_cache_len = 0;
static size_t seq_cache_cap = 0;

/* List of values already used in the sequence */
static seq_t *used_vals = NULL;
static size_t used_len = 0;
static size_t used_cap = 0;

/* Ensure seq_cache has capacity for at least 'need' elements */
static void ensure_cache_cap(size_t need)
{
    if (need <= seq_cache_cap)
        return;
    size_t newcap = seq_cache_cap ? seq_cache_cap << 1 : 128;
    while (newcap < need)
        newcap <<= 1;
    seq_t *tmp = (seq_t *)realloc(seq_cache, newcap * sizeof(seq_t));
    if (!tmp)
        abort(); /* allocation error */
    seq_cache = tmp;
    seq_cache_cap = newcap;
}

/* Ensure used_vals has capacity for at least 'need' elements */
static void ensure_used_cap(size_t need)
{
    if (need <= used_cap)
        return;
    size_t newcap = used_cap ? used_cap << 1 : 128;
    while (newcap < need)
        newcap <<= 1;
    seq_t *tmp = (seq_t *)realloc(used_vals, newcap * sizeof(seq_t));
    if (!tmp)
        abort(); /* allocation error */
    used_vals = tmp;
    used_cap = newcap;
}

/* Return a mask of decimal digits occurring in x (bit d set if digit d occurs). */
static unsigned digit_mask(seq_t x)
{
    unsigned m = 0;
    while (x > 0) {
        unsigned d = (unsigned)(x % 10);
        m |= 1u << d;
        x /= 10;
    }
    return m;
}

/* Test whether val is already in used_vals. */
static bool used_contains(seq_t val)
{
    for (size_t i = 0; i < used_len; ++i)
        if (used_vals[i] == val)
            return true;
    return false;
}

/* Append a new value to used_vals. */
static void used_append(seq_t val)
{
    if (used_len == used_cap)
        ensure_used_cap(used_len + 1);
    used_vals[used_len++] = val;
}

/* Return the n-th term (n ≥ 1). */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0; /* undefined for safety */

    /* Ensure first term (1) is present. */
    if (seq_cache_len == 0) {
        if (seq_cache_len == seq_cache_cap)
            ensure_cache_cap(seq_cache_len + 1);
        seq_cache[seq_cache_len++] = (seq_t)1;
        used_append((seq_t)1);
    }

    /* Generate terms up to n if needed. */
    while (seq_cache_len < (size_t)n) {
        seq_t prev = seq_cache[seq_cache_len - 1];
        unsigned prev_mask = digit_mask(prev);
        seq_t candidate = (seq_t)1;
        while (true) {
            /* Skip numbers already used. */
            if (used_contains(candidate)) {
                ++candidate;
                continue;
            }
            unsigned cand_mask = digit_mask(candidate);
            /* No common digits with previous term. */
            if (prev_mask & cand_mask) {
                ++candidate;
                continue;
            }
            seq_t sum = prev + candidate;
            unsigned sum_mask = digit_mask(sum);
            /* No common digits between sum and either term. */
            if ((prev_mask & sum_mask) || (cand_mask & sum_mask))
                ++candidate;
            else
                break; /* candidate is valid */
        }
        /* Store the new term. */
        if (seq_cache_len == seq_cache_cap)
            ensure_cache_cap(seq_cache_len + 1);
        seq_cache[seq_cache_len++] = candidate;
        used_append(candidate);
    }

    return seq_cache[(size_t)n - 1];
}
