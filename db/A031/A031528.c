/*  OEIS A031528
    Numbers k such that the continued fraction for sqrt(k) has even
    period and if the last term of the periodic part is deleted the
    central term is 30.  The sequence is generated by testing successive
    integers k and storing those that satisfy the condition.
    The function implements the specification in C11 and C++17.
*/

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* ------------------------------------------------------------------ */
/* Integer square‑root for idx_t (uint64_t).  Safe for all values.     */
/* ------------------------------------------------------------------ */
static inline idx_t isqrt_idx(idx_t n)
{
    idx_t low = 0, high = n;
    while (low <= high) {
        idx_t mid = low + (high - low) / 2;
        unsigned __int128 sq = (unsigned __int128)mid * (unsigned __int128)mid;
        if (sq == n) return mid;
        if (sq < (unsigned __int128)n)
            low = mid + 1;
        else
            high = mid - 1;
    }
    return high;
}

/* ------------------------------------------------------------------ */
/* Main sequence function                                             */
/* ------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    /* static cache for the terms already found */
    static seq_t *cache      = NULL;
    static size_t cache_size = 0;
    static size_t cache_cap  = 0;

    /* the next integer to test; start at 2 since 1 is a perfect square */
    static idx_t next_k = 2;

    /* grow the cache until it contains at least n terms */
    while (cache_size < (size_t)n) {
        idx_t k = next_k++;
        /* skip perfect squares */
        idx_t r = isqrt_idx(k);
        if (r * r == k)
            continue;

        /* compute the continued fraction of sqrt(k) */
        idx_t a0 = r;
        idx_t m  = 0;
        idx_t d  = 1;
        idx_t a  = a0;

        /* store the period; 8192 is ample for the required range */
        static idx_t period[8192];
        size_t L = 0;

        do {
            m = d * a - m;
            /* use 128 bit for the division to avoid overflow */
            idx_t d_next = (idx_t)(( (unsigned __int128)(k - m * m) ) / d);
            d = d_next;
            a = (a0 + m) / d;
            period[L++] = a;
        } while (d != 1);           /* period terminates when d == 1 */

        /* odd period: not allowed */
        if (L % 2 == 0) {
            /* check that the central element equals 30 */
            if (period[L / 2 - 1] == 30) {
                /* store this k in the cache */
                if (cache_size == cache_cap) {
                    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                    if (!tmp)
                        exit(EXIT_FAILURE);
                    cache = tmp;
                    cache_cap = new_cap;
                }
                cache[cache_size++] = (seq_t)k;
            }
        }
    }

    /* cache is guaranteed to contain at least n terms */
    return cache[n - 1];
}
