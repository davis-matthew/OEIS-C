/*
 * A381802  a(n) = number of distinct residues r mod n of numbers k congruent
 *          to r (mod n) such that rad(k) does not divide n, where rad =
 *          A007947.
 * https://oeis.org/A381802
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = n - |{m mod n : m is product of primes dividing n}|
 * Range:     u8 n <= 262, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This algorithm generates the monoid of residues generated by the primes
   of n (including 0) via BFS and counts its size.  The sequence value
   a(n) is then n minus that count. */

#include <stdlib.h>
#include <string.h>
#include <stdint.h>

seq_t a(idx_t n)
{
    /* Special cases: a(1) = a(2) = 0 */
    if (n <= 2)
        return 0;

    /* 1. Extract distinct prime factors of n */
    const int MAX_PRIMES = 16;           /* enough for n <= 10^4 */
    idx_t primes[MAX_PRIMES];
    size_t prim_cnt = 0;
    idx_t m = n;

    if ((m & 1ULL) == 0) {              /* factor 2 */
        primes[prim_cnt++] = 2;
        while ((m & 1ULL) == 0) m >>= 1;
    }
    for (idx_t p = 3; p * p <= m; p += 2) {
        if (m % p == 0) {
            primes[prim_cnt++] = p;
            while (m % p == 0) m /= p;
        }
    }
    if (m > 1) {
        if (prim_cnt < MAX_PRIMES)
            primes[prim_cnt++] = m;
    }

    /* 2. Allocate visited marker array and BFS queue */
    idx_t N = n;                        /* alias for clarity */
    uint8_t *visited = (uint8_t*)malloc(N * sizeof(uint8_t));
    if (!visited) return 0;              /* allocation failure fallback */

    /* maximum queue size is N (each residue visited once) */
    idx_t *queue = (idx_t*)malloc(N * sizeof(idx_t));
    if (!queue) { free(visited); return 0; }

    memset(visited, 0, N * sizeof(uint8_t));

    /* Start from residue 1 (always reachable) */
    visited[1] = 1;
    seq_t visited_cnt = 1;
    idx_t head = 0, tail = 0;
    queue[tail++] = 1;

    /* 3. BFS over the monoid generated by primes */
    while (head < tail) {
        idx_t r = queue[head++];
        for (size_t i = 0; i < prim_cnt; ++i) {
            idx_t newr = (r * primes[i]) % N;
            if (!visited[newr]) {
                visited[newr] = 1;
                ++visited_cnt;
                queue[tail++] = newr;
            }
        }
    }

    free(queue);
    free(visited);

    /* 4. Desired value: a(n) = n - number of reachable residues */
    return (seq_t)N - visited_cnt;
}
