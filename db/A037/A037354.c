/* Sequence: Numbers whose base-4 and base-7 expansions have no digits in
 * common.  No closed form is known; the sequence is generated by brute-force
 * testing each integer for the digit-intersection property. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/mem.h"

/* Check whether val has no common digit in its base‑4 and base‑7 representations. */
static bool no_common_digits_idx(idx_t val)
{
    uint64_t mask4 = 0, mask7 = 0;
    idx_t v = val;
    while (v != 0) {
        int d = v % 4;
        mask4 |= 1ULL << d;
        v /= 4;
    }
    v = val;
    while (v != 0) {
        int d = v % 7;
        mask7 |= 1ULL << d;
        v /= 7;
    }
    return (mask4 & mask7) == 0;
}

/* External linkage function required by the build. */
seq_t a(idx_t n)
{
    /* Static cache of computed terms. */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;
    static idx_t next_candidate = 1;

    /* Populate the cache until we have at least n terms. */
    while (cache_len < n) {
        /* Grow cache storage if necessary. */
        if (cache_cap == 0) {
            cache_cap = 64;
            cache = mem_resize(seq_t, cache, cache_cap);
            if (!cache) return 0;
        }
        if (no_common_digits_idx(next_candidate)) {
            if (cache_len == cache_cap) {
                cache_cap *= 2;
                cache = mem_resize(seq_t, cache, cache_cap);
                if (!cache) return 0;
            }
            cache[cache_len++] = (seq_t)next_candidate;
        }
        ++next_candidate;
    }

    return cache[n - 1];
}
