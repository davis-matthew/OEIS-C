/* Sequence: Trajectory of 15 under prime factor concatenation procedure.
   a(0)=15; subsequent terms are generated by repeatedly factoring the current
   number into primes (with multiplicity), outputting the factors in ascending order,
   and setting the next current to the decimal concatenation of those factors. */

#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>

#include "../utils/factor_u64.h"
#include "../utils/digit_count.h"

/* Precomputed powers of 10 up to 10^20 (fits in 64-bit). */
static const uint64_t pow10_arr[21] = {
    1ULL, 10ULL, 100ULL, 1000ULL, 10000ULL, 100000ULL,
    1000000ULL, 10000000ULL, 100000000ULL, 1000000000ULL,
    10000000000ULL, 100000000000ULL, 1000000000000ULL, 10000000000000ULL,
    100000000000000ULL, 1000000000000000ULL, 10000000000000000ULL,
    100000000000000000ULL, 1000000000000000000ULL, 10000000000000000000ULL
};

static seq_t *cache = NULL;          /* cached sequence values */
static size_t cache_size = 0;        /* number of stored terms */
static size_t cache_cap  = 0;        /* allocated capacity */

/* Ensure the cache can hold at least 'needed' elements. */
static void cache_ensure(size_t needed)
{
    if (needed <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 16;
    while (new_cap < needed)
        new_cap *= 2;
    cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    cache_cap = new_cap;
}

seq_t a(idx_t n)
{
    /* Fast return if already computed. */
    if ((size_t)n < cache_size)
        return cache[(size_t)n];

    /* Allocate enough space. */
    cache_ensure((size_t)n + 1);

    /* Initialize first term if not yet done. */
    if (cache_size == 0) {
        cache[0] = (seq_t)15;
        cache_size = 1;
    }

    /* Current value (as 64‑bit for factoring). */
    uint64_t cur = (uint64_t)cache[0];
    size_t pos = 1; /* next index to fill */

    /* Main loop: generate terms until 'n' is reached. */
    while (pos <= (size_t)n) {
        /* Factor cur. */
        uint64_t primes[64];
        uint64_t exps  [64];
        size_t cnt = 0;
        factor_u64(cur, primes, exps, &cnt);

        /* Emit prime factors (with multiplicity). */
        for (size_t i = 0; i < cnt && pos <= (size_t)n; ++i) {
            for (uint64_t e = 0; e < exps[i] && pos <= (size_t)n; ++e) {
                cache[pos++] = (seq_t)primes[i];
            }
        }

        /* If we have produced the desired term, stop. */
        if (pos > (size_t)n)
            break;

        /* Build the next current by concatenating the prime factors. */
        uint64_t new_cur = 0;
        for (size_t i = 0; i < cnt; ++i) {
            for (uint64_t e = 0; e < exps[i]; ++e) {
                uint64_t p    = primes[i];
                size_t  digs  = (size_t)digit_count(p);
                new_cur = new_cur * pow10_arr[digs] + p;
            }
        }
        cur = new_cur;
    }

    /* Update cached size. */
    cache_size = pos;
    return cache[(size_t)n];
}
