/* Sequence A037396: numbers k such that every base‑5 digit of k is a
   base‑9 digit of k.  The sequence is generated by checking each
   integer k from 1 upward and counting those that satisfy the digit
   inclusion condition.  The search is performed using 64‑bit integer
   arithmetic for speed; the resulting value is promoted to seq_t
   (which may be wider) when returned.  This is safe for the range of
   n tested (up to at least 10 000, where all terms fit in 64 bits). */

#include <stdbool.h>
#include <stdint.h>

/* Return true iff every digit present in the base‑5 representation
   of k also appears somewhere in the base‑9 representation of k. */
static bool ok_digit_subset_uint64(uint64_t k)
{
    uint64_t mask5 = 0, mask9 = 0;

    /* Collect digits of k in base 5. */
    uint64_t t = k;
    while (t > 0) {
        unsigned d = t % 5;
        mask5 |= 1ull << d;
        t /= 5;
    }

    /* Collect digits of k in base 9. */
    t = k;
    while (t > 0) {
        unsigned d = t % 9;
        mask9 |= 1ull << d;
        t /= 9;
    }

    /* All base‑5 digits must be present among base‑9 digits. */
    return (mask5 & ~mask9) == 0;
}

/* Return the nth term of the sequence (offset 1). */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;          /* behaviour for n < 1 is undefined */

    idx_t count = 0;
    uint64_t k = 1;              /* start testing from 1 */

    for (;;) {
        if (ok_digit_subset_uint64(k)) {
            ++count;
            if (count == n)
                return (seq_t)k;
        }
        ++k;
    }
}
