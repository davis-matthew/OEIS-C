/*
 * A048718  Binary expansion matches ((0)*0001)*(0*); or, Zeckendorf-like
 *          expansion of n using recurrence f(n) = f(n-1) + f(n-4).
 * https://oeis.org/A048718
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 18, u16 n <= 44, u32 n <= 44, u64 n <= 44, u128 n <= 44,
 *            big any n
 * Helpers:   pow2
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A048718: numbers whose binary representation has at most one 1 in any
   four consecutive bits (i.e. any two 1s differ by at least 4 positions).
   The sequence is generated by the recurrence
        count_exact(h) = g(h-4)    (g(k) = g(k-1)+g(k-4), g(k)=1 for k<0)
   and each term is obtained by repeatedly extracting the largest admissible bit:
        while n > 0
            find h s.t. total(h-1) <= n < total(h)
            n      := n - total(h-1)
            value  := value + 2^h
   This yields a(n) for all n >= 0.  */

#include <stdint.h>
#include <stddef.h>
#include "../utils/pow2.h"   /* seq_t pow2(idx_t exp); */

seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;

    seq_t result = (seq_t)0;

    /* Pre‑compute g(k) up to a safe limit.  
       For the recurrence g(k)=g(k-1)+g(k-4) with g(k)=1 for k<0,
       the growth factor is <1.381, so g(200) already exceeds
       any 64‑bit limit.  */
    enum { MAX_G = 200 };
    static idx_t g[MAX_G];
    static int init = 0;
    if (!init) {
        for (idx_t i = 0; i < MAX_G; ++i) {
            idx_t a = (i >= 1) ? g[i - 1] : (idx_t)1;
            idx_t b = (i >= 4) ? g[i - 4] : (idx_t)1;
            g[i] = a + b;
        }
        init = 1;
    }

    while (n > 0) {
        /* Find the highest bit h of the current term.  */
        idx_t cum = 1;          /* total(-1) = 1 (only zero).  */
        idx_t h = 0;
        while (1) {
            idx_t count_exact = (h >= 4) ? g[h - 4] : (idx_t)1;
            idx_t new_cum = cum + count_exact;
            if (new_cum > n)
                break;
            cum = new_cum;
            ++h;
        }
        idx_t offset = n - cum;
        result = result + pow2(h);   /* add 2^h to the term.  */
        n = offset;                  /* recurse on the remainder.  */
    }

    return result;
}
