/*
 * A048128  Becomes prime or 4 after exactly 6 iterations of f(x) = sum of
 *          prime factors of x.
 * https://oeis.org/A048128
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 3500, u32 n <= 3500, u64 n <= 3500,
 *            u128 n <= 3500, big any n
 * Helpers:   is_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A048128 – numbers that become prime or 4 after exactly 6
   iterations of f(x) = sum of prime factors (with multiplicity). */
/* The sequence is generated by brute‑force search for each n.
   Each candidate is tested up to 6 iterations; the result must be
   prime or 4, and none of the first 5 iterations produce 4 or a
   prime. */

#include <stdbool.h>
#include <stdint.h>
#include "../utils/is_prime.h"

static seq_t sum_prime_factors(seq_t x)
{
    uint64_t n = (uint64_t)x;
    if (n <= 1) return (seq_t)n;

    uint64_t sum = 0;
    /* factor 2 */
    while ((n & 1ULL) == 0) {
        sum += 2;
        n >>= 1;
    }
    /* odd factors */
    for (uint64_t i = 3; i * i <= n; i += 2) {
        while (n % i == 0) {
            sum += i;
            n /= i;
        }
    }
    if (n > 1) sum += n;
    return (seq_t)sum;
}

static bool good_candidate(seq_t x)
{
    seq_t y = x;
    /* 6 iterations */
    for (int k = 0; k < 6; ++k) {
        y = sum_prime_factors(y);
    }
    /* final must be 4 or prime */
    if (!(y == (seq_t)4 || is_prime((idx_t)y)))
        return false;

    /* ensure that no earlier iteration ended with 4 or prime */
    seq_t z = x;
    for (int k = 0; k < 5; ++k) {
        z = sum_prime_factors(z);
        if (z == (seq_t)4 || is_prime((idx_t)z))
            return false;
    }
    return true;
}

seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;

    idx_t count = 0;
    uint64_t cand = 2;          /* start scanning from 2 upward */
    seq_t result = 0;

    while (1) {
        if (good_candidate((seq_t)cand)) {
            ++count;
            if (count == n) {
                result = (seq_t)cand;
                break;
            }
        }
        ++cand;
    }
    return result;
}
