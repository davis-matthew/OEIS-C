/*
 * A048792  When cubed gives number composed just of the digits 0, 1, 2, 3, 4.
 * https://oeis.org/A048792
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 9, u16 n <= 28, u32 n <= 39, u64 n <= 39, u128 n <= 39,
 *            big any n
 * Helpers:   cube_digits_ok
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the nth element of sequence A048792.
   It is generated by enumerating all non‑negative integers m, testing
   whether m^3 contains only the decimal digits 0,1,2,3,4, and storing
   those m in ascending order.  The first term is a(0)=0.  The algorithm
   is a simple incremental scan and is fast enough for n≈10 000.   */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/cube_digits_ok.h"

/*---------------------------------------------------------------------*/

/*---------------------------------------------------------------------*/
/*  Dynamic array used to store the computed terms.                     */
static seq_t *cache = NULL;        /* array of computed terms            */
static size_t cache_cap = 0;       /* allocated capacity                 */
static size_t cache_len = 0;       /* number of terms stored (incl. a(0))*/

/*  The next integer to test.  The sequence starts with 0, so the first
    candidate we examine is 1. */
static idx_t next_candidate = 1;

/*---------------------------------------------------------------------*/
/*  Ensure the cache can hold at least 'min_cap' elements.             */
static void grow_cache(size_t min_cap)
{
    if (min_cap <= cache_cap) return;
    size_t new_cap = cache_cap > 0 ? cache_cap : 8;
    while (new_cap < min_cap) new_cap *= 2;
    seq_t *new_ptr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!new_ptr) abort();        /* out of memory */
    cache = new_ptr;
    cache_cap = new_cap;
}

/*---------------------------------------------------------------------*/
/*  Main sequence function.  It expands the cache until it holds the
    term a(n).                                                           */
seq_t a(idx_t n)
{
    /* Initialize first term a(0)=0 on first call. */
    if (cache_len == 0) {
        grow_cache(8);
        cache[0] = (seq_t)0;
        cache_len = 1;
    }

    /* Expand until we have at least n+1 elements. */
    while (cache_len <= (size_t)n) {
        if (cube_digits_ok(next_candidate)) {
            grow_cache(cache_len + 1);
            cache[cache_len++] = (seq_t)next_candidate;
        }
        ++next_candidate;
    }

    return cache[(size_t)n];
}
