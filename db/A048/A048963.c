/*
 * A048963  Table in which n-th row lists digits in periodic part of decimal
 *          expansion of reciprocal of n-th prime.
 * https://oeis.org/A048963
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy, tabf, nice
 * Formula:   not stated
 * Range:     u8 n <= 3155, u16 n <= 3155, u32 n <= 3155, u64 n <= 3155,
 *            u128 n <= 3155, big any n
 * Helpers:   grow_uint32
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n) as the n-th digit in the concatenated periodic parts
 * of 1/p where p runs over the primes in increasing order.
 * Example: n=1 -> 0 (period of 1/2), n=4 -> 1 (first digit of period of 1/7).
 * The periodic parts are generated by standard long division.
 * The code memoizes all computed digits and primes so that multiple
 * calls are efficient. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/grow_uint32.h"

/* ---------- dynamic array helpers ---------- */
static void grow_seq_t(seq_t **arr, size_t *cap, size_t need)
{
    if (*cap < need) {
        size_t new_cap = (*cap == 0 ? 4 : *cap << 1);
        while (new_cap < need) new_cap <<= 1;
        *arr = (seq_t *)realloc(*arr, new_cap * sizeof(seq_t));
        *cap = new_cap;
    }
}

/* ---------- cached data ---------- */
static seq_t   *digits   = NULL;
static size_t  digits_len = 0;
static size_t  digits_cap = 0;

static uint32_t *primes = NULL;
static size_t  primes_len = 0;
static size_t  primes_cap = 0;

/* ---------- prime generator (trial division) ---------- */
static uint32_t next_prime(void)
{
    if (primes_len == 0) {               /* first prime */
        grow_uint32(&primes, &primes_cap, 4);
        primes[0] = 2;
        primes_len = 1;
        return 2;
    }

    uint32_t candidate = primes[primes_len - 1] + 1;
    for (;;) {
        if (candidate % 2 == 0) { candidate++; continue; }
        bool is_prime = true;
        for (size_t i = 0; i < primes_len; ++i) {
            uint32_t p = primes[i];
            if ((uint64_t)p * (uint64_t)p > (uint64_t)candidate) break;
            if (candidate % p == 0) { is_prime = false; break; }
        }
        if (is_prime) {
            grow_uint32(&primes, &primes_cap, primes_len + 1);
            primes[primes_len++] = candidate;
            return candidate;
        }
        candidate++;
    }
}

/* ---------- generate the next periodic part ---------- */
static void generate_next_period(void)
{
    uint32_t p = next_prime();

    /* terminating decimals: 1/2 = .5, 1/5 = .2 → period digit 0 */
    if (p == 2 || p == 5) {
        grow_seq_t(&digits, &digits_cap, digits_len + 1);
        digits[digits_len++] = (seq_t)0;
        return;
    }

    uint64_t remainder = 1;
    for (;;) {
        remainder *= 10;
        uint64_t digit = remainder / p;
        remainder    %= p;

        grow_seq_t(&digits, &digits_cap, digits_len + 1);
        digits[digits_len++] = (seq_t)digit;

        if (remainder == 1) break;     /* period completed */
    }
}

/* ---------- public function ---------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                /* out-of-bounds safety */

    size_t target = (size_t)n;
    while (digits_len < target) {
        generate_next_period();
    }
    return digits[target - 1];
}
