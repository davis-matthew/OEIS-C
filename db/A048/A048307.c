/*
 * A048307  Numbers whose decimal expansions, read from left to right, have
 *          run lengths that strictly increase.
 * https://oeis.org/A048307
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 34, u16 n <= 57, u32 n <= 57, u64 n <= 57, u128 n <= 57,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes OEIS A048307: numbers whose decimal expansions have strictly increasing run lengths;
   the terms are generated by a simple brute‑force search. */
#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* Return true if the decimal representation of x has strictly increasing run lengths. */
static bool is_good(seq_t x)
{
    if (x == 0) return true;   /* zero has one run of length 1 */

    /* collect digits in reverse order: digits[0] = least significant */
    int digits[128];
    int len = 0;
    seq_t y = x;
    while (y != 0) {
        digits[len++] = (int)(y % 10);
        y /= 10;
    }

    int prev_len = 0;
    int i = len - 1;            /* start from the most significant digit */
    while (i >= 0) {
        int cur_digit = digits[i];
        int run_len = 1;
        while (i > 0 && digits[i-1] == cur_digit) {
            run_len++;
            i--;
        }
        if (prev_len >= run_len) return false;   /* not strictly increasing */
        prev_len = run_len;
        i--;
    }
    return true;
}

/* Cache holding computed sequence values a(0)..a(max_cached) */
static seq_t *cache = NULL;
static size_t cache_cap = 0;
static size_t cache_len = 0;
static seq_t next_candidate = 0;

/* Grow the cache to include at least terms 0..n. */
static void ensure_cache(idx_t n)
{
    if (cache_len > (size_t)n) return;

    /* enlarge the cache array if necessary */
    while (n >= (idx_t)cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 16;
        cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        cache_cap = new_cap;
    }

    /* search for the remaining terms */
    while ((idx_t)cache_len <= n) {
        while (true) {
            if (is_good(next_candidate)) {
                cache[cache_len++] = next_candidate;
                next_candidate++;            /* prepare candidate for next term */
                break;
            }
            next_candidate++;
        }
    }
}

/* Public function */
seq_t a(idx_t n)
{
    ensure_cache(n);
    return cache[(size_t)n];
}
