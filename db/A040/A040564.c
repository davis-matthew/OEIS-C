/* Continued fraction for sqrt(589).
   a(0) = floor(sqrt(589)) = 24.
   For n ≥ 1 the term a(n) is the (n‑1) mod period length element of
   the periodic part of the expansion of sqrt(589).  The period is
   generated by the standard algorithm for continued fractions of
   quadratic surds. */

#include <stdint.h>
#include <stddef.h>

seq_t a(idx_t n)
{
    /* Return the first term */
    if (n == 0) {
        return (seq_t)24;
    }

    /* The square root of 589 is not an integer.  Compute a0. */
    static const seq_t D = (seq_t)589;
    static seq_t a0 = 0;
    if (a0 == 0) {
        /* simple integer square‑root calculation */
        seq_t x = 0;
        while ((x + 1) * (x + 1) <= D) {
            x++;
        }
        a0 = x;              /* = 24 */
    }

    /* Lazily compute and cache the periodic part once. */
    static seq_t period[256];          /* enough for any period of sqrt(589) */
    static idx_t period_len = 0;

    if (period_len == 0) {            /* first invocation – compute period */
        seq_t m = 0;
        seq_t d = 1;
        seq_t a = a0;
        idx_t i = 0;

        /* The standard continued fraction algorithm */
        while (1) {
            m = d * a - m;
            d = (D - m * m) / d;      /* integer division exact */
            a = (a0 + m) / d;         /* floor((a0 + m)/d) */

            period[i++] = a;
            if (a == 2 * a0) {        /* period ends when a == 2*a0 */
                break;
            }
        }
        period_len = i;              /* store length */
    }

    /* Return the requested term from the periodic part. */
    return period[(n - 1) % period_len];
}
