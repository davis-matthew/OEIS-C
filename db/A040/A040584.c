/* Continued fraction for sqrt(609) (OEIS A040584)
   The terms are generated by the classic algorithm for quadratic
   surds.  a(0)=⌊√609⌋=24 and the periodic part starts with a(1).
   The period ends when the partial quotient equals 2×a(0)=48.

   The function caches the period on first call so that all subsequent
   accesses are O(1).  It works for any seq_t type and for any non‑negative
   index, regardless of call order. */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

#define _CF_MAX_PERIOD 256

static seq_t _cf_period[_CF_MAX_PERIOD];
static size_t _cf_period_len;
static bool _cf_computed = false;

/* Compute the periodic part of the continued fraction for sqrt(609). */
static void _compute_cf(void)
{
    const idx_t D = 609;           /* square‑free integer */
    uint64_t a0 = 0;               /* floor(sqrt(D)) */

    for (uint64_t i = 0; i * i <= D; ++i) a0 = i;   /* small enough to avoid overflow */

    uint64_t m = 0, d = 1;
    uint64_t a = a0;
    size_t idx = 0;

    do {
        m = d * a - m;
        d = (D - m * m) / d;
        a = (a0 + m) / d;

        if (idx < _CF_MAX_PERIOD)
            _cf_period[idx++] = (seq_t)a;
    } while (a != 2 * a0);          /* period terminates when a == 2*a0 */

    _cf_period_len = idx;
    _cf_computed = true;
}

seq_t a(idx_t n)
{
    if (!_cf_computed) {
        _compute_cf();
    }

    if (n == 0) {
        /* a0 = floor(sqrt(609)) = 24 */
        return (seq_t)24;
    }

    /* Periodic part: a(1), a(2), ... */
    idx_t idx = (idx_t)((n - 1) % (idx_t)_cf_period_len);
    return _cf_period[idx];
}
