/*
 * A040067  Primes p such that x^3 = 14 has a solution mod p.
 * https://oeis.org/A040067
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 39, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   mod_pow
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Search: primes p such that 14 is a cubic residue modulo p (i.e. the congruence
   x³ ≡ 14 (mod p) has a solution).  The sequence is generated by
   iterating over primes and testing the cubic residuosity condition. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/mod_pow.h"

seq_t a(idx_t n)
{
    /* static storage for the primes that satisfy the condition */
    static seq_t *results = NULL;
    static size_t res_cap = 0;
    static size_t res_len = 0;

    /* static storage for all primes encountered so far (for primality testing) */
    static idx_t *primes = NULL;
    static size_t primes_cap = 0;
    static size_t primes_len = 0;

    /* next integer to test for primality */
    static idx_t current = 2;

    /* guard against n == 0 (though according to the problem this should
       never happen) */
    if (n == 0) return 0;

    /* grow array helpers */
    if (results == NULL) {
        res_cap = 32;
        results = (seq_t *)realloc(NULL, res_cap * sizeof(seq_t));
        if (!results) return 0; /* allocation failure */
    }
    if (primes == NULL) {
        primes_cap = 32;
        primes = (idx_t *)realloc(NULL, primes_cap * sizeof(idx_t));
        if (!primes) return 0;
    }

    /* main generation loop: keep searching until we have at least n terms */
    while (res_len < (size_t)n) {
        /* Test current for primality using known primes */
        bool isprime = true;
        for (size_t i = 0; i < primes_len; ++i) {
            idx_t p = primes[i];
            if ((uint64_t)p * (uint64_t)p > current) break;
            if (current % p == 0) { isprime = false; break; }
        }
        if (isprime) {
            /* store the new prime for future divisibility checks */
            if (primes_len == primes_cap) {
                primes_cap *= 2;
                idx_t *tmp = (idx_t *)realloc(primes, primes_cap * sizeof(idx_t));
                if (!tmp) return 0;
                primes = tmp;
            }
            primes[primes_len++] = current;

            /* Determine whether 14 is a cubic residue modulo current */
            bool qualifies = false;
            if (current == 2 || current == 3 || current == 7) {
                qualifies = true;
            } else if (current % 3 == 2) {          /* p ≡ 2 (mod 3) → all non‑zero residues are cubes */
                qualifies = true;
            } else if (current % 3 == 1) {          /* p ≡ 1 (mod 3) → test the cubic residue condition */
                seq_t r = mod_pow((seq_t)14,
                                  (uint64_t)(current - 1) / 3,
                                  (seq_t)current);
                if (r == (seq_t)1) qualifies = true;
            } /* p % 3 == 0 cannot happen for primes other than 3 */

            if (qualifies) {
                /* add to results list */
                if (res_len == res_cap) {
                    res_cap *= 2;
                    seq_t *tmp = (seq_t *)realloc(results, res_cap * sizeof(seq_t));
                    if (!tmp) return 0;
                    results = tmp;
                }
                results[res_len++] = (seq_t)current;
            }
        }
        ++current;
    }

    return results[n - 1];
}
