/* Recurrence: a(0) = ⌊√313⌋ = 17.
   For n ≥ 1, a(n) are the continued‑fraction terms of √313.
   They are generated by the standard algorithm:
     m₀ = 0 , d₀ = 1 , a₀ = ⌊√313⌋
     mᵢ₊₁ = dᵢ·aᵢ - mᵢ
     dᵢ₊₁ = (313 - mᵢ₊₁²) / dᵢ
     aᵢ₊₁ = ⌊(a₀ + mᵢ₊₁) / dᵢ₊₁⌋
   The period ends when aᵢ₊₁ = 2·a₀. */

#include <stddef.h>

seq_t a(idx_t n)
{
    /* Cache the periodic part after the first call. */
    static seq_t period[512];
    static size_t period_len = 0;

    if (period_len == 0) {
        const seq_t D   = (seq_t)313;     /* radicand */
        const seq_t a0  = (seq_t)17;      /* floor(sqrt(313)) */

        seq_t m = (seq_t)0;
        seq_t d = (seq_t)1;
        seq_t a_k = a0;

        do {
            /* m_{k+1} = d_k * a_k - m_k */
            m = d * a_k - m;
            /* d_{k+1} = (D - m_{k+1}²) / d_k */
            d = (D - m * m) / d;
            /* a_{k+1} = ⌊(a0 + m_{k+1}) / d_{k+1}⌋ */
            a_k = (a0 + m) / d;
            period[period_len++] = a_k;
        } while (a_k != 2 * a0);
    }

    if (n == 0) {
        return (seq_t)17;                 /* a(0) */
    }

    /* Map n-1 into the periodic block. */
    size_t idx = (size_t)((n - 1) % period_len);
    return period[idx];
}
