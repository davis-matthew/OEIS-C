/*
 * A040242  Continued fraction for sqrt(259).
 * https://oeis.org/A040242
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, cofr, easy
 * Formula:   a(0)=16; for n≥1, a(n) is the n‑th partial quotient in the
 *            simple continued fraction expansion of √259
 * Range:     u8 n <= 1, u16 n <= 80, u32 n <= 80, u64 n <= 80, u128 n <= 80,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

seq_t a(idx_t n) {
    /* The continued fraction of √259 starts with
       a0 = ⌊√259⌋ = 16. Subsequent terms are
       generated by the recurrence
           m_{k+1} = d_k·a_k – m_k
           d_{k+1} = (259 – m_{k+1}²) / d_k
           a_{k+1} = ⌊(16 + m_{k+1}) / d_{k+1}⌋
       where m_0 = 0, d_0 = 1, a_0 = 16. */
    if (n == 0) {
        return (seq_t)16;
    }

    seq_t a0 = (seq_t)16;
    seq_t D  = (seq_t)259;
    seq_t m  = (seq_t)0;
    seq_t d  = (seq_t)1;
    seq_t a  = a0;

    for (idx_t i = 1; i <= n; ++i) {
        m = d * a - m;
        d = (D - m * m) / d;
        a = (a0 + m) / d;
    }
    return a;
}
