/* Continuous fraction coefficients for sqrt(649).
   a(0) equals floor(sqrt(649)) = 25.
   For n >= 1 the coefficients are generated by
   m_{k}=d_{k-1}*a_{k-1}-m_{k-1},
   d_{k}=(N - m_{k}^2)/d_{k-1},
   a_{k}=⌊(a0 + m_{k})/d_{k}⌋,
   with N = 649 and a0 = 25. */

seq_t a(idx_t n)
{
    /* constants for sqrt(649) */
    const seq_t N   = (seq_t)649;
    const seq_t a0  = (seq_t)25;

    if (n == 0)
        return a0;

    /* initial state of the continued fraction algorithm */
    seq_t m = 0;      /* m0 */
    seq_t d = 1;      /* d0 */
    seq_t a_curr = a0; /* a0, the 0‑th coefficient */

    for (idx_t i = 1; i <= n; ++i) {
        /* compute next state */
        seq_t m_next = d * a_curr - m;
        seq_t d_next = (N - m_next * m_next) / d;
        seq_t a_next = (a0 + m_next) / d_next;

        /* update for next iteration */
        m = m_next;
        d = d_next;
        a_curr = a_next;
    }

    return a_curr;
}
