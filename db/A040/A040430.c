/* Continued fraction for sqrt(452) using the standard
   extraction algorithm.  The first term a(0) is floor(sqrt(452)).
   For n > 0 the terms are generated by:
   m  = d * a_prev - m_prev
   d  = (N - m^2) / d_prev
   a  = (a0 + m) / d
   where N = 452 and a0 = floor(sqrt(N)). */

#include <stdint.h>
#include "../utils/floor_sqrt.h"

seq_t a(idx_t n) {
    const seq_t N = 452;
    seq_t a0 = floor_sqrt(N);
    if (n == 0) return a0;

    seq_t m   = 0;
    seq_t d   = 1;
    seq_t aval = a0;

    for (idx_t i = 1; i <= n; ++i) {
        m   = d * aval - m;
        d   = (N - m * m) / d;
        aval = (a0 + m) / d;
    }
    return aval;
}
