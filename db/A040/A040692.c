/* Continued fraction coefficients for sqrt(719).  a(0) = floor(sqrt(719)),
   subsequent terms are generated by the standard continued‑fraction algorithm
   for square roots, producing a periodic sequence. */

#include <stdlib.h>

seq_t a(idx_t n)
{
    /* static cache of the periodic part */
    static seq_t *period = NULL;
    static idx_t period_len = 0;
    static idx_t period_cap = 0;

    const seq_t a0   = (seq_t)26;   /* floor(sqrt(719)) */
    const idx_t D    = 719;         /* the radicand */

    if (period_len == 0) {
        /* compute one full period */
        idx_t m  = 0;
        idx_t d  = 1;
        idx_t a  = (idx_t)a0;      /* as idx_t for calculations */

        do {
            idx_t m_next = d * a - m;
            idx_t d_next = (D - m_next * m_next) / d;
            idx_t a_next = ((idx_t)a0 + m_next) / d_next;

            /* grow storage if needed */
            if (period_len == period_cap) {
                period_cap = period_cap ? period_cap * 2 : 256;
                period = (seq_t *)realloc(period, period_cap * sizeof(seq_t));
            }
            period[period_len++] = (seq_t)a_next;

            /* end of period when a_next == 2*a0 */
            if (a_next == 2 * (idx_t)a0) {
                break;
            }

            /* advance for next step */
            m = m_next;
            d = d_next;
            a = a_next;
        } while (1);
    }

    if (n == 0) {
        return a0;
    }

    /* index into the period (periodic part starts at n==1) */
    idx_t idx = (n - 1) % period_len;
    return period[idx];
}
