/* Continued fraction coefficients for sqrt(919).
   a(0) = floor(sqrt(919)) = 30.
   For n ≥ 1 the terms are generated by the standard
   continued‑fraction recurrence for √919. */

#include <stdint.h>  /* for uint64_t used by the build system */

seq_t a(idx_t n)
{
    const seq_t D      = (seq_t)919;    /* D = 919 */
    const seq_t a0     = (seq_t)30;     /* a(0) = floor(√919) */

    if (n == 0)
        return a0;

    /* Initialize the recurrence variables m₀, d₀, a₀ */
    seq_t m   = 0;          /* m₀ */
    seq_t d   = 1;          /* d₀ */
    seq_t a_k = a0;         /* a₀ */

    /* Compute aₙ by iterating the recurrence n times */
    for (idx_t i = 0; i < n; ++i) {
        /* m_{k+1} = d_k * a_k - m_k */
        seq_t m_next = d * a_k - m;

        /* d_{k+1} = (D - m_{k+1}²) / d_k  */
        seq_t d_next = (D - m_next * m_next) / d;

        /* a_{k+1} = floor((a₀ + m_{k+1}) / d_{k+1}) */
        seq_t a_next = (a0 + m_next) / d_next;

        /* Advance to the next step */
        m   = m_next;
        d   = d_next;
        a_k = a_next;
    }

    return a_k;
}
