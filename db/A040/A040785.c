/*
 * A040785  Continued fraction for sqrt(814).
 * https://oeis.org/A040785
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, cofr, easy
 * Formula:   a(n) is the n-th coefficient of the continued fraction for
 *            sqrt(814)
 * Range:     u8 n <= 1, u16 n <= 88, u32 n <= 88, u64 n <= 88, u128 n <= 88,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>   /* for uint64_t if needed, but idx_t is provided by the build */

seq_t a(idx_t n)
{
    /* Continued‑fraction of sqrt(814) is generated by
       m_{k+1} = d_k · a_k − m_k
       d_{k+1} = (D − m_{k+1}²) / d_k
       a_{k+1} = ⌊(a0 + m_{k+1}) / d_{k+1}⌋
       with D = 814, a0 = 28, m0 = 0, d0 = 1. */
    const seq_t A0 = 28;
    const seq_t D  = 814;

    seq_t m = 0;
    seq_t d = 1;
    seq_t a_coeff = A0;   /* a_0 */

    if (n == 0)
        return a_coeff;

    /* Iterate until the n-th term is reached. */
    for (idx_t i = 1; i <= n; ++i)
    {
        seq_t m_next = d * a_coeff - m;
        seq_t d_next = (D - m_next * m_next) / d;
        a_coeff       = (A0 + m_next) / d_next;
        m = m_next;
        d = d_next;
    }
    return a_coeff;
}
