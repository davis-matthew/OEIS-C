/* Continued fraction terms for sqrt(873).
   a(0) = floor(sqrt(873)) = 29.
   Subsequent terms are generated by the classical continued‑fraction
   algorithm for quadratic surds.  The sequence is periodic after the
   initial term. */

#include <stdint.h>
#include <stdlib.h>

/* Integer square root of an unsigned 64‑bit number.
   Returns the largest x with x*x <= n. */
static idx_t isqrt_u64(idx_t n)
{
    idx_t low = 0;
    idx_t high = (idx_t)1ULL << 32;   /* high enough for all 64‑bit values */

    while (low < high) {
        idx_t mid = (low + high + 1) >> 1;
        if ((unsigned __int128)mid * mid <= n)
            low = mid;
        else
            high = mid - 1;
    }
    return low;
}

seq_t a(idx_t n)
{
    /* Static state for the continued‑fraction expansion */
    static idx_t   *period = NULL;    /* array of small integers        */
    static size_t   period_len = 0;    /* length of the period           */
    static idx_t    a0 = 0;            /* floor(sqrt(873))               */
    static int      init = 0;          /* one‑time initialisation flag   */

    if (!init) {
        /* ---------- initialise period ---------- */
        const idx_t D   = 873ULL;          /* the non‑square integer          */
        a0 = isqrt_u64(D);                /* 29                               */

        /* variables of the classical algorithm */
        idx_t m = 0;                /* m_0                     */
        idx_t d = 1;                /* d_0                     */
        idx_t a_val = a0;           /* a_0                     */

        /* dynamic array for the period: values are <= 2*a0 <= 58 */
        size_t cap = 8;
        period = (idx_t *)malloc(cap * sizeof(idx_t));
        if (period == NULL)            /* allocation failure → return 0 */
            return (seq_t)0;

        period_len = 0;

        while (1) {
            /* m_{k+1} = d_k * a_k - m_k */
            m = (unsigned __int128)d * a_val - m;

            /* d_{k+1} = (D - m_{k+1}²) / d_k */
            d = ((unsigned __int128)D - (unsigned __int128)m * m) / d;

            /* a_{k+1} = floor((a0 + m_{k+1}) / d_{k+1}) */
            a_val = (a0 + m) / d;

            /* store a_{k+1} */
            if (period_len >= cap) {
                cap <<= 1;
                idx_t *tmp = (idx_t *)realloc(period, cap * sizeof(idx_t));
                if (tmp == NULL) {          /* allocation failure   */
                    free(period);
                    period = NULL;
                    return (seq_t)0;
                }
                period = tmp;
            }
            period[period_len++] = a_val;

            /* period ends when a_{k+1} == 2*a0 */
            if (a_val == 2 * a0)
                break;
        }
        init = 1;
    }

    /* ---------- return requested term ---------- */
    if (n == 0)
        return (seq_t)a0;

    size_t idx = (size_t)(n - 1) % period_len;
    return (seq_t)period[idx];
}
