/* 
   Continued fraction terms for √644.
   a(0) = ⌊√644⌋ = 25.
   For n > 0 the terms are generated by the standard
   sqrt‑continued‑fraction algorithm:
       m₀ = 0,  d₀ = 1,  a₀ = 25
       m_{k+1} = d_k a_k – m_k
       d_{k+1} = (644 – m_{k+1}²) / d_k
       a_{k+1} = ⌊(a₀ + m_{k+1}) / d_{k+1}⌋
   This yields the sequence a(n) listed in the OEIS entry.
*/

seq_t a(idx_t n)
{
    /* Using idx_t for intermediate arithmetic to avoid overflow 
       on very small seq_t types.  All returned values fit in seq_t. */
    const idx_t D   = 644;         /* constant 644 */
    const idx_t a0  = 25;          /* floor(sqrt(644)) */

    if (n == (idx_t)0) return (seq_t)a0;

    idx_t m = 0;
    idx_t d = 1;
    idx_t a_val = a0;

    for (idx_t i = 1; i <= n; ++i) {
        idx_t m_next = d * a_val - m;
        idx_t d_next = (D - m_next * m_next) / d;
        idx_t a_next = (a0 + m_next) / d_next;

        m = m_next;
        d = d_next;
        a_val = a_next;
    }

    return (seq_t)a_val;
}
