/* Continued fraction terms for sqrt(964).
   a(0) = floor(sqrt(964)) = 31.
   For n >= 1 the terms are generated by the standard
   recurrence:
       m_{k+1} = d_k * a_k - m_k
       d_{k+1} = (D - m_{k+1}^2) / d_k
       a_{k+1} = floor((a0 + m_{k+1}) / d_{k+1})
   where D = 964 and a0 = floor(sqrt(D)).  This produces the
   periodic continued fraction expansion of sqrt(964).  The function
   returns the nth term (with a(0) indexed at 0).  It works for
   arbitrary access order and runs in O(n) time per call. */

#include <stddef.h>

seq_t a(idx_t n)
{
    /* Special‑case the zero‑th term. */
    if (n == 0)
        return (seq_t)31;

    /* Constants for the continued fraction calculation. */
    const seq_t D   = (seq_t)964;   /* the radicand */
    const seq_t a0  = (seq_t)31;    /* floor(sqrt(964)) */

    /* State variables of the recurrence. */
    seq_t m = (seq_t)0;
    seq_t d = (seq_t)1;
    seq_t a_k = a0;

    /* Iterate until the desired index is reached. */
    for (idx_t i = (idx_t)1; i <= n; ++i)
    {
        /* Compute the next partial quotient a_k. */
        seq_t m_next  = d * a_k - m;
        seq_t d_next  = (D - m_next * m_next) / d;
        a_k = (a0 + m_next) / d_next;

        /* Update the state for the next step. */
        m = m_next;
        d = d_next;

        /* When i == n we have a(n). */
        if (i == n)
            return a_k;
    }

    /* Control should never reach here. */
    return (seq_t)0;
}
