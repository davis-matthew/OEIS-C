/* Continued fraction expansion of √421.
   a(0) = ⌊√421⌋ = 20.
   For n ≥ 1, a(n) is generated by the standard recurrence:
       m_(k+1) = d_k·a_k – m_k
       d_(k+1) = (421 – m_(k+1)²) / d_k
       a_(k+1) = ⌊(20 + m_(k+1)) / d_(k+1)⌋
   This yields the sequence of partial quotients of the regular continued
   fraction.  The implementation relies only on integer arithmetic. */

seq_t a(idx_t n)
{
    /* constants for √421 */
    const idx_t D = 421;
    const idx_t a0 = 20;                /* floor(sqrt(421)) */
    if (n == 0)
        return (seq_t)a0;

    /* recurrence variables – all 64‑bit to avoid overflow */
    idx_t m = 0;
    idx_t d = 1;
    idx_t ak = a0;                      /* a_k for current k */

    for (idx_t k = 1; k <= n; ++k) {
        /* compute next triple (m, d, a) */
        m = d * ak - m;
        d = (D - m * m) / d;
        ak = (a0 + m) / d;              /* floor division */

        if (k == n)
            return (seq_t)ak;
    }

    /* unreachable */
    return (seq_t)0;
}
