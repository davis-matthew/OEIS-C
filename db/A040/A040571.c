/* Computation of the continued fraction coefficients of sqrt(596).
   At n = 0 the term is a0 = floor(sqrt(596)) = 24.
   For n > 0 the terms are generated by the standard recurrence for
   quadratic irrationals:
        m0 = 0,   d0 = 1,   a0 = 24
        m_{k+1} = d_k * a_k - m_k
        d_{k+1} = (596 - m_{k+1}^2) / d_k
        a_{k+1} = (24 + m_{k+1}) / d_{k+1}
   The function returns the a_n term of this sequence. */
#include <stdint.h>

seq_t a(idx_t n) {
    const seq_t a0 = (seq_t)24;
    const seq_t D  = (seq_t)596;

    if (n == 0) return a0;

    seq_t m = 0;
    seq_t d = 1;
    seq_t a_val = a0;

    for (idx_t i = 1; i <= n; ++i) {
        m = d * a_val - m;
        d = (D - m * m) / d;
        a_val = (a0 + m) / d;
    }
    return a_val;
}
