/*
 * A062084  Squarefree numbers such that every digit as well as sum of the
 *          digits is a squarefree number.
 * https://oeis.org/A062084
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 46, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A062084: squarefree numbers whose decimal digits are
   squarefree and whose digit sum is also squarefree.  No closed
   formula is known, so the sequence is generated by scanning
   successive integers and keeping those that satisfy the
   requirements.  The function a(n) returns the n‑th term
   (a(1) = 1). */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* ------------------------------------------------------------ */
/* Prime sieve to test squarefreeness of numbers and sums.      */
/* PRIMELIMIT should be at least sqrt(max_candidate).           */
#define PRIMELIMIT 100000
static uint32_t primes[PRIMELIMIT];
static size_t primes_cnt = 0;
static bool primes_ready = false;

static void init_primes(void)
{
    if (primes_ready) return;
    bool *isp = (bool *)calloc(PRIMELIMIT + 1, sizeof(bool));
    if (!isp) exit(1);
    for (int i = 2; i <= PRIMELIMIT; ++i) isp[i] = true;
    for (int p = 2; (int64_t)p * p <= PRIMELIMIT; ++p)
        if (isp[p])
            for (int m = p * p; m <= PRIMELIMIT; m += p)
                isp[m] = false;
    for (int i = 2; i <= PRIMELIMIT; ++i)
        if (isp[i]) primes[primes_cnt++] = (uint32_t)i;
    free(isp);
    primes_ready = true;
}

/* ------------------------------------------------------------ */
/* Check whether n is squarefree (for 64‑bit numbers).           */
static bool is_squarefree_uint64(uint64_t n)
{
    if (n <= 1) return true;
    for (size_t i = 0; i < primes_cnt; ++i)
    {
        uint64_t p = (uint64_t)primes[i];
        uint64_t p2 = p * p;
        if (p2 > n) break;
        if (n % p2 == 0) return false;
    }
    return true;
}

/* ------------------------------------------------------------ */
/* Allowed decimal digits: 1,2,3,5,6,7 are squarefree; 0,4,8,9 not. */
static const bool allowed_digit[10] = {
    false, /* 0 */
    true,  /* 1 */
    true,  /* 2 */
    true,  /* 3 */
    false, /* 4 */
    true,  /* 5 */
    true,  /* 6 */
    true,  /* 7 */
    false, /* 8 */
    false  /* 9 */
};

/* ------------------------------------------------------------ */
/* Check if x satisfies the OEIS definition.                    */
static bool candidate_ok(uint64_t x)
{
    uint64_t n = x;
    uint64_t sum = 0;
    while (n > 0)
    {
        int d = (int)(n % 10);
        if (!allowed_digit[d]) return false;
        sum += (uint64_t)d;
        n /= 10;
    }
    if (!is_squarefree_uint64(sum)) return false;
    return is_squarefree_uint64(x);
}

/* ------------------------------------------------------------ */
/* Storage for the sequence                                */
#define SEQ_CAP 100000
static seq_t seq[SEQ_CAP];
static size_t seq_len = 0;
static uint64_t last_checked = 0;

/* ------------------------------------------------------------ */
/* Main interface required by the judge.                       */
seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;   /* behavior below offset not required */
    init_primes();

    /* Grow the sequence until it contains the n‑th term. */
    while (seq_len < (size_t)n)
    {
        ++last_checked;
        if (candidate_ok(last_checked))
        {
            if (seq_len >= SEQ_CAP) break; /* safety guard, unlikely */
            seq[seq_len++] = (seq_t)last_checked;
        }
    }
    return seq[(size_t)n - 1];
}
