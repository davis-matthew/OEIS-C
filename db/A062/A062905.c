/*
 * A062905  Numbers k such that k and its reversal are both multiples of 15.
 * https://oeis.org/A062905
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 43, u32 n <= 43, u64 n <= 43, u128 n <= 43,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the nth term of A062905.
   A(n) is the nth non‑negative integer k such that both k
   and its decimal reversal are multiples of 15.  The sequence
   is generated by searching for numbers satisfying
   k % 15 == 0 and reverse(k) % 15 == 0, starting from 0. */

#include <stdlib.h>

/* Reverse the decimal representation of x. */
static seq_t reverse_digits(seq_t x) {
    seq_t rev = 0;
    while (x != 0) {
        seq_t d = x % 10;
        rev = rev * 10 + d;
        x = x / 10;
    }
    return rev;
}

/* Return true if num satisfies the condition. */
static int satisfies(seq_t num) {
    if (num % 15 != 0)
        return 0;
    seq_t rev = reverse_digits(num);
    return (rev % 15 == 0);
}

seq_t a(idx_t n) {
    static seq_t *cache = NULL;
    static idx_t cache_size = 0;
    static idx_t cache_cap = 0;
    static seq_t last_checked = 0;   /* last k examined */

    /* Initialize: first term is 0 */
    if (cache_size == 0) {
        cache_cap = 16;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache) return 0; /* allocation failure: unlikely for test */
        cache[0] = 0;
        cache_size = 1;
        last_checked = 0;
    }

    /* Generate terms until we have at least n terms */
    seq_t k = last_checked + 1;
    while (cache_size < n) {
        if (satisfies(k)) {
            if (cache_size >= cache_cap) {
                cache_cap *= 2;
                cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
            }
            cache[cache_size++] = k;
        }
        last_checked = k;
        k = k + 1;
    }

    return cache[n - 1];
}
