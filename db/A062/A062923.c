/*
 * A062923  Numbers k that, when expressed in base 4 and then interpreted in
 *          base 8, give a multiple of k.
 * https://oeis.org/A062923
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 16, u16 n <= 67, u32 n <= 100, u64 n <= 100,
 *            u128 n <= 100, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation: a(n) is the nth integer k such that converting the base‑4
   representation of k to base‑8 gives a multiple of k.  The first term
   a(1) is 0.  Sequence is generated by sequential search of integers. */

#include <stdlib.h>
#include <stdbool.h>

/* Helpers for dynamic array of seq_t */
static seq_t *cache = NULL;
static size_t cache_size = 0;
static size_t cache_cap = 0;

static void cache_push(seq_t val) {
    if (cache_size == cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 4;
        seq_t *new_ptr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!new_ptr) exit(1);          /* memory exhausted */
        cache = new_ptr;
        cache_cap = new_cap;
    }
    cache[cache_size++] = val;
}

static void cache_init(void) {
    if (!cache) {          /* first time: seed with the value 0 */
        cache_push((seq_t)0);
    }
}

/* Test if k satisfies the property:  interpret base‑4 digits of k in base‑8
   and check if the result is a multiple of k. */
static bool is_good(seq_t k) {
    if (k == 0) return true;
    seq_t t = k;
    seq_t f_mod = (seq_t)0;
    seq_t pow_mod = (seq_t)1;
    while (t) {
        seq_t d = t % (seq_t)4;
        f_mod = (f_mod + d * pow_mod) % k;
        pow_mod = (pow_mod * (seq_t)8) % k;
        t = t / (seq_t)4;
    }
    return f_mod == (seq_t)0;
}

seq_t a(idx_t n) {
    cache_init();
    if (n <= cache_size) return cache[n - 1];

    /* continue generating until we have at least n terms */
    static seq_t next_check = (seq_t)1;   /* next candidate after the seed 0 */

    while (cache_size < n) {
        seq_t k = next_check;
        if (is_good(k)) cache_push(k);
        ++next_check;
    }
    return cache[n - 1];
}
