/*
 * A062729  Numbers that are not divisible by any prime=p, where either p-2 or
 *          p+2 is prime.
 * https://oeis.org/A062729
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) is the n-th positive integer all of whose prime divisors p
 *            satisfy that neither p-2 nor p+2 is prime (i.e. p is not part of
 *            a twin‑prime pair)
 * Range:     u8 n <= 44, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence is generated by sieving for forbidden primes (primes with a twin)
 * and marking all multiples of those primes as bad.
 * The remaining numbers form the required sequence.
 */

#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <stddef.h>

/* -------------------------------------------------------------- */
/*  Dynamic storage for precomputed good numbers                 */
/* -------------------------------------------------------------- */

static uint64_t *good_vals   = NULL;   /* array holding good numbers   */
static size_t   good_len     = 0;      /* number of good numbers stored */
static size_t   good_cap     = 0;      /* allocated capacity of good_vals */
static size_t   sieve_limit  = 0;      /* highest sieve bound processed */

/* -------------------------------------------------------------- */
/*  Helper: Build the sequence up to at least n_needed terms   */
/* -------------------------------------------------------------- */

static void build_to_term(idx_t n_needed)
{
    if (good_len >= (size_t)n_needed) return;          /* already enough */

    /* start with a moderate bound, expand if necessary */
    size_t B = (sieve_limit == 0) ? 200000 : sieve_limit;

    while (good_len < (size_t)n_needed) {

        size_t L = B + 2;                              /* include p+2 check  */
        unsigned char *is_prime = (unsigned char *)malloc(L + 1);
        unsigned char *bad      = (unsigned char *)malloc(B + 1);

        if (!is_prime || !bad) {                      /* allocation failed */
            free(is_prime); free(bad);
            return;
        }

        /* ---------- sieve of Eratosthenes up to L ---------- */
        memset(is_prime, 1, L + 1);
        is_prime[0] = is_prime[1] = 0;
        for (size_t i = 2; i * i <= L; ++i)
            if (is_prime[i])
                for (size_t j = i * i; j <= L; j += i)
                    is_prime[j] = 0;

        /* ---------- mark numbers divisible by forbidden primes ---------- */
        memset(bad, 0, B + 1);                         /* 0 = good so far   */
        for (size_t p = 2; p <= L; ++p)
            if (is_prime[p]) {
                int twin = 0;
                if (p > 2 && p - 2 >= 2 && is_prime[p - 2]) twin = 1;
                if (p + 2 <= L && is_prime[p + 2])      twin = 1;
                if (twin) {                             /* p is forbidden   */
                    for (size_t m = p; m <= B; m += p)
                        bad[m] = 1;
                }
            }

        /* ---------- rebuild good_vals array ---------- */
        size_t new_len = 0;
        if (good_cap < B + 1) {
            size_t new_cap = B + 1;
            uint64_t *tmp = (uint64_t *)realloc(good_vals, new_cap * sizeof(uint64_t));
            if (!tmp) {                                 /* allocation failed */
                free(is_prime); free(bad);
                return;
            }
            good_vals = tmp;
            good_cap  = new_cap;
        }
        for (size_t i = 1; i <= B; ++i)
            if (!bad[i])
                good_vals[new_len++] = (uint64_t)i;

        good_len    = new_len;
        sieve_limit = B;

        free(is_prime);
        free(bad);

        if (good_len < (size_t)n_needed)           /* need more: double bound */
            B = B * 2;
        else
            break;
    }
}

/* -------------------------------------------------------------- */
/*  Public interface: a(n)                                         */
/* -------------------------------------------------------------- */

seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for n<1 but safety */
    build_to_term(n);
    return (seq_t)good_vals[n - 1];
}
