/* OEIS A317966
   a(n) = the nth nonsquare that is 1 or 2 mod 4 and cannot be written
   as prime + square (positive square).  Generated by searching
   successive integers. */
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include "../utils/floor_sqrt.h"   /* floor_sqrt(seq_t) */
#include "../utils/is_prime.h"     /* is_prime(idx_t) */

static seq_t *cache = NULL;          /* memoised terms */
static size_t cache_cap = 0;
static size_t cache_len = 0;
static idx_t checked_up_to = 4;      /* numbers < 5 are ignored */

static void append_term(seq_t val)
{
    if (cache_len == cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
        void *p = realloc(cache, new_cap * sizeof(seq_t));
        if (!p) exit(1);
        cache = (seq_t *)p;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

static void ensure_cache(idx_t n)
{
    if (cache_len >= (size_t)n) return;

    while (cache_len < (size_t)n) {
        ++checked_up_to;
        seq_t m = (seq_t)checked_up_to;

        /* Only numbers ≡ 1 or 2 (mod 4). */
        uint64_t mod4 = (uint64_t)m & 3ULL;
        if (!(mod4 == 1 || mod4 == 2)) continue;

        /* Skip perfect squares. */
        seq_t sq = floor_sqrt(m);
        if (sq * sq == m) continue;

        /* Check representability as prime + square (s ≥ 1). */
        bool representable = false;
        for (idx_t s = 1; ; ++s) {
            seq_t ss = (seq_t)s * (seq_t)s;
            if (ss > m - 2) break;          /* difference < 2, cannot be prime */
            seq_t p = m - ss;
            if (is_prime((idx_t)p)) {       /* prime check, p fits in idx_t */
                representable = true;
                break;
            }
        }

        if (!representable) append_term(m);
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;                    /* offset 1; undefined for n = 0 */
    ensure_cache(n);
    return cache[(size_t)n - 1];
}
