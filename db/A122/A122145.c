/* OEIS A122145: Numbers k such that largest prime divisor q(k) < largest
   prime power divisor M(k).  The sequence is generated by sieving
   smallest prime factors and counting terms incrementally. */

/* The code follows the constraints in the prompt. */

#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

static uint32_t *spf = NULL;      /* smallest prime factor array */
static size_t   spf_cap = 0;      /* allocated size of spf              */
static size_t   spf_limit = 3;    /* current upper bound when spf is built */

/* Build (or extend) the spf table up to 'limit' inclusively.
   The routine is incremental: it only marks the new range. */
static void ensure_spf(size_t limit)
{
    if (spf_cap > limit) return;               /* already big enough */

    size_t old_cap = spf_cap;
    size_t new_cap = limit + 1;
    uint32_t *new_spf = (uint32_t *)realloc(spf, new_cap * sizeof(uint32_t));
    if (!new_spf) abort();
    spf = new_spf;
    memset(spf + old_cap, 0, (new_cap - old_cap) * sizeof(uint32_t));
    spf_cap = new_cap;

    /* Mark composites in the new range using all primes up to sqrt(limit) */
    uint32_t sqrt_lim = (uint32_t)0;
    for (uint32_t p = 2; (uint64_t)p * p <= limit; ++p) { /* simple sqrt loop */
        if (spf[p] == p) {                     /* p is prime */
            uint64_t start = (uint64_t)p * (uint64_t)p;
            if (start < old_cap) {
                start = ((old_cap + p - 1) / p) * p;
            }
            for (uint64_t j = start; j <= limit; j += p) {
                if (spf[j] == 0) spf[j] = p;
            }
        }
    }

    /* Any position still zero is a prime; set spf[i] = i. */
    for (size_t i = old_cap; i < spf_cap; ++i) {
        if (spf[i] == 0) spf[i] = (uint32_t)i;
    }
}

/* Check whether k satisfies q(k) < M(k). */
static bool satisfies(uint64_t k)
{
    if (k < 4) return false;            /* sequence begins at 4 */

    uint64_t n = k;
    uint32_t largest_prime = 0;
    uint64_t max_prime_power = 0;

    while (n > 1) {
        uint32_t p = spf[n];
        if (p == 0) p = (uint32_t)n;    /* prime larger than current spf_cap */

        uint32_t exp = 0;
        while (n % p == 0) {
            n /= p;
            ++exp;
        }

        if (p > largest_prime) largest_prime = p;

        uint64_t power = 1;
        for (uint32_t t = 0; t < exp; ++t) power *= p;

        if (power > max_prime_power) max_prime_power = power;
    }

    return max_prime_power > largest_prime;
}

/* Cache of found terms.  cache[i] = a(i+1). */
static uint64_t *cache = NULL;
static size_t   cache_len = 0;          /* number of elements in cache     */
static size_t   cache_cap = 0;          /* allocated capacity              */
static size_t   last_tested = 0;        /* largest integer tested so far */

static void cache_add(uint64_t value)
{
    if (cache_len >= cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 16 : cache_cap * 2;
        uint64_t *new_cache = (uint64_t *)realloc(cache, new_cap * sizeof(uint64_t));
        if (!new_cache) abort();
        cache = new_cache;
        cache_cap = new_cap;
    }
    cache[cache_len++] = value;
}

/* Main sequence function. */
seq_t a(idx_t n)
{
    if (n < 1) return (seq_t)0;          /* undefined for n == 0 */

    /* Pre‑build spf up to current spf_limit if needed. */
    if (spf_limit > 1) ensure_spf(spf_limit);

    /* Generate terms until we have at least n of them. */
    while (cache_len < (size_t)n) {
        size_t k = last_tested + 1;

        /* If we are about to test beyond the current spf coverage,
           extend the spf limit by a factor of two (capped at k). */
        if (k > spf_limit) {
            spf_limit = (spf_limit == 0) ? 4 : spf_limit * 2;
            if (spf_limit < k) spf_limit = k;
            ensure_spf(spf_limit);
        }

        if (satisfies((uint64_t)k))
            cache_add((uint64_t)k);

        ++last_tested;
    }

    return (seq_t)cache[n - 1];
}
