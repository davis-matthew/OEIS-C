/*
 * A107273  Vertically symmetrical dates MMDDYYYY (American notation)
 *          excluding years which are divisible by 10, considered as numbers,
 *          in increasing order.
 * https://oeis.org/A107273
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, fini, full, nonn
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 42, u64 n <= 42, u128 n <= 42,
 *            big any n
 * Helpers:   is_vert_sym
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Vectorially symmetric dates (A107273)
   a(n) is the n‑th 8‑digit integer MMDDYYYY (American notation) that
   is vertically symmetrical on a calculator display, while the year
   is not a multiple of 10.  The sequence is generated by enumerating
   all dates, testing the symmetry rule, storing the results in
   increasing order, and returning the n‑th term (1‑based).  Values
   beyond the known 42 terms return 0. */
#include <stdio.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>
#include "../utils/is_vert_sym.h"

/* Return the number of days in the given month of the given year. */
static int days_in_month(uint32_t year, int month)
{
    static const int dim[12] = {31,28,31,30,31,30,31,31,30,31,30,31};
    int d = dim[month-1];
    if (month == 2) {
        if ((year % 400 == 0) || (year % 4 == 0 && year % 100 != 0))
            d = 29;
    }
    return d;
}

/* Sequence a(n) for n >= 1. */
seq_t a(idx_t n)
{
    static seq_t *arr = NULL;
    static size_t cap = 0, sz = 0;
    static bool ready = false;

    if (!ready) {
        cap = 128;
        arr = (seq_t *)malloc(cap * sizeof(seq_t));
        if (!arr) return (seq_t)0;  /* allocation failure – unlikely in tests */

        for (int month = 1; month <= 12; ++month) {
            for (int day = 1; day <= 31; ++day) {
                if (day > days_in_month(1, month)) /* will adjust year below */
                    continue;
                for (uint32_t year = 1; year <= 9999; ++year) {
                    if (year % 10 == 0)
                        continue;                /* skip years divisible by 10 */
                    if (day > days_in_month(year, month))
                        continue;

                    char s[9];
                    snprintf(s, sizeof s, "%02u%02u%04u", month, day, year);
                    if (!is_vert_sym(s))
                        continue;

                    seq_t val = (seq_t)month * (seq_t)1000000u
                              + (seq_t)day   * (seq_t)10000u
                              + (seq_t)year;
                    if (sz == cap) {
                        cap *= 2;
                        arr = (seq_t *)realloc(arr, cap * sizeof(seq_t));
                        if (!arr) return (seq_t)0;  /* allocation failure */
                    }
                    arr[sz++] = val;
                }
            }
        }
        ready = true;
    }

    if (n == 0 || n > sz)
        return (seq_t)0;            /* undefined for out‑of‑range indices */
    return arr[n-1];
}
