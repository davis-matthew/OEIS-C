/* Sequence: A107184 – primes of the form x^2 + 75*y^2.
   The values are generated by enumerating (x, y) pairs up to a
   dynamically increasing bound and keeping the distinct prime values
   in ascending order.  The algorithm is a simple brute‑force search
   with pruning; it performs well for n ≤ 10 000. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include <math.h>
#include "../utils/is_prime.h"   /* provides bool is_prime(uint64_t) */

/* comparison helper for qsort */
static int compare_seq(const void *a, const void *b)
{
    seq_t left  = *(const seq_t *)a;
    seq_t right = *(const seq_t *)b;
    if (left < right)  return -1;
    if (left > right)  return  1;
    return 0;
}

seq_t a(idx_t n)
{
    /* static state */
    static seq_t *primes = NULL;
    static size_t primes_cnt = 0, primes_cap = 0;
    static uint64_t limit = 1000ULL;   /* starting bound for searching */

    if (n == 0) return 0;           /* offset 1 – undefined below 1 */

    /* initialise allocation once */
    if (primes == NULL) {
        primes_cap = 8;
        primes = (seq_t*)malloc(primes_cap * sizeof(seq_t));
    }

    /* loop until we have at least n primes */
    while (primes_cnt < (size_t)n) {
        /* increase search bound */
        limit *= 2ULL;

        /* upper bound for y */
        uint64_t maxY = (uint64_t)(sqrt((long double)limit / 75.0L));

        for (uint64_t y = 1; y <= maxY; ++y) {
            __int128 y2_128 = (__int128)75 * y * y;
            if (y2_128 > limit) break;
            uint64_t y2 = (uint64_t)y2_128;

            uint64_t rem = limit - y2;
            uint64_t maxX = (uint64_t)(sqrt((long double)rem));

            for (uint64_t x = 1; x <= maxX; ++x) {
                __int128 val_128 = (__int128)x * x + y2;
                if (val_128 > limit) break;
                uint64_t val = (uint64_t)val_128;
                if (is_prime(val)) {
                    /* grow array if needed */
                    if (primes_cnt >= primes_cap) {
                        size_t new_cap = primes_cap * 2;
                        seq_t *tmp = (seq_t*)realloc(primes, new_cap * sizeof(seq_t));
                        if (!tmp) {      /* malloc failed – abort */
                            free(primes);
                            primes = NULL;
                            primes_cnt = primes_cap = 0;
                            return 0;
                        }
                        primes = tmp;
                        primes_cap = new_cap;
                    }
                    primes[primes_cnt++] = (seq_t)val;
                }
            }
        }

        /* sort and deduplicate the collected primes */
        if (primes_cnt > 1) {
            qsort(primes, primes_cnt, sizeof(seq_t), compare_seq);
        }
        size_t uniq = 0;
        for (size_t i = 0; i < primes_cnt; ++i) {
            if (uniq == 0 || primes[i] != primes[uniq-1]) {
                primes[uniq++] = primes[i];
            }
        }
        primes_cnt = uniq;
    }

    return primes[n-1];
}
