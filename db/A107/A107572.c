/* Sequence A107572: list of all side lengths a,b,c of scalene integer
   triangles sorted by increasing perimeter, then lexicographically by
   (a,b,c). The sequence is obtained by flattening each triple in the
   order a,b,c.
   No closed formula; the sequence is generated by enumerating triangles. */

#include <stdint.h>

seq_t a(idx_t n)
{
    if (n < 1) return 0;            /* undefined for n < 1, but protect anyway */
    idx_t count = 0;                 /* number of side values emitted so far */

    for (idx_t p = 9; ; ++p) {       /* smallest perimeter of a scalene triangle is 9 (2,3,4) */
        for (idx_t a_side = 1; a_side <= p / 3; ++a_side) {
            for (idx_t b_side = a_side + 1; ; ++b_side) {
                idx_t c_side = p - a_side - b_side;
                if (b_side >= c_side) break;   /* ensures a<b<c */
                if (a_side + b_side > c_side) { /* triangle inequality */
                    /* emit a_side */
                    ++count;
                    if (count == n) return (seq_t)a_side;
                    /* emit b_side */
                    ++count;
                    if (count == n) return (seq_t)b_side;
                    /* emit c_side */
                    ++count;
                    if (count == n) return (seq_t)c_side;
                }
            }
        }
    }
    /* unreachable */
    return 0;
}
