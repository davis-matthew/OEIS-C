/*
 * A052015  Primes with distinct digits in ascending order.
 * https://oeis.org/A052015
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, fini, full, easy
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 34, u32 n <= 100, u64 n <= 100, u128 n <= 100,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Formula: a(n) = the n-th prime number whose decimal
 * digits are in strictly increasing order.
 * The sequence is empty for n = 0 or n larger than the
 * number of such primes (there are 100 of them).
 */
#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>

/* Test primality of an unsigned 64‑bit integer.  All numbers
   generated by this sequence fit in 64 bits, so a simple
   trial‑division test is fast enough. */
static bool is_prime_uint64(uint64_t n)
{
    if (n < 2)              return false;
    if (n % 2 == 0)         return n == 2;
    for (uint64_t d = 3; d * d <= n; d += 2)
        if (n % d == 0)     return false;
    return true;
}

/* Return the n-th element of the A052015 sequence. */
seq_t a(idx_t n)
{
    /* Pre‑computed table of primes with ascending digits.
       Stored in static arrays so that repeated calls share the work. */
    static seq_t primes[511];
    static size_t prime_count = 0;
    static bool initialized = false;

    if (!initialized) {
        /* Generate all numbers with strictly increasing digits 1‑9.
           Represent a choice of digits by a 9‑bit mask.  Bit k (0‑based)
           corresponds to digit k+1.  The mask 0 is skipped. */
        for (uint32_t mask = 1; mask < (1u << 9); ++mask) {
            uint64_t val = 0;
            for (int d = 1; d <= 9; ++d) {
                if (mask & (1u << (d - 1)))
                    val = val * 10 + (uint64_t)d;
            }
            if (is_prime_uint64(val)) {
                /* The target type seq_t is guaranteed to hold the value
                   (the test suite uses a type large enough for the
                   100 “real” terms). */
                primes[prime_count++] = (seq_t)val;
            }
        }

        /* The resulting primes are not guaranteed to be in sorted order
           because the masks are processed in bit‑pattern order, not
           numeric order.  Sort them once here.  A simple insertion sort
           is adequate for the at most 511 entries. */
        for (size_t i = 1; i < prime_count; ++i) {
            seq_t key = primes[i];
            size_t j = i;
            while (j > 0 && primes[j - 1] > key) {
                primes[j] = primes[j - 1];
                --j;
            }
            primes[j] = key;
        }

        initialized = true;
    }

    if (n == 0 || (size_t)(n - 1) >= prime_count)
        return 0;
    return primes[n - 1];
}
