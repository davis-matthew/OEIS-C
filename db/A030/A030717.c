/*
 * A030717  The first list after the following procedure: starting with a list
 *          [1] and an empty list, repeatedly add the distinct values already
 *          in the first list in ascending order to the second list and add
 *          the corresponding frequencies of those values to the first list.
 * https://oeis.org/A030717
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf, nice
 * Formula:   not stated
 * Range:     u8 n <= 579, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Recurrence: a(1)=1.  For n>1, the sequence is generated by repeatedly
 * applying the rule:
 *   Let L1 be the first list (initially [1]) and L2 the second list (empty).
 *   At each stage:
 *     1. Append to L2 all distinct values of L1, in ascending order.
 *     2. Append to L1 the frequencies of those distinct values.
 *   The sequence a(n) is the nth term of the first list L1. */
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <stddef.h>

/* Simple open-addressing hash table mapping a seq_t value to its frequency */
typedef struct {
    seq_t *keys;      /* keys (0 means empty slot; 0 never occurs in L1) */
    seq_t *counts;    /* frequency counts of keys */
    size_t cap;       /* table capacity (power of two) */
    size_t mask;      /* cap - 1, for hash indexing */
    size_t size;      /* number of occupied entries */
} Map;

/* Hash: use lower 64 bits of the value (works for builtin types). */
static inline uint64_t hash_seq_t(seq_t x)
{
    return (uint64_t)x;
}

/* Initialise map with a reasonable capacity */
static void map_init(Map *m)
{
    m->cap   = 1 << 15;  /* 32768 slots – more than enough for n ≤ 10⁴ */
    m->mask  = m->cap - 1;
    m->size  = 0;
    m->keys  = (seq_t*)calloc(m->cap, sizeof(seq_t));
    m->counts = (seq_t*)calloc(m->cap, sizeof(seq_t));
}

/* Double table size when more than half full */
static void map_rehash(Map *m, size_t new_cap)
{
    seq_t *new_keys   = (seq_t*)calloc(new_cap, sizeof(seq_t));
    seq_t *new_counts = (seq_t*)calloc(new_cap, sizeof(seq_t));
    size_t new_mask   = new_cap - 1;

    for (size_t i = 0; i < m->cap; ++i) {
        if (m->keys[i] != 0) {
            uint64_t h = hash_seq_t(m->keys[i]) & new_mask;
            while (new_keys[h] != 0) h = (h + 1) & new_mask;
            new_keys[h]   = m->keys[i];
            new_counts[h] = m->counts[i];
        }
    }
    free(m->keys);
    free(m->counts);
    m->keys   = new_keys;
    m->counts = new_counts;
    m->cap    = new_cap;
    m->mask   = new_mask;
}

static void map_ensure(Map *m)
{
    if (m->size > m->cap / 2) {
        map_rehash(m, m->cap << 1);
    }
}

static void map_increment(Map *m, seq_t key)
{
    uint64_t h = hash_seq_t(key) & m->mask;
    while (m->keys[h] != 0) {
        if (m->keys[h] == key) {
            m->counts[h] += 1;
            return;
        }
        h = (h + 1) & m->mask;
    }
    /* new entry */
    m->keys[h]   = key;
    m->counts[h] = 1;
    m->size++;
    map_ensure(m);
}

/* Temporary struct for sorting distinct values */
typedef struct { seq_t key; seq_t count; } KV;

static int cmp_KV(const void *a, const void *b)
{
    const KV *x = (const KV*)a;
    const KV *y = (const KV*)b;
    return (x->key < y->key) ? -1 : (x->key > y->key);
}

/* Return the nth term of A030717 */
seq_t a(idx_t n)
{
    static bool     init_done = false;
    static seq_t   *list      = NULL;   /* the first list (L1) */
    static size_t   list_len  = 0;      /* current length of list */
    static size_t   list_cap  = 0;      /* capacity of list array      */
    static Map      map;               /* value → frequency in L1     */
    static KV      *kv_buf  = NULL;    /* buffer for distinct keys    */
    static size_t   kv_cap  = 0;        /* capacity of kv_buf          */

    if (!init_done) {
        list_cap  = 128;
        list      = (seq_t*)calloc(list_cap, sizeof(seq_t));
        list[0]   = (seq_t)1;            /* first term is 1 */
        list_len  = 1;

        map_init(&map);
        map_increment(&map, (seq_t)1);    /* initial frequency of 1 */

        kv_cap = 1024;
        kv_buf = (KV*)calloc(kv_cap, sizeof(KV));

        init_done = true;
    }

    /* Expand the first list until it contains at least n terms. */
    while (list_len < (size_t)n) {
        /* Ensure temporary buffer is large enough for all distinct keys. */
        if (map.size > kv_cap) {
            kv_cap = map.size * 2;
            kv_buf = (KV*)realloc(kv_buf, kv_cap * sizeof(KV));
        }

        /* Build snapshot of distinct values in L1. */
        size_t kv_len = 0;
        for (size_t i = 0; i < map.cap; ++i) {
            if (map.keys[i] != 0) {
                kv_buf[kv_len].key   = map.keys[i];
                kv_buf[kv_len].count = map.counts[i];
                ++kv_len;
            }
        }

        /* Sort by key ascending. */
        qsort(kv_buf, kv_len, sizeof(KV), cmp_KV);

        /* Ensure list buffer has enough space for the new terms. */
        if (list_len + kv_len > list_cap) {
            size_t new_cap = list_cap;
            while (new_cap < list_len + kv_len) new_cap <<= 1;
            list = (seq_t*)realloc(list, new_cap * sizeof(seq_t));
            list_cap = new_cap;
        }

        /* Append frequencies to the first list and update map. */
        for (size_t i = 0; i < kv_len; ++i) {
            /* Add the frequency to the list. */
            list[list_len++] = kv_buf[i].count;
            /* Increase the count of that frequency value in the map. */
            map_increment(&map, kv_buf[i].count);
        }
    }

    return list[n - 1];
}
