/*
 * A039277  Numbers whose base-4 representation has the same nonzero number of
 *          0's and 1's.
 * https://oeis.org/A039277
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 48, u16 n <= 56, u32 n <= 56, u64 n <= 56, u128 n <= 56,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A039277: numbers whose base‑4 representation has the same
   nonzero number of 0's and 1's.  The values are generated by searching
   successive integers and keeping those that satisfy the condition.
   No known closed‑form formula is available. */
#include <stdlib.h>
#include <stdbool.h>

static bool qualifies(idx_t x)
{
    unsigned zero = 0;
    unsigned one  = 0;
    idx_t t = x;
    if (t == 0) return false;
    while (t > 0)
    {
        unsigned d = t & 3;          /* t % 4, faster using bitwise mask */
        if (d == 0) zero++;
        else if (d == 1) one++;
        t >>= 2;                     /* t / 4 */
    }
    return (zero == one) && (zero > 0);
}

seq_t a(idx_t n)
{
    /* Handle invalid or zero indexes: behaviour undefined by OEIS spec,
       but we return 0 to avoid crashes. */
    if (n == 0) return (seq_t)0;

    static seq_t *cache = NULL;
    static size_t cache_cap = 0;
    static idx_t next_candidate = 1;
    static idx_t found_count = 0;

    while (found_count < n)
    {
        /* Find next qualifying number */
        while (!qualifies(next_candidate))
            next_candidate++;

        /* Grow cache if necessary */
        if (found_count >= cache_cap)
        {
            size_t new_cap = cache_cap ? cache_cap * 2 : 8;
            seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
            if (!tmp) abort();  /* stop silently on allocation error */
            cache = tmp;
            cache_cap = new_cap;
        }

        cache[found_count] = (seq_t)next_candidate;
        found_count++;
        next_candidate++;
    }

    return cache[n - 1];
}
