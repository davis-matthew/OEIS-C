/*
 * A039099  Numbers whose base-9 representation has the same number of 3's and
 *          6's.
 * https://oeis.org/A039099
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 154, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implements A039099: numbers whose base‑9 representation has the same
   number of 3's and 6's.  The values are generated by brute‑forcing
   successive integers and caching those that satisfy the condition. */
#include <stdlib.h>
#include <stdbool.h>

/* static storage for the sequence cache */
static seq_t *cache = NULL;      /* array of found terms */
static size_t   cache_cap = 0;   /* allocated capacity */
static size_t   cache_size = 0;  /* number of cached terms */
static idx_t    tested  = 0;     /* next integer to test          */

/* check whether a given value has equal counts of 3 and 6 in base 9 */
static bool good(seq_t v)
{
    unsigned c3 = 0, c6 = 0;
    seq_t x = v;
    /* base‑9 digit extraction */
    while (x > 0)
    {
        unsigned d = (unsigned)(x % 9);
        if (d == 3)   ++c3;
        else if (d == 6) ++c6;
        x /= 9;
    }
    /* for v == 0 the loop is skipped, so counts are 0, which agrees */
    return c3 == c6;
}

/* ensure the cache can hold at least new_cap elements */
static void ensure_cache_cap(size_t new_cap)
{
    if (new_cap <= cache_cap) return;
    size_t cap = (cache_cap) ? cache_cap * 2 : 8;
    if (cap < new_cap) cap = new_cap;
    seq_t *p = (seq_t*)realloc(cache, cap * sizeof(seq_t));
    if (!p) abort();          /* out of memory */
    cache = p;
    cache_cap = cap;
}

/* public sequence function */
seq_t a(idx_t n)
{
    /*  n is 1‑based, so we need at least n cached terms */
    while (cache_size < (size_t)n) {
        seq_t val = (seq_t)tested;
        if (good(val)) {
            ensure_cache_cap(cache_size + 1);
            cache[cache_size++] = val;
        }
        ++tested;
    }
    return cache[n - 1];
}
