/* Computes a(n): the n-th number whose base‑7 representation contains
   the same number of 1’s and 6’s. The sequence is generated by scanning
   integers in increasing order and counting the relevant digits. */

#include <stdbool.h>

/* Return true if x has the same number of 1's and 6's in base 7. */
static bool balanced_base7(seq_t x)
{
    unsigned count1 = 0, count6 = 0;
    seq_t t = x;

    while (t > (seq_t)0) {
        unsigned digit = (unsigned)(t % (seq_t)7);
        if (digit == 1)       count1++;
        else if (digit == 6)  count6++;
        t /= (seq_t)7;
    }
    return count1 == count6;
}

/* OEIS A039039 */
seq_t a(idx_t n)
{
    idx_t found = 0;
    seq_t curr  = (seq_t)0;

    while (1) {
        if (balanced_base7(curr)) {
            found++;
            if (found == n) return curr;
        }
        curr++;
    }
}
