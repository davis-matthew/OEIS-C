/*
 * A039438  Numbers whose base-11 representation has the same nonzero number
 *          of 0's and 1's.
 * https://oeis.org/A039438
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 47, u32 n <= 47, u64 n <= 47, u128 n <= 47,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation: generate numbers in base 11 whose representation has an equal,
   non‑zero count of 0 digits and 1 digits.  Numbers are generated by
   recursive enumeration of the base‑11 digits and collected in ascending
   order.  The function a() returns the n-th term of the sequence. */

#include <stdlib.h>
#include <stddef.h>

static seq_t *seq_cache   = 0;   /* cache of computed terms           */
static size_t cache_len   = 0;   /* number of cached terms            */
static size_t cache_cap   = 0;   /* capacity of cache                 */
static idx_t  next_gen_len = 2;  /* next base‑11 length to generate   */

static void push_back(seq_t val) {
    if (cache_len >= cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 64 : cache_cap * 2;
        seq_t *p = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
        seq_cache = p;
        cache_cap = new_cap;
    }
    seq_cache[cache_len++] = val;
}

/* Recursive enumeration of length‑L base‑11 numbers. */
static void rec_gen(idx_t L, idx_t pos, seq_t current, idx_t zeros, idx_t ones) {
    if (pos == L) {
        if (zeros == ones && zeros > 0)
            push_back(current);
        return;
    }
    int start = (pos == 0) ? 1 : 0;
    for (int d = start; d <= 10; ++d) {
        rec_gen(L, pos + 1, current * 11 + d, zeros + (d == 0), ones + (d == 1));
    }
}

static void generate_length(idx_t L) {
    rec_gen(L, 0, 0, 0, 0);
}

/* Comparator for qsort. Works for both built‑in integer types and
   arbitrary‑precision integer types that provide operator<. */
static int seq_compare(const void *a, const void *b) {
    const seq_t *pa = (const seq_t *)a;
    const seq_t *pb = (const seq_t *)b;
    if (*pa < *pb) return -1;
    if (*pa > *pb) return 1;
    return 0;
}

/* Return the n-th term (1‑based). */
seq_t a(idx_t n) {
    if (n == 0) return 0;                    /* undefined for n = 0 */

    while (cache_len < n) {
        size_t old_len = cache_len;          /* position where new terms start */
        generate_length(next_gen_len);
        /* The newly added segment is already all larger than previous
           terms (because it has longer base‑11 representation), so only
           the new segment needs sorting. */
        qsort(&seq_cache[old_len], cache_len - old_len,
              sizeof(seq_t), seq_compare);
        next_gen_len++;
    }
    return seq_cache[n - 1];
}
