/* Recurrence: a(0)=2; for n≥1 a(n) equals the nth term of the Fibonacci word,
   i.e. the infinite word generated by 0→01, 1→0 starting with 0.  The chain
   a(1)=1, a(2)=0, a(3)=0, a(4)=1, … is obtained from this morphism. */

#include <stdlib.h>   /* malloc, free */

static seq_t *f = NULL;          /* current Fibonacci word list (index 0…f_len-1) */
static idx_t f_len = 0;          /* length of the list */

seq_t a(idx_t n) {
    /* Special case: first term is 2, not part of the Fibonacci word. */
    if (n == 0) return (seq_t)2;

    /* Initialise the word list on the first call. */
    if (f == NULL) {
        f = (seq_t*)malloc(sizeof(seq_t));
        if (f == NULL) exit(EXIT_FAILURE);
        f[0] = (seq_t)0;   /* first term of the standard Fibonacci word */
        f_len = 1;
    }

    /* If we already have enough terms, return the cached value. */
    if (n < f_len) return f[n];

    /* Expand the word list until it contains the requested index. */
    while (f_len <= n) {
        /* Count zeros in the current word to determine the next length. */
        idx_t zeros = 0;
        for (idx_t i = 0; i < f_len; ++i)
            if (f[i] == (seq_t)0) ++zeros;

        idx_t next_len = f_len + zeros;          /* each 0 expands to 01 (add 1) */
        seq_t *next = (seq_t*)malloc(next_len * sizeof(seq_t));
        if (next == NULL) exit(EXIT_FAILURE);

        /* Apply the morphism 0→01, 1→0. */
        idx_t pos = 0;
        for (idx_t i = 0; i < f_len; ++i) {
            if (f[i] == (seq_t)0) {
                next[pos++] = (seq_t)0;
                next[pos++] = (seq_t)1;
            } else { /* f[i] == 1 */
                next[pos++] = (seq_t)0;
            }
        }

        /* Replace the old word with the new one. */
        free(f);
        f = next;
        f_len = next_len;
    }

    return f[n];
}
