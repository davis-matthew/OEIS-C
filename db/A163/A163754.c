/*
 * A163754  Exactly two distinct primes occur as substrings of the digits of
 *          n.
 * https://oeis.org/A163754
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 59, u16 n <= 9999, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   digit_len, ensure_capacity, is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   a(n) = the n-th natural number that has exactly two distinct primes
   occurring as decimal substrings of its digits.
   The implementation performs a linear search supplemented by a
   memoisation cache.  Substrings are generated by extracting the
   decimal digits from most‑significant to least‑significant, then
   iterating over all continuous ranges.  A prime test is applied to
   each constructed value; exactly two distinct primes are required.
*/

#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>
#include "../utils/digit_len.h"
#include "../utils/ensure_capacity.h"
#include "../utils/is_prime_big.h"

static bool has_exactly_two_prime_substrings(seq_t num)
{
    size_t len = digit_len(num);
    if (len == 0) return false;

    static uint8_t *buf = NULL;
    static size_t buf_cap = 0;
    if (buf_cap < len) {
        free(buf);
        buf = (uint8_t *)malloc(len);
        buf_cap = len;
    }

    /* extract digits (least‑significant first) */
    seq_t tmp = num;
    for (size_t i = 0; i < len; ++i) {
        buf[i] = (uint8_t)(tmp % 10);
        tmp /= 10;
    }
    /* reverse to most‑significant first */
    for (size_t i = 0; i < len / 2; ++i) {
        uint8_t t = buf[i];
        buf[i] = buf[len - 1 - i];
        buf[len - 1 - i] = t;
    }

    bool first = false, second = false;
    seq_t p1 = 0, p2 = 0;   /* store distinct primes */

    for (size_t i = 0; i < len; ++i) {
        seq_t val = 0;
        for (size_t j = i; j < len; ++j) {
            val = val * 10 + (seq_t)buf[j];
            if (is_prime_big(val)) {
                if (!first) {
                    first = true;
                    p1 = val;
                } else if (p1 != val) {
                    if (!second) {
                        second = true;
                        p2 = val;
                    } else if (p2 != val) {
                        return false;  /* third distinct prime */
                    }
                }
            }
        }
    }
    return first && second;
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined, defensive */

    static seq_t *terms = NULL;
    static size_t terms_cap = 0;
    static idx_t terms_cnt = 0;
    static idx_t search_start = 1;

    while (terms_cnt < n) {
        idx_t cand_idx = search_start;
        while (true) {
            seq_t cand = (seq_t)cand_idx;
            if (has_exactly_two_prime_substrings(cand)) {
                ensure_capacity(terms_cnt + 1, &terms_cap, (void **)&terms, sizeof(seq_t));
                terms[terms_cnt++] = cand;
                search_start = cand_idx + 1;
                break;
            }
            ++cand_idx;
        }
    }
    return terms[n - 1];
}
