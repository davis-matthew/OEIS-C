/* Sequence A265693: squarefree composites with at least one prime factor greater
   than sqrt(n).  Generated by scanning successive integers, testing
   square‑freeness, compositeness, and the inequality
   (n / max_prime) < max_prime. */
#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/factor_u64.h"
#include "../utils/is_squarefree.h"

seq_t a(idx_t n) {
    /* static workspace for memoisation */
    static seq_t *seq = NULL;
    static size_t size = 0, cap = 0;
    static idx_t nxt = 6;                 /* next integer to test (>=6) */

    if (n == (idx_t)0) {                  /* offset is 1; behaviour below ignored */
        return (seq_t)0;
    }

    while (size < n) {
        uint64_t num = (uint64_t)nxt;      /* current integer to test */
        seq_t cand = (seq_t)num;

        /* factorise num */
        uint64_t prime[16], expo[16];
        size_t pcnt;
        factor_u64(num, prime, expo, &pcnt);

        /* must be a composite square‑free number */
        if (pcnt >= 2) {
            bool squarefree = true;
            for (size_t i = 0; i < pcnt; ++i) {
                if (expo[i] != 1) { squarefree = false; break; }
            }
            if (squarefree) {
                uint64_t maxp = prime[pcnt - 1];   /* primes come in ascending order */
                uint64_t m = num / maxp;          /* cofactor = n / maxp */
                if (m < maxp) {                    /* maxp > sqrt(n)  */
                    /* store this term */
                    if (size == cap) {
                        size_t newcap = (cap == 0) ? 16 : cap << 1;
                        seq = (seq_t *)realloc(seq, newcap * sizeof(seq_t));
                        cap = newcap;
                    }
                    seq[size++] = cand;
                }
            }
        }
        ++nxt;
    }
    return seq[n - 1];
}
