/*********************************************************************
 *  OEIS sequence A168855: Number of reduced words of length n in the
 *  Coxeter group generated by 34 involutions with all pairwise
 *  relations (S_iS_j)^20=I.
 *
 *  Generating function:  P(t)/Q(t) with
 *      P(t) = t^20 + 2 t^19 + … + 2 t + 1
 *      Q(t) = 528 t^20 - 32 t^19 - … - 32 t + 1
 *  The sequence satisfies the recurrence
 *
 *      a(0) = 1
 *      for 0 < n < 20:      a(n) = 2 + 32 * Σ_{k=0}^{n-1} a(k)
 *      for n ≥ 20:          a(n) = (n==20?1:0) + 32 * Σ_{k=1}^{19} a(n-k)
 *                                       - 528 * a(n-20)
 *
 *  The implementation below follows this recurrence exactly.
 *********************************************************************/

#include <stdlib.h>
#include "../utils/p_coef.h"

seq_t a(idx_t n)
{
    /* Handle the trivial case immediately. */
    if (n == 0) return (seq_t)1;

    /* Allocate array for a[0..n] */
    seq_t *a = (seq_t*)malloc((size_t)(n + 1) * sizeof(seq_t));
    if (!a) return (seq_t)0;          /* graceful failure */

    a[0] = (seq_t)1;

    /* 0 < n < 20 part */
    if (n < 20) {
        seq_t sum_prev = a[0];        /* Σ_{k=0}^{i-1} a(k)  */
        for (idx_t i = 1; i <= n; ++i) {
            seq_t val = p_coef(i) + (seq_t)32 * sum_prev;
            a[i] = val;
            sum_prev += val;
        }
        seq_t result = a[n];
        free(a);
        return result;
    }

    /* Compute terms a[1]..a[19] */
    seq_t sum_prev = a[0];
    for (idx_t i = 1; i <= 19; ++i) {
        seq_t val = (seq_t)2 + (seq_t)32 * sum_prev;
        a[i] = val;
        sum_prev += val;
    }

    /*  n ≥ 20 part */
    for (idx_t i = 20; i <= n; ++i) {
        seq_t sum19 = (seq_t)0;
        for (int k = 1; k <= 19; ++k)
            sum19 += a[i - k];

        seq_t val = p_coef(i) + (seq_t)32 * sum19;
        val -= (seq_t)528 * a[i - 20];
        a[i] = val;
    }

    seq_t result = a[n];
    free(a);
    return result;
}
