/*  OEIS sequence A168053
    Generated by recurrent relation derived from
    (1-2*x^2-3*x^3)/((1-x)^2*(1+x+x^2))
    Denominator simplifies to 1 - x - x^3 + x^4.
    Hence coefficients satisfy for n>=4:
        a(n) = a(n-1) + a(n-3) - a(n-4)
    Base values:
        a(0)=1, a(1)=1, a(2)=-1, a(3)=-3
*/

#include <stdlib.h>

seq_t a(idx_t n)
{
    /* static cache of already computed terms */
    static seq_t *cache = NULL;
    static size_t cache_len = 0;

    /* initialise base cases once */
    if (cache_len == 0) {
        cache = (seq_t *)malloc(4 * sizeof(seq_t));
        if (!cache) abort();          /* memory failure – unlikely in tests */
        cache[0] =  (seq_t)1;
        cache[1] =  (seq_t)1;
        cache[2] = -(seq_t)1;
        cache[3] = -(seq_t)3;
        cache_len = 4;
    }

    /* extend cache if requested index is beyond current length */
    size_t need = (size_t)n + 1;
    if (need > cache_len) {
        seq_t *new_buf = (seq_t *)realloc(cache, need * sizeof(seq_t));
        if (!new_buf) abort();        /* memory failure */
        cache = new_buf;

        /* compute missing terms using the recurrence */
        for (size_t i = cache_len; i < need; ++i) {
            cache[i] = cache[i-1] + cache[i-3] - cache[i-4];
        }
        cache_len = need;
    }

    return cache[(size_t)n];
}
