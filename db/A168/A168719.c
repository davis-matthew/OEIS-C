/*  OEIS A168719 – number of reduced words of length n in the
    Coxeter group generated by 42 involutions with all braid
    relations of order 17.
    The generating function is

          t^17 + 2t^16 + 2t^15 + … + 2t^1 + 1
    G(t) = ------------------------------------
          820t^17 − 40t^16 − 40t^15 − … − 40t^1 + 1

    From this rational function the coefficients a(n) satisfy
    the linear recurrence

          a(n) = 40⋅(a(n−1)+…+a(n−16)) − 820⋅a(n−17)   for n ≥ 18

    Initial values (obtained from the recurrence for n = 0 … 17) are

          a(0)=1
          a(1)=42
          a(2)=1722
          …
          a(17)=40⋅∑_{k=1}^{16}a(k) − 819

    The code below computes a(n) for arbitrary n ≥ 0 using memoisation.
*/

#include <stddef.h>
#include <stdlib.h>

static seq_t *cache = NULL;          /* array holding computed a(n) */
static size_t cache_size = 0;        /* number of elements already computed */
static size_t cache_capacity = 0;    /* allocated capacity of cache */

/* ensure that cache[n] is computed */
static void ensure_up_to(idx_t n)
{
    if (cache == NULL) {
        /* initial allocation – we need at least the first 18 terms */
        cache_capacity = 18;
        cache = (seq_t *)malloc(cache_capacity * sizeof(seq_t));
        if (!cache) exit(1);

        /* a(0) */
        cache[0] = 1;

        /* compute a(1) … a(16) from the non‑homogeneous equations */
        for (idx_t i = 1; i <= 16; ++i) {
            seq_t sum = 0;
            for (idx_t k = 1; k <= i; ++k)
                sum += 40 * cache[i - k];
            cache[i] = 2 + sum;          /* a(i) = 2 + 40*∑_{k=1}^{i} a(i−k) */
        }

        /* compute a(17) using the special inhomogeneous equation */
        seq_t sum16 = 0;
        for (idx_t k = 1; k <= 16; ++k)
            sum16 += cache[k];
        cache[17] = 40 * sum16 - 819;   /* a(17) = 40*∑_{k=1}^{16}a(k) – 819 */

        cache_size = 18;                /* indices 0 … 17 are available */
    }

    if ((size_t)(n + 1) <= cache_size) return;

    /* extend capacity if necessary */
    if ((size_t)(n + 1) > cache_capacity) {
        size_t new_cap = cache_capacity;
        while ((size_t)(n + 1) > new_cap) new_cap *= 2;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) exit(1);
        cache = tmp;
        cache_capacity = new_cap;
    }

    /* compute missing terms using the homogeneous recurrence */
    for (idx_t idx = cache_size; idx <= n; ++idx) {
        if (idx < 18) continue;        /* first 18 terms already known */
        seq_t sum16 = 0;
        for (idx_t k = 1; k <= 16; ++k)
            sum16 += cache[idx - k];
        cache[idx] = 40 * sum16 - 820 * cache[idx - 17];
    }
    cache_size = n + 1;
}

seq_t a(idx_t n)
{
    ensure_up_to(n);
    return cache[n];
}
