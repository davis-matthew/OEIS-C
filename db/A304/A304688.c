/*
 * A304688  Primes p > 5 such that there is a polygonal number P_s(k) (with s
 *          >= 3, k >= 5) equal to p-1.
 * https://oeis.org/A304688
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 59, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Helpers:   floor_sqrt, is_prime_big, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A304688: primes p > 5 such that p - 1 is a polygonal number
   P_s(k) with s ≥ 3 and k ≥ 5.  The sequence is generated by
   testing primes in order and keeping those that satisfy the
   polygonal property.  The function a(idx_t n) returns the nth
   term (offset 1). */

#include <stddef.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>

#include "../utils/floor_sqrt.h"
#include "../utils/is_prime_big.h"
#include "../utils/seq_realloc.h"

/* ------------------------------------------------------------------ */
/* Test whether a prime p (>5) can be written as P_s(k) + 1 with
   k ≥ 5 and s ≥ 3.  p is assumed to be prime. */
static bool
is_polygonal_prime(seq_t p)
{
    /* p must be > 5 */
    if (p <= (seq_t)5)
        return false;

    /* p - 1 must be a polygonal number P_s(k) */
    seq_t pm1 = p - (seq_t)1;

    /* Compute the maximal k such that k(k+1)/2 ≤ p-1.
       kmax = floor((sqrt(8*(p-1)+1)-1)/2) */
    seq_t disc = (seq_t)8 * pm1 + (seq_t)1;
    seq_t sqrt_disc = floor_sqrt(disc);
    idx_t kmax = (idx_t)((sqrt_disc - (seq_t)1) / (idx_t)2);

    if (kmax < (idx_t)5)
        return false;

    for (idx_t k = (idx_t)5; k <= kmax; ++k)
    {
        /* denominator = k(k-1) */
        seq_t denom = (seq_t)k * ((seq_t)k - (seq_t)1);
        if (denom == (seq_t)0)  /* should not happen for k≥5 */
            continue;

        /* numerator = 2*(p-1) + 2*k^2 - 4*k */
        seq_t numerator = (seq_t)2 * pm1
                        + (seq_t)2 * (seq_t)k * (seq_t)k
                        - (seq_t)4 * (seq_t)k;

        if (numerator % denom != (seq_t)0)
            continue;

        seq_t s = numerator / denom;
        if (s < (seq_t)3)
            continue;

        /* At this point P_s(k) == p-1 is guaranteed by construction. */
        return true;
    }
    return false;
}

/* ------------------------------------------------------------------ */
/* Cached sequence */
static seq_t  *seq_cache   = NULL;
static size_t seq_len     = 0;   /* number of terms cached */
static size_t seq_cap     = 0;   /* capacity of cache */
static seq_t  next_candidate = (seq_t)7;   /* next odd number to test */

/* Grow the sequence until it contains at least `needed` terms by
   generating primes in order. */
static void
build_sequence(idx_t needed)
{
    if (seq_len >= needed)
        return;

    /* initial allocation */
    if (seq_cap == 0)
    {
        seq_cap = 64;
        seq_cache = (seq_t *)seq_realloc(NULL, 0, seq_cap);
    }

    seq_t cand = next_candidate;

    while (seq_len < needed)
    {
        if (is_prime_big(cand) && is_polygonal_prime(cand))
        {
            if (seq_len == seq_cap)
            {
                seq_cap <<= 1;
                seq_cache = (seq_t *)seq_realloc(seq_cache,
                                                 seq_cap >> 1, seq_cap);
            }
            seq_cache[seq_len++] = cand;
        }

        /* advance to next odd number */
        cand += (seq_t)2;
    }

    /* Remember the next candidate for subsequent calls */
    next_candidate = cand;
}

/* ------------------------------------------------------------------ */
/* Return the nth term of the sequence (offset 1). */
seq_t
a(idx_t n)
{
    if (n == (idx_t)0)  /* undefined below offset */
        return (seq_t)0;

    /* Build or grow the cache as needed */
    if (seq_len < n)
        build_sequence(n);

    return seq_cache[n - (idx_t)1];
}
