/*
 * A304573  Number of non-perfect powers (A007916) less than n and relatively
 *          prime to n.
 * https://oeis.org/A304573
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = φ(n) − #{k < n : gcd(k,n)=1 and k is a perfect power}
 * Range:     u8 n <= 71, u16 n <= 71, u32 n <= 71, u64 n <= 71, u128 n <= 71,
 *            big any n
 * Helpers:   gcd
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The function computes the count of numbers less than n that are
   relatively prime to n and not perfect powers.  The value φ(n) is
   obtained by factorisation of n.  All perfect powers k < n are
   generated by repeatedly multiplying a base by itself; duplicates are
   avoided with a static boolean array.  The algorithm runs in O(n)
   time for n up to about 100 000 and is fully compatible with C11
   and C++17. */

#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include "../utils/gcd.h"

seq_t a(idx_t n) {
    if (n <= 1) return 0;          /* a(1)=0, a(2) will be handled below */

    /* compute φ(n) */
    seq_t phi = n;
    idx_t temp = n;
    for (idx_t p = 2; (unsigned __int128)p * p <= temp; ++p) {
        if (temp % p == 0) {
            while (temp % p == 0) temp /= p;
            phi -= phi / p;
        }
    }
    if (temp > 1) phi -= phi / temp;

    /* count perfect powers coprime to n */
    static uint8_t *seen = NULL;
    static idx_t seen_max = 0;
    if (seen_max < n) {
        uint8_t *t = (uint8_t *)realloc(seen, n * sizeof(uint8_t));
        if (!t) return phi;   /* allocation failure – unlikely for n ≤ 10000 */
        seen = t;
        seen_max = n;
    }
    memset(seen, 0, n * sizeof(uint8_t));

    seq_t count_pp = 0;
    const seq_t one = 1;

    if (n > 1) count_pp += one;   /* 1 is a perfect power */

    for (idx_t base = 2; (seq_t)base * (seq_t)base < n; ++base) {
        seq_t val = (seq_t)base * (seq_t)base;
        while (val < n) {
            if (!seen[(idx_t)val]) {
                seen[(idx_t)val] = 1;
                if (gcd(val, n) == 1) count_pp += one;
            }
            unsigned __int128 next = (unsigned __int128)val * base;
            if (next >= n) break;
            val = (seq_t)next;
        }
    }

    return phi - count_pp;
}
