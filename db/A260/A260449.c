/*********************************************************************
 *  OEIS A260449: Infinite palindromic word with initial word 123
 *
 *  The word is generated by:
 *      w(1) = 1,2,3
 *      w(k) = w(k-1) + m(k-1) + reverse(w(k-1))    for k ≥ 2
 *  where m(k) is the middle element inserted at step k.
 *
 *  The sequence a(n) are the terms of the infinite word:
 *      a(1)=1, a(2)=2, a(3)=3, a(4)=1, a(5)=3, a(6)=2, … .
 *
 *  Recurrence used in this implementation:
 *      let p = 2^⌊log₂n⌋   (the largest power of two ≤ n)
 *      if n == p:                a(n) = a(p/2)          (since p = 2^k  →  p/2 = 2^(k-1))
 *      else:                     a(n) = a(2·p - n)      (mirror position in the current palindrome)
 *
 *  Base cases: a(1)=1, a(2)=2, a(3)=3.
 *
 *  The function runs in O(log n) time and uses no caching beyond recursion.
 *********************************************************************/

#include <stdint.h>   /* for idx_t and seq_t types (provided by the build) */
#include "../utils/floor_log2.h"

seq_t a(idx_t n) {
    if (n <= 3)   /* Base cases: the initial word */
        return (seq_t)n;

    /* p = 2^k , k = ⌊log₂n⌋ */
    idx_t k = floor_log2(n);
    idx_t p = 1ULL << k;          /* 2^k, largest power of two ≤ n */

    if (n == p) {
        /* middle element of the current palindrome */
        return a(k - 1);          /* a(p/2) where p = 2^k → p/2 = 2^(k-1) */
    } else {
        /* mirror position: 2^(k+1) - n */
        idx_t mirrored = (p << 1) - n;
        return a(mirrored);
    }
}
