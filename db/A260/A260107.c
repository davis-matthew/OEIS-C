/*
 * A260107  Lexicographically first increasing sequence of positive integers
 *          such that there are exactly a(k) terms less than or equal to
 *          3*a(k), for each k.
 * https://oeis.org/A260107
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 85, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n), the lexicographically first increasing sequence of positive integers such that 
   for each k, exactly a(k) terms are ≤ 3*a(k).  The sequence is generated by the rule:
   a(n) = 3*n – 2 when the value n‑1 has already appeared earlier in the sequence;
   otherwise a(n) = a(n‑1) + 1. */
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

static seq_t *seq_vals = NULL;       /* 1‑based array of the sequence values */
static size_t seq_cap = 0;           /* current capacity of seq_vals (in entries) */
static size_t max_computed = 0;      /* largest index whose value is known */

static unsigned char *seen = NULL;   /* bitmap: seen[x] == 1 if value x has appeared */
static size_t seen_cap = 0;          /* current capacity of seen (in bytes) */

static void ensure_seq_capacity(size_t needed)
{
    if (needed <= seq_cap)
        return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 4;
    if (new_cap < needed)
        new_cap = needed;
    seq_vals = (seq_t *)realloc(seq_vals, new_cap * sizeof(*seq_vals));
    seq_cap = new_cap;
}

static void ensure_seen_capacity(size_t needed)
{
    if (needed <= seen_cap)
        return;
    size_t new_cap = seen_cap ? seen_cap * 2 : 8;
    while (new_cap < needed)
        new_cap <<= 1;
    unsigned char *tmp = (unsigned char *)realloc(seen, new_cap);
    /* zero the new part */
    if (tmp && new_cap > seen_cap)
        memset(tmp + seen_cap, 0, new_cap - seen_cap);
    seen = tmp;
    seen_cap = new_cap;
}

/* Mark that the value `val` has appeared in the sequence. */
static void mark_seen(seq_t val)
{
    /* Convert only if the value fits in size_t; otherwise ignore it
       because it will never be used as i‑1 for any request we handle. */
    if (val > (seq_t)SIZE_MAX)
        return;
    size_t idx = (size_t)val;
    ensure_seen_capacity(idx + 1);
    seen[idx] = 1;
}

seq_t a(idx_t n)
{
    if (n == 0)            /* undefined for n < 1, harmless */
        return (seq_t)0;

    /* If already computed, return immediately. */
    if (n <= max_computed)
        return seq_vals[n];

    /* Ensure the storage arrays are large enough. */
    ensure_seq_capacity(n + 2);            /* +2 for safe indexing */
    ensure_seen_capacity(n + 5);           /* a bit of slack for values 3*n-2 */

    /* First‑time initialization. */
    if (max_computed == 0) {
        seq_vals[1] = (seq_t)1;
        mark_seen(seq_vals[1]);
        max_computed = 1;
    }

    /* Compute values up to n. */
    for (idx_t i = max_computed + 1; i <= n; ++i) {
        seq_t val;
        if (i > 1 && seen[(size_t)(i - 1)])
            val = (seq_t)3 * i - 2;
        else
            val = seq_vals[i - 1] + 1;

        seq_vals[i] = val;
        mark_seen(val);
    }
    max_computed = n;
    return seq_vals[n];
}
