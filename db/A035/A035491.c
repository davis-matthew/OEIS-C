/*
 * A035491  Relevant part of deck in Guy's shuffling problem (A035485): row n
 *          of the table lists the first 2n "cards" (numbers) after the n-th
 *          shuffle.
 * https://oeis.org/A035491
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabf, nice
 * Formula:   not stated
 * Range:     u8 n <= 90, u16 n <= 90, u32 n <= 90, u64 n <= 90, u128 n <= 90,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A035491: concatenation of first 2n cards after each shuffle
   in Guy's shuffling problem.  The sequence is generated by simulating
   the in‑shuffle described in the OEIS entry.  The algorithm keeps a
   global cache of all generated values so that each call to a(n) is
   O(1) after the required rows have been produced. */

#include <stdlib.h>

/* Global cache of the concatenated sequence.  (seq_t is the build's
   integer type; idx_t is unsigned 64‑bit.) */
static seq_t *prefix      = NULL;   /* array of generated values       */
static size_t prefix_len  = 0;      /* number of values stored          */
static size_t prefix_cap  = 0;      /* allocated capacity in elements   */

/* Current deck after the last shuffled row. */
static seq_t *curr_deck   = NULL;   /* array of 2*row size              */
static size_t curr_size   = 0;      /* number of elements in curr_deck  */
static idx_t  last_r      = 0;      /* last row number generated        */

/* Resize the prefix array to hold at least `need` elements. */
static void ensure_prefix_capacity(size_t need)
{
    if (need <= prefix_cap) return;
    size_t new_cap = prefix_cap ? prefix_cap << 1 : 16;
    while (new_cap < need) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(prefix, new_cap * sizeof(seq_t));
    if (!tmp) abort();          /* allocation failure */
    prefix = tmp;
    prefix_cap = new_cap;
}

/* Generate the first row (r = 1).  After this call, curr_deck points
   to the shuffled deck of row 1, curr_size == 2, and prefix contains
   the first two values. */
static void generate_first_row(void)
{
    seq_t *base = (seq_t *)malloc(2 * sizeof(seq_t));
    base[0] = (seq_t)1;
    base[1] = (seq_t)2;

    seq_t *shuffled = (seq_t *)malloc(2 * sizeof(seq_t));
    shuffled[0] = base[1];
    shuffled[1] = base[0];
    free(base);

    ensure_prefix_capacity(2);
    memcpy(prefix, shuffled, 2 * sizeof(seq_t));
    prefix_len = 2;

    curr_deck = shuffled;
    curr_size = 2;
    last_r    = 1;
}

/* Generate the next row (r = last_r + 1).  After this call, curr_deck
   holds the shuffled deck of the new row, curr_size == 2*r, and
   prefix has been extended accordingly. */
static void generate_next_row(void)
{
    idx_t r = last_r + 1;
    size_t new_size = (size_t)2 * r;

    /* Build the deck before shuffle: copy the previous deck and append
       the two new cards (2r‑1, 2r). */
    seq_t *base = (seq_t *)malloc(new_size * sizeof(seq_t));
    memcpy(base, curr_deck, curr_size * sizeof(seq_t));
    base[curr_size]     = (seq_t)(2 * r - 1);
    base[curr_size + 1] = (seq_t)(2 * r);

    /* In‑shuffle: bottom half starts at index r. */
    seq_t *shuffled = (seq_t *)malloc(new_size * sizeof(seq_t));
    for (size_t k = 0; k < (size_t)r; ++k) {
        shuffled[2 * k]     = base[r + k];
        shuffled[2 * k + 1] = base[k];
    }

    /* Append the new row to the global sequence. */
    ensure_prefix_capacity(prefix_len + new_size);
    memcpy(prefix + prefix_len, shuffled, new_size * sizeof(seq_t));
    prefix_len += new_size;

    /* Free the old deck and set up for the next iteration. */
    free(curr_deck);
    curr_deck = shuffled;
    curr_size = new_size;
    last_r    = r;

    free(base);
}

/* Main sequence accessor.  For n >= 1, returns the nth term of A035491. */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;          /* undefined for n < 1 */

    /* Generate rows until we have at least n values. */
    if (prefix_len == 0) generate_first_row();
    while (prefix_len < (size_t)n)
        generate_next_row();

    return prefix[n - 1];
}
