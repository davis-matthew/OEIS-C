/* A348699: Prime with a prime number of prime digits.
   Generated by searching sequential primes and testing their digit
   counts.  The function uses a static cache so that calls with
   arbitrary n in any order are answered efficiently. */
#include <stdbool.h>
#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>

#include "../utils/is_prime_small.h"   /* is_prime_small(seq_t) */
#include "../utils/next_prime.h"       /* next_prime(uint64_t) */
#include "../utils/ensure_capacity.h"  /* ensure_capacity(size_t, size_t*, void**, size_t) */
#include "../utils/prime_digit_count.h"

/* cache of qualifying primes */
static seq_t *qual_primes = NULL;     /* array of seq_t */
static size_t qual_size  = 0;         /* number of stored primes */
static size_t qual_cap   = 0;         /* allocated capacity */

/* last prime that has been examined */
static uint64_t last_checked = 1;

seq_t a(idx_t n)
{
    /* nothing is defined for n == 0; callers will never request it */
    if (n < 1)
        return (seq_t)0;

    /* Ensure the cache contains at least n qualifying primes */
    while (qual_size < (size_t)n) {
        /* Get the next prime after the last examined number */
        last_checked = next_prime(last_checked);

        /* Count prime digits */
        int cnt = prime_digit_count(last_checked);

        /* If that count itself is prime, store the prime */
        if (is_prime_small((seq_t)cnt)) {
            if (qual_size == qual_cap) {
                size_t new_cap = qual_cap ? qual_cap * 2 : 128;
                ensure_capacity(new_cap, &qual_cap, (void **)&qual_primes,
                                sizeof(seq_t));
            }
            qual_primes[qual_size++] = (seq_t)last_checked;
        }
    }

    return qual_primes[(size_t)n - 1];
}
