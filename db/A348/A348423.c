/*
 * A348423  Odd composite numbers k such that 2*k-3 is prime.
 * https://oeis.org/A348423
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 10, u16 n <= 3783, u32 n <= 1166, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A348423: odd composite numbers k such that 2*k-3 is prime.
   The sequence is generated by iterating over odd k, testing for
   compositeness and primality of 2*k-3.  Results are memoized so
   calls may occur in any order. */
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"

static seq_t *cache = NULL;   /* cached sequence values */
static size_t cache_len = 0;  /* number of cached entries */
static size_t cache_cap = 0;  /* allocated capacity for cache */

/* next odd integer to test; starts at the first odd > 2 */
static idx_t next_candidate = 9;

/* Append a new term to the cache, growing it if needed. */
static void append_term(seq_t val)
{
    if (cache_len == cache_cap) {
        size_t new_cap = cache_cap == 0 ? 16 : cache_cap * 2;
        seq_t *new_ptr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!new_ptr) { abort(); }
        cache = new_ptr;
        cache_cap = new_cap;
    }
    cache[cache_len++] = val;
}

/* Find the nth term (1‑based).  The function is safe for arbitrary
   order of calls and n≥1. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;  /* undefined for n=0 – return 0 */

    /* Expand cache until it contains the desired index. */
    while (cache_len < n) {
        /* Search for the next odd composite satisfying the condition. */
        for (;;) {
            idx_t k = next_candidate;
            next_candidate += 2;  /* ready for next iteration */
            if (is_prime_big((seq_t)k)) continue;          /* skip primes */
            seq_t pk = (seq_t)k * 2 - 3;                   /* 2*k-3  */
            if (is_prime_big(pk)) {
                append_term((seq_t)k);   /* store the term */
                break;                   /* found one, exit inner loop */
            }
        }
    }

    return cache[n - 1];
}
