/*
 * A278826  Rook's moves in chess: possible difference between origin and
 *          destination square when the squares are numbered sequentially, row
 *          by row.
 * https://oeis.org/A278826
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  sign, easy, fini, full
 * Formula:   not stated
 * Range:     i8 n <= 28, i16 n <= 28, i32 n <= 28, i64 n <= 28, i128 n <= 28,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: distinct signed differences Y–X for all rook moves on
   an 8×8 board numbered row‑wise from 1 to 64.  The sequence is
   generated by enumerating every rook move, collecting the
   resulting differences, removing duplicates and sorting the
   remaining values ascending. */

#include <stdbool.h>
#include <stddef.h>

seq_t a(idx_t n)
{
    /* The maximum absolute difference is 7*8 = 56.  We use an
       array indexed 0..112 (offset 56) to record which differences
       have appeared. */
    static bool seen[113] = { false };
    static seq_t diffs[28];
    static size_t diff_cnt = 0;
    static bool initialized = false;

    if (!initialized) {
        /* Enumerate all rook moves. */
        for (idx_t x = 1; x <= 64; ++x) {
            idx_t row = (x - 1) / 8;
            idx_t col = (x - 1) % 8;

            /* Horizontal moves: same row. */
            for (int d = -(int)col; d <= 7 - (int)col; ++d) {
                if (d == 0) continue;
                int j = (int)x + d;
                if (j < 1 || j > 64) continue;
                int diff = j - (int)x;
                seen[diff + 56] = true;
            }
            /* Vertical moves: same column. */
            for (int d = -(int)row; d <= 7 - (int)row; ++d) {
                if (d == 0) continue;
                int j = (int)x + d * 8;
                if (j < 1 || j > 64) continue;
                int diff = j - (int)x;
                seen[diff + 56] = true;
            }
        }

        /* Collect distinct differences in ascending order. */
        for (int i = 0; i < 113; ++i) {
            if (seen[i]) {
                diffs[diff_cnt++] = (seq_t)(i - 56);
            }
        }
        /* diff_cnt should be 28 for the standard 8×8 board. */
        initialized = true;
    }

    if (n == 0 || (size_t)n > diff_cnt)
        return (seq_t)0; /* Undefined for indices outside the range. */
    return diffs[(size_t)n - 1];
}
