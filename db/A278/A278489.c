/*  OEIS A278489
 *  a(n) = the n‑th integer k (starting with 0) that satisfies
 *  k - A002828(k) = n, i.e. at least one of
 *      A002828(k+1) == 1  or
 *      A002828(k+2) == 2  or
 *      A002828(k+3) == 3  or
 *      A002828(k+4) == 4
 *  holds.  (A002828(x) is the minimal number of squares needed to
 *  represent x, 1‑4 for x>0.)
 *
 *  The sequence is generated by a simple incremental search.
 */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include "../utils/min_squares.h"

/* ------------------------------------------------------------ */
/*  Helper: minimal number of squares needed to represent x     */

/* ------------------------------------------------------------ */
/*  Test whether k satisfies the non‑leaf condition             */
/* ------------------------------------------------------------ */
static bool satisfies(idx_t k)
{
    return (min_squares(k + 1) == 1) ||
           (min_squares(k + 2) == 2) ||
           (min_squares(k + 3) == 3) ||
           (min_squares(k + 4) == 4);
}

/* ------------------------------------------------------------ */
/*  Cache for already found values                              */
/* ------------------------------------------------------------ */
static idx_t *seq_cache = NULL;   /* array of k satisfying the condition */
static size_t cache_len = 0;      /* number of stored elements   */
static size_t cache_cap = 0;      /* allocated capacity          */
static idx_t next_candidate = 0;  /* next integer to test       */

/* Ensure enough capacity for one more element */
static void ensure_cache_capacity(void)
{
    if (cache_len >= cache_cap) {
        size_t new_cap = (cache_cap == 0) ? 64 : cache_cap << 1;
        idx_t *tmp = (idx_t *)realloc(seq_cache, new_cap * sizeof(idx_t));
        seq_cache = tmp;
        cache_cap = new_cap;
    }
}

/* ------------------------------------------------------------ */
/*  Main function required by the build                         */
/* ------------------------------------------------------------ */
seq_t a(idx_t n)
{
    /* Initialise static state on first call */
    static bool initialized = false;
    if (!initialized) {
        seq_cache   = NULL;
        cache_len   = 0;
        cache_cap   = 0;
        next_candidate = 0;
        initialized = true;
    }

    /* Generate terms until we have at least n+1 values */
    while (cache_len <= n) {
        if (satisfies(next_candidate)) {
            ensure_cache_capacity();
            seq_cache[cache_len++] = next_candidate;
        }
        ++next_candidate;
    }

    return (seq_t)seq_cache[n];
}
