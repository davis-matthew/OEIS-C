#include <stdbool.h>

/* Sequence A154153: numbers k such that 28 + k*(k+1)/2 is a perfect square.
   Generated by merging the two Pell‑equation sequences (x,y) with
   x^2 - 8*y^2 = -223, using the recurrence
        x' = 3*x + 8*y ,  y' = x + 3*y.
   For each sequence, k = (x-1)/2.  The two sequences are
   6,47,278,1623,...  and 8,57,336,1961,...
   Their interleaving gives the complete sequence. */

seq_t a(idx_t n)
{
    /* distance of n could be large, but only a few operations per term */
    seq_t x1 = (seq_t)13, y1 = (seq_t)7;   /* (13,7)  -> k=6   */
    seq_t x2 = (seq_t)17, y2 = (seq_t)8;   /* (17,8)  -> k=8   */
    idx_t   count = (idx_t)0;
    seq_t   result = 0;

    while (count < n)
    {
        seq_t k1 = (x1 - (seq_t)1) / (seq_t)2;
        seq_t k2 = (x2 - (seq_t)1) / (seq_t)2;

        if (k1 < k2)                /* take smaller k and advance first sequence */
        {
            result = k1;
            seq_t nx = x1 * (seq_t)3 + y1 * (seq_t)8;
            seq_t ny = x1 * (seq_t)1 + y1 * (seq_t)3;
            x1 = nx;  y1 = ny;
        }
        else                         /* take smaller k and advance second sequence */
        {
            result = k2;
            seq_t nx = x2 * (seq_t)3 + y2 * (seq_t)8;
            seq_t ny = x2 * (seq_t)1 + y2 * (seq_t)3;
            x2 = nx;  y2 = ny;
        }
        ++count;
    }
    return result;
}
