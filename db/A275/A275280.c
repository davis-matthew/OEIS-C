/*
 * A275280  Irregular triangle listing numbers m of n that have prime divisors
 *          p that also divide n, in order of appearance in a matrix of
 *          products that arranges the powers of prime divisors p of n along
 *          independent axes.
 * https://oeis.org/A275280
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy, tabf
 * Formula:   a(n) is obtained by concatenating, for each integer k ≥ 1, * the
 *            numbers m ≤ k that can be expressed as a product * Π p_i ^ e_i *
 *            where each p_i is a distinct prime divisor of k and * 0 ≤ e_i ≤
 *            ⌊log_{p_i} k⌋. * The product list is generated by iterating over
 *            the primes * in descending order; for...
 * Range:     u8 n <= 816, u16 n <= 9578, u32 n <= 9578, u64 n <= 9578,
 *            u128 n <= 9578, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stddef.h>
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Global storage for generated sequence */
static seq_t *seq_data = NULL;   /* array of terms */
static size_t  seq_len  = 0;     /* number of terms stored */
static size_t  seq_cap  = 0;     /* allocated capacity */
static idx_t   next_k   = 1;     /* next value of k to generate */

/* Temporary storage for prime factorisation of current k */
static idx_t prime_buf[32];   /* primes dividing the current k */
static size_t prime_cnt = 0;  /* number of distinct primes */

/* Current k being processed; used by recursion */
static idx_t current_k;

/* Ensure that the cache can hold at least 'need' elements */
static void ensure_cache_capacity(size_t need)
{
    if (need <= seq_cap) return;
    size_t new_cap = seq_cap == 0 ? 4 : seq_cap * 2;
    while (new_cap < need) new_cap *= 2;
    seq_t *tmp = (seq_t *)realloc(seq_data, new_cap * sizeof(seq_t));
    seq_data = tmp;
    seq_cap = new_cap;
}

/* Store a new term in the cache */
static void add_to_cache(seq_t val)
{
    ensure_cache_capacity(seq_len + 1);
    seq_data[seq_len++] = val;
}

/* Recursive generator of all products ≤ current_k */
static void recurse_products(size_t depth, seq_t prod)
{
    if (depth == prime_cnt) {          /* a complete product */
        add_to_cache(prod);
        return;
    }
    idx_t p = prime_buf[prime_cnt - 1 - depth];   /* outermost prime first */
    seq_t power = 1;
    seq_t limit = (seq_t)current_k;

    for ( ;; ) {
        seq_t curr_prod = prod * power;
        if (curr_prod > limit) break;      /* further powers will be larger */
        recurse_products(depth + 1, curr_prod);

        /* prepare next power, abort if it would exceed limit or overflow */
        if (power > limit / (seq_t)p) break;
        power *= (seq_t)p;
    }
}

/* Generate the row corresponding to the given k and append to cache */
static void generate_row(idx_t k)
{
    /* Factorise k into distinct primes */
    idx_t tmp = k;
    prime_cnt = 0;
    for (idx_t p = 2; p * p <= tmp; ++p) {
        if (tmp % p == 0) {
            prime_buf[prime_cnt++] = p;
            while (tmp % p == 0) tmp /= p;
        }
    }
    if (tmp > 1) prime_buf[prime_cnt++] = tmp;

    current_k = k;
    recurse_products(0, (seq_t)1);
}

/* Public function as required */
seq_t a(idx_t n)
{
    /* Generate terms until we have at least n of them */
    while (seq_len < (size_t)n) {
        generate_row(next_k);
        ++next_k;
    }
    return seq_data[n - 1];
}
