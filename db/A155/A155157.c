/*
 * A155157  a(n) = 10*a(n-1) + 10*a(n-2), with a(0)=1, a(1)=9, a(2)=99.
 * https://oeis.org/A155157
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   a(n) = 10*a(n-1) + 10*a(n-2), a(0)=1, a(1)=9, a(2)=99
 * Range:     u8 n <= 2, u16 n <= 4, u32 n <= 9, u64 n <= 18, u128 n <= 37,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

seq_t a(idx_t n)
{
    /* Base cases – the first three terms are hard‑coded as they are
       the only known ones that cannot be generated by the loop below. */
    if (n == 0)
        return (seq_t)1;
    if (n == 1)
        return (seq_t)9;
    if (n == 2)
        return (seq_t)99;

    /* a_nm2 holds a(n-2), a_nm1 holds a(n-1) during the iteration. */
    seq_t a_nm2 = (seq_t)9;   /* a(1) */
    seq_t a_nm1 = (seq_t)99;  /* a(2) */
    seq_t a_n   = a_nm1;      /* placeholder */

    /* Compute the sequence up to the desired n.  The recurrence is
       linear and requires only two previous terms, so the algorithm
       runs in O(n) time and O(1) extra space. */
    for (idx_t k = 3; k <= n; ++k) {
        a_n = (seq_t)10 * a_nm1 + (seq_t)10 * a_nm2;
        a_nm2 = a_nm1;
        a_nm1 = a_n;
    }
    return a_n;
}
