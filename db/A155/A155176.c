/*
 * A155176  Perimeter s/6 (divided by 6) of primitive Pythagorean triangles
 *          such that perimeters are Averages of twin prime pairs, q=p+1,
 *          a=q^2-p^2, c=q^2+p^2, b=2*p*q, s=a+b+c, s-+1 are primes.
 * https://oeis.org/A155176
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 3, u16 n <= 15, u32 n <= 16, u64 n <= 37, u128 n <= 37,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"

/* This sequence lists s/6 where s = 2(p+1)(2p+1) is the perimeter of the
   primitive Pythagorean triangle generated by consecutive integers
   p and p+1.  We only keep those p for which s-1 and s+1 are prime.
   The values are generated by iterating over p in increasing order
   and selecting the qualifying perimeters.  The sequence is memoized
   so later calls recompute only new entries. */

seq_t a(idx_t n) {
    /* static memoization state */
    static seq_t *cache = NULL;
    static size_t cache_cap = 0;   /* allocated capacity */
    static size_t cache_len = 0;   /* number of terms stored */
    static idx_t next_p = 1;       /* next p to test */

    /* extend cache until we have at least n terms */
    while (cache_len < n) {
        seq_t pp = (seq_t)next_p;
        seq_t s  = 2 * (pp + 1) * (2 * pp + 1);   /* perimeter */

        /* test the prime neighbours */
        if (is_prime_big(s - 1) && is_prime_big(s + 1)) {
            /* allocate or grow cache if necessary */
            if (cache_len == cache_cap) {
                size_t new_cap = cache_cap ? cache_cap * 2 : 64;
                seq_t *tmp = (seq_t *)realloc(cache,
                                              new_cap * sizeof(seq_t));
                if (!tmp) exit(EXIT_FAILURE);
                cache = tmp;
                cache_cap = new_cap;
            }

            cache[cache_len++] = s / 6;   /* store the term */
        }

        ++next_p;   /* advance to next p */
    }

    return cache[n - 1];
}
