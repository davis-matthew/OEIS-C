/* Sequence : A155185 (Primes in A155175)
   Formula:  a(n) is the n‑th prime hypotenuse c of the primitive
   Pythagorean triple generated by p, q = p+1 (p ≥ 1) where
   c = p² + q², a = q² – p², b = 2pq,  s = a + b + c.
   The triple is accepted iff  c is prime and both  s–1  and  s+1
   are prime.  The sequence begins 5, 13, 113, 1741, …  (offset = 1). */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"

static seq_t *cache = NULL;        /* stored terms */
static size_t cap = 0;             /* current capacity of cache */
static size_t len = 0;             /* number of terms stored */
static uint64_t last_p = 0;        /* last value of p tried */

/* ensure cache can hold at least 'need' elements */
static void grow_cache(size_t need)
{
    if (need <= cap) return;
    size_t new_cap = cap ? cap * 2 : 16;
    while (new_cap < need) new_cap <<= 1;
    seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!tmp) abort();
    cache = tmp;
    cap = new_cap;
}

seq_t a(idx_t n)
{
    if (n == (idx_t)0) return (seq_t)0;   /* undefined for n = 0 */

    size_t target = (size_t)n;
    if (target > len) {
        while (len < target) {
            ++last_p;                     /* next integer p */
            uint64_t p = last_p;
            uint64_t q = p + 1;

            /* Compute triangle parameters using 64‑bit arithmetic */
            uint64_t a_val = q*q - p*p;   /* a = q² – p² */
            uint64_t b_val = 2*p*q;       /* b = 2pq */
            uint64_t c_val = q*q + p*p;   /* c = q² + p² */
            uint64_t s_val = a_val + b_val + c_val; /* s = a+b+c */

            seq_t c_seq = (seq_t)c_val;
            if (is_prime_big(c_seq) &&
                is_prime_big((seq_t)(s_val - 1)) &&
                is_prime_big((seq_t)(s_val + 1))) {
                grow_cache(len + 1);
                cache[len++] = c_seq;
            }
        }
    }
    return cache[target - 1];
}
