/*
 * A097470  Number of 0's in the decimal expansion of the lesser of twin
 *          primes.
 * https://oeis.org/A097470
 *
 * Offset:    2    (a(2) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 24, u16 n <= 106, u32 n <= 106, u64 n <= 106,
 *            u128 n <= 106, big any n
 * Helpers:   is_prime, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation: a(n) = number of decimal 0's in the lesser twin prime
   corresponding to index n (offset 2). The sequence is generated by
   searching for twin primes and counting zeros. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime.h"
#include "../utils/seq_realloc.h"

static seq_t *zeros_cache = NULL;   /* cache of zero counts       */
static size_t zeros_cap   = 0;      /* cache capacity             */
static size_t zeros_count = 0;      /* number of entries stored   */
static uint64_t next_candidate = 3; /* next odd number to test    */

/* Ensure the cache can hold at least `needed` entries. */
static void ensure_capacity(size_t needed)
{
    if (zeros_cap >= needed)
        return;
    size_t new_cap = zeros_cap ? zeros_cap * 2 : 16;
    while (new_cap < needed)
        new_cap *= 2;
    zeros_cache = seq_realloc(zeros_cache, zeros_cap, new_cap);
    zeros_cap   = new_cap;
}

/* Expand the cache until the twin prime with zero‑based index
   `needed_idx` is stored. */
static void expand_twin_primes(size_t needed_idx)
{
    while (zeros_count <= needed_idx) {
        uint64_t m = next_candidate;          /* lesser twin candidate */

        if (is_prime((idx_t)m) && is_prime((idx_t)(m + 2))) {
            /* Count 0 digits in m. */
            seq_t m_seq = (seq_t)m;
            seq_t zero  = 0;
            while (m_seq) {
                if ((m_seq % (seq_t)10) == 0)
                    zero++;
                m_seq = m_seq / (seq_t)10;
            }
            ensure_capacity(zeros_count + 1);
            zeros_cache[zeros_count] = zero;
            zeros_count++;
        }
        next_candidate = m + 2; /* advance to next odd */
    }
}

/* External function implementing OEIS entry a(n). */
seq_t a(idx_t n)
{
    if (n < 2)
        return (seq_t)0;                        /* below offset */

    size_t need_idx = (size_t)(n - 2);           /* zero‑based index */
    if (zeros_count <= need_idx)
        expand_twin_primes(need_idx);
    return zeros_cache[need_idx];
}
