/* 1‑limiting word of the morphism 0→01, 1→20, 2→1 starting with 1;
   a(n) is the n‑th symbol (1‑based) of the infinite word generated by
   iterating this morphism.  The algorithm builds successive iterates
   until the required length is reached and returns the appropriate symbol. */
#include <stdlib.h>

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* undefined for n < 1 */

    /* Work with a byte array of symbols (0,1,2).  This avoids
       constructing arbitrary‑precision integers in the temporary array. */
    unsigned char *w   = (unsigned char *)malloc(sizeof(unsigned char));
    if (!w) return (seq_t)0;
    w[0] = 1;   /* initial word: "1" */

    size_t len   = 1;   /* current word length */
    size_t iter  = 0;   /* iteration counter */

    while (1) {
        /* Expand w into the next iterate.  Each symbol expands to
           at most 2 symbols, so the new length is <= 2*len.
           Allocate a buffer slightly larger to avoid reallocations. */
        size_t new_cap = len * 2 + 1;
        unsigned char *neww = (unsigned char *)malloc(new_cap);
        if (!neww) { free(w); return (seq_t)0; }

        size_t newlen = 0;
        for (size_t i = 0; i < len; ++i) {
            unsigned char s = w[i];
            if (s == 0) {            /* 0 → 0 1 */
                neww[newlen++] = 0;
                neww[newlen++] = 1;
            } else if (s == 1) {      /* 1 → 2 0 */
                neww[newlen++] = 2;
                neww[newlen++] = 0;
            } else {                  /* 2 → 1 */
                neww[newlen++] = 1;
            }
        }

        free(w);
        w   = neww;
        len = newlen;
        ++iter;

        /* We only need odd iterates because the fixed point is reached
           after an odd number of expansions.  Stop when the word is
           long enough for the requested index. */
        if ((iter & 1) && len >= (size_t)n)
            break;
    }

    seq_t result = (seq_t)w[(size_t)(n - 1)];
    free(w);
    return result;
}
