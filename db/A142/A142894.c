/* Primes congruent to 10 modulo 63 (OEIS A142894) */
#include <stdbool.h>
#include <stdlib.h>

/* Simple deterministic primality test suitable for the small numbers
   generated by this sequence.  It uses trial division by odd numbers
   up to sqrt(n). */
static bool is_prime(seq_t n)
{
    if (n < 2) return false;
    if (n % 2 == 0) return n == 2;
    for (seq_t i = 3; i <= n / i; i += 2) {
        if (n % i == 0) return false;
    }
    return true;
}

seq_t a(idx_t n)
{
    /* a(1) is defined; for n == 0 return 0 (undefined) */
    if (n == 0) return 0;

    /* Cached list of primes ≡ 10 (mod 63) */
    static seq_t *primes = NULL;
    static size_t primes_cap = 0;      /* allocated capacity */
    static idx_t primes_cnt = 0;       /* number of stored primes  */
    static idx_t cand = 73;            /* first candidate (73 ≡ 10 mod 63) */

    /* Ensure we have at least n primes cached */
    while (primes_cnt < n) {
        if (is_prime(cand)) {
            /* Grow the array if necessary */
            if (primes_cnt == primes_cap) {
                size_t new_cap = (primes_cap > 0) ? primes_cap * 2 : 4;
                seq_t *new_arr = (seq_t *)malloc(new_cap * sizeof(seq_t));
                if (!new_arr) exit(1);   /* out of memory */
                for (size_t i = 0; i < primes_cnt; ++i) new_arr[i] = primes[i];
                free(primes);
                primes = new_arr;
                primes_cap = new_cap;
            }
            primes[primes_cnt++] = cand;
        }
        cand += 63;   /* next number 10 mod 63 */
    }

    return primes[n - 1];
}
