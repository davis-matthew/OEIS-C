/* Computes the n‑th prime of the form 3*x^2 + 5*x*y - 6*y^2
   (equivalently 6*x^2 + 11*x*y + y^2).  A prime p≠97 is representable
   iff 97 is a quadratic residue modulo p, i.e. the Legendre symbol (97|p)=1.
   The value 97 itself is also included.  The sequence is generated by
   testing successive primes and storing those that satisfy the
   Legendre condition.  */

#include <stdbool.h>
#include <stddef.h>          /* size_t */

#include "../utils/is_prime.h"   /* bool is_prime(idx_t)            */
#include "../utils/grow_seq.h"   /* void grow_seq(seq_t **,size_t*,size_t) */

static seq_t *series      = NULL;   /* dynamic array of found terms   */
static size_t series_cap  = 0;      /* capacity of the array          */
static size_t series_len  = 0;      /* number of terms stored         */

static uint64_t candidate  = 2;     /* next integer to test           */

static bool resid[97]      = {false};
static bool resid_init     = false;

/* (97|p) = 1  iff  p mod 97 is a quadratic residue modulo 97.
   Special case: p = 97 is representable.                                          */
static bool legendre_97(uint64_t p)
{
    if (p == 97) return true;          /* 97 itself is represented */
    return resid[p % 97];
}

/* Return the n-th term of OEIS A142957            */
seq_t a(idx_t n)
{
    /* Build the residue table once */
    if (!resid_init) {
        for (uint64_t i = 1; i < 97; ++i)
            resid[(i * i) % 97] = true;
        resid_init = true;
    }

    /* Extend the sequence until we have at least n terms */
    while (series_len < (size_t)n) {
        /* Search for the next representable prime */
        while (true) {
            if (is_prime(candidate)) {
                if (candidate == 2 || legendre_97(candidate)) {
                    /* Store the prime */
                    if (series_len == series_cap)
                        grow_seq(&series, &series_cap, series_len + 1);
                    series[series_len++] = (seq_t)candidate;
                    ++candidate;                /* advance past this prime */
                    break;                       /* move to next term needed */
                }
            }
            ++candidate;                         /* next integer to test   */
        }
    }

    return series[n - 1];
}
