/*
 * A142312  Primes congruent to 1 mod 45.
 * https://oeis.org/A142312
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 269, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   next_prime
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: Primes congruent to 1 (mod 45)
 *
 * The sequence is defined as the increasing list of primes p with
 * p ≡ 1 (mod 45).  The first terms are
 * 181, 271, 541, 631, 811, …
 *
 * This implementation builds the sequence lazily: as many terms as
 * required by a call to a(n) are generated by advancing prime
 * candidates with next_prime().  The cache persists across calls
 * so that repeated accesses are inexpensive.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/next_prime.h"

seq_t a(idx_t n)
{
    /* Silence compiler warnings for unused variable types */
    (void)(n);

    /* Static cache for already found terms */
    static seq_t *cache     = NULL;
    static idx_t cache_len  = 0; /* number of terms stored */
    static idx_t cache_cap  = 0; /* capacity of cache array */

    /* Static variable holding the last prime inspected */
    static uint64_t last_prime = 2; /* start from the first prime */

    /* Ensure we have at least n terms in the cache */
    while (cache_len < n) {
        /* Find next prime after `last_prime` */
        last_prime = next_prime(last_prime);

        /* Test the congruence condition */
        if (last_prime % 45ULL == 1ULL) {
            /* Grow cache if necessary */
            if (cache_len == cache_cap) {
                if (cache_cap == 0) cache_cap = 16;
                else                cache_cap <<= 1;   /* double capacity */
                cache = (seq_t*)realloc(cache, cache_cap * sizeof(seq_t));
            }
            /* Store the new term */
            cache[cache_len++] = (seq_t)last_prime;
        }
    }

    /* Return the requested term (1‑based index) */
    return cache[n - 1];
}
