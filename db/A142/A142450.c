/* Prime congruent to 43 (mod 49): a(n) is the n‑th prime p with p % 49 == 43
   (OEIS A142450).  The sequence is generated by consecutive search over
   numbers congruent to 43 (mod 49) and primality testing with is_prime_big. */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>
#include "../utils/is_prime_big.h"   /* declares bool is_prime_big(seq_t) */

/* static storage for primes found so far (offset 1: a(1) is prime_seq[0]) */
static seq_t *prime_seq   = NULL;   /* dynamic array of primes */
static idx_t  prime_cnt   = 0;      /* number of primes stored */
static size_t prime_cap   = 0;      /* current capacity of prime_seq */

/* next candidate in the arithmetic progression 43,92,141,... */
static seq_t next_candidate = (seq_t)43;

/* Ensure prime_seq has room for at least “need” elements. */
static void grow_if_needed(idx_t need)
{
    if ((idx_t)prime_cap >= need) return;
    size_t new_cap = prime_cap ? prime_cap * 2 : 16;
    while (new_cap < (size_t)need) new_cap *= 2;
    seq_t *tmp = (seq_t *)realloc(prime_seq, new_cap * sizeof(seq_t));
    if (!tmp) exit(1);            /* out of memory */
    prime_seq = tmp;
    prime_cap = new_cap;
}

/* Generate and append the next prime ≡ 43 (mod 49). */
static void generate_next_prime(void)
{
    while (1) {
        seq_t candidate = next_candidate;
        next_candidate = candidate + (seq_t)49;   /* advance to the next number in the progression */

        if (is_prime_big(candidate)) {
            grow_if_needed(prime_cnt + 1);
            prime_seq[prime_cnt] = candidate;
            prime_cnt++;
            return;
        }
    }
}

/* Public function required by the framework. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* behavior below offset is unspecified */
    while (prime_cnt < n) generate_next_prime();   /* generate primes up to n */
    return prime_seq[n - 1];        /* offset 1: a(1) is the first element */
}
