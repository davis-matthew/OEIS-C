/*
 * A327102  BII-numbers of set-systems with non-spanning edge-connectivity >=
 *          2.
 * https://oeis.org/A327102
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 61, u16 n <= 61, u32 n <= 61, u64 n <= 61, u128 n <= 61,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A327102:
   the nth BII‑number of set‑systems whose non‑spanning edge‑connectivity is
   at least 2.  The sequence is generated by testing consecutive
   integers for the required property. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* Union‑find helpers for vertices 0..63. */
static inline int uf_find(int v, int *parent) {
    int p = parent[v];
    return (p == v) ? v : (parent[v] = uf_find(p, parent));
}
static inline void uf_union(int a, int b, int *parent) {
    int ra = uf_find(a, parent);
    int rb = uf_find(b, parent);
    if (ra != rb) parent[ra] = rb;
}

/* Tests whether the set‑system associated with BII‑number n has
   non‑spanning edge‑connectivity ≥ 2. */
static bool has_property(idx_t n) {
    if (n == 0) return false;

    idx_t temp = n;
    idx_t pos = 1;
    uint64_t emasks[64];
    size_t ecount = 0;

    /* Collect masks for all edges: one for each binary index of n. */
    while (temp) {
        if (temp & 1) {
            uint64_t mask = 0;
            idx_t j = pos;
            uint64_t bitpos = 1;
            while (j) {
                if (j & 1) mask |= 1ULL << (bitpos - 1);
                j >>= 1;
                ++bitpos;
            }
            emasks[ecount++] = mask;
        }
        temp >>= 1;
        ++pos;
    }

    if (ecount <= 1) return false;   /* single edge -> empty after removal */

    /* Determine the set of vertices appearing in the hypergraph. */
    uint64_t vertices_present = 0;
    for (size_t i = 0; i < ecount; ++i) vertices_present |= emasks[i];

    /* Check that the full hypergraph is connected. */
    int parent[64];
    for (int i = 0; i < 64; ++i) parent[i] = i;

    for (size_t i = 0; i < ecount; ++i) {
        uint64_t mask = emasks[i];
        int first = __builtin_ctzll(mask);
        while (mask) {
            int b = __builtin_ctzll(mask);
            uf_union(first, b, parent);
            mask &= mask - 1;
        }
    }

    int root = -1;
    for (int v = 0; v < 64; ++v) {
        if (vertices_present & (1ULL << v)) {
            int r = uf_find(v, parent);
            if (root == -1) root = r;
            else if (root != r) return false; /* disconnected */
        }
    }

    /* Verify no edge is a bridge: removing any edge leaves the graph
       connected and non‑empty. */
    for (size_t k = 0; k < ecount; ++k) {
        if (ecount - 1 == 0) return false;

        uint64_t remaining = 0;
        for (size_t i = 0; i < ecount; ++i)
            if (i != k) remaining |= emasks[i];

        int parent2[64];
        for (int i = 0; i < 64; ++i) parent2[i] = i;

        for (size_t i = 0; i < ecount; ++i) {
            if (i == k) continue;
            uint64_t mask = emasks[i];
            int first = __builtin_ctzll(mask);
            while (mask) {
                int b = __builtin_ctzll(mask);
                uf_union(first, b, parent2);
                mask &= mask - 1;
            }
        }

        int rootR = -1;
        for (int v = 0; v < 64; ++v) {
            if (remaining & (1ULL << v)) {
                int r = uf_find(v, parent2);
                if (rootR == -1) rootR = r;
                else if (rootR != r) return false; /* removal disconnects */
            }
        }
    }

    return true;
}

/* Main sequence function: returns the n‑th term (1‑based). */
seq_t a(idx_t n) {
    static idx_t *seq = NULL;
    static size_t seq_len = 0;
    static size_t seq_cap = 0;
    static idx_t last_checked = 0;

    while (seq_len < (size_t)n) {
        ++last_checked;
        if (has_property(last_checked)) {
            if (seq_len == seq_cap) {
                size_t new_cap = seq_cap ? seq_cap * 2 : 16;
                idx_t *tmp = (idx_t *)realloc(seq, new_cap * sizeof(idx_t));
                if (!tmp) abort();
                seq = tmp;
                seq_cap = new_cap;
            }
            seq[seq_len++] = last_checked;
        }
    }
    return (seq_t)seq[n - 1];
}
