/*
 * A063637  Primes p such that p+2 is a semiprime.
 * https://oeis.org/A063637
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = the nth prime p such that p+2 is a semiprime (product of
 *            two primes, counted with multiplicity)
 * Range:     u8 n <= 24, u16 n <= 2132, u32 n <= 9513, u64 n <= 9513,
 *            u128 n <= 9513, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This implementation keeps a small sieve of primes up to a growing limit.  For each prime in the sieve it checks
   whether p+2 is semiprime by trial division using the same list of primes.  The resulting primes are stored in
   a static array _terms which is extended as needed to answer any requested index.  All data structures are
   static so the function can be called in any order.  The code is valid C99 and compiles as C++17.  It uses only
   operations allowed on seq_t (assignment from native integer constants) and size_t/int types for indexing. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

static idx_t _prime_limit = 2000000;   /* initial sieve limit */
static idx_t * _primes = NULL;          /* list of primes up to _prime_limit */
static size_t _prime_cnt = 0;

static seq_t * _terms = NULL;          /* sequence values */
static size_t _term_cnt = 0;
static bool _initialized = false;

/* ------------------------------------------------------------------ */
/* Simple sieve of Eratosthenes: store primes in _primes up to 'limit' */
/* ------------------------------------------------------------------ */
static void _compute_primes(idx_t limit)
{
    size_t sz = (size_t)limit + 1;
    unsigned char *is_comp = (unsigned char *)calloc(sz, 1);   /* zeroed array of composite flags */
    if (!is_comp) exit(EXIT_FAILURE);

    /* estimate number of primes for allocation */
    size_t cap = (limit / 10) + 16;
    _primes = (idx_t *)malloc(cap * sizeof(idx_t));
    if (!_primes) { free(is_comp); exit(EXIT_FAILURE); }

    for (idx_t i = 2; i <= limit; ++i) {
        if (!is_comp[(size_t)i]) {
            if (_prime_cnt >= cap) {
                cap <<= 1;
                idx_t *tmp = (idx_t *)realloc(_primes, cap * sizeof(idx_t));
                if (!tmp) { free(is_comp); free(_primes); exit(EXIT_FAILURE); }
                _primes = tmp;
            }
            _primes[_prime_cnt++] = i;
            if ((idx_t)i * (idx_t)i <= limit) {
                for (idx_t j = i * i; j <= limit; j += i) is_comp[(size_t)j] = 1;
            }
        }
    }
    free(is_comp);
}

/* ------------------------------------------------------------------ */
/* Check whether 'm' (passed as uint64_t) is a semiprime (product of
   exactly two primes, counting multiplicity).  We use the prime list
   generated by the sieve; it is sufficient because m <= limit+2.  */
/* ------------------------------------------------------------------ */
static bool _is_semiprime(uint64_t m)
{
    int factors = 0;
    for (size_t i = 0; i < _prime_cnt && (uint64_t)_primes[i] * (uint64_t)_primes[i] <= m; ++i) {
        uint64_t p = (uint64_t)_primes[i];
        while (m % p == 0) {
            ++factors;
            m /= p;
            if (factors > 2) return false;            /* more than two prime factors */
        }
    }
    if (m > 1) ++factors;                           /* remaining prime factor */
    return factors == 2;
}

/* ------------------------------------------------------------------ */
/* Build the sequence up to at least 'need' terms.  Recompute the
   sieve and the sequence if necessary.  This function is idempotent
   and can be called from any order. */
/* ------------------------------------------------------------------ */
static void _ensure_terms(idx_t need)
{
    if (_initialized && _term_cnt >= (size_t)need) return;

    idx_t limit = _prime_limit;
    while (_term_cnt < (size_t)need) {
        _compute_primes(limit);

        /* Discard previous terms */
        if (_terms) { free(_terms); _terms = NULL; }
        size_t tcap = limit;
        _terms = (seq_t *)malloc(tcap * sizeof(seq_t));
        if (!_terms) exit(EXIT_FAILURE);
        _term_cnt = 0;

        for (size_t i = 0; i < _prime_cnt; ++i) {
            seq_t p = (seq_t)_primes[i];
            if (_is_semiprime((uint64_t)_primes[i] + 2)) {
                if (_term_cnt >= tcap) {
                    tcap <<= 1;
                    seq_t *tmp = (seq_t *)realloc(_terms, tcap * sizeof(seq_t));
                    if (!tmp) { free(_terms); exit(EXIT_FAILURE); }
                    _terms = tmp;
                }
                _terms[_term_cnt++] = p;
            }
        }

        /* Not enough yet – double the sieve limit and try again */
        if (_term_cnt < (size_t)need) {
            limit <<= 1;
        } else {
            _prime_limit = limit;
        }
    }
    _initialized = true;
}

/* ------------------------------------------------------------------ */
/* Public function as required by the specification.  It returns
   a(seq_t), where a(1) is the first term (2).  Undefined for n=0. */
/* ------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                 /* safety: sequence undefined for n=0 */
    _ensure_terms(n);
    if (n > _term_cnt) return 0;           /* unreachable for normal calls */
    return _terms[n - 1];
}
