/*
 * A295060  Solution of the complementary equation a(n) = 2*a(n-1) - b(n-2),
 *          where a(0) = 3, a(1) = 5, b(0) = 1, b(1) = 2, and (a(n)) and
 *          (b(n)) are increasing complementary sequences.
 * https://oeis.org/A295060
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 15, u32 n <= 28, u64 n <= 28, u128 n <= 28,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A295060:
   Complementary increasing sequences a() and b() are generated by
   a(0)=3, a(1)=5, b(0)=1, b(1)=2 and
   a(n) = 2*a(n-1) - b(n-2)   for n >= 2.  b(n) is the smallest
   integer > b(n-1) not already equal to any a(k).  This routine
   returns a(n) for any n >= 0 using memoisation. */

#include <stdlib.h>

/* Static cache of previously computed terms. */
static size_t            a_cap   = 0,    /* current capacity of a_arr */
                         b_cap   = 0,    /* current capacity of b_arr */
                         a_len   = 0,    /* number of a terms stored */
                         a_pos   = 0;    /* index into a_arr for b search */
static seq_t *           a_arr   = NULL;/* a[0 .. a_len-1] */
static seq_t *           b_arr   = NULL;/* b[0 .. a_len-1] */
static seq_t             next_b   = 0;  /* next integer to test for b */

/* Grow an array of seq_t to hold at least 'needed' elements. */
static inline void
ensure_capacity(size_t *cap, seq_t **arr, size_t needed)
{
    if (needed > *cap) {
        size_t new_cap = (*cap > 0) ? (*cap) << 1 : 2;
        while (new_cap < needed) new_cap <<= 1;
        void *tmp = realloc(*arr, new_cap * sizeof(seq_t));
        if (!tmp) abort();                 /* out‑of‑memory */
        *arr    = (seq_t *)tmp;
        *cap    = new_cap;
    }
}

/* Compute a(n).  The function is safe to call in any order. */
seq_t a(idx_t n)
{
    /* Initialisation on first call. */
    if (!a_arr) {
        a_cap    = 2;
        b_cap    = 2;
        a_arr    = (seq_t *)malloc(a_cap * sizeof(seq_t));
        b_arr    = (seq_t *)malloc(b_cap * sizeof(seq_t));
        if (!a_arr || !b_arr) abort();

        a_arr[0] = (seq_t)3;
        a_arr[1] = (seq_t)5;
        b_arr[0] = (seq_t)1;
        b_arr[1] = (seq_t)2;
        a_len    = 2;       /* a[0] and a[1] stored */
        a_pos    = 0;       /* start of a_arr for b search */
        next_b   = (seq_t)3;/* smallest integer > b[1] */
    }

    /* Ensure the caches are big enough for the requested index. */
    size_t target = (size_t)n;
    ensure_capacity(&a_cap, &a_arr, target + 1);
    ensure_capacity(&b_cap, &b_arr, target + 1);

    /* Generate terms up to the target index. */
    while (a_len <= target) {
        size_t i = a_len;   /* index of the new a value to compute */

        /* Recurrence: a(i) = 2*a(i-1) - b(i-2). */
        seq_t new_a = ((seq_t)2 * a_arr[i-1]) - b_arr[i-2];
        a_arr[i] = new_a;

        /* Find b(i): smallest integer > next_b not already occuring in a. */
        seq_t cand = next_b;
        while (a_pos < a_len && a_arr[a_pos] == cand) {
            ++a_pos;
            ++cand;
        }
        b_arr[i] = cand;
        next_b   = cand + (seq_t)1;   /* candidate for next b */

        ++a_len;
    }

    return a_arr[target];
}
