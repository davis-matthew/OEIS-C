/*
 * A295963  Solution of the complementary equation a(n) = a(n-1) + a(n-2) +
 *          b(n) - 1, where a(0) = 1, a(1) = 2, b(0) = 3, b(1) = 4, b(2) = 5,
 *          and (a(n)) and (b(n)) are increasing complementary sequences.
 * https://oeis.org/A295963
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 8, u16 n <= 19, u32 n <= 42, u64 n <= 88, u128 n <= 180,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* 
   Computation of OEIS sequence A295963.
   The sequence is generated by iterating the complementary
   construction:

   a(0) = 1, a(1) = 2                              
   b(0) = 3, b(1) = 4, b(2) = 5
   a(n) = a(n-1) + a(n-2) + b(n) - 1  (n ≥ 2)

   The sequence b(n) is the n-th positive integer that is not in
   a(0), a(1), …, a(n-1).  The algorithm maintains the list of a’s
   and keeps a running pointer to the smallest missing number
   not yet used as a b.  Only O(n) work and memory are required.
*/

#include <stdlib.h>
#include <stddef.h>

seq_t a(idx_t n)
{
    /* static state for memoized sequence values */
    static seq_t *seq   = NULL;   /* array of a(i) values */
    static size_t len   = 0;      /* current number of stored terms */
    static size_t cap   = 0;      /* capacity of the array */

    /* state for generating the missing numbers (b(n)) */
    static idx_t  processed_b = 0;   /* how many b's have been produced */
    static idx_t  next_candidate = 1; /* next number to test as a missing one */
    static idx_t  skip_index = 0;    /* index in seq to skip over a's */

    /* -----------------------------------------------------------------
       initialise with base terms a(0)=1, a(1)=2
     ----------------------------------------------------------------- */
    if (len == 0) {
        cap = 4;
        seq = (seq_t *)malloc(cap * sizeof(seq_t));
        seq[0] = (seq_t)1;
        seq[1] = (seq_t)2;
        len   = 2;
    }

    /* -----------------------------------------------------------------
       extend the array until it contains a(n)
     ----------------------------------------------------------------- */
    while (len <= n) {
        idx_t     i      = (idx_t)len;          /* index of new term */
        seq_t     b_val;                        /* b(i) */

        /* find the i-th missing number (0‑based index) */
        while (1) {
            /* skip over any a value that equals the candidate */
            while (skip_index < len && seq[skip_index] == (seq_t)next_candidate) {
                ++skip_index;
                ++next_candidate;
            }

            /* next_candidate is currently a missing number */
            if (processed_b == i) {
                b_val = (seq_t)next_candidate;
                ++processed_b;          /* consume this missing number */
                ++next_candidate;       /* advance for the next iteration */
                break;
            } else {
                ++processed_b;          /* skip this missing number */
                ++next_candidate;
            }
        }

        /* compute a(i) */
        seq_t a_prev   = seq[i - 1];
        seq_t a_prev2  = seq[i - 2];
        seq_t a_new    = a_prev + a_prev2 + b_val - 1;

        /* grow the array if necessary */
        if (len == cap) {
            cap = (cap == 0) ? 4 : cap * 2;
            seq = (seq_t *)realloc(seq, cap * sizeof(seq_t));
        }
        seq[len] = a_new;
        ++len;
    }

    return seq[n];
}
