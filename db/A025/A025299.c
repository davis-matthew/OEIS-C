/*
 * A025299  Numbers that are the sum of 2 nonzero squares in 8 or more ways.
 * https://oeis.org/A025299
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 10, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   alloc_seq_array
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A025299: numbers that are the sum of two non‑zero squares in
   at least eight distinct ways.  The sequence is generated by
   pre‑computing all values up to a bound that contains the
   required 10 000 terms. */
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include "../utils/alloc_seq_array.h"

static seq_t *seq_table = NULL;
static idx_t seq_len   = 0;

static void init_seq(void)
{
    /* Empirical bound that contains far more than the first 10 000
       terms of the sequence (see OEIS data).  48 000 000 is enough,
       60 000 000 gives extra safety. */
    const size_t BOUND = 60000000;

    /* Count array for sums of two squares. Values capped at 8 to save
       memory (we only need to know whether the count is ≥8). */
    uint8_t *cnt = (uint8_t *)malloc(BOUND + 1);
    memset(cnt, 0, BOUND + 1);

    /* Enumerate unordered pairs (a,b) with a,b > 0, a <= b. */
    for (uint32_t a = 1; (uint64_t)a * a <= BOUND; ++a) {
        uint64_t a2 = (uint64_t)a * a;
        for (uint32_t b = a; (uint64_t)b * b + a2 <= BOUND; ++b) {
            uint64_t s = a2 + (uint64_t)b * b;
            if (cnt[(size_t)s] < 8) {   /* we only care about ≥8 */
                ++cnt[(size_t)s];
            }
        }
    }

    /* Count how many sums reach the threshold. */
    size_t count = 0;
    for (size_t i = 1; i <= BOUND; ++i)
        if (cnt[i] >= 8)
            ++count;

    /* Allocate the resulting sequence array. */
    seq_table = alloc_seq_array(count);
    seq_len   = (idx_t)count;

    size_t pos = 0;
    for (size_t i = 1; i <= BOUND; ++i)
        if (cnt[i] >= 8)
            seq_table[pos++] = (seq_t)i;

    free(cnt);
}

seq_t a(idx_t n)
{
    if (!seq_table) init_seq();          /* one‑time initialization */

    if (n == 0) return 0;                /* undefined below offset */

    if (n > seq_len)                    /* safety: should not happen */
        return seq_table[seq_len - 1];

    return seq_table[(size_t)(n - 1)];
}
