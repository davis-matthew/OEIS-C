/* Sequence A025613: numbers of the form 3^i * 4^j, i,j >= 0.
   The terms are generated by a simple two‑pointer merge of multiples
   of 3 and 4.  This algorithm yields the sorted sequence in O(n). */

#include <stdlib.h>
#include <stddef.h>

static seq_t *cache = NULL;   /* array of generated terms, 0‑based */
static size_t cache_len = 0;  /* number of terms stored in cache */
static size_t p3 = 0;         /* next position to multiply by 3   */
static size_t p4 = 0;         /* next position to multiply by 4   */

seq_t a(idx_t n)
{
    /* n is 1‑based; the first term is 1 */
    if (n == 0)
        return (seq_t)0;   /* undefined for n==0, but return 0 */

    size_t needed = (size_t)n;

    /* allocate or grow the cache if necessary */
    if (cache_len < needed) {
        /* at first call: allocate initial room */
        if (cache == NULL) {
            cache = (seq_t *)malloc(needed * sizeof(seq_t));
            if (cache == NULL)
                return (seq_t)0;          /* allocation failure (unlikely) */
            cache[0] = (seq_t)1;         /* a(1) = 1   */
            cache_len = 1;
            p3 = 0;
            p4 = 0;
        } else {
            cache = (seq_t *)realloc(cache, needed * sizeof(seq_t));
            if (cache == NULL)
                return (seq_t)0;          /* allocation failure */
        }

        /* generate remaining terms up to 'needed' */
        while (cache_len < needed) {
            seq_t mult3 = cache[p3] * (seq_t)3;
            seq_t mult4 = cache[p4] * (seq_t)4;

            seq_t next;
            if (mult3 < mult4) {
                next = mult3;
                ++p3;
            } else if (mult4 < mult3) {
                next = mult4;
                ++p4;
            } else {                  /* equal */
                next = mult3;
                ++p3;
                ++p4;
            }

            cache[cache_len++] = next;
        }
    }

    /* return the requested term (0‑based index) */
    return cache[n - 1];
}
