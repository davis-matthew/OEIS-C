/* Euclid–Mullin 7th term sequence (A094463)
 *
 * a(n) is the 7th term of the Euclid–Mullin prime sequence
 * started with the n-th prime (1‑based indexing).
 *
 * The sequence is generated by iterating:
 *   p1 = p_n
 *   p_{k+1} = smallest prime factor of (p1*p2*...*p_k + 1)
 *   return p7.
 *
 *  Implementation notes:
 *   - Uses trial division with a dynamically extended prime table.
 *   - Uses is_prime_big for final primality checks.
 *   - Works for any seq_t (uint8_t … big‑int) and idx_t (uint64_t).
 *   - No global state except static prime cache.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

#include "../utils/get_prime.h"
#include "../utils/floor_sqrt.h"
#include "../utils/build_primes_upto.h"
#include "../utils/is_prime_big.h"
#include "../utils/gcd.h"

/* static cache of primes for trial division */
static uint64_t *prime_cache = NULL;
static size_t prime_cache_cnt = 0;
static idx_t prime_cache_limit = 0;

/* ensure prime_cache contains all primes <= limit */
static void ensure_prime_cache(idx_t limit)
{
    if (prime_cache_limit >= limit)
        return;
    if (prime_cache) {
        free(prime_cache);
        prime_cache = NULL;
    }
    build_primes_upto(limit, &prime_cache, &prime_cache_cnt);
    prime_cache_limit = limit;
}

/* smallest prime factor of a seq_t number   (assumes n > 1) */
static seq_t smallest_prime_factor(seq_t n)
{
    if (is_prime_big(n))
        return n;
    if ((n % 2) == 0)
        return 2;
    idx_t sqrt_n = (idx_t)floor_sqrt(n);
    if (sqrt_n < 3)
        sqrt_n = 3;
    ensure_prime_cache(sqrt_n);
    for (size_t i = 0; i < prime_cache_cnt; ++i) {
        uint64_t p = prime_cache[i];
        if ((seq_t)p > sqrt_n + 1)
            break;
        if ((n % (seq_t)p) == 0)
            return (seq_t)p;
    }
    /* If no divisor found, n is prime (should not happen due to is_prime_big) */
    return n;
}

seq_t a(idx_t n)
{
    if (n < 1)
        return 0;   /* undefined for n < 1 */

    /* first term: the n-th prime */
    seq_t cur = (seq_t)get_prime(n);
    seq_t product = cur;

    for (int i = 1; i < 7; ++i) {
        seq_t val = product + 1;                   /* product + 1 */
        seq_t spf = smallest_prime_factor(val);    /* smallest prime factor */
        cur = spf;
        product = product * spf;                   /* update product */
    }
    return cur;   /* 7th term */
}
