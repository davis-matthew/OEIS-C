/* Sequence A094186: infinite binary word generated by
   starting with [0,1] and repeatedly appending the prefix
   of current sequence of length k, for k = 1,2,3,... */

/* Return the n-th term (1‑based).  values are 0 or 1. */
#include <stdlib.h>

seq_t a(idx_t n)
{
    /* handle the first two values explicitly */
    if (n == 1) return (seq_t)0;
    if (n == 2) return (seq_t)1;

    /* static cache to store the sequence */
    static seq_t *seq  = NULL;
    static size_t seq_cap = 0;
    static size_t seq_len = 0;
    static idx_t  next_k  = 1;  /* next prefix length to append */

    /* lazy initialization of the cache */
    if (seq == NULL) {
        seq_cap = 16;
        seq = (seq_t *)malloc(seq_cap * sizeof(seq_t));
        seq[0] = (seq_t)0;
        seq[1] = (seq_t)1;
        seq_len = 2;
    }

    /* extend the cache until it contains at least n elements */
    while (seq_len < n) {
        /* ensure enough capacity for the next append */
        while (seq_len + next_k > seq_cap) {
            size_t new_cap = seq_cap * 2;
            if (new_cap == 0) new_cap = 16;
            seq_t *tmp = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
            seq = tmp;
            seq_cap = new_cap;
        }
        /* copy the first next_k elements to the end */
        for (idx_t i = 0; i < next_k; ++i) {
            seq[seq_len + i] = seq[i];
        }
        seq_len += next_k;
        ++next_k;
    }

    return seq[n - 1];
}
