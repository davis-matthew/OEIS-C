/*
 * A059931  Numbers n such that n and n^(1/2) combined use different digits.
 * https://oeis.org/A059931
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, fini, full
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 18, u32 n <= 22, u64 n <= 22, u128 n <= 22,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Identification of n such that n is a perfect square and
   the decimal digits used by n and its integer square root are
   all distinct and disjoint.
   The sequence is generated by enumerating squares m^2 where
   both m and m^2 have no repeated digits and the digit sets
   are disjoint.  a(1)=4 is the first such square. */
#include <stdlib.h>
#include <stdint.h>
#include <stddef.h>

static seq_t *cache = NULL;   /* stored squares  */
static size_t cache_size = 0; /* number of stored terms */
static size_t cache_cap   = 0; /* allocated capacity of cache */
static seq_t  m_next = 1;     /* next integer whose square to test */

/* Return true and write the mask if x has all distinct digits.
   mask_out receives the bit mask of the digits of x. */
static inline int distinct_digits(seq_t x, uint32_t *mask_out)
{
    uint32_t mask = 0;
    if (x == 0) {
        *mask_out = 1u << 0;
        return 1;
    }
    while (x != (seq_t)0) {
        uint32_t d = (uint32_t)(x % 10);
        if (mask & (1u << d)) return 0;      /* duplicate digit */
        mask |= 1u << d;
        x = x / 10;
    }
    *mask_out = mask;
    return 1;
}

/* Extend the cache until it contains at least need terms. */
static void extend_cache(idx_t need)
{
    while (cache_size < (size_t)need) {
        seq_t m   = (seq_t)m_next;
        seq_t sq  = m * m;
        uint32_t mask_m, mask_sq;
        if (!distinct_digits(m, &mask_m) || !distinct_digits(sq, &mask_sq)
            || (mask_m & mask_sq) != 0) {
            /* not a record */
        } else {
            if (cache_size == cache_cap) {    /* grow cache */
                size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) abort();            /* allocation failure */
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_size++] = sq;
        }
        ++m_next;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for offset 0 */
    if (cache_size < (size_t)n) extend_cache(n);
    return cache[n-1];
}
