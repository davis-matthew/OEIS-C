/*
 * A103274  Number of ways of writing prime(n) in the form
 *          2*prime(i)+prime(j).
 * https://oeis.org/A103274
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1000, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   estimate_prime_upper_bound
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  This function computes A103274:  a(n) = number of ways of writing
    prime(n) in the form 2*prime(i)+prime(j).  It maintains a static
    list of primes large enough for the largest n requested.  For each
    n it counts pairs (i,j) with 2*p_i + p_j = prime(n).  The list of
    primes is generated by a simple sieve of Eratosthenes whenever the
    requested n exceeds the current list size.  The sieve array is
    reused as a primality flag array.  The algorithm runs in
    O(pi(p_n)) ≈ O(n log n) time per call, well under the limits for n≈10 000.  */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>
#include "../utils/estimate_prime_upper_bound.h"

/* static storage for primes and primality flags */
static uint64_t *prime_arr  = NULL;   /* list of prime values  */
static size_t   prime_cnt  = 0;       /* number of primes stored */
static size_t   prime_cap  = 0;       /* capacity of prime_arr   */
static uint8_t *prime_flag = NULL;   /* bit array: 1 = prime    */

/* enlarge the prime table until it contains at least 'need' primes */
static void ensure_primes(idx_t need)
{
    if (prime_cnt >= (size_t)need)
        return;

    /* approximate upper bound for the 'need'-th prime */
    uint64_t up = estimate_prime_upper_bound((uint64_t)need);
    if (up < 100) up = 100;                 /* minimal size */
    size_t limit = (size_t)up + 10;         /* safety margin */

    /* Allocate sieve array, initially all true (1) */
    uint8_t *sieve = (uint8_t *)malloc(limit + 1);
    if (!sieve) return;                    /* allocation failed */
    memset(sieve, 1, limit + 1);
    sieve[0] = 0; sieve[1] = 0;             /* 0 and 1 are not prime */

    /* Eratosthenes sieve */
    size_t sqrt_lim = (size_t)(sqrt((double)limit));
    for (size_t i = 2; i <= sqrt_lim; ++i) {
        if (!sieve[i]) continue;
        for (size_t j = i * i; j <= limit; j += i)
            sieve[j] = 0;
    }

    /* Count primes and store them */
    size_t cnt = 0;
    for (size_t i = 2; i <= limit; ++i)
        if (sieve[i]) ++cnt;

    /* Allocate (or resize) prime array if needed */
    if (prime_cap < cnt) {
        uint64_t *tmp = (uint64_t *)realloc(prime_arr, cnt * sizeof(uint64_t));
        if (!tmp) { free(sieve); return; } /* on failure keep old data */
        prime_arr = tmp;
        prime_cap = cnt;
    }

    /* Copy primes into prime_arr */
    size_t idx = 0;
    for (size_t i = 2; i <= limit && idx < cnt; ++i)
        if (sieve[i])
            prime_arr[idx++] = i;

    prime_cnt = cnt;
    /* Replace old flag array */
    free(prime_flag);
    prime_flag = sieve;     /* use sieve as the flag array */
}

/* Main sequence function */
seq_t a(idx_t n)
{
    if (n < 1) return 0; /* undefined for n < 1 */

    /* Ensure we have prime(n) available */
    ensure_primes((size_t)n);

    uint64_t pn = prime_arr[(size_t)n - 1];   /* prime(n) */

    /* Simple cases: no representations for primes <= 2 */
    if (pn <= 2) return 0;

    seq_t count = 0;
    /* For every prime i with 2*prime(i) <= pn-2 */
    for (size_t k = 0; k < prime_cnt; ++k) {
        uint64_t pi = prime_arr[k];
        uint64_t two_pi = pi * 2;
        if (two_pi > pn - 2) break;          /* further i will be too large */

        uint64_t r = pn - two_pi;            /* candidate prime(j) */
        if (prime_flag[r]) ++count;          /* primality test */
    }
    return count;
}
