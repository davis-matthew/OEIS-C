/*
 * A329566  For all n >= 0, exactly six sums are prime among a(n+i) + a(n+j),
 *          0 <= i < j < 6; lexicographically earliest such sequence of
 *          distinct nonnegative numbers.
 * https://oeis.org/A329566
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 84, u16 n <= 84, u32 n <= 84, u64 n <= 84, u128 n <= 84,
 *            big any n
 * Helpers:   isPrimeGeneric
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Return the lexicographically earliest sequence of distinct
   nonnegative integers a(n) such that for each n ≥ 0 exactly
   six of the fifteen pairwise sums of a(n),…,a(n+5) are prime.
   The sequence is generated by back‑tracking with memoisation;
   a(n) is found as the smallest unused integer that keeps
   the sixth‑term window containing exactly six primes. */

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include "../utils/isPrimeGeneric.h"

/* ----------------------------------------------------------------------
   Internal storage for the sequence and the set of numbers already
   used.  The "used" array is a simple bitset covering all values
   encountered so far; it is expanded lazily.  Since the
   permutation of non‑negative integers is conjectured, the values
   stay well below 2^64 for all n that can be reasonably required.
   ---------------------------------------------------------------------- */
static seq_t *seq_cache = NULL;
static size_t seq_len = 0;
static size_t seq_cap = 0;

static uint8_t *used_cache = NULL;
static size_t used_cap = 0;

/* ----------------------------------------------------------------------
   Resize helpers for the sequence and the used array.
   ---------------------------------------------------------------------- */
static void ensure_seq_capacity(size_t needed)
{
    if (needed >= seq_cap) {
        size_t new_cap = seq_cap ? seq_cap << 1 : 16;
        while (new_cap <= needed) new_cap <<= 1;
        seq_cache = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
        seq_cap = new_cap;
    }
}

static void ensure_used_capacity(size_t val)
{
    if (val >= used_cap) {
        size_t new_cap = used_cap ? used_cap << 1 : 64;
        while (new_cap <= val) new_cap <<= 1;
        used_cache = (uint8_t *)realloc(used_cache,
                                        new_cap * sizeof(uint8_t));
        /* initialise new region to 0 */
        memset(used_cache + used_cap, 0, new_cap - used_cap);
        used_cap = new_cap;
    }
}

/* ----------------------------------------------------------------------
   Count the number of prime sums within a 6‑element window.
   ---------------------------------------------------------------------- */
static int count_prime_sums(const seq_t *w)
{
    int cnt = 0;
    for (size_t i = 0; i < 5; ++i)
        for (size_t j = i + 1; j < 6; ++j)
            if (isPrimeGeneric(w[i] + w[j]))
                ++cnt;
    return cnt;
}

/* ----------------------------------------------------------------------
   Build the sequence up to (but excluding) index n.
   ---------------------------------------------------------------------- */
static void extend_to(idx_t n)
{
    while ((size_t)n >= seq_len) {
        size_t idx = seq_len;                 /* index to fill */
        size_t cand = 0;                       /* next candidate */
        seq_t window[6];

        /* Search for the first admissible candidate. */
        for (;;) {
            /* Skip numbers already used. */
            if (cand < used_cap && used_cache[cand]) {
                ++cand;
                continue;
            }

            /* If there is a complete window, test it. */
            if (idx >= 5) {
                /* copy the previous five values */
                for (size_t k = 0; k < 5; ++k)
                    window[k] = seq_cache[idx - 5 + k];
                window[5] = (seq_t)cand;           /* new last term */

                if (count_prime_sums(window) != 6) {
                    ++cand;
                    continue;
                }
            }
            /* candidate accepted */
            break;
        }

        /* Store the chosen value. */
        ensure_seq_capacity(seq_len + 1);
        seq_cache[seq_len++] = (seq_t)cand;

        /* Mark this value as used. */
        ensure_used_capacity(cand);
        used_cache[cand] = 1;
    }
}

/* ----------------------------------------------------------------------
   Public interface: return the nth term of the sequence.
   ---------------------------------------------------------------------- */
seq_t a(idx_t n)
{
    extend_to(n);
    return seq_cache[(size_t)n];
}
