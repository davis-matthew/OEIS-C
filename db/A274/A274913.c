/*
 * A274913  Square array read by antidiagonals upwards in which each new term
 *          is the least positive integer distinct from its neighbors.
 * https://oeis.org/A274913
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, tabl
 * Formula:   Implements A274913 by filling the square array by antidiagonals
 *            upward; each entry receives the smallest positive integer
 *            distinct from all already-assigned orthogonal and diagonal
 *            neighbors
 * Range:     u8 n <= 105, u16 n <= 105, u32 n <= 105, u64 n <= 105,
 *            u128 n <= 105, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <string.h>
#include <stdbool.h>

/* Returns the nth term (1‑based) of OEIS A274913.  The sequence is generated by
   constructing the square array in antidiagonal order and using the
   “least positive integer distinct from neighbors” rule.  The array is
   grown only as needed and cached between calls.  */
seq_t a(idx_t n)
{
    /* Static state for incremental construction */
    static idx_t  last_filled_d = 0;   /* largest diagonal fully computed */
    static idx_t  current_size  = 0;   /* current square dimension */
    static seq_t *grid          = NULL;/* one‑dimensional 1‑based storage */

    if (n < 1)           /* offset is 1; undefined for n < 1 */
        return 0;

    /* Determine the diagonal that contains the nth element:
       find smallest d with d(d+1)/2 >= n. */
    idx_t d = 1;
    idx_t tri = 1;                 /* triangular number for d */
    while (tri < n) {
        ++d;
        tri = d * (d + 1) / 2;
    }

    /* Grow the grid if necessary */
    if (d > current_size) {
        idx_t new_size = d;
        seq_t *new_grid = (seq_t *)malloc(new_size * new_size * sizeof(seq_t));
        if (!new_grid) exit(1);   /* allocation failure */
        memset(new_grid, 0, new_size * new_size * sizeof(seq_t));

        /* Copy existing data */
        if (grid) {
            for (idx_t r = 1; r <= current_size; ++r) {
                for (idx_t c = 1; c <= current_size; ++c) {
                    new_grid[(r - 1) * new_size + (c - 1)] =
                        grid[(r - 1) * current_size + (c - 1)];
                }
            }
            free(grid);
        }
        grid = new_grid;
        current_size = new_size;
    }

    /* Fill any diagonals that have not yet been populated. */
    while (last_filled_d < d) {
        ++last_filled_d;
        idx_t diag = last_filled_d;
        for (idx_t offset = 0; offset < diag; ++offset) {
            idx_t row = diag - offset;
            idx_t col = offset + 1;

            /* Compute linear index in the one‑dimensional array */
            size_t idx = (row - 1) * current_size + (col - 1);
            if (grid[idx] != 0)   /* already computed */
                continue;

            /* Gather values of all already-assigned neighbors */
            seq_t neigh[8];
            size_t ncnt = 0;
            static const int dr[8] = {-1, -1, -1, 0, 0,  1, 1, 1};
            static const int dc[8] = {-1,  0,  1,-1, 1, -1, 0, 1};

            for (int dir = 0; dir < 8; ++dir) {
                idx_t rr = row + dr[dir];
                idx_t cc = col + dc[dir];
                if (rr >= 1 && rr <= current_size &&
                    cc >= 1 && cc <= current_size) {
                    seq_t val =
                        grid[(rr - 1) * current_size + (cc - 1)];
                    if (val != 0)
                        neigh[ncnt++] = val;
                }
            }

            /* Find the smallest positive integer not in the neighbor set */
            seq_t cand = 1;
            while (true) {
                bool found = false;
                for (size_t k = 0; k < ncnt; ++k) {
                    if (neigh[k] == cand) {
                        found = true;
                        break;
                    }
                }
                if (!found)
                    break;
                ++cand;
            }

            grid[idx] = cand;
        }
    }

    /* Locate the requested element on diagonal 'd' */
    idx_t prev_tri = (d - 1) * d / 2;          /* terms before this diagonal */
    idx_t offset   = n - prev_tri - 1;        /* position within diagonal */
    idx_t row      = d - offset;
    idx_t col      = offset + 1;

    size_t idx = (row - 1) * current_size + (col - 1);
    return grid[idx];
}
