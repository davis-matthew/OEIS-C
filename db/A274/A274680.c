/* 
   OEIS A274680: Values of n such that 2*n+1 and 4*n+1 are triangular numbers.
   Computation method:
   - Set X = 2*l + 1, Y = 2*k + 1 where k, l satisfy 2n+1 = k(k+1)/2 and 4n+1 = l(l+1)/2.
   - These variables satisfy the Pell-type equation X^2 - 2 Y^2 = -9.
   - The fundamental solution is (X, Y) = (3, 3). All solutions are generated by
     (X_{t+1}, Y_{t+1}) = (3 X_t + 4 Y_t, 2 X_t + 3 Y_t).
   - The valid solutions correspond to Y ≡ 3 or 5 (mod 8) (ensuring k ≡ 1 or 2 (mod 4)).
   - For each valid Y the sequence term is n = (Y^2 - 9) / 16.
*/

#include <stdbool.h>

seq_t a(idx_t n)
{
    if (n == 1) return 0;          /* a(1) = 0 */

    idx_t target = n;
    seq_t X = 3, Y = 3;           /* first solution (X0, Y0) = (3, 3) */
    idx_t count = 1;              /* a(1) already counted */

    while (true) {
        /* next solution:  (X_{t+1}, Y_{t+1}) = (3X + 4Y, 2X + 3Y) */
        seq_t nextX = 3 * X + 4 * Y;
        seq_t nextY = 2 * X + 3 * Y;
        X = nextX;
        Y = nextY;

        seq_t mod8 = Y % 8;
        if (mod8 == 3 || mod8 == 5) {
            seq_t val = (Y * Y - 9) / 16;
            ++count;
            if (count == target) return val;
        }
    }
}
