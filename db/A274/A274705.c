/*
 * A274705  Rectangular array read by ascending antidiagonals. Row n has the
 *          exponential generating function 1/M_{n}(z^n) where M_{n}(z) is the
 *          n-th Mittag-Leffler function, nonzero coefficients only, for n>=1.
 * https://oeis.org/A274705
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  sign, tabl
 * Formula:   not stated
 * Range:     i8 n <= 11, i16 n <= 23, i32 n <= 32, i64 n <= 44, i128 n <= 44,
 *            big any n
 * Helpers:   binomial
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A274705 (rectangular array read by ascending antidiagonals).
   The value a(n) is R(m,j) where the m-th row is generated by the
   recurrence
        R(m,0) = 1
        R(m,n) = -∑_{k=0}^{n-1} binomial(m*n+1, m*k+1) * R(m,k)   (n≥1)
   The array is read by ascending antidiagonals: for each sum s=m+j
   (s≥1) all positions with that sum are output in order of increasing j
   (equivalently decreasing m).
   a(0)=1.                                     */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/binomial.h"

static seq_t **row_cache = NULL;      /* row_cache[m] -> array of R(m,*)   */
static size_t *row_len_arr = NULL;    /* length of each cached row        */
static size_t  cache_cap   = 0;        /* size of row_cache and row_len_arr */

/* Ensure that row m is computed up to index max_j (inclusive) and return
   the pointer to that row.  Row indices start at 1; index 0 of each row
   holds R(m,0)=1.  All memory allocations are cast to the proper type
   so the code compiles in both C11 and C++17. */
static seq_t *ensure_row(idx_t m, idx_t max_j)
{
    /* Grow the cache to accommodate row m, if necessary. */
    if ((size_t)m >= cache_cap) {
        size_t new_cap = (size_t)m + 1;
        row_cache   = (seq_t **)realloc(row_cache,   new_cap * sizeof(seq_t *));
        row_len_arr = (size_t *)realloc(row_len_arr, new_cap * sizeof(size_t));
        for (size_t i = cache_cap; i < new_cap; ++i) {
            row_cache[i]   = NULL;
            row_len_arr[i] = 0;
        }
        cache_cap = new_cap;
    }

    /* Never needed for m==0, but if it occurs just return NULL. */
    if (m == 0) return NULL;

    /* Create the row if it does not exist yet. */
    if (row_cache[m] == NULL) {
        row_cache[m]   = (seq_t *)calloc(1, sizeof(seq_t));   /* R(m,0)=1   */
        row_len_arr[m] = 1;
        row_cache[m][0] = (seq_t)1;
    }

    /* If the row already has the needed entries, just return it. */
    if (row_len_arr[m] > (size_t)max_j)
        return row_cache[m];

    /* Extend the row up to max_j. */
    size_t old_len = row_len_arr[m];
    row_cache[m] = (seq_t *)realloc(row_cache[m], (size_t)(max_j + 1) * sizeof(seq_t));

    for (idx_t i = (idx_t)old_len; i <= max_j; ++i) {
        if (i == 0) continue;          /* R(m,0)=1 already set */
        seq_t sum = (seq_t)0;
        for (idx_t k = 0; k < i; ++k) {
            idx_t a = m * i + 1;
            idx_t b = m * k + 1;
            seq_t coeff = binomial(a, b);
            sum += coeff * row_cache[m][k];
        }
        row_cache[m][i] = -sum;
    }
    row_len_arr[m] = (size_t)(max_j + 1);
    return row_cache[m];
}

/* Main accessor for the sequence.  Given the global index n (starting at
   0) it converts it to the corresponding (m,j) position in the
   anti‑diagonal traversal and returns R(m,j). */
seq_t a(idx_t n)
{
    /* Find the smallest s with t(s)=s*(s+1)/2 > n.  This is the sum
       (row index + column index) of the element a(n). */
    idx_t s = 1;
    while ((s * (s + 1) / 2) <= n)
        ++s;

    /* The first index of this diagonal is at cumulative count
       prev_tri = (s-1)*s/2. */
    idx_t prev_tri = (s - 1) * s / 2;
    idx_t t = n - prev_tri;          /* offset within the diagonal (0‑based) */
    idx_t j = t;                      /* column index            */
    idx_t m = s - j;                  /* row index (>=1)         */

    seq_t *row = ensure_row(m, j);
    return row[j];
}
