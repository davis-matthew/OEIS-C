/*
 * A274280  Numbers that are a product of distinct Lucas numbers
 *          (1,3,4,7,11,...)
 * https://oeis.org/A274280
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 148, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS sequence A274280
    Numbers that are a product of distinct Lucas numbers
    (1,3,4,7,11,18,29,...)
    The sequence is generated by maintaining all products of
    Lucas numbers with strictly increasing indices in a min‑heap.
*/

#include <stddef.h>
#include <stdlib.h>
#include <limits.h>

static inline int cmp_seq_t(const void *p, const void *q) {
    const seq_t *a = (const seq_t *)p;
    const seq_t *b = (const seq_t *)q;
    if (*a < *b) return -1;
    if (*a > *b) return  1;
    return 0;
}

/*------------------------------------------------------------------*/
/* Node used in the heap: product value and indices describing the
   combination that produced it (seq_pos : index of base product in
   seq_vals, gen_idx : index of Lucas factor used). */
typedef struct {
    seq_t val;
    size_t seq_pos;   /* index into seq_vals of the base product   */
    size_t gen_idx;   /* index in lucas[] of the Lucas factor used */
} Node;

/*------------------------------------------------------------------*/
/* Pre‑computed Lucas numbers (starting with L2=3).  Forty terms
   are easily sufficient for n up to ~10000. */
#define LUCAS_CNT 40
static seq_t lucas[LUCAS_CNT];

/*------------------------------------------------------------------*/
/* Sequence storage */
static seq_t *seq_vals   = NULL;   /* 1‑based values: seq_vals[0] = 1   */
static size_t *last_gen = NULL;   /* last generator used for each value */
static size_t seq_cap   = 0;
static size_t seq_len   = 0;

/*------------------------------------------------------------------*/
/* Heap for generating the next smallest product */
static Node *heap      = NULL;
static size_t heap_cap = 0;
static size_t heap_size = 0;

static inline void heap_swap(Node *a, Node *b) {
    Node t = *a; *a = *b; *b = t;
}

static void heap_push(Node n) {
    if (heap_size == heap_cap) {
        size_t newcap = heap_cap ? heap_cap << 1 : 64;
        Node *tmp = (Node *)realloc(heap, newcap * sizeof(Node));
        if (!tmp) abort();   /* critical failure */
        heap  = tmp;
        heap_cap = newcap;
    }
    size_t i = heap_size++;
    heap[i] = n;
    while (i) {
        size_t p = (i - 1) >> 1;
        if (cmp_seq_t(&heap[i].val, &heap[p].val) < 0) {
            heap_swap(&heap[i], &heap[p]);
            i = p;
        } else break;
    }
}

static Node heap_pop(void) {
    Node min = heap[0];
    if (--heap_size) {
        heap[0] = heap[heap_size];
        size_t i = 0;
        while (1) {
            size_t l = (i << 1) + 1, r = l + 1;
            if (l >= heap_size) break;
            size_t s = l;
            if (r < heap_size &&
                cmp_seq_t(&heap[r].val, &heap[l].val) < 0)
                s = r;
            if (cmp_seq_t(&heap[s].val, &heap[i].val) < 0) {
                heap_swap(&heap[i], &heap[s]);
                i = s;
            } else break;
        }
    }
    return min;
}

/*------------------------------------------------------------------*/
/* Initialize Lucas numbers */
static void init_lucas(void) {
    static int done = 0;
    if (done) return;
    done = 1;
    seq_t a = 2, b = 1, c;
    for (size_t i = 0; i < LUCAS_CNT; ++i) { /* compute L2, L3, ... */
        c = a + b;
        lucas[i] = c;
        a = b; b = c;
    }
}

/*------------------------------------------------------------------*/
/* Initialize sequence storage and first heap node */
static void init_sequence(void) {
    static int done = 0;
    if (done) return;
    done = 1;

    seq_cap = 64;
    seq_vals = (seq_t *)malloc(seq_cap * sizeof(seq_t));
    last_gen = (size_t *)malloc(seq_cap * sizeof(size_t));
    seq_len = 1;
    seq_vals[0] = 1;                     /* first term            */
    last_gen[0] = SIZE_MAX;               /* no generator used    */

    /* first candidate: 1 * lucas[0] = 3 */
    Node n = { .val = seq_vals[0] * lucas[0],
               .seq_pos = 0,
               .gen_idx = 0 };
    heap_push(n);
}

/*------------------------------------------------------------------*/
/* Expand sequence until it contains at least n elements */
static void expand_to(idx_t n) {
    while (seq_len < (size_t)n) {
        Node cur = heap_pop();
        seq_t cur_val = cur.val;

        /* skip duplicates */
        if (cur_val == seq_vals[seq_len - 1]) {
            /* generate next for same base product */
            if (cur.gen_idx + 1 < LUCAS_CNT) {
                Node nxt = { .val = seq_vals[cur.seq_pos] * lucas[cur.gen_idx + 1],
                             .seq_pos = cur.seq_pos,
                             .gen_idx = cur.gen_idx + 1 };
                heap_push(nxt);
            }
            continue;
        }

        /* add new value to sequence */
        if (seq_len == seq_cap) {
            size_t newcap = seq_cap << 1;
            seq_t *tmpv = (seq_t *)realloc(seq_vals, newcap * sizeof(seq_t));
            size_t *tmpg = (size_t *)realloc(last_gen, newcap * sizeof(size_t));
            if (!tmpv || !tmpg) abort();
            seq_vals = tmpv; last_gen = tmpg; seq_cap = newcap;
        }
        seq_vals[seq_len]    = cur_val;
        last_gen[seq_len]    = cur.gen_idx;
        ++seq_len;

        /* generate next candidate for same base product */
        if (cur.gen_idx + 1 < LUCAS_CNT) {
            Node nxt = { .val = seq_vals[cur.seq_pos] * lucas[cur.gen_idx + 1],
                         .seq_pos = cur.seq_pos,
                         .gen_idx = cur.gen_idx + 1 };
            heap_push(nxt);
        }

        /* generate first candidate for the new product itself */
        size_t newpos = seq_len - 1;           /* index of newly added value */
        size_t next_gen = last_gen[newpos] + 1;
        if (next_gen < LUCAS_CNT) {
            Node nxt = { .val = seq_vals[newpos] * lucas[next_gen],
                         .seq_pos = newpos,
                         .gen_idx = next_gen };
            heap_push(nxt);
        }
    }
}

/*------------------------------------------------------------------*/
/* Public API: returns the n‑th term (1‑based) */
seq_t a(idx_t n) {
    if (n < 1) return 0;          /* undefined for n < 1 */
    init_lucas();
    init_sequence();
    expand_to(n);
    return seq_vals[n - 1];
}
