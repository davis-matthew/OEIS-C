/*
 * A274255  Numbers n such that n^2 is the sum of three nonzero squares while
 *          n is not.
 * https://oeis.org/A274255
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 53, u16 n <= 57, u32 n <= 57, u64 n <= 57, u128 n <= 57,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence of numbers n such that n^2 is the sum of three nonzero squares
   while n itself is not. The sequence is generated by testing integers in
   increasing order and keeping those that satisfy the condition. */
#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* Integer square root for 64‑bit unsigned integers (floor(sqrt(x))). */
static uint64_t isqrt_u64(uint64_t x)
{
    uint64_t lo = 0;
    uint64_t hi = (uint64_t)1 << 32;        /* sqrt(UINT64_MAX) < 2^32 */
    while (lo < hi) {
        uint64_t mid = (lo + hi) >> 1;
        if (mid <= x / mid)          /* mid*mid <= x without overflow */
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

/* Test if a positive integer m has a representation m = a² + b² + c²
   with a,b,c ≥ 1. Only 64‑bit arithmetic is used; this is sufficient
   for the range needed by the sequence. */
static bool has_three_nonzero_squares_u64(uint64_t m)
{
    if (m < 3) return false;                  /* smallest sum is 1+1+1=3 */
    uint64_t a_limit = isqrt_u64(m);
    for (uint64_t a = 1; a <= a_limit; ++a) {
        uint64_t a2 = a * a;
        if (m <= a2) break;                   /* remaining part would be ≤0 */
        uint64_t rem1 = m - a2;
        if (rem1 < 2) continue;               /* need at least 1² + 1² */

        uint64_t b_limit = isqrt_u64(rem1);
        for (uint64_t b = a; b <= b_limit; ++b) {
            uint64_t b2 = b * b;
            if (rem1 <= b2) break;
            uint64_t rem2 = rem1 - b2;
            if (rem2 == 0) continue;          /* c would be zero */
            uint64_t c = isqrt_u64(rem2);
            if (c * c == rem2 && c >= 1)
                return true;
        }
    }
    return false;
}

/* Dynamic cache of sequence values. */
static seq_t *seq_cache = NULL;
static size_t seq_len = 0;        /* number of cached terms */
static size_t seq_cap = 0;        /* allocated capacity */
static uint64_t next_candidate = 1;  /* next integer to test */

/* Allocate more space for the cache. */
static void grow_cache(size_t needed)
{
    size_t new_cap = seq_cap ? seq_cap * 2 : 16;
    while (new_cap < needed) new_cap *= 2;
    seq_cache = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    seq_cap = new_cap;
}

/* Ensure that at least n terms are cached (1‑based). */
static void ensure_terms(idx_t n)
{
    if (seq_len >= (size_t)n) return;

    while (seq_len < (size_t)n) {
        /* Find next candidate satisfying the definition. */
        for (;;) {
            ++next_candidate;
            bool x = has_three_nonzero_squares_u64(next_candidate);
            bool y = has_three_nonzero_squares_u64((uint64_t)next_candidate *
                                                   (uint64_t)next_candidate);
            if (!x && y) {
                if (seq_len == seq_cap) grow_cache(seq_len + 1);
                seq_cache[seq_len++] = (seq_t)next_candidate;
                break;
            }
        }
    }
}

/* Public sequence function. */
seq_t a(idx_t n)
{
    ensure_terms(n);
    return seq_cache[n - 1];
}
