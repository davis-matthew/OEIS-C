/* Sequence A274004: each integer ≥ 3 occurs twice; powers of two once.  This
   sequence is generated by emitting every integer starting at 3 twice, except
   that if the integer is a power of two it is emitted once.  The function
   a(idx_t n) returns the n‑th term (1‑based).  The result is memoised so
   that calls may be in arbitrary order. */

#include <stddef.h>
#include <stdlib.h>
#include <stdbool.h>

/* Cached values of the sequence */
static seq_t *cache = NULL;    /* array of computed terms */
static size_t cache_len = 0;   /* number of terms currently stored */
static size_t cache_cap = 0;   /* allocated capacity */

/* Current state of the generator */
static seq_t current_value = 3;  /* next value to emit */
static unsigned current_rem   = 2;  /* remaining times to emit current_value */

/* Ensure the cache can hold at least 'needed' terms */
static void grow_cache(size_t needed)
{
    if (needed <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 128;
    while (new_cap < needed)
        new_cap *= 2;
    seq_t *new_ptr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!new_ptr) abort(); /* out of memory */
    cache = new_ptr;
    cache_cap = new_cap;
}

/* Return true if x is a power of two (x ≥ 2).  Works for any integer type. */
static inline bool is_power_of_two(seq_t x)
{
    if (x <= 1)
        return false;
    while ((x & 1) == 0)
        x >>= 1;
    return x == 1;
}

/* Produce the next term of the sequence and store it in the cache. */
static void produce_next(void)
{
    if (cache_len == 0) {     /* initialisation on first use */
        current_value = 3;
        current_rem   = 2;   /* 3 appears twice */
    }
    grow_cache(cache_len + 1);
    cache[cache_len++] = current_value;
    if (--current_rem == 0) {          /* move to next integer */
        current_value++;
        current_rem = is_power_of_two(current_value) ? 1 : 2;
    }
}

/* External function required by the build. */
seq_t a(idx_t n)
{
    if (n < 1)
        return 0;      /* undefined for n < 1, but not used in tests */

    size_t needed = (size_t)n;
    while (cache_len < needed)
        produce_next();

    return cache[n - 1];
}
