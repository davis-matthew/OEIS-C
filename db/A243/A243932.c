/*
 * A243932  Positive integers with the same number of twin divisors as
 *          non-twin divisors.
 * https://oeis.org/A243932
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 34, u16 n <= 2518, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implementation of OEIS A243932: numbers with equal numbers of twin
   divisors and non‑twin divisors.  The series is generated by
   searching the natural numbers in ascending order and checking the
   divisor condition.  No external tables are used and the search
   works for any order of calls. */ 

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>

/* ---------- helper : enumerate all divisors and count twin status ---------- */
static void gen_divisors(int pos, uint64_t cur, uint64_t orig,
                         uint64_t *twin, uint64_t *total,
                         uint64_t primes[], int exps[], int cnt)
{
    if (pos < 0) {
        (*total)++;
        bool isTwin = false;
        if (cur > 2 && orig % (cur - 2) == 0) isTwin = true;
        if (cur + 2 <= orig && orig % (cur + 2) == 0) isTwin = true;
        if (isTwin) (*twin)++;
        return;
    }

    uint64_t p   = primes[pos];
    int     e    = exps[pos];
    uint64_t pw  = cur;                 /* exponent 0 */
    gen_divisors(pos - 1, pw, orig, twin, total, primes, exps, cnt);

    for (int i = 1; i <= e; ++i)        /* exponents 1..e */
    {
        pw *= p;
        gen_divisors(pos - 1, pw, orig, twin, total, primes, exps, cnt);
    }
}

static bool has_equal_twin_non_twin(uint64_t n)
{
    uint64_t twin = 0, total = 0;
    uint64_t primes[64];
    int     exps[64];
    int     cnt = 0;

    /*  factorisation of n  */
    uint64_t temp = n;
    if (temp > 1) {
        if (temp % 2 == 0) {
            int e = 0;
            while (temp % 2 == 0) { temp /= 2; ++e; }
            primes[cnt] = 2;  exps[cnt] = e;  ++cnt;
        }
        for (uint64_t i = 3; i <= temp / i; i += 2) {
            if (temp % i == 0) {
                int e = 0;
                while (temp % i == 0) { temp /= i; ++e; }
                primes[cnt] = i;  exps[cnt] = e;  ++cnt;
            }
        }
        if (temp > 1) {                         /* remaining prime > sqrt */
            primes[cnt] = temp;  exps[cnt] = 1;  ++cnt;
        }
    }

    /*  enumerate all divisors and count twin status  */
    gen_divisors(cnt - 1, 1, n, &twin, &total, primes, exps, cnt);

    return twin == (total - twin);
}

/* ---------- sequence storage and generator ---------- */
static seq_t *seq_cache = NULL;
static idx_t  seq_len   = 0;
static idx_t  seq_cap   = 0;
static uint64_t next_to_check = 1;

/*  Return the nth term (a(1)=first term) of A243932.  */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;           /* out of range for this sequence */

    /* Allocate cache on first call */
    if (seq_cache == NULL) {
        seq_len   = 0;
        seq_cap   = 0;
    }

    /* Find terms until we have at least n of them */
    while (seq_len < n) {
        uint64_t cand = next_to_check;
        if (has_equal_twin_non_twin(cand)) {
            if (seq_len == seq_cap) {
                size_t new_cap = seq_cap ? seq_cap * 2 : 1;
                seq_t *tmp = (seq_t *)realloc(seq_cache,
                                              new_cap * sizeof(seq_t));
                if (!tmp) abort();          /* out‑of‑memory */
                seq_cache = tmp;
                seq_cap   = new_cap;
            }
            seq_cache[seq_len++] = (seq_t)cand;
        }
        ++cand;
        next_to_check = cand;
    }

    return seq_cache[n - 1];
}
