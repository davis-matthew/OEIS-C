/*
 * A243064  Numbers n such that k*n/(k+n) and k*n/(k-n) are integers for only
 *          one k > 0.
 * https://oeis.org/A243064
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 62, u16 n <= 62, u32 n <= 62, u64 n <= 62, u128 n <= 62,
 *            big any n
 * Helpers:   count_k, gcd_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A243064
   Numbers n such that k*n/(k+n) and k*n/(k-n) are integers for
   exactly one k > 0.  The term a(n) is the n‑th such
   number (offset 1).  The implementation counts, for each integer
   n, how many pairs (a,b) with gcd(a,b)=1, a≠b exist such that
   n = b·m and lcm(a+b,|a-b|) divides m.  Each such pair
   gives one admissible k = a·m.  The sequence is generated by
   scanning n upward until the requested index is reached. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/count_k.h"
#include "../utils/gcd_u64.h"

/* --- helpers --------------------------------------------------- */

/* Return true iff n has exactly one admissible k */
static bool is_valid(uint64_t n)
{
    return count_k(n) == 1;
}

/* --- sequence function ------------------------------------------------ */
static seq_t *terms = NULL;
static size_t terms_len = 0;
static size_t terms_cap = 0;

static void ensure_capacity(size_t needed)
{
    if (terms_cap < needed) {
        size_t newcap = terms_cap == 0 ? 16 : terms_cap * 2;
        while (newcap < needed) newcap *= 2;
        seq_t *tmp = (seq_t *)realloc(terms, newcap * sizeof(seq_t));
        if (!tmp) exit(EXIT_FAILURE);
        terms = tmp;
        terms_cap = newcap;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined for n = 0, guard */
    if (terms_len < (size_t)n) {
        ensure_capacity(n);
        uint64_t candidate = terms_len == 0 ? 3 : (uint64_t)terms[terms_len - 1] + 1;
        while (terms_len < (size_t)n) {
            /* search next valid n */
            while (!is_valid(candidate)) ++candidate;
            terms[terms_len++] = (seq_t)candidate;
            ++candidate;
        }
    }
    return terms[n - 1];
}
