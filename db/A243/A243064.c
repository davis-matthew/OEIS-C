/* Sequence A243064
   Numbers n such that k*n/(k+n) and k*n/(k-n) are integers for
   exactly one k > 0.  The term a(n) is the n‑th such
   number (offset 1).  The implementation counts, for each integer
   n, how many pairs (a,b) with gcd(a,b)=1, a≠b exist such that
   n = b·m and lcm(a+b,|a-b|) divides m.  Each such pair
   gives one admissible k = a·m.  The sequence is generated by
   scanning n upward until the requested index is reached. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/gcd_u64.h"
#include "../utils/mem.h"

/* Count how many k satisfy the conditions for a given n */
static uint64_t count_k(uint64_t n)
{
    uint64_t cnt = 0;
    /* iterate over all divisors b of n */
    for (uint64_t i = 1; (unsigned __int128)i * i <= n; ++i) {
        if (n % i) continue;
        uint64_t ds[2] = { i, n / i };
        for (int di = 0; di < 2; ++di) {
            uint64_t b = ds[di];
            uint64_t d = n / b;          /* m = n/b */
            /* cases with a > b */
            for (uint64_t a = b + 1; ; ++a) {
                uint64_t s = a + b;
                uint64_t t = a - b;
                uint64_t g_ab = gcd_u64(a, b);
                if (g_ab != 1) continue;
                uint64_t g_st = gcd_u64(s, t);
                unsigned __int128 l128 = (unsigned __int128)(s / g_st) * t;
                if (l128 > d) break;   /* l increases with a */
                uint64_t l = (uint64_t)l128;
                if (d % l == 0) {
                    ++cnt;
                    if (cnt > 1) return cnt;   /* early exit */
                }
            }
            /* cases with a < b */
            for (uint64_t a = 1; a < b; ++a) {
                uint64_t g_ab = gcd_u64(a, b);
                if (g_ab != 1) continue;
                uint64_t s = a + b;
                uint64_t t = b - a;
                uint64_t g_st = gcd_u64(s, t);
                unsigned __int128 l128 = (unsigned __int128)(s / g_st) * t;
                if (l128 > d) continue;   /* l too large */
                uint64_t l = (uint64_t)l128;
                if (d % l == 0) {
                    ++cnt;
                    if (cnt > 1) return cnt;
                }
            }
        }
    }
    return cnt;
}

/* --- helpers --------------------------------------------------- */

/* Return true iff n has exactly one admissible k */
static bool is_valid(uint64_t n)
{
    return count_k(n) == 1;
}

/* --- sequence function ------------------------------------------------ */
static seq_t *terms = NULL;
static size_t terms_len = 0;
static size_t terms_cap = 0;

static void ensure_capacity(size_t needed)
{
    if (terms_cap < needed) {
        size_t newcap = terms_cap == 0 ? 16 : terms_cap * 2;
        while (newcap < needed) newcap *= 2;
        seq_t *tmp = mem_resize(seq_t, terms, newcap);
        if (!tmp) exit(EXIT_FAILURE);
        terms = tmp;
        terms_cap = newcap;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined for n = 0, guard */
    if (terms_len < (size_t)n) {
        ensure_capacity(n);
        uint64_t candidate = terms_len == 0 ? 3 : (uint64_t)terms[terms_len - 1] + 1;
        while (terms_len < (size_t)n) {
            /* search next valid n */
            while (!is_valid(candidate)) ++candidate;
            terms[terms_len++] = (seq_t)candidate;
            ++candidate;
        }
    }
    return terms[n - 1];
}
