/*
 * A243604  Number of length n+2 0..7 arrays with no three elements in a row
 *          with pattern aba (with a!=b) and new values 0..7 introduced in
 *          0..7 order.
 * https://oeis.org/A243604
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 4, u16 n <= 8, u32 n <= 14, u64 n <= 25, u128 n <= 48,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A243604
   a(1) = 4, a(2) = 10, a(3) = 29, ...
   Recurrence provided by OEIS, but the sequence is best generated by a
   DP that keeps the three last symbols and the current maximum symbol.
   The DP ensures that the alphabet is introduced in order (0,1,2,…)
   and that the pattern a b a with a≠b never appears in a row. */

#include <stdlib.h>
#include <stdint.h>
#include <string.h>

#define K_MAX      8                    /* alphabet size (0..7)         */
#define SENTINEL   8                    /* value for "no previous"     */
#define STATE_C    (K_MAX + 1)          /* values: 0..7 plus sentinel   */
#define STATE_COUNT (K_MAX * STATE_C * STATE_C)

/* External types supplied by the build */
seq_t a(idx_t n)
{
    /* Static memoisation state */
    static seq_t *terms = NULL;          /* 1‑indexed table of a(1)…   */
    static size_t terms_cap = 0;         /* allocated size‑1            */
    static idx_t  computed_up_to = 0;    /* highest n already known     */

    static seq_t *cur  = NULL;           /* DP array for current length */
    static seq_t *next = NULL;           /* DP array for next length    */
    static idx_t   cur_len = 0;          /* length processed so far     */

    /* Initialise DP arrays on first call */
    if (!cur) {
        cur  = (seq_t *)calloc(STATE_COUNT, sizeof(seq_t));
        next = (seq_t *)calloc(STATE_COUNT, sizeof(seq_t));
        if (!cur || !next) return 0;    /* allocation failed           */
        /* Start with length 0: only sentinel values, max 0 */
        cur[((0 * STATE_C + SENTINEL) * STATE_C) + SENTINEL] = 1;
        cur_len = 0;
    }

    /* Grow the terms table if necessary */
    if (n > terms_cap) {
        size_t new_cap = terms_cap ? terms_cap * 2 : 16;
        while (new_cap < n + 1) new_cap <<= 1;
        seq_t *tmp = (seq_t *)realloc(terms, (new_cap + 1) * sizeof(seq_t));
        if (!tmp && new_cap) return 0;  /* allocation failed */
        terms = tmp;
        terms_cap = new_cap;
    }

    /* Return already known value */
    if (n <= computed_up_to) return terms[n];

    /* Extend DP computation up to length n+2 */
    idx_t target_len = n + 2;            /* number of symbols in the array */
    for (idx_t step = cur_len; step < target_len; ++step) {
        /* clear next array */
        memset(next, 0, STATE_COUNT * sizeof(seq_t));

        /* Transition all states from length “step” to “step+1” */
        for (size_t idx = 0; idx < STATE_COUNT; ++idx) {
            seq_t cur_val = cur[idx];
            if (!cur_val) continue;

            /* decode state: ((k * STATE_C + a) * STATE_C) + b */
            size_t tmp = idx;
            size_t b = tmp % STATE_C;          tmp /= STATE_C;
            size_t a = tmp % STATE_C;          tmp /= STATE_C;
            size_t k = tmp;                    /* 0 ≤ k ≤ 7 */

            /* ----- Candidate 1: use an existing symbol 0..k ----- */
            for (size_t c = 0; c <= k; ++c) {
                /* forbid pattern a b a with a≠b */
                if (a != SENTINEL && b != SENTINEL &&
                    a != b && a == c)
                    continue;

                size_t newk = k;
                size_t newa = b;
                size_t newb = c;
                size_t new_idx = ((newk * STATE_C + newa) * STATE_C) + newb;
                next[new_idx] += cur_val;
            }

            /* ----- Candidate 2: introduce a new symbol (k+1) ----- */
            if (k + 1 < K_MAX) {
                /* New symbol cannot appear before the very first element */
                if (!(a == SENTINEL && b == SENTINEL)) {
                    size_t c = k + 1;
                    /* The pattern check is irrelevant here because c > k,
                       hence c cannot equal a if a < k. */
                    size_t newk = c;
                    size_t newa = b;
                    size_t newb = c;
                    size_t new_idx = ((newk * STATE_C + newa) * STATE_C) + newb;
                    next[new_idx] += cur_val;
                }
            }
        }

        /* Swap cur and next for next iteration */
        seq_t *tmp_ptr = cur;
        cur = next;
        next = tmp_ptr;

        /* After step+1 elements processed, we may have a new sequence value */
        if (step + 1 >= 3) { /* length ≥ 3 corresponds to a(n) with n=step-1 */
            idx_t term_idx = step - 1; /* n value */
            seq_t sum = 0;
            for (size_t i = 0; i < STATE_COUNT; ++i)
                sum += cur[i];
            terms[term_idx] = sum;
            if (term_idx > computed_up_to)
                computed_up_to = term_idx;
        }
    }

    cur_len = target_len;
    return terms[n];
}
