/*
 * A280875  Set a(1)=0, a(2)=1, a(3)=3; b(1)=1, b(2)=2; c(1)=3. Thereafter,
 *          a(n) is the smallest positive integer m such that m is not yet in
 *          sequence a, m-a(n-1) is not yet in sequence b, and m-a(n-2) is not
 *          yet in sequence c; set b(n-1)=m-a(n-1), c(n-2)=m-a(n-2).
 * https://oeis.org/A280875
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 148, u16 n <= 999, u32 n <= 999, u64 n <= 999,
 *            u128 n <= 999, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Implementation of OEIS sequence A280875.
   The sequence is generated by a greedy search:
   a(1)=0, a(2)=1, a(3)=3.
   For n≥4, a(n) is the smallest positive m such that
     (1) m is not yet in a,
     (2) m-a(n-1) is not yet in b,
     (3) m-a(n-2) is not yet in c,
   after which b(n-1)=m-a(n-1) and c(n-2)=m-a(n-2) are appended. */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

/* Static storage for the sequences.  All arrays grow lazily. */
static seq_t  *A = NULL;      /* sequence a */
static size_t A_cap = 0, A_len = 0;

static intmax_t *B = NULL;    /* sequence b (can be negative) */
static size_t B_cap = 0, B_len = 0;

static intmax_t *C = NULL;    /* sequence c (can be negative) */
static size_t C_cap = 0, C_len = 0;

/* Ensure B and C have at least 'needed' capacity. */
static void ensure_A(size_t needed) {
    if (needed <= A_cap) return;
    size_t new_cap = A_cap ? A_cap * 2 : 8;
    while (new_cap < needed) new_cap <<= 1;
    A = (seq_t*)realloc(A, new_cap * sizeof(seq_t));
    A_cap = new_cap;
}

static void ensure_B(size_t needed) {
    if (needed <= B_cap) return;
    size_t new_cap = B_cap ? B_cap * 2 : 8;
    while (new_cap < needed) new_cap <<= 1;
    B = (intmax_t*)realloc(B, new_cap * sizeof(intmax_t));
    B_cap = new_cap;
}

static void ensure_C(size_t needed) {
    if (needed <= C_cap) return;
    size_t new_cap = C_cap ? C_cap * 2 : 8;
    while (new_cap < needed) new_cap <<= 1;
    C = (intmax_t*)realloc(C, new_cap * sizeof(intmax_t));
    C_cap = new_cap;
}

/* Linear searches for membership. */
static bool contains_A(seq_t val) {
    for (size_t i = 0; i < A_len; ++i)
        if (A[i] == val) return true;
    return false;
}

static bool contains_B(intmax_t val) {
    for (size_t i = 0; i < B_len; ++i)
        if (B[i] == val) return true;
    return false;
}

static bool contains_C(intmax_t val) {
    for (size_t i = 0; i < C_len; ++i)
        if (C[i] == val) return true;
    return false;
}

/* Main function that implements the OEIS sequence. */
seq_t a(idx_t n) {
    if (n < 1) return (seq_t)0;         /* undefined for n<1 */

    /* Grow the stored sequences until we have a(n). */
    while (A_len < n) {
        /* Initialise base values. */
        if (A_len == 0) {
            ensure_A(1);
            A[0] = (seq_t)0;
            A_len = 1;
            continue;
        }
        if (A_len == 1) {
            ensure_A(2);
            A[1] = (seq_t)1;
            A_len = 2;
            continue;
        }
        if (A_len == 2) {
            ensure_A(3);
            A[2] = (seq_t)3;
            A_len = 3;

            /* initialise b and c sequences. */
            ensure_B(2);
            B[0] = 1;
            B[1] = 2;
            B_len = 2;

            ensure_C(1);
            C[0] = 3;
            C_len = 1;
            continue;
        }

        /* Compute the next value of a. */
        seq_t m = 1;
        seq_t a_prev1 = A[A_len - 1];   /* a(n-1) */
        seq_t a_prev2 = A[A_len - 2];   /* a(n-2) */

        while (true) {
            if (!contains_A(m)) {
                intmax_t d1 = (intmax_t)m - (intmax_t)a_prev1;
                intmax_t d2 = (intmax_t)m - (intmax_t)a_prev2;
                if (!contains_B(d1) && !contains_C(d2))
                    break;               /* found the required m */
            }
            ++m;
        }

        /* Append the new values to the sequences. */
        ensure_A(A_len + 1);
        A[A_len++] = m;

        ensure_B(B_len + 1);
        B[B_len++] = (intmax_t)m - (intmax_t)a_prev1;

        ensure_C(C_len + 1);
        C[C_len++] = (intmax_t)m - (intmax_t)a_prev2;
    }

    return A[n - 1];
}
