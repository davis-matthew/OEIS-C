/*
 * A032943  Numbers whose base-8 representation Sum_{i=0..m} d(i)*8^(m-i) has
 *          d(i)=0 for all odd i.
 * https://oeis.org/A032943
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) is the nth positive integer whose base‑8 representation has
 *            digit 0 in every odd position when the most significant digit
 *            has index 0
 * Range:     u8 n <= 38, u16 n <= 638, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence can be generated by iterating natural numbers 1,2,3,…
   and selecting those that satisfy the criterion.  For n up to 10 000
   this scan is well under the time limit. */

#include <stdbool.h>

seq_t a(idx_t n)
{
    idx_t found = 0;          /* how many valid numbers found so far    */
    for (idx_t cur = 1; ; ++cur)  /* scan all positive integers             */
    {
        /* Convert cur to base‑8 digits stored least‑significant first.   */
        idx_t tmp = cur;
        int digits[32];   /* enough for 8^20 > 2^64 */
        int dcnt = 0;     /* number of digits (L)          */

        while (tmp > 0) {
            digits[dcnt++] = (int)(tmp % 8);
            tmp /= 8;
        }

        /* Check the odd‑position condition. */
        bool ok = true;
        for (int i = 0; i < dcnt && ok; ++i) {
            /* index from the most significant digit = dcnt-1-i   */
            if ( ((dcnt - 1 - i) & 1) != 0 )      /* odd position   */
                if (digits[i] != 0)
                    ok = false;
        }

        if (ok) {
            ++found;
            if (found == n)
                return (seq_t)cur;   /* cast to seq_t is safe here */
        }
    }
}
