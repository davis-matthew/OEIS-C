/*
 * A032850  Numbers whose base-3 representation Sum_{i=0..m} d(i)*3^i has d(m)
 *          <= d(m-1) >= d(m-2) <= ...
 * https://oeis.org/A032850
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) = nth number whose base‑3 representation has digits
 *            d(m)…d(0) such that d(m) <= d(m‑1) >= d(m‑2) <= d(m‑3) …
 *            (alternating <= and >= comparisons)
 * Range:     u8 n <= 54, u16 n <= 54, u32 n <= 54, u64 n <= 54, u128 n <= 54,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence is generated by exhaustive construction of valid base‑3 strings
   in ascending numeric order. The function caches generated terms so that
   subsequent calls can reuse the data. */

#include <stdint.h>
#include <stdlib.h>

/* static cache of generated sequence values */
static seq_t *seq_cache = NULL; /* array of terms */
static size_t cache_len = 0;    /* current number of stored terms   */
static size_t cache_cap = 0;    /* capacity of seq_cache            */
static size_t next_len_to_gen = 1; /* next length of base‑3 numbers to generate */

/* append a value to the cache, expanding it if necessary */
static void push_value(seq_t val)
{
    if (cache_len >= cache_cap) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 64;
        seq_t *newp = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
        if (!newp) exit(EXIT_FAILURE); /* abort on allocation failure */
        seq_cache = newp;
        cache_cap = new_cap;
    }
    seq_cache[cache_len++] = val;
}

/* recursive generation of numbers of a given total length.
   pos   : index of the next lower digit to assign (0 … len‑2)
   prev  : value of the higher (previous) digit d[pos+1]
   val   : numeric value of digits higher than pos already built
   The algorithm ensures that the digits satisfy the alternating
   <= / >= constraints. */
static void rec_gen(size_t len, size_t pos, int prev, seq_t val)
{
    if (pos == 0) { /* last digit to assign (least significant) */
        size_t stepParity = (len - 2) - pos; /* pos==0 -> parity = len‑2 */
        int lo, hi;
        if ((stepParity & 1) == 0) {         /* even: prev <= curr  → curr >= prev */
            lo = prev;
            hi = 2;
        } else {                             /* odd:  prev >= curr → curr <= prev */
            lo = 0;
            hi = prev;
        }
        for (int d = lo; d <= hi; ++d) {
            seq_t newval = val * ((seq_t)3) + (seq_t)d;
            push_value(newval);
        }
        return;
    }

    size_t stepParity = (len - 2) - pos;
    int lo, hi;
    if ((stepParity & 1) == 0) { /* even: prev <= curr → curr >= prev */
        lo = prev;
        hi = 2;
    } else {                     /* odd:  prev >= curr → curr <= prev */
        lo = 0;
        hi = prev;
    }

    for (int d = lo; d <= hi; ++d) {
        seq_t newval = val * ((seq_t)3) + (seq_t)d;
        rec_gen(len, pos - 1, d, newval);
    }
}

/* generate all numbers having exactly 'len' base‑3 digits */
static void generate_len(size_t len)
{
    if (len == 1) { /* special case: single‑digit numbers 1 and 2 */
        push_value((seq_t)1);
        push_value((seq_t)2);
    } else {
        for (int msd = 1; msd <= 2; ++msd) { /* most significant digit cannot be 0 */
            seq_t val = (seq_t)msd;
            rec_gen(len, len - 2, msd, val);
        }
    }
}

/* ensure that the cache contains at least 'n' terms */
static void ensure_cached(idx_t n)
{
    while (cache_len < (size_t)n) {
        generate_len(next_len_to_gen++);
    }
}

/* public function: a(n) – 1‑based index */
seq_t a(idx_t n)
{
    ensure_cached(n);
    return seq_cache[(size_t)(n - 1)];
}
