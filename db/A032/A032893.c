/*
 * A032893  Numbers whose base-5 representation Sum_{i=0..m} d(i)*5^i has d(0)
 *          >= d(1) <= d(2) >= ...
 * https://oeis.org/A032893
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 60, u16 n <= 60, u32 n <= 60, u64 n <= 60, u128 n <= 60,
 *            big any n
 * Helpers:   seq_alloc, seq_realloc, valid_base5_alt
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: Numbers whose base‑5 digits alternate ≥, ≤, ≥, … 
   in the order of least significant digit first.
   Condition: d(0) ≥ d(1) ≤ d(2) ≥ d(3) ≤ …   (d(i) are base‑5 digits)
   The sequence is generated by testing each natural number for this
   property; a(1) is the smallest number satisfying it. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/seq_alloc.h"
#include "../utils/seq_realloc.h"
#include "../utils/valid_base5_alt.h"

/* Main sequence function */
seq_t a(idx_t n)
{
    /* Static memoisation cache – expanded as needed */
    static seq_t *cache = NULL;
    static idx_t cache_len = 0;   /* number of terms stored                */
    static idx_t cache_cap = 0;   /* current array capacity                 */
    static seq_t next_candidate = 1; /* next integer to test                 */

    /* Ensure cache has at least n terms */
    while (cache_len < n) {
        /* Find the next integer that satisfies the rule */
        while (!valid_base5_alt(next_candidate))
            ++next_candidate;

        /* Grow cache if necessary */
        if (cache_len == cache_cap) {
            idx_t new_cap = cache_cap ? cache_cap * 2 : 16;
            seq_t *tmp = seq_realloc(cache, cache_cap, new_cap);
            if (!tmp)
                abort();               /* memory allocation failed */
            cache      = tmp;
            cache_cap  = new_cap;
        }

        /* Store the found value */
        cache[cache_len++] = next_candidate;
        ++next_candidate;
    }

    return cache[n - 1];             /* n is 1‑based */
}
