/*
 * A032863  Numbers whose base-8 representation Sum_{i=0..m} d(i)*8^i has d(m)
 *          > d(m-1) < d(m-2) > ...
 * https://oeis.org/A032863
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 59, u16 n <= 59, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Helpers:   is_valid_base8
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes OEIS A032863: numbers whose base‑8 digits strictly alternate
   (d[m] > d[m‑1] < d[m‑2] > …).  The sequence is generated by
   enumerating integers and testing that property. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_valid_base8.h"

static seq_t *values = NULL;
static idx_t  values_len = 0;
static idx_t  values_cap = 0;
static seq_t  last_checked = 0;

static void ensure_capacity(idx_t needed)
{
    if (needed <= values_cap)
        return;
    idx_t new_cap = values_cap ? values_cap * 2 : 128;
    while (new_cap < needed)
        new_cap *= 2;
    seq_t *new_vals = (seq_t *)realloc(values, new_cap * sizeof(seq_t));
    if (!new_vals)
        abort();
    values = new_vals;
    values_cap = new_cap;
}

seq_t a(idx_t n)
{
    if (n == (idx_t)0)
        return (seq_t)0;   /* offset 1, n = 0 unused */

    while (values_len < n) {
        ensure_capacity(values_len + 1);
        if (is_valid_base8(last_checked))
            values[values_len++] = last_checked;
        last_checked++;
    }
    return values[n - 1];
}
