/*
 * A032847  Numbers whose base-9 representation Sum_{i=0..m} d(i)*9^i has d(m)
 *          < d(m-1) > d(m-2) < ...
 * https://oeis.org/A032847
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) = the n-th base‑9 number with alternating < > pattern,
 *            where a(1)=1, a(2)=2, … (no closed formula)
 * Range:     u8 n <= 57, u16 n <= 57, u32 n <= 57, u64 n <= 57, u128 n <= 57,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Code to generate OEIS A032847: numbers with alternating base‑9 digits.
   The sequence is generated by a breadth‑first search over digit strings:
   each next digit must be greater than the previous one when the position
   is even (from the right, 0‑based), and less when the position is odd.
   The implementation stores generated values in a resizable array `cache`
   and rebuilds it on demand for arbitrary n. */


#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* static state for memoisation */
static seq_t *cache = NULL;          /* the generated values */
static size_t cache_len = 0;         /* number of stored values   */
static size_t cache_cap = 0;         /* capacity of cache        */

/* state for incremental generation of digit strings */
typedef struct {
    seq_t cur;          /* numeric value of the partial number */
    uint8_t last;       /* most significant digit written so far */
    bool   next_greater;/* true if next digit must be > last, false if < last */
} State;

/* arrays for the previous and current generation step */
static State *states_prev = NULL;
static size_t states_prev_len = 0;
static size_t states_prev_cap = 0;
static State *states_curr = NULL;
static size_t states_curr_len = 0;
static size_t states_curr_cap = 0;

/* ------------------------------------------------------------------ */
/* Ensure that `cache` can hold at least `required` elements.  In C++ we
   must cast the return value of realloc from void* to seq_t*.          */
static void ensure_cache(size_t required)
{
    if (required > cache_cap) {
        size_t new_cap = cache_cap ? cache_cap : 64;
        while (new_cap < required) new_cap <<= 1;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) abort();             /* out of memory */
        cache = tmp;
        cache_cap = new_cap;
    }
}

/* Ensure that a State array can hold at least `required` elements. */
static void ensure_states(State **arr, size_t *len, size_t *cap, size_t required)
{
    if (required > *cap) {
        size_t new_cap = *cap ? *cap : 16;
        while (new_cap < required) new_cap <<= 1;
        State *tmp = (State *)realloc(*arr, new_cap * sizeof(State));
        if (!tmp) abort();
        *arr = tmp;
        *cap = new_cap;
    }
}

/* Append a new value to `cache`. */
static void cache_push(seq_t val)
{
    ensure_cache(cache_len + 1);
    cache[cache_len++] = val;
}

/* Generate all numbers of the next digit length from `states_prev`. */
static void generate_next_length(void)
{
    /* prepare space for the new states */
    states_curr_len = 0;
    size_t max_est = states_prev_len * 4 + 16;   /* approximate growth */
    ensure_states(&states_curr, &states_curr_len, &states_curr_cap, max_est);

    for (size_t i = 0; i < states_prev_len; ++i) {
        const State *s = &states_prev[i];
        for (int d = 0; d <= 8; ++d) {
            if (s->next_greater) {
                if (d <= s->last) continue;    /* must be greater */
            } else {
                if (d >= s->last) continue;    /* must be less  */
            }
            seq_t new_val = s->cur * (seq_t)9 + (seq_t)d;
            cache_push(new_val);

            /* create state for the next iteration */
            ensure_states(&states_curr, &states_curr_len, &states_curr_cap,
                          states_curr_len + 1);
            State *t = &states_curr[states_curr_len++];
            t->cur = new_val;
            t->last = (uint8_t)d;
            t->next_greater = !s->next_greater;
        }
    }

    /* discard old states */
    free(states_prev);
    states_prev = states_curr;
    states_prev_len = states_curr_len;
    states_prev_cap = states_curr_cap;
    states_curr = NULL;
    states_curr_len = 0;
    states_curr_cap = 0;
}

/* Initialise generation with one‑digit numbers 1…8. */
static void generate_length_one(void)
{
    states_prev_len = 0;
    size_t max_est = 8;
    ensure_states(&states_prev, &states_prev_len, &states_prev_cap, max_est);

    for (int d = 1; d <= 8; ++d) {
        seq_t val = (seq_t)d;
        cache_push(val);
        ensure_states(&states_prev, &states_prev_len, &states_prev_cap,
                      states_prev_len + 1);
        State *t = &states_prev[states_prev_len++];
        t->cur = val;
        t->last = (uint8_t)d;
        t->next_greater = true;      /* next digit must be greater than d */
    }
}

/* ------------------------------------------------------------------ */
/* Public function required by the OEIS framework.                     */
seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined for n<1, safeguard */

    /* keep generating until we have at least n terms */
    static idx_t generated_len = 0;
    while (cache_len < (size_t)n) {
        if (generated_len == 0) {
            generate_length_one();
            generated_len = 1;
        } else {
            ++generated_len;
            generate_next_length();
        }
    }
    return cache[(size_t)n - 1];
}
