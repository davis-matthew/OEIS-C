/* OEIS A038852 – Numbers that are divisible by 6 (and 18) and are
   differences between two cubes in at least one way.
   The sequence is generated by exhaustive search of a^3−b^3 (a>b>0)
   for a up to 2000, storing only values divisible by 6, then
   sorting and removing duplicates.  The array is computed once and
   served on demand.  */

#include <stdlib.h>
#include <stdbool.h>

/* Comparator for seq_t values – returns negative if x<y, 0 if equal,
   positive if x>y. */
static int cmp_seq_t(const void *p1, const void *p2)
{
    const seq_t *x = (const seq_t *)p1;
    const seq_t *y = (const seq_t *)p2;
    if (*x < *y) return -1;
    if (*x > *y) return 1;
    return 0;
}

/* Global storage for the pre‑computed sequence */
static seq_t *global_terms = NULL;
static size_t global_terms_len = 0;
static bool global_built = false;

/* Build the sequence once and store it in global_terms */
static void build_global_sequence(void)
{
    if (global_built) return;
    global_built = true;

    /* Upper bound for a that generates many terms.  2000^3 fits in
       64‑bit unsigned and gives thousands of terms. */
    const idx_t MAX_A = 2000;

    /* Maximum number of (a,b) pairs – fits in size_t. */
    const size_t MAX_PAIRS = (size_t)MAX_A * (MAX_A - 1) / 2;
    seq_t *tmp = (seq_t *)malloc(MAX_PAIRS * sizeof(seq_t));
    if (!tmp) exit(1);

    size_t cnt = 0;
    for (idx_t a = 1; a <= MAX_A; ++a) {
        seq_t a3 = (seq_t)a * a * a;
        for (idx_t b = 1; b < a; ++b) {
            seq_t b3 = (seq_t)b * b * b;
            seq_t diff = a3 - b3;
            if ((diff % (seq_t)6) == 0) {
                tmp[cnt++] = diff;
            }
        }
    }

    /* Sort the collected values. */
    qsort(tmp, cnt, sizeof(seq_t), cmp_seq_t);

    /* Remove duplicates in place. */
    size_t uniq = 0;
    for (size_t i = 0; i < cnt; ++i) {
        if (i == 0 || tmp[i] != tmp[i - 1]) {
            tmp[uniq++] = tmp[i];
        }
    }

    /* Resize to actual size. */
    seq_t *final = (seq_t *)realloc(tmp, uniq * sizeof(seq_t));
    if (!final) exit(1);

    global_terms      = final;
    global_terms_len  = uniq;
}

/* Public function */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;      /* below offset – undefined behaviour */
    build_global_sequence();
    if ((idx_t)n > global_terms_len) return (seq_t)0;  /* out of pre‑computed range */
    return global_terms[n - 1];
}
