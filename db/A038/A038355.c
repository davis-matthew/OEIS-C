/*
 * A038355  Numbers whose base-6 representation has the same nonzero number of
 *          3's and 4's.
 * https://oeis.org/A038355
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base, easy
 * Formula:   not stated
 * Range:     u8 n <= 26, u16 n <= 52, u32 n <= 52, u64 n <= 52, u128 n <= 52,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A038355: numbers whose base‑6 representation has the same non‑zero
   number of 3's and 4's.   The sequence is generated by a simple
   brute‑force search. */

#include <stdlib.h>
#include <stdbool.h>

/* Return true if x contains equal, positive counts of digits 3 and 4 in base 6. */
static bool good(seq_t x)
{
    unsigned c3 = 0, c4 = 0;
    while (x > 0) {
        seq_t d = x % (seq_t)6;
        if (d == (seq_t)3)
            ++c3;
        else if (d == (seq_t)4)
            ++c4;
        x /= (seq_t)6;
    }
    return (c3 == c4) && (c3 > 0);
}

/* Static storage for computed terms.  The capacity far exceeds the
   anticipated maximum n (≈10 000).  It works for both plain integral
   seq_t types and for arbitrary‑precision classes, as all C++ objects
   are default‑constructed and all C types are trivially constructed. */
#define CACHE_CAP 200000
static seq_t cache[CACHE_CAP];
static idx_t terms_found = 0;
static seq_t candidate  = 1;

/* Generate terms until at least n have been found. */
static void ensure_terms(idx_t n)
{
    while (terms_found < n) {
        if (good(candidate))
            cache[terms_found++] = candidate;
        ++candidate;
    }
}

/* Public function required by the tester. */
seq_t a(idx_t n)
{
    if (n < 1)
        return (seq_t)0;          /* undefined for indices before the offset */
    ensure_terms(n);
    return cache[n - 1];
}
