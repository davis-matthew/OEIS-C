#include <stdlib.h>
#include "../utils/binomial.h"

seq_t a(idx_t n)
{
    seq_t sum = 0;
    for (idx_t k = 0; k <= n; ++k) {
        idx_t N = 3*n + k + 1;
        idx_t K = n - k;
        sum += binomial(N, K);
    }
    return sum;
}
