/*
 * A356160  Numbers k such that the smallest positive k such that n divides
 *          k*A276086(k) is equal to n, where A276086 is primorial base
 *          exp-function.
 * https://oeis.org/A356160
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 72, u16 n <= 72, u32 n <= 72, u64 n <= 72, u128 n <= 72,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  A356160 – Numbers k such that the smallest positive m with
    k | m*A276086(m) equals k.  The sequence is generated by
    iterating m=1,2,3,… and, for each m, blocking every k>m
    that divides m*A276086(m).  The remaining numbers (those
    never blocked) are the terms of the sequence. */

/* Standard headers */
#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>

/* ------------------------------------------------------------------------ */
/* Constants and global data                                                 */
/* ------------------------------------------------------------------------ */
#define MAX_K_LIMIT      2000000U          /* safe upper bound for k */
#define MAX_PRIME_LIMIT  200000U           /* limit for prime sieve */

static idx_t primes[30000];    /* list of primes up to MAX_PRIME_LIMIT */
static size_t primes_cnt = 0;  /* number of primes found */

static bool *blocked = NULL;               /* blocked[k] == true  -> k is not in the sequence */
static size_t blocked_cap = 0;             /* capacity of blocked array */

/* ------------------------------------------------------------------------ */
/* Prime sieve (once)                                                       */
/* ------------------------------------------------------------------------ */
static void init_primes(void)
{
    bool *sieve = (bool *)calloc(MAX_PRIME_LIMIT + 1, sizeof(bool));
    if (!sieve) exit(EXIT_FAILURE);
    for (idx_t i = 2; i <= MAX_PRIME_LIMIT; ++i) {
        if (!sieve[i]) {
            primes[primes_cnt++] = i;
            if (i * i <= MAX_PRIME_LIMIT) {
                for (idx_t j = i * i; j <= MAX_PRIME_LIMIT; j += i)
                    sieve[j] = true;
            }
        }
    }
    free(sieve);
}

/* ------------------------------------------------------------------------ */
/* Factorisation of an integer (using the prime list)                       */
/* ------------------------------------------------------------------------ */
static void factorise_uint64(idx_t n, idx_t out_p[32], idx_t out_e[32], size_t *len)
{
    *len = 0;
    for (size_t i = 0; i < primes_cnt && (idx_t)primes[i] * primes[i] <= n; ++i) {
        idx_t p = primes[i];
        idx_t cnt = 0;
        while (n % p == 0) {
            n /= p;
            ++cnt;
        }
        if (cnt) {
            out_p[(*len)] = p;
            out_e[(*len)] = cnt;
            ++(*len);
        }
    }
    if (n > 1) {                       /* remaining prime factor */
        out_p[(*len)] = n;
        out_e[(*len)] = 1;
        ++(*len);
    }
}

/* ------------------------------------------------------------------------ */
/* Recursive divisor generation: mark all divisors > m and <= MAX_K_LIMIT   */
/* ------------------------------------------------------------------------ */
static void block_divisors_rec(size_t idx, uint64_t current,
                               const idx_t p[], const idx_t e[],
                               size_t len, uint64_t max_lim, idx_t m)
{
    if (idx == len) {
        if (current > (uint64_t)m && current <= max_lim)
            blocked[(size_t)current] = true;
        return;
    }

    uint64_t pow = 1;                         /* p[idx]^exp */
    for (idx_t exp = 0; exp <= e[idx]; ++exp) {
        if (current > max_lim / pow) break;
        block_divisors_rec(idx + 1, current * pow, p, e, len, max_lim, m);
        if (exp < e[idx]) {
            if (pow > max_lim / p[idx]) break;
            pow *= p[idx];
        }
    }
}

/* ------------------------------------------------------------------------ */
/* Main sequence function a(n)                                             */
/* ------------------------------------------------------------------------ */
seq_t a(idx_t n)
{
    /* Static state */
    static seq_t *seq = NULL;             /* sequence values      */
    static size_t seq_cap = 0;            /* capacity of seq      */
    static size_t seq_len = 0;            /* number of terms      */
    static idx_t processed_m = 0;         /* last processed m     */
    static int prime_inited = 0;          /* prime list flag      */

    /* Initialise once */
    if (!prime_inited) {
        prime_inited = 1;
        init_primes();

        blocked_cap = MAX_K_LIMIT + 1;
        blocked = (bool *)calloc(blocked_cap, sizeof(bool));
        if (!blocked) exit(EXIT_FAILURE);
    }

    /* Grow sequence array if needed */
    if (!seq) {
        seq_cap = 8;
        seq = (seq_t *)malloc(seq_cap * sizeof(seq_t));
        if (!seq) exit(EXIT_FAILURE);
    }

    /* Generate terms until we have n of them */
    while (seq_len < (size_t)n) {

        /* Step 1: next m to process */
        ++processed_m;

        /* Step 2: if not blocked, it is a sequence term */
        if (!blocked[(size_t)processed_m]) {
            if (seq_len >= seq_cap) {
                seq_cap = seq_cap ? seq_cap * 2 : 8;
                seq = (seq_t *)realloc(seq, seq_cap * sizeof(seq_t));
                if (!seq) exit(EXIT_FAILURE);
            }
            seq[seq_len++] = (seq_t)processed_m;
        }

        /* Step 3: compute combined factorisation of m * A276086(m) */
        idx_t prime_f[32], exp_f[32];
        size_t flen = 0;

        /* Factorisation of m itself */
        factorise_uint64(processed_m, prime_f, exp_f, &flen);

        /* Process digits in primorial base and merge exponents */
        idx_t temp = processed_m;
        idx_t pidx = 0;
        while (temp > 0 && pidx < primes_cnt) {
            idx_t p   = primes[pidx];
            idx_t dig = temp % p;         /* digit for this prime */
            if (dig > 0) {
                /* merge into prime_f/exp_f */
                bool found = false;
                for (size_t j = 0; j < flen; ++j) {
                    if (prime_f[j] == p) {
                        exp_f[j] += dig;
                        found = true;
                        break;
                    }
                }
                if (!found) {
                    prime_f[flen] = p;
                    exp_f[flen]   = dig;
                    ++flen;
                }
            }
            temp /= p;
            ++pidx;
        }

        /* Step 4: block all divisors > m of this product */
        block_divisors_rec(0, 1U, prime_f, exp_f, flen,
                           (uint64_t)MAX_K_LIMIT, processed_m);
    }

    return seq[(size_t)n - 1];
}
