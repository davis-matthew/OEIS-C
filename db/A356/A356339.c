#include <stdint.h>

static seq_t sigma_k(idx_t m, uint8_t k)
{
    seq_t res = (seq_t)1;
    idx_t n = m;

    for (idx_t p = 2; p * p <= n; ++p) {
        if (n % p == 0) {
            idx_t exp = 0;
            while (n % p == 0) {
                n /= p;
                ++exp;
            }

            /* compute pk = p^k */
            seq_t pk = (seq_t)1;
            for (idx_t i = 0; i < k; ++i) pk *= (seq_t)p;

            /* sum_{i=0}^{exp} (p^k)^i = 1 + pk + pk^2 + ...   */
            seq_t term = (seq_t)0;
            seq_t pow   = (seq_t)1;
            for (idx_t i = 0; i <= exp; ++i) {
                term += pow;
                pow  *= pk;
            }
            res *= term;
        }
    }

    if (n > 1) {               /* remaining prime factor with exponent 1 */
        /* k is 1 or 3, exp = 1 */
        seq_t pk = (seq_t)1;
        for (idx_t i = 0; i < k; ++i) pk *= (seq_t)n;

        seq_t term = (seq_t)0;
        seq_t pow   = (seq_t)1;
        for (idx_t i = 0; i <= (idx_t)1; ++i) {
            term += pow;
            pow  *= pk;
        }
        res *= term;
    }

    return res;
}

seq_t a(idx_t n)
{
    seq_t sum   = 0;          /* accumulator for the sum   */
    seq_t binom = 1;          /* binomial(2*n, 0)          */

    for (idx_t k = n; k > 0; --k) {
        /* sigma_2(k) = sigma_k(k, 2) */
        seq_t sigma = sigma_k(k, 2u);

        sum += binom * sigma; /* add current term */

        /* Prepare binomial for the next (k-1) when k>1 */
        if (k > 1) {
            seq_t num = (seq_t)(n + k);
            seq_t den = (seq_t)(n - k + 1);
            binom = (binom * num) / den;   /* exact division */
        }
    }

    return sum;
}
