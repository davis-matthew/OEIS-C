/*
 * A356935  Numbers whose prime indices all have odd bigomega (number of prime
 *          factors with multiplicity). Products of primes indexed by elements
 *          of A026424. MM-numbers of finite multisets of finite odd-length
 *          multisets of positive integers.
 * https://oeis.org/A356935
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 1, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Validated: partial, pass, 59 terms through n = 59 (2026-11-03)
 * Helpers:   bigomega, build_primes_upto, mem
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A356935 – Numbers whose prime factors are the primes
   whose index has odd bigomega.  The terms are the ascending
   unique values generated by repeatedly multiplying the allowed
   primes with arbitrarily many factors.  The algorithm uses a
   heap to produce the sequence in O(n·k) where k is the number
   of allowed primes. */

#include <stddef.h>
#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

#include "../utils/bigomega.h"
#include "../utils/build_primes_upto.h"
#include "../utils/mem.h"

/* comparison function for qsort */
static int cmp_seq_t(const void *p1, const void *p2)
{
    const seq_t *x = (const seq_t *)p1;
    const seq_t *y = (const seq_t *)p2;
    if (*x < *y) return -1;
    if (*y < *x) return 1;
    return 0;
}

typedef struct {
    seq_t  val;
    size_t pidx;
} Candidate;

/* --------------------------- global state --------------------------- */
static bool            initialized = false;
static uint64_t       *all_primes   = NULL;
static size_t          all_prime_cnt = 0;
static uint64_t       *allowed_primes = NULL;
static size_t          allowed_cnt = 0;
static size_t         *idx_ptr = NULL;           /* current index for each prime */

static Candidate      *heap     = NULL;
static size_t          heap_size = 0;
static size_t          heap_cap  = 0;

static seq_t          *seq      = NULL;
static size_t          seq_len   = 0;
static size_t          seq_cap   = 0;

/* ------------------------ heap helper functions -------------------- */
static void heap_push(Candidate c)
{
    size_t i = heap_size++;
    while (i > 0) {
        size_t parent = (i - 1) >> 1;
        if (cmp_seq_t(&heap[parent].val, &c.val) <= 0)
            break;
        heap[i] = heap[parent];
        i = parent;
    }
    heap[i] = c;
}

static Candidate heap_pop(void)
{
    Candidate top = heap[0];
    size_t   i   = 0;
    heap_size--;
    Candidate last = heap[heap_size];
    while (true) {
        size_t left  = (i << 1) + 1;
        size_t right = left + 1;
        if (left >= heap_size)
            break;
        size_t smallest = left;
        if (right < heap_size &&
            cmp_seq_t(&heap[right].val, &heap[left].val) < 0)
            smallest = right;
        if (cmp_seq_t(&last.val, &heap[smallest].val) <= 0)
            break;
        heap[i] = heap[smallest];
        i = smallest;
    }
    heap[i] = last;
    return top;
}

/* --------------------------- init routine --------------------------- */
static void initialise(void)
{
    /* Sufficient limit to get enough primes for ~10 000 terms */
    const idx_t LIMIT = 2000000;

    build_primes_upto(LIMIT, &all_primes, &all_prime_cnt);

    allowed_primes = (uint64_t *)malloc(all_prime_cnt * sizeof(uint64_t));
    allowed_cnt = 0;
    for (size_t i = 0; i < all_prime_cnt; ++i) {
        idx_t index = (idx_t)(i + 1);    /* primes are 1‑based indexed */
        seq_t omega = bigomega(index);
        if ((omega & 1) != 0)           /* odd bigomega of the index */
            allowed_primes[allowed_cnt++] = all_primes[i];
    }

    idx_ptr = (size_t *)calloc(allowed_cnt, sizeof(size_t)); /* all start at 0 */

    heap_cap = allowed_cnt;
    heap = mem_new(Candidate, heap_cap);
    for (size_t i = 0; i < allowed_cnt; ++i)
        heap_push((Candidate){ .val = (seq_t)allowed_primes[i], .pidx = i });

    seq_cap = 1024;
    seq = mem_new(seq_t, seq_cap);
    seq[0] = (seq_t)1;
    seq_len = 1;

    initialized = true;
}

/* ---------------------------- public function --------------------- */
seq_t a(idx_t n)
{
    if (!initialized)
        initialise();

    while (seq_len < (size_t)n) {
        /* ----------------------------------------------------------------
           1.   Obtain the minimal candidate value.
           2.   Collect all primes that yield this value.
           3.   Append the value to the sequence (once).
           4.   For each prime that produced it, advance its index and
                push the next candidate into the heap.
           ---------------------------------------------------------------- */
        Candidate first = heap_pop();
        seq_t val = first.val;

        /* Append new term if it is not a duplicate of the last one */
        if (seq_len == 0 || val != seq[seq_len - 1]) {
            if (seq_len == seq_cap) {
                seq_cap <<= 1;
                seq = mem_resize(seq_t, seq, seq_cap);
            }
            seq[seq_len++] = val;
        }

        /* Process all other primes with the same minimal value */
        while (heap_size > 0 &&
               cmp_seq_t(&heap[0].val, &val) == 0) {

            Candidate dup = heap_pop();
            idx_ptr[dup.pidx]++; /* advance index for this prime */
            seq_t next = seq[idx_ptr[dup.pidx]] *
                         (seq_t)allowed_primes[dup.pidx];
            heap_push((Candidate){ .val = next, .pidx = dup.pidx });
        }

        /* Advance index for the prime that gave the first minimal value */
        idx_ptr[first.pidx]++;          /* now idx points to the just added term */
        seq_t next_first = seq[idx_ptr[first.pidx]] *
                           (seq_t)allowed_primes[first.pidx];
        heap_push((Candidate){ .val = next_first, .pidx = first.pidx });
    }

    return seq[(size_t)n - 1];
}
