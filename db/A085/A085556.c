/*
 * A085556  Numbers that have exactly as many prime digits as nonprime digits.
 * https://oeis.org/A085556
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, easy, nonn
 * Formula:   not stated
 * Range:     u8 n <= 44, u16 n <= 59, u32 n <= 59, u64 n <= 59, u128 n <= 59,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes A085556: numbers that have exactly as many prime digits as nonprime digits.
   The sequence is generated by searching integers and selecting those whose
   number of prime digits (2,3,5,7) equals the number of nonprime digits.  */
#include <stdlib.h>

seq_t a(idx_t n)
{
    static seq_t *cache = NULL;
    static size_t cachelen = 0;
    static size_t cachesz = 0;
    static uint64_t next_uint = 1;   /* Candidate integer to test */

    if (n == 0) return 0;   /* Undefined for n = 0, but guarded */

    while (cachelen < n) {
        uint64_t cand = next_uint++;    /* Next integer to examine */

        unsigned len = 0, prime = 0;
        uint64_t t = cand;
        while (t > 0) {
            unsigned d = t % 10;
            len++;
            if (d == 2 || d == 3 || d == 5 || d == 7) prime++;
            t /= 10;
        }
        if (len % 2 == 0 && prime * 2 == len) {
            if (cachelen == cachesz) {
                size_t newsz = cachesz == 0 ? 8 : cachesz * 2;
                seq_t *tmp = (seq_t *)realloc(cache, newsz * sizeof(seq_t));
                cache = tmp;
                cachesz = newsz;
            }
            cache[cachelen++] = (seq_t) cand;
        }
    }
    return cache[n-1];
}
