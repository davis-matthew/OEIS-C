/* Sequence of positive integers divisible by 5 whose prime factors are all ≤ 7.
   Generated by iteratively multiplying the already known numbers by 2, 3, 5, or 7
   and keeping the smallest unused value.  The array `seq` holds the sequence
   values in ascending order. */
#include <stdlib.h>

seq_t a(idx_t n)
{
    static seq_t *seq = NULL;     /* array of generated terms   */
    static size_t  size    = 0;   /* current number of terms    */
    static size_t  capacity = 0;  /* allocated array capacity   */
    static idx_t   i2 = 0, i3 = 0, i5 = 0, i7 = 0;  /* indices for next *prime */

    if (n == 0)  /* undefined for n<1; return 0 as a safe sentinel */
        return (seq_t)0;

    /* initialisation: first term is 5 (must contain a factor 5)      */
    if (size == 0) {
        capacity = 16;
        seq = (seq_t *)malloc(capacity * sizeof(seq_t));
        if (seq == NULL) abort(); /* allocation failure */
        seq[0] = (seq_t)5;
        size  = 1;
    }

    /* generate terms up to the requested index n */
    while (size < (size_t)n) {
        /* compute the next candidates by multiplying existing terms */
        seq_t cand2 = seq[i2] * (seq_t)2;
        seq_t cand3 = seq[i3] * (seq_t)3;
        seq_t cand5 = seq[i5] * (seq_t)5;
        seq_t cand7 = seq[i7] * (seq_t)7;

        /* choose the minimal candidate */
        seq_t next = cand2;
        if (cand3 < next) next = cand3;
        if (cand5 < next) next = cand5;
        if (cand7 < next) next = cand7;

        /* advance pointers that produced the minimal value */
        if (cand2 == next) i2++;
        if (cand3 == next) i3++;
        if (cand5 == next) i5++;
        if (cand7 == next) i7++;

        /* grow the array if necessary */
        if (size + 1 > capacity) {
            size_t new_cap = capacity * 2;
            seq_t *new_seq = (seq_t *)realloc(seq, new_cap * sizeof(seq_t));
            if (new_seq == NULL) abort(); /* allocation failure */
            seq = new_seq;
            capacity = new_cap;
        }

        seq[size++] = next;
    }

    return seq[n-1];
}
