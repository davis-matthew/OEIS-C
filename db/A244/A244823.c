/*  OEIS A244823 – decimal digits of the fraction 21413747/656616555
 *  (c/P).  The sequence a(n) gives the (n+1)-st digit after the leading
 *  zero of the decimal expansion 0.0326122557..., with offset -1.
 *  a(-1) is the first non‑zero digit (3), a(0)=2, a(1)=6, etc.
 *
 *  The value is generated by long division on the fly; the current
 *  remainder is stored statically so successive calls can continue
 *  generating digits.  No external libraries are required beyond the
 *  standard <stdlib.h> and <stdbool.h>.
 */

#include <stdlib.h>
#include <stdbool.h>

/* static state */
static seq_t *digits = NULL;     /* cached digits, index 0 = a(-1) */
static size_t digits_cap = 0;    /* current capacity of the array   */
static size_t digits_len = 0;    /* number of digits stored          */
static seq_t rem = 21413747;     /* current remainder, start with numerator */

/*  a(idx_t n)  returns the nth term of the sequence
 *   (n ≥ -1).  For indices below -1 the behaviour is undefined.  */
seq_t a(idx_t n)
{
    /* indices below the offset are not required. */
    if (n < -1)
        return 0;

    /* target position in our digit cache:
     * digits[0] holds a(-1), digits[1] holds a(0), …  */
    size_t desired = (size_t)n + 1;          /* n is signed, addition yields -1+1=0 for n=-1 */

    /* Generate digits until the desired one is available. */
    while (digits_len <= desired) {
        /* Compute next decimal digit of the fraction.  */
        seq_t temp   = rem * 10;
        seq_t raw    = temp / 656616555;     /* digit to store in cache */
        rem          = temp % 656616555;     /* update remainder          */

        /* Skip the very first digit (the leading zero after the decimal point). */
        if (digits_len == 0 && raw == 0)
            continue;

        /* Grow the cache when needed.  */
        if (digits_len == digits_cap) {
            digits_cap = digits_cap ? digits_cap * 2 : 64;
            seq_t *newptr = (seq_t *)realloc(digits, digits_cap * sizeof(seq_t));
            if (!newptr)
                abort();                      /* allocation failed */
            digits = newptr;
        }

        digits[digits_len++] = raw;
    }

    return digits[desired];
}
