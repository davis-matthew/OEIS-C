/*
 * A244863  Semiprimes whose digit sum is a perfect square.
 * https://oeis.org/A244863
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 9, u16 n <= 2023, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Validated: standard, pass, 67 terms through n = 9529 (2026-11-01)
 * Helpers:   digit_sum, ipow_i32, is_prime, smallest_prime_factor
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the nth term of OEIS sequence A244863:
   the semiprimes whose digit sum is a perfect square.  The terms are
   generated by a simple scan of the positive integers, checking for
   semiprimality and a square digit sum.  The implementation uses
   helper functions from the utils library; no external storage or
   memoisation is required.  It works for any seq_t type that exposes
   the usual arithmetic operators.  */
#include <stdbool.h>
#include <stdint.h>
#include <stddef.h>
#include "../utils/digit_sum.h"
#include "../utils/ipow_i32.h"
#include "../utils/is_prime.h"
#include "../utils/smallest_prime_factor.h"

/* Floor square root by binary search */
static inline seq_t floor_sqrt(seq_t x)
{
    seq_t lo = 0, hi = 1;
    while (ipow_i32(hi, 2) <= x)
        hi <<= 1;
    while (lo < hi)
    {
        seq_t mid = (lo + hi) >> 1;
        seq_t mid2 = mid * mid;
        if (mid2 <= x)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo - 1;
}

/* Test whether m is a semiprime (product of exactly two primes,
   counting multiplicity).  */
static bool is_semiprime(uint64_t m)
{
    if (m < 4)            /* 2, 3 are prime, 1 is not */
        return false;
    uint64_t p = smallest_prime_factor(m);
    if (p == m)          /* m itself is prime */
        return false;
    uint64_t q = m / p;
    return is_prime((idx_t)q);   /* q must be prime */
}

/* Main sequence function.  */
seq_t a(idx_t n)
{
    if (n < 1) return 0;            /* undefined for non‑positive indices */

    idx_t found = 0;
    for (uint64_t x = 4; ; ++x)     /* start at 4, the first semiprime */
    {
        if (!is_semiprime(x))
            continue;

        seq_t s = digit_sum((seq_t)x);
        seq_t r = floor_sqrt(s);
        if (r * r == s)            /* digit sum is a perfect square */
        {
            ++found;
            if (found == n)
                return (seq_t)x;
        }
    }
}
