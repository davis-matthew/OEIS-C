/*  OEIS sequence A244545
 *  a(n) is the nth integer n such that for every integer k>0, n*6^k+1
 *  is divisible by at least one of 7,13,31,37,43.
 *
 *  The sequence satisfies
 *      a(n) = a(n-24) + 4488211        for n>24,
 *  where the first 24 terms are obtained by searching the definition.
 *
 *  The implementation precomputes the residues that n must satisfy
 *  for k=1..12 (after this period all k give the same residues),
 *  then finds the first 24 numbers satisfying them.
 *  All further terms are generated by the linear recurrence above.
 */

#include <stdbool.h>
#include "../utils/_modinv_small.h"

/* Prime divisors to test against */
static const int _primes[5] = {7, 13, 31, 37, 43};
static const int _pcount = 5;

/* Pre‑computed residues:  residue[prime_index][k-1]  (k = 1..12)  */
static int _residues[5][12];

/* First 24 terms, computed on first call */
static seq_t _base[24];
static bool _init_done = false;

/* Initialize residue tables and the first 24 terms */
static void _init_sequence(void) {
    /* compute residues for k=1..12 */
    for (int pi = 0; pi < _pcount; ++pi) {
        int p = _primes[pi];
        int pow = 1 % p;                /* 6^0 mod p */
        for (int k = 1; k <= 12; ++k) {
            pow = (pow * 6) % p;        /* 6^k mod p */
            int inv = _modinv_small(pow, p);
            int r = (p - inv) % p;      /* n ≡ -inv (mod p)  */
            _residues[pi][k-1] = r;
        }
    }

    /* search for the first 24 numbers satisfying the property */
    seq_t cand = 1;
    int found = 0;
    while (found < 24) {
        bool ok = true;
        for (int k = 0; k < 12 && ok; ++k) {
            bool matched = false;
            for (int pi = 0; pi < _pcount; ++pi) {
                if ((cand % _primes[pi]) == (seq_t)_residues[pi][k]) {
                    matched = true;   break;
                }
            }
            if (!matched) ok = false;
        }
        if (ok) { _base[found] = cand; ++found; }
        ++cand;
    }
    _init_done = true;
}

seq_t a(idx_t n) {
    if (n == 0) return 0;        /* safety for out‑of‑range inputs */

    if (!_init_done) _init_sequence();

    idx_t zero = n - 1;          /* zero‑based index */
    idx_t rem   = zero % 24;     /* position within the first cycle   */
    idx_t block = zero / 24;     /* number of full 24‑step blocks     */

    seq_t increment = ((seq_t)block) * 4488211;
    return _base[rem] + increment;
}
