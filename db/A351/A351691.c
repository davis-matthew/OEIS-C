/*
 * A351691  Lexicographically earliest infinite sequence of distinct positive
 *          numbers such that, for n>2, a(n) has a common factor with a(n-1),
 *          shares a 1-bit in its binary expansion with a(n-1), has no common
 *          factor with a(n-2), and does not share a 1-bit in its binary
 *          expansion with a(n-2).
 * https://oeis.org/A351691
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 64, u32 n <= 64, u64 n <= 64, u128 n <= 64,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  A351691: Lexicographically earliest infinite sequence of distinct positive
 *  integers such that, for n>2,
 *      gcd(a(n),a(n-1)) > 1
 *      (a(n) & a(n-1)) != 0
 *      gcd(a(n),a(n-2)) == 1
 *      (a(n) & a(n-2)) == 0
 *      a(n) has at least one prime factor not dividing a(n-1)
 *
 *  The sequence is generated by a minimal‑search algorithm that builds the
 *  terms one by one, storing previously computed values and testing each
 *  candidate in increasing order until all constraints are satisfied.
 *  Initial terms: a(1)=1, a(2)=2, a(3)=6.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* GCD for integral types */
static inline seq_t my_gcd(seq_t a, seq_t b)
{
    while (b != 0) {
        seq_t t = a % b;
        a = b;
        b = t;
    }
    return a;
}

/* Factor a 64‑bit integer into distinct primes.
 * primes[] must have room for at least 64 elements.
 * cnt is set to the number of distinct primes found. */
static void factor_uint64(uint64_t n, uint64_t *primes, size_t *cnt)
{
    *cnt = 0;
    if (n <= 1) return;
    if (n % 2 == 0) {
        primes[(*cnt)++] = 2;
        while (n % 2 == 0) n /= 2;
    }
    uint64_t f = 3;
    while (f * f <= n) {
        if (n % f == 0) {
            primes[(*cnt)++] = f;
            while (n % f == 0) n /= f;
        }
        f += 2;
    }
    if (n > 1) primes[(*cnt)++] = n;
}

/* Checks if cand has any prime factor not in prev_primes[].
 * prev_primes contains the distinct prime factors of the previous term. */
static bool candidate_has_new_prime(seq_t cand,
                                    uint64_t *prev_primes, size_t prev_cnt)
{
    uint64_t cand64 = (uint64_t)cand;
    uint64_t cand_primes[64];
    size_t cand_cnt;
    factor_uint64(cand64, cand_primes, &cand_cnt);

    for (size_t i = 0; i < cand_cnt; ++i) {
        uint64_t p = cand_primes[i];
        bool in_prev = false;
        for (size_t j = 0; j < prev_cnt; ++j) {
            if (p == prev_primes[j]) { in_prev = true; break; }
        }
        if (!in_prev) return true; /* found a new prime factor */
    }
    return false; /* all factors already in previous term */
}

seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* not used, keep function safe */

    static seq_t *buf = NULL;   /* array of computed terms */
    static size_t cap = 0;      /* allocated capacity */
    static size_t len = 0;      /* number of terms stored */

    /* Initialise with the first three terms if empty */
    if (len == 0) {
        cap = 8;
        buf = (seq_t *)realloc(NULL, cap * sizeof(seq_t));
        buf[0] = (seq_t)1;
        buf[1] = (seq_t)2;
        buf[2] = (seq_t)6;
        len   = 3;
    }

    /* Generate terms until we have at least n terms */
    while (len < n) {
        seq_t prev  = buf[len - 1];
        seq_t prev2 = buf[len - 2];

        /* Factor the previous term once for the new–prime test */
        uint64_t prev_primes[64];
        size_t prev_cnt;
        factor_uint64((uint64_t)prev, prev_primes, &prev_cnt);

        seq_t cand = 1;
        for (;;) {
            ++cand;

            /* Skip already used numbers */
            bool used = false;
            for (size_t i = 0; i < len; ++i) {
                if (buf[i] == cand) { used = true; break; }
            }
            if (used) continue;

            /* Must share a common factor with the previous term */
            if (my_gcd(prev, cand) == (seq_t)1) continue;

            /* Must share a 1‑bit with the previous term */
            if ((prev & cand) == (seq_t)0) continue;

            /* Must have no common factor with the term before that */
            if (my_gcd(prev2, cand) != (seq_t)1) continue;

            /* Must have no common 1‑bit with the term before that */
            if ((prev2 & cand) != (seq_t)0) continue;

            /* Must have at least one prime factor not in the previous term */
            if (!candidate_has_new_prime(cand, prev_primes, prev_cnt)) continue;

            /* All constraints satisfied */
            break;
        }

        /* Append the found candidate and grow array if needed */
        if (len == cap) {
            size_t new_cap = cap ? cap * 2 : 8;
            buf = (seq_t *)realloc(buf, new_cap * sizeof(seq_t));
            cap = new_cap;
        }
        buf[len++] = cand;
    }

    return buf[n - 1];
}
