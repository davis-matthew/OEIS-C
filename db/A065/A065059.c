/*
 * A065059  Primes p such that prime(p) + pi(p) is a prime.
 * https://oeis.org/A065059
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn, changed
 * Formula:   not stated
 * Range:     u8 n <= 2, u16 n <= 160, u32 n <= 51, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   build_primes_upto, get_prime, is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes primes p such that prime(p) + pi(p) is a prime.
   The sequence is generated by iterating over the primes in order
   and caching the ones that satisfy the condition. */

#include <stdlib.h>
#include <stdbool.h>
#include <stdint.h>

#include "../utils/build_primes_upto.h"
#include "../utils/get_prime.h"
#include "../utils/is_prime_big.h"

/* --- Prime list cache ---------------------------------------------------- */
static uint64_t *prime_list   = NULL; /* increasing list of primes          */
static size_t   prime_count   = 0;   /* number of primes currently stored */
static uint64_t prime_limit   = 1000;/* maximum prime value built so far   */

/* Expand the prime list to include all primes ≤ new_limit. */
static void extend_primes(uint64_t new_limit)
{
    /* Free existing list if any */
    if (prime_list)
        free(prime_list);

    size_t cnt = 0;
    uint64_t *tmp = NULL;
    /* build_primes_upto builds array of primes ≤ limit */
    build_primes_upto((idx_t)new_limit, &tmp, &cnt);

    prime_list   = tmp;
    prime_count  = cnt;
    prime_limit  = new_limit;
}

/* Ensure the prime list contains at least m primes (i.e., has length ≥ m). */
static void ensure_prime_index(uint64_t m)
{
    uint64_t limit = prime_limit > 0 ? prime_limit : 1000;
    while ((uint64_t)prime_count < m) {
        limit <<= 1;            /* double the limit each time */
        extend_primes(limit);
    }
}

/* --- Special sequence cache ---------------------------------------------- */
static uint64_t *special_list   = NULL; /* primes that satisfy the condition */
static size_t   special_count  = 0;     /* number of terms currently stored */
static size_t   special_cap    = 0;     /* allocation capacity               */
static size_t   last_checked_idx = 0;   /* next index in prime_list to test */

/* Ensure that at least n terms of the sequence have been computed. */
static void ensure_specials(idx_t n)
{
    while (special_count < (size_t)n) {
        if (!prime_list) /* initialise the prime list if needed */
            extend_primes(prime_limit);

        /* If we have run out of cached primes, extend the list. */
        if (last_checked_idx >= prime_count) {
            uint64_t target = last_checked_idx + 1;
            if (prime_count < target)
                ensure_prime_index(target);
        }

        uint64_t p       = prime_list[last_checked_idx];   /* current prime p   */
        uint64_t i       = last_checked_idx + 1;           /* pi(p) = index    */
        ensure_prime_index(p);                             /* need prime at index p */
        uint64_t prime_of_p = get_prime(p);                /* prime(p)         */
        uint64_t sum       = prime_of_p + i;               /* prime(p)+pi(p)   */

        if (is_prime_big((seq_t)sum)) {
            /* Append p to the special list. */
            if (special_count >= special_cap) {
                size_t new_cap = special_cap ? special_cap * 2 : 16;
                uint64_t *new_arr = (uint64_t *)
                        realloc(special_list, new_cap * sizeof(uint64_t));
                if (!new_arr) abort(); /* allocation failed */
                special_list = new_arr;
                special_cap  = new_cap;
            }
            special_list[special_count++] = p;
        }
        last_checked_idx++;
    }
}

/* Public function required by the build. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;                      /* offset is 1 for real usage */
    if (!prime_list) extend_primes(prime_limit);
    ensure_specials(n);
    return (seq_t)special_list[n - 1];
}
