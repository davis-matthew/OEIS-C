/*
 * A065217  Numbers which need 12 'Reverse and Add' steps to reach a
 *          palindrome.
 * https://oeis.org/A065217
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 174, u64 n <= 1000, u128 n <= 1000,
 *            big any n
 * Helpers:   is_palindrome, reverse_seq
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes a(n) of A065217: numbers that reach a palindrome after
   exactly 12 Reverse‑and‑Add steps.  The sequence is generated by
   testing successive integers in increasing order and storing when
   they satisfy the property. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_palindrome.h"   /* is_palindrome(seq_t, idx_t) */
#include "../utils/reverse_seq.h"    /* reverse_seq(seq_t) */

static bool needs_exact_steps(seq_t x) {
    if (is_palindrome(x, 10))
        return false;               /* exclude starting palindromes */
    for (int s = 1; s <= 12; ++s) {
        seq_t rev = reverse_seq(x);
        x += rev;
        if (is_palindrome(x, 10))
            return s == 12;         /* true only if reached at step 12 */
    }
    return false;
}

/* ---- cache for selected terms ---- */
static seq_t  *cache          = NULL;   /* dynamic array of answers */
static size_t cache_size      = 0;      /* number of terms stored     */
static size_t cache_capacity  = 0;      /* allocated slots            */
static seq_t  candidate       = 1;      /* next integer to test       */

/* Ensure cache can hold at least n elements.  Use a cast for realloc
   that works in C++ as well as C. */
static void resize_cache(size_t n) {
    if (n <= cache_capacity)
        return;
    size_t new_cap = 16;
    while (new_cap < n)
        new_cap <<= 1;
    seq_t *newp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    cache = newp;
    cache_capacity = new_cap;
}

/* Append value to cache. */
static void append_cache(seq_t val) {
    resize_cache(cache_size + 1);
    cache[cache_size++] = val;
}

/* ------------------------------------------------------------- */
/*                      OEIS sequence function                   */
seq_t a(idx_t n)
{
    /* compute terms until we have at least n stored */
    while (cache_size < (size_t)n) {
        if (!is_palindrome(candidate, 10) && needs_exact_steps(candidate))
            append_cache(candidate);
        ++candidate;
    }
    return cache[(size_t)n - 1];
}
