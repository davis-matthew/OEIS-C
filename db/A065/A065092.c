/*
 * A065092  Primes with property that when written in base two complementing
 *          any single bit yields a composite number.
 * https://oeis.org/A065092
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 6, u16 n <= 732, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   bitlen64, is_prime_u64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A065092: primes p such that changing any single binary bit of p
 * or prefixing a 1 (i.e., p + 2^⌊log₂p⌋) yields a composite number.
 * The sequence is generated by sieving primes and testing each one.
 * The implementation follows the required interface with external linkage.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>
#include "../utils/bitlen64.h"   /* extern unsigned bitlen64(uint64_t);      */
#include "../utils/is_prime_u64.h" /* extern bool is_prime_u64(uint64_t);      */

/* --------- Helper for prime generation ----------------------------------- */

static uint64_t sieve_limit = 0;           /* largest integer previously sieved */
static uint32_t *prime_list = NULL;        /* primes up to sieve_limit           */
static size_t prime_cap = 0, prime_cnt = 0;

static void extend_sieve(uint64_t limit)
{
    if (limit <= sieve_limit) return;

    uint64_t sz = limit + 1;
    uint8_t *comp = (uint8_t *)malloc(sz);
    if (!comp) exit(1);

    for (uint64_t i = 0; i < sz; ++i) comp[i] = 0;
    comp[0] = comp[1] = 1;

    for (uint64_t i = 2; i * i <= limit; ++i) {
        if (!comp[i]) {
            for (uint64_t j = i * i; j <= limit; j += i) comp[j] = 1;
        }
    }

    for (uint64_t i = 2; i <= limit; ++i) {
        if (!comp[i] && i > sieve_limit) {
            if (prime_cnt == prime_cap) {
                prime_cap = prime_cap ? prime_cap << 1 : 16;
                uint32_t *tmp = (uint32_t *)realloc(prime_list, prime_cap * sizeof(uint32_t));
                if (!tmp) exit(1);
                prime_list = tmp;
            }
            prime_list[prime_cnt++] = (uint32_t)i;
        }
    }

    free(comp);
    sieve_limit = limit;
}

/* --------- Test whether a prime satisfies the property ------------------- */

static bool good_prime(uint32_t p)
{
    unsigned L = bitlen64((uint64_t)p);

    for (unsigned i = 0; i < L; ++i) {
        uint64_t q = (uint64_t)p ^ ((uint64_t)1 << i);
        if (q < 2) continue;          /* flip to 0 gives composite */
        if (is_prime_u64(q)) return false;
    }

    uint64_t pref = (uint64_t)p + ((uint64_t)1 << L);
    if (is_prime_u64(pref)) return false;

    return true;
}

/* --------- Main sequence function --------------------------------------- */

static size_t prime_test_idx = 0;          /* next prime in prime_list to test   */
static uint64_t *seq_arr = NULL;          /* gathered sequence values (uint64_t) */
static size_t seq_cap = 0, seq_len = 0;

seq_t a(idx_t n)
{
    if (n == 0) return 0;               /* offset 1; return 0 for n==0 by convention */

    while (seq_len < (size_t)n) {
        if (prime_test_idx >= prime_cnt) {
            uint64_t new_limit = sieve_limit ? sieve_limit * 2 : 1000;
            if (new_limit < sieve_limit + 1000) new_limit = sieve_limit + 1000;
            extend_sieve(new_limit);
        }

        uint32_t p = prime_list[prime_test_idx++];
        if (good_prime(p)) {
            if (seq_len == seq_cap) {
                seq_cap = seq_cap ? seq_cap << 1 : 16;
                uint64_t *tmp = (uint64_t *)realloc(seq_arr, seq_cap * sizeof(uint64_t));
                if (!tmp) exit(1);
                seq_arr = tmp;
            }
            seq_arr[seq_len++] = (uint64_t)p;
        }
    }

    return (seq_t)seq_arr[n - 1];
}
