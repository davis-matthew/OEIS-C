/*
 * A268390  Products of an even number of distinct primes and the square of a
 *          number in the sequence (including 1).
 * https://oeis.org/A268390
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   a(n) = the n-th positive integer whose prime‑exponent bitwise
 *            XOR is zero. (OEIS A268390, offset 1)
 * Range:     u8 n <= 83, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>

/* ---------- Small‑prime factorisation utilities ---------- */
static uint64_t *primes      = NULL;   /* list of primes found so far  */
static size_t    primes_len  = 0;      /* number of primes in the list   */
static size_t    primes_cap  = 0;      /* allocated capacity of primes   */
static uint64_t  next_prime_candidate = 2;  /* next integer to test for primality */

/* Integer square‑root (floor) for uint64_t, avoids floating point */
static inline uint64_t isqrt_uint64(uint64_t n)
{
    uint64_t x = 0;
    uint64_t bit = (uint64_t)1 << 62;  /* start with the highest bit */
    while (bit != 0) {
        uint64_t trial = x | bit;
        if (trial <= n / trial) {
            x = trial;
        }
        bit >>= 1;
    }
    return x;
}

/* Ensure that the prime list contains all primes <= limit.  The list is
   grown incrementally; new primes are generated by trial division using
   the primes that are already known. */
static void ensure_prime_limit(uint64_t limit)
{
    if (limit < 2) return;

    if (primes_cap == 0) {
        primes_cap = 32;                           /* initial capacity   */
        primes = (uint64_t *)malloc(primes_cap * sizeof(uint64_t));
        if (!primes) exit(EXIT_FAILURE);
    }

    while (primes_len == 0 ? 1 : primes[primes_len - 1] < limit) {
        /* Find next prime candidate */
        while (true) {
            uint64_t p = next_prime_candidate;
            bool is_prime = true;
            for (size_t i = 0; i < primes_len &&
                                 primes[i] * primes[i] <= p; ++i) {
                if (p % primes[i] == 0) {
                    is_prime = false;
                    break;
                }
            }
            next_prime_candidate++;
            if (is_prime) {
                if (primes_len == primes_cap) {
                    primes_cap <<= 1;
                    uint64_t *tmp = (uint64_t *)realloc(primes,
                            primes_cap * sizeof(uint64_t));
                    if (!tmp) exit(EXIT_FAILURE);
                    primes = tmp;
                }
                primes[primes_len++] = p;
                break;
            }
        }
    }
}

/* Compute the XOR of the exponents in the prime factorisation of x.
   Uses the global prime list; ensure the list covers primes up to
   sqrt(x) before calling.  The result is an integer from 0 up to some
   small value. */
static uint64_t xor_of_exponents(uint64_t x)
{
    uint64_t res = 0;
    uint64_t temp = x;

    /* Ensure we have all primes needed for factorisation */
    ensure_prime_limit(isqrt_uint64(temp) + 1);

    for (size_t i = 0; i < primes_len && primes[i] * primes[i] <= temp; ++i) {
        uint64_t p = primes[i];
        if (temp % p == 0) {
            unsigned int cnt = 0;
            do {
                temp /= p;
                ++cnt;
            } while (temp % p == 0);
            res ^= cnt;
        }
    }
    if (temp > 1) {                 /* remaining prime factor with exponent 1 */
        res ^= 1;
    }
    return res;
}

/* Test whether a candidate number satisfies the sequence condition.  */
static inline bool condition_holds(uint64_t candidate)
{
    return xor_of_exponents(candidate) == 0;
}

/* ---------- Sequence definition ---------- */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)0;   /* defined only for n>=1 */

    idx_t count = 0;
    uint64_t candidate = 1;

    while (count < n) {
        if (condition_holds(candidate)) {
            ++count;
            if (count == n) {
                return (seq_t)candidate;
            }
        }
        ++candidate;
    }

    /* Unreachable, but keep the compiler happy */
    return (seq_t)0;
}
