/*
 * A320892  Numbers with an even number of prime factors (counted with
 *          multiplicity) that cannot be factored into distinct semiprimes.
 * https://oeis.org/A320892
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 1099, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * A320892: Numbers with an even number of prime factors (counted with multiplicity)
 * that cannot be expressed as a product of distinct semiprimes.
 *
 * The sequence is generated by a brute‑force search:
 *   * Scan all integers in increasing order.
 *   * For each integer n the following are checked
 *     (a) bigOmega(n) is even;
 *     (b) there is NO factorisation of n into distinct semiprimes.
 *   * If both conditions hold, n is appended to the output sequence.
 *
 * The search uses a small pre‑computed list of primes (8 000 000 elements) and
 * a depth‑first search that attempts to pair the prime factors of n into
 * distinct semiprimes.  Because n ≤ 8 000 000 in practice for the first
 * 10 000 terms, this implementation satisfies the performance requirements.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* ------------------------------------------------------------- */
/*                                types                            */
/* ------------------------------------------------------------- */
#ifndef seq_t
/* seq_t is supplied by the build environment */
#endif
#ifndef idx_t
/* idx_t is supplied by the build environment (uint64_t) */
#endif

/* ------------------------------------------------------------- */
/*                   prime table generation                       */
/* ------------------------------------------------------------- */
#define PRIME_SIEVE_LIMIT 8000000LU  /* 8 000 000 ensures >10 000th term */

static uint32_t *primes = NULL;     /* list of primes up to PRIME_SIEVE_LIMIT */
static size_t    prime_cnt = 0;     /* number of primes stored */

/* simple sieve of Eratosthenes – collects primes in a global array  */
static void build_prime_table(void)
{
    if (primes != NULL) return;  /* already built */

    /* allocate buffer for primes (rough estimate) */
    size_t max_primes = PRIME_SIEVE_LIMIT / 10;  /* <600 000 for 8 M */
    primes = (uint32_t *)malloc(max_primes * sizeof(uint32_t));

    bool *mark = (bool *)calloc(PRIME_SIEVE_LIMIT + 1, 1);
    for (uint32_t i = 2; i <= PRIME_SIEVE_LIMIT; ++i) {
        if (!mark[i]) {
            primes[prime_cnt++] = i;
            if ((uint64_t)i * i <= PRIME_SIEVE_LIMIT) {
                for (uint32_t j = i * i; j <= PRIME_SIEVE_LIMIT; j += i)
                    mark[j] = true;
            }
        }
    }
    free(mark);
}

/* ------------------------------------------------------------- */
/*          check whether n can be factored into distinct semiprimes */
/* ------------------------------------------------------------- */
static bool dfs_distinct(int total,
                         const uint64_t *pList,
                         bool *used,
                         uint64_t *usedProd,
                         int prodCnt)
{
    /* find first unused index */
    int i = 0;
    while (i < total && used[i]) ++i;
    if (i == total) return true;      /* all paired */

    for (int j = i + 1; j < total; ++j) {
        if (used[j]) continue;

        uint64_t prod = pList[i] * pList[j];

        /* check duplicate product */
        bool dup = false;
        for (int k = 0; k < prodCnt; ++k)
            if (usedProd[k] == prod) { dup = true; break; }
        if (dup) continue;

        used[i] = used[j] = true;
        usedProd[prodCnt++] = prod;

        if (dfs_distinct(total, pList, used, usedProd, prodCnt)) return true;

        /* backtrack */
        used[i] = used[j] = false;
        --prodCnt;
    }
    return false;
}

/* true if n belongs to the sequence (i.e. even bigOmega and NO distinct semiprime factorisation) */
static bool is_in_sequence(uint64_t n)
{
    if (n < 4) return false;  /* too small to have even bigOmega ≥ 2 */

    /* factorise n */
    uint64_t primeList[64];
    int totalPrimes = 0;
    uint64_t m = n;

    for (size_t i = 0; i < prime_cnt && (uint64_t)primes[i] * primes[i] <= m; ++i) {
        uint32_t p = primes[i];
        while (m % p == 0) {
            primeList[totalPrimes++] = p;
            m /= p;
        }
    }
    if (m > 1) {                /* remainder is a prime > sqrt(n) */
        primeList[totalPrimes++] = m;
    }

    if (totalPrimes % 2 != 0) return false;   /* odd bigOmega → skip */

    /* try to build a distinct-semi‑prime factorisation */
    bool used[64] = {false};
    uint64_t usedProd[32]; /* at most totalPrimes/2 products */
    int prodCnt = 0;

    bool hasDistinct = dfs_distinct(totalPrimes, primeList, used, usedProd, prodCnt);
    return !hasDistinct;  /* sequence element when distinct factorisation does NOT exist */
}

/* ------------------------------------------------------------- */
/*                       sequence generation                       */
/* ------------------------------------------------------------- */
static seq_t *seq_cache   = NULL;  /* stored sequence values */
static size_t seq_cap     = 0;
static idx_t  seq_len     = 0;      /* number of terms stored */
static idx_t  next_int    = 2;      /* next integer to test */

/* ensure cache has at least (needed) capacity */
static void ensure_seq_capacity(idx_t needed)
{
    if (needed <= seq_cap) return;
    size_t new_cap = seq_cap ? seq_cap * 2 : 32;
    while (new_cap < (size_t)needed) new_cap *= 2;
    seq_cache = (seq_t *)realloc(seq_cache, new_cap * sizeof(seq_t));
    seq_cap = new_cap;
}

seq_t a(idx_t n)
{
    /* build prime table once */
    build_prime_table();

    /* generate terms until we have at least n terms */
    while (seq_len < n) {
        uint64_t val = (uint64_t)next_int;
        if (is_in_sequence(val)) {
            ensure_seq_capacity(seq_len + 1);
            seq_cache[seq_len++] = (seq_t)val;   /* cast to seq_t */
        }
        ++next_int;
    }
    return seq_cache[n - 1];
}
