/*
 * A070879  Stern's diatomic array read by rows (version 3 - same as version
 *          2, A070878, but with final 0 in each row omitted).
 * https://oeis.org/A070879
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, tabf, easy
 * Formula:   a(n) is the n‑th element of Stern’s diatomic array read by rows
 *            (trailing zero omitted), where f(0,1)=1, f(m,2k−1)=f(m−1,k),
 *            f(m,2k )=f(m−1,k)+f(m−1,k+1) (m≥1)
 * Range:     u8 n <= 100, u16 n <= 100, u32 n <= 100, u64 n <= 100,
 *            u128 n <= 100, big any n
 * Validated: partial, pass, 101 terms through n = 100 (2026-11-01)
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* The sequence is generated by first determining the row that
   contains index n.  For n≥0 let m = ⌊log₂(n+1)⌋; the first index of
   row m is 2^m−1.  If k = n-(2^m−1)+1 (1≤k≤2^m) then a(n)=f(m,k).  */

#include <stdint.h>

/* Recursively evaluate f(m,k) described above.  If k>2^m the
   value is defined to be 0, which is correctly handled by the
   recursion falling to the m==0 case. */
static seq_t stern_val(idx_t m, idx_t k)
{
    if (m == 0)
        return (k == 1) ? (seq_t)1 : (seq_t)0;

    if (k & 1ULL)                 /* odd index: f(m,2x−1)=f(m−1,x) */
        return stern_val(m - 1, (k + 1) >> 1);
    else                           /* even index: f(m,2x)=f(m−1,x)+f(m−1,x+1) */
        return stern_val(m - 1, k >> 1) +
               stern_val(m - 1, (k >> 1) + 1);
}

/* Return ⌊log₂(x)⌋ for 1 ≤ x < 2⁶⁴. */
static inline idx_t floor_log2_idx(idx_t x)
{
    /* gcc/clang builtin: */
    return 63 - __builtin_clzll(x);
}

/* Public function required by the build. */
seq_t a(idx_t n)
{
    idx_t m   = floor_log2_idx(n + 1);          /* find the row of n   */
    idx_t pow = ((idx_t)1) << m;                /* 2^m                 */
    idx_t k   = n - (pow - 1) + 1;              /* 1 ≤ k ≤ 2^m         */

    return stern_val(m, k);
}
