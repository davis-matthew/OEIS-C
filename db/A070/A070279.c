/*
 * A070279  Sum of digits of n equals the sum of digits of 2n.
 * https://oeis.org/A070279
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 14, u16 n <= 3632, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   digit_sum
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Code to compute OEIS sequence A070279:
   a(n) = the nth positive integer n such that the sum of its decimal digits
   equals the sum of the decimal digits of 2n.
   The sequence is generated by iterating over multiples of 9 (since
   9 divides n iff digit_sum(n) ≡ 0 (mod 9) and then checking the
   equality condition.  Results are memoised in a static array so that
   repeated calls with arbitrary n are fast. */

#include <stdlib.h>
#include <string.h>
#include "../utils/digit_sum.h"

static seq_t *terms = NULL;        /* cached terms of the sequence   */
static size_t  terms_len = 0;      /* number of cached terms         */
static size_t  terms_cap = 0;      /* capacity of the cache array    */
static idx_t   k_next   = 1;        /* next multiple index (n = 9*k)  */

static void grow_terms(void)
{
    size_t new_cap = terms_cap ? terms_cap * 2 : 16;
    seq_t *new_arr = (seq_t *)malloc(new_cap * sizeof(seq_t));
    if (!new_arr) abort();            /* out of memory */
    if (terms) {
        memcpy(new_arr, terms, terms_len * sizeof(seq_t));
        free(terms);
    }
    terms     = new_arr;
    terms_cap = new_cap;
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;            /* safety: offset is 1 */

    while (terms_len < n) {
        seq_t candidate = (seq_t)(9 * k_next);
        seq_t doubled   = candidate + candidate;

        if (digit_sum(candidate) == digit_sum(doubled)) {
            if (terms_len == terms_cap) grow_terms();
            terms[terms_len++] = candidate;
        }
        ++k_next;
    }
    return terms[n - 1];
}
