/*
 * A070815  Solutions to phi(gpf(x)) - gpf(phi(x)) = 254 = c are special
 *          multiples of 257, x = 257k, where largest prime factors of factor
 *          k were observed from {2, 3, 5, 17}. See solutions to other even
 *          cases of c (=A070813): A007283 for 0, A070004 for 2, A070814 for
 *          14, A070816 for 65534.
 * https://oeis.org/A070815
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 36, u32 n <= 37, u64 n <= 37, u128 n <= 37,
 *            big any n
 * Helpers:   seq_alloc_new_array, seq_free_array
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*  OEIS A070815
 *
 *  Formula:
 *      a(n) = 257 * k(n)
 *
 *  where the sequence k(n) consists of all positive integers of the form
 *      k = 2^e * m
 *  with integer e ≥ 0 and m a product of distinct primes chosen from {3,5,17}
 *  (m = 1,3,5,15,17,51,85,255).  k(n) is ordered increasingly.
 *
 *  The sequence is generated by merging eight arithmetic progressions
 *  M[i] * 2^e (i = 0..7) where M = {1,3,5,15,17,51,85,255}.  Each new
 *  term is the smallest of the current candidates, then the corresponding
 *  candidate is multiplied by 2 to advance that progression.
 *
 *  The function a(idx_t n) returns the n‑th term (n ≥ 1).  For n = 0 it
 *  returns 0.
 */

#include <stdint.h>
#include <stddef.h>
#include "../utils/seq_alloc_new_array.h"
#include "../utils/seq_free_array.h"

static seq_t *k_array = NULL;     /* stores generated k values (0‑based)      */
static size_t k_len   = 0;        /* number of stored k values               */
static seq_t cur[8];              /* current candidates for the 8 progressions */
static int  cur_init = 0;         /* flag whether cur has been initialized   */
static const seq_t M[8] = { (seq_t)1, (seq_t)3, (seq_t)5, (seq_t)15,
                            (seq_t)17, (seq_t)51, (seq_t)85, (seq_t)255 };

/* prepare k_array to contain at least n elements */
static void
ensure_k(idx_t n)
{
    if (k_len >= (size_t)n)
        return;                              /* already have enough */

    /* allocate (or re‑allocate) array of size n */
    seq_t *new_k = seq_alloc_new_array((size_t)n);
    if (k_array && k_len > 0) {
        /* copy existing data */
        for (size_t i = 0; i < k_len; ++i)
            new_k[i] = k_array[i];
        seq_free_array(k_array);
    }
    k_array = new_k;

    /* initialize candidate array once */
    if (!cur_init) {
        for (int i = 0; i < 8; ++i)
            cur[i] = M[i];
        cur_init = 1;
    }

    /* generate missing k values */
    for (size_t i = k_len; i < (size_t)n; ++i) {
        /* find index of smallest candidate */
        int min_idx = 0;
        seq_t min_val = cur[0];
        for (int j = 1; j < 8; ++j)
            if (cur[j] < min_val) {
                min_val = cur[j];
                min_idx = j;
            }

        new_k[i] = min_val;          /* store next k */
        cur[min_idx] *= (seq_t)2;    /* advance that progression */
    }

    k_len = n;
}

seq_t
a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;         /* Undefined for offset 0; harmless */

    ensure_k(n);
    return k_array[n - 1] * (seq_t)257;   /* a(n) = 257 * k(n) */
}
