/*
 * A070547  a(n) = Card(k, 0<k<n such that phi(k) divides phi(n-k)).
 * https://oeis.org/A070547
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  easy, nonn
 * Formula:   a(n) = Card(k, 0<k<n such that phi(k) divides phi(n-k))
 * Range:     u8 n <= 77, u16 n <= 10000, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>

/* Small prime factorisation cache and phi precomputation */
static idx_t  phi_cache_len = 0;      /* phi_cache currently valid for indices < phi_cache_len */
static seq_t *phi_cache     = NULL;   /* phi_cache[i] holds φ(i), allocated with size >= phi_cache_len */

static idx_t  spf_len = 0;            /* spf array currently valid up to spf_len-1 */
static uint32_t *spf = NULL;          /* smallest prime factor array */

static size_t primes_cap = 0;         /* capacity of primes array */
static size_t primes_cnt = 0;         /* number of primes found so far */
static uint32_t *primes  = NULL;      /* list of primes generated by the linear sieve */

/* Ensure the smallest‑prime‑factor array is allocated and filled up to n */
static void ensure_spfs(idx_t n)
{
    if (n < spf_len) return;
    /* grow spf */
    if (spf == NULL) {
        spf = (uint32_t*)malloc((n + 1) * sizeof(uint32_t));
    } else if (n + 1 > spf_len) {
        spf = (uint32_t*)realloc(spf, (n + 1) * sizeof(uint32_t));
    }
    for (idx_t i = spf_len; i <= n; ++i) spf[i] = 0;

    /* linear sieve to fill spf and primes list */
    for (idx_t i = 2; i <= n; ++i) {
        if (spf[i] == 0) {
            spf[i] = (uint32_t)i;
            if (primes_cnt == primes_cap) {
                primes_cap = primes_cap ? primes_cap * 2 : 8;
                primes = (uint32_t*)realloc(primes, primes_cap * sizeof(uint32_t));
            }
            primes[primes_cnt++] = (uint32_t)i;
        }
        for (size_t j = 0; j < primes_cnt && (idx_t)primes[j] <= spf[i] && i * (idx_t)primes[j] <= n; ++j) {
            spf[i * (idx_t)primes[j]] = primes[j];
        }
    }
    spf_len = n + 1;
}

/* Fill phi_cache up to n (inclusive) */
static void ensure_phi_cache(idx_t n)
{
    if (n + 1 <= phi_cache_len) return;

    if (phi_cache == NULL) {
        phi_cache = (seq_t*)malloc((n + 1) * sizeof(seq_t));
    } else if (phi_cache_len < n + 1) {
        phi_cache = (seq_t*)realloc(phi_cache, (n + 1) * sizeof(seq_t));
    }

    ensure_spfs(n);

    /* phi[0] is meaningless; set phi[1] = 1 */
    if (phi_cache_len == 0) {
        phi_cache[0] = 0;
        phi_cache[1] = 1;
        phi_cache_len = 2;
    }

    for (idx_t i = phi_cache_len; i <= n; ++i) {
        seq_t res = (seq_t)i;
        idx_t temp = i;
        idx_t last_p = 0;
        while (temp > 1) {
            idx_t p = spf[temp];
            if (p != last_p) {
                res = (res / p) * (p - 1);
                last_p = p;
            }
            temp /= p;
        }
        phi_cache[i] = res;
    }
    phi_cache_len = n + 1;
}

/* Public interface to obtain φ(n) */
static seq_t phi_cache_value(idx_t n)
{
    ensure_phi_cache(n);
    return phi_cache[n];
}

/* Main sequence function */
seq_t a(idx_t n)
{
    if (n <= 1) return (seq_t)0;
    seq_t count = 0;
    for (idx_t k = 1; k < n; ++k) {
        seq_t phi_k     = phi_cache_value(k);
        seq_t phi_nk    = phi_cache_value(n - k);
        if (phi_nk % phi_k == 0) {
            ++count;
        }
    }
    return count;
}
