/*
 * A070330  Nontrivial numbers in which suffixing or inserting a 0 anywhere
 *          yields only composite numbers.
 * https://oeis.org/A070330
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 5, u16 n <= 55, u32 n <= 55, u64 n <= 55, u128 n <= 55,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* OEIS A070330: Nontrivial numbers such that suffixing or inserting a zero anywhere
   yields only composite numbers.  The sequence is generated by a brute‑force
   search with memoisation. */

#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>

#include "../utils/is_prime_big.h"

static seq_t *cache = NULL;
static size_t cache_cap   = 0;
static size_t cache_len   = 0;
static seq_t next_candidate = 1;   /* first value to test */

/* Test whether x satisfies the definition. */
static bool is_candidate(seq_t x)
{
    /* exclude multiples of 2, 3, or 5 */
    if ((x % 2 == 0) || (x % 3 == 0) || (x % 5 == 0))
        return false;

    /* number of decimal digits in x */
    seq_t tmp = x;
    size_t digits = 0;
    while (tmp > 0) {
        tmp /= 10;
        digits++;
    }
    if (digits == 0) digits = 1;   /* for x == 0, not used */

    /* Inserting 0 between digits (positions 1 .. digits-1) */
    seq_t pow10_k = 10;   /* 10^1 */
    for (size_t k = 1; k < digits; ++k) {
        if (k > 1) pow10_k *= 10;        /* raise to 10^k */
        seq_t left  = x / pow10_k;
        seq_t right = x % pow10_k;
        seq_t cand  = left * 10 * pow10_k + right;
        if (is_prime_big(cand))
            return false;
    }

    /* Suffixing 0 */
    if (is_prime_big(x * 10))
        return false;

    return true;
}

seq_t a(idx_t n)
{
    if (n == 0)
        return 0;   /* offset starts at 1 */

    /* Generate terms until we have at least n of them */
    while (cache_len < (size_t)n) {
        if (is_candidate(next_candidate)) {
            /* grow the cache if necessary */
            if (cache_len == cache_cap) {
                size_t new_cap = cache_cap ? cache_cap * 2 : 8;
                seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
                if (!tmp) exit(1);
                cache = tmp;
                cache_cap = new_cap;
            }
            cache[cache_len++] = next_candidate;
        }
        ++next_candidate;
    }
    return cache[n - 1];
}
