/*
 * A324050  Numbers satisfying Korselt's criterion: squarefree numbers n such
 *          that for every prime divisor p of n, p-1 divides n-1.
 * https://oeis.org/A324050
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, easy
 * Formula:   not stated
 * Range:     u8 n <= 55, u16 n <= 6558, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Korselt numbers: squarefree n such that for every prime divisor p of n,
   (p-1) divides n-1.  Generated by building all numbers up to a bound
   and filtering; the bound grows as needed. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* Internal state */
static seq_t *terms = NULL;
static size_t terms_cap = 0;
static size_t terms_len = 0;
static uint64_t current_bound = 0;

/* Append a term, resizing on demand */
static void push_term(seq_t val)
{
    if (terms_len == terms_cap) {
        size_t new_cap = terms_cap ? terms_cap << 1ULL : 64;
        seq_t *new_ptr = (seq_t *)realloc(terms, new_cap * sizeof(seq_t));
        if (!new_ptr) abort();
        terms = new_ptr;
        terms_cap = new_cap;
    }
    terms[terms_len++] = val;
}

/* Build all Korselt numbers up to 'bound' (inclusive) */
static void build_terms(uint64_t bound)
{
    /* SPF sieve */
    uint32_t *spf = (uint32_t *)malloc((bound + 1) * sizeof(uint32_t));
    if (!spf) abort();
    for (uint64_t i = 0; i <= bound; ++i) spf[i] = 0;
    for (uint64_t i = 2; i <= bound; ++i) {
        if (spf[i] == 0) {
            spf[i] = (uint32_t)i;
            if (i * i <= bound) {
                for (uint64_t j = i * i; j <= bound; j += i)
                    if (spf[j] == 0) spf[j] = (uint32_t)i;
            }
        }
    }

    /* reset term list */
    terms_len = 0;
    push_term((seq_t)1);           /* 1 is always included */

    /* enumerate numbers */
    for (uint64_t n = 2; n <= bound; ++n) {
        if (spf[n] == (uint32_t)n) {          /* prime */
            push_term((seq_t)n);
        } else {                            /* composite */
            uint64_t tmp = n;
            bool ok = true;
            while (tmp > 1) {
                uint32_t p = spf[tmp];
                int exp = 0;
                while (tmp % p == 0) {
                    tmp /= p;
                    ++exp;
                }
                if (exp > 1) { ok = false; break; }          /* not squarefree */
                if ((n - 1) % (p - 1) != 0) { ok = false; break; }
            }
            if (ok) push_term((seq_t)n);
        }
    }

    free(spf);
    current_bound = bound;
}

/* Public sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;            /* undefined, return 0 */

    /* initialise on first call */
    if (terms == NULL) {
        build_terms(200000);             /* initial bound */
    }

    /* extend bound until we have enough terms */
    while ((size_t)n > terms_len) {
        uint64_t new_bound = current_bound * 2;
        if (new_bound < 200000) new_bound = 200000;
        free(terms);
        terms_cap = 0;
        terms_len = 0;
        build_terms(new_bound);
    }

    return terms[(size_t)n - 1];
}
