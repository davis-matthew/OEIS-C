/* Sequence A324772: The "Octanacci" sequence.
   Defined by:
     S0 = 1, S1 = 0;
     S_{n+2} = S_{n+1} S_n S_{n+1}
   a(n) is the nth letter (0‑indexed) of the infinite word generated by
   iterating this recurrence (the limit of S_k as k → ∞). */

#include <stddef.h>

static seq_t get_value(size_t k, idx_t pos, const idx_t *len)
{
    if (k == 0) return (seq_t)1;   /* S0 = "1"   */
    if (k == 1) return (seq_t)0;   /* S1 = "0"   */

    if (pos < len[k-1])
        return get_value(k-1, pos, len);

    pos -= len[k-1];
    if (pos < len[k-2])
        return get_value(k-2, pos, len);

    pos -= len[k-2];
    return get_value(k-1, pos, len);
}

seq_t a(idx_t n)
{
    /* Pre‑compute lengths L_k until L_k > n.
       L0 = 1, L1 = 1, L_{k+2} = 2*L_{k+1} + L_k   */
    static idx_t len[64];
    static size_t len_sz = 0;

    if (len_sz == 0) {
        len[0] = 1;
        len[1] = 1;
        len_sz = 2;
    }

    while (len[len_sz-1] <= n) {
        /* Note: the recurrence grows quickly, so overflow is unlikely
           for the problem constraints (n up to ~10^4). */
        idx_t next = len[len_sz-1] << 1; /* 2*L_{k-1} */
        next += len[len_sz-2];           /* + L_{k-2} */
        len[len_sz++] = next;
        /* For safety, terminate if we exceed the static array size. */
        if (len_sz >= sizeof(len)/sizeof(len[0])) break;
    }

    /* Find smallest k with len[k] > n. */
    size_t k = len_sz - 1;
    return get_value(k, n, len);
}
