/* A324909: odd numbers k for which sigma(k^2) ≡ 3 (mod 4).  
   Generated by checking odd integers and counting prime factors ≡1 (mod 4). */
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/alloc_seq_array.h"
#include "../utils/seq_free_array.h"

static seq_t *cache = NULL;
static idx_t cache_size = 0;
static idx_t cache_cap = 0;
static idx_t last_checked = 1;  /* last odd integer examined */

/* Grow the cache array to hold at least 'needed' elements. */
static void grow_cache(idx_t needed)
{
    if (cache_cap >= needed) return;
    while (cache_cap < needed)
        cache_cap = (cache_cap == 0 ? 64 : cache_cap << 1);

    seq_t *new_cache = alloc_seq_array(cache_cap);
    for (idx_t i = 0; i < cache_size; ++i)
        new_cache[i] = cache[i];
    if (cache) seq_free_array(cache);
    cache = new_cache;
}

/* Ensure that at least n terms of the sequence are cached. */
static void ensure_terms(idx_t n)
{
    if (cache_size >= n) return;

    while (cache_size < n)
    {
        idx_t cand = last_checked + 2;   /* next odd integer */
        idx_t temp = cand;
        unsigned int parity = 0;          /* 0: even, 1: odd number of ≡1 mod 4 primes */

        for (idx_t p = 3; p <= temp / p; p += 2)
        {
            while (temp % p == 0)
            {
                if ((p & 3) == 1) parity ^= 1;
                temp /= p;
            }
        }
        if (temp > 1 && (temp & 3) == 1) parity ^= 1;

        if (parity)
        {
            grow_cache(cache_size + 1);
            cache[cache_size++] = (seq_t)cand;
        }
        last_checked = cand;
    }
}

seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* undefined for offset 0 */
    ensure_terms(n);
    return cache[n - 1];
}
