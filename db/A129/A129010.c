/*
 * A129010  Nonnegative values x of solutions (x, y) to the Diophantine
 *          equation x^2+(x+833)^2 = y^2.
 * https://oeis.org/A129010
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 none, u16 none, u32 n <= 40, u64 n <= 40, u128 n <= 40,
 *            big any n
 * Helpers:   floor_sqrt
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A129010: x-values of solutions to x² + (x + 833)² = y².
   Recurrence for n > 30:
      a(n) = 6*a(n-15) - a(n-30) + 1666
   Initial values:
      a(1) = 0, a(2) = 124, a(3) = 168, a(4) = 187, a(5) = 343,
      a(6) = 399, a(7) = 595, a(8) = 624, a(9) = 915, a(10) = 952,
      a(11) = 1260, a(12) = 1372, a(13) = 1768, a(14) = 1827,
      a(15) = 1975
   The first 30 terms are computed algorithmically by brute‑force search
   for integer solutions of the Diophantine equation.  Subsequent
   terms are generated by the recurrence, memoized in a dynamic array. */

#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include "../utils/floor_sqrt.h"

/* Number of initial terms that we precompute by search. */
#define PRECOMP_N 30

/* Array holding the first PRECOMP_N values.  The array must be
   filled on the first call to a().  The index 0 corresponds to a(1). */
static seq_t first_vals[PRECOMP_N];
static bool first_vals_ready = false;

/* Compute the first PRECOMP_N terms by brute‑forcing solutions of
   2x² + 1666x + 833² = y².  The floor_sqrt() routine works for both
   built‑in integer types and arbitrary‑precision seq_t. */
static void compute_first_vals(void)
{
    if (first_vals_ready)
        return;

    idx_t found = 0;
    seq_t x = (seq_t)0;
    const seq_t three = (seq_t)833;
    const seq_t three_sq = three * three;

    /* The computer's integer type is large enough for the values
       encountered during this search (the 30th solution is well
       within 64‑bit range).  All arithmetic is performed with seq_t. */
    while (found < PRECOMP_N) {
        /* rhs = 2*x² + 1666*x + 833² */
        seq_t rhs = ( (seq_t)2 * x ) * x;
        rhs += (seq_t)1666 * x;
        rhs += three_sq;

        seq_t y = floor_sqrt(rhs);
        if (y * y == rhs) {
            first_vals[found++] = x;
        }
        ++x;
    }
    first_vals_ready = true;
}

/* Cache for terms beyond the precomputed range.
   cache[1] ... cache[n] hold the sequence values. */
static seq_t *cache = NULL;
static size_t cache_len = 0;   /* allocated length (including unused 0th slot) */
static idx_t cache_max = 0;    /* largest index for which cache is valid */

/* Expand the cache so that it can hold indices up to n (inclusive). */
static void ensure_cache_capacity(idx_t n)
{
    if ((idx_t)cache_len >= n + 1)
        return;
    size_t new_len = (size_t)(n + 1) * 2;
    seq_t *tmp = (seq_t *)realloc(cache, new_len * sizeof(seq_t));
    if (!tmp) {
        /* In the unlikely event of allocation failure, abort. */
        abort();
    }
    cache = tmp;
    cache_len = new_len;
}

/* Primary interface for the OEIS sequence. */
seq_t a(idx_t n)
{
    if (n == 0)
        return (seq_t)0;          /* undefined, return 0 for safety */

    /* Make sure the first PRECOMP_N terms are available. */
    compute_first_vals();

    if (n <= PRECOMP_N)
        return first_vals[n - 1];

    /* Allocate the cache on first use. */
    if (cache == NULL) {
        const size_t init_size = 64;
        cache = (seq_t *)malloc((init_size + 1) * sizeof(seq_t));
        if (!cache) abort();
        cache_len = init_size + 1;
        for (idx_t i = 1; i <= PRECOMP_N; ++i)
            cache[i] = first_vals[i - 1];
        cache_max = PRECOMP_N;
    }

    /* Compute any missing terms up to n using the recurrence. */
    if (n > cache_max) {
        ensure_cache_capacity(n);
        for (idx_t i = cache_max + 1; i <= n; ++i) {
            /* Compute: 6*a(i-15) - a(i-30) + 1666
               Using temp = 6*a(i-15) + 1666  then subtract a(i-30).   */
            seq_t tmp = cache[i - 15];
            tmp = (tmp * (seq_t)6) + (seq_t)1666;
            cache[i] = tmp - cache[i - 30];
        }
        cache_max = n;
    }

    return cache[n];
}
