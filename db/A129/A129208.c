/* Recurrence:
   a(n+2) * a(n-2) = -144*a(n+1)*a(n-1) + 2257*a(n)^2
   with a(0)=1, a(1)=2, a(2)=41, a(3)=1562.
   For n ≥ 4 the sequence is generated by
   a(n+2) = ( -144*a(n+1)*a(n-1) + 2257*a(n)^2 ) / a(n-2). */
seq_t a(idx_t n)
{
    if (n == 0) return (seq_t)1;
    if (n == 1) return (seq_t)2;
    if (n == 2) return (seq_t)41;
    if (n == 3) return (seq_t)1562;

    /* Sliding window for a(n-2), a(n-1), a(n), a(n+1) */
    seq_t a0 = (seq_t)1;   /* a(n-2) */
    seq_t a1 = (seq_t)2;   /* a(n-1) */
    seq_t a2 = (seq_t)41;  /* a(n)   */
    seq_t a3 = (seq_t)1562;/* a(n+1) */

    for (idx_t k = 4; k <= n; ++k) {
        seq_t numerator = (- (seq_t)144) * a3 * a1 + (seq_t)2257 * a2 * a2;
        seq_t a_next   = numerator / a0;   /* exact division */

        /* shift window: a0<-a1, a1<-a2, a2<-a3, a3<-a_next */
        a0 = a1;
        a1 = a2;
        a2 = a3;
        a3 = a_next;
    }
    return a3;
}
