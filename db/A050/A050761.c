/*
 * A050761  Numbers k such that the decimal expansion of the k-th Fibonacci
 *          number contains no pair of consecutive equal digits (probably
 *          finite).
 * https://oeis.org/A050761
 *
 * Offset:    0    (a(0) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 45, u16 n <= 45, u32 n <= 45, u64 n <= 45, u128 n <= 45,
 *            big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence: A050761 – Numbers k such that the decimal expansion of the
 * k‑th Fibonacci number contains no pair of consecutive equal digits.
 * The sequence is generated by iterating the Fibonacci recurrence
 * and testing each term for the absence of adjacent equal digits.
 * No formula is known; the implementation simply scans Fibonacci
 * numbers until the desired number of qualifying indices is found. */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

/* ---- Big integer helpers (decimal digits) -------------------------------- */

typedef struct {
    uint8_t *digits;  /* least‑significant digit first */
    int      len;     /* number of used digits          */
    int      cap;     /* capacity of the digits array   */
} BigInt;

static void big_init(BigInt *b, int init_cap)
{
    b->digits = (uint8_t *)malloc((size_t)init_cap);
    b->len    = 0;
    b->cap    = init_cap;
}

static void big_ensure(BigInt *b, int needed)
{
    if (needed <= b->cap) return;
    int newcap = b->cap == 0 ? 1 : b->cap;
    while (newcap < needed) newcap <<= 1;
    b->digits = (uint8_t *)realloc(b->digits, (size_t)newcap);
    b->cap    = newcap;
}

static void big_set_uint(BigInt *b, uint64_t v)
{
    big_ensure(b, 1);
    if (v == 0) {
        b->len = 1;
        b->digits[0] = 0;
        return;
    }
    int i = 0;
    while (v) {
        big_ensure(b, i + 1);
        b->digits[i++] = (uint8_t)(v % 10);
        v /= 10;
    }
    b->len = i;
}

static void big_add(const BigInt *x, const BigInt *y, BigInt *z)
{
    int maxlen = x->len > y->len ? x->len : y->len;
    big_ensure(z, maxlen + 1);
    unsigned carry = 0;
    int i;
    for (i = 0; i < maxlen; ++i) {
        unsigned a = i < x->len ? x->digits[i] : 0;
        unsigned b = i < y->len ? y->digits[i] : 0;
        unsigned s = a + b + carry;
        z->digits[i] = (uint8_t)(s % 10);
        carry        = s / 10;
    }
    if (carry) {
        z->digits[i++] = (uint8_t)carry;
    }
    z->len = i;
}

static bool no_consecutive_equal(const BigInt *b)
{
    if (b->len < 2) return true;
    for (int i = b->len - 2; i >= 0; --i) {
        if (b->digits[i] == b->digits[i + 1]) return false;
    }
    return true;
}

/* ---- Main sequence function ------------------------------------------------ */

seq_t a(idx_t n)
{
    /* static state – reused across calls */
    static bool      init     = false;
    static BigInt    f_prev;
    static BigInt    f_curr;
    static BigInt    f_next;
    static idx_t     next_k   = 1;          /* current Fibonacci index */
    static idx_t     found    = 0;          /* how many qualifying k found */
    static seq_t   *values   = NULL;        /* stored a(i) terms */
    static size_t  values_len  = 0;         /* number of stored terms  */
    static size_t  values_cap  = 0;         /* capacity of values      */

    if (!init) {
        big_init(&f_prev, 8);
        big_init(&f_curr, 8);
        big_init(&f_next, 8);
        big_set_uint(&f_prev, 0);           /* F0 */
        big_set_uint(&f_curr, 1);           /* F1 */
        next_k = 1;
        init   = true;
    }

    /* Grow the array of results if necessary */
    if (values == NULL && n == 0) {
        values_cap = 64;
        values = (seq_t *)malloc(values_cap * sizeof(seq_t));
    }
    while (values_len <= (size_t)n) {
        /* Test current Fibonacci number */
        if (no_consecutive_equal(&f_curr)) {
            if (values_len == values_cap) {
                values_cap <<= 1;
                values = (seq_t *)realloc(values, values_cap * sizeof(seq_t));
            }
            values[values_len++] = (seq_t)next_k;
        }

        /* Advance Fibonacci: F_{k+1} = F_k + F_{k-1} */
        big_add(&f_prev, &f_curr, &f_next);
        /* Shift for next round */
        BigInt tmp = f_prev;
        f_prev = f_curr;
        f_curr = f_next;
        f_next = tmp;
        ++next_k;
    }

    return values[(size_t)n];
}
