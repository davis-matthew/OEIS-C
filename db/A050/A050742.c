/*  A050742: a(n) = the n‑th integer k such that the decimal expansion of k^3
    contains no pair of consecutive equal digits.  */

/*  The sequence is generated by testing successive integers k,
    storing those whose cubes have no adjacent equal decimal digits.
    The array is extended on demand; any order of calls to a(n) is
    supported because the cache is static.                                          */

#include <stdbool.h>
#include <stdlib.h>

/* check whether a decimal number v has no consecutive equal digits */
static inline bool no_consecutive_equal_digits(seq_t v)
{
    int last = -1;                 /* sentinel for first digit          */
    while (v != (seq_t)0) {
        int d = (int)(v % (seq_t)10);   /* last digit of v                 */
        if (d == last) return false;    /* consecutive duplicate found      */
        last = d;
        v /= (seq_t)10;                 /* shift right by one digit         */
    }
    return true;
}

seq_t a(idx_t n)
{
    /* Static cache: values already found */
    static seq_t *cache    = NULL;
    static size_t cache_size = 0;      /* number of stored terms           */
    static size_t cache_cap  = 0;      /* allocated capacity               */
    static idx_t next_start     = 0;   /* next candidate to test           */

    /* initialise cache on first call */
    if (cache_cap == 0) {
        cache_cap = 64;
        cache = (seq_t *)malloc(cache_cap * sizeof(seq_t));
        if (!cache) return 0;          /* allocation failure – return 0   */
    }

    /* grow cache until it can hold at least 'n' terms */
    while (cache_cap < n) {
        size_t new_cap = cache_cap << 1;
        seq_t *tmp = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!tmp) return 0;            /* allocation failure – return 0   */
        cache = tmp;
        cache_cap = new_cap;
    }

    /* generate terms until we have at least 'n' values */
    while (cache_size < n) {
        seq_t k = (seq_t)next_start;

        /* compute k^3 */
        seq_t cube = k * k;
        cube *= k;

        if (no_consecutive_equal_digits(cube)) {
            cache[cache_size++] = k;   /* store if valid                  */
        }
        next_start++;                   /* advance to next integer          */
    }

    return cache[n - 1];
}
