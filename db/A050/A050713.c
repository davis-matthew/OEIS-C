/*
 * A050713  Inserting a digit '3' between adjacent digits of n makes a prime.
 * https://oeis.org/A050713
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, base
 * Formula:   not stated
 * Range:     u8 n <= 31, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   interleave3_uint64
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Sequence A050713: Numbers n such that inserting the digit 3 between every
 * pair of adjacent decimal digits of n produces a prime.
 *
 * No useful closed‑form formula is known; the sequence is generated by
 * testing consecutive integers and storing those that satisfy the definition.
 */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include "../utils/interleave3_uint64.h"

/* ---------- Utility: 64‑bit Miller–Rabin primality test ---------- */

static uint64_t modpow_uint64(uint64_t a, uint64_t e, uint64_t mod)
{
    unsigned __int128 res = 1;
    unsigned __int128 base = a % mod;
    while (e) {
        if (e & 1)
            res = (res * base) % mod;
        base = (base * base) % mod;
        e >>= 1;
    }
    return (uint64_t)res;
}

static bool is_prime_uint64(uint64_t n)
{
    if (n < 2)
        return false;
    /* trial division for small primes */
    static const uint64_t small_primes[] =
        {2ULL,3ULL,5ULL,7ULL,11ULL,13ULL,17ULL,19ULL,23ULL,29ULL,31ULL,37ULL};
    for (size_t i = 0; i < sizeof(small_primes)/sizeof(small_primes[0]); ++i) {
        uint64_t p = small_primes[i];
        if (n == p)
            return true;
        if (n % p == 0)
            return false;
    }
    /* Miller–Rabin with deterministic bases for 64‑bit integers */
    uint64_t d = n - 1;
    int s = 0;
    while ((d & 1) == 0) {
        d >>= 1;
        ++s;
    }
    static const uint64_t bases[] =
        {2ULL, 325ULL, 9375ULL, 28178ULL, 450775ULL, 9780504ULL, 1795265022ULL};
    for (size_t i = 0; i < sizeof(bases)/sizeof(bases[0]); ++i) {
        uint64_t a = bases[i] % n;
        if (a == 0)
            continue;
        uint64_t x = modpow_uint64(a, d, n);
        if (x == 1 || x == n - 1)
            continue;
        bool composite = true;
        for (int r = 1; r < s; ++r) {
            x = modpow_uint64(x, 2, n);
            if (x == n - 1) {
                composite = false;
                break;
            }
        }
        if (composite)
            return false;
    }
    return true;
}

/* ---------- Interleave a 3 between every adjacent pair of digits ---------- */

/* ---------- Memoized sequence storage ---------- */

static seq_t *cache = NULL;
static size_t cache_len = 0;
static size_t cache_cap = 0;

static void ensure_cache_cap(size_t needed)
{
    if (needed <= cache_cap)
        return;
    size_t new_cap = cache_cap ? cache_cap * 2 : 8;
    while (new_cap < needed)
        new_cap *= 2;
    seq_t *new_ptr = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
    if (!new_ptr)
        return; /* allocation failure; the caller will not be able to continue */
    cache = new_ptr;
    cache_cap = new_cap;
}

/* ---------- Main sequence function ---------- */

seq_t a(idx_t n)
{
    if (n == 0)
        return 0;         /* undefined for n==0, return 0 as placeholder */

    if (cache_len < n) {
        /* start searching from 1; the first accepted term is 11 */
        idx_t candidate = (cache_len == 0) ? 1 : (idx_t)cache[cache_len - 1] + 1;
        if (candidate < 10)
            candidate = 10; /* single‑digit numbers are not part of the sequence */

        while (cache_len < n) {
            uint64_t inter = interleave3_uint64(candidate);
            if (inter >= 2 && is_prime_uint64(inter)) {
                ensure_cache_cap(cache_len + 1);
                cache[cache_len++] = (seq_t)candidate;
            }
            ++candidate;
        }
    }

    return cache[n - 1];
}
