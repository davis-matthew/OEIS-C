/* Sequence A308186: the nth symbol of the fixed point of the morphism
   a → a b a b   (a = 1, b = 2)
   b → b         (b = 2)
   Alphabet {a,b} = {1,2}.  The sequence is generated by
   iteratively expanding an initial word until it contains at least
   n symbols, then returning the (n−1)th element. */
#include <stdlib.h>

seq_t a(idx_t n)
{
    /* static buffer holding the current word, encoded as 1 and 2.
       len stores its length. */
    static seq_t *word = NULL;
    static idx_t len = 0;

    /* initialise with the seed word "a" if needed */
    if (len == 0) {
        word = (seq_t *)malloc(sizeof(seq_t));
        word[0] = (seq_t)1;   /* a */
        len   = 1;
    }

    /* expand until we have at least n symbols */
    while (len < n) {
        idx_t oldlen = len;
        /* allocate a temporary array that is at most 4× oldlen long;
           each 'a' becomes 4 symbols, each 'b' stays 1. */
        seq_t *next = (seq_t *)malloc(sizeof(seq_t) * oldlen * 4);
        idx_t pos = 0;
        for (idx_t i = 0; i < oldlen; ++i) {
            if (word[i] == (seq_t)1) {        /* a → a b a b */
                next[pos++] = (seq_t)1;
                next[pos++] = (seq_t)2;
                next[pos++] = (seq_t)1;
                next[pos++] = (seq_t)2;
            } else {                         /* b → b */
                next[pos++] = (seq_t)2;
            }
        }
        free(word);
        word = next;
        len  = pos;
    }

    return word[n - 1];
}
