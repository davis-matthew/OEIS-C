/*
 * A308319  Lexicographically earliest sequence of distinct terms starting
 *          with a prime such that one of the terms of {a(n), a(n+1)} is prime
 *          and the other not, with [a(n) + a(n+1)] = nonprime.
 * https://oeis.org/A308319
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 107, u16 n <= 1338, u32 n <= 1338, u64 n <= 1338,
 *            u128 n <= 1338, big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Algorithm: build the lexicographically earliest permutation of the
   positive integers starting with a prime such that for every n ≥ 1
   * exactly one of a(n), a(n+1) is prime,
   * the sum a(n)+a(n+1) is not prime.
   a(2k-1) is a prime, a(2k) is a composite (or 1).  The sequence is
   generated by greedy search: at each position choose the smallest
   unused integer that satisfies the conditions. */

/* -------------------------------------------------------------------------- */
#include <stdbool.h>
#include <stddef.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include "../utils/is_prime_big.h"

/* -------------------------------------------------------------------------- */
/* --- Helper: sum_is_prime ------------------------------------------------- */
static inline bool sum_is_prime(seq_t x, seq_t y)
{
    seq_t s = x + y;
    return is_prime_big(s);
}

/* -------------------------------------------------------------------------- */
/* --- Helper: ensure capacity for the “used” bit array --------------------- */
static void ensure_used_capacity(size_t min_cap, unsigned char **used, size_t *used_cap)
{
    if (*used_cap >= min_cap)
        return;
    size_t new_cap = (*used_cap) ? (*used_cap) : 8;
    while (new_cap < min_cap)
        new_cap <<= 1;                     /* double until enough */

    unsigned char *tmp = (unsigned char *)realloc(*used, new_cap);
    if (!tmp)
        abort();
    /* Initialise the newly allocated part to 0 (unused). */
    memset(tmp + *used_cap, 0, new_cap - *used_cap);
    *used = tmp;
    *used_cap = new_cap;
}

/* -------------------------------------------------------------------------- */
/* --- Helper: ensure capacity for the sequence array ---------------------- */
static void ensure_seq_capacity(size_t min_cap, seq_t **seq, size_t *seq_cap)
{
    if (*seq_cap >= min_cap)
        return;
    size_t new_cap = (*seq_cap) ? (*seq_cap) : 8;
    while (new_cap < min_cap)
        new_cap <<= 1;                     /* double until enough */

    seq_t *tmp = (seq_t *)realloc(*seq, new_cap * sizeof(seq_t));
    if (!tmp)
        abort();
    *seq = tmp;
    *seq_cap = new_cap;
}

/* -------------------------------------------------------------------------- */
/* --- Main function -------------------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0)
        return 0;          /* out of range, but not required by spec */

    /* Static state for memoisation. */
    static seq_t *seq        = NULL;   /* stored values */
    static size_t seq_len    = 0;      /* number of stored values */
    static size_t seq_cap    = 0;      /* allocated capacity */

    static unsigned char *used  = NULL;   /* used flag array */
    static size_t used_cap      = 0;      /* allocated capacity */

    while (seq_len < n)
    {
        seq_t candidate;
        idx_t pos = seq_len + 1;          /* 1‑based position */

        /* ------------------------------------------------------------------ */
        /* First term: the smallest unused prime (2). */
        if (seq_len == 0)
        {
            candidate = 2;
            ensure_used_capacity((size_t)candidate + 1, &used, &used_cap);
            used[(size_t)candidate] = 1;
        }
        else
        {
            seq_t last = seq[seq_len - 1];
            bool need_prime = (pos & 1U); /* odd positions → prime, even → composite */

            if (need_prime)
            {
                /* Find the smallest unused prime whose sum with the last term
                   is composite (i.e. non‑prime). */
                seq_t cand = 2;
                for (;; ++cand)
                {
                    ensure_used_capacity((size_t)cand + 1, &used, &used_cap);
                    if (used[(size_t)cand])
                        continue;
                    if (!is_prime_big(cand))
                        continue;
                    if (sum_is_prime(cand, last))
                        continue;
                    candidate = cand;
                    break;
                }
            }
            else
            {
                /* Even position → composite (1 treated as composite). */
                seq_t cand = 1;
                for (;; ++cand)
                {
                    ensure_used_capacity((size_t)cand + 1, &used, &used_cap);
                    if (used[(size_t)cand])
                        continue;
                    if (is_prime_big(cand))
                        continue;
                    if (sum_is_prime(cand, last))
                        continue;
                    candidate = cand;
                    break;
                }
            }

            /* Mark the chosen candidate as used. */
            ensure_used_capacity((size_t)candidate + 1, &used, &used_cap);
            used[(size_t)candidate] = 1;
        }

        /* Store the candidate in the sequence. */
        ensure_seq_capacity(seq_len + 1, &seq, &seq_cap);
        seq[seq_len++] = candidate;
    }

    return seq[n - 1];
}
