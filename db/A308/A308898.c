/* Recurrence: a(n) is the n-th symbol of the fixed point of the morphism
   0 → 01, 1 → 2, 2 → 3, 3 → 012.  The fixed point is generated by
   repeatedly applying the morphism to an initial symbol 0. */

#include <stdlib.h>

static seq_t *cache = NULL;
static idx_t cache_len = 0;

static void extend_cache(idx_t n)
{
    if (n < cache_len)
        return;

    /* Ensure the initial word is present */
    if (cache == NULL) {
        cache = (seq_t *)malloc(sizeof(seq_t));
        cache[0] = 0;
        cache_len = 1;
    }

    while (cache_len <= n) {
        /* Compute length of the next word */
        idx_t new_len = 0;
        for (idx_t i = 0; i < cache_len; ++i) {
            uint8_t s = (uint8_t)cache[i];
            if (s == 0)
                new_len += 2; /* 01 */
            else if (s == 1 || s == 2)
                new_len += 1; /* 2 or 3 */
            else
                new_len += 3; /* 012 */
        }

        /* Allocate space for the next word */
        seq_t *new_cache = (seq_t *)malloc(new_len * sizeof(seq_t));
        idx_t pos = 0;
        for (idx_t i = 0; i < cache_len; ++i) {
            uint8_t s = (uint8_t)cache[i];
            if (s == 0) {
                new_cache[pos++] = 0;
                new_cache[pos++] = 1;
            } else if (s == 1) {
                new_cache[pos++] = 2;
            } else if (s == 2) {
                new_cache[pos++] = 3;
            } else { /* s == 3 */
                new_cache[pos++] = 0;
                new_cache[pos++] = 1;
                new_cache[pos++] = 2;
            }
        }

        free(cache);
        cache = new_cache;
        cache_len = new_len;
    }
}

seq_t a(idx_t n)
{
    extend_cache(n);
    return cache[n];
}
