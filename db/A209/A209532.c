/*
 * A209532  Half the number of (n+1) X 7 0..2 arrays with every 2 X 2 subblock
 *          having exactly two distinct clockwise edge differences.
 * https://oeis.org/A209532
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 3, u32 n <= 8, u64 n <= 17, u128 n <= 35,
 *            big any n
 * Helpers:   pow2
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/*
 * Formula:  a(n) = 3*2^((7*n)/2 + 2) + 1  for n even
 *            a(n) = 2^((7*n)/2 + 7/2) + 1  for n odd
 * (This follows from the proven closed‑form expressions of A209532.)
 *
 * The sequence satisfies a(1)=129, a(2)=1537, a(3)=16385.
 * It can also be generated by the recurrence
 *   a(n)=a(n-1)+128*a(n-2)-128*a(n-3)
 * with those three initial values.
 */

#include "../utils/pow2.h"

/* ------------------------------------------------------------------ */
/*  A209532: Half the number of (n+1)×7 0..2 arrays with the given */
seq_t a(idx_t n)
{
    seq_t result;
    /* compute exponent according to parity of n                           */
    if ((n & 1) == 0) {            /* n even */
        idx_t exp = (7 * n) / 2 + 2;
        result = pow2(exp);       /* 2^exp */
        result *= (seq_t)3;       /* 3*2^exp */
        result += (seq_t)1;       /* +1    */
    } else {                        /* n odd */
        idx_t exp = (7 * n + 7) / 2; /* (7*n + 7)/2 is integer for odd n */
        result = pow2(exp);       /* 2^exp */
        result += (seq_t)1;       /* +1    */
    }
    return result;
}
