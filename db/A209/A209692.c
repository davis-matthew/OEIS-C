/*
 * Sequence A209692
 * a(n) is the coefficient of the polynomial v(n,x) (defined below),
 * read row‑wise.  The polynomials are generated by
 *
 *   u(1,x) = v(1,x) = 1
 *   u(n,x) = x * u(n‑1,x) + x * v(n‑1,x)
 *   v(n,x) = u(n‑1,x) + 2x * v(n‑1,x) + 1      (n ≥ 2)
 *
 * The triangle is obtained by writing the coefficients of v(n,x)
 * from the constant term up to x^(n‑1).  a(1)=1, a(2)=2, a(3)=2,
 * a(4)=1, a(5)=6, a(6)=4, …
 */

#include <stdlib.h>

seq_t a(idx_t n)
{
    if (n <= 1) {                /* offset is 1, a(1)=1 */
        return (seq_t)1;
    }

    /* Find row r such that r(r+1)/2 ≥ n  (1‑based indices)  */
    idx_t r = 1;
    while ((r * (r + 1)) / 2 < n) {
        ++r;
    }

    /* Position within the row (0‑based) */
    idx_t prev_total = (r * (r - 1)) / 2;
    idx_t pos = n - prev_total - 1;   /* 0 ≤ pos < r */

    /* Allocate arrays to hold coefficients of size up to r   */
    size_t max_len = (size_t)r;
    seq_t *u_cur  = (seq_t*)malloc(sizeof(seq_t) * max_len);
    seq_t *u_next = (seq_t*)malloc(sizeof(seq_t) * max_len);
    seq_t *v_cur  = (seq_t*)malloc(sizeof(seq_t) * max_len);
    seq_t *v_next = (seq_t*)malloc(sizeof(seq_t) * max_len);
    if (!u_cur || !u_next || !v_cur || !v_next) {
        /* Allocation failed – return 0 as a safe fallback. */
        free(u_cur); free(u_next); free(v_cur); free(v_next);
        return (seq_t)0;
    }

    /* Initial row (n=1): u(1)=v(1)=1 */
    u_cur[0] = (seq_t)1;
    v_cur[0] = (seq_t)1;
    size_t cur_len = 1;   /* number of coefficients in current row */

    /* Build rows 2 … r */
    for (idx_t row = 2; row <= r; ++row) {
        size_t new_len = (size_t)row;   /* length of new row */

        /* Constant term of new u is zero. */
        u_next[0] = (seq_t)0;

        /* Constant term of new v is u_prev[0] + 1. */
        v_next[0] = u_cur[0] + (seq_t)1;

        /* Compute coefficients for higher degrees */
        for (size_t k = 1; k < new_len; ++k) {
            /* u_next[k] = u_prev[k-1] + v_prev[k-1]  (shifted by x) */
            seq_t u_prev_k1 = (k - 1 < cur_len) ? u_cur[k - 1] : (seq_t)0;
            seq_t v_prev_k1 = (k - 1 < cur_len) ? v_cur[k - 1] : (seq_t)0;
            u_next[k] = u_prev_k1 + v_prev_k1;

            /* v_next[k] = u_prev[k] + 2 * v_prev[k-1]  (shifted by x) */
            seq_t u_prev_k  = (k < cur_len) ? u_cur[k] : (seq_t)0;
            seq_t v_prev_k1_ = v_cur[k - 1];
            v_next[k] = u_prev_k + (seq_t)2 * v_prev_k1_;
        }

        /* Swap current and next arrays */
        seq_t *tmp = u_cur;  u_cur = u_next;  u_next = tmp;
        tmp = v_cur;         v_cur = v_next;  v_next = tmp;

        cur_len = new_len;
    }

    /* v_cur now contains coefficients of row r */
    seq_t result = v_cur[(size_t)pos];

    /* Clean up */
    free(u_cur);  free(u_next);
    free(v_cur);  free(v_next);

    return result;
}
