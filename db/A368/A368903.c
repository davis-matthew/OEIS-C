/*
 * A368903  Numbers k for which there is no prime p such that p^p divides
 *          A342001(k), but for A003415(k) such a prime exists. Here
 *          A003415(n) is the arithmetic derivative of n, and A342001(n) =
 *          A003415(n) / A003557(n).
 * https://oeis.org/A368903
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   not stated
 * Range:     u8 n <= 42, u16 n <= 67, u32 n <= 67, u64 n <= 67, u128 n <= 67,
 *            big any n
 * Helpers:   factor_u64, seq_realloc
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation of OEIS sequence A368903.
   The sequence is generated by testing each integer k (starting from 1),
   computing its arithmetic derivative A003415(k), dividing by its square‑free
   kernel to obtain A342001(k), and keeping k if the former contains a
   prime power p^p while the latter does not.  A static cache of all found
   values allows any a(n) to be returned in O(1) after the initial scan. */

#include <stdint.h>
#include <stdbool.h>
#include <stdlib.h>
#include <string.h>
#include "../utils/factor_u64.h"
#include "../utils/seq_realloc.h"

/* Return true iff the integer m has a prime divisor p raised to at least p. */
static bool has_pp_power(uint64_t m)
{
    if (m < 4)                     /* 2^2 is the smallest p^p */
        return false;
    uint64_t primes[64];
    uint64_t exps[64];
    size_t cnt;
    factor_u64(m, primes, exps, &cnt);
    for (size_t i = 0; i < cnt; ++i)
        if (exps[i] >= primes[i])
            return true;
    return false;
}

seq_t a(idx_t n)
{
    static seq_t *cache = NULL;
    static size_t cache_len = 0;
    static size_t cache_cap = 0;
    static idx_t max_checked = 0;

    if (n == 0)
        return 0;   /* a(0) is undefined; return 0, acceptable for offset */

    /* Generate terms until we have at least n of them. */
    while (cache_len < n)
    {
        /* Next integer to examine */
        idx_t cand = max_checked + 1;
        ++max_checked;

        /* Factorise cand */
        uint64_t primes[64];
        uint64_t exps[64];
        size_t cnt;
        factor_u64((uint64_t)cand, primes, exps, &cnt);

        /* Compute the square‑free kernel rad = product of distinct primes */
        uint64_t rad = 1;
        for (size_t i = 0; i < cnt; ++i)
            rad *= primes[i];

        /* Divisor = cand / rad is A003557(cand) */
        uint64_t divisor = (uint64_t)cand / rad;

        /* Arithmetic derivative A003415(cand) = sum((cand / p_i) * e_i) */
        uint64_t deriv = 0;
        for (size_t i = 0; i < cnt; ++i)
            deriv += ((uint64_t)cand / primes[i]) * exps[i];

        if (deriv == 0)   /* k = 1 gives derivative 0, skip */
            continue;

        /* A342001(cand) = deriv / divisor */
        uint64_t g = deriv / divisor;

        /* Check the defining conditions */
        if (has_pp_power(deriv) && !has_pp_power(g))
        {
            /* Grow cache if necessary */
            if (cache_len == cache_cap)
            {
                size_t new_cap = cache_cap ? cache_cap * 2 : 16;
                seq_t *tmp = seq_realloc(cache, cache_cap, new_cap);
                cache = tmp;
                cache_cap = new_cap;
            }
            /* Store the qualifying k */
            cache[cache_len++] = (seq_t)cand;
        }
    }

    return cache[n - 1];
}
