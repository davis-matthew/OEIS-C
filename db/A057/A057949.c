/*
 * A057949  Numbers with more than one factorization into S-primes. See
 *          A054520 and A057948 for definition.
 * https://oeis.org/A057949
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, changed
 * Formula:   not stated
 * Range:     u8 none, u16 n <= 729, u32 n <= 10000, u64 n <= 10000,
 *            u128 n <= 10000, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Sequence A057949: Numbers ≡1 (mod 4) that contain at least four prime
 * factors ≡3 (mod 4) (with multiplicity) and have no exponent equal to
 * k−1.  The function returns the n-th such integer in increasing order.
 * Since no closed formula is known, the sequence is generated by a
 * sieve-like search and cached so that repeated calls with arbitrary
 * arguments are fast. */

#include <stdint.h>
#include <stdlib.h>
#include <stdbool.h>
#include <string.h>

/* ---- Prime table (up to a fixed limit) --------------------------------- */
#define PRIME_LIMIT 2000000            /* enough for n ≤ 10000 */
#define PRIME_CAP    200000            /* ≈π(PRIME_LIMIT) */

static uint32_t primes[PRIME_CAP];
static size_t primes_cnt = 0;
static bool primes_ready = false;

/* Build the list of primes up to PRIME_LIMIT using a simple sieve. */
static void init_primes(void)
{
    if (primes_ready) return;
    /* Boolean sieve: 0 – prime, 1 – composite */
    uint8_t *sieve = (uint8_t *)calloc(PRIME_LIMIT + 1, sizeof(uint8_t));
    if (!sieve) exit(EXIT_FAILURE);

    for (size_t i = 2; i <= PRIME_LIMIT; ++i) {
        if (!sieve[i]) {
            if (primes_cnt < PRIME_CAP) primes[primes_cnt++] = (uint32_t)i;
            if (i * i <= PRIME_LIMIT) {
                for (size_t j = i * i; j <= PRIME_LIMIT; j += i)
                    sieve[j] = 1;
            }
        }
    }
    free(sieve);
    primes_ready = true;
}

/* ---- Cache for already‑computed terms --------------------------------- */
static seq_t *cache = NULL;      /* array of sequence values           */
static idx_t  cache_size = 0;    /* number of values stored             */
static idx_t  cache_cap  = 0;    /* allocated capacity                  */
static uint64_t next_candidate = 5; /* next 1 mod 4 number to test        */

/* Append a new term to the cache, growing the array if needed. */
static void cache_append(seq_t value)
{
    if (cache_size == cache_cap) {
        cache_cap = (cache_cap == 0) ? 16 : cache_cap << 1;
        cache = (seq_t *)realloc(cache, cache_cap * sizeof(seq_t));
        if (!cache) exit(EXIT_FAILURE);
    }
    cache[cache_size++] = value;
}

/* ---- Main sequence function ------------------------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;   /* offset starts at 1 – unspecified behaviour below */

    /* Ensure primes are ready. */
    if (!primes_ready) init_primes();

    /* Generate terms until we have at least n of them. */
    while (cache_size < n) {
        uint64_t val = next_candidate;  /* candidate ≡1 (mod 4) */
        uint64_t temp = val;
        uint8_t  max_exp = 0;   /* maximum exponent among 3‑mod‑4 primes */
        uint8_t  k3      = 0;   /* total count of such primes */

        /* Factorisation by trial division using the prime list */
        for (size_t i = 0; i < primes_cnt; ++i) {
            uint64_t p = primes[i];
            if (p > temp / p) break;     /* p·p > temp          */
            if (temp % p) continue;

            uint8_t exp = 0;
            while (temp % p == 0) {
                ++exp;
                temp /= p;
            }
            if (p % 4 == 3) {
                k3 += exp;
                if (exp > max_exp) max_exp = exp;
            }
        }
        /* Remaining factor (if >1) */
        if (temp > 1) {
            if (temp % 4 == 3) {
                k3 += 1;
                if (1 > max_exp) max_exp = 1;
            }
        }

        /* Accept the candidate if it satisfies the definition. */
        if (k3 >= 4 && max_exp <= k3 - 2) {
            cache_append( (seq_t)val );
        }

        next_candidate += 4; /* move to the next 1 mod 4 number */
    }

    /* Return the n‑th term (indexing starts at 1). */
    return cache[n - 1];
}
