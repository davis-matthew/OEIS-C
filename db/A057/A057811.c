/* A057811: numbers k such that π(k) is even.
   The sequence is generated by a simple sieve of Eratosthenes.
   For each integer k we keep a running count of primes ≤k.
   Whenever this count is even, k is appended to the sequence.  */

#include <stdlib.h>
#include <stdbool.h>
#include <stddef.h>   /* for size_t */

/* static state */
static idx_t        limit   = 0;         /* current sieve limit   */
static bool        *is_prime = NULL;     /* boolean array of primes      */
static seq_t       *seq      = NULL;     /* sequence values              */
static size_t       seq_len  = 0;         /* number of values in seq     */

/* rebuild the sieve and sequence up to new_limit */
static void rebuild(idx_t new_limit)
{
    /* allocate flag array */
    bool *s = (bool*)malloc(sizeof(bool)*(new_limit+1));
    if (!s) abort();
    s[0] = false;
    s[1] = false;
    for (idx_t i = 2; i <= new_limit; ++i) s[i] = true;

    /* sieve of Eratosthenes */
    for (idx_t i = 2; i <= new_limit / i; ++i)
        if (s[i])
            for (idx_t j = i*i; j <= new_limit; j += i)
                s[j] = false;

    /* replace old sieve */
    if (is_prime) free(is_prime);
    is_prime = s;
    limit = new_limit;

    /* rebuild the sequence */
    seq = (seq_t*)realloc(seq, sizeof(seq_t)*new_limit);
    seq_len = 0;

    idx_t prime_cnt = 0;
    for (idx_t k = 1; k <= new_limit; ++k)
    {
        if (is_prime[k]) ++prime_cnt;
        if ((prime_cnt & 1) == 0)
            seq[seq_len++] = (seq_t)k;
    }
}

/* return the nth term (1‑based) of sequence A057811 */
seq_t a(idx_t n)
{
    while (seq_len < n)
    {
        idx_t next = (limit == 0) ? 1000 : limit * 2 + 100;
        rebuild(next);
    }
    return seq[n-1];
}
