/*
 * A057144  Smallest of the most frequently occurring numbers in 1-to-n
 *          multiplication table.
 * https://oeis.org/A057144
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn
 * Formula:   a(n) = smallest product having the maximum frequency in the n×n
 *            multiplication table (products x*y for 1≤x,y≤n)
 * Range:     u8 n <= 44, u16 n <= 1979, u32 n <= 8867, u64 n <= 8867,
 *            u128 n <= 8867, big any n
 * Helpers:   none
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

#include <stdlib.h>
#include <stdint.h>
#include <string.h>

/* Smallest product that occurs most often in the 1‑to‑n multiplication
   table.  The table is generated by counting frequencies of every
   product i*j and then selecting the smallest product that attains
   the largest frequency.  The implementation uses a 16‑bit counter
   array of size n²+1, which is sufficient for n≤10000 and holds
   the maximum frequency (below 1000).  Indexing is performed on
   `idx_t` which is 64‑bit, so it can address all products up to
   n².  `seq_t` is cast from the `idx_t` product for the final return. */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined but safe guard */

    /* Size of the counter array: n²+1 entries (0 unused). */
    size_t size = (size_t)n * (size_t)n + 1ULL;

    /* Allocate the counter array (16‑bit counters). */
    uint16_t *cnt = (uint16_t *)malloc(size * sizeof(uint16_t));
    if (!cnt) return 0;            /* allocation failed */

    /* Initialise all counters to zero. */
    memset(cnt, 0, size * sizeof(uint16_t));

    uint16_t maxf = 0;             /* current maximum frequency */
    seq_t    minprod = 0;          /* smallest product with max frequency */

    /* Count frequencies of all products i*j. */
    for (idx_t i = 1; i <= n; ++i) {
        for (idx_t j = 1; j <= n; ++j) {
            idx_t prod_idx = i * j;                /* product fits in idx_t (≤ n²) */
            uint16_t c = ++cnt[(size_t)prod_idx];  /* increment counter */

            if (c > maxf) {
                maxf    = c;
                minprod = (seq_t)prod_idx;
            } else if (c == maxf && (seq_t)prod_idx < minprod) {
                minprod = (seq_t)prod_idx;
            }
        }
    }

    free(cnt);
    return minprod;
}
