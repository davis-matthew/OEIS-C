/*
 * A057747 – Number of decompositions of 2n‑1 into a lucky number and an
 * even‑lucky number (A045954).
 *
 * A lucky number list is obtained by the standard “lucky sieve” starting
 * with the odd integers.  The even‑lucky numbers are generated by applying
 * the same sieve to the list of even integers.  For a given n ≥ 1 the
 * target sum is 2n–1; we count the pairs (l, e) with l lucky, e even‑lucky
 * and l + e = 2n–1.
 */

#include <stdlib.h>

static idx_t     max_lucky_limit = 0,    /* largest limit for which the tables
                                            are already built */
                   max_even_limit  = 0;
static unsigned int  *lucky_nums     = NULL,  /* lucky numbers */
                      *even_nums     = NULL;  /* even‑lucky numbers */
static size_t        lucky_count   = 0,
                      even_count    = 0;
static unsigned char *is_lucky      = NULL,    /* bitmap: 1 if index is lucky */
                      *is_even       = NULL;    /* bitmap: 1 if index is even‑lucky */
static size_t        is_lucky_size = 0,
                      is_even_size  = 0;

/* Build lucky numbers (odd) up to 'limit' (inclusive) */
static void build_lucky_numbers(idx_t limit)
{
    if (limit <= max_lucky_limit) return;

    size_t sz = (limit + 1) / 2;                /* number of odd ints ≤ limit */
    unsigned int *cur = (unsigned int *)malloc(sz * sizeof(unsigned int));
    size_t cur_sz = 0;
    for (idx_t i = 1; i <= limit; i += 2) cur[cur_sz++] = (unsigned int)i;

    /* Apply the lucky sieve */
    for (size_t step_idx = 1; step_idx < cur_sz; ++step_idx) {
        unsigned int step = cur[step_idx];
        if (step > cur_sz) break;
        unsigned int *next = (unsigned int *)malloc(cur_sz * sizeof(unsigned int));
        size_t next_sz = 0;
        size_t pos = 1;                         /* 1‑based position in the list */
        for (size_t i = 0; i < cur_sz; ++i, ++pos) {
            if (pos % step != 0) next[next_sz++] = cur[i];
        }
        free(cur);
        cur = next;
        cur_sz = next_sz;
    }

    /* Free previous tables */
    if (lucky_nums) free(lucky_nums);
    lucky_nums   = cur;
    lucky_count  = cur_sz;
    max_lucky_limit = limit;

    /* Build bitmap */
    if (is_lucky) free(is_lucky);
    is_lucky = (unsigned char *)calloc(limit + 1, sizeof(unsigned char));
    is_lucky_size = limit + 1;
    for (size_t i = 0; i < lucky_count; ++i) {
        unsigned int v = lucky_nums[i];
        if (v <= limit) is_lucky[v] = 1;
    }
}

/* Build even‑lucky numbers (even) up to 'limit' (inclusive) */
static void build_even_lucky_numbers(idx_t limit)
{
    if (limit <= max_even_limit) return;

    size_t sz = limit / 2;                        /* number of even ints ≤ limit */
    unsigned int *cur = (unsigned int *)malloc(sz * sizeof(unsigned int));
    size_t cur_sz = 0;
    for (idx_t i = 2; i <= limit; i += 2) cur[cur_sz++] = (unsigned int)i;

    /* Apply the lucky sieve */
    for (size_t step_idx = 1; step_idx < cur_sz; ++step_idx) {
        unsigned int step = cur[step_idx];
        if (step > cur_sz) break;
        unsigned int *next = (unsigned int *)malloc(cur_sz * sizeof(unsigned int));
        size_t next_sz = 0;
        size_t pos = 1;
        for (size_t i = 0; i < cur_sz; ++i, ++pos) {
            if (pos % step != 0) next[next_sz++] = cur[i];
        }
        free(cur);
        cur = next;
        cur_sz = next_sz;
    }

    /* Free previous tables */
    if (even_nums) free(even_nums);
    even_nums  = cur;
    even_count = cur_sz;
    max_even_limit = limit;

    /* Build bitmap */
    if (is_even) free(is_even);
    is_even = (unsigned char *)calloc(limit + 1, sizeof(unsigned char));
    is_even_size = limit + 1;
    for (size_t i = 0; i < even_count; ++i) {
        unsigned int v = even_nums[i];
        if (v <= limit) is_even[v] = 1;
    }
}

/* Main sequence function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined for n=0; safe guard */

    idx_t target = 2 * n - 1;       /* 2n‑1 */
    if (target < 3) return 0;       /* only possible for n=1 */

    /* Ensure tables up to 'target' are ready */
    build_lucky_numbers(target);
    build_even_lucky_numbers(target);

    seq_t count = 0;
    for (size_t idx = 0; idx < lucky_count; ++idx) {
        unsigned int l = lucky_nums[idx];
        if (l > target) break;
        idx_t e = target - l;                  /* remaining part to be even‑lucky */
        if (e < 2) continue;                   /* smallest even‑lucky is 2 */
        if ((size_t)e < is_even_size && is_even[e]) {
            ++count;
        }
    }
    return count;
}
