/*
 * A165893  Numbers n with property that n(n+2)(n+4) is a triangular number.
 * https://oeis.org/A165893
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, fini, full
 * Formula:   not stated
 * Range:     u8 n <= 1, u16 n <= 3, u32 n <= 8, u64 n <= 9, u128 n <= 9,
 *            big any n
 * Helpers:   floor_sqrt
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computes the n‑th term of OEIS A165893: integers n such that
   n(n+2)(n+4) is a triangular number.
   The sequence is generated by brute‑force search and cached. */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/floor_sqrt.h"

/* cached results: cache[i] == a(i+1) */
static seq_t *cache = NULL;
static size_t  cache_len = 0;
static size_t  cache_cap = 0;
static idx_t   last_checked = 0;

/* Ensure cache has space for at least `need` elements */
static void ensure_cache_cap(size_t need)
{
    if (cache_cap < need) {
        size_t new_cap = cache_cap ? cache_cap * 2 : 4;
        while (new_cap < need) new_cap <<= 1;
        seq_t *new_cache = (seq_t *)realloc(cache, new_cap * sizeof(seq_t));
        if (!new_cache) abort();
        cache      = new_cache;
        cache_cap  = new_cap;
    }
}

/* Test whether raise `cand` satisfies the condition */
static bool is_solution(idx_t cand)
{
    seq_t x = (seq_t)cand;              /* cast to seq_t */
    seq_t t = x * (x + 2) * (x + 4);    /* n*(n+2)*(n+4)      */
    t = (t << 3) + 1;                  /* 8*t + 1            */
    seq_t s = floor_sqrt(t);           /* sqrt floor         */
    return (s * s == t);
}

/* Main function */
seq_t a(idx_t n)
{
    if (n == 0) return 0;              /* undefined index, return 0 */

    /* Generate terms until we have at least n elements */
    while (cache_len < (size_t)n) {
        /* Find next integer that satisfies the condition */
        while (!is_solution(last_checked)) {
            ++last_checked;
        }
        /* Store the solution */
        ensure_cache_cap(cache_len + 1);
        cache[cache_len++] = (seq_t)last_checked;
        ++last_checked;                /* next search start point */
    }

    return cache[n - 1];
}
