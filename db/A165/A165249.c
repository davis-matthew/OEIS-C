/*
 * A165249  Those positive integers n where the number of 1's, when n is
 *          written in binary, on the left half of the binary representation
 *          equals the number of 1's on the right half of the binary
 *          representation.
 * https://oeis.org/A165249
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  base, nonn
 * Formula:   not stated
 * Range:     u8 n <= 78, u16 n <= 1000, u32 n <= 1000, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   good_ull
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* Computation of sequence A165249.
 *
 * a(n) = the nth positive integer whose binary representation
 *        has the same number of 1's in its left half as in its
 *        right half (the middle bit, if the length is odd,
 *        is ignored).  The sequence is generated by a simple
 *        search with memoisation.
 *
 * The implementation keeps an internal cache of already found
 * terms and extends it until the requested index is reached.
 * It uses 64‑bit arithmetic for the bit tests; for the
 * arbitrary‑precision build the candidate value is cast to
 * seq_t before being stored.  No external helpers are
 * required.
 */

#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>
#include "../utils/good_ull.h"

seq_t a(idx_t n)
{
    /* Memoised cache of all terms found so far. */
    static seq_t *cache     = NULL;
    static size_t cap       = 0;
    static size_t len       = 0;
    static unsigned long long last = 0;      /* last tested candidate */

    if (n == 0) return 0;                     /* undefined for indices <1 */

    /* Generate terms until we have at least n of them. */
    while (len < n) {
        unsigned long long cand = ++last;
        if (cand == 0) continue;              /* overflow guard */

        if (good_ull(cand)) {
            if (len == cap) {                 /* grow cache if needed */
                size_t newcap = cap ? cap * 2 : 16;
                seq_t *tmp = (seq_t *)realloc(cache, newcap * sizeof(seq_t));
                cache = tmp;
                cap   = newcap;
            }
            cache[len++] = (seq_t)cand;
        }
    }
    return cache[n - 1];
}
