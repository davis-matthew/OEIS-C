/*
 * A165671  Primes p such that (p^2+2)/33 is not prime.
 * https://oeis.org/A165671
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, less, easy
 * Formula:   not stated
 * Range:     u8 n <= 25, u16 n <= 261, u32 n <= 261, u64 n <= 1000,
 *            u128 n <= 1000, big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* This function returns the n-th prime p such that (p^2+2)/33 is not prime.
   The sequence is generated by testing primes in order, using trial division
   with the primes found so far, and checking the condition with is_prime_big.
   It uses only the facilities described in the specification. */
#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>
#include <stdlib.h>

#include "../utils/is_prime_big.h"   /* bool is_prime_big(seq_t n); */

/* Grow a dynamically resizing array of seq_t. */
static void grow_seq(seq_t **a, size_t *cap, size_t need)
{
    if (*cap < need) {
        size_t new_cap = (*cap == 0) ? 16 : (*cap << 1);
        if (new_cap < need) new_cap = need;
        seq_t *tmp = (seq_t *)realloc(*a, new_cap * sizeof(seq_t));
        if (!tmp) abort();
        *a = tmp;
        *cap = new_cap;
    }
}

/* Grow a dynamically resizing array of uint64_t. */
static void grow_uint64(uint64_t **a, size_t *cap, size_t need)
{
    if (*cap < need) {
        size_t new_cap = (*cap == 0) ? 16 : (*cap << 1);
        if (new_cap < need) new_cap = need;
        uint64_t *tmp = (uint64_t *)realloc(*a, new_cap * sizeof(uint64_t));
        if (!tmp) abort();
        *a = tmp;
        *cap = new_cap;
    }
}

/* Storage for all primes found so far (used for trial division). */
static uint64_t *prime_list = NULL;
static size_t prime_list_len = 0;
static size_t prime_list_cap = 0;

/* Storage for sequence elements that satisfy the condition. */
static seq_t *seq_vals = NULL;
static size_t seq_vals_len = 0;
static size_t seq_vals_cap = 0;

/* Next candidate to test for primality. */
static uint64_t candidate = 2;

/* Return the next prime, updating prime_list. */
static uint64_t next_prime(void)
{
    while (1) {
        bool is_p = true;
        for (size_t i = 0; i < prime_list_len; ++i) {
            uint64_t p = prime_list[i];
            if (p * p > candidate) break;
            if (candidate % p == 0) { is_p = false; break; }
        }
        if (is_p) {
            /* Store new prime. */
            grow_uint64(&prime_list, &prime_list_cap, prime_list_len + 1);
            prime_list[prime_list_len++] = candidate;
            uint64_t ret = candidate;
            candidate++;                     /* advance to next number */
            if (candidate > 2 && (candidate & 1) == 0) candidate++;  /* skip evens */
            return ret;
        }
        candidate++;                         /* advance to next number */
        if (candidate > 2 && (candidate & 1) == 0) candidate++;    /* skip evens */
    }
}

/* Main function required by the framework. */
seq_t a(idx_t n)
{
    if (n == 0) abort();               /* offset is 1 */

    /* Generate terms until we have at least n terms. */
    while (seq_vals_len < (size_t)n) {
        uint64_t p = next_prime();

        /* Check (p^2+2)/33. */
        uint64_t mod33 = ((p % 33ULL) * (p % 33ULL) + 2ULL) % 33ULL;
        bool exclude = false;
        if (mod33 == 0) {
            seq_t q = ((seq_t)p * (seq_t)p + 2) / 33;
            if (is_prime_big(q))
                exclude = true;
        }

        if (!exclude) {
            grow_seq(&seq_vals, &seq_vals_cap, seq_vals_len + 1);
            seq_vals[seq_vals_len++] = (seq_t)p;
        }
    }

    return seq_vals[n - 1];
}
