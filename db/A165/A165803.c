/*
 * A165803  Integers n such that the trajectory of n under repeated
 *          applications of the map k->(k-3)/2 is a chain of primes that
 *          reaches 2 or 3 (n itself need not be a prime).
 * https://oeis.org/A165803
 *
 * Offset:    1    (a(1) is the first term)
 * Keywords:  nonn, fini, full
 * Formula:   not stated
 * Range:     u8 n <= 7, u16 n <= 7, u32 n <= 7, u64 n <= 7, u128 n <= 7,
 *            big any n
 * Helpers:   is_prime_big
 *
 * Sequence data from the OEIS (https://oeis.org), licensed CC BY-SA 4.0.
 */

/* A165803: numbers n such that repeated (n-3)/2 gives primes ending at 2 or 3.  
   The sequence is generated by starting with the primes 2,3 and iteratively
   applying n = 2p + 3 for each prime p in the set.  All such n are stored
   in strictly increasing order; a(1)=2, a(2)=3, a(3)=7, a(4)=9, … */

#include <stdlib.h>
#include <stdbool.h>
#include "../utils/is_prime_big.h"

static seq_t *seq = NULL;                 /* list of sequence terms */
static size_t seq_len = 0, seq_cap = 0;
static seq_t *primes = NULL;              /* list of primes found in the sequence */
static size_t primes_len = 0, primes_cap = 0;

/* grow the array to accommodate at least 'need' elements */
static void ensure_seq_cap(size_t need) {
    if (need > seq_cap) {
        size_t newcap = seq_cap ? seq_cap * 2 : 4;
        if (newcap < need) newcap = need;
        seq = (seq_t *)realloc(seq, newcap * sizeof(seq_t));
        seq_cap = newcap;
    }
}
static void ensure_primes_cap(size_t need) {
    if (need > primes_cap) {
        size_t newcap = primes_cap ? primes_cap * 2 : 4;
        if (newcap < need) newcap = need;
        primes = (seq_t *)realloc(primes, newcap * sizeof(seq_t));
        primes_cap = newcap;
    }
}

/* build the complete sequence once */
static void build_sequence(void) {
    if (seq_len) return;   /* already built */

    /* initialise with the two seed primes 2 and 3 */
    ensure_seq_cap(2);
    ensure_primes_cap(2);
    seq[0] = (seq_t)2;
    seq[1] = (seq_t)3;
    seq_len = 2;
    primes[0] = (seq_t)2;
    primes[1] = (seq_t)3;
    primes_len = 2;

    /* iterate over primes, generating successors n = 2p + 3 */
    for (size_t i = 0; i < primes_len; ++i) {
        seq_t p = primes[i];
        seq_t n = (seq_t)2 * p + (seq_t)3;
        ensure_seq_cap(seq_len + 1);
        seq[seq_len++] = n;

        if (is_prime_big(n)) {
            ensure_primes_cap(primes_len + 1);
            primes[primes_len++] = n;
        }
    }
}

seq_t a(idx_t n) {
    if (n == 0) return 0;       /* undefined for index 0, return 0 */
    build_sequence();           /* ensure the sequence is ready */
    if ((idx_t)n > seq_len) return 0;  /* index beyond the sequence */
    return seq[n - 1];
}
