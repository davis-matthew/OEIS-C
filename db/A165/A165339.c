/* Sequence A165339: Numbers that eventually reach the cycle 919-1459
   under the map x -> sum of cubes of decimal digits.  The sequence
   is generated by scanning integers in increasing order and testing
   whether they reach the cycle.  
   The algorithm pre‑computes, once, the reachability status for all
   numbers up to LIMIT (2 000 000).  Any larger intermediate value
   quickly falls below LIMIT, after which the memoised status is used. */

#include <stdbool.h>

#define LIMIT 2000000   /* include all values that can appear after a few steps */

/* memoisation tables */
static unsigned char status[ LIMIT + 1 ];   /* 0=unknown,1=reaches,2=not */
static int visit_stamp[ LIMIT + 1 ];
static int cur_stamp = 1;

/* sum of cubes of decimal digits of x */
static seq_t sum_cubes(seq_t x)
{
    seq_t sum = 0;
    while (x != 0) {
        seq_t d = x % 10;
        sum += d * d * d;
        x /= 10;
    }
    return sum;
}

/* precompute reachability for all numbers <= LIMIT */
static void init_status(void)
{
    static bool done = false;
    if (done) return;
    done = true;

    for (int i = 0; i <= LIMIT; ++i) {
        status[i] = 0;
        visit_stamp[i] = 0;
    }
    status[919] = 1;
    status[1459] = 1;

    int path[200];
    for (int i = 0; i <= LIMIT; ++i) {
        if (status[i] != 0) continue;

        int len = 0;
        int cur = i;
        while (1) {
            if (cur == 919 || cur == 1459) {
                for (int k = 0; k < len; ++k) status[ path[k] ] = 1;
                break;
            }
            if (status[cur] == 1) {
                for (int k = 0; k < len; ++k) status[ path[k] ] = 1;
                break;
            }
            if (status[cur] == 2) {
                for (int k = 0; k < len; ++k) status[ path[k] ] = 2;
                break;
            }
            if (visit_stamp[cur] == cur_stamp) {        /* cycle detected */
                for (int k = 0; k < len; ++k) status[ path[k] ] = 2;
                break;
            }
            visit_stamp[cur] = cur_stamp;
            path[len++] = cur;
            seq_t nxt = sum_cubes((seq_t)cur);
            cur = (int)nxt;
            if (len >= 200) {                      /* safety, should not happen */
                for (int k = 0; k < len; ++k) status[ path[k] ] = 2;
                break;
            }
        }
        ++cur_stamp;
    }
}

/* return true if x eventually reaches the cycle {919,1459} */
static bool reaches_cycle(seq_t x)
{
    while (x > LIMIT) {
        x = sum_cubes(x);
    }
    return status[(int)x] == 1;
}

/* ------------------------- main sequence ------------------------- */
seq_t a(idx_t n)
{
    if (n == 0) return 0;          /* undefined, return 0 as guard */
    init_status();

    idx_t count = 0;
    seq_t val = 1;
    while (1) {
        if (reaches_cycle(val)) {
            ++count;
            if (count == n) return val;
        }
        val++;
    }
}
